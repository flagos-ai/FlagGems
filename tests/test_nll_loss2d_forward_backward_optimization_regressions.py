import pytest
import torch

import flag_gems


@pytest.mark.nll_loss2d_forward_backward
@pytest.mark.parametrize("spatial", [True])
def test_nll_saved_weight_version_check(spatial):
    x = torch.randn(
        (2, 3, 2, 2) if spatial else (2, 3), device=flag_gems.device, requires_grad=True
    )
    target = torch.zeros(
        (2, 2, 2) if spatial else (2,), device=x.device, dtype=torch.long
    )
    weight = torch.ones(3, device=x.device)
    fn = flag_gems.nll_loss2d_forward if spatial else flag_gems.nll_loss_forward
    loss, _ = fn(x, target, weight, 1, -100)
    weight[0] = 2
    with pytest.raises(RuntimeError, match="modified by an inplace operation"):
        torch.autograd.grad(loss, x)


pytestmark = [pytest.mark.nllloss]
