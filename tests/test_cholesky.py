@pytest.mark.parametrize("dtype", [torch.float32, torch.float64])
def test_cholesky(shape, dtype):
    # Create a positive-definite matrix: A = B @ B^T + I
    n = shape[-1]
    B = torch.randn(shape, dtype=dtype, device=flag_gems.device)
