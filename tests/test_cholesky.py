def _spd(n, dtype=torch.float32):
    B = torch.randn(n, n, dtype=dtype, device=flag_gems.device)
    return (
        B @ B.transpose(-2, -1)
        + torch.eye(n, dtype=dtype, device=flag_gems.device) * 0.1
    )


