import pytest
import torch

import flag_gems

from . import accuracy_utils as utils
from ._baddbmm_autograd import compare_gradients

pytestmark = [pytest.mark.baddbmm, pytest.mark.baddbmm_backward]


@pytest.mark.parametrize("dtype", utils.FLOAT_DTYPES)
@pytest.mark.parametrize(
    "shape",
    [
        (2, 3, 5, 7),
        (1, 1, 1, 1),
        (0, 3, 5, 7),
        (2, 0, 5, 7),
        (2, 3, 0, 7),
        (2, 3, 5, 0),
        (2, 17, 31, 23),
    ],
)
@pytest.mark.parametrize("strided", [False, True])
@pytest.mark.parametrize(
    "scalars",
    [(1.0, 1.0), (0.25, 0.5), (1.0, 0.0)],
)
def test_baddbmm_backward(dtype, shape, strided, scalars):
    batch, m, k, n = shape

    def tensor(shape):
        x = (
            torch.randn((*shape, 2), device=flag_gems.device, dtype=dtype)[..., 1]
            if strided
            else torch.randn(shape, device=flag_gems.device, dtype=dtype)
        )
        return x.detach().requires_grad_()

    inputs = [tensor((batch, m, k)), tensor((batch, k, n))]
    inputs.insert(0, tensor((n,)))
    kwargs = {"alpha": scalars[0], "beta": scalars[1]}
    refs = [x.detach().clone().requires_grad_() for x in inputs]
    output = flag_gems.baddbmm(*inputs, **kwargs)
    reference = torch.baddbmm(*refs, **kwargs)
    compare_gradients(
        output, reference, inputs, refs, dtype, reduce_dim=max(1, batch * m, m, n, k)
    )
