"""Accuracy tests for ``aten::slow_conv_transpose3d``.

The operator applies a 3D transposed convolution with the transposed-conv
weight layout ``(C_in, C_out, kD, kH, kW)``.  3D volumes grow cubically with the
output size, so the shapes below stay deliberately small: a single 3D output
plane already holds thousands of elements, which is enough to cover the
boundary masks, the stride/dilation remainder logic and the channel tiling
without making the reference (CPU/CUDA ``aten::slow_conv_transpose3d``) and the
Triton kernel expensive.
"""

import pytest
import torch

import flag_gems

from . import accuracy_utils as utils

# (input_shape, weight_shape) pairs, weight is (C_in, C_out, kD, kH, kW).
# Input volumes are kept at D=8, H=16, W=16 or smaller: 3D conv outputs scale
# as D*H*W*kD*kH*kW*C_in*C_out, and larger volumes push the slow reference
# kernel into seconds per case.
SHAPES_AND_WEIGHTS = [
    ((2, 4, 8, 16, 16), (4, 8, 3, 3, 3)),
    ((1, 8, 6, 8, 8), (8, 4, 2, 2, 2)),
]
# Stride/padding combinations in both accepted forms: a scalar int (which the
# operator broadcasts to all three spatial dims) and an explicit 3-triple.
STRIDE_PADDING = [
    (1, 0),
    (2, 0),
    ((2, 1, 1), (1, 0, 2)),
    ((1, 2, 3), (2, 2, 1)),
]


def _triple(value):
    if isinstance(value, int):
        return [value, value, value]
    return list(value)


def _atol(dtype):
    # fp16/bf16 accumulate in fp32 through the tensor-core path while the
    # reference computes in the storage dtype, so the low-precision cases need a
    # looser absolute tolerance than the fp32 default.
    return 2e-2 if dtype in (torch.float16, torch.bfloat16) else 1e-4


