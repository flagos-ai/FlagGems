import pytest
import torch

import flag_gems

pytestmark = [pytest.mark.cholesky_inverse, pytest.mark.cholesky_inverse_backward]


@pytest.mark.parametrize("dtype", [torch.float32, torch.float64])
@pytest.mark.parametrize(
    "shape", [(0, 0), (1, 1), (4, 4), (17, 17), (2, 32, 32), (2, 2, 8, 8), (0, 4, 4)]
)
@pytest.mark.parametrize("upper", [False, True])
@pytest.mark.parametrize("strided", [False, True])
def test_cholesky_inverse_backward(dtype, shape, upper, strided):
    n = shape[-1]
    value = torch.randn(shape, device=flag_gems.device, dtype=dtype) * 0.01
    value = value.triu() if upper else value.tril()
    value = value + torch.eye(n, device=value.device, dtype=dtype) * 2
    if strided:
        storage = torch.empty((*shape, 2), device=value.device, dtype=dtype)
        storage[..., 1] = value
        value = storage[..., 1]
    x = value.detach().requires_grad_()
    ref = x.detach().clone().requires_grad_()
    out = flag_gems.cholesky_inverse(x, upper=upper)
    expected = torch.cholesky_inverse(ref, upper=upper)
    grad = torch.randn_like(out)
    actual_grad = torch.autograd.grad(out, x, grad)[0]
    expected_grad = torch.autograd.grad(expected, ref, grad)[0]
    tolerance = 1e-5 if dtype == torch.float32 else 1e-10
    torch.testing.assert_close(out, expected, rtol=tolerance, atol=tolerance)
    torch.testing.assert_close(
        actual_grad, expected_grad, rtol=tolerance, atol=tolerance
    )
