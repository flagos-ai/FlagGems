def test_conv_depthwise3d_backward_shape_and_dtype(dtype):
    """The gradient carries the input's exact shape and dtype."""
    torch.manual_seed(0)
    inp = torch.randn((2, 1, 6, 6, 6), dtype=dtype, device=flag_gems.device)
    weight = torch.randn((1, 1, 3, 3, 3), dtype=dtype, device=flag_gems.device)
    ones = [1, 1, 1]
    out_shape = torch.ops.aten.conv_depthwise3d(
        inp, weight, [3, 3, 3], None, ones, ones, ones
    ).shape
    out_grad = torch.randn(out_shape, dtype=dtype, device=flag_gems.device)

    res_in_grad = flag_gems.conv_depthwise3d_backward(
        out_grad, inp, weight, [3, 3, 3], ones, ones, ones
    )
    assert res_in_grad.shape == inp.shape
    assert res_in_grad.dtype == dtype


@pytest.mark.conv_depthwise3d_backward
@pytest.mark.parametrize("dtype", BACKWARD_DTYPES)
def test_conv_depthwise3d_backward_noncontiguous_grad(dtype):
    """An expanded upstream gradient is non-contiguous and must not be read linearly."""
    torch.manual_seed(0)
    inp = torch.randn((2, 1, 6, 6, 6), dtype=dtype, device=flag_gems.device)
    weight = torch.randn((1, 1, 3, 3, 3), dtype=dtype, device=flag_gems.device)
    ones = [1, 1, 1]
    kernel = [3, 3, 3]
    out_shape = torch.ops.aten.conv_depthwise3d(
        inp, weight, kernel, None, ones, ones, ones
    ).shape

    base_grad = torch.randn((1, 1, *out_shape[2:]), dtype=dtype, device=inp.device)
    out_grad = base_grad.expand(out_shape)
    assert not out_grad.is_contiguous()

    ref_inp = inp.detach().to(dtype=torch.float64).requires_grad_(True)
    ref_weight = weight.detach().to(dtype=torch.float64)
    ref_out = torch.ops.aten.conv_depthwise3d(
        ref_inp, ref_weight, kernel, None, ones, ones, ones
    )
    (ref_in_grad,) = torch.autograd.grad(ref_out, ref_inp, out_grad.to(torch.float64))

    res_in_grad = flag_gems.conv_depthwise3d_backward(
        out_grad, inp, weight, kernel, ones, ones, ones
    )
    utils.gems_assert_close(
        res_in_grad,
        ref_in_grad,
        dtype,
        reduce_dim=_kernel_volume(weight.shape),
    )
