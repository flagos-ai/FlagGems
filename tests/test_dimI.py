def _make_coo(shape, sparse_dim, dtype, nnz=4, seed=0):
    """Build a COO tensor with ``sparse_dim`` sparse and the rest dense."""
    shape = tuple(shape)
    gen = torch.Generator().manual_seed(seed)
    indices = torch.stack(
        [
            torch.randint(0, size, (nnz,), dtype=torch.long, generator=gen)
            for size in shape[:sparse_dim]
        ]
    )
    dense_shape = shape[sparse_dim:]
    values = torch.randn((nnz,) + dense_shape, generator=gen)
    if dtype == torch.bool:
        values = values > 0
    else:
        values = values.to(dtype)
    return torch.sparse_coo_tensor(indices, values, shape, device=flag_gems.device)


def _make_empty_coo(shape, sparse_dim, dtype):
    shape = tuple(shape)
    indices = torch.empty(sparse_dim, 0, dtype=torch.long, device=flag_gems.device)
    values = torch.empty(
        (0,) + shape[sparse_dim:], dtype=dtype, device=flag_gems.device
    )
    return torch.sparse_coo_tensor(indices, values, shape, device=flag_gems.device)


