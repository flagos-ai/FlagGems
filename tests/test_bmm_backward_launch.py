    warm, _, inputs, _, _ = build(name, dtype)
    torch.autograd.grad(warm, inputs, torch.ones_like(warm))
    stream = torch.cuda.Stream(device=warm.device)
    with torch.cuda.stream(stream):
        out, ref, inputs, refs, reduction = build(name, dtype)
        incoming = torch.ones_like(out)
    stream.synchronize()
    caller = torch.cuda.current_stream()
    original = triton.runtime.driver.active.get_current_stream
    launches = []

    def record(device):
        result = original(device)
        launches.append((device, result))
        return result

    monkeypatch.setattr(triton.runtime.driver.active, "get_current_stream", record)
    actual = torch.autograd.grad(out, inputs, incoming)
    assert torch.cuda.current_stream() == caller
    stream.synchronize()
    assert launches and all(raw == stream.cuda_stream for _, raw in launches)
