def test_asinh_backward_no_torch_compute():
    class RecordOps(TorchDispatchMode):
        def __init__(self):
            self.names = []

        def __torch_dispatch__(self, func, types, args=(), kwargs=None):
            self.names.append(func._schema.name)
            return func(*args, **(kwargs or {}))

    inp = torch.randn((257,), device=flag_gems.device, requires_grad=True)
    grad = torch.randn_like(inp)
    out = flag_gems.asinh(inp)
    # Warm the pointwise code generator before observing the real backward.
    torch.autograd.grad(out, inp, grad, retain_graph=True)
    recorder = RecordOps()
    with recorder:
        torch.autograd.grad(out, inp, grad)
    forbidden = {
        "aten::pow",
        "aten::mul",
        "aten::add",
        "aten::rsqrt",
        "aten::sqrt",
        "aten::div",
    }
    assert forbidden.isdisjoint(recorder.names), recorder.names


