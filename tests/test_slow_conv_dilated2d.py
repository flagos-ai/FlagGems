def test_slow_conv_dilated2d_zero_in_channels(bias_on):
    """An empty contraction returns bias (or zero) pre-filled, not uninitialised.

    The native CUDA lane aborts on zero input channels (``CUDA kernel launch
    blocks must be positive``), so the expected value is the mathematical
    result: the empty sum plus the broadcast bias.
    """
    inp = torch.empty((1, 0, 4, 4), dtype=torch.float32, device=flag_gems.device)
    weight = torch.empty((3, 0, 3, 3), dtype=torch.float32, device=flag_gems.device)
