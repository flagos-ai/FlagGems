    x3 = torch.randn((3, 8, 8), dtype=dtype, device=flag_gems.device)
    weight = torch.randn((4, 3, 3, 3), dtype=dtype, device=flag_gems.device)
    ref_x3 = utils.to_reference(x3, True)
