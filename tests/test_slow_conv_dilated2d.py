    res_out = flag_gems.slow_conv_dilated2d(inp, weight, 3, bias, 1, 0, 1)

    assert res_out.shape == (1, 3, 2, 2)
    expected = (
        bias.reshape(1, 3, 1, 1).expand_as(res_out)
        if bias_on
        else torch.zeros_like(res_out)
    )
    assert torch.equal(res_out, expected)


