"""Accuracy tests for ``aten::slow_conv_dilated2d``.

``slow_conv_dilated2d`` is the dilated, ``groups == 1`` reference path for 2-D
cross correlation. The reference values come from
``torch.ops.aten.slow_conv_dilated2d`` itself (CPU or CUDA), which is available
for float16 / bfloat16 / float32 / float64 on both devices.

The operator takes its geometry as positional ``kernel_size`` / ``stride`` /
``padding`` / ``dilation`` pairs, so every case below passes them explicitly;
``stride`` / ``padding`` / ``dilation`` have no in-kernel defaults.
"""

import pytest
import torch

import flag_gems

from . import accuracy_utils as utils

# (input shape, weight shape, kernel_size) triples. The first two keep the
# kernel smaller than the input under every stride/padding/dilation combination
# exercised below; the third is a non-square plane with a matching 1 x 2 kernel
# so the two spatial axes cannot be transposed by accident.
SHAPE_CASES = [
    ((2, 3, 8, 8), (4, 3, 3, 3), (3, 3)),
    ((1, 2, 7, 9), (3, 2, 2, 2), (2, 2)),
    ((2, 4, 12, 12), (6, 4, 3, 3), (3, 3)),
]

# Geometry sweep: unit step vs a genuine stride, no padding vs a border, and the
# minimal dilation vs a real dilated (atrous) receptive field.
STRIDES = [(1, 1), (2, 2)]
PADDINGS = [(0, 0), (1, 1)]
DILATIONS = [(1, 1), (2, 2)]

# Low-precision convolution accumulates a long reduction chain over
# C_in * kH * kW taps, so fp16/bf16 outputs drift from the fp64 reference well
# beyond the framework's default 1e-4 absolute tolerance.
LOW_PRECISION_ATOL = 2e-2
DEFAULT_ATOL = 1e-4


def _atol(dtype):
    return (
        LOW_PRECISION_ATOL if dtype in (torch.float16, torch.bfloat16) else DEFAULT_ATOL
    )


@pytest.mark.slow_conv_dilated2d
@pytest.mark.parametrize("shape_input, shape_weight, kernel", SHAPE_CASES)
@pytest.mark.parametrize("stride", STRIDES)
@pytest.mark.parametrize("padding", PADDINGS)
@pytest.mark.parametrize("dilation", DILATIONS)
@pytest.mark.parametrize("bias", [True, False])
@pytest.mark.parametrize("dtype", utils.FLOAT_DTYPES)
def test_slow_conv_dilated2d(
    shape_input, shape_weight, kernel, stride, padding, dilation, bias, dtype
):
    inp = torch.randn(shape_input, dtype=dtype, device=flag_gems.device)
    weight = torch.randn(shape_weight, dtype=dtype, device=flag_gems.device)
    ref_inp = utils.to_reference(inp, True)
    ref_weight = utils.to_reference(weight, True)

    if bias:
        bias_tensor = torch.randn(shape_weight[0], dtype=dtype, device=flag_gems.device)
        ref_bias = utils.to_reference(bias_tensor, True)
    else:
        bias_tensor = None
        ref_bias = None

    ref_out = torch.ops.aten.slow_conv_dilated2d(
        ref_inp, ref_weight, list(kernel), ref_bias, stride, padding, dilation
    )

    with flag_gems.use_gems():
        res_out = torch.ops.aten.slow_conv_dilated2d(
            inp, weight, list(kernel), bias_tensor, stride, padding, dilation
        )

    utils.gems_assert_close(res_out, ref_out, dtype, atol=_atol(dtype))


