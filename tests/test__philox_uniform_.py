"""Accuracy tests for ``aten::_philox_uniform_``.

``_philox_uniform_`` is a stateless Philox RNG operator whose result is a pure
function of the ``(seed, offset)`` pair carried in ``key``. torch builds that
ship the operator can be compared against directly; for builds that predate it
(no schema in the installed torch) the reference is computed here from the
same ATen algorithm: Philox-4x32 counter values mapped through
``transformation::uniform_real``.

The reference re-implements ``aten/src/ATen/native/cuda/PhiloxDistribution.cu``
step for step so the comparison is exact rather than statistical.
"""

import numpy as np
import pytest
import torch

import flag_gems

from . import accuracy_utils as utils

# 32-bit Philox-4x32 constants, as used by ATen's StatelessPhilox4x32.cuh.
_PHILOX_KEY_A = np.uint32(0x9E3779B9)
_PHILOX_KEY_B = np.uint32(0xBB67AE85)
_PHILOX_ROUND_A = np.uint32(0xD2511F53)
_PHILOX_ROUND_B = np.uint32(0xCD9E8D57)
_U64_MAX = np.uint64(0xFFFFFFFF)

# numeric_limits<T>::digits drives the mantissa extraction in
# at::transformation::uniform_real.
_DIGITS = {
    torch.float16: 11,
    torch.bfloat16: 8,
    torch.float32: 24,
    torch.float64: 53,
}


def _mulhilo32(a, b):
    p = a.astype(np.uint64) * b.astype(np.uint64)
    return (p & _U64_MAX).astype(np.uint32), (p >> np.uint64(32)).astype(np.uint32)


def _philox_round(ctr, key):
    c0, c1, c2, c3 = ctr
    k0, k1 = key
    r0_lo, r0_hi = _mulhilo32(_PHILOX_ROUND_A, c0)
    r1_lo, r1_hi = _mulhilo32(_PHILOX_ROUND_B, c2)
    return (
        np.uint32(r1_hi ^ c1 ^ k0),
        r1_lo,
        np.uint32(r0_hi ^ c3 ^ k1),
        r0_lo,
    )


def _philox_4x32(seed, offset, rounds=10):
    """Stateless Philox-4x32 with subsequence fixed to 0."""
    seed = np.uint64(seed)
    offset = np.uint64(offset)
    key = (
        np.uint32(seed & _U64_MAX),
        np.uint32(seed >> np.uint64(32)),
    )
    ctr = (
        np.uint32(offset & _U64_MAX),
        np.uint32(offset >> np.uint64(32)),
        np.uint32(0),
        np.uint32(0),
    )
    for _ in range(rounds - 1):
        ctr = _philox_round(ctr, key)
        key = (
            np.uint32(
                (key[0].astype(np.uint64) + _PHILOX_KEY_A.astype(np.uint64)) & _U64_MAX
            ),
            np.uint32(
                (key[1].astype(np.uint64) + _PHILOX_KEY_B.astype(np.uint64)) & _U64_MAX
            ),
        )
    return _philox_round(ctr, key)


def _quantize(value, torch_dtype):
    """Round a python float through the operator's storage dtype."""
    return torch.tensor(value, dtype=torch_dtype).item()


def _reference_uniform(numel, seed, offset, low, high, torch_dtype):
    """Compute the expected ``_philox_uniform_`` output on the same algorithm.

    Mirrors ATen: the endpoints are cast to the output scalar type first
    (c10::Half/BFloat16 arithmetic rounds ``hi - lo`` back to the storage
    dtype), the mantissa extraction runs in ``numeric_limits<T>::digits`` bits,
    and each sample is cast back to ``scalar_t`` before storing.
    """
    digits = _DIGITS[torch_dtype]
    per_counter = 2 if torch_dtype == torch.float64 else 4
    if torch_dtype == torch.float64:
        acc_dtype, out_dtype = np.float64, np.float64
    else:
        acc_dtype, out_dtype = np.float32, np.float32
    mask = np.uint64((1 << digits) - 1)
    divisor = acc_dtype(1.0) / acc_dtype(2.0**digits)

    lo = _quantize(low, torch_dtype)
    hi = _quantize(high, torch_dtype)
    if torch_dtype in (torch.float16, torch.bfloat16):
        # c10::Half/BFloat16 operator- rounds the difference to storage dtype.
        rng = _quantize(hi - lo, torch_dtype)
    else:
        rng = hi - lo

    out = np.empty(numel, dtype=out_dtype)
    for i in range(numel):
        r0, r1, r2, r3 = _philox_4x32(
            np.uint64(seed), np.uint64(offset) + np.uint64(i // per_counter)
        )
        j = i % per_counter
        if torch_dtype == torch.float64:
            word = (
                (np.uint64(r0) << np.uint64(32)) | np.uint64(r1)
                if j == 0
                else (np.uint64(r2) << np.uint64(32)) | np.uint64(r3)
            )
            x = (word & mask).astype(acc_dtype) * divisor
            out[i] = acc_dtype(x * (hi - lo) + lo)
        else:
            word = [r0, r1, r2, r3][j]
            x = np.float32(np.uint32(word & np.uint32(mask))) * divisor
            out[i] = acc_dtype(x * acc_dtype(rng) + acc_dtype(lo))
    # numpy has no half-precision bfloat16 view, so round through torch and
    # hand the comparison a tensor in the target dtype.
    result = torch.from_numpy(out).to(torch_dtype)
    # Keep the reference on the test device, but on CPU under --ref cpu so
    # to_cpu()'s device assertion in gems_assert_close holds.
    if utils.TO_CPU:
        return result
    return result.to(flag_gems.device)


def _make_key(seed, offset, device):
    return torch.tensor([seed, offset], dtype=torch.uint64, device=device)


