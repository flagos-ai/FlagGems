@pytest.mark.philox_uniform_
def test_philox_uniform_value_range():
    """Samples always land in [low, high) regardless of the stream state."""
    for dtype in (torch.float16, torch.float32, torch.bfloat16):
        for low, high in ((-4.0, -1.0), (0.0, 1.0), (-2.5, 7.5)):
            key = _make_key(2024, 1 << 20, flag_gems.device)
            out = flag_gems._philox_uniform_(
                torch.empty(4096, dtype=dtype, device=flag_gems.device),
                key,
                low,
                high,
            )
            outf = out.float()
            assert outf.min().item() >= low
            assert outf.max().item() < high


