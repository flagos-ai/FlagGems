"""Accuracy tests for ``aten::glu_jvp``.

``glu_jvp(glu, x, dx, dim)`` pushes a tangent ``dx`` through
:func:`torch.nn.functional.glu`: with ``a``/``b`` the two halves of ``x``
narrowed along ``dim`` and ``glu = a * sigmoid(b)``, the output is
``dx_a * sigmoid(b) + glu * (1 - sigmoid(b)) * dx_b``. ``glu`` therefore has
the shape of ``F.glu(x, dim)`` (the ``dim`` axis halved) and is consumed as an
independent operand, so the test computes it with ``F.glu`` beforehand.

Shapes exercise every kernel addressing mode: contiguous 2D/3D inputs, a 4D
input with the tangent applied along each of three dims (including negative),
and non-contiguous ``x``/``dx`` produced by a transpose on an axis other than
the narrowed one. Half-precision JVP values are large relative to fp32
tolerances (the pushed-forward tangent spans the sigmoid derivative), so
fp16/bfloat16 use a looser absolute tolerance.
"""

import pytest
import torch

import flag_gems

from . import accuracy_utils as utils

# Shapes mirror utils.GLU_SHAPES: even extents on the narrowed dim for every
# rank covered by the kernel's slot addressing, plus a non-contiguous variant.
SHAPES = [(2,), (128, 256), (20, 32, 16), (16, 128, 64, 60)]
NON_CONTIGUOUS_SHAPE = (8, 2, 6, 8)


@pytest.mark.glu_jvp
@pytest.mark.parametrize("shape", SHAPES)
@pytest.mark.parametrize("dim", [-1, 0, 1])
@pytest.mark.parametrize("dtype", utils.FLOAT_DTYPES)
def test_glu_jvp(shape, dim, dtype):
    if dim >= len(shape):
        pytest.skip("dim out of range for this shape")

    x = torch.randn(shape, dtype=dtype, device=flag_gems.device)
    dx = torch.randn(shape, dtype=dtype, device=flag_gems.device)
    ref_x = utils.to_reference(x, True)
    ref_dx = utils.to_reference(dx, True)

    ref_glu = torch.nn.functional.glu(ref_x, dim=dim)
    res_glu = torch.nn.functional.glu(x, dim=dim)

    ref_out = torch.ops.aten.glu_jvp(ref_glu, ref_x, ref_dx, dim)
    res_out = flag_gems.glu_jvp(res_glu, x, dx, dim)
    atol = 1e-2 if dtype in (torch.float16, torch.bfloat16) else 1e-4
    utils.gems_assert_close(res_out, ref_out, dtype, atol=atol)


@pytest.mark.glu_jvp
@pytest.mark.parametrize("dtype", utils.FLOAT_DTYPES)
def test_glu_jvp_non_contiguous(dtype):
    # x/dx non-contiguous via a transpose on an axis other than the narrowed
    # dim, so the kernel takes the general (index-decomposed) addressing path.
    x = torch.randn(NON_CONTIGUOUS_SHAPE, dtype=dtype, device=flag_gems.device)
    dx = torch.randn(NON_CONTIGUOUS_SHAPE, dtype=dtype, device=flag_gems.device)
    x = x.transpose(1, 2)
    dx = dx.transpose(1, 2)
    ref_x = utils.to_reference(x, True)
    ref_dx = utils.to_reference(dx, True)

    ref_glu = torch.nn.functional.glu(ref_x, dim=2)
    res_glu = torch.nn.functional.glu(x, dim=2)

    ref_out = torch.ops.aten.glu_jvp(ref_glu, ref_x, ref_dx, 2)
    res_out = flag_gems.glu_jvp(res_glu, x, dx, 2)
    atol = 1e-2 if dtype in (torch.float16, torch.bfloat16) else 1e-4
    utils.gems_assert_close(res_out, ref_out, dtype, atol=atol)
