import pytest
import torch

import flag_gems

from . import accuracy_utils as utils


@pytest.mark.flatten_dense_tensors
@pytest.mark.parametrize("dtype", utils.FLOAT_DTYPES)
@pytest.mark.parametrize("count", [1, 2, 3, 4, 7])
@pytest.mark.parametrize("layout", ["contiguous", "transpose", "offset", "empty"])
def test_flatten_dense_tensors(dtype, count, layout):
    tensors = []
    for i in range(count):
        t = torch.randn((3 + i, 9), device=flag_gems.device, dtype=dtype)
        if layout == "transpose":
            t = t.t()
        elif layout == "offset":
            t = t[1:, 1::2]
        elif layout == "empty":
            t = t[:0]
        tensors.append(t)
    refs = [utils.to_reference(t) for t in tensors]
    ref = torch.ops.aten.flatten_dense_tensors.default(refs)
    res = flag_gems.flatten_dense_tensors(tensors)
    utils.gems_assert_equal(res, ref)
    assert res.stride() == ref.stride()
    if res.numel():
        assert (res.data_ptr() == tensors[0].data_ptr()) == (
            count == 1 and tensors[0].is_contiguous()
        )


