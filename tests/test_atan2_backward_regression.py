import pytest
import torch

import flag_gems

from . import accuracy_utils as utils

pytestmark = [pytest.mark.atan2, pytest.mark.atan2_backward]


@pytest.mark.parametrize("seed", range(64))
@pytest.mark.parametrize("scalar_first", [False, True])
def test_atan2_backward_bf16_broadcast_rounding(seed, scalar_first):
    # Fixed seeds preserve the regression across rounds and reference modes.
    generator = torch.Generator(device=flag_gems.device).manual_seed(seed)
    shapes = [(), (17, 33)] if scalar_first else [(17, 33), ()]
    values = [
        torch.randn(
            (*shape, 2),
            device=flag_gems.device,
            dtype=torch.bfloat16,
            generator=generator,
        )[..., 1]
        .detach()
        .requires_grad_(True)
        for shape in shapes
    ]
    references = [value.detach().clone().requires_grad_(True) for value in values]
    grad = torch.randn(
        (17, 33, 3), device=flag_gems.device, dtype=torch.bfloat16, generator=generator
    )[..., 1]
    expected = torch.autograd.grad(torch.atan2(*references), references, grad)
    actual = torch.autograd.grad(flag_gems.atan2(*values), values, grad)
    for result, reference in zip(actual, expected):
        utils.gems_assert_close(
            result,
            utils.to_reference(reference),
            torch.bfloat16,
            reduce_dim=15,
            equal_nan=True,
        )
