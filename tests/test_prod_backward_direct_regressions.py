import pytest
import torch

import flag_gems

from . import accuracy_utils as utils


@pytest.mark.prod_backward
@pytest.mark.parametrize("value", [0.99951171875, 1.0009765625])
def test_product_single_zero_against_float64_derivative(value):
    x = torch.full((257,), value, dtype=torch.float16, device=flag_gems.device)
    x[0] = 0
    x.requires_grad_()
    output = flag_gems.prod(x)
    grad = torch.tensor(0.75, device=x.device, dtype=x.dtype)
    (result,) = torch.autograd.grad(output, x, grad)
    # Analytic derivative at the sole zero, independently accumulated in FP64.
    derivative = torch.full((256,), value, dtype=torch.float64).prod()
    reference = torch.zeros(257, dtype=x.dtype)
    reference[0] = derivative.to(x.dtype) * grad.cpu()
    utils.gems_assert_close(result, utils.to_reference(reference.to(x.device)), x.dtype)


pytestmark = [pytest.mark.prod]
