# ``_nested_tensor_strides`` reads only layout metadata: the output is a CPU
# int64 tensor of shape (num_tensors, max_rank) and never depends on the
# constituent values or dtypes. Coverage is driven by the shape families
# (1-D/2-D/3-D inner, single constituent), by dtype, and by the storage-layout
# family: plain nested tensors report contiguous strides, while tensors built
# over a shared buffer report the stored (possibly non-contiguous) strides --
# the distinction a recomputing implementation gets wrong.
#
# NOTE on mixed ranks: constituents of different rank cannot be nested on this
# build. ``torch.nested.nested_tensor([zeros(2, 3), zeros(4, 5, 6)])`` (and
# ``_nested_tensor_from_tensor_list``) raises "All Tensors given to
# nested_tensor must have the same dimension", and the jagged layout rejects
# ``_nested_tensor_strides`` with NotImplementedError. Only trailing dimensions
# may vary within one rank, which is what NT_SHAPE_SETS covers.
