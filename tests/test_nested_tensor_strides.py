@pytest.mark.nested_tensor_strides
def test_nested_tensor_strides_dispatch_stability():
    # The impl delegates to the very op it registers (below the autograd key);
    # repeated dispatcher calls with an unrelated native op in between must
    # stay stable: no recursion, no state drift, identical values.
    nt = _make_nested(torch.float32, flag_gems.device, ((2, 3), (4, 5)))

    first = flag_gems._nested_tensor_strides(nt)
    for _ in range(3):
        x = torch.randn(8, device=flag_gems.device)
        _ = torch.relu(x)
        again = flag_gems._nested_tensor_strides(nt)
        assert again.equal(first)

    # The aten op and the bound method route into the same impl.
    via_op = torch.ops.aten._nested_tensor_strides.default(nt)
    via_method = nt._nested_tensor_strides()
    assert via_op.equal(first)
    assert via_method.equal(first)


