@pytest.mark.to_mkldnn
@pytest.mark.parametrize("shape,dtype,out_dtype", OUT_ROWS)
def test_to_mkldnn_out_overload(shape, dtype, out_dtype):
    inp = tu.make_input(dtype, shape, ["-1", "1"]).cpu()
    ref_inp = tu.to_reference(inp)
    result_dtype = inp.dtype if out_dtype is None else out_dtype

    ref_out = torch.empty(shape, dtype=result_dtype, layout=torch._mkldnn)
    res_out = torch.empty(shape, dtype=result_dtype, layout=torch._mkldnn)

    torch.ops.aten.to_mkldnn(ref_inp, out_dtype, out=ref_out)
    res = flag_gems.to_mkldnn(inp, out_dtype, out=res_out)

    # The out overload returns the buffer it was given, not a fresh tensor.
    assert res is res_out
    tu.assert_result_equal(res_out.to_dense(), ref_out.to_dense())
    tu.assert_result_equal(inp, ref_inp)


@pytest.mark.to_mkldnn
@pytest.mark.parametrize("shape,dtype", BACKWARD_ROWS)
def test_to_mkldnn_backward(shape, dtype):
    inp = tu.make_input(dtype, shape, ["-1", "1"]).cpu()
    ref_inp = tu.to_reference(inp)
    upstream = tu.make_input(dtype, shape, ["-1", "1"]).cpu()
    inp.requires_grad_(True)
    ref_inp.requires_grad_(True)

    ref_out = torch.ops.aten.to_mkldnn(ref_inp)
    res_out = flag_gems.to_mkldnn(inp)

    # Forward contract first: the candidate returns the native opaque layout.
    assert res_out.is_mkldnn
    tu.assert_result_equal(res_out.to_dense(), ref_out.to_dense())

    # An mkldnn result only accepts an mkldnn upstream gradient, so the identity
    # through to_dense() carries the non-uniform upstream to the original leaf.
    (ref_grad,) = torch.autograd.grad(
        ref_out.to_dense(), ref_inp, grad_outputs=upstream
    )
    (res_grad,) = torch.autograd.grad(res_out.to_dense(), inp, grad_outputs=upstream)

    tu.assert_result_equal(res_grad, ref_grad)


