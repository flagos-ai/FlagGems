def _round(tensor, dtype):
    """Send an intermediate through ``dtype`` and back to the working precision."""
    return tensor.to(dtype).to(tensor.dtype)


def _reference(input, hx, w_ih, w_hh, b_ih, b_hh, dtype):
    """Eager decomposition of the cell.

    The eager op is a sequence of separate ``linear``, ``add`` and ``relu``
    calls, so every intermediate lands in ``dtype`` before feeding the next
    one. The reference reproduces those boundaries, and only the math *within*
    each step runs at the wider reference precision.
    """
    gi = _round(torch.nn.functional.linear(input, w_ih, b_ih), dtype)
    gh = _round(torch.nn.functional.linear(hx, w_hh, b_hh), dtype)
    return torch.relu(_round(gi + gh, dtype))


def _inputs(batch, input_size, hidden_size, dtype, bias=True, seed=0):
    torch.manual_seed(seed)
    dev = flag_gems.device
    input = torch.randn(batch, input_size, dtype=dtype, device=dev)
    hx = torch.randn(batch, hidden_size, dtype=dtype, device=dev)
    # Scaled down to keep the pre-activations modest, so the relu passes
    # through values of a comparable magnitude for every hidden size.
    w_ih = torch.randn(hidden_size, input_size, dtype=dtype, device=dev) * 0.1
    w_hh = torch.randn(hidden_size, hidden_size, dtype=dtype, device=dev) * 0.1
    b_ih = torch.randn(hidden_size, dtype=dtype, device=dev) if bias else None
    b_hh = torch.randn(hidden_size, dtype=dtype, device=dev) if bias else None
    return input, hx, w_ih, w_hh, b_ih, b_hh


