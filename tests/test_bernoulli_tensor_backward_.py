@pytest.mark.parametrize("dtype", utils.FLOAT_DTYPES)
@pytest.mark.parametrize("shape", [(), (0,), (2, 0, 3), (3, 17)])
@pytest.mark.parametrize("probability_shape", ["scalar", "full"])
@pytest.mark.parametrize("needs", [(True, False), (False, True), (True, True)])
def test_bernoulli_tensor_backward_(dtype, shape, probability_shape, needs):
    x = torch.rand(shape, device=flag_gems.device, dtype=dtype, requires_grad=needs[0])
    p = torch.rand(
        () if probability_shape == "scalar" else shape,
        device=flag_gems.device,
        dtype=dtype,
        requires_grad=needs[1],
    )
    rx, rp = [t.detach().clone().requires_grad_(need) for t, need in zip((x, p), needs)]
    output = flag_gems.bernoulli_(x.clone(), p)
    reference = rx.clone().bernoulli_(rp)
    inputs = [t for t, need in zip((x, p), needs) if need]
    refs = [t for t, need in zip((rx, rp), needs) if need]
    incoming = torch.full_like(output, float("nan"))
    actual = torch.autograd.grad(output, inputs, incoming, retain_graph=True)
    expected = torch.autograd.grad(reference, refs, incoming)
    for a, b in zip(actual, expected):
        utils.gems_assert_equal(a, utils.to_reference(b))
    for result in actual:
        result.fill_(7)
    repeated = torch.autograd.grad(output, inputs, torch.ones_like(output))
    for result, ref in zip(repeated, expected):
        utils.gems_assert_equal(result, utils.to_reference(ref))


