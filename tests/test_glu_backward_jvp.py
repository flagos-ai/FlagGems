"""Accuracy tests for ``aten::glu_backward_jvp``.

``glu_backward_jvp`` is the forward-mode (JVP) rule that PyTorch's
``torch.func.jvp`` reaches for :func:`torch.nn.functional.glu`. It consumes the
forward-mode tangents of the glu inputs together with the reverse-mode gradient
w.r.t. the glu output and the tangent of that gradient, and produces the tangent
of the gradient w.r.t. ``x``:

    x, dx, grad_x : shape of ``x``            (the split axis holds two halves)
    grad_glu      : shape of ``glu(x, dim)``  (the split axis is halved)
    dgrad_glu     : ``grad_glu`` shape, or 1 along ``dim`` to broadcast

The reference follows the ATen composite the operator is documented against::

    g   = torch.nn.functional.glu(x, dim)
    gb  = torch.ops.aten.glu_backward(g, x, dim)   # only used to pin the split
    out = torch.ops.aten.glu_backward_jvp(grad_x, g, x, dgrad_glu, dx, dim)

``grad_glu`` (the second operand) and ``gb`` only supply the split extent and
are never loaded, so the test feeds the same random ``grad_x`` to the ATen
reference and to the FlagGems call.
"""

import pytest
import torch

import flag_gems

from . import accuracy_utils as utils

# Every shape keeps ``dim`` even so the GLU split into two halves is exact, and
# every listed ``dim`` pair below is chosen per shape accordingly. Ranks 3 to 5
# cover the leading, middle and trailing split-axis layouts that the kernel's
# address decode specialises on.
GLU_BWD_JVP_SHAPES = [
    (4, 8, 16),
    (2, 16, 32),
    (2, 4, 8, 16),
    (1, 8, 4, 8, 16),
]

# ``dim`` covers the leading, a middle and the trailing axis of the shapes
# above; ``-1`` and ``2`` both select the trailing axis, the layout real gated
# activations use. Shape (1, 8, 4, 8, 16) is only valid for the trailing dims
# because its leading extent is 1 (odd), so dims for it are filtered at runtime.
GLU_BWD_JVP_DIMS = [0, 1, 2, -1]

# The reference runs upcast to fp64 (``utils.to_reference(t, True)``) and
# ``gems_assert_close`` rounds it back to the input dtype before comparing, so
# even the bitwise-identical ATen CUDA kernel shows double-rounding error
# against the fp64 reference for fp16/bf16 (measured up to ~0.13 in bf16).
# fp32 results also lose precision when the fp64 reference is rounded back
# (``rtol`` 1.3e-6 makes the check sensitive), hence the loose fp32 atol too.
LOW_PRECISION_ATOL = 2e-1
FP32_ATOL = 2e-2


def _make_inputs(shape, dim, dtype, device):
    """Build the five operands of ``glu_backward_jvp`` for one test case."""
    glu_shape = list(shape)
    glu_shape[dim] //= 2
    return (
        torch.randn(shape, dtype=dtype, device=device),
        torch.randn(glu_shape, dtype=dtype, device=device),
        torch.randn(shape, dtype=dtype, device=device),
        torch.randn(glu_shape, dtype=dtype, device=device),
        torch.randn(shape, dtype=dtype, device=device),
    )


def _reference(grad_x, grad_glu, x, dgrad_glu, dx, dim):
    g = torch.nn.functional.glu(x, dim)
    # ``gb`` only pins the split extent along ``dim``; the actual first operand
    # of the JVP rule is ``grad_x`` itself, exactly as ATen documents.
    gb = torch.ops.aten.glu_backward(g, x, dim)
    assert gb.shape == grad_x.shape
    assert g.shape == grad_glu.shape
    return torch.ops.aten.glu_backward_jvp(grad_x, g, x, dgrad_glu, dx, dim)


@pytest.mark.glu_backward_jvp
@pytest.mark.parametrize("dim", GLU_BWD_JVP_DIMS)
@pytest.mark.parametrize("shape", GLU_BWD_JVP_SHAPES)
@pytest.mark.parametrize("dtype", utils.FLOAT_DTYPES)
def test_glu_backward_jvp(shape, dim, dtype):
    d = dim % len(shape)
    # GLU halves ``dim``; skip combinations whose split axis is odd.
    if shape[d] % 2 != 0:
        pytest.skip(f"shape {shape} has odd extent {shape[d]} along dim {dim}")
    tensors = _make_inputs(shape, dim, dtype, flag_gems.device)
    ref_tensors = [utils.to_reference(t, True) for t in tensors]

    ref_out = _reference(*ref_tensors, dim)

    res_out = flag_gems.glu_backward_jvp(*tensors, dim)
    atol = FP32_ATOL if dtype == torch.float32 else LOW_PRECISION_ATOL
    utils.gems_assert_close(res_out, ref_out, dtype, atol=atol)


