import pytest
import torch

import flag_gems

from . import accuracy_utils as utils

pytestmark = [pytest.mark.pow_backward, pytest.mark.pow]


# Existing FlagGems forward tests use an upcast golden reference. CUDA's
# weak-scalar Half/BFloat16 conversion is intentionally a backward reference.
@pytest.mark.parametrize("dtype", utils.FLOAT_DTYPES)
@pytest.mark.parametrize("exponent", [-0.999, 2.3, 100.001, -111.999])
def test_scalar_forward_preserves_upstream_nan_semantics(dtype, exponent):
    x = torch.tensor(
        [-2.0, -1.0, -0.5, 0.5, 1.0, 2.0], dtype=dtype, device=flag_gems.device
    )
    actual = flag_gems.pow_tensor_scalar(x, exponent)
    expected = torch.pow(utils.to_reference(x, True), exponent)
    utils.gems_assert_close(actual, expected, dtype, equal_nan=True)


@pytest.mark.parametrize("dtype", utils.FLOAT_DTYPES)
@pytest.mark.parametrize("exponent", [-0.999, 2.3, 100.001, -111.999])
def test_scalar_backward_native_cuda_rounding(dtype, exponent):
    x = torch.linspace(
        0.95, 1.05, 65, dtype=dtype, device=flag_gems.device
    ).requires_grad_()
    ref = x.detach().clone().requires_grad_()
    actual = flag_gems.pow_tensor_scalar(x, exponent)
    expected = torch.pow(ref, exponent)
    upstream = torch.full_like(actual, 0.75)
    (gradient,) = torch.autograd.grad(actual, x, upstream)
    (reference,) = torch.autograd.grad(expected, ref, upstream)
    utils.gems_assert_close(
        gradient, utils.to_reference(reference), dtype, equal_nan=True
    )
