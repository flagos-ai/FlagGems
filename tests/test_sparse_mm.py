def _make_sparse(M, K, dtype, device, sparsity, layout):
    """Build the masked dense values and the sparse tensor in ``layout``."""
    dense = torch.randn((M, K), dtype=torch.float32, device=device)
    if sparsity == 0.0:
        mask = torch.ones((M, K), dtype=torch.bool, device=device)
    elif sparsity == 1.0:
        mask = torch.zeros((M, K), dtype=torch.bool, device=device)
    else:
        mask = torch.rand((M, K), device=device) > sparsity
    values = (dense * mask).to(dtype)
    if layout == "csc":
        sparse = values.to_sparse_csc()
    elif layout == "coo":
        sparse = values.to_sparse()
    else:
        sparse = values.to_sparse_csr()
    # to_sparse_* drops explicit zeros; densify so the reference uses exactly
    # the stored pattern (matters for the amax/amin reductions).
    return values, sparse


def _reference(sparse, mat2):
    """fp64 reference built with ``to_reference(upcast=True)``.

    A plain fp32 GPU matmul would use TF32, which drifts far beyond the fp32
    tolerance of this op; upcasting also puts the reference on CPU under
    ``--ref cpu`` so its device matches the returned tensor.
    """
    ref_sparse = utils.to_reference(sparse, True)
    ref_mat2 = utils.to_reference(mat2, True)
    return ref_sparse.to_dense() @ ref_mat2


def _reduce_reference(sparse, mat2, reduce):
    """fp64 reference for the ``.reduce`` overload.

    torch only implements ``aten::_sparse_mm.reduce`` on the CPU sparse CSR
    backend, so the reference is computed explicitly from the per-nnz
    products: ``sum`` is the plain SpMM, ``mean`` divides by the row's stored
    nnz, and amax/amin fold the products. The fold walks the stored CSR
    entries only -- implicit zeros at non-nnz positions are not part of the
    reduction (verified against torch's CPU kernel) -- and rows with no stored
    entries yield 0 for every reduction.
    """
    ref_sparse = utils.to_reference(sparse, True)
    ref_mat2 = utils.to_reference(mat2, True)
    sd = ref_sparse.to_dense()
    crow = ref_sparse.crow_indices()
    col = ref_sparse.col_indices()
    vals = ref_sparse.values()
    M, N = ref_sparse.shape[0], ref_mat2.shape[1]
    if reduce == "sum":
        return sd @ ref_mat2
    out = torch.zeros((M, N), dtype=ref_mat2.dtype, device=ref_mat2.device)
    for r in range(M):
        start, end = int(crow[r]), int(crow[r + 1])
        if end == start:
            continue
        prod = vals[start:end, None] * ref_mat2[col[start:end]]
        if reduce == "mean":
            out[r] = prod.sum(dim=0) / (end - start)
        elif reduce == "amax":
            out[r] = prod.max(dim=0).values
        else:
            out[r] = prod.min(dim=0).values
    return out


