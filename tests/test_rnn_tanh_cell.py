    hx = torch.randn(batch_size, hidden_size, dtype=dtype, device=flag_gems.device)
    w_ih = torch.randn(hidden_size, input_size, dtype=dtype, device=flag_gems.device)
    w_hh = torch.randn(hidden_size, hidden_size, dtype=dtype, device=flag_gems.device)
    if has_bias:
        b_ih = torch.randn(hidden_size, dtype=dtype, device=flag_gems.device)
        b_hh = torch.randn(hidden_size, dtype=dtype, device=flag_gems.device)
    else:
        b_ih, b_hh = None, None
    return inp, hx, w_ih, w_hh, b_ih, b_hh


