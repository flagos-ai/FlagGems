# The native PyTorch composite kernel rounds the intermediate gate products to
# the input dtype before the tanh, while the Triton kernel accumulates in
# float32 and is therefore *closer* to a float64 reference.  Comparing the two
# low-precision paths elementwise needs a looser atol than the FlagGems default.
_ATOL = {torch.float32: 1e-4, torch.float16: 5e-3, torch.bfloat16: 3e-2}

