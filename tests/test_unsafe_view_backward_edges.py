from . import accuracy_utils as utils
from ._unsafe_view_backward_pointwise import TOL

DTYPES = list(dict.fromkeys([*utils.FLOAT_DTYPES, torch.float64]))


def close(a, b, dtype):
    torch.testing.assert_close(
        a.cpu(),
        b.cpu().to(dtype),
        rtol=TOL[dtype][0],
        atol=TOL[dtype][1],
        equal_nan=True,
    )


@pytest.mark.unsafe_view_backward
@pytest.mark.unsafe_view_backward
@pytest.mark.sort_backward
@pytest.mark.parametrize("dtype", DTYPES)
def test_rank9_and_scalar_view(dtype):
    shape = (2, 1, 2, 1, 2, 1, 2, 1, 2)
    g = torch.randn(4, 8, 2, device=flag_gems.device, dtype=dtype)[..., 1]
    close(flag_gems.unsafe_view_backward(g, shape), g.reshape(shape), dtype)
