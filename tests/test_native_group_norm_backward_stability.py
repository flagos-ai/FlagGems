# These seeds reproduce native CPU/CUDA cancellation differences against the
# independent FP64 supplied-statistic VJP. Keep the original tolerance.
@pytest.mark.parametrize("seed", [12, 60, 106, 146, 217])
@pytest.mark.parametrize("strided", [False, True])
@pytest.mark.parametrize("mask", [(True, True, True), (True, False, False)])
def test_hw1_fixed_seed_fp64_derivative(seed, strided, mask):
    torch.manual_seed(seed)
    case = make_case(
        "native_group_norm_backward", torch.float32, (3, 4, 1, 1), strided, 0
    )
    args = (*case.args[:-1], mask)
    actual = flag_gems.group_norm_backward(*args)
    expected = group_norm_hw1_fp64_gradient(args)
    utils.gems_assert_close(
        actual[0],
        utils.to_reference(expected),
        torch.float32,
        reduce_dim=3,
        equal_nan=True,
    )
    dense = tuple(t.contiguous() if isinstance(t, torch.Tensor) else t for t in args)
    native = torch.ops.aten.native_group_norm_backward(*dense)
    for index in (1, 2):
        if mask[index]:
            utils.gems_assert_close(
                actual[index],
                utils.to_reference(native[index]),
                torch.float32,
                reduce_dim=3,
            )
        else:
            assert actual[index] is None


@pytest.mark.parametrize("delta", [0.0, 1e-4, 1e-3])
@pytest.mark.parametrize("strided", [False, True])
def test_hw1_nearly_constant_groups(delta, strided):
    torch.manual_seed(61)
    case = make_case(
        "native_group_norm_backward", torch.float32, (3, 4, 1, 1), strided, 0
    )
    args = list(case.args)
    x = args[1]
    x.copy_(
        torch.tensor([0.9, 0.9 + delta, -0.9, -0.9 + delta], device=x.device)
        .reshape(1, 4, 1, 1)
        .expand_as(x)
    )
    _, args[2], args[3] = torch.ops.aten.native_group_norm(
        x.contiguous(), args[4], None, 3, 4, 1, 2, 1e-5
    )
    actual = flag_gems.group_norm_backward(*args)
    expected = group_norm_hw1_fp64_gradient(args)
    utils.gems_assert_close(
        actual[0],
        utils.to_reference(expected),
        torch.float32,
        reduce_dim=3,
        equal_nan=True,
    )


