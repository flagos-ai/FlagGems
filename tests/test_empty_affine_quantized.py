import pytest
import torch

import flag_gems

from . import accuracy_utils as utils


@pytest.mark.empty_affine_quantized
@pytest.mark.underscore_empty_affine_quantized
# Quantized factories accept quantized scalar types, not FLOAT_DTYPES.
@pytest.mark.parametrize("dtype", [torch.qint8, torch.quint8, torch.qint32])
@pytest.mark.parametrize("shape", [(2, 3), (0, 3), (2, 3, 4, 5)])
@pytest.mark.parametrize("channels_last", [False, True])
def test_empty_affine_quantized(dtype, shape, channels_last):
    if channels_last and len(shape) != 4:
        pytest.skip("channels_last requires rank four")
    memory_format = torch.channels_last if channels_last else torch.contiguous_format
    kwargs = dict(dtype=dtype, device=flag_gems.device, memory_format=memory_format)
    kwargs.update(scale=0.25, zero_point=2)
    ref = torch.ops.aten._empty_affine_quantized.default(shape, **kwargs)
    res = flag_gems._empty_affine_quantized(shape, **kwargs)
    assert res.shape == ref.shape
    assert res.stride() == ref.stride()
    assert res.dtype == ref.dtype
    assert res.device == ref.device
    assert res.qscheme() == ref.qscheme()
    assert res.untyped_storage().nbytes() == ref.untyped_storage().nbytes()
    # Native empty data is unspecified. Check our deterministic initialization
    # separately from the native metadata comparison.
    raw = torch.empty(0, dtype=torch.uint8, device=res.device).set_(
        res.untyped_storage()
    )
    golden = torch.zeros(raw.shape, dtype=torch.uint8, device=res.device)
    utils.gems_assert_equal(raw, utils.to_reference(golden))
    assert res.q_scale() == ref.q_scale()
    assert res.q_zero_point() == ref.q_zero_point()
