"""Accuracy tests for ``aten::_scaled_mm_v2``.

The operator is the recipe-driven spelling of the scaled matrix multiply:
``scale_a``/``scale_b`` arrive as lists, paired with ``recipe_a``/``recipe_b``
(``TensorWise`` / ``RowWise``) and, optionally, ``swizzle_a``/``swizzle_b``.

Only ``float8_e4m3fn`` operands with ``float32`` decoding scales are exercised,
matching what the upstream scaled GEMM kernels accept.  The reference is built
from the same operands in float32, so the comparison is deterministic.

``TensorWise`` / ``RowWise`` are the recipes the Triton kernel implements; the
block-wise recipes (``BlockWise1x128`` and friends) need a cublasLt that this
backend does not ship, so they are rejected rather than silently mishandled.
"""

