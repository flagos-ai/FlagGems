def test_nested_tensor_size_from_strided_buffer():
    # A nested tensor built over one buffer with explicit (non-contiguous)
    # strides: sizes come from the stored metadata, not from contiguous
    # strides of the dense views. Construction is CPU-only; ``_nested_view_from_buffer``
    # tensors do not support ``.size()`` ("NestedTensorImpl doesn't support
    # sizes") but the metadata queries work, which is exactly the distinction
    # this operator exposes.
    flat = torch.arange(60, dtype=torch.float32)
    sizes = torch.tensor([[2, 3], [4, 3]], dtype=torch.int64)
    strides = torch.tensor([[6, 2], [3, 1]], dtype=torch.int64)
