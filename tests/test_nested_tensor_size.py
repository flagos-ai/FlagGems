    nt = torch.ops.aten._nested_view_from_buffer.default(flat, sizes, strides, offsets)
    assert nt.is_nested

    ref_out = torch.ops.aten._nested_tensor_size(utils.to_reference(nt))
    res_out = flag_gems._nested_tensor_size(nt)

    assert ref_out.tolist() == [[2, 3], [4, 3]]
    assert res_out.tolist() == [[2, 3], [4, 3]]
    utils.gems_assert_equal(res_out, ref_out)


