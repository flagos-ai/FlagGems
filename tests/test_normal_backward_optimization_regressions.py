import pytest
import torch

import flag_gems


@pytest.mark.normal_backward
@pytest.mark.parametrize("upstream", [1.0, float("nan"), float("inf")])
def test_zero_derivatives_are_fresh_and_outputs_do_not_alias(upstream):
    mean = torch.randn((9, 7), device=flag_gems.device, requires_grad=True)
    std = torch.ones_like(mean, requires_grad=True)
    y = flag_gems.normal_tensor_tensor(mean, std)
    a, b = torch.autograd.grad(
        y, (mean, std), torch.full_like(y, upstream), retain_graph=True
    )
    torch.testing.assert_close(a, torch.zeros_like(a), atol=0, rtol=0)
    torch.testing.assert_close(b, torch.zeros_like(b), atol=0, rtol=0)
    assert a.data_ptr() != b.data_ptr()
    a[(0,) * a.ndim] = 7
    assert b[(0,) * b.ndim].item() == 0
    c, d = torch.autograd.grad(y, (mean, std), torch.ones_like(y))
    torch.testing.assert_close(c, torch.zeros_like(c), atol=0, rtol=0)
    torch.testing.assert_close(d, torch.zeros_like(d), atol=0, rtol=0)
    assert c.data_ptr() != a.data_ptr()


pytestmark = [pytest.mark.normal]
