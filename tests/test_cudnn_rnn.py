# ---------------------------------------------------------------------------
# RNN mode constants
# ---------------------------------------------------------------------------
RNN_RELU = 0
RNN_TANH = 1
LSTM = 2
GRU = 3


def _make_rnn_weights(
    input_size, hidden_size, num_layers, bidirectional, mode, proj_size=0, bias=True
):
    """Create an nn.RNN/LSTM/GRU module and return it."""
    if mode == RNN_RELU:
        return torch.nn.RNN(
            input_size,
            hidden_size,
            num_layers,
            nonlinearity="relu",
            bidirectional=bidirectional,
            bias=bias,
        )
    elif mode == RNN_TANH:
        return torch.nn.RNN(
            input_size,
            hidden_size,
            num_layers,
            nonlinearity="tanh",
            bidirectional=bidirectional,
            bias=bias,
        )
    elif mode == LSTM:
        return torch.nn.LSTM(
            input_size,
            hidden_size,
            num_layers,
            bidirectional=bidirectional,
            proj_size=proj_size,
            bias=bias,
        )
    elif mode == GRU:
        return torch.nn.GRU(
            input_size,
            hidden_size,
            num_layers,
            bidirectional=bidirectional,
            bias=bias,
        )


def _get_hx_cx(
    mode, num_layers, num_directions, batch_size, hidden_out, hidden_size, dtype, device
):
    """Create initial hidden (and cell) states."""
    hx_shape = (num_layers * num_directions, batch_size, hidden_out)
    hx = torch.randn(hx_shape, dtype=dtype, device=device)
    cx = (
        torch.randn(
            (num_layers * num_directions, batch_size, hidden_size),
            dtype=dtype,
            device=device,
        )
        if mode == LSTM
        else None
    )
    return hx, cx


def _get_weight_stride0(mode, has_bias, proj_size):
    """Return expected weight_stride0 value."""
    if proj_size > 0 and mode == LSTM:
        return 5 if has_bias else 3
    else:
        return 4 if has_bias else 2


# ---------------------------------------------------------------------------
# Reference backend
# ---------------------------------------------------------------------------
# fp16/fp32 use the cuDNN-backed ``aten::_cudnn_rnn``.  cuDNN's RNN path does
# not support bfloat16 on every backend, so for bfloat16 the reference uses
# the native ``nn.{LSTM,GRU,RNN}`` forward (which also handles proj_size),
# upcast to fp32.


def _cudnn_rnn_ref(
    inp,
    weights,
    ws,
    hx,
    cx,
    mode,
    hidden_size,
    proj_size,
    num_layers,
    batch_first,
    dropout,
    train,
    bidirectional,
    batch_sizes,
    dropout_state,
):
    """Reference forward (output, hy, cy, reserve, weight_buf) for the dtype.

    cuDNN ``aten::_cudnn_rnn`` for fp16/fp32; native ``nn.{LSTM,GRU,RNN}``
    forward (upcast to fp32) for bfloat16.  Returns a 5-tuple matching the
    ``aten::_cudnn_rnn`` layout.
    """
    if inp.dtype != torch.bfloat16:
        return torch.ops.aten._cudnn_rnn(
            inp,
            weights,
            ws,
            None,
            hx,
            cx,
            mode,
            hidden_size,
            proj_size,
            num_layers,
            batch_first,
            dropout,
            train,
            bidirectional,
            batch_sizes,
            dropout_state,
        )

    has_bias = ws in (4, 5)
    inp32 = inp.to(torch.float32)
    hx32 = hx.to(torch.float32)
    cx32 = cx.to(torch.float32) if cx is not None else None
    weights32 = tuple(w.to(torch.float32) for w in weights)

    rnn = _make_rnn_weights(
        inp.size(-1),
        hidden_size,
        num_layers,
        bidirectional,
        mode,
        proj_size=proj_size,
        bias=has_bias,
    ).to(device=inp.device, dtype=torch.float32)
    rnn.batch_first = batch_first
    with torch.no_grad():
        for p, w32 in zip(rnn._flat_weights, weights32):
            p.copy_(w32)
    rnn.flatten_parameters()

    if mode == LSTM:
        out, (hy, cy) = rnn(inp32, (hx32, cx32))
    else:
        out, hy = rnn(inp32, hx32)
        cy = None
    return (
        out.to(inp.dtype),
        hy.to(inp.dtype),
        cy.to(inp.dtype) if cy is not None else None,
        None,
        None,
    )


