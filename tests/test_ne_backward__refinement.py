import pytest
import torch

import flag_gems


@pytest.mark.ne_backward_
@pytest.mark.parametrize("needs", [(True, False), (False, True), (True, True)])
def test_inplace_ne_respects_each_gradient_requirement(needs):
    device = flag_gems.device
    leaves = [torch.randn(257, device=device, requires_grad=need) for need in needs]
    a = leaves[0] * 1 if needs[0] else leaves[0].clone()
    y = flag_gems.ne_(a, leaves[1])
    requested = [x for x in leaves if x.requires_grad]
    gradients = torch.autograd.grad(y, requested, torch.full_like(y, float("nan")))
    for g in gradients:
        torch.testing.assert_close(g, torch.zeros_like(g), atol=0, rtol=0)


pytestmark = [pytest.mark.ne_]
