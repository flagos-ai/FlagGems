def _make_dense_sparse(M, K, dtype, device, sparsity):
    """Return the masked dense values and the boolean pattern."""
    dense = torch.randn((M, K), dtype=torch.float32, device=device)
    if sparsity == 0.0:
        mask = torch.ones((M, K), dtype=torch.bool, device=device)
    elif sparsity == 1.0:
        mask = torch.zeros((M, K), dtype=torch.bool, device=device)
    else:
        mask = torch.rand((M, K), device=device) > sparsity
    return (dense * mask).to(dtype), mask


def _to_layout(dense, layout):
    if layout == "csr":
        return dense.to_sparse_csr()
    if layout == "csc":
        return dense.to_sparse_csc()
    return dense.to_sparse()


def _bias_for(kind, M, N, dtype, device):
    if kind == "vector":
        return torch.randn((N,), dtype=dtype, device=device)
    if kind == "row":
        return torch.randn((1, N), dtype=dtype, device=device)
    if kind == "col":
        return torch.randn((M, 1), dtype=dtype, device=device)
    if kind == "scalar":
        return torch.randn((), dtype=dtype, device=device)
    return torch.randn((M, N), dtype=dtype, device=device)


def _reference(bias, dense, mat2, beta, alpha):
    """fp64 reference built with ``to_reference(upcast=True)``.

    A plain fp32 GPU matmul would use TF32, which drifts far beyond the fp32
    tolerance of this op; upcasting also puts the reference on CPU under
    ``--ref cpu`` so its device matches the returned tensor.
    """
    ref_bias = utils.to_reference(bias, True)
    ref_dense = utils.to_reference(dense, True)
    ref_mat2 = utils.to_reference(mat2, True)
    prod = ref_dense @ ref_mat2
    return (beta * ref_bias + alpha * prod).to(dense.dtype)


