import pytest
import torch
import torch.nn.functional as F

import flag_gems

from . import accuracy_utils as utils

# (input shape, weight shape, padding, output_padding, stride, dilation, groups)
# Weight follows the transposed-conv layout (C_in, C_out / groups, kH, kW).
BACKWARD_CASES = [
    ((2, 2, 8, 8), (2, 4, 3, 3), 1, 1, 2, 1, 1),
    ((2, 4, 9, 9), (4, 3, 3, 3), 1, 1, 2, 1, 2),
    ((1, 2, 5, 5), (2, 2, 3, 3), 0, 0, 1, 1, 1),
    ((2, 4, 8, 8), (4, 4, 3, 3), 0, 0, 1, 2, 1),
    ((2, 2, 10, 10), (2, 3, 4, 4), 2, 1, 3, 2, 1),
    ((2, 6, 7, 7), (6, 3, 3, 3), 0, 0, 1, 1, 2),
    ((2, 4, 6, 4), (4, 4, 5, 5), 1, 0, 1, 2, 1),
]


def _grad_input_reduction_dim(weight_shape, groups):
    # grad_input accumulates over C_out/groups and the kernel volume.
    reduce_dim = weight_shape[1]
    for size in weight_shape[2:]:
        reduce_dim *= size
    return max(reduce_dim, 1)


@pytest.mark.cudnn_convolution_transpose_backward
@pytest.mark.skipif(
    flag_gems.vendor_name == "cambricon", reason="Issue #5254: Not supported"
)
@pytest.mark.parametrize(
    "shape, kernel, padding, output_padding, stride, dilation, groups",
    BACKWARD_CASES,
)
@pytest.mark.parametrize("dtype", utils.FLOAT_DTYPES)
def test_cudnn_convolution_transpose_backward(
    shape, kernel, padding, output_padding, stride, dilation, groups, dtype
):
    torch.manual_seed(0)
    torch.backends.cudnn.allow_tf32 = False

    inp = torch.randn(shape, dtype=dtype, device=flag_gems.device, requires_grad=True)
    weight = torch.randn(kernel, dtype=dtype, device=flag_gems.device)
    ref_inp = utils.to_reference(inp, True)
    ref_weight = utils.to_reference(weight, True)

    # The reference forward is the generic conv_transpose2d: aten
    # ``cudnn_convolution_transpose`` has no CPU implementation, so it cannot
    # serve as the reference under ``--ref=cpu`` (nor on backends without
    # cuDNN). Both compute the same forward, so the autograd of this one is the
    # reference gradient.
    ref_out = F.conv_transpose2d(
        ref_inp,
        ref_weight,
        bias=None,
        stride=(stride, stride),
        padding=(padding, padding),
        output_padding=(output_padding, output_padding),
        groups=groups,
        dilation=(dilation, dilation),
    )
    # grad_output must match the forward output shape.
    out_grad = torch.randn(ref_out.shape, dtype=dtype, device=flag_gems.device)
    ref_out = ref_out.to(dtype)
    ref_grad = utils.to_reference(out_grad, True)
    (ref_in_grad,) = torch.autograd.grad(ref_out, ref_inp, ref_grad)

    res_in_grad = flag_gems.cudnn_convolution_transpose_backward(
        out_grad,
        inp,
        weight,
        padding=(padding, padding),
        output_padding=(output_padding, output_padding),
        stride=(stride, stride),
        dilation=(dilation, dilation),
        groups=groups,
        benchmark=False,
        deterministic=False,
        allow_tf32=False,
    )

    assert res_in_grad.shape == inp.shape
    assert res_in_grad.dtype == dtype
    utils.gems_assert_close(
        res_in_grad,
        ref_in_grad,
        dtype,
        reduce_dim=_grad_input_reduction_dim(kernel, groups),
    )
