def _cpu_float2_reduce(x, g, mean, dtype):
    n, c, hw = x.shape
    tx = min(512, max(32, 1 << (hw - 1).bit_length()))
    ty = 512 // tx
    tid = torch.arange(512)
    lane = tid % 32
    sums, dots = ([], [])
    for ch in range(c):
        sums_thread = torch.zeros(512)
        dots_thread = torch.zeros(512)
        for nb in range((n + ty - 1) // ty):
            b = nb * ty + tid // tx
            for sb in range((hw + tx - 1) // tx):
                s = sb * tx + tid % tx
                valid = (b < n) & (s < hw)
                gx = torch.where(
                    valid, g[b.clamp(max=n - 1), ch, s.clamp(max=hw - 1)], 0
                )
                xx = torch.where(
                    valid, x[b.clamp(max=n - 1), ch, s.clamp(max=hw - 1)], 0
                )
                sums_thread += gx
                dots_thread += (gx * (xx - mean[ch])).to(dtype).float()
        for delta in (16, 8, 4, 2, 1):
            rhs = torch.where(lane + delta < 32, tid + delta, tid)
            sums_thread = sums_thread + sums_thread[rhs].to(dtype).float()
            dots_thread = dots_thread + dots_thread[rhs].to(dtype).float()
        sums_warp = torch.cat((sums_thread[::32], torch.zeros(16)))
        dots_warp = torch.cat((dots_thread[::32], torch.zeros(16)))
        i = torch.arange(32)
        for delta in (16, 8, 4, 2, 1):
            rhs = torch.where(i + delta < 32, i + delta, i)
            sums_warp = sums_warp + sums_warp[rhs].to(dtype).float()
            dots_warp = dots_warp + dots_warp[rhs].to(dtype).float()
        sums.append(sums_warp[0])
        dots.append(dots_warp[0])
    return (torch.stack(dots), torch.stack(sums))


