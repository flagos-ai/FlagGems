def _to_reference(inp):
    """Independent oracle that retains the view metadata under test.

    A plain clone can compact strides, reset the storage offset or materialize
    the lazy conjugate flag, all of which this operator is supposed to carry
    through, so the dense storage is copied instead.
    """
    reference = torch.empty(0, dtype=inp.dtype, device=inp.device).set_(
        inp.untyped_storage().clone(),
        inp.storage_offset(),
        inp.size(),
        inp.stride(),
    )
    if inp.is_conj():
        reference = reference.conj()
    return utils.to_reference(reference)


def _apply_layout(base, layout):
    if layout == "asis":
        return base
    if layout == "transposed":
        return base.transpose(-1, -2)
    if layout == "column_step":
        return base[:, ::2]
    if layout == "offset_window":
        return base[1:4, 1:4]
    if layout == "conj":
        return base.conj()
    if layout == "transposed_conj":
        return base.transpose(-1, -2).conj()
    raise ValueError("unsupported layout " + repr(layout))


def _layout_pair(shape, layout, dtype):
    # Candidate operand, independently stored reference operand, and both
    # backing tensors so a write through either view can be traced back.
    base = _make_input(dtype, shape)
    ref_base = _to_reference(base.detach())
    return _apply_layout(base, layout), _apply_layout(ref_base, layout), base, ref_base


def _assert_view_semantics(res_out, inp):
    """Assert the layout contract against aten's view of the same tensor.

    The oracle is built on ``inp`` itself rather than on the value reference:
    under ``--ref=cpu`` the reference is copied to the host, and that copy
    compacts the strides and resets the storage offset of a non-dense view, so
    its layout is no longer the one this operator has to reproduce.
    """
    aten_out = _ATEN_OP(inp)
    assert (res_out is inp) == (aten_out is inp)
    # matrix_H aliases its input instead of copying, so shared storage,
    # strides, storage offset and the lazy conjugate bit must match aten.
    assert res_out.untyped_storage().data_ptr() == inp.untyped_storage().data_ptr()
    assert res_out._is_view() == aten_out._is_view()
    assert res_out.shape == aten_out.shape
    assert res_out.stride() == aten_out.stride()
    assert res_out.storage_offset() == aten_out.storage_offset()
    assert res_out.is_conj() == aten_out.is_conj()


