# 32-bit Philox-4x32 constants, as used by ATen's StatelessPhilox4x32.cuh.
_PHILOX_KEY_A = np.uint32(0x9E3779B9)
_PHILOX_KEY_B = np.uint32(0xBB67AE85)
_PHILOX_ROUND_A = np.uint32(0xD2511F53)
_PHILOX_ROUND_B = np.uint32(0xCD9E8D57)
_U32_MAX = np.uint64(0xFFFFFFFF)

# Shapes beyond the shared distribution set: a single element, sizes that are
# not multiples of the 4 elements a Philox call yields (exercising the tail
# loop), and a couple of multi-dimensional cases.
_EXTRA_SHAPES = [(1,), (1024,), (997,), (16, 33), (2, 3, 5, 7)]
SHAPES = utils.DISTRIBUTION_SHAPES + _EXTRA_SHAPES


def _mulhilo32(a, b):
    p = a.astype(np.uint64) * b.astype(np.uint64)
    return (p & _U32_MAX).astype(np.uint32), (p >> np.uint64(32)).astype(np.uint32)


def _philox_round(ctr, key):
    c0, c1, c2, c3 = ctr
    k0, k1 = key
    r0_lo, r0_hi = _mulhilo32(_PHILOX_ROUND_A, c0)
    r1_lo, r1_hi = _mulhilo32(_PHILOX_ROUND_B, c2)
    return (
        np.uint32(r1_hi ^ c1 ^ k0),
        r1_lo,
        np.uint32(r0_hi ^ c3 ^ k1),
        r0_lo,
    )


def _philox_4x32(seed, offsets, rounds=10):
    """Stateless Philox-4x32 with subsequence fixed to 0, over a block."""
    seed = np.uint64(seed)
    key = (
        np.uint32(int(seed) & 0xFFFFFFFF),
        np.uint32(int(seed) >> 32),
    )
    offsets = np.asarray(offsets).astype(np.uint64)
    ctr = (
        (offsets & _U32_MAX).astype(np.uint32),
        (offsets >> np.uint64(32)).astype(np.uint32),
        np.zeros(offsets.shape, dtype=np.uint32),
        np.zeros(offsets.shape, dtype=np.uint32),
    )
    for _ in range(rounds - 1):
        ctr = _philox_round(ctr, key)
        key = (
            np.uint32((int(key[0]) + int(_PHILOX_KEY_A)) & 0xFFFFFFFF),
            np.uint32((int(key[1]) + int(_PHILOX_KEY_B)) & 0xFFFFFFFF),
        )
    return _philox_round(ctr, key)


def _fma_to_f32(word):
    """Reproduce ``fmaf(static_cast<float>(word), 2**-32, 2**-33)``.

    ``static_cast<float>`` rounds the uint32 word before the fused
    multiply-add, and both constants are powers of two, so evaluating the
    expression in float64 and rounding once matches the device result exactly.
    """
    return (
        word.astype(np.float32).astype(np.float64) * 2.3283064365386963e-10
        + 1.1641532182693481e-10
    ).astype(np.float32)


def _affine_f32(values, mean, std):
    """``values * sigma + mu`` in float32, contracted to a fused multiply-add."""
    mu = np.float32(mean)
    sigma = np.float32(std)
    return (values.astype(np.float64) * float(sigma) + float(mu)).astype(np.float32)


def _reference_normal(numel, seed, offset, mean, std, torch_dtype, device=None):
    """Compute the expected ``_philox_normal_`` output from the ATen algorithm.

    Arithmetics follow ``_philox_normal_cuda_``: 8-byte outputs accumulate in
    double and pair two Philox words per sample, everything else accumulates in
    float and consumes one word per sample, and the result is cast back to the
    storage dtype before storing.
    """
    if torch_dtype == torch.float64:
        per_call = 2
    else:
        per_call = 4
    num_chunks = -(-numel // per_call)
    counters = np.uint64(offset) + np.arange(num_chunks, dtype=np.uint64)
    r0, r1, r2, r3 = _philox_4x32(seed, counters)

    if torch_dtype == torch.float64:
        m = 2.3283064365386963e-10  # 2**-32, exact, so the sums are exact too
        u1 = r0.astype(np.float64) * m + (r1.astype(np.float64) * m * m + m * m * 0.5)
        u2 = r2.astype(np.float64) * m + (r3.astype(np.float64) * m * m + m * m * 0.5)
        radius = np.sqrt(-2.0 * np.log(u1))
        theta = 6.2831853071795864 * u2
        vals = np.stack([radius * np.cos(theta), radius * np.sin(theta)])
        out = (vals.T.reshape(-1)[:numel] * np.float64(std) + np.float64(mean)).astype(
            np.float64
        )
    else:
        u = np.stack(
            [_fma_to_f32(r0), _fma_to_f32(r1), _fma_to_f32(r2), _fma_to_f32(r3)]
        )
        radius = np.sqrt(np.float32(-2.0) * np.log(u))
        theta = np.float32(6.2831853071795864) * u
        # Words 0/1 and 2/3 each form a (cosine, sine) pair; the angle comes
        # from the odd-indexed word and the radius from the even-indexed one.
        vals = np.stack(
            [
                radius[0] * np.cos(theta[1]),
                radius[0] * np.sin(theta[1]),
                radius[2] * np.cos(theta[3]),
                radius[2] * np.sin(theta[3]),
            ]
        )
        out = _affine_f32(vals.T.reshape(-1)[:numel], mean, std)

    result = torch.from_numpy(np.ascontiguousarray(out)).to(torch_dtype)
    # Keep the reference on the caller's device, but on CPU under --ref cpu
    # so to_cpu()'s device assertion in gems_assert_close holds.
    if device is not None and not utils.TO_CPU:
        result = result.to(device)
    return result


def _make_key(seed, offset, device):
    return torch.tensor([seed, offset], dtype=torch.uint64, device=device)


