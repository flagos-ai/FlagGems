"""Accuracy tests for ``aten::_philox_normal_``.

``_philox_normal_`` is a stateless Philox RNG operator whose result is a pure
function of the ``(seed, offset)`` pair carried in ``key``. torch builds that
ship the operator can be compared against directly; for builds that predate it
(no schema in the installed torch) the reference is computed here from the same
ATen algorithm: Philox-4x32 counter values fed through the Box-Muller
transforms in ``aten/src/ATen/native/cuda/PhiloxDistribution.cu``.

The reference re-implements that file step for step (word rounding included) so
the comparison is deterministic rather than statistical.
"""

