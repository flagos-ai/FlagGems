@pytest.mark.parametrize("dtype", utils.FLOAT_DTYPES)
def test_philox_normal_statistics(dtype):
    """Sanity-check the distribution itself, independently of the stream.

    A whole-range mismatch in the Box-Muller pairing or angle assignment would
    still look plausible element-wise in a small sample, but it shifts the
    sample mean or standard deviation well outside the sampling error.
    """
    mean, std = -3.0, 2.0
    numel = 1 << 16
    key = _make_key(31337, 4, flag_gems.device)

    res_out = flag_gems._philox_normal_(
        torch.empty(numel, dtype=dtype, device=flag_gems.device), key, mean, std
    )

    values = res_out.float()
    # Sampling error of the mean is std/sqrt(numel) ~= 0.008; leave a wide
    # margin so the test cannot flake.
    assert abs(values.mean().item() - mean) < 0.1
    assert abs(values.std().item() - std) < 0.1
