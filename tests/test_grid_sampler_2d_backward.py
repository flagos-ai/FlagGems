@pytest.mark.grid_sampler_2d_backward
@pytest.mark.parametrize("align_corners", GRID_SAMPLER_ALIGN_CORNERS)
def test_grid_sampler_2d_backward_reflection_boundaries(align_corners):
    # Fold and clip boundaries (0, n-1, and the reflection fold points) are
    # the delicate spots of bilinear + reflection: the grad_grid multiplier
    # is zero exactly on them, and multi-period folding flips signs.
    H = W = 8
    pix_values = [0.0, 7.0, 7.5, 8.0, -0.5, -1.0, 15.5, 16.0, 23.5, -8.5]
    pix_pairs = [(x, y) for x in pix_values for y in pix_values]
    if align_corners:
        to_grid = lambda pix: pix / (W - 1) - 1
    else:
        to_grid = lambda pix: (pix + 0.5) / W - 1

    OH, OW = 5, 7
    torch.manual_seed(11)
    input = torch.randn(2, 3, H, W, device=flag_gems.device)
    grad_output = torch.randn(2, 3, OH, OW, device=flag_gems.device)
    grid = torch.zeros(2, OH, OW, 2, device=flag_gems.device)
    k = 0
    for n in range(2):
        for oh in range(OH):
            for ow in range(OW):
                x_pix, y_pix = pix_pairs[k % len(pix_pairs)]
                k += 1
                grid[n, oh, ow, 0] = to_grid(x_pix)
                grid[n, oh, ow, 1] = to_grid(y_pix)

    ref_grad_input, ref_grad_grid = torch.ops.aten.grid_sampler_2d_backward(
        utils.to_reference(grad_output),
        utils.to_reference(input),
        utils.to_reference(grid),
        0,
        2,
        align_corners,
        [True, True],
    )
    grad_input, grad_grid = flag_gems.grid_sampler_2d_backward(
        grad_output, input, grid, 0, 2, align_corners, (True, True)
    )
    utils.gems_assert_close(grad_input, ref_grad_input, torch.float32)
    utils.gems_assert_close(grad_grid, ref_grad_grid, torch.float32)
