import pytest
import torch

import flag_gems

from . import accuracy_utils as utils

NAMES = [
    pytest.param(
        "bernoulli_", marks=[pytest.mark.bernoulli_, pytest.mark.bernoulli_backward_]
    )
]


def apply(name, x):
    return flag_gems.ceil(x) if name == "ceil" else getattr(flag_gems, name)(x.clone())


@pytest.mark.parametrize("name", NAMES)
@pytest.mark.parametrize("dtype", utils.FLOAT_DTYPES)
@pytest.mark.parametrize("shape", [(), (3, 17)])
def test_zero_backward_results_are_independent(name, dtype, shape):
    leaf = torch.randn(shape, device=flag_gems.device, dtype=dtype, requires_grad=True)
    output = apply(name, leaf)
    first = torch.autograd.grad(
        output, leaf, torch.ones_like(output), retain_graph=True
    )[0]
    torch.testing.assert_close(first, torch.zeros_like(first), atol=0, rtol=0)
    first.fill_(7)
    # Zero derivatives must ignore NaN incoming gradients, and a prior caller
    # mutating its returned gradient must not poison a subsequent callback.
    incoming = torch.full_like(output, float("nan"))
    second = torch.autograd.grad(output, leaf, incoming)[0]
    torch.testing.assert_close(second, torch.zeros_like(second), atol=0, rtol=0)


@pytest.mark.parametrize("name", NAMES)
@pytest.mark.parametrize("dtype", utils.FLOAT_DTYPES)
def test_zero_backward_accumulates_into_existing_leaf_grad(name, dtype):
    leaf = torch.randn(
        (3, 17), device=flag_gems.device, dtype=dtype, requires_grad=True
    )
    leaf.grad = torch.ones_like(leaf)
    before = leaf.grad.clone()
    apply(name, leaf).sum().backward()
    torch.testing.assert_close(leaf.grad, before, atol=0, rtol=0)


