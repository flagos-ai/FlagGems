@pytest.mark.version
def test_version_dispatch_sentinel_composite_key():
    # Poison check: the shipped arrangement registers on the
    # CompositeImplicitAutograd key, which is the only key that intercepts
    # every layout for this operator (backend keys only catch dense; the
    # sparse keys are registered natively but never selected -- measured with
    # fresh-process sentinels). torch.ops.aten._version must reach the
    # submitted implementation for dense, COO and CSR inputs.
    from flag_gems.ops.version import version as real_impl

    lib = torch.library.Library("aten", "IMPL")
    hits = []

    def sentinel(self):
        hits.append(str(self.layout))
        return real_impl(self)

    lib.impl("_version", sentinel, "CompositeImplicitAutograd")
    try:
        t = torch.randn(3, device=flag_gems.device)
        coo = _make_coo(2, (2, 2), seed=3).to(flag_gems.device)
        csr = torch.sparse_csr_tensor(
            torch.tensor([0, 2, 2], dtype=torch.int64, device=flag_gems.device),
            torch.tensor([0, 1], dtype=torch.int64, device=flag_gems.device),
            torch.randn(2, device=flag_gems.device),
            (2, 3),
        )
        for want_layout, tensor in zip(
            [torch.strided, torch.sparse_coo, torch.sparse_csr], [t, coo, csr]
        ):
            before = len(hits)
            r = torch.ops.aten._version(tensor)
            assert len(hits) > before, f"composite key did not intercept {want_layout}"
            assert r == real_impl(tensor)
            assert hits[-1] == str(want_layout)
    finally:
        lib._destroy()

    # after the sentinel is gone the dispatched call still works (registry is
    # intact and no stale state leaked)
    t = torch.randn(2, device=flag_gems.device)
    assert torch.ops.aten._version(t) == flag_gems.version(t)


