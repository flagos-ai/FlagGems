# ---------------------------------------------------------------------------
# The ``--ref=cpu`` trap for a mutation-history op
# ---------------------------------------------------------------------------
# ``utils.to_reference()`` COPIES when it moves a tensor to the reference
# device, and a copy starts a fresh version counter. Therefore a reference
# view/copy of an already-mutated tensor can NOT be compared against it, in
# either phase:
#   * GPU phase: to_reference() returns the SAME object, so mutating "both"
#     sides mutates one counter twice;
#   * quick-cpu phase: to_reference() returns a fresh copy, so a mutated impl
#     tensor (version N) would be compared against a copy (version 0).
# Every cross-side assertion below therefore uses two DISTINCT tensors that
# receive an identical mutation sequence; both start at 0, so equal histories
# must produce equal counters in either phase.


def twin(shape, dtype=torch.float32):
    """A tensor distinct from any test tensor, in both phases, at version 0.

    Only its version counter is ever read, so the contents are irrelevant.
    """
    return utils.to_reference(torch.zeros(shape, dtype=dtype, device=flag_gems.device))


def _make_coo(nnz, size, seed=0):
    gen = torch.Generator().manual_seed(seed)
    numel = 1
    for s in size:
        numel *= s
    flat = torch.randperm(numel, generator=gen)[:nnz]
    indices = torch.empty((len(size), nnz), dtype=torch.int64)
    for d in reversed(range(len(size))):
        indices[d] = flat % size[d]
        flat = flat // size[d]
    values = torch.randn(nnz, generator=gen)
    return torch.sparse_coo_tensor(indices, values, size)


def _assert_version_matches_atin(inp, ref_inp=None):
    """The submitted implementation must equal the native aten op for inp.

    ``ref_inp`` may be supplied when ``inp`` has been mutated: see the
    ``--ref=cpu`` note above.
    """
    if ref_inp is None:
        ref_inp = utils.to_reference(inp)
    ref_out = torch.ops.aten._version(ref_inp)
    res_out = flag_gems.version(inp)
    assert isinstance(res_out, int)
    assert res_out == ref_out, f"{res_out} != {ref_out}"
    return res_out


