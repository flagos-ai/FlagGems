@pytest.mark._dimV
def test_accuracy__dimV_dispatch_stability():
    # The registration is on the Sparse dispatch key; exercise the
    # dispatcher-routed path repeatedly (a recursion bug or stale state would
    # surface here) and across an unrelated op dispatch (_nnz) in between.
    flag_gems.only_enable(include=["_dimV"])

    sparse = _make_coo(2, 5, (2, 3), seed=11).to(flag_gems.device)
    hybrid = torch.sparse_coo_tensor(
        torch.tensor([[0, 1]]), torch.randn(2, 3), (2, 3)
    ).to(flag_gems.device)

    for _ in range(3):
        assert torch.ops.aten._dimV(sparse) == 0
        assert torch.ops.aten._dimV(hybrid) == 1

    # Cross-op interference: dispatching a related metadata op afterwards
    # must not corrupt or re-route _dimV (no shared mutable state in the
    # impl; _nnz registration is not part of this op's contract).
    flag_gems.only_enable(include=["_dimV", "_nnz"])
    assert torch.ops.aten._nnz(sparse) == 5

    for _ in range(3):
        assert torch.ops.aten._dimV(sparse) == 0
        assert torch.ops.aten._dimV(hybrid) == 1
