# _dimV is a layout-metadata query returning a plain int; the result is
# independent of dtype and stored data. Coverage is driven by sparse COO
# structure instead: plain, hybrid (dense trailing dims), uncoalesced,
# zero-nnz and 1-sparse-dim non-hybrid tensors.
if QUICK_MODE:
    SPARSE_DIM_SIZES = [(2, 3)]
else:
    SPARSE_DIM_SIZES = [(2, 3), (4, 5, 6)]


def _make_coo(nnd, nnz, size, seed=0):
    gen = torch.Generator().manual_seed(seed)
    numel = 1
    for s in size[:nnd]:
        numel *= s
    flat = torch.randperm(numel, generator=gen)[:nnz]
    indices = torch.empty((nnd, nnz), dtype=torch.int64)
    for d in reversed(range(nnd)):
        indices[d] = flat % size[d]
        flat = flat // size[d]
    # Deliberately unsorted: uncoalesced COO must return the same metadata.
    values = torch.randn(nnz, generator=gen)
    return torch.sparse_coo_tensor(indices, values, size)


def _coo_cases(shape):
    n0 = shape[0]
    dense_tail = shape[1:] if len(shape) > 1 else ()
    return [
        ("plain", _make_coo(len(shape), 3, shape, seed=1)),
        (
            "hybrid",
            torch.sparse_coo_tensor(
                torch.randint(0, n0, (1, 2)),
                torch.randn(2, *dense_tail),
                shape,
            ),
        ),
        ("uncoalesced", _make_coo(len(shape), 4, shape, seed=3)),
        (
            "zero-nnz",
            torch.sparse_coo_tensor(
                torch.zeros(len(shape), 0, dtype=torch.int64),
                torch.zeros(0),
                shape,
            ),
        ),
        (
            # Non-hybrid 1-sparse-dim COO: values are 1-D, so the sparse size
            # is just the leading dimension; _dimV == dim() - 1 == 0.
            "1-sparse-dim",
            torch.sparse_coo_tensor(
                torch.randint(0, n0, (1, 2)), torch.randn(2), (n0,)
            ),
        ),
    ]


