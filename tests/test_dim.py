# non-contiguous and as_strided views), sparse COO (plain, 1-D, hybrid with
# dense trailing dims, zero-nnz, uncoalesced) and sparse compressed
# (CSR/CSC/BSR/BSC), plus nested tensors.
if QUICK_MODE:
    STRIDED_SHAPES = [(2, 3)]
else:
    STRIDED_SHAPES = [(), (5,), (2, 3), (2, 3, 4), (2, 3, 4, 5), (1, 1, 1, 1, 1, 1)]


def _make_coo(nnd, nnz, size, seed=0):
    gen = torch.Generator().manual_seed(seed)
    numel = 1
    for s in size[:nnd]:
        numel *= s
    flat = torch.randperm(numel, generator=gen)[:nnz]
    indices = torch.empty((nnd, nnz), dtype=torch.int64)
    for d in reversed(range(nnd)):
        indices[d] = flat % size[d]
        flat = flat // size[d]
    # Deliberately unsorted: uncoalesced COO must return the same metadata.
    values = torch.randn(nnz, generator=gen)
    return torch.sparse_coo_tensor(indices, values, size)


def _make_compressed(dev):
    c = torch.tensor([0, 2, 4], dtype=torch.int64, device=dev)
    cc = torch.tensor([0, 1, 0, 1], dtype=torch.int64, device=dev)
    val = torch.randn(4, device=dev)
    brow = torch.tensor([0, 1, 2], dtype=torch.int64, device=dev)
    bcol = torch.tensor([0, 1], dtype=torch.int64, device=dev)
    bval = torch.randn(2, 2, 2, device=dev)
    return {
        "csr": torch.sparse_csr_tensor(c, cc, val, (2, 3), device=dev),
        "csc": torch.sparse_csc_tensor(cc, c, val, (2, 3), device=dev),
        "bsr": torch.sparse_bsr_tensor(brow, bcol, bval, (4, 4), device=dev),
        "bsc": torch.sparse_bsc_tensor(bcol, brow, bval, (4, 4), device=dev),
    }


