def test_dim_is_dispatch_free():
    # The implementation must not re-enter the dispatcher: reading `ndim` is a
    # TensorImpl property read. Instrumented with TorchDispatchMode, a call to
    # flag_gems.dim must not raise any dispatcher op on any layout (a re-entrant
    # `self.dim()` would).
    class Recorder(torch.utils._python_dispatch.TorchDispatchMode):
        def __init__(self):
            self.seen = []

        def __torch_dispatch__(self, func, types, args=(), kwargs=None):
            self.seen.append(func._schema.name)
            return func(*args, **(kwargs or {}))

    dev = flag_gems.device
    cases = [
        torch.randn(2, 3, device=dev),
        _make_coo(2, 3, (2, 3), seed=9).to(dev),
        _make_compressed(dev)["csr"],
    ]
    for t in cases:
        with Recorder() as rec:
            res_out = flag_gems.dim(t)
        assert res_out == utils.to_reference(t).dim()
        assert rec.seen == [], f"unexpected dispatcher calls: {rec.seen}"


