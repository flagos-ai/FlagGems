def _reference_grads(grad, ref_a, ref_b):
    """Exact-math gradient reference, independent of the dispatch registry.

    ``torch.ops.aten._sparse_sparse_matmul`` resolves through the dispatch
    table, so once FlagGems' sparse kernels are activated (the dispatch test in
    this file, or another suite) the "native" call would silently exercise the
    FlagGems implementation instead of cuSPARSE.  Reproducing the ATen
    composition of ``FunctionsManual.cpp::sparse_sparse_matmul_backward``
    directly in float64 avoids both that aliasing and the low-precision
    accumulation-order difference between cuSPARSE and the FlagGems SpGEMM
    kernels: the gradient math is defined exactly, and each implementation may
    round it in its own order within the tested tolerance.

    The composition per saved operand is one SpGEMM against the transposed
    other operand, projected by ATen's ``sparse_mask_like_grad(x, gx, False)``:

    - ``x._nnz() >= gx._nnz()`` uses ``aten::_sparse_mask_projection(gx, x)``:
      the result keeps the *product's* stored support, with an explicit 0
      wherever the operand lacks the coordinate (measured on device).
    - otherwise ``gx.sparse_mask(x)``: the result keeps the *operand's* stored
      support, with an explicit 0 wherever the product lacks the coordinate.

    The product's own support is its nonzero float pattern: an SpGEMM only
    stores coordinates with a nonzero accumulated value.
    """
    dt = torch.float64 if ref_a.dtype in _LOW_PREC_DTYPES else ref_a.dtype
    a_dense = ref_a.detach().to(dt).to_dense()
    b_dense = ref_b.detach().to(dt).to_dense()
    g_dense = grad.detach().to(dt).to_dense()
    ga_dense = g_dense @ b_dense.t()
    gb_dense = a_dense.t() @ g_dense

    def _build(product_dense, operand):
        keep_where = (
            "product" if operand._nnz() >= (product_dense != 0).sum() else "operand"
        )
        prod_nz = (product_dense != 0).nonzero(as_tuple=False)
        prod_set = set(map(tuple, prod_nz.tolist()))
        op_idx = operand.detach().coalesce()._indices()
        op_set = set(map(tuple, op_idx.t().tolist()))
        if operand.shape[0] * operand.shape[1] == 0:
            keep = set()
        elif keep_where == "product":
            keep = prod_set
        else:
            keep = op_set
        keep = sorted(keep)
        if not keep:
            empty = torch.empty(2, 0, dtype=torch.int64, device=operand.device)
            return torch.sparse_coo_tensor(
                empty,
                torch.empty(0, dtype=operand.dtype, device=operand.device),
                operand.shape,
                device=operand.device,
            )
        kk = torch.tensor(keep, dtype=torch.int64, device=operand.device)
        vals = torch.zeros(len(keep), dtype=dt, device=operand.device)
        for pos, coord in enumerate(keep):
            if coord in prod_set:
                vals[pos] = product_dense[coord[0], coord[1]]
        return torch.sparse_coo_tensor(
            kk.t(), vals.to(operand.dtype), operand.shape, device=operand.device
        )

    ga = _build(ga_dense, ref_a)
    gb = _build(gb_dense, ref_b)
    return ga, gb


