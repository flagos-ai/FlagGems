def _make_sparse(M, K, dtype, device, sparsity, seed=0):
    """Build a coalesced COO tensor with the requested fill fraction.

    ``sparsity`` is the fraction of *stored* entries (like the kernelgen
    workload density); 1.0 yields a fully empty tensor.
    """
