def _make_sparse(M, K, dtype, device, sparsity, seed=0):
    """Build a coalesced COO tensor with the requested fill fraction.

    ``sparsity`` is the fraction of *stored* entries (like the kernelgen
    workload density); 1.0 yields a fully empty tensor.
    """
    generator = torch.Generator(device="cpu").manual_seed(seed)
    if sparsity >= 1.0 or M == 0 or K == 0:
        nnz = 0
    else:
        nnz = max(1, int(M * K * (1.0 - sparsity)))
    flat = torch.randperm(M * K, generator=generator)[:nnz]
    rows = (flat // K).to(torch.int64).to(device)
    cols = (flat % K).to(torch.int64).to(device)
    values = (
        torch.randn(nnz, generator=generator, dtype=torch.float32).to(dtype).to(device)
    )
    return torch.sparse_coo_tensor(
        torch.stack([rows, cols]), values, (M, K), device=device
    ).coalesce()


