import pytest
import torch

import flag_gems

from . import accuracy_utils as utils

# lu_solve only supports the dtypes that lu_factor supports (float32/float64
# on CUDA); fp16/bf16 are rejected by PyTorch's cuSOLVER lu_factor.
LU_SOLVE_DTYPES = [torch.float32] + ([torch.float64] if utils.fp64_is_supported else [])

# (n, nrhs) pairs covering single/multiple right-hand sides and sizes that are
# not powers of two.
LU_SOLVE_SHAPES = [(1, 1), (2, 2), (3, 1), (4, 4), (8, 2), (16, 3), (32, 7), (64, 1)]


def _make_inputs(n, nrhs, dtype, batch=()):
    """Build a well-conditioned LU factorization and a right-hand side.

    A = M @ M^T + n * I keeps the condition number small so that the reference
    and the Triton result agree to close to machine precision.
    """
    eye = torch.eye(n, dtype=dtype, device=flag_gems.device)
    M = torch.randn(batch + (n, n), dtype=dtype, device=flag_gems.device)
    A = M @ M.transpose(-2, -1) + eye * n
    LU, pivots = torch.linalg.lu_factor(A)
    B = torch.randn(batch + (n, nrhs), dtype=dtype, device=flag_gems.device)
    return B, LU, pivots


@pytest.mark.lu_solve
@pytest.mark.parametrize("shape", LU_SOLVE_SHAPES)
@pytest.mark.parametrize("dtype", LU_SOLVE_DTYPES)
def test_lu_solve(shape, dtype):
    n, nrhs = shape
    B, LU, pivots = _make_inputs(n, nrhs, dtype)

    ref_B = utils.to_reference(B)
    ref_LU = utils.to_reference(LU)
    ref_pivots = utils.to_reference(pivots)
    ref_out = torch.lu_solve(ref_B, ref_LU, ref_pivots)

    res_out = flag_gems.lu_solve(B, LU, pivots)

    utils.gems_assert_close(res_out, ref_out, dtype)


