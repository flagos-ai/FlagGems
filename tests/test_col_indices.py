@pytest.mark.col_indices
def test_accuracy_col_indices_mutation_through_view():
    # Real aliasing proof: a write through the returned view must be visible in
    # the sparse tensor's own buffer, and vice versa.
    csr = _make_csr((2, 4), nnz=3, seed=3)
    original = csr.col_indices().clone()

    res_out = flag_gems.col_indices(csr)
    assert res_out.data_ptr() == csr.col_indices().data_ptr()

    res_out[0] = -7
    assert csr.col_indices()[0].item() == -7

    # Reverse direction: mutate the tensor's own buffer and observe the change
    # through the previously returned view.
    csr.col_indices()[1] = -9
    assert res_out[1].item() == -9

    # Restore and confirm the buffers are still identical element-wise.
    res_out.copy_(original)
    assert torch.equal(res_out, csr.col_indices())
    utils.gems_assert_equal(res_out, utils.to_reference(csr).col_indices())


@pytest.mark.col_indices
def test_accuracy_col_indices_unsupported_layouts():
    # Only row-compressed layouts carry a column-index buffer. Column-compressed
    # (CSC/BSC), COO and strided inputs must reproduce the native ATen
    # rejection message verbatim; the strided case additionally proves the
    # override does not re-enter itself (a naive delegation would recurse).
    crow = torch.tensor([0, 2, 4], dtype=torch.int64, device=flag_gems.device)
    ccol = torch.tensor([0, 1, 0, 1], dtype=torch.int64, device=flag_gems.device)
    val = torch.randn(4, device=flag_gems.device)

    csc = torch.sparse_csc_tensor(ccol, crow, val, (3, 3))
    bsc = torch.sparse_bsc_tensor(
        ccol, crow, torch.randn(4, 2, 2, device=flag_gems.device), (4, 4)
    )
    coo = torch.sparse_coo_tensor(
        torch.tensor([[0, 1], [1, 0]], dtype=torch.int64, device=flag_gems.device),
        torch.randn(2, device=flag_gems.device),
        (2, 3),
    )
    dense = torch.randn(2, 3, device=flag_gems.device)

    for tensor in (csc, bsc, coo, dense):
        with pytest.raises(RuntimeError, match="expected sparse row compressed"):
            flag_gems.col_indices(tensor)


