# ``col_indices`` returns the internal column-index buffer of a sparse
# compressed tensor as a zero-copy aliasing view. Coverage is therefore driven
# by layout and by the alias contract rather than by element values:
# row-compressed layouts (CSR/BSR) expose the buffer, while column-compressed
# layouts (CSC/BSC), COO and strided tensors follow the native ATen rejection.
if QUICK_MODE:
    CSR_SHAPES = [(2, 3)]
else:
    CSR_SHAPES = [(2, 3), (8, 16), (33, 65)]


def _make_csr(shape, nnz, seed=0):
    """Build a CSR tensor with ``nnz`` random entries on ``flag_gems.device``."""
    gen = torch.Generator().manual_seed(seed)
    crow = torch.zeros(shape[0] + 1, dtype=torch.int64)
    counts = torch.bincount(
        torch.randint(0, shape[0], (nnz,), generator=gen), minlength=shape[0]
    )
    crow[1:] = counts.cumsum(0)
    ccol = torch.randint(0, shape[1], (nnz,), generator=gen).to(torch.int64)
    values = torch.randn(nnz, generator=gen)
    return torch.sparse_csr_tensor(
        crow.to(flag_gems.device),
        ccol.to(flag_gems.device),
        values.to(flag_gems.device),
        shape,
    )


def _make_bsr(shape, block=2):
    """Build a BSR tensor with one fully-covered 2x2 block pair."""
    crow = torch.tensor([0, 1, 2], dtype=torch.int64, device=flag_gems.device)
    ccol = torch.tensor([0, 1], dtype=torch.int64, device=flag_gems.device)
    values = torch.randn(2, block, block, device=flag_gems.device)
    return torch.sparse_bsr_tensor(crow, ccol, values, shape)


