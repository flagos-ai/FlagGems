def prod_cpu_half_precision(case, refs, grad):
    """CPU Half global prod accumulates in Half; use independent FP64 values.

    Preserve the native CPU zero-safe scan graph when zeros are present.
    The nonzero derivative follows ATen's explicitly rounded output/x stage.
    """
    x = refs[0]
    value = torch.prod(x.double(), **case.kwargs).to(x.dtype)
    if x.numel() and bool((x == 0).any()):
        return (value, None)
