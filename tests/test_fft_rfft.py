@pytest.mark.fft_rfft
@pytest.mark.parametrize("shape", [(0, 8), (3, 0, 8)])
def test_fft_rfft_empty_batch(shape):
    """An empty batch of non-empty rows yields an empty result of bin width.

    ATen cannot serve this case at all: both the cuFFT and the MKL backends
    reject a zero-sized batch outright, so there is no reference to compare
    against and the expected shape is asserted directly.
    """
    inp = torch.zeros(shape, dtype=torch.float32, device=DEVICE)
    res = flag_gems.fft_rfft(inp)
    assert res.shape == shape[:-1] + (shape[-1] // 2 + 1,)
    assert res.dtype == torch.complex64
    assert res.numel() == 0


