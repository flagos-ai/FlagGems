    with pytest.raises((ValueError, RuntimeError)):
        flag_gems.grid_sampler(input_t, grid4, 3, 0, False)
    with pytest.raises((ValueError, RuntimeError)):
        flag_gems.grid_sampler(input_t, grid4, 0, 5, False)

