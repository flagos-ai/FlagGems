    grid_bad = torch.rand(2, 4, 4, 3, device=flag_gems.device)
    with pytest.raises((ValueError, RuntimeError)):
        flag_gems.grid_sampler(input_t, grid_bad, 0, 0, False)
    grid_bat = torch.rand(1, 4, 4, 2, device=flag_gems.device)
    with pytest.raises((ValueError, RuntimeError)):
        flag_gems.grid_sampler(input_t, grid_bat, 0, 0, False)
