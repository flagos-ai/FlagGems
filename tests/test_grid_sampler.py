@pytest.mark.grid_sampler
def test_grid_sampler_out_of_range_grid():
    # Grids far outside [-1, 1] plus NaN coordinates: zeros padding must give
    # 0 for both, border/reflection give finite clamped/reflected values, and
    # NaN grid entries map to 0 under border/reflection (PyTorch semantics).
    N, C, H, W = 1, 2, 4, 4
    OH, OW = 3, 3
    input_t = torch.randn(N, C, H, W, device=flag_gems.device)
    gex = torch.full((N, OH, OW, 2), 100.0, device=flag_gems.device)
    gnan = torch.full((N, OH, OW, 2), float("nan"), device=flag_gems.device)

    ref_in = utils.to_reference(input_t).to(torch.float32)
    ref_gex = utils.to_reference(gex).to(torch.float32)
    ref_gnan = utils.to_reference(gnan).to(torch.float32)
    # torch's zeros-padding NaN behavior is backend-dependent (CUDA yields 0,
    # CPU propagates NaN), so the NaN-vs-zeros combination is compared against
    # the CUDA reference only.
    is_cuda_ref = ref_in.device.type == "cuda"
    for pad in (0, 1, 2):
        ref_ex = torch.ops.aten.grid_sampler(ref_in, ref_gex, 0, pad, False)
        res_ex = flag_gems.grid_sampler(input_t, gex, 0, pad, False)
        utils.gems_assert_close(res_ex, ref_ex, torch.float32)

        if not is_cuda_ref and pad == 0:
            # CPU reference disagrees with CUDA on zeros+NaN; skip that combo.
            continue
        ref_na = torch.ops.aten.grid_sampler(ref_in, ref_gnan, 0, pad, False)
        res_na = flag_gems.grid_sampler(input_t, gnan, 0, pad, False)
        utils.gems_assert_close(res_na, ref_na, torch.float32, equal_nan=False)


