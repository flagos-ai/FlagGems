def test_grid_sampler_error_paths():
    # Error paths mirror torch's own checks.
    input_t = torch.randn(2, 3, 4, 4, device=flag_gems.device)
    grid4 = torch.rand(2, 4, 4, 2, device=flag_gems.device)

    # bicubic on 5D is rejected
    input5 = torch.randn(1, 1, 2, 2, 2, device=flag_gems.device)
    grid5 = torch.rand(1, 2, 2, 2, 3, device=flag_gems.device)
    with pytest.raises((ValueError, RuntimeError)):
        flag_gems.grid_sampler(input5, grid5, 2, 0, False)

