"""Accuracy tests for ``aten::slow_conv_transpose2d``.

The reference is ``torch.ops.aten.slow_conv_transpose2d`` itself, called on the
upcast (or on-CPU) reference tensors produced by ``utils.to_reference``, so the
comparison exercises the same ATen math the operator has to reproduce.

Note that a transposed convolution stores its weight as ``(C_in, C_out, kH, kW)``
-- the opposite of ``aten::conv2d`` -- so the weight shapes below are read as
input channels first.  ``output_padding`` has to stay strictly smaller than
either ``stride`` or ``dilation`` for the same axis, which is what the
combinations below respect.
"""

import pytest
import torch

import flag_gems

from . import accuracy_utils as utils

# (input_shape, weight_shape, use_bias, stride, padding, output_padding, dilation)
# Covers the 4-D batched and 3-D unbatched entry points, the plain stride-1
# route, strided routes with and without output_padding, asymmetric pairs and a
# dilated route.  Spatial extents stay small so the whole matrix runs quickly.
CONV_TRANSPOSE2D_CASES = [
    ((2, 3, 8, 8), (3, 4, 3, 3), True, 1, 0, 0, 1),
    ((2, 3, 8, 8), (3, 4, 3, 3), False, (2, 2), (1, 1), (1, 1), 1),
    ((1, 4, 5, 6), (4, 2, 3, 2), True, (2, 1), (1, 0), (1, 0), 1),
    ((3, 8, 8), (3, 4, 3, 3), True, 1, 0, 0, 1),
    ((2, 5, 5), (2, 3, 2, 2), False, (2, 2), (0, 1), (0, 1), 1),
    ((1, 3, 6, 6), (3, 2, 2, 2), True, 1, (1, 1), 0, (2, 2)),
]

# The fp16/bf16 forward path is a tf32 tl.dot with an fp32 accumulator, so the
# absolute tolerance has to cover the reduced multiply precision; the fp32 path
# runs with `input_precision="ieee"` and keeps the default tolerance.
CONV_TRANSPOSE2D_ATOL = {torch.float16: 2e-2, torch.bfloat16: 2e-2}


def _as_pair(value):
    return (value, value) if isinstance(value, int) else tuple(value)


def _reference(
    inp, weight, bias, kernel_size, stride, padding, output_padding, dilation
):
    return torch.ops.aten.slow_conv_transpose2d(
        inp,
        weight,
        list(kernel_size),
        bias,
        list(stride),
        list(padding),
        list(output_padding),
        list(dilation),
    )


@pytest.mark.slow_conv_transpose2d
@pytest.mark.parametrize(
    "input_shape, weight_shape, use_bias, stride, padding, output_padding, dilation",
    CONV_TRANSPOSE2D_CASES,
)
@pytest.mark.parametrize("dtype", utils.FLOAT_DTYPES)
def test_slow_conv_transpose2d(
    input_shape,
    weight_shape,
    use_bias,
    stride,
    padding,
    output_padding,
    dilation,
    dtype,
):
    stride = _as_pair(stride)
    padding = _as_pair(padding)
    output_padding = _as_pair(output_padding)
    dilation = _as_pair(dilation)
    kernel_size = (weight_shape[2], weight_shape[3])

    inp = torch.randn(input_shape, dtype=dtype, device=flag_gems.device)
    weight = torch.randn(weight_shape, dtype=dtype, device=flag_gems.device)
    bias = None
    if use_bias:
        bias = torch.randn(weight_shape[1], dtype=dtype, device=flag_gems.device)

    ref_inp = utils.to_reference(inp, True)
    ref_weight = utils.to_reference(weight, True)
    ref_bias = utils.to_reference(bias, True)
    ref_out = _reference(
        ref_inp,
        ref_weight,
        ref_bias,
        kernel_size,
        stride,
        padding,
        output_padding,
        dilation,
    ).to(dtype)

    res_out = flag_gems.slow_conv_transpose2d(
        inp, weight, kernel_size, bias, stride, padding, output_padding, dilation
    )
    # Every output element accumulates C_in * kH * kW terms, so scale the
    # absolute tolerance by that count, as the sibling conv tests do.
    reduce_dim = weight_shape[0] * kernel_size[0] * kernel_size[1]
    utils.gems_assert_close(
        res_out,
        ref_out,
        dtype,
        reduce_dim=reduce_dim,
        atol=CONV_TRANSPOSE2D_ATOL.get(dtype, 1e-4),
    )


@pytest.mark.slow_conv_transpose2d
@pytest.mark.parametrize("dtype", utils.FLOAT_DTYPES)
def test_slow_conv_transpose2d_out_variant(dtype):
    """The ``out=`` form writes into the supplied tensor and returns it."""
    input_shape = (2, 3, 8, 8)
    weight_shape = (3, 4, 3, 3)
    kernel_size = (3, 3)
    stride = (2, 2)
    padding = (1, 1)
    output_padding = (1, 1)
    dilation = (1, 1)

    inp = torch.randn(input_shape, dtype=dtype, device=flag_gems.device)
    weight = torch.randn(weight_shape, dtype=dtype, device=flag_gems.device)
    bias = torch.randn(weight_shape[1], dtype=dtype, device=flag_gems.device)

    ref_out = _reference(
        utils.to_reference(inp, True),
        utils.to_reference(weight, True),
        utils.to_reference(bias, True),
        kernel_size,
        stride,
        padding,
        output_padding,
        dilation,
    ).to(dtype)

    out = torch.empty_like(ref_out, device=flag_gems.device)
    res_out = flag_gems.slow_conv_transpose2d(
        inp,
        weight,
        kernel_size,
        bias,
        stride,
        padding,
        output_padding,
        dilation,
        out=out,
    )
    assert res_out.data_ptr() == out.data_ptr()
    reduce_dim = weight_shape[0] * kernel_size[0] * kernel_size[1]
    utils.gems_assert_close(
        out,
        ref_out,
        dtype,
        reduce_dim=reduce_dim,
        atol=CONV_TRANSPOSE2D_ATOL.get(dtype, 1e-4),
    )
