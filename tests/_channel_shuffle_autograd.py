import torch

from . import accuracy_utils as utils


def compare_gradients(
    actual_out, expected_out, inputs, refs, dtype, reduce_dim=1, forward_reference=None
):
    utils.gems_assert_close(
        actual_out,
        utils.to_reference(
            expected_out if forward_reference is None else forward_reference
        ),
        dtype,
        reduce_dim=reduce_dim,
        equal_nan=True,
    )
    grad = torch.randn(
        (*actual_out.shape, 2), device=actual_out.device, dtype=actual_out.dtype
    )[..., 1]
    actual = torch.autograd.grad(actual_out, inputs, grad)
    expected = torch.autograd.grad(expected_out, refs, grad)
    for got, want, source in zip(actual, expected, inputs):
        assert got.shape == source.shape
        assert got.dtype == source.dtype
        utils.gems_assert_close(
            got, utils.to_reference(want), dtype, reduce_dim=reduce_dim, equal_nan=True
        )
