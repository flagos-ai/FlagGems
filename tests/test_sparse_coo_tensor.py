def _coords(dtype=torch.float32, nnz=8, dense=()):
    """Deterministic, duplicate-free coordinates plus matching values."""
    linear = torch.arange(nnz, device=DEVICE)
    indices = torch.stack([((linear * 3 + d) % nnz) for d in range(2)]).to(torch.int64)
    total = nnz
    for extent in dense:
        total *= extent
    values = torch.arange(total, dtype=dtype, device=DEVICE).reshape((nnz,) + dense)
    return indices, values


