import pytest
import torch

import flag_gems

from . import accuracy_utils as utils

pytestmark = [
    pytest.mark.binary_cross_entropy_with_logits,
    pytest.mark.binary_cross_entropy_with_logits_backward,
]


@pytest.mark.parametrize("dtype", utils.FLOAT_DTYPES)
@pytest.mark.parametrize("seed", range(8))
@pytest.mark.parametrize("weights", ["none", "weight", "pos", "both"])
@pytest.mark.parametrize("reduction", [0, 1, 2])
def test_bce_backward_low_precision_boundaries(dtype, seed, weights, reduction):
    torch.manual_seed(seed)
    # All binary16 bit patterns cover narrow sigmoid/log-sigmoid rounding
    # boundaries that normal FP16 random generation rarely reaches. Native
    # CUDA is the oracle for dtype materialization; NaN/Inf are retained.
    values = torch.arange(65536, device=flag_gems.device, dtype=torch.int32)
    values = values.to(torch.int16).view(torch.float16).to(dtype).view(256, 256)
    storage = torch.empty((256, 256, 2), device=values.device, dtype=dtype)
    storage[..., 1] = values
    x = storage[..., 1].detach().requires_grad_()
    target = torch.rand_like(x).requires_grad_()
    refs = [t.detach().clone().requires_grad_() for t in (x, target)]
    weight = (
        torch.rand(256, device=x.device, dtype=dtype)
        if weights in ("weight", "both")
        else None
    )
    positive = (
        torch.rand(256, device=x.device, dtype=dtype) * 2
        if weights in ("pos", "both")
        else None
    )
    actual = flag_gems.binary_cross_entropy_with_logits(
        x, target, weight=weight, pos_weight=positive, reduction=reduction
    )
    expected = torch.nn.functional.binary_cross_entropy_with_logits(
        *refs,
        weight=weight,
        pos_weight=positive,
        reduction=["none", "mean", "sum"][reduction],
    )
    grad = torch.randn((*actual.shape, 2), device=x.device, dtype=dtype)[..., 1]
    got = torch.autograd.grad(actual, (x, target), grad)
    want = torch.autograd.grad(expected, refs, grad)
    for a, b in zip(got, want):
        utils.gems_assert_close(a, utils.to_reference(b), dtype, equal_nan=True)
