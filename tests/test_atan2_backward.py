import pytest
import torch

import flag_gems

from . import accuracy_utils as utils
from ._atan2_autograd import compare_gradients

pytestmark = [pytest.mark.atan2, pytest.mark.atan2_backward]


@pytest.mark.parametrize("dtype", utils.FLOAT_DTYPES)
@pytest.mark.parametrize(
    "shapes",
    [
        ((), ()),
        ((0,), (0,)),
        ((0,), ()),
        ((), (0,)),
        ((257,), (257,)),
        ((17, 33), (33,)),
        ((2, 1, 5), (1, 3, 1)),
        ((17, 33), ()),
    ],
)
@pytest.mark.parametrize("needs", [(True, True), (True, False), (False, True)])
@pytest.mark.parametrize("strided", [False, True])
def test_atan2_backward(dtype, shapes, needs, strided):
    values = []
    for shape, required in zip(shapes, needs):
        value = (
            torch.randn((*shape, 2), device=flag_gems.device, dtype=dtype)[..., 1]
            if strided
            else torch.randn(shape, device=flag_gems.device, dtype=dtype)
        )
        values.append(value.detach().requires_grad_(required))
    refs = [x.detach().clone().requires_grad_(need) for x, need in zip(values, needs)]
    result = flag_gems.atan2(*values)
    reference = torch.atan2(*refs)
    compare_gradients(
        result,
        reference,
        [x for x in values if x.requires_grad],
        [x for x in refs if x.requires_grad],
        dtype,
        reduce_dim=15,
    )


@pytest.mark.parametrize("dtype", utils.FLOAT_DTYPES)
def test_atan2_backward_singular(dtype):
    x = torch.zeros(17, dtype=dtype, device=flag_gems.device, requires_grad=True)
    y = torch.zeros_like(x, requires_grad=True)
    gx, gy = torch.autograd.grad(flag_gems.atan2(x, y), (x, y), torch.ones_like(x))
    assert torch.isnan(gx).all() and torch.isnan(gy).all()
