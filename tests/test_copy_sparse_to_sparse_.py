import weakref

import pytest
import torch

import flag_gems

from . import accuracy_utils as utils


@pytest.mark.copy_sparse_to_sparse_
@pytest.mark.parametrize("dtype", utils.FLOAT_DTYPES)
@pytest.mark.parametrize("resize", [False, True])
@pytest.mark.parametrize("coalesced", [False, True])
@pytest.mark.parametrize("strided", [False, True])
def test_copy_sparse_to_sparse_(dtype, resize, coalesced, strided):
    idx = torch.tensor([[0, 1, 2], [1, 0, 2]], device=flag_gems.device)
    values = torch.randn((3, 4), dtype=dtype, device=flag_gems.device)
    if strided:
        idx = idx.t().contiguous().t()
        values = values.t().contiguous().t()
    src = torch.sparse_coo_tensor(idx, values, (3, 3, 4), is_coalesced=coalesced)
    if resize:
        dst = torch.sparse_coo_tensor(
            torch.empty((2, 0), dtype=torch.int64, device=flag_gems.device),
            torch.empty((0, 4), dtype=dtype, device=flag_gems.device),
            (5, 5, 4),
        )
    else:
        dst = torch.sparse_coo_tensor(
            idx.clone(), torch.zeros_like(values), (3, 3, 4), is_coalesced=not coalesced
        )
    dst_ref = weakref.ref(dst)
    old_values = dst._values()
    ref = torch.ops.aten.copy_sparse_to_sparse_.default(
        utils.to_reference(dst.clone()), utils.to_reference(src)
    )
    res = flag_gems.copy_sparse_to_sparse_(dst, src)
    assert res is dst_ref() is dst
    assert res.shape == ref.shape
    assert res.is_coalesced() == ref.is_coalesced()
    utils.gems_assert_equal(res._indices(), ref._indices())
    utils.gems_assert_equal(res._values(), ref._values())
    if not resize:
        utils.gems_assert_equal(old_values, ref._values())


