def _make_nested(dtype, device, shapes):
    parts = []
    for shape in shapes:
        if dtype.is_floating_point:
            parts.append(torch.randn(shape, dtype=dtype, device=device))
        elif dtype == torch.bool:
            parts.append(torch.zeros(shape, dtype=dtype, device=device))
        else:
            parts.append(torch.randint(0, 100, shape, dtype=dtype, device=device))
    return torch.nested.nested_tensor(parts, device=device)


