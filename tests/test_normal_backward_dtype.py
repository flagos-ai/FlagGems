import pytest
import torch

import flag_gems

from . import accuracy_utils as utils

pytestmark = [pytest.mark.normal_backward, pytest.mark.normal]


@pytest.mark.parametrize("dtype", utils.FLOAT_DTYPES)
@pytest.mark.parametrize("shape", [(), (0,), (5, 7)])
@pytest.mark.parametrize("kind", [0, 1, 2])
def test_tensor_parameter_dtype_and_zero_derivative(dtype, shape, kind):
    mean = torch.zeros(shape, dtype=dtype, device=flag_gems.device, requires_grad=True)
    std = torch.ones(shape, dtype=dtype, device=flag_gems.device, requires_grad=True)
    if kind == 0:
        output = flag_gems.normal_tensor_tensor(mean, std)
        targets = (mean, std)
    elif kind == 1:
        output = flag_gems.normal_tensor_float(mean, 1.0)
        targets = (mean,)
    else:
        output = flag_gems.normal_float_tensor(0.5, std)
        targets = (std,)
    assert output.dtype == dtype and output.shape == shape
    gradients = torch.autograd.grad(
        output, targets, torch.full_like(output, float("nan"))
    )
    for gradient, target in zip(gradients, targets):
        assert gradient.dtype == target.dtype and gradient.shape == target.shape
        utils.gems_assert_equal(gradient, utils.to_reference(torch.zeros_like(target)))


# Native Tensor/Tensor normal uses the mean dtype, including mixed parameters.
@pytest.mark.parametrize(
    "mean_dtype,std_dtype",
    [
        (torch.float16, torch.float32),
        (torch.bfloat16, torch.float32),
        (torch.float32, torch.float64),
    ],
)
def test_mixed_tensor_parameter_output_dtype(mean_dtype, std_dtype):
    mean = torch.zeros(7, dtype=mean_dtype, device=flag_gems.device, requires_grad=True)
    std = torch.ones(7, dtype=std_dtype, device=flag_gems.device, requires_grad=True)
    expected = torch.normal(mean, std)
    actual = flag_gems.normal_tensor_tensor(mean, std)
    assert actual.dtype == expected.dtype == mean_dtype
    gradients = torch.autograd.grad(actual, (mean, std), torch.ones_like(actual))
    for gradient, target in zip(gradients, (mean, std)):
        assert gradient.dtype == target.dtype
        utils.gems_assert_equal(gradient, utils.to_reference(torch.zeros_like(target)))
