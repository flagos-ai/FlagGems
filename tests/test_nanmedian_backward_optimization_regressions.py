import pytest
import torch

import flag_gems

from . import accuracy_utils as utils


@pytest.mark.nanmedian_backward
@pytest.mark.parametrize(
    "values", [[float("nan")] * 4, [1.0, 2.0, 3.0], [float("inf")] * 3]
)
@pytest.mark.parametrize("upstream", [1.0, float("nan"), float("inf")])
def test_global_nanmedian_special_values(values, upstream):
    x = torch.tensor(
        values, dtype=torch.float32, device=flag_gems.device, requires_grad=True
    )
    ref = utils.to_reference(x).detach().requires_grad_()
    expected = torch.nanmedian(ref)
    actual = flag_gems.nanmedian(x)
    utils.gems_assert_close(actual, expected, x.dtype, equal_nan=True)
    grad = torch.tensor(upstream, device=x.device)
    (dx,) = torch.autograd.grad(actual, x, grad)
    (dr,) = torch.autograd.grad(expected, ref, utils.to_reference(grad))
    if utils.TO_CPU and not torch.isfinite(utils.to_reference(grad)):
        # Native CPU uses where; CUDA multiplies the mask, preserving 0*NaN/Inf.
        # Independently emulate CUDA for these nonfinite upstream gradients.
        mask = (ref == expected) | (torch.isnan(ref) & torch.isnan(expected))
        dr = utils.to_reference(grad) / mask.sum() * mask.to(ref.dtype)
    utils.gems_assert_close(dx, dr, x.dtype, equal_nan=True)


pytestmark = [pytest.mark.nanmedian]
