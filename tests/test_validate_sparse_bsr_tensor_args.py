def _make_inputs(layout, shape, index_dtype, dtype, device, strided_batch=False):
    cdim, dim, batch, dense = shape
    blocked = layout in (torch.sparse_bsr, torch.sparse_bsc)
    row_major = layout in (torch.sparse_csr, torch.sparse_bsr)
    per_segment = min(dim, 2)
    nnz = cdim * per_segment
    comp = torch.arange(cdim + 1, dtype=index_dtype, device=device) * per_segment
    plain = torch.arange(per_segment, dtype=index_dtype, device=device).repeat(cdim)
    comp = comp.expand(*batch, cdim + 1).clone()
    plain = plain.expand(*batch, nnz).clone()
    if strided_batch and batch:
        comp = torch.stack((comp, comp), dim=-2)[..., 0, :]
        plain = torch.stack((plain, plain), dim=-2)[..., 0, :]
    br, bc = (2, 3) if blocked else (1, 1)
    rows, cols = (cdim, dim) if row_major else (dim, cdim)
    block_shape = (br, bc) if blocked else ()
    values = torch.zeros(
        (*batch, nnz, *block_shape, *dense), dtype=dtype, device=device
    )
    size = (*batch, rows * br, cols * bc, *dense)
    return comp, plain, values, size


