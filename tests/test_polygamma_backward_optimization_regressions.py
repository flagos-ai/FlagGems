import pytest
import torch

import flag_gems

from . import accuracy_utils as utils


@pytest.mark.polygamma_backward
@pytest.mark.parametrize("dtype", utils.FLOAT_DTYPES)
@pytest.mark.parametrize("order", range(7))
def test_polygamma_derivative_wide_positive_domain(dtype, order):
    x = (
        torch.logspace(-2, 2, 1025, dtype=torch.float64, device=flag_gems.device)
        .to(dtype)
        .requires_grad_()
    )
    y = flag_gems.polygamma(order, x)
    (actual,) = torch.autograd.grad(y, x, torch.full_like(y, 0.75))
    # FP64 analytic derivative, rounded before upstream multiplication as CUDA does.
    reference = torch.polygamma(order + 1, x.detach().double()).to(dtype) * 0.75
    utils.gems_assert_close(
        actual, utils.to_reference(reference), dtype, equal_nan=True
    )


pytestmark = [pytest.mark.polygamma]
