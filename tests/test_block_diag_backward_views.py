import pytest
import torch

import flag_gems

from . import accuracy_utils as utils

pytestmark = [pytest.mark.block_diag, pytest.mark.block_diag_backward]


@pytest.mark.parametrize("dtype", utils.FLOAT_DTYPES)
@pytest.mark.parametrize("shapes", [((3, 4), (2, 5)), ((0, 4), (0, 4))])
@pytest.mark.parametrize("strided", [False, True])
def test_block_diag_backward_views_higher_order(dtype, shapes, strided):
    xs = [
        torch.randn(s, device=flag_gems.device, dtype=dtype, requires_grad=True)
        for s in shapes
    ]
    refs = [x.detach().clone().requires_grad_() for x in xs]
    actual, expected = flag_gems.block_diag(*xs), torch.block_diag(*refs)
    shape = (*actual.shape, 3) if strided else actual.shape
    grad = torch.randn(shape, device=flag_gems.device, dtype=dtype)
    grad = (grad[..., 1] if strided else grad).detach().requires_grad_()
    reference_grad = grad.detach().clone().requires_grad_()
    got = torch.autograd.grad(actual, xs, grad, create_graph=True)
    want = torch.autograd.grad(expected, refs, reference_grad, create_graph=True)
    for a, b in zip(got, want):
        torch.testing.assert_close(a, b, atol=0, rtol=0)
        assert a.untyped_storage().data_ptr() == grad.untyped_storage().data_ptr()
    weights = [torch.randn_like(x) for x in xs]
    actual_second = torch.autograd.grad(got, grad, weights)[0]
    expected_second = torch.autograd.grad(want, reference_grad, weights)[0]
    torch.testing.assert_close(actual_second, expected_second, atol=0, rtol=0)


