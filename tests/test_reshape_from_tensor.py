    # Triton moves complex values as real/imaginary pairs.
    inp = torch.randn((4, 6), dtype=torch.complex64, device=flag_gems.device).t()
    if conjugate:
        inp = inp.conj()
    if negative:
        inp = torch.ops.aten._neg_view.default(inp)
    shape = torch.tensor([2, 12], dtype=torch.int64)
    ref = torch.ops.aten._reshape_from_tensor.default(utils.to_reference(inp), shape)
    res = flag_gems._reshape_from_tensor(inp, shape)
