import pytest
import torch

import flag_gems

from . import accuracy_utils as utils


@pytest.mark.reshape_from_tensor
@pytest.mark.underscore_reshape_from_tensor
@pytest.mark.parametrize("dtype", utils.FLOAT_DTYPES)
@pytest.mark.parametrize(
    "layout", ["view", "transpose", "offset", "empty", "high_rank"]
)
def test_reshape_from_tensor(dtype, layout):
    inp = torch.randn((4, 6), dtype=dtype, device=flag_gems.device)
    if layout == "transpose":
        inp = inp.t()
    elif layout == "offset":
        inp = inp[1:, 1::2].t()
    elif layout == "empty":
        inp = inp[:0]
    elif layout == "high_rank":
        inp = torch.randn((2,) * 9, device=flag_gems.device, dtype=dtype).permute(
            8, 6, 4, 2, 0, 7, 5, 3, 1
        )
    shape = torch.tensor([-1], dtype=torch.int64)
    ref = torch.ops.aten._reshape_from_tensor.default(utils.to_reference(inp), shape)
    native = torch.ops.aten._reshape_from_tensor.default(inp, shape)
    res = flag_gems._reshape_from_tensor(inp, shape)
    utils.gems_assert_equal(res, ref)
    assert res.stride() == native.stride()
    assert res.storage_offset() == native.storage_offset()
    if inp.numel():
        assert (res.data_ptr() == inp.data_ptr()) == (
            native.data_ptr() == inp.data_ptr()
        )


