def _network(n):
    """Bose-Nelson compare-exchange network (cutlass ``StaticSort``)."""
    seq = []

    def pb(i, j, x, y):
        if x == 1 and y == 1:
            seq.append((i - 1, j - 1))
        elif x == 1 and y == 2:
            seq.append((i - 1, j))
            seq.append((i - 1, j - 1))
        elif x == 2 and y == 1:
            seq.append((i - 1, j - 1))
            seq.append((i, j - 1))
        else:
            left = x >> 1
            mid = (y if (x & 1) else (y + 1)) >> 1
            pb(i, j, left, mid)
            pb(i + left, j + mid, x - left, y - mid)
            pb(i + left, j, x - left, mid)

    def ps(i, m):
        if m <= 1:
            return
        left = m >> 1
        ps(i, left)
        ps(i + left, m - left)
        pb(i, i + left, left, m - left)

    ps(1, n)
    return seq


