def _reference_mask(dense, algorithm):
    """Reference selection on CPU, mirroring the aten CUDA kernel.

    Each 4x4 tile is sorted ascending with the CUTLASS ``StaticSort``
    compare-exchange network (a compare-exchange swaps whenever ``not lhs <
    rhs``, so equal keys are exchanged as well) and then scanned from the
    largest, keeping a value when its tile row and tile column still have
    capacity.  ``dense`` is the input tensor (on any device).
    """
    vals = dense.detach().to("cpu").to(torch.float32)
    key = vals.abs() if algorithm == "largest_abs_values_greedy" else vals
    rows, cols = vals.shape
    rows_r = (rows + 31) // 32 * 32
    cols_r = (cols + 63) // 64 * 64
    padded = torch.full((rows_r, cols_r), float("-inf"), dtype=torch.float32)
    padded[:rows, :cols] = vals
    keys = torch.full((rows_r, cols_r), float("-inf"), dtype=torch.float32)
    keys[:rows, :cols] = key
    out = torch.zeros((rows_r, cols_r), dtype=torch.float64)
    nb, ntb = rows_r // 4, cols_r // 4
    for i in range(nb):
        for j in range(ntb):
            tile = keys[4 * i : 4 * i + 4, 4 * j : 4 * j + 4]
            order = list(range(16))
            kvals = tile.flatten().tolist()
            for a, b in _NET16:
                if not (kvals[a] < kvals[b]):
                    kvals[a], kvals[b] = kvals[b], kvals[a]
                    order[a], order[b] = order[b], order[a]
            nr = [0] * 4
            nc = [0] * 4
            for step in range(15, -1, -1):
                r, c = order[step] // 4, order[step] % 4
                if nr[r] < 2 and nc[c] < 2:
                    out[4 * i + r, 4 * j + c] = padded[4 * i + r, 4 * j + c].item()
                    nr[r] += 1
                    nc[c] += 1
    return out


