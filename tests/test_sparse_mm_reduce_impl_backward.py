def test_sparse_mm_reduce_impl_backward_strided_inputs(reduce):
    # The kernels must honour the caller's strides: ``weight`` can be a
    # transposed (column-major) view and ``grad_out`` a non-contiguous slice.
    # The old amax/amin kernel hard-coded ``col * N`` for the grad_other row
    # stride, which silently wrote the wrong rows for these layouts.
    device = flag_gems.device
    M, N, K = 6, 10, 4
    dtype = torch.float32
    _, sparse = _make_sparse(M, K, dtype, device, 0.5, "csr")
    csr = _csr_of(sparse)

    weight = torch.randn((N, K), dtype=dtype, device=device).t()
    assert weight.stride(0) == 1 and not weight.is_contiguous()
    grad_out_base = torch.randn((M, N * 2), dtype=dtype, device=device)
    grad_out = grad_out_base[:, ::2]
    assert not grad_out.is_contiguous()

    arg_out = None
    if reduce in ("amax", "amin"):
        arg_out = _make_arg_out(csr, weight, reduce)
    ref_gv, ref_go = _reference_grads(csr, grad_out, weight, reduce)
    res_self, res_other = flag_gems._sparse_mm_reduce_impl_backward(
        sparse, grad_out, weight, reduce, arg_out
    )
    utils.gems_assert_close(res_self.values().cpu(), ref_gv.cpu(), dtype, atol=1e-4)
    utils.gems_assert_close(
        res_other.cpu(), ref_go.cpu(), dtype, atol=1e-4, reduce_dim=max(M, 1)
    )


