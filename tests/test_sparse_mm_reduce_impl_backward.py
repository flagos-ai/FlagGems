def _make_arg_out(csr, weight, reduce):
    """Build the forward's arg_out contract (strict > / <, first index wins).

    Matches aten's update_with_index rule: each (row, n) holds the nnz index
    of the argmax/argmin of val[e] * weight[col[e], n] over the row's stored
    entries, or the nnz sentinel for rows with no stored entries.  The fold is
    vectorised over the padded (row, slot) product matrix -- products keep CSR
    order inside a row and argmax/argmin report the first extremal slot, which
    is exactly the strict first-index rule.
    """
    crow, col, vals = csr
    M = crow.numel() - 1
    N = weight.shape[1]
    nnz = int(col.numel())
    counts = (crow[1:] - crow[:-1]).clamp_min(0)
    slots = int(counts.max().item()) if M > 0 else 0
    if slots == 0:
        return torch.full((M, N), nnz, dtype=torch.int64, device=col.device)
    row = torch.repeat_interleave(
        torch.arange(M, device=col.device, dtype=torch.int64), counts
    )
    within = torch.arange(nnz, device=col.device) - crow[row]
    prod = vals.to(torch.float64)[:, None] * weight.to(torch.float64)[col, :]
    pad = float("-inf") if reduce == "amax" else float("inf")
    pm = torch.full((M, slots, N), pad, dtype=torch.float64, device=col.device)
    pm[row, within] = prod
    slot_arg = pm.argmax(dim=1) if reduce == "amax" else pm.argmin(dim=1)
    e_idx = torch.zeros(M, slots, dtype=torch.int64, device=col.device)
    e_idx[row, within] = torch.arange(nnz, device=col.device)
    arg = torch.where((counts > 0).view(M, 1), torch.gather(e_idx, 1, slot_arg), nnz)
    return arg


def _reference_grads(csr, grad_out, weight, reduce):
    """fp64 reference for the backward pair.

    ``aten::_sparse_mm_reduce_impl_backward`` is only registered for
    ``SparseCsrCPU`` in torch, so the reference mirrors the CPU kernel's math
    from the stored CSR structure:
      - sum:   grad_val[e] = dot(weight[col[e], :], grad_out[row(e), :])
               grad_other = dense(self)^T @ grad_out
      - mean:  both divided by the row's stored nnz
      - amax/amin: the gradient flows only through the entries referenced by
        arg_out (built with the same strict > / < first-index rule as the
        forward pass's arg contract).
    """
    crow, col, vals = csr
    M = crow.numel() - 1
    K = weight.shape[0]
    N = weight.shape[1]
    nnz = int(col.numel())
    ref_csr_vals = utils.to_reference(vals, True)
    ref_go = utils.to_reference(grad_out, True)
    ref_w = utils.to_reference(weight, True)
    # col comes from the CUDA-side structure; under --ref cpu the reference
    # tensors live on CPU, so move the structure indices along.
    counts = (crow[1:] - crow[:-1]).clamp_min(0)
    col_r = col.to(ref_csr_vals.device)
    row = torch.repeat_interleave(
        torch.arange(M, device=ref_csr_vals.device, dtype=torch.int64),
        counts.to(ref_csr_vals.device),
    )

    # aten's CPU kernel accumulates in ``opmath_t``: float32 for fp16/bf16
    # inputs and the input dtype itself for fp32/fp64.  Mirroring that keeps
    # the reference's reduction precision identical to the kernel's; an fp64
    # reference would differ by up to one bf16 ulp wherever the row's products
    # cancel (hf32/bf16 inputs are only stored at ~3 decimal digits).
    calc = torch.float64 if vals.dtype == torch.float64 else torch.float32
    rvals = ref_csr_vals.to(calc)
    rgo = ref_go.to(calc)
    rw = ref_w.to(calc)

    gv = torch.zeros(nnz, dtype=calc, device=ref_csr_vals.device)
    gother = torch.zeros((K, N), dtype=calc, device=ref_csr_vals.device)

    if reduce in ("sum", "mean"):
        # grad_val[e] = dot(weight[col[e]], grad_out[row(e)]); for mean both
        # outputs divide by the row's stored nnz.
        contrib = rvals[:, None] * rgo[row]
        counts_r = counts.to(ref_csr_vals.device)
        if reduce == "mean":
            denom = counts_r[row].to(calc).clamp_min(1).view(-1, 1)
            contrib = contrib / denom
        gv = (rw[col_r] * rgo[row]).sum(dim=1)
        if reduce == "mean":
            gv = gv / counts_r[row].to(calc).clamp_min(1)
        gother.index_add_(0, col_r, contrib)
    else:
        arg = _make_arg_out(csr, weight, reduce).to(ref_csr_vals.device)
        selected = arg < nnz
        e = arg[selected]
        rr = (
            torch.arange(M, device=ref_csr_vals.device)
            .view(-1, 1)
            .expand(M, N)[selected]
        )
        nn = (
            torch.arange(N, device=ref_csr_vals.device)
            .view(1, -1)
            .expand(M, N)[selected]
        )
        gv.index_add_(0, e, rw[col_r[e], nn] * rgo[rr, nn])
        gother.index_put_(
            (col_r[e], nn),
            rvals[e] * rgo[rr, nn],
            accumulate=True,
        )
    # ``--ref cpu`` keeps the reference on CPU (to_reference moves the inputs
    # there); the caller moves the reference outputs to match the convention
    # used by the sparse_sampled_addmm tests (ref stays on CPU, results are
    # moved there for comparison).
    return gv, gother


