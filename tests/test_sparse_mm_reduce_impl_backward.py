def test_dispatch_reaches_gems_impl():
    # Structural dispatch proof: the SparseCsr key registration must be
    # selected for a CSR ``self``. The registrar resolves impls through
    # FULL_CONFIG_BY_FUNC, so the mapping entry is swapped for a spy and the
    # aten call must land there (an aten fallback would skip it).
    import unittest.mock

    calls = {"count": 0}
    real_impl = flag_gems._sparse_mm_reduce_impl_backward

    def spy(*args, **kwargs):
        calls["count"] += 1
        return real_impl(*args, **kwargs)

    mapping = dict(flag_gems.FULL_CONFIG_BY_FUNC)
    mapping["_sparse_mm_reduce_impl_backward"] = [
        ("_sparse_mm_reduce_impl_backward", spy) + tuple(item[2:])
        for item in mapping.get("_sparse_mm_reduce_impl_backward", [])
    ]
    sparse = torch.eye(4, device=flag_gems.device).to_sparse_csr()
    grad_out = torch.randn(4, 4, device=flag_gems.device)
    weight = torch.randn(4, 4, device=flag_gems.device)
    with unittest.mock.patch.object(flag_gems, "FULL_CONFIG_BY_FUNC", mapping):
        # only_enable is the CI-compliant activation path (use_gems() is
        # banned in test files) and is idempotent for an already-registered
        # op, so no explicit teardown is needed.
        flag_gems.only_enable(include=["_sparse_mm_reduce_impl_backward"])
        res_self, _ = torch.ops.aten._sparse_mm_reduce_impl_backward(
            sparse,
            grad_out,
            weight,
            "sum",
            torch.empty(0, dtype=torch.int64, device=flag_gems.device),
            [True, True],
        )

    assert calls["count"] == 1, "aten dispatch did not reach the Gems implementation"
    assert res_self.layout == torch.sparse_csr
