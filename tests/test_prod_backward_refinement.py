from types import SimpleNamespace

import pytest
import torch

import flag_gems

from . import accuracy_utils as utils
from ._prod_backward_reference_fixes import prod_cpu_half_precision


@pytest.mark.prod_backward
@pytest.mark.parametrize("dtype", utils.FLOAT_DTYPES)
@pytest.mark.parametrize("dim", [None, -1])
@pytest.mark.parametrize("zeros", [0, 1, 2])
def test_split_product_with_and_without_zeros(dtype, dim, zeros):
    torch.manual_seed(11)
    shape = (4097,) if dim is None else (3, 2051)
    x = 1 + (torch.rand(shape, device=flag_gems.device, dtype=dtype) * 2 - 1) * 0.001
    if zeros:
        x.flatten()[:zeros] = 0
        if dim is not None:
            x[1, :2] = 0
    x.requires_grad_()
    kw = {} if dim is None else {"dim": dim}
    actual = flag_gems.prod(x) if dim is None else flag_gems.prod_dim(x, dim)
    ref = utils.to_reference(x).detach().requires_grad_()
    # Preserve the established same-dtype CPU scan oracle for CUDA Half zeros.
    if dtype == torch.float16 and zeros and not utils.TO_CPU:
        ref = x.detach().cpu().requires_grad_()
    expected = torch.prod(ref, **kw)
    upstream = torch.full_like(expected, 0.75)
    (dr,) = torch.autograd.grad(expected, ref, upstream)
    forward = torch.prod(ref.detach().double(), **kw).to(dtype)
    if dtype == torch.float16 and not zeros:
        accurate, override = prod_cpu_half_precision(
            SimpleNamespace(kwargs=kw), (ref,), upstream
        )
        forward, (dr,) = accurate, override
    (dx,) = torch.autograd.grad(actual, x, upstream.to(x.device))
    utils.gems_assert_close(actual, utils.to_reference(forward.to(x.device)), dtype)
    utils.gems_assert_close(
        dx, utils.to_reference(dr.to(x.device)), dtype, equal_nan=True
    )


