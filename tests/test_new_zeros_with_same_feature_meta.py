import pytest
import torch

import flag_gems

from . import accuracy_utils as utils


@pytest.mark.new_zeros_with_same_feature_meta
@pytest.mark.underscore_new_zeros_with_same_feature_meta
@pytest.mark.parametrize("dtype", utils.FLOAT_DTYPES)
@pytest.mark.parametrize("batch_dims", [0, 1, 2, 3])
@pytest.mark.parametrize("layout", ["contiguous", "transpose", "offset", "empty"])
def test_new_zeros_with_same_feature_meta(dtype, batch_dims, layout):
    inp = torch.empty((2, 3), device=flag_gems.device, dtype=dtype)
    other = torch.randn((5, 7), device=flag_gems.device, dtype=dtype)
    if layout == "transpose":
        other = other.t()
    elif layout == "offset":
        other = other[1:4, 1:6:2]
    elif layout == "empty":
        other = other[:0]
    # CPU reference checks values; the native device reference also checks
    # storage metadata, including gaps and offsets retained from other.
    ref_inp = utils.to_reference(inp)
    ref_other = utils.to_reference(other)
    ref = torch.ops.aten._new_zeros_with_same_feature_meta.default(
        ref_inp, ref_other, self_num_batch_dims=batch_dims
    )
    native = torch.ops.aten._new_zeros_with_same_feature_meta.default(
        inp, other, self_num_batch_dims=batch_dims
    )
    res = flag_gems._new_zeros_with_same_feature_meta(
        inp, other, self_num_batch_dims=batch_dims
    )
    utils.gems_assert_equal(res, ref)
    assert res.dtype == other.dtype
    assert res.device == other.device
    assert res.stride() == native.stride()
    assert res.storage_offset() == native.storage_offset()
    assert res.untyped_storage().nbytes() == native.untyped_storage().nbytes()
    if res.numel():
        assert res.data_ptr() != other.data_ptr()


