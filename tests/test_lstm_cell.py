    # reduction lengths the way the other GEMM-backed operators do.
    reduce_dim = input_size + hidden_size
    gems_assert_close(res_out[0], ref_out[0], dtype, reduce_dim=reduce_dim)
    gems_assert_close(res_out[1], ref_out[1], dtype, reduce_dim=reduce_dim)


