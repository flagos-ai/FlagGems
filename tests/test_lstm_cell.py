@pytest.mark.lstm_cell
def test_accuracy_lstm_cell_invalid_input():
    """Malformed calls raise rather than returning a meaningless result."""
    batch, input_size, hidden_size = 4, 8, 8
    input, hx, w_ih, w_hh, b_ih, b_hh = _inputs(
        batch, input_size, hidden_size, torch.float32
    )
    dev = flag_gems.device

    with pytest.raises(IndexError):
        flag_gems.lstm_cell(input[0], hx, w_ih, w_hh, b_ih, b_hh)

    with pytest.raises(RuntimeError, match="inconsistent input_size"):
        flag_gems.lstm_cell(
            torch.randn(batch, input_size + 1, device=dev), hx, w_ih, w_hh, b_ih, b_hh
        )

    with pytest.raises(RuntimeError, match="hidden0 batch size"):
        flag_gems.lstm_cell(
            input,
            [torch.randn(batch + 1, hidden_size, device=dev), hx[1]],
            w_ih,
            w_hh,
            b_ih,
            b_hh,
        )

    with pytest.raises(RuntimeError, match="inconsistent hidden_size"):
        flag_gems.lstm_cell(
            input,
            [torch.randn(batch, hidden_size + 1, device=dev), hx[1]],
            w_ih,
            w_hh,
            b_ih,
            b_hh,
        )

    with pytest.raises(RuntimeError, match="hidden1 batch size"):
        flag_gems.lstm_cell(input, [hx[0], hx[1][:1]], w_ih, w_hh, b_ih, b_hh)

    with pytest.raises(RuntimeError, match="two hidden states"):
        flag_gems.lstm_cell(input, [hx[0]], w_ih, w_hh, b_ih, b_hh)

    with pytest.raises(RuntimeError, match="two hidden states"):
        flag_gems.lstm_cell(input, [hx[0], hx[1], hx[0]], w_ih, w_hh, b_ih, b_hh)

    with pytest.raises(RuntimeError):
        flag_gems.lstm_cell(input, hx, w_ih[:-GATES], w_hh, b_ih, b_hh)

    with pytest.raises(RuntimeError, match="elements"):
        flag_gems.lstm_cell(input, hx, w_ih, w_hh, b_ih[:-1], b_hh)

    with pytest.raises(RuntimeError, match="same dtype"):
        flag_gems.lstm_cell(input.double(), hx, w_ih, w_hh, b_ih, b_hh)


