import pytest
import torch

import flag_gems

from .accuracy_utils import FLOAT_DTYPES, QUICK_MODE, gems_assert_close, to_reference
from .conftest import TO_CPU

GATES = 4

# (batch, input_size, hidden_size)
SHAPES = (
    [(4, 16, 16), (1, 1, 1)]
    if QUICK_MODE
    else [
        (1, 1, 1),
        (1, 8, 16),
        (2, 3, 5),
        (4, 16, 16),
        (5, 7, 11),
        (8, 32, 32),
        (16, 64, 64),
        (3, 129, 65),
        (32, 128, 128),
    ]
)


def _reference(input, hx, w_ih, w_hh, b_ih, b_hh):
    """Eager decomposition of the cell, evaluated at the reference precision."""
    gates = torch.nn.functional.linear(input, w_ih, b_ih) + torch.nn.functional.linear(
        hx[0], w_hh, b_hh
    )
    i, f, g, o = gates.chunk(GATES, dim=1)
    cy = torch.sigmoid(f) * hx[1] + torch.sigmoid(i) * torch.tanh(g)
    hy = torch.sigmoid(o) * torch.tanh(cy)
    return hy, cy


def _inputs(batch, input_size, hidden_size, dtype, bias=True, seed=0):
    torch.manual_seed(seed)
    gate_size = GATES * hidden_size
    dev = flag_gems.device
    input = torch.randn(batch, input_size, dtype=dtype, device=dev)
    hx = [
        torch.randn(batch, hidden_size, dtype=dtype, device=dev),
        torch.randn(batch, hidden_size, dtype=dtype, device=dev),
    ]
    # Scaled down so the gate pre-activations stay in the useful range of the
    # sigmoid / tanh rather than saturating for the wider hidden sizes.
    w_ih = torch.randn(gate_size, input_size, dtype=dtype, device=dev) * 0.1
    w_hh = torch.randn(gate_size, hidden_size, dtype=dtype, device=dev) * 0.1
    b_ih = torch.randn(gate_size, dtype=dtype, device=dev) if bias else None
    b_hh = torch.randn(gate_size, dtype=dtype, device=dev) if bias else None
    return input, hx, w_ih, w_hh, b_ih, b_hh


