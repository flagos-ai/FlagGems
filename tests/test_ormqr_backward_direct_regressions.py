import pytest
import torch

import flag_gems

from . import accuracy_utils as utils
from ._ormqr_backward_reference_fixes import ormqr_fp64_reference


@pytest.mark.ormqr_backward
@pytest.mark.parametrize("left", [False, True])
@pytest.mark.parametrize("transpose", [False, True])
@pytest.mark.parametrize("strided", [False, True])
def test_batched_ormqr_all_parameter_gradients(left, transpose, strided):
    torch.manual_seed(230)
    device = flag_gems.device
    packed, tau = torch.geqrf(torch.randn((2, 4, 3), device=device))
    other = torch.randn((2, 4, 2) if left else (2, 2, 4), device=device)
    args = []
    for value in (packed, tau, other):
        if strided:
            storage = torch.empty((*value.shape, 2), device=device)
            storage[..., 1] = value
            value = storage[..., 1]
        args.append(value.detach().requires_grad_())
    refs = tuple(utils.to_reference(value).detach().requires_grad_() for value in args)
    expected = ormqr_fp64_reference(*refs, left=left, transpose=transpose)
    actual = flag_gems.ormqr(*args, left=left, transpose=transpose)
    utils.gems_assert_close(actual, expected, torch.float32, reduce_dim=4)
    grad = torch.randn_like(actual)
    reference_grads = torch.autograd.grad(expected, refs, utils.to_reference(grad))
    actual_grads = torch.autograd.grad(actual, args, grad)
    for result, reference in zip(actual_grads, reference_grads):
        utils.gems_assert_close(result, reference, torch.float32, reduce_dim=4)


pytestmark = [pytest.mark.ormqr]
