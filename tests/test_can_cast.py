def test_can_cast_category_boundaries(from_, to):
    ref = torch.ops.aten.can_cast(from_, to)
    res = flag_gems.can_cast(from_, to)
    assert res == ref, f"can_cast({from_}, {to}): got {res}, expected {ref}"
    assert isinstance(res, bool)


@pytest.mark.can_cast
def test_can_cast_full_dtype_grid():
    """Every (from_, to) pair over the dtype grid must match native ATen."""
    mismatches = []
    for from_ in _DTYPES:
        for to in _DTYPES:
            ref = torch.ops.aten.can_cast(from_, to)
            res = flag_gems.can_cast(from_, to)
            if res != ref:
                mismatches.append((from_, to, res, ref))
    assert not mismatches, f"{len(mismatches)} pairs disagree with ATen: {mismatches}"


