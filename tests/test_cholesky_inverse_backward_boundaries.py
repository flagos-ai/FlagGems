import pytest
import torch

import flag_gems

pytestmark = [pytest.mark.cholesky_inverse, pytest.mark.cholesky_inverse_backward]


# Native cholesky_inverse supports float32/float64, not float16/bfloat16.
@pytest.mark.parametrize("dtype", [torch.float32, torch.float64])
# Cross the fused-kernel and existing matrix-composition boundaries.
@pytest.mark.parametrize("n", [33, 64, 65, 129])
@pytest.mark.parametrize("upper", [False, True])
def test_cholesky_inverse_backward_boundaries(dtype, n, upper):
    value = torch.randn((2, n, n), device=flag_gems.device, dtype=dtype) * 0.01
    value = value.triu() if upper else value.tril()
    value = value + torch.eye(n, device=value.device, dtype=dtype) * 2
    x = value.detach().requires_grad_()
    reference_x = value.detach().clone().requires_grad_()
    actual = flag_gems.cholesky_inverse(x, upper=upper)
    expected = torch.cholesky_inverse(reference_x, upper=upper)
    # Independently strided upstream gradients exercise the copy path too.
    grad = torch.randn((2, n, n, 2), device=x.device, dtype=dtype)[..., 1]
    actual_grad = torch.autograd.grad(actual, x, grad)[0]
    expected_grad = torch.autograd.grad(expected, reference_x, grad)[0]
    tolerance = 1e-5 if dtype == torch.float32 else 1e-10
    torch.testing.assert_close(actual, expected, rtol=tolerance, atol=tolerance)
    torch.testing.assert_close(
        actual_grad, expected_grad, rtol=tolerance, atol=tolerance
    )
