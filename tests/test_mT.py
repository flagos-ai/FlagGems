@pytest.mark.mT
@pytest.mark.parametrize("shape", [(5, 6), (2, 3, 4, 5)])
def test_mT_shares_storage(shape):
    # The result is a view: same storage pointer, writes propagate both ways,
    # and the operand's own layout metadata is untouched.
    inp = torch.randn(shape, device=flag_gems.device, dtype=torch.float32)
    inp_shape, inp_stride, inp_offset = (
        inp.shape,
        inp.stride(),
        inp.storage_offset(),
    )

    with flag_gems.use_gems():
        res_out = flag_gems.mT(inp)

    assert res_out is not inp
    assert res_out.untyped_storage().data_ptr() == inp.untyped_storage().data_ptr()

    snapshot = inp.clone()
    res_out.fill_(1.0)
    ref = torch.ops.aten.mT(snapshot)
    assert torch.equal(inp, torch.ops.aten.mT(ref).fill_(1.0))
    assert inp.shape == inp_shape
    assert inp.stride() == inp_stride
    assert inp.storage_offset() == inp_offset


@pytest.mark.mT
def test_mT_autograd():
    # The view participates in autograd and routes the gradient transposed.
    inp = torch.randn(
        4, 6, device=flag_gems.device, dtype=torch.float32, requires_grad=True
    )
    ref_inp = utils.to_reference(inp).detach().requires_grad_(True)

    with flag_gems.use_gems():
        res_out = flag_gems.mT(inp)
    grad = torch.randn(res_out.shape, device=flag_gems.device, dtype=torch.float32)
    res_out.backward(grad)

    ref_out = torch.ops.aten.mT(ref_inp)
    ref_out.backward(utils.to_reference(grad))
    utils.gems_assert_close(inp.grad, ref_inp.grad, torch.float32)


@pytest.mark.mT
def test_mT_rank1_raises():
    # rank < 2 has no last two dimensions to swap: rank 1 must raise, while
    # rank 0 follows the deprecated ATen identity path (the same object).
    inp = torch.randn(8, device=flag_gems.device, dtype=torch.float32)
    with pytest.raises(RuntimeError):
        with flag_gems.use_gems():
            flag_gems.mT(inp)

    scalar = torch.tensor(3.14, device=flag_gems.device, dtype=torch.float32)
    with flag_gems.use_gems():
        res_out = flag_gems.mT(scalar)
    assert res_out is scalar
