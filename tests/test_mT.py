"""Accuracy tests for ``aten::mT(Tensor(a) self) -> Tensor(a)``.

``mT`` is a zero-copy view operator: it swaps the last two dimensions of a
rank >= 2 tensor and returns a view aliasing the operand's storage.  The tests
verify the view contract (shape/stride/storage sharing, laziness of the conj
bit, autograd through the view) and the error paths for rank < 2, mirroring
the ``Tensor.mT`` attribute semantics.  Because a view never touches element
data, one float dtype sweep is enough; the layout checks are dtype-agnostic.
"""

import pytest
import torch

import flag_gems

from . import accuracy_utils as utils

# 2D / 3D / 4D shapes: the last two dims get swapped, earlier dims stay put.
MT_SHAPES = [(16, 32), (7, 8, 9), (2, 3, 4, 5)]


def _check_view_metadata(res, ref):
    # The view must match the reference layout exactly and alias the operand.
    assert res.shape == ref.shape
    assert res.stride() == ref.stride()
    assert res.storage_offset() == ref.storage_offset()
    assert res.is_conj() == ref.is_conj()


@pytest.mark.mT
@pytest.mark.parametrize("shape", MT_SHAPES)
@pytest.mark.parametrize("dtype", utils.FLOAT_DTYPES)
def test_mT(shape, dtype):
    inp = torch.randn(shape, dtype=dtype, device=flag_gems.device)
    ref_inp = utils.to_reference(inp)

    with flag_gems.use_gems():
        res_out = flag_gems.mT(inp)

    ref_out = torch.ops.aten.mT(ref_inp)
    _check_view_metadata(res_out, ref_out)
    utils.gems_assert_close(res_out, ref_out, dtype)


