def test_celu_backward__leaf_error_preserves_input():
    x = torch.rand(17, device=flag_gems.device, requires_grad=True)
    before = x.detach().clone()
    with pytest.raises(RuntimeError, match="leaf"):
        flag_gems.celu_(x)
    torch.testing.assert_close(x.detach(), before, atol=0, rtol=0)


@pytest.mark.parametrize("dtype", utils.FLOAT_DTYPES)
@pytest.mark.parametrize("alpha", [0.125, 1.0, 2.0])
def test_celu__backward_saturation(dtype, alpha):
    x = torch.tensor(
        [-20.0, -8.0, -3.0, -0.01, 0.0, 0.1, 4.0], device=flag_gems.device, dtype=dtype
    ).requires_grad_()
    ref = x.detach().clone().requires_grad_()
    output = flag_gems.celu_(x.clone(), alpha)
    expected = torch.nn.functional.celu(ref.clone(), alpha, inplace=True)
    compare_gradients(output, expected, (x,), (ref,), dtype)
