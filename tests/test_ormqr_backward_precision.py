import pytest
import torch

import flag_gems

from . import accuracy_utils as utils
from ._ormqr_backward_reference_fixes import ormqr_fp64_reference

pytestmark = [pytest.mark.ormqr_backward, pytest.mark.ormqr]


# Native ORMQR supports float32/float64; Half/BFloat16 are unsupported.
@pytest.mark.parametrize("dtype", [torch.float32, torch.float64])
@pytest.mark.parametrize("left", [False, True])
@pytest.mark.parametrize("transpose", [False, True])
@pytest.mark.parametrize("tf32", [False, True])
def test_householder_vjp_is_independent_of_tf32(
    dtype, left, transpose, tf32, monkeypatch
):
    monkeypatch.setattr(torch.backends.cuda.matmul, "allow_tf32", tf32)
    torch.manual_seed(41)
    a, tau = torch.geqrf(torch.randn((4, 3), device=flag_gems.device, dtype=dtype))
    other = torch.randn((4, 2) if left else (2, 4), device=a.device, dtype=dtype)
    args = tuple(x.detach().requires_grad_() for x in (a, tau, other))
    refs = tuple(utils.to_reference(x).detach().requires_grad_() for x in args)
    expected = ormqr_fp64_reference(*refs, left=left, transpose=transpose)
    actual = flag_gems.ormqr(*args, left=left, transpose=transpose)
    utils.gems_assert_close(actual, expected, dtype)
    grad = torch.randn_like(actual)
    target = torch.autograd.grad(expected, refs, utils.to_reference(grad))
    computed = torch.autograd.grad(actual, args, grad)
    for a_grad, reference in zip(computed, target):
        utils.gems_assert_close(a_grad, reference, dtype)
