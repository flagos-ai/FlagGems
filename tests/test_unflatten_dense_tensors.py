def test_unflatten_dense_tensors_metadata(flat_numel, shapes, dtype):
    # Regression: outputs must be *views* of flat preserving its alias,
    # stride and storage offset; zero-numel outputs must be fresh empty
    # tensors (no base, zero-size storage), matching the native op.
    inp = torch.randn(flat_numel, dtype=dtype, device=flag_gems.device)
    templates = _make_templates(shapes, dtype, flag_gems.device)

    ref_out = torch_unflatten_dense_tensors(inp, templates)
    res_out = flag_gems.unflatten_dense_tensors(inp, templates)

    assert len(res_out) == len(ref_out)
    for res, ref, shape in zip(res_out, ref_out, shapes):
        assert tuple(res.shape) == tuple(ref.shape)
        assert res.stride() == ref.stride()
        assert res.storage_offset() == ref.storage_offset()
        assert res.untyped_storage().size() == ref.untyped_storage().size()
        numel = 1
        for s in shape:
            numel *= s
        if numel == 0:
            # zero-numel outputs are fresh empty tensors, not views of flat
            assert res._base is None
        else:
            assert res._base is inp, "non-view output does not alias flat"
    # writing through a view must be visible in flat (alias semantics)
    non_empty = [i for i, s in enumerate(shapes) if all(d > 0 for d in s)]
    if non_empty:
        i = non_empty[0]
        res_out[i].fill_(1.0)
        assert torch.all(inp.view(-1)[: res_out[i].numel()] == 1)


