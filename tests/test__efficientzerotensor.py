@pytest.mark.efficientzerotensor
def test_accuracy_efficientzerotensor_zero_buffer_allocated_once(monkeypatch):
    # The O(1) claim rests on the per-(device, dtype) buffer being reused: the
    # Triton store must run on the FIRST use only. A cache keyed on an
    # un-indexed device ("cuda") can never hit the entry stored under the
    # indexed one ("cuda:0"), which silently turns every call into a kernel
    # launch -- correct values, no speedup. Count the launches to pin it.
    op_module = sys.modules[flag_gems._efficientzerotensor.__module__]
    launches = []

    class _CountingKernel:
        def __getitem__(self, grid):
            def launch(*args, **kwargs):
                launches.append(grid)
                return op_module.__dict__["_real_zero_fill_kernel"][grid](
                    *args, **kwargs
                )

            return launch

    dtype = torch.float32
    # Call with the UN-INDEXED device name, exactly as the benchmark and the
    # public API do; the cache entry lands under the indexed form.
    device = torch.device(flag_gems.device)
    if device.index is None:
        device = torch.device(device.type, torch.cuda.current_device())

    monkeypatch.setitem(
        op_module.__dict__, "_real_zero_fill_kernel", op_module._zero_fill_kernel
    )
    monkeypatch.setattr(op_module, "_zero_fill_kernel", _CountingKernel())
    monkeypatch.delitem(op_module._ZERO_BASES, (device, dtype), raising=False)

    pointers = set()
    for _ in range(4):
        t = flag_gems._efficientzerotensor([64], dtype=dtype, device=flag_gems.device)
        assert bool((t == 0).all())
        pointers.add(t.data_ptr())

    assert (
        len(launches) == 1
    ), f"zero buffer refilled per call: {len(launches)} launches"
    assert len(pointers) == 1, "every result must view the same one-element buffer"


