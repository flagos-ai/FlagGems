@pytest.mark.make_dual
def test_accuracy__make_dual_inference_mode(caplog):
    # Under ``torch.inference_mode()`` inference tensors carry neither the
    # Autograd nor the ADInplaceOrView key, so dispatch reaches the registered
    # FlagGems CUDA override. Its depth-1 entry delegates to
    # ``torch._make_dual``, which re-enters the override from below the
    # autograd keys (depth 2). Both entries log ``GEMS _MAKE_DUAL``, so exactly
    # two records prove the depth-2 branch ran and neither calls recursed.
    with torch.inference_mode(), dual_level():
        primal = _gen((3, 4), torch.float32, flag_gems.device)
        tangent = _gen((3, 4), torch.float32, flag_gems.device)
        assert primal.is_inference()
        ref_primal = utils.to_reference(primal)
        ref_tangent = utils.to_reference(tangent)

        # Native reference first, before FlagGems is enabled.
        ref_out = _ref_make_dual(ref_primal, ref_tangent, 0)

        _enable_gems_dispatch()
        caplog.clear()
        with caplog.at_level(logging.DEBUG, logger="flag_gems.ops._make_dual"):
            res_out = torch._make_dual(primal, tangent, 0)

        gems_logs = [
            record
            for record in caplog.records
            if record.name == "flag_gems.ops._make_dual"
            and "GEMS _MAKE_DUAL" in record.getMessage()
        ]
        assert len(gems_logs) == 2, (
            "expected one log from the depth-1 entry and one from the depth-2 "
            f"re-entry, got {len(gems_logs)}"
        )

        utils.gems_assert_equal(res_out, ref_out)
        assert res_out.data_ptr() == primal.data_ptr()
        assert res_out.is_inference() == ref_out.is_inference()
        ref_primal_out, ref_tangent_out = unpack_dual(ref_out)
        res_primal_out, res_tangent_out = unpack_dual(res_out)
        utils.gems_assert_equal(res_primal_out, ref_primal_out)
        assert res_tangent_out is None
        assert (res_tangent_out is None) == (ref_tangent_out is None)


