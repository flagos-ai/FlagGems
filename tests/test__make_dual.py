def _gen(shape, dtype, device):
    if dtype.is_floating_point:
        return torch.randn(shape, dtype=dtype, device=device)
    if dtype == torch.bool:
        return torch.randint(0, 2, size=shape, dtype=dtype, device=device)
    lo, hi = torch.iinfo(dtype).min, torch.iinfo(dtype).max
    return torch.randint(lo, hi, shape, dtype=dtype, device=device)


