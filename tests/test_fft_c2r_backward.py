@pytest.mark.fft_c2r_backward
@pytest.mark.parametrize("norm", [0, 1, 2])
def test_fft_c2r_backward_matches_irfft_autograd(norm):
    """End-to-end check against the torch.fft.irfft autograd chain.

    Measured irfft forward-output scales (relative to the unscaled c2r):
    backward 1/N, forward 1, ortho 1/sqrt(N); the autograd gradient carries
    the same factor applied to this operator's unscaled (code 0) result,
    which the ortho case matches exactly with the ortho-scaled rfft (code 1).
    """
    torch.manual_seed(1)
    N = 16
    grad = torch.randn(4, N, dtype=torch.float32, device=DEVICE)
    n_onesided = N // 2 + 1
    x = torch.randn(
        4, n_onesided, dtype=torch.complex64, device=DEVICE, requires_grad=True
    )
    y = torch.fft.irfft(x, n=N, dim=-1, norm=NORM_STR[norm])
    loss = (y * grad).sum()
    gx = torch.autograd.grad(loss, x)[0]
    unscaled = _reference(grad, -1, 0)
    expected = {0: unscaled / N, 1: unscaled, 2: _reference(grad, -1, 1)}[norm]
    expected = expected.to(gx.device)
    torch.testing.assert_close(gx, expected, rtol=1e-4, atol=1e-4)


