"""Accuracy tests for ``fft_c2r_backward``.

``aten::_fft_c2r`` has no registered ``aten::_fft_c2r_backward`` schema; the
backward is a manual autograd function in ``FunctionsManual.cpp``:
``gI = _fft_r2c(grad, dim, normalization, onesided=True)`` with bins
``1 .. 1 + (N - K)`` doubled along the transformed axis. Tests compare the
FlagGems operator against that exact formula (computed with ATen) and against
the end-to-end ``torch.fft.irfft`` autograd chain. The tests call the
``flag_gems.fft_c2r_backward`` entry point directly rather than through
``use_gems()`` because the CI rule forbids explicit ``use_gems()`` calls in
test files.
"""

