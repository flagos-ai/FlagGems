def _reference(grad, dim, norm):
    """ATen manual autograd formula for fft_c2r_backward."""
    grad = utils.to_reference(grad)
    d = int(dim) % grad.ndim
    gI = torch.ops.aten._fft_r2c(grad, [d], norm, True)
    double_length = grad.size(d) - gI.size(d)
    if double_length > 0:
        ref = gI.clone()
        ref.narrow(d, 1, double_length).mul_(2)
        return ref
    return gI


@pytest.mark.fft_c2r_backward
@pytest.mark.parametrize("case", CASES)
def test_fft_c2r_backward(case):
    shape, dim, norm, dtype = case
    if dtype == torch.float64 and not utils.fp64_is_supported:
        pytest.skip("float64 is not supported by this device")
    torch.manual_seed(0)
    grad = torch.randn(shape, dtype=dtype, device=DEVICE)
    ref_grad = utils.to_reference(grad)
    ref = _reference(ref_grad, dim, norm)
