import pytest
import torch
from torch.utils._python_dispatch import TorchDispatchMode

import flag_gems

from . import accuracy_utils as utils
from ._sort_backward_cases import INDEX_OPS, forward, make_case, make_tensor
from ._sort_backward_pointwise import TOL


def gems_forward(inputs, p):
    x = inputs[0]
    _ = p["op"]
    return flag_gems.sort_stable(
        x, stable=True, dim=p["dim"], descending=p["descending"]
    )[0]


class NoNativeCompute(TorchDispatchMode):

    def __torch_dispatch__(self, func, types, args=(), kwargs=None):
        blocked = {
            "mul",
            "add",
            "sub",
            "div",
            "cos",
            "cosh",
            "sin",
            "sinh",
            "sigmoid",
            "silu_backward",
            "softplus_backward",
            "softshrink_backward",
            "gather",
            "scatter",
            "scatter_add",
            "scatter_reduce",
            "index",
            "index_put",
            "clone",
            "copy_",
            "_to_copy",
        }
        if func._schema.name.split("::")[-1] in blocked:
            raise AssertionError("native computation in backward: " + str(func))
        return func(*args, **kwargs or {})


@pytest.mark.sort_backward
@pytest.mark.parametrize(
    "op",
    [
        pytest.param("sort", marks=getattr(pytest.mark, "sort_backward"))
        for op in INDEX_OPS
    ],
)
@pytest.mark.parametrize("dtype", utils.FLOAT_DTYPES)
@pytest.mark.parametrize("strided", [False, True])
def test_index_autograd(op, dtype, strided):
    torch.manual_seed(20261123)
    inputs, p = make_case("sort", dtype, 0, strided)
    inputs = [x.detach().requires_grad_() for x in inputs]
    refs = [x.detach().requires_grad_() for x in inputs]
    y = gems_forward(inputs, p)
    expected = forward(refs, p)
    torch.testing.assert_close(y, expected, rtol=TOL[dtype][0], atol=TOL[dtype][1])
    g = make_tensor(y.shape, dtype, flag_gems.device, strided)
    want = torch.autograd.grad(expected, refs, g)
    with NoNativeCompute():
        got = torch.autograd.grad(y, inputs, g)
    for a, b in zip(got, want):
        torch.testing.assert_close(a, b, rtol=TOL[dtype][0], atol=TOL[dtype][1])


