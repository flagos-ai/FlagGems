import pytest
import torch

import flag_gems

from . import accuracy_utils as utils
from . import conftest as cfg

if cfg.QUICK_MODE:
    # Single tiny shape keeps the quick smoke run fast.
    KL_DIV_SHAPES = [(2, 3)]
else:
    # Tiny broadcastable shape plus larger 2D shapes so the reduction paths
    # (none/mean/sum) are exercised across multiple block counts.
    KL_DIV_SHAPES = [(2, 3), (128, 256), (512, 512)]


def _make_input(shape, dtype, device):
    # input is interpreted as log-probabilities
    inp = torch.randn(shape, dtype=dtype, device=device)
    # target is interpreted as probabilities in [0, 1]
    target = torch.rand(shape, dtype=dtype, device=device)
    return inp, target


@pytest.mark.kl_div
@pytest.mark.parametrize("shape", KL_DIV_SHAPES)
@pytest.mark.parametrize("dtype", utils.FLOAT_DTYPES)
@pytest.mark.parametrize("reduction", [0, 1, 2])
@pytest.mark.parametrize("log_target", [False, True])
def test_kl_div(shape, dtype, reduction, log_target):
    inp, target = _make_input(shape, dtype, flag_gems.device)

    # Upcast the reference so that it is computed in higher precision than the
    # Triton kernel, which accumulates in float32.
    ref_inp = utils.to_reference(inp, True)
    ref_target = utils.to_reference(target, True)

    ref_out = torch.ops.aten.kl_div(
        ref_inp, ref_target, reduction, log_target=log_target
    )
    res_out = flag_gems.kl_div(inp, target, reduction, log_target=log_target)

    utils.gems_assert_close(res_out, ref_out, dtype, equal_nan=True)


