def test_broadcast_integer_indices(dtype):
    x = torch.randn(3, 4, device=flag_gems.device, dtype=dtype, requires_grad=True)
    idx = [
        torch.tensor([[0], [2]], device=x.device, dtype=torch.int32),
        torch.tensor([[0, 1, 2]], device=x.device, dtype=torch.int32),
    ]
    y = torch.ops.aten._unsafe_index.Tensor(x, idx)
    g = torch.randn_like(y)
    expected = torch.autograd.grad(y, x, g)[0]
    actual = flag_gems.unsafe_index_backward(g, x, idx)
    close(actual, expected, dtype)


