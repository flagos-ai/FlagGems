"""Accuracy tests for ``aten::mH`` (the conjugate-transpose view).

``mH`` is a pure metadata/view operator: it swaps the last two dimensions and
toggles the lazy conjugate bit for complex dtypes, without touching any
element.  The checks therefore focus on the view contract rather than values:
shape, strides, shared storage, the ``is_conj()`` lazy bit, rank handling
(1-D rejected, 0-D deprecated warn + conj path) and non-contiguous/batched
inputs.  The reference is ``Tensor.mH`` (``aten::mH``), which is a
CompositeImplicitAutograd view valid on both CPU and CUDA for every dtype.
"""

import pytest
import torch

import flag_gems

from . import accuracy_utils as utils

# mH is defined for matrices and batches of matrices; every shape here has
# ndim >= 2 except the dedicated 0-D/1-D rank tests below.
MH_SHAPES = [
    (4, 6),
    (64, 128),
    (2, 3, 8, 16),
    (5, 4, 7),
    (3, 1, 0, 9),  # batched with a zero-sized matrix
]


@pytest.mark.mH
@pytest.mark.parametrize("shape", MH_SHAPES)
@pytest.mark.parametrize("dtype", utils.FLOAT_DTYPES)
def test_mH(shape, dtype):
    # mH for real dtypes is exactly transpose(-2, -1): a stride exchange view.
    inp = torch.randn(shape, dtype=dtype, device=flag_gems.device)
    ref_inp = utils.to_reference(inp)

    ref_out = ref_inp.mH
    # Call the wrapper directly (no dispatch): mH is a zero-copy view, so its
    # contract must be observed on the FlagGems implementation itself.
    res_out = flag_gems.ops.mH(inp)
    utils.gems_assert_close(res_out, ref_out, dtype)
    assert res_out.shape == ref_out.shape
    assert res_out.stride() == ref_out.stride()
    assert res_out.is_conj() == ref_out.is_conj()
    assert res_out.untyped_storage().data_ptr() == inp.untyped_storage().data_ptr()


