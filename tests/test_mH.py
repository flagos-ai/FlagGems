@pytest.mark.mH
@pytest.mark.parametrize("shape", [(4, 6), (2, 3, 8, 16)])
def test_mH_complex(shape):
    # mH conjugates the last two dimensions as well as transposing them; the
    # lazy conjugate bit (not a materialized conjugate) must be set and the
    # result must still alias the input storage.
    # mH's conjugation semantics only exist for complex dtypes, so this test
    # covers torch.complex64 (the dtype used by aten's lazy-conj machinery).
    dtype = torch.complex64
    inp = torch.randn(shape, dtype=dtype, device=flag_gems.device)
    ref_inp = utils.to_reference(inp)

    ref_out = ref_inp.mH
    # Call the wrapper directly (no dispatch): mH is a zero-copy view, so its
    # contract must be observed on the FlagGems implementation itself.
