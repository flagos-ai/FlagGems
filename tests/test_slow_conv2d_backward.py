"""Accuracy tests for ``aten::_slow_conv2d_backward``.

The operator returns the (grad_input, grad_weight, grad_bias) gradients of the
slow reference conv2d. Tests always pass ``output_mask=[True, True, True]`` so
all three gradients are computed, and compare against
``torch.ops.aten._slow_conv2d_backward.output_mask``. Small feature maps keep
the slow (non-cuDNN) reference path fast; the stride/padding combos cover both
tap misalignment and zero-padding edges of the backward. The reference runs on
upcast inputs (``to_reference(inp, True)``); low-precision gradients therefore
need a relaxed atol since the kernels accumulate in fp32.
"""

import pytest
import torch

import flag_gems

from . import accuracy_utils as utils

# (input_shape, weight_shape, kernel_size, stride, padding). Inputs are small
# because the slow conv2d backward is a plain reference implementation and the
# ATen slow path itself is slow on large inputs.
SHAPES = [
    # 1x1 kernel, square input
    ((2, 3, 8, 8), (5, 3, 1, 1), [1, 1], [1, 1], [0, 0]),
    # 3x3 kernel, unit stride, no padding
    ((2, 4, 10, 10), (6, 4, 3, 3), [3, 3], [1, 1], [0, 0]),
    # 3x3 kernel with same-padding
    ((3, 3, 9, 9), (4, 3, 3, 3), [3, 3], [1, 1], [1, 1]),
    # 3x3 kernel, stride 2
    ((2, 3, 5, 5), (4, 3, 3, 3), [3, 3], [2, 2], [1, 1]),
    # asymmetric kernel/stride/padding
    ((1, 2, 7, 11), (3, 2, 2, 3), [2, 3], [2, 1], [1, 2]),
]


@pytest.mark.slow_conv2d_backward
@pytest.mark.parametrize("shape,weight_shape,kernel_size,stride,padding", SHAPES)
@pytest.mark.parametrize("dtype", utils.FLOAT_DTYPES)
def test_slow_conv2d_backward(shape, weight_shape, kernel_size, stride, padding, dtype):
    inp = torch.randn(shape, dtype=dtype, device=flag_gems.device)
    weight = torch.randn(weight_shape, dtype=dtype, device=flag_gems.device)
    ho = (shape[2] + 2 * padding[0] - kernel_size[0]) // stride[0] + 1
    wo = (shape[3] + 2 * padding[1] - kernel_size[1]) // stride[1] + 1
    grad_output = torch.randn(
        (shape[0], weight_shape[0], ho, wo), dtype=dtype, device=flag_gems.device
    )

    ref_inp = utils.to_reference(inp, True)
    ref_weight = utils.to_reference(weight, True)
    ref_grad_output = utils.to_reference(grad_output, True)

    with flag_gems.use_gems():
        gi, gw, gb = flag_gems.ops._slow_conv2d_backward(
            grad_output,
            inp,
            weight,
            kernel_size,
            stride,
            padding,
            [True, True, True],
        )

    ref_gi, ref_gw, ref_gb = torch.ops.aten._slow_conv2d_backward.output_mask(
        ref_grad_output,
        ref_inp,
        ref_weight,
        kernel_size,
        stride,
        padding,
        [True, True, True],
    )

    if dtype in (torch.float16, torch.bfloat16):
        # The reference runs on upcast inputs while the kernels accumulate in
        # fp32 for low-precision inputs, so the gradients need a relaxed atol.
        atol = 5e-2
    else:
        atol = 1e-3
    utils.gems_assert_close(gi, ref_gi, dtype, atol=atol)
    utils.gems_assert_close(gw, ref_gw, dtype, atol=atol)
    utils.gems_assert_close(gb, ref_gb, dtype, atol=atol)
