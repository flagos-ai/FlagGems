import pytest
import torch

import flag_gems

from . import accuracy_utils as utils


@pytest.mark.neg_backward
@pytest.mark.parametrize("dtype", utils.FLOAT_DTYPES)
@pytest.mark.parametrize("offset", [0, 1, 7])
def test_negative_contiguous_gradients_with_storage_offsets(dtype, offset):
    x = torch.randn(257, dtype=dtype, device=flag_gems.device, requires_grad=True)
    y = flag_gems.neg(x)
    storage = torch.randn(257 + offset, dtype=dtype, device=x.device)
    grad = storage[offset:]
    assert grad.is_contiguous()
    (actual,) = torch.autograd.grad(y, x, grad)
    torch.testing.assert_close(actual, -grad)


pytestmark = [pytest.mark.neg]
