import pytest
import torch

import flag_gems

from . import accuracy_utils as utils

pytestmark = [pytest.mark.baddbmm, pytest.mark.baddbmm_backward]


@pytest.mark.parametrize("dtype", utils.FLOAT_DTYPES)
@pytest.mark.parametrize("shape", [(2, 3, 5, 7), (2, 17, 31, 23)])
@pytest.mark.parametrize("strided", [False, True])
@pytest.mark.parametrize("tf32", [False, True])
@pytest.mark.parametrize("scalars", [(1.0, 1.0), (0.25, 0.5), (1.0, 0.0)])
def test_backward_matches_cpu_fp64_with_tf32(
    dtype, shape, strided, tf32, monkeypatch, scalars
):
    # This module deliberately has no IEEE fixture: exercise the candidate
    # under both runner settings, using an independent CPU FP64 reference.
    monkeypatch.setattr(torch.backends.cuda.matmul, "allow_tf32", tf32)
    generator = torch.Generator().manual_seed(2)
    batch, m, k, n = shape

    def tensor(size):
        data = torch.randn(size, generator=generator).to(dtype)
        if strided:
            storage = torch.empty((*size, 2), device=flag_gems.device, dtype=dtype)
            storage[..., 1] = data.to(flag_gems.device)
            return storage[..., 1].detach().requires_grad_()
        return data.to(flag_gems.device).requires_grad_()

    inputs = [tensor((batch, m, k)), tensor((batch, k, n))]
    inputs.insert(0, tensor((n,)))
    refs = [x.detach().cpu().double().requires_grad_() for x in inputs]
    kwargs = {"alpha": scalars[0], "beta": scalars[1]}
    output = flag_gems.baddbmm(*inputs, **kwargs)
    reference = torch.baddbmm(*refs, **kwargs)
    reduction = max(1, batch * m, m, n, k)
    utils.gems_assert_close(
        output,
        utils.to_reference(reference.to(device=output.device, dtype=dtype)),
        dtype,
        reduce_dim=reduction,
    )
    grad_cpu = torch.randn((*output.shape, 2), generator=generator).to(dtype)[..., 1]
    grad_storage = torch.empty((*output.shape, 2), device=output.device, dtype=dtype)
    grad_storage[..., 1] = grad_cpu.to(output.device)
    actual = torch.autograd.grad(output, inputs, grad_storage[..., 1])
    expected = torch.autograd.grad(reference, refs, grad_cpu.double())
    for got, want, source in zip(actual, expected, inputs):
        assert got.shape == source.shape and got.dtype == source.dtype
        utils.gems_assert_close(
            got,
            utils.to_reference(want.to(device=got.device, dtype=dtype)),
            dtype,
            reduce_dim=reduction,
        )


@pytest.mark.parametrize("dtype", utils.FLOAT_DTYPES)
@pytest.mark.parametrize("shape", [(), (1,), (1, 1, 1)])
@pytest.mark.parametrize("beta", [0.7, 1.0])
@pytest.mark.parametrize("strided", [False, True])
def test_scalar_bias_reduction_keeps_opmath_partials(dtype, shape, beta, strided):
    # Each 32-element partial overflows Half in the former generic reduction,
    # while the materialized scaled gradient has an exact total of zero.
    bias = torch.ones(shape, dtype=dtype, device=flag_gems.device, requires_grad=True)
    a = torch.zeros((2, 17, 31), dtype=dtype, device=flag_gems.device)
    b = torch.zeros((2, 31, 23), dtype=dtype, device=flag_gems.device)
    reference_bias = bias.detach().clone().requires_grad_()
    output = flag_gems.baddbmm(bias, a, b, beta=beta)
    reference = torch.baddbmm(reference_bias, a, b, beta=beta)
    data = torch.zeros((2, 17, 23), dtype=dtype)
    data.view(-1)[:2] = 65504
    data.view(-1)[32:34] = -65504
    storage = torch.empty((*data.shape, 2), dtype=dtype, device=flag_gems.device)
    storage[..., 1] = data.to(flag_gems.device)
    incoming = storage[..., 1] if strided else data.to(flag_gems.device)
    actual = torch.autograd.grad(output, bias, incoming)[0]
    native = torch.autograd.grad(reference, reference_bias, incoming)[0]
    cpu_reference = (
        (data.float() * beta).to(dtype).double().sum().to(dtype).reshape(shape)
    )
    assert torch.isfinite(actual).all()
    utils.gems_assert_close(actual, utils.to_reference(native), dtype, reduce_dim=34)
    utils.gems_assert_close(
        actual,
        utils.to_reference(cpu_reference.to(actual.device)),
        dtype,
        reduce_dim=34,
    )


@pytest.mark.parametrize("dtype", utils.FLOAT_DTYPES)
@pytest.mark.parametrize("beta", [float("inf"), float("nan")])
def test_scalar_bias_nonfinite_scale_masks_padding(dtype, beta):
    bias = torch.ones((), dtype=dtype, device=flag_gems.device, requires_grad=True)
    a = torch.zeros((2, 3, 5), dtype=dtype, device=flag_gems.device)
    b = torch.zeros((2, 5, 7), dtype=dtype, device=flag_gems.device)
    native_bias = bias.detach().clone().requires_grad_()
    output = flag_gems.baddbmm(bias, a, b, beta=beta)
    reference = torch.baddbmm(native_bias, a, b, beta=beta)
    incoming = torch.ones_like(output)
    actual = torch.autograd.grad(output, bias, incoming)[0]
    expected = torch.autograd.grad(reference, native_bias, incoming)[0]
    utils.gems_assert_close(actual, utils.to_reference(expected), dtype, equal_nan=True)
