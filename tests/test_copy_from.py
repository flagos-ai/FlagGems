# Keep both the registry-id marker and the CI-derived aten-name marker.
@pytest.mark.copy_from
@pytest.mark.underscore_copy_from
@pytest.mark.parametrize("shape", utils.POINTWISE_SHAPES)
@pytest.mark.parametrize("dtype", utils.FLOAT_DTYPES)
def test_copy_from(shape, dtype):
    src = torch.randn(shape, dtype=dtype, device=flag_gems.device)
    ref_src = utils.to_reference(src)
    ref_dst = utils.to_reference(
        torch.zeros(shape, dtype=dtype, device=flag_gems.device)
    )
    res_dst = torch.zeros(shape, dtype=dtype, device=flag_gems.device)

    # aten::_copy_from has no native CUDA implementation, so build the reference
    # from the native copy_ (whose semantics _copy_from shares).
    ref_out = ref_dst.copy_(ref_src)
    res_out = flag_gems._copy_from(src, res_dst)

    # The result aliases and mutates the destination tensor.
    assert res_out.data_ptr() == res_dst.data_ptr()
    utils.gems_assert_equal(res_out, ref_out)
    utils.gems_assert_equal(res_dst, ref_src)


