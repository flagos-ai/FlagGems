# torch's native CUDA implementation of _rowwise_prune segfaults, so the
# reference is always computed on CPU regardless of the ``--ref`` option.
SHAPES = [(2, 32)] if cfg.QUICK_MODE else [(4, 6), (64, 128), (1025, 17)]
IDX_DTYPES = [torch.int32, torch.int64]


def _reference_rowwise_prune(weight, mask, compressed_indices_dtype):
    # Equivalent to aten's CPU implementation: kept rows are stacked in their
    # original order, and each kept row maps to the number of kept rows before
    # it (a running count), while pruned rows map to -1.
    counts = torch.cumsum(mask.to(torch.int64), dim=0) - 1
    row_indices = torch.where(mask, counts, torch.tensor(-1, dtype=torch.int64))
    row_indices = row_indices.to(compressed_indices_dtype)
    kept = torch.nonzero(mask).flatten()
    return weight.index_select(0, kept), row_indices


