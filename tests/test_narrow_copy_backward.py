def clone_inputs(case, needs_grad, reference=False):
    result = []
    for i, x in enumerate(case.args):
        if isinstance(x, torch.Tensor):
            if reference:
                x = utils.to_reference(x)
            size = (
                1
                + x.storage_offset()
                + sum((max(n - 1, 0) * s for (n, s) in zip(x.shape, x.stride())))
            )
            storage = torch.empty(size, dtype=x.dtype, device=x.device)
            y = storage.as_strided(x.shape, x.stride(), x.storage_offset())
            y.copy_(x)
            x = y.detach().requires_grad_(needs_grad and i in case.grad_inputs)
        result.append(x)
    return tuple(result)


