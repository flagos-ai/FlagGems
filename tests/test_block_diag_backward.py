import pytest
import torch

import flag_gems

from . import accuracy_utils as utils
from ._block_diag_autograd import compare_gradients

pytestmark = [pytest.mark.block_diag, pytest.mark.block_diag_backward]


@pytest.mark.parametrize("dtype", utils.FLOAT_DTYPES)
@pytest.mark.parametrize(
    "shapes",
    [((3, 4), (5, 4)), ((), (5,)), ((0,), (3, 4)), ((0, 4), (0, 4)), ((3, 4), (3, 4))],
)
@pytest.mark.parametrize("strided", [False, True])
def test_block_diag_backward(dtype, shapes, strided):
    inputs = []
    for shape in shapes:
        x = (
            torch.randn((*shape, 2), device=flag_gems.device, dtype=dtype)[..., 1]
            if strided
            else torch.randn(shape, device=flag_gems.device, dtype=dtype)
        )
        inputs.append(x.detach().requires_grad_())
    refs = [x.detach().clone().requires_grad_() for x in inputs]
    compare_gradients(
        flag_gems.block_diag(*inputs), torch.block_diag(*refs), inputs, refs, dtype
    )
