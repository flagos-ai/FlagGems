def _make_sparse(M, K, dtype, device, sparsity, layout):
    """Build the masked dense values and the sparse tensor in ``layout``."""
    dense = torch.randn((M, K), dtype=torch.float32, device=device)
    if sparsity == 0.0:
        mask = torch.ones((M, K), dtype=torch.bool, device=device)
    elif sparsity == 1.0:
        mask = torch.zeros((M, K), dtype=torch.bool, device=device)
    else:
        mask = torch.rand((M, K), device=device) > sparsity
    values = (dense * mask).to(dtype)
    if layout == "csc":
        sparse = values.to_sparse_csc()
    elif layout == "coo":
        sparse = values.to_sparse()
    else:
        sparse = values.to_sparse_csr()
    return values, sparse


def _reduce_reference(sparse, mat2, reduce):
    """fp64 reference for the dual-output SpMM reduce.

    ``aten::_sparse_mm_reduce_impl`` is only registered for ``SparseCsrCPU`` in
    torch, so the reference folds the per-nnz products explicitly from the
    stored CSR structure: ``sum`` is the plain SpMM, ``mean`` divides by the
    row's stored nnz, and amax/amin fold the products. The fold walks the
    stored CSR entries only -- implicit zeros at non-nnz positions are not part
    of the reduction (verified against torch's CPU kernel) -- and rows with no
    stored entries yield 0 for every reduction.

    The reference always returns the empty ``arg_out`` form, which is what the
    aten CPU backend produces outside grad mode; the implementation is only
    checked for the same shape/dtype contract.
    """
    ref_sparse = utils.to_reference(sparse, True)
    ref_mat2 = utils.to_reference(mat2, True)
    ref_csr = ref_sparse.to_sparse_csr()
    crow = ref_csr.crow_indices()
    col = ref_csr.col_indices()
    vals = ref_csr.values()
    M, N = ref_sparse.shape[0], ref_mat2.shape[1]
    arg_out = torch.empty((0,), dtype=torch.int64, device=ref_mat2.device)
    if reduce == "sum":
        return ref_sparse.to_dense() @ ref_mat2, arg_out
    out = torch.zeros((M, N), dtype=ref_mat2.dtype, device=ref_mat2.device)
    for r in range(M):
        start, end = int(crow[r]), int(crow[r + 1])
        if end == start:
            continue
        prod = vals[start:end, None] * ref_mat2[col[start:end]]
        if reduce == "mean":
            out[r] = prod.sum(dim=0) / (end - start)
        elif reduce == "amax":
            out[r] = prod.max(dim=0).values
        else:
            out[r] = prod.min(dim=0).values
    return out, arg_out


