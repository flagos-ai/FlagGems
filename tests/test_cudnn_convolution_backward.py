def test_cudnn_convolution_backward_shape_and_dtype(shape, kernel, dtype):
    """The gradient has the input's shape/dtype and ignores bias entirely."""
    torch.manual_seed(0)
    spatial_dims = len(shape) - 2
    ones = [1] * spatial_dims
    inp = torch.randn(shape, dtype=dtype, device=flag_gems.device)
    weight = torch.randn(kernel, dtype=dtype, device=flag_gems.device)
    out_shape = torch.cudnn_convolution(
        inp, weight, ones, ones, ones, 1, False, False, False
    ).shape
    out_grad = torch.randn(out_shape, dtype=dtype, device=flag_gems.device)

    grad = flag_gems.cudnn_convolution_backward(
        out_grad, inp, weight, ones, ones, ones, 1, False, False, False
    )
    assert grad.shape == inp.shape
    assert grad.dtype == dtype
