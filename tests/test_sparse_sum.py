def _all_dims(ndim):
    """Every non-empty subset of ``range(ndim)``, in a stable order."""
    result = []
    for size in range(1, ndim + 1):
        result.extend(list(c) for c in itertools.combinations(range(ndim), size))
    return result


def _make_sparse(shape, dtype, device, density=0.5, seed=0, coalesce=True):
    """Build a COO tensor with distinct random coordinates.

    ``density`` is the stored fraction; the leading test values keep it below
    1.0 unless a fully dense structure is requested, so duplicate coordinates
    (which coalesce would fold) never appear.
    """
    generator = torch.Generator(device="cpu").manual_seed(seed)
    numel = 1
    for size in shape:
        numel *= size
    nnz = 0 if numel == 0 else max(1, int(numel * density))
    flat = torch.randperm(numel, generator=generator)[:nnz]
    coords = []
    remain = flat.clone()
    for size in reversed(shape):
        coords.append(remain % size)
        remain = remain // size
    indices = (
        torch.stack(coords[::-1]).to(torch.int64).to(device)
        if coords
        else torch.empty((len(shape), 0), dtype=torch.int64, device=device)
    )
    if dtype == torch.bool:
        values = (
            torch.randint(0, 2, (nnz,), generator=generator).to(torch.bool).to(device)
        )
    elif dtype in _INT_DTYPES:
        values = torch.randint(-8, 8, (nnz,), generator=generator).to(dtype).to(device)
    else:
        values = torch.randn(nnz, generator=generator).to(dtype).to(device)
    tensor = torch.sparse_coo_tensor(indices, values, size=shape, device=device)
    return tensor.coalesce() if coalesce else tensor


def _reference_values(sparse, upcast=True):
    """fp64 (or native integer) reference view of the stored values."""
    values = sparse.coalesce()._values()
    if values.is_floating_point():
        return utils.to_reference(values, upcast)
    return values


def _compare_dense(result, ref, dtype):
    assert result.layout == torch.strided
    assert result.shape == ref.shape
    if dtype in _INT_DTYPES:
        assert result.dtype == ref.dtype
        # ``to_reference`` honours the ``--ref cpu`` device convention, so
        # compare both sides through it before the exact integer check.
        utils.gems_assert_equal(utils.to_reference(result), utils.to_reference(ref))
        return
    got = utils.to_reference(result, upcast=True).to(torch.float64)
    ref64 = utils.to_reference(ref, upcast=True).to(torch.float64)
    # fp16/bf16 accumulate in fp32 inside the aten reference; the tolerance
    # follows the value precision (mirrors the ops contract).
    atol = 6e-3 if dtype in _LOW_PREC_DTYPES else 1e-5
    utils.gems_assert_close(got, ref64, torch.float64, atol=atol)


def _compare_sparse(result, ref, dtype):
    """Compare the projected COO structure exactly and the values numerically.

    The projected support set is deterministic: every distinct kept
    coordinate that appears in the input is stored, in ascending row-major
    order, with explicit structural zeros preserved.
    """
    assert result.layout == torch.sparse_coo
    assert result.shape == ref.shape
    ref = ref.coalesce()
    result = result.coalesce()
    assert result._nnz() == ref._nnz()
    assert torch.equal(result._indices().cpu(), ref._indices().cpu())
    if dtype in _INT_DTYPES:
        assert result._values().dtype == ref._values().dtype
        utils.gems_assert_equal(
            utils.to_reference(result._values()), utils.to_reference(ref._values())
        )
        return
    got = utils.to_reference(result._values(), upcast=True).to(torch.float64)
    ref64 = utils.to_reference(ref._values(), upcast=True).to(torch.float64)
    atol = 6e-3 if dtype in _LOW_PREC_DTYPES else 1e-5
    utils.gems_assert_close(got, ref64, torch.float64, atol=atol)


def _compare(result, ref, dtype):
    if ref.is_sparse:
        _compare_sparse(result, ref, dtype)
    else:
        _compare_dense(result, ref, dtype)


