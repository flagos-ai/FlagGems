def test_efficientzerotensor_views():
    res = flag_gems._efficientzerotensor((2, 3), device=flag_gems.device)
    ref = torch.ops.aten._efficientzerotensor.default((2, 3), device=flag_gems.device)
    view = res.t()
    assert view._is_zerotensor()
    assert view.stride() == ref.t().stride()
    utils.gems_assert_equal(view.clone(), utils.to_reference(ref.t().clone()))


