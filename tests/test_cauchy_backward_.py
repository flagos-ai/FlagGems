def test_cauchy_backward__leaf_error_preserves_input():
    x = torch.rand(17, device=flag_gems.device, requires_grad=True)
    before = x.detach().clone()
    with pytest.raises(RuntimeError, match="leaf"):
        flag_gems.cauchy_(x)
    torch.testing.assert_close(x.detach(), before, atol=0, rtol=0)


def test_cauchy_backward_strided_storage():
    leaf = torch.rand(40, device=flag_gems.device, requires_grad=True)
    storage = leaf.clone()
    before = storage.detach().clone()
    view = storage[1::3]
    output = flag_gems.cauchy_(view)
    mask = torch.ones(40, device=leaf.device, dtype=torch.bool)
    mask[1::3] = False
    torch.testing.assert_close(storage[mask], before[mask], atol=0, rtol=0)
    actual = torch.autograd.grad(output, leaf, torch.ones_like(output))[0]
    torch.testing.assert_close(actual, torch.zeros_like(leaf), atol=0, rtol=0)
