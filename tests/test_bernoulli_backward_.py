def check_unary(name, dtype, shape, strided, expanded_grad):
    n = math.prod(shape)
    length = n * 2 + 9 if strided else n
    raw = torch.rand(length, device=flag_gems.device, dtype=dtype)
    root = raw.detach().requires_grad_(True)
    ref_root = raw.detach().clone().requires_grad_(True)
    if strided:
        strides = []
        step = 2
        for size in reversed(shape):
            strides.append(step)
            step *= max(size, 1)
        strides.reverse()
        x = root.clone().as_strided(shape, strides, 3)
        ref = ref_root.clone().as_strided(shape, strides, 3)
    else:
        x, ref = (root.clone().view(shape), ref_root.clone().view(shape))
    before = root.detach().clone()
    expected_out = unary_reference(name, ref)
    actual_out = getattr(flag_gems, name)(x)
    assert actual_out.requires_grad
    assert actual_out.grad_fn is not None
    assert actual_out is x
    if expanded_grad:
        grad = torch.randn((), device=x.device, dtype=dtype).expand(shape)
    else:
        grad = torch.randn((*shape, 3), device=x.device, dtype=dtype)[..., 1]
    actual = torch.autograd.grad(actual_out, root, grad)[0]
    expected = torch.autograd.grad(expected_out, ref_root, grad)[0]
