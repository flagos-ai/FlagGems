@pytest.mark.parametrize("dtype", utils.FLOAT_DTYPES)
@pytest.mark.parametrize("p_requires_grad", [False, True])
def test_bernoulli_backward_tensor_probability(dtype, p_requires_grad):
    leaf = torch.rand((3, 17), dtype=dtype, device=flag_gems.device, requires_grad=True)
    prob = torch.rand(
        (17,), dtype=dtype, device=flag_gems.device, requires_grad=p_requires_grad
    )
    ref_leaf = leaf.detach().clone().requires_grad_()
    ref_prob = prob.detach().clone().requires_grad_(p_requires_grad)
    out = flag_gems.bernoulli_(leaf.clone(), prob)
    expected = ref_leaf.clone().bernoulli_(ref_prob)
    inputs = (leaf, prob) if p_requires_grad else (leaf,)
    refs = (ref_leaf, ref_prob) if p_requires_grad else (ref_leaf,)
    grad = torch.randn_like(out)
    actual_grads = torch.autograd.grad(out, inputs, grad)
    expected_grads = torch.autograd.grad(expected, refs, grad)
    for actual, reference in zip(actual_grads, expected_grads):
        torch.testing.assert_close(actual, reference, atol=0, rtol=0)
    assert torch.all((out == 0) | (out == 1))


def test_bernoulli_backward_strided_storage():
    leaf = torch.rand(40, device=flag_gems.device, requires_grad=True)
    storage = leaf.clone()
    before = storage.detach().clone()
    view = storage[1::3]
    output = flag_gems.bernoulli_(view)
    mask = torch.ones(40, device=leaf.device, dtype=torch.bool)
    mask[1::3] = False
    torch.testing.assert_close(storage[mask], before[mask], atol=0, rtol=0)
    actual = torch.autograd.grad(output, leaf, torch.ones_like(output))[0]
    torch.testing.assert_close(actual, torch.zeros_like(leaf), atol=0, rtol=0)
