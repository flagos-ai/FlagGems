import pytest
import torch

import flag_gems

from . import accuracy_utils as utils
from ._channel_shuffle_autograd import compare_gradients

pytestmark = [pytest.mark.channel_shuffle, pytest.mark.channel_shuffle_backward]


@pytest.mark.parametrize("dtype", utils.FLOAT_DTYPES)
@pytest.mark.parametrize(
    "shape,groups",
    [
        ((2, 6, 5), 3),
        ((2, 6, 3, 5), 2),
        ((2, 6, 2, 3, 5), 3),
        ((0, 6, 3, 5), 3),
        ((2, 6, 0, 5), 2),
        ((2, 6, 3, 5), 1),
    ],
)
@pytest.mark.parametrize("layout", ["plain", "strided", "channels_last"])
def test_channel_shuffle_backward(dtype, shape, groups, layout):
    x = (
        torch.randn((*shape, 2), device=flag_gems.device, dtype=dtype)[..., 1]
        if layout == "strided"
        else torch.randn(shape, device=flag_gems.device, dtype=dtype)
    )
    if layout == "channels_last" and len(shape) == 4:
        x = x.to(memory_format=torch.channels_last)
    x = x.detach().requires_grad_()
    ref = x.detach().clone().requires_grad_()
    compare_gradients(
        flag_gems.channel_shuffle(x, groups),
        torch.channel_shuffle(ref, groups),
        (x,),
        (ref,),
        dtype,
    )
