"""Accuracy tests for ``complex_backward``.

``aten::complex(real, imag)`` builds a complex tensor from two real tensors.
There is no ``aten::complex_backward`` schema; ATen's gradient is the
``ComplexBackward0`` autograd node with the formula

    real: at::real(grad)
    imag: at::imag(grad)

i.e. for a complex upstream gradient ``g`` the partials are ``Re(g)`` and
``Im(g)`` elementwise. FlagGems exposes this as a plain function rather than a
dispatcher key, and the tests call it directly.

Note the convention: PyTorch's complex autograd treats the VJP as the conjugate
product, which for ``out = real + i*imag`` collapses to ``real -> Re(g)`` and
``imag -> Im(g)``. Verified against ``torch.autograd.grad`` below.
"""

import pytest
import torch

import flag_gems

from . import accuracy_utils as utils

BACKWARD_SHAPES = [
    (4,),
    (7, 13),
    (2, 3, 5),
    (1,),
]

# complex64 accepts fp32 parts; complex128 accepts fp64 parts. Reduced-precision
# parts are not supported by aten::complex on CUDA, so they are not tested.
COMPLEX_BACKWARD_DTYPES = [torch.complex64]
if flag_gems.runtime.device.support_fp64:
    COMPLEX_BACKWARD_DTYPES.append(torch.complex128)


def _part_dtype(complex_dtype):
    return torch.float64 if complex_dtype is torch.complex128 else torch.float32


@pytest.mark.complex_backward
@pytest.mark.parametrize("shape", BACKWARD_SHAPES)
@pytest.mark.parametrize("dtype", COMPLEX_BACKWARD_DTYPES)
def test_complex_backward(shape, dtype):
    dtype_part = _part_dtype(dtype)
    real = torch.randn(shape, dtype=dtype_part, device=flag_gems.device)
    imag = torch.randn(shape, dtype=dtype_part, device=flag_gems.device)

    ref_real = real.detach().to(dtype_part).requires_grad_(True)
    ref_imag = imag.detach().to(dtype_part).requires_grad_(True)
    ref_out = torch.complex(ref_real, ref_imag)
    out_grad = torch.randn(ref_out.shape, dtype=dtype, device=flag_gems.device)
    ref_real_grad, ref_imag_grad = torch.autograd.grad(
        ref_out, (ref_real, ref_imag), out_grad
    )

    res_real_grad, res_imag_grad = flag_gems.complex_backward(out_grad, real, imag)

    assert res_real_grad.shape == real.shape
    assert res_real_grad.dtype == dtype_part
    assert res_imag_grad.shape == imag.shape
    assert res_imag_grad.dtype == dtype_part
    utils.gems_assert_close(res_real_grad, ref_real_grad, dtype_part)
    utils.gems_assert_close(res_imag_grad, ref_imag_grad, dtype_part)


@pytest.mark.complex_backward
@pytest.mark.parametrize("dtype", COMPLEX_BACKWARD_DTYPES)
def test_complex_backward_matches_parts(dtype):
    """The closed form is Re(g) / Im(g); check it against the autograd formula."""
    dtype_part = _part_dtype(dtype)
    shape = (5, 9)
    real = torch.randn(shape, dtype=dtype_part, device=flag_gems.device)
    imag = torch.randn(shape, dtype=dtype_part, device=flag_gems.device)
    out_grad = torch.randn(shape, dtype=dtype, device=flag_gems.device)

    res_real_grad, res_imag_grad = flag_gems.complex_backward(out_grad, real, imag)
    utils.gems_assert_close(res_real_grad, out_grad.real, dtype_part)
    utils.gems_assert_close(res_imag_grad, out_grad.imag, dtype_part)


@pytest.mark.complex_backward
@pytest.mark.parametrize("dtype", COMPLEX_BACKWARD_DTYPES)
def test_complex_backward_noncontiguous_grad(dtype):
    """A transposed upstream gradient is non-contiguous."""
    dtype_part = _part_dtype(dtype)
    shape = (8, 6)
    real = torch.randn(shape, dtype=dtype_part, device=flag_gems.device)
    imag = torch.randn(shape, dtype=dtype_part, device=flag_gems.device)
    out_grad = torch.randn((shape[1], shape[0]), dtype=dtype, device=real.device)
    out_grad = out_grad.t()
    assert not out_grad.is_contiguous()

    ref_real = real.detach().requires_grad_(True)
    ref_imag = imag.detach().requires_grad_(True)
    ref_real_grad, ref_imag_grad = torch.autograd.grad(
        torch.complex(ref_real, ref_imag), (ref_real, ref_imag), out_grad
    )

    res_real_grad, res_imag_grad = flag_gems.complex_backward(out_grad, real, imag)
    utils.gems_assert_close(res_real_grad, ref_real_grad, dtype_part)
    utils.gems_assert_close(res_imag_grad, ref_imag_grad, dtype_part)
