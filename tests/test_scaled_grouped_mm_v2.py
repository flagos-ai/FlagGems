def test_scaled_grouped_mm_v2_tensor_wise(dtype):
    """``TensorWise`` recipes carry a single scalar factor per operand.

    The upstream kernels do not implement this combination (they reject it
    with "No gemm implementation was found"), so the Triton kernel is checked
    against the per-group reference alone.
    """
    mat_a, mat_b, scale_a, scale_b, offs = _make_case("m_varying", dtype)
    groups = mat_b.shape[0]
    total_m = mat_a.shape[0]
    n_size = mat_b.shape[-1]

    scale_a = torch.full((1,), 0.9, device=flag_gems.device)
    scale_b = torch.full((1,), 1.1, device=flag_gems.device)
    ref = (
        _reference(
            mat_a,
            mat_b,
            torch.full((total_m,), 0.9, device=flag_gems.device),
            torch.full((groups, n_size), 1.1, device=flag_gems.device),
            offs,
        )
        .to(torch.bfloat16)
        .float()
    )

    res = flag_gems._scaled_grouped_mm_v2(
        mat_a,
        mat_b,
        [scale_a],
        [0],
        [0],
        [scale_b],
        [0],
        [0],
        offs,
        None,
        torch.bfloat16,
        [],
        False,
    )

    torch.testing.assert_close(res.float().cpu(), ref, atol=2.5e-1, rtol=5e-1)


