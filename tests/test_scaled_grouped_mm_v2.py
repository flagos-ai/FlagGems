"""Accuracy tests for ``aten::_scaled_grouped_mm_v2``.

The operator is the newer, recipe-driven spelling of the grouped scaled
matrix multiply: ``scale_a``/``scale_b`` arrive as lists, paired with
``recipe_a``/``recipe_b`` (``TensorWise`` / ``RowWise``) and, optionally,
``swizzle_a``/``swizzle_b``.

Only ``float8_e4m3fn`` operands with ``float32`` decoding scales and a
``bfloat16`` high-precision output are exercised, matching what the upstream
grouped GEMM kernels accept.  The reference is computed group by group on the
CPU from the same operands, so the comparison is deterministic.
"""

