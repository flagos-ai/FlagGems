# atleast_2d is a pure view/reshape: its cost is independent of numel, so
# the shape sweep spans small-to-large 1-D sizes plus a 2-D square. Yield
# 1-tuples: the harness unpacks each yielded item as an argument list.
ATLEAST_2D_SHAPES = [
    (16,),
    (1024,),
    (65536,),
    (1048576,),
    (64, 64),
]


class Atleast2dBenchmark(base.Benchmark):
    def set_shapes(self, shape_file_path=None):
        self.shapes = ATLEAST_2D_SHAPES

    def get_input_iter(self, cur_dtype):
        # atleast_2d never reads element data; the dtype sweep exists to
        # match the repository benchmark convention and vary itemsize.
        for shape in self.shapes:
            inp = torch.empty(shape, dtype=cur_dtype, device=self.device)
            yield (inp,)


