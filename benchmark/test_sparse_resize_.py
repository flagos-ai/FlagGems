def _torch_sparse_resize(indices, values, shape, size, sparse_dim, dense_dim):
    # Construct fresh metadata on both paths so every timed invocation starts
    # from the smaller shape. Reusing self would only benchmark a no-op after
    # the first call. The shared index/value buffers require no payload copy
    # unless the dense trailing dimensions grow.
    inp = torch.sparse_coo_tensor(indices, values, shape, check_invariants=False)
    return torch.ops.aten.sparse_resize_.default(inp, size, sparse_dim, dense_dim)


