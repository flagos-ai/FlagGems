TEMPLATE_COUNTS = [1, 8, 64, 256]


def _partition(numel, count):
    # Exact near-equal 1-D partition of numel into count pieces.
    base, rem = divmod(numel, count)
    return [base + 1 if i < rem else base for i in range(count)]


