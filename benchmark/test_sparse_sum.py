# Stored fraction of the random COO pattern.  The projection + coalesce cost
# (the part this operator replaces) scales with nnz, so the sparse regime is
# the interesting one; 0.01 keeps the largest shapes well inside memory.
DENSITY = 0.01
DENSITY_SMALL = 0.05

# The 2-D shapes live in ``core_shapes.yaml`` under the ``sparse_sum`` key so
# the benchmark harness resolves them through the standard shape file.


def _make_sparse_coo(shape, dtype, device, density, seed=0):
    m, n = shape
    generator = torch.Generator(device="cpu").manual_seed(seed)
    nnz = max(1, int(m * n * density))
    flat = torch.randperm(m * n, generator=generator)[:nnz]
    rows = (flat // n).to(torch.int64).to(device)
    cols = (flat % n).to(torch.int64).to(device)
    values = (
        torch.randn(nnz, generator=generator, dtype=torch.float32).to(dtype).to(device)
    )
    return torch.sparse_coo_tensor(
        torch.stack([rows, cols]), values, (m, n), device=device
    ).coalesce()


def _torch_sparse_sum(x):
    return torch.ops.aten._sparse_sum.dim(x, [1])


def _input_fn(shape, dtype, device, seed=0):
    density = DENSITY_SMALL if shape[0] <= 1024 else DENSITY
    yield (_make_sparse_coo(shape, dtype, device, density, seed=seed),)


