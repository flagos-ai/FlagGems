# Shapes for the movedim benchmark: 2D, 3D and 4D inputs. movedim is a
# zero-copy view operator, so the benchmark measures dispatch + as_strided
# overhead rather than data movement; large shapes keep the dispatch cost
# from being dominated by timer noise.
MOVEDIM_SHAPES = [
    (1024, 1024),
    (4096, 4096),
    (64, 512, 512),
    (128, 256, 64),
    (8, 16, 32, 64),
]


class MovedimBenchmark(base.Benchmark):
    """Benchmark for ``aten::movedim`` (zero-copy permutation view)."""

    DEFAULT_SHAPE_DESC = "input shape"

    def set_shapes(self, shape_file_path=None):
        # Fixed shape list: movedim is shape-agnostic, so the generic shape
        # file is not used and a small explicit sweep is enough.
        self.shapes = MOVEDIM_SHAPES

    def get_input_iter(self, dtype):
        for shape in self.shapes:
            inp = torch.randn(shape, dtype=dtype, device=self.device)
            # Move the first axis to the last position for every shape.
            yield inp, 0, inp.dim() - 1


