# (nnz, shape) pairs for CSC inputs. ccol_indices_copy moves ncols + 1 int64
# values, so the sweep varies the column count (the copied payload) across
# small-to-large cases while the values dtype follows the benchmark dtype
# sweep; crow/ccol stay int64 like every default-constructed sparse tensor.
CCOL_INDICES_COPY_CASES = [
    (256, (64, 128)),
    (4096, (512, 512)),
    (65536, (2048, 2048)),
    (1048576, (4096, 8192)),
]


def _make_csc(nnz, shape, cur_dtype, device):
    """Valid CSC with crow length ncols + 1 and col/values length nnz.

    Built on CPU (the ``bincount`` + ``cumsum`` pattern needs no device-side
    fill kernel) and moved to the benchmark device once.
    """
    nrows, ncols = shape
    counts = torch.bincount(
        torch.randint(0, ncols, (nnz,), dtype=torch.int64),
        minlength=ncols,
    )
    crow = torch.zeros(ncols + 1, dtype=torch.int64)
    crow[1:] = counts.cumsum(0)
    ccol = torch.randint(0, nrows, (nnz,), dtype=torch.int64)
    values = utils.generate_tensor_input((nnz,), cur_dtype, "cpu")
    return torch.sparse_csc_tensor(crow, ccol, values, shape).to(device)


