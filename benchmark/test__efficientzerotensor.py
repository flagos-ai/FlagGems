# Creation is O(1) in the requested size, so the sweep varies the requested
# metadata rather than the bytes written. The 2-D and 3-D entries keep every
# dimension >= 2 so the multi-dimensional expansion path is measured too, and
# each stays inside the 1-D case's element budget (no kernel is launched per
# call, so these measure the same stride-0-expansion path at different shapes).
ZERO_SIZES = [(16,), (65536,), (1048576,), (256, 256), (128, 128, 64)]


class EfficientZeroTensorBenchmark(base.Benchmark):
    def set_shapes(self, shape_file_path=None):
        self.shapes = ZERO_SIZES

    def get_input_iter(self, cur_dtype):
        # The harness unpacks each yielded tuple: list items become positional
        # args, dict items become kwargs. So yield a 2-item tuple -- the size
        # list as the single positional arg and a kwargs dict for the
        # dtype/device sweep (a third positional would bind to the ``out``
        # parameter of an out overload instead).
        for shape in self.shapes:
            yield (list(shape), {"dtype": cur_dtype, "device": self.device})


