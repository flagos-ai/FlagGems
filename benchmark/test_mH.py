# mH is a zero-copy view op (last-two-dim conjugate transpose), so the measured
# cost is host dispatch plus the one-program rank-guard launch, independent of
# the element count.  The shapes therefore cover 2-D, 3-D and batched 4-D
# layouts, which is what changes the stride bookkeeping, rather than scaling
# the number of elements.
MH_SHAPES = [
    (64, 64),
    (1024, 1024),
    (4096, 4096),
    (64, 512, 512),
    (8, 16, 32, 64),
    (4, 8, 256, 256),
]


