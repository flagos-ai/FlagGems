# Sparsity of the random CSR pattern used by the benchmarks (fraction of
# structural zeros). 0.9 keeps the SpMM bandwidth-bound, which is the common
# real-world case.
SPARSITY = 0.9


def _make_sparse_csr(shape, dtype, device, sparsity=SPARSITY):
    m, n = shape[-2:]
    dense = torch.randn(shape, dtype=dtype, device=device)
    mask = torch.rand((m, n), device=device) > sparsity
    mask = mask.expand(shape)
    dense = (dense * mask).contiguous()

    if torch.device(device).type == "cuda":
        return dense.to_sparse_csr()
    csr_cpu = dense.cpu().to_sparse_csr()
    return torch.sparse_csr_tensor(
        csr_cpu.crow_indices().to(device),
        csr_cpu.col_indices().to(device),
        csr_cpu.values().to(device),
        size=csr_cpu.shape,
        dtype=csr_cpu.dtype,
        device=device,
    )


