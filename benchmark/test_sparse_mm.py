# Sparsity of the random CSR pattern used by the benchmarks (fraction of
# structural zeros). 0.9 keeps the SpMM bandwidth-bound, which is the common
# real-world case.
SPARSITY = 0.9


def _make_sparse_csr(shape, dtype, device, sparsity=SPARSITY):
    m, n = shape[-2:]
    dense = torch.randn(shape, dtype=dtype, device=device)
    mask = torch.rand((m, n), device=device) > sparsity
    mask = mask.expand(shape)
    dense = (dense * mask).contiguous()

    if torch.device(device).type == "cuda":
        return dense.to_sparse_csr()
    csr_cpu = dense.cpu().to_sparse_csr()
    return torch.sparse_csr_tensor(
        csr_cpu.crow_indices().to(device),
        csr_cpu.col_indices().to(device),
        csr_cpu.values().to(device),
        size=csr_cpu.shape,
        dtype=csr_cpu.dtype,
        device=device,
    )


def _torch_sparse_mm(mat1, mat2):
    """Torch baseline.

    The native CUDA kernel only implements fp32/fp64; fp16/bf16 run through an
    fp32 upcast of the sparse triple, mirroring the reference used in tests.
    """
    if mat1.dtype in (torch.float16, torch.bfloat16):
        return torch.ops.aten._sparse_mm(mat1.float(), mat2.float()).to(mat1.dtype)
    return torch.ops.aten._sparse_mm(mat1, mat2)


def _input_fn(m, n, k, dtype, device, b_column_major=False, sparsity=SPARSITY):
    mat1 = _make_sparse_csr((m, k), dtype, device, sparsity)
    mat2 = torch.randn([k, n], dtype=dtype, device=device)
    if b_column_major:
        mat2 = mat2.t().contiguous().t()
    yield mat1, mat2


