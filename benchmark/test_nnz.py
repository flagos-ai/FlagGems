# aten::_nnz(Tensor self) -> int reports the number of stored entries of a
# sparse tensor. It is a pure layout-metadata query -- the measured work is
# dispatch plus index-buffer introspection, never data movement -- and dense
# (strided) tensors raise NotImplementedError, so every input is a sparse
# tensor. Dense logical shapes vary while the allocation stays small, because
# nnz is fixed and the op is O(1) in it.
NNZ_SIZES = [(16, 16), (1024, 16), (1024, 1024), (16384, 1024)]


class NnzBenchmark(base.Benchmark):
    def set_shapes(self, shape_file_path=None):
        # The op is O(1) in nnz, so the shape file sweep adds nothing; a small
        # fixed sparse-size sweep exercises the host path instead.
        self.shapes = NNZ_SIZES

    def get_input_iter(self, cur_dtype):
        # _nnz never reads element data; the dtype sweep exists to match the
        # repository benchmark convention and vary itemsize metadata. Yield a
        # 1-tuple: the harness unpacks each yielded item as an argument list,
        # and iterating a bare Tensor would pass its scalars.
        for shape in self.shapes:
            nnz = shape[0]
            indices = torch.stack(
                [
                    torch.randint(0, shape[0], (nnz,)),
                    torch.randint(0, shape[1], (nnz,)),
                ]
            ).to(self.device)
            # Values are never read by the metadata query; empty keeps the
            # dtype sweep (including int16/bool) free of randn restrictions.
            values = torch.empty(nnz, dtype=cur_dtype, device=self.device)
            inp = torch.sparse_coo_tensor(indices, values, shape).coalesce()
            yield (inp,)


