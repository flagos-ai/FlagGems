# The cost of ``sparse_mask`` follows the number of stored entries of the mask,
# not the element count of ``self``: the kernel streams one value per stored
# entry through the strides of ``self``. 1/64 of the dense grid is kept sparse
# so the gather stays the dominant term while the mask stays a realistic size.
SPARSE_MASK_SHAPES = [(1024, 1024), (4096, 4096)]
SPARSE_MASK_NNZ_FRACTION = 64


def _make_mask(shape, dtype, device):
    numel = 1
    for size in shape:
        numel *= size
    nnz = max(1, numel // SPARSE_MASK_NNZ_FRACTION)
    flat = torch.randperm(numel, device=device)[:nnz]
    indices = torch.empty((len(shape), nnz), dtype=torch.int64, device=device)
    for dim in reversed(range(len(shape))):
        indices[dim] = flat % shape[dim]
        flat = flat // shape[dim]
    values = torch.zeros(nnz, dtype=dtype, device=device)
    return torch.sparse_coo_tensor(indices, values, shape).coalesce()


