# aten::_dimI(Tensor self) -> int reports the sparse dimension count of a COO
# tensor. It is a pure layout-metadata query -- the measured work is dispatch
# plus layout introspection, never data movement -- and dense / SparseCsr
# tensors raise NotImplementedError, so every input is a sparse COO tensor.
#
# Case descriptors are (shape, sparse_dim): fully sparse layouts
# (sparse_dim == ndim, dense_dim == 0) of rank 1-5, plus hybrid layouts
# (0 < sparse_dim < ndim). The logical shapes vary while the allocation stays
# small, because nnz is fixed and the op is O(1) in it.
DIM_I_CASES = [
    ((256,), 1),
    ((1024, 1024), 2),
    ((1024, 1024), 1),
    ((20, 320, 15), 3),
    ((20, 320, 15), 2),
    ((64, 512, 512), 3),
    ((64, 512, 512), 2),
    ((16, 1024, 1024, 16), 3),
    ((8, 16, 16, 16, 16), 5),
]

# Number of stored entries for every case. The op never reads them, so nnz
# only affects input allocation.
DIM_I_NNZ = 128


def _make_sparse_input(shape, sparse_dim, dtype, device, nnz=DIM_I_NNZ, seed=0):
    gen = torch.Generator("cpu").manual_seed(seed)
    indices = torch.stack(
        [
            torch.randint(0, size, (nnz,), dtype=torch.long, generator=gen)
            for size in shape[:sparse_dim]
        ]
    ).to(device)
    # Values are never read by the metadata query; empty() keeps the dtype
    # sweep (int16/bool included) free of randn restrictions.
    values = torch.empty((nnz,) + tuple(shape[sparse_dim:]), dtype=dtype, device=device)
    return torch.sparse_coo_tensor(indices, values, shape, device=device)


