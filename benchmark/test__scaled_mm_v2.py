"""Performance benchmark for ``aten::_scaled_mm_v2``.

The operator is the recipe-driven spelling of the scaled matrix multiply: the
fp8 operands carry ``float32`` decoding scales described by
``recipe_a``/``recipe_b``.  Two recipes are timed -- ``TensorWise`` (one scalar
factor per operand) and ``RowWise`` (a factor per row of ``mat_a`` / column of
``mat_b``) -- since they read the scale buffers with different granularity.
"""

from typing import Generator

import pytest
import torch

import flag_gems

from . import base, consts


def _cuda_fp8_available():
    if flag_gems.device != "cuda" or not torch.cuda.is_available():
        return False
    if not hasattr(torch, "float8_e4m3fn"):
        return False
    major, minor = torch.cuda.get_device_capability()
    return major * 10 + minor >= 89


def _native_benchmark_available():
    return _cuda_fp8_available() and hasattr(torch, "_scaled_mm_v2")


# ``TensorWise`` / ``RowWise`` as the operator spells them.
RECIPE_TENSOR_WISE = 0
RECIPE_ROW_WISE = 1


class ScaledMMV2Benchmark(base.Benchmark):
    DEFAULT_METRICS = consts.DEFAULT_METRICS[:] + ["tflops"]

    def __init__(self, recipe, dtype=torch.bfloat16):
        # float8_e4m3fn operands are CUDA-only (sm89+); the operator has no
        # float16/float32/bfloat16 variant, so the dtype set is hardcoded.
        super().__init__(
            "scaled_mm_v2",
            torch._scaled_mm_v2,
            dtypes=[torch.float8_e4m3fn],
        )
        self.set_gems(flag_gems._scaled_mm_v2)
        self.recipe = recipe
        self.out_dtype = dtype

    def set_shapes(self, shape_file_path=None):
        # fp8 GEMM throughput is sensitive to tile shape; time a small, a
        # mid and a large cubic size so both ends of the scale are covered.
        self.shapes = [
            (128, 128, 128),
            (512, 512, 512),
            (1024, 1024, 1024),
        ]
        if base.Config.bench_level == consts.BenchLevel.COMPREHENSIVE:
            self.shapes = list(dict.fromkeys(self.shapes + self.set_more_shapes()))
        self.shape_desc = "M, N, K"

    def set_more_shapes(self):
        return [
            (256, 4096, 4096),
            (4096, 4096, 4096),
        ]

    def get_input_iter(self, cur_dtype) -> Generator:
        for m_size, n_size, k_size in self.shapes:
            mat_a = torch.randn(m_size, k_size, device=flag_gems.device)
            mat_a = (mat_a * 0.25).to(cur_dtype)

            mat_b = torch.randn(n_size, k_size, device=flag_gems.device)
            mat_b = (mat_b * 0.25).to(cur_dtype).transpose(0, 1)

            if self.recipe == RECIPE_TENSOR_WISE:
                scale_a = torch.full((1,), 0.75, device=flag_gems.device)
                scale_b = torch.full((1,), 1.25, device=flag_gems.device)
            else:
                scale_a = torch.linspace(
                    0.75, 1.25, m_size, device=flag_gems.device
                ).reshape(m_size, 1)
                scale_b = torch.linspace(
                    1.25, 0.75, n_size, device=flag_gems.device
                ).reshape(1, n_size)

            yield (
                mat_a,
                mat_b,
                [scale_a],
                [self.recipe],
                [0],
                [scale_b],
                [self.recipe],
                [0],
                None,
                self.out_dtype,
                [],
                False,
            )

    def get_tflops(self, op, *args, **kwargs):
        m_size, k_size = args[0].shape
        n_size = args[1].shape[1]
        return 2 * m_size * n_size * k_size


