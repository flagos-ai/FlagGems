def _torch_rowwise_prune(weight, mask, compressed_indices_dtype):
    # torch's native CUDA _rowwise_prune kernel segfaults, so the baseline is
    # the equivalent composite of working CUDA ops.
    counts = torch.cumsum(mask.to(torch.int64), dim=0) - 1
    row_indices = torch.where(mask, counts, torch.tensor(-1, dtype=torch.int64))
    row_indices = row_indices.to(compressed_indices_dtype)
    kept = torch.nonzero(mask).flatten()
    return weight.index_select(0, kept), row_indices


def _input_fn(shape, cur_dtype, device):
    M = shape[0]
    weight = utils.generate_tensor_input(shape, cur_dtype, device)
    mask = torch.rand(M, device=device) < 0.5
    yield weight, mask, torch.int32


def _get_gbps(bench_fn_args, latency):
    weight, mask = bench_fn_args[0], bench_fn_args[1]
    M, K = weight.shape
    kept = int(torch.sum(mask))
    io_amount = shape_utils.size_in_bytes(weight) + shape_utils.size_in_bytes(mask)
    io_amount += kept * K * weight.element_size() + M * 4
    return io_amount * 1e-9 / (latency * 1e-3)


