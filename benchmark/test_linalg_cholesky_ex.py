import pytest
import torch

import flag_gems

from . import base

CASES = [
    ((), 2, False),
    ((1,), 3, True),
    ((2,), 4, False),
    ((2, 3), 5, True),
    ((1,), 7, False),
    ((3,), 3, True),
    ((2, 2), 4, False),
    ((4,), 6, True),
]


class LinalgCholeskyExBenchmark(base.Benchmark):
    DEFAULT_SHAPE_DESC = "operator configuration"

    def set_shapes(self, shape_file_path=None):
        self.shapes = CASES

    def get_input_iter(self, dtype):
        for case in self.shapes:
            batch_shape, n, upper = case
            raw = torch.randn(*batch_shape, n, n, dtype=dtype, device=self.device)
            eye = torch.eye(n, dtype=dtype, device=self.device).expand(
                *batch_shape, n, n
            )
            yield raw @ raw.transpose(-1, -2) + 2.0 * eye, {
                "upper": upper,
                "check_errors": False,
            }


