import pytest
import torch

import flag_gems

from . import base

CASES = [
    ((), 2),
    ((1,), 3),
    ((2,), 4),
    ((2, 3), 5),
    ((1,), 7),
    ((3,), 3),
    ((2, 2), 4),
    ((4,), 6),
]


class LinalgInvBenchmark(base.Benchmark):
    DEFAULT_SHAPE_DESC = "operator configuration"

    def set_shapes(self, shape_file_path=None):
        self.shapes = CASES

    def get_input_iter(self, dtype):
        for case in self.shapes:
            batch_shape, n = case
            raw = torch.randn(*batch_shape, n, n, dtype=dtype, device=self.device)
            eye = torch.eye(n, dtype=dtype, device=self.device).expand(
                *batch_shape, n, n
            )
            yield raw @ raw.transpose(-1, -2) + 3.0 * eye, {}


