CASES = [
    ((2, 3, 2, 3), (2, 3)),
    ((3, 3, 3, 3), (3, 3)),
    ((2, 2, 2, 2), (2, 2)),
    ((1, 1), (1,)),
    ((4, 4), (4,)),
    ((2, 4, 2, 4), (2, 4)),
    ((1, 3, 1, 3), (1, 3)),
    ((3, 2, 3, 2), (3, 2)),
]


class LinalgTensorsolveBenchmark(base.Benchmark):
    DEFAULT_SHAPE_DESC = "operator configuration"

    def set_shapes(self, shape_file_path=None):
        self.shapes = CASES

    def get_input_iter(self, dtype):
        for case in self.shapes:
            lhs_shape, rhs_shape = case
            solution_shape = lhs_shape[: -len(rhs_shape)]
            p = 1
            for size in solution_shape:
                p *= size
            raw = torch.randn(p, p, dtype=dtype, device=self.device)
            matrix = raw @ raw.T + 2.0 * torch.eye(p, dtype=dtype, device=self.device)
            solution = torch.randn(*solution_shape, dtype=dtype, device=self.device)
            yield matrix.reshape(*lhs_shape), {
                "other": (matrix @ solution.reshape(-1)).reshape(*rhs_shape),
                "dims": None,
            }


