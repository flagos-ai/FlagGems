import pytest
import torch

import flag_gems

from . import base, consts


@pytest.mark.copy_from
@pytest.mark.underscore_copy_from
def test_copy_from():
    # Stock PyTorch has no CUDA _copy_from kernel. Its native copy_ performs
    # the equivalent operation with destination/source arguments reversed.
    # Measure native copy_ against the registered FlagGems _copy_from wrapper.
    def torch_copy_from(src, dst, non_blocking=False):
        return dst.copy_(src, non_blocking=non_blocking)

    def input_fn(shape, dtype, device):
        src = torch.randn(shape, dtype=dtype, device=device)
        dst = torch.zeros(shape, dtype=dtype, device=device)
        yield src, dst

    bench = base.GenericBenchmark(
        input_fn=input_fn,
        op_name="copy_from",
        torch_op=torch_copy_from,
        gems_op=flag_gems._copy_from,
        dtypes=consts.FLOAT_DTYPES,
    )

    bench.run()
