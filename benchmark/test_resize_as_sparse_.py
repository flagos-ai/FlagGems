# Sparse dimensions grow while the nnz/payload stay unchanged. These paired
# shapes represent sparse resize inputs, not pointwise extents.
RESIZE_AS_SPARSE_SHAPES = [
    ((2, 3), (4, 5)),
    ((256, 1024), (512, 1024)),
    ((16, 4096, 8), (32, 4096, 8)),
]


def _torch_resize_as_sparse(indices, values, shape, template):
    # Construct fresh metadata on both paths so every timed invocation starts
    # with the smaller shape. Reusing self would only benchmark a no-op after
    # the first call. The shared index/value buffers require no payload copy.
    inp = torch.sparse_coo_tensor(indices, values, shape, check_invariants=False)
    return torch.ops.aten.resize_as_sparse_.default(inp, template)


def _gems_resize_as_sparse(indices, values, shape, template):
    inp = torch.sparse_coo_tensor(indices, values, shape, check_invariants=False)
    return flag_gems.resize_as_sparse_(inp, template)


