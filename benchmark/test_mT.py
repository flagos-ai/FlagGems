import pytest
import torch

import flag_gems

from . import base, consts

# Shapes covering 2D / 3D / 4D.  mT is a zero-copy view operator, so the
# benchmark measures dispatch + as_strided overhead rather than data movement.
MT_SHAPES = [
    (1024, 1024),
    (4096, 4096),
    (64, 512, 512),
    (128, 256, 64),
    (8, 16, 32, 64),
]


class MTBenchmark(base.Benchmark):
    """Benchmark for ``aten::mT`` (zero-copy last-two-dims transposition)."""

    DEFAULT_SHAPE_DESC = "input shape"

    def set_shapes(self, shape_file_path=None):
        self.shapes = MT_SHAPES

    def get_input_iter(self, cur_dtype):
        for shape in self.shapes:
            inp = torch.randn(shape, dtype=cur_dtype, device=self.device)
            yield (inp,)


@pytest.mark.mT
@pytest.mark.parametrize("dtype", consts.FLOAT_DTYPES)
def test_mT(dtype):
    bench = MTBenchmark(
        op_name="mT",
        torch_op=torch.ops.aten.mT,
        gems_op=flag_gems.ops.mT,
        dtypes=[dtype],
    )
    bench.run()
