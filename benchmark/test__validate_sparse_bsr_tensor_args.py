import pytest
import torch

import flag_gems

from . import base, consts, utils
from .generated_operator_utils import OperatorBenchmark

# BSR sizes need rank >= 2: the last two extents are the block extents and the leading
# extents are batch extents. Every extent of the last two must be divisible by the
# matching block extent, which is why an odd extent gets a 1-wide block. The last entry
# is an explicit (size, block) descriptor; the others derive their block from the size.
_BSR_BENCH_SHAPES = [
    (2, 19, 7),
    (64, 64),
    (1024, 1024),
    (20, 320, 15),
    (16, 128, 64, 60),
    (16, 7, 57, 32, 29),
    (4096, 4096),
    ((64, 64), (4, 8)),
]

# Static capability gates, read once at import from the suite's own flags, so listing
# never touches a device and no dtype is probed: an index tensor may only use a dtype
# the backend offers, and a bfloat16 payload row is dropped when the backend has no
# bfloat16 support. consts.INT_DTYPES holds int16/int32 only, so no int64 payload is
# generated by the randint-based builder.
_INDEX_DTYPES = [torch.int32]
if flag_gems.runtime.device.support_int64:
    _INDEX_DTYPES.append(torch.int64)
_VALUE_DTYPES = [
    dtype
    for dtype in consts.FLOAT_DTYPES + consts.INT_DTYPES
    if dtype != torch.bfloat16 or flag_gems.runtime.device.support_bf16
]


def _size_extents(seq):
    """A BSR size is rank >= 2 of non-negative integer extents; zero extents are valid."""
    if not isinstance(seq, (tuple, list)) or len(seq) < 2:
        raise ValueError(f"a BSR size needs at least two extents, got {seq!r}")
    for extent in seq:
        if isinstance(extent, bool) or not isinstance(extent, int):
            raise ValueError(f"a BSR size extent must be an integer, got {extent!r}")
        if extent < 0:
            raise ValueError(f"a BSR size extent must be non-negative, got {extent}")
    return tuple(seq)


def _block_extents(seq):
    """A BSR block is a divisor pair: exactly two positive integer extents."""
    if not isinstance(seq, (tuple, list)) or len(seq) != 2:
        raise ValueError(f"a BSR block needs exactly two extents, got {seq!r}")
    for extent in seq:
        if isinstance(extent, bool) or not isinstance(extent, int):
            raise ValueError(f"a BSR block extent must be an integer, got {extent!r}")
        if extent <= 0:
            raise ValueError(f"a BSR block extent must be positive, got {extent}")
    return tuple(seq)


def _split_descriptor(shape):
    """Return (size, explicit_block_or_None); extents are validated, never coerced."""
    if (
        isinstance(shape, (tuple, list))
        and len(shape) == 2
        and all(isinstance(part, (tuple, list)) for part in shape)
    ):
        return _size_extents(shape[0]), _block_extents(shape[1])
    return _size_extents(shape), None


def _derived_block(size):
    return (2 if size[-2] % 2 == 0 else 1, 2 if size[-1] % 2 == 0 else 1)


def _require_divisible(size, block):
    """An incompatible request is rejected rather than adjusted."""
    for extent, width, axis in (
        (size[-2], block[0], "row"),
        (size[-1], block[1], "column"),
    ):
        if extent % width != 0:
            raise ValueError(
                f"the {axis} extent {extent} is not divisible by the block extent {width}"
            )


def _case_fn(shape, dtype):
    del dtype
    size, explicit_block = _split_descriptor(shape)
    block = explicit_block if explicit_block is not None else _derived_block(size)
    _require_divisible(size, block)
    ncol_blocks = size[-1] // block[1]
    # One stored block per row is the sparse baseline, two cover a denser row and are
    # only offered when the column extent has room for two distinct column blocks. A
    # zero column extent stores no block at all, so that structure advertises 0.
    densities = [1, 2] if ncol_blocks >= 2 else [1] if ncol_blocks == 1 else [0]
    for index_dtype in _INDEX_DTYPES:
        for blocks_per_row in densities:
            yield base.BenchmarkCasePlan(
                shape={"size": list(size), "block": list(block)},
                params={
                    "blocks_per_row": blocks_per_row,
                    "index_dtype": str(index_dtype),
                },
                builder_args=(size, block, index_dtype, blocks_per_row),
            )


def _build_inputs_fn(plan, dtype, device):
    size, block, index_dtype, blocks_per_row = plan.builder_args
    block_rows, block_cols = block
    batch = tuple(size[:-2])
    nrow_blocks = size[-2] // block_rows
    # blocks_per_row is used exactly as planned: the planner emits 0 only for a
    # zero-column structure and never exceeds the column block count.
    crow_indices = (
        torch.arange(nrow_blocks + 1, dtype=index_dtype, device=device) * blocks_per_row
    )
    # The column blocks of a row are 0 .. blocks_per_row - 1, so they stay sorted,
    # distinct and inside the column extent, and the offsets above are non-decreasing
    # and end at the stored block count.
    col_indices = torch.arange(blocks_per_row, dtype=index_dtype, device=device).repeat(
        nrow_blocks
    )
    values = utils.generate_tensor_input(
        batch + (nrow_blocks * blocks_per_row, block_rows, block_cols), dtype, device
    )
    if batch:
        crow_indices = crow_indices.expand(batch + crow_indices.shape).contiguous()
        col_indices = col_indices.expand(batch + col_indices.shape).contiguous()
    # GenericBenchmark.unpack_to_args_kwargs keeps each Tensor and the int list in
    # positional args, so the four operands are returned flat. Wrapping them in a
    # tuple would pass one nested tuple as crow_indices.
    return crow_indices, col_indices, values, list(size)


class ValidateSparseBsrTensorArgsBenchmark(OperatorBenchmark):
    # The operator has no tensor output and only reads its inputs, so the generic
    # bandwidth/flops metrics do not apply; latency is the operator metric.
    DEFAULT_METRICS = ["latency"]

    def set_shapes(self, shape_file_path=None):
        # Keep a caller-supplied shape file, otherwise use the BSR sizes.
        if shape_file_path is None:
            self.shapes = [tuple(shape) for shape in _BSR_BENCH_SHAPES]
            return
        super().set_shapes(shape_file_path, default_shapes=_BSR_BENCH_SHAPES)

    def set_more_shapes(self):
        # The generic extra shapes are not valid BSR sizes (1-dim, or an extent that
        # the block does not divide), so the default list is complete.
        return []


@pytest.mark.validate_sparse_bsr_tensor_args
def test__validate_sparse_bsr_tensor_args():
    bench = ValidateSparseBsrTensorArgsBenchmark(
        op_name="_validate_sparse_bsr_tensor_args",
        case_fn=_case_fn,
        build_inputs_fn=_build_inputs_fn,
        torch_op=torch.ops.aten._validate_sparse_bsr_tensor_args,
        gems_op=getattr(flag_gems, "_validate_sparse_bsr_tensor_args", None),
        dtypes=_VALUE_DTYPES,
    )
    bench.run()
