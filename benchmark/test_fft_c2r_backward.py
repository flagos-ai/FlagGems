CASES = [
    ((16,), -1, 0),
    ((4, 16), -1, 0),
    ((2, 7), -1, 1),
    ((64, 256), -1, 0),
    ((2, 8, 32), 1, 0),
    ((2, 8, 32), -1, 0),
    ((8, 64, 4096), -1, 0),
    ((512, 4096), -1, 0),
]


def _reference(grad, dim=-1, normalization=0):
    d = int(dim) % grad.ndim
    gI = torch.ops.aten._fft_r2c(grad, [d], int(normalization), True)
    double_length = grad.size(d) - gI.size(d)
    if double_length > 0:
        ref = gI.clone()
        ref.narrow(d, 1, double_length).mul_(2)
        return ref
    return gI


