@triton.jit
def _sum_broadcast(
    G,
    OUT,
    N: tl.constexpr,
    OSH: tl.constexpr,
    OSTR: tl.constexpr,
    RSH: tl.constexpr,
    RSTR: tl.constexpr,
    B: tl.constexpr,
):
    row = tl.program_id(0)
    dtype: tl.constexpr = tl.float64 if G.dtype.element_ty == tl.float64 else tl.float32
    acc = tl.full((B,), 0, dtype)
    for start in range(tl.cdiv(N, B)):
        col = start * B + tl.arange(0, B)
        off = _offset(row, OSH, OSTR) + _offset(col, RSH, RSTR)
        value = tl.load(G + off, col < N, other=0).to(dtype)
        acc += value
    tl.store(OUT + row, tl.sum(acc, 0))


