@triton.jit
def strided_offset(index, shape: tl.constexpr, strides: tl.constexpr):
    offset = tl.full(index.shape, 0, tl.int64)
    for axis in tl.static_range(len(shape) - 1, -1, -1):
        offset += (index % shape[axis]) * strides[axis]
        index //= shape[axis]
    return offset


@triton.jit
def _copy_kernel(
    X,
    Y,
    N,
    SHAPE: tl.constexpr,
    STRIDES: tl.constexpr,
    CONTIGUOUS: tl.constexpr,
    BLOCK: tl.constexpr,
):
    i = tl.program_id(0) * BLOCK + tl.arange(0, BLOCK)
    if CONTIGUOUS:
        offset = i
    else:
        offset = strided_offset(i, SHAPE, STRIDES)
    value = tl.load(X + offset, i < N, other=0)
    tl.store(Y + i, value, i < N)


def copy_tensor(x, dtype=None):
    out = torch.empty(
        x.shape, dtype=x.dtype if dtype is None else dtype, device=x.device
    )
    if x.numel():
        with torch_device_fn.device(x.device):
            _copy_kernel[(triton.cdiv(x.numel(), 512),)](
                x,
                out,
                x.numel(),
                tuple(x.shape),
                tuple(x.stride()),
                x.is_contiguous(),
                512,
            )
    return out


