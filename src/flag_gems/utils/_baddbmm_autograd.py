@triton.jit
def _gradient_product(
    X,
    Y,
    O,
    M: tl.constexpr,
    N: tl.constexpr,
    R: tl.constexpr,
    SX0: tl.constexpr,
    SX1: tl.constexpr,
    SY0: tl.constexpr,
    SY1: tl.constexpr,
    SO0: tl.constexpr,
    PM,
    PN,
    ALPHA: tl.constexpr,
    TM: tl.constexpr,
    TN: tl.constexpr,
    TK: tl.constexpr,
):
    rows = PM * TM + tl.arange(0, TM)
    cols = PN * TN + tl.arange(0, TN)
    inner = tl.arange(0, TK)
    acc_dtype: tl.constexpr = (
        tl.float64 if O.dtype.element_ty == tl.float64 else tl.float32
    )
    acc = tl.zeros((TM, TN), acc_dtype)
    for start in range(0, R, TK):
        kk = start + inner
        x = tl.load(
            X + rows[:, None] * SX0 + kk[None, :] * SX1,
            (rows[:, None] < M) & (kk[None, :] < R),
            other=0,
        )
        y = tl.load(
            Y + kk[:, None] * SY0 + cols[None, :] * SY1,
            (kk[:, None] < R) & (cols[None, :] < N),
            other=0,
        )
        acc += tl.dot(x, y, allow_tf32=False)
    # Match the reference's materialized matmul result before scalar scaling.
    value = acc.to(O.dtype.element_ty)
    if ALPHA != 1:
        value = value.to(acc_dtype) * ALPHA
    tl.store(
        O + rows[:, None] * SO0 + cols[None, :],
        value,
        (rows[:, None] < M) & (cols[None, :] < N),
    )


