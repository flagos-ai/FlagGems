def _flatten_1d(t):
    # Return (flat_stride, tensor) such that flattened element r of the M-element
    # view lives at r * flat_stride. Multi-dimensional stat tensors produced by
    # strided wrapping have a contiguous chain of strides ending in the inner
    # stride; otherwise fall back to a dense copy with unit stride.
    if t.dim() <= 1:
        return (t.stride(0) if t.dim() > 0 else 1), t
    sizes = t.shape
    strides = t.stride()
    s = strides[-1]
    for i in range(t.dim() - 1):
        if strides[i] != strides[i + 1] * sizes[i + 1]:
            return 1, copy_tensor(t)
    return s, t


def _flatten_strides(t, M, N):
    # Return (row_stride, col_stride, None) such that element (r, c) of the
    # MxN flattened view lives at r*row_stride + c*col_stride, iff the tensor's
    # strides form a contiguous chain. Otherwise return (N, 1, dense_copy).
    if t.numel() == 0:
        return N, 1, t
    sizes = t.shape
    strides = t.stride()
    s = strides[-1]
    chain = True
    for i in range(t.dim() - 1):
        if strides[i] != strides[i + 1] * sizes[i + 1]:
            chain = False
            break
    if chain:
        row_stride = N * s
        return row_stride, s, t
    return N, 1, copy_tensor(t)


