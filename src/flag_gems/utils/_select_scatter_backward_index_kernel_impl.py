def contiguous_strides(shape):
    out = []
    stride = 1
    for n in reversed(shape):
        out.append(stride)
        stride *= max(n, 1)
    return tuple(reversed(out))


@triton.jit
def offset(linear, SHAPE: tl.constexpr, STRIDES: tl.constexpr):
    result = tl.full(linear.shape, 0, tl.int64)
    for d in tl.static_range(len(SHAPE) - 1, -1, -1):
        result += linear % SHAPE[d] * STRIDES[d]
        linear = linear // SHAPE[d]
    return result


