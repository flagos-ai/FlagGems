@triton.jit
def _multiply(a, b):
    return a * b


@triton.jit
def _empty_value(Y, NZ, Z, M: tl.constexpr, PRODUCT: tl.constexpr, B: tl.constexpr):
    i = tl.program_id(0) * B + tl.arange(0, B)
    tl.store(Y + i, 1 if PRODUCT else 0, i < M)
    tl.store(NZ + i, 1, i < M)
    tl.store(Z + i, 0, i < M)


@triton.jit
def _partials(
    X,
    V,
    Z,
    N: tl.constexpr,
    CHUNKS: tl.constexpr,
    SHAPE: tl.constexpr,
    XS: tl.constexpr,
    OSH: tl.constexpr,
    OSTR: tl.constexpr,
    RSH: tl.constexpr,
    RSTR: tl.constexpr,
    PRODUCT: tl.constexpr,
    P: tl.constexpr,
    B: tl.constexpr,
):
    row, chunk = tl.program_id(0), tl.program_id(1)
    col = chunk * B + tl.arange(0, B)
    off = _offset(row, OSH, OSTR) + _offset(col, RSH, RSTR)
    x = tl.load(X + off, col < N, other=0).to(tl.float32)
    if PRODUCT:
        v = tl.reduce(tl.where(col < N, x, 1), 0, _multiply)
        z = tl.sum(((col < N) & (x == 0)).to(tl.int32), 0)
        tl.store(Z + row * CHUNKS + chunk, z)
    else:
        a = tl.abs(x)
        if P == float("inf"):
            v = tl.max(tl.where(col < N, a, 0), 0)
        elif P == -float("inf"):
            v = tl.min(tl.where(col < N, a, float("inf")), 0)
        elif P == 0:
            v = tl.sum(((col < N) & (a != 0)).to(tl.float32), 0)
        elif P == 2:
            v = tl.sum(tl.where(col < N, a * a, 0), 0)
        elif P == 1:
            v = tl.sum(tl.where(col < N, a, 0), 0)
        else:
            v = tl.sum(tl.where(col < N, libdevice.pow(a, P), 0), 0)
    tl.store(V + row * CHUNKS + chunk, v)


@triton.jit
def _finish(
    V,
    Z,
    Y,
    NONZERO,
    ZEROS,
    CHUNKS: tl.constexpr,
    PRODUCT: tl.constexpr,
    P: tl.constexpr,
    B: tl.constexpr,
):
    row = tl.program_id(0)
    i = tl.arange(0, B)
    if PRODUCT:
        a = tl.load(V + row * CHUNKS + i, i < CHUNKS, other=1)
        z = tl.load(Z + row * CHUNKS + i, i < CHUNKS, other=0)
        product = tl.reduce(a, 0, _multiply)
        zero_count = tl.sum(z, 0)
        tl.store(NONZERO + row, product)
        tl.store(ZEROS + row, zero_count)
        # Keep real zeros in the reduction so 0*Inf/NaN follows IEEE semantics.
        # The VJP uses the separately saved zero counts and zero-safe scan.
        value = product
    else:
        if P == float("inf"):
            a = tl.load(V + row * CHUNKS + i, i < CHUNKS, other=0)
            value = tl.max(a, 0)
        elif P == -float("inf"):
            a = tl.load(V + row * CHUNKS + i, i < CHUNKS, other=float("inf"))
            value = tl.min(a, 0)
        else:
            a = tl.load(V + row * CHUNKS + i, i < CHUNKS, other=0)
            value = tl.sum(a, 0)
            if P != 0 and P != 1:
                value = libdevice.pow(value, 1.0 / P)
    tl.store(Y + row, value)


def reduction_plan(x, dim):
    rank = x.ndim
    if dim is None:
        dims = tuple(range(rank))
    elif rank == 0:
        dims = ()
    else:
        ds = (dim,) if isinstance(dim, int) else tuple(dim)
        if any(d < -rank or d >= rank for d in ds):
            raise IndexError("Dimension out of range")
        dims = tuple(d % rank for d in ds)
        if len(set(dims)) != len(dims):
            raise RuntimeError("dim appears multiple times")
        if not dims:
            dims = tuple(range(rank))
    outer = tuple(i for i in range(rank) if i not in dims)
    osh = tuple(x.shape[i] for i in outer)
    rsh = tuple(x.shape[i] for i in dims)
    ostr = tuple(x.stride(i) for i in outer)
    rstr = tuple(x.stride(i) for i in dims)
    return dims, outer, osh, rsh, ostr, rstr


def reduce_values(x, dim, keepdim, *, product=False, p=2):
    dims, outer, osh, rsh, ostr, rstr = reduction_plan(x, dim)
    m, n = math.prod(osh), math.prod(rsh)
    if not product and n == 0 and math.isinf(p):
        raise RuntimeError(
            "linalg.vector_norm cannot compute an infinity norm on an empty reduction"
        )
    shape = (
        tuple(1 if i in dims else x.shape[i] for i in range(x.ndim)) if keepdim else osh
    )
    y = torch.empty(shape, dtype=x.dtype, device=x.device)
    nz = torch.empty((m,), dtype=torch.float32, device=x.device)
    zeros = torch.empty((m,), dtype=torch.int32, device=x.device)
    if m and not n:
        with torch_device_fn.device(x.device):
            _empty_value[(triton.cdiv(m, 256),)](y, nz, zeros, m, product, 256)
        return y, nz, zeros
    if m:
        chunks = max(1, triton.cdiv(n, 2048))
        v = torch.empty((m, chunks), dtype=torch.float32, device=x.device)
        z = torch.empty((m, chunks), dtype=torch.int32, device=x.device)
        with torch_device_fn.device(x.device):
            _partials[(m, chunks)](
                x,
                v,
                z,
                n,
                chunks,
                tuple(x.shape),
                tuple(x.stride()),
                osh,
                ostr,
                rsh,
                rstr,
                product,
                p,
                2048,
                enable_fp_fusion=False,
            )
            _finish[(m,)](
                v,
                z,
                y,
                nz,
                zeros,
                chunks,
                product,
                p,
                triton.next_power_of_2(chunks),
                enable_fp_fusion=False,
            )
    return y, nz, zeros


@triton.jit
def _gradient(
    X,
    G,
    Y,
    NONZERO,
    ZEROS,
    O,
    COUNT: tl.constexpr,
    SHAPE: tl.constexpr,
    XS: tl.constexpr,
    GS: tl.constexpr,
    OUTER: tl.constexpr,
    PRODUCT: tl.constexpr,
    P: tl.constexpr,
    TIES,
    B: tl.constexpr,
):
    i = tl.program_id(0) * B + tl.arange(0, B)
    remaining = i
    xo = tl.full((B,), 0, tl.int64)
    go = tl.full((B,), 0, tl.int64)
    row = tl.full((B,), 0, tl.int64)
    scale = 1
    for d in tl.static_range(len(SHAPE) - 1, -1, -1):
        coordinate = remaining % SHAPE[d]
        remaining //= SHAPE[d]
        xo += coordinate * XS[d]
        go += coordinate * GS[d]
        if OUTER[d]:
            row += coordinate * scale
            scale *= SHAPE[d]
    dtype: tl.constexpr = X.dtype.element_ty
    x = tl.load(X + xo, i < COUNT, other=0).to(tl.float32)
    g = tl.load(G + go, i < COUNT, other=0).to(tl.float32)
    y = tl.load(Y + row, i < COUNT, other=0).to(tl.float32)
    if PRODUCT:
        nz = tl.load(NONZERO + row, i < COUNT, other=1).to(dtype).to(tl.float32)
        zeros = tl.load(ZEROS + row, i < COUNT, other=0)
        ratio = (y / x).to(dtype).to(tl.float32)
        ordinary = g * ratio
        result = tl.where(
            zeros == 0, ordinary, tl.where((zeros == 1) & (x == 0), g * nz, 0)
        )
        if len(SHAPE) == 0:
            result = g
    else:
        sign = tl.where(x > 0, 1.0, tl.where(x < 0, -1.0, 0.0))
        if P == 0:
            result = tl.full((B,), 0, tl.float32)
        elif P == 1:
            result = g * sign
        elif P == float("inf") or P == -float("inf"):
            ties = tl.load(TIES + row, i < COUNT, other=1)
            result = tl.where(tl.abs(x) == y, sign * g / ties, 0)
        elif P == 2:
            ratio = (x / y).to(dtype).to(tl.float32)
            result = g * tl.where(y == 0, 0, ratio)
        elif P < 1:
            power = libdevice.pow(tl.abs(x), P - 1.0).to(dtype).to(tl.float32)
            power = tl.where(x == 0, 0, power)
            first = (sign * power).to(dtype).to(tl.float32)
            second = (first * g).to(dtype).to(tl.float32)
            norm_power = libdevice.pow(y, 1.0 - P).to(dtype).to(tl.float32)
            result = second * norm_power
        else:
            if P < 2:
                power = libdevice.pow(tl.abs(x), P - 1.0).to(dtype).to(tl.float32)
                numerator = (sign * power).to(dtype).to(tl.float32)
            else:
                power = libdevice.pow(tl.abs(x), P - 2.0).to(dtype).to(tl.float32)
                numerator = (x * power).to(dtype).to(tl.float32)
            denom = libdevice.pow(y, P - 1.0).to(dtype).to(tl.float32)
            factor = (g / denom).to(dtype).to(tl.float32)
            result = numerator * tl.where(y == 0, 0, factor)
    tl.store(O + i, result, i < COUNT)


@triton.jit
def _count_ties(
    X,
    Y,
    T,
    N: tl.constexpr,
    OSH: tl.constexpr,
    OSTR: tl.constexpr,
    RSH: tl.constexpr,
    RSTR: tl.constexpr,
    B: tl.constexpr,
):
    row = tl.program_id(0)
    value = tl.load(Y + row).to(tl.float32)
    count = tl.full((), 0, tl.int32)
    for start in range(tl.cdiv(N, B)):
        col = start * B + tl.arange(0, B)
        off = _offset(row, OSH, OSTR) + _offset(col, RSH, RSTR)
        x = tl.load(X + off, col < N, other=0).to(tl.float32)
        count += tl.sum(((col < N) & (tl.abs(x) == value)).to(tl.int32), 0)
    tl.store(T + row, count)


def reduction_gradient(x, g, y, nz, zeros, dim, keepdim, *, product=False, p=2):
    dims, outer, osh, rsh, ostr, rstr = reduction_plan(x, dim)
    if not keepdim:
        for d in sorted(dims):
            g = g.unsqueeze(d)
    g = g.expand(x.shape)
    out = torch.empty(x.shape, dtype=x.dtype, device=x.device)
    if product:
        if x.ndim == 0:
            return g
        if x.numel():
            prefix = torch.empty(x.shape, dtype=x.dtype, device=x.device)
            with torch_device_fn.device(x.device):
                split = min(65535, max(1, triton.cdiv(math.prod(rsh), 1024)))
                _product_gradient[(math.prod(osh), split)](
                    x,
                    g,
                    y,
                    zeros,
                    prefix,
                    out,
                    math.prod(rsh),
                    osh,
                    rsh,
                    tuple(x.stride(i) for i in outer),
                    tuple(x.stride(i) for i in dims),
                    tuple(g.stride(i) for i in outer),
                    tuple(out.stride(i) for i in outer),
                    tuple(out.stride(i) for i in dims),
                    math.prod(osh),
                    triton.next_power_of_2(math.prod(osh)),
                    dim is None,
                    256,
                    split,
                    enable_fp_fusion=False,
                )
        return out
    if x.numel():
        ties = zeros
        with torch_device_fn.device(x.device):
            if not product and math.isinf(p):
                ties = torch.empty(
                    (math.prod(osh),), dtype=torch.int32, device=x.device
                )
                _count_ties[(math.prod(osh),)](
                    x, y, ties, math.prod(rsh), osh, ostr, rsh, rstr, 1024
                )
            _gradient[(triton.cdiv(x.numel(), 256),)](
                x,
                g,
                y,
                nz,
                zeros,
                out,
                x.numel(),
                tuple(x.shape),
                tuple(x.stride()),
                tuple(g.stride()),
                tuple(i in outer for i in range(x.ndim)),
                product,
                p,
                ties,
                256,
                enable_fp_fusion=False,
            )
    return out


@triton.jit
def _product_gradient(
    X,
    G,
    Y,
    ZEROS,
    PREFIX,
    OUT,
    N: tl.constexpr,
    OSH: tl.constexpr,
    RSH: tl.constexpr,
    XOS: tl.constexpr,
    XRS: tl.constexpr,
    GOS: tl.constexpr,
    OOS: tl.constexpr,
    ORS: tl.constexpr,
    ROWS: tl.constexpr,
    BR: tl.constexpr,
    GLOBAL: tl.constexpr,
    B: tl.constexpr,
    SPLIT: tl.constexpr,
):
    row = tl.program_id(0)
    xb = _offset(row, OSH, XOS)
    ob = _offset(row, OSH, OOS)
    gb = _offset(row, OSH, GOS)
    g = tl.load(G + gb).to(tl.float32)
    y = tl.load(Y + row).to(tl.float32)
    zeros = tl.load(ZEROS + row)
    dtype: tl.constexpr = X.dtype.element_ty
    index = tl.arange(0, B)
    rows = tl.arange(0, BR)
    any_zeros = tl.sum(tl.load(ZEROS + rows, rows < ROWS, other=0), 0) > 0
    if not any_zeros:
        for chunk in range(tl.cdiv(N, B * SPLIT)):
            col = (chunk * SPLIT + tl.program_id(1)) * B + index
            x = tl.load(X + xb + _offset(col, RSH, XRS), col < N, other=1).to(
                tl.float32
            )
            ratio = (y / x).to(dtype).to(tl.float32)
            tl.store(OUT + ob + _offset(col, RSH, ORS), g * ratio, col < N)
    elif tl.program_id(1) == 0:
        if GLOBAL and zeros > 1:
            for chunk in range(tl.cdiv(N, B)):
                col = chunk * B + index
                tl.store(OUT + ob + _offset(col, RSH, ORS), 0, col < N)
        else:
            carry = tl.full((), 1, tl.float32)
            for chunk in range(tl.cdiv(N, B)):
                col = chunk * B + index
                x = tl.load(X + xb + _offset(col, RSH, XRS), col < N, other=1).to(
                    tl.float32
                )
                inclusive = tl.associative_scan(x, 0, _multiply)
                exclusive = tl.gather(inclusive, tl.maximum(index - 1, 0), 0)
                exclusive = tl.where(index == 0, 1, exclusive)
                tl.store(
                    PREFIX + ob + _offset(col, RSH, ORS), carry * exclusive, col < N
                )
                carry = carry * tl.reduce(x, 0, _multiply)
            carry = tl.full((), 1, tl.float32)
            for chunk in range(tl.cdiv(N, B)):
                col = (tl.cdiv(N, B) - 1 - chunk) * B + index
                x = tl.load(X + xb + _offset(col, RSH, XRS), col < N, other=1).to(
                    tl.float32
                )
                inclusive = tl.associative_scan(x, 0, _multiply, reverse=True)
                exclusive = tl.gather(inclusive, tl.minimum(index + 1, B - 1), 0)
                exclusive = tl.where(index == B - 1, 1, exclusive)
                right = (carry * exclusive).to(dtype).to(tl.float32)
                left = tl.load(
                    PREFIX + ob + _offset(col, RSH, ORS), col < N, other=1
                ).to(tl.float32)
                derivative = (left * right).to(dtype).to(tl.float32)
                tl.store(OUT + ob + _offset(col, RSH, ORS), g * derivative, col < N)
                carry = carry * tl.reduce(x, 0, _multiply)
