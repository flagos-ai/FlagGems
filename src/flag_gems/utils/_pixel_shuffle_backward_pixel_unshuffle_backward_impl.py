        h = i // (W // R) % (H // R)
        c = i // ((W // R) * (H // R)) % (C * R * R)
        batch = i // ((W // R) * (H // R) * C * R * R)
        source = (
            ((batch * C + c // (R * R)) * H + h * R + c // R % R) * W + w * R + c % R
        )
