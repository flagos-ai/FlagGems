def scatter_reduction(grad, self, dim, index, src, reduce, include_self, result):
    if reduce not in ("sum", "mean", "prod", "amax", "amin"):
        raise ValueError("unsupported scatter reducer")
    if index.shape != src.shape:
        raise RuntimeError("scatter backward requires src.shape == index.shape")
    dim %= self.ndim
    dx = torch.empty(self.shape, dtype=self.dtype, device=self.device)
    ds = torch.empty(src.shape, dtype=src.dtype, device=src.device)
    wide = (
        reduce == "prod"
        and self.dtype in (torch.float16, torch.bfloat16)
        and (src.shape[dim] >= 32)
    )
    aux = torch.empty(
        (3, self.numel()),
        dtype=torch.float32 if wide else self.dtype,
        device=self.device,
    )
    if self.numel():
        reduce_stats[self.numel(),](
            grad,
            self,
            index,
            src,
            result,
            dx,
            aux,
            self.numel(),
            tuple(self.shape),
            tuple(src.shape),
            grad.stride(),
            self.stride(),
            index.stride(),
            src.stride(),
            result.stride(),
            dim,
            reduce,
            include_self,
            wide,
            min(256, triton.next_power_of_2(max(1, src.shape[dim]))),
            enable_fp_fusion=False,
        )
    if src.numel():
        reduce_src[triton.cdiv(src.numel(), 256),](
            index,
            src,
            result,
            aux,
            ds,
            src.numel(),
            self.numel(),
            tuple(self.shape),
            tuple(src.shape),
            index.stride(),
            src.stride(),
            result.stride(),
            contiguous_strides(self.shape),
            dim,
            reduce,
            256,
            enable_fp_fusion=False,
        )
    return (dx, ds)
