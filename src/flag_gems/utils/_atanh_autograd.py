def strided_offset(index, shape: tl.constexpr, strides: tl.constexpr):
    offset = tl.full(index.shape, 0, tl.int64)
    for axis in tl.static_range(len(shape) - 1, -1, -1):
        offset += (index % shape[axis]) * strides[axis]
        index //= shape[axis]
    return offset


