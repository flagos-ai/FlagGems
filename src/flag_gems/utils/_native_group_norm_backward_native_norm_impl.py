@triton.jit
def _channel_sums(
    X,
    DY,
    DS,
    DB,
    C: tl.constexpr,
    HW: tl.constexpr,
    SH: tl.constexpr,
    XS: tl.constexpr,
    GS: tl.constexpr,
    HALF_PRODUCT: tl.constexpr,
    B: tl.constexpr,
):
    nc = tl.program_id(0)
    dxs = tl.full((B,), 0, tl.float32)
    dys = tl.full((B,), 0, tl.float32)
    for start in range(tl.cdiv(HW, B)):
        s = start * B + tl.arange(0, B)
        logical = nc * HW + s
        x = tl.load(X + linear_offset(logical, SH, XS), s < HW, other=0).to(tl.float32)
        g = tl.load(DY + linear_offset(logical, SH, GS), s < HW, other=0).to(tl.float32)
        product = x * g
        if HALF_PRODUCT:
            product = product.to(X.dtype.element_ty).to(tl.float32)
        dxs += product
        dys += g
    tl.store(DS + nc, tl.sum(dxs, 0))
    tl.store(DB + nc, tl.sum(dys, 0))


