    if HAS_W:
        w = tl.load(W + ch * WS, i < D, other=0).to(tl.float32)
        ds = ds * w
        db = db * w
    sum1, sum2 = tl.sum(ds, 0), tl.sum(db, 0)
    mean = tl.load(MEAN + n * MS[0] + group * MS[1]).to(tl.float32)
    rstd = tl.load(RSTD + n * RS[0] + group * RS[1]).to(tl.float32)
