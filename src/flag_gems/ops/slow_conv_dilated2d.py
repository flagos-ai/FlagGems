"""Triton implementation of ``aten::slow_conv_dilated2d`` (forward).

A direct, im2col-free 2-D (dilated) convolution.  The output plane is
flattened to ``p = oh * W_out + ow`` and every program owns a
``(BLOCK_CO, BLOCK_P)`` tile of ``(out_channel, output_position)``.  The
contraction axis ``K = C_in * kH * kW`` is walked in chunks of ``BK`` rows,
each chunk covering ``BK`` consecutive ``(ci, kh, kw)`` triples, so one
``tl.dot`` consumes a rectangular tile.

Semantics (``weight`` is the plain conv layout ``(C_out, C_in, kH, kW)``, no
kernel flip):

    out[n, co, oh, ow] = bias[co]
        + sum_{ci, kh, kw} self[n, ci,
                                 oh*SH + kh*DH - PH,
                                 ow*SW + kw*DW - PW] * weight[co, ci, kh, kw]

where taps that fall outside the input contribute zero.  ``self`` may be 4-D
``(N, C_in, H, W)`` or unbatched 3-D ``(C_in, H, W)``; the output rank follows
the input rank.  ``stride``, ``padding``, ``dilation`` and ``kernel_size``
accept an int (broadcast to both spatial dims) or a 2-element sequence, and
negative padding (which shrinks the output) is accepted, as in ATen.

Precision: fp16/bf16 use the native tensor-core ``tl.dot`` with fp32
accumulation; fp32 uses an IEEE ``tl.dot`` for 1x1 and wide (>= 10 taps)
kernels and the ``tf32x3`` emulation for the 3x3 class (error ~1e-6, inside the
1e-4 fp32 tolerance).  ``tl.dot`` has no fp64 form, so fp64 falls back to an
FMA kernel that accumulates in true fp64.
"""

