def _pow2(value, low, high):
    value = int(value)
    if value < 1:
        value = 1
    return max(low, min(high, triton.next_power_of_2(value)))


def _tap_tile(is_fp32, c_out, plane, k_tot):
    """Pick (BLOCK_CO, BLOCK_M, BLOCK_K, num_warps, ab_tiles) for the general path.

    The choice is fixed by tile sweeps measured on this target.  Both dot
    operand orders are numerically identical, so choosing between them is
    purely a performance question and the winner is a shape property.
    """
    block_co = _pow2(c_out, _MIN_TILE, 128)
    k_lim = max(_MIN_TILE, triton.next_power_of_2(k_tot))
    if is_fp32:
        # fp32 runs on the FFMA pipe (no tensor-core dot): the 128-wide channel
        # tiles want 8 warps, the 64-wide ones 4, and a 32-wide K step is best
        # except for very large K.
        ab_tiles = k_tot < 1536
        warps = 8 if block_co == 128 else 4
        block_k = min(64 if k_tot >= 3072 else 32, k_lim)
        return block_co, 128, block_k, warps, ab_tiles
    # Low precision (tensor cores): the wide (128, 64) tile wins only on large
    # planes; everywhere else the smaller (64, 32) tile is better or equal.
    if plane > _WIDE_PLANE:
        block_m, block_k = 128, (64 if k_tot % 64 == 0 else 32)
    else:
        block_m, block_k = 64, 32
    return block_co, block_m, min(block_k, k_lim), 4, True


