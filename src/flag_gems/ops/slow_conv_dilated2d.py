@triton.jit
def _conv2d_dot(
    x_ptr,
    w_ptr,
    b_ptr,
    out_ptr,
    CIN,
    H,
    W,
    COUT,
    HO,
    WO,
    SH,
    SW,
    PH,
    PW,
    DH,
    DW,
    P_TOTAL,
    K,
    HAS_BIAS: tl.constexpr,
    PREC: tl.constexpr,
    KH: tl.constexpr,
    KW: tl.constexpr,
    BLOCK_CO: tl.constexpr,
    BLOCK_P: tl.constexpr,
    BK: tl.constexpr,
):
    # Implicit im2col + tl.dot: reduction axis k = ci * (KH * KW) + kh * KW + kw.
    pid = tl.program_id(0)
    num_p = tl.cdiv(P_TOTAL, BLOCK_P)
    num_cob = tl.cdiv(COUT, BLOCK_CO)

    p_blk = pid % num_p
    co_blk = (pid // num_p) % num_cob
    n = pid // (num_p * num_cob)

    p = p_blk * BLOCK_P + tl.arange(0, BLOCK_P)
    co = co_blk * BLOCK_CO + tl.arange(0, BLOCK_CO)
    pmask = p < P_TOTAL
    comask = co < COUT

    oh = p // WO
    ow = p % WO
    ohs = oh * SH
    ows = ow * SW

    acc = tl.zeros((BLOCK_CO, BLOCK_P), dtype=tl.float32)

    HW = H * W
    KHKW = KH * KW
    x_base = x_ptr + n * CIN * HW

    for k0 in range(0, K, BK):
        k = k0 + tl.arange(0, BK)
        km = k < K
        ci = k // KHKW
        rem = k - ci * KHKW
        kh = rem // KW
        kw = rem - kh * KW
        ih = ohs[None, :] + kh[:, None] * DH - PH
        iw = ows[None, :] + kw[:, None] * DW - PW
        inb = pmask[None, :] & km[:, None] & (ih >= 0) & (ih < H) & (iw >= 0) & (iw < W)
        x_off = ci[:, None] * HW + ih * W + iw
        x = tl.load(x_base + x_off, mask=inb, other=0.0)
        wt = tl.load(
            w_ptr + co[:, None] * K + k[None, :],
            mask=comask[:, None] & km[None, :],
            other=0.0,
        )
        if PREC == 0:
            acc = tl.dot(wt, x, acc, input_precision="ieee")
        elif PREC == 1:
            acc = tl.dot(wt, x, acc, input_precision="tf32x3")
        else:
            acc = tl.dot(wt, x, acc)

    if HAS_BIAS:
        bias = tl.load(b_ptr + co, mask=comask, other=0.0)
        acc += bias[:, None]

    out_base = out_ptr + n * (COUT * P_TOTAL) + co[:, None] * P_TOTAL
    omask = comask[:, None] & pmask[None, :]
    tl.store(out_base + p[None, :], acc.to(out_ptr.dtype.element_ty), mask=omask)


@triton.jit
def _conv2d_fma(
    x_ptr,
    w_ptr,
    b_ptr,
    out_ptr,
    CIN,
    H,
    W,
    COUT,
    HO,
    WO,
    SH,
    SW,
    PH,
    PW,
    DH,
    DW,
    P_TOTAL,
    HAS_BIAS: tl.constexpr,
    KH: tl.constexpr,
    KW: tl.constexpr,
    BLOCK_CO: tl.constexpr,
    BLOCK_P: tl.constexpr,
):
    # Direct FMA accumulation in the element type: the fp64 lane, where
    # ``tl.dot`` has no form.
    pid = tl.program_id(0)
    num_p = tl.cdiv(P_TOTAL, BLOCK_P)
    num_cob = tl.cdiv(COUT, BLOCK_CO)

    p_blk = pid % num_p
    co_blk = (pid // num_p) % num_cob
    n = pid // (num_p * num_cob)

    p = p_blk * BLOCK_P + tl.arange(0, BLOCK_P)
    co = co_blk * BLOCK_CO + tl.arange(0, BLOCK_CO)
    pmask = p < P_TOTAL
    comask = co < COUT

    oh = p // WO
    ow = p % WO
    ohs = oh * SH
    ows = ow * SW

    acc = tl.zeros((BLOCK_CO, BLOCK_P), dtype=out_ptr.dtype.element_ty)

    HW = H * W
    KHKW = KH * KW
    x_base = x_ptr + n * CIN * HW
    w_base = w_ptr + co[:, None] * (CIN * KHKW)

    for ci in range(CIN):
        xc = x_base + ci * HW
        wc = w_base + ci * KHKW
        for kh in tl.static_range(KH):
            ih = ohs - PH + kh * DH
            row_ok = (ih >= 0) & (ih < H)
            a_off = ih * W
            for kw in tl.static_range(KW):
                iw = ows - PW + kw * DW
                inb = pmask & row_ok & (iw >= 0) & (iw < W)
                x = tl.load(xc + a_off + iw, mask=inb, other=0.0)
                w = tl.load(wc + kh * KW + kw, mask=comask[:, None], other=0.0)
                acc += w * x[None, :]

    if HAS_BIAS:
        bias = tl.load(b_ptr + co, mask=comask, other=0.0)
        acc += bias[:, None]

    out_base = out_ptr + n * (COUT * P_TOTAL) + co[:, None] * P_TOTAL
    omask = comask[:, None] & pmask[None, :]
    tl.store(out_base + p[None, :], acc, mask=omask)


def _pick_config(COUT, P_TOTAL, taps, dtype):
    """Workload-class ``(BLOCK_CO, BLOCK_P, BK, PREC, num_warps, num_stages)``.

    ``tl.dot`` needs every dimension >= 16, so the power-of-two caps never go
    below 16 even when ``C_out`` or the output plane is smaller than that; the
    excess lanes are masked out.
    """
    p2 = triton.next_power_of_2
    if dtype == torch.float64:
        # FMA kernel: tile shape only (BK/PREC unused).
        if taps == 1:
            bc, bp, warps = 64, 64, 4
        elif taps <= 9:
            bc, bp, warps = 16, 256, 4
        else:
            bc, bp, warps = 64, 128, 8
        return (
            max(16, min(bc, p2(COUT))),
            max(16, min(bp, p2(P_TOTAL))),
            16,
            0,
            warps,
            2,
        )
    if dtype in (torch.float16, torch.bfloat16):
        bc, bp, bk, prec, warps, stages = 64, 64, 64, 2, 4, 2
    elif taps == 1:
        bc, bp, bk, prec, warps, stages = 64, 64, 64, 0, 4, 2
    elif taps >= 10:
        bc, bp, bk, prec, warps, stages = 64, 128, 64, 0, 8, 3
    else:
        # 3x3 class: three-pass tf32 dot, ~1e-6 relative error.
        bc, bp, bk, prec, warps, stages = 32, 64, 32, 1, 4, 3
    return (
        max(16, min(bc, p2(COUT))),
        max(16, min(bp, p2(P_TOTAL))),
        bk,
        prec,
        warps,
        stages,
    )


def _fill_bias_or_zero(out, bias):
    """Pre-fill ``out`` the way native pre-fills its buffer: bias broadcast
    over the spatial dims, or zeros when there is no bias."""
    if out.numel() == 0:
        return
    if bias is None:
        out.zero_()
    else:
        bias_view = bias.reshape(1, -1, 1, 1)
        out.copy_(bias_view.expand_as(out))


def _slow_conv_dilated2d_impl(
    self, weight, kernel_size, bias, stride, padding, dilation, out
):
    kernel_size = _as_pair(kernel_size, "kernel sizes")
    stride = _as_pair(stride, "strides")
    padding = _as_pair(padding, "pads")
    dilation = _as_pair(dilation, "dilations")

    for name, values in (
        ("kernel size", kernel_size),
        ("stride", stride),
        ("dilation", dilation),
    ):
        if not all(v > 0 for v in values):
            raise RuntimeError(
                f"{name} should be greater than zero, but got {list(values)}"
            )

    if not torch.is_tensor(self) or not torch.is_tensor(weight):
        raise TypeError("slow_conv_dilated2d expects tensor inputs")
    if self.dim() not in (3, 4):
        raise RuntimeError(
            f"input must be 3D or 4D tensor but got {self.dim()}D tensor"
        )
    if not self.is_floating_point():
        raise RuntimeError(
            "slow_conv_dilated2d not implemented for non-floating point dtypes"
        )
    supported = (torch.float32, torch.float16, torch.bfloat16, torch.float64)
    if self.dtype not in supported:
        raise RuntimeError(f"slow_conv_dilated2d: unsupported dtype {self.dtype}")

    # Native materialises strided operands and unsqueezes the unbatched 3-D
    # input; the kernel below indexes both with plain contiguous offsets.
    unbatched = self.dim() == 3
    inp = self if self.is_contiguous() else self.contiguous()
    if unbatched:
        inp = inp.unsqueeze(0)

    N, CIN, H, W = inp.shape
    KH, KW = kernel_size
    SH, SW = stride
    PH, PW = padding
    DH, DW = dilation

    HO = (H + 2 * PH - DH * (KH - 1) - 1) // SH + 1
    WO = (W + 2 * PW - DW * (KW - 1) - 1) // SW + 1

    if HO < 0 or WO < 0:
        raise RuntimeError(
            f"calculated output size {HO} {WO} is too small "
            "(all sizes must be non-negative)"
        )
    if weight.dim() != 4:
        raise RuntimeError(f"weight must be 4D tensor but got {weight.dim()}D tensor")
    COUT = weight.shape[0]
    if CIN != weight.shape[1]:
        raise RuntimeError(
            f"Need input of dimension 4 and input.size[1] == {weight.shape[1]} "
            f"but got input to be of shape {list(inp.shape)}"
        )
    if bias is not None:
        if not torch.is_tensor(bias):
            raise TypeError("slow_conv_dilated2d: bias must be a Tensor or None")
        if bias.shape != (COUT,):
            raise RuntimeError(
                f"bias must be 1D tensor of length {COUT} "
                f"but got shape {list(bias.shape)}"
            )

    shape = (N, COUT, HO, WO)
    expected = shape[1:] if unbatched else shape
    wrote_out = False
    if out is not None:
        if out.dtype != inp.dtype or out.device != inp.device:
            raise RuntimeError("out dtype and device must match the input")
        if tuple(out.shape) != expected:
            # ATen resizes a mismatched out buffer (deprecated path, still the
            # observable contract on 2.8.0a0); keep the same behaviour.
            out.resize_(expected)
        if out.is_contiguous():
            target = out.unsqueeze(0) if unbatched else out
            wrote_out = True
        else:
            target = torch.empty(shape, dtype=inp.dtype, device=inp.device)
    else:
        target = torch.empty(shape, dtype=inp.dtype, device=inp.device)

    P_TOTAL = HO * WO
    weight_c = weight if weight.is_contiguous() else weight.contiguous()
    bias_c = None
    if bias is not None:
        bias_c = bias if bias.is_contiguous() else bias.contiguous()

    if P_TOTAL == 0 or COUT == 0 or N == 0:
        pass
    elif CIN == 0:
        # Empty contraction: the output is exactly the pre-filled buffer.
        _fill_bias_or_zero(target, bias_c)
    else:
        _launch(
            inp,
            weight_c,
            bias_c,
            target,
            N,
            CIN,
            H,
            W,
            COUT,
            (KH, KW),
            (SH, SW),
            (PH, PW),
            (DH, DW),
            HO,
            WO,
            P_TOTAL,
        )

    if out is not None:
        if not wrote_out:
            out.copy_(target[0] if unbatched else target)
        return out
    return target[0] if unbatched else target


def _launch(
    inp,
    weight,
    bias,
    out,
    N,
    CIN,
    H,
    W,
    COUT,
    kernel_size,
    stride,
    padding,
    dilation,
    HO,
    WO,
    P_TOTAL,
):
    KH, KW = kernel_size
    SH, SW = stride
    PH, PW = padding
    DH, DW = dilation
    dtype = inp.dtype
    taps = KH * KW
    K = CIN * taps

    BLOCK_CO, BLOCK_P, BK, prec, num_warps, num_stages = _pick_config(
        COUT, P_TOTAL, taps, dtype
    )
    grid = (N * triton.cdiv(COUT, BLOCK_CO) * triton.cdiv(P_TOTAL, BLOCK_P),)
    with torch_device_fn.device(inp.device):
        if dtype == torch.float64:
            _conv2d_fma[grid](
                inp,
                weight,
                bias if bias is not None else weight,
                out,
                CIN,
                H,
                W,
                COUT,
                HO,
                WO,
                SH,
                SW,
                PH,
                PW,
                DH,
                DW,
                P_TOTAL,
                HAS_BIAS=bias is not None,
                KH=KH,
                KW=KW,
                BLOCK_CO=BLOCK_CO,
                BLOCK_P=BLOCK_P,
                num_warps=num_warps,
            )
        else:
            _conv2d_dot[grid](
                inp,
                weight,
                bias if bias is not None else weight,
                out,
                CIN,
                H,
                W,
                COUT,
                HO,
                WO,
                SH,
                SW,
                PH,
                PW,
                DH,
                DW,
                P_TOTAL,
                K,
                HAS_BIAS=bias is not None,
                PREC=prec,
                KH=KH,
                KW=KW,
                BLOCK_CO=BLOCK_CO,
                BLOCK_P=BLOCK_P,
                BK=BK,
                num_warps=num_warps,
                num_stages=num_stages,
            )


