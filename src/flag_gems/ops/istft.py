# One Triton program handles one (channel, frame) block: it loads the
# post-FFT frame, multiplies by the window, and scatter-adds the samples into
# the output signal with atomics. A second kernel builds the squared-window
# envelope the same way (deterministic, no atomics needed since it only
# depends on the window), and a final elementwise kernel divides the signal by
# the envelope. This fuses torch's mul + unfold_backward + slice + div chain.
@libentry()
@triton.jit
def istft_overlap_add_kernel(
    frames_ptr,  # (channel, n_frames, n_fft) real frames after windowing
    signal_ptr,  # (channel, expected_len) accumulated output signal
    window_ptr,  # (n_fft,)
    n_frames,
    n_fft,
    hop_length,
    signal_stride0,
    signal_stride1,
    OUT_FFT: tl.constexpr,
    BLOCK: tl.constexpr,
):
    pid = tl.program_id(0)
    frame_idx = pid % n_frames
    channel = pid // n_frames

    offs = tl.arange(0, BLOCK)
    mask = offs < n_fft
    base = (channel * n_frames + frame_idx) * OUT_FFT
    frame = tl.load(frames_ptr + base + offs, mask=mask, other=0.0)
    win = tl.load(window_ptr + offs, mask=mask, other=0.0)
    frame = frame * win

    sample = frame_idx * hop_length + offs
    out_base = channel * signal_stride0
    tl.atomic_add(signal_ptr + out_base + sample * signal_stride1, frame, mask=mask)


@libentry()
@triton.jit
def istft_envelope_kernel(
    window_ptr,  # (n_fft,)
    envelope_ptr,  # (out_len)
    n_frames,
    n_fft,
    hop_length,
    out_offset,  # envelope starts at this index of the padded signal
    out_len,
    BLOCK: tl.constexpr,
):
    # Each program accumulates the squared-window contributions landing on a
    # BLOCK of output samples. Only frames covering [block_start, block_end)
    # contribute, so the walk runs from the first to the last covering frame
    # instead of all n_frames.
    pid = tl.program_id(0)
    offs = pid * BLOCK + tl.arange(0, BLOCK)
    mask = offs < out_len
    # Output sample t corresponds to padded-signal index t + out_offset.
    pad_idx = offs + out_offset
    # Accumulate in the window dtype so fp64 inputs keep full precision.
    acc = tl.zeros([BLOCK], dtype=window_ptr.dtype.element_ty)
    # Frame f covers padded samples [f*hop, f*hop + n_fft). The per-lane first
    # frame is (pad_idx - n_fft + 1) / hop clamped to zero; a block shares a
    # narrow frame range because BLOCK bounds are checked per lane.
    first_f = tl.maximum(pad_idx - n_fft + 1, 0) // hop_length
    f_start = tl.min(first_f, axis=0)
    f_end = tl.minimum(tl.max(pad_idx, axis=0) // hop_length + 1, n_frames)
    for fi in range(f_start, f_end):
        lo = fi * hop_length
        hi = lo + n_fft
        in_frame = (pad_idx >= lo) & (pad_idx < hi) & mask
        local = pad_idx - lo
        w = tl.load(window_ptr + local, mask=in_frame, other=0.0)
        acc += tl.where(in_frame, (w * w).to(acc.dtype), 0.0)
    tl.store(envelope_ptr + offs, acc, mask=mask)


