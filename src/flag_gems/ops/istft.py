def _validate_istft_arguments(
    self: torch.Tensor,
    n_fft: int,
    hop_length: int,
    win_length: int,
    window: Optional[torch.Tensor],
    onesided: bool,
    length: Optional[int],
    return_complex: bool,
) -> None:
    if self.dtype != torch.complex64:
        raise RuntimeError("istft currently supports complex64 input only")
    if self.ndim not in (2, 3):
        raise RuntimeError("istft expected a 2D or 3D input tensor")
    if self.device.type != flag_gems.device:
        raise RuntimeError(
            f"istft expected input on {flag_gems.device}, but got {self.device.type}"
        )
    if n_fft <= 0 or n_fft > 1024 or n_fft & (n_fft - 1):
        raise RuntimeError("n_fft must be a power of two no larger than 1024")
    if not 0 < hop_length <= win_length:
        raise RuntimeError("expected 0 < hop_length <= win_length")
    if not 0 < win_length <= n_fft:
        raise RuntimeError("expected 0 < win_length <= n_fft")
    if length is not None and length < 0:
        raise RuntimeError("expected length to be non-negative")
    if self.shape[-1] == 0:
        raise RuntimeError("istft expected at least one frame")

    expected_freq = n_fft // 2 + 1 if onesided else n_fft
    if self.shape[-2] != expected_freq:
        raise RuntimeError(
            f"expected the frequency dimension to be {expected_freq}, "
            f"but got {self.shape[-2]}"
        )
    if return_complex and onesided:
        raise RuntimeError("Cannot have onesided output if window or input is complex")

    if window is not None:
        if window.device != self.device:
            raise RuntimeError("window and input must be on the same device")
        if window.dtype != self.real.dtype:
            raise RuntimeError("window and input must have the same dtype")
        if window.ndim != 1 or window.numel() != win_length:
            raise RuntimeError(f"expected a 1D window of length {win_length}")


