# entry point
# ---------------------------------------------------------------------------
def greater_(A, B):
    logger.debug("GEMS GREATER_")
    if isinstance(B, torch.Tensor):
        return _run_tensor(A, B)
    if isinstance(B, (bool, int, float)):
        return _run_scalar(A, B)
    raise TypeError("greater_(): argument 'other' must be a Tensor or a Number")
