@triton.jit
def gather_kernel(
    G,
    I,
    O,
    N: tl.constexpr,
    SHAPE: tl.constexpr,
    IS: tl.constexpr,
    GS: tl.constexpr,
    XS: tl.constexpr,
    DIM: tl.constexpr,
    CLEAR: tl.constexpr,
    B: tl.constexpr,
):
    i = tl.program_id(0) * B + tl.arange(0, B)
    live = i < N
    coords = ()
    rem = i
    for d in tl.static_range(len(SHAPE) - 1, -1, -1):
        coords = (rem % SHAPE[d],) + coords
        rem = rem // SHAPE[d]
    index = tl.load(I + offset(i, SHAPE, IS), live, other=0).to(tl.int64)
    address = tl.full((B,), 0, tl.int64)
    for d in tl.static_range(len(SHAPE)):
        c = index if d == DIM else coords[d]
        if CLEAR:
            address += c * XS[d]
        else:
            address += c * GS[d]
    if CLEAR:
        tl.store(O + address, 0, live)
    else:
        value = tl.load(G + address, live, other=0)
        tl.store(O + i, value, live)


