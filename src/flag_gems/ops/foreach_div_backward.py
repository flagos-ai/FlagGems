"""First-order gradients of the ``_foreach_div.List`` family.

``torch.ops.aten._foreach_div_backward`` does not exist in this Torch build:
``native_functions.yaml`` has no ``_foreach_*_backward`` entry at all.  The
gradients are derived by the auto-generated ``ForeachDivBackward0`` autograd
node from the derivatives recorded for the *forward* operator
(``tools/autograd/derivatives.yaml``, ``_foreach_div.List``):

    grad_self[i]  = div_tensor_self_backward(grads[i], other[i])  = grad[i] / other[i]
    grad_other[i] = div_tensor_other_backward(grads[i], self[i], other[i])
                  = -grad[i] * ((self[i] / other[i]) / other[i])

Only the ``.List`` overload carries derivatives in this build (``.Scalar`` /
``.ScalarList`` / ``.Tensor`` divide by a constant and have no differentiable
operand besides ``self``), so this module implements exactly that overload:
paired tensor lists in, two paired gradient lists out.

The exact ATen rounding is reproduced per dtype, verified bit-exact against
``torch.autograd.grad(torch._foreach_div([x], [y]))`` on CUDA:

* ``float64``: plain ``/`` -- already correctly rounded.
* ``float32``: ``tl.math.div_rn`` for every division.  Triton's fp32 ``/``
  lowers to ``fdiv.approx`` on NVIDIA, which disagrees with ATen in a large
  fraction of elements; the round-to-nearest libdevice call matches exactly.
* ``float16`` / ``bfloat16``: each elementwise step is computed in fp32 and
  materialised back into the storage dtype before the next step, matching
  ATen's per-op opmath (``grad/other`` -> round -> ``self/other`` -> round ->
  ``(/other)`` -> round -> ``* -grad`` -> round).
* ``complex64`` / ``complex128``: the operands are split into interleaved
  real/imag pairs and each complex division follows the c10 ``operator/=``
  algorithm (ratio on the larger component, ``scl = 1/(c + d*rat)``).
  This matches the ATen result to within a few fp32 ulp per element rather
  than bit-exactly; the comparison tolerance (rtol 1.3e-6 for complex64)
  covers it.

The kernel layout follows the shared ``utils/foreach`` executor: one metadata
buffer of ``(grad, self, other, grad_self, grad_other, numel)`` pointer runs,
tensors grouped by ``(device, dtype)``, one launch per group, two stores per
element.  Unlike the single-tensor ``div_backward`` there is no broadcast form
to fall back to: the ``.List`` overload pairs equal-length lists position by
position, and ATen raises when a pair's shapes do not broadcast to a common
shape, which this wrapper reproduces.
"""

import logging
from typing import List, Sequence, Tuple

import torch
import triton
import triton.language as tl

from flag_gems.runtime import torch_device_fn
from flag_gems.utils.foreach import check_dtype_supported, check_tensor_list, tl_dtype

logger = logging.getLogger(__name__)

# Floating dtypes that can carry a gradient at all: an integer or bool tensor
# cannot require grad, so the backward never sees one as self/other.
_GRAD_DTYPES = frozenset(
    (
        torch.float16,
        torch.bfloat16,
        torch.float32,
        torch.float64,
        torch.complex64,
        torch.complex128,
    )
)

_BLOCK = 1024
_NUM_WARPS = 4


@triton.jit
def _cdiv_c10(ar, ai, br, bi):
    """c10 ``complex<T>`` division (``complex.h`` ``operator/=``).

    Follows numpy's algorithm: pick the larger denominator component, form the
    ratio against it and scale by ``1/(c + d*rat)``.  The zero/zero case yields
    the complex inf/nan the C++ code produces (``a/|c|, b/|d|``).
    """
    abs_br = tl.abs(br)
    abs_bi = tl.abs(bi)
    use_br = abs_br >= abs_bi
    rat = tl.where(use_br, bi / br, br / bi)
    scl = 1.0 / tl.where(use_br, br + bi * rat, br * rat + bi)
    real = tl.where(use_br, (ar + ai * rat) * scl, (ar * rat + ai) * scl)
    imag = tl.where(use_br, (ai - ar * rat) * scl, (ai * rat - ar) * scl)
    # The zero/zero case: ATen yields (a/|c|, b/|d|), a complex inf/nan.  The
    # scalar-lane form cannot use ``.any()``, so fold the correction into the
    # same where: when both components are zero, rat/scl are nan already and
    # the branches below take over through the mask.
    both_zero = (abs_br == 0.0) & (abs_bi == 0.0)
    safe_abs_br = tl.where(both_zero, 1.0, abs_br)
    safe_abs_bi = tl.where(both_zero, 1.0, abs_bi)
    real = tl.where(both_zero, ar / safe_abs_br, real)
    imag = tl.where(both_zero, ai / safe_abs_bi, imag)
    return real, imag


@triton.jit
def _real_backward_fp64(grad, a, b):
    """The fp64 gradient pair: plain division is already IEEE-rounded."""
    grad_self = grad / b
    grad_other = -grad * ((a / b) / b)
    return grad_self, grad_other


@triton.jit
def _real_backward(
    grad,
    a,
    b,
    dt,
):
    """The fp32-and-below gradient pair at one element.

    ``grad``, ``a``, ``b`` arrive in fp32; ``dt`` is the storage dtype the
    results must materialise into after every step.  Round-to-nearest division
    matches ATen (Triton's fp32 ``/`` lowers to ``fdiv.approx`` on NVIDIA);
    each intermediate is materialised back into the storage dtype exactly as
    ATen's per-op opmath evaluation does.
    """
    grad_self = tl.math.div_rn(grad, b).to(dt)
    ab = tl.math.div_rn(a, b).to(dt)
    ab_over_b = tl.math.div_rn(ab.to(tl.float32), b).to(dt)
    grad_other = (-grad * ab_over_b.to(tl.float32)).to(dt)
    return grad_self, grad_other


@triton.jit
def _complex_backward(ar, ai, br, bi, gr, gi):
    """The complex gradient pair at one element.

    ATen's ``div_tensor_other_backward`` evaluates
    ``-grad * ((self / other) / other).conj()``: divide ``self`` by ``other``,
    divide that by ``other`` again, conjugate the *result*, then multiply.
    Each complex step uses the c10 division/multiplication on the split
    components.
    """
    # conj(other) = (br, -bi)
    gsr, gsi = _cdiv_c10(gr, gi, br, -bi)
    # t1 = self / other
    t1r, t1i = _cdiv_c10(ar, ai, br, bi)
    # t2 = t1 / other
    t2r, t2i = _cdiv_c10(t1r, t1i, br, bi)
    # -grad * conj(t2) = (gr, gi) * (t2r, -t2i) with a negation on the outer pair:
    # real = (-gr)*t2r - (-gi)*(-t2i) = -gr*t2r - gi*t2i
    # imag = (-gr)*(-t2i) + (-gi)*t2r = gr*t2i - gi*t2r
    return gsr, gsi, -gr * t2r - gi * t2i, gr * t2i - gi * t2r


@triton.jit
def foreach_div_backward_kernel(
    meta_ptr,
    NT: tl.constexpr,
    DT: tl.constexpr,
    IS64: tl.constexpr,
    IS_COMPLEX: tl.constexpr,
    BLOCK: tl.constexpr,
):
    """One launch per ``(device, dtype)`` group, two stores per element.

    Metadata layout, all int64::

        [0,          NT)   grad_output pointers
        [NT,       2*NT)   self pointers
        [2*NT,     3*NT)   other pointers
        [3*NT,     4*NT)   grad_self pointers
        [4*NT,     5*NT)   grad_other pointers
        [5*NT,     6*NT)   element counts

    Real dtypes load each component directly.  Complex dtypes read the
    interleaved ``(real, imag, ...)`` float stream the complex tensor storage
    uses: element ``i`` occupies words ``2i`` and ``2i + 1``, so the complex
    kernel indexes by ``2 * idx`` with its own ``2 * n_elements`` mask.
    """
    t = tl.program_id(1)
    offset = tl.program_id(0) * BLOCK

    grad_raw = tl.load(meta_ptr + t)
    self_raw = tl.load(meta_ptr + NT + t)
    other_raw = tl.load(meta_ptr + 2 * NT + t)
    out_self_raw = tl.load(meta_ptr + 3 * NT + t)
    out_other_raw = tl.load(meta_ptr + 4 * NT + t)
    n_elements = tl.load(meta_ptr + 5 * NT + t)

    idx = offset + tl.arange(0, BLOCK)
    mask = idx < n_elements

    if IS_COMPLEX:
        grad_ptr = grad_raw.to(tl.pointer_type(DT))
        self_ptr = self_raw.to(tl.pointer_type(DT))
        other_ptr = other_raw.to(tl.pointer_type(DT))
        out_self_ptr = out_self_raw.to(tl.pointer_type(DT))
        out_other_ptr = out_other_raw.to(tl.pointer_type(DT))
        # DT is the *real* component type for pointer arithmetic; complex
        # tensors are contiguous streams of (real, imag) pairs.
        off2 = 2 * idx
        ar = tl.load(self_ptr + off2, mask=mask, other=0.0)
        ai = tl.load(self_ptr + off2 + 1, mask=mask, other=0.0)
        br = tl.load(other_ptr + off2, mask=mask, other=0.0)
        bi = tl.load(other_ptr + off2 + 1, mask=mask, other=0.0)
        gr = tl.load(grad_ptr + off2, mask=mask, other=0.0)
        gi = tl.load(grad_ptr + off2 + 1, mask=mask, other=0.0)
        gsr, gsi, orr, ori = _complex_backward(ar, ai, br, bi, gr, gi)
        tl.store(out_self_ptr + off2, gsr, mask=mask)
        tl.store(out_self_ptr + off2 + 1, gsi, mask=mask)
        tl.store(out_other_ptr + off2, orr, mask=mask)
        tl.store(out_other_ptr + off2 + 1, ori, mask=mask)
    else:
        grad_ptr = grad_raw.to(tl.pointer_type(DT))
        self_ptr = self_raw.to(tl.pointer_type(DT))
        other_ptr = other_raw.to(tl.pointer_type(DT))
        out_self_ptr = out_self_raw.to(tl.pointer_type(DT))
        out_other_ptr = out_other_raw.to(tl.pointer_type(DT))
        grad = tl.load(grad_ptr + idx, mask=mask, other=0.0)
        a = tl.load(self_ptr + idx, mask=mask, other=0.0)
        b = tl.load(other_ptr + idx, mask=mask, other=0.0)
        if IS64:
            grad_self, grad_other = _real_backward_fp64(
                grad.to(tl.float64), a.to(tl.float64), b.to(tl.float64)
            )
        else:
            grad_self, grad_other = _real_backward(
                grad.to(tl.float32), a.to(tl.float32), b.to(tl.float32), DT
            )
        tl.store(out_self_ptr + idx, grad_self, mask=mask)
        tl.store(out_other_ptr + idx, grad_other, mask=mask)


def _check_shapes(self_list, other_list, grad_list):
    """ATen's per-pair broadcast check for the ``.List`` overload.

    The autograd engine hands the backward a grad that already has the forward
    output shape, which is the broadcast of the pair.  A pair whose shapes do
    not broadcast therefore cannot occur from a real autograd chain, but the
    explicit entry point validates the same precondition ATen would.
    """
    for i, (a, b, g) in enumerate(zip(self_list, other_list, grad_list)):
        if g.shape != torch.broadcast_shapes(a.shape, b.shape):
            raise RuntimeError(
                f"grad_output[{i}] shape {tuple(g.shape)} does not match the "
                f"broadcast shape {tuple(torch.broadcast_shapes(a.shape, b.shape))} "
                f"of self[{i}] and other[{i}]"
            )


def _group_pairs(
    self_list: List[torch.Tensor],
    other_list: List[torch.Tensor],
    grad_list: List[torch.Tensor],
):
    """Group the three lists by ``(device, dtype)`` of the self operand.

    ATen's backward groups the saved tensors the same way the forward grouping
    did; since ``self``, ``other`` and ``grad`` share the dtype within one
    autograd node for every real chain, keying on the self operand's pair and
    validating the rest matches it keeps the fast path one launch per group.
    Mixed-dtype lists fall into separate groups, one launch each.
    """
    groups = {}
    for i in range(len(self_list)):
        a = self_list[i]
        key = (a.device, a.dtype)
        groups.setdefault(key, []).append(i)
    return groups


def _launch_group(
    indices,
    self_list,
    other_list,
    grad_list,
    device,
    dtype,
) -> None:
    """One Triton launch for one ``(device, dtype)`` group.

    The metadata is built in the *segmented* order the kernel indexes:
    first all grad pointers, then all self, other, grad_self, grad_other
    pointers, and finally the element counts -- six ``nt``-long runs for a
    group of ``nt`` tensors.
    """
    nt = len(indices)
    numels = [self_list[i].numel() for i in indices]
    max_numel = max(numels)
    grad_self_buffers: List[torch.Tensor] = [None] * nt
    grad_other_buffers: List[torch.Tensor] = [None] * nt
    grads_run: List[int] = []
    selves_run: List[int] = []
    others_run: List[int] = []
    out_selves_run: List[int] = []
    out_others_run: List[int] = []
    for pos, i in enumerate(indices):
        g = grad_list[i].contiguous()
        a = self_list[i].contiguous()
        b = other_list[i].contiguous()
        # The kernel writes through flat pointers, so the outputs must be
        # contiguous; ``empty_like`` would preserve a non-contiguous input's
        # strides and misplace the elements.
        gs = torch.empty(a.shape, dtype=a.dtype, device=a.device)
        go = torch.empty(b.shape, dtype=b.dtype, device=b.device)
        grad_self_buffers[pos] = gs
        grad_other_buffers[pos] = go
        grads_run.append(g.data_ptr())
        selves_run.append(a.data_ptr())
        others_run.append(b.data_ptr())
        out_selves_run.append(gs.data_ptr())
        out_others_run.append(go.data_ptr())
    if max_numel == 0:
        return grad_self_buffers, grad_other_buffers
    values = (
        grads_run + selves_run + others_run + out_selves_run + out_others_run + numels
    )

    meta = torch.tensor(values, dtype=torch.int64, device=device)

    block = _BLOCK
    for candidate in (1024, 2048, 4096, 8192, 16384):
        block = candidate
        if nt * ((max_numel + candidate - 1) // candidate) <= (1 << 18):
            break
    # CUDA caps gridDim.y at 65535; the offset axis must therefore stay on X
    # for huge tensors, exactly what the enlarged block guarantees (the
    # executor's ``_pick_block`` keeps ``nt * cdiv(numel, block)`` within
    # 2**18, and the largest block keeps a single-tensor run at <= 4096
    # tiles -- comfortably inside the limit even for 16M-element entries).
    grid = (triton.cdiv(max_numel, block), nt)

    is_complex = dtype.is_complex
    # The complex kernel indexes the interleaved stream with component words,
    # so its element count is the complex element count; DT is the component
    # dtype in that case.
    comp_dtype = torch.complex64 if dtype is torch.complex128 else dtype
    if is_complex:
        comp_dtype = torch.float64 if dtype is torch.complex128 else torch.float32
    else:
        comp_dtype = dtype
    kernel_dt = tl_dtype(comp_dtype)
    with torch_device_fn.device(device):
        foreach_div_backward_kernel[grid](
            meta,
            nt,
            kernel_dt,
            IS64=(comp_dtype == torch.float64),
            IS_COMPLEX=is_complex,
            BLOCK=block,
            num_warps=_NUM_WARPS,
        )
    return grad_self_buffers, grad_other_buffers


def foreach_div_backward(
    grad_output: Sequence[torch.Tensor],
    self_: Sequence[torch.Tensor],
    other: Sequence[torch.Tensor],
) -> Tuple[List[torch.Tensor], List[torch.Tensor]]:
    """Gradients of ``torch._foreach_div(self, other)`` (the ``.List`` overload).

    Args:
        grad_output: Upstream gradients, one per forward output, already shaped
            like the forward result (the pair's broadcast shape).
        self_: Numerators of the forward division, one tensor per position.
        other: Denominators, one tensor per position.

    Returns:
        Tuple ``(grad_self, grad_other)``: per-position gradients with the
        shapes and dtypes of ``self_`` and ``other``.

    The argument order follows the derivatives.yaml entry
    (``grads[i], self[i], other[i]``) with the grad list first, matching the
    ``div_backward`` entry point convention.
    """
    logger.debug("GEMS _FOREACH_DIV_BACKWARD")
    grad_list = list(check_tensor_list(grad_output))
    self_list = list(check_tensor_list(self_))
    other_list = list(check_tensor_list(other))
    if not (len(grad_list) == len(self_list) == len(other_list)):
        raise RuntimeError(
            "Tensor list must have same number of elements as grad_output, "
            f"got {len(self_list)}, {len(other_list)} and {len(grad_list)}"
        )
    for t in self_list:
        check_dtype_supported(t.dtype, _GRAD_DTYPES)

    _check_shapes(self_list, other_list, grad_list)

    grad_self_out: List[torch.Tensor] = [None] * len(self_list)
    grad_other_out: List[torch.Tensor] = [None] * len(other_list)
    for (device, dtype), indices in _group_pairs(
        self_list, other_list, grad_list
    ).items():
        gs, go = _launch_group(indices, self_list, other_list, grad_list, device, dtype)
        for pos, i in enumerate(indices):
            grad_self_out[i] = gs[pos]
            grad_other_out[i] = go[pos]
    return grad_self_out, grad_other_out


