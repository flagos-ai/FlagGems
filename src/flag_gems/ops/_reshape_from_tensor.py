@triton.jit
def _rft_high_rank_kernel(
    src,
    dst,
    n,
    SHAPE: tl.constexpr,
    STRIDES: tl.constexpr,
    BLOCK: tl.constexpr,
    KIND: tl.constexpr,
    NEG: tl.constexpr,
    CONJ: tl.constexpr,
):
    offs = tl.program_id(0).to(tl.int64) * BLOCK + tl.arange(0, BLOCK)
    rem = offs
    acc = tl.full((BLOCK,), 0, tl.int64)
    for d in tl.static_range(len(SHAPE) - 1, -1, -1):
        acc += (rem % SHAPE[d]) * STRIDES[d]
        rem //= SHAPE[d]
    _rft_store(src, dst, acc, offs, offs < n, KIND, NEG, CONJ)


def _physical_view(src):
    # Rebuild only tensor metadata. The storage, offset, and strides stay the
    # same, while lazy conjugate/negative bits are applied by the Triton load.
    return torch.empty(0, dtype=src.dtype, device=src.device).set_(
        src.untyped_storage(), src.storage_offset(), src.shape, src.stride()
    )


