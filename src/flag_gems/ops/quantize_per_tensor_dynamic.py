# Fused single-pass quantizer for tensors that fit in a single program. This
# collapses the three-kernel (min/max reduce -> host sync -> quantize) path
# into one launch: it loads the whole tensor, reduces to (rmin, rmax) with 0
# folded in, derives the (scale, zero_point) exactly as ATen's
# ChooseQuantizationParams (double-precision scale, f32 min/max adjustment,
# error-based zero-point selection, round-half-to-even), writes the quantized
# output and stores the scale/zero_point plus a non-finite flag for the host.
@libentry()
@triton.jit
def quantize_fused_singlepass_kernel(
    inp,
    out,
    scale_ptr,
    zero_point_ptr,
    status_ptr,
    n_elements,
    qmin_full: tl.constexpr,
    qmax_full: tl.constexpr,
    reduce_range: tl.constexpr,
    BLOCK_SIZE: tl.constexpr,
):
    offset = tl.arange(0, BLOCK_SIZE)
    mask = offset < n_elements
    x = tl.load(inp + offset, mask=mask, other=0.0).to(tl.float64)
    # Include 0 in the observed range (PyTorch's dynamic per-tensor quantizer).
    rmin = tl.minimum(tl.min(x), 0.0)
    rmax = tl.maximum(tl.max(x), 0.0)

    # Error parity with ATen: a NaN in the input makes min/max NaN and the
    # native ChooseQuantizationParams raises on `min <= max`.
    has_nan = tl.max((x != x).to(tl.int64)) > 0

    qmin = qmin_full // 2 if reduce_range else qmin_full
    qmax = qmax_full // 2 if reduce_range else qmax_full
    # The stored integer is clamped to the *full* type range (ATen's kernel uses
    # std::numeric_limits<underlying_t>); only the qparams derivation sees the
    # reduce_range-halved range.
    store_qmin: tl.constexpr = qmin_full
    store_qmax: tl.constexpr = qmax_full

    # ChooseQuantizationParams: scale is a double computed from the float32
    # min/max; the small-scale adjustments run in float32 space (C++ keeps
    # min/max as floats), the zero point in double.
    scale = (rmax - rmin) / (qmax - qmin)
    scale32 = scale.to(tl.float32)
    recip32 = 1.0 / scale32
    # scale == 0 or reciprocal overflow (subnormal scale) -> fallback 0.1.
    scale_fallback = (scale32 == 0.0) | tl_extra_shim.isinf(recip32)
    scale = tl.where(scale_fallback, 0.1, scale)

    # Cut off small scale (SMALL_SCALE_THRESHOLD = 6.1e-5, QuantUtils.h).
    SMALL = _SMALL_SCALE_THRESHOLD
    needs_clamp = scale < SMALL
    org_scale32 = scale.to(tl.float32)
    scale = tl.where(needs_clamp, SMALL, scale)

    # Adjust rmin/rmax with float32 arithmetic (they are float in C++). The
    # three cases are mutually exclusive and branch off the original values:
    # min == 0 widens max, max == 0 widens min, otherwise both are amplified.
    # ``amplifier`` is computed in double and narrowed once: Triton turns a
    # float32 division on a kernel value into an approximate reciprocal
    # multiply, whereas C++ does a correctly rounded float division, and that
    # 1-ulp difference flips round-half-to-even zero points.
    rmin32 = rmin.to(tl.float32)
    rmax32 = rmax.to(tl.float32)
    amplifier = (tl.full((), SMALL, tl.float64) / org_scale32.to(tl.float64)).to(
        tl.float32
    )
    widened = tl.full((), SMALL, tl.float32) * (qmax - qmin)
    adj_rmin = tl.where(
        rmax32 == 0.0,
        -widened,
        tl.where(rmin32 == 0.0, rmin32, rmin32 * amplifier),
    )
    adj_rmax = tl.where(
        rmin32 == 0.0,
        widened,
        tl.where(rmax32 == 0.0, rmax32, rmax32 * amplifier),
    )
    rmin_eff = tl.where(needs_clamp, adj_rmin.to(tl.float64), rmin)
    rmax_eff = tl.where(needs_clamp, adj_rmax.to(tl.float64), rmax)

    # Zero point: pick the pair (min, qmin) / (max, qmax) with the smaller
    # arithmetic error, then round half to even and clamp.
    zp_from_min = qmin - rmin_eff / scale
    zp_from_max = qmax - rmax_eff / scale
    err_min = tl.abs(qmin.to(tl.float64)) - tl.abs(rmin_eff / scale)
    err_max = tl.abs(qmax.to(tl.float64)) - tl.abs(rmax_eff / scale)
    initial_zp = tl.where(err_min < err_max, zp_from_min, zp_from_max)
    # NaN comparisons are false in IEEE, so a NaN initial_zp falls through to
    # the nearbyint branch; converting NaN to int yields INT64_MIN on the GPU,
    # exactly the value ATen's error message reports.
    nudged = tl.minimum(
        tl.maximum(initial_zp, qmin.to(tl.float64)), qmax.to(tl.float64)
    )
    nudged = tl.where(
        (initial_zp < qmin) | (initial_zp > qmax),
        nudged,
        tl_extra_shim.rint(initial_zp),
    )
    zp = tl.where(has_nan, 0.0, nudged)

    # ATen clamps with std::max first then std::min; with a NaN q (possible
    # when the input holds +/-inf so scale becomes inf) both comparisons are
    # false in Triton and the value falls to qmin, matching ATen's int64
    # conversion of NaN followed by the same clamp. The clamp bounds are the
    # full type range, not the reduce_range-halved ones.
    q = tl.minimum(
        tl.maximum(tl_extra_shim.rint(x / scale) + zp, store_qmin), store_qmax
    )
    tl.store(out + offset, q.to(out.type.element_ty), mask=mask)
    # Single program -> every thread holds the same reduced scalars; broadcast
    # them once into the 1-element buffers. A status flag tells the host to
    # raise the matching ATen error instead of returning garbage: 1 for NaN
    # (min <= max violation), 2 for a +inf maximum (zero point becomes NaN).
    status = tl.where(has_nan, 1, tl.where(tl_extra_shim.isinf(rmax), 2, 0))
    tl.store(scale_ptr, scale.to(scale_ptr.type.element_ty))
    tl.store(zero_point_ptr, zp.to(zero_point_ptr.type.element_ty))
    tl.store(status_ptr, status)


