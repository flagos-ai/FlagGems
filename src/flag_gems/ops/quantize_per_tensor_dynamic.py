def _spec(dtype, reduce_range):
    """Return (storage_dtype, qmin, qmax) for a quantized dtype / reduce_range.

    ``reduce_range`` halves the quantized range to avoid instruction overflow on
    some hardware.
    """
    if dtype == torch.quint8:
        if reduce_range:
            return torch.uint8, 0, 127
        return torch.uint8, 0, 255
    elif dtype == torch.qint8:
        if reduce_range:
            return torch.int8, -64, 63
        return torch.int8, -128, 127
    else:
        raise ValueError(f"Unsupported quantized dtype: {dtype}")


