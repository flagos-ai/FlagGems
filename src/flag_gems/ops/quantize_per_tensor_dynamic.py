    # double and the input is upcast), so we mirror that: load the scale as a
    # full-precision float64 scalar and divide in float64. Computing in float32
    # would diverge from the reference on values that land exactly on a .5
    # boundary after rounding. ``rint`` performs round-half-to-even, matching
    # PyTorch's nearbyint.
