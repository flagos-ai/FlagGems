    mask = offset < n_elements
    x = tl.load(inp + offset, mask=mask, other=0.0).to(tl.float64)
    # Include 0 in the observed range (PyTorch's dynamic per-tensor quantizer).
    rmin = tl.minimum(tl.min(x), 0.0)
    rmax = tl.maximum(tl.max(x), 0.0)

