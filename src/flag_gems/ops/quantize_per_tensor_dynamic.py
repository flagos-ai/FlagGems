def quantize_kernel(
    inp,
    out,
    scale_ptr,
    zero_point,
    qmin: tl.constexpr,
    qmax: tl.constexpr,
    n_elements,
    BLOCK_SIZE: tl.constexpr,
):
    pid = tl.program_id(0)
    offset = pid * BLOCK_SIZE + tl.arange(0, BLOCK_SIZE)
    mask = offset < n_elements
    x = tl.load(inp + offset, mask=mask, other=0.0).to(tl.float64)
    # ATen's CUDA path computes nearbyint(raw_val / scale) with the double
    # q_scale; rint performs round-half-to-even, matching nearbyint.
    scale = tl.load(scale_ptr)
    # ATen clamps with std::max first then std::min (see the note in the fused
    # kernel); qmin/qmax here are the full type bounds.
    q = tl.minimum(tl.maximum(tl_extra_shim.rint(x / scale) + zero_point, qmin), qmax)
    tl.store(out + offset, q.to(out.type.element_ty), mask=mask)


def _choose_quant_params(rmin, rmax, qmin, qmax):
    """Compute (scale, zero_point) matching PyTorch's ChooseQuantizationParams.

    Mirrors ATen/native/quantized/cpu/QuantUtils.h: double-precision scale,
    f32 ==0 / reciprocal-overflow fallback to 0.1, SMALL_SCALE_THRESHOLD clamp
    with float32 min/max adjustment, error-based zero-point selection and
    round-half-to-even nudging.
    """
    if rmin != rmin or rmax != rmax:  # NaN: ATen raises on min <= max
        raise RuntimeError(_QPARAMS_MIN_MAX_ERROR)
    # Note: a degenerate range (rmin == rmax) needs no special case here. The
    # double scale is 0, the f32 zero test below replaces it with 0.1, and the
    # zero point is then derived from the minimum, exactly as ATen does.
    scale = (float(rmax) - float(rmin)) / (qmax - qmin)
    scale32 = float(torch.tensor(scale, dtype=torch.float64).to(torch.float32))
    if scale32 == 0.0 or float(
        torch.tensor(1.0, dtype=torch.float32) / torch.tensor(scale32)
    ) == float("inf"):
        scale = 0.1
    SMALL = float(_SMALL_SCALE_THRESHOLD.value)  # 6.1e-5 as float32
    if scale < SMALL:
        org_scale32 = float(torch.tensor(scale, dtype=torch.float64).to(torch.float32))
        scale = SMALL
        rmin32 = float(torch.tensor(rmin, dtype=torch.float64).to(torch.float32))
        rmax32 = float(torch.tensor(rmax, dtype=torch.float64).to(torch.float32))
        if rmin32 == 0.0:
            rmax32 = float(torch.tensor(SMALL * (qmax - qmin)).to(torch.float32))
        elif rmax32 == 0.0:
            rmin32 = float(torch.tensor(-SMALL * (qmax - qmin)).to(torch.float32))
        else:
            amplifier32 = float(
                torch.tensor(SMALL, dtype=torch.float32)
                / torch.tensor(org_scale32, dtype=torch.float32)
            )
            rmin32 = float(
                torch.tensor(rmin32, dtype=torch.float32)
                * torch.tensor(amplifier32, dtype=torch.float32)
            )
            rmax32 = float(
                torch.tensor(rmax32, dtype=torch.float32)
                * torch.tensor(amplifier32, dtype=torch.float32)
            )
        rmin, rmax = rmin32, rmax32
    zp_from_min = qmin - float(rmin) / scale
    zp_from_max = qmax - float(rmax) / scale
    err_min = abs(qmin) - abs(float(rmin) / scale)
    err_max = abs(qmax) - abs(float(rmax) / scale)
    initial_zp = zp_from_min if err_min < err_max else zp_from_max
    if initial_zp < qmin:
        zp = qmin
    elif initial_zp > qmax:
        zp = qmax
    else:
        zp = int(torch.round(torch.tensor(initial_zp, dtype=torch.float64)).item())
    return float(scale), int(zp)


def _raise_status(status):
    """Raise the error ATen would have raised for a non-finite input."""
    if status == 1:
        raise RuntimeError(_QPARAMS_MIN_MAX_ERROR)
    elif status == 2:
        raise RuntimeError(_ZP_LOWER_BOUND_ERROR)


def _quantize_per_tensor_dynamic_impl(inp, dtype, reduce_range):
    # ATen QTensor.cpp: dtype must be QInt8/QUInt8/Half. The Half path accepts
    # any input dtype (contiguous copy to Half), while the qint8/quint8 path
    # requires a float32 input (PerTensorAffineQuantizer::quantize).
    if dtype == torch.float16:
        return inp.to(torch.float16).contiguous()
    if inp.dtype != torch.float32:
        name = _ATEN_DTYPE_NAMES.get(inp.dtype, str(inp.dtype).replace("torch.", ""))
        raise RuntimeError("Quantize only works on Float Tensor, got " + name)
    if inp.numel() == 0:
        # ATen computes input.min() before anything else and raises on empty.
        raise RuntimeError(_EMPTY_MINMAX_ERROR)

    # Match ATen: output is always contiguous; kernels index flat storage.
    inp = inp.contiguous()

    if reduce_range and torch.backends.quantized.engine == "qnnpack":
        reduce_range = False

    qmin_full, qmax_full = _spec(dtype, reduce_range)
    n_elements = inp.numel()

    # Allocate via ``empty_strided`` to bypass the GEMS ``aten::empty`` override,
    # which launches a Triton zero-init kernel (~25us) per call. The int_repr and
    # the reduction mid-buffers are fully overwritten by the kernels below, so an
    # uninitialized allocation is safe and removes that fixed overhead.
    storage_dtype = torch.uint8 if dtype == torch.quint8 else torch.int8
    int_repr = torch.empty_strided(
        inp.shape, inp.stride(), dtype=storage_dtype, device=inp.device
    )

    # Fused single-pass path: when the whole tensor fits in a single program the
    # min/max reduction, (scale, zero_point) derivation and the quantize write
    # all run in one kernel launch with no host-side ``.item()`` sync on the
    # tensor data. The (scale, zero_point) readback remains (it is the API
    # contract: torch._make_per_tensor_quantized_tensor needs host scalars).
    fused_block = triton.next_power_of_2(n_elements)
    if fused_block <= 1 << 17:
        scale_tensor = torch.empty_strided(
            (1,), (1,), dtype=torch.float64, device=inp.device
        )
        zp_tensor = torch.empty_strided(
            (1,), (1,), dtype=torch.int64, device=inp.device
        )
        status_tensor = torch.empty_strided(
            (1,), (1,), dtype=torch.int64, device=inp.device
        )
        with torch_device_fn.device(inp.device):
            quantize_fused_singlepass_kernel[(1,)](
                inp,
                int_repr,
                scale_tensor,
                zp_tensor,
                status_tensor,
                n_elements,
                qmin_full,
                qmax_full,
                reduce_range,
                fused_block,
            )
        status = int(status_tensor.item())
        _raise_status(status)
        # Read back the (scale, zero_point) the kernel computed on the device.
        scale_val = float(scale_tensor.item())
        zp_val = int(zp_tensor.item())
        return torch._make_per_tensor_quantized_tensor(
            int_repr, scale=scale_val, zero_point=zp_val
        )

    # Two-stage reduction path for tensors too large for a single program.
    rmin = torch.empty_strided((1,), (1,), dtype=torch.float32, device=inp.device)
    rmax = torch.empty_strided((1,), (1,), dtype=torch.float32, device=inp.device)

    block_size = 1024
    mid_size = triton.cdiv(n_elements, block_size)
    block_mid = triton.next_power_of_2(mid_size)
    min_mid = torch.empty_strided(
        (mid_size,), (1,), dtype=torch.float32, device=inp.device
    )
    max_mid = torch.empty_strided(
        (mid_size,), (1,), dtype=torch.float32, device=inp.device
    )

    with torch_device_fn.device(inp.device):
        min_max_kernel_1[(mid_size,)](inp, min_mid, max_mid, n_elements, block_size)
        min_max_kernel_2[(1,)](min_mid, max_mid, rmin, rmax, mid_size, block_mid)

    rmin_val = rmin.item()
    rmax_val = rmax.item()
    if rmin_val != rmin_val or rmax_val != rmax_val:
        raise RuntimeError(_QPARAMS_MIN_MAX_ERROR)
    if rmax_val == float("inf"):
        # A +inf maximum makes the zero point NaN; ATen raises while
        # materializing it. A -inf minimum keeps the error-based zero point
        # finite, so that case is quantized normally (with scale=inf).
        raise RuntimeError(_ZP_LOWER_BOUND_ERROR)
    # ChooseQuantizationParams halves the range itself when reduce_range is set.
    qmin, qmax = (
        (qmin_full // 2, qmax_full // 2) if reduce_range else (qmin_full, qmax_full)
    )
    scale_val, zp_val = _choose_quant_params(rmin_val, rmax_val, qmin, qmax)

    # ---- Step 2: pointwise quantize ----
    # The scale is passed as a float64 tensor so the kernel keeps full precision
    # for the (double-precision) quantization division.
    scale_tensor = torch.tensor([scale_val], dtype=torch.float64, device=inp.device)
    grid = (mid_size,)
    with torch_device_fn.device(inp.device):
        quantize_kernel[grid](
            inp,
            int_repr,
            scale_tensor,
            zp_val,
            qmin_full,
            qmax_full,
            n_elements,
            block_size,
        )

    return torch._make_per_tensor_quantized_tensor(
        int_repr, scale=scale_val, zero_point=zp_val
    )


def quantize_per_tensor_dynamic(inp, dtype, reduce_range=True):
    logger.debug("GEMS QUANTIZE_PER_TENSOR_DYNAMIC")
    if dtype not in (torch.quint8, torch.qint8, torch.float16):
        # ATen's message concatenates the enum name without a separator.
        name = _ATEN_DTYPE_NAMES.get(dtype, str(dtype).replace("torch.", ""))
        raise RuntimeError(f"dtype {name}not supported")
    return _quantize_per_tensor_dynamic_impl(inp, dtype, reduce_range)


def quantize_per_tensor_dynamic_out(inp, dtype, reduce_range=True, *, out=None):
    logger.debug("GEMS QUANTIZE_PER_TENSOR_DYNAMIC_OUT")
    if out is None:
        return quantize_per_tensor_dynamic(inp, dtype, reduce_range)
    result = quantize_per_tensor_dynamic(inp, dtype, reduce_range)
    # ``out`` must be a quantized tensor with the same dtype and (resizable)
    # shape, mirroring ATen's resize + copy semantics.
    out.copy_(result)
    return out
