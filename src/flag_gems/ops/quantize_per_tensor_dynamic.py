def _spec(dtype, reduce_range):
    """Return (qmin, qmax) before reduce_range halving, as in ATen QTensor.cpp.

    ATen derives qmin/qmax from the full type range and halves both inside
    ChooseQuantizationParams when ``reduce_range`` is set (unless the quantized
    engine is QNNPACK, in which case reduce_range is ignored).
    """
    if dtype == torch.quint8:
        return 0, 255
    elif dtype == torch.qint8:
        return -128, 127
    else:
        raise ValueError(f"Unsupported quantized dtype: {dtype}")


