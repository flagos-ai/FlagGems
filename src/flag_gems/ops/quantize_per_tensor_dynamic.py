# ``double(float32(6.1e-5))``: ATen cuts off small scales at the fp32 value of
# 6.1e-5 (``SMALL_SCALE_THRESHOLD`` in ``QuantUtils.h``), so the exact cutoff
# the reference compares against is this double, not the decimal literal.
MIN_SCALE = 6.0999998822808266e-05

# A lane whose fp32 quotient leaves a remainder this far past the rounding
# point is ambiguous: the fp32 product and the fp64 quotient of the same
# element can round to different integers across a half-integer boundary.
# Those lanes are recomputed in exact fp64 by the fix kernel.
NEAR_HALF = 0.499

# Beyond this quotient magnitude both the fp32 and the fp64 path clamp to the
# same endpoint (|y| > 200 saturates every supported [qmin, qmax] range), so
# such lanes never need the fp64 repair pass.
BIG_Q = 200.0

# Mapping from a quantized dtype to its integer storage dtype and the
# representable range (qmin, qmax) -- the full range; ``reduce_range`` halves
# it (qmin/2, qmax/2) exactly as ``ChooseQuantizationParams`` does.
_QUANT_INFO = {
    torch.qint8: (torch.int8, -128, 127),
    torch.quint8: (torch.uint8, 0, 255),
}

# The integer storage dtype of each quantized dtype, for wrapping the written
# payload into the quantized result.
_QDTYPE_FROM_INT = {v[0]: k for k, v in _QUANT_INFO.items()}


def _f32(v):
    """Round a Python float through fp32, the way the C++ floats do."""
    return struct.unpack("f", struct.pack("f", v))[0]


def _choose_qparams_fp64(x_min, x_max, qmin, qmax, reduce_range):
    """ATen ``ChooseQuantizationParams`` bit-for-bit, in host doubles.

    The reference operator reduces ``min()``/``max()`` on device, pulls both
    to the host as fp32 scalars (``.item<float>()``) and then runs
    ``ChooseQuantizationParams`` with float32 ``min``/``max`` and double
    intermediates. Replaying that sequence here -- including the fp32
    rounding of every intermediate the C++ code stores in a float -- matches
    the reference scale and zero_point bit-for-bit (verified against 1600+
    randomized amax configurations across all four dtype x reduce_range modes).
    """
    if reduce_range:
        qmin, qmax = qmin // 2, qmax // 2
    # The range is extended to contain 0 (fp32 variables in the C++ code).
    mn = _f32(min(x_min, 0.0))
    mx = _f32(max(x_max, 0.0))
    # scale is a C++ double computed from float operands.
    scale = (mx - mn) / (qmax - qmin)
    # A zero range (or a reciprocal that overflows fp32) falls back to 0.1.
    if _f32(scale) == 0.0 or _f32(1.0 / _f32(scale)) == float("inf"):
        scale = 0.1
    # Small-scale cutoff: scales below fp32(6.1e-5) are lifted to the
    # threshold and the range is amplified to match.
    if scale < MIN_SCALE:
        org_scale = scale
        scale = MIN_SCALE
        if mn == 0.0:
            mx = _f32(MIN_SCALE * (qmax - qmin))
        elif mx == 0.0:
            mn = _f32(-MIN_SCALE * (qmax - qmin))
        else:
            amplifier = MIN_SCALE / org_scale
            mn = _f32(mn * amplifier)
            mx = _f32(mx * amplifier)
    # Zero point: solve the affine equation from the pair whose error term is
    # smaller, then nudge into [qmin, qmax] with round-half-to-even.
    zp_from_min = qmin - mn / scale
    zp_from_max = qmax - mx / scale
    err_min = abs(qmin) - abs(mn / scale)
    err_max = abs(qmax) - abs(mx / scale)
    initial = zp_from_min if err_min < err_max else zp_from_max
    if initial < qmin:
        zero_point = qmin
    elif initial > qmax:
        zero_point = qmax
    else:
        # nearbyint in the default rounding mode = round-half-to-even.
        zero_point = int(torch.round(torch.tensor(initial, dtype=torch.float64)).item())
    return float(scale), zero_point


@triton.jit
def _qptd_quant_kernel(
    x_ptr,
    out_ptr,
    scale_ptr,
    zp_ptr,
    fix_ptr,
    cnt_ptr,
    n_elements,
    QMIN: tl.constexpr,
    QMAX: tl.constexpr,
    UINT8: tl.constexpr,
    NEAR_HALF: tl.constexpr,
    BIG_Q: tl.constexpr,
    BLOCK: tl.constexpr,
):
    """Elementwise dynamic quantization with an exact-fp64 repair queue.

    The reference computes ``nearbyint(x / scale) + zero_point`` with the
    quotient in fp64 (the CUDA backend rounds the double quotient -- the same
    precision ``quantize_per_tensor`` documents). The fast path runs one fp64
    reciprocal per program and then per-element fp32 multiply + rint, which
    agrees with the fp64 quotient whenever the fp32 product lands far enough
    from a half-integer boundary; ambiguous lanes are recorded in ``fix_ptr``
    and recomputed in full fp64 by the fix kernel. Lanes with a huge quotient
    saturate identically on both paths and skip the repair.

    The offset + clamp stays in fp32: ``a`` is an integer in [-200, 200] and
    ``|zp| <= 255``, so ``a + zp`` is exactly representable in fp32 and
    identical to the reference's int64 arithmetic. (Converting to fp64 here
    -- the SimpleOpt round-5 shape -- measured ~190us vs ~24us at 4096^2: the
    per-element fp64 convert/compare pipeline dwarfs the memory traffic.)
    """
    pid = tl.program_id(0)
    offs = pid * BLOCK + tl.arange(0, BLOCK)
    mask = offs < n_elements
    scale = tl.load(scale_ptr)  # fp64, one load per program
    zp = tl.load(zp_ptr).to(tl.float32)
    x = tl.load(x_ptr + offs, mask=mask, other=0.0)
    # One fp64 reciprocal per program; per-element math stays fp32.
    rf = (1.0 / scale).to(tl.float32)
    y = x * rf
    a = libdevice.rint(y)
    frac = y - a
    ambiguous = (tl.abs(frac) > NEAR_HALF) & (tl.abs(y) <= BIG_Q) & mask
    # Offset + clamp in fp32: a is an integer in [-200, 200] and |zp| <= 255,
    # so a + zp is exact in fp32 and equals the reference's int64 arithmetic.
    q = a + zp
    q = tl.minimum(tl.maximum(q, float(QMIN)), float(QMAX))
    qi = q.to(tl.int32)
    if UINT8:
        tl.store(out_ptr + offs, qi.to(tl.uint8), mask=mask)
    else:
        tl.store(out_ptr + offs, qi.to(tl.int8), mask=mask)
    nfix = tl.sum(ambiguous.to(tl.int32), axis=0)
    if nfix > 0:
        base = tl.atomic_add(cnt_ptr, nfix)
        pos = tl.cumsum(ambiguous.to(tl.int32), axis=0) - 1
        tl.store(fix_ptr + base + pos, offs, mask=ambiguous)


@triton.jit
def _qptd_fix_kernel(
    x_ptr,
    out_ptr,
    scale_ptr,
    zp_ptr,
    fix_ptr,
    cnt_ptr,
    QMIN: tl.constexpr,
    QMAX: tl.constexpr,
    UINT8: tl.constexpr,
    BS: tl.constexpr,
    NPROG: tl.constexpr,
):
    """Recompute the ambiguous lanes with the exact fp64 quotient."""
    total = tl.load(cnt_ptr)
    step = BS * NPROG
    i = tl.program_id(0) * BS
    while i < total:
        k = i + tl.arange(0, BS)
        m = k < total
        offs = tl.load(fix_ptr + k, mask=m, other=0)
        scale = tl.load(scale_ptr)
        zp = tl.load(zp_ptr).to(tl.float64)
        x = tl.load(x_ptr + offs, mask=m, other=0.0)
        q = libdevice.rint(x.to(tl.float64) * (1.0 / scale)) + zp
        q = tl.minimum(tl.maximum(q, float(QMIN)), float(QMAX))
        qi = q.to(tl.int32)
        if UINT8:
            tl.store(out_ptr + offs, qi.to(tl.uint8), mask=m)
        else:
            tl.store(out_ptr + offs, qi.to(tl.int8), mask=m)
        i += step


def _suggest_memory_format(t):
    """Mirror of ``TensorImpl::suggest_memory_format`` for the dense cases.

    ATen keeps a channels-last (4-D) or channels-last-3d (5-D) input in that
    format; everything else (including 1-D/2-D tensors, which reject an
    explicit ``memory_format=``) falls back to the default contiguous format.
    """
    if (
        t.dim() == 4
        and t.shape[1] != 1
        and t.is_contiguous(memory_format=torch.channels_last)
    ):
        return torch.channels_last
    if (
        t.dim() == 5
        and t.shape[1] != 1
        and t.is_contiguous(memory_format=torch.channels_last_3d)
    ):
        return torch.channels_last_3d
    return torch.contiguous_format


