    if out.shape != self.shape:
        # ATen resizes the destination first; the QuantizedCUDA backend has no
        # ``resize_`` implementation, so a shape mismatch surfaces that gap.
        raise NotImplementedError(
            "Could not run 'aten::resize_' with arguments from the "
            "'QuantizedCUDA' backend. This could be because the operator "
            "doesn't exist for this backend, or was omitted during the "
            "selective/custom build process."
        )
    result, scale, zero_point = _quantize_impl(self, dtype, reduce_range)
    # Quantized ``copy_`` overwrites the integers and adopts the source
    # quantizer -- the same landing ATen reaches, minus its staging copy.
    out.copy_(_make_per_tensor_from_int(result, scale, zero_point))
    return out
