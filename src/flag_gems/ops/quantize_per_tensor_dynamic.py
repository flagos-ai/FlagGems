# Fused single-pass quantizer for tensors that fit in a single program. This
# collapses the three-kernel (min/max reduce -> host sync -> quantize) path
# into one launch: it loads the whole tensor, reduces to (rmin, rmax) with 0
# folded in (matching PyTorch's dynamic per-tensor quantization), derives the
# (scale, zero_point) with ``rint`` (round-half-to-even), writes the quantized
# output and writes the scale/zero_point out for the host to read back. With no
# host-side ``.item()`` sync and a single launch this removes the ~260us of
# fixed three-launch overhead that dominates the cost on small tensors.
