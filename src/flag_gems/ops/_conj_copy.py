    pid = tl.program_id(0)
    offsets = pid * BLOCK_SIZE + tl.arange(0, BLOCK_SIZE)
    mask = offsets < n_floats

    # A complex tensor is laid out in memory as interleaved real/imaginary
    # float pairs: (r0, i0, r1, i1, ...). Reinterpreting the (contiguous)
    # complex tensor as its underlying float dtype yields a flat array of
    # length 2 * numel where even indices hold the real part and odd
    # indices hold the imaginary part. Conjugation keeps the real part and
    # negates the imaginary part, so we negate exactly the odd-indexed
    # elements. Loading/storing a single contiguous float stream keeps the
    # memory transactions fully coalesced, which is markedly faster than
    # issuing two separate loads/stores per complex element.
