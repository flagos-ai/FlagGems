def _collapse(shape, strides):
    """Merge an inner dim (size s, stride t) into the previous outer dim (size S,
    stride T) only when T == s * t, so the merged dim has stride t because
    offset = i*T + j*t = (i*s + j)*t. A transposed view (T == t, S == t) fails
    this test and is deliberately kept as two dims."""
    dims = []
    for s, t in zip(shape, strides):
        if s == 1:
            continue
        if dims and dims[-1][1] == s * t:
            dims[-1] = (dims[-1][0] * s, t)
        else:
            dims.append((s, t))
    return dims


def _is_contiguous(shape, strides):
    expect = 1
    for s, t in zip(reversed(shape), reversed(strides)):
        if s == 1:
            continue
        if t != expect:
            return False
        expect *= s
    return True


