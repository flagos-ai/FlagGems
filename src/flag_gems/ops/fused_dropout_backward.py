"""Backward kernel for the legacy fused dropout: ``grad_output * mask / p``.

The pinned Torch build registers no standalone ``aten::_fused_dropout_backward``
schema: derivatives.yaml routes ``_fused_dropout``'s input gradient through the
manual autograd function ``_fused_dropout_backward(grad, mask, p)``.  The legacy
fused dropout forward draws ``mask = bernoulli(p)`` with ``p`` the *keep*
probability and scales the output by ``1 / p``, so the backward multiplies the
upstream gradient by the kept positions and the same reciprocal.

Numerics follow ATen bit-exactly:
- fp16/bf16: the product ``grad * mask`` and the reciprocal multiply run in
  float32 opmath, rounding to the input dtype between them, exactly like the
  native chain (mul kernel in opmath, then div-by-cpu-scalar which lowers to a
  reciprocal multiply with an IEEE float32 ``1/p``).
- fp64: everything stays in float64.  The reciprocal is loaded from a
  one-element device tensor because Triton types Python-float scalar arguments
  as float32, which would corrupt the float64 math.
"""

import logging

import torch
import triton
import triton.language as tl

from flag_gems.runtime import torch_device_fn
from flag_gems.utils import libentry

logger = logging.getLogger(__name__)

_INV_CACHE = {}

# One program handles ``BLOCK`` lanes.  2048 lanes / 8 warps measured best on
# H20 across 256^2 .. 4096^2 streaming workloads (KernelGen SimpleOpt round 1);
# both larger (4096/8) and smaller (1024/4) tiles regressed.
_BLOCK_SIZE = 2048
_NUM_WARPS = 8


def _inv_fp32(p):
    """The IEEE float32 reciprocal ``1.0f / float(p)`` used by ATen div."""
    v = _INV_CACHE.get(p)
    if v is None:
        try:
            import numpy as np

            v = float(np.float32(1.0) / np.float32(p))
        except Exception:
            import struct

            p32 = struct.unpack("f", struct.pack("f", p))[0]
            v = struct.unpack("f", struct.pack("f", 1.0 / p32))[0]
        _INV_CACHE[p] = v
    return v


