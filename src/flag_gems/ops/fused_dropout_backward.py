@triton.jit
def _fused_dropout_backward_kernel(
    grad_ptr,
    mask_ptr,
    out_ptr,
    inv_ptr,
    n_elements,
    inv_p,
    BLOCK: tl.constexpr,
    EVEN: tl.constexpr,
    OP64: tl.constexpr,
):
    pid = tl.program_id(0)
    offs = pid * BLOCK + tl.arange(0, BLOCK)
    if EVEN:
        g = tl.load(grad_ptr + offs)
        m = tl.load(mask_ptr + offs)
    else:
        inb = offs < n_elements
        g = tl.load(grad_ptr + offs, mask=inb, other=0)
        m = tl.load(mask_ptr + offs, mask=inb, other=0)
    dt = out_ptr.dtype.element_ty
    if OP64:
        t = g * m
        t = t * tl.load(inv_ptr).to(tl.float64)
    else:
        # ATen ordering: opmath product rounded to the storage dtype, then the
        # float32 reciprocal multiply rounded back to the storage dtype.
        t32 = (g.to(tl.float32) * m.to(tl.float32)).to(dt).to(tl.float32)
        t = (t32 * inv_p).to(dt)
    if EVEN:
        tl.store(out_ptr + offs, t)
    else:
        tl.store(out_ptr + offs, t, mask=inb)


def fused_dropout_backward(grad_output: torch.Tensor, mask: torch.Tensor, p: float):
    """Gradient of the legacy fused dropout w.r.t. its input.

    Args:
        grad_output: Gradient w.r.t. the dropout output.
        mask: The uint8 (0/1) keep mask returned by the forward.
        p: The keep probability handed to the forward.

    Returns:
        Gradient w.r.t. the input, with the same shape and dtype as
        ``grad_output``.
    """
    logger.debug("GEMS FUSED_DROPOUT_BACKWARD")
    if grad_output.dtype not in (
        torch.float16,
        torch.bfloat16,
        torch.float32,
        torch.float64,
    ):
        raise TypeError(
            f"unsupported dtype for fused_dropout_backward: {grad_output.dtype}"
        )
    if grad_output.shape != mask.shape:
        raise RuntimeError(
            "fused_dropout_backward grad_output and mask shapes differ: "
            f"{tuple(grad_output.shape)} vs {tuple(mask.shape)}"
        )
    if p <= 0:
        # The forward scales by 1/p, so p=0 has no finite backward; native
        # autograd propagates NaN the same way (0 * inf), but a Python float
        # division by zero raises before the kernel can reproduce it.
        raise ValueError("fused_dropout_backward requires a positive keep probability")

    grad = grad_output.contiguous()
    mask_c = mask.contiguous()
    out = torch.empty_like(grad)
    n = grad.numel()
    if n == 0:
        return out
    even = (n % _BLOCK_SIZE) == 0
    op64 = grad.dtype == torch.float64
    if op64:
        inv_tensor = torch.tensor(1.0 / p, dtype=torch.float64, device=grad.device)
        inv_p = 1.0
    else:
        inv_tensor = grad  # unused placeholder pointer
        inv_p = _inv_fp32(p)
    grid = ((n + _BLOCK_SIZE - 1) // _BLOCK_SIZE,)
    with torch_device_fn.device(grad.device):
        _fused_dropout_backward_kernel[grid](
            grad,
            mask_c,
            out,
            inv_tensor,
            n,
            inv_p,
            BLOCK=_BLOCK_SIZE,
            EVEN=even,
            OP64=op64,
            num_warps=_NUM_WARPS,
            num_stages=1,
        )
    return out


