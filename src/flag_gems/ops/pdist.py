    assert x.ndim == 2, "pdist only supports 2D input"
    if x.dtype != torch.float32:
        raise RuntimeError(
            f"pdist Triton kernel supports torch.float32, but got {x.dtype}"
        )
    N = x.shape[0]
    M = x.shape[1]

    if N < 2:
        raise ValueError("pdist requires at least 2 rows")

    x = x.contiguous()
    num_pairs = N * (N - 1) // 2
