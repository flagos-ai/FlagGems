def _pad8(values):
    return list(values) + [0] * (_MAX_DIM - len(values))


def _sparse_strides(sizes):
    """Row-major strides of the leading ``len(sizes)`` dimensions."""
    acc = 1
    out = []
    for size in reversed(sizes):
        out.append(acc)
        acc *= size
    out.reverse()
    return out


