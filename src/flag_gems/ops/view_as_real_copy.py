    src_offsets = src_base[:, None] + lane[None, :]
    dst_offsets = i[:, None] * 2 + lane[None, :]
    mask2 = mask[:, None]
    values = tl.load(src_ptr + src_offsets, mask=mask2)
    tl.store(dst_ptr + dst_offsets, values, mask=mask2)


