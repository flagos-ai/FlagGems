"""In-place elementwise ``greater-or-equal`` (``aten::ge_``).

``ge_tensor_(self, other)`` and ``ge_scalar_(self, other)`` mutate ``self`` in
place with the 0/1 comparison result and return the same tensor object.  Both
overloads exercised by the original pytest are covered:

* ``other`` is a Tensor  -> values are promoted to ``torch.result_type(self, other)``
  before the comparison, and the operand is broadcast up to the receiver.
* ``other`` is a Python number -> values are promoted to
  ``torch.result_type(self, other)`` (wrapped-number promotion).

Every element of the result is produced by a Triton device kernel.  The host
wrapper only performs metadata queries, zero-copy dtype views, launch-argument
preparation, the JIT launch, and the autograd bookkeeping (mark the receiver
dirty, return a zero gradient) that the native comparison operator also has.

Because the operation is memory bound, the device kernels are already at the
bandwidth roof for large tensors; the wrapper therefore resolves the launch
decision once per (shape, strides, dtypes, device) signature and reuses it, so
small tensors do not pay repeated promotion and planning work on every call.
Only shape/stride/dtype metadata is cached — never tensor data.
"""

