@triton.jit(do_not_specialize=["other_scalar"])
def _ge_contig_kernel(
    self_ptr,
    other_ptr,
    other_scalar,
    numel,
    last_dim,
    MODE: tl.constexpr,
    CT: tl.constexpr,
    OT: tl.constexpr,
    BLOCK: tl.constexpr,
    I64: tl.constexpr,
    EVEN: tl.constexpr,
):
    """Fast path: the receiver is contiguous.

    MODE 0 -> ``other`` has the receiver's shape and is contiguous.
    MODE 1 -> ``other`` is contiguous and broadcasts along the last dimension.
    MODE 2 -> ``other`` is a scalar.

    ``EVEN`` says ``numel`` is a multiple of ``BLOCK``: in that case every
    lane is in bounds and the mask is dropped entirely, which lets the backend
    emit vectorized 128-bit global accesses instead of predicated scalars.
    """
    pid = tl.program_id(0)
    if I64:
        idx = pid.to(tl.int64) * BLOCK + tl.arange(0, BLOCK).to(tl.int64)
    else:
        idx = pid * BLOCK + tl.arange(0, BLOCK)
    if EVEN:
        a = tl.load(self_ptr + idx).to(CT)
    else:
        a = tl.load(self_ptr + idx, mask=idx < numel, other=0).to(CT)
    if MODE == 2:
        b = tl.full([BLOCK], other_scalar, CT)
    elif MODE == 1:
        if EVEN:
            b = tl.load(other_ptr + (idx % last_dim)).to(CT)
        else:
            b = tl.load(other_ptr + (idx % last_dim), mask=idx < numel, other=0).to(CT)
    else:
        if EVEN:
            b = tl.load(other_ptr + idx).to(CT)
        else:
            b = tl.load(other_ptr + idx, mask=idx < numel, other=0).to(CT)
    if EVEN:
        tl.store(self_ptr + idx, (a >= b).to(OT))
    else:
        tl.store(self_ptr + idx, (a >= b).to(OT), mask=idx < numel)


@triton.jit(do_not_specialize=["other_scalar"])
def _ge_nd_kernel(
    self_ptr,
    other_ptr,
    meta_ptr,
    other_scalar,
    numel,
    NDIM: tl.constexpr,
    SCALAR: tl.constexpr,
    CT: tl.constexpr,
    OT: tl.constexpr,
    BLOCK: tl.constexpr,
):
    """General path: strided / broadcasting operands, with int64 offsets.

    ``meta_ptr`` holds the receiver shape, receiver strides and operand strides
    stored least-significant-dimension first; a broadcast dimension has an
    operand stride of 0.
    """
    pid = tl.program_id(0)
    idx = pid.to(tl.int64) * BLOCK + tl.arange(0, BLOCK).to(tl.int64)
    mask = idx < numel
    off_s = tl.zeros([BLOCK], dtype=tl.int64)
    off_o = tl.zeros([BLOCK], dtype=tl.int64)
    rem = idx
    for i in tl.static_range(NDIM):
        shp = tl.load(meta_ptr + i)
        st_s = tl.load(meta_ptr + NDIM + i)
        st_o = tl.load(meta_ptr + 2 * NDIM + i)
        coord = rem % shp
        rem = rem // shp
        off_s += coord * st_s
        off_o += coord * st_o
    a = tl.load(self_ptr + off_s, mask=mask, other=0).to(CT)
    if SCALAR:
        b = tl.full([BLOCK], other_scalar, CT)
    else:
        b = tl.load(other_ptr + off_o, mask=mask, other=0).to(CT)
    tl.store(self_ptr + off_s, (a >= b).to(OT), mask=mask)


def _operand_broadcasts_to(receiver, operand):
    b = operand.shape
    if len(b) > receiver.dim():
        return False
    for i in range(1, len(b) + 1):
        db = b[-i]
        if db != 1 and db != receiver.shape[-i]:
            return False
    return True


def _byte_view(tensor):
    """Zero-copy byte view of a bool tensor so kernels can be typed on ints."""
    try:
        return tensor.view(torch.uint8)
    except RuntimeError:
        return None


def _plan(self, other):
    """Resolve the launch decision for one (receiver, operand) signature."""
    numel = self.numel()
    scalar = not isinstance(other, torch.Tensor)
    dtype = self.dtype

    if scalar:
        kind = 1 if isinstance(other, float) else (3 if isinstance(other, bool) else 2)
        key = (dtype, self.shape, None, kind, 0, numel)
    else:
        other_dtype = other.dtype
        if other_dtype not in _SUPPORTED:
            raise RuntimeError(f"ge_ not implemented for {other_dtype}")
        if not _operand_broadcasts_to(self, other):
            raise RuntimeError(
                "ge_: the operand cannot be broadcast to the receiver's shape"
            )
        # result_type of identical dtypes is that dtype; skip the C++ call.
        if other_dtype is dtype:
            key = (dtype, self.shape, other.shape, 0, 0, numel)
        else:
            key = (dtype, self.shape, other.shape, other_dtype, 1, numel)

    plan = _PLANS.get(key)
    if plan is not None:
        return plan

    contig = self.is_contiguous()
    if scalar:
        compute = torch.result_type(self, other)
        other_contig = True
    else:
        compute = (
            dtype
            if (not scalar and other.dtype is dtype)
            else torch.result_type(self, other)
        )
        other_contig = other.is_contiguous()

    CT = _TL_DTYPE[compute]
    OT = _TL_DTYPE[dtype]
    bool_self = dtype is torch.bool
    bool_other = (not scalar) and other.dtype is torch.bool

    if contig:
        mode = None
        last = 0
        if scalar:
            mode = 2
        elif other.shape == self.shape and other_contig:
            mode = 0
        elif (
            self.dim() >= 1
            and other.numel() == self.shape[-1]
            and other_contig
            and all(d == 1 for d in other.shape[:-1])
        ):
            mode = 1
            last = self.shape[-1]
        if mode is not None:
            # Larger tiles give each thread more outstanding 128-bit loads for
            # the mid/large streaming cases; tiny tensors use a small tile so
            # the grid still spreads over the machine's SMs instead of running
            # as a handful of CTAs.
            if numel >= 2**20:
                block = 2048
            elif numel <= 4096:
                block = 256
            else:
                block = _BLOCK
            plan = (
                0,  # contiguous kernel
                mode,
                CT,
                OT,
                bool_self,
                bool_other,
                triton.cdiv(numel, block),
                last,
                numel >= 2**31,
                numel,
                block,
                numel % block == 0,
            )
            if len(_PLANS) < _CACHE_MAX:
                _PLANS[key] = plan
            return plan

    # General strided / broadcasting path, stored least-significant dim first.
    ndim = self.dim()
    pad = ndim - (0 if scalar else other.dim())
    o_shape = [1] * pad + ([] if scalar else list(other.shape))
    o_stride = [0] * pad + ([] if scalar else list(other.stride()))
    for i in range(ndim):
        if o_shape[i] == 1:
            o_stride[i] = 0
    meta = list(self.shape)[::-1] + list(self.stride())[::-1] + o_stride[::-1]
    plan = (
        1,  # ND kernel
        ndim,
        CT,
        OT,
        bool_self,
        bool_other,
        triton.cdiv(numel, _BLOCK),
        0,
        True,
        meta,
        _BLOCK,
        False,
    )
    if len(_PLANS) < _CACHE_MAX:
        _PLANS[key] = plan
    return plan


