import logging

import torch

logger = logging.getLogger(__name__)


def _has_same_storage_numel(self: torch.Tensor, other: torch.Tensor) -> bool:
    """Return whether two tensors share the same number of storage elements.

    Mirrors ``aten::_has_same_storage_numel(Tensor self, Tensor other) ->
    bool``: the storage element count of a tensor is
    ``untyped_storage().nbytes() // element_size()`` (native_functions.yaml
    storage-numel semantics). The result is pure allocation metadata and
    never depends on stored element data, so it is computed from tensor
    metadata only. ``untyped_storage``, ``nbytes`` and ``element_size`` are
    distinct operators that this worktree does not register, so evaluating
    them here cannot re-enter (and recurse into) this implementation.

    Note that the element count covers the WHOLE underlying storage, not the
    tensor's own extent: any two views of one storage compare equal even
    when their shapes differ, while same-shaped tensors backed by separate
    storages compare unequal. Verified against native ATen on H20.
    """
    logger.debug("GEMS _HAS_SAME_STORAGE_NUMEL")
    return (self.untyped_storage().nbytes() // self.element_size()) == (
        other.untyped_storage().nbytes() // other.element_size()
    )
