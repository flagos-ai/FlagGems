"""Gradient of the ``_foreach_maximum.Scalar`` / ``_foreach_maximum.ScalarList`` family.

``torch.ops.aten._foreach_maximum_backward`` does not exist in this Torch
build: ``native_functions.yaml`` has no ``_foreach_*_backward`` entry at all.
The gradient is derived by the auto-generated ``ForeachMaximumBackward{0,1}``
autograd nodes from the derivatives recorded for the *forward* operators
(``tools/autograd/derivatives.yaml``):

* ``_foreach_maximum.Scalar``::

      self: at::where(self[i] == scalar, grads[i] / 2, grads[i])
            .masked_fill_(self[i] < scalar, 0)

* ``_foreach_maximum.ScalarList`` (one scalar per tensor)::

      self: at::where(self[i] == scalars[i], grads[i] / 2, grads[i])
            .masked_fill_(self[i] < scalars[i], 0)

Only these two overloads carry derivatives: the ``.List`` overload takes a
second *tensor* list whose operands ATen does not differentiate here, and the
in-place variants return no value.  This module implements exactly those two
forms: a tensor list and scalar(s) in, one gradient list out.

The formula collapses to ``grad * (self >= s)`` with the tie position scaled
by ``1/2`` (the subgradient of ``max``).  Verified bit-exact against
``torch.autograd.grad(torch.ops.aten._foreach_maximum.*)`` on CUDA for
fp16/bf16/fp32/fp64:

* ``grads[i] / 2`` is exact in every float dtype (a power of two), so there is
  no opmath rounding to reproduce -- the whole chain is dtype-local.
* The comparisons use the scalar **cast to the tensor's dtype** first.  A
  Python ``0.3`` against an fp16 tensor compares equal to the fp16 value
  nearest to 0.3, so the kernel must cast the scalar on the host (or to the
  load dtype) instead of comparing in fp32 -- otherwise that tie position
  receives the full gradient where ATen gives half.
* ``masked_fill_`` runs *after* the ``where``, so a non-finite gradient at a
  masked position is overwritten with zero, and a non-finite gradient at or
  above the tie is propagated unchanged.  A NaN scalar never compares equal
  or less, so its gradients pass through untouched -- the kernel keeps the
  same branch structure so all of these fall out naturally.
* Complex is rejected up front the way the forward is (``foreach_binary_op_
  scalar_cuda`` not implemented for complex), and integer/bool tensors cannot
  carry a gradient in the first place.

Because there is no standalone ``aten::_foreach_maximum_backward`` schema to
register a kernel against, the surface here is the explicit entry point plus
a ``torch.autograd.Function`` bridge (same pattern as ``deg2rad_backward``).
"""

