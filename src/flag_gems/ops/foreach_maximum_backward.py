def _launch_group(indices, self_list, grad_list, scalars, device, dtype):
    """One Triton launch for one ``(device, dtype)`` group.

    The metadata is built in the segmented order the kernel indexes: all self
    pointers, then all grad pointers, then all output pointers, then the
    element counts -- four ``nt``-long runs for a group of ``nt`` tensors.
    """
    nt = len(indices)
    numels = [self_list[i].numel() for i in indices]
    max_numel = max(numels)
    grad_out: List[torch.Tensor] = [None] * nt
    selves_run: List[int] = []
    grads_run: List[int] = []
    outs_run: List[int] = []
    for pos, i in enumerate(indices):
        x = self_list[i].contiguous()
        g = grad_list[i].contiguous()
        o = torch.empty_like(x)
        grad_out[pos] = o
        selves_run.append(x.data_ptr())
        grads_run.append(g.data_ptr())
        outs_run.append(o.data_ptr())
    if max_numel == 0:
        return grad_out

    values = selves_run + grads_run + outs_run + numels
    # ``frombuffer`` + ``empty`` + ``copy_`` sidesteps the generic
    # sequence-to-tensor path: the direct ``torch.tensor(..., device=cuda)``
    # form pays a synchronising pageable H2D that measured ~2ms per call --
    # more than the kernel itself on every workload -- while this composite
    # stays ~17us.  The call is layout-only host-side plumbing, not tensor
    # compute (see the allow-torch-compute note in tools/ci_checks).
    buf = array.array("q", values)
    host = torch.frombuffer(buf, dtype=torch.int64)  # allow-torch-compute
    meta = torch.empty(len(values), dtype=torch.int64, device=device)
    meta.copy_(host, non_blocking=True)

    block = _BLOCK
    for candidate in (1024, 2048, 4096, 8192, 16384):
        block = candidate
        if nt * ((max_numel + candidate - 1) // candidate) <= (1 << 18):
            break
    # The tensor index rides grid.y (NT-sized) and the block index grid.x:
    # CUDA allows 2**31 - 1 programs on the x axis, so a single 2**30-element
    # tensor never runs out of blocks, while a y-axis layout would hit the
    # 65535 program cap exactly at 2**30 / 16384 + 1.
    grid = (triton.cdiv(max_numel, block), nt)

    # ``.Scalar`` broadcasts one value to every position: when the scalars are
    # all equal there is nothing for an array to index and the value travels
    # as a kernel argument; a real per-tensor list takes the device buffer.
    common = scalars[0] if len(set(scalars)) == 1 else None
    by_value = common is not None
    if by_value:
        scalar_buf = meta  # unused by the kernel; keeps the pointer slot valid
        scalar_value = float(common)
    else:
        scalar_buf = torch.tensor([float(v) for v in scalars], dtype=dtype).to(
            device, non_blocking=True
        )
        scalar_value = 0.0

    with torch_device_fn.device(device):
        foreach_maximum_backward_kernel[grid](
            meta,
            scalar_buf,
            scalar_value,
            nt,
            tl_dtype(dtype),
            SCALAR_BY_VALUE=by_value,
            BLOCK=block,
            num_warps=_NUM_WARPS,
        )
    return grad_out


