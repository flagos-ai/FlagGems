def trapezoid_dx_kernel(
    y_ptr,
    out_ptr,
    dx,
    M,
    N,
    BLOCK_M: tl.constexpr,
    BLOCK_N: tl.constexpr,
    COMPUTE_DTYPE: tl.constexpr,
):
    pid = ext.program_id(0) * BLOCK_M + tl.arange(0, BLOCK_M)[:, None]
    row_mask = pid < M
    y_row = y_ptr + pid * N

    acc = tl.zeros([BLOCK_M, BLOCK_N], dtype=COMPUTE_DTYPE)
    # The trapezoidal rule sum_{i=1..N-1} 0.5*(y_i + y_{i-1}) is equivalent to a
    # single weighted pass over y where every element has weight 1 except the two
    # endpoints, which have weight 0.5. This reads each y element only once.
    for off in range(0, N, BLOCK_N):
        k = off + tl.arange(0, BLOCK_N)[None, :]
        col_mask = k < N
        mask = row_mask & col_mask
        y_k = tl.load(y_row + k, mask=mask, other=0.0).to(COMPUTE_DTYPE)
        w = tl.where((k == 0) | (k == N - 1), 0.5, 1.0)
        acc += y_k * w

    out = tl.sum(acc, axis=1)[:, None] * dx.to(COMPUTE_DTYPE)
    tl.store(out_ptr + pid, out, mask=row_mask)


