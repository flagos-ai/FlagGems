@triton.jit
def _ssst_kernel(
    x_ptr,
    ld,
    rows,
    cols,
    packed_ptr,
    spm,
    packed_t_ptr,
    rows_t,
    width_t,
    qbuf_ptr,
    qb_stride,
    qbuf_t_ptr,
    qbt_stride,
    masks_ptr,
    sm0,
    sm1,
    IS_ABS: tl.constexpr,
):
    pid_r = tl.program_id(0)
    pid_c = tl.program_id(1)
    row0 = pid_r * 32
    col0 = pid_c * 32

    lane_ = tl.arange(0, 16)[:, None, None]  # (16,1,1)
    ti = tl.arange(0, 8)[None, :, None]  # (1,8,1)
    tj = tl.arange(0, 8)[None, None, :]  # (1,1,8)
    lr = lane_ // 4
    lc = lane_ % 4

    # Load the 16 lanes of every 4x4 tile in the 8x8 tile patch.
    # lane = r_in * 4 + c_in
    rr = row0 + ti * 4 + lr
    cc = col0 + tj * 4 + lc
    m = (rr < rows) & (cc < cols)
    xr = tl.load(x_ptr + rr * ld + cc, mask=m, other=float("-inf"))
    V0 = xr.to(tl.float32)

    # Order-preserving 16-bit key of the value with the original lane index
    # packed into the low 4 bits. Comparators test only the value bits
    # (key >> 4), so ties swap exactly like the value-only CUTLASS network,
    # while the sort carries a single int32 tensor instead of V + P.
    if IS_ABS:
        xr = tl.abs(xr)
    xb = xr.to(tl.int16, bitcast=True).to(tl.int32)
    key16 = tl.where(xb < 0, (~xb) & 0xFFFF, (xb & 0xFFFF) | 0x8000)
    K = (key16 << 4) | (lane_ + tl.zeros((1, 8, 8), tl.int32))
    for e in tl.static_range(len(_NET16_A)):
        i = _NET16_A[e]
        j = _NET16_B[e]
        ki = tl.sum(tl.where(lane_ == i, K, 0), 0)
        kj = tl.sum(tl.where(lane_ == j, K, 0), 0)
        sw = ~((ki >> 4) < (kj >> 4))
        nki = tl.where(sw, kj, ki)
        nkj = tl.where(sw, ki, kj)
        K = tl.where(lane_ == i, nki[None, :, :], K)
        K = tl.where(lane_ == j, nkj[None, :, :], K)

    # Recover the original lane order from the sorted keys.
    P = K & 0xF

    # LargestValuesGreedy: visit from the largest, keep while row/col
    # counts are below 2.
    S = tl.zeros((16, 8, 8), tl.int32)
    for step in tl.static_range(15, -1, -1):
        which = tl.sum(tl.where(lane_ == step, P, 0), 0)  # (8,8)
        r4 = which // 4
        c4 = which % 4
        crow = tl.sum(S * ((lr == r4[None, :, :]).to(tl.int32)), 0)
        ccol = tl.sum(S * ((lc == c4[None, :, :]).to(tl.int32)), 0)
        ok = (crow < 2) & (ccol < 2)
        S += ((lane_ == which[None, :, :]) & ok[None, :, :]).to(tl.int32)

    # packed: per (tile, tile-row) two slots from the selected columns.
    # Values are gathered from the ORIGINAL tile values V0 by the selected
    # original lane index (ascending column order).
    ty = packed_ptr.dtype.element_ty
    for a in tl.static_range(4):
        sel = (S != 0) & (lr == a)
        cnt = tl.sum(sel.to(tl.int32), 0)
        c0 = tl.min(tl.where(sel, lc, 4), 0)
        c1 = tl.min(tl.where(sel & (lc != c0[None, :, :]), lc, 4), 0)
        two = cnt == 2
        one = cnt == 1
        late = one & (c0 >= 2)
        c0e = tl.where(cnt > 0, c0, 0)
        c1e = tl.where(two, c1, tl.where(late, c0, 0))
        v0 = tl.sum(tl.where(sel & (lc == c0e[None, :, :]), V0, 0.0), 0)
        v1 = tl.sum(tl.where(sel & (lc == c1e[None, :, :]), V0, 0.0), 0)
        g0 = tl.where(two | (one & (c0 < 2)), v0, 0.0)
        g1 = tl.where(two | late, v1, 0.0)
        # canonical 4-bit quad: idx0 | idx1 << 2
        qv = tl.where(
            two,
            c0 | (c1 << 2),
            tl.where(
                one, tl.where(c0 < 2, c0 | ((c0 ^ 1) << 2), (c0 ^ 1) | (c0 << 2)), 0
            ),
        )
        pr = row0 + ti * 4 + a
        qrow = (row0 + ti * 4 + a)[:, None]
        qcol = (pid_c * 8 + tj)[None, :]
        tl.store(qbuf_ptr + qrow * qb_stride + qcol, qv.to(tl.int16))
        for s in tl.static_range(2):
            pc = pid_c * 16 + tj * 2 + s
            offs = packed_ptr + pr * spm + pc
            val = g0 if s == 0 else g1
            tl.store(offs, val.to(ty))

    # packed_trans: the same selection on the transposed tile grid
    # (grid transpose + in-tile transpose).
    tyt = packed_t_ptr.dtype.element_ty
    for a in tl.static_range(4):
        sel = (S != 0) & (lc == a)
        cnt = tl.sum(sel.to(tl.int32), 0)
        lk = lr
        c0 = tl.min(tl.where(sel, lk, 4), 0)
        c1 = tl.min(tl.where(sel & (lk != c0[None, :, :]), lk, 4), 0)
        two = cnt == 2
        one = cnt == 1
        late = one & (c0 >= 2)
        c0e = tl.where(cnt > 0, c0, 0)
        c1e = tl.where(two, c1, tl.where(late, c0, 0))
        t0 = tl.sum(tl.where(sel & (lk == c0e[None, :, :]), V0, 0.0), 0)
        t1 = tl.sum(tl.where(sel & (lk == c1e[None, :, :]), V0, 0.0), 0)
        u0 = tl.where(two | (one & (c0 < 2)), t0, 0.0)
        u1 = tl.where(two | late, t1, 0.0)
        qvt = tl.where(
            two,
            c0 | (c1 << 2),
            tl.where(
                one, tl.where(c0 < 2, c0 | ((c0 ^ 1) << 2), (c0 ^ 1) | (c0 << 2)), 0
            ),
        )
        pr_t = col0 + tj * 4 + a
        mt = pr_t < rows_t
        qrow_t = pr_t[:, None]
        qcol_t = (pid_r * 8 + ti)[None, :]
        tl.store(qbuf_t_ptr + qrow_t * qbt_stride + qcol_t, qvt.to(tl.int16), mask=mt)
        for s in tl.static_range(2):
            pc_t = pid_r * 16 + ti * 2 + s
            m2 = mt & (pc_t < width_t)
            offs = packed_t_ptr + pr_t[:, None] * width_t + pc_t[None, :]
            val = u0 if s == 0 else u1
            tl.store(offs, val.to(tyt), mask=m2)

    # threads_masks: per-tile 16-bit selection mask split into the four
    # quadrant byte slots.
    vals16 = tl.sum(S * (1 << lane_), 0)
    lo = (vals16 & 0xFF).to(tl.uint8)
    hi = ((vals16 >> 8) & 0xFF).to(tl.uint8)
    t1 = tl.arange(0, 8)
    q8 = (t1[:, None] % 2) * 2 + (t1[None, :] % 2)  # (8,8) quadrant id
    ii = pid_r * 4 + t1 // 2
    jj = pid_c * 4 + t1 // 2
    zero_u = tl.zeros((8, 8), tl.uint8)
    for s in tl.static_range(8):
        is_lo = s == 2 * q8
        is_hi = s == 2 * q8 + 1
        val = tl.where(is_lo, lo, tl.where(is_hi, hi, zero_u))
        offs = masks_ptr + ii[:, None] * sm0 + jj[None, :] * sm1 + s
        # Only the element whose quadrant owns slot s may write; unmasked
        # zero stores from the other 3 lanes sharing (ii,jj) would race.
        tl.store(offs, val, mask=is_lo | is_hi)


@triton.jit
def _meta_reorder(qbuf_ptr, qb_stride, meta_ptr, m_total_rows, n16, ncols2):
    pid_r = tl.program_id(0)
    pid_c = tl.program_id(1)
    r = pid_r * 32 + tl.arange(0, 32)
    j = pid_c * 16 + tl.arange(0, 16)
    mr = r < m_total_rows
    mj = j < n16
    mm = mr[:, None] & mj[None, :]
    val = tl.zeros((32, 16), tl.int32)
    for q in tl.static_range(4):
        qv = tl.load(
            qbuf_ptr + r[:, None] * qb_stride + (4 * j + q)[None, :], mask=mm, other=0
        ).to(tl.int32)
        val += (qv & 0xF) << (4 * q)
    # CUTLASS ColumnMajorInterleaved<2> scatter
    dr = (r // 32) * 32 + (r % 8) * 4 + (r % 32) // 8
    dr_ = dr[:, None]
    j_ = j[None, :]
    tr = ((dr_ % 2 == 0) & (j_ % 2 == 1)).to(tl.int32)
    bl = ((dr_ % 2 == 1) & (j_ % 2 == 0)).to(tl.int32)
    dr2 = dr_ + tr - bl
    dc2 = j_ - tr + bl
    off = (dc2 // 2) * (2 * m_total_rows) + dr2 * 2 + (dc2 % 2)
    tl.store(meta_ptr + off, val.to(tl.int16), mask=mm)


def _causal1122(dense):
    """Host fallback for the causal1122 algorithm (per-tile-row capacities)."""
    rows, cols = dense.shape
    rows_r = (rows + 31) // 32 * 32
    cols_r = (cols + 63) // 64 * 64
    padded = torch.full(
        (rows_r, cols_r), float("-inf"), dtype=torch.float32, device=dense.device
    )
    padded[:rows, :cols] = dense.to(torch.float32)
    nb, ntb = rows_r // 4, cols_r // 4
    tiles = padded.view(nb, 4, ntb, 4).permute(0, 2, 1, 3).reshape(-1, 16)
    n = tiles.shape[0]
    k4 = tiles.view(n, 4, 4)
    out = torch.zeros(n, 4, 4, dtype=torch.bool, device=dense.device)
    ar = torch.arange(n, device=dense.device)
    max_row = torch.tensor([1, 1, 2, 2], device=dense.device)
    col_count = torch.zeros(n, 4, dtype=torch.long, device=dense.device)
    for row in range(4):
        vals = k4[:, row, :].clone()
        pos = torch.arange(4, device=dense.device).unsqueeze(0).repeat(n, 1)
        for a, b in ((0, 1), (2, 3), (0, 2), (1, 3), (1, 2)):
            swap = ~(vals[:, a] < vals[:, b])
            va = vals[:, a].clone()
            pa = pos[:, a].clone()
            vals[:, a] = torch.where(swap, vals[:, b], vals[:, a])
            pos[:, a] = torch.where(swap, pos[:, b], pos[:, a])
            vals[:, b] = torch.where(swap, va, vals[:, b])
            pos[:, b] = torch.where(swap, pa, pos[:, b])
        row_count = torch.zeros(n, dtype=torch.long, device=dense.device)
        for step in range(3, -1, -1):
            which = pos[:, step]
            col = which % 4
            keep = (col_count[ar, col] < 2) & (row_count < max_row[row])
            chosen = torch.zeros(n, 4, dtype=torch.bool, device=dense.device)
            chosen[ar, which] = keep
            out[:, row, :] |= chosen
            row_count += chosen.sum(dim=1)
            col_count += chosen.long()
    sel = out.view(nb, ntb, 16)
    pruned = torch.where(sel, tiles, torch.zeros_like(tiles)).view(nb, ntb, 4, 4)
    # reuse the packing helpers through the generic path below
    return pruned.permute(0, 2, 1, 3).reshape(rows_r, cols_r)


def _sparse_semi_structured_tile(input, algorithm: str = "", use_cutlass: bool = True):
    logger.debug("GEMS SPARSE_SEMI_STRUCTURED_TILE")

    dense = input
    if dense.dim() != 2:
        raise RuntimeError("Can only sparsify 2d tensors")
    if dense.dtype not in (torch.float16, torch.bfloat16):
        raise TypeError(
            "_sparse_semi_structured_tile supports only float16 and bfloat16 "
            f"inputs, got {dense.dtype}"
        )
    if dense.stride(1) != 1:
        raise RuntimeError(
            "Can only sparsify contiguous tensors. Sparsify the transpose otherwise."
        )
    rows, cols = dense.shape
    if cols % 32 != 0:
        raise RuntimeError("Number of cols should be multiple of 32")
    if algorithm not in _ALGORITHMS:
        raise RuntimeError(f'Unknown algorithm "{algorithm}"')
    if not use_cutlass:
        raise NotImplementedError(
            "_sparse_semi_structured_tile only implements the CUTLASS metadata "
            "layout (use_cutlass=True)"
        )
    if algorithm == "causal1122":
        raise NotImplementedError(
            '_sparse_semi_structured_tile does not implement the "causal1122" '
            "algorithm yet; use the default or largest_*_greedy"
        )

    rows_r = (rows + 31) // 32 * 32
    cols_r = (cols + 63) // 64 * 64
    dev = dense.device

    packed = torch.zeros(rows_r, cols_r // 2, dtype=dense.dtype, device=dev)
    meta = torch.zeros(rows_r * cols_r // 16, dtype=torch.int16, device=dev)
    rows_t = (cols + 31) // 32 * 32
    width_t = (rows + 63) // 64 * 64 // 2
    packed_t = torch.zeros(rows_t, width_t, dtype=dense.dtype, device=dev)
    ncols_t = (rows + 63) // 64 * 64 // 16
    meta_t = torch.zeros(rows_t * ncols_t, dtype=torch.int16, device=dev)
    masks = torch.zeros(rows_r // 8, cols_r // 8, 8, dtype=torch.uint8, device=dev)
    qbuf = torch.zeros(rows_r, cols_r // 4, dtype=torch.int16, device=dev)
    qbuf_t = torch.zeros(rows_t, rows_r // 4, dtype=torch.int16, device=dev)

    grid = (rows_r // 32, cols_r // 32)
    _ssst_kernel[grid](
        dense,
        dense.stride(0),
        rows,
        cols,
        packed,
        packed.stride(0),
        packed_t,
        rows_t,
        width_t,
        qbuf,
        qbuf.stride(0),
        qbuf_t,
        qbuf_t.stride(0),
        masks,
        masks.stride(0),
        masks.stride(1),
        algorithm == "largest_abs_values_greedy",
    )
    _meta_reorder[(rows_r // 32, (cols_r // 16 + 15) // 16)](
        qbuf,
        qbuf.stride(0),
        meta,
        rows_r,
        cols_r // 16,
        cols_r // 32,
    )
    _meta_reorder[(rows_t // 32, (ncols_t + 15) // 16)](
        qbuf_t,
        qbuf_t.stride(0),
        meta_t,
        rows_t,
        ncols_t,
        ncols_t // 2,
    )
    # The reorder kernels scatter into the CUTLASS physical buffer; the aten
    # output view exposes it as (rows, 2, cols/32) with element (r, k, c) at
    # offset 2r + k + rows*2*c.
    meta = meta.view(cols_r // 32, rows_r, 2).permute(1, 2, 0)
    meta_t = meta_t.view(ncols_t // 2, rows_t, 2).permute(1, 2, 0)
    return (packed, meta, packed_t, meta_t, masks)
