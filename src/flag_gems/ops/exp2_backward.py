"""Autograd bridge and Triton backward kernel for ``aten::exp2``.

The pinned Torch build exposes no ``aten::exp2_backward`` schema: ATen
derives the input gradient from the autograd formula
``grad * result.conj() * M_LN2`` -- the gradient of ``exp2`` is the output
gradient multiplied by the (already stored) forward result ``exp2(x)``
and the constant ``ln(2)``.

The kernel below fuses the ATen two-kernel chain (``exp2`` recompute, then
the gradient multiply) into a single launch while keeping ATen's
per-op rounding boundaries: the recomputed ``exp2(x)`` is rounded to
the storage dtype before the multiply, and the product is rounded
again on store, so fp32/fp16/bf16 gradients are bit-exact against
native autograd.

The launch passes ``enable_reflect_ftz=False`` so Triton keeps denormal
support in the compiled libdevice call: the default (FTZ on) flushes
``exp2(x)`` subnormals below ``2**-126`` to zero, which diverges from ATen
by up to 1 ULP on inputs below ``-126``.
"""

import logging

import torch
import triton
import triton.language as tl
import triton.language.extra.libdevice as libdevice

from flag_gems.runtime import torch_device_fn

logger = logging.getLogger(__name__)

# d/dx exp2(x) = exp2(x) * ln(2)
_M_LN2 = 0.6931471805599453

# The block size is dispatched on the tensor size: launch-bound small tensors
# win from more CTAs, large streaming tensors from the wider block.
_SMALL_NUMEL = 4096
_SMALL_BLOCK = 256
_LARGE_BLOCK = 1024
_NUM_WARPS = 4


@triton.jit
def _exp2_backward_kernel(
    grad_output_ptr,
    x_ptr,
    grad_input_ptr,
    n_elements,
    BLOCK: tl.constexpr,
    LOWP: tl.constexpr,  # 0 = fp32, 1 = fp16, 2 = bf16
):
    pid = tl.program_id(axis=0)
    offsets = pid * BLOCK + tl.arange(0, BLOCK)
    mask = offsets < n_elements

    grad = tl.load(grad_output_ptr + offsets, mask=mask, other=0.0)
    x = tl.load(x_ptr + offsets, mask=mask, other=0.0)

    # All math runs in fp32 and every step is rounded back to the storage
    # dtype, exactly like ATen's sequence of elementwise kernels does.
    xf = x.to(tl.float32)
    gf = grad.to(tl.float32)

    # Step 1: y = exp2(x). ATen recomputes exp2 inside the backward graph;
    # libdevice.exp2 matches its `exp2f` for every storage dtype.
    y = libdevice.exp2(xf)
    if LOWP == 1:
        y = y.to(tl.float16).to(tl.float32)
    elif LOWP == 2:
        y = y.to(tl.bfloat16).to(tl.float32)

    # Step 2: grad_input = grad_output * y  (binary mul, rounded)
    out = gf * y
    if LOWP == 1:
        out = out.to(tl.float16).to(tl.float32)
    elif LOWP == 2:
        out = out.to(tl.bfloat16).to(tl.float32)

    # Step 3: multiply by ln(2)
    result = out * 0.6931471805599453
    if LOWP == 1:
        result = result.to(tl.float16)
    elif LOWP == 2:
        result = result.to(tl.bfloat16)

    tl.store(grad_input_ptr + offsets, result, mask=mask)


def _lowp_code(dtype: torch.dtype) -> int:
    if dtype == torch.float16:
        return 1
    if dtype == torch.bfloat16:
        return 2
    return 0


def exp2_backward(grad_output: torch.Tensor, x: torch.Tensor):
    """Gradient of ``exp2``: elementwise ``grad_output * exp2(x) * ln(2)``.

    Args:
        grad_output: Gradient w.r.t. the ``exp2`` output.
        x: Original input tensor of ``exp2`` (used to recompute the output).

    Returns:
        Gradient w.r.t. the input, with the same dtype as ``x``.
    """
