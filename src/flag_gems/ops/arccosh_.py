def arccosh_(A):
    logger.debug("GEMS ARCCOSH_")
    n = A.numel()
    if n == 0:
        return A
    if A.is_contiguous():
        _launch_flat(A, n)
        return A
    spec = _collapse(A.shape, A.stride())
    if len(spec) == 1 and spec[0][1] == 1:
        # effectively flat, unit stride
        _launch_flat(A, n)
        return A
    if len(spec) > _MAX_RANK:
        arccosh_func(A, out0=A)
        return A
    _launch_strided(A, spec)
    return A
