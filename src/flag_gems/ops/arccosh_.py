@triton.jit
def arccosh_func(x):
    # arccosh(x) = log(x + sqrt(x - 1) * sqrt(x + 1))
    x32 = x.to(tl.float32)
    t = x32 - 1.0
    # ``t`` is exact (Sterbenz), so t * (t + 2) == x^2 - 1 keeps precision near 1
    y32 = tl.log(x32 + tl.sqrt(t * (t + 2.0)))
    return y32.to(x.dtype)


@triton.jit
def _acosh_vec(x, FAST: tl.constexpr):
    """log(x + sqrt(x^2 - 1)) with the sqrt formed stably from x-1.

    ``t = x - 1`` is exact (Sterbenz), so ``t * (t + 2) = x^2 - 1`` keeps full
    relative precision near x == 1 and a single sqrt replaces the two the
    previous form used.

    FAST uses ``p * rsqrt(p)`` (the hardware approximate reciprocal sqrt) for
    2-byte dtypes, where the fp16/bf16 rounding of the stored result dominates
    the ~1e-7 relative error of the approximation; the two NaN corners of that
    identity (p == 0 -> 0*inf, p == inf -> inf*0) are patched by falling back to
    p itself, which is the right value in both cases (acosh(1) = 0,
    acosh(inf) = inf).
    """
    xf = x.to(tl.float32)
    t = xf - 1.0
    p = t * (t + 2.0)
    if FAST:
        s = p * tl.rsqrt(p)
        s = tl.where(s == s, s, p)
    else:
        s = tl.sqrt(p)
    y = tl.log(xf + s)
    return tl.where(xf >= 1.0, y, float("nan"))


