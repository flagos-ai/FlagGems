def _bind_runner(compiled, grid_x, dev):
    try:
        from triton import knobs as _trt_knobs
        from triton.runtime import driver as _trt_driver

        stream = _trt_driver.active.get_current_stream(dev)
        run = compiled.run
        fn = compiled.function
        meta = compiled.packed_metadata
        enter = _trt_knobs.runtime.launch_enter_hook
        leave = _trt_knobs.runtime.launch_exit_hook
    except Exception:
        return None

    def _runner(*args):
        run(grid_x, 1, 1, stream, fn, meta, None, enter, leave, *args)

    return _runner


def _launcher(kern, grid, num_warps, consts, tag=()):
    """``fn(*runtime_args)`` for one fixed launch plan (tag = JIT-specialised
    operand dtypes, which are not part of ``consts``)."""
    grid_x = grid if isinstance(grid, int) else int(grid[0])
    key = (id(kern), grid_x, num_warps, consts, tag)

    def jit_launch(*args):
        return kern[(grid_x,)](*args, *consts, num_warps=num_warps)

    def launch(*args):
        dev = torch_device_fn.current_device()
        st = _LAUNCH_STATE.get(key)
        if st is not None and st[0] == dev:
            st[1](*args, *consts)
            return
        runner = _bind_runner(jit_launch(*args), grid_x, dev) or jit_launch
        _LAUNCH_STATE[key] = (dev, runner)

    return launch


def _plan(key, build):
    fn = _PLAN.get(key)
    if fn is None:
        if len(_PLAN) >= 256:
            _PLAN.clear()
        fn = _PLAN[key] = build()
    return fn


def _collapse(shape, strides):
    """Collapse a strided layout into <= _MAX_RANK dims, innermost = smallest stride."""
    dims = [(int(s), int(st)) for s, st in zip(shape, strides) if int(s) != 1]
    if not dims:
        return [(1, 1)]
    # outer dims first (largest stride), innermost last (smallest stride)
    dims = sorted(dims, key=lambda p: (-p[1], -p[0]))
    merged = []
    for s, st in dims:
        if merged:
            ps, pst = merged[-1]
            if pst == st * s:
                merged[-1] = (ps * s, st)
                continue
        merged.append((s, st))
    return merged


def _launch_flat(t, n):
    block = _BLOCK_WIDE if t.element_size() <= 2 else _BLOCK
    fast = t.element_size() <= 2
    if n < block:
        # launch-latency bound: one program, tile shrunk to the tensor
        block = max(1024, triton.next_power_of_2(n))
    grid = (min(triton.cdiv(n, block), _MAX_GRID),)
    consts = (n >= 2147483648, (n % block) == 0, fast, block)
    # the grid is part of the plan: two sizes can share consts (both launch the
    # same compiled kernel) but must not share the launch geometry
    _plan(
        (_arccosh_flat, consts, grid, t.dtype),
        lambda: _launcher(_arccosh_flat, grid, _NUM_WARPS, consts, t.dtype),
    )(t, n)


