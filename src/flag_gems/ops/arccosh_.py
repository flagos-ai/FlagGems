"""In-place arccosh (aten::arccosh_).

Semantics preserved from the reference:
  self[i] = acosh(self[i]) computed in fp32, result cast back to self.dtype.
  The very same Tensor object is returned (identity + storage preserved).

Numerically stable form:
  t = x - 1
  y = log(1 + t + sqrt(t) * sqrt(t + 2))
which is exact at x == 1 (+0.0), returns +inf at x == +inf, and never
overflows for large x (unlike log(x + sqrt(x*x - 1))).
Domain guard: y = NaN where x < 1 (also keeps NaN inputs NaN).

Both kernels use a persistent grid-stride loop (grid capped at a small
constant, far below the device grid.x limit) and the flat kernel has an EVEN
specialization that drops the tail mask when numel is an exact multiple of
BLOCK, which is the common case for the measured workloads.
"""

