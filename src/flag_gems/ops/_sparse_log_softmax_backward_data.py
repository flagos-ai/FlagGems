def _pool_key(shape, sdim, dim):
    """Pool (group) key strides and the pool count.

    torch's ``get_offsets`` removes the reduced axis from the pool key only
    when a *positive* ``dim`` is inside the sparse rank; a literal negative
    ``dim`` is never matched and keeps the full coordinate.  The pool is
    therefore "every sparse coordinate except the one along `dim`" for
    ``0 <= dim < sparse_dim`` and the full coordinate otherwise.
    """
    if 0 <= dim < sdim:
        retained = [a for a in range(sdim) if a != dim]
    else:
        retained = list(range(sdim))
    sizes = [int(shape[a]) for a in retained]
    strides = [1] * len(sizes)
    run = 1
    for i in range(len(sizes) - 1, -1, -1):
        strides[i] = run
        run *= sizes[i]
    key = [0] * max(sdim, 1)
    for i, a in enumerate(retained):
        key[a] = strides[i]
    return key, max(run, 1)


def _plain_strides(shape, sdim):
    """Ordinary row-major strides of the sparse axes (the join key)."""
    strides = [1] * max(sdim, 1)
    for i in range(sdim - 2, -1, -1):
        strides[i] = strides[i + 1] * int(shape[i + 1])
    return strides


def _keys(idx, nnz, strides, rank):
    out = torch.empty(nnz, dtype=torch.int64, device=idx.device)
    if rank == 0:
        out.zero_()
        return out
    if nnz == 0:
        return out
    s_t = torch.tensor(list(strides), dtype=torch.int64, device=idx.device)
    _row_key_kernel[(triton.cdiv(nnz, 1024),)](
        _flat(idx),
        out,
        nnz,
        s_t,
        RANK=len(strides),
        BLOCK=1024,
    )
    return out


