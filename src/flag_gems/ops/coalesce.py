"""Triton implementation of ``aten::coalesce`` for COO sparse tensors.

Pipeline (all real device work stays inside triton kernels):

1. ``_coalesce_hist``     - zero the value accumulator and the unique-key
                            counter, mark the set of linear keys present in the
                            input, and (when the key space fits in 32 bits)
                            publish each element's linear key so the scatter
                            kernel can reload it coalesced.
2. ``_coalesce_scan``     - word-level popcount + inclusive scan, pack
                            ``(exclusive_prefix << 32) | word_bits`` per word and
                            publish the per-superblock totals.
3. ``_coalesce_scatter``  - rank every stored element, atomically accumulate its
                            value into the dense accumulator and record the
                            element's linear key at the ranked position. The
                            per-superblock offsets are folded into this kernel as
                            an in-register scan, so no separate scan kernel
                            launch is needed for the workload sizes in use.
4. ``_coalesce_finalize`` - decode the ranked linear keys back into per-dimension
                            coordinates (a fully coalesced div/mod pass) and cast
                            the dense accumulator to the output dtype over the
                            first ``r`` (final nnz) slots; ``r`` is read from the
                            device so the host never drains the pipeline early.

Only the resulting COO tensor is returned; the input tensor is never mutated.
"""

import logging

import torch
import triton
import triton.language as tl

logger = logging.getLogger(__name__)

_U32_MAX = 1 << 32
_HIST_BLOCK = 1024
_SCAN_SB_LOG = 11
_SCAN_SB = 1 << _SCAN_SB_LOG
_SCAN_BLOCK = 2048
_FIN_BLOCK = 1024
_SB_INREG_MAX = 1024

_FP8 = tuple(
    d
    for d in (
        getattr(torch, "float8_e4m3fn", None),
        getattr(torch, "float8_e5m2", None),
        getattr(torch, "float8_e4m3fnuz", None),
        getattr(torch, "float8_e5m2fnuz", None),
    )
    if d is not None
)

_F32_DT = (torch.float16, torch.bfloat16, torch.float32)
_F64_DT = (torch.float64,)
_I_DT = (torch.bool, torch.int8, torch.uint8, torch.int16, torch.int32, torch.int64)


@triton.jit
def _popc32(x):
    """Population count of a 32-bit pattern held in an int32 value."""
    x = x - ((x >> 1) & 0x55555555)
    x = (x & 0x33333333) + ((x >> 2) & 0x33333333)
    x = (x + (x >> 4)) & 0x0F0F0F0F
    x = x + (x >> 8)
    x = x + (x >> 16)
    return x & 0x3F


@triton.jit
def _fold_key(
    idx_ptr,
    offs,
    m,
    n,
    S,
    D1: tl.constexpr,
    D2: tl.constexpr,
    D3: tl.constexpr,
    D4: tl.constexpr,
):
    """Row-major linear key; ``Dm`` is shape[m] for m >= 1.

    The dims are constexpr, so a power-of-two shape folds into shifts and adds
    instead of runtime integer multiplies.
    """
    k = tl.load(idx_ptr + offs, mask=m, other=0)
    if S > 1:
        k = k * D1 + tl.load(idx_ptr + n + offs, mask=m, other=0)
    if S > 2:
        k = k * D2 + tl.load(idx_ptr + 2 * n + offs, mask=m, other=0)
    if S > 3:
        k = k * D3 + tl.load(idx_ptr + 3 * n + offs, mask=m, other=0)
    if S > 4:
        k = k * D4 + tl.load(idx_ptr + 4 * n + offs, mask=m, other=0)
    return k


@triton.jit
def _coalesce_hist(
    idx_ptr,
    bits_ptr,
    acc_ptr,
    cnt_ptr,
    key_out_ptr,
    n,
    S,
    D1: tl.constexpr,
    D2: tl.constexpr,
    D3: tl.constexpr,
    D4: tl.constexpr,
    WRITE_KEY: tl.constexpr,
    BLOCK: tl.constexpr,
):
    pid = tl.program_id(0)
    offs = pid * BLOCK + tl.arange(0, BLOCK)
    m = offs < n
    if pid == 0:
        tl.store(cnt_ptr, 0)
    # Zero this program's slice of the dense value accumulator; the scatter
    # kernel runs only after this kernel completes, so the plain stores are
    # race-free and replace a separate zeroing memset.
    tl.store(
        acc_ptr + offs,
        tl.zeros([BLOCK], dtype=acc_ptr.dtype.element_ty),
        mask=m,
    )
    k = _fold_key(idx_ptr, offs, m, n, S, D1, D2, D3, D4)
    if WRITE_KEY:
        # Publish the key so scatter can reload it coalesced rather than
        # re-reading every index row and re-folding it.
        tl.store(key_out_ptr + offs, k.to(tl.uint32), mask=m)
    w = (k >> 5).to(tl.int32)
    bit = tl.full([BLOCK], 1, tl.int32) << (k & 31).to(tl.int32)
    # Relaxed orderings are sufficient across this whole pipeline: the scratch
    # buffers are private to one launch and strictly stream-ordered.
    tl.atomic_or(bits_ptr + w, bit, mask=m, sem="relaxed")


@triton.jit
def _coalesce_scan(
    bits_ptr,
    table_ptr,
    blk_tot_ptr,
    cnt_ptr,
    NW,
    BLOCK: tl.constexpr,
):
    pid = tl.program_id(0)
    woffs = pid * BLOCK + tl.arange(0, BLOCK)
    wm = woffs < NW
    v = tl.load(bits_ptr + woffs, mask=wm, other=0)
    pc = _popc32(v)
    inc = tl.cumsum(pc, axis=0)
    exc = inc - pc
    packed = (exc.to(tl.int64) << 32) | (v.to(tl.int64) & 0xFFFFFFFF)
    tl.store(table_ptr + woffs, packed, mask=wm)
    tot = tl.sum(pc, axis=0)
    tl.store(blk_tot_ptr + pid, tot)
    tl.atomic_add(cnt_ptr, tot, sem="relaxed")


@triton.jit
def _coalesce_blkoff(
    blk_tot_ptr,
    blk_off_ptr,
    NB2,
    NTP: tl.constexpr,
):
    idx = tl.arange(0, NTP)
    m = idx < NB2
    t = tl.load(blk_tot_ptr + idx, mask=m, other=0)
    inc = tl.cumsum(t, axis=0)
    tl.store(blk_off_ptr + idx, inc - t, mask=m)


@triton.jit
def _coalesce_scatter(
    keyin_ptr,
    idx_ptr,
    vals_ptr,
    table_ptr,
    blk_tot_ptr,
    blk_off_ptr,
    acc_ptr,
    key_ptr,
    out_idx_ptr,
    n,
    NB2,
    S,
    D1: tl.constexpr,
    D2: tl.constexpr,
    D3: tl.constexpr,
    D4: tl.constexpr,
    NTP: tl.constexpr,
    KEY_PATH: tl.constexpr,
    INREG_SB: tl.constexpr,
    SB_LOG: tl.constexpr,
    BLOCK: tl.constexpr,
):
    pid = tl.program_id(0)
    offs = pid * BLOCK + tl.arange(0, BLOCK)
    m = offs < n
    if KEY_PATH:
        k = tl.load(keyin_ptr + offs, mask=m, other=0).to(tl.int64)
    else:
        k = _fold_key(idx_ptr, offs, m, n, S, D1, D2, D3, D4)
    w = (k >> 5).to(tl.int32)
    packed = tl.load(table_ptr + w, mask=m, other=0)
    exc = (packed >> 32).to(tl.int32)
    bits = (packed & 0xFFFFFFFF).to(tl.int32)
    lmask = (tl.full([BLOCK], 1, tl.int32) << (k & 31).to(tl.int32)) - 1
    if INREG_SB:
        # Each program re-derives the superblock exclusive offsets in registers;
        # NB2 is small enough for this size class that no extra launch is needed.
        sidx = tl.arange(0, NTP)
        st = tl.load(blk_tot_ptr + sidx, mask=sidx < NB2, other=0)
        soff = tl.cumsum(st, axis=0) - st
        blk = tl.gather(soff, w >> SB_LOG, axis=0)
    else:
        blk = tl.load(blk_off_ptr + (w >> SB_LOG), mask=m, other=0)
    pos = exc + _popc32(bits & lmask) + blk
    raw = tl.load(vals_ptr + offs, mask=m, other=0)
    val = tl.where(m, raw, 0).to(acc_ptr.dtype.element_ty)
    tl.atomic_add(acc_ptr + pos, val, mask=m)
    if KEY_PATH:
        tl.store(key_ptr + pos, k.to(tl.uint32), mask=m)
    else:
        for d in range(0, S):
            u = tl.load(idx_ptr + d * n + offs, mask=m, other=0)
            tl.store(out_idx_ptr + d * n + pos, u, mask=m)


@triton.jit
def _coalesce_finalize(
    acc_ptr,
    out_ptr,
    cnt_ptr,
    key_ptr,
    out_idx_ptr,
    n,
    S,
    D1: tl.constexpr,
    D2: tl.constexpr,
    D3: tl.constexpr,
    D4: tl.constexpr,
    KEY_PATH: tl.constexpr,
    IS_BOOL: tl.constexpr,
    BLOCK: tl.constexpr,
):
    pid = tl.program_id(0)
    offs = pid * BLOCK + tl.arange(0, BLOCK)
    m = offs < tl.load(cnt_ptr)
    v = tl.load(acc_ptr + offs, mask=m, other=0)
    if IS_BOOL:
        v = (v != 0).to(tl.int64)
    tl.store(out_ptr + offs, v.to(out_ptr.dtype.element_ty), mask=m)
    if KEY_PATH:
        k = tl.load(key_ptr + offs, mask=m, other=0).to(tl.int64)
        if S == 1:
            tl.store(out_idx_ptr + offs, k, mask=m)
        elif S == 2:
            c0 = k // D1
            tl.store(out_idx_ptr + offs, c0, mask=m)
            tl.store(out_idx_ptr + n + offs, k - c0 * D1, mask=m)
        elif S == 3:
            c0 = k // (D1 * D2)
            rem = k - c0 * (D1 * D2)
            c1 = rem // D2
            tl.store(out_idx_ptr + offs, c0, mask=m)
            tl.store(out_idx_ptr + n + offs, c1, mask=m)
            tl.store(out_idx_ptr + 2 * n + offs, rem - c1 * D2, mask=m)
        elif S == 4:
            c0 = k // (D1 * D2 * D3)
            rem = k - c0 * (D1 * D2 * D3)
            c1 = rem // (D2 * D3)
            rem2 = rem - c1 * (D2 * D3)
            c2 = rem2 // D3
            tl.store(out_idx_ptr + offs, c0, mask=m)
            tl.store(out_idx_ptr + n + offs, c1, mask=m)
            tl.store(out_idx_ptr + 2 * n + offs, c2, mask=m)
            tl.store(out_idx_ptr + 3 * n + offs, rem2 - c2 * D3, mask=m)
        else:
            c0 = k // (D1 * D2 * D3 * D4)
            rem = k - c0 * (D1 * D2 * D3 * D4)
            c1 = rem // (D2 * D3 * D4)
            rem2 = rem - c1 * (D2 * D3 * D4)
            c2 = rem2 // (D3 * D4)
            rem3 = rem2 - c2 * (D3 * D4)
            c3 = rem3 // D4
            tl.store(out_idx_ptr + offs, c0, mask=m)
            tl.store(out_idx_ptr + n + offs, c1, mask=m)
            tl.store(out_idx_ptr + 2 * n + offs, c2, mask=m)
            tl.store(out_idx_ptr + 3 * n + offs, c3, mask=m)
            tl.store(out_idx_ptr + 4 * n + offs, rem3 - c3 * D4, mask=m)


def coalesce(self):
    """Coalesce a COO sparse tensor, matching ``aten::coalesce`` semantics."""
    logger.debug("GEMS COALESCE")
    if self.layout != torch.sparse_coo:
        raise RuntimeError(
            "coalesce expected sparse coordinate tensor layout but got "
            f"{self.layout}"
        )
    if self.dense_dim() != 0:
        raise NotImplementedError("coalesce with dense dimensions is not implemented")

    values = self._values()
    vdt = values.dtype
    if vdt in _FP8 or (vdt not in _F32_DT and vdt not in _F64_DT and vdt not in _I_DT):
        raise NotImplementedError(f'"coalesce_sparse_cuda" not implemented for {vdt!r}')

    if self.is_coalesced() or self._nnz() == 0:
        return self

    shape = tuple(int(d) for d in self.shape)
    S = self.sparse_dim()
    n = self._nnz()
    dev = self.device

    if vdt in _F32_DT:
        adt = torch.float32
    elif vdt in _F64_DT:
        adt = torch.float64
    else:
        adt = torch.int64

    K = 1
    for d in shape:
        K *= d
    key_path = K < _U32_MAX
    NW = (K + 31) // 32
    NB2 = (NW + _SCAN_SB - 1) // _SCAN_SB
    inreg_sb = NB2 <= _SB_INREG_MAX
    NTP = max(16, triton.next_power_of_2(NB2)) if inreg_sb else 16
    dims = list(shape) + [0] * (5 - len(shape))
    D1, D2, D3, D4 = dims[1], dims[2], dims[3], dims[4]

    indices = self._indices()

    bits = torch.zeros(NW, dtype=torch.int32, device=dev)
    table = torch.empty(NW, dtype=torch.int64, device=dev)
    cnt = torch.empty(1, dtype=torch.int32, device=dev)
    is_bool = vdt == torch.bool
    out_vals = torch.empty(n, dtype=torch.uint8 if is_bool else vdt, device=dev)
    accbuf = torch.empty(n, dtype=adt, device=dev)
    # Two separate key buffers: the histogram publishes the consumed keys and
    # the scatter writes the ranked keys, so they must not alias.
    keyin = torch.empty(n, dtype=torch.uint32, device=dev)
    keys = torch.empty(n, dtype=torch.uint32, device=dev)
    out_idx = torch.empty(S * n, dtype=torch.int64, device=dev)
    if inreg_sb:
        blk_tot = torch.empty(NB2, dtype=torch.int32, device=dev)
        blk_off = blk_tot
    else:
        blk = torch.empty(NB2 + NTP, dtype=torch.int32, device=dev)
        blk_tot = blk[:NB2]
        blk_off = blk[NB2:]

    grid_n = (triton.cdiv(n, _HIST_BLOCK),)
    _coalesce_hist[grid_n](
        indices,
        bits,
        accbuf,
        cnt,
        keyin,
        n,
        S,
        D1,
        D2,
        D3,
        D4,
        WRITE_KEY=key_path,
        BLOCK=_HIST_BLOCK,
        num_warps=8,
    )
    _coalesce_scan[(triton.cdiv(NW, _SCAN_BLOCK),)](
        bits, table, blk_tot, cnt, NW, BLOCK=_SCAN_BLOCK, num_warps=8
    )
    if not inreg_sb:
        _coalesce_blkoff[(1,)](blk_tot, blk_off, NB2, NTP=NTP)
    _coalesce_scatter[grid_n](
        keyin,
        indices,
        values,
        table,
        blk_tot,
        blk_off,
        accbuf,
        keys,
        out_idx,
        n,
        NB2,
        S,
        D1,
        D2,
        D3,
        D4,
        NTP=NTP,
        KEY_PATH=key_path,
        INREG_SB=inreg_sb,
        SB_LOG=_SCAN_SB_LOG,
        BLOCK=_HIST_BLOCK,
        num_warps=8,
    )
    _coalesce_finalize[grid_n](
        accbuf,
        out_vals,
        cnt,
        keys,
        out_idx,
        n,
        S,
        D1,
        D2,
        D3,
        D4,
        KEY_PATH=key_path,
        IS_BOOL=is_bool,
        BLOCK=_FIN_BLOCK,
    )

    # Single trailing device->host read; every kernel above is already queued.
    r = int(cnt.item())
    if r <= 0:
        return self

    out_indices = out_idx.view(S, n)[:, :r]
    out_values = out_vals[:r]
    if is_bool:
        out_values = out_values.view(torch.bool)
    return torch.sparse_coo_tensor(
        out_indices, out_values, shape, device=dev, is_coalesced=True
    )
