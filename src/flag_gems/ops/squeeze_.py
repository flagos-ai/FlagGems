logger = logging.getLogger(__name__)


def _normalize_dim(dim: int, ndim: int) -> int:
    """Normalize a dimension index the way ATen does for squeeze.

    ATen reports the valid range as ``[-nd, nd - 1]`` where ``nd`` is at least
    1, which is why a 0-d tensor accepts ``dim=0`` and ``dim=-1``.
    """
    nd = max(ndim, 1)
    if not -nd <= dim <= nd - 1:
        raise IndexError(
            f"Dimension out of range (expected to be in range of "
            f"[-{nd}, {nd - 1}], but got {dim})"
        )
    return dim + nd if dim < 0 else dim


def _squeeze_inplace(self: torch.Tensor, drop) -> torch.Tensor:
    """Rebind ``self`` in place with the dimension indices in ``drop`` removed.

    squeeze is a pure metadata operation: the surviving sizes, strides and the
    storage offset are kept verbatim so the result aliases the same storage.
    ``as_strided_`` performs the metadata write in place, which also bumps the
    version counter and honours autograd's in-place checks exactly like
    ``aten::squeeze_`` does -- including the no-op calls where nothing is
    removed.
    """
    shape = self.shape
    strides = self.stride()
    new_shape = [size for i, size in enumerate(shape) if i not in drop]
    new_strides = [stride for i, stride in enumerate(strides) if i not in drop]
    self.as_strided_(new_shape, new_strides, self.storage_offset())
    return self


