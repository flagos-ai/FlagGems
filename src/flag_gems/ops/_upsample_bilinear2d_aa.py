        if exact_h:
            num_h64 = num_h + zero64
            den_h64 = den_h + zero64
            if num_h >= den_h:
                start_num_h = (2 * oh_safe - 1) * num_h64 + den_h64
                end_num_h = (2 * oh_safe + 3) * num_h64 + den_h64
            else:
                start_num_h = (2 * oh_safe + 1) * num_h64 - den_h64
                end_num_h = (2 * oh_safe + 1) * num_h64 + 3 * den_h64
            span_start_h = (tl.maximum(start_num_h, 0) // (2 * den_h64)).to(tl.int32)
            span_end_h = tl.minimum((end_num_h // (2 * den_h64)).to(tl.int32), IH)
            span_size_h = span_end_h - span_start_h
