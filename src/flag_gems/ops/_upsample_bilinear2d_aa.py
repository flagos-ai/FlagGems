def bilinear_scale_params(src_size, dst_size, align_corners, scale):
    if align_corners:
        if dst_size > 1:
            return (src_size - 1) / (dst_size - 1), src_size - 1, dst_size - 1, True
        return 0.0, 0, 1, True
    if scale is not None and scale > 0:
        return 1.0 / scale, 0, 1, False
    return src_size / dst_size, src_size, dst_size, True


