def _upsample_bilinear2d_aa(
    input: torch.Tensor,
    output_size: Tuple[int],
    align_corners: bool = False,
    scales_h: Optional[float] = None,
    scales_w: Optional[float] = None,
):
    logger.debug("GEMS UPSAMPLE_BILINEAR2D_AA")
    assert input.device.type == device.name
    assert input.ndim == 4, "The ndim of input must be 4"
    assert len(output_size) == 2, "The len of output_size must be 2"

    OH, OW = output_size
    N, C, IH, IW = input.shape
    output = torch.empty((N, C, OH, OW), device=input.device, dtype=input.dtype)
    if output.numel() == 0:
        return output

    input = input.contiguous()
    reciprocal_scale_h, num_h, den_h, exact_h = bilinear_scale_params(
        IH, OH, align_corners, scales_h
    )
    reciprocal_scale_w, num_w, den_w, exact_w = bilinear_scale_params(
        IW, OW, align_corners, scales_w
    )
    reciprocal_scale_h = float(reciprocal_scale_h)
    reciprocal_scale_w = float(reciprocal_scale_w)

    def grid(META):
        raw_x = triton.cdiv(OW, META["BLOCK_X"])
        raw_y = triton.cdiv(OH, META["BLOCK_Y"])
        if raw_x * raw_y <= 65535:
            return (raw_x, raw_y)
        gx = min(raw_x, 256)
        gy = min(raw_y, max(1, 65535 // gx))
        return (gx, gy)

    with torch_device_fn.device(input.device):
        if reciprocal_scale_h >= 1.0 or reciprocal_scale_w >= 1.0:
            support_h = reciprocal_scale_h if reciprocal_scale_h >= 1.0 else 1.0
            support_w = reciprocal_scale_w if reciprocal_scale_w >= 1.0 else 1.0
            interpolate_h = int(math.ceil(2.0 * support_h)) + 1
            interpolate_w = int(math.ceil(2.0 * support_w)) + 1
            general_interpolate_bilinear2d_aa_kernel[grid](
                output,
                input,
                N,
                C,
                OH,
                OW,
                IH,
                IW,
                reciprocal_scale_h,
                reciprocal_scale_w,
                num_h,
                den_h,
                num_w,
                den_w,
                exact_h,
                exact_w,
                interpolate_h,
                interpolate_w,
            )
        else:
            upsample_bilinear2d_aa_kernel[grid](
                output,
                input,
                N,
                C,
                OH,
                OW,
                IH,
                IW,
                reciprocal_scale_h,
                reciprocal_scale_w,
                num_h,
                den_h,
                num_w,
                den_w,
                exact_h,
                exact_w,
            )
    return output
