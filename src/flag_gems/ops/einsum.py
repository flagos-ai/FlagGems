import logging
from collections import Counter
from typing import List, Tuple

import torch

from flag_gems.ops.bmm import bmm as gems_bmm
from flag_gems.ops.mul import mul as gems_mul
from flag_gems.ops.sum import sum as gems_sum
from flag_gems.ops.sum import sum_dim as gems_sum_dim

logger = logging.getLogger(__name__)

# einsum reduces every equation to two Triton kernels:
#   * a batched matmul (flag_gems.ops.bmm) for the contraction between two
#     operands -- plain matmul, batched matmul, dot and outer products are all
#     special cases of a (Batch, M, K) x (Batch, K, N) product;
#   * a reduction (flag_gems.ops.sum / sum_dim) for single-operand summations.
# Everything else (diagonal extraction, transpose/permute, reshape, broadcast)
# is a metadata-only view and carries no arithmetic, so no torch compute op
# runs on the hot path.

_ELLIPSIS = "\0"  # internal sentinel that never collides with a real label


def _parse_equation(
    equation: str, operands: Tuple[torch.Tensor, ...]
) -> Tuple[List[List[str]], List[str]]:
    """Parse an einsum equation into per-operand label lists and output labels.

    Each subscript is turned into a list of single-character labels. An
    ellipsis is expanded into freshly allocated labels shared across operands
    (broadcasting the batch dims), so the rest of the engine only ever sees
    explicit labels. When the output is implicit it follows the numpy/torch
    rule: every index that appears exactly once, in alphabetical order, with
    the broadcast (ellipsis) dims placed in front.
    """
    equation = equation.replace(" ", "")
    if "->" in equation:
        inputs_str, out_str = equation.split("->")
        explicit_output = True
    else:
        inputs_str, out_str = equation, ""
        explicit_output = False

    input_strs = inputs_str.split(",")
    assert len(input_strs) == len(operands), (
        "einsum(): the number of subscripts in the equation "
        f"({len(input_strs)}) does not match the number of operands "
        f"({len(operands)})"
    )

    # How many dims does the ellipsis cover? It is the largest number of
    # dimensions left uncovered by explicit labels across all operands.
    ellipsis_ndim = 0
    for sub, op in zip(input_strs, operands):
        if "..." in sub:
            explicit = len(sub.replace("...", ""))
            ellipsis_ndim = max(ellipsis_ndim, op.dim() - explicit)

    used = set(inputs_str + out_str) - {".", "-", ">"}
    pool = [
        chr(c)
        for c in list(range(ord("A"), ord("Z") + 1))
        + list(range(ord("a"), ord("z") + 1))
        if chr(c) not in used
    ]
    ellipsis_labels = pool[:ellipsis_ndim]
    assert len(ellipsis_labels) == ellipsis_ndim, "einsum(): ran out of labels"

    def expand(sub: str) -> List[str]:
        if "..." in sub:
            head, tail = sub.split("...")
            return list(head) + ellipsis_labels + list(tail)
        return list(sub)

    input_labels = [expand(sub) for sub in input_strs]

    if explicit_output:
        if "..." in out_str:
            head, tail = out_str.split("...")
            output_labels = list(head) + ellipsis_labels + list(tail)
        else:
            output_labels = list(out_str)
    else:
        counts = Counter(lbl for labels in input_labels for lbl in labels)
        singles = sorted(
            lbl for lbl, c in counts.items() if c == 1 and lbl not in ellipsis_labels
        )
        output_labels = ellipsis_labels + singles

    return input_labels, output_labels


def _diagonalize(
    labels: List[str], operand: torch.Tensor
) -> Tuple[List[str], torch.Tensor]:
    """Collapse repeated labels inside one operand through diagonal views.

    Handles ``"ii->i"`` (diagonal) and ``"ii->"`` (trace). ``torch.diagonal``
    returns a view, so this performs no arithmetic.
    """
    while True:
        counts = Counter(labels)
        repeated = next((lbl for lbl, c in counts.items() if c > 1), None)
        if repeated is None:
            break
        d1, d2 = [i for i, lbl in enumerate(labels) if lbl == repeated][:2]
        operand = torch.diagonal(operand, dim1=d1, dim2=d2)
        # diagonal drops dims d1/d2 and appends the shared axis at the end.
        labels = [lbl for i, lbl in enumerate(labels) if i not in (d1, d2)]
        labels.append(repeated)
    return labels, operand


def _sum_over(
    labels: List[str], operand: torch.Tensor, keep: set
) -> Tuple[List[str], torch.Tensor]:
    """Reduce (via Triton sum) the axes whose label is not needed downstream."""
    reduce_dims = [i for i, lbl in enumerate(labels) if lbl not in keep]
    if not reduce_dims:
        return labels, operand
    if len(reduce_dims) == len(labels):
        return [], gems_sum(operand)
    operand = gems_sum_dim(operand, dim=reduce_dims, keepdim=False)
    labels = [lbl for i, lbl in enumerate(labels) if i not in reduce_dims]
    return labels, operand


def _permute_to(
    labels: List[str], operand: torch.Tensor, target: List[str]
) -> torch.Tensor:
    """Permute an operand so its axes follow ``target`` order (a view)."""
    if labels == target:
        return operand
    perm = [labels.index(lbl) for lbl in target]
    return operand.permute(perm)


def _contract_pair(
    labels_a: List[str],
    a: torch.Tensor,
    labels_b: List[str],
    b: torch.Tensor,
    keep: set,
) -> Tuple[List[str], torch.Tensor]:
    """Contract two operands, dispatching the multiply-add to Triton bmm.

    The two operands are permuted and reshaped into
    ``(Batch, M, K) x (Batch, K, N)`` where:
      * Batch = labels shared by both and still needed (or broadcast batch),
      * K     = labels shared by both and contracted away,
      * M / N = labels unique to a / b that survive.
    The heavy lifting is a single ``flag_gems.ops.bmm`` call.
    """
    set_a, set_b = set(labels_a), set(labels_b)
    shared = set_a & set_b

    batch = [lbl for lbl in labels_a if lbl in shared and lbl in keep]
    contracted = [lbl for lbl in labels_a if lbl in shared and lbl not in keep]
    free_a = [lbl for lbl in labels_a if lbl not in set_b]
    free_b = [lbl for lbl in labels_b if lbl not in set_a]

    # Pure-reduction contraction (no free output axes, e.g. dot product
    # "i,i->" or "bi,bi->b"): a degenerate (M=1, N=1) bmm serialises the whole
    # K reduction inside a single program and is very slow. Instead fuse a
    # Triton elementwise multiply with a Triton reduction.
    if not free_a and not free_b and contracted:
        a = _permute_to(labels_a, a, batch + contracted)
        b = _permute_to(labels_b, b, batch + contracted)
        prod = gems_mul(a, b)  # Triton pointwise multiply.
        if not batch:
            return [], gems_sum(prod)  # Triton reduction over everything.
        reduce_dims = list(range(len(batch), prod.dim()))
        prod = gems_sum_dim(prod, dim=reduce_dims, keepdim=False)
        return batch, prod

    # Permute both operands so axes line up as [batch, free, contracted].
    a = _permute_to(labels_a, a, batch + free_a + contracted)
    b = _permute_to(labels_b, b, batch + contracted + free_b)

    # Read sizes straight off the permuted tensors.
    a_labels = batch + free_a + contracted
    b_labels = batch + contracted + free_b
    a_sizes = dict(zip(a_labels, a.shape))
    b_sizes = dict(zip(b_labels, b.shape))

    # Broadcast batch and contracted dims to a common size on both sides
    # (size-1 dims are expanded through a view).
    batch_shape = [max(a_sizes[lbl], b_sizes[lbl]) for lbl in batch]
    contracted_shape = [max(a_sizes[lbl], b_sizes[lbl]) for lbl in contracted]
    free_a_shape = [a_sizes[lbl] for lbl in free_a]
    free_b_shape = [b_sizes[lbl] for lbl in free_b]

    a = a.expand(batch_shape + free_a_shape + contracted_shape)
    b = b.expand(batch_shape + contracted_shape + free_b_shape)

    def _prod(shape):
        out = 1
        for s in shape:
            out *= s
        return out

    B = _prod(batch_shape)
    m = _prod(free_a_shape)
    n = _prod(free_b_shape)
    k = _prod(contracted_shape)

    a3 = a.reshape(B, m, k).contiguous()
    b3 = b.reshape(B, k, n).contiguous()

    out = gems_bmm(a3, b3)  # Triton batched matmul -- the only compute op.

    out = out.reshape(batch_shape + free_a_shape + free_b_shape)
    out_labels = batch + free_a + free_b
    return out_labels, out


def einsum(equation: str, *operands, path=None):
    """Einstein summation backed by FlagGems Triton kernels.

    The contraction path itself is metadata bookkeeping; every arithmetic
    operation is delegated to a Triton kernel (``bmm`` for products, ``sum`` /
    ``sum_dim`` for reductions). Diagonal, transpose and reshape steps are
    views and perform no computation.

    Args:
        equation: Einstein summation equation string.
        operands: Input tensors (also accepts a single list/tuple of tensors).
        path: Accepted for API compatibility; the contraction order is derived
            left-to-right, matching ``torch.einsum`` results.

    Returns:
        The contracted result tensor.
    """
    logger.debug("GEMS EINSUM")

    if len(operands) == 1 and isinstance(operands[0], (list, tuple)):
        operands = tuple(operands[0])

    input_labels, output_labels = _parse_equation(equation, operands)
    out_set = set(output_labels)

    # 1) Per-operand cleanup: collapse repeated labels, then drop any label that
    #    is neither in the output nor shared with another operand.
    all_labels = Counter(lbl for labels in input_labels for lbl in labels)
    cur_labels: List[List[str]] = []
    cur_ops: List[torch.Tensor] = []
    for labels, op in zip(input_labels, operands):
        labels, op = _diagonalize(labels, op)
        # A label can be reduced now only if it is unique to this operand and
        # not part of the output.
        keep = set(
            lbl
            for lbl in labels
            if lbl in out_set or all_labels[lbl] > labels.count(lbl)
        )
        labels, op = _sum_over(labels, op, keep)
        cur_labels.append(labels)
        cur_ops.append(op)

    # 2) Contract operands left-to-right via Triton bmm.
    acc_labels, acc = cur_labels[0], cur_ops[0]
    for i in range(1, len(cur_ops)):
        # Labels still needed = output labels or labels appearing in any
        # not-yet-consumed operand.
        remaining = Counter()
        for labels in cur_labels[i + 1 :]:
            remaining.update(set(labels))
        keep = out_set | set(remaining)
        acc_labels, acc = _contract_pair(
            acc_labels, acc, cur_labels[i], cur_ops[i], keep
        )

    # 3) Single-operand equations may still carry non-output labels to reduce.
    if len(cur_ops) == 1:
        acc_labels, acc = _sum_over(acc_labels, acc, out_set)

    # 4) Final permute to the requested output order (a view).
    acc = _permute_to(acc_labels, acc, output_labels)
    return acc.contiguous() if acc.dim() > 0 else acc
