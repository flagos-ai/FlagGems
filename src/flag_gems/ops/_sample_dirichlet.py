def sample_dirichlet_kernel(
    alpha_ptr,
    out_ptr,
    N,
    K,
    philox_seed,
    philox_offset,
    BLOCK_K: tl.constexpr,
    MAX_ITER: tl.constexpr,
):
    """
    Sample from Dirichlet distribution.
    Input shape: [N, K], output shape: [N, K]
    Each row is normalized to sum to 1.
    """
    philox_seed = philox_seed.to(tl.int64)
    philox_offset = philox_offset.to(tl.int64)

    row_id = tl.program_id(0)

    if row_id >= N:
        return

    # Process K elements in this row
    gamma_sum = 0.0

    for k_start in range(0, K, BLOCK_K):
        k_offs = k_start + tl.arange(0, BLOCK_K)
        mask = k_offs < K

        # Load alpha values
        alpha_idx = row_id * K + k_offs
        alpha = tl.load(alpha_ptr + alpha_idx, mask=mask, other=1.0).to(tl.float32)
        alpha = tl.maximum(alpha, 1e-6)

        # Sample gamma for each element
        counter_base = philox_offset + alpha_idx.to(tl.int64) * 512
        c0 = (counter_base & 0xFFFFFFFF).to(tl.uint32)
        c1 = ((counter_base >> 32) & 0xFFFFFFFF).to(tl.uint32)
        z = c0 * 0

        gamma = sample_gamma_marsaglia_tsang(alpha, philox_seed, c0, c1, z, MAX_ITER)

        # Accumulate sum
        gamma_sum += tl.sum(tl.where(mask, gamma, 0.0))

        # Normalize and store
        normalized = gamma / tl.maximum(gamma_sum, 1e-10)
        tl.store(out_ptr + alpha_idx, normalized, mask=mask)


