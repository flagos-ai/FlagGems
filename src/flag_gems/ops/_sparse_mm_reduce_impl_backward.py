# torch maps the ``max``/``min`` spellings onto amax/amin in the same kernel,
# so they normalise to a single code here.
_REDUCE_CODES = {
    "sum": 0,
    "mean": 1,
    "amax": 2,
    "amin": 3,
    "max": 2,
    "min": 3,
}


