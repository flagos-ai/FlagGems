def _sparse_mm_reduce_impl_bwd_val_kernel(
    row_ptr,
    col_ptr,
    weight_ptr,
    grad_out_ptr,
    crow_ptr,
    grad_val_ptr,
    N,
    stride_weight_k,
    stride_weight_n,
    stride_go_m,
    stride_go_n,
    IS_FP64: tl.constexpr,
    IS_MEAN: tl.constexpr,
    BLOCK_N: tl.constexpr,
):
    """One program per nnz entry.

    grad_val[e] = dot(weight[col[e], :], grad_out[row(e), :]), divided by the
    row's stored nnz for ``mean``.  ``row`` comes from a precomputed COO row
    index so no binary search over ``crow`` is needed.
    """
    e = ext.program_id(0).to(tl.int64)
    row = tl.load(row_ptr + e).to(tl.int64)
    col = tl.load(col_ptr + e).to(tl.int64)
    acc_dtype = tl.float64 if IS_FP64 else tl.float32
    noff = ext.program_id(1) * BLOCK_N + tl.arange(0, BLOCK_N).to(tl.int64)
    nmask = noff < N
    w = tl.load(
        weight_ptr + col * stride_weight_k + noff * stride_weight_n,
        mask=nmask,
        other=0.0,
    ).to(acc_dtype)
    g = tl.load(
        grad_out_ptr + row * stride_go_m + noff * stride_go_n,
        mask=nmask,
        other=0.0,
    ).to(acc_dtype)
    # The full dot product spans every N block: accumulate this block's
    # partial sum atomically (grad_val[e] starts at zero).
    val = tl.sum(w * g, axis=0)
    if IS_MEAN:
        # The row-nnz division is applied once per entry, not once per partial
        # sum, so scale the partial by the total block count before the atomic.
        start = tl.load(crow_ptr + row).to(acc_dtype)
        end = tl.load(crow_ptr + row + 1).to(acc_dtype)
        val = val / tl.maximum(end - start, 1.0)
    tl.atomic_add(grad_val_ptr + e, val.to(grad_val_ptr.dtype.element_ty))


