def _sparse_mm_reduce_impl_bwd_amax_kernel(
    arg_ptr,
    stride_arg_m,
    stride_arg_n,
    col_ptr,
    val_ptr,
    weight_ptr,
    grad_out_ptr,
    grad_val_ptr,
    grad_other_ptr,
    N,
    nnz,
    stride_weight_k,
    stride_weight_n,
    stride_go_m,
    stride_go_n,
    HAS_VAL: tl.constexpr,
    HAS_OTHER: tl.constexpr,
    BLOCK_N: tl.constexpr,
):
    """One program per (row, column block) for amax/amin.

    The gradient flows only through the entries referenced by ``arg_out``:
    grad_val[arg_out[r, n]] += weight[col[arg], n] * grad_out[r, n] and
    grad_other[col[arg], n] += val[arg] * grad_out[r, n].  Entries never
    selected keep zero, and arg_out == nnz (a row with no stored entries)
    selects nothing.  ``HAS_VAL``/``HAS_OTHER`` drop the atomic for outputs
    that ``output_mask`` disabled (a disabled output has no buffer to pass).
    """
    row = ext.program_id(0)
    rn = ext.program_id(1) * BLOCK_N + tl.arange(0, BLOCK_N)
    rmask = rn < N
    row64 = row.to(tl.int64)
    rn64 = rn.to(tl.int64)
    arg = tl.load(
        arg_ptr + row64 * stride_arg_m + rn64 * stride_arg_n,
        mask=rmask,
        other=0,
    ).to(tl.int64)
    sel = rmask & (arg < nnz)
    e = tl.where(sel, arg, 0)
    c = tl.load(col_ptr + e, mask=sel, other=0).to(tl.int64)
    v = tl.load(val_ptr + e, mask=sel, other=0.0)
    g = tl.load(
        grad_out_ptr + row64 * stride_go_m + rn64 * stride_go_n, mask=rmask, other=0.0
    )
    wv = tl.load(
        weight_ptr + c * stride_weight_k + rn64 * stride_weight_n, mask=sel, other=0.0
    )
    if HAS_VAL:
        tl.atomic_add(
            grad_val_ptr + e,
            (wv * g).to(grad_val_ptr.dtype.element_ty),
            mask=sel,
        )
    if HAS_OTHER:
        tl.atomic_add(
            grad_other_ptr + c * N + rn64,
            (v * g).to(grad_other_ptr.dtype.element_ty),
            mask=sel,
        )


def _row_indices(crow, nnz, device):
    """Expand the CSR ``crow`` structure into a per-nnz row index (COO row)."""
    M = crow.numel() - 1
    counts = (crow[1:] - crow[:-1]).clamp_min(0)
    return torch.repeat_interleave(
        torch.arange(M, device=device, dtype=crow.dtype), counts
    )


def _to_csr(sparse):
    if sparse.layout == torch.sparse_csr:
        return sparse
    if sparse.layout in (
        torch.sparse_coo,
        torch.sparse_csc,
        torch.sparse_bsr,
        torch.sparse_bsc,
    ):
        return sparse.to_sparse_csr()
    raise RuntimeError(
        f"_sparse_mm_reduce_impl_backward: Expected self to have a sparse "
        f"layout, but got {sparse.layout}"
    )


def _sparse_mm_reduce_impl_backward(
    self, grad_out, weight, reduce="sum", arg_out=None, output_mask=None
):
    """Backward of ``aten::_sparse_mm_reduce_impl``: computes the pair
    ``(grad_self, grad_other)`` for the SpMM reduce forward.

    ``grad_self`` keeps the CSR structure of ``self``; only its values are
    computed here and reassembled with the input's ``crow_indices`` /
    ``col_indices`` (sum: ``dot(weight[col], grad_out[row])``, mean divides by
    the row's stored nnz, amax/amin route the gradient through ``arg_out``).
    ``grad_other`` scatters ``val * grad_out[row]`` back onto the weight rows
    (arg-gated for amax/amin).

    ``output_mask`` gates the two returns exactly like aten: a disabled output
    is ``None``, not a zero tensor.  ``amax``/``amin`` need the forward pass's
    ``arg_out`` per-(row, n) nnz index tensor (with the ``nnz`` sentinel for
    rows that have no stored entries).
    """
    logger.debug("GEMS _SPARSE_MM_REDUCE_IMPL_BACKWARD")

    if output_mask is None:
        output_mask = (True, True)
    mask0 = bool(output_mask[0])
    mask1 = bool(output_mask[1])

    if self.layout == torch.strided:
        raise NotImplementedError(
            f"Could not run '_sparse_mm_reduce_impl_backward' with arguments "
            f"from the '{self.layout}' backend. This could be because the "
            f"operator doesn't exist for this backend, or was omitted during "
            f"the selective/custom build process"
        )
    if grad_out.layout != torch.strided or weight.layout != torch.strided:
        raise RuntimeError(
            "_sparse_mm_reduce_impl_backward: Expected grad_out and weight to "
            "have strided layout"
        )
    if self.dim() != 2:
        raise RuntimeError(
            f"sparse_mm_reduce: expected self to be a 2-D tensor, got "
            f"{self.dim()}-D tensor."
        )
    if self.dense_dim() != 0:
        raise RuntimeError("sparse_mm_reduce: expected non-hybrid self tensor.")
    if grad_out.dim() != 2 or grad_out.shape[0] != self.shape[0]:
        raise RuntimeError(
            f"Expected a tensor of dimension 2 and tensor.size[0] == "
            f"{self.shape[0]} but got: dimension {grad_out.dim()} and "
            f"tensor.size[0] = {grad_out.shape[0]}"
        )
    if weight.dim() != 2 or weight.shape[0] != self.shape[1]:
        raise RuntimeError(
            f"Expected a tensor of dimension 2 and tensor.size[0] == "
            f"{self.shape[1]} but got: dimension {weight.dim()} and "
            f"tensor.size[0] = {weight.shape[0]}"
        )
    if grad_out.shape[1] != weight.shape[1]:
        raise RuntimeError(
            f"Expected a tensor of dimension 2 and tensor.size[1] == "
            f"{weight.shape[1]} but got: dimension {grad_out.dim()} and "
            f"tensor.size[1] = {grad_out.shape[1]}"
        )

    if reduce not in _REDUCE_CODES:
        raise RuntimeError(
            f"reduce argument must be either sum, prod, mean, amax or amin, "
            f"got {reduce}"
        )
    if reduce == "prod":
        raise RuntimeError(
            "sparse_mm_reduce: reduce type of prod has not been enabled."
        )

    csr = _to_csr(self)
    if csr.layout != torch.sparse_csr:
        raise RuntimeError(
            f"sparse_mm_reduce: expect self to be SparseCsr, got {csr.layout}"
        )

    if self.dtype not in _SPARSE_MM_REDUCE_IMPL_BWD_DTYPES:
        raise RuntimeError(f'"spmm_reduce_kernel" not implemented for {self.dtype!r}')
    if self.dtype != grad_out.dtype or self.dtype != weight.dtype:
        raise RuntimeError(
            f"Expected tensor for argument to have scalar type {self.dtype} "
            f"but got a different one"
        )

    M, K = csr.shape
    N = weight.shape[1]
    nnz = csr._nnz()

    if not mask0 and not mask1:
        return None, None

    crow = csr.crow_indices()
    col = csr.col_indices()
    val = csr.values()

    # Low-precision atomics accumulate at the destination dtype, which is both
    # inaccurate and order dependent; accumulate in fp32 (fp64 for double) and
    # narrow once at the end, matching aten's ``opmath_t`` behaviour.
    atom_dtype = torch.float64 if val.dtype == torch.float64 else torch.float32
    val_acc = None
    other_acc = None
    if mask0:
        val_acc = torch.empty(nnz, dtype=atom_dtype, device=val.device)
        val_acc.zero_()
    if mask1:
        other_acc = torch.empty((K, N), dtype=atom_dtype, device=weight.device)
        other_acc.zero_()

    row = _row_indices(crow, nnz, val.device)
    is_mean = reduce == "mean"
    is_fp64 = val.dtype == torch.float64

    if nnz == 0 or M == 0 or N == 0:
        # Nothing to accumulate: every stored entry stays zero, and empty
        # rows / gaps in grad_other keep zero too.
        grad_self = None
        grad_other = None
        if mask0:
            grad_self = torch.sparse_csr_tensor(
                crow, col, val_acc.to(val.dtype), size=(M, K), device=val.device
            )
        if mask1:
            grad_other = other_acc.to(weight.dtype)
        return grad_self, grad_other

    block_n = min(triton.next_power_of_2(N), 1024)
    with torch_device_fn.device(val.device):
        if reduce in ("sum", "mean"):
            if mask0:
                _sparse_mm_reduce_impl_bwd_val_kernel[(nnz, triton.cdiv(N, block_n))](
                    row,
                    col,
                    weight,
                    grad_out,
                    crow,
                    val_acc,
                    N,
                    weight.stride(0),
                    weight.stride(1),
                    grad_out.stride(0),
                    grad_out.stride(1),
                    IS_FP64=is_fp64,
                    IS_MEAN=is_mean,
                    BLOCK_N=block_n,
                    num_warps=4,
                )
            if mask1:
                if is_mean:
                    _sparse_mm_reduce_impl_bwd_other_mean_kernel[
                        (nnz, triton.cdiv(N, block_n))
                    ](
                        row,
                        col,
                        val,
                        crow,
                        grad_out,
                        other_acc,
                        N,
                        grad_out.stride(0),
                        grad_out.stride(1),
                        other_acc.stride(0),
                        other_acc.stride(1),
                        IS_FP64=is_fp64,
                        BLOCK_N=block_n,
                        num_warps=4,
                    )
                else:
                    _sparse_mm_reduce_impl_bwd_other_kernel[
                        (nnz, triton.cdiv(N, block_n))
                    ](
                        row,
                        col,
                        val,
                        grad_out,
                        other_acc,
                        N,
                        grad_out.stride(0),
                        grad_out.stride(1),
                        other_acc.stride(0),
                        other_acc.stride(1),
                        IS_FP64=is_fp64,
                        IS_MEAN=False,
                        BLOCK_N=block_n,
                        num_warps=4,
                    )
        else:
            if arg_out is None:
                raise RuntimeError(
                    "sparse_mm_reduce: amax/amin backward requires the "
                    "forward's arg_out indices"
                )
            grid = (M, triton.cdiv(N, block_n))
            _sparse_mm_reduce_impl_bwd_amax_kernel[grid](
                arg_out,
                arg_out.stride(0),
                arg_out.stride(1),
                col,
                val,
                weight,
                grad_out,
                val_acc if mask0 else grad_out,
                other_acc if mask1 else weight,
                N,
                nnz,
                weight.stride(0),
                weight.stride(1),
                grad_out.stride(0),
                grad_out.stride(1),
                HAS_VAL=mask0,
                HAS_OTHER=mask1,
                BLOCK_N=block_n,
                num_warps=4,
            )

    grad_self = None
    grad_other = None
    if mask0:
        grad_self = torch.sparse_csr_tensor(
            crow, col, val_acc.to(val.dtype), size=(M, K), device=val.device
        )
    if mask1:
        grad_other = other_acc.to(weight.dtype)
    return grad_self, grad_other
