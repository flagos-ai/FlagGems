def _qkv_last_dim_stride1_kernel(
    q_ptr,
    k_ptr,
    v_ptr,
    q_stride_last,
    k_stride_last,
    v_stride_last,
    q_head_dim,
    out_ptr,
    USE_HEAD_DIM: tl.constexpr,
):
    """Probe, on device, whether q/k/v are stride-1 along the last dimension.

    This materialises ``check_last_dim_stride_equals_1_dense`` from PyTorch's
    SDP backend selection: every fused kernel requires the head-dim axis to be
    contiguous in memory.  We confirm the trailing stride is exactly one
    element wide by comparing the byte gap between ``ptr + stride_last`` and
    ``ptr`` against the gap between two adjacent elements (``ptr + 1``).  The
    two gaps match iff ``stride_last == 1``.  When the head-dim is a singleton
    the stride is irrelevant (see the upstream ``ignore_singleton_dim`` branch),
    so the kernel short-circuits via ``USE_HEAD_DIM``.
    """
    q_adj_gap = tl.cast(q_ptr + 1, tl.int64) - tl.cast(q_ptr, tl.int64)
    q_stg_gap = tl.cast(q_ptr + q_stride_last, tl.int64) - tl.cast(q_ptr, tl.int64)
    k_adj_gap = tl.cast(k_ptr + 1, tl.int64) - tl.cast(k_ptr, tl.int64)
    k_stg_gap = tl.cast(k_ptr + k_stride_last, tl.int64) - tl.cast(k_ptr, tl.int64)
    v_adj_gap = tl.cast(v_ptr + 1, tl.int64) - tl.cast(v_ptr, tl.int64)
    v_stg_gap = tl.cast(v_ptr + v_stride_last, tl.int64) - tl.cast(v_ptr, tl.int64)

    stride_ok = (
        (q_adj_gap == q_stg_gap) & (k_adj_gap == k_stg_gap) & (v_adj_gap == v_stg_gap)
    )
    if USE_HEAD_DIM:
        stride_ok = stride_ok | (q_head_dim == 1)
    tl.store(out_ptr, stride_ok)


