"""Backward kernel for ``complex``.

``aten::complex`` has gradient formula ``real: at::real(grad)``,
``imag: at::imag(grad)``. FlagGems has no ``complex`` forward operator, so this
kernel is exposed as a plain function that returns the ``(grad_real, grad_imag)``
pair, mirroring ``cudnn_convolution_backward``."""

import logging

logger = logging.getLogger(__name__)

import torch
import triton
import triton.language as tl


@triton.jit
def _cb_copy(g_ptr, o_ptr, n2, BLOCK: tl.constexpr, EVEN: tl.constexpr):
    """Re/Im of a complex grad ARE the two halves of its storage, so the
    backward is one straight 2n-float copy into a complex-typed buffer."""
    pid = tl.program_id(0)
    offs = pid * BLOCK + tl.arange(0, BLOCK)
    if EVEN:
        # Host-proven exact tiling: no predication, so the copy lowers to a
        # pure vector move.
        tl.store(o_ptr + offs, tl.load(g_ptr + offs))
    else:
        mask = offs < n2
        tl.store(o_ptr + offs, tl.load(g_ptr + offs, mask=mask, other=0.0),
                 mask=mask)


@triton.jit
def _cb_copy_strided(g_ptr, o_ptr, n2, inner, inner_stride, o_stride,
                     BLOCK: tl.constexpr):
    """Non-contiguous upstream grad: gather the 2n floats in source order."""
    pid = tl.program_id(0)
    offs = pid * BLOCK + tl.arange(0, BLOCK)
    mask = offs < n2
    half = offs // 2
    part = offs - half * 2
    o = half // inner
    src = (o * o_stride + (half - o * inner) * inner_stride) * 2 + part
    tl.store(o_ptr + offs, tl.load(g_ptr + src, mask=mask, other=0.0), mask=mask)


def _collapse(shape, strides):
    """Reduce a strided layout to (inner_len, inner_stride, outer_stride).

    Element index i (row-major over the output view) maps to
        (i // inner_len) * outer_stride + (i % inner_len) * inner_stride
    in the source storage. Trailing dims that are mutually contiguous are
    folded into one inner run so only a single div/mod is needed.
    """
    dims = [(s, st) for s, st in zip(shape, strides) if s != 1]
    if not dims:
        return 1, 1, 1
    inner_stride = dims[-1][1]
    inner = dims[-1][0]
    k = len(dims) - 1
    while k > 0 and dims[k - 1][1] == dims[k][1] * dims[k][0]:
        k -= 1
        inner *= dims[k][0]
    if k == 0:
        return inner, inner_stride, 1
    return inner, inner_stride, dims[k - 1][1]


def complex_backward(grad_output, real, imag):
    out = torch.empty(real.shape, dtype=grad_output.dtype, device=grad_output.device)
    n = grad_output.numel()
    if n == 0:
        return out.real, out.imag
    n2 = 2 * n
    src_view = torch.view_as_real(grad_output)
    dst_view = torch.view_as_real(out)
    if grad_output.is_contiguous():
        # Deterministic configuration (no autotune search): one power-of-two
        # tile covering the whole buffer when it is small, otherwise 1024-wide
        # tiles. Both keep BLOCK a power of two so the copy vectorizes.
        if n2 <= 1024:
            block = triton.next_power_of_2(n2)
            warps = 1 if block <= 128 else (2 if block <= 512 else 4)
        else:
            block = 1024
            warps = 4
        _cb_copy[(triton.cdiv(n2, block),)](
            src_view, dst_view, n2, BLOCK=block, EVEN=(n2 % block == 0),
            num_warps=warps,
        )
    else:
        inner, inner_stride, o_stride = _collapse(
            list(grad_output.shape), list(grad_output.stride())
        )
        BLOCK = 1024
        _cb_copy_strided[(triton.cdiv(n2, BLOCK),)](
            src_view, dst_view, n2, inner, inner_stride, o_stride,
            BLOCK=BLOCK, num_warps=4,
        )
    return out.real, out.imag
