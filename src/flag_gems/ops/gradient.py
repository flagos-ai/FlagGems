@triton.jit
def _rnd(x, comp, BF16: tl.constexpr):
    # Round a float32 intermediate to the output precision and come back,
    # replicating torch's per-op rounding on float16 / bfloat16 CUDA ops.
    # Implemented on the bit pattern: Triton may otherwise elide the
    # f32->f16->f32 conversion pair when the value feeds an FMA, which changes
    # results.  bfloat16 rounds by truncating the f32 mantissa to 7 bits
    # (top-16 RNE); float16 rounds by truncating to 10 mantissa bits (dropping
    # 13 low bits) with round-to-nearest-even -- exactly the float16 rounding
    # for the normal range.  float16 subnormals (|x| < 2**-14) keep extra
    # precision here; the absolute deviation from the reference conversion is
    # below 1e-7, far below the test tolerances.
    b = x.to(tl.int32, bitcast=True)
    sgn = b & -2147483648
    absb = b & 0x7FFFFFFF
    if BF16:
        r = (absb + 0x7FFF + ((absb >> 16) & 1)) & -65536
    else:
        r = (absb + 0x0FFF + ((absb >> 13) & 1)) & (-8192)
    mag = r & 0x7FFFFFFF
    r = tl.where(mag >= 0x47800000, 0x7F800000, r)
    y = (sgn | r).to(tl.float32, bitcast=True)
    return y


