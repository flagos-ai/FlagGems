def _broadcast_strides(tensor, shape):
    """Strides of ``tensor`` expressed in ``shape``'s coordinate space."""
    ndim = len(shape)
    pad = ndim - tensor.dim()
    strides = (0,) * pad + tuple(tensor.stride())
    sizes = (1,) * pad + tuple(tensor.shape)
    return tuple(0 if sizes[i] == 1 else strides[i] for i in range(ndim))


def _padded(values, fill=0):
    values = tuple(values)
    return values + (fill,) * (_MAX_DIMS - len(values))


