@triton.jit
def _grid_sampler_cubic_weight(t, a: tl.constexpr):
    # Keys cubic convolution (a=-0.75), same as grid_sampler_2d.
    ad = tl.abs(t)
    ad2 = ad * ad
    ad3 = ad2 * ad
    w1 = (a + 2.0) * ad3 - (a + 3.0) * ad2 + 1.0
    w2 = a * ad3 - 5.0 * a * ad2 + 8.0 * a * ad - 4.0 * a
    return tl.where(ad <= 1.0, w1, tl.where(ad < 2.0, w2, 0.0))


@triton.jit
def _grid_sampler_round_half_to_even(x):
    """Round half to even (banker's rounding), matching PyTorch's nearbyint.

    The parity check stays entirely in the float domain (no int cast).
    """
    r = tl.floor(x)
    d = x - r
    is_odd = tl.abs(r - 2.0 * tl.floor(r / 2.0)) > 0.5
    return tl.where((d > 0.5) | ((tl.abs(d - 0.5) < 1e-10) & is_odd), r + 1.0, r)


@triton.jit
def _grid_sampler_reflect_coord(coord, n, align_corners: tl.constexpr):
    """Reflect a continuous (pixel-space) coordinate into the valid range.

    align_corners=True:  reflect over [0, n-1] (twice_low=0, twice_high=2n-2).
    align_corners=False: reflect over [-0.5, n-0.5] (twice_low=-1, twice_high=2n-1).
    span is the HALF-period: the triangle wave folds every span and the flip
    parity picks the mirror. Mirrors grid_sampler_2d._reflect_coord.
    """
    if align_corners:
        min = 0.0
        span = n - 1.0
    else:
        min = -0.5
        span = n * 1.0
    in_abs = tl.abs(coord - min)
    extra = in_abs % span
    flips = tl.floor(in_abs / span)
    ref = tl.where(flips % 2 == 0, extra, span - extra) + min
    ref = tl.where(span == 0, 0.0, ref)
    return tl.minimum(tl.maximum(ref, 0.0), n - 1)


@triton.jit
def _grid_sampler_reflect_int_index(idx, n, align_corners: tl.constexpr):
    """Reflect an integer tap index into [0, n-1] (multi-period safe)."""
    if align_corners:
        p = 2 * (n - 1)
        idx_mod = tl.where(p == 0, 0, idx - tl.floor(idx / p) * p)
        return tl.where(idx_mod >= n, p - idx_mod, idx_mod).to(tl.int32)
    else:
        p = 2 * n
        x = idx + 0.5
        x_mod = x - tl.floor(x / p) * p
        x_mod = tl.where(x_mod > n, p - x_mod, x_mod)
        return (x_mod - 0.5).to(tl.int32)


