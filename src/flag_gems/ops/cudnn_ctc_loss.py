def cudnn_ctc_loss_forward_kernel(
    log_probs,
    targets,
    input_lengths,
    target_lengths,
    target_offsets,
    neg_log_likelihood,
    log_alpha,
    T,
    N,
    C,
    STATE_COUNT_MAX: tl.constexpr,
    BLANK: tl.constexpr,
    BLOCK_S: tl.constexpr,
):
    batch = tl.program_id(0)
    states = tl.arange(0, BLOCK_S)

    input_len = tl.load(input_lengths + batch)
    target_len = tl.load(target_lengths + batch)
    state_count = target_len * 2 + 1
    valid_state = states < state_count
    stored_state = states < STATE_COUNT_MAX

    is_blank_state = (states % 2) == 0
    target_index = (states - 1) // 2
    target_mask = (target_index >= 0) & (target_index < target_len)
    target_safe_index = tl.where(target_mask, target_index, 0)

    target_origin = tl.load(target_offsets + batch)
    target_ptrs = targets + target_origin + target_safe_index

    target_value = tl.load(target_ptrs, mask=target_mask, other=BLANK)
    labels = tl.where(is_blank_state, BLANK, target_value)

    # The extended label sequence always starts with the blank symbol, so the
    # blank emission probability only has to be loaded once per batch entry.
    # An empty target has nothing to align, so cuDNN reports a zero loss for it
    # and seeds the gradient with `exp(log_probs)`, which the backward pass then
    # leaves untouched (nothing accumulates posterior mass into state 0).
    init_state = (states == 0) | ((states == 1) & (target_len > 0))
    init_logp = tl.load(
        log_probs + batch * C + labels,
        mask=init_state & stored_state & (input_len > 0),
        other=0.0,
    ).to(tl.float32)
    alpha = tl.where(
        init_state & valid_state & (input_len > 0), init_logp, -float("inf")
    )
    # `log_alpha` is laid out with a `BLOCK_S` row stride so that every state
    # recorded for the backward pass can be read back with the same block shape.
    # The padding lanes are part of the block as well because the next step's
    # shifted loads read them; they are masked to `-inf` up front.
    alpha = tl.where(valid_state, alpha, -float("inf"))
    alpha0_row = log_alpha + batch * T * BLOCK_S + states
    tl.store(alpha0_row, alpha)

    prev_target_index = tl.where(target_index > 0, target_index - 1, 0)
    prev_target_value = tl.load(
        targets + target_origin + prev_target_index,
        mask=target_mask & (target_index > 0),
        other=BLANK,
    )
    skip_allowed = (
        (~is_blank_state) & (target_index > 0) & (target_value != prev_target_value)
    )

    # `alpha` is carried in registers, so the two shifted neighbours are
    # gathered from the carried block instead of being re-read from global
    # memory on every step. That removes the per-step barrier the memory
    # round-trip would need.
    shift1 = tl.where(states > 0, states - 1, 0)
    shift2 = tl.where(states > 1, states - 2, 0)

    for t in tl.range(1, T):
        prev1 = tl.where(states > 0, tl.gather(alpha, shift1, 0), -float("inf"))
        prev2 = tl.where(states > 1, tl.gather(alpha, shift2, 0), -float("inf"))

        acc = _logaddexp3(alpha, prev1, prev2, skip_allowed)
        logp = tl.load(
            log_probs + t * N * C + batch * C + labels,
            mask=valid_state & (t < input_len),
            other=0.0,
        ).to(tl.float32)
        alpha = tl.where(valid_state & (t < input_len), acc + logp, -float("inf"))
        tl.store(
            log_alpha + batch * T * BLOCK_S + t * BLOCK_S + states,
            alpha,
        )

    if input_len <= 0:
        # Matches cuDNN: an empty input with an empty target is the one case it
        # reports as infinite; an empty input with a non-empty target (nothing
        # to align) is reported as a zero loss, like any other infeasible
        # alignment.
        loss = tl.where(target_len == 0, float("inf"), 0.0)
    elif target_len == 0:
        # Nothing to align: cuDNN reports a zero loss for the empty label
        # sequence and attributes no probability mass to any target state.
        loss = 0.0
    else:
        # The terminal states are picked out with a masked block load, which
        # keeps the result scalar for the scalar `neg_log_likelihood` store.
        # `tl.max` doubles as a single-value gather since exactly one lane is
        # kept unmasked.
        final_row = log_alpha + batch * T * BLOCK_S + (input_len - 1) * BLOCK_S + states
        final_alpha = tl.load(final_row, mask=stored_state, other=-float("inf")).to(
            tl.float32
        )
        last = tl.max(
            tl.where(states == state_count - 1, final_alpha, -float("inf")), axis=0
        )
        prev_last = tl.max(
            tl.where(
                (states == state_count - 2) & (target_len > 0),
                final_alpha,
                -float("inf"),
            ),
            axis=0,
        )
        log_likelihood = _logaddexp(last, prev_last)
        # An infeasible alignment also yields -inf, but cuDNN reports it as a
        # zero loss rather than +inf (verified for `input_len < target_len`,
        # e.g. two time steps for three labels). Only the empty-input /
        # empty-target combination above is infinite.
        loss = tl.where(log_likelihood == -float("inf"), 0.0, -log_likelihood)

    tl.store(neg_log_likelihood + batch, loss)


