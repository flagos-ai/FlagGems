@triton.jit
def cudnn_ctc_loss_backward_kernel(
    log_probs,
    targets,
    input_lengths,
    target_lengths,
    target_offsets,
    neg_log_likelihood,
    log_alpha,
    grad_input,
    T,
    N,
    C,
    STATE_COUNT_MAX: tl.constexpr,
    BLANK: tl.constexpr,
    BLOCK_S: tl.constexpr,
    DETERMINISTIC: tl.constexpr,
    NUM_STAGES: tl.constexpr,
):
    batch = tl.program_id(0)
    states = tl.arange(0, BLOCK_S)

    input_len = tl.load(input_lengths + batch)
    target_len = tl.load(target_lengths + batch)
    nll = tl.load(neg_log_likelihood + batch).to(tl.float32)
    state_count = target_len * 2 + 1
    valid_state = states < state_count
    stored_state = states < STATE_COUNT_MAX

    is_blank_state = (states % 2) == 0
    target_index = (states - 1) // 2
    target_mask = (target_index >= 0) & (target_index < target_len)
    target_safe_index = tl.where(target_mask, target_index, 0)

    target_origin = tl.load(target_offsets + batch)
    target_ptrs = targets + target_origin + target_safe_index

    target_value = tl.load(target_ptrs, mask=target_mask, other=BLANK)
    labels = tl.where(is_blank_state, BLANK, target_value)

    state1 = states + 1
    is_blank_state1 = (state1 % 2) == 0
    target_index1 = (state1 - 1) // 2
    target_mask1 = (target_index1 >= 0) & (target_index1 < target_len)
    target_safe_index1 = tl.where(target_mask1, target_index1, 0)
    target_ptrs1 = targets + target_origin + target_safe_index1
    target_value1 = tl.load(target_ptrs1, mask=target_mask1, other=BLANK)
    labels1 = tl.where(is_blank_state1, BLANK, target_value1)

    state2 = states + 2
    target_index2 = (state2 - 1) // 2
    target_mask2 = (target_index2 >= 0) & (target_index2 < target_len)
    target_safe_index2 = tl.where(target_mask2, target_index2, 0)
    target_ptrs2 = targets + target_origin + target_safe_index2
    target_value2 = tl.load(target_ptrs2, mask=target_mask2, other=BLANK)
    labels2 = target_value2

    beta_init = tl.where(
        ((states == state_count - 1) | ((states == state_count - 2) & (target_len > 0)))
        & valid_state
        & (input_len > 0),
        0.0,
        -float("inf"),
    )
    beta_init = tl.where(valid_state, beta_init, -float("inf"))
    # The eager call differentiates the summed loss, so every batch entry
    # carries a unit upstream gradient: `log_likelihood` is `-nll` outright.
    log_likelihood = -nll
    # `-nll` is `+inf` only for the empty-input/empty-target case; an infeasible
    # alignment reports a zero loss instead (see the forward kernel), so the
    # posterior is identically zero there and the subtraction below must not
    # turn into inf - inf.
    aligned = log_likelihood > -float("inf")

    next1_valid = (states + 1 < state_count) & stored_state
    skip_allowed = (
        (~is_blank_state) & (states + 2 < state_count) & (target_value != target_value2)
    )
    shift1 = tl.where(states + 1 < BLOCK_S, states + 1, 0)
    shift2 = tl.where(states + 2 < BLOCK_S, states + 2, 0)

    # The scatter destination is `labels`-indexed, and those collide: every
    # blank state and every repeated label land on the same address. `atomic_add`
    # resolves the collisions in arrival order, which varies between runs, so
    # `deterministic=True` needs the reduction ordered instead. The grouping is
    # derived from `labels` alone (fixed for the whole loop), so the sort and the
    # group-boundary scan are hoisted out of it and the loop only pays for one
    # segmented sum per step.
    #
    # Every lane participates, not just `stored_state`: the padding lanes carry
    # `BLANK` and a zero posterior, so folding them into the blank group leaves
    # that column unchanged while letting the whole `BLOCK_S` block sort and scan
    # without a masked-lane special case.
    if DETERMINISTIC:
        order = tl.sort(labels.to(tl.int64) * BLOCK_S + states)
        perm = (order % BLOCK_S).to(tl.int32)
        sorted_labels = tl.gather(labels, perm, 0)
        prev_sorted = tl.gather(sorted_labels, tl.maximum(states - 1, 0), 0)
        next_sorted = tl.gather(sorted_labels, tl.minimum(states + 1, BLOCK_S - 1), 0)
        group_first = (states == 0) | (sorted_labels != prev_sorted)
        group_last = (states == BLOCK_S - 1) | (sorted_labels != next_sorted)
        group_end = tl.associative_scan(
            tl.where(group_last, states, BLOCK_S), 0, _min_index, reverse=True
        )

    # `beta` is carried in registers, so the shifted neighbours are gathered
    # from the carried block instead of going through a double-buffered
    # scratch row, which removes the per-step barrier. Same `num_stages`
    # prefetch as the forward: the `log_alpha` row and the `log_probs` row for a
    # step are independent of `beta`, so they can be loaded ahead of the
    # reduction. Measured 2x on this kernel; results are bit-identical because
    # only the scheduling changes.
    beta = beta_init
    for step in tl.range(0, T, num_stages=NUM_STAGES):
        t = input_len - 1 - step
        active = t >= 0
        safe_t = tl.where(active, t, 0)

        alpha_t = tl.load(
            log_alpha + batch * T * BLOCK_S + safe_t * BLOCK_S + states,
            mask=active & stored_state,
            other=-float("inf"),
        ).to(tl.float32)
        log_post = alpha_t + beta - log_likelihood
        # An empty label sequence has no state to accumulate the posterior
        # mass into, so the gradient stays at `exp(log_probs)`; an infeasible
        # alignment has no posterior at all, so its gradient is zero.
        posterior = tl.where(
            active & valid_state & (target_len > 0) & aligned,
            tl.exp(log_post),
            0.0,
        )
        # Both accumulation paths are masked identically: only an active step of
        # a feasible alignment moves posterior mass. `safe_t` clamps an inactive
        # step to row 0, so leaving the mask off here would let a padding step
        # read-modify-write row 0 on top of the real `t = 0` contribution (or, as
        # a read of a row written earlier in the same kernel, silently drop it).
        # The atomic path below already carries the full predicate; this is the
        # same predicate spelled out for the ordered path.
        accum_mask = active & valid_state & (target_len > 0) & aligned & stored_state
        if DETERMINISTIC:
            # Reorder the per-state deltas into label order, take a suffix-free
            # running sum, and collapse each group onto its first lane. Groups
            # are disjoint addresses, so one store per label accumulates into
            # `grad_input` in a fixed order regardless of scheduling.
            sorted_delta = tl.gather(-posterior, perm, 0)
            running = tl.cumsum(sorted_delta, 0)
            group_sum = tl.gather(running, group_end, 0) - (running - sorted_delta)
            destination = grad_input + safe_t * N * C + batch * C + sorted_labels
            # `group_first` is in sorted order, so the validity mask has to be
            # permuted to match it before the two are combined.
            sorted_mask = tl.gather(accum_mask, perm, 0)
            scatter = group_first & sorted_mask
            previous = tl.load(destination, mask=scatter, other=0.0)
            tl.store(destination, previous + group_sum, mask=scatter)
        else:
            tl.atomic_add(
                grad_input + safe_t * N * C + batch * C + labels,
                -posterior,
                sem="relaxed",
                mask=accum_mask,
            )

        stay = beta + tl.load(
            log_probs + safe_t * N * C + batch * C + labels,
            mask=active & valid_state,
            other=-float("inf"),
        ).to(tl.float32)
        next1 = tl.where(
            next1_valid, tl.gather(beta, shift1, 0), -float("inf")
        ) + tl.load(
            log_probs + safe_t * N * C + batch * C + labels1,
            mask=active & next1_valid,
            other=-float("inf"),
        ).to(
            tl.float32
        )
        next2 = tl.where(
            (states + 2 < state_count) & stored_state,
            tl.gather(beta, shift2, 0),
            -float("inf"),
        ) + tl.load(
            log_probs + safe_t * N * C + batch * C + labels2,
            mask=active & skip_allowed & stored_state,
            other=-float("inf"),
        ).to(
            tl.float32
        )

        beta_next = _logaddexp3(stay, next1, next2, skip_allowed)
        beta = tl.where(active & valid_state, beta_next, -float("inf"))


