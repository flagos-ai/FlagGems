@triton.jit
def cudnn_ctc_loss_backward_kernel(
    log_probs,
    targets,
    input_lengths,
    target_lengths,
    target_offsets,
    neg_log_likelihood,
    log_alpha,
    grad_input,
    T,
    N,
    C,
    STATE_COUNT_MAX: tl.constexpr,
    BLANK: tl.constexpr,
    BLOCK_S: tl.constexpr,
    DETERMINISTIC: tl.constexpr,
    NUM_STAGES: tl.constexpr,
):
    batch = tl.program_id(0)
    states = tl.arange(0, BLOCK_S)

    input_len = tl.load(input_lengths + batch)
    target_len = tl.load(target_lengths + batch)
    nll = tl.load(neg_log_likelihood + batch).to(tl.float32)
    state_count = target_len * 2 + 1
    valid_state = states < state_count
    stored_state = states < STATE_COUNT_MAX

    is_blank_state = (states % 2) == 0
    target_index = (states - 1) // 2
    target_mask = (target_index >= 0) & (target_index < target_len)
    target_safe_index = tl.where(target_mask, target_index, 0)

    target_origin = tl.load(target_offsets + batch)
    target_ptrs = targets + target_origin + target_safe_index

    target_value = tl.load(target_ptrs, mask=target_mask, other=BLANK)
    labels = tl.where(is_blank_state, BLANK, target_value)

    state1 = states + 1
    is_blank_state1 = (state1 % 2) == 0
    target_index1 = (state1 - 1) // 2
    target_mask1 = (target_index1 >= 0) & (target_index1 < target_len)
    target_safe_index1 = tl.where(target_mask1, target_index1, 0)
    target_ptrs1 = targets + target_origin + target_safe_index1
    target_value1 = tl.load(target_ptrs1, mask=target_mask1, other=BLANK)
    labels1 = tl.where(is_blank_state1, BLANK, target_value1)

    state2 = states + 2
    target_index2 = (state2 - 1) // 2
    target_mask2 = (target_index2 >= 0) & (target_index2 < target_len)
    target_safe_index2 = tl.where(target_mask2, target_index2, 0)
    target_ptrs2 = targets + target_origin + target_safe_index2
    target_value2 = tl.load(target_ptrs2, mask=target_mask2, other=BLANK)
    labels2 = target_value2

    beta_init = tl.where(
        ((states == state_count - 1) | ((states == state_count - 2) & (target_len > 0)))
        & valid_state
        & (input_len > 0),
        0.0,
        -float("inf"),
    )
    beta_init = tl.where(valid_state, beta_init, -float("inf"))
    # The eager call differentiates the summed loss, so every batch entry
    # carries a unit upstream gradient: `log_likelihood` is `-nll` outright.
    log_likelihood = -nll
    # `-nll` is `+inf` only for the empty-input/empty-target case; an infeasible
    # alignment reports a zero loss instead (see the forward kernel), so the
    # posterior is identically zero there and the subtraction below must not
    # turn into inf - inf.
    aligned = log_likelihood > -float("inf")

    next1_valid = (states + 1 < state_count) & stored_state
    skip_allowed = (
        (~is_blank_state) & (states + 2 < state_count) & (target_value != target_value2)
    )
    shift1 = tl.where(states + 1 < BLOCK_S, states + 1, 0)
    shift2 = tl.where(states + 2 < BLOCK_S, states + 2, 0)

    # The scatter destination is `labels`-indexed, and those collide: every
    # blank state and every repeated label land on the same address. `atomic_add`
    # resolves the collisions in arrival order, which varies between runs, so
    # `deterministic=True` needs the reduction ordered instead. The grouping is
    # derived from `labels` alone (fixed for the whole loop), so the sort and the
    # group-boundary scan are hoisted out of it and the loop only pays for one
    # segmented sum per step.
    #
    # Every lane participates, not just `stored_state`: the padding lanes carry
    # `BLANK` and a zero posterior, so folding them into the blank group leaves
    # that column unchanged while letting the whole `BLOCK_S` block sort and scan
    # without a masked-lane special case.
    if DETERMINISTIC:
        order = tl.sort(labels.to(tl.int64) * BLOCK_S + states)
        perm = (order % BLOCK_S).to(tl.int32)
        sorted_labels = tl.gather(labels, perm, 0)
        prev_sorted = tl.gather(sorted_labels, tl.maximum(states - 1, 0), 0)
        next_sorted = tl.gather(sorted_labels, tl.minimum(states + 1, BLOCK_S - 1), 0)
        group_first = (states == 0) | (sorted_labels != prev_sorted)
        group_last = (states == BLOCK_S - 1) | (sorted_labels != next_sorted)
        group_end = tl.associative_scan(
            tl.where(group_last, states, BLOCK_S), 0, _min_index, reverse=True
        )

    # `beta` is carried in registers, so the shifted neighbours are gathered
    # from the carried block instead of going through a double-buffered
    # scratch row, which removes the per-step barrier. Same `num_stages`
    # prefetch as the forward: the `log_alpha` row and the `log_probs` row for a
    # step are independent of `beta`, so they can be loaded ahead of the
    # reduction. Measured 2x on this kernel; results are bit-identical because
    # only the scheduling changes.
    beta = beta_init
    for step in tl.range(0, T, num_stages=NUM_STAGES):
        t = input_len - 1 - step
        active = t >= 0
        safe_t = tl.where(active, t, 0)

        alpha_t = tl.load(
            log_alpha + batch * T * BLOCK_S + safe_t * BLOCK_S + states,
            mask=active & stored_state,
            other=-float("inf"),
        ).to(tl.float32)
        log_post = alpha_t + beta - log_likelihood
        # An empty label sequence has no state to accumulate the posterior
        # mass into, so the gradient stays at `exp(log_probs)`; an infeasible
        # alignment has no posterior at all, so its gradient is zero.
        posterior = tl.where(
            active & valid_state & (target_len > 0) & aligned,
            tl.exp(log_post),
            0.0,
        )
        if DETERMINISTIC:
            # Reorder the per-state deltas into label order, take a suffix-free
            # running sum, and collapse each group onto its first lane. Groups
            # are disjoint addresses, so one store per label accumulates into
            # `grad_input` in a fixed order regardless of scheduling.
            sorted_delta = tl.gather(-posterior, perm, 0)
            running = tl.cumsum(sorted_delta, 0)
            group_sum = tl.gather(running, group_end, 0) - (running - sorted_delta)
            destination = grad_input + safe_t * N * C + batch * C + sorted_labels
            previous = tl.load(destination, mask=group_first, other=0.0)
            tl.store(destination, previous + group_sum, mask=group_first)
        else:
            tl.atomic_add(
                grad_input + safe_t * N * C + batch * C + labels,
                -posterior,
                sem="relaxed",
                mask=active & valid_state & (target_len > 0) & aligned & stored_state,
            )

        stay = beta + tl.load(
            log_probs + safe_t * N * C + batch * C + labels,
            mask=active & valid_state,
            other=-float("inf"),
        ).to(tl.float32)
        next1 = tl.where(
            next1_valid, tl.gather(beta, shift1, 0), -float("inf")
        ) + tl.load(
            log_probs + safe_t * N * C + batch * C + labels1,
            mask=active & next1_valid,
            other=-float("inf"),
        ).to(
            tl.float32
        )
        next2 = tl.where(
            (states + 2 < state_count) & stored_state,
            tl.gather(beta, shift2, 0),
            -float("inf"),
        ) + tl.load(
            log_probs + safe_t * N * C + batch * C + labels2,
            mask=active & skip_allowed & stored_state,
            other=-float("inf"),
        ).to(
            tl.float32
        )

        beta_next = _logaddexp3(stay, next1, next2, skip_allowed)
        beta = tl.where(active & valid_state, beta_next, -float("inf"))


def _lengths_to_tensor(values, device):
    if torch.is_tensor(values):
        return values.to(device=device, dtype=torch.long).reshape(-1).contiguous()
    return torch.tensor(list(values), dtype=torch.long, device=device)


def _upload_inputs(targets, input_lengths, target_lengths, device):
    """Put targets, lengths and offsets on the device without a host round trip.

    Targets normally arrive on the CPU (cuDNN's own convention) and the lengths
    as Python sequences, so the common path is pure H2D: the targets and both
    length vectors are packed into one host vector and carried up in a single
    copy. The non-blocking form is what makes that cheap -- a regular pageable
    copy measured ~2.1ms on H20 (it bounces through a staging buffer), against
    ~14us for the async form. The copy is ordered on the caller's stream, so the
    kernels below still see the data.

    When the caller hands over device-resident targets they are copied straight
    into the packed buffer instead: sending them down to the host only to bring
    them back would add a device sync to every call.
    """
    batch = len(input_lengths)
    offsets = [0] * batch
    running = 0
    for index, length in enumerate(target_lengths):
        offsets[index] = running
        running += int(length)
    lengths_host = torch.tensor(
        list(input_lengths) + list(target_lengths) + offsets, dtype=torch.long
    )

    # The packed buffer is int32 at the head (so the targets stay contiguous for
    # the kernels) and int64 past it (so the lengths keep their natural width).
    # `view(torch.long)` needs the offset 8-byte aligned, so an odd target count
    # gets one padding slot.
    target_count = targets.numel()
    target_slots = target_count + (target_count % 2)
    total_slots = target_slots + 2 * lengths_host.numel()

    if targets.device.type == "cpu":
        packed_host = torch.empty(total_slots, dtype=torch.int32)
        packed_host[:target_count].copy_(targets.detach())
        packed_host[target_slots:].view(torch.long).copy_(lengths_host)
        packed = torch.empty_like(packed_host, device=device)
        packed.copy_(packed_host, non_blocking=True)
    else:
        packed = torch.empty(total_slots, dtype=torch.int32, device=device)
        packed[:target_count].copy_(targets.detach().to(dtype=torch.int32))
        packed[target_slots:].view(torch.long).copy_(lengths_host, non_blocking=True)

    work_targets = packed[:target_count]
    lengths = packed[target_slots:].view(torch.long)
    return (
        work_targets,
        lengths[:batch],
        lengths[batch : 2 * batch],
        lengths[2 * batch :],
    )


def _target_offsets(target_lengths, device, batch_size):
    """Exclusive prefix sum of `target_lengths`.

    Python sequences are summed on the host so no extra device kernel is
    needed; tensor arguments fall back to `cumsum`.
    """
    if not torch.is_tensor(target_lengths):
        offsets = [0] * batch_size
        running = 0
        for index, length in enumerate(target_lengths):
            offsets[index] = running
            running += int(length)
        return torch.tensor(offsets, dtype=torch.long, device=device)
    lengths = _lengths_to_tensor(target_lengths, device)
    return lengths.cumsum(0) - lengths


def _length_stats(values, name):
    """Return `(min, max)` of a host-side length argument.

    Only called with the sequences `_host_lengths` returns: tensor arguments
    are already flattened to the host there, so no device sync is left here.
    """
    lengths = list(values)
    if not lengths:
        raise RuntimeError(f"{name} must not be empty")
    return min(lengths), max(lengths)


# Label bounds are a pure function of the target tensor's contents, and the
# reduction that computes them costs ~7us on the host -- comparable to a kernel
# launch, which is real money at the smallest benchmark shape. Keyed the same way
# `_length_stats` in `ctc_loss.py` caches its statistics: device, address, size
# and `_version`, so an in-place mutation invalidates the entry. The tensor is
# held in the value to keep the address from being recycled underneath the key.
_TARGET_BOUNDS_CACHE = {}
_TARGET_BOUNDS_CACHE_LIMIT = 64


def _label_bounds(targets):
    """`(min, max)` of the labels, cached across calls with the same tensor."""
    if targets.device.type != "cpu":
        # A device tensor would need a synchronizing read to answer this; that is
        # the caller's choice to pay, not something to memoise.
        bounds = targets.aminmax()
        return int(bounds.min), int(bounds.max)

    key = (targets.data_ptr(), targets.numel(), targets._version)
    cached = _TARGET_BOUNDS_CACHE.get(key)
    if cached is not None:
        return cached[1]

    bounds = targets.aminmax()
    result = (int(bounds.min), int(bounds.max))
    if len(_TARGET_BOUNDS_CACHE) >= _TARGET_BOUNDS_CACHE_LIMIT:
        _TARGET_BOUNDS_CACHE.clear()
    _TARGET_BOUNDS_CACHE[key] = (targets, result)
    return result


def _host_lengths(input_lengths, target_lengths, batch_size):
    """Host copies of both length arguments, taking at most one device sync.

    Tensor arguments need a synchronising read before the range checks can run,
    and asking for each statistic separately paid for that read three times
    (~28us apiece on H20 -- as much as two kernel launches, which is visible at
    the smallest benchmark shape). Both vectors are `batch_size` long by the
    time this runs, so they move in a single copy.
    """
    if not torch.is_tensor(input_lengths) and not torch.is_tensor(target_lengths):
        return list(input_lengths), list(target_lengths)
    parts = []
    for values in (input_lengths, target_lengths):
        if torch.is_tensor(values):
            parts.append(values.reshape(-1).to(dtype=torch.long))
        else:
            parts.append(torch.tensor(list(values), dtype=torch.long))
    # Both vectors are packed into one buffer and read back with a single
    # `.cpu()` -- `torch.cat` is not allowed here, and staging by hand keeps the
    # one-sync property the docstring above is about.
    total = sum(part.numel() for part in parts)
    packed = torch.empty(total, dtype=torch.long, device=parts[0].device)
    offset = 0
    for part in parts:
        end = offset + part.numel()
        packed[offset:end].copy_(part)
        offset = end
    host = packed.cpu().tolist()
    return host[:batch_size], host[batch_size:]


def _check_targets(targets, target_lengths, num_classes):
    """Reject target tensors the kernels would read or write out of bounds.

    Both failure modes are memory safety issues, not accuracy issues: a short
    `targets` makes the forward's `targets + origin + index` run past the end of
    the buffer, and an out-of-range label makes `log_probs + t * N * C + b * C +
    label` read past the row and the backward's `atomic_add` write past the end
    of `grad_input`. cuDNN faults on both as well, so there is no odd-but-valid
    behaviour to preserve -- only a check to add before any kernel launches.

    The check runs against the *caller's* tensor rather than the staged device
    copy. Targets normally arrive on the CPU (cuDNN's own convention), where the
    label bounds are a host-side pass and are memoised by `_label_bounds`;
    validating the staged device copy instead would force a sync into an
    otherwise fully asynchronous path.
    """
    total = (
        sum(target_lengths)
        if not torch.is_tensor(target_lengths)
        else int(target_lengths.sum())
    )
    if int(total) != targets.numel():
        raise RuntimeError(
            "cudnn_ctc_loss expected sum(target_lengths) to equal "
            f"targets.numel(), but got {int(total)} and {targets.numel()}"
        )
    if targets.numel():
        label_min, label_max = _label_bounds(targets)
        if label_min < 0 or label_max >= num_classes:
            raise RuntimeError(
                "cudnn_ctc_loss expected targets to be in the range "
                f"[0, {num_classes}), but got [{label_min}, {label_max}]"
            )


# Both kernels walk `T` serially, and the per-step `log_probs` / `log_alpha`
# loads do not depend on the value being carried through the loop. Pipelining
# those loads is what makes the loop reduction-bound rather than latency-bound.
# 4 is where the benefit plateaus on H20 (swept 2..6): forward gained
# 1.25x/1.59x/1.57x and backward 2.03x/2.19x/2.06x on the three larger shapes,
# with the produced values bit-identical -- only the load schedule moves, never
# the order the recurrence is evaluated in. Deeper staging only adds registers.
_NUM_STAGES = 4


def _launch_params(block_s):
    """Pick the launch shape for a state-row block of `block_s` lanes.

    Both kernels carry the whole state row in one block and walk T serially, so
    occupancy is set by `block_s`. A row of 256 lanes (>= 128 target labels)
    leaves only one state lane per thread at Triton's default 4 warps; widening
    to 8 warps measured 1.13x on forward and 1.33x on backward there, while
    smaller rows regress because the extra warps mostly idle. Tuned on H20.
    """
    return {"num_warps": 8} if block_s >= 256 else {}


def _launch_backward(
    work_log_probs,
    work_targets,
    work_input_lengths,
    work_target_lengths,
    target_offsets,
    neg_log_likelihood,
    log_alpha,
    grad_input,
    T,
    batch_size,
    num_classes,
    state_count_max,
    blank,
    deterministic,
):
    block_s = triton.next_power_of_2(state_count_max)
    launch_params = _launch_params(block_s)
    with torch_device_fn.device(work_log_probs.device):
        # `grad_input` is filled entirely by the init kernel -- `exp(log_probs)`
        # on the valid time steps, zero elsewhere -- so it needs no separate
        # zero initialization before the accumulation below.
        total = work_log_probs.numel()
        block = 256
        grid = (triton.cdiv(total, block),)
        cudnn_ctc_loss_init_grad_kernel[grid](
            work_log_probs,
            work_input_lengths,
            work_target_lengths,
            log_alpha,
            grad_input,
            total,
            T,
            batch_size,
            num_classes,
            block_s,
            block,
        )
        cudnn_ctc_loss_backward_kernel[(batch_size,)](
            work_log_probs,
            work_targets,
            work_input_lengths,
            work_target_lengths,
            target_offsets,
            neg_log_likelihood,
            log_alpha,
            grad_input,
            T,
            batch_size,
            num_classes,
            state_count_max,
            blank,
            block_s,
            deterministic,
            _NUM_STAGES,
            **launch_params,
        )


def _check_log_probs(log_probs, blank):
    """Reject `log_probs`/`blank` combinations cuDNN itself refuses."""
    if log_probs.ndim != 3:
        raise RuntimeError(
            "Expected 3-dimensional tensor, but got "
            f"{log_probs.ndim}-dimensional tensor for argument #1 'log_probs'"
        )
    if not torch.is_floating_point(log_probs):
        raise RuntimeError(f'"cudnn_ctc_loss" not implemented for {log_probs.dtype}')
    if log_probs.dtype != torch.float32:
        raise RuntimeError(
            "Expected tensor for argument #1 'log_probs' to have scalar type "
            f"Float; but got {log_probs.dtype} instead"
        )
    if blank != 0:
        raise RuntimeError("blank must be label 0 for cudnn_ctc_loss")

    T, batch_size, _ = log_probs.shape
    # cuDNN rejects these with `CUDNN_STATUS_BAD_PARAM`. The Triton path has to
    # reject them up front instead: `log_alpha` is `(N, T, BLOCK_S)`, so with
    # `T == 0` every batch entry addresses offset 0 of an empty buffer and the
    # forward kernel's store is an illegal access that poisons the whole CUDA
    # context, not just this call.
    if T == 0:
        raise RuntimeError("Expected log_probs to have a positive time dimension")
    if batch_size == 0:
        raise RuntimeError("Expected log_probs to have a positive batch dimension")


def _prepare_inputs(targets, input_lengths, target_lengths, device, batch_size):
    """Move targets, lengths and offsets to the device; return them with the host lengths.

    The lengths arrive as Python sequences (the ATen schema allows tensors too,
    handled here), but every kernel needs them on the device. A blocking H2D
    copy of a few hundred bytes costs ~2ms of host time on the CUDA backend, and
    several of them per call dwarf the kernels, so the targets and both length
    vectors go up in as few copies as possible.

    A host copy of the lengths is returned as well: every range check below reads
    it, and taking it once here means the tensor-argument path pays for a single
    device sync instead of one per check.
    """
    if not torch.is_tensor(input_lengths) and not torch.is_tensor(target_lengths):
        input_lengths = list(input_lengths)
        target_lengths = list(target_lengths)
        if len(input_lengths) != batch_size or len(target_lengths) != batch_size:
            raise RuntimeError(
                "input_lengths/target_lengths need to have size matching " "batch_size"
            )
        (
            work_targets,
            work_input_lengths,
            work_target_lengths,
            target_offsets,
        ) = _upload_inputs(targets, input_lengths, target_lengths, device)
    else:
        work_targets = targets.to(device=device, dtype=torch.int32).contiguous()
        work_input_lengths = _lengths_to_tensor(input_lengths, device)
        work_target_lengths = _lengths_to_tensor(target_lengths, device)
        target_offsets = _target_offsets(target_lengths, device, batch_size)

    if work_input_lengths.numel() != batch_size:
        raise RuntimeError("input_lengths needs to have size to match batch_size")
    if work_target_lengths.numel() != batch_size:
        raise RuntimeError("target_lengths needs to have size to match batch_size")
    if work_targets.ndim != 1:
        raise RuntimeError(
            "Expected 1-dimensional tensor, but got "
            f"{work_targets.ndim}-dimensional tensor for argument #2 'targets'"
        )
    if targets.dtype != torch.int32:
        raise RuntimeError(
            "Expected tensor for argument #2 'targets' to have scalar type "
            f"Int; but got {targets.dtype} instead"
        )

    host_input_lengths, host_target_lengths = _host_lengths(
        input_lengths, target_lengths, batch_size
    )
    return (
        (work_targets, work_input_lengths, work_target_lengths, target_offsets),
        host_input_lengths,
        host_target_lengths,
    )


def _check_lengths(host_input_lengths, host_target_lengths, targets, num_classes, T):
    """Range-check the lengths and labels; return `max(target_lengths)`."""
    min_target_len, max_target = _length_stats(host_target_lengths, "target_lengths")
    if min_target_len < 0:
        raise RuntimeError("target_lengths must be non-negative")
    _, max_input = _length_stats(host_input_lengths, "input_lengths")
    if max_input > T:
        raise RuntimeError("input_lengths must be in [0, T]")
    _check_targets(targets, host_target_lengths, num_classes)
    return max_target


def _cudnn_ctc_loss_impl(
    log_probs,
    targets,
    input_lengths,
    target_lengths,
    blank,
    deterministic,
    zero_infinity,
):
    _check_log_probs(log_probs, blank)
    T, batch_size, num_classes = log_probs.shape
    work_log_probs = log_probs.contiguous()

    (
        (work_targets, work_input_lengths, work_target_lengths, target_offsets),
        host_input_lengths,
        host_target_lengths,
    ) = _prepare_inputs(
        targets, input_lengths, target_lengths, log_probs.device, batch_size
    )
    max_target = _check_lengths(
        host_input_lengths, host_target_lengths, targets, num_classes, T
    )

    state_count_max = 2 * max_target + 1
    block_s = triton.next_power_of_2(state_count_max)
    launch_params = _launch_params(block_s)

    neg_log_likelihood = torch.empty(
        (batch_size,), dtype=torch.float32, device=log_probs.device
    )
    log_alpha = torch.empty(
        (batch_size, T, block_s),
        dtype=torch.float32,
        device=log_probs.device,
    )
    grad_input = torch.empty_like(work_log_probs)
    if batch_size > 0:
        with torch_device_fn.device(log_probs.device):
            cudnn_ctc_loss_forward_kernel[(batch_size,)](
                work_log_probs,
                work_targets,
                work_input_lengths,
                work_target_lengths,
                target_offsets,
                neg_log_likelihood,
                log_alpha,
                T,
                batch_size,
                num_classes,
                state_count_max,
                blank,
                block_s,
                _NUM_STAGES,
                **launch_params,
            )

    # cuDNN materializes the gradient of `log_probs` eagerly, so it is returned
    # as a plain tensor alongside the loss. PyTorch's native autograd rule for
    # `_cudnn_ctc_loss` consumes exactly this pair: it scales `raw_grad` by the
    # per-batch upstream gradient and applies the `zero_infinity` mask itself.
    # So `zero_infinity` is accepted only to match the schema -- masking here
    # would hand the autograd rule an already-masked gradient and make the
    # returned `raw_grad` diverge from what the native kernel reports.
    if batch_size > 0:
        _launch_backward(
            work_log_probs,
            work_targets,
            work_input_lengths,
            work_target_lengths,
            target_offsets,
            neg_log_likelihood,
            log_alpha,
            grad_input,
            T,
            batch_size,
            num_classes,
            state_count_max,
            blank,
            deterministic,
        )

    return neg_log_likelihood, grad_input


def cudnn_ctc_loss(
    log_probs,
    targets,
    input_lengths,
    target_lengths,
    blank=0,
    deterministic=True,
    zero_infinity=False,
):
    logger.debug("GEMS CUDNN_CTC_LOSS")
    return _cudnn_ctc_loss_impl(
        log_probs,
        targets,
        input_lengths,
        target_lengths,
        blank,
        deterministic,
        zero_infinity,
    )
