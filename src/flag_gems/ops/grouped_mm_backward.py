# Semantics (matching ATen's ``_grouped_mm`` backward, i.e. the row-major fast
# paths of the ``_grouped_mm_mat1_backward`` / ``_grouped_mm_mat2_backward``
# autograd helpers):
#
#   group i covers rows [offs[i - 1], offs[i]) of the leading (token) dim of
#   ``mat1`` / ``grad_output``, with ``offs`` an int32 tensor of cumulative
#   group ends.
#
#   grad_mat1[rows_i, :] = grad_output[rows_i, :] @ mat2[i]^T   # (m_i, n) @ (n, k)
#   grad_mat2[i, :, :]   = mat1[rows_i, :]^T @ grad_output[rows_i, :]
#                                                        # (k, m_i) @ (m_i, n)
#
# The pinned Torch build has no standalone ``aten::_grouped_mm_backward``
# schema: ATen derives the two input gradients from those helpers, and this
# module reproduces both with grouped-GEMM kernels.  The kernels accumulate
# in float32 and cast to the input dtype (bf16 only, like the forward op).


