def grouped_mm_backward(grad_output, mat1, mat2, offs=None):
    """Input gradients of ``aten::_grouped_mm``.

    Args:
        grad_output: Gradient w.r.t. the ``_grouped_mm`` output, ``(M, N)``.
        mat1: Forward operand, 2-D ``(M, K)`` (rows partitioned by ``offs``).
        mat2: Forward operand, 3-D ``(G, K, N)``.
        offs: Optional int32 tensor of cumulative group ends over ``mat1``
            rows.  ``None`` means uniform groups (3-D ``mat1``).

    Returns:
        ``(grad_mat1, grad_mat2)`` with the shapes of ``mat1`` / ``mat2``.
    """
    logger.debug("GEMS GROUPED_MM_BACKWARD")
    if grad_output.dtype != torch.bfloat16:
        raise ValueError("grouped_mm_backward only supports bfloat16 inputs")
    if offs is None:
        if mat1.dim() != 3:
            raise ValueError("grouped_mm_backward without offs requires a 3-D mat1")
        # Uniform groups: collapse the group dim into the row dim.
        g_dim, m_dim, k_dim = mat1.shape
        grad_out3 = grad_output.reshape(g_dim * m_dim, grad_output.shape[-1])
        grad_mat1_flat, grad_mat2 = grouped_mm_backward(
            grad_out3,
            mat1.reshape(g_dim * m_dim, k_dim),
            mat2,
            _uniform_offs(g_dim, m_dim, grad_output.device),
        )
        return grad_mat1_flat.view(g_dim, m_dim, k_dim), grad_mat2

    if offs.dtype != torch.int32:
        raise ValueError("grouped_mm_backward offs must be int32")
    if mat1.dim() != 2 or mat2.dim() != 3:
        raise ValueError("grouped_mm_backward expects 2-D mat1 and 3-D mat2 with offs")

    M, N = grad_output.shape
    K = mat1.shape[1]
    G = mat2.shape[0]

    grad_output = grad_output.contiguous()
    mat1 = mat1.contiguous()
    mat2 = mat2.contiguous()
    offs = offs.contiguous()

    grad_mat1 = torch.empty_like(mat1)
    grad_mat2 = torch.empty_like(mat2)
    BG = triton.next_power_of_2(max(G, 1))

    # Config selection from shape scalars only (measured on H20-3e):
    # - large output (M*K big): TMA descriptor loads when tensors are
    #   contiguous and 16B-aligned (hardware zero-fill covers N/K/M edges;
    #   masked stores preserve group boundaries); otherwise the 128x128x64 s5
    #   fallback
    # - medium output: small tiles with 4 warps give the best occupancy
    # - small output: keep the conservative 128x128x64 config
    with torch_device_fn.device(grad_output.device):
        use_tma_d1 = (
            _HAS_TMA
            and M * K > 3_000_000
            and grad_output.stride(1) == 1
            and grad_output.stride(0) == N
            and N % 8 == 0
            and mat2.stride(2) == 1
            and mat2.stride(1) == N
            and mat2.stride(0) == K * N
            and grad_output.data_ptr() % 16 == 0
            and mat2.data_ptr() % 16 == 0
            and grad_mat1.data_ptr() % 16 == 0
        )
        if use_tma_d1:
            go_desc = TensorDescriptor.from_tensor(grad_output, [128, 64])
            m2_desc = TensorDescriptor.from_tensor(mat2.view(G * K, N), [128, 64])
            grid1 = (triton.cdiv(M, 128) + G, triton.cdiv(K, 128))
            _dmat1_tma_kernel[grid1](
                go_desc,
                m2_desc,
                grad_mat1,
                offs,
                M,
                N,
                K,
                G,
                grad_mat1.stride(0),
                grad_mat1.stride(1),
                BM=128,
                BK=128,
                BN=64,
                BG=BG,
                EVEN_K=(K % 128 == 0),
                num_warps=8,
                num_stages=3,
            )
        else:
            if M * K > 16_000_000:
                bm1, bk1, bn1, w1, s1 = 128, 128, 64, 8, 5
            elif M * K > 3_000_000:
                bm1, bk1, bn1, w1, s1 = 64, 128, 64, 4, 4
            else:
                bm1, bk1, bn1, w1, s1 = 128, 128, 64, 8, 3
            # grad_mat1: C tiles (BM rows x BK k-cols), contraction over n in
            # blocks of BN
            grid1 = (triton.cdiv(M, bm1) + G, triton.cdiv(K, bk1))
            _dmat1_kernel[grid1](
                grad_output,
                mat2,
                grad_mat1,
                offs,
                M,
                N,
                K,
                G,
                grad_output.stride(0),
                grad_output.stride(1),
                mat2.stride(0),
                mat2.stride(1),
                mat2.stride(2),
                grad_mat1.stride(0),
                grad_mat1.stride(1),
                BM=bm1,
                BK=bk1,
                BN=bn1,
                BG=BG,
                EVEN_K=(K % bk1 == 0),
                EVEN_N=(N % bn1 == 0),
                num_warps=w1,
                num_stages=s1,
            )

        # Config selection for grad_mat2: large per-group output (K*N*G big)
        # favors many small output tiles (64x128) with 32-row contraction
        # chunks for higher occupancy; otherwise small tiles with 4 warps win.
        if K * N * G > 32_000_000:
            bk2, bn2, bm2, w2, s2 = 64, 128, 32, 4, 4
        else:
            bk2, bn2, bm2, w2, s2 = 64, 128, 64, 4, 4

        # grad_mat2: C tiles (BK k-rows x BN n-cols), contraction over group
        # rows in blocks of BM
        grid2 = (triton.cdiv(K, bk2), triton.cdiv(N, bn2), G)
        _dmat2_kernel[grid2](
            mat1,
            grad_output,
            grad_mat2,
            offs,
            M,
            N,
            K,
            G,
            mat1.stride(0),
            mat1.stride(1),
            grad_output.stride(0),
            grad_output.stride(1),
            grad_mat2.stride(0),
            grad_mat2.stride(1),
            grad_mat2.stride(2),
            BK=bk2,
            BN=bn2,
            BM=bm2,
            EVEN_K=(K % bk2 == 0),
            EVEN_N=(N % bn2 == 0),
            num_warps=w2,
            num_stages=s2,
        )
    return grad_mat1, grad_mat2


def _uniform_offs(g, m, device):
    ends = torch.arange(1, g + 1, device=device, dtype=torch.int32)
    return ends * m
