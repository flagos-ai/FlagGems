"""Autograd bridge and Triton backward kernel for ``aten::exp``.

The pinned Torch build exposes no ``aten::exp_backward`` schema: ATen
derives the input gradient from the autograd formula
``grad * result.conj()`` -- i.e. the gradient of ``exp`` is simply the
output gradient multiplied by the (already stored) forward result
``exp(x)``.

The kernel below fuses the ATen two-kernel chain (``exp`` recompute, then
the gradient multiply) into a single launch while keeping ATen's
per-op rounding boundaries: the recomputed ``exp(x)`` is rounded to
the storage dtype before the multiply, and the product is rounded
again on store, so fp32/fp16/bf16 gradients are bit-exact against
native autograd.
"""

import logging

import torch
import triton
import triton.language as tl
import triton.language.extra.libdevice as libdevice

from flag_gems.runtime import torch_device_fn
from flag_gems.utils import libentry

logger = logging.getLogger(__name__)

# The block size is dispatched on the tensor size: launch-bound small tensors
# win from more CTAs, large streaming tensors from the wider block. Both
# values come from the SimpleOpt sweep on H20-3e.
_SMALL_NUMEL = 4096
_SMALL_BLOCK = 256
_LARGE_BLOCK = 1024
_NUM_WARPS = 4


@libentry()
@triton.jit
def _exp_backward_kernel(
    grad_output_ptr,
    x_ptr,
    grad_input_ptr,
    n_elements,
    BLOCK: tl.constexpr,
    LOWP: tl.constexpr,  # 0 = fp32, 1 = fp16, 2 = bf16
):
    pid = tl.program_id(axis=0)
    offsets = pid * BLOCK + tl.arange(0, BLOCK)
    mask = offsets < n_elements

    grad = tl.load(grad_output_ptr + offsets, mask=mask, other=0.0)
    x = tl.load(x_ptr + offsets, mask=mask, other=0.0)

    # All math runs in fp32 and every step is rounded back to the storage
    # dtype, exactly like ATen's sequence of elementwise kernels does.
    xf = x.to(tl.float32)
    gf = grad.to(tl.float32)

    # Step 1: y = exp(x). ATen recomputes exp inside the backward graph;
    # libdevice.exp matches its `expf` for every storage dtype (fp16/bf16
    # included -- tl.exp lowers to ex2.approx and is not bit-exact there).
    y = libdevice.exp(xf)
    if LOWP == 1:
        y = y.to(tl.float16).to(tl.float32)
    elif LOWP == 2:
        y = y.to(tl.bfloat16).to(tl.float32)

    # Step 2: grad_input = grad_output * y  (binary mul, rounded)
    out = gf * y
    if LOWP == 1:
        out = out.to(tl.float16)
    elif LOWP == 2:
        out = out.to(tl.bfloat16)

    tl.store(grad_input_ptr + offsets, out, mask=mask)


def _lowp_code(dtype: torch.dtype) -> int:
    if dtype == torch.float16:
        return 1
    if dtype == torch.bfloat16:
        return 2
    return 0


def exp_backward(grad_output: torch.Tensor, x: torch.Tensor):
    """Gradient of ``exp``: ``grad_output * exp(x)``.

    Args:
        grad_output: Gradient w.r.t. the ``exp`` output.
        x: Original input tensor of ``exp`` (used to recompute the output).

    Returns:
        Gradient w.r.t. the input, with the same dtype as ``x``.
    """
    logger.debug("GEMS EXP_BACKWARD")
    if grad_output.numel() == 0:
        return torch.empty(grad_output.shape, dtype=x.dtype, device=x.device)

    grad_contig = grad_output.contiguous()
    x_contig = x.contiguous()
    # The gradient keeps the forward input's dtype: ATen's formula rounds every
    # intermediate to that storage dtype.
    grad_input = torch.empty(
        grad_contig.shape, dtype=x.dtype, device=grad_contig.device
    )
    n_elements = grad_contig.numel()
    block = _SMALL_BLOCK if n_elements <= _SMALL_NUMEL else _LARGE_BLOCK
    grid = ((n_elements + block - 1) // block,)
    with torch_device_fn.device(grad_output.device):
        _exp_backward_kernel[grid](
            grad_contig,
            x_contig,
            grad_input,
            n_elements,
            BLOCK=block,
            LOWP=_lowp_code(x.dtype),
            num_warps=_NUM_WARPS,
        )
    return grad_input


