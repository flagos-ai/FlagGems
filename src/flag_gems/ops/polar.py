@triton.jit
def linear_offset(index, shape: tl.constexpr, strides: tl.constexpr):
    remaining = index.to(tl.int64)
    result = tl.full(index.shape, 0, tl.int64)
    for axis in tl.static_range(len(shape) - 1, -1, -1):
        coordinate = remaining % shape[axis]
        result = result + coordinate * strides[axis]
        remaining = remaining // shape[axis]
    return result


