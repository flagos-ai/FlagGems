"""Triton implementation of ``aten.linalg_cholesky_ex`` (batched Cholesky).

The aten reference returns ``(L, info)``:

* ``L``  -- the requested triangular factor with the unused triangle zeroed,
* ``info`` -- int32 tensor with one entry per matrix (0 on success).

Only one triangle of the input is read (lower when ``upper=False``, upper when
``upper=True``); that triangle is mirrored to form the Hermitian work matrix.

The whole ``BLOCK_N x BLOCK_N`` tile stays register-resident inside one program
per matrix and is factored with an unblocked right-looking Cholesky using
rank-1 updates.  Every floating point operation that contributes to the
returned factor happens inside the Triton kernel; the host wrapper only
allocates outputs, computes a few scalars and launches the kernel.
"""

import torch
import triton
import triton.language as tl


@triton.jit
def _cholesky_ex_kernel(
    A_ptr,
    Out_ptr,
    Info_ptr,
    N,
    NUM,
    s0,
    s1,
    s2,
    o0,
    o1,
    o2,
    UPPER: tl.constexpr,
    BLOCK_N: tl.constexpr,
    NSTEPS: tl.constexpr,
    IS64: tl.constexpr,
):
    pid = tl.program_id(0)
    r = tl.arange(0, BLOCK_N)
    ri = r[:, None]
    cj = r[None, :]
    valid = (ri < N) & (cj < N)

    # --- load one whole matrix, then mirror the requested triangle ---------
    x = tl.load(A_ptr + pid * s0 + ri * s1 + cj * s2, mask=valid, other=0.0)
    if IS64:
        W = x
    else:
        W = x.to(tl.float32)

    if UPPER:
        tri = tl.where(ri <= cj, W, 0.0)
    else:
        tri = tl.where(ri >= cj, W, 0.0)
    # symmetry: tri + tri^T would double the diagonal
    W = tri + tl.trans(tri) - tl.where(ri == cj, tri, 0.0)
    W = tl.where(valid, W, 0.0)

    # --- unblocked right-looking Cholesky (rank-1 updates) ------------------
    # Invariant: entering step j the tile holds
    #     W = A - sum_{k<j} L[:, k] L[:, k]^T
    # on the trailing (i>j, c>j) sub-block.  The trip count is the exact matrix
    # order, not the padded tile width: rows/columns >= N are zero and the store
    # is masked to the valid region, so the padded steps would be dead work on
    # the serial critical path.
    # ``info`` is the 1-based index of the first non-positive pivot, matching
    # ``aten::linalg_cholesky_ex``; 0 means the factorisation succeeded.
    info = 0
    for j in tl.static_range(NSTEPS):
        col = tl.sum(tl.where(cj == j, W, 0.0), axis=1)
        pivot = tl.sum(tl.where(r == j, col, 0.0))
        # A non-positive or non-finite pivot means the leading minor of order
        # j+1 is not positive definite.  Record the first such j and keep the
        # loop going: the trip count is a static range, and the trailing values
        # are discarded by the caller once info != 0.
        bad = (pivot <= 0.0) or (pivot != pivot)
        if bad and info == 0:
            info = j + 1
        scale = tl.sqrt(pivot)
        inv = 1.0 / scale
        col = tl.where(r > j, col * inv, 0.0)
        col = tl.where(r == j, scale, col)
        # column j now holds L[:, j] exactly (zeros above the diagonal)
        W = tl.where(cj == j, col[:, None], W)
        upd = col[:, None] * col[None, :]
        W = tl.where((ri > j) & (cj > j), W - upd, W)

    if UPPER:
        res = tl.trans(W)
    else:
        res = W

    tl.store(
        Out_ptr + pid * o0 + ri * o1 + cj * o2,
        res.to(Out_ptr.dtype.element_ty),
        mask=valid,
    )
    tl.store(Info_ptr + pid, info)


