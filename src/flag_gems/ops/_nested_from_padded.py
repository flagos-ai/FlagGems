    """Create a nested tensor from a padded dense tensor.

    ``cpu_nested_shape_example`` is an int64 tensor on CPU whose i-th row is the
    nested size ``[len_i, *inner_dims]`` of the i-th component. The returned nested
    tensor reuses the values of ``padded`` with the padding rows removed.
    """
