# ``_nested_from_padded`` builds a legacy (``torch.strided``) nested tensor from
# a padded dense tensor. ``cpu_nested_shape_example`` carries one size row per
# component: entry ``j`` of row ``b`` is the extent of component ``b`` along
# padded dimension ``j + 1``, so entry 0 is its length along the ragged (padded)
# dimension 1. Only that left-aligned prefix box is kept, and its elements are
# concatenated in row-major order into the flat ``values`` buffer of the result;
# padding trimmed off the trailing dims is dropped, not copied. The components
# of the result are therefore contiguous boxes laid out back to back.
#
# With ``fuse_transform_0213=True`` the padded tensor is first permuted
# ``(0, 2, 1, 3)`` and flattened to ``[B, E, T * C]`` -- fusing the (0<->2) and
# (1<->3) transposes used around transformer attention -- and the same prefix
# copy then runs on that transformed layout.


