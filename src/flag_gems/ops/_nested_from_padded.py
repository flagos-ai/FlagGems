def _nested_from_padded_bwd_contig_kernel(
    gvalues,
    totals,  # [B] int64 element count of each component
    out_starts,  # [B] int64 element offset of each component in `gvalues`
    grad_input,
    plane,  # int64 element count of one padded row after dim 0
    BLOCK: tl.constexpr,
):
    """Write the dense gradient when every component's prefix is contiguous.

    Component ``b`` owns the contiguous run ``[0, totals[b])`` of padded row
    ``b``, and the matching upstream values are the contiguous run
    ``[out_starts[b], out_starts[b] + totals[b])`` of the flat values gradient.
    Everything past ``totals[b]`` is padding, whose gradient is zero. One
    program writes a whole block of the row, so the entire dense gradient is
    produced by a single kernel instead of a fill plus one copy per component.
    """
    b = tle.program_id(0)
    chunk = tle.program_id(1)

    total = tl.load(totals + b)
    pos = chunk * BLOCK + tl.arange(0, BLOCK)
    inrow = pos < plane
    # A component never extends past its padded row for a valid shape example;
    # clamping the read to the row keeps a malformed one from reading past the
    # values buffer instead of only writing zeros.
    inbox = inrow & (pos < total)

    val = tl.load(gvalues + tl.load(out_starts + b) + pos, mask=inbox, other=0.0)
    tl.store(grad_input + b.to(tl.int64) * plane + pos, val, mask=inrow)


