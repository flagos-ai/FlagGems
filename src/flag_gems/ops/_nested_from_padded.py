def _nested_from_padded_kernel(
    padded,
    sizes,  # [B, NDIM] int64 component extents; entry 0 is the ragged length
    pstrides,  # [NDIM] int64 stride of padded dimension j + 1
    out_starts,  # [B] int64 element offset of each component in `values`
    values,
    stride_b,  # int64 stride of padded dimension 0
    NDIM: tl.constexpr,
    BLOCK: tl.constexpr,
):
    """Copy one component's prefix box into the flat ``values`` buffer.

    Program ``(b, chunk)`` handles elements ``chunk * BLOCK`` onwards of
    component ``b``. Destination positions are walked in row-major order over
    the component's own extents and mapped back to the source position in
    ``padded``, so a prefix box of any dimensionality is handled uniformly.
    """
    b = tle.program_id(0)
    chunk = tle.program_id(1)

    sizes_b = sizes + b * NDIM
    # Total element count of the component's prefix box.
    total = tl.load(sizes_b)
    for d in tl.static_range(1, NDIM):
        total *= tl.load(sizes_b + d)

    pos = chunk * BLOCK + tl.arange(0, BLOCK)
    mask = pos < total

    # Decompose the destination index into per-dimension coordinates, fastest
    # varying dimension first; what remains belongs to the ragged dimension 1.
    src = b.to(tl.int64) * stride_b
    rem = pos.to(tl.int64)
    for d in tl.static_range(NDIM - 1, 0, -1):
        extent = tl.load(sizes_b + d)
        # Guard the empty component (extent 0 makes `mask` all-false anyway) so
        # the index arithmetic never divides by zero.
        extent = tl.where(extent == 0, 1, extent)
        src += (rem % extent) * tl.load(pstrides + d)
        rem = rem // extent
    src += rem * tl.load(pstrides)

    val = tl.load(padded + src, mask=mask)
    tl.store(values + tl.load(out_starts + b) + pos, val, mask=mask)


def _prefix_is_contiguous(sizes: torch.Tensor, padded: torch.Tensor) -> bool:
    """Whether every component's prefix box is a contiguous run in ``padded``.

    That holds when each row of ``sizes`` matches the trailing dims of
    ``padded`` exactly, i.e. only the ragged dimension is trimmed.
    """
    return bool(
        (sizes[:, 1:] == torch.tensor(padded.shape[2:], dtype=sizes.dtype)).all()
    )


