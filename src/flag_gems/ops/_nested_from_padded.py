class _NestedFromPaddedBackward(torch.autograd.Function):
    """Give ``_nested_from_padded`` a Triton first-order backward.

    ``aten::_nested_from_padded`` is a pure copy, so ATen's generated
    ``NestedFromPaddedBackward0`` zero-fills the whole padded tensor and then
    copies every component's prefix back with one kernel per component. The
    wrapper below replaces that with a single un-padding kernel. Only the flat
    ``values`` buffer is wrapped: a nested tensor cannot be returned from a
    custom ``Function`` (``NestedTensorImpl`` has no ``sizes``), and the outer
    ``_nested_view_from_buffer`` view then carries the gradient to this node.

    The gradient layout is the layout the values were copied from. With
    ``fuse_transform_0213`` that is the already-permuted ``[B, E, T * C]`` view,
    and the permute that built it is part of the forward graph, so its own
    backward un-permutes the result back to the original 4D padded tensor.

    The Triton backward does not build a graph for higher-order gradients, the
    same first-order restriction as the other FlagGems autograd wrappers.
    """

