@triton.jit
def _cubic_weight(t, a: tl.constexpr):
    # Keys cubic convolution (a=-0.75), same as upsample_bicubic2d.
    ad = tl.abs(t)
    ad2 = ad * ad
    ad3 = ad2 * ad
    w1 = (a + 2.0) * ad3 - (a + 3.0) * ad2 + 1.0
    w2 = a * ad3 - 5.0 * a * ad2 + 8.0 * a * ad - 4.0 * a
    return tl.where(ad <= 1.0, w1, tl.where(ad < 2.0, w2, 0.0))


@triton.jit
def _reflect_int_index(idx, n, align_corners: tl.constexpr):
    # Reflect an integer tap index into [0, n-1].
    # align_corners=True: period 2*(n-1), fold around 0 and n-1.
    # align_corners=False: period 2*n shifted by 0.5 (reflect around -0.5 and n-0.5),
    #   implemented via the continuous formula then floored, so multi-period
    #   out-of-range indices are handled correctly.
    if align_corners:
        p = 2 * (n - 1)
        # p is 0 only when n == 1; in that case every tap maps to 0.
        idx_mod = tl.where(p == 0, 0, idx - tl.floor(idx / p) * p)
        return tl.where(idx_mod >= n, p - idx_mod, idx_mod).to(tl.int32)
    else:
        p = 2 * n
        x = idx + 0.5
        x_mod = x - tl.floor(x / p) * p
        x_mod = tl.where(x_mod > n, p - x_mod, x_mod)
        return (x_mod - 0.5).to(tl.int32)


