# Metadata-based kernels (fallback: N > 4, mixed dtype groups, non-contiguous,
# or offsets that do not fit in 32 bits).
# meta layout (int64): [offsets (N+1), chunk-prefix (N+1), ptrs (N)]
# ---------------------------------------------------------------------------
@triton.jit
def _flatten_contig_kernel(
    out_ptr,
    meta,
    N,
    BLOCK: tl.constexpr,
    LOG2N: tl.constexpr,
    DT: tl.constexpr,
):
    pid = tl.program_id(0)
    coff = meta + (N + 1)
    ptrs = meta + 2 * (N + 1)
    # binary search: first idx in [1, N] with chunk-prefix[idx] > pid
    lo = tl.full([1], 1, tl.int32)
    hi = tl.full([1], N, tl.int32)
    for _ in tl.static_range(LOG2N):
        mid = (lo + hi) >> 1
        cm = tl.load(coff + mid)
        advance = cm <= pid
        lo = tl.where(advance, mid + 1, lo)
        hi = tl.where(advance, hi, mid)
    t = lo - 1
    k = pid - tl.load(coff + t)
    off_t = tl.load(meta + t)
    end_t = tl.load(meta + t + 1)
    ptr_t = tl.load(ptrs + t)
    start = off_t + k.to(tl.int64) * BLOCK
    offs = start + tl.arange(0, BLOCK)
    mask = offs < end_t
    local = offs - off_t
    pp = ptr_t.to(tl.pointer_type(DT))
    x = tl.load(pp + local, mask=mask)
    tl.store(out_ptr + offs, x, mask=mask)


@triton.jit
def _flatten_general_kernel(
    out_ptr,
    meta,
    shapes,
    strides,
    N,
    BLOCK: tl.constexpr,
    LOG2N: tl.constexpr,
    DT: tl.constexpr,
    MAX_DIM: tl.constexpr,
):
    # shapes/strides rows are stored reversed (last dim first), padded with shape 1.
    pid = tl.program_id(0)
    coff = meta + (N + 1)
    ptrs = meta + 2 * (N + 1)
    lo = tl.full([1], 1, tl.int32)
    hi = tl.full([1], N, tl.int32)
    for _ in tl.static_range(LOG2N):
        mid = (lo + hi) >> 1
        cm = tl.load(coff + mid)
        advance = cm <= pid
        lo = tl.where(advance, mid + 1, lo)
        hi = tl.where(advance, hi, mid)
    t = lo - 1
    k = pid - tl.load(coff + t)
    off_t = tl.load(meta + t)
    end_t = tl.load(meta + t + 1)
    ptr_t = tl.load(ptrs + t)
    start = off_t + k.to(tl.int64) * BLOCK
    offs = start + tl.arange(0, BLOCK)
    mask = offs < end_t
    local = offs - off_t
    # decompose logical flat index -> physical element offset (row-major order)
    acc = local
    phys = tl.zeros([BLOCK], tl.int64)
    base_s = shapes + t.to(tl.int64) * MAX_DIM
    base_r = strides + t.to(tl.int64) * MAX_DIM
    for d in tl.static_range(MAX_DIM):
        sd = tl.load(base_s + d)
        st = tl.load(base_r + d)
        idx = acc % sd
        acc = acc // sd
        phys += idx * st
    pp = ptr_t.to(tl.pointer_type(DT))
    x = tl.load(pp + phys, mask=mask)
    tl.store(out_ptr + offs, x, mask=mask)


def _launch_group(out, group, group_offsets, tl_dt):
    dev = out.device
    N = len(group)
    numels = [group_offsets[k + 1] - group_offsets[k] for k in range(N)]
    chunks = [(n + _BLOCK - 1) // _BLOCK for n in numels]
    total_chunks = sum(chunks)
    if total_chunks == 0:
        return
    LOG2N = _LOG2N if N <= (1 << _LOG2N) else N.bit_length()
    coff = [0] * (N + 1)
    for i, c in enumerate(chunks):
        coff[i + 1] = coff[i] + c
    meta = torch.tensor(
        group_offsets + coff + [t.data_ptr() for t in group],
        dtype=torch.int64,
        device=dev,
    )
    if all(t.is_contiguous() for t in group):
        _flatten_contig_kernel[(total_chunks,)](
            out,
            meta,
            N,
            BLOCK=_BLOCK,
            LOG2N=LOG2N,
            DT=tl_dt,
            num_warps=_NUM_WARPS,
        )
    else:
        nd = max(t.dim() for t in group)
        max_dim = max(_MAX_DIM, nd)
        shapes = torch.ones(N, max_dim, dtype=torch.int64, device=dev)
        strides = torch.zeros(N, max_dim, dtype=torch.int64, device=dev)
        for i, t in enumerate(group):
            for d in range(t.dim()):
                shapes[i, t.dim() - 1 - d] = t.shape[d]
                strides[i, t.dim() - 1 - d] = t.stride(d)
        _flatten_general_kernel[(total_chunks,)](
            out,
            meta,
            shapes,
            strides,
            N,
            BLOCK=_BLOCK,
            LOG2N=LOG2N,
            DT=tl_dt,
            MAX_DIM=max_dim,
            num_warps=_NUM_WARPS,
        )


def flatten_dense_tensors(tensors):
    """``aten::flatten_dense_tensors(Tensor[] tensors) -> Tensor``."""
    logger.debug("GEMS FLATTEN_DENSE_TENSORS")
    # Iterating a bare Tensor yields its rows and would silently flatten only
    # the first dimensions, so reject the same inputs the reference rejects.
    if isinstance(tensors, torch.Tensor):
        raise TypeError(
            "flatten_dense_tensors(): argument 'tensors' (position 1) must be "
            "a list of Tensors, not Tensor"
        )
    for item in tensors:
        if not isinstance(item, torch.Tensor):
            raise TypeError(
                "flatten_dense_tensors(): expected Tensor as element, but got "
                f"{type(item).__name__}"
            )
    n = len(tensors)
    if n == 0:
        raise RuntimeError("torch.cat(): expected a non-empty list of Tensors")

    # Fast path 1: single tensor. For a contiguous tensor the reference itself
    # returns a zero-copy flattened view, so return the same view. Non-contiguous
    # single tensors are copied through the general metadata kernel.
    if n == 1:
        t0 = tensors[0]
        if t0.is_contiguous():
            return t0.view(-1)
        tl_dt = _TL_DTYPE.get(t0.dtype)
        if tl_dt is None:
            raise RuntimeError("flatten_dense_tensors: unsupported dtype %s" % t0.dtype)
        total = t0.numel()
        out = torch.empty(total, dtype=t0.dtype, device=t0.device)
        if total == 0:
            return out
        _launch_group(out, [t0], [0, total], tl_dt)
        return out

    ts = list(tensors)
    dev = ts[0].device
    # Single fused pass over the list: numels, offsets, max_chunks, uniformity,
    # contiguity (avoids several small python loops).
    dt0 = ts[0].dtype
    numels = [ts[0].numel()]
    offs = [0, numels[0]]
    uniform = True
    contig = ts[0].is_contiguous()
    for i in range(1, n):
        t = ts[i]
        if t.dtype != dt0:
            uniform = False
        if not t.is_contiguous():
            contig = False
        m = t.numel()
        numels.append(m)
        offs.append(offs[i] + m)
    total = offs[n]
    if uniform:
        out_dtype = dt0
    else:
        out_dtype = dt0
        for t in ts[1:]:
            out_dtype = torch.promote_types(out_dtype, t.dtype)
    if _TL_DTYPE.get(out_dtype) is None:
        raise RuntimeError(
            "flatten_dense_tensors: unsupported output dtype %s" % out_dtype
        )

    out = torch.empty(total, dtype=out_dtype, device=dev)
    if total == 0:
        return out

    # Fast path 2: small-N contiguous uniform-dtype list -> 2D-grid kernel with
    # scalar (packed) metadata, avoiding per-call device metadata construction.
    if uniform and 2 <= n <= 4 and total < (1 << 32) and contig:
        tl_dt = _TL_DTYPE[out_dtype]
        # Launch-config specialization by element size: 16-bit dtypes prefer
        # smaller blocks / fewer warps (more, finer-grained programs); 32-bit
        # dtypes prefer large blocks.
        esize = ts[0].element_size()
        if esize <= 2:
            block, nw = 1024, 4
        elif esize == 4:
            block, nw = 4096, 8
        else:
            block, nw = _BLOCK, _NUM_WARPS
        max_chunks = max((m + block - 1) // block for m in numels)
        # The maskless variant is only safe when every tensor has exactly
        # max_chunks full chunks (equal numels that are multiples of BLOCK);
        # otherwise per-chunk bounds masks are required.
        masked = not (all(m == numels[0] for m in numels) and numels[0] % block == 0)
        vs = [(numels[i] << 32) | offs[i] for i in range(n)]
        ps = [t.data_ptr() for t in ts]
        if n == 2:
            _flatten_n2[(2, max_chunks)](
                out,
                ps[0],
                ps[1],
                vs[0],
                vs[1],
                BLOCK=block,
                DT=tl_dt,
                MASKED=masked,
                num_warps=nw,
            )
        elif n == 3:
            _flatten_n3[(3, max_chunks)](
                out,
                ps[0],
                ps[1],
                ps[2],
                vs[0],
                vs[1],
                vs[2],
                BLOCK=block,
                DT=tl_dt,
                MASKED=masked,
                num_warps=nw,
            )
        else:
            _flatten_n4[(4, max_chunks)](
                out,
                ps[0],
                ps[1],
                ps[2],
                ps[3],
                vs[0],
                vs[1],
                vs[2],
                vs[3],
                BLOCK=block,
                DT=tl_dt,
                MASKED=masked,
                num_warps=nw,
            )
        return out

    # Fallback: grouped metadata path (mixed dtypes, N > 4, large totals,
    # non-contiguous tensors). offs holds the global element offsets.
    cur = 0
    while cur < n:
        dt = ts[cur].dtype
        tl_dt = _TL_DTYPE.get(dt)
        if tl_dt is None:
            raise RuntimeError("flatten_dense_tensors: unsupported dtype %s" % dt)
        j = cur + 1
        while j < n and ts[j].dtype == dt:
            j += 1
        _launch_group(out, ts[cur:j], offs[cur : j + 1], tl_dt)
        cur = j
    return out


