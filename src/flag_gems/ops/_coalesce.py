def _coalesce_impl(self, out=None):
    """Coalesce a sparse COO tensor ``self`` (optionally into ``out``)."""
    if not isinstance(self, torch.Tensor) or self.layout != torch.sparse_coo:
        raise RuntimeError(
            "_coalesce only supports sparse coordinate (coo) tensors, "
            f"but got layout {getattr(self, 'layout', None)}"
        )
    device = self.device
    if device.type != "cuda":
        raise NotImplementedError("_coalesce triton implementation requires CUDA")
    dtype = self.dtype
    if dtype not in _ACC_DTYPE:
        raise RuntimeError(f"_coalesce does not support values dtype {dtype}")

    sp = self.sparse_dim()
    shape = tuple(self.shape)
    values = self._values()
    n = self._nnz()
    dense_shape = tuple(values.shape[1:])
    dv = 1
    for d in dense_shape:
        dv *= d

    def _finish(res):
        if out is None:
            return res
        if not isinstance(out, torch.Tensor) or out.layout != torch.sparse_coo:
            raise RuntimeError("_coalesce.out requires a sparse COO out tensor")
        out.copy_(res)
        out._coalesced_(True)
        return out

    if self._nnz() == 0 or sp == 0:
        return _finish(_empty_out_like(shape, sp, dv, dtype, values, device))

    if sp > _MAX_SPARSE_DIM:
        raise NotImplementedError(
            f"_coalesce supports at most {_MAX_SPARSE_DIM} sparse dimensions "
            f"(got {sp})"
        )

    dims = list(shape[:sp])
    numel = 1
    for d in dims:
        numel *= d
    if numel == 0:
        return _finish(_empty_out_like(shape, sp, dv, dtype, values, device))

    strides = [1] * sp
    acc = 1
    for d in range(sp - 1, -1, -1):
        strides[d] = acc
        acc *= dims[d]

    # The dense key space is only materialised when it stays small relative
    # to the number of stored elements; larger key spaces fall back to the
    # native implementation.
    if numel > _DENSE_MAX or numel > 64 * self._nnz():
        raise NotImplementedError(
            f"_coalesce currently handles dense key spaces up to {_DENSE_MAX} "
            f"elements (got numel={numel}, nnz={self._nnz()})"
        )

    is_bool = dtype == torch.bool
    acc_dtype = _ACC_DTYPE[dtype]
    idx = self._indices()
    vals = _as_u8(values) if is_bool else values
    n = self._nnz()

    s = strides + [0] * (_MAX_SPARSE_DIM - sp)
    d = dims + [1] * (_MAX_SPARSE_DIM - sp)
    s0, s1, s2, s3, s4 = s
    d0, d1, d2, d3, d4 = d

    acc_buf = torch.zeros(numel, dtype=acc_dtype, device=device)
    flag_buf = torch.zeros(numel, dtype=torch.uint8, device=device)

    _scatter_kernel[(triton.cdiv(n, _SCAT_BLOCK),)](
        idx,
        vals,
        acc_buf,
        flag_buf,
        n,
        numel,
        dv,
        s0,
        s1,
        s2,
        s3,
        s4,
        S=sp,
        BLOCK=_SCAT_BLOCK,
        num_warps=_SCAT_WARPS,
    )

    nb = triton.cdiv(numel, _TILE)
    cnt = torch.empty(nb, dtype=torch.int32, device=device)
    mtens = torch.empty(1, dtype=torch.int32, device=device)
    key_buf = torch.empty(n, dtype=torch.int32, device=device)

    _count_kernel[(nb,)](flag_buf, cnt, numel, BLOCK=_TILE, num_warps=_TILE_WARPS)
    if nb <= _PREFIX_LANES:
        _keylist_prefix_kernel[(nb,)](
            flag_buf,
            cnt,
            key_buf,
            mtens,
            numel,
            nb,
            PB=_PREFIX_LANES,
            BLOCK=_TILE,
            num_warps=_TILE_WARPS,
        )
    else:
        base = torch.empty(nb, dtype=torch.int32, device=device)
        _scan_kernel[(1,)](
            cnt,
            base,
            mtens,
            nb,
            B=triton.next_power_of_2(nb),
            num_warps=8,
        )
        _keylist_kernel[(nb,)](
            flag_buf,
            base,
            key_buf,
            numel,
            BLOCK=_TILE,
            num_warps=_TILE_WARPS,
        )

    m = int(mtens.item())
    if m == 0:
        return _finish(_empty_out_like(shape, sp, dv, dtype, values, device))

    oidx = torch.empty((sp, m), dtype=torch.int64, device=device)
    oval = torch.empty((m,) + dense_shape, dtype=dtype, device=device)
    oval_ptr = _as_u8(oval) if is_bool else oval

    _emit_kernel[(triton.cdiv(m, _EMIT_BLOCK),)](
        key_buf,
        acc_buf,
        oidx,
        oval_ptr,
        m,
        dv,
        m,
        s0,
        s1,
        s2,
        s3,
        s4,
        d0,
        d1,
        d2,
        d3,
        d4,
        S=sp,
        IS_BOOL=is_bool,
        BLOCK=_EMIT_BLOCK,
        num_warps=_EMIT_WARPS,
    )

    res = torch.sparse_coo_tensor(oidx, oval, shape, is_coalesced=True)
    return _finish(res)


