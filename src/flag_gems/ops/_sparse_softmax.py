        gg = tl.load(gid_ptr + rr, mask=rr < nnz, other=-1)
        c = tl.sum(tl.where((rr < nnz) & (gg == gval), 1, 0), axis=0)
        run_len = run_len + c
        more = c == B_R
        r = r + B_R
