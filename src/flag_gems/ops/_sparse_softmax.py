@triton.jit
def _bw_dense_kernel(
    g_ptr,
    o_ptr,
    ps_ptr,
    dv_ptr,
    outer,
    L,
    inner,
    nchunk,
    stride_r,
    stride_l,
    outer_stride,
    B_L: tl.constexpr,
    B_I: tl.constexpr,
    WRITE: tl.constexpr,
    ACC64: tl.constexpr,
):
    """Case B backward: ``dv = o * (g - sum_L g*o)``.  ``WRITE == 0`` computes the
    per-row partial sums, ``WRITE == 1`` writes the gradient."""
