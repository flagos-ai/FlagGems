import triton
import triton.language as tl

logger = logging.getLogger(__name__)

# A single fused launch handles at most this many grad segments; beyond that the
# kernel falls back to one launch per grad. 8 comfortably covers `torch.chunk`
# with the default number of outputs while keeping the unrolled if/elif chain small.
_MAX_SEG = 8
# CUDA caps grid.y * grid.z at 65535 each; segments beyond this use the fallback.
_MAX_GRID_YZ = 65535


@triton.jit
def _copy_seg(
    src, dst, nblk, slab, dst_slab, base, I64: tl.constexpr, BLOCK: tl.constexpr
):
    """Copy one grad's slabs; tiles are walked with the grid stride."""
    o = tl.program_id(2)
    b = tl.program_id(0)
    stride = tl.num_programs(0)
    r = tl.arange(0, BLOCK)
    for _ in range(0, tl.cdiv(nblk - b, stride)):
        offs = b * BLOCK + r
        if I64:
            idx = offs.to(tl.int64)
            s_off = o.to(tl.int64) * slab + idx
            d_off = o.to(tl.int64) * dst_slab + base + idx
        else:
            s_off = o * slab + offs
            d_off = o * dst_slab + base + offs
        mask = offs < slab
        tl.store(dst + d_off, tl.load(src + s_off, mask=mask), mask=mask)
        b += stride


