"""chunk_backward: concatenate per-chunk gradients along ``dim``.

Reference semantics (Gems tests/test_chunk.py::test_chunk_backward):
    grads = [g0, g1, ...] where gi is the incoming gradient for chunk i of the
    original tensor split along ``dim``; the backward is the concatenation of
    those gradients along ``dim``.

Every grad decomposes as (outer, d_i, inner) around ``dim``; the whole grad
slab for a fixed leading index ``o`` is a *contiguous* run of ``d_i * inner``
elements that maps to a contiguous run of the same length in the contiguous
output.  So no per-element division is needed: the grid is (tile, segment,
leading index) and the address math is one multiply-add per element.

This is a pure streaming copy, so the per-call cost is dominated by launch
overhead on small inputs and by sustained bandwidth on large ones.  Both are
addressed by fusing *all* grads into a single launch: the kernel selects the
source pointer for its segment with a compile-time-unrolled ``if/elif`` chain,
and each CTA walks a grid-stride run of tiles so a capped number of CTAs keeps
the memory pipeline saturated without per-tile block-scheduling cost.  A
per-grad launch loop remains as the fallback for shapes the fused kernel does
not cover.
"""

