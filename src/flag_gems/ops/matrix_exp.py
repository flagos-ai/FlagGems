import logging
import math

import torch

from flag_gems.ops.bmm import bmm as triton_bmm

logger = logging.getLogger(__name__)

# Taylor terms used after scaling. With scaling to ||A/2^s|| <= 1 the remainder
# after K terms is bounded by 1/(K+1)!, so K = 18 (1/19! ~ 8e-18) is well below
# fp32/fp64 rounding error.
_TAYLOR_TERMS = 18


def _batched_bmm(a, b):
    # triton_bmm expects contiguous (B, M, K) x (B, K, N) tensors.
    return triton_bmm(a.contiguous(), b.contiguous())


def matrix_exp(A):
    """Matrix exponential exp(A) via scaling-and-squaring with a Taylor series.

    exp(A) = (exp(A / 2^s))^(2^s). The inner exponential is a truncated Taylor
    series; every matrix product is evaluated by the Triton ``bmm`` kernel, so
    the computation stays on-device with no torch.linalg fallback.

    Args:
        A: tensor of shape (*, n, n) - one or more square matrices.

    Returns:
        Matrix exponential, same shape and dtype as the input.
    """
    logger.debug("GEMS MATRIX_EXP")

    if A.ndim < 2 or A.shape[-1] != A.shape[-2]:
        raise RuntimeError("matrix_exp: expected a batch of square matrices.")

    orig_dtype = A.dtype
    orig_shape = A.shape
    n = A.shape[-1]

    # fp16/bf16 lack the range for the intermediate products, so compute in fp32.
    compute_dtype = (
        torch.float32 if orig_dtype in (torch.float16, torch.bfloat16) else orig_dtype
    )
    work = A.to(compute_dtype).contiguous()

    # Collapse the batch dims to a single leading dimension for bmm.
    batched = work.reshape(-1, n, n)
    batch = batched.shape[0]

    # exp(0) = I is the degenerate n == 0 shortcut; also short-circuits empty batch.
    identity = torch.eye(n, dtype=compute_dtype, device=A.device)
    identity = identity.unsqueeze(0).expand(batch, n, n).contiguous()
    if n == 0:
        return work.reshape(orig_shape).to(orig_dtype)

    # Scale so that the largest matrix inf-norm (max abs row sum) is <= 1; the
    # same s is applied to every matrix in the batch (over-scaling a matrix only
    # costs extra squarings, it stays exact).
    inf_norms = batched.abs().sum(dim=-1).amax(dim=-1)
    max_norm = inf_norms.max().item()
    s = max(0, math.ceil(math.log2(max_norm))) if max_norm > 0.0 else 0
    scaled = batched / (2.0**s)

    # Horner-free Taylor accumulation: term_k = term_{k-1} @ scaled / k.
    result = identity.clone()
    term = identity.clone()
    for k in range(1, _TAYLOR_TERMS + 1):
        term = _batched_bmm(term, scaled) / k
        result = result + term

    # Undo the scaling by repeated squaring.
    for _ in range(s):
        result = _batched_bmm(result, result)

    result = result.reshape(orig_shape)
    if result.dtype != orig_dtype:
        result = result.to(orig_dtype)
    return result
