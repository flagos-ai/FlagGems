_PLAN_CACHE = {}


def _compute_plan(dims):
    """Post-order list of (lhs, rhs) node indices; nodes 0..n-1 are inputs."""
    n = len(dims) - 1
    cost = [[0] * n for _ in range(n)]
    split = [[0] * n for _ in range(n)]
    for L in range(2, n + 1):
        for i in range(n - L + 1):
            j = i + L - 1
            best = None
            best_k = i
            for k in range(i, j):
                c = cost[i][k] + cost[k + 1][j] + dims[i] * dims[k + 1] * dims[j + 1]
                if best is None or c < best:
                    best = c
                    best_k = k
            cost[i][j] = best
            split[i][j] = best_k

    steps = []
    node_id = {}
    next_id = [n]

    def build(i, j):
        key = (i, j)
        if key in node_id:
            return node_id[key]
        if i == j:
            node_id[key] = i
            return i
        k = split[i][j]
        left_node = build(i, k)
        right_node = build(k + 1, j)
        node_id[key] = next_id[0]
        steps.append((left_node, right_node))
        next_id[0] += 1
        return node_id[key]

    build(0, n - 1)
    return steps


def _plan(dims):
    key = tuple(dims)
    plan = _PLAN_CACHE.get(key)
    if plan is None:
        plan = _compute_plan(key)
        _PLAN_CACHE[key] = plan
    return plan


def _run(matrices):
    """_run(matrices) -> Tensor : product of the matrix chain (multi_dot)."""
    n = len(matrices)
    if n == 0:
        raise ValueError("chain_matmul: empty matrix list")
    if n == 1:
        return matrices[0]
    dims = [matrices[0].shape[0]] + [m.shape[1] for m in matrices]
    plan = _plan(dims)
    if n == 3 and max(dims) <= 16:
        return _chain3(matrices[0], matrices[1], matrices[2], plan[0] == (0, 1))
    if (
        n == 4
        and len(plan) == 3
        and plan[0] == (2, 3)
        and plan[1][0] == 1
        and plan[1][1] == 4
        and plan[2] == (0, 5)
        and matrices[0].dtype in (torch.float16, torch.bfloat16)
    ):
        a, b, c, d = matrices
        if (
            b.shape[0] <= 128
            and d.shape[1] <= 64
            and a.shape[0] <= 64
            and a.shape[1] == b.shape[0]
        ):
            e = _mm(c, d)
            return _mm_last2(a, b, e)
    vals = list(matrices)
    for lhs, rhs in plan:
        vals.append(_mm(vals[lhs], vals[rhs]))
    return vals[-1]


def chain_matmul(matrices):
    """``aten::chain_matmul(Tensor[] matrices) -> Tensor``."""
    logger.debug("GEMS CHAIN_MATMUL")
    return _run(matrices)
