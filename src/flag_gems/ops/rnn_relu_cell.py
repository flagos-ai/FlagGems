"""Single-step ReLU RNN cell (``aten::rnn_relu_cell``) in Triton.

    hy = relu(input @ w_ih^T + b_ih + hx @ w_hh^T + b_hh)

ATen evaluates this as four separate eager operators -- ``linear``, ``linear``,
``add``, ``relu`` -- so both gate matrices and the sum round-trip through global
memory in the input dtype.  One fused kernel replaces all of them: a program
owns a ``(BLOCK_B, BLOCK_H)`` output tile, runs both reduced GEMMs into
registers, adds the biases, applies the activation and stores once.

The arithmetic reproduces ATen's rounding boundaries rather than being more
accurate than ATen, which is what the accuracy tests compare against:

* each ``linear`` accumulates in fp32 (fp64 for double input) and adds its own
  bias before a single rounding to the input dtype -- a cuBLAS ``addmm`` with
  ``beta = 1`` behaves exactly that way;
* the elementwise add of the two gate matrices rounds again;
* the activation runs in the accumulator precision and only the store rounds.

For fp32 and fp64 inputs none of those roundings is observable, so the whole
path is exact in the input precision.
"""

