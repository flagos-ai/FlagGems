def _box_muller_f64(r0, r1, r2, r3):
    """Pair four Philox words into two standard normals, in float64.

    Mirrors ``box_muller_double``: each normal spends two words, packed into
    roughly 64 bits of uniform randomness instead of 32, so one Philox call
    yields two samples rather than four.
    """
    m = 2.3283064365386963e-10
    u1 = tl.fma(r0.to(tl.float64), m, r1.to(tl.float64) * m * m + m * m * 0.5)
    u2 = tl.fma(r2.to(tl.float64), m, r3.to(tl.float64) * m * m + m * m * 0.5)

    radius = tl.sqrt(-2.0 * tl.log(u1))
    theta = 6.2831853071795864 * u2

    return radius * tl.cos(theta), radius * tl.sin(theta)


@triton.jit
def _philox_normal_kernel(
    out_ptr,
    key_ptr,
    N,
    mean,
    std,
    BLOCK: tl.constexpr,
):
    """Fill ``out_ptr`` with normal samples from a stateless Philox stream.

    ``key_ptr`` addresses a ``(seed, offset)`` pair. Output element ``i`` comes
    from the ``i // 4``-th Philox 4x32 counter value, so each lane owns one
    counter and writes the four normals it yields. ``mean``/``std`` are the
    float32 scalars ATen uses as its accumulator for every 16/32-bit output.
    """
    seed = tl.load(key_ptr).to(tl.uint64)
    offset = tl.load(key_ptr + 1).to(tl.uint64)
    # tl.cast rather than ``N.to``: Triton specializes small integer arguments
    # such as 1 into constexprs, which have no ``.to``.
    N = tl.cast(N, tl.int64)
    # Element counts can exceed 2**31, so every offset stays 64-bit; an int32
    # product here would wrap and let the masked stores run past the buffer.
    chunk = (tl.program_id(0).to(tl.int64)) * BLOCK + tl.arange(0, BLOCK).to(tl.int64)
    counter = offset + chunk.to(tl.uint64)
    c0 = (counter & 0xFFFFFFFF).to(tl.uint32)
    c1 = ((counter >> 32) & 0xFFFFFFFF).to(tl.uint32)
    zero = c0 * 0
    r0, r1, r2, r3 = tl.philox(seed, c0, c1, zero, zero)

    n0, n1, n2, n3 = _box_muller_f32(r0, r1, r2, r3)
    dtype = out_ptr.dtype.element_ty
    base = chunk * 4
    tl.store(out_ptr + base, tl.fma(n0, std, mean).to(dtype), mask=base < N)
    tl.store(out_ptr + base + 1, tl.fma(n1, std, mean).to(dtype), mask=base + 1 < N)
    tl.store(out_ptr + base + 2, tl.fma(n2, std, mean).to(dtype), mask=base + 2 < N)
    tl.store(out_ptr + base + 3, tl.fma(n3, std, mean).to(dtype), mask=base + 3 < N)


