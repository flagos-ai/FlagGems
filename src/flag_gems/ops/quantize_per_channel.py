#   qint8   -> int8   [-128, 127]
#   qint32  -> int32  [-2147483648, 2147483647]
_QRANGE = {
    torch.quint8: (torch.uint8, 0, 255),
    torch.qint8: (torch.int8, -128, 127),
    torch.qint32: (torch.int32, -2147483648, 2147483647),
}


