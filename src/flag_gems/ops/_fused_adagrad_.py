        BLOCK_SIZE = max(BLOCK_SIZE, 128)
        BLOCK_SIZE = min(BLOCK_SIZE, 4096)

        grid = (triton.cdiv(n, BLOCK_SIZE),)

        # fp64 params accumulate in fp64; everything else in fp32.
