            for name, tensor in (
                ("param", param),
                ("grad", grad),
                ("state_sum", state_sum),
            ):
                if tensor.dtype != expected_dtype:
                    raise RuntimeError(
                        "params, grads, and state_sums must have same dtype, "
                        f"device, and layout: {name}[{i}] dtype {tensor.dtype} "
                        f"differs from params[0] dtype {expected_dtype}"
                    )
