def _nvfb_scatter_kernel(
    grad_ptr,
    out_ptr,
    cum_ptr,
    sizes_ptr,
    strides_ptr,
    offsets_ptr,
    total,
    C,
    niter,
    D: tl.constexpr,
    BLOCK: tl.constexpr,
):
    """Map each packed gradient element to its buffer position and store it.

    Every program owns one BLOCK of packed elements. The owning component is
    found with a per-element binary search over the packed-start table (the
    table is monotone, ``niter = ceil(log2(C))`` rounds). The identity layout
    degenerates to a vectorized copy; contiguous components skip the stride
    decode and write ``offset + j`` runs; the general path decodes the packed
    index row-major against the component's sizes.
    """
    pid = tl.program_id(0)
    i = pid.to(tl.int64) * BLOCK + tl.arange(0, BLOCK).to(tl.int64)
    m = i < total
    ident = tl.load(cum_ptr + C + 2)
    if ident != 0:
        # Identity layout: out[i] = grad[i], pure vectorized copy.
        v = tl.load(grad_ptr + i, mask=m, other=0.0)
        tl.store(out_ptr + i, v, mask=m)
    else:
        lo = tl.zeros([BLOCK], dtype=tl.int32)
        hi = tl.full([BLOCK], C, dtype=tl.int32)
        for _ in range(niter):
            mid = (lo + hi) // 2
            cm = tl.load(cum_ptr + mid, mask=m, other=0)
            left = cm > i
            hi = tl.where(left, mid, hi)
            lo = tl.where(left, lo, mid)
        base = tl.load(cum_ptr + lo, mask=m, other=0)
        j = i - base
        contig = tl.load(cum_ptr + C + 1)
        off = tl.load(offsets_ptr + lo, mask=m, other=0)
        if contig != 0:
            pos = off + j
        else:
            pos = off
            tmp = j
            for d in tl.static_range(D):
                k = D - 1 - d
                s = tl.load(sizes_ptr + lo * D + k, mask=m, other=1)
                st = tl.load(strides_ptr + lo * D + k, mask=m, other=0)
                r = tmp % s
                tmp = tmp // s
                pos = pos + r * st
        v = tl.load(grad_ptr + i, mask=m, other=0.0)
        tl.store(out_ptr + pos, v, mask=m)


