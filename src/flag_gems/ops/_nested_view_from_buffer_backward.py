@triton.jit
def _nvfb_prep_kernel(
    sizes_ptr,
    strides_ptr,
    offsets_ptr,
    cum_ptr,
    C,
    D: tl.constexpr,
    BLOCK_C: tl.constexpr,
):
    """Build the per-component packed-start table and layout flags.

    ``cum[0..C-1]`` holds the exclusive prefix of component numels, so
    component ``c`` occupies packed gradient elements
    ``[cum[c], cum[c] + numel_c)``. ``cum[C]`` stores the packed total,
    ``cum[C + 1]`` a flag telling whether every component has row-major
    contiguous strides, and ``cum[C + 2]`` whether additionally
    ``offsets[c] == cum[c]`` for every component (identity layout, in which
    case the whole restore is a straight copy).
    """
    offs = tl.arange(0, BLOCK_C)
    m = offs < C
    numels = tl.full([BLOCK_C], 1, tl.int64)
    for d in tl.static_range(D):
        s = tl.load(sizes_ptr + offs * D + d, mask=m, other=1)
        numels = numels * s
    numels = tl.where(m, numels, 0)
    csum = tl.cumsum(numels, axis=0)
    excl = csum - numels
    tl.store(cum_ptr + offs, excl, mask=m)
    total = tl.sum(numels, axis=0)
    tl.store(cum_ptr + C, total)
    # Contiguity flag: for every component, strides[k] must equal
    # prod(sizes[k+1:]).
    ok = tl.full([BLOCK_C], 1, tl.int32)
    expected = tl.full([BLOCK_C], 1, tl.int64)
    for d in tl.static_range(D):
        k = D - 1 - d
        st = tl.load(strides_ptr + offs * D + k, mask=m, other=0)
        sz = tl.load(sizes_ptr + offs * D + k, mask=m, other=1)
        ok = tl.where(m & (st != expected), 0, ok)
        expected = expected * sz
    all_contig = tl.min(tl.where(m, ok, 1), axis=0)
    tl.store(cum_ptr + C + 1, all_contig.to(tl.int64))
    # Identity flag: offsets match the packed layout, so the restore is a copy.
    o = tl.load(offsets_ptr + offs, mask=m, other=-1)
    same = tl.where(m & (o != excl), 0, 1).to(tl.int64)
    ident = tl.where(all_contig != 0, tl.min(same, axis=0), 0)
    tl.store(cum_ptr + C + 2, ident)


