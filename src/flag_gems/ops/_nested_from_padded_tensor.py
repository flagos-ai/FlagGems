# ``offsets`` is nested-tensor metadata that is commonly reused across many
# ``_nested_from_padded_tensor`` calls (e.g. the same ragged layout across
# iterations). Reading ``offsets[-1]`` to size the packed output forces a
# device -> host sync the first time we see a given offsets tensor; cache the
# resolved total length ``S`` keyed by the offsets tensor so repeated calls on
# an unchanged offsets avoid the sync. The cache is invalidated via the
# tensor's version counter -- any in-place mutation of ``offsets`` bumps
# ``_version`` and the next call re-syncs. Inference tensors do not expose a
# version counter, so they fall back to the always-correct synced path.
_SUM_S_CACHE: WeakTensorKeyDictionary = WeakTensorKeyDictionary()


def _resolve_sum_s(offsets):
    """Return the total packed length ``S = offsets[-1]`` with cache reuse."""
    try:
        version = offsets._version
    except RuntimeError:
        # Inference tensors do not track a version counter.
        return int(offsets[-1].item())

    cached = _SUM_S_CACHE.get(offsets)
    if cached is not None and cached[0] == version:
        return cached[1]

    S = int(offsets[-1].item())
    _SUM_S_CACHE[offsets] = (version, S)
    return S


