#   raw rows [0, 1], [2, 3], [4, 5]).
#
# * Offsets: ``offsets[0] = 0`` and ``offsets[i+1] = offsets[i] + addend_i``,
#   where ``addend_i`` is the row's int64 element count truncated to int32 and
#   sign-extended back. Native computes the row product with
#   ``std::accumulate(ptr, ptr + dim, /*int*/ 1, std::multiplies())`` -- the
#   accumulator type is the ``int`` initializer -- stores it in an ``int64_t``
#   and adds it to an int64 offsets accumulator. Truncating the exact int64
#   product to int32 is equivalent to that int32 chained multiply (modular
#   arithmetic is a ring homomorphism). Measured:
#   (46341, 46341) -> offsets [0, -2147479015];
#   (46341, 46341, 46341) -> [0, -1932785795];
#   (65536, 32768) twice -> [0, -2147483648, -4294967296].
#   The offsets length is ``ntensors`` -- there is NO trailing total count.
#
