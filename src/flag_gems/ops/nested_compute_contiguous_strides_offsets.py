def nested_compute_contiguous_strides_offsets(
    nested_size: torch.Tensor,
) -> tuple[torch.Tensor, torch.Tensor]:
    """Compute contiguous strides and storage offsets from nested sizes.

    Mirrors ``aten::_nested_compute_contiguous_strides_offsets(Tensor
    nested_size) -> (Tensor, Tensor)``, the helper ``torch.nested`` uses to
    derive the strides/offset metadata of a non-jagged nested tensor from its
    per-component shapes.

    Args:
        nested_size (Tensor): int64 tensor of shape ``(ntensors, dim)`` whose
            rows are the shapes of the nested tensor's components (a CPU
            tensor in native usage; CUDA inputs are accepted here too).

    Returns:
        tuple[Tensor, Tensor]: contiguous strides (same shape as
        ``nested_size``) and exclusive storage offsets (shape ``(ntensors,)``,
        with no trailing total).
    """
    logger.debug("GEMS _NESTED_COMPUTE_CONTIGUOUS_STRIDES_OFFSETS")

    sizes = nested_size

    # Empty `sizes` means an empty nested tensor: native returns the input
    # object itself as the strides (any dtype, no check) plus empty offsets.
    # Both metadata outputs stay on CPU, matching the native CPU contract.
    if sizes.dim() == 0:
        return sizes, torch.empty((0,), dtype=torch.int64, device="cpu")

    # `sizes.size(1)` is evaluated before the dtype check, so a 1-D input
    # raises the ATen dimension error even when its dtype is not int64.
    ntensors = sizes.size(0)
    orig_dim = sizes.size(1)

    if sizes.dtype != torch.int64:
        raise RuntimeError(
            "expected scalar type Long but found "
            + _ATEN_TYPE_NAMES.get(sizes.dtype, str(sizes.dtype))
        )

    if orig_dim == 0:
        # Native returns the input itself as the strides, and the offsets are
        # the iota over the components (possibly zero-length). The offsets are
        # CPU metadata as in the native CPU path.
        offsets = torch.arange(ntensors, dtype=torch.int64)
        return sizes, offsets

    if ntensors == 0:
        # Native segfaults here (it writes offsets_ptr[0] into an empty
        # tensor); return the well-defined empty result instead.
        return torch.empty_like(sizes), torch.empty((0,), dtype=torch.int64)

    # Raw element read in data-pointer order, which for a non-contiguous input
    # is NOT its .contiguous() copy. `as_strided` reproduces the native
    # pointer arithmetic; the values are copied into a numpy array before any
    # arithmetic, so no alias is created.
    if sizes.is_contiguous():
        host_sizes = sizes.detach().cpu()
        mat = host_sizes.numpy()
    else:
        flat = torch.as_strided(
            sizes, (ntensors * orig_dim,), (1,), sizes.storage_offset()
        )
        mat = flat.detach().cpu().numpy().reshape(ntensors, orig_dim)

    # Suffix products under int64 wraparound (matches the C++ chained multiply
    # and numpy's modular int64 overflow); column 0 of each row is the row's
    # element count.
    with np.errstate(over="ignore"):
        suffix = np.cumprod(mat[:, ::-1], axis=1)[:, ::-1]
        strides = np.empty_like(suffix)
        strides[:, :-1] = suffix[:, 1:]
        strides[:, -1] = 1
        # Native truncates each row product to int32 before accumulating.
        addends = suffix[:, 0].astype(np.int32).astype(np.int64)
        offsets = np.zeros(ntensors, np.int64)
        np.cumsum(addends[:-1], out=offsets[1:])

    strides_t = torch.from_numpy(strides)
    offsets_t = torch.from_numpy(offsets)
    # The metadata results are CPU tensors, matching native: the native op
    # allocates both outputs with the input's options and is only ever handed
    # a CPU sizes tensor (torch.nested builds it on CPU). Returning CPU
    # metadata for a CUDA input keeps the output placement contract identical
    # instead of making it device-dependent.
    return strides_t, offsets_t
