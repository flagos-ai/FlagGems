def _out_dtype_of(tensors):
    dts = []
    for t in tensors:
        dts.append(torch.float32 if not t.dtype.is_floating_point else t.dtype)
    for cand in (torch.float64, torch.float32, torch.float16, torch.bfloat16):
        if cand in dts:
            return cand
    return torch.float32


