"""Triton implementation of aten::glu_jvp (forward-mode JVP of aten::glu).

Semantics
---------
With ``d`` the (non-negative) narrowed dim, ``N = glu.size(d)`` and
``a = x[..., 0:N, ...]``, ``b = x[..., N:2N, ...]`` (narrowed along ``d``), the
primal is ``glu = a * sigmoid(b)`` and the pushforward is

    out = da * sigmoid(b) + glu * (1 - sigmoid(b)) * db

so the first half of ``x`` is never read.  The output shape is the broadcast of
``glu`` and the three narrowed operands over every axis except ``d``, with the
``d`` axis fixed to ``N`` (native ``narrow(dim, m, m)`` semantics).

Kernel shape
------------
The output is viewed as ``[M, K]`` (``M = prod(out_shape[:-1])``, ``K =
out_shape[-1]``).  Each program owns a ``ROWS x BLOCK`` tile: the outer (row)
axis is vectorized over ``ROWS``, the contiguous last axis over ``BLOCK``, and
both tile axes are masked, so one kernel serves every rank, broadcast pattern
and non-contiguous stride layout.

Two addressing modes share that kernel:

* ``FAST``: every operand's outer axes follow the output's outer layout scaled
  by a constant row step (the normal case for dense operands, including the
  narrowed halves of ``x``/``dx``).  Then the element offset is just
  ``row * row_step + col * last_stride`` -- one multiply-add per operand, with
  no index decomposition at all.  The wrapper proves this layout in Python.
* general: the flat row index is decomposed into the outer output indices and
  dotted with each operand's per-axis broadcast strides.

The wrapper performs metadata work only (dim wrap, extension checks, zero-copy
``narrow`` views, broadcast-stride alignment, output allocation) and the single
device kernel evaluates the expression above with fp32 intermediates for
half/float inputs and fp64 for double inputs, rounding exactly once on store.
"""

