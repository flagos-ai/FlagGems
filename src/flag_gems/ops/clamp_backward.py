def _clamp_backward_kernel(
    grad_ptr,
    self_ptr,
    out_ptr,
    n_elements,
    min_value,
    max_value,
    BLOCK: tl.constexpr,
):
    pid = tl.program_id(0).to(tl.int64)
    offs = pid * BLOCK + tl.arange(0, BLOCK)
    mask = offs < n_elements
