    x = tl.load(self_ptr + offs, mask=mask, other=0.0)
    # PyTorch's clamp VJP keeps the gradient at both boundaries (inclusive), so an
    # element equal to min or max still receives grad_output. A NaN input fails
    # both comparisons and therefore gets zero, matching aten. When min > max the
    # clamp is saturated everywhere and the gradient is zero.
