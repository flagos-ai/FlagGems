        u2 = tl.maximum(uint_to_uniform_float(r1), 1e-7)
        u3 = uint_to_uniform_float(r2)
        u4 = tl.maximum(uint_to_uniform_float(r3), 1e-7)

        # Standard normal via Box-Muller.
