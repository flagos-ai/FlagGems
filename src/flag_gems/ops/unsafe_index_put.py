def index_kernel(
    G,
    O,
    INDICES,
    MASK,
    N: tl.constexpr,
    QUERY: tl.constexpr,
    XSHAPE: tl.constexpr,
    XSTRIDES: tl.constexpr,
    GSTRIDES: tl.constexpr,
    BPOS: tl.constexpr,
    MAPPING: tl.constexpr,
    SLOTS: tl.constexpr,
    ISTRIDES: tl.constexpr,
    MSTRIDES: tl.constexpr,
    MODE: tl.constexpr,
    MASKED: tl.constexpr,
    CLAMP: tl.constexpr,
    FILL: tl.constexpr,
    B: tl.constexpr,
):
    i = tl.program_id(0) * B + tl.arange(0, B)
    live = i < N
    coords = ()
    remain = i
    for d in tl.static_range(len(QUERY) - 1, -1, -1):
        coords = (remain % QUERY[d],) + coords
        remain = remain // QUERY[d]
    active = live
    if MASKED:
        moff = tl.full((B,), 0, tl.int64)
        for d in tl.static_range(len(QUERY)):
            moff += coords[d] * MSTRIDES[d]
        active = live & tl.load(MASK + moff, live, other=0)
    address = tl.full((B,), 0, tl.int64)
    for d in tl.static_range(len(XSHAPE)):
        if SLOTS[d] >= 0:
            ioff = tl.full((B,), 0, tl.int64)
            for k in tl.static_range(len(BPOS)):
                ioff += coords[BPOS[k]] * ISTRIDES[SLOTS[d]][k]
            v = tl.load(INDICES[SLOTS[d]] + ioff, active, other=0).to(tl.int64)
            if CLAMP == 0:
                v = tl.minimum(tl.maximum(v, 0), XSHAPE[d] - 1)
            elif CLAMP == 1:
                v = tl.minimum(tl.maximum(v, -XSHAPE[d]), XSHAPE[d] - 1)
            v = tl.where(v < 0, v + XSHAPE[d], v)
        else:
            v = coords[MAPPING[d]]
        address += v * XSTRIDES[d]
    if MODE == 0:
        value = tl.load(G + address, active, other=FILL)
        tl.store(O + i, value, live)
    elif MODE == 1 or MODE == 3:
        gaddress = tl.full((B,), 0, tl.int64)
        for d in tl.static_range(len(QUERY)):
            gaddress += coords[d] * GSTRIDES[d]
        value = tl.load(G + gaddress, active, other=0)
        if MODE == 1:
            tl.atomic_add(O + address, value, active, sem="relaxed")
        else:
            tl.store(O + address, value, active)
    else:
        tl.store(O + address, 0, active)


def indexed(
    grad,
    self,
    indices,
    mode,
    mask=None,
    clamp=-1,
    query_shape=None,
    fill=0,
    initial=None,
):
    if mask is not None:
        query_shape = (
            mask.shape
            if query_shape is None
            else broadcast_shapes([query_shape, mask.shape])
        )
    if mode in (1, 3):
        query_shape = (
            grad.shape
            if query_shape is None
            else broadcast_shapes([query_shape, grad.shape])
        )
    q, ptrs, bpos, mapping, slots, istrides = index_plan(self, indices, query_shape)
    if mode == 0:
        out = torch.empty(q, device=grad.device, dtype=grad.dtype)
        xstrides = grad.stride()
    elif mode in (1, 3):
        acc_dtype = (
            torch.float32
            if mode == 1 and self.dtype in (torch.float16, torch.bfloat16)
            else self.dtype
        )
        out = (
            copy_tensor(self, zero=True, dtype=acc_dtype)
            if initial is None
            else copy_tensor(initial, dtype=acc_dtype)
        )
        xstrides = contiguous_strides(self.shape)
    else:
        out = copy_tensor(grad)
        xstrides = contiguous_strides(self.shape)
    n = math.prod(q)
    if n and self.numel():
        if mode in (1, 3):
            gstrides = _expanded_strides(grad, q)
        else:
            gstrides = (0,) * len(q)
        mstrides = _expanded_strides(mask, q) if mask is not None else (0,) * len(q)
        index_kernel[triton.cdiv(n, 256),](
            grad,
            out,
            ptrs,
            mask if mask is not None else grad,
            n,
            q,
            tuple(self.shape),
            xstrides,
            gstrides,
            bpos,
            mapping,
            slots,
            istrides,
            mstrides,
            mode,
            mask is not None,
            clamp,
            fill,
            256,
        )
    elif mode == 0 and n:
        copy_kernel[triton.cdiv(n, 256),](
            out, out, n, q, contiguous_strides(q), True, 256
        )
    if mode == 1 and out.dtype != self.dtype:
        return copy_tensor(out, dtype=self.dtype)
    return out


@triton.jit
def _broadcast_sum(
    V,
    O,
    TARGET: tl.constexpr,
    VSTRIDES: tl.constexpr,
    RSHAPE: tl.constexpr,
    RSTRIDES: tl.constexpr,
    RN: tl.constexpr,
    B: tl.constexpr,
):
    out_index = tl.program_id(0)
    base = offset(out_index, TARGET, VSTRIDES)
    XTYPE: tl.constexpr = tl.float64 if V.dtype.element_ty == tl.float64 else tl.float32
    total = tl.full((), 0, XTYPE)
    r = tl.arange(0, B)
    for tile in range((RN + B - 1) // B):
        j = tile * B + r
        value = tl.load(V + base + offset(j, RSHAPE, RSTRIDES), j < RN, other=0).to(
            XTYPE
        )
        total += tl.sum(value, 0)
    tl.store(O + out_index, total)


def reduce_values(value, shape):
    shape = tuple(shape)
    if tuple(value.shape) == shape:
        return value
    padded = (1,) * (value.ndim - len(shape)) + shape
    if len(padded) != value.ndim or any(
        (t != v and t != 1 for (t, v) in zip(padded, value.shape))
    ):
        raise RuntimeError("gradient cannot reduce to values shape")
    axes = [
        d for (d, (t, v)) in enumerate(zip(padded, value.shape)) if t == 1 and v != 1
    ]
    rshape = tuple((value.shape[d] for d in axes))
    rstrides = tuple((value.stride(d) for d in axes))
    out = torch.empty(shape, dtype=value.dtype, device=value.device)
    if out.numel():
        _broadcast_sum[out.numel(),](
            value, out, padded, value.stride(), rshape, rstrides, math.prod(rshape), 256
        )
    return out


def unsafe_index_put_backward(grad_output, self, indices, values, accumulate=False):
    dx = grad_output if accumulate else indexed(grad_output, self, indices, 2)
