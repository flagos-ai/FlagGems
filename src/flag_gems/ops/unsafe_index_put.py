def copy_tensor(tensor, shape=None, zero=False, dtype=None):
    shape = tuple(tensor.shape) if shape is None else tuple(shape)
    if math.prod(shape) != tensor.numel():
        raise RuntimeError("incompatible gradient reshape")
    out = torch.empty(shape, dtype=dtype or tensor.dtype, device=tensor.device)
    if out.numel():
        copy_kernel[triton.cdiv(out.numel(), 256),](
            tensor, out, out.numel(), tuple(tensor.shape), tensor.stride(), zero, 256
        )
    return out


def _expanded_strides(tensor, shape):
    padding = len(shape) - tensor.ndim
    if padding < 0:
        raise RuntimeError("invalid broadcast rank")
    for a, b in zip((1,) * padding + tuple(tensor.shape), shape):
        if a != 1 and a != b:
            raise RuntimeError("incompatible broadcast dimensions")
    return (0,) * padding + tuple(
        (0 if n == 1 else s for (n, s) in zip(tensor.shape, tensor.stride()))
    )


def index_plan(tensor, indices, query_shape=None):
    if len(indices) > tensor.ndim:
        raise IndexError("too many indices")
    indices = list(indices) + [None] * (tensor.ndim - len(indices))
    dims = [d for (d, index) in enumerate(indices) if index is not None]
    for d in dims:
        if indices[d].dtype not in (torch.int64, torch.int32):
            raise RuntimeError("unsafe indexing requires integer indices")
        if indices[d].device != tensor.device:
            raise RuntimeError("indices must be on the input device")
    bshape = tuple(broadcast_shapes([indices[d].shape for d in dims])) if dims else ()
    adjacent = not dims or dims[-1] - dims[0] + 1 == len(dims)
    rest = [d for d in range(tensor.ndim) if d not in dims]
    insertion = dims[0] if dims and adjacent else 0
    shape = (
        tuple((tensor.shape[d] for d in rest[:insertion]))
        + bshape
        + tuple((tensor.shape[d] for d in rest[insertion:]))
    )
    if not dims:
        shape = tuple(tensor.shape)
    query = (
        tuple(broadcast_shapes([shape, query_shape]))
        if query_shape is not None
        else shape
    )
    pad = len(query) - len(shape)
    bpos = tuple(range(pad + insertion, pad + insertion + len(bshape)))
    rpos = [
        pad + j if j < insertion else pad + j + len(bshape) for j in range(len(rest))
    ]
    mapping = tuple(
        (rpos[rest.index(d)] if d in rest else -1 for d in range(tensor.ndim))
    )
    slots = tuple((dims.index(d) if d in dims else -1 for d in range(tensor.ndim)))
    istrides = tuple((_expanded_strides(indices[d], bshape) for d in dims))
    return (query, tuple((indices[d] for d in dims)), bpos, mapping, slots, istrides)


