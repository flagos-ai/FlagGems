# Tile size for the generic (non-contiguous) fallback path. It has no autotune
# because irregular strides make BLOCK sweep benefits negligible; 1024 keeps
# four 128-bit vector loads in flight per warp.
_BLOCK = 1024
# Highest tensor rank the generic (non-contiguous) path handles. Matches the
# 8-dim ceiling used by the other Gems elementwise fallbacks.
_MAXDIM = 8
_INT32_LIMIT = 2**31


def _broadcast_shapes(*shapes):
    """Shape-only broadcast (metadata, no tensor work)."""
    ndim = max((len(s) for s in shapes), default=0)
    padded = [[1] * (ndim - len(s)) + list(s) for s in shapes]
    result = []
    for dims in zip(*padded):
        size = 1
        for d in dims:
            if d == 1:
                continue
            if size == 1:
                size = d
            elif d != size:
                raise RuntimeError(
                    "shape mismatch: objects cannot be broadcast to a single shape"
                )
        result.append(size)
    return tuple(result)


def _bitwidth(dtype):
    if dtype in (torch.float16, torch.bfloat16):
        return 16
    if dtype == torch.float32:
        return 32
    return 64


def _aligned_strides(t, ndim):
    """Strides of `t` aligned to `ndim` output dims, 0 where broadcast."""
    off = ndim - t.dim()
    st = t.stride()
    res = []
    for i in range(ndim):
        j = i - off
        if j < 0 or t.shape[j] == 1:
            res.append(0)
        else:
            res.append(st[j])
    return res


def copysign_backward(grad_output, self, other):
    """Gradient of ``copysign`` w.r.t. ``self``.

    ``grad_output * sign(self) * sign(other)``, with the sign of ``other`` read
    from its sign bit so ``-0.0`` counts as negative. ``sign(self)`` is zero at
    both zeros. ``other`` may be a tensor or a Python scalar.
    """
    logger.debug("GEMS COPYSIGN_BACKWARD")
    if isinstance(other, torch.Tensor):
        other_t = other
        other_neg = False
        out_shape = _broadcast_shapes(grad_output.shape, self.shape, other.shape)
    else:
        other_t = None
        other_neg = math.copysign(1.0, float(other)) < 0.0
        out_shape = _broadcast_shapes(grad_output.shape, self.shape)

    out = torch.empty(out_shape, dtype=self.dtype, device=self.device)
    n = out.numel()
    if n == 0:
        return out

    bw = _bitwidth(self.dtype)
    use_scalar = other_t is None

    if (
        grad_output.shape == out_shape
        and self.shape == out_shape
        and grad_output.is_contiguous()
        and self.is_contiguous()
        and (use_scalar or (other_t.shape == out_shape and other_t.is_contiguous()))
    ):
        _copysign_bwd_flat[lambda meta: (triton.cdiv(n, meta["BLOCK"]),)](
            grad_output,
            self,
            grad_output if use_scalar else other_t,
            out,
            n,
            SCALAR_OTHER=use_scalar,
            OTHER_NEG=other_neg,
            BITWIDTH=bw,
            IDX64=n >= _INT32_LIMIT,
        )
        return out

    ndim = len(out_shape)
    if ndim > _MAXDIM:
        raise ValueError("copysign_backward supports rank <= 8")

    # Reverse to innermost-first so the kernel's ascending loop is row-major.
    dims = list(out_shape)[::-1] + [1] * (_MAXDIM - ndim)
    g_st = _aligned_strides(grad_output, ndim)[::-1] + [0] * (_MAXDIM - ndim)
    s_st = _aligned_strides(self, ndim)[::-1] + [0] * (_MAXDIM - ndim)
    if use_scalar:
        o_st = [0] * _MAXDIM
        o_arg = grad_output
    else:
        o_st = _aligned_strides(other_t, ndim)[::-1] + [0] * (_MAXDIM - ndim)
        o_arg = other_t

    _copysign_bwd_generic[(triton.cdiv(n, _BLOCK),)](
        grad_output,
        self,
        o_arg,
        out,
        n,
        *dims,
        *g_st,
        *s_st,
        *o_st,
        SCALAR_OTHER=use_scalar,
        OTHER_NEG=other_neg,
        BITWIDTH=bw,
        BLOCK=_BLOCK,
        num_warps=4,
    )
    return out
