@triton.jit
def _neg_sign(x, BITWIDTH: tl.constexpr):
    """True sign bit of x, including -0.0 (float `< 0` compares cannot see it)."""
    if BITWIDTH == 16:
        return x.to(tl.int16, bitcast=True) < 0
    elif BITWIDTH == 32:
        return x.to(tl.int32, bitcast=True) < 0
    else:
        return x.to(tl.int64, bitcast=True) < 0


@triton.jit
def _bwd_expr(g, s, flip):
    # torch.copysign autograd: grad * sign(self) * signbit(other); 0 where self == 0.
    r = tl.where(flip, -g, g)
    r = tl.where(s == 0, 0.0, r)
    r = tl.where(s != s, s, r)
    return r


