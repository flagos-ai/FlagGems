_MAX_GRID_X = 65535
# A single kernel cannot address a tensor wider than a few hundred MB on this
# backend (the codegen has no 64-bit integers, so the address arithmetic
# overflows and the device raises a SIP error: reproduced on 1G fp32 = 4GB,
# while 8 launches of 512MB slices are fine).  Anything above this many
# elements is therefore processed as consecutive slices.
_CHUNK_ELEMS = 134217728  # 2**27
_BLOCK_MAX = 131072
_BLOCK_MAX_HUGE = 262144
_MAXD = 8


def _pick_block(n):
    """Empty-kernel cost on this vendor is dominated by a fixed term plus a
    per-program term, so the tensor is handed to one program while it fits in
    128K elements (262K above 256 programs) instead of a fixed 2048-element
    tile."""
    block = 1 << max(10, (n - 1).bit_length())
    if block > _BLOCK_MAX:
        block = _BLOCK_MAX
    if (n + block - 1) // block > 256:
        block = _BLOCK_MAX_HUGE
    while (n + block - 1) // block > _MAX_GRID_X:
        block *= 2
    return block


def _pick_warps(block, nblocks):
    if block <= 16384:
        return 2
    if block <= 32768:
        return 4
    if nblocks <= 2:
        return 8
    if nblocks <= 4:
        return 4
    return 2


def _launch(x, out, mask, scale, zero_point, fake_quant_enabled, quant_min, quant_max):
    n = x.numel()
    if n == 0:
        return
    block = _pick_block(n)
    nblocks = (n + block - 1) // block
    grid = (nblocks,)
    nw = _pick_warps(block, nblocks)

    if x.is_contiguous():
        _fq_flat_kernel[grid](
            x,
            scale,
            zero_point,
            fake_quant_enabled,
            out,
            mask,
            n,
            quant_min,
            quant_max,
            BLOCK=block,
            num_warps=nw,
        )
    else:
        rank = x.dim()
        # Logical row-major order decomposes from the innermost dimension, so the
        # per-dim shape/stride pairs are passed last-dim-first.
        shp = list(reversed(x.shape)) + [1] * (_MAXD - rank)
        st = list(reversed(x.stride())) + [0] * (_MAXD - rank)
        _fq_strided_kernel[grid](
            x,
            scale,
            zero_point,
            fake_quant_enabled,
            out,
            mask,
            n,
            shp[0],
            shp[1],
            shp[2],
            shp[3],
            shp[4],
            shp[5],
            shp[6],
            shp[7],
            st[0],
            st[1],
            st[2],
            st[3],
            st[4],
            st[5],
            st[6],
            st[7],
            quant_min,
            quant_max,
            NDIM=rank,
            BLOCK=block,
            num_warps=nw,
        )
    return out, mask


def _fake_quantize_per_tensor_affine_cachemask_tensor_qparams(
    self, scale, zero_point, fake_quant_enabled, quant_min, quant_max
):
    logger.debug("GEMS FAKE_QUANTIZE_PER_TENSOR_AFFINE_CACHEMASK_TENSOR_QPARAMS")

    if fake_quant_enabled.dtype == torch.int64:
        # A 64-bit scalar load does not compile on this backend ("64-bit data
        # type not supported"), which made every case of this operator fail.
        # int64 is stored here as one int32 word per element, so reinterpreting
        # the magnitude as int32 (metadata only, no kernel) yields the value for
        # the 0/1 flag aten passes; the flag is only ever tested != 0.
        fake_quant_enabled = fake_quant_enabled.reshape(1).view(torch.int32)

    out = torch.empty(self.shape, dtype=self.dtype, device=self.device)
    mask = torch.empty(self.shape, dtype=torch.bool, device=self.device)

    n = self.numel()
    if n == 0:
        return out, mask

    if self.is_contiguous() and n > _CHUNK_ELEMS:
        xv = self.reshape(-1)
        ov = out.reshape(-1)
        mv = mask.reshape(-1)
        for start in range(0, n, _CHUNK_ELEMS):
            end = min(start + _CHUNK_ELEMS, n)
            _launch(
                xv[start:end],
                ov[start:end],
                mv[start:end],
                scale,
                zero_point,
                fake_quant_enabled,
                quant_min,
                quant_max,
            )
        return out, mask

    _launch(
        self, out, mask, scale, zero_point, fake_quant_enabled, quant_min, quant_max
    )
    return out, mask
