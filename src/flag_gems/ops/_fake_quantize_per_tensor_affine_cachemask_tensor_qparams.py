@triton.jit
def _fq_quantize(x, inv, zp, scale, qmin_f, qmax_f):
    """Fake-quantize fp32 values. Returns (dequantized, in_range).

    The rounding happens *before* zero_point is added, which is what ATen's
    tensor-qparams kernel does and what is observable on exact ties: adding an
    odd zero_point first moves a tie half a level off the .5 grid, so the two
    orders disagree on 16.9% of a tie/nextafter corpus for scale=0.1,
    zero_point=-17.  Verified against aten on cpu for every (dtype, enabled,
    zero_point, scale) combination of the upstream corpus.
    """
    v = x * inv
    # ties-to-even rounding of v (ATen uses std::nearbyint) with the 2**23
    # magic-add trick: for |v| < 2**23 the sum lands in [2**23, 2**24) whose ulp
    # is exactly 1.0, so the hardware round-half-to-even yields the integer
    # directly and subtracting the magic constant is exact.  No magnitude guard
    # is needed: |v| >= 2**23 is always outside [quant_min, quant_max] once
    # zero_point is added, so both the clamped value and the in-range flag are
    # unchanged by it.
    av = tl.abs(v)
    ra = (av + 8388608.0) - 8388608.0
    r = tl.where(v < 0.0, -ra, ra)

    q = r + zp
    in_range = (q >= qmin_f) & (q <= qmax_f)
    qc = tl.minimum(tl.maximum(q, qmin_f), qmax_f)
    # ATen's clamp does not propagate NaN: a NaN input lands on QUANT_MIN.
    qc = tl.where(x != x, qmin_f, qc)
    return (qc - zp) * scale, in_range


