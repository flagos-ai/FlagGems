class _SlowConvTranspose2d(torch.autograd.Function):
    """Autograd entry point; gradients come from the Triton kernels above."""

    @staticmethod
    def forward(ctx, x, weight, bias, st, pd, op, dl, kh, kw, has_bias):
        cin, hin, win = x.shape[1], x.shape[2], x.shape[3]
        cout = weight.shape[1]
        hout = (hin - 1) * st[0] - 2 * pd[0] + dl[0] * (kh - 1) + op[0] + 1
        wout = (win - 1) * st[1] - 2 * pd[1] + dl[1] * (kw - 1) + op[1] + 1
        out = torch.empty(
            (x.shape[0], cout, hout, wout), device=x.device, dtype=x.dtype
        )
