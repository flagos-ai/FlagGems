@triton.jit
def _sct2d_dot(
    x_ptr,
    w_ptr,
    b_ptr,
    o_ptr,
    Cin,
    Hin,
    Win,
    Cout,
    Hout,
    Wout,
    xs0,
    xs1,
    xs2,
    xs3,
    ws0,
    ws1,
    ws2,
    ws3,
    os0,
    os1,
    os2,
    os3,
    bs,
    sh,
    sw,
    ph,
    pw,
    dh,
    dw,
    HAS_BIAS: tl.constexpr,
    BLOCK_M: tl.constexpr,
    BLOCK_CO: tl.constexpr,
    BLOCK_K: tl.constexpr,
    KH: tl.constexpr,
    KW: tl.constexpr,
    PREC: tl.constexpr,
):
    pid_m = tl.program_id(0)
    pid_co = tl.program_id(1)
    n = tl.program_id(2)

    mtotal = Hout * Wout
    m = pid_m * BLOCK_M + tl.arange(0, BLOCK_M)
    valid_m = m < mtotal
    oh = m // Wout
    ow = m - oh * Wout

    co = pid_co * BLOCK_CO + tl.arange(0, BLOCK_CO)
    valid_co = co < Cout

    acc = tl.zeros((BLOCK_M, BLOCK_CO), dtype=tl.float32)
    xbase = x_ptr + n * xs0

    for kh in tl.static_range(KH):
        nh = oh + ph - kh * dh
        qh = nh // sh
        ih = qh
        vh = (qh * sh == nh) & (qh >= 0) & (qh < Hin)
        for kw in tl.static_range(KW):
            nw = ow + pw - kw * dw
            qw = nw // sw
            iw = qw
            vw = (qw * sw == nw) & (qw >= 0) & (qw < Win)
            rowmask = valid_m & vh & vw
            woff = kh * ws2 + kw * ws3
            for k0 in range(0, Cin, BLOCK_K):
                kk = k0 + tl.arange(0, BLOCK_K)
                kmask = kk < Cin
                a = tl.load(
                    xbase + kk[None, :] * xs1 + ih[:, None] * xs2 + iw[:, None] * xs3,
                    mask=rowmask[:, None] & kmask[None, :],
                    other=0.0,
                )
                b = tl.load(
                    w_ptr + kk[:, None] * ws0 + co[None, :] * ws1 + woff,
                    mask=kmask[:, None] & valid_co[None, :],
                    other=0.0,
                )
                # A masked row holds zeros, but this tap's weight may be infinite
                # or NaN; pairing 0 with it would fabricate a value the reference
                # never forms.  Drop the whole contribution for rows where the tap
                # does not reach the output element.
                contrib = tl.dot(a, b, input_precision=PREC)
                acc += tl.where(rowmask[:, None], contrib, 0.0)

    if HAS_BIAS:
        bias = tl.load(b_ptr + co * bs, mask=valid_co, other=0.0)
        acc = acc + bias.to(tl.float32)[None, :]

    optr = o_ptr + n * os0 + co[None, :] * os1 + oh[:, None] * os2 + ow[:, None] * os3
    tl.store(
        optr, acc.to(o_ptr.dtype.element_ty), mask=valid_m[:, None] & valid_co[None, :]
    )


