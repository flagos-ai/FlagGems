    a = a.broadcast_to(shape)
    b = b.broadcast_to(shape)
    c = c.broadcast_to(shape)
    # Host-function convention: route layout normalization through the FlagGems
    # contiguous op instead of calling tensor.contiguous() directly.
    a = contiguous(a) if not a.is_contiguous() else a
    b = contiguous(b) if not b.is_contiguous() else b
    c = contiguous(c) if not c.is_contiguous() else c

