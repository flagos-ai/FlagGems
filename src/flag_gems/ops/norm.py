def make_l2_plan(inp):
    shape, dtype, device = (tuple(inp.shape), inp.dtype, inp.device)
    n = math.prod(shape)
    grid = (n + 1023) // 1024

    def backward(x, grad, norm):
        out = torch.empty(shape, dtype=dtype, device=device)
        if n:
            xc = x.is_contiguous()
            xs = () if xc else tuple(x.stride())
            args = (n, shape, xs, xc, 1024)
            key = (
                device,
                dtype,
                grad.dtype,
                norm.dtype,
                args,
                x.data_ptr() & 15,
                grad.data_ptr() & 15,
                norm.data_ptr() & 15,
            )
            with torch_device_fn.device(device):
                launch = _CODE.get(key)
                if launch is None:
                    compiled = _l2[grid,](
                        x, grad, norm, out, *args, enable_fp_fusion=False
                    )
                    _CODE[key] = compiled[grid, 1, 1]
                else:
                    launch(x, grad, norm, out, *args)
        return out

    return backward


