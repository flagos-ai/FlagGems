logger = logging.getLogger(__name__)


def swapdims(self: torch.Tensor, dim0: int, dim1: int) -> torch.Tensor:
    """Return a view of the tensor with ``dim0`` and ``dim1`` exchanged.

    ``torch.swapdims`` is an alias of :func:`torch.transpose`, and this op
    shares the zero-copy view semantics of the sibling ``transpose`` op: the
    sizes and strides of ``dim0`` and ``dim1`` are exchanged via
    :func:`torch.as_strided`, no element is read or written, and the result
    aliases ``self`` (matching ``aten::swapdims(Tensor(a) self, int dim0,
    int dim1) -> Tensor(a)``). The storage offset is preserved, autograd
    tracks the view, and the original strides are kept exactly (including
    the degenerate no-op cases).
    """
    logger.debug("GEMS SWAPDIMS")

    ndim = self.dim()

    # Normalize negative dims with aten's convention. A 0D tensor accepts only
    # 0 and -1 (both denote the sole axis), so clamp the accepted range to
    # [-1, 0] instead of the rank-based range used for higher ranks. ATen
    # reports out-of-range dims using the value as passed in by the caller.
    max_dim = max(ndim, 1)
    if dim0 < 0:
        dim0 += max_dim
    if dim1 < 0:
        dim1 += max_dim

    # Match aten's IndexError message, which echoes the dim as passed in.
    if not (0 <= dim0 < max_dim):
        raise IndexError(
            f"Dimension out of range (expected to be in range of "
            f"[-{max_dim}, {max_dim - 1}], but got "
            f"{dim0 - max_dim if dim0 < 0 else dim0})"
        )
    if not (0 <= dim1 < max_dim):
        raise IndexError(
            f"Dimension out of range (expected to be in range of "
            f"[-{max_dim}, {max_dim - 1}], but got "
            f"{dim1 - max_dim if dim1 < 0 else dim1})"
        )

    shape = list(self.shape)
    strides = list(self.stride())

    # 0D / 1D / same-dim swaps keep the layout; every in-range call still
    # yields a *fresh* view of the operand (returning ``self`` is rejected by
    # PyTorch's view-op checks), which ``as_strided`` reproduces.
