def digamma_backward_kernel(
    g_ptr,
    x_ptr,
    o_ptr,
    n_elements,
    BLOCK_SIZE: tl.constexpr,
    IS64: tl.constexpr,
):
    pid = tl.program_id(axis=0)
    offsets = pid * BLOCK_SIZE + tl.arange(0, BLOCK_SIZE)
    mask = offsets < n_elements

    g = tl.load(g_ptr + offsets, mask=mask)
    x = tl.load(x_ptr + offsets, mask=mask)

    if IS64:
        grad_input = g * _trigamma_f64(x)
    else:
        # Compute polygamma in fp32, materialise it in the input dtype, then
        # multiply -- this reproduces ATen's per-op fp32-compute/fp16-store
        # rounding for float16/bfloat16 exactly.
        poly = _trigamma_f32(x.to(tl.float32))
        poly = poly.to(o_ptr.dtype.element_ty)
        grad_input = g * poly

    tl.store(o_ptr + offsets, grad_input, mask=mask)


def digamma_backward(grad_output: torch.Tensor, x: torch.Tensor):
    """``grad_output * polygamma(1, x)`` for the first-order digamma gradient."""
    logger.debug("GEMS DIGAMMA_BACKWARD")
    if not isinstance(grad_output, torch.Tensor) or not isinstance(x, torch.Tensor):
        raise TypeError("digamma_backward expects two torch.Tensor arguments")

    if grad_output.numel() == 0:
        return torch.empty(x.shape, dtype=x.dtype, device=x.device)

    if grad_output.shape != x.shape:
        # A unary op can still see a broadcast upstream gradient once autograd
        # has already reduced it; materialise the common shape.
        grad_output = grad_output.expand(x.shape)
    grad_contig = grad_output.contiguous()
    x_contig = x.contiguous()

    grad_input = torch.empty(x.shape, dtype=x.dtype, device=x.device)
    n_elements = x_contig.numel()
    grid = lambda meta: (triton.cdiv(n_elements, meta["BLOCK_SIZE"]),)
    with torch_device_fn.device(x.device):
        digamma_backward_kernel[grid](
            grad_contig,
            x_contig,
            grad_input,
            n_elements,
            BLOCK_SIZE=_BLOCK,
            IS64=x.dtype == torch.float64,
            num_warps=_NUM_WARPS,
        )
    return grad_input


