"""First-order gradient of ``torch.digamma``.

``torch.ops.aten.digamma_backward`` does not exist as a standalone schema; ATen
serves it through the ``DigammaBackward0`` autograd node, whose formula is

    grad_input = grad_output * polygamma(1, x)

where ``polygamma(1, x)`` is the trigamma function.  This module provides

* ``digamma_backward(grad_output, x)`` -- the explicit Triton entry point, and
* ``DigammaFunction`` -- an ``autograd.Function`` that pairs the FlagGems
  ``digamma`` forward with this backward kernel.  It is used directly (or via
  ``flag_gems.digamma_backward``) because this Torch build has no
  ``aten::digamma_backward`` schema to register the kernel against.

Rounding semantics (validated bit-exactly against ATen on CUDA):

* ``float64``: the whole trigamma and the final multiply are computed in fp64.
* ``float16`` / ``bfloat16``: ATen computes ``polygamma`` in fp32 from an
  upcast input, stores the *result* in the input dtype and only then multiplies
  by ``grad_output``.  We reproduce that: upcast -> fp32 trigamma -> cast back
  to the input dtype -> multiply in the input dtype.
* ``float32``: fp32 trigamma times fp32 grad in fp32.
"""

