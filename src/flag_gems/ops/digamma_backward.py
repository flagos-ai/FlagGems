# is ~2us faster at 4096x4096 but leaves only 4 CTAs for a 64x64 tensor, which
# triples the measured latency there and drags the geomean down (1.43x vs 1.24x).
_BLOCK = 512
_NUM_WARPS = 4


@triton.jit
def _trigamma_f32(x):
    """fp32 trigamma, mirroring ATen's CUDA ``calc_trigamma<float>``.

    Every constant is materialised with ``tl.full`` so Triton does not fold the
    Python literal down to fp32 width implicitly (which silently truncated the
    value of ``pi`` before).
    """
    pi = tl.full([], 3.1415926535897932384626433832795028841971, tl.float32)
    c6 = tl.full([], 1.0 / 6.0, tl.float32)
    c30 = tl.full([], 1.0 / 30.0, tl.float32)
    c42 = tl.full([], 1.0 / 42.0, tl.float32)

    reflect = x < 0.5
    s = tl.sin(pi * x)
    # Reflection: trigamma(x) = -pi^2 / sin^2(pi*x) + trigamma(1 - x)
    result = tl.where(reflect, -(pi * pi) / (s * s), 0.0)
    y = tl.where(reflect, 1.0 - x, x)

    # Six recurrence steps: trigamma(y) = trigamma(y + 1) + 1 / y^2
    for _ in range(6):
        result += 1.0 / (y * y)
        y += 1.0

    # Euler-Maclaurin tail expansion for large y
    iyy = 1.0 / (y * y)
    result += (1.0 + 1.0 / (2.0 * y) + iyy * (c6 - iyy * (c30 - iyy * c42))) / y

    sign = tl.where(reflect, -1.0, 1.0)
    return sign * result


@triton.jit
def _trigamma_f64(x):
    """fp64 trigamma, bit-exact with ATen's ``calc_trigamma<double>``."""
    pi = tl.full([], 3.1415926535897932384626433832795028841971, tl.float64)
    c6 = tl.full([], 1.0 / 6.0, tl.float64)
    c30 = tl.full([], 1.0 / 30.0, tl.float64)
    c42 = tl.full([], 1.0 / 42.0, tl.float64)

    reflect = x < 0.5
    s = tl.sin(pi * x)
    result = tl.where(reflect, -(pi * pi) / (s * s), 0.0)
    y = tl.where(reflect, 1.0 - x, x)

    for _ in range(6):
        result += 1.0 / (y * y)
        y += 1.0

    iyy = 1.0 / (y * y)
    result += (1.0 + 1.0 / (2.0 * y) + iyy * (c6 - iyy * (c30 - iyy * c42))) / y

    sign = tl.where(reflect, -1.0, 1.0)
    return sign * result


