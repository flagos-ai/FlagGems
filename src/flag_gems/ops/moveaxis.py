def _normalize_moveaxis_axes(self: torch.Tensor, source, destination):
    """Shared argument normalization for the ``moveaxis`` overloads.

    Replicates the validation order of ``aten::moveaxis``: a length mismatch
    between ``source`` and ``destination`` is reported before out-of-range
    dimensions, and repeated dims are reported after all dims are known to be
    in range.

    Returns:
        The permutation ``order`` for ``as_strided``: output axis ``p`` takes
        input axis ``order[p]``.
    """
    ndim = self.dim()

    # Normalize to lists of ints (the int overload passes scalars).
    if isinstance(source, (list, tuple)):
        src = [int(s) for s in source]
    else:
        src = [int(source)]
    if isinstance(destination, (list, tuple)):
        dst = [int(d) for d in destination]
    else:
        dst = [int(destination)]

    if len(src) != len(dst):
        # aten::moveaxis delegates to movedim internally, so its error message
        # text says "movedim:" even when raised through the moveaxis entry point.
        raise RuntimeError(
            f"movedim: Invalid source or destination dims: source ({src} dims) "
            f"should contain the same number of dims as destination ({dst} dims)"
        )

    # Normalize negative dims, matching aten's IndexError message. For a 0-d
    # tensor aten's range is [-1, 0]: both 0 and -1 refer to the only dim.
    def normalize(dim):
        if dim < -max(ndim, 1) or dim >= max(ndim, 1):
            raise IndexError(
                "Dimension out of range (expected to be in range of "
                f"[-{max(ndim, 1)}, {max(ndim - 1, 0)}], but got {dim})"
            )
        return dim % ndim if ndim > 0 else 0

    src = [normalize(d) for d in src]
    dst = [normalize(d) for d in dst]

    if len(set(src)) != len(src):
        raise RuntimeError(f"movedim: repeated dim in `source` ({src})")
    if len(set(dst)) != len(dst):
        raise RuntimeError(f"movedim: repeated dim in `destination` ({dst})")

    src_set, dst_set = set(src), set(dst)
    rest = [i for i in range(ndim) if i not in src_set]
    order = []
    ri = 0
    for p in range(ndim):
        if p in dst_set:
            order.append(src[dst.index(p)])
        else:
            order.append(rest[ri])
            ri += 1
    return order


