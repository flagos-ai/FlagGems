@triton.jit
def _renorm_tile_kernel(
    x_ptr,
    M,
    Q,
    P,
    sM,
    sQ,
    sP,
    p,
    inv_p,
    maxnorm,
    P_MODE: tl.constexpr,
    BQ: tl.constexpr,
    BM: tl.constexpr,
):
    """Q > 1: each program owns BM slices and walks the whole reduction."""
    pid = tl.program_id(0)
    m = pid * BM + tl.arange(0, BM)
    q = tl.arange(0, BQ)
    m_mask = (m < M)[None, :]
