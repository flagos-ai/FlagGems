def _row_layout(shape, strides):
    """Express (shape, strides) as (rows, inner, row_stride) when possible.

    ``inner`` counts the trailing elements with unit stride; every dimension in
    front of them must be uniformly strided so one row stride describes the
    whole layout.  Returns ``None`` for layouts that are not expressible that
    way (non unit innermost stride, permuted strides, ...).
    """
    if len(shape) == 0:
        return (1, 1, 1)
    if strides[-1] != 1:
        return None
    inner = 1
    expected = 1
    k = len(shape) - 1
    while k >= 0 and strides[k] == expected:
        inner *= shape[k]
        expected *= shape[k]
        k -= 1
    if k < 0:
        return (1, inner, inner)
    row_stride = strides[k]
    for i in range(k):
        if strides[i] != strides[i + 1] * shape[i + 1]:
            return None
    rows = 1
    for i in range(k + 1):
        rows *= shape[i]
    return (rows, inner, row_stride)


def _flip_flags(t):
    conj_bit = bool(t.is_conj())
    neg_bit = bool(t.is_neg())
    return (1 if neg_bit else 0, 1 if (neg_bit == conj_bit) else 0)


