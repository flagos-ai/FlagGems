def conj_physical_backward_(grad_output, self):
    logger.debug("GEMS CONJ_PHYSICAL_BACKWARD_")
    g = grad_output
    # ``view(lane_dtype)`` below requires an innermost unit stride; an expanded
    # (broadcast) upstream gradient has stride 0 there, and a lazy conj/neg bit
    # also blocks the view, so materialize a dense copy first.
    if g.is_complex() and (g.stride(-1) != 1 or g.is_conj() or g.is_neg()):
        g = g.resolve_conj().resolve_neg() if (g.is_conj() or g.is_neg()) else g
        g = g.contiguous()
    n_elem = g.numel()
    contiguous = g.is_contiguous()
    if contiguous:
        out = torch.empty_like(g)
    else:
        out = torch.empty(g.shape, dtype=g.dtype, device=g.device)
    if n_elem == 0:
        return out

    flip_even, flip_odd = _flip_flags(g)
    complex_input = g.is_complex()
    if complex_input:
        lane_dtype = torch.float32 if g.dtype == torch.complex64 else torch.float64
        src = g.view(lane_dtype)
        dst = out.reshape(-1).view(lane_dtype)
        n = n_elem * 2
        scale = 2
    else:
        src = g
        dst = out.reshape(-1)
        n = n_elem
        scale = 1

    if contiguous:
        itemsize = src.element_size()
        _launch_flat(src.reshape(-1), dst, n, itemsize, flip_even, flip_odd)
        return out

    layout = _row_layout(tuple(g.shape), tuple(g.stride()))
    if layout is None:
        raise NotImplementedError(
            "conj_physical_backward_: unsupported layout "
            f"shape={tuple(g.shape)} strides={tuple(g.stride())}"
        )
    rows, inner, row_stride = layout
    _launch_strided(
        src,
        dst,
        rows * inner * scale,
        inner * scale,
        row_stride * scale,
        flip_even,
        flip_odd,
    )
    return out
