# Gather-based backward kernel for nearest-neighbor 3D upsampling.
# Each thread owns one input voxel and sums the gradients of every output
# voxel that mapped to it in the forward pass. This avoids atomics and the
# float32 scratch buffer, writing the result directly in the output dtype.
#
# The candidate output range per input voxel is derived from the forward
# mapping input = floor(output * reciprocal_scale) clamped to [0, I-1].
# For each candidate output index we re-evaluate that exact mapping and only
# accumulate when it lands on the current input voxel, so the result matches
# the forward rule regardless of floating-point edge cases.
@triton.jit
def _upsample_nearest3d_backward_kernel(
    grad_output_ptr,
    grad_input_ptr,
    OD,
    OH,
    OW,
    ID,
    IH,
    IW,
    reciprocal_scale_d,
    reciprocal_scale_h,
    reciprocal_scale_w,
    MAX_D: tl.constexpr,
    MAX_H: tl.constexpr,
    MAX_W: tl.constexpr,
    BLOCK_SIZE: tl.constexpr,
):
    pid = tl.program_id(0)
    nc_pid = tl.program_id(1)

    # Linear index over the spatial input volume (ID * IH * IW).
    idx = pid * BLOCK_SIZE + tl.arange(0, BLOCK_SIZE)
    mask = idx < (ID * IH * IW)

    iw = idx % IW
    tmp = idx // IW
    ih = tmp % IH
    id_ = tmp // IH

    # Starting candidate output index for each dimension (one before the
    # nominal start to stay robust to rounding).
    od_start = (id_.to(tl.float32) / reciprocal_scale_d).to(tl.int32) - 1
    oh_start = (ih.to(tl.float32) / reciprocal_scale_h).to(tl.int32) - 1
    ow_start = (iw.to(tl.float32) / reciprocal_scale_w).to(tl.int32) - 1
    od_start = tl.maximum(od_start, 0)
    oh_start = tl.maximum(oh_start, 0)
    ow_start = tl.maximum(ow_start, 0)

    acc = tl.zeros((BLOCK_SIZE,), dtype=tl.float32)

    for dd in tl.static_range(MAX_D):
        od = od_start + dd
        src_d = tl.minimum((od * reciprocal_scale_d).to(tl.int32), ID - 1)
        valid_d = (od < OD) & (src_d == id_)
        for hh in tl.static_range(MAX_H):
            oh = oh_start + hh
            src_h = tl.minimum((oh * reciprocal_scale_h).to(tl.int32), IH - 1)
            valid_h = (oh < OH) & (src_h == ih)
            for ww in tl.static_range(MAX_W):
                ow = ow_start + ww
                src_w = tl.minimum((ow * reciprocal_scale_w).to(tl.int32), IW - 1)
                valid_w = (ow < OW) & (src_w == iw)

                valid = mask & valid_d & valid_h & valid_w
                offset_o = ((nc_pid * OD + od) * OH + oh) * OW + ow
                acc += tl.load(grad_output_ptr + offset_o, mask=valid, other=0.0)

    offset_i = ((nc_pid * ID + id_) * IH + ih) * IW + iw
    tl.store(grad_input_ptr + offset_i, acc, mask=mask)


