    # interleaved real/imag view. resolve_conj/resolve_neg are view-class
    # metadata ops (no data compute); the pragma marks them for the checker.
    g = torch.resolve_neg(g)  # allow-torch-compute
    g = torch.resolve_conj(g)  # allow-torch-compute
    gin = torch.view_as_real(g).reshape(-1)

