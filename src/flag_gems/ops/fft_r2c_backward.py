"""Triton implementation of ``fft_r2c_backward`` — the input gradient of
``aten::_fft_r2c`` (the onesided real -> complex FFT used by ``torch.fft.rfft``).

ATen implements the backward as a manual autograd function in
``torch/csrc/autograd/FunctionsManual.cpp``:

    fft_r2c_backward(grad, dim, normalization, onesided, last_dim_size):
        if not onesided:
            return real(_fft_c2c(grad, dim, normalization, forward=False))
        complex_full_grad = zeros(new_shape) with [:K] = grad
        return real(_fft_c2c(complex_full_grad, dim, normalization, forward=False))

There is no registered ``aten::_fft_r2c_backward`` schema, so this operator
exposes the backward directly: given ``grad_output`` (a complex tensor of the
onesided rfft output, length ``K = N//2 + 1`` along the transformed axis), it
returns the real input gradient ``grad_input`` of length ``N``. ``last_dim_size``
carries the original signal length N, which is not inferable from the
K-length grad (odd and even N share the same K).

Two Triton kernels: for power-of-two N a per-row radix-2 decimation-in-frequency
inverse complex FFT runs fully in registers (literal-constexpr butterfly stage
chains, bit-reversal via register gather); the onesided zero-padding is supplied
for free by masking the single contiguous interleaved load to the ``2K`` real
components. For arbitrary N a direct-DFT fallback evaluates the unnormalized
inverse sum ``U[n] = sum_k Z_k e^{+2i pi k n / N}`` per row. The inverse
normalization scale is fused into the store: ATen FFTNormMode code 0 (backward)
applies no inverse scale, code 1 (ortho) applies ``1/sqrt(n)``, code 2 (forward)
applies ``1/n``. Launch geometry (``num_warps``/``num_stages``) is specialized
on the transform length and the number of rows. No reference kernels are
reused, so the ``backward`` value is produced by this module alone.
"""

