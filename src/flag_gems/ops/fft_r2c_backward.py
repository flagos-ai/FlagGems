@triton.jit
def _dft_kernel(
    gin_ptr, out_ptr, scale, K, N: tl.constexpr, NP: tl.constexpr, KP: tl.constexpr
):
    """One program per row: direct DFT (non-power-of-2 N fallback).
    The spectrum is an arbitrary complex tensor (no Hermitian symmetry):
    U[n] = sum_{k<K} Z_k e^{+2*pi*i*k*n/N}; store Re(U[n]) * scale."""
    pid = tl.program_id(0)
    kp = tl.arange(0, KP)
    kmask = kp < K
    base = pid * (2 * K)
    zr = tl.load(gin_ptr + base + 2 * kp, mask=kmask, other=0.0)
    zi = tl.load(gin_ptr + base + 2 * kp + 1, mask=kmask, other=0.0)

    nn = tl.arange(0, NP).to(tl.float32)[:, None]
    kk = kp.to(tl.float32)[None, :]
    ang = TWOPI * kk * nn / N
    c = tl.cos(ang)
    s = tl.sin(ang)
    tot = tl.sum(zr[None, :] * c - zi[None, :] * s, axis=1)
    nmask = tl.arange(0, NP) < N
    tl.store(
        out_ptr + pid * N + tl.arange(0, NP),
        (tot * scale).to(out_ptr.dtype.element_ty),
        mask=nmask,
    )


def _next_pow2(v):
    v = max(1, int(v))
    return 1 << (v - 1).bit_length()


def _run_rows(gin, out, num_rows, K, N, norm):
    """Run the row-wise inverse transform over a flattened interleaved view."""
    # ATen FFTNormMode on the inverse transform (verified against autograd):
    # code 0 (backward) applies no inverse scale, code 1 (ortho) applies
    # 1/sqrt(n), code 2 (forward) applies 1/n.
    scale = {0: 1.0, 1: 1.0 / math.sqrt(N), 2: 1.0 / N}[norm]

    if (N & (N - 1)) == 0 and N >= 4:
        LOGN = N.bit_length() - 1
        if N >= 4096:
            # wide blocks only pay off when the grid is large enough to
            # saturate the GPU; with few programs the shuffle cost dominates
            nw = 16 if num_rows >= 1024 else 8
        elif N >= 1024:
            nw = 8 if num_rows < 512 else 4
        else:
            nw = 2
        ns = 4 if N >= 4096 else 2
        _fft_pow2_kernel[(num_rows,)](
            gin,
            out,
            scale,
            N=N,
            LOGN=LOGN,
            ONESIDED=K != N,
            num_warps=nw,
            num_stages=ns,
        )
    else:
        npt = _next_pow2(N)
        kpt = _next_pow2(K)
        _dft_kernel[(num_rows,)](
            gin,
            out,
            scale,
            K,
            N=N,
            NP=npt,
            KP=kpt,
            num_warps=4,
        )


