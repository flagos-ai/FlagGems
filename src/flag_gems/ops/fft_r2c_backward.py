    x2i = tl.reshape(xi, (M, 2, h))
    ar, br = tl.split(tl.permute(x2r, (0, 2, 1)))
    ai, bi = tl.split(tl.permute(x2i, (0, 2, 1)))
    jj = tl.arange(0, h).to(tl.float32)
