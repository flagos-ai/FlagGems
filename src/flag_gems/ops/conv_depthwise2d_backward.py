@triton.jit
def _cdw_gw_kernel(
    X,
    GO,
    GW,
    N,
    OH,
    OW,
    H,
    W_IN,
    C,
    KH: tl.constexpr,
    KW: tl.constexpr,
    SH: tl.constexpr,
    SW: tl.constexpr,
    PH: tl.constexpr,
    PW: tl.constexpr,
    DH: tl.constexpr,
    DW: tl.constexpr,
    BLOCK_HW: tl.constexpr,
):
    # One program handles one (c, kh, kw) tap and reduces over ALL (n, oh, ow).
    c = tl.program_id(0)
    ckk = tl.program_id(1)

    HW = OH * OW
    kh = ckk // KW
    kw = ckk % KW

    acc = tl.zeros((BLOCK_HW,), dtype=tl.float32)
    for n in range(0, N):
        for h0 in range(0, OH * OW, BLOCK_HW):
            hw = h0 + tl.arange(0, BLOCK_HW)
            mhw = hw < HW
            oh = hw // OW
            ow = hw % OW
            go = tl.load(
                GO + (n * C + c) * HW + oh * OW + ow,
                mask=mhw,
                other=0.0,
            )
            ih = oh * SH - PH + kh * DH
            iw = ow * SW - PW + kw * DW
            ok = mhw & (ih >= 0) & (ih < H) & (iw >= 0) & (iw < W_IN)
            xv = tl.load(
                X + (n * C + c) * (H * W_IN) + ih * W_IN + iw,
                mask=ok,
                other=0.0,
            )
            acc += tl.where(ok, go * xv, 0.0)
    total = tl.sum(acc, axis=0)
    tl.store(GW + c * KH * KW + kh * KW + kw, total.to(GW.dtype.element_ty))


