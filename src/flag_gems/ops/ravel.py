    if R2 > 0:
        g += ((r // d0) % s0) * t0
    if R2 > 1:
        g += ((r // d1) % s1) * t1
    if R2 > 2:
        g += ((r // d2) % s2) * t2
    if R2 > 3:
        g += ((r // d3) % s3) * t3
    if R2 > 4:
        g += ((r // d4) % s4) * t4
    if R2 > 5:
        g += ((r // d5) % s5) * t5
    if R2 > 6:
        g += ((r // d6) % s6) * t6
    if R2 > 7:
        g += ((r // d7) % s7) * t7

    src = i0[None, :].to(tl.int64) + g[:, None]
    v = tl.load(in_ptr + src, mask=mr[:, None] & m0[None, :], other=0)
    if NEG:
        v = -v
    dst = i0[:, None].to(tl.int64) * P + r[None, :]
    tl.store(out_ptr + dst, tl.trans(v), mask=m0[:, None] & mr[None, :])


