# Launch config: int8/uint8 copy prefers wide blocks (16 elements/thread ->
# 128-bit vector ld/st); int32 already reaches 128-bit at BLOCK=1024. Tiny
# 8-bit inputs use BLOCK=1024 so the mask-free even kernel covers them exactly.
