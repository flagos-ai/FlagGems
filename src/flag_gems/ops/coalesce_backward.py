"""Triton implementation of the ``aten::_coalesce`` backward for sparse COO.

``_coalesce(self)`` de-duplicates a sparse COO tensor: coordinates sharing the
same linear key are merged (values summed) and the unique keys are emitted in
ascending order.  Its autograd derivative (``derivatives.yaml``:
``_coalesce ... self: grad``) routes the upstream gradient back to the sparse
input, which traces to a ``sparse_mask`` + ``_values`` chain with the effect

    grad_input.values[k] = grad_output.values[j]
        for every stored input position k whose coordinate equals the
        output coordinate j (a merged group of duplicates all receives the
        merged output's gradient, matching autograd on the merged value);

    grad_input.indices = self.indices  (the input's own stored coordinates);
    grad_input stays uncoalesced exactly when ``self`` was uncoalesced.

The fused Triton restore therefore only has to move ``nnz`` scalars: build
the per-position linear keys of both coordinate lists with the dimension
strides passed as scalar arguments, then for every input position find its
rank in the (already ascending) output key list and copy the matching output
value.  A first device-side probe decides whether input and output index
tables are elementwise identical (the identity case, covering
already-coalesced inputs and every duplicate-free input), in which case the
whole backward collapses to a plain value copy.

Per-call time here is dominated by launch and host-call overhead rather than
by streaming bandwidth (the payload is ``nnz`` scalars), so the design keeps
every small constant on the kernel argument list:

  1. ``_cb_identity_kernel`` - one-block comparison of the two index tables
  (only launched when ``m == n``); publishes an identity flag.
  2. ``_cb_copy_kernel``     - identity fast path: stream the values.
  3. ``_cb_keys_kernel``     - write the ``n`` input linear keys and the
  ``m`` output linear keys into two int64 buffers.
  4. ``_cb_search_kernel``   - general path up to one register-resident
  output tile: every program holds the whole sorted output key list and
  copies the matched value for its tile of input positions.
  5. ``_cb_mvalues_kernel``  - wide-``m`` fallback: gather through the
  ``torch.searchsorted`` rank vector instead of the register-resident scan.

The wrapper dispatches between the paths from ``m``, ``n`` and the identity
flag, so duplicate-free inputs never pay for the key build.
"""

