@triton.jit
def _cb_keys_kernel(
    idx_ptr,
    out_idx_ptr,
    in_key_ptr,
    out_key_ptr,
    n,
    m,
    numel,
    s0,
    s1,
    s2,
    s3,
    s4,
    S: tl.constexpr,
    BLOCK: tl.constexpr,
):
    """Linearise the stored coordinates of both index tables.

    The sparse COO index layout is row-major ``(S, nnz)``; dimension ``d``
    of position ``p`` lives at ``idx_ptr + d * nnz + p``.
    """
    pid = tl.program_id(0)
    offs = (pid * BLOCK + tl.arange(0, BLOCK)).to(tl.int64)
    # Input keys: n positions.
    mask = offs < n
    k = tl.zeros((BLOCK,), dtype=tl.int64)
    if S > 0:
        k = k + tl.load(idx_ptr + offs, mask=mask, other=0).to(tl.int64) * s0
    if S > 1:
        k = k + tl.load(idx_ptr + n + offs, mask=mask, other=0).to(tl.int64) * s1
    if S > 2:
        k = k + tl.load(idx_ptr + 2 * n + offs, mask=mask, other=0).to(tl.int64) * s2
    if S > 3:
        k = k + tl.load(idx_ptr + 3 * n + offs, mask=mask, other=0).to(tl.int64) * s3
    if S > 4:
        k = k + tl.load(idx_ptr + 4 * n + offs, mask=mask, other=0).to(tl.int64) * s4
    tl.store(in_key_ptr + offs, k, mask=mask)
    # Output keys: m positions.
    omask = offs < m
    ok = tl.zeros((BLOCK,), dtype=tl.int64)
    if S > 0:
        ok = ok + tl.load(out_idx_ptr + offs, mask=omask, other=0).to(tl.int64) * s0
    if S > 1:
        ok = ok + tl.load(out_idx_ptr + m + offs, mask=omask, other=0).to(tl.int64) * s1
    if S > 2:
        ok = (
            ok
            + tl.load(out_idx_ptr + 2 * m + offs, mask=omask, other=0).to(tl.int64) * s2
        )
    if S > 3:
        ok = (
            ok
            + tl.load(out_idx_ptr + 3 * m + offs, mask=omask, other=0).to(tl.int64) * s3
        )
    if S > 4:
        ok = (
            ok
            + tl.load(out_idx_ptr + 4 * m + offs, mask=omask, other=0).to(tl.int64) * s4
        )
    tl.store(out_key_ptr + offs, ok, mask=omask)


@triton.jit
def _cb_identity_kernel(
    idx_ptr,
    out_idx_ptr,
    n,
    S: tl.constexpr,
    flag_ptr,
    BLOCK: tl.constexpr,
):
    """Publish 1 when both index tables are elementwise identical."""
    offs = tl.arange(0, BLOCK)
    mask = offs < n
    same = tl.full((BLOCK,), 1, tl.int32)
    for d in tl.static_range(S):
        a = tl.load(idx_ptr + d * n + offs, mask=mask, other=-1)
        b = tl.load(out_idx_ptr + d * n + offs, mask=mask, other=-2)
        same = tl.where(mask & (a != b), 0, same)
    tl.store(flag_ptr + tl.arange(0, 1), tl.min(same, axis=0).to(tl.uint8))


@triton.jit
def _cb_copy_kernel(
    out_val_ptr,
    in_val_ptr,
    n,
    BLOCK: tl.constexpr,
):
    """Identity fast path: stream the values back unchanged."""
    pid = tl.program_id(0)
    offs = pid * BLOCK + tl.arange(0, BLOCK)
    mask = offs < n
    v = tl.load(out_val_ptr + offs, mask=mask, other=0)
    tl.store(in_val_ptr + offs, v, mask=mask)


@triton.jit
def _cb_search_kernel(
    in_key_ptr,
    in_val_ptr,
    out_key_ptr,
    out_val_ptr,
    in_val_out_ptr,
    n,
    m,
    MB: tl.constexpr,
    BLOCK: tl.constexpr,
):
    """Scatter output values onto input positions by key match.

    Every program loads the whole output key list (``m <= MB``) into
    registers/SMEM, then streams a tile of input positions: for each input
    key a linear scan over the sorted output keys finds the match and copies
    the value.  Duplicate input keys receive the same output value, which is
    exactly the merged-group gradient.  The ``(BLOCK, MB)`` comparison matrix
    must stay small (256 x 256): LLVM's optimizer blows up superlinearly on
    the wide i64 rank-reduction and a 1024-wide tile never finishes compiling.
    """
    pid = tl.program_id(0)
    # Sorted output keys resident in one block.
    mo = tl.arange(0, MB)
    # Masked lanes carry +inf-equivalent keys so they never rank below a
    # real key (an -1 filler would inflate every count by 1 for key 0).
    okeys = tl.load(out_key_ptr + mo, mask=mo < m, other=2**62).to(tl.int64)
    ovals = tl.load(out_val_ptr + mo, mask=mo < m, other=0)

    offs = pid * BLOCK + tl.arange(0, BLOCK)
    mask = offs < n
    ikeys = tl.load(in_key_ptr + offs, mask=mask, other=0).to(tl.int64)

    # rank: number of output keys strictly less than the input key; the
    # output key list is ascending (coalesce emits unique keys sorted), so
    # the match sits exactly at that rank when it exists.
    rank = tl.sum((okeys[None, :] < ikeys[:, None]).to(tl.int32), axis=1)
    hit = rank < m
    rank_c = tl.where(hit, rank, 0)
    sel = mo[None, :] == rank_c[:, None]
    matched_val = tl.sum(tl.where(sel, ovals[None, :], 0), axis=1)
    matched_key = tl.sum(tl.where(sel, okeys, 0), axis=1)
    ok = mask & hit & (matched_key == ikeys)
    tl.store(in_val_out_ptr + offs, matched_val, mask=ok)


@triton.jit
def _cb_mvalues_kernel(
    rank_ptr,
    hit_ptr,
    out_val_ptr,
    in_val_out_ptr,
    n,
    BLOCK: tl.constexpr,
):
    """Gather the matched output values through the searchsorted rank.

    The wide-``m`` fallback ranks every input key with ``torch.searchsorted``
    (one launch, no sort) and this kernel turns the rank into the restored
    value: lanes whose rank hits the key keep the matched value, every other
    lane (input coordinate the forward dropped entirely - impossible for a
    coalesce output, but kept for safety) is zero.
    """
    pid = tl.program_id(0)
    offs = pid * BLOCK + tl.arange(0, BLOCK)
    mask = offs < n
    rank = tl.load(rank_ptr + offs, mask=mask, other=0).to(tl.int64)
    hit = tl.load(hit_ptr + offs, mask=mask, other=0) != 0
    v = tl.load(out_val_ptr + rank, mask=mask & hit, other=0)
    tl.store(in_val_out_ptr + offs, v, mask=mask)


def coalesce_backward(grad_output: torch.Tensor, self_: torch.Tensor) -> torch.Tensor:
    """Backward of ``aten::_coalesce`` for sparse COO tensors.

    Routes the upstream gradient back to the uncoalesced input: the restored
    gradient keeps ``self_``'s own index table and receives, at every stored
    position, the upstream value of the coalesced output group that merged it
    (identity for duplicate-free inputs).

    Args:
        grad_output (torch.Tensor): Sparse COO gradient w.r.t. the coalesced
            forward output (same shape and layout as ``self_``).
        self_ (torch.Tensor): The original (possibly uncoalesced) sparse COO
            input of the forward; supplies the restored index table.

    Returns:
        torch.Tensor: Fresh sparse COO tensor with ``self_``'s indices and
        the restored values.
    """
    logger.debug("GEMS COALESCE_BACKWARD")

    if grad_output.layout != torch.sparse_coo or self_.layout != torch.sparse_coo:
        raise RuntimeError(
            "coalesce_backward expected sparse coordinate (coo) tensors but got "
            f"layout {grad_output.layout} / {self_.layout}"
        )
    if grad_output.shape != self_.shape:
        raise RuntimeError(
            "coalesce_backward expected grad_output and self_ to share shapes, got "
            f"{tuple(grad_output.shape)} vs {tuple(self_.shape)}"
        )
    if self_._values().dtype not in _VALUE_DTYPES:
        raise NotImplementedError(
            f"coalesce_backward does not support values dtype {self_._values().dtype}"
        )
    S = self_.sparse_dim()
    if S > _MAX_SPARSE_DIM:
        raise NotImplementedError(
            f"coalesce_backward supports at most {_MAX_SPARSE_DIM} sparse "
            f"dimensions but got {S}"
        )

    n = self_._nnz()
    m = grad_output._nnz()
    if n == 0 or m == 0:
        return sparse_coo_tensor(
            self_._indices().clone(),
            torch.zeros_like(self_._values()),
            self_.shape,
            is_coalesced=self_.is_coalesced(),
        )

    shape = tuple(int(d) for d in self_.shape)
    numel = 1
    for d in shape:
        numel *= d
    # Cumulative linearization strides: dim 0 moves in blocks of D1*D2*...,
    # the last dim elementwise; trailing padded dims move by 1 but are never
    # indexed (S <= _MAX_SPARSE_DIM).
    dims = list(shape) + [1] * (_MAX_SPARSE_DIM - len(shape))
    s0 = 1
    for d in dims[1:]:
        s0 *= d
    s1 = 1
    for d in dims[2:]:
        s1 *= d
    s2 = 1
    for d in dims[3:]:
        s2 *= d
    s3 = 1
    for d in dims[4:]:
        s3 *= d
    s4 = 1

    dev = self_.device
    idx = self_._indices()
    out_idx = grad_output._indices()
    out_vals = grad_output._values()
    in_vals = self_._values()

    grad_indices = idx.clone()
    grad_values = torch.empty_like(in_vals)

    with torch.cuda.device(dev):
        # Identity probe: duplicate-free input (m == n and equal index
        # tables) covers already-coalesced inputs and every duplicate-free
        # uncoalesced input; the backward is a pure value copy there.
        identity = False
        if m == n:
            flag = torch.zeros(1, dtype=torch.uint8, device=dev)
            _cb_identity_kernel[(1,)](
                idx.to(device=dev, dtype=torch.int64).contiguous(),
                out_idx.to(device=dev, dtype=torch.int64).contiguous(),
                n,
                S,
                flag,
                BLOCK=triton.next_power_of_2(int(n)),
                num_warps=4,
            )
            identity = bool(flag.item())

        if identity:
            grid = (triton.cdiv(n, _BLOCK),)
            _cb_copy_kernel[grid](
                out_vals.to(device=dev).contiguous(),
                grad_values,
                n,
                BLOCK=_BLOCK,
                num_warps=_BLOCK_WARPS,
            )
            return sparse_coo_tensor(
                grad_indices,
                grad_values,
                self_.shape,
                is_coalesced=self_.is_coalesced(),
            )

        # General path: key both index tables, then scatter by key match.
        keys_in = torch.empty(n, dtype=torch.int64, device=dev)
        keys_out = torch.empty(m, dtype=torch.int64, device=dev)
        _cb_keys_kernel[(triton.cdiv(max(n, m), _BLOCK),)](
            idx.to(device=dev, dtype=torch.int64).contiguous(),
            out_idx.to(device=dev, dtype=torch.int64).contiguous(),
            keys_in,
            keys_out,
            n,
            m,
            numel,
            s0,
            s1,
            s2,
            s3,
            s4,
            S=S,
            BLOCK=_BLOCK,
            num_warps=_BLOCK_WARPS,
        )
        if m <= _SORT_TILE:
            _cb_search_kernel[(triton.cdiv(n, _SORT_TILE),)](
                keys_in,
                in_vals.to(device=dev).contiguous(),
                keys_out,
                out_vals.to(device=dev).contiguous(),
                grad_values,
                n,
                m,
                MB=_SORT_TILE,
                BLOCK=_SORT_TILE,
                num_warps=4,
            )
        else:
            # Wide duplicate space (m beyond one register-resident tile):
            # ``searchsorted`` ranks every input key in the sorted
            # output key list with one launch, and the Triton gather turns
            # the rank into the restored value (misses stay zero).  No sort
            # is needed: keys_out is already ascending from the forward
            # coalesce.
            rank = searchsorted(keys_out, keys_in)
            hit = (rank < m) & (keys_out[rank.clamp(max=m - 1)] == keys_in)
            _cb_mvalues_kernel[(triton.cdiv(n, _BLOCK),)](
                rank.to(torch.int64),
                hit.to(torch.uint8),
                out_vals.to(device=dev).contiguous(),
                grad_values,
                n,
                BLOCK=_BLOCK,
                num_warps=_BLOCK_WARPS,
            )

    return sparse_coo_tensor(
        grad_indices, grad_values, self_.shape, is_coalesced=self_.is_coalesced()
    )


