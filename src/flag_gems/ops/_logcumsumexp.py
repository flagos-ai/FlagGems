# Rows longer than this are scanned in fixed-size chunks. The value is the
# largest block whose ``tl.associative_scan`` still compiles quickly (~1 s
# measured on H20); above it compile time grows steeply for no benefit, since a
# bigger block is not what makes the scan faster.
_MAX_SINGLE_BLOCK = 4096

# Elements per chunk on the chunked path. Each chunk scans one block of this
# width, and the inter-chunk carry is applied by a second pass.
_CHUNK_ELEMS = 4096

# The complex chunked path uses a narrower tile: the complex combine's compile
# time grows much more steeply with the block width than the real one's (~20 s
# at 1024 vs ~100 s at 4096, measured on H20), and the smaller tile is also
# slightly faster to run (0.0003 s vs 0.0006 s warm at N=16384). The real path
# keeps the wide tile because there the compile is ~1 s either way.
_CHUNK_ELEMS_COMPLEX = 1024


def _chunked_scan(
    src_view, dst_view, N, K, M, acc_is_fp64, inp, is_complex, real_input
):
    """Two-pass chunked scan for rows longer than ``_MAX_SINGLE_BLOCK``.

    Pass 1 scans every chunk independently and records each chunk's running
    total; pass 2 computes each chunk's carry-in from the totals of the chunks
    before it and shifts the chunk by that carry. ``logaddexp`` is associative,
    so this reproduces a whole-row scan exactly while keeping the compiled tile
    at ``_CHUNK_ELEMS`` for any row length.

    The scanned rows are the ``M*K`` pairs of the (M, N, K) factorization, so
    the grid's first axis is that product and each program derives its own row
    base from it.

    Complex inputs need the complex kernels: ``dst_view`` is then the ``(..., 2)``
    real view, and the real kernels would scan the interleaved re/im parts as
    independent real numbers instead of combining complex pairs.
    """
    rows = M * K
    chunk = min(
        _CHUNK_ELEMS_COMPLEX if is_complex else _CHUNK_ELEMS,
        triton.next_power_of_2(N),
    )
    num_chunks = triton.cdiv(N, chunk)
    total_dtype = torch.float64 if acc_is_fp64 else torch.float32
    chunk_total = torch.empty(rows, num_chunks, dtype=total_dtype, device=inp.device)

    warps = 8 if chunk > 2048 else 4
    with torch_device_fn.device(inp.device):
        if is_complex:
            # The imaginary totals are a separate buffer rather than a second
            # row of ``chunk_total``: the two are consumed as distinct kernel
            # arguments by the fan-in.
            chunk_total_i = torch.empty(
                rows, num_chunks, dtype=total_dtype, device=inp.device
            )
            _logcumsumexp_complex_chunk_kernel[(rows, num_chunks)](
                src_view,
                dst_view,
                chunk_total,
                chunk_total_i,
                N,
                K,
                num_chunks,
                CHUNK=chunk,
                IS_FP64=acc_is_fp64,
                REAL_INPUT=real_input,
                num_warps=warps,
            )
            _logcumsumexp_complex_fanin_kernel[(rows, num_chunks)](
                dst_view,
                chunk_total,
                chunk_total_i,
                N,
                K,
                num_chunks,
                CHUNK=chunk,
                IS_FP64=acc_is_fp64,
                num_warps=warps,
            )
            return
        _logcumsumexp_chunk_kernel[(rows, num_chunks)](
            src_view,
            dst_view,
            chunk_total,
            N,
            K,
            num_chunks,
            CHUNK=chunk,
            IS_FP64=acc_is_fp64,
            num_warps=warps,
        )
        _logcumsumexp_fanin_kernel[(rows, num_chunks)](
            dst_view,
            chunk_total,
            N,
            K,
            num_chunks,
            CHUNK=chunk,
            IS_FP64=acc_is_fp64,
            num_warps=warps,
        )


def _logcumsumexp_wrapper(inp, dim=1, dtype=None, out=None):
    if not isinstance(dim, int):
        raise TypeError(f"dim must be an int, but got {type(dim).__name__}")
    dim = _normalize_dim(inp, dim)

    result_dtype = _resolve_dtype(inp, dtype)
    if inp.is_complex() and not result_dtype.is_complex:
        raise RuntimeError(
            "logcumsumexp: cannot compute a complex input into the real dtype "
            f"{result_dtype}"
        )

    if out is None:
        out = torch.empty(inp.shape, dtype=result_dtype, device=inp.device)
    else:
        # ``out=`` contract: same device, same dtype, resized shape, and the
        # caller's tensor (not a replacement) comes back.
        if out.device != inp.device:
            raise RuntimeError(
                "Expected all tensors to be on the same device, but got self "
                f"is on {inp.device}, different from other tensors on {out.device}"
            )
        if out.dtype != result_dtype:
            raise RuntimeError(
                f"out must have dtype {result_dtype}, but got {out.dtype}"
            )
        if tuple(out.shape) != tuple(inp.shape):
            out.resize_(inp.shape)

    if inp.numel() == 0:
        return out

    # Factor the logical (M, N, K) scan geometry: the scanned axis is the
    # middle one, M is the product of the leading dims, K the trailing ones.
    ndim = max(inp.ndim, 1)
    shape = list(inp.shape) if inp.ndim else [1]
    M = 1
    for i in range(dim):
        M *= shape[i]
    N = shape[dim]
    K = 1
    for i in range(dim + 1, ndim):
        K *= shape[i]

    is_complex = out.is_complex()
    acc_is_fp64 = result_dtype in (torch.float64, torch.complex128)

    # A non-contiguous output cannot be addressed linearly, so compute into a
    # contiguous scratch buffer and copy back; the caller's layout and buffer
    # are preserved.
    if out.is_contiguous():
        target = out
        scratch = None
    else:
        target = torch.empty(inp.shape, dtype=result_dtype, device=inp.device)
        scratch = out

    src_view = _real_view(inp)
    dst_view = _real_view(target)

    # A single program would have to scan the whole row, and
    # ``tl.associative_scan`` compile time grows steeply with the block size
    # (measured: ~4 s at N=8192, ~24 s at 32768, ~5 min at 131072), so long rows
    # are split into fixed-size chunks instead -- the row length then only
    # selects the grid, not the compiled tile.
    if N > _MAX_SINGLE_BLOCK:
        _chunked_scan(
            src_view,
            dst_view,
            N,
            K,
            M,
            acc_is_fp64,
            inp,
            is_complex,
            not inp.is_complex(),
        )
    else:
        BLOCK_SIZE = triton.next_power_of_2(N)
        num_warps = 8 if BLOCK_SIZE > 2048 else 4
        grid = (M, K)
        with torch_device_fn.device(inp.device):
            if is_complex:
                _logcumsumexp_complex_kernel[grid](
                    src_view,
                    dst_view,
                    N,
                    K,
                    BLOCK_SIZE,
                    acc_is_fp64,
                    not inp.is_complex(),
                    num_warps=num_warps,
                )
            else:
                _logcumsumexp_kernel[grid](
                    src_view,
                    dst_view,
                    N,
                    K,
                    BLOCK_SIZE,
                    acc_is_fp64,
                    num_warps=num_warps,
                )

    if scratch is not None:
        scratch.copy_(target)
        return scratch
    return out


def _logcumsumexp(inp, dim=1, *, dtype=None):
    logger.debug("GEMS _LOGCUMSUMEXP")
    return _logcumsumexp_wrapper(inp, dim, dtype)


def _logcumsumexp_out(inp, dim=1, *, dtype=None, out):
    logger.debug("GEMS _LOGCUMSUMEXP_OUT")
    return _logcumsumexp_wrapper(inp, dim, dtype, out)
