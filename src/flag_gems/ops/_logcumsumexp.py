def _logaddexp(a, b):
    """Associative ``logaddexp`` on real scalars.

    Mirrors ``_log_add_exp_helper`` from
    ``aten/src/ATen/native/cuda/LogcumsumexpKernel.cu``.  Because the shift is
    taken against the *pairwise* maximum instead of the maximum of the whole
    row, prefixes far below the row maximum stay accurate (no underflow to
    ``-inf``), and the ``min == max`` special case reproduces ATen's handling
    of all-``+-inf`` inputs instead of producing NaN.
    """
    lo = tl.minimum(a, b)
    hi = tl.maximum(a, b)
    # ATen returns its first argument verbatim when min == max is not finite
    # (both +inf or both -inf); log1p(inf - inf) would otherwise give NaN.
    merged = tl_extra_shim.log1p(tl.exp(lo - hi)) + hi
    both_inf = (lo == hi) & (tl.abs(lo) == float("inf"))
    res = tl.where(both_inf, a, merged)
    # fmin/fmax ignore NaN operands, so NaN has to be made infectious
    # explicitly (ATen propagates it through min/max ordering).
    return tl.where((a != a) | (b != b), float("nan"), res)


