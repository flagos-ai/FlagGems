@triton.jit
def _logaddexp(a, b):
    """Associative ``logaddexp`` on real scalars.

    Mirrors ``_log_add_exp_helper`` from
    ``aten/src/ATen/native/cuda/LogcumsumexpKernel.cu``.  Because the shift is
    taken against the *pairwise* maximum instead of the maximum of the whole
    row, prefixes far below the row maximum stay accurate (no underflow to
    ``-inf``), and the ``min == max`` special case reproduces ATen's handling
    of all-``+-inf`` inputs instead of producing NaN.
    """
    lo = tl.minimum(a, b)
    hi = tl.maximum(a, b)
    # ATen returns its first argument verbatim when min == max is not finite
    # (both +inf or both -inf); log1p(inf - inf) would otherwise give NaN.
    merged = tl_extra_shim.log1p(tl.exp(lo - hi)) + hi
    both_inf = (lo == hi) & (tl.abs(lo) == float("inf"))
    res = tl.where(both_inf, a, merged)
    # fmin/fmax ignore NaN operands, so NaN has to be made infectious
    # explicitly (ATen propagates it through min/max ordering).
    return tl.where((a != a) | (b != b), float("nan"), res)


@triton.jit
def _complex_log1p(x, y):
    """``c10::log1p`` for a complex number (CUDA path of c10/util/complex_math.h).

    Evaluates ``log(r) + i * atan2(y, x + 1)`` with ``r = hypot(1 + x, y)``,
    using ``log1p`` on the squared modulus for small ``|z|`` so that the
    result stays accurate near the origin.
    """
    zabs = tl_extra_shim.hypot(x, y)
    theta = tl_extra_shim.atan2(y, x + 1.0)
    r = x * (2.0 + x) + y * y
    small = tl.where(r == 0.0, x, 0.5 * tl_extra_shim.log1p(r))
    big = tl_extra_shim.log(tl_extra_shim.hypot(x + 1.0, y))
    return tl.where(zabs < 0.5, small, big), theta


@triton.jit
def _complex_exp(x, y):
    """``_fast_build_exp`` from ATen: complex exp for finite z = x + iy."""
    exp_abs = tl.exp(x)
    return exp_abs * tl.cos(y), exp_abs * tl.sin(y)


@triton.jit
def _complex_exp_pos_inf(y):
    """``_fast_build_exp_inf`` from ATen: real part is +inf, only angle matters.

    The axes are forced to zero so that ``inf * 0`` does not turn the exact
    +/-i directions into NaN.
    """
    cos_v = tl.cos(y)
    sin_v = tl.sin(y)
    real = tl.where(cos_v == 0.0, 0.0, float("inf") * cos_v)
    imag = tl.where(sin_v == 0.0, 0.0, float("inf") * sin_v)
    return real, imag


@triton.jit
def _complex_logaddexp(ar, ai, br, bi):
    """Associative complex ``logaddexp``; ATen's complex ``_log_add_exp_helper``.

    The operands are ordered by real part like ATen's
    ``_logcumsumexp_minmax`` (NaNs last), then combined as
    ``hi + log1p(exp(lo - hi))`` with ATen's dedicated +-inf branches so that
    infinite and NaN inputs keep their exact parity.
    """
    a_nan = (ar != ar) | (ai != ai)
    b_nan = (br != br) | (bi != bi)
    a_first = ar < br
    lo_r = tl.where(b_nan, br, tl.where(a_nan, ar, tl.where(a_first, ar, br)))
    lo_i = tl.where(b_nan, bi, tl.where(a_nan, ai, tl.where(a_first, ai, bi)))
    hi_r = tl.where(b_nan, br, tl.where(a_nan, ar, tl.where(a_first, br, ar)))
    hi_i = tl.where(b_nan, bi, tl.where(a_nan, ai, tl.where(a_first, bi, ai)))

    # Infectious NaNs collapse to a quiet NaN pair.
    nan_out = (lo_r != lo_r) | (lo_i != lo_i)

    # Both real parts are the same non-finite value.
    both_inf = (lo_r == hi_r) & tl_extra_shim.isinf(lo_r)
    neg_inf = both_inf & (lo_r < 0.0)

    # Generic branch.
    e_r, e_i = _complex_exp(lo_r - hi_r, lo_i - hi_i)
    l_r, l_i = _complex_log1p(e_r, e_i)
    gen_r = l_r + hi_r
    gen_i = l_i + hi_i

    # +inf branch: log1p(exp(lo) + exp(hi) - 1) with infinite-modulus
    # exponentials, which is how ATen avoids NaN here.
    e1_r, e1_i = _complex_exp_pos_inf(lo_i)
    e2_r, e2_i = _complex_exp_pos_inf(hi_i)
    p_r, p_i = _complex_log1p(e1_r + e2_r - 1.0, e1_i + e2_i)

    out_r = tl.where(
        nan_out, float("nan"), tl.where(neg_inf, lo_r, tl.where(both_inf, p_r, gen_r))
    )
    out_i = tl.where(
        nan_out, float("nan"), tl.where(neg_inf, lo_i, tl.where(both_inf, p_i, gen_i))
    )
    return out_r, out_i


