"""First-order gradients of ``torch.dot``.

``torch.ops.aten.dot_backward`` does not exist in this Torch build: ATen derives
the gradients through the ``DotBackward0`` autograd node, which evaluates

    grad_self = grad * other
    grad_other = grad * self

Both are single elementwise multiplies.  For the low-precision floating
dtypes ATen runs the multiply in fp32 opmath and materialises the result
back into the storage dtype, which is what the kernel below reproduces;
the formulas are bit-exact against native autograd on CUDA.

This module exposes

* ``dot_backward(grad_output, self, tensor)`` -- the explicit Triton entry
  point returning ``(grad_self, grad_tensor)``, and
* ``DotFunction`` -- an ``autograd.Function`` that pairs the FlagGems ``dot``
  forward with this backward kernel, for callers that want the whole
  autograd chain in Triton.

Because there is no standalone ``aten::dot_backward`` schema to register a
kernel against, the surface here is the explicit function plus the bridge
(same pattern as ``div_backward`` / ``digamma_backward``).
"""

import logging

import torch
import triton
import triton.language as tl

from flag_gems.runtime import torch_device_fn
from flag_gems.utils import libentry

logger = logging.getLogger(__name__)

# 1024 elements per program: this is a pure elementwise read 3 / write 2 kernel,
# so a wide block amortises the launch overhead.
_BLOCK = 1024
_NUM_WARPS = 4


@libentry()
@triton.jit
def _dot_backward_kernel(
    grad_ptr,
    self_ptr,
    other_ptr,
    grad_self_ptr,
    grad_other_ptr,
    n_elements,
    GRAD_SCALAR: tl.constexpr,
    IS64: tl.constexpr,
    BLOCK: tl.constexpr,
):
    pid = tl.program_id(axis=0)
    offsets = pid * BLOCK + tl.arange(0, BLOCK)
    mask = offsets < n_elements

    # ``dot`` returns a 0-dim tensor, so the upstream gradient is normally a
    # scalar.  Loading it once avoids reading ``grad_ptr + offsets`` past the
    # single element the caller provided.
    if GRAD_SCALAR:
        grad = tl.load(grad_ptr)
        x = tl.load(self_ptr + offsets, mask=mask)
        y = tl.load(other_ptr + offsets, mask=mask)
    else:
        grad = tl.load(grad_ptr + offsets, mask=mask)
        x = tl.load(self_ptr + offsets, mask=mask)
        y = tl.load(other_ptr + offsets, mask=mask)

    if IS64:
        # fp64 needs no opmath upcast: multiplying in the storage dtype is
        # bit-identical to ATen's ``DotBackward0``.
        grad_self = grad * y
        grad_other = grad * x
    else:
        # fp32 and lower: ATen runs the multiply in fp32 opmath and materialises
        # the result back into the storage dtype.
        dt = grad_ptr.dtype.element_ty
        g32 = grad.to(tl.float32)
        x32 = x.to(tl.float32)
        y32 = y.to(tl.float32)

        grad_self = (g32 * y32).to(dt)
        grad_other = (g32 * x32).to(dt)

    tl.store(grad_self_ptr + offsets, grad_self, mask=mask)
    tl.store(grad_other_ptr + offsets, grad_other, mask=mask)


def _dot_backward_impl(grad_output: torch.Tensor, x: torch.Tensor, y: torch.Tensor):
    """Equal-shape contiguous Triton path."""
    grad_contig = grad_output.contiguous()
    x_contig = x.contiguous()
    y_contig = y.contiguous()

    grad_x = torch.empty(x.shape, dtype=x.dtype, device=x.device)
    grad_y = torch.empty(y.shape, dtype=y.dtype, device=y.device)

    n_elements = x_contig.numel()
    if n_elements == 0:
        return grad_x, grad_y

    # ``dot`` produces a 0-dim output, so the upstream gradient is typically a
    # scalar; if a caller passes a full-shape tensor, read it elementwise.
    grad_scalar = grad_contig.numel() == 1 and grad_contig.dim() <= 1

    # 1024 elements per program with 4 warps
    block = _BLOCK
    grid = (triton.cdiv(n_elements, block),)
    with torch_device_fn.device(x.device):
        _dot_backward_kernel[grid](
            grad_contig,
            x_contig,
            y_contig,
            grad_x,
            grad_y,
            n_elements,
            GRAD_SCALAR=grad_scalar,
            IS64=(x.dtype == torch.float64),
            BLOCK=block,
            num_warps=_NUM_WARPS,
        )
    return grad_x, grad_y


def dot_backward(
    grad_output: torch.Tensor,
    self_: torch.Tensor,
    tensor: torch.Tensor,
):
    """Gradients of ``self_ . tensor`` (1-D dot product).

    Args:
        grad_output: Upstream gradient, a scalar for the 1-D dot product.
        self_: First forward operand.
        tensor: Second forward operand.

    Returns:
        Tuple ``(grad_self, grad_tensor)`` where
        ``grad_self = grad_output * tensor`` and
        ``grad_tensor = grad_output * self_``.
    """
    logger.debug("GEMS DOT_BACKWARD")
    if not isinstance(grad_output, torch.Tensor):
        raise TypeError("dot_backward expects grad_output to be a torch.Tensor")
    if not isinstance(self_, torch.Tensor) or not isinstance(tensor, torch.Tensor):
        raise TypeError("dot_backward expects tensor self_ and tensor arguments")

    if self_.shape != tensor.shape:
        # Broadcast operands: autograd reduces the upstream gradient to the
        # output shape and sums it back down per operand.  Compose the same
        # ATen formula here; a fused broadcast kernel is not worth a second
        # code path for an elementwise op.
        grad_x, grad_y = _broadcast_fallback(grad_output, self_, tensor)
        return grad_x, grad_y

    return _dot_backward_impl(grad_output, self_, tensor)


def _broadcast_fallback(grad_output, x, y):
    """Broadcast fallback: ATen's exact formula plus the reduction."""
    out_shape = torch.broadcast_shapes(x.shape, y.shape)  # allow-torch-compute
    grad = grad_output
    if grad.shape != out_shape:
        grad = grad.expand(out_shape)
    x_full = x.expand(out_shape)
    y_full = y.expand(out_shape)
    grad_x = grad * y_full  # allow-torch-compute
    grad_y = grad * x_full  # allow-torch-compute
    grad_x = _reduce_broadcast(grad_x, out_shape, x.shape)
    grad_y = _reduce_broadcast(grad_y, out_shape, y.shape)
    return grad_x.to(x.dtype), grad_y.to(y.dtype)


def _reduce_broadcast(grad: torch.Tensor, full_shape, target_shape):
    """Sum ``grad`` over the axes an operand broadcast away."""
    if tuple(full_shape) == tuple(target_shape):
        return grad
    reduce_dims = []
    padded = (1,) * (len(full_shape) - len(target_shape)) + tuple(target_shape)
    for dim, (full, tgt) in enumerate(zip(full_shape, padded)):
        if tgt == 1 and full != 1:
            reduce_dims.append(dim)
    if reduce_dims:
        grad = torch.sum(grad, dim=reduce_dims, keepdim=True)  # allow-torch-compute
    return grad.reshape(target_shape)


