def _zero_fill(out):
    buf = out.view(_fill_view(out.element_size()))
    count = buf.numel()
    if count:
        grid = (triton.cdiv(count, _BLOCK_FILL),)
        _diagflat_zero_kernel[grid](
            buf,
            count,
            BLOCK=_BLOCK_FILL,
            WIDE=(count + 2 * _BLOCK_FILL) > _INT32_MAX,
            num_warps=4,
        )


def _fill_with_diagonal(out, src, n, m, base, sstride):
    """Single-launch fill + diagonal write for the real-dtype large-output path.

    Returns False when the per-span diagonal count would exceed ``MAX_DIAG``
    (only for very small ``m``), in which case the caller falls back to the
    separate scatter launch.
    """
    stride = m + 1
    if (m + 1 + _BLOCK_FILL) // stride + 1 > _BLOCK_DIAG:
        return False
    if out.numel() > _INT32_MAX - 2 * _BLOCK_FILL:
        return False

    buf = out.view(_fill_view(out.element_size()))
    count = buf.numel()
    grid = (triton.cdiv(count, _BLOCK_FILL),)
    _diagflat_fill_diag_kernel[grid](
        buf,
        out,
        src,
        count,
        m,
        base,
        sstride,
        n,
        BLOCK=_BLOCK_FILL,
        WIDE=False,
        MAX_DIAG=_BLOCK_DIAG,
        num_warps=4,
    )
    return True


def _diagonal_params(out, k):
    """``(base, jmul, real_dtype)`` for the offset-k diagonal of ``out``.

    For real dtypes the target address is ``i * (m + 1) + base`` with
    ``jmul == 0``.  Complex tensors are viewed as their real component type with
    a doubled inner extent, giving ``i * (m + 1) + base - (i & 1) * m``.
    """
    m = out.shape[0]
    if out.is_complex():
        base = 2 * k if k >= 0 else 2 * (-k) * m
        return base, m, _COMPLEX_REAL[out.dtype]
    base = k if k >= 0 else (-k) * m
    return base, 0, None


def _fused_tile(self, out, k, real_dtype):
    """Single-launch path; returns False when the tiled kernel cannot be used.

    Only small outputs take this path (see the ``_FUSE_MAX_ELEMS`` comment).
    The clamped origin needs ``BR <= m`` and ``BC <= m``, so for small ``m`` the
    tile side shrinks to the largest power of two that still fits.
    """
    m = out.shape[0]
    if real_dtype is not None:
        return False
    if k < 0 or k >= m:
        return False
    if m * m > _FUSE_MAX_ELEMS:
        return False
    if not self.is_contiguous():
        return False
    br = _FUSE_BR if m >= _FUSE_BR else (1 << (m.bit_length() - 1))
    bc = _FUSE_BC if m >= _FUSE_BC else (1 << (m.bit_length() - 1))
    src = self.reshape(-1)
    grid = (triton.cdiv(m, br), triton.cdiv(m, bc))
    _diagflat_tile_kernel[grid](
        src,
        out,
        m,
        k,
        src.stride(0),
        BR=br,
        BC=bc,
        num_warps=4,
    )
    return True


def _forward(self, k):
    n = self.numel()
    m = n + (k if k >= 0 else -k)
    out = torch.empty((m, m), dtype=self.dtype, device=self.device)
    if out.numel() == 0:
        return out

    base, jmul, real_dtype = _diagonal_params(out, k)

    if _fused_tile(self, out, k, real_dtype):
        return out

    if real_dtype is None and n > 0:
        flat = self.reshape(-1)
        base, jmul, _ = _diagonal_params(out, k)
        if _fill_with_diagonal(out, flat, n, m, base, flat.stride(0)):
            return out

    _zero_fill(out)

    if n > 0:
        flat = self.reshape(-1)
        base, jmul, real_dtype = _diagonal_params(out, k)
        if real_dtype is not None:
            if not flat.is_contiguous():
                raise NotImplementedError(
                    "diagflat: non-contiguous complex input is not supported"
                )
            src = flat.view(real_dtype)
            dst = out.view(real_dtype)
            count = 2 * n
            sstride = 1
        else:
            src = flat
            dst = out
            count = n
            sstride = flat.stride(0)
        grid = (triton.cdiv(count, _BLOCK_SCATTER),)
        _diagflat_scatter_kernel[grid](
            src,
            dst,
            count,
            sstride,
            m + 1,
            base,
            jmul,
            BLOCK=_BLOCK_SCATTER,
            num_warps=4,
        )
    return out


def _backward(grad_out, shape, k):
    m = grad_out.shape[0]
    n = m - (k if k >= 0 else -k)
    grad_in = torch.empty(shape, dtype=grad_out.dtype, device=grad_out.device)
    if n <= 0 or grad_in.numel() == 0:
        return grad_in

    if grad_out.is_complex():
        real_dtype = _COMPLEX_REAL[grad_out.dtype]
        src = grad_out.view(real_dtype)
        dst = grad_in.view(real_dtype)
        count = 2 * n
        sstride = m + 1
        base = 2 * k if k >= 0 else 2 * (-k) * m
        jmul = m
    else:
        src = grad_out
        dst = grad_in
        count = n
        sstride = m + 1
        base = k if k >= 0 else (-k) * m
        jmul = 0

    grid = (triton.cdiv(count, _BLOCK_SCATTER),)
    _diagflat_gather_kernel[grid](
        src, dst, count, sstride, base, jmul, BLOCK=_BLOCK_SCATTER, num_warps=4
    )
    return grad_in


