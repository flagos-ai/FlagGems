"""Copy variant of the forward-mode AD dual constructor.

``aten::_make_dual_copy(Tensor primal, Tensor tangent, int level) -> Tensor``
is the copy companion of ``_make_dual``: instead of aliasing ``primal`` it
returns an independent tensor holding ``primal``'s values. Measured on the
target build, the native kernel is an inference-mode-only path
(``AutogradComposite.cpp`` asserts ``InferenceMode::is_enabled()`` and that both
inputs are inference tensors), and the result does not share storage with
``primal`` while comparing equal to it.

The dual metadata itself cannot be produced by a device kernel, so the device
work here is the copy: a flat streaming kernel for contiguous inputs and a
gather that walks the input's own shape/stride metadata otherwise. Both write
every element of the returned tensor.
"""

