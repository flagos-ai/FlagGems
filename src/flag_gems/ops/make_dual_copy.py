def _copy_kernel(src_ptr, dst_ptr, n_elements, BLOCK: tl.constexpr):
    pid = tl.program_id(axis=0)
    offsets = pid * BLOCK + tl.arange(0, BLOCK)
    mask = offsets < n_elements
    vals = tl.load(src_ptr + offsets, mask=mask, other=0)
    tl.store(dst_ptr + offsets, vals, mask=mask)


@triton.jit
def _copy_strided_kernel(
    src_ptr,
    dst_ptr,
    divs_ptr,
    shape_ptr,
    src_stride_ptr,
    dst_stride_ptr,
    n_elements,
    NDIM: tl.constexpr,
    BLOCK: tl.constexpr,
):
    pid = tl.program_id(axis=0)
    offsets = pid * BLOCK + tl.arange(0, BLOCK)
    mask = offsets < n_elements
    idx = offsets.to(tl.int64)
    src_off = tl.zeros([BLOCK], dtype=tl.int64)
    dst_off = tl.zeros([BLOCK], dtype=tl.int64)
    for d in tl.static_range(NDIM):
        div = tl.load(divs_ptr + d)
        sh = tl.load(shape_ptr + d)
        coord = (idx // div) % sh
        src_off += coord * tl.load(src_stride_ptr + d)
        dst_off += coord * tl.load(dst_stride_ptr + d)
    vals = tl.load(src_ptr + src_off, mask=mask, other=0)
    tl.store(dst_ptr + dst_off, vals, mask=mask)


def _as_copyable(t):
    """Reinterpret complex tensors as integer tensors so Triton can address them.

    Triton pointers cannot carry a complex element type. Each complex dtype has
    an integer type of the same element width, so the copy stays bit-exact.
    ``complex128.view(torch.int64)`` doubles the last dimension; that is
    harmless for the flat path, which treats the view as one contiguous buffer.
    """
    if t.dtype == torch.complex32:
        return t.view(torch.int32)
    if t.dtype == torch.complex64:
        return t.view(torch.int64)
    if t.dtype == torch.complex128:
        return t.view(torch.int64)
    return t


def _is_complex128(t):
    return t.dtype == torch.complex128


def _strided_copy(src, dst):
    s = _as_copyable(src)
    d = _as_copyable(dst)
    shape = s.shape
    ndim = len(shape)
    divs = [1] * ndim
    acc = 1
    for i in range(ndim - 1, -1, -1):
        divs[i] = acc
        acc *= shape[i]
    dev = s.device
    div_t = torch.tensor(divs, dtype=torch.int64, device=dev)
    shp_t = torch.tensor(shape, dtype=torch.int64, device=dev)
    ss_t = torch.tensor(s.stride(), dtype=torch.int64, device=dev)
    ds_t = torch.tensor(d.stride(), dtype=torch.int64, device=dev)
    n = s.numel()
    block = 512
    grid = (triton.cdiv(n, block),)
    _copy_strided_kernel[grid](
        s, d, div_t, shp_t, ss_t, ds_t, n, NDIM=ndim, BLOCK=block
    )


def _flat_config(numel):
    if numel <= 131072:
        return 2048, 4
    return 8192, 8


def _flat_copy(src, dst):
    s = _as_copyable(src)
    d = _as_copyable(dst)
    n = s.numel()
    block, num_warps = _flat_config(n)
    grid = (triton.cdiv(n, block),)
    _copy_kernel[grid](s, d, n, BLOCK=block, num_warps=num_warps)


def _make_dual_copy(
    primal: torch.Tensor, tangent: torch.Tensor, level: int
) -> torch.Tensor:
    """Return an independent copy of ``primal`` carrying dual metadata.

    Args:
        primal (torch.Tensor): Primal tensor to copy.
        tangent (torch.Tensor): Tangent tensor. Part of the aten signature; the
            returned values come from ``primal`` alone.
        level (int): Forward-AD level.

    Returns:
        torch.Tensor: A tensor with the same shape and values as ``primal``.
    """
    logger.debug("GEMS MAKE_DUAL_COPY")
    out = torch.empty_like(primal)
    n = primal.numel()
    if n == 0:
        return out
    if primal.is_contiguous():
        _flat_copy(primal, out)
    elif _is_complex128(primal):
        # complex128 has no 128-bit integer view, so its strides cannot be
        # expressed for the gather kernel; native strided copy is used instead.
        out.copy_(primal)
    else:
        _strided_copy(primal, out)
    return out


