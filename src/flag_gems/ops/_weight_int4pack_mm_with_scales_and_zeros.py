# Conventions for this operator (kept self-consistent across kernel, test, benchmark):
#
# 1. mat2 shape: (N, K//2) dtype=uint8
#    - N = output channels, K = input features (must be even).
#    - Each byte packs two int4 values: low nibble (bits 0-3) for even column 2*j,
#      high nibble (bits 4-7) for odd column (2*j+1).
#    - This is the same byte-pair packing used by _convert_weight_to_int4pack.
#
# 2. int4 value interpretation: unsigned 0..15.
#    Dequant: w = (q - zero) * scale
#    where q ∈ [0, 15] is the unsigned 4-bit value.
#
# 3. qScale shape: (G, N) where G = K // qGroupSize, dtype = same as A.
#    qZeros shape: (G, N), dtype = same as A.
#    - Grouping is along the K dimension: features k in range
#      [g*qGroupSize, (g+1)*qGroupSize) share scale/zero qScale[g, n] / qZeros[g, n]
#      for output channel n.
#    - qGroupSize must divide K evenly.
#
# 4. Output shape: (M, N) = matmul(A, W_deq) where A is (M, K) and
#    W_deq is the dequantized weight matrix of shape (K, N).
#    Output dtype matches A's dtype.
# =============================================================================


