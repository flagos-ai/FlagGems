@triton.jit
def _round(value, ROUND_DTYPE: tl.constexpr, ACC_DTYPE: tl.constexpr):
    """Round an accumulator through the input dtype, as an eager op would."""
    if ROUND_DTYPE == ACC_DTYPE:
        return value
    else:
        return value.to(ROUND_DTYPE).to(ACC_DTYPE)


