    offs_n = tl.program_id(1) * BLOCK_H + tl.arange(0, BLOCK_H)
    b_mask = offs_b < B
    n_mask = offs_n < H

    # Gate order in the packed weight / bias layout is reset, update, new.
    row_r = offs_n
    row_z = offs_n + H
    row_n = offs_n + 2 * H

