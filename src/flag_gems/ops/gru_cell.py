def gru_cell(input, hx, w_ih, w_hh, b_ih=None, b_hh=None):
    """Single GRU cell step.

    Args:
        input: Input of shape ``(batch, input_size)``.
        hx: Hidden state of shape ``(batch, hidden_size)``.
        w_ih: Input-hidden weights of shape ``(3 * hidden_size, input_size)``.
        w_hh: Hidden-hidden weights of shape ``(3 * hidden_size, hidden_size)``.
        b_ih: Optional input-hidden bias of shape ``(3 * hidden_size,)``.
        b_hh: Optional hidden-hidden bias of shape ``(3 * hidden_size,)``.

    Returns:
        The new hidden state of shape ``(batch, hidden_size)``.
    """
    logger.debug("GEMS GRU_CELL")
    _check_cell_args("gru_cell", input, hx, w_ih, w_hh, b_ih, b_hh, 3)

    batch, input_size = input.shape
    hidden_size = w_hh.shape[1]
    out = torch.empty((batch, hidden_size), dtype=input.dtype, device=input.device)
    if batch == 0 or hidden_size == 0:
        return out

    block_b = _block(batch, 16)
    block_h = _block(hidden_size, 32)
    block_k = _block(max(input_size, hidden_size), 64)

    _gru_cell_kernel[(triton.cdiv(batch, block_b), triton.cdiv(hidden_size, block_h))](
        input,
        hx,
        w_ih,
        w_hh,
        b_ih if b_ih is not None else input,
        b_hh if b_hh is not None else input,
        out,
        batch,
        input_size,
        hidden_size,
        input.stride(0),
        input.stride(1),
        hx.stride(0),
        hx.stride(1),
        w_ih.stride(0),
        w_ih.stride(1),
        w_hh.stride(0),
        w_hh.stride(1),
        out.stride(0),
        out.stride(1),
        HAS_BIH=b_ih is not None,
        HAS_BHH=b_hh is not None,
        ACC_DTYPE=_ACC_DTYPE[input.dtype],
        ROUND_DTYPE=_ROUND_DTYPE[input.dtype],
        BLOCK_B=block_b,
        BLOCK_H=block_h,
        BLOCK_K=block_k,
        num_warps=4,
        num_stages=3,
    )
    return out
