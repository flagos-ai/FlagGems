def batch_norm_no_update_backward_kernel(
    grad_output_pointer,
    input_pointer,
    running_mean_pointer,
    running_var_pointer,
    weight_pointer,
    input_grad_pointer,
    weight_grad_pointer,
    bias_grad_pointer,
    batch_dim,
    spatial_dim,
    chunk_size,
    nchunk,
    grad_output_batch_stride,
    grad_output_feat_stride,
    grad_output_spatial_stride,
    input_batch_stride,
    input_feat_stride,
    input_spatial_stride,
    input_grad_batch_stride,
    input_grad_feat_stride,
    input_grad_spatial_stride,
    eps,
    input_grad_mask: tl.constexpr,
    weight_grad_mask: tl.constexpr,
    bias_grad_mask: tl.constexpr,
    finalize: tl.constexpr,
    BLOCK_M: tl.constexpr,
    BLOCK_N: tl.constexpr,
):
    """Eval-mode batch normalization backward.

    ``aten::_batch_norm_no_update`` has no independent backward schema: the
    engine derives its gradients from ``native_batch_norm_backward`` with
    ``train=False`` and empty saved statistics, so the running estimates are the
    normalisation statistics and the gradients are

        grad_input  = grad_output * weight * rsqrt(running_var + eps)
        grad_weight = sum_{B,S} grad_output * (input - running_mean) * invstd
        grad_bias   = sum_{B,S} grad_output

    One program owns one feature channel and reduces over the whole
    (batch, spatial) plane, so the per-channel reductions complete in a single
    launch without a scratch buffer or finalize pass.
    """
    feat_pid = tl.program_id(axis=0)
    chunk_pid = tl.program_id(axis=1)

    running_mean = tl.load(feat_pid + running_mean_pointer).to(tl.float32)
    inv_std = 1.0 / tl.sqrt(
        tl.load(feat_pid + running_var_pointer).to(tl.float32) + eps
    )
    if weight_pointer:
        weight = tl.load(feat_pid + weight_pointer).to(tl.float32)
        scale = weight * inv_std
    else:
        scale = inv_std

    chunk_start = chunk_pid * chunk_size
    chunk_end = tl.minimum(chunk_start + chunk_size, spatial_dim)
    chunk_len = chunk_end - chunk_start

    # Stream the assigned spatial chunk once: accumulate the per-channel
    # reduction terms used by the weight and bias gradients, and store the
    # input gradient in the same walk. Eval mode normalises with fixed
    # statistics, so the input gradient is the plain
    # ``grad_output * weight * inv_std`` form without the training-mode
    # correction term; it has no dependency on the completed reductions.
    # term1 = sum((input - mean) * inv_std * grad_output)
    # term2 = sum(grad_output)
    term1 = tl.zeros([BLOCK_M, BLOCK_N], dtype=tl.float32)
    term2 = tl.zeros([BLOCK_M, BLOCK_N], dtype=tl.float32)

    for m_step in range(0, tl.cdiv(batch_dim, BLOCK_M)):
        for n_step in range(0, tl.cdiv(chunk_len, BLOCK_N)):
            batch_offset = m_step * BLOCK_M + tl.arange(0, BLOCK_M)
            batch_mask = batch_offset < batch_dim

            spatial_offset = chunk_start + n_step * BLOCK_N + tl.arange(0, BLOCK_N)
            spatial_mask = spatial_offset < chunk_end

            mask = batch_mask[:, None] & spatial_mask[None, :]

            curr_grad_output_pointer = (
                grad_output_pointer
                + grad_output_feat_stride * feat_pid
                + grad_output_batch_stride * batch_offset[:, None]
                + grad_output_spatial_stride * spatial_offset[None, :]
            )
            curr_input_pointer = (
                input_pointer
                + input_feat_stride * feat_pid
                + input_batch_stride * batch_offset[:, None]
                + input_spatial_stride * spatial_offset[None, :]
            )
            curr_input_grad_pointer = (
                input_grad_pointer
                + input_grad_feat_stride * feat_pid
                + input_grad_batch_stride * batch_offset[:, None]
                + input_grad_spatial_stride * spatial_offset[None, :]
            )

            curr_input = tl.load(curr_input_pointer, mask=mask).to(tl.float32)
            curr_pre_lin = (curr_input - running_mean) * inv_std
            curr_grad_output = tl.load(curr_grad_output_pointer, mask=mask).to(
                tl.float32
            )

            term1 += curr_pre_lin * curr_grad_output
            term2 += curr_grad_output

            if input_grad_mask:
                tl.store(
                    curr_input_grad_pointer,
                    curr_grad_output * scale,
                    mask=mask,
                )

    term1 = tl.sum(term1)
    term2 = tl.sum(term2)

    if finalize:
        # Single chunk: the per-channel reduction is complete. ``term1`` is the
        # raw sum of ``grad_output * (input - mean) * inv_std``, which already
        # carries the inv_std factor, so only the output cast remains.
        if weight_grad_mask:
            tl.store(
                feat_pid + weight_grad_pointer,
                term1.to(weight_grad_pointer.dtype.element_ty),
            )
        if bias_grad_mask:
            tl.store(
                feat_pid + bias_grad_pointer,
                term2.to(bias_grad_pointer.dtype.element_ty),
            )
    else:
        # Chunked: park the raw fp64 partials in the scratch row; the finalize
        # kernel folds them and casts exactly once per channel.
        if weight_grad_mask:
            tl.store(
                feat_pid * nchunk + chunk_pid + weight_grad_pointer,
                term1.to(tl.float64),
            )
        if bias_grad_mask:
            tl.store(
                feat_pid * nchunk + chunk_pid + bias_grad_pointer, term2.to(tl.float64)
            )


@triton.jit
def batch_norm_no_update_finalize_kernel(
    weight_partial_pointer,
    bias_partial_pointer,
    weight_grad_pointer,
    bias_grad_pointer,
    nchunk,
    finalize_mask: tl.constexpr,
    bias_finalize_mask: tl.constexpr,
    BLOCK: tl.constexpr,
):
    """Fold the fp64 per-chunk partials of one channel, then cast exactly once."""
    feat_pid = tl.program_id(axis=0)

    offs = tl.arange(0, BLOCK)
    part_mask = offs < nchunk

    if finalize_mask:
        acc_w = tl.load(
            feat_pid * nchunk + offs + weight_partial_pointer, mask=part_mask, other=0.0
        )
        tl.store(
            feat_pid + weight_grad_pointer,
            tl.sum(acc_w).to(weight_grad_pointer.dtype.element_ty),
        )
    if bias_finalize_mask:
        acc_b = tl.load(
            feat_pid * nchunk + offs + bias_partial_pointer, mask=part_mask, other=0.0
        )
        tl.store(
            feat_pid + bias_grad_pointer,
            tl.sum(acc_b).to(bias_grad_pointer.dtype.element_ty),
        )


def batch_norm_no_update_backward(
    grad_output: Tensor,
    input: Tensor,
    weight=None,
    running_mean=None,
    running_var=None,
    eps: float = 1e-05,
    output_mask=(True, True, True),
):
    """Return selected input, weight and bias gradients of eval-mode batch norm.

    Mirrors the gradients the autograd engine produces for
    ``aten::_batch_norm_no_update``: the running estimates act as the
    normalisation statistics (no batch-statistics derivation, no running-stats
    update).  ``output_mask`` selects which gradients are computed, matching
    ATen's ``native_batch_norm_backward`` contract.
    """
    logger.debug("GEMS BATCH_NORM_NO_UPDATE_BACKWARD")

    input_3d = make_3d_for_bn(input)
    grad_output_3d = make_3d_for_bn(grad_output)

    batch_dim, feat_dim, spatial_dim = input_3d.shape

    if running_mean is None or running_var is None:
        raise RuntimeError(
            "batch_norm_no_update_backward requires both running_mean and running_var"
        )

    if output_mask[0]:
        input_grad = torch.empty_like(input_3d)
    else:
        # The kernel takes the input-gradient buffer as a pointer argument, so a
        # real (unused) tensor must be supplied even when the input gradient is
        # masked out. The kernel's ``input_grad_mask`` constexpr guard
        # dead-code-eliminates every store into it.
        input_grad = torch.empty((1,), dtype=input.dtype, device=input.device)
    if output_mask[1]:
        weight_grad = torch.empty((feat_dim,), dtype=input.dtype, device=input.device)
    else:
        weight_grad = torch.empty((1,), dtype=input.dtype, device=input.device)
    if output_mask[2]:
        bias_grad = torch.empty((feat_dim,), dtype=input.dtype, device=input.device)
    else:
        bias_grad = torch.empty((1,), dtype=input.dtype, device=input.device)

    if output_mask[0]:
        input_grad_strides = input_grad.stride()
    else:
        input_grad_strides = (0, 0, 0)

    needs_reduce = bool(output_mask[1] or output_mask[2])

    # Split wide planes into spatial chunks so that more than `feat_dim`
    # programs are resident: with few channels (e.g. C=6) a single program per
    # channel leaves the GPU idle. Each program reduces its own chunk into a
    # scratch row; a finalize pass folds the chunks per channel.
    nchunk = max(1, -(-spatial_dim // _CHUNK_SPATIAL_TARGET))
    chunk_size = -(-spatial_dim // nchunk)

    if needs_reduce and nchunk > 1:
        w_partial = torch.empty(
            (feat_dim, nchunk), dtype=torch.float64, device=input.device
        )
        b_partial = torch.empty(
            (feat_dim, nchunk), dtype=torch.float64, device=input.device
        )
    else:
        nchunk = 1
        chunk_size = spatial_dim
        w_partial = weight_grad if output_mask[1] else input_grad
        b_partial = bias_grad if output_mask[2] else input_grad

    # Launches 2D grid: one program per (feature channel, spatial chunk).
    with torch_device_fn.device(input.device):
        batch_norm_no_update_backward_kernel[(feat_dim, nchunk)](
            grad_output_3d,
            input_3d,
            running_mean,
            running_var,
            weight,
            input_grad,
            w_partial,
            b_partial,
            batch_dim,
            spatial_dim,
            chunk_size,
            nchunk,
            *grad_output_3d.stride(),
            *input_3d.stride(),
            *input_grad_strides,
            eps,
            input_grad_mask=bool(output_mask[0]),
            weight_grad_mask=bool(output_mask[1]),
            bias_grad_mask=bool(output_mask[2]),
            finalize=nchunk == 1,
        )

    if needs_reduce and nchunk > 1:
        with torch_device_fn.device(input.device):
            batch_norm_no_update_finalize_kernel[(feat_dim,)](
                w_partial,
                b_partial,
                weight_grad,
                bias_grad,
                nchunk,
                finalize_mask=bool(output_mask[1]),
                bias_finalize_mask=bool(output_mask[2]),
                BLOCK=triton.next_power_of_2(nchunk),
            )

    return (
        input_grad.view_as(input) if output_mask[0] else None,
        weight_grad if output_mask[1] else None,
        bias_grad if output_mask[2] else None,
    )
