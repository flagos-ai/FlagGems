# Wide-regime policy: enough programs to fill the SMs several times over. A
# spatial plane larger than this target is split into chunks, each reduced by
# its own program into an fp64 scratch row; a finalize pass folds the chunks
# per channel.
_CHUNK_SPATIAL_TARGET = 4096


def make_3d_for_bn(input: Tensor) -> Tensor:
    """
    Converts the input to a 3D view for batch normalization.

    Args:
        input: Input to render 3D.

    Returns:
        Input's 3D view.
    """
    if input.ndim == 2:
        input = input.unsqueeze(-1)

    elif input.ndim >= 4:
        input = input.flatten(2, -1)

    return input


