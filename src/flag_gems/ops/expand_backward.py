def _reduce_3d(
    grad: torch.Tensor, out: torch.Tensor, OUTS: int, RED: int, INN: int
) -> None:
    """Sum ``grad`` viewed as ``(OUTS, RED, INN)`` over ``RED`` into ``out`` ``(OUTS, INN)``."""
    if INN == 1:
        _reduce_flat(grad, out, OUTS, RED)
        return

    # Choose ``BLOCK_I`` wide enough that the 1-D grid still supplies
    # ``_MIN_PROGRAMS`` programs (a small ``O`` -- a prepended leading dim --
    # needs a narrower inner tile to spread the keep axis over the device).
    block_i = triton.next_power_of_2(max(1, (INN * OUTS) // _MIN_PROGRAMS))
    block_i = min(max(block_i, 64), _MAX_BLOCK_I, triton.next_power_of_2(INN))
    n_i = triton.cdiv(INN, block_i)
    # Spend the rest of the tile budget on ``BLOCK_R``: a longer reduce slice
    # means fewer loop iterations per program.
    block_r = min(
        triton.next_power_of_2(max(RED, 1)),
        max(8, _TILE_ELEMS // block_i),
        _MAX_BLOCK_R,
    )

    # A single-pass launch needs one program per ``(o, inner tile)`` pair.  When
    # the keep axis is tiny (``O == 1`` with a short run of kept dims) that is
    # fewer programs than the device can hold, and every program then streams
    # the whole reduce axis alone.  Split the reduce axis across programs in that
    # case and fold the partial sums in a second pass; each slice keeps at least
    # ``_MIN_CHUNK_R`` rows so the split stays worthwhile.
    num_chunk = 1
    if OUTS * n_i < _MIN_PROGRAMS and RED > _MIN_CHUNK_R:
        wanted = triton.cdiv(_SPLIT_PROGRAMS, OUTS * n_i)
        num_chunk = min(triton.cdiv(RED, _MIN_CHUNK_R), max(1, wanted))
    with torch_device_fn.device(grad.device):
        if num_chunk == 1:
            _expand_backward_kernel[(OUTS * n_i,)](
                grad,
                out,
                RED,
                INN,
                n_i,
                BLOCK_R=block_r,
                BLOCK_I=block_i,
                num_warps=_NUM_WARPS,
            )
            return

        chunk_r = triton.next_power_of_2(triton.cdiv(RED, num_chunk))
        mid = torch.empty(
            (OUTS, n_i, num_chunk, block_i), dtype=torch.float32, device=grad.device
        )
        _expand_backward_chunk_kernel[(OUTS * n_i * num_chunk,)](
            grad,
            mid,
            RED,
            INN,
            n_i,
            num_chunk,
            BLOCK_R=chunk_r,
            BLOCK_I=block_i,
            num_warps=_NUM_WARPS,
        )
        _expand_backward_final_kernel[(OUTS * n_i,)](
            mid,
            out,
            INN,
            n_i,
            num_chunk,
            BLOCK_C=triton.next_power_of_2(num_chunk),
            BLOCK_I=block_i,
            num_warps=_NUM_WARPS,
        )


def _reduce_flat(grad: torch.Tensor, out: torch.Tensor, OUTS: int, RED: int) -> None:
    """Row-wise sum over ``RED`` for the ``INN == 1`` layout (two stages)."""
    # Fixed 4K-element chunks: wide enough to coalesce the flat stream, and
    # enough chunks per row to spread the launch across the device in both
    # the single-row (``O == 1``) and the many-row (``O`` in the tens of
    # thousands) layouts.
    block = min(triton.next_power_of_2(max(RED, 1)), 4096)
    num_chunk = triton.cdiv(RED, block)
    block_c = triton.next_power_of_2(num_chunk)

    with torch_device_fn.device(grad.device):
        if num_chunk == 1:
            # A single chunk per row: stage 2 is a trivial store, so keep the
            # whole row in one program and skip the intermediate buffer.
            _expand_backward_kernel[(OUTS,)](
                grad,
                out,
                RED,
                1,
                1,
                BLOCK_R=min(triton.next_power_of_2(max(RED, 1)), 8192),
                BLOCK_I=1,
                num_warps=4,
            )
            return

        mid = torch.empty((OUTS, num_chunk), dtype=torch.float32, device=grad.device)
        _expand_backward_flat_kernel[(OUTS * num_chunk,)](
            grad,
            mid,
            RED,
            num_chunk,
            BLOCK=block,
            num_warps=4,
        )
        _expand_backward_flat_final_kernel[(OUTS,)](
            mid,
            out,
            num_chunk,
            BLOCK_C=block_c,
            num_warps=4,
        )


def _reduce_runs(grad: torch.Tensor, shape, runs, out_dtype) -> torch.Tensor:
    """Sum ``grad`` over each contiguous run of dims in ``runs``, in order.

    ``runs`` is a list of ``(lo, hi)`` inclusive index pairs into the current
    shape.  Every run is folded independently; because the fold keeps the
    reduced dims at size 1, the next run's coordinates are unchanged.

    ATen rounds only once, on the single store back to the input dtype.  A
    multi-run reduction therefore keeps every intermediate in fp32 and only
    rounds the final result, so the accumulated value matches the native
    ``sum`` instead of drifting through a low-precision intermediate.
    """
    cur = grad
    cur_shape = list(shape)
    # A single run reduces straight from the storage dtype: the kernel promotes
    # each loaded row to fp32 before accumulating, so the input never needs a
    # full-tensor fp32 copy.  A multi-run fold keeps every non-final partial in
    # fp32 and rounds only on the last store -- the single rounding point ATen
    # uses.
    work_dtype = out_dtype
    for idx, (lo, hi) in enumerate(runs):
        # Collapse the run to a single axis: (outer, R, inner).
        outer = 1
        for d in range(lo):
            outer *= cur_shape[d]
        R = 1
        for d in range(lo, hi + 1):
            R *= cur_shape[d]
        inner = 1
        for d in range(hi + 1, len(cur_shape)):
            inner *= cur_shape[d]

        out_shape = cur_shape[:lo] + [1] * (hi - lo + 1) + cur_shape[hi + 1 :]
        # Only the *last* fold stores in the output dtype (the single rounding
        # point ATen uses); earlier folds keep their partial sums in fp32 so a
        # multi-run reduce does not round twice.
        stage_dtype = work_dtype if idx == len(runs) - 1 else torch.float32
        out = torch.empty((outer, inner), dtype=stage_dtype, device=grad.device)
        _reduce_3d(cur.reshape(outer, R, inner), out, outer, R, inner)
        cur = out.reshape(out_shape)
        cur_shape = out_shape
    return cur.to(out_dtype)


def _broadcast_runs(grad_shape, keep_shape):
    """Group the dims that ``expand`` broadcast into contiguous ``(lo, hi)`` runs.

    ``keep_shape`` is the forward input shape right-aligned to ``grad_shape``
    (leading dims padded with 1).  A dim is reduced when the target size is
    larger than the kept size (broadcast) or when it only exists in the target
    (prepended leading dim, padded as 1 here).
    """
    ndim = len(grad_shape)
    reduced = [d for d in range(ndim) if keep_shape[d] == 1 and grad_shape[d] != 1]
    runs = []
    for d in reduced:
        if runs and d == runs[-1][1] + 1:
            runs[-1] = (runs[-1][0], d)
        else:
            runs.append((d, d))
    return runs


def expand_backward(grad_output: torch.Tensor, input: torch.Tensor):
    """Gradient of ``expand``: sum ``grad_output`` back to ``input``'s shape.

    Args:
        grad_output: Gradient w.r.t. the ``expand`` output.
        input: Original input tensor of ``expand`` (shape only; also fixes the
            result dtype and device).

    Returns:
        Gradient w.r.t. the input, with the same shape as ``input``.
    """
    logger.debug("GEMS EXPAND_BACKWARD")
    in_shape = list(input.shape)
    out_shape = list(grad_output.shape)

    if input.numel() == 0:
        return torch.empty(in_shape, dtype=input.dtype, device=input.device)

    # Right-align ``in_shape`` to the gradient rank; leading dims were prepended
    # by ``expand`` and are summed out entirely.
    keep_shape = [1] * (len(out_shape) - len(in_shape)) + in_shape
    runs = _broadcast_runs(out_shape, keep_shape)

    grad = grad_output
    if not grad.is_contiguous():
        grad = grad.contiguous()

    if not runs:
        # No dimension was broadcast: the gradient is the (possibly reshaped)
        # gradient itself.
        if grad.shape == tuple(in_shape):
            return grad.clone()
        return grad.reshape(in_shape).contiguous()

    res = _reduce_runs(grad, out_shape, runs, input.dtype)
    return res.reshape(in_shape)


