# Tiled-kernel launch shape. The sweep on H20-3e shows a 4096-element tile is
# the sweet spot for the coalesced inner axis: wider tiles spill registers and
# narrower ones lose their rows. ``BLOCK_R`` stays small -- it only has to span
# a couple of 128-byte rows -- so most of the tile budget goes to ``BLOCK_I``,
# the axis that turns contiguous.  The tile is also shrunk when it would leave
# the device starved of programs (a small prepended dim with a big keep axis).
_TILE_ELEMS = 4096
_MAX_BLOCK_R = 32
_MAX_BLOCK_I = 512
_MIN_PROGRAMS = 2048
# Two-pass split of the reduce axis: target this many programs and never make a
# chunk shorter than ``_MIN_CHUNK_R`` rows.
_SPLIT_PROGRAMS = 16384
_MIN_CHUNK_R = 16
# One warp per program.  With a ``[BLOCK_R, BLOCK_I]`` tile the two-warp codegen
# splits the contiguous inner axis across warps, which fragments the loads: on
# H20-3e the same tile runs at ~2x the bandwidth with a single warp (measured
# 77 us vs 149 us for a 32x64 fp16 tile) because one warp keeps each row's
# 128-byte segment contiguous.
_NUM_WARPS = 1


