"""Autograd bridge and Triton kernel for ``aten::expand_backward``.

The pinned Torch build exposes no ``aten::expand_backward`` schema: ATen
materialises the gradient through the ``ExpandBackward0`` autograd node, whose
whole body is ``grad_output.sum_to_size(input.shape)`` (one native reduction
kernel).  ``expand`` itself is a zero-copy broadcast view, so its backward is a
sum-to-shape reduction:

* every dimension the forward broadcast (target size > source size) and every
  dimension the forward *prepended* (target rank > source rank) is summed out;
* every remaining dimension is kept, so the result has the forward input's
  shape exactly (``keepdim`` semantics).

The reduced dims of a real ``expand`` gradient almost always form one
contiguous run, which the kernel treats as a single ``(O, R, I)`` problem:
``O`` and ``I`` index the kept dims around the run and ``R`` is the product of
the reduced sizes inside it.  Each program owns a tile of ``BLOCK_I`` inner
lanes and streams ``R`` in ``BLOCK_R`` chunks, so loads stay coalesced along the
innermost kept axis and the accumulator lives in registers.  When the reduced
dims form several disjoint runs, the runs are folded one at a time; every fold
keeps its intermediate in fp32, so the single stored result rounds exactly once
(the same boundary ATen's ``sum`` uses).

Two layouts need their own launch shape:

* ``I > 1`` -- the tiled ``(O, R, I)`` kernel above.
* ``I == 1`` -- the kept dims are a single point, so there is no inner axis to
  tile.  A flat two-stage reduction is used instead: stage 1 writes one partial
  sum per ``(O, chunk)`` slice and stage 2 folds the partials per ``O``.  A
  single-pass tiled launch here would either serialise the whole stream in one
  program (``O == 1``, full reduce) or leave the reduce axis untilled.

All grids are 1-D: a 4-D gradient such as ``(8, 64, 512, 512)`` expands to more
than 65535 inner tiles, which would exceed the CUDA grid-Y limit if the
``(O, ; inner tile)`` split were passed as a 2-D grid.
"""

