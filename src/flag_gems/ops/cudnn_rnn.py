            f_gate = tl.zeros([BLOCK_SIZE], dtype=tl.float32)
            g_gate = tl.zeros([BLOCK_SIZE], dtype=tl.float32)
            o_gate = tl.zeros([BLOCK_SIZE], dtype=tl.float32)

