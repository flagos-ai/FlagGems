        if batch_first:
            t_inp_off = batch_idx * batch_inp_stride + t * input_dim
            t_out_off = batch_idx * batch_out_stride + t * hidden_out
        else:
            t_inp_off = t * (batch_size * input_dim) + batch_idx * input_dim
