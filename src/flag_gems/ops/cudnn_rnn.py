def _compute_offsets(batch_sizes):
    """Return (input_offsets, output_offsets) for packed sequences."""
    inp_offs = [0]
    for bs in batch_sizes:
        inp_offs.append(inp_offs[-1] + bs)
    inp_offs.pop()  # remove last (total_len)
    out_offs = list(inp_offs)  # same layout for output
    return inp_offs, out_offs


def _triton_layer_forward(
    input_seq,
    hx,
    cx,
    w_ih,
    w_hh,
    b_ih,
    b_hh,
    w_hr,
    mode,
    reverse,
    batch_size,
    seq_len,
    input_dim,
    hidden_size,
    proj_size,
    batch_first,
    batch_sizes=None,
):
    """Run one RNN layer+dir using Triton kernels.

    When ``batch_sizes`` is not None, uses the packed variant.
    """
    device = input_seq.device
    dtype = input_seq.dtype
    hidden_out = proj_size if (proj_size > 0 and mode == _LSTM) else hidden_size
    is_packed = batch_sizes is not None
    max_batch = max(batch_sizes) if is_packed else batch_size

    # Reverse input if needed (non-packed only; packed handles reverse in-kernel)
    if reverse and not is_packed:
        input_seq = torch.flip(input_seq, [0]).contiguous()

    # Compute offsets for packed layout
    inp_offs, out_offs = _compute_offsets(batch_sizes) if is_packed else (None, None)

    # Allocate output
    if is_packed:
        total_len = input_seq.size(0)
        output = torch.empty(total_len, hidden_out, device=device, dtype=dtype)
    else:
        output = torch.empty(seq_len, max_batch, hidden_out, device=device, dtype=dtype)

    # Scratch buffers
    scratch_dim = max(hidden_out, hidden_size) if mode == _LSTM else hidden_out
    h_scratch = torch.empty(max_batch, scratch_dim, device=device, dtype=torch.float32)
    h_read = torch.empty(max_batch, scratch_dim, device=device, dtype=torch.float32)

    hy_out = torch.empty(max_batch, hidden_out, device=device, dtype=dtype)
    cy_out = (
        torch.empty(max_batch, hidden_size, device=device, dtype=dtype)
        if mode == _LSTM
        else None
    )

    grid = (max_batch,)

    has_bias_flag = b_ih is not None
    if not has_bias_flag:
        b_dummy = torch.empty(0, device=device, dtype=torch.float32)
        b_ih_ptr = b_hh_ptr = b_dummy
    else:
        b_ih_ptr = b_ih.contiguous()
        b_hh_ptr = b_hh.contiguous()

    w_hr_ptr = (
        w_hr
        if (w_hr is not None)
        else torch.empty(0, device=device, dtype=torch.float32)
    )

    with runtime.torch_device_fn.device(device):
        if is_packed:
            # Packed path
            bs_t = torch.tensor(batch_sizes, dtype=torch.int32, device=device)
            io_t = torch.tensor(inp_offs, dtype=torch.int32, device=device)
            oo_t = torch.tensor(out_offs, dtype=torch.int32, device=device)
            num_steps = len(batch_sizes)

            if mode in (_RNN_RELU, _RNN_TANH):
                nonlinearity = 0 if mode == _RNN_RELU else 1
                _rnn_packed_kernel[grid](
                    input_seq,
                    hx,
                    w_ih,
                    w_hh,
                    b_ih_ptr,
                    b_hh_ptr,
                    output,
                    hy_out,
                    h_scratch,
                    h_read,
                    bs_t,
                    io_t,
                    oo_t,
                    num_steps,
                    max_batch,
                    input_dim,
                    hidden_out,
                    nonlinearity,
                    has_bias_flag,
                    reverse,
                    BLOCK_SIZE=64,
                )
            elif mode == _LSTM:
                c_scratch = torch.empty(
                    max_batch, hidden_size, device=device, dtype=torch.float32
                )
                _lstm_packed_kernel[grid](
                    input_seq,
                    hx,
                    cx,
                    w_ih,
                    w_hh,
                    w_hr_ptr,
                    b_ih_ptr,
                    b_hh_ptr,
                    output,
                    hy_out,
                    cy_out,
                    h_scratch,
                    h_read,
                    c_scratch,
                    bs_t,
                    io_t,
                    oo_t,
                    num_steps,
                    max_batch,
                    input_dim,
                    hidden_size,
                    proj_size,
                    has_bias_flag,
                    w_hr is not None,
                    reverse,
                    BLOCK_SIZE=64,
                )
            elif mode == _GRU:
                _gru_packed_kernel[grid](
                    input_seq,
                    hx,
                    w_ih,
                    w_hh,
                    b_ih_ptr,
                    b_hh_ptr,
                    output,
                    hy_out,
                    h_scratch,
                    h_read,
                    bs_t,
                    io_t,
                    oo_t,
                    num_steps,
                    max_batch,
                    input_dim,
                    hidden_size,
                    has_bias_flag,
                    reverse,
                    BLOCK_SIZE=64,
                )
        else:
            # Uniform batch path
            if mode in (_RNN_RELU, _RNN_TANH):
                nonlinearity = 0 if mode == _RNN_RELU else 1
                _rnn_kernel[grid](
                    input_seq,
                    hx,
                    w_ih,
                    w_hh,
                    b_ih_ptr,
                    b_hh_ptr,
                    output,
                    hy_out,
                    h_scratch,
                    h_read,
                    seq_len,
                    max_batch,
                    input_dim,
                    hidden_out,
                    batch_first,
                    nonlinearity,
                    has_bias_flag,
                    BLOCK_SIZE=64,
                )
            elif mode == _LSTM:
                c_scratch = torch.empty(
                    max_batch, hidden_size, device=device, dtype=torch.float32
                )
                _lstm_kernel[grid](
                    input_seq,
                    hx,
                    cx,
                    w_ih,
                    w_hh,
                    w_hr_ptr,
                    b_ih_ptr,
                    b_hh_ptr,
                    output,
                    hy_out,
                    cy_out,
                    h_scratch,
                    h_read,
                    c_scratch,
                    seq_len,
                    max_batch,
                    input_dim,
                    hidden_size,
                    proj_size,
                    batch_first,
                    has_bias_flag,
                    w_hr is not None,
                    BLOCK_SIZE=64,
                )
            elif mode == _GRU:
                _gru_kernel[grid](
                    input_seq,
                    hx,
                    w_ih,
                    w_hh,
                    b_ih_ptr,
                    b_hh_ptr,
                    output,
                    hy_out,
                    h_scratch,
                    h_read,
                    seq_len,
                    max_batch,
                    input_dim,
                    hidden_size,
                    batch_first,
                    has_bias_flag,
                    BLOCK_SIZE=64,
                )

    # Reverse output back if needed (non-packed only; packed handles in-kernel)
    if reverse and not is_packed:
        output = torch.flip(output, [0]).contiguous()

    return output, hy_out, cy_out


# ===================================================================
#  Triton dropout between layers
# ===================================================================


def _triton_dropout(x, p, train):
    """Apply dropout using a Triton kernel."""
    if p <= 0.0 or not train:
        return x
    return torch.nn.functional.dropout(x, p=p, training=train)


# ===================================================================
#  Main entry point
# ===================================================================


def _decode_layout(ws, mode):
    if ws == _WS_NB:
        return False, False
    if ws == _WS_B:
        return True, False
    if ws == _WS_NBP:
        if mode != _LSTM:
            raise ValueError("proj only for LSTM")
        return False, True
    if ws == _WS_BP:
        if mode != _LSTM:
            raise ValueError("proj only for LSTM")
        return True, True
    raise ValueError(f"Unsupported weight_stride0: {ws}")


def cudnn_rnn(
    input,
    weight,
    weight_stride0,
    weight_buf,
    hx,
    cx,
    mode,
    hidden_size,
    proj_size,
    num_layers,
    batch_first,
    dropout,
    train,
    bidirectional,
    batch_sizes,
    dropout_state,
):
    """Triton-based replacement for ``aten::_cudnn_rnn``.

    All code paths use Triton kernels.
    """
    logger.debug("GEMS CUDNN_RNN")

    num_directions = 2 if bidirectional else 1
    has_bias, has_proj = _decode_layout(weight_stride0, mode)
    is_packed = bool(batch_sizes)

    # --- Normalize input ---
    if is_packed:
        input_seq = input.contiguous()
        max_batch = max(batch_sizes)
    elif batch_first:
        input_seq = input.transpose(0, 1).contiguous()
        max_batch = input_seq.size(1)
    else:
        input_seq = input.contiguous()
        max_batch = input_seq.size(1)

    # --- Validate ---
    hidden_out = proj_size if has_proj else hidden_size
    expected = (num_layers * num_directions, max_batch, hidden_out)
    if hx.shape != expected:
        raise ValueError(f"hx shape mismatch: {tuple(hx.shape)} vs {expected}")
    if mode == _LSTM:
        if cx is None:
            raise ValueError("cx required for LSTM")
        expected_c = (num_layers * num_directions, max_batch, hidden_size)
        if cx.shape != expected_c:
            raise ValueError(f"cx shape mismatch: {tuple(cx.shape)} vs {expected_c}")

    # --- Allocate outputs ---
    if is_packed:
        output = torch.empty(
            input_seq.size(0),
            hidden_out * num_directions,
            device=input.device,
            dtype=input.dtype,
        )
    else:
        seq_len = input_seq.size(0)
        output = torch.empty(
            seq_len,
            max_batch,
            hidden_out * num_directions,
            device=input.device,
            dtype=input.dtype,
        )

    hy = torch.empty_like(hx)
    cy = (
        torch.empty_like(cx)
        if mode == _LSTM
        else torch.empty(
            num_layers * num_directions,
            max_batch,
            hidden_size,
            device=input.device,
            dtype=input.dtype,
        )
    )

    # --- Layer-by-layer ---
    layer_input = input_seq

    for layer_idx in range(num_layers):
        for direction_idx in range(num_directions):
            w_idx = (layer_idx * num_directions + direction_idx) * weight_stride0
            w_ih = weight[w_idx]
            w_hh = weight[w_idx + 1]
            b_ih = weight[w_idx + 2] if has_bias else None
            b_hh = weight[w_idx + 3] if has_bias else None
            w_hr = weight[w_idx + (4 if has_bias else 2)] if has_proj else None

            layer_hx_idx = layer_idx * num_directions + direction_idx
            h = hx[layer_hx_idx]
            c = cx[layer_hx_idx] if mode == _LSTM else None
            rev = direction_idx == 1

            layer_input_dim = (
                weight[0].size(1) if layer_idx == 0 else hidden_out * num_directions
            )

            layer_out, h_out, c_out = _triton_layer_forward(
                layer_input,
                h,
                c,
                w_ih,
                w_hh,
                b_ih,
                b_hh,
                w_hr,
                mode,
                rev,
                max_batch,
                seq_len if not is_packed else 0,
                layer_input_dim,
                hidden_size,
                proj_size,
                False,  # batch_first already normalized
                batch_sizes if is_packed else None,
            )

            out_start = direction_idx * hidden_out
            out_end = out_start + hidden_out
            if is_packed:
                output[:, out_start:out_end] = layer_out
            else:
                output[:, :, out_start:out_end] = layer_out

            hy[layer_hx_idx] = h_out
            if mode == _LSTM:
                cy[layer_hx_idx] = c_out

        # ---- Dropout between layers (Triton) ----
        # Always clone: the next layer's directions both read the SAME
        # input, but they write to different slices of the output tensor.
        if layer_idx < num_layers - 1:
            layer_input = _triton_dropout(output, dropout, train).clone()

    # --- Finalize layout ---
    if not is_packed and batch_first:
        output = output.transpose(0, 1).contiguous()

    reserve = torch.empty(0, device=input.device, dtype=torch.uint8)
    return output, hy, cy, reserve, weight_buf
