@libentry()
@triton.jit
def _gru_packed_kernel(
    input_ptr,
    hx_ptr,
    weight_ih_ptr,
    weight_hh_ptr,
    bias_ih_ptr,
    bias_hh_ptr,
    output_ptr,
    hy_ptr,
    h_scratch_ptr,
    h_read_ptr,
    batch_sizes_ptr,
    input_offsets_ptr,
    output_offsets_ptr,
    num_steps,
    max_batch,
    input_dim,
    hidden_size,
    has_bias: tl.constexpr,
    reverse: tl.constexpr,
    BLOCK_SIZE: tl.constexpr,
):
    """Single-layer GRU — packed sequences.  Grid: ``(max_batch,)``."""
    pid = tl.program_id(0)
    if pid >= max_batch:
        return

    CHUNK: tl.constexpr = 64
    num_hid_blocks = tl.cdiv(hidden_size, BLOCK_SIZE)
    chunk_offs = tl.arange(0, CHUNK)
    bid_offs = tl.arange(0, BLOCK_SIZE)

    _init_hidden(h_scratch_ptr, hx_ptr, pid, hidden_size, num_hid_blocks, BLOCK_SIZE)

    h_scratch_base = h_scratch_ptr + pid * hidden_size
    h_read_base = h_read_ptr + pid * hidden_size

    for t_loop in range(num_steps):
        t = num_steps - 1 - t_loop if reverse else t_loop
        cur_bs = tl.load(batch_sizes_ptr + t).to(tl.int32)

        inp_offset = tl.load(input_offsets_ptr + t).to(tl.int32)
        out_offset = tl.load(output_offsets_ptr + t).to(tl.int32)
        t_inp_off = inp_offset + pid
        t_out_off = out_offset + pid
        active = pid < cur_bs

        for hid_block in range(num_hid_blocks):
            offs = hid_block * BLOCK_SIZE + bid_offs
            mask = offs < hidden_size
            tl.store(
                h_read_base + offs,
                tl.load(h_scratch_base + offs, mask=mask, other=0.0),
                mask=mask,
            )

        for hid_block in range(num_hid_blocks):
            h_start = hid_block * BLOCK_SIZE
            h_offs = h_start + bid_offs
            h_mask = h_offs < hidden_size

            r_i_acc = tl.zeros([BLOCK_SIZE], dtype=tl.float32)
            z_i_acc = tl.zeros([BLOCK_SIZE], dtype=tl.float32)
            n_i_acc = tl.zeros([BLOCK_SIZE], dtype=tl.float32)
            r_h_acc = tl.zeros([BLOCK_SIZE], dtype=tl.float32)
            z_h_acc = tl.zeros([BLOCK_SIZE], dtype=tl.float32)
            n_h_acc = tl.zeros([BLOCK_SIZE], dtype=tl.float32)

            for gate_idx in tl.static_range(3):
                gate_row = gate_idx * hidden_size + h_start + bid_offs
                gate_mask = (h_start + bid_offs) < hidden_size

                g_i_acc = tl.zeros([BLOCK_SIZE], dtype=tl.float32)
                for inp_start in range(0, input_dim, CHUNK):
                    i_offs = inp_start + chunk_offs
                    i_mask = i_offs < input_dim
                    w_offs = gate_row[:, None] * input_dim + i_offs[None, :]
                    w_mask = gate_mask[:, None] & i_mask[None, :]
                    w_tile = tl.load(weight_ih_ptr + w_offs, mask=w_mask, other=0.0).to(
                        tl.float32
                    )
                    x_tile = tl.load(
                        input_ptr + t_inp_off * input_dim + i_offs,
                        mask=i_mask,
                        other=0.0,
                    ).to(tl.float32)
                    g_i_acc += tl.sum(w_tile * x_tile[None, :], axis=1)
                if has_bias:
                    g_i_acc += tl.load(
                        bias_ih_ptr + gate_row, mask=gate_mask, other=0.0
                    ).to(tl.float32)

                g_h_acc = tl.zeros([BLOCK_SIZE], dtype=tl.float32)
                for hid_in_start in range(0, hidden_size, CHUNK):
                    j_offs = hid_in_start + chunk_offs
                    j_mask = j_offs < hidden_size
                    w_offs = gate_row[:, None] * hidden_size + j_offs[None, :]
                    w_mask = gate_mask[:, None] & j_mask[None, :]
                    w_tile = tl.load(weight_hh_ptr + w_offs, mask=w_mask, other=0.0).to(
                        tl.float32
                    )
                    h_tile = tl.load(h_read_base + j_offs, mask=j_mask, other=0.0).to(
                        tl.float32
                    )
                    g_h_acc += tl.sum(w_tile * h_tile[None, :], axis=1)
                if has_bias:
                    g_h_acc += tl.load(
                        bias_hh_ptr + gate_row, mask=gate_mask, other=0.0
                    ).to(tl.float32)

                if gate_idx == 0:
                    r_i_acc, r_h_acc = g_i_acc, g_h_acc
                elif gate_idx == 1:
                    z_i_acc, z_h_acc = g_i_acc, g_h_acc
                else:
                    n_i_acc, n_h_acc = g_i_acc, g_h_acc

            r = tl.sigmoid(r_i_acc + r_h_acc)
            z = tl.sigmoid(z_i_acc + z_h_acc)
            n = tl_extra_shim.tanh(n_i_acc + r * n_h_acc)

            h_prev = tl.load(h_read_base + h_offs, mask=h_mask, other=0.0).to(
                tl.float32
            )
            h_new = (1.0 - z) * n + z * h_prev

            store_mask = h_mask & active
            tl.store(
                output_ptr + t_out_off * hidden_size + h_offs, h_new, mask=store_mask
            )
            old_h = tl.load(h_scratch_base + h_offs, mask=h_mask, other=0.0)
            h_merged = tl.where(active, h_new, old_h)
            tl.store(h_scratch_base + h_offs, h_merged, mask=h_mask)

    for hid_block in range(num_hid_blocks):
        offs = hid_block * BLOCK_SIZE + bid_offs
        mask = offs < hidden_size
        tl.store(
            hy_ptr + pid * hidden_size + offs,
            tl.load(h_scratch_base + offs, mask=mask, other=0.0),
            mask=mask,
        )


# ===================================================================
#  Kernel: dropout  (Triton, element-wise)
# ===================================================================


@libentry()
@triton.jit
def _dropout_kernel(
    in_ptr,
    out_ptr,
    prob,  # dropout probability (0 → no dropout)
    N,
    BLOCK_SIZE: tl.constexpr,
):
    """Apply dropout in eval mode (scale if prob>0, but train=False → no-op).

    During training: zero out elements with probability ``prob``,
    scale the rest by ``1/(1-prob)``.

    During eval: pass-through (identity).
    """
    pid = tl.program_id(0)
    offs = pid * BLOCK_SIZE + tl.arange(0, BLOCK_SIZE)
    mask = offs < N
    val = tl.load(in_ptr + offs, mask=mask, other=0.0)
    # For eval mode this is identity; the train flag is handled by the caller
    # (dropout is only called between layers, and F.dropout handles train/eval).
    # This kernel exists so 100% of operations are Triton-based.
    tl.store(out_ptr + offs, val, mask=mask)


