def _batch_norm_impl_index_backward_kernel(
    grad_output_pointer,
    input_pointer,
    mean_pointer,
    inv_std_pointer,
    weight_pointer,
    input_grad_pointer,
    weight_grad_pointer,
    bias_grad_pointer,
    batch_dim,
    spatial_dim,
    grad_output_batch_stride,
    grad_output_feat_stride,
    grad_output_spatial_stride,
    input_batch_stride,
    input_feat_stride,
    input_spatial_stride,
    input_grad_batch_stride,
    input_grad_feat_stride,
    input_grad_spatial_stride,
    is_train: tl.constexpr,
    input_grad_mask: tl.constexpr,
    weight_grad_mask: tl.constexpr,
    bias_grad_mask: tl.constexpr,
    BLOCK_M: tl.constexpr,
    BLOCK_N: tl.constexpr,
):
    feat_pid = tl.program_id(axis=0)

    mean = tl.load(feat_pid + mean_pointer).to(tl.float32)
    inv_std = tl.load(feat_pid + inv_std_pointer).to(tl.float32)

    # First pass: accumulate the reduction terms used both for the weight/bias
    # gradients and (in training mode) for the input-gradient correction term.
    # term1 = sum((input - mean) * inv_std * grad_output)
    # term2 = sum(grad_output)
    term1 = tl.zeros([BLOCK_M, BLOCK_N], dtype=tl.float32)
    term2 = tl.zeros([BLOCK_M, BLOCK_N], dtype=tl.float32)

    for m_step in range(0, tl.cdiv(batch_dim, BLOCK_M)):
        for n_step in range(0, tl.cdiv(spatial_dim, BLOCK_N)):
            batch_offset = m_step * BLOCK_M + tl.arange(0, BLOCK_M)
            batch_mask = batch_offset < batch_dim

            spatial_offset = n_step * BLOCK_N + tl.arange(0, BLOCK_N)
            spatial_mask = spatial_offset < spatial_dim

            curr_grad_output_pointer = (
                grad_output_pointer
                + grad_output_feat_stride * feat_pid
                + grad_output_batch_stride * batch_offset[:, None]
                + grad_output_spatial_stride * spatial_offset[None, :]
            )
            curr_input_pointer = (
                input_pointer
                + input_feat_stride * feat_pid
                + input_batch_stride * batch_offset[:, None]
                + input_spatial_stride * spatial_offset[None, :]
            )

            mask = batch_mask[:, None] & spatial_mask[None, :]
            curr_input = tl.load(curr_input_pointer, mask=mask).to(tl.float32)

            curr_pre_lin = (curr_input - mean) * inv_std
            curr_grad_output = tl.load(curr_grad_output_pointer, mask=mask).to(
                tl.float32
            )

            term1 += curr_pre_lin * curr_grad_output
            term2 += curr_grad_output

    term1 = tl.sum(term1)
    term2 = tl.sum(term2)

    if weight_grad_mask:
        tl.store(feat_pid + weight_grad_pointer, term1)
    if bias_grad_mask:
        tl.store(feat_pid + bias_grad_pointer, term2)

    if not input_grad_mask:
        return

    if weight_pointer:
        weight = tl.load(feat_pid + weight_pointer).to(tl.float32)
    else:
        weight = 1.0

    # Second pass: compute the input gradient.  In training mode the canonical
    # batch-norm backward correction term is applied; in evaluation mode the
    # gradient is simply ``grad_output * weight * inv_std`` because the
    # normalization statistics are fixed (no population to reduce over).
    count = batch_dim * spatial_dim

    for m_step in range(0, tl.cdiv(batch_dim, BLOCK_M)):
        for n_step in range(0, tl.cdiv(spatial_dim, BLOCK_N)):
            batch_offset = m_step * BLOCK_M + tl.arange(0, BLOCK_M)
            batch_mask = batch_offset < batch_dim

            spatial_offset = n_step * BLOCK_N + tl.arange(0, BLOCK_N)
            spatial_mask = spatial_offset < spatial_dim

            curr_grad_output_pointer = (
                grad_output_pointer
                + grad_output_feat_stride * feat_pid
                + grad_output_batch_stride * batch_offset[:, None]
                + grad_output_spatial_stride * spatial_offset[None, :]
            )
            curr_input_pointer = (
                input_pointer
                + input_feat_stride * feat_pid
                + input_batch_stride * batch_offset[:, None]
                + input_spatial_stride * spatial_offset[None, :]
            )
            curr_input_grad_pointer = (
                input_grad_pointer
                + input_grad_feat_stride * feat_pid
                + input_grad_batch_stride * batch_offset[:, None]
                + input_grad_spatial_stride * spatial_offset[None, :]
            )

            curr_grad_output = tl.load(
                curr_grad_output_pointer,
                mask=batch_mask[:, None] & spatial_mask[None, :],
            ).to(tl.float32)

            if is_train:
                curr_input = tl.load(
                    curr_input_pointer,
                    mask=batch_mask[:, None] & spatial_mask[None, :],
                ).to(tl.float32)
                curr_pre_lin = (curr_input - mean) * inv_std
                curr_input_grad = (
                    inv_std
                    * weight
                    * (curr_grad_output - (term1 * curr_pre_lin + term2) / count)
                )
            else:
                curr_input_grad = curr_grad_output * weight * inv_std

            tl.store(
                curr_input_grad_pointer,
                curr_input_grad,
                mask=batch_mask[:, None] & spatial_mask[None, :],
            )


def _batch_norm_impl_index_backward(
    impl_index: int,
    input: Tensor,
    grad_output: Tensor,
    weight=None,
    running_mean=None,
    running_var=None,
    save_mean=None,
    save_var_transform=None,
    train: bool = False,
    eps: float = 1e-5,
    output_mask=(True, True, True),
    reservedSpace=None,
):
    """Backward pass dispatcher for ``_batch_norm_impl_index``.

    ``_batch_norm_impl_index`` (the JIT forward) selects one of three batch
    normalization backends at run time and returns an ``impl_index`` so that the
    matching backward implementation can be invoked later:

        * ``impl_index == 0``  -> native batch norm (saves ``save_invstd``)
        * ``impl_index == 1``  -> cudnn batch norm (saves ``save_invstd``)
        * ``impl_index == 2``  -> miopen batch norm (saves ``save_invstd``)

    In every training backend the value stored in the ``save_var_transform``
    slot is the *inverse standard deviation* ``1 / sqrt(var + eps)`` rather than
    the raw variance, so a single native-style backward kernel covers all three.
    When ``train`` is ``False`` (inference / eval mode) the saved statistics are
    empty and the inverse standard deviation is rebuilt from ``running_var``
    via ``rsqrt(running_var + eps)``; the input gradient then degenerates to the
    plain ``grad_output * weight * inv_std`` form.
    """
    logger.debug("GEMS _BATCH_NORM_IMPL_INDEX_BACKWARD")

    input_3d = make_3d_for_bn(input)
    grad_output_3d = make_3d_for_bn(grad_output)

    batch_dim, feat_dim, spatial_dim = input_3d.shape

    # Resolve the per-feature mean to use for the backward computation.  In
    # training mode the saved mean is available; in eval mode the saved mean is
    # empty and the running mean is used instead.
    if save_mean is not None and save_mean.numel() != 0:
        mean = save_mean
    else:
        mean = running_mean

    # Resolve the per-feature inverse standard deviation.  Every training
    # backend stores the inverse standard deviation in the save_var slot, so
    # it can be used directly.  In eval mode (empty save_var) the inverse
    # standard deviation is recomputed from the running variance.
    if save_var_transform is not None and save_var_transform.numel() != 0:
        invstd = save_var_transform
    else:
        acc_dtype = torch.float32
        invstd = torch.rsqrt(running_var.to(acc_dtype) + eps).to(input.dtype)

    # Empty input: nothing to reduce over.  Mirror the aten fallback that
    # produces the requested (possibly zero-element) gradients so the autograd
    # graph stays intact.
    if input.numel() == 0:
        grad_input = None
        grad_weight = None
        grad_bias = None
        if output_mask[0]:
            grad_input = torch.empty_like(input_3d)
        if output_mask[1]:
            grad_weight = torch.zeros(
                (feat_dim,), dtype=input.dtype, device=input.device
            )
        if output_mask[2]:
            grad_bias = torch.zeros((feat_dim,), dtype=input.dtype, device=input.device)
        return (
            grad_input.view_as(input) if grad_input is not None else None,
            grad_weight,
            grad_bias,
        )

    if output_mask[0]:
        input_grad = torch.empty_like(input_3d)
    else:
        # The backward kernel takes the input-gradient buffer as a pointer
        # argument, so a real (unused) tensor must be supplied even when the
        # input gradient is masked out.  The kernel's ``input_grad_mask``
        # constexpr guard dead-code-eliminates every store into it.
        input_grad = torch.empty((1,), dtype=input.dtype, device=input.device)
    if output_mask[1]:
        weight_grad = torch.empty((feat_dim,), dtype=input.dtype, device=input.device)
    else:
        weight_grad = torch.empty((1,), dtype=input.dtype, device=input.device)
    if output_mask[2]:
        bias_grad = torch.empty((feat_dim,), dtype=input.dtype, device=input.device)
    else:
        bias_grad = torch.empty((1,), dtype=input.dtype, device=input.device)

    if output_mask[0]:
        input_grad_strides = input_grad.stride()
    else:
        input_grad_strides = (0, 0, 0)

    # Launches 1D grid where each program operates over one feature.
    with torch_device_fn.device(input.device):
        _batch_norm_impl_index_backward_kernel[(feat_dim,)](
            grad_output_3d,
            input_3d,
            mean,
            invstd,
            weight,
            input_grad,
            weight_grad,
            bias_grad,
            batch_dim,
            spatial_dim,
            *grad_output_3d.stride(),
            *input_3d.stride(),
            *input_grad_strides,
            bool(train),
            bool(output_mask[0]),
            bool(output_mask[1]),
            bool(output_mask[2]),
        )

    return (
        input_grad.view_as(input) if output_mask[0] else None,
        weight_grad if output_mask[1] else None,
        bias_grad if output_mask[2] else None,
    )
