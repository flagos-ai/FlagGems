# conv_tbc_backward notes
# -----------------------
#   * grad_bias  = sum over (time, batch) of grad_output
#   * grad_weight[k, c, o] = sum_{t,b} input_pad[t + k, b, c] * grad_output[t, b, o]
#   * grad_input[t, b, c]  = sum_{k,o} grad_output_pad[t + kw-1-k, b, o] * weight[k, c, o]
#
# Both weight/input gradients are GEMMs once the sliding windows are laid out
# as matrices.  The layouts are chosen so that the *source* innermost axis of
# every staged copy is the contiguous channel axis: staging with a strided
# innermost axis (e.g. `(kw*in_c, olen*batch)` built straight from the
# `(time, batch, in_c)` tensor) costs ~25x more here.
#
# The GEMMs are plain @triton.jit launches with a fixed tile chosen from the
# problem shape: `triton.autotune` / `libentry` cannot be used on this stack
# (event timings read back as 0, so the tuner always keeps config[0], and the
# libentry wrapper adds ~20us of host time per launch, which is the same order
# as these kernels' own run time).

