def lu_solve_kernel(
    B,
    LU,
    PIV,
    X,
    m,
    k,
    stride_bb,
    stride_bm,
    stride_bk,
    stride_lub,
    stride_lum,
    stride_luk,
    stride_pb,
    stride_xb,
    stride_xm,
    stride_xk,
    BLOCK_M: tl.constexpr,
    BLOCK_K: tl.constexpr,
):
    """Solve ``LU x = P b`` for a batch of right-hand sides.

    Each program owns one matrix of the batch and a block of right-hand-side
    columns. The pivots are applied to ``b`` first, then the unit lower
    triangular factor is handled by forward substitution and the upper
    triangular factor by back substitution.
    """
    pid_b = program_id(0)
    pid_k = program_id(1)

    rows = tl.arange(0, BLOCK_M)
    cols = pid_k * BLOCK_K + tl.arange(0, BLOCK_K)
    mask_m = rows < m
    mask_k = cols < k
    mask2 = mask_m[:, None] & mask_k[None, :]

    # Build the row permutation induced by the pivots: ``perm[i]`` is the index
    # of the original row that the factorization moved to position ``i``.
    piv = tl.load(PIV + pid_b * stride_pb + rows, mask=mask_m, other=1)
    perm = rows
    for t in range(0, m):
        p = tl.sum(tl.where(rows == t, piv, 0)) - 1
        p = tl.where(p < 0, 0, p)
        at = tl.sum(tl.where(rows == t, perm, 0))
        ap = tl.sum(tl.where(rows == p, perm, 0))
        perm = tl.where(rows == t, ap, perm)
        perm = tl.where(rows == p, at, perm)

    # Gather the permuted right-hand sides: y = P b.
    y = tl.load(
        B + pid_b * stride_bb + perm[:, None] * stride_bm + cols[None, :] * stride_bk,
        mask=mask2,
        other=0.0,
    )

    # Forward substitution for the unit lower triangular factor: L y' = P b.
    for j in range(0, m):
        yj = tl.sum(tl.where(rows[:, None] == j, y, 0.0), axis=0)
        lcol = tl.load(
            LU + pid_b * stride_lub + rows * stride_lum + j * stride_luk,
            mask=mask_m,
            other=0.0,
        )
        y = y - tl.where(rows[:, None] > j, lcol[:, None] * yj[None, :], 0.0)

    # Back substitution for the upper triangular factor: U x = y.
    for step in range(0, m):
        j = m - 1 - step
        yj = tl.sum(tl.where(rows[:, None] == j, y, 0.0), axis=0)
        diag = tl.load(LU + pid_b * stride_lub + j * stride_lum + j * stride_luk)
        aj = yj / diag
        ucol = tl.load(
            LU + pid_b * stride_lub + rows * stride_lum + j * stride_luk,
            mask=mask_m,
            other=0.0,
        )
        y = tl.where(rows[:, None] < j, y - ucol[:, None] * aj[None, :], y)
        y = tl.where(rows[:, None] == j, aj[None, :], y)

    tl.store(
        X + pid_b * stride_xb + rows[:, None] * stride_xm + cols[None, :] * stride_xk,
        y,
        mask=mask2,
    )


def _pick_num_warps(block_m, block_k):
    size = block_m * block_k
    if size > 16384:
        return 16
    if size > 4096:
        return 8
    return 4


