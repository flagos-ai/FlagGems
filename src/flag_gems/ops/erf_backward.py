    exponential = e32.to(dt)

    # Step 3: tmp = M_2_SQRTPI * exponential  (fp32 scalar mul, rounded to dtype)
    tmp32 = C * exponential.to(tl.float32)
    tmp = tmp32.to(dt)

    # Step 4: grad_input = tmp * grad_output  (binary mul, fp32 math, rounded)
