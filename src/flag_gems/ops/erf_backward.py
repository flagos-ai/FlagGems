    offsets = pid * BLOCK + tl.arange(0, BLOCK)
    mask = offsets < n_elements

    grad = tl.load(grad_output_ptr + offsets, mask=mask, other=0.0)
    x = tl.load(x_ptr + offsets, mask=mask, other=0.0)

    dt = x.dtype

    # Step 1: squared = x.pow(2)  (fp32 math, rounded to storage dtype)
    x32 = x.to(tl.float32)
    squared = (x32 * x32).to(dt)

    # Step 2: exponential = exp(-squared)  (fp32 math, rounded to storage dtype)
    # libdevice.exp is bit-exact with ATen's expf; default tl.exp (ex2.approx
    # lowering) differs by 1 ULP on a small fraction of elements.
