"""Gather the values of ``self`` at the indices of a sparse COO ``mask``.

``aten::sparse_mask(Tensor self, Tensor mask) -> Tensor`` returns a sparse COO
tensor that has the indices and the coalesced state of ``mask`` and the dtype
of ``self``. Measured on the target build:

- The index buffer of the result is the one of ``mask``, in the same order:
  an uncoalesced ``mask`` (duplicate entries included) gives an uncoalesced
  result that keeps every stored entry.
- ``self`` may be strided or sparse COO. A strided ``self`` is read through
  its own strides, so non-contiguous and zero-stride (expanded) inputs are
  valid. A sparse ``self`` contributes the sum of every entry stored at the
  matching index, and zero where it stores nothing; this matches the native
  kernel, which coalesces ``self`` internally.
- Hybrid masks (trailing dense dimensions) keep one value block per stored
  entry.
- The dtype of ``mask`` is irrelevant: only its indices are read.

The device work is the gather itself: one kernel streams the strided values
into the result. The sparse-``self`` path matches indices with a sort and a
binary search, because both of its operands are small index buffers.
"""

