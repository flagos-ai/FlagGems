            hit,
            nnz_c,
            nnz_m,
            block,
            *_axis_args(strides),
            P=sparse_dim,
            STEPS=STEPS,
            BLOCK_I=_BLOCK_I,
            BLOCK_D=_BLOCK_D,
            num_warps=_NUM_WARPS,
