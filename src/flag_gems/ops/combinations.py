"""Triton implementation of ``aten::combinations`` for FlagGems.

``combinations(self, r, with_replacement)`` emits every ordered-by-index
selection of ``r`` elements of the 1-D input, i.e. row ``m`` of the output is
the ``m``-th combination in lexicographic order.  The op is therefore an
index_gather: each output element is one element of the input, so no arithmetic
is needed on the values themselves.

The output is produced by *unranking*: for each row ``m`` the kernel computes the
``r`` source indices directly from ``m`` by subtracting the size of the blocks
of rows that share a leading index, rather than enumerating combinations on the
host.

* ``r == 2`` and ``r == 3`` have closed-form unranking (a quadratic/cubic bound
  refined by exact integer arithmetic), and the r == 2 kernel additionally
  derives three neighbouring rows with lexicographic "next combination" steps,
  so one program writes a (BLOCK, 8) tile.
* every other rank uses a generic binary search over the binomial coefficient.

Integer offsets and the binomial coefficients are computed in int64.  The
binomials are capped at ``2^62`` because the intermediate products of the exact
recurrence can overflow int64 even when the final value fits; the cap is far
above any reachable output size and never changes a result for those.
"""

