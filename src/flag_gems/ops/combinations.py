@triton.jit
def _comb_capped(c, k, cap, R: tl.constexpr):
    # Elementwise exact min(C(c, k), cap) for k >= 1 (int64), with R >= k.
    # Returns 0 when c < k.  Uses symmetry C(c,k) = C(c,c-k) so the
    # multiplicative intermediates are monotone non-decreasing and never
    # exceed the final value (<= total <= 2^62).
    kk = tl.full((), k, tl.int64)
    lt = c < kk
    cs = c - kk
    s = tl.where(cs < kk, cs, kk)  # s = min(c - k, k)
    s = tl.where(s < 0, s * 0, s)  # clamp for c < k (value fixed below)
    v = c * 0 + 1
    for i in tl.static_range(1, R + 1):
        num = c - s + i
        active = i <= s
        prod = v * num // i
        capped = v > cap // num
        v = tl.where(active & capped, cap, v)
        v = tl.where(active & ~capped, prod, v)
    return tl.where(lt, c - c, v)


@triton.jit
def _x2_bound(S, hi):
    # Largest x in [1, hi] with C(x, 2) < S, via fp32 root + bounded refine.
    # Host only uses this for n <= 2^20 (S <= 2^41), where the fp32 estimate
    # is within +/-1 of the exact boundary; 1 refine iteration converges.
    s_f = S.to(tl.float32)
    x = ((1.0 + tl.sqrt(1.0 + 8.0 * s_f)) * 0.5).to(tl.int64)
    x = tl.minimum(x, hi)
    x = tl.where((x + 1) * x // 2 < S, x + 1, x)
    x = tl.where(x * (x - 1) // 2 >= S, x - 1, x)
    return x


@triton.jit
def _x3_bound(S, hi):
    # Largest x in [1, hi] with C(x, 3) < S, via fp32 cbrt root + refine.
    # C(x,3) < x^3/6 makes the raw cbrt an underestimate of x by 1..2, so a
    # +1 bias before truncation lands in [x-1, x+1]; one refine iteration
    # converges (x <= n+1 <= 2^20 keeps fp32 error well below 1).
    s_f = S.to(tl.float32)
    x = (tl.exp(tl.log(6.0 * s_f) / 3.0) + 1.0).to(tl.int64)
    x = tl.minimum(x, hi)
    x = tl.where((x + 1) * x * (x - 1) // 6 < S, x + 1, x)
    x = tl.where(x * (x - 1) * (x - 2) // 6 >= S, x - 1, x)
    return x


@triton.jit
def _advance2(c0, c1, N, WR: tl.constexpr):
    # Lexicographic next-combination advance for r == 2.
    if WR:
        inc1 = c1 < N - 1
        a = tl.where(inc1, c0, c0 + 1)
        b = tl.where(inc1, c1 + 1, c0 + 1)
    else:
        inc1 = c1 < N - 1
        a = tl.where(inc1, c0, c0 + 1)
        b = tl.where(inc1, c1 + 1, c0 + 2)
    return a, b


@triton.jit
def _combinations_kernel(
    out_ptr,
    in_ptr,
    stride,
    n,
    total,
    r: tl.constexpr,
    WR: tl.constexpr,
    BLOCK: tl.constexpr,
):
    # Closed-form unranking for r == 2 only (host guarantees this), processing
    # 4 consecutive rows per lane: row m0 via the fp32-root closed form, rows
    # m0+1..m0+3 via 3 incremental next-combination advances.  Per-lane values
    # form a (BLOCK, 8) tile (exact power of 2, no waste for r == 2) so the
    # single 2D load/store stays fully coalesced/vectorized.
    pid = tl.program_id(0)
    lanes = tl.arange(0, BLOCK)
    m0 = pid * (4 * BLOCK) + 4 * lanes
    m0 = m0.to(tl.int64)
    rmask0 = m0 < total
    m = tl.where(rmask0, m0, m0 * 0)
    off0 = m0 * 2
    st = stride + m * 0
    N = n + m * 0
    if WR:
        # total = C(n+1, 2); i0 = n - x where x = largest C(x,2) < S
        S = N * (N + 1) // 2 - m
        x = _x2_bound(S, N)
        c0 = N - x
        m2 = (x + 1) * x // 2 - S
        c1 = c0 + m2
    else:
        S = N * (N - 1) // 2 - m
        x = _x2_bound(S, N - 1)
        c0 = N - 1 - x
        m2 = (x + 1) * x // 2 - S
        c1 = N - x + m2
    a1, b1 = _advance2(c0, c1, N, WR)
    a2, b2 = _advance2(a1, b1, N, WR)
    a3, b3 = _advance2(a2, b2, N, WR)
    cols = tl.arange(0, 8)
    j0 = (cols % 2 == 0)[None, :]
    t = cols // 2
    r0 = tl.where(j0, c0[:, None], c1[:, None])
    r1 = tl.where(j0, a1[:, None], b1[:, None])
    r2 = tl.where(j0, a2[:, None], b2[:, None])
    r3 = tl.where(j0, a3[:, None], b3[:, None])
    i8 = tl.where(
        t[None, :] == 0,
        r0,
        tl.where(t[None, :] == 1, r1, tl.where(t[None, :] == 2, r2, r3)),
    )
    t64 = t.to(tl.int64)
    rowm = (m0[:, None] + t64[None, :]) < total
    vals = tl.load(in_ptr + i8 * st[:, None], mask=rowm, other=0)
    tl.store(out_ptr + off0[:, None] + cols[None, :], vals, mask=rowm)


