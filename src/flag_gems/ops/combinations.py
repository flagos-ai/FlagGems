@triton.jit
def _unrank_kernel(
    out_ptr,
    in_ptr,
    stride,
    n,
    total,
    r: tl.constexpr,
    WR: tl.constexpr,
    LOGM: tl.constexpr,
    BLOCK: tl.constexpr,
):
    # Generic exact binary-search unranking (any r).
    pid = tl.program_id(0)
    rows = pid * BLOCK + tl.arange(0, BLOCK)
    rmask = rows < total
    m0 = rows.to(tl.int64)
    m = tl.where(rmask, m0, m0 * 0)
    off = rows.to(tl.int64) * r
    st = stride + m * 0
    cap = tl.full((), (1 << 62), tl.int64)
    N = n + m * 0
    lo = m * 0
    for j in range(r):
        rr = r - j
        if WR:
            S = _comb_capped(N - lo + rr - 1, rr, cap, r) - m
            lo_c = lo
            hi_c = (N - 1) + m * 0
            for _ in tl.static_range(LOGM):
                mid = (lo_c + hi_c) >> 1
                fv = _comb_capped(N - mid + rr - 2, rr, cap, r)
                cnd = fv < S
                lo_c = tl.where(cnd, lo_c, mid + 1)
                hi_c = tl.where(cnd, mid, hi_c)
            c = lo_c
            val = tl.load(in_ptr + c * st, mask=rmask, other=0)
            tl.store(out_ptr + off + j, val, mask=rmask)
            m = _comb_capped(N - c + rr - 1, rr, cap, r) - S
            lo = c
        else:
            S = _comb_capped(N - lo, rr, cap, r) - m
            lo_c = lo
            hi_c = (N - rr) + m * 0
            for _ in tl.static_range(LOGM):
                mid = (lo_c + hi_c) >> 1
                fv = _comb_capped(N - 1 - mid, rr, cap, r)
                cnd = fv < S
                lo_c = tl.where(cnd, lo_c, mid + 1)
                hi_c = tl.where(cnd, mid, hi_c)
            c = lo_c
            val = tl.load(in_ptr + c * st, mask=rmask, other=0)
            tl.store(out_ptr + off + j, val, mask=rmask)
            m = _comb_capped(N - c, rr, cap, r) - S
            lo = c + 1


def combinations(self, r=2, with_replacement=False):
    logger.debug("GEMS COMBINATIONS")
    if r < 0:
        raise RuntimeError("Expect a non-negative number, but got {}".format(r))
    if self.dim() != 1:
        raise RuntimeError(
            "Expect a 1D vector, but got shape {}".format(list(self.shape))
        )
    flat = self
    n = flat.numel()
    if r == 0:
        return torch.empty(0, dtype=flat.dtype, device=flat.device)
    if with_replacement:
        total = math.comb(n + r - 1, r) if n + r - 1 >= r else 0
    else:
        total = math.comb(n, r) if n >= r else 0
    out = torch.empty((total, r), dtype=flat.dtype, device=flat.device)
    if total == 0:
        return out
    if r == 2 and n <= (1 << 20):
        grid = (triton.cdiv(total, 4 * _BLOCK),)
        _combinations_kernel[grid](
            out,
            flat,
            flat.stride(0),
            n,
            total,
            r,
            int(with_replacement),
            BLOCK=_BLOCK,
        )
    elif r == 3 and n <= (1 << 20):
        grid = (triton.cdiv(total, _BLOCK),)
        _combinations1_kernel[grid](
            out,
            flat,
            flat.stride(0),
            n,
            total,
            r,
            int(with_replacement),
            BLOCK=_BLOCK,
        )
    else:
        grid = (triton.cdiv(total, _BLOCK),)
        _unrank_kernel[grid](
            out,
            flat,
            flat.stride(0),
            n,
            total,
            r,
            int(with_replacement),
            LOGM=max(1, n.bit_length() + 1),
            BLOCK=_BLOCK,
        )
    return out


