import logging

import torch
import triton
import triton.language as tl

from flag_gems.runtime import torch_device_fn

logger = logging.getLogger(__name__)

_BLOCK_SIZE = 1024
_MAX_RANK = 8


@triton.jit
def _split_copy_contig_kernel(
    src_ptr,
    dst_ptr,
    n_elements,
    src_begin,
    src_period,
    chunk_numel,
    BLOCK_SIZE: tl.constexpr,
):
    """Copy one chunk out of a contiguous input in a single linear pass.

    For a contiguous input the flat source offset of the ``i``-th element of
    the chunk starting at ``chunk_start`` along ``dim`` is

        src_off = (i // chunk_numel) * period + chunk_start * chunk_numel
                  + (i % chunk_numel)

    where ``chunk_numel = split_size * dim_stride`` and ``period =
    dim_size * dim_stride`` (one step along ``dim`` advances ``period``
    elements in the flat layout). The div/mod pair reproduces that mapping
    exactly for every ``dim`` position, so one 1D launch copies the whole
    chunk without per-chunk host round trips.
    """
    pid = tl.program_id(axis=0)
    offsets = pid * BLOCK_SIZE + tl.arange(0, BLOCK_SIZE)
    mask = offsets < n_elements
    offsets = offsets.to(tl.int64)

    src_offsets = (
        (offsets // chunk_numel) * src_period + src_begin + offsets % chunk_numel
    )
    values = tl.load(src_ptr + src_offsets, mask=mask)
    tl.store(dst_ptr + offsets, values, mask=mask)


@triton.jit
def _split_copy_strided_kernel(
    src_ptr,
    dst_ptr,
    s0,
    s1,
    s2,
    s3,
    s4,
    s5,
    s6,
    s7,
    d0,
    d1,
    d2,
    d3,
    d4,
    d5,
    d6,
    d7,
    n_elements,
    src_base,
    RANK: tl.constexpr,
    BLOCK_SIZE: tl.constexpr,
):
    """Gather one chunk out of a (possibly) non-contiguous input.

    The output chunk is contiguous, so its flat offset is the output index.
    Each output index is decomposed row-major over the chunk shape, whose
    ``dim`` extent is the chunk length and whose remaining extents equal the
    input's; every recovered coordinate is scaled by the matching *input*
    stride (the chunked one included), and the wrapper folds the storage
    offset plus ``chunk_start * stride(dim)`` into ``src_base``.
    """
    pid = tl.program_id(axis=0)
    offsets = pid * BLOCK_SIZE + tl.arange(0, BLOCK_SIZE)
    mask = offsets < n_elements
    offsets = offsets.to(tl.int64)

    src_strides = [s0, s1, s2, s3, s4, s5, s6, s7]
    chunk_dims = [d0, d1, d2, d3, d4, d5, d6, d7]

    rem = offsets
    src_offsets = tl.full([], src_base, tl.int64)
    for j in tl.static_range(RANK - 1, -1, -1):
        idx = rem % chunk_dims[j]
        rem = rem // chunk_dims[j]
        src_offsets += idx * src_strides[j]

    values = tl.load(src_ptr + src_offsets, mask=mask)
    tl.store(dst_ptr + offsets, values, mask=mask)


def split_copy(self: torch.Tensor, split_size: int, dim: int = 0):
    """Split ``self`` into chunks of ``split_size`` along ``dim`` and copy each.

    This mirrors ``aten::split_copy``: the out-of-place counterpart of
    ``torch.split``. The last chunk is smaller when ``dim``'s size is not
    divisible by ``split_size``; a ``split_size`` larger than the dimension
    yields a single whole-dimension chunk. Negative ``dim`` is normalized like
    PyTorch. Every output chunk is contiguous, freshly allocated, and never
    aliases the input. 0-dim inputs, out-of-range ``dim`` and non-positive
    ``split_size`` (unless the dimension itself is empty) are rejected with
    the same error messages PyTorch raises.
    """
    logger.debug("GEMS SPLIT_COPY")

    if self.dim() == 0:
        raise RuntimeError("split expects at least a 1-dimensional tensor")
    if split_size < 0:
        raise RuntimeError(
            f"split expects split_size be non-negative, but got split_size={split_size}"
        )

    dim_size = self.size(dim)
    if split_size == 0 and dim_size != 0:
        raise RuntimeError(
            "split_size can only be 0 if dimension size is 0, but got dimension "
            f"size of {dim_size}"
        )
    dim = dim % self.dim()

    dim_stride = self.stride(dim)
    out_shape = list(self.shape)
    out_shape[dim] = min(split_size, dim_size)

    src_strides = [int(s) for s in self.stride()]
    dim_stride = src_strides[dim]
    period = dim_size * dim_stride
    # An empty dimension still splits into a single empty chunk (torch keeps
    # one output whose ``dim`` extent is 0).
    n_chunks = max(1, (dim_size + split_size - 1) // split_size)

    result = []
    chunk_start = 0
    for _ in range(n_chunks):
        chunk_len = min(split_size, dim_size - chunk_start)
        out_shape[dim] = chunk_len
        out = torch.empty(out_shape, dtype=self.dtype, device=self.device)
        n_elements = out.numel()

        if n_elements > 0:
            if self.is_contiguous():
                # For a contiguous input the (period, chunk_numel) div/mod
                # decomposition is exact for every dim position, so a single
                # linear copy covers the whole chunk.
                with torch_device_fn.device(self.device):
                    grid = lambda meta: (triton.cdiv(n_elements, meta["BLOCK_SIZE"]),)
                    _split_copy_contig_kernel[grid](
                        self,
                        out,
                        n_elements,
                        chunk_start * dim_stride,
                        period,
                        chunk_len * dim_stride,
                        BLOCK_SIZE=_BLOCK_SIZE,
                    )
            else:
                rank = self.dim()
                if rank > _MAX_RANK:
                    raise RuntimeError(
                        f"split_copy supports at most {_MAX_RANK} dimensions, "
                        f"got {rank}"
                    )
                # The chunk shape mirrors the input shape with the chunked
                # dimension clamped to the chunk length; both arrays are
                # padded to 8 entries with zero-stride / size-1 slots so the
                # kernel always receives its full fixed argument sets. Order
                # matters: strides first, dims second, matching the kernel
                # signature.
                chunk_strides = list(src_strides)
                chunk_dims = list(self.shape)
                chunk_dims[dim] = chunk_len
                chunk_strides = chunk_strides + [0] * (_MAX_RANK - len(chunk_strides))
                chunk_dims = chunk_dims + [1] * (_MAX_RANK - len(chunk_dims))

                # Kernel-side decomposition recovers the source offset within
                # one ``dim`` slice. ``src_base`` only carries the chunk's
                # first position along ``dim``: Triton receives ``self``'s
                # data pointer, which already includes the storage offset, so
                # it must not be added here again.
                src_base = chunk_start * dim_stride
                with torch_device_fn.device(self.device):
                    grid = lambda meta: (triton.cdiv(n_elements, meta["BLOCK_SIZE"]),)
                    _split_copy_strided_kernel[grid](
                        self,
                        out,
                        *chunk_strides,
                        *chunk_dims,
                        n_elements,
                        src_base,
                        RANK=rank,
                        BLOCK_SIZE=_BLOCK_SIZE,
                    )
        result.append(out)
        chunk_start += chunk_len

    return result
