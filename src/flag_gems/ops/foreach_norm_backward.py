"""Input gradients of the ``_foreach_norm.Scalar`` family.

``torch.ops.aten._foreach_norm_backward`` does not exist in this Torch build:
the only derivative-carrying overload is ``_foreach_norm.Scalar`` and its
gradient is evaluated by the auto-generated ``ForeachNormBackward0`` node,
which calls the shared ``norm_backward`` in
``torch/csrc/autograd/FunctionsManual.cpp`` with ``dim=None``:

    ord == 1     : self.sgn() * grad
    ord == 2     : (self / norm).masked_fill_(norm == 0, 0) * grad
    ord == +-inf : mask = |self| == norm | isnan(|self|)
                   self.sgn() * ((grad / mask.sum()) * mask)
    p < 1        : (sgn * |x|^(p-1)).masked_fill_(x == 0, 0) * grad * norm^(1-p)
    1 < p < 2    : (sgn * |x|^(p-1)) * (grad / norm^(p-1)).masked_fill_(norm == 0, 0)
    p > 2        : (x * |x|^(p-2)) * (grad / norm^(p-1)).masked_fill_(norm == 0, 0)

``ord == 0`` returns an undefined gradient in ATen (a null tensor), so the
explicit entry point refuses it rather than silently producing zeros.

Verified bit-exact against ``torch.autograd.grad`` on CUDA for every branch
(fp16/bf16/fp32/fp64, orders 1/2/3/0.5/+inf/-inf/-1/-2, zero tensors, ties,
nan entries, non-contiguous views).  Two empirically load-bearing details:

* the ``norm`` in the formulas is the *forward* result itself.  For
  fp16/bf16 it is the fp32-accumulated sum rounded once to the storage
  dtype; the elementwise division must use that rounded value, not a fresh
  fp32 reduction, or the result drifts by 1 ulp on some elements.
* ATen evaluates ``(self / norm) * grad`` in that order for ord 2.  In
  fp32, ``(g * x) / n`` rounds differently; the kernel keeps the ATen
  order.

The wrapper recomputes the norms with :func:`flag_gems.ops._foreach_reduction._foreach_norm`
-- the same two-stage reduction FlagGems' forward uses -- so an autograd
bridge that mixes both stays consistent, and the elementwise pass then runs
for the whole list in one launch per ``(device, dtype)`` group through the
shared metadata-buffer layout (pointers to ``grad``, ``self``, the norm
scalar and the output, then element counts).

The ``.List`` and ``.ScalarList`` overloads have no derivatives.yaml entry,
so this module implements exactly the ``.Scalar`` overload: one ``ord``
broadcast to every tensor, one upstream gradient per tensor, one gradient
list out.
"""

