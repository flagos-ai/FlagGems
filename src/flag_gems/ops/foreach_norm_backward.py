@triton.jit
def _aten_pow_scalar(
    base,
    e: tl.constexpr,
    IS32: tl.constexpr,
    IS64: tl.constexpr,
    IS16: tl.constexpr,
    DT: tl.constexpr,
):
    """``torch.pow(tensor, scalar)`` for a float base, mirrored exactly.

    ``pow_tensor_scalar_kernel`` (``aten/src/ATen/native/cuda/PowKernel.cu``)
    special-cases 0.5/-0.5/-1/2/3/-2 and otherwise calls ``::pow``, which on
    device evaluates the *double* ``std::pow(float, double)`` and rounds once
    to float.  ``libdevice.pow`` alone is float-precision ``powf`` and drifts
    up to ~1e-4 relative from that on ordinary values, so the generic case
    widens to fp64 first.  The divides inside the -1/-2 cases must be
    round-to-nearest: Triton's ``/`` lowers to ``div.approx`` on fp32.
    ``IS32``/``IS64``/``IS16`` are compile-time dtype selectors (Triton traces
    every branch of a runtime condition, so the dtype switch has to be
    constexpr).  For the Half/BFloat16 dispatch the multi-step special cases
    square/cube *in the storage dtype* -- the lambda's ``base * base`` on
    ``at::Half`` rounds through the Half constructor between steps -- so
    ``IS16`` rounds each sub-product back to ``base.dtype``.
    """
    if e == 0.5:
        if IS64:
            r = tl.sqrt(base)
        elif IS32:
            # fp32 needs the IEEE-rounded sqrt.rn: ``tl.sqrt`` lowers to a
            # faster approximation on fp32 that torch's sqrt kernel (which
            # the 0.5 exponent dispatches to) never produces.
            r = tl.sqrt_rn(base)
        else:
            # fp16/bf16 widen to the fp32 opmath before the sqrt.
            r = tl.sqrt_rn(base.to(tl.float32))
        return r
    elif e == -0.5:
        if IS64:
            r = tl_extra_shim.rsqrt(base)
        elif IS32:
            r = tl_extra_shim.rsqrt(base)
        else:
            r = tl_extra_shim.rsqrt(base.to(tl.float32))
        return r
    elif e == 1.0:
        return base
    elif e == -1.0:
        if IS64:
            r = 1.0 / base
        else:
            r = tl.math.div_rn(1.0, base)
        return r
    elif e == 2.0:
        # For fp16/bf16 ATen's lambda rounds ``base * base`` into the storage
        # dtype (the at::Half ctor between sub-steps).  A ``tl.where`` on the
        # constexpr selector keeps one dtype per instantiation, which the
        # tracer requires.
        sq = base * base
        return tl.where(IS16, sq.to(DT).to(tl.float32), sq)
    elif e == 3.0:
        sq = base * base
        cube = sq * base
        sq16 = sq.to(DT).to(tl.float32)
        return tl.where(IS16, (sq16 * base).to(DT).to(tl.float32), cube)
    elif e == -2.0:
        sq = base * base
        sq16 = sq.to(DT).to(tl.float32)
        sq_use = tl.where(IS16, sq16, sq)
        if IS64:
            r = 1.0 / sq_use
        else:
            r = tl.math.div_rn(1.0, sq_use)
        return r
    else:
        b64 = base.to(tl.float64)
        e64 = tl.full((), e, dtype=tl.float64)
        r64 = tl_extra_shim.pow(b64, e64)
        if IS64:
            return r64
        return r64.to(base.dtype)


@triton.jit
def foreach_norm_backward_kernel(
    meta_ptr,
    NT: tl.constexpr,
    DT: tl.constexpr,
    AW: tl.constexpr,
    IS32: tl.constexpr,
    IS64: tl.constexpr,
    IS16: tl.constexpr,
    ORD: tl.constexpr,
    IS_INF: tl.constexpr,
    IS_NEGINF: tl.constexpr,
    BLOCK: tl.constexpr,
):
    """One launch per ``(device, dtype)`` group.

    Metadata layout, all int64::

        [0,        NT)   grad_output pointers
        [NT,     2*NT)   self pointers
        [2*NT,   3*NT)   grad_self pointers
        [3*NT,   4*NT)   norm values (one 0-dim forward result per tensor)
        [4*NT,   5*NT)   element counts

    ``ORD`` is the runtime order as a float (ignored for the constexpr
    branches 1/2).  Every intermediate is rounded to the storage dtype
    exactly as the ATen chain does, which is what makes fp16/bf16 bit-exact
    against autograd.
    """
    t = tl.program_id(1)
    offset = tl.program_id(0) * BLOCK

    grad_raw = tl.load(meta_ptr + t)
    self_raw = tl.load(meta_ptr + NT + t)
    out_raw = tl.load(meta_ptr + 2 * NT + t)
    norm_raw = tl.load(meta_ptr + 3 * NT + t)
    n_elements = tl.load(meta_ptr + 4 * NT + t)

    grad_ptr = grad_raw.to(tl.pointer_type(DT))
    self_ptr = self_raw.to(tl.pointer_type(DT))
    out_ptr = out_raw.to(tl.pointer_type(DT))
    norm_ptr = norm_raw.to(tl.pointer_type(DT))

    idx = offset + tl.arange(0, BLOCK)
    mask = idx < n_elements

    norm_val = tl.load(norm_ptr)
    x = tl.load(self_ptr + idx, mask=mask, other=0.0)
    g = tl.load(grad_ptr)

    if IS_INF or IS_NEGINF:
        # mask = |x| == norm | isnan(|x|); grad / mask.sum() * mask, then * sgn(x).
        # The shim's isnan has no fp16 overload, so the magnitude is tested in
        # fp32 (an exact widening: fp16 nan casts to fp32 nan).
        ax = tl.abs(x)
        axf = ax.to(tl.float32)
        m = (ax == norm_val) | tl_extra_shim.isnan(axf)
        msum = tl.sum(m.to(tl.float32), axis=0)
        g_over = tl.where(m, g / msum, 0.0)
        sgn = tl.where(x > 0, 1.0, tl.where(x < 0, -1.0, 0.0))
        out = g_over * sgn
    elif ORD == 1.0:
        # self.sgn() * grad
        sgn = tl.where(x > 0, 1.0, tl.where(x < 0, -1.0, 0.0))
        out = sgn * g
    elif ORD == 2.0:
        # ATen order: (self / norm) first, masked_fill for a zero norm, then * grad.
        ratio = (x / norm_val).to(DT).to(tl.float32)
        ratio = tl.where(norm_val == 0.0, 0.0, ratio)
        out = (ratio * g).to(DT)
    else:
        # Finite p != 1/2: branch on the runtime value of ORD.  ATen evaluates
        # the chain as a series of *tensor* ops, so for fp16/bf16 every
        # intermediate materialises in fp32 opmath and rounds back to the
        # storage dtype between steps; for fp32/fp64 the chain runs in the
        # input dtype itself.  Compute with ``AW`` (the working dtype: fp32
        # for the half types, DT otherwise) and round through DT exactly at
        # the op boundaries ATen materialises.
        p = ORD
        if p < 1.0:
            sgn = tl.where(x > 0, 1.0, tl.where(x < 0, -1.0, 0.0))
            mag = tl.abs(x).to(AW)
            self_scaled = (
                (sgn * _aten_pow_scalar(mag, ORD - 1.0, IS32, IS64, IS16, DT))
                .to(DT)
                .to(AW)
            )
            self_scaled = tl.where(x == 0.0, 0.0, self_scaled)
            root = (
                _aten_pow_scalar(tl.abs(norm_val), 1.0 - ORD, IS32, IS64, IS16, DT)
                .to(DT)
                .to(AW)
            )
            t1 = (self_scaled * g).to(DT).to(AW)
            out = (t1 * root).to(DT)
        elif p < 2.0:
            sgn = tl.where(x > 0, 1.0, tl.where(x < 0, -1.0, 0.0))
            mag = tl.abs(x).to(AW)
            self_scaled = (
                (sgn * _aten_pow_scalar(mag, ORD - 1.0, IS32, IS64, IS16, DT))
                .to(DT)
                .to(AW)
            )
            scale_v = (
                (
                    g
                    / _aten_pow_scalar(
                        tl.abs(norm_val), ORD - 1.0, IS32, IS64, IS16, DT
                    )
                    .to(DT)
                    .to(AW)
                )
                .to(DT)
                .to(AW)
            )
            scale_v = tl.where(norm_val == 0.0, 0.0, scale_v)
            out = (self_scaled * scale_v).to(DT)
        else:
            mag = tl.abs(x).to(AW)
            # ATen materialises ``self.abs().pow_(p-2)`` (a tensor op) in the
            # storage dtype before the multiply reads it, and likewise for
            # ``norm.pow(p-1)`` before the divide.
            mag_pow = (
                _aten_pow_scalar(mag, ORD - 2.0, IS32, IS64, IS16, DT).to(DT).to(AW)
            )
            self_scaled = (x.to(AW) * mag_pow).to(DT).to(AW)
            scale_v = (
                (
                    g
                    / _aten_pow_scalar(
                        tl.abs(norm_val), ORD - 1.0, IS32, IS64, IS16, DT
                    )
                    .to(DT)
                    .to(AW)
                )
                .to(DT)
                .to(AW)
            )
            scale_v = tl.where(norm_val == 0.0, 0.0, scale_v)
            out = (self_scaled * scale_v).to(DT)

    tl.store(out_ptr + idx, out.to(DT), mask=mask)


@triton.jit
def _f64_norm_kernel(
    meta_ptr,
    NT: tl.constexpr,
    ORD: tl.constexpr,
    IS_INF: tl.constexpr,
    IS_NEGINF: tl.constexpr,
    G: tl.constexpr,
    BLOCK: tl.constexpr,
):
    """One-program-per-tensor fp64 norm of order ``ORD``.

    The shared forward's reduction stage accumulates in fp32 (an exact
    widening for fp16/bf16 but a lossy narrowing for fp64), which costs the
    backward more than the fp64 rtol once the norm is raised to ``p-1`` or
    ``1-p``.  This kernel accumulates in fp64 so a list of gradients matches
    the native autograd chain inside the fp64 tolerance.
    """
    t = tl.program_id(0)
    in_ptr = tl.load(meta_ptr + t).to(tl.pointer_type(tl.float64))
    out_ptr = tl.load(meta_ptr + NT + t).to(tl.pointer_type(tl.float64))
    n_elements = tl.load(meta_ptr + 2 * NT + t)

    n_blocks = tl.cdiv(n_elements, BLOCK)
    per_chunk = tl.cdiv(n_blocks, G)
    first = tl.program_id(1) * per_chunk
    last = tl.minimum(first + per_chunk, n_blocks)

    acc = tl.zeros((BLOCK,), dtype=tl.float64)
    if IS_NEGINF:
        acc = tl.full((BLOCK,), float("inf"), dtype=tl.float64)
    for b in tl.range(first, last):
        idx = b * BLOCK + tl.arange(0, BLOCK)
        mask = idx < n_elements
        x = tl.load(in_ptr + idx, mask=mask, other=0.0)
        mag = tl.abs(x)
        if IS_INF:
            acc = tl.maximum(acc, mag)
        elif IS_NEGINF:
            acc = tl.minimum(acc, tl.where(mask, mag, float("inf")))
        elif ORD == 1.0:
            acc += mag
        elif ORD == 2.0:
            acc += mag * mag
        else:
            acc += tl.where(
                mask, tl.exp(ORD * tl.log(tl.where(mag > 0, mag, 1e-300))), 0.0
            )

    if IS_INF:
        part = tl.max(acc)
    elif IS_NEGINF:
        part = tl.min(acc)
    elif ORD == 2.0:
        part = tl.sqrt(tl.sum(acc))
    elif ORD == 1.0:
        part = tl.sum(acc)
    else:
        e64 = tl.full((), 1.0 / ORD, dtype=tl.float64)
        part = tl_extra_shim.pow(tl.sum(acc), e64)
    part = tl.where(n_elements == 0, 0.0, part)
    tl.store(out_ptr + t, part)


def _f64_norms(tensors: List[torch.Tensor], ord_f: float) -> List[torch.Tensor]:
    """fp64 norms for the fp64 tensors of the list, one launch per tensor."""
    ord_f = float(ord_f)
    inf_mode = 1 if ord_f == float("inf") else (-1 if ord_f == float("-inf") else 0)
    results: List[torch.Tensor] = [None] * len(tensors)
    for i, t in enumerate(tensors):
        if t.dtype != torch.float64:
            continue
        device = t.device
        a = t if t.is_contiguous() else t.contiguous()
        out = torch.empty((), dtype=torch.float64, device=device)
        meta = torch.tensor(
            [a.data_ptr(), out.data_ptr(), a.numel()],
            dtype=torch.int64,
            device=device,
        )
        with torch_device_fn.device(device):
            _f64_norm_kernel[(1, 1)](
                meta,
                1,
                ord_f,
                inf_mode == 1,
                inf_mode == -1,
                1,
                1024,
                num_warps=_NUM_WARPS,
            )
        results[i] = out
    return results


def foreach_norm_backward(
    grad_output: Sequence[torch.Tensor],
    self_: Sequence[torch.Tensor],
    ord=2,
) -> List[torch.Tensor]:
    """Gradients of ``torch.ops.aten._foreach_norm.Scalar(self, ord)``.

    Args:
        grad_output: Upstream gradients, one 0-dim scalar per forward output
            (the norm result of the corresponding tensor).
        self_: The original inputs, one tensor per position.
        ord: The order of the norm, matching the forward call.

    Returns:
        List ``grad_self``: per-position gradients with the shapes and
        dtypes of ``self_``.

    The argument order follows the derivatives.yaml entry
    (``norm_backward(grads[i], self[i], ord, result[i])``) with the grad
    list first, matching the ``div_backward`` entry point convention.
    """
    logger.debug("GEMS _FOREACH_NORM_BACKWARD")
    grad_list = list(check_tensor_list(grad_output))
    self_list = list(check_tensor_list(self_))
    if len(grad_list) != len(self_list):
        raise RuntimeError(
            "Tensor list must have same number of elements as grad_output, "
            f"got {len(self_list)} and {len(grad_list)}"
        )
    for t in self_list:
        check_dtype_supported(t.dtype, _GRAD_DTYPES)

    ord_f = float(ord)
    if ord_f == 0.0:
        raise RuntimeError(
            "foreach_norm_backward: ord=0 has no derivative (ATen returns an "
            "undefined gradient for the 0-norm)."
        )

    # The norms the formulas reference are the forward results: recomputed
    # with the FlagGems forward so an autograd bridge mixing both stays
    # consistent, and fp16/bf16 rounding matches.  (fp64 inputs go through a
    # dedicated double-precision reduction below: the shared forward's stage
    # one accumulates in fp32, which would cost the backward three orders of
    # magnitude against the fp64 rtol.)
    if any(t.dtype == torch.float64 for t in self_list):
        norms = _f64_norms(self_list, ord_f)
        # The fp64 kernel skips other dtypes: those keep the shared forward.
        missing = [i for i, n in enumerate(norms) if n is None]
        if missing:
            rest = _foreach_norm([self_list[i] for i in missing], ord=ord_f, dtype=None)
            for i, n in zip(missing, rest):
                norms[i] = n
    else:
        norms = _foreach_norm(self_list, ord=ord_f, dtype=None)

    grad_self_out: List[torch.Tensor] = [None] * len(self_list)

    # Group by (device, dtype)
    groups: dict = {}
    for i, x in enumerate(self_list):
        groups.setdefault((x.device, x.dtype), []).append(i)

    for (device, dtype), indices in groups.items():
        nt = len(indices)
        numels = [self_list[i].numel() for i in indices]
        max_numel = max(numels)
        if max_numel == 0:
            for pos, i in enumerate(indices):
                grad_self_out[i] = torch.empty(
                    self_list[i].shape, dtype=dtype, device=device
                )
            continue

        grads_run: List[int] = []
        selves_run: List[int] = []
        outs_run: List[int] = []
        norm_run: List[int] = []
        out_bufs: List[torch.Tensor] = [None] * nt
        for pos, i in enumerate(indices):
            g = grad_list[i].reshape(())
            a = self_list[i].contiguous()
            o = torch.empty(a.shape, dtype=dtype, device=device)
            out_bufs[pos] = o
            n = norms[i].reshape(())
            grads_run.append(g.data_ptr())
            selves_run.append(a.data_ptr())
            outs_run.append(o.data_ptr())
            norm_run.append(n.data_ptr())

        values = grads_run + selves_run + outs_run + norm_run + numels
        meta = torch.tensor(values, dtype=torch.int64, device=device)

        block = _BLOCK
        for candidate in (1024, 2048, 4096, 8192, 16384):
            block = candidate
            if nt * ((max_numel + candidate - 1) // candidate) <= (1 << 18):
                break
        grid = (triton.cdiv(max_numel, block), nt)

        kernel_dt = tl_dtype(dtype)
        is_inf = math.isinf(ord_f) and ord_f > 0
        is_neginf = math.isinf(ord_f) and ord_f < 0

        with torch_device_fn.device(device):
            foreach_norm_backward_kernel[grid](
                meta,
                nt,
                kernel_dt,
                tl_dtype(torch.float32) if dtype.itemsize < 4 else kernel_dt,
                dtype == torch.float32,
                dtype == torch.float64,
                dtype.itemsize == 2,
                ord_f,
                is_inf,
                is_neginf,
                block,
                num_warps=_NUM_WARPS,
            )
        for pos, i in enumerate(indices):
            grad_self_out[i] = out_bufs[pos]

    return grad_self_out


