    pid_n = tl.program_id(1)

    KK = KH * KW
    co = pid_m * BLOCK_M + tl.arange(0, BLOCK_M)
    mco = co < CO
    jj = pid_n * BLOCK_N + tl.arange(0, BLOCK_N)
    mj = jj < CIKK
    ss = tl.arange(0, BLOCK_S)
    ms = ss < SPLIT_K

    v = tl.load(
        part_ptr
        + ss[:, None, None] * SP_PID
        + co[None, :, None] * SP_CO
        + jj[None, None, :],
        mask=ms[:, None, None] & mco[None, :, None] & mj[None, None, :],
        other=0.0,
    )
    if F64:
        acc = tl.sum(v, axis=0)
    else:
        acc = tl.sum(v.to(tl.float32), axis=0)

    cij = jj // KK
    rem = jj - cij * KK
    khj = rem // KW
    kwj = rem - khj * KW
    o_off = (
        co[:, None] * SO_CO
        + cij[None, :] * SO_CI
        + khj[None, :] * SO_KH
        + kwj[None, :] * SO_KW
    )
    tl.store(
        out_ptr + o_off,
        acc.to(out_ptr.dtype.element_ty),
        mask=mco[:, None] & mj[None, :],
    )

    if HAS_B:
        # grad_bias shares the (n, ho, wo) reduction axis with grad_weight, so
        # its per-slab partials ride along on the same split-K slabs. A single
        # program walks the whole CO range: the (M, N) grid is tiled for the
        # grad_weight columns (CI*kH*kW), which is a different extent from CO,
        # so reusing those lanes would leave part of the bias vector unwritten.
        if pid_m == 0 and pid_n == 0:
            for c0 in range(0, CO, BLOCK_N):
                cb = c0 + tl.arange(0, BLOCK_N)
                mcb = cb < CO
                vb = tl.load(
                    bpart_ptr + ss[:, None] * B_STRIDE_PID + cb[None, :],
                    mask=ms[:, None] & mcb[None, :],
                    other=0.0,
                )
                if F64:
                    bs = tl.sum(vb, axis=0)
                else:
                    bs = tl.sum(vb.to(tl.float32), axis=0)
                tl.store(gb_ptr + cb, bs.to(gb_ptr.dtype.element_ty), mask=mcb)


