@triton.jit
def _gb_partial_kernel(
    go_ptr,
    part_ptr,
    CO,
    K,
    HO,
    WO,
    SGO_N,
    SGO_CO,
    SGO_HO,
    SGO_WO,
    F64: tl.constexpr,
    BLOCK_CO: tl.constexpr,
    BLOCK_K: tl.constexpr,
):
    pid_co = tl.program_id(0)
    pid_k = tl.program_id(1)
    co = pid_co * BLOCK_CO + tl.arange(0, BLOCK_CO)
    mco = co < CO
    HW = HO * WO
    k = pid_k * BLOCK_K + tl.arange(0, BLOCK_K)
    mk = k < K
    n = k // HW
    r = k - n * HW
    ho = r // WO
    wo = r - ho * WO
    off = n * SGO_N + co[:, None] * SGO_CO + ho[None, :] * SGO_HO + wo[None, :] * SGO_WO
    v = tl.load(go_ptr + off, mask=mco[:, None] & mk[None, :], other=0.0)
    if F64:
        acc = tl.sum(v, axis=1)
    else:
        acc = tl.sum(v.to(tl.float32), axis=1)
    tl.store(part_ptr + pid_k * CO + co, acc, mask=mco)


@triton.jit
def _gb_final_kernel(
    part_ptr,
    out_ptr,
    NPART,
    CO,
    F64: tl.constexpr,
    BLOCK_CO: tl.constexpr,
    BLOCK_P: tl.constexpr,
):
    pid = tl.program_id(0)
    co = pid * BLOCK_CO + tl.arange(0, BLOCK_CO)
    mco = co < CO
    if F64:
        acc = tl.zeros((BLOCK_CO,), dtype=tl.float64)
    else:
        acc = tl.zeros((BLOCK_CO,), dtype=tl.float32)
    for p0 in range(0, NPART, BLOCK_P):
        pp = p0 + tl.arange(0, BLOCK_P)
        mp = pp < NPART
        v = tl.load(
            part_ptr + pp[:, None] * CO + co[None, :],
            mask=mp[:, None] & mco[None, :],
            other=0.0,
        )
        acc += tl.sum(v, axis=0)
    tl.store(out_ptr + co, acc.to(out_ptr.dtype.element_ty), mask=mco)


