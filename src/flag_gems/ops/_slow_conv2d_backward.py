def _gi_kernel(
    go_ptr,
    w_ptr,
    out_ptr,
    CO,
    CI,
    HO,
    WO,
    H,
    W,
    SGO_N,
    SGO_CO,
    SGO_HO,
    SGO_WO,
    SW_CO,
    SW_CI,
    SW_KH,
    SW_KW,
    SO_N,
    SO_CI,
    SO_H,
    SO_W,
    KH: tl.constexpr,
    KW: tl.constexpr,
    SH: tl.constexpr,
    SW: tl.constexpr,
    PH: tl.constexpr,
    PW: tl.constexpr,
    F64: tl.constexpr,
    BLOCK_CI: tl.constexpr,
    BLOCK_HW: tl.constexpr,
):
    pid_hw = tl.program_id(0)
    pid_ci = tl.program_id(1)
    n = tl.program_id(2)

    HW = H * W
    hw = pid_hw * BLOCK_HW + tl.arange(0, BLOCK_HW)
    mhw = hw < HW
    ih = hw // W
    iw = hw - ih * W

    ci = pid_ci * BLOCK_CI + tl.arange(0, BLOCK_CI)
    mci = ci < CI

    if F64:
        acc = tl.zeros((BLOCK_CI, BLOCK_HW), dtype=tl.float64)
    else:
        acc = tl.zeros((BLOCK_CI, BLOCK_HW), dtype=tl.float32)

    for kh in tl.static_range(KH):
        hh = ih + PH - kh
        oh = hh // SH
        okh = (hh >= 0) & (hh - oh * SH == 0) & (oh < HO)
        for kw in tl.static_range(KW):
            ww = iw + PW - kw
            ow = ww // SW
            okw = (ww >= 0) & (ww - ow * SW == 0) & (ow < WO)
            ok = mhw & okh & okw
            go_base = go_ptr + n * SGO_N + oh * SGO_HO + ow * SGO_WO
            w_base = w_ptr + ci * SW_CI + kh * SW_KH + kw * SW_KW
            for co_i in range(0, CO):
                g = tl.load(go_base + co_i * SGO_CO, mask=ok, other=0.0)
                wv = tl.load(w_base + co_i * SW_CO, mask=mci, other=0.0)
                # Reference rule: out-of-range taps are zero-padded BEFORE the
                # multiply, so they contribute an exact 0 even for NaN weights.
                # Selecting the whole product is required (0 * NaN == NaN).
                if F64:
                    acc += tl.where(ok[None, :], wv[:, None] * g[None, :], 0.0)
                else:
                    acc += tl.where(
                        ok[None, :],
                        wv[:, None].to(tl.float32) * g[None, :].to(tl.float32),
                        0.0,
                    )

    o_off = n * SO_N + ci[:, None] * SO_CI + ih[None, :] * SO_H + iw[None, :] * SO_W
    tl.store(
        out_ptr + o_off,
        acc.to(out_ptr.dtype.element_ty),
        mask=mci[:, None] & mhw[None, :],
    )


