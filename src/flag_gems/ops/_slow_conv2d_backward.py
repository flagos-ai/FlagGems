    pid_co = tl.program_id(0)
    pid_k = tl.program_id(1)
    co = pid_co * BLOCK_CO + tl.arange(0, BLOCK_CO)
    mco = co < CO
    HW = HO * WO
    k = pid_k * BLOCK_K + tl.arange(0, BLOCK_K)
    mk = k < K
    n = k // HW
    r = k - n * HW
    ho = r // WO
    wo = r - ho * WO
    off = n * SGO_N + co[:, None] * SGO_CO + ho[None, :] * SGO_HO + wo[None, :] * SGO_WO
