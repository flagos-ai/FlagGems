"""Sparse tensor sum (``aten::_sparse_sum``, five overloads).

``aten::_sparse_sum`` sums a sparse COO tensor.  The aten implementation
(``aten/src/ATen/native/sparse/SparseTensorMath.cpp``) has two distinct
semantics:

* ``_sparse_sum(self)`` / ``.dtype(self, dtype)`` sum **every** stored value:
  ``self.coalesce().values().sum(dtype)``.  The result is a 0-D dense tensor
  (an ``int64`` scalar for integer/bool inputs unless ``dtype`` says
  otherwise).
* ``.dim(self, dim)`` / ``.dim_dtype`` project the stored entries onto the
  kept dims.  Dense dims inside the values are summed first, then the
  projection is coalesced: entries sharing the kept sparse coordinates are
  added together and explicit structural zeros survive as stored entries.
  The result is a coalesced COO tensor whenever at least one sparse dim
  survives; summing every sparse dim returns a dense tensor over the kept
  dense dims.  ``.dim_dtype`` casts the tensor to ``dtype`` first, so the
  accumulation happens in the requested dtype.
* ``.dim_out(self, dim, out=...)`` computes the same result and writes it
  into ``out``.

Only COO inputs dispatch (CSR/CSC raise in aten) and a dense input raises.

The single-value ``default``/``.dtype`` paths reduce the coalesced value
buffer with a two-stage Triton reduction following the ``Tensor.sum``
accumulator rules: fp16/bf16/fp32 accumulate in fp32, fp64 in fp64 and
integers/bools in int64 before the final cast (integer narrowing is modular,
so accumulating wide is exact).

The ``dim`` paths stay sparse, and their projection + coalesce dominates
aten's runtime because aten sorts the projected coordinates on the GPU.  This
implementation replaces the sort with a stable partition:

1. ``_ssum_scatter`` folds every stored entry into a dense per-kept-coordinate
   accumulator with atomics and flags the coordinate as present.  Structural
   zeros therefore keep their slot, matching aten's behaviour of coalescing
   (not dropping) explicit zeros.
2. ``_ssum_count`` / ``_ssum_scan`` turn the presence flags into per-block
   counts and exclusive offsets.
3. ``_ssum_emit`` walks the flags in ascending key order, decodes each kept
   coordinate back into per-dim indices and writes the folded value, so the
   output is row-major sorted and coalesced exactly like aten.

``_ssum_dense_sum`` handles the dense-dim reduction of hybrid sparse tensors
and ``_ssum_reduce_rows`` the dense result of summing every sparse dim.
"""

