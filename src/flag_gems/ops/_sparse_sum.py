def _acc_mode(dtype):
    """Return ``(mode, accumulator_dtype)`` used to fold values of ``dtype``."""
    if dtype in _ACC_F32_DTYPES:
        return ACC_F32, torch.float32
    if dtype == torch.float64:
        return ACC_F64, torch.float64
    return ACC_I64, torch.int64


def _sum_result_dtype(dtype, out_dtype):
    """Result dtype of ``values.sum(out_dtype)`` for the given value dtype."""
    if out_dtype is not None:
        return out_dtype
    if dtype in _INT_RESULT_DTYPES:
        return torch.int64
    return dtype


def _numel(shape):
    total = 1
    for size in shape:
        total *= size
    return total


def _mask_bits(flags):
    """Fold per-position booleans into a ``tl.constexpr`` bit mask."""
    mask = 0
    for i, flag in enumerate(flags):
        if flag:
            mask |= 1 << i
    return mask


def _int_table(values, device):
    return torch.tensor(values, dtype=torch.int64, device=device)


@libentry()
@triton.jit
def _ssum_scatter(
    idx_ptr,
    val_ptr,
    acc_ptr,
    flag_ptr,
    nnz,
    stride_ptr,
    DENSE_NUM: tl.constexpr,
    KEEP_MASK: tl.constexpr,
    SPARSE_DIM: tl.constexpr,
    BLOCK: tl.constexpr,
):
    # Fold every stored entry into the accumulator slot of its kept
    # coordinate.  ``stride_ptr`` holds the row-major key stride per sparse
    # dim (0 for summed dims), so the key is the rank of the kept coordinates.
    pid = ext.program_id(0)
    offs = pid * BLOCK + tl.arange(0, BLOCK)
    mask = offs < nnz
    key = tl.zeros([BLOCK], dtype=tl.int64)
    for d in tl.static_range(SPARSE_DIM):
        if (KEEP_MASK >> d) & 1:
            coord = tl.load(idx_ptr + d * nnz + offs, mask=mask, other=0).to(tl.int64)
            stride = tl.load(stride_ptr + d).to(tl.int64)
            key += coord * stride
    acc_t = acc_ptr.dtype.element_ty
    for j in tl.static_range(DENSE_NUM):
        val = tl.load(val_ptr + offs * DENSE_NUM + j, mask=mask, other=0)
        tl.atomic_add(acc_ptr + key * DENSE_NUM + j, val.to(acc_t), mask=mask)
    tl.store(flag_ptr + key, 1, mask=mask)


@libentry()
@triton.jit
def _ssum_count(flag_ptr, count_ptr, n, BLOCK: tl.constexpr):
    pid = ext.program_id(0)
    offs = pid * BLOCK + tl.arange(0, BLOCK)
    mask = offs < n
    flag = tl.load(flag_ptr + offs, mask=mask, other=0)
    tl.store(count_ptr + pid, tl.sum(flag, axis=0))


@libentry()
@triton.jit
def _ssum_scan(count_ptr, base_ptr, nblocks, BLOCK: tl.constexpr):
    # Exclusive prefix sum over the per-block counts (single program; the
    # number of blocks is the key space divided by BLOCK).
    offs = tl.arange(0, BLOCK)
    mask = offs < nblocks
    count = tl.load(count_ptr + offs, mask=mask, other=0)
    inclusive = tl.cumsum(count, axis=0)
    tl.store(base_ptr + offs, inclusive - count, mask=mask)


@libentry()
@triton.jit
def _ssum_emit(
    flag_ptr,
    acc_ptr,
    out_idx_ptr,
    out_val_ptr,
    base_ptr,
    key_space,
    out_nnz,
    stride_ptr,
    DENSE_NUM: tl.constexpr,
    KEEP_MASK: tl.constexpr,
    SPARSE_DIM: tl.constexpr,
    BLOCK: tl.constexpr,
):
    # Emit the surviving coordinates in ascending key order.  The key is
    # decoded with the same strides used to build it, so the output indices
    # are row-major sorted like ``coalesce``.
    pid = ext.program_id(0)
    offs = pid * BLOCK + tl.arange(0, BLOCK)
    mask = offs < key_space
    flag = tl.load(flag_ptr + offs, mask=mask, other=0)
    rank = tl.cumsum(flag, axis=0) - 1
    pos = tl.load(base_ptr + pid) + rank
    active = mask & (flag != 0)
    remain = offs.to(tl.int64)
    row = 0
    for d in tl.static_range(SPARSE_DIM):
        if (KEEP_MASK >> d) & 1:
            stride = tl.load(stride_ptr + d).to(tl.int64)
            coord = remain // stride
            tl.store(out_idx_ptr + row * out_nnz + pos, coord, mask=active)
            remain = remain % stride
            row += 1
    for j in tl.static_range(DENSE_NUM):
        val = tl.load(acc_ptr + offs * DENSE_NUM + j, mask=active, other=0)
        tl.store(out_val_ptr + pos * DENSE_NUM + j, val, mask=active)


@libentry()
@triton.jit
def _ssum_dense_sum(
    val_ptr,
    out_ptr,
    dense_num,
    out_num,
    out_stride_ptr,
    size_ptr,
    in_stride_ptr,
    DENSE_DIM: tl.constexpr,
    KEEP_MASK: tl.constexpr,
    BLOCK: tl.constexpr,
):
    # Sum the requested dense dims of one stored value block.  One program per
    # stored entry walks its flat dense block and folds every element into the
    # kept-coordinate slot; the caller zeroes ``out_ptr`` first.
    entry = ext.program_id(0)
    acc_t = out_ptr.dtype.element_ty
    base = entry.to(tl.int64) * out_num
    for start in range(0, dense_num, BLOCK):
        offs = start + tl.arange(0, BLOCK)
        mask = offs < dense_num
        val = tl.load(val_ptr + entry * dense_num + offs, mask=mask, other=0)
        pos = tl.zeros([BLOCK], dtype=tl.int64)
        for d in tl.static_range(DENSE_DIM):
            if (KEEP_MASK >> d) & 1:
                size = tl.load(size_ptr + d).to(tl.int64)
                in_stride = tl.load(in_stride_ptr + d).to(tl.int64)
                out_stride = tl.load(out_stride_ptr + d).to(tl.int64)
                coord = (offs.to(tl.int64) // in_stride) % size
                pos += coord * out_stride
        tl.atomic_add(out_ptr + base + pos, val.to(acc_t), mask=mask)


@libentry()
@triton.jit
def _ssum_reduce_rows(
    val_ptr,
    out_ptr,
    nnz,
    dense_num,
    BLOCK_N: tl.constexpr,
    BLOCK_C: tl.constexpr,
):
    # Reduce the stored-entry axis of an ``(nnz, dense_num)`` block into a
    # dense row of ``dense_num`` values.
    pid = ext.program_id(0)
    cols = pid * BLOCK_C + tl.arange(0, BLOCK_C)
    cmask = cols < dense_num
    acc_t = out_ptr.dtype.element_ty
    acc = tl.zeros([BLOCK_C], dtype=acc_t)
    for start in range(0, nnz, BLOCK_N):
        rows = start + tl.arange(0, BLOCK_N)
        mask = (rows < nnz)[:, None] & cmask[None, :]
        val = tl.load(
            val_ptr + rows[:, None] * dense_num + cols[None, :], mask=mask, other=0
        )
        acc += tl.sum(val.to(acc_t), axis=0)
    tl.store(out_ptr + cols, acc, mask=cmask)


@libentry()
@triton.jit
def _ssum_stage1(val_ptr, mid_ptr, n, BLOCK: tl.constexpr, MODE: tl.constexpr):
    pid = ext.program_id(0)
    offs = pid * BLOCK + tl.arange(0, BLOCK)
    mask = offs < n
    val = tl.load(val_ptr + offs, mask=mask, other=0)
    if MODE == ACC_F32:
        val = val.to(tl.float32)
    elif MODE == ACC_I64:
        val = val.to(tl.int64)
    tl.store(mid_ptr + pid, tl.sum(val, axis=0))


