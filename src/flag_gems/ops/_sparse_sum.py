def _reduce_values(values, out_dtype):
    """``values.sum(out_dtype)`` over the whole value buffer."""
    values = values.contiguous()
    mode, acc_dtype = _acc_mode(values.dtype)
    total = _sum_result_dtype(values.dtype, out_dtype)
    num = values.numel()
    device = values.device
    with torch_device_fn.device(device):
        if num == 0:
            out = torch.zeros((), dtype=acc_dtype, device=device)
        else:
            # Two-stage reduction: 1024 elements per program keeps the
            # partial-sum buffer (num / 1024) small enough for stage 2.
            block = 1024
            mid_num = triton.cdiv(num, block)
            mid = torch.empty(mid_num, dtype=acc_dtype, device=device)
            _ssum_stage1[(mid_num,)](values, mid, num, BLOCK=block, MODE=mode)
            out = torch.empty((), dtype=acc_dtype, device=device)
            _ssum_stage2[(1,)](
                mid, out, mid_num, BLOCK=triton.next_power_of_2(mid_num), MODE=mode
            )
    return out.to(total)


def _reduce_entry_axis(values, out_shape):
    """Reduce the stored-entry axis of a ``(nnz, *out_shape)`` value block."""
    values = values.contiguous()
    out_num = _numel(out_shape)
    out_dtype = _sum_result_dtype(values.dtype, None)
    mode, acc_dtype = _acc_mode(values.dtype)
    nnz = values.shape[0]
    device = values.device
    with torch_device_fn.device(device):
        out = torch.zeros(out_num, dtype=acc_dtype, device=device)
        if nnz and out_num:
            # Columns per program for the entry-axis reduction; 256 keeps the
            # 64-row tile (BLOCK_N below) inside a 16K-element register block.
            block_c = 256
            _ssum_reduce_rows[(triton.cdiv(out_num, block_c),)](
                values, out, nnz, out_num, BLOCK_N=64, BLOCK_C=block_c
            )
    return out.view(out_shape).to(out_dtype)


def _sum_dense_dims(values, dense_shape, sum_dense, keep_dense):
    """Sum the requested dense dims, keeping the other dims in place."""
    out_shape = [dense_shape[d] for d in keep_dense]
    dense_num = _numel(dense_shape)
    out_num = _numel(out_shape)
    value_dtype = values.dtype
    _, acc_dtype = _acc_mode(value_dtype)
    nnz = values.shape[0]
    device = values.device
    in_strides = [0] * len(dense_shape)
    out_strides = [0] * len(dense_shape)
    run = 1
    for d in reversed(range(len(dense_shape))):
        in_strides[d] = run
        run *= dense_shape[d]
    run = 1
    for d in reversed(keep_dense):
        out_strides[d] = run
        run *= dense_shape[d]
    kept_mask = _mask_bits([d in keep_dense for d in range(len(dense_shape))])
    with torch_device_fn.device(device):
        out = torch.zeros(nnz * out_num, dtype=acc_dtype, device=device)
        if nnz and out_num and sum_dense:
            ndim = len(dense_shape)
            table = _int_table(out_strides + dense_shape + in_strides, device)
            _ssum_dense_sum[(nnz,)](
                values,
                out,
                dense_num,
                out_num,
                table,
                table[ndim : 2 * ndim],
                table[2 * ndim :],
                DENSE_DIM=ndim,
                KEEP_MASK=kept_mask,
                # Each program walks one stored dense block; 256 elements per
                # pass keeps two register vectors live (value + position) and
                # matches the dense-block sizes seen in practice.
                BLOCK=256,
            )
    return out.view(nnz, *out_shape).to(value_dtype)


def _normalize_dims(dims, ndim):
    wrapped = [d + ndim if d < 0 else d for d in dims]
    for original, d in zip(dims, wrapped):
        if d < 0 or d >= ndim:
            raise IndexError(
                f"Dimension out of range (expected to be in range of "
                f"[{-ndim}, {ndim - 1}], but got {original})"
            )
    for i, d in enumerate(wrapped):
        if d in wrapped[:i]:
            raise RuntimeError(f"dim {d} appears multiple times in the list of dims")
    return sorted(wrapped)


def _check_coo(self, op_name):
    if self.layout != torch.sparse_coo:
        raise RuntimeError(
            f"{op_name}: expected a sparse COO tensor, but got layout {self.layout}"
        )


def _project(self, dims, dtype, op_name):
    """Shared body of ``.dim`` and ``.dim_dtype``."""
    _check_coo(self, op_name)
    ndim = self.dim()
    sparse_dim = self.sparse_dim()
    dims = _normalize_dims(dims, ndim)
    coalesced = self.coalesce()
    values = coalesced._values()
    if dtype is not None and values.dtype != dtype:
        values = values.to(dtype)
    shape = list(coalesced.shape)
    dense_shape = list(values.shape[1:])
    sum_sparse = [d for d in dims if d < sparse_dim]
    sum_dense = [d - sparse_dim for d in dims if d >= sparse_dim]
    keep_dims = [d for d in range(ndim) if d not in dims]
    keep_sparse = [d for d in keep_dims if d < sparse_dim]
    keep_dense = [d - sparse_dim for d in keep_dims if d >= sparse_dim]

    if sum_dense:
        values = _sum_dense_dims(values, dense_shape, sum_dense, keep_dense)
    out_dense_shape = [dense_shape[d] for d in keep_dense]
    nnz = coalesced._nnz()
    device = values.device
    indices = coalesced._indices()

    if len(sum_sparse) == sparse_dim:
        # Every sparse dim is summed: the result is dense over the kept dense
        # dims (a 0-D scalar when no dense dim is kept).
        if not out_dense_shape:
            return _reduce_values(values, None)
        return _reduce_entry_axis(values, out_dense_shape)

    if not sum_sparse:
        # Only dense dims were reduced; the sparse structure is untouched.
        sizes = tuple([shape[d] for d in keep_sparse] + out_dense_shape)
        return torch.sparse_coo_tensor(
            indices, values, size=sizes, device=device, is_coalesced=True
        )

    dense_num = _numel(out_dense_shape)
    if nnz:
        if not values.is_contiguous():
            values = values.contiguous()
        if not indices.is_contiguous():
            indices = indices.contiguous()

    keep_mask = _mask_bits([d in keep_sparse for d in range(sparse_dim)])
    strides = [0] * sparse_dim
    key_space = 1
    for d in reversed(range(sparse_dim)):
        if d in keep_sparse:
            strides[d] = key_space
            key_space *= shape[d]
    stride_table = _int_table(strides, device)
    _, acc_dtype = _acc_mode(values.dtype)
    # 1024 keys per program: one block covers a typical kept-dim extent
    # (<= 1024 rows/cols) in a single pass, keeping the count/scan arrays tiny.
    block = 1024
    num_blocks = max(1, triton.cdiv(key_space, block))
    with torch_device_fn.device(device):
        acc = torch.zeros(key_space * dense_num, dtype=acc_dtype, device=device)
        flag = torch.zeros(key_space, dtype=torch.int32, device=device)
        if nnz:
            _ssum_scatter[(triton.cdiv(nnz, block),)](
                indices,
                values,
                acc,
                flag,
                nnz,
                stride_table,
                DENSE_NUM=dense_num,
                KEEP_MASK=keep_mask,
                SPARSE_DIM=sparse_dim,
                BLOCK=block,
            )
        counts = torch.empty(num_blocks, dtype=torch.int32, device=device)
        bases = torch.empty(num_blocks, dtype=torch.int32, device=device)
        _ssum_count[(num_blocks,)](flag, counts, key_space, BLOCK=block)
        _ssum_scan[(1,)](
            counts, bases, num_blocks, BLOCK=triton.next_power_of_2(num_blocks)
        )
        out_nnz = int(counts.sum().item())
        kept = len(keep_sparse)
        out_indices = torch.empty(kept, out_nnz, dtype=torch.int64, device=device)
        out_values = torch.empty(out_nnz * dense_num, dtype=acc_dtype, device=device)
        if out_nnz:
            _ssum_emit[(num_blocks,)](
                flag,
                acc,
                out_indices,
                out_values,
                bases,
                key_space,
                out_nnz,
                stride_table,
                DENSE_NUM=dense_num,
                KEEP_MASK=keep_mask,
                SPARSE_DIM=sparse_dim,
                BLOCK=block,
            )
    sizes = tuple([shape[d] for d in keep_sparse] + out_dense_shape)
    out_values = out_values.view(out_nnz, *out_dense_shape).to(values.dtype)
    return torch.sparse_coo_tensor(
        out_indices, out_values, size=sizes, device=device, is_coalesced=True
    )


def _sparse_sum(self):
    logger.debug("GEMS _SPARSE_SUM")
    _check_coo(self, "_sparse_sum")
    return _reduce_values(self.coalesce()._values(), None)


def _sparse_sum_dtype(self, *, dtype):
    logger.debug("GEMS _SPARSE_SUM.DTYPE")
    _check_coo(self, "_sparse_sum.dtype")
    return _reduce_values(self.coalesce()._values(), dtype)


def _sparse_sum_dim(self, dim):
    logger.debug("GEMS _SPARSE_SUM.DIM")
    return _project(self, dim, None, "_sparse_sum.dim")


def _sparse_sum_dim_dtype(self, dim, *, dtype):
    logger.debug("GEMS _SPARSE_SUM.DIM_DTYPE")
    return _project(self, dim, dtype, "_sparse_sum.dim_dtype")


def _sparse_sum_dim_out(self, dim, *, out):
    logger.debug("GEMS _SPARSE_SUM.DIM_OUT")
    result = _project(self, dim, None, "_sparse_sum.dim_out")
    if out.dtype != result.dtype:
        raise RuntimeError(
            f"Expected out tensor to have dtype {result.dtype}, but got "
            f"{out.dtype} instead"
        )
    if out.layout != result.layout:
        raise RuntimeError(
            f"Expected out tensor to have layout {result.layout}, but got "
            f"{out.layout} instead"
        )
    if tuple(out.shape) != tuple(result.shape):
        # aten resizes a dense ``out`` in place (a deprecated behaviour); the
        # sparse backends have no resize_.  Allocate the correctly shaped
        # tensor instead of mutating the caller's storage.
        if out.layout == torch.sparse_coo:
            raise NotImplementedError(
                "Could not run 'aten::resize_' with arguments from the "
                "'Sparse" + str(out.device.type).upper() + "' backend."
            )
        out = torch.empty_like(result)
    return out.copy_(result)
