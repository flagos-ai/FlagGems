def _sparse_meta(self):
    size = tuple(int(s) for s in self.shape)
    sparse_dim = self.sparse_dim()
    dense_shape = tuple(int(s) for s in size[sparse_dim:])
    dnumel = 1
    for s in dense_shape:
        dnumel *= s
    return size, sparse_dim, dense_shape, dnumel


def _strides(sizes, skip=-1):
    w = [0] * len(sizes)
    run = 1
    for s in range(len(sizes) - 1, -1, -1):
        if s != skip:
            w[s] = run
            run *= int(sizes[s])
    return w


