@triton.jit
def _hash_slot_kernel(
    key_ptr,
    slot_ptr,
    table_ptr,
    nnz,
    nslots,
    SHIFT,
    BLOCK: tl.constexpr,
):
    """Open-addressing hash insert: map every entry to a group slot.

    ``table`` (length ``nslots``, int64) is pre-filled with -1 as the empty
    sentinel.  Entries with the same key adopt the same slot; a slot claimed
    by another key is skipped with linear probing.  The table load factor is
    kept at or below 0.5 (``nslots >= 2 * nnz``) so probing terminates.
    """
    offs = tl.program_id(0) * BLOCK + tl.arange(0, BLOCK)
    m = offs < nnz
    key = tl.load(key_ptr + offs, mask=m, other=0)
    pos = ((key * 6364136223846793005) >> SHIFT) & (nslots - 1)
    slot = tl.full([BLOCK], -1, dtype=tl.int64)
    done = tl.zeros([BLOCK], dtype=tl.int1)
    while tl.sum((m & ~done).to(tl.int32), axis=0) > 0:
        old = tl.atomic_cas(table_ptr + pos, -1, key)
        ok = (old == -1) | (old == key)
        slot = tl.where(ok & ~done, pos, slot)
        done = done | (ok & m)
        pos = tl.where(done, pos, (pos + 1) % nslots)
    tl.store(slot_ptr + offs, slot, mask=m)


def _group_slots(keys, device):
    """Hash-group int64 keys: returns ``(slot_per_entry, nslots)``.

    The group ids are only required to be consistent within one call (the
    table is rebuilt deterministically for the same key sequence), which is
    all the group-reduce kernels need.
    """
    nnz = int(keys.numel())
    nslots = 8
    while nslots < 2 * max(nnz, 1):
        nslots *= 2
    bits = max(1, (nslots - 1).bit_length())
    table = torch.full((nslots,), -1, dtype=torch.int64, device=device)
    slot = torch.empty(nnz, dtype=torch.int64, device=device)
    if nnz > 0:
        grid = (triton.cdiv(nnz, _BLOCK_N),)
        _hash_slot_kernel[grid](
            keys, slot, table, nnz, nslots, SHIFT=64 - bits, BLOCK=_BLOCK_N
        )
    return slot, table, nslots


@triton.jit
def _seg_scan_kernel(
    sorted_keys,
    gstart,
    slots,
    total,
    n,
    BLOCK: tl.constexpr,
):
    """Single-program walk over the sorted keys.

    Emits the start offset of every group into ``gstart`` (groups are
    contiguous runs of equal keys), the compact group id of every sorted
    position into ``slots``, and the number of groups into ``total``.
    """
    run = 0
    for start in range(0, n, BLOCK):
        p = start + tl.arange(0, BLOCK)
        m = p < n
        key = tl.load(sorted_keys + p, mask=m, other=-1)
        prev = tl.load(sorted_keys + p - 1, mask=m & (p > 0), other=-1)
        first = (p == 0) | (key != prev)
        f32 = first.to(tl.int32)
        cs = tl.cumsum(f32, 0)
        slot = run + cs - 1
        tl.store(gstart + slot, p, mask=first & m)
        tl.store(slots + p, slot, mask=m)
        run += tl.sum(f32, axis=0)
    tl.store(total, run)


@triton.jit
def _slot_scatter_kernel(perm, slots_sorted, slots, n, BLOCK: tl.constexpr):
    """slots[perm[p]] = slots_sorted[p]: group ids in the original entry order."""
    pid = tl.program_id(0)
    offs = pid * BLOCK + tl.arange(0, BLOCK)
    m = offs < n
    p = tl.load(perm + offs, mask=m, other=0)
    v = tl.load(slots_sorted + offs, mask=m, other=0)
    tl.store(slots + p, v, mask=m)


def _compact_slots(keys):
    """Compact int64 keys into group ids ``[0, ngroups)`` in ascending key order.

    Returns ``(slots, ngroups)`` where ``slots[i]`` is the group id of
    ``keys[i]``.  Scratch memory is O(nnz) (sort + boundary scan), never sized
    by the coordinate space.
    """
    n = int(keys.numel())
    if n == 0:
        return torch.empty(0, dtype=torch.int64, device=keys.device), 0
    sorted_keys, perm = sort(keys.contiguous())
    slots_sorted = torch.empty(n, dtype=torch.int64, device=keys.device)
    gstart = torch.empty(n + 1, dtype=torch.int64, device=keys.device)
    total = torch.empty(1, dtype=torch.int32, device=keys.device)
    _seg_scan_kernel[(1,)](sorted_keys, gstart, slots_sorted, total, n, BLOCK=_BLOCK_K)
    ngroups = int(total.item())
    slots = torch.empty(n, dtype=torch.int64, device=keys.device)
    grid = (triton.cdiv(n, _BLOCK_N),)
    _slot_scatter_kernel[grid](perm, slots_sorted, slots, n, BLOCK=_BLOCK_N)
    return slots, ngroups


def _seg_boundaries(sorted_keys):
    """Group a 1-D sorted key array into contiguous compact groups.

    Returns ``(slots_sorted, gstart, ngroups)``: ``slots_sorted[p]`` is the
    group id of sorted position ``p`` and ``gstart[g]``..``gstart[g + 1]``
    bound group ``g``'s member range.  Sorting uses the existing FlagGems
    sort kernel; the boundary scan is the dedicated kernel above.  Scratch
    memory is O(n) (one int32/int64 entry per sorted position), never sized
    by the coordinate space.
    """
    n = int(sorted_keys.numel())
    # the callers pass keys already ordered by the FlagGems sort kernel, so no
    # re-sort happens here
    sorted_keys = sorted_keys.contiguous()
    slots = torch.empty(n, dtype=torch.int64, device=sorted_keys.device)
    gstart = torch.empty(max(n, 1), dtype=torch.int64, device=sorted_keys.device)
    total = torch.empty(1, dtype=torch.int32, device=sorted_keys.device)
    if n > 0:
        _seg_scan_kernel[(1,)](sorted_keys, gstart, slots, total, n, BLOCK=_BLOCK_K)
    else:
        return (
            torch.empty(0, dtype=torch.int64, device=sorted_keys.device),
            torch.zeros(1, dtype=torch.int64, device=sorted_keys.device),
            0,
        )
    ngroups = int(total.item())
    gstart_full = torch.empty(ngroups + 1, dtype=torch.int64, device=sorted_keys.device)
    gstart_full[:ngroups] = gstart[:ngroups]
    gstart_full[ngroups] = n
    return slots, gstart_full, ngroups


def triton_coalesce(self):
    """Coalesce a sparse COO tensor with the Triton kernels above.

    Returns ``(indices, values, nnz)`` where the entries are sorted by their
    row-major sparse key and duplicate coordinates are summed — the same
    result as the native ``aten::coalesce`` without calling it.
    """
    if self.is_coalesced():
        return self._indices().contiguous(), self._values().contiguous(), self._nnz()
    size, sparse_dim, dense_shape, dnumel = _sparse_meta(self)
    src = self
    wide_dtype = None
    if self.dtype in _ATOMIC_UNSUPPORTED:
        # bool duplicates coalesce as a logical or; a numeric sum converted
        # back matches that (every non-zero count becomes true).
        is_int = self.dtype in (
            torch.bool,
            torch.int8,
            torch.uint8,
            torch.int16,
            torch.uint16,
        )
        wide_dtype = torch.int64 if is_int else torch.float32
        src = torch.sparse_coo_tensor(
            self._indices(),
            _triton_cast(self._values(), wide_dtype),
            size,
            dtype=wide_dtype,
            device=self.device,
        )
    idx, vals, total = _coalesce(src, dense_shape, dnumel)
    vals = vals.reshape((total,) + dense_shape)
    if wide_dtype is not None:
        vals = _triton_cast(vals, self.dtype)
    return idx, vals, total


def _coalesce(self, dense_shape, dnumel):
    """Device-side coalescing: histogram sort plus duplicate accumulation."""
    size = tuple(int(s) for s in self.shape)
    sparse_dim = self.sparse_dim()
    device = self._indices().device
    src = self._indices().contiguous()
    nnz = self._nnz()
    vals = self._values().reshape(nnz, dnumel)
    w = _strides([int(s) for s in size[:sparse_dim]])
    sizes = torch.tensor(
        [int(s) for s in size[:sparse_dim]], dtype=torch.int64, device=device
    )
    wt = torch.tensor(w, dtype=torch.int64, device=device)
    domain = 1
    for s in size[:sparse_dim]:
        domain *= int(s)
    keys = torch.empty(nnz, dtype=torch.int64, device=device)
    _key_all[(triton.cdiv(nnz, _BLOCK_N),)](
        src, wt, keys, nnz, sparse_dim, BLOCK=_BLOCK_N
    )
    hist = torch.zeros(domain, dtype=torch.int32, device=device)
    _hist[(triton.cdiv(nnz, _BLOCK_N),)](keys, hist, nnz, BLOCK=_BLOCK_N)
    start = torch.empty(domain + 1, dtype=torch.int32, device=device)
    distinct = torch.empty(1, dtype=torch.int32, device=device)
    _scan[(1,)](hist, start, distinct, domain, BLOCK=_BLOCK_K)
    total = int(distinct.item())
    idx_out = torch.empty((sparse_dim, max(total, 1)), dtype=torch.int64, device=device)
    if total > 0:
        _coalesce_idx[(triton.cdiv(domain, _BLOCK_N),)](
            wt,
            sizes,
            start,
            idx_out,
            idx_out.stride(0),
            domain,
            sparse_dim,
            BLOCK=_BLOCK_N,
        )
    vout = torch.zeros((max(total, 1), dnumel), dtype=vals.dtype, device=device)
    if nnz > 0:
        _scatter_val[(nnz, triton.cdiv(dnumel, _BLOCK_V))](
            vals, keys, start, vout, dnumel, nnz, _BLOCK_V
        )
    return idx_out[:, :total].contiguous(), vout[:total], total


def _pool_key(self, dim, indices=None):
    """Pool (group) keys of every entry; ``indices`` may be the coalesced
    index matrix (required when ``self`` is uncoalesced — computing pool keys
    over the raw stored coordinates would mismatch the coalesced values)."""
    size, sparse_dim, dense_shape, _ = _sparse_meta(self)
    device = self._indices().device
    src = (self._indices() if indices is None else indices).contiguous()
    nnz = src.shape[1]
    w = _strides([int(s) for s in size[:sparse_dim]], skip=dim)
    wt = torch.tensor(w, dtype=torch.int64, device=device)
    keys = torch.empty(nnz, dtype=torch.int64, device=device)
    _key_pool[(triton.cdiv(nnz, _BLOCK_N),)](
        src, wt, keys, nnz, sparse_dim, dim, BLOCK=_BLOCK_N
    )
    return keys


def _forward_core(self, dim, out_dtype):
    size, sparse_dim, dense_shape, dnumel = _sparse_meta(self)
    device = self._indices().device
    if self.is_coalesced():
        indices = self._indices()
        vals = self._values().reshape(self._nnz(), dnumel)
        nnz = self._nnz()
    else:
        indices, vals, nnz = _coalesce(self, dense_shape, dnumel)
    via32 = self.dtype in (torch.float8_e4m3fn, torch.float8_e5m2)
    f64 = out_dtype == torch.float64
    result = torch.empty((nnz, dnumel), dtype=out_dtype, device=device)
    ginfo = None
    if nnz > 0:
        if dim >= sparse_dim:
            a = dim - sparse_dim
            outer = 1
            for s in dense_shape[:a]:
                outer *= s
            red = dense_shape[a]
            inner = 1
            for s in dense_shape[a + 1 :]:
                inner *= s
            oi = outer * inner
            small = red <= 128
            np2r = 1
            while np2r < red:
                np2r *= 2
            # keep the register tile bounded as the reduce axis grows
            bci = _BLOCK_CI
            if red > 64:
                bci = 32
            elif red > 32:
                bci = 64
            if inner == 1:
                _lse_wide[(nnz, outer)](vals, result, red, np2r, outer, f64, via32)
            else:
                _lse_dense[(nnz, triton.cdiv(oi, bci))](
                    vals,
                    result,
                    red,
                    inner,
                    oi,
                    f64,
                    via32,
                    NP2R=np2r,
                    SMALL=small,
                    BLOCK_CI=bci,
                )
        else:
            # The pool keys of the coalesced entries are compacted with the
            # FlagGems sort kernel; the groups are contiguous runs in sorted
            # order, replacing the dense histogram + scan + placement with an
            # O(nnz) boundary scan.
            keys = _pool_key(self, dim, indices)
            sorted_keys, perm = sort(keys)
            _, gstart, ngroups = _seg_boundaries(sorted_keys)
            _group_lse[(ngroups, triton.cdiv(dnumel, _BLOCK_D))](
                vals, result, gstart, perm, dnumel, f64, via32, BLOCK_D=_BLOCK_D
            )
            ginfo = (gstart, perm)
    return indices, result, size, sparse_dim, dense_shape, dnumel, ginfo


def _forward(self, dim, out_dtype):
    indices, result, size, sparse_dim, dense_shape, dnumel, _ = _forward_core(
        self, dim, out_dtype
    )
    nnz = result.shape[0]
    return torch.sparse_coo_tensor(
        indices,
        result.reshape((nnz,) + dense_shape),
        size,
        dtype=out_dtype,
        device=indices.device,
        is_coalesced=True,
    )


class _SparseLogSoftmax(torch.autograd.Function):
    @staticmethod
    def forward(ctx, inp, dim, out_dtype):
        indices, result, size, sparse_dim, dense_shape, dnumel, ginfo = _forward_core(
            inp, dim, out_dtype
        )
        ctx.dim = dim
        ctx.sparse_dim = sparse_dim
        ctx.size = size
        ctx.dense_shape = dense_shape
        ctx.dnumel = dnumel
        ctx.indices = indices
        ctx.ginfo = ginfo
        ctx.in_dtype = inp.dtype
        ctx.save_for_backward(result)
        nnz = result.shape[0]
        return torch.sparse_coo_tensor(
            indices,
            result.reshape((nnz,) + dense_shape),
            size,
            dtype=out_dtype,
            device=indices.device,
            is_coalesced=True,
        )

    @staticmethod
    def backward(ctx, grad_out):
        oval = ctx.saved_tensors[0]
        nnz = oval.shape[0]
        # Rank <= 8 takes the fast path; beyond that the general kernels below
        # stay authoritative.  The fast path joins grad_output to the output by
        # coordinate, so it needs the two support matrices rather than a reshape.
        if ctx.sparse_dim <= 8 and ctx.in_dtype in (torch.float32, torch.float64):
            if grad_out.is_coalesced():
                # An already-coalesced support needs no sort: its indices are
                # ordered and duplicate-free, so only the payload is reshaped.
                f_idx = grad_out._indices().contiguous()
                f_vals = grad_out._values()
                f_total = grad_out._nnz()
            else:
                f_idx, f_vals, f_total = triton_coalesce(grad_out)
            fast = _bwd_fast_backward(
                ctx.dim,
                ctx.sparse_dim,
                ctx.size,
                ctx.dense_shape,
                oval,
                ctx.indices,
                f_idx,
                f_vals.reshape(f_total, ctx.dnumel),
                ctx.ginfo,
            )
            return (
                torch.sparse_coo_tensor(  # allow-torch-compute: package gradient values
                    ctx.indices,
                    fast.reshape((nnz,) + tuple(ctx.dense_shape)),
                    ctx.size,
                    dtype=ctx.in_dtype,
                    device=ctx.indices.device,
                    is_coalesced=True,
                ),
                None,
                None,
            )
        if grad_out.is_coalesced():
            dy = grad_out._values().reshape(nnz, ctx.dnumel)
        else:
            _, g_vals, total = triton_coalesce(grad_out)
            dy = g_vals.reshape(total, ctx.dnumel)
        do = torch.empty_like(dy)
        dnumel = ctx.dnumel
        f64 = ctx.in_dtype == torch.float64
        if nnz > 0:
            if ctx.dim >= ctx.sparse_dim:
                a = ctx.dim - ctx.sparse_dim
                outer = 1
                for s in ctx.dense_shape[:a]:
                    outer *= s
                red = ctx.dense_shape[a]
                inner = 1
                for s in ctx.dense_shape[a + 1 :]:
                    inner *= s
                oi = outer * inner
                _bwd_dense[(nnz, triton.cdiv(oi, _BLOCK_CI))](
                    dy, oval, do, red, inner, oi, f64, BLOCK_CI=_BLOCK_CI
                )
            else:
                gstart, order = ctx.ginfo
                ng = gstart.numel() - 1
                adt = torch.float64 if f64 else do.dtype
                acc = torch.empty(ng * dnumel, dtype=adt, device=oval.device)
                _bwd_gseq[(ng, triton.cdiv(dnumel, _BLOCK_D))](
                    dy, gstart, order, acc, dnumel, f64, BLOCK_D=_BLOCK_D
                )
                _bwd_gwrite[(ng, triton.cdiv(dnumel, _BLOCK_D))](
                    dy, oval, gstart, order, acc, do, dnumel, f64, BLOCK_D=_BLOCK_D
                )
        grads = torch.sparse_coo_tensor(
            ctx.indices,
            do.reshape((nnz,) + ctx.dense_shape),
            ctx.size,
            dtype=ctx.in_dtype,
            device=ctx.indices.device,
            is_coalesced=True,
        )
        return grads, None, None


def _resolve_dtype(self, dtype):
    if dtype is None:
        return self.dtype
    target = dtype if isinstance(dtype, torch.dtype) else torch.dtype(dtype)
    if target not in (torch.float32, torch.float64):
        raise RuntimeError(
            "\"log_softmax\" not implemented for '%s'" % _NAMES.get(target, str(target))
        )
    if self.dtype == torch.float16 and target == torch.float32:
        raise RuntimeError(
            "log_softmax: with half to float conversion is not supported on cuda:0"
        )
    return target


def _sparse_log_softmax_int(self, dim, dtype=None):
    """``aten::_sparse_log_softmax.int`` overload: positional dtype."""
    return _sparse_log_softmax(self, dim, half_to_float=False, dtype=dtype)


def _sparse_log_softmax_out(self, dim, half_to_float, out=None):
    """``aten::_sparse_log_softmax.out`` overload."""
    return _sparse_log_softmax(self, dim, half_to_float=half_to_float, out=out)


def _sparse_log_softmax(self, dim, half_to_float=False, dtype=None, out=None):

    logger.debug("GEMS SPARSE_LOG_SOFTMAX")
    if not self.is_sparse or self.layout != torch.sparse_coo:
        raise RuntimeError(
            "Could not run 'aten::_sparse_log_softmax' with arguments from the "
            "'CUDA' backend. This could be because the operator doesn't exist for "
            "this backend, or was omitted during the selective/custom build process "
            "(if using a custom build). If you are a Facebook employee using PyTorch "
            "on mobile, you can also receive this error if you are trying to run the "
            "operator with a lite interpreter."
        )
    if half_to_float:
        raise RuntimeError(
            "log_softmax: with half to float conversion is not supported on cuda:0"
        )
    if not isinstance(dim, int):
        raise TypeError("dim must be an int")
    if dim < -self.dim() or dim >= self.dim():
        raise IndexError(
            "Dimension out of range (expected to be in range of [%d, %d], but got %d)"
            % (-self.dim(), self.dim() - 1, dim)
        )
    dim = dim % self.dim()
    if dtype is None and self.dtype not in (torch.float32, torch.float64):
        raise RuntimeError(
            "\"log_softmax\" not implemented for '%s'"
            % _NAMES.get(self.dtype, str(self.dtype))
        )
    target = _resolve_dtype(self, dtype)
    if self.requires_grad and target in (torch.float32, torch.float64):
        result = _SparseLogSoftmax.apply(self, dim, target)
    else:
        result = _forward(self, dim, target)
    if out is None:
        return result
    out.copy_(result)
    return out


@triton.jit
def _bwd_fast_gkey(
    idx,
    mid,
    m,
    NNZ,
    S0: tl.constexpr,
    S1: tl.constexpr,
    S2: tl.constexpr,
    S3: tl.constexpr,
    S4: tl.constexpr,
    S5: tl.constexpr,
    S6: tl.constexpr,
    S7: tl.constexpr,
    RANK: tl.constexpr,
):
    """Row-major weighted rank of the coordinate at ``mid`` (0 when masked)."""
    k = tl.zeros_like(mid).to(tl.int64)
    if RANK > 0:
        k += tl.load(idx + mid, mask=m, other=0).to(tl.int64) * S0
    if RANK > 1:
        k += tl.load(idx + NNZ + mid, mask=m, other=0).to(tl.int64) * S1
    if RANK > 2:
        k += tl.load(idx + 2 * NNZ + mid, mask=m, other=0).to(tl.int64) * S2
    if RANK > 3:
        k += tl.load(idx + 3 * NNZ + mid, mask=m, other=0).to(tl.int64) * S3
    if RANK > 4:
        k += tl.load(idx + 4 * NNZ + mid, mask=m, other=0).to(tl.int64) * S4
    if RANK > 5:
        k += tl.load(idx + 5 * NNZ + mid, mask=m, other=0).to(tl.int64) * S5
    if RANK > 6:
        k += tl.load(idx + 6 * NNZ + mid, mask=m, other=0).to(tl.int64) * S6
    if RANK > 7:
        k += tl.load(idx + 7 * NNZ + mid, mask=m, other=0).to(tl.int64) * S7
    return k


@triton.jit
def _bwd_fast_find(
    g_idx,
    g_nnz,
    needle,
    S0: tl.constexpr,
    S1: tl.constexpr,
    S2: tl.constexpr,
    S3: tl.constexpr,
    S4: tl.constexpr,
    S5: tl.constexpr,
    S6: tl.constexpr,
    S7: tl.constexpr,
    RANK: tl.constexpr,
    STEPS: tl.constexpr,
):
    """Grad row whose rank equals ``needle``, or ``-1`` when absent."""
    lo = needle - needle
    hi = lo + g_nnz
    for _ in tl.static_range(STEPS):
        mid = (lo + hi) >> 1
        act = lo < hi
        m = act & (mid < g_nnz)
        gk = _bwd_fast_gkey(g_idx, mid, m, g_nnz, S0, S1, S2, S3, S4, S5, S6, S7, RANK)
        lt = m & (gk < needle)
        lo = tl.where(lt, mid + 1, lo)
        hi = tl.where(lt, hi, tl.where(act, mid, hi))
    inside = lo < g_nnz
    gk = _bwd_fast_gkey(g_idx, lo, inside, g_nnz, S0, S1, S2, S3, S4, S5, S6, S7, RANK)
    return tl.where(inside & (gk == needle), lo, -1)


def _plain_rank_strides(shape, sdim):
    """Row-major strides of the sparse axes (the join key weights)."""
    strides = [1] * max(sdim, 1)
    for i in range(sdim - 2, -1, -1):
        strides[i] = strides[i + 1] * int(shape[i + 1])
    return strides


def _bwd_fast_strides8(strides):
    """Pad the rank strides to the eight the unrolled kernels take."""
    values = [int(x) for x in list(strides)[:8]]
    return values + [0] * (8 - len(values))


# --------------------------------------------------------------------------
# backward: support join + fused ordered kernels
# --------------------------------------------------------------------------
#
# ``_SparseLogSoftmax.backward`` works on the coalesced *output* support: an
# upstream coordinate that is absent from the output contributes nothing to any
# output row, and an output coordinate that the upstream gradient does not
# mention takes G = 0 (measured on the native autograd node and
# ``_sparse_log_softmax_backward_data``).  The general kernels below keep the
# authoritative contract for every rank; the fused kernels after them handle the
# common ranks with the launch overhead removed.
#
# All reductions walk their axis in ascending member order in the values' own
# dtype and exp comes from libdevice, so the arithmetic per element matches the
# general path and the native kernel; the speedup comes from fusing the
# coordinate join into the producer kernels instead of the launch count.
@triton.jit
def _bwd_join(
    g_vals,
    g_idx,
    y_idx,
    j_vals,
    g_nnz,
    y_nnz,
    S0: tl.constexpr,
    S1: tl.constexpr,
    S2: tl.constexpr,
    S3: tl.constexpr,
    S4: tl.constexpr,
    S5: tl.constexpr,
    S6: tl.constexpr,
    S7: tl.constexpr,
    RANK: tl.constexpr,
    STEPS: tl.constexpr,
    CN: tl.constexpr,
    BLOCK: tl.constexpr,
):
    """Copy each joined grad row onto the output support; misses stay zero.

    One program per output row: the row's coordinate rank is looked up in the
    upstream index matrix (row-major, ascending, duplicate-free — both supports
    are coalesced) and its payload is copied to ``j_vals``.  Rows without an
    upstream coordinate keep the zero-initialized buffer, which is exactly the
    native "absent coordinate contributes G = 0" rule.
    """
    row = tl.program_id(0)
    co = tl.arange(0, BLOCK)
    m = co < CN
    needle = _bwd_fast_gkey(
        y_idx, row, row < row + 1, y_nnz, S0, S1, S2, S3, S4, S5, S6, S7, RANK
    )
    src_row = _bwd_fast_find(
        g_idx, g_nnz, needle, S0, S1, S2, S3, S4, S5, S6, S7, RANK, STEPS
    )
    ok = src_row >= 0
    src = tl.where(ok, src_row, 0).to(tl.int64) * CN
    vals = tl.load(g_vals + src + co, mask=m & ok, other=0.0)
    tl.store(j_vals + row.to(tl.int64) * CN + co, vals, mask=m)


@triton.jit
def _bwd_fast_dense(
    dy,
    y_vals,
    o_vals,
    R,
    INNER,
    OI,
    ROWS,
    F64: tl.constexpr,
    BLOCK_ROWS: tl.constexpr,
    BLOCK_CI: tl.constexpr,
    CHUNK: tl.constexpr,
):
    """dO = dY - exp(OUT) * sum_dense(dY) in the input's own precision.

    Each lane owns one (row, dense position) pair and adds the reduced axis
    chunk by chunk in ascending order, so the per-element rounding matches the
    general ``_bwd_dense`` and the native kernel exactly; within a chunk the
    loads are vectorized and the partial sums are folded lane-wise in register,
    which keeps the memory pipeline busy without touching the addition order.
    """
    row0 = tl.program_id(0) * BLOCK_ROWS
    oi = tl.program_id(1) * BLOCK_CI + tl.arange(0, BLOCK_CI)
    lanes = row0 + tl.arange(0, BLOCK_ROWS)
    rm = lanes < ROWS
    ch = tl.arange(0, CHUNK)
    lanes3 = lanes[:, None, None]
    oi3 = oi[None, None, :]
    base3 = (
        lanes3 * (OI * R)
        + (oi3 // INNER) * (R * INNER)
        + (oi3 - (oi3 // INNER) * INNER)
    )
    ptr = base3 + ch[None, :, None] * INNER
    if F64:
        acc = tl.zeros([BLOCK_ROWS, BLOCK_CI], dtype=tl.float64)
        for r0 in range(0, R, CHUNK):
            m3 = (
                rm[:, None, None]
                & (oi < OI)[None, None, :]
                & (r0 + ch < R)[None, :, None]
            )
            part = tl.load(dy + ptr + r0 * INNER, mask=m3, other=0.0)
            for j in tl.static_range(CHUNK):
                acc += tl.sum(tl.where(ch[None, :, None] == j, part, 0.0), axis=1)
        for r0 in range(0, R, CHUNK):
            m3 = (
                rm[:, None, None]
                & (oi < OI)[None, None, :]
                & (r0 + ch < R)[None, :, None]
            )
            g2 = tl.load(dy + ptr + r0 * INNER, mask=m3, other=0.0)
            ov = tl.load(y_vals + ptr + r0 * INNER, mask=m3, other=0.0)
            res = g2 - _ld.exp(ov) * acc[:, None, :]
            tl.store(o_vals + ptr + r0 * INNER, res, mask=m3)
    else:
        acc = tl.zeros([BLOCK_ROWS, BLOCK_CI], dtype=tl.float32)
        for r0 in range(0, R, CHUNK):
            m3 = (
                rm[:, None, None]
                & (oi < OI)[None, None, :]
                & (r0 + ch < R)[None, :, None]
            )
            part = tl.load(dy + ptr + r0 * INNER, mask=m3, other=0.0)
            for j in tl.static_range(CHUNK):
                acc += tl.sum(tl.where(ch[None, :, None] == j, part, 0.0), axis=1)
        for r0 in range(0, R, CHUNK):
            m3 = (
                rm[:, None, None]
                & (oi < OI)[None, None, :]
                & (r0 + ch < R)[None, :, None]
            )
            g2 = tl.load(dy + ptr + r0 * INNER, mask=m3, other=0.0)
            ov = tl.load(y_vals + ptr + r0 * INNER, mask=m3, other=0.0)
            res = g2 - _ld.exp(ov) * acc[:, None, :]
            tl.store(o_vals + ptr + r0 * INNER, res, mask=m3)


@triton.jit
def _bwd_fast_gseq(
    dy,
    START,
    ORDER,
    ACC,
    Dn,
    ROWS,
    F64: tl.constexpr,
    BLOCK_ROWS: tl.constexpr,
    BLOCK_D: tl.constexpr,
):
    """Deterministic per-pool sum of the joined grads in member order.

    The column lanes are blocked; each (pool, column) lane serially walks its
    pool's members in ascending entry order, the same order the general
    ``_bwd_gseq`` sums in, so the rounding matches the general path and the
    native kernel.
    """
    g = tl.program_id(0)
    lo = tl.load(START + g)
    hi = tl.load(START + g + 1)
    off = tl.program_id(1) * BLOCK_D + tl.arange(0, BLOCK_D)
    md = off < Dn
    if F64:
        acc = tl.zeros([BLOCK_ROWS, BLOCK_D], dtype=tl.float64)
        for j in range(lo, hi):
            p = tl.load(ORDER + j)
            acc += tl.load(dy + p * Dn + off[None, :], mask=md[None, :], other=0.0).to(
                tl.float64
            )
    else:
        acc = tl.zeros([BLOCK_ROWS, BLOCK_D], dtype=tl.float32)
        for j in range(lo, hi):
            p = tl.load(ORDER + j)
            acc += tl.load(dy + p * Dn + off[None, :], mask=md[None, :], other=0.0).to(
                tl.float32
            )
    tl.store(ACC + g * Dn + off[None, :], acc, mask=md[None, :])


@triton.jit
def _bwd_fast_gwrite(
    dy,
    y_vals,
    START,
    ORDER,
    ACC,
    DO,
    Dn,
    F64: tl.constexpr,
    BLOCK_D: tl.constexpr,
):
    """dO = dY - exp(OUT) * pool_sum, written in member order."""
    g = tl.program_id(0)
    lo = tl.load(START + g)
    hi = tl.load(START + g + 1)
    off = tl.program_id(1) * BLOCK_D + tl.arange(0, BLOCK_D)
    md = off < Dn
    for j in range(lo, hi):
        p = tl.load(ORDER + j)
        if F64:
            g2 = tl.load(dy + p * Dn + off, mask=md, other=0.0).to(tl.float64)
            ov = tl.load(y_vals + p * Dn + off, mask=md, other=0.0).to(tl.float64)
            a = tl.load(ACC + g * Dn + off, mask=md, other=0.0).to(tl.float64)
        else:
            g2 = tl.load(dy + p * Dn + off, mask=md, other=0.0).to(tl.float32)
            ov = tl.load(y_vals + p * Dn + off, mask=md, other=0.0).to(tl.float32)
            a = tl.load(ACC + g * Dn + off, mask=md, other=0.0).to(tl.float32)
        tl.store(DO + p * Dn + off, g2 - _ld.exp(ov) * a, mask=md)


def _bwd_fast_backward(
    dim,
    sparse_dim,
    size,
    dense_shape,
    oval,
    y_indices,
    grad_indices,
    grad_values,
    ginfo,
):
    """Fused backward on the output support.

    ``oval`` is the saved forward payload (``nnz x dnumel``), ``y_indices`` the
    coalesced output index matrix and ``grad_indices``/``grad_values`` the
    coalesced upstream gradient.  The upstream rows are first joined onto the
    output support (absent coordinates become zero rows), then the ordered
    dense/pool kernels run on the joined buffer, so an upstream support that is
    narrower or wider than the output support cannot misalign the payload.
    """
    shape = [int(s) for s in size]
    tail = tuple(int(s) for s in dense_shape)
    cn = 1
    for s in tail:
        cn *= s
    cn = max(cn, 1)
    device = oval.device
    y_nnz = int(oval.shape[0])
    g_nnz = int(grad_indices.shape[1])
    o_vals = torch.empty((y_nnz,) + tail, dtype=oval.dtype, device=device)
    if y_nnz == 0:
        return o_vals

    y_vals = oval.reshape(y_nnz, cn)
    y_idx = y_indices.contiguous()
    g_idx = grad_indices.contiguous()
    g_vals = grad_values.contiguous().reshape(g_nnz, cn)
    o_flat = o_vals.reshape(y_nnz, cn)
    dy = torch.zeros_like(y_vals)
    if g_nnz > 0:
        fs = _bwd_fast_strides8(_plain_rank_strides(shape, sparse_dim))
        steps = max(1, min(62, int(max(g_nnz, 2) - 1).bit_length() + 1))
        bc = max(min(1024, triton.next_power_of_2(cn)), 1)
        _bwd_join[(y_nnz,)](
            g_vals,
            g_idx,
            y_idx,
            dy,
            g_nnz,
            y_nnz,
            fs[0],
            fs[1],
            fs[2],
            fs[3],
            fs[4],
            fs[5],
            fs[6],
            fs[7],
            RANK=min(sparse_dim, 8),
            STEPS=steps,
            CN=cn,
            BLOCK=bc,
        )

    if dim < sparse_dim:
        # The forward saved the pool segmentation of the coalesced support:
        # group boundaries in ``ginfo[0]`` and the member order in ``ginfo[1]``.
        gstart, order = ginfo
        ng = gstart.numel() - 1
        acc = torch.empty(ng * cn, dtype=dy.dtype, device=device)
        _bwd_fast_gseq[(ng, triton.cdiv(cn, _BLOCK_D))](
            dy,
            gstart,
            order,
            acc,
            cn,
            ROWS=1,
            F64=dy.dtype == torch.float64,
            BLOCK_ROWS=1,
            BLOCK_D=_BLOCK_D,
        )
        _bwd_fast_gwrite[(ng, triton.cdiv(cn, _BLOCK_D))](
            dy,
            y_vals,
            gstart,
            order,
            acc,
            o_flat,
            cn,
            F64=dy.dtype == torch.float64,
            BLOCK_D=_BLOCK_D,
        )
    else:
        a = min(max(dim - sparse_dim, 0), max(len(tail) - 1, 0))
        dsize = max(tail[a] if tail else 1, 1)
        inner = 1
        for s in tail[a + 1 :]:
            inner *= s
        outer = 1
        for s in tail[:a]:
            outer *= s
        oi = max(outer, 1) * max(inner, 1)
        # Lane budget: every lane walks the reduce axis in ascending chunks.
        # BLOCK_CI covers the dense positions of one (row, outer) pair, then
        # rows fill the remaining lanes of a 128-wide tile.
        bci = max(min(_BLOCK_CI, triton.next_power_of_2(oi)), 1)
        cols = triton.cdiv(oi, bci)
        rows = max(1, min(_BLOCK_CI // bci, y_nnz))
        rows = triton.next_power_of_2(rows)
        chunk = 8
        _bwd_fast_dense[(triton.cdiv(y_nnz, rows), cols)](
            dy,
            y_vals,
            o_flat,
            dsize,
            max(inner, 1),
            oi,
            y_nnz,
            F64=dy.dtype == torch.float64,
            BLOCK_ROWS=rows,
            BLOCK_CI=bci,
            CHUNK=chunk,
        )
    return o_vals
