@triton.jit
def _hash_slot_kernel(
    key_ptr,
    slot_ptr,
    table_ptr,
    nnz,
    nslots,
    SHIFT,
    BLOCK: tl.constexpr,
):
    """Open-addressing hash insert: map every entry to a group slot.

    ``table`` (length ``nslots``, int64) is pre-filled with -1 as the empty
    sentinel.  Entries with the same key adopt the same slot; a slot claimed
    by another key is skipped with linear probing.  The table load factor is
    kept at or below 0.5 (``nslots >= 2 * nnz``) so probing terminates.
    """
    offs = tl.program_id(0) * BLOCK + tl.arange(0, BLOCK)
    m = offs < nnz
    key = tl.load(key_ptr + offs, mask=m, other=0)
    pos = ((key * 6364136223846793005) >> SHIFT) & (nslots - 1)
    slot = tl.full([BLOCK], -1, dtype=tl.int64)
    done = tl.zeros([BLOCK], dtype=tl.int1)
    while tl.sum((m & ~done).to(tl.int32), axis=0) > 0:
        old = tl.atomic_cas(table_ptr + pos, -1, key)
        ok = (old == -1) | (old == key)
        slot = tl.where(ok & ~done, pos, slot)
        done = done | (ok & m)
        pos = tl.where(done, pos, (pos + 1) % nslots)
    tl.store(slot_ptr + offs, slot, mask=m)


def _group_slots(keys, device):
    """Hash-group int64 keys: returns ``(slot_per_entry, nslots)``.

    The group ids are only required to be consistent within one call (the
    table is rebuilt deterministically for the same key sequence), which is
    all the group-reduce kernels need.
    """
    nnz = int(keys.numel())
    nslots = 8
    while nslots < 2 * max(nnz, 1):
        nslots *= 2
    bits = max(1, (nslots - 1).bit_length())
    table = torch.full((nslots,), -1, dtype=torch.int64, device=device)
    slot = torch.empty(nnz, dtype=torch.int64, device=device)
    if nnz > 0:
        grid = (triton.cdiv(nnz, _BLOCK_N),)
        _hash_slot_kernel[grid](
            keys, slot, table, nnz, nslots, SHIFT=64 - bits, BLOCK=_BLOCK_N
        )
    return slot, table, nslots


@triton.jit
def _seg_scan_kernel(
    sorted_keys,
    gstart,
    slots,
    total,
    n,
    BLOCK: tl.constexpr,
):
    """Single-program walk over the sorted keys.

    Emits the start offset of every group into ``gstart`` (groups are
    contiguous runs of equal keys), the compact group id of every sorted
    position into ``slots``, and the number of groups into ``total``.
    """
    run = 0
    for start in range(0, n, BLOCK):
        p = start + tl.arange(0, BLOCK)
        m = p < n
        key = tl.load(sorted_keys + p, mask=m, other=-1)
        prev = tl.load(sorted_keys + p - 1, mask=m & (p > 0), other=-1)
        first = (p == 0) | (key != prev)
        f32 = first.to(tl.int32)
        cs = tl.cumsum(f32, 0)
        slot = run + cs - 1
        tl.store(gstart + slot, p, mask=first & m)
        tl.store(slots + p, slot, mask=m)
        run += tl.sum(f32, axis=0)
    tl.store(total, run)


@triton.jit
def _slot_scatter_kernel(perm, slots_sorted, slots, n, BLOCK: tl.constexpr):
    """slots[perm[p]] = slots_sorted[p]: group ids in the original entry order."""
    pid = tl.program_id(0)
    offs = pid * BLOCK + tl.arange(0, BLOCK)
    m = offs < n
    p = tl.load(perm + offs, mask=m, other=0)
    v = tl.load(slots_sorted + offs, mask=m, other=0)
    tl.store(slots + p, v, mask=m)


def _compact_slots(keys):
    """Compact int64 keys into group ids ``[0, ngroups)`` in ascending key order.

    Returns ``(slots, ngroups)`` where ``slots[i]`` is the group id of
    ``keys[i]``.  Scratch memory is O(nnz) (sort + boundary scan), never sized
    by the coordinate space.
    """
    n = int(keys.numel())
    if n == 0:
        return torch.empty(0, dtype=torch.int64, device=keys.device), 0
    sorted_keys, perm = sort(keys.contiguous())
    slots_sorted = torch.empty(n, dtype=torch.int64, device=keys.device)
    gstart = torch.empty(n + 1, dtype=torch.int64, device=keys.device)
    total = torch.empty(1, dtype=torch.int32, device=keys.device)
    _seg_scan_kernel[(1,)](sorted_keys, gstart, slots_sorted, total, n, BLOCK=_BLOCK_K)
    ngroups = int(total.item())
    slots = torch.empty(n, dtype=torch.int64, device=keys.device)
    grid = (triton.cdiv(n, _BLOCK_N),)
    _slot_scatter_kernel[grid](perm, slots_sorted, slots, n, BLOCK=_BLOCK_N)
    return slots, ngroups


def _seg_boundaries(sorted_keys):
    """Group a 1-D sorted key array into contiguous compact groups.

    Returns ``(slots_sorted, gstart, ngroups)``: ``slots_sorted[p]`` is the
    group id of sorted position ``p`` and ``gstart[g]``..``gstart[g + 1]``
    bound group ``g``'s member range.  Sorting uses the existing FlagGems
    sort kernel; the boundary scan is the dedicated kernel above.  Scratch
    memory is O(n) (one int32/int64 entry per sorted position), never sized
    by the coordinate space.
    """
    n = int(sorted_keys.numel())
    # the callers pass keys already ordered by the FlagGems sort kernel, so no
    # re-sort happens here
    sorted_keys = sorted_keys.contiguous()
    slots = torch.empty(n, dtype=torch.int64, device=sorted_keys.device)
    gstart = torch.empty(max(n, 1), dtype=torch.int64, device=sorted_keys.device)
    total = torch.empty(1, dtype=torch.int32, device=sorted_keys.device)
    if n > 0:
        _seg_scan_kernel[(1,)](sorted_keys, gstart, slots, total, n, BLOCK=_BLOCK_K)
    else:
        return (
            torch.empty(0, dtype=torch.int64, device=sorted_keys.device),
            torch.zeros(1, dtype=torch.int64, device=sorted_keys.device),
            0,
        )
    ngroups = int(total.item())
    gstart_full = torch.empty(ngroups + 1, dtype=torch.int64, device=sorted_keys.device)
    gstart_full[:ngroups] = gstart[:ngroups]
    gstart_full[ngroups] = n
    return slots, gstart_full, ngroups


def triton_coalesce(self):
    """Coalesce a sparse COO tensor with the Triton kernels above.

    Returns ``(indices, values, nnz)`` where the entries are sorted by their
    row-major sparse key and duplicate coordinates are summed — the same
    result as the native ``aten::coalesce`` without calling it.
    """
    if self.is_coalesced():
        return self._indices().contiguous(), self._values().contiguous(), self._nnz()
    size, sparse_dim, dense_shape, dnumel = _sparse_meta(self)
    src = self
    wide_dtype = None
    if self.dtype in _ATOMIC_UNSUPPORTED:
        # bool duplicates coalesce as a logical or; a numeric sum converted
        # back matches that (every non-zero count becomes true).
        is_int = self.dtype in (
            torch.bool,
            torch.int8,
            torch.uint8,
            torch.int16,
            torch.uint16,
        )
        wide_dtype = torch.int64 if is_int else torch.float32
        src = torch.sparse_coo_tensor(
            self._indices(),
            _triton_cast(self._values(), wide_dtype),
            size,
            dtype=wide_dtype,
            device=self.device,
        )
    idx, vals, total = _coalesce(src, dense_shape, dnumel)
    vals = vals.reshape((total,) + dense_shape)
    if wide_dtype is not None:
        vals = _triton_cast(vals, self.dtype)
    return idx, vals, total


def _coalesce(self, dense_shape, dnumel):
    """Device-side coalescing: histogram sort plus duplicate accumulation."""
    size = tuple(int(s) for s in self.shape)
    sparse_dim = self.sparse_dim()
    device = self._indices().device
    src = self._indices().contiguous()
    nnz = self._nnz()
    vals = self._values().reshape(nnz, dnumel)
    w = _strides([int(s) for s in size[:sparse_dim]])
    sizes = torch.tensor(
        [int(s) for s in size[:sparse_dim]], dtype=torch.int64, device=device
    )
    wt = torch.tensor(w, dtype=torch.int64, device=device)
    domain = 1
    for s in size[:sparse_dim]:
        domain *= int(s)
    keys = torch.empty(nnz, dtype=torch.int64, device=device)
    _key_all[(triton.cdiv(nnz, _BLOCK_N),)](
        src, wt, keys, nnz, sparse_dim, BLOCK=_BLOCK_N
    )
    hist = torch.zeros(domain, dtype=torch.int32, device=device)
    _hist[(triton.cdiv(nnz, _BLOCK_N),)](keys, hist, nnz, BLOCK=_BLOCK_N)
    start = torch.empty(domain + 1, dtype=torch.int32, device=device)
    distinct = torch.empty(1, dtype=torch.int32, device=device)
    _scan[(1,)](hist, start, distinct, domain, BLOCK=_BLOCK_K)
    total = int(distinct.item())
    idx_out = torch.empty((sparse_dim, max(total, 1)), dtype=torch.int64, device=device)
    if total > 0:
        _coalesce_idx[(triton.cdiv(domain, _BLOCK_N),)](
            wt,
            sizes,
            start,
            idx_out,
            idx_out.stride(0),
            domain,
            sparse_dim,
            BLOCK=_BLOCK_N,
        )
    vout = torch.zeros((max(total, 1), dnumel), dtype=vals.dtype, device=device)
    if nnz > 0:
        _scatter_val[(nnz, triton.cdiv(dnumel, _BLOCK_V))](
            vals, keys, start, vout, dnumel, nnz, _BLOCK_V
        )
    return idx_out[:, :total].contiguous(), vout[:total], total


def _pool_key(self, dim, indices=None):
    """Pool (group) keys of every entry; ``indices`` may be the coalesced
    index matrix (required when ``self`` is uncoalesced — computing pool keys
    over the raw stored coordinates would mismatch the coalesced values)."""
    size, sparse_dim, dense_shape, _ = _sparse_meta(self)
    device = self._indices().device
    src = (self._indices() if indices is None else indices).contiguous()
    nnz = src.shape[1]
    w = _strides([int(s) for s in size[:sparse_dim]], skip=dim)
    wt = torch.tensor(w, dtype=torch.int64, device=device)
    keys = torch.empty(nnz, dtype=torch.int64, device=device)
    _key_pool[(triton.cdiv(nnz, _BLOCK_N),)](
        src, wt, keys, nnz, sparse_dim, dim, BLOCK=_BLOCK_N
    )
    return keys


def _forward_core(self, dim, out_dtype):
    size, sparse_dim, dense_shape, dnumel = _sparse_meta(self)
    device = self._indices().device
    if self.is_coalesced():
        indices = self._indices()
        vals = self._values().reshape(self._nnz(), dnumel)
        nnz = self._nnz()
    else:
        indices, vals, nnz = _coalesce(self, dense_shape, dnumel)
    via32 = self.dtype in (torch.float8_e4m3fn, torch.float8_e5m2)
    f64 = out_dtype == torch.float64
    result = torch.empty((nnz, dnumel), dtype=out_dtype, device=device)
    ginfo = None
    if nnz > 0:
        if dim >= sparse_dim:
            a = dim - sparse_dim
            outer = 1
            for s in dense_shape[:a]:
                outer *= s
            red = dense_shape[a]
            inner = 1
            for s in dense_shape[a + 1 :]:
                inner *= s
            oi = outer * inner
            small = red <= 128
            np2r = 1
            while np2r < red:
                np2r *= 2
            # keep the register tile bounded as the reduce axis grows
            bci = _BLOCK_CI
            if red > 64:
                bci = 32
            elif red > 32:
                bci = 64
            if inner == 1:
                _lse_wide[(nnz, outer)](vals, result, red, np2r, outer, f64, via32)
            else:
                _lse_dense[(nnz, triton.cdiv(oi, bci))](
                    vals,
                    result,
                    red,
                    inner,
                    oi,
                    f64,
                    via32,
                    NP2R=np2r,
                    SMALL=small,
                    BLOCK_CI=bci,
                )
        else:
            # The pool keys of the coalesced entries are compacted with the
            # FlagGems sort kernel; the groups are contiguous runs in sorted
            # order, replacing the dense histogram + scan + placement with an
            # O(nnz) boundary scan.
            keys = _pool_key(self, dim, indices)
            sorted_keys, perm = sort(keys)
            _, gstart, ngroups = _seg_boundaries(sorted_keys)
            _group_lse[(ngroups, triton.cdiv(dnumel, _BLOCK_D))](
                vals, result, gstart, perm, dnumel, f64, via32, BLOCK_D=_BLOCK_D
            )
            ginfo = (gstart, perm)
    return indices, result, size, sparse_dim, dense_shape, dnumel, ginfo


def _forward(self, dim, out_dtype):
    indices, result, size, sparse_dim, dense_shape, dnumel, _ = _forward_core(
        self, dim, out_dtype
    )
    nnz = result.shape[0]
    return torch.sparse_coo_tensor(
        indices,
        result.reshape((nnz,) + dense_shape),
        size,
        dtype=out_dtype,
        device=indices.device,
        is_coalesced=True,
    )


class _SparseLogSoftmax(torch.autograd.Function):
    @staticmethod
    def forward(ctx, inp, dim, out_dtype):
        indices, result, size, sparse_dim, dense_shape, dnumel, ginfo = _forward_core(
            inp, dim, out_dtype
        )
        ctx.dim = dim
        ctx.sparse_dim = sparse_dim
        ctx.size = size
        ctx.dense_shape = dense_shape
        ctx.dnumel = dnumel
        ctx.indices = indices
        ctx.ginfo = ginfo
        ctx.in_dtype = inp.dtype
        ctx.save_for_backward(result)
        nnz = result.shape[0]
        return torch.sparse_coo_tensor(
            indices,
            result.reshape((nnz,) + dense_shape),
            size,
            dtype=out_dtype,
            device=indices.device,
            is_coalesced=True,
        )

    @staticmethod
    def backward(ctx, grad_out):
        oval = ctx.saved_tensors[0]
        nnz = oval.shape[0]
        if grad_out.is_coalesced():
            dy = grad_out._values().reshape(nnz, ctx.dnumel)
        else:
            _, g_vals, total = triton_coalesce(grad_out)
            dy = g_vals.reshape(total, ctx.dnumel)
        do = torch.empty_like(dy)
        dnumel = ctx.dnumel
        f64 = ctx.in_dtype == torch.float64
        if nnz > 0:
            if ctx.dim >= ctx.sparse_dim:
                a = ctx.dim - ctx.sparse_dim
                outer = 1
                for s in ctx.dense_shape[:a]:
                    outer *= s
                red = ctx.dense_shape[a]
                inner = 1
                for s in ctx.dense_shape[a + 1 :]:
                    inner *= s
                oi = outer * inner
                _bwd_dense[(nnz, triton.cdiv(oi, _BLOCK_CI))](
                    dy, oval, do, red, inner, oi, f64, BLOCK_CI=_BLOCK_CI
                )
            else:
                gstart, order = ctx.ginfo
                ng = gstart.numel() - 1
                adt = torch.float64 if f64 else do.dtype
                acc = torch.empty(ng * dnumel, dtype=adt, device=oval.device)
                _bwd_gseq[(ng, triton.cdiv(dnumel, _BLOCK_D))](
                    dy, gstart, order, acc, dnumel, f64, BLOCK_D=_BLOCK_D
                )
                _bwd_gwrite[(ng, triton.cdiv(dnumel, _BLOCK_D))](
                    dy, oval, gstart, order, acc, do, dnumel, f64, BLOCK_D=_BLOCK_D
                )
        grads = torch.sparse_coo_tensor(
            ctx.indices,
            do.reshape((nnz,) + ctx.dense_shape),
            ctx.size,
            dtype=ctx.in_dtype,
            device=ctx.indices.device,
            is_coalesced=True,
        )
        return grads, None, None


def _resolve_dtype(self, dtype):
    if dtype is None:
        return self.dtype
    target = dtype if isinstance(dtype, torch.dtype) else torch.dtype(dtype)
    if target not in (torch.float32, torch.float64):
        raise RuntimeError(
            "\"log_softmax\" not implemented for '%s'" % _NAMES.get(target, str(target))
        )
    if self.dtype == torch.float16 and target == torch.float32:
        raise RuntimeError(
            "log_softmax: with half to float conversion is not supported on cuda:0"
        )
    return target


def _sparse_log_softmax_int(self, dim, dtype=None):
    """``aten::_sparse_log_softmax.int`` overload: positional dtype."""
    return _sparse_log_softmax(self, dim, half_to_float=False, dtype=dtype)


def _sparse_log_softmax_out(self, dim, half_to_float, out=None):
    """``aten::_sparse_log_softmax.out`` overload."""
    return _sparse_log_softmax(self, dim, half_to_float=half_to_float, out=out)


def _sparse_log_softmax(self, dim, half_to_float=False, dtype=None, out=None):

    logger.debug("GEMS SPARSE_LOG_SOFTMAX")
    if not self.is_sparse or self.layout != torch.sparse_coo:
        raise RuntimeError(
            "Could not run 'aten::_sparse_log_softmax' with arguments from the "
            "'CUDA' backend. This could be because the operator doesn't exist for "
            "this backend, or was omitted during the selective/custom build process "
            "(if using a custom build). If you are a Facebook employee using PyTorch "
            "on mobile, you can also receive this error if you are trying to run the "
            "operator with a lite interpreter."
        )
    if half_to_float:
        raise RuntimeError(
            "log_softmax: with half to float conversion is not supported on cuda:0"
        )
    if not isinstance(dim, int):
        raise TypeError("dim must be an int")
    if dim < -self.dim() or dim >= self.dim():
        raise IndexError(
            "Dimension out of range (expected to be in range of [%d, %d], but got %d)"
            % (-self.dim(), self.dim() - 1, dim)
        )
    dim = dim % self.dim()
    if dtype is None and self.dtype not in (torch.float32, torch.float64):
        raise RuntimeError(
            "\"log_softmax\" not implemented for '%s'"
            % _NAMES.get(self.dtype, str(self.dtype))
        )
    target = _resolve_dtype(self, dtype)
    if self.requires_grad and target in (torch.float32, torch.float64):
        result = _SparseLogSoftmax.apply(self, dim, target)
    else:
        result = _forward(self, dim, target)
    if out is None:
        return result
    out.copy_(result)
    return out
