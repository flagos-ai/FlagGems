def compute_bias_grad(grad, beta, bias):
    # Column-broadcast gradients are fused; this covers all other layouts.
    if grad.numel() == 0:
        return fresh_zero_gradient(bias.shape, bias.dtype, bias.device)
    if bias.numel() == 1:
        return scalar_bias_gradient(grad, beta, bias)
    scaled = (
        mul(grad, beta)
        if beta != 1
        else (grad if grad.is_contiguous() else copy_tensor(grad))
    )
    return sum_to_size(scaled, bias.shape)
