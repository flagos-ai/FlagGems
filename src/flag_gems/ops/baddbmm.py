    @staticmethod
    def _save_context(ctx, bias, A, B, beta, alpha):
        ctx.save_for_backward(A, B, bias)
        ctx.alpha = alpha
        ctx.beta = beta
        ctx.matrix_plan = matrix_plan(
            A, B, ctx.needs_input_grad[1:3], alpha, beta, bias, ctx.needs_input_grad[0]
        )

