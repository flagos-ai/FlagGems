def fresh_zero_gradient(shape, dtype, device):
    if 0 in shape:
        return torch.empty(shape, dtype=dtype, device=device)
    out = torch.empty((), dtype=dtype, device=device)
    key = (device, dtype)
    launch = _ZERO_FILL_LAUNCHERS.get(key)
    if launch is None:
        kernel = _zero_fill_kernel[1,](out, 1, 32, num_warps=1)
        _ZERO_FILL_LAUNCHERS[key] = kernel[1, 1, 1]
    else:
        launch(out, 1, 32)
    return out.expand(shape)


