def _repack_taps_kernel(
    w_ptr,
    wp_ptr,
    Cin,
    Co,
    wsCo,
    wsCi,
    wsKD,
    wsKH,
    wsKW,
    kH: tl.constexpr,
    kW: tl.constexpr,
    TOT,
    BLK: tl.constexpr,
):
    """(Co, Cin, kD, kH, kW) -> (kD*kH*kW, Cin, Co) contiguous repack."""
    pid = tl.program_id(0)
    i = pid * BLK + tl.arange(0, BLK)
    m = i < TOT
    co = i % Co
    t = i // Co
    ci = t % Cin
    tap = t // Cin
    KHW: tl.constexpr = kH * kW
    kd = tap // KHW
    r = tap - kd * KHW
    kh = r // kW
    kw = r - kh * kW
