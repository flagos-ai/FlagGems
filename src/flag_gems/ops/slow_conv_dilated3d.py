def slow_conv_dilated3d(
    self,
    weight,
    kernel_size,
    bias=None,
    stride=(1, 1, 1),
    padding=(0, 0, 0),
    dilation=(1, 1, 1),
    out=None,
    **kwargs,
):
    """Forward dilated 3-D cross-correlation, matching aten::slow_conv_dilated3d."""
    logger.debug("GEMS SLOW_CONV_DILATED3D")
    x = self

    if not torch.is_tensor(x) or not torch.is_tensor(weight):
        raise TypeError("input and weight must be tensors")

    ndim = x.dim()
    if ndim == 4:
        unbatched = True
    elif ndim == 5:
        unbatched = False
    else:
        raise RuntimeError("input must be 4D or 5D tensor but got %dD tensor" % ndim)

    if weight.dim() != 5:
        raise RuntimeError(
            "weight must be a 5D tensor but got %dD tensor" % weight.dim()
        )

    ks = _triple(kernel_size, "kernel_size")
    kD, kH, kW = ks
    if kD <= 0 or kH <= 0 or kW <= 0:
        raise RuntimeError(
            "kernel size should be greater than zero, but got %s" % (list(ks),)
        )
    if (int(weight.size(2)), int(weight.size(3)), int(weight.size(4))) != ks:
        raise RuntimeError(
            "weight[2:] shape %s must be equal to kernel_size %s"
            % (list(weight.shape[2:]), list(ks))
        )

    if unbatched:
        N = 1
        C, D, H, W = int(x.size(0)), int(x.size(1)), int(x.size(2)), int(x.size(3))
    else:
        N = int(x.size(0))
        C, D, H, W = (int(x.size(1)), int(x.size(2)), int(x.size(3)), int(x.size(4)))

    Cin = int(weight.size(1))
    Co = int(weight.size(0))
    if C != Cin:
        raise RuntimeError(
            "Need input of dimension %d and input.size[1] == %d but got input "
            "to be of shape %s" % (x.dim(), Cin, list(x.shape))
        )

    sD, sH, sW = _triple(stride, "stride")
    pD, pH, pW = _triple(padding, "padding")
    dD, dH, dW = _triple(dilation, "dilation")

    if sD <= 0 or sH <= 0 or sW <= 0:
        raise RuntimeError("stride should be greater than zero")
    if dD <= 0 or dH <= 0 or dW <= 0:
        raise RuntimeError("dilation should be greater than zero")

    Do = (D + 2 * pD - dD * (kD - 1) - 1) // sD + 1
    Ho = (H + 2 * pH - dH * (kH - 1) - 1) // sH + 1
    Wo = (W + 2 * pW - dW * (kW - 1) - 1) // sW + 1
    if Do < 0 or Ho < 0 or Wo < 0:
        raise RuntimeError(
            "calculated output size %d %d %d is too small (all sizes must be "
            "non-negative)" % (Do, Ho, Wo)
        )

    if x.dtype not in _SUPPORTED_DTYPES:
        raise RuntimeError("\"slow_conv_dilated3d\" not implemented for '%s'" % x.dtype)

    # Validate bias before any early return: a wrong-length bias used to be read
    # out of bounds by the kernel, and a length-0 output would silently skip the
    # validation entirely. ATen checks `bias.dim() == 1` and `bias.size(0) == Co`.
    has_bias = bias is not None
    if has_bias:
        if bias.dim() != 1:
            raise RuntimeError("bias must be 1D tensor but got %dD tensor" % bias.dim())
        if int(bias.size(0)) != Co:
            raise RuntimeError(
                "Need bias of dimension 1 and bias.size[0] == %d but got input "
                "to be of shape %s" % (Co, list(bias.shape))
            )
        if bias.device != x.device:
            raise RuntimeError(
                "bias and input must be on the same device, but got bias on %s "
                "and input on %s" % (bias.device, x.device)
            )

    out_shape = (Co, Do, Ho, Wo) if unbatched else (N, Co, Do, Ho, Wo)
    if out is None:
        out = torch.empty(out_shape, dtype=x.dtype, device=x.device)
    elif tuple(out.shape) != tuple(out_shape):
        raise RuntimeError(
            "out has shape %s but expected %s" % (list(out.shape), list(out_shape))
        )

    L = Do * Ho * Wo
    if L == 0 or N == 0 or Co == 0:
        return out
    if Cin == 0:
        # No reduction happens, so every output element is just the bias. Fill it
        # explicitly instead of leaving torch.empty's contents in place (which is
        # what ATen's im2col+bias path also produces).
        if has_bias:
            # Channel dim is 0 for the unbatched 4-D layout and 1 for 5-D.
            bias_shape = (
                ((Co,) + (1,) * (out.dim() - 1))
                if unbatched
                else ((1, Co) + (1,) * (out.dim() - 2))
            )
            out.copy_(bias.to(x.dtype).view(bias_shape).expand(out_shape))
        else:
            out.zero_()
        return out

    if unbatched:
        xsC, xsD, xsH, xsW = x.stride()
        xsN = 0
        osCo, osD, osH, osW = out.stride()
        osN = 0
    else:
        xsN, xsC, xsD, xsH, xsW = x.stride()
        osN, osCo, osD, osH, osW = out.stride()
    wsCo, wsCi, wsKD, wsKH, wsKW = weight.stride()

    b_ptr = bias if has_bias else weight
    bsCo = bias.stride(0) if has_bias else 1

    taps = kD * kH * kW
    wp = torch.empty((taps, Cin, Co), dtype=x.dtype, device=x.device)
    total = taps * Cin * Co
    _repack_taps_kernel[(triton.cdiv(total, 1024),)](
        weight,
        wp,
        Cin,
        Co,
        wsCo,
        wsCi,
        wsKD,
        wsKH,
        wsKW,
        kH=kH,
        kW=kW,
        TOT=total,
        BLK=1024,
    )

    if x.dtype == torch.float64:
        BL, BCO, BCI, warps = 32, 32, 4, 4
        grid = (triton.cdiv(L, BL), triton.cdiv(Co, BCO), N)
        _conv3d_tap_f64_kernel[grid](
            x,
            wp,
            b_ptr,
            out,
            D,
            H,
            W,
            Cin,
            Co,
            Ho,
            Wo,
            sD,
            sH,
            sW,
            pD,
            pH,
            pW,
            dD,
            dH,
            dW,
            xsN,
            xsC,
            xsD,
            xsH,
            xsW,
            osN,
            osCo,
            osD,
            osH,
            osW,
            L,
            taps,
            bsCo,
            kD=kD,
            kH=kH,
            kW=kW,
            HAS_BIAS=has_bias,
            BL=BL,
            BCO=BCO,
            BCI=BCI,
            num_warps=warps,
        )
    else:
        # Shape-keyed launch geometry. The fully unrolled static tap loop keeps the
        # accumulator plus every live A/B tile in registers, so its occupancy
        # ceiling is set by the tile shape. Shapes whose flattened output spatial
        # size is at most 1024 launch only a handful of CTAs, so they want a
        # narrower tile and fewer warps (measured 2.80x vs 1.52x on the fp32 shape
        # with L=512); the larger shapes keep the wider tiles that won there.
        if L <= 1024:
            BL, BCO, BCI, warps = 16, 16, 16, 2
            stages = None
        elif x.dtype == torch.float32 and Co <= 16:
            # tl.dot needs N >= 16, so a 16-channel output already fills BCO=16;
            # the wider tile would only add registers and padded-out lanes. The
            # narrow tile also cannot afford the software-pipelining registers, so
            # it runs single-staged (measured 1.93x vs 0.96x on the 16-channel
            # fp32 shape).
            BL, BCO, BCI, warps = 64, 16, 16, 4
            stages = 1
        elif x.dtype == torch.float32:
            BL, BCO, BCI, warps = 32, 32, 16, 4
            # Same reasoning as the narrow branch: the reduction is fully unrolled
            # over taps, so the default pipeliner only buffers an already
            # straight-line loop. It wins on the large-spatial fp32 shapes
            # (2.16x -> 3.23x and 4.46x -> 5.00x measured) and loses on the small
            # ones, which keep the default.
            stages = 1 if L >= 4000 else None
        else:
            BL, BCO, BCI, warps = 64, 32, 16, 4
            stages = None
