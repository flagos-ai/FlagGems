def _conv3d_mixed(
    x_ptr,
    w_ptr,
    b_ptr,
    out_ptr,
    N,
    CIN,
    D,
    H,
    W,
    COUT,
    KD,
    KH,
    KW,
    SD,
    SH,
    SW,
    PD,
    PH,
    PW,
    DD,
    DH,
    DW,
    DO,
    HO,
    WO,
    P_TOTAL,
    HAS_BIAS: tl.constexpr,
    PREC: tl.constexpr,
    FP64: tl.constexpr,
    BLOCK_CO: tl.constexpr,
    BLOCK_P: tl.constexpr,
    BK: tl.constexpr,
):
    pid0 = tl.program_id(0)
    pid1 = tl.program_id(1)
    n = tl.program_id(2)

    p = pid0 * BLOCK_P + tl.arange(0, BLOCK_P)
    co = pid1 * BLOCK_CO + tl.arange(0, BLOCK_CO)

    pmask = p < P_TOTAL
    comask = co < COUT

    HW = H * W
    DHW = D * H * W
    HWO = HO * WO
    KVOL3 = KD * KH * KW

    od = p // HWO
    rem = p % HWO
    oh = rem // WO
    ow = rem % WO

    if FP64:
        acc = tl.zeros((BLOCK_CO, BLOCK_P), dtype=tl.float64)
    else:
        acc = tl.zeros((BLOCK_CO, BLOCK_P), dtype=tl.float32)

    TAPS = BK // CIN
    if TAPS < 1:
        TAPS = 1
    r = tl.arange(0, BK)
    kk_r0 = r // CIN
    rowok = kk_r0 < TAPS
    for ci0 in range(0, CIN, BK):
        ci_r = ci0 + (r % CIN)
        ciok = ci_r < CIN
        for kc in range(0, KVOL3, TAPS):
            kk_r = kc + kk_r0
            kd_r = kk_r // (KH * KW)
            kh_r = (kk_r // KW) % KH
            kw_r = kk_r % KW
            kvalid = rowok & ciok & (kk_r < KVOL3)
            idr = od[None, :] * SD + kd_r[:, None] * DD - PD
            ihr = oh[None, :] * SH + kh_r[:, None] * DH - PH
            iwr = ow[None, :] * SW + kw_r[:, None] * DW - PW
            inb = (
                pmask[None, :]
                & kvalid[:, None]
                & (idr >= 0)
                & (idr < D)
                & (ihr >= 0)
                & (ihr < H)
                & (iwr >= 0)
                & (iwr < W)
            )
            x_off = (n * CIN + ci_r[:, None]) * DHW + idr * HW + ihr * W + iwr
            x = tl.load(x_ptr + x_off, mask=inb, other=0.0)
            w_off = co[:, None] * (CIN * KVOL3) + ci_r[None, :] * KVOL3
            w_off = w_off + kk_r[None, :]
            wt = tl.load(
                w_ptr + w_off, mask=comask[:, None] & kvalid[None, :], other=0.0
            )
            if FP64:
                # tl.dot has no fp64 form: contract each BK-row chunk in fp32
                # and fold the partial result into an fp64 accumulator, so only
                # the intra-chunk (BK <= 128) summation is fp32.
                x = x.to(tl.float32)
                wt = wt.to(tl.float32)
                acc += tl.dot(wt, x, input_precision="ieee").to(tl.float64)
            elif PREC == 0:
                acc = tl.dot(wt, x, acc, input_precision="ieee")
            elif PREC == 1:
                acc = tl.dot(wt, x, acc, input_precision="tf32x3")
            else:
                acc = tl.dot(wt, x, acc)

    if HAS_BIAS:
        bias = tl.load(b_ptr + co, mask=comask, other=0.0)
        acc += bias[:, None]

    out_off = (n * COUT + co[:, None]) * P_TOTAL + p[None, :]
    omask = pmask[None, :] & comask[:, None]
    if FP64:
        tl.store(out_ptr + out_off, acc.to(out_ptr.dtype.element_ty), mask=omask)
    elif PREC == 2:
        tl.store(out_ptr + out_off, acc.to(x_ptr.dtype.element_ty), mask=omask)
    else:
        tl.store(out_ptr + out_off, acc, mask=omask)


def _pick_blocks(N, COUT, CIN, P_TOTAL, KVOL3, dtype):
    """Workload-class (BLOCK_CO, BLOCK_P, BK) heuristic.

    The classes separate tiny spatial outputs, 1x1x1 (pure channel GEMM),
    few-output-channel and deep-contraction shapes.  Every branch keeps
    ``BK >= 16`` so ``tl.dot`` is legal and gives the small tiles enough
    programs to fill the device.
    """
    low_precision = dtype in (torch.float16, torch.bfloat16)
    per_n_p = P_TOTAL // max(1, N)
    K = CIN * KVOL3
    p2 = triton.next_power_of_2
    if per_n_p < 1024:  # tiny spatial output
        bc, bp = 16, 16
        bk = min(64, p2(CIN) * 2)
    elif KVOL3 == 1:  # 1x1x1 channel GEMM
        bc, bp = 16, 128
        bk = p2(CIN)
    elif COUT <= 16:  # few channels, big spatial
        bc, bp = 16, 128
        bk = min(32, p2(CIN) * 2)
    elif COUT <= 32:
        if K >= 800:  # deep contraction (Cin=32 x 3x3x3)
            bc, bp = 16, 64
            bk = min(128, p2(CIN) * 2)
        else:
            bc, bp = 32, 32
            bk = min(128, p2(CIN) * (4 if low_precision else 2))
    else:  # COUT >= 64
        if K >= 1024:  # heaviest contraction (Cin=64 x 3x3x3)
            bc, bp = 32, 64
            bk = p2(CIN)
        else:
            bc, bp = 32, 32
            bk = min(128, p2(CIN) * (2 if low_precision else 1))
    bk = max(16, bk)
    return bc, bp, bk


def _fill_bias_or_zero(out, bias):
    """Pre-fill ``out`` the way native pre-fills its buffer: bias broadcast
    over the spatial dims, or zeros when there is no bias."""
    if out.numel() == 0:
        return
    if bias is None:
        out.zero_()
    else:
        bias_view = bias.reshape(1, -1, 1, 1, 1)
        out.copy_(bias_view.expand_as(out))


def _slow_conv_dilated3d_impl(
    self, weight, kernel_size, bias, stride, padding, dilation, out
):
    kernel_size = _as_triple(kernel_size, "kernel sizes")
    stride = _as_triple(stride, "strides")
    padding = _as_triple(padding, "pads")
    dilation = _as_triple(dilation, "dilations")

    for name, values in (
        ("kernel size", kernel_size),
        ("stride", stride),
        ("dilation", dilation),
    ):
        if not all(v > 0 for v in values):
            raise RuntimeError(
                f"{name} should be greater than zero, but got {list(values)}"
            )

    if not torch.is_tensor(self) or not torch.is_tensor(weight):
        raise TypeError("slow_conv_dilated3d expects tensor inputs")
    if self.dim() not in (4, 5):
        raise RuntimeError(
            f"input must be 4D or 5D tensor but got {self.dim()}D tensor"
        )
    if not self.is_floating_point():
        raise RuntimeError(
            "slow_conv_dilated3d not implemented for non-floating point dtypes"
        )
    supported = (torch.float32, torch.float16, torch.bfloat16, torch.float64)
    if self.dtype not in supported:
        raise RuntimeError(f"slow_conv_dilated3d: unsupported dtype {self.dtype}")

    # Native materialises strided operands and unsqueezes the unbatched 4-D
    # input; the kernel below indexes both with plain contiguous offsets.
    unbatched = self.dim() == 4
    inp = self if self.is_contiguous() else self.contiguous()
    if unbatched:
        inp = inp.unsqueeze(0)

    N, CIN, D, H, W = inp.shape
    KD, KH, KW = kernel_size
    SD, SH, SW = stride
    PD, PH, PW = padding
    DD, DH, DW = dilation

    DO = (D + 2 * PD - DD * (KD - 1) - 1) // SD + 1
    HO = (H + 2 * PH - DH * (KH - 1) - 1) // SH + 1
    WO = (W + 2 * PW - DW * (KW - 1) - 1) // SW + 1

    if DO < 0 or HO < 0 or WO < 0:
        raise RuntimeError(
            f"calculated output size {DO} {HO} {WO} is too small "
            "(all sizes must be non-negative)"
        )
    if weight.dim() != 5:
        raise RuntimeError(f"weight must be 5D tensor but got {weight.dim()}D tensor")
    COUT = weight.shape[0]
    if CIN != weight.shape[1]:
        raise RuntimeError(
            f"Need input of dimension 5 and input.size[1] == {weight.shape[1]} "
            f"but got input to be of shape {list(inp.shape)}"
        )
    if bias is not None:
        if not torch.is_tensor(bias):
            raise TypeError("slow_conv_dilated3d: bias must be a Tensor or None")
        if bias.shape != (COUT,):
            raise RuntimeError(
                f"bias must be 1D tensor of length {COUT} "
                f"but got shape {list(bias.shape)}"
            )

    shape = (N, COUT, DO, HO, WO)
    expected = shape[1:] if unbatched else shape
    wrote_out = False
    if out is not None:
        if tuple(out.shape) != expected:
            raise RuntimeError(
                f"out shape {tuple(out.shape)} does not match expected {expected}"
            )
        if out.dtype != inp.dtype or out.device != inp.device:
            raise RuntimeError("out dtype and device must match the input")
        if out.is_contiguous():
            target = out.unsqueeze(0) if unbatched else out
            wrote_out = True
        else:
            target = torch.empty(shape, dtype=inp.dtype, device=inp.device)
    else:
        target = torch.empty(shape, dtype=inp.dtype, device=inp.device)

    P_TOTAL = DO * HO * WO
    weight_c = weight if weight.is_contiguous() else weight.contiguous()
    bias_c = None
    if bias is not None:
        bias_c = bias if bias.is_contiguous() else bias.contiguous()

    if P_TOTAL == 0 or COUT == 0 or N == 0:
        pass
    elif CIN == 0:
        # Empty contraction: the output is exactly the pre-filled buffer.
        _fill_bias_or_zero(target, bias_c)
    else:
        _launch(
            inp,
            weight_c,
            bias_c,
            target,
            N,
            CIN,
            D,
            H,
            W,
            COUT,
            (KD, KH, KW),
            (SD, SH, SW),
            (PD, PH, PW),
            (DD, DH, DW),
            DO,
            HO,
            WO,
            P_TOTAL,
        )

    if out is not None:
        if not wrote_out:
            out.copy_(target[0] if unbatched else target)
        return out
    return target[0] if unbatched else target


def _launch(
    inp,
    weight,
    bias,
    out,
    N,
    CIN,
    D,
    H,
    W,
    COUT,
    kernel_size,
    stride,
    padding,
    dilation,
    DO,
    HO,
    WO,
    P_TOTAL,
):
    KD, KH, KW = kernel_size
    SD, SH, SW = stride
    PD, PH, PW = padding
    DD, DH, DW = dilation
    dtype = inp.dtype
    if dtype == torch.float64:
        fp64 = True
    elif dtype in (torch.float32, torch.float16, torch.bfloat16):
        fp64 = False
    else:
        raise RuntimeError(f"slow_conv_dilated3d: unsupported dtype {dtype}")

    BLOCK_CO, BLOCK_P, BK = _pick_blocks(N, COUT, CIN, P_TOTAL, KD * KH * KW, dtype)
    if dtype == torch.float32:
        prec = 1 if CIN * KD * KH * KW >= 1024 else 0
    elif fp64:
        prec = 0
    else:
        prec = 2
    num_warps = 8 if BLOCK_CO * BLOCK_P > 2048 else 4

    grid = (triton.cdiv(P_TOTAL, BLOCK_P), triton.cdiv(COUT, BLOCK_CO), N)
    with torch_device_fn.device(inp.device):
        _conv3d_mixed[grid](
            inp,
            weight,
            bias if bias is not None else weight,
            out,
            N,
            CIN,
            D,
            H,
            W,
            COUT,
            KD,
            KH,
            KW,
            SD,
            SH,
            SW,
            PD,
            PH,
            PW,
            DD,
            DH,
            DW,
            DO,
            HO,
            WO,
            P_TOTAL,
            HAS_BIAS=bias is not None,
            PREC=prec,
            FP64=fp64,
            BLOCK_CO=BLOCK_CO,
            BLOCK_P=BLOCK_P,
            BK=BK,
            num_warps=num_warps,
        )


