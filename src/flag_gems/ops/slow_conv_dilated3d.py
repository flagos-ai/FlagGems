"""Triton implementation of ``aten::slow_conv_dilated3d`` (forward).

A direct, im2col-free 3-D (dilated) convolution.  The output plane is
flattened to ``p = od * H_out * W_out + oh * W_out + ow`` and every program
owns a ``(BLOCK_CO, BLOCK_P)`` tile of ``(out_channel, output_position)``.
The contraction axis ``K = C_in * kD * kH * kW`` is walked in chunks of ``BK``
rows, each chunk covering ``BK // C_in`` kernel taps for every input channel,
so one ``tl.dot`` consumes a rectangular tile with no channel padding waste.

Semantics (``weight`` is the plain conv layout ``(C_out, C_in, kD, kH, kW)``,
no kernel flip):

    out[n, co, od, oh, ow] = bias[co]
        + sum_{ci, kd, kh, kw} self[n, ci,
                                   od*SD + kd*DD - PD,
                                   oh*SH + kh*DH - PH,
                                   ow*SW + kw*DW - PW] * weight[co, ci, kd, kh, kw]

where taps that fall outside the input contribute zero.  ``self`` may be 5-D
``(N, C_in, D, H, W)`` or unbatched 4-D ``(C_in, D, H, W)``; the output rank
follows the input rank.  ``stride``, ``padding``, ``dilation`` and
``kernel_size`` accept an int (broadcast to all three spatial dims) or a
3-element sequence.

Precision: fp32 inputs use an IEEE ``tl.dot`` for small contractions and the
``tf32x3`` emulation above ``K = 1024``; fp16/bf16 use the native tensor-core
dot with fp32 accumulation.  ``tl.dot`` has no fp64 form, so fp64 inputs
contract each ``BK``-row chunk in fp32 and fold the chunk partial into an fp64
accumulator (the fp64 operands themselves are rounded to fp32 per element).
"""

