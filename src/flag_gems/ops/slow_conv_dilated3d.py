def _conv3d_tap_kernel(
    x_ptr,
    wp_ptr,
    b_ptr,
    o_ptr,
    D,
    H,
    W,
    Cin,
    Co,
    Ho,
    Wo,
    sD,
    sH,
    sW,
    pD,
    pH,
    pW,
    dD,
    dH,
    dW,
    xsN,
    xsC,
    xsD,
    xsH,
    xsW,
    osN,
    osCo,
    osD,
    osH,
    osW,
    L,
    bsCo,
    kD: tl.constexpr,
    kH: tl.constexpr,
    kW: tl.constexpr,
    HAS_BIAS: tl.constexpr,
    PREC: tl.constexpr,
    BL: tl.constexpr,
    BCO: tl.constexpr,
    BCI: tl.constexpr,
):
    pid_l = tl.program_id(0)
    pid_c = tl.program_id(1)
    n = tl.program_id(2)
    HWo = Ho * Wo

    lidx = pid_l * BL + tl.arange(0, BL)
    ml = lidx < L
    do = lidx // HWo
    rem = lidx - do * HWo
    ho = rem // Wo
    wo = rem - ho * Wo

    co = pid_c * BCO + tl.arange(0, BCO)
    mc = co < Co

    rowD = do * sD - pD
    rowH = ho * sH - pH
    rowW = wo * sW - pW
    rowA = rowD * xsD + rowH * xsH + rowW * xsW

    acc = tl.zeros((BL, BCO), dtype=tl.float32)
    x_base = x_ptr + n * xsN

    for kd in tl.static_range(kD):
        id_ = rowD + kd * dD
        okD = (id_ >= 0) & (id_ < D)
        for kh in tl.static_range(kH):
            ih_ = rowH + kh * dH
            okH = (ih_ >= 0) & (ih_ < H)
            for kw in tl.static_range(kW):
                iw_ = rowW + kw * dW
                ok = ml & okD & okH & (iw_ >= 0) & (iw_ < W)
                base = rowA + (kd * dD) * xsD + (kh * dH) * xsH + (kw * dW) * xsW
                tap = (kd * kH + kh) * kW + kw
                wb = wp_ptr + tap * Cin * Co + co[None, :]
                for c0 in range(0, Cin, BCI):
                    ci = c0 + tl.arange(0, BCI)
                    mci = ci < Cin
                    a = tl.load(
                        x_base + base[:, None] + (ci * xsC)[None, :],
                        mask=ok[:, None] & mci[None, :],
                        other=0.0,
                    )
                    bt = tl.load(
                        wb + (ci * Co)[:, None],
                        mask=mci[:, None] & mc[None, :],
                        other=0.0,
                    )
                    if PREC == 1:
                        acc = tl.dot(a, bt, acc, input_precision="ieee")
                    else:
                        acc = tl.dot(a, bt, acc)

    if HAS_BIAS:
        # bias may be a non-contiguous view (e.g. bias[::2]); ATen makes it
        # contiguous, so honour the caller's stride rather than assuming 1.
        acc += tl.load(b_ptr + co * bsCo, mask=mc, other=0.0).to(tl.float32)[None, :]

    optr = (
        o_ptr
        + n * osN
        + (co * osCo)[None, :]
        + (do * osD + ho * osH + wo * osW)[:, None]
    )
    tl.store(
        optr,
        acc.to(o_ptr.dtype.element_ty),
        mask=ml[:, None] & mc[None, :],
    )


