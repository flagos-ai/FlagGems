import logging

import triton
import triton.language as tl

from flag_gems.utils import pointwise_dynamic, tl_extra_shim
from flag_gems.utils._atanh_autograd import unary_autograd

# libdevice atanh is a branch-free polynomial/rational approximation that
# keeps full relative accuracy down to x ~ 0, unlike the naive
# 0.5*log((1+x)/(1-x)) which cancels catastrophically for small |x|.
_ATANH = tl_extra_shim.atanh
logger = logging.getLogger(__name__)


@pointwise_dynamic(promotion_methods=[(0, "INT_TO_FLOAT")])
@triton.jit
def atanh_func(x):
    # Match torch.atanh by evaluating in float32 before casting back.
    return _ATANH(x.to(tl.float32))


def atanh(A):
    logger.debug("GEMS ATANH")
    return unary_autograd(A, "atanh", atanh_func)


def atanh_(A):
    logger.debug("GEMS ATANH_")
    # ATen rejects in-place atanh on integer and bool inputs (the float result
    # cannot be cast back into the output buffer); mirror that instead of
    # silently truncating.
    if not A.dtype.is_floating_point:
        raise RuntimeError(
            "result type Float can't be cast to the desired output type " f"{A.dtype}"
        )
    return unary_autograd(A, "atanh", lambda x: atanh_func(x, out0=x), inplace=True)
