def _rebind_view(t: torch.Tensor) -> torch.Tensor:
    """Re-create ``t`` from its storage without lazy conj/neg bits.

    ``view`` and ``view_as_real`` refuse unresolved conjugate views, but the
    storage-level view carries the same size/stride/offset. Native reshape
    resolves the lazy bits the same way when it must materialize.
    """
    return torch.empty(0, dtype=t.dtype, device=t.device).set_(
        t.untyped_storage(), t.storage_offset(), t.size(), t.stride()
    )


def _copy_logical(src: torch.Tensor, dst: torch.Tensor) -> None:
    """Copy the logical values of ``src`` into ``dst`` (same logical shape).

    The transpose-reducing tiled kernel handles the common materializing
    layout; ``copy_`` covers everything else, and handles arbitrary strides on
    both sides with a single data movement. Complex tensors ride a real-valued
    view because Triton has no complex pointer type; the lazy conj/neg bits are
    re-applied afterwards so the destination holds the same logical values as
    the input.
    """
    if src.is_complex():
        copy_(torch.view_as_real(dst), torch.view_as_real(_rebind_view(src)))
        if src.is_conj():
            conj_physical_(dst)
        if src.is_neg():
            # flag_gems ``neg_`` is real-valued only (Triton has no complex
            # dtype), so negate through the real view.
            neg_(torch.view_as_real(dst))
    elif src.is_neg():
        # A lazy-neg view keeps the pre-negation values in storage; negate the
        # copied result to recover the logical values.
        copy_(dst, _rebind_view(src))
        neg_(dst)
    elif not _tile_copy(src, dst):
        copy_(dst, src)


def reshape_as(self: torch.Tensor, other: torch.Tensor) -> torch.Tensor:
    """Returns this tensor with the same shape as ``other``.

    This is equivalent to ``self.reshape(other.size())``: a stride-expressible
    target returns a view of ``self``, anything else a materialized copy.
    """
    logger.debug("GEMS RESHAPE_AS")
    if not isinstance(self, torch.Tensor):
        raise TypeError("reshape_as expects a torch.Tensor input for 'self'")
    if not isinstance(other, torch.Tensor):
        raise TypeError("reshape_as expects a torch.Tensor input for 'other'")

    target_shape = tuple(other.size())
    if self.numel() != other.numel():
        raise RuntimeError(
            f"shape '{list(target_shape)}' is invalid for input of size {self.numel()}"
        )

    # Any layout the view can express returns a zero-copy view, matching
    # native reshape's computeStride decision. Consulting the port of the ATen
    # helper in Python first keeps the frequent "not viewable" case from paying
    # for the RuntimeError a failing ``view`` raises across the C++ boundary.
    if computeStride(self.shape, self.stride(), target_shape) is not None:
        return self.view(target_shape)

    # Materialize: one copy from the original strides into the final output.
    if self.requires_grad and torch.is_grad_enabled():
        return _ReshapeAsMaterialize.apply(self, tuple(self.shape), target_shape)

    out = torch.empty(target_shape, dtype=self.dtype, device=self.device)
    _copy_logical(self, out.view(self.shape))
    return out
