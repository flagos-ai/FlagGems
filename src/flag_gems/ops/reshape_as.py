"""Triton implementation of ``aten::reshape_as``.

``reshape_as(self, other)`` returns ``self`` reshaped to ``other.size()``.
When the target shape is stride-expressible from ``self`` the result is a
zero-copy view sharing storage with ``self`` (strided slices, transposes,
expanded and conjugate views included); only layouts the view cannot express
are materialized, copying once from the original strides into the final
output.

Materializing is the only part that moves data, and by construction it always
reads a non-contiguous source into a contiguous destination. The generic
pointwise ``copy_`` tiles by the *logical* shape, which emits an uncoalesced
access pattern once the innermost logical axis is the outermost physical one.
``_tile_copy_kernel`` instead loads the tile with the source's contiguous axis
innermost, transposes it, and stores with the destination's contiguous axis
innermost, so both the load and the store stay coalesced. It is used whenever
the layout reduces to a single transposed pair of axes; ``copy_`` remains the
fallback for everything else.
"""

