                    vec_q = tl.sum(tl.where(cc == q, v, 0.0), axis=1)
                    new_vec_p = crot * vec_p - srot * vec_q
                    new_vec_q = srot * vec_p + crot * vec_q
                    v = tl.where(cc == p, new_vec_p[:, None], v)
                    v = tl.where(cc == q, new_vec_q[:, None], v)
