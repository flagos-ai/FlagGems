def _complex_to_real_embedding_kernel(
    A_RI,
    R,
    M: tl.constexpr,
    N: tl.constexpr,
    BLOCK_SIZE: tl.constexpr,
):
    """Embed a complex Hermitian A (n x n) into a real symmetric R (2n x 2n).

    R = [[ Re(A), -Im(A) ], [ Im(A), Re(A) ) ]]. R is real symmetric with the
    same eigenvalues as A (each with doubled multiplicity); its real
    eigenvectors [x; y] recover the complex eigenvector x + i*y.
    """
    batch = tl.program_id(0)
    offsets = tl.arange(0, BLOCK_SIZE)
    total = 4 * M * N
    mask = offsets < total
    row = offsets // (2 * N)
    col = offsets - row * (2 * N)
    src_row = tl.where(row < M, row, row - M)
    src_col = tl.where(col < N, col, col - N)
    comp = tl.where((row < M) & (col >= N), 1, 0)
    comp = tl.where((row >= M) & (col < N), 1, comp)
    vals = tl.load(
        A_RI + batch * M * N * 2 + (src_row * N + src_col) * 2 + comp,
        mask=mask,
        other=0.0,
    )
    sign = tl.where((row < M) & (col >= N), -1.0, 1.0)
    tl.store(R + batch * 4 * M * N + offsets, vals * sign, mask=mask)


@libentry()
@triton.jit
def _complex_eigh_pick_kernel(
    W_REAL,
    V_REAL,
    W,
    V_RI,
    N: tl.constexpr,
    REAL_N: tl.constexpr,
    BLOCK_N: tl.constexpr,
):
    """Recover complex eigenpairs from the real embedding's spectrum.

    The real embedding has each eigenvalue twice (multiplicity 2); we take the
    first of each pair. Each real eigenvector [x; y] (x, y in R^n) maps to the
    complex eigenvector x + i*y. Columns are re-orthonormalised (Gram-Schmidt)
    so the returned V is unitary despite the embedding's sign freedom.
    """
    batch = tl.program_id(0)
    rows = tl.arange(0, BLOCK_N)
    cols = tl.arange(0, BLOCK_N)
    row_mask = rows < N
    col_mask = cols < N
    # Even columns carry the first copy of each repeated eigenvalue.
    src_cols = cols * 2
    base = V_REAL + batch * (2 * N) * REAL_N
    vx = tl.load(
        base + rows[:, None] * REAL_N + src_cols[None, :],
        mask=row_mask[:, None] & col_mask[None, :],
        other=0.0,
    )
    vy = tl.load(
        base + (N + rows[:, None]) * REAL_N + src_cols[None, :],
        mask=row_mask[:, None] & col_mask[None, :],
        other=0.0,
    )

    out_base = V_RI + batch * N * N * 2
    offsets = rows[:, None] * N + cols[None, :]
    mask = row_mask[:, None] & col_mask[None, :]

    # Gram-Schmidt across columns for unitarity, then write real/imag interleaved.
    c = 0
    while c < N:
        cur_x = tl.sum(tl.where(cols[None, :] == c, vx, 0.0), axis=1)
        cur_y = tl.sum(tl.where(cols[None, :] == c, vy, 0.0), axis=1)
        p = 0
        while p < c:
            prev_x = tl.sum(tl.where(cols[None, :] == p, vx, 0.0), axis=1)
            prev_y = tl.sum(tl.where(cols[None, :] == p, vy, 0.0), axis=1)
            coeff_r = tl.sum(
                tl.where(row_mask, prev_x * cur_x + prev_y * cur_y, 0.0), axis=0
            )
            coeff_i = tl.sum(
                tl.where(row_mask, prev_x * cur_y - prev_y * cur_x, 0.0), axis=0
            )
            cur_x = cur_x - prev_x * coeff_r + prev_y * coeff_i
            cur_y = cur_y - prev_x * coeff_i - prev_y * coeff_r
            p += 1
        norm_sq = tl.sum(tl.where(row_mask, cur_x * cur_x + cur_y * cur_y, 0.0), axis=0)
        inv_norm = tl.rsqrt(tl.maximum(norm_sq, 1.0e-20))
        cur_x = cur_x * inv_norm
        cur_y = cur_y * inv_norm
        vx = tl.where(cols[None, :] == c, cur_x[:, None], vx)
        vy = tl.where(cols[None, :] == c, cur_y[:, None], vy)
        c += 1

    tl.store(out_base + offsets * 2, vx, mask=mask)
    tl.store(out_base + offsets * 2 + 1, vy, mask=mask)

    # Eigenvalues: take the even-indexed entries (first of each pair).
    w_idx = tl.arange(0, BLOCK_N)
    w_mask = w_idx < N
    w_vals = tl.load(W_REAL + batch * REAL_N + w_idx * 2, mask=w_mask, other=0.0)
    tl.store(W + batch * N + w_idx, w_vals, mask=w_mask)


def _symmetrise_by_uplo(A, UPLO):
    """Build a full symmetric/Hermitian matrix from the chosen triangle of A.

    eigh only uses one triangle; the other is taken as its (conjugate) transpose.
    Construction avoids triu/tril and diag_embed on the (possibly complex) tensor:
    those backend overrides are not specialised for complex dtypes. A real index
    mask selects the triangle; the diagonal is fixed in place after mirroring so
    it is not doubled.
    """
    n = A.shape[-1]
    idx = torch.arange(n, device=A.device)
    if UPLO == "U":
        tri_mask = idx[None, :] >= idx[:, None]  # upper triangle incl. diagonal
    else:
        tri_mask = idx[None, :] <= idx[:, None]  # lower triangle incl. diagonal

    tri = A * tri_mask  # bool mask broadcast; elementwise mul, no kernel override issue
    if A.is_complex():
        sym = tri + tri.mH
    else:
        sym = tri + tri.transpose(-2, -1)
    # The diagonal was mirrored (doubed); restore it from the single-triangle value.
    sym = sym.clone()
    sym.diagonal(dim1=-2, dim2=-1).copy_(tri.diagonal(dim1=-2, dim2=-1))
    return sym


def _jacobi_eigh_real(A, n, compute_v=True):
    """Real symmetric eigendecomposition via the global-memory Jacobi path.

    Each sweep drives every (p, q) pair through a round-robin ordering. Per
    step, ROUND/2 disjoint pairs are rotated in parallel through three passes
    — compute (c, s), right-rotate the columns (A := A J, V := V J), then
    left-rotate the rows (A := J^T A) — so a sweep completes in O(N) launches.

    When compute_v is False, eigenvector computation and storage are skipped;
    eigenvalues do not depend on V.
    """
    batch = A.shape[0]
    block_n = triton.next_power_of_2(n)
    sweeps = 14 if n <= 17 else 12

    W = torch.empty((batch, n), dtype=torch.float32, device=A.device)
    if compute_v:
        V = torch.empty((batch, n, n), dtype=torch.float32, device=A.device)
    else:
        # A valid-but-unused pointer: the kernels guard every V access behind
        # COMPUTE_V, so the buffer is never read or written here. Triton still
        # needs a real pointer to compile, so a single-element tensor suffices.
        V = torch.empty((1,), dtype=torch.float32, device=A.device)

    round_n = n if n % 2 == 0 else n + 1
    half = round_n // 2
    work = torch.empty((batch, n, n), dtype=torch.float32, device=A.device)
    cs = torch.empty((batch, half, 2), dtype=torch.float32, device=A.device)
    with torch_device_fn.device(A.device):
        _jacobi_eigh_global_init_kernel[(batch,)](
            A, work, V, N=n, BLOCK_N=block_n, COMPUTE_V=compute_v, num_warps=4
        )
        for _ in range(sweeps):
            for step in range(round_n - 1):
                _jacobi_eigh_global_cs_kernel[(batch, half)](
                    work,
                    cs,
                    n,
                    step,
                    ROUND=round_n,
                    BLOCK_N=block_n,
                    num_warps=4,
                )
                _jacobi_eigh_global_col_kernel[(batch, half)](
                    work,
                    V,
                    cs,
                    n,
                    step,
                    ROUND=round_n,
                    BLOCK_N=block_n,
                    COMPUTE_V=compute_v,
                    num_warps=4,
                )
                _jacobi_eigh_global_row_kernel[(batch, half)](
                    work,
                    cs,
                    n,
                    step,
                    ROUND=round_n,
                    BLOCK_N=block_n,
                    num_warps=4,
                )
        _jacobi_eigh_extract_diag_kernel[(batch,)](
            work, W, n, BLOCK_N=block_n, num_warps=4
        )
    Ws = W

    # Ascending sort of eigenvalues; permute eigenvector columns only when V
    # was computed.
    W_sorted = torch.empty_like(Ws)
    if compute_v:
        V_sorted = torch.empty_like(V)
        with torch_device_fn.device(A.device):
            _jacobi_eigh_sort_kernel[(batch, n)](
                Ws, V, W_sorted, V_sorted, N=n, BLOCK_N=block_n, num_warps=1
            )
        return W_sorted, V_sorted
    else:
        # Eigenvalues only: sort W ascending on device (no eigenvectors to
        # permute, so the sort kernel is not needed).
        W_sorted, _ = Ws.sort(dim=-1)
        V_dummy = torch.empty((0,), dtype=torch.float32, device=A.device)
        return W_sorted, V_dummy


def _jacobi_eigh_complex(A, n, compute_v=True):
    """Complex Hermitian eigendecomposition via real embedding.

    A -> real symmetric R (2n x 2n) -> real Jacobi eigh -> recover complex (W, V).
    Computed in float32; complex128 is widened only at the return cast. When
    compute_v is False the pick kernel is skipped (eigenvalues come from the
    real path alone).
    """
    batch = A.shape[0]
    a_ri = torch.view_as_real(A.contiguous()).reshape(batch, n, n, 2)
    real_n = 2 * n
    R = torch.empty((batch, real_n, real_n), dtype=torch.float32, device=A.device)
    block_embed = triton.next_power_of_2(4 * n * n)
    with torch_device_fn.device(A.device):
        _complex_to_real_embedding_kernel[(batch,)](
            a_ri, R, M=n, N=n, BLOCK_SIZE=block_embed, num_warps=1
        )

    W_real, V_real = _jacobi_eigh_real(R, real_n, compute_v=compute_v)

    # The embedding doubles each eigenvalue; take the even-indexed entries.
    w_idx = torch.arange(0, n, device=A.device) * 2
    W = W_real[..., w_idx]

    if not compute_v:
        V_dummy = torch.empty((0,), dtype=A.dtype, device=A.device)
        return W, V_dummy

    # Pick writes float32 real/imag regardless of input complex width; collect
    # into a complex64 buffer and cast to the target dtype at the return.
    V_f32 = torch.empty((batch, n, n), dtype=torch.complex64, device=A.device)
    v_ri = torch.view_as_real(V_f32.contiguous()).reshape(batch, n, n, 2)
    block_n = triton.next_power_of_2(n)
    with torch_device_fn.device(A.device):
        _complex_eigh_pick_kernel[(batch,)](
            W_real,
            V_real,
            W,
            v_ri,
            N=n,
            REAL_N=real_n,
            BLOCK_N=block_n,
            num_warps=1,
        )
    V = V_f32.to(A.dtype)
    return W, V


def linalg_eigh(A, UPLO="L", compute_v=True):
    """Eigenvalue decomposition of symmetric/Hermitian matrices on device.

    Dispatch by size (all paths are Triton kernels):
      - n == 2  : closed-form 2x2 kernel.
      - n < 2   : diagonal as eigenvalues, identity as eigenvectors.
      - 3 <= n <= 64 (real) / 2n <= 128 (complex): register-resident Jacobi.
      - larger  : global-memory pair-wise Jacobi.
    Complex inputs use a real embedding; eigenvalues are real, eigenvectors
    complex and unitary. fp16/bf16 are widened to fp32 and cast back.

    When compute_v is False, only eigenvalues are computed and eigenvectors
    are returned as an empty tensor.
    """
    logger.debug("GEMS LINALG_EIGH")

    if A.ndim < 2 or A.shape[-1] != A.shape[-2]:
        raise ValueError(f"Input matrix must be square, got shape {A.shape}")

    n = A.shape[-1]
    batch_shape = A.shape[:-2]
    out_dtype = A.dtype
    is_complex = A.is_complex()

    # Eigenvector return type for the compute_v=False case: empty, input dtype.
    empty_v = lambda: torch.empty((0,), dtype=out_dtype, device=A.device)

    if n < 2:
        # 0x0 / 1x1: eigenvalues are the diagonal, eigenvectors the identity.
        # UPLO is irrelevant here (single diagonal element); avoid constructing a
        # symmetrised matrix so no complex-host ops are needed for trivial inputs.
        # For Hermitian input the diagonal is real; take the real part. The
        # identity eigenvectors are built as real then cast, since the overridden
        # ones_like does not specialise complex dtypes.
        diag = A.diagonal(dim1=-2, dim2=-1).clone()
        if is_complex:
            w_dtype = torch.float32 if out_dtype == torch.complex64 else torch.float64
            eigenvalues = diag.real.to(w_dtype)
        else:
            eigenvalues = diag.to(out_dtype)
        if not compute_v:
            return eigenvalues, empty_v()
        # Identity eigenvectors on the input's last two dims, built in a real
        # dtype then cast (avoids complex ones_like).
        eye = torch.eye(n, dtype=torch.float32, device=A.device)
        eye_shape = (*batch_shape, n, n)
        eigenvectors = eye.expand(eye_shape).contiguous().to(out_dtype)
        return eigenvalues, eigenvectors

    # eigh uses only one triangle; build the full symmetric/Hermitian matrix.
    A_sym = _symmetrise_by_uplo(A, UPLO)

    # fp16/bf16 (real) are widened to fp32 for the Triton kernels.
    if not is_complex and out_dtype in (torch.float16, torch.bfloat16):
        A_sym = A_sym.to(torch.float32)

    if n == 2 and not is_complex:
        A_flat = A_sym.reshape(-1, 2, 2)
        eigenvalues = torch.zeros(
            A_flat.shape[0], 2, dtype=A_flat.dtype, device=A_flat.device
        )
        grid = (A_flat.shape[0],)
        with torch_device_fn.device(A_sym.device):
            _eig_2x2_kernel[grid](
                A_flat,
                eigenvalues,
                A_flat.shape[0],
                A_flat.stride(0),
                eigenvalues.stride(0),
                BLOCK_SIZE=1,
            )

        eigenvalues = eigenvalues.reshape(*batch_shape, 2)
        if not compute_v:
            return eigenvalues.to(out_dtype), empty_v()

        a_elem = A_flat[:, 0, 0]
        d_vec = A_flat[:, 0, 1]
        ev1 = eigenvalues.reshape(-1, 2)[:, 0]
        ev2 = eigenvalues.reshape(-1, 2)[:, 1]

        v1 = torch.stack([d_vec, ev1 - a_elem], dim=1)
        v2 = torch.stack([d_vec, ev2 - a_elem], dim=1)

        small_d = torch.abs(d_vec) < 1e-10
        v1[small_d, 0] = 1.0
        v1[small_d, 1] = 0.0
        v2[small_d, 0] = 0.0
        v2[small_d, 1] = 1.0

        v1 = v1 / v1.norm(dim=1, keepdim=True)
        v2 = v2 / v2.norm(dim=1, keepdim=True)

        eigenvectors = torch.zeros_like(A_flat)
        eigenvectors[:, 0, 0] = v1[:, 0]
        eigenvectors[:, 0, 1] = v2[:, 0]
        eigenvectors[:, 1, 0] = v1[:, 1]
        eigenvectors[:, 1, 1] = v2[:, 1]

        eigenvectors = eigenvectors.reshape(*batch_shape, 2, 2)
    else:
        # General case: Jacobi (real) or real embedding (complex). Both operate
        # on a flattened (batch, n, n) layout and reshape back at the end.
        A_flat = A_sym.reshape(-1, n, n)
        if is_complex:
            W, V = _jacobi_eigh_complex(A_flat, n, compute_v=compute_v)
        else:
            W, V = _jacobi_eigh_real(A_flat, n, compute_v=compute_v)
        eigenvalues = W.reshape(*batch_shape, n)
        if compute_v:
            eigenvectors = V.reshape(*batch_shape, n, n)
        else:
            eigenvectors = empty_v()

    # Eigenvalues are always real; eigenvectors match the input dtype. For
    # complex input, complex64 -> float32 eigenvalues, complex128 -> float64.
    # For real input, eigenvalues/eigenvectors both return the input dtype
    # (fp16/bf16 results cast back from the fp32 computation above).
    if is_complex:
        w_dtype = torch.float32 if out_dtype == torch.complex64 else torch.float64
        eigenvalues = eigenvalues.to(w_dtype)
    else:
        eigenvalues = eigenvalues.to(out_dtype)
        if compute_v:
            eigenvectors = eigenvectors.to(out_dtype)

    return eigenvalues, eigenvectors
