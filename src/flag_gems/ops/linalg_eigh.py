                srot = tl.where(active, srot, 0.0)

                col_p = tl.sum(tl.where(cc == p, g, 0.0), axis=1)
                col_q = tl.sum(tl.where(cc == q, g, 0.0), axis=1)
                row_p = tl.sum(tl.where(rr == p, g, 0.0), axis=0)
                row_q = tl.sum(tl.where(rr == q, g, 0.0), axis=0)

