                g = tl.where(cc == q, new_col_q[:, None], g)
                g = tl.where(rr == p, new_row_p[None, :], g)
                g = tl.where(rr == q, new_row_q[None, :], g)

                new_pp = (
                    crot * crot * diag_p
                    - 2.0 * crot * srot * off
                    + srot * srot * diag_q
                )
                new_qq = (
                    srot * srot * diag_p
                    + 2.0 * crot * srot * off
                    + crot * crot * diag_q
                )
                g = tl.where((rr == p) & (cc == p), new_pp, g)
                g = tl.where((rr == q) & (cc == q), new_qq, g)
                g = tl.where(((rr == p) & (cc == q)) | ((rr == q) & (cc == p)), 0.0, g)

