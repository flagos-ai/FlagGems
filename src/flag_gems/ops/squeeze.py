def _normalize_dims(ndim: int, dims) -> list:
    """Validate a ``dims`` sequence with aten's rules and messages.

    ``aten::squeeze`` processes the entries in order: each dim is first
    range-checked (and reported exactly as the caller passed it in), then
    checked for repeats. A dim repeating later in the list is therefore
    reported before an out-of-range entry that comes after it.

    A 0-d tensor has no real axis, yet aten still accepts both ``0`` and ``-1``
    for it (both denote the sole, degenerate axis), so the accepted range is
    widened to at least one axis.
    """
    max_dim = max(ndim, 1)
    normalized = []
    seen = set()
    for dim in dims:
        if not isinstance(dim, int):
            raise TypeError(
                f"squeeze(): 'dim' must be an int or a list of ints, but got "
                f"{type(dim).__name__}"
            )
        if dim < -max_dim or dim >= max_dim:
            raise IndexError(
                f"Dimension out of range (expected to be in range of "
                f"[-{max_dim}, {max_dim - 1}], but got {dim})"
            )
        wrapped = dim % max_dim
        if wrapped in seen:
            raise RuntimeError(
                f"dim {wrapped} appears multiple times in the list of dims"
            )
        seen.add(wrapped)
        normalized.append(wrapped)
    return normalized


