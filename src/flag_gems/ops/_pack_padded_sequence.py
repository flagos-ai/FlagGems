    # It is returned on CPU to match the aten contract.
    steps = torch.arange(max_len, dtype=torch.int64).unsqueeze(1)
    active = lengths_cpu.unsqueeze(0) > steps
    batch_sizes = active.sum(dim=1)

    data = torch.empty(total_len, *feat_shape, dtype=input.dtype, device=input.device)

    if total_len > 0 and feat_size > 0:
        # Packed rows are ordered time-step-major: the time index is a
        # run-length expansion of range(max_len) over batch_sizes, and within
        # each time-step run the batch index restarts at 0. Subtracting the
        # first packed row of each run from the row id therefore yields the
        # batch index, so both indices come from one arange and one cumsum.
        step_ids = torch.arange(max_len, dtype=torch.int64)
        time_index = torch.repeat_interleave(step_ids, batch_sizes)
        run_starts = torch.repeat_interleave(
            torch.cumsum(batch_sizes, dim=0) - batch_sizes, batch_sizes
        )
        batch_index = torch.arange(total_len, dtype=torch.int64) - run_starts

