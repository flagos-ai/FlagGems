def _coo_addmm_accumulate_kernel(
    indices,
    values,
    rhs,
    acc,
    alpha,
    nnz,
    M,
    N,
    K,
    stride_ix_dim,
    stride_ix_entry,
    stride_val,
    stride_rhs_k,
    stride_rhs_n,
    IS_FP64: tl.constexpr,
    BLOCK_E: tl.constexpr,
    BLOCK_N: tl.constexpr,
):
    e = tl.program_id(0).to(tl.int64) * BLOCK_E + tl.arange(0, BLOCK_E)
    n = tl.program_id(1).to(tl.int64) * BLOCK_N + tl.arange(0, BLOCK_N)
    row = tl.load(indices + e * stride_ix_entry, e < nnz, 0)
    col = tl.load(indices + stride_ix_dim + e * stride_ix_entry, e < nnz, 0)
    valid = (e < nnz) & (row >= 0) & (row < M) & (col >= 0) & (col < K)
    mask = valid[:, None] & (n[None, :] < N)
    if IS_FP64:
        alpha = alpha.to(tl.int64).to(tl.float64, bitcast=True)
    acc_dtype: tl.constexpr = tl.float64 if IS_FP64 else tl.float32
    v = tl.load(values + e * stride_val, valid, 0).to(acc_dtype)
    b = tl.load(
        rhs + col[:, None] * stride_rhs_k + n[None, :] * stride_rhs_n, mask, 0
    ).to(acc_dtype)
    tl.atomic_add(
        acc + row[:, None] * N + n[None, :],
        (alpha * v)[:, None] * b,
        mask,
        sem="relaxed",
    )


