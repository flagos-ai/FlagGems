def _to_csr(mat1):
    # NOTE (review P2): the COO/CSC/BSR/BSC branch converts on the hot path
    # (a torch compute op). aten's _sparse_addmm also supports those layouts,
    # so the conversion mirrors the native behavior; a dedicated Triton
    # conversion kernel would be needed to avoid it.
    if mat1.layout == torch.sparse_csr:
        return mat1
    if mat1.layout in (
        torch.sparse_coo,
        torch.sparse_csc,
        torch.sparse_bsr,
        torch.sparse_bsc,
    ):
        return mat1.to_sparse_csr()
    raise RuntimeError(
        f"_sparse_addmm: Expected mat1 to have a sparse layout, "
        f"but got {mat1.layout}"
    )


def _bias_strides(self, M, N):
    """Return (stride_m, stride_n) implementing addmm's bias broadcasting."""
    if self.numel() == 1:
        return 0, 0
    if self.dim() == 1 and self.shape[0] == N:
        return 0, self.stride(0)
    if self.shape != (M, N):
        self = self.broadcast_to((M, N))
    return self.stride(0), self.stride(1)


def _coo_addmm(bias, lhs, rhs, out, beta, alpha):
    M, K = lhs.shape
    N = rhs.shape[1]
    shape = (M, N)
    if not broadcastable_to(bias.shape, shape):
        raise RuntimeError(
            f"addmm: bias shape {bias.shape} cannot broadcast to {shape}"
        )
    if (
        bias.device != lhs.device
        or rhs.device != lhs.device
        or (out is not None and out.device != lhs.device)
    ):
        raise RuntimeError("addmm: expected all tensors to be on the same device")
    if out is not None and out.dtype != rhs.dtype:
        raise RuntimeError(f"addmm: expected out dtype {rhs.dtype}, got {out.dtype}")

    nnz = lhs._nnz()
    alpha, beta = float(alpha), float(beta)
    has_product = bool(M and N and nnz and alpha != 0)
    # Debug mode queries global settings and performs no tensor computation.
    deterministic = torch.get_deterministic_debug_mode()  # allow-torch-compute
    if has_product and deterministic:
        msg = "COO addmm on FlagOS uses atomic accumulation and is not deterministic"
        if deterministic == 1:
            warnings.warn(msg, UserWarning, stacklevel=2)
        else:
            raise RuntimeError(msg)

    if out is None:
        out = torch.empty(shape, device=rhs.device, dtype=rhs.dtype)
    elif out.shape != shape:
        out.resize_(shape)
    if not M or not N:
        return out
    if torch._debug_has_internal_overlap(out) == 1:
        raise RuntimeError("addmm: output has internal overlap")

    # Native COO addmm scales the bias even for beta=0 when there are no entries.
    # Otherwise beta=0 must not read bias (including its NaNs/Infs).
    has_bias = beta != 0 or nnz == 0
    bias_strides = (
        broadcasted_stride(bias.shape, bias.stride(), shape) if has_bias else (0, 0)
    )
    is_fp64 = rhs.dtype == torch.float64
    if is_fp64:
        # Triton's runtime Python float arguments are fp32; pass fp64 as bits.
        alpha, beta = (
            struct.unpack("=q", struct.pack("=d", x))[0] for x in (alpha, beta)
        )

    with torch_device_fn.device(rhs.device):
        acc = out
        if has_product:
            # Accumulate every stored COO entry, including duplicates. Scratch
            # is output-sized, independent of the sparse matrix's key space.
            indices, values = lhs._indices(), lhs._values()
            acc = torch.zeros(
                shape,
                dtype=torch.float64 if is_fp64 else torch.float32,
                device=rhs.device,
            )
            _coo_addmm_accumulate_kernel[(triton.cdiv(nnz, 4), triton.cdiv(N, 64))](
                indices,
                values,
                rhs,
                acc,
                alpha,
                nnz,
                M,
                N,
                K,
                *indices.stride(),
                values.stride(0),
                *rhs.stride(),
                IS_FP64=is_fp64,
                BLOCK_E=4,
                BLOCK_N=64,
            )
        _coo_addmm_write_kernel[(triton.cdiv(M * N, 256),)](
            acc,
            bias,
            out,
            beta,
            M,
            N,
            *bias_strides,
            *out.stride(),
            HAS_PRODUCT=has_product,
            HAS_BIAS=has_bias,
            IS_FP64=is_fp64,
            BLOCK=256,
        )
    return out


def _sparse_addmm_impl(self, mat1, mat2, *, beta=1.0, alpha=1.0, out=None):
    if self.layout != torch.strided:
        raise RuntimeError(
            f"_sparse_addmm: Expected self to have strided layout, "
            f"but got {self.layout}"
        )
    # Dense mat1 falls back to the general FlagGems addmm path, exactly like
    # aten (the Triton kernel only covers the sparse x strided product). The
    # native torch.addmm is deliberately not used: production operator code
    # must not call torch compute APIs.
    if mat1.layout == torch.strided:
        M, N = mat1.shape[0], mat2.shape[1]
        if out is None:
            return addmm(self, mat1, mat2, beta=beta, alpha=alpha)
        if out.shape != (M, N):
            # Native resize_out semantics: reuse the caller's storage and
            # write the (M, N) result in place.
            out.set_(out.untyped_storage(), 0, (M, N))
        return addmm_out(self, mat1, mat2, beta=beta, alpha=alpha, out=out)
    if mat2.layout != torch.strided:
        raise RuntimeError(
            f"_sparse_addmm: Expected mat2 to have strided layout, "
            f"but got {mat2.layout}"
        )
    if out is not None and out.layout != torch.strided:
        raise RuntimeError(
            f"_sparse_addmm: Expected out to have strided layout, "
            f"but got {out.layout}"
        )

    if mat1.dim() != 2:
        raise RuntimeError(
            f"_sparse_addmm: Expected mat1 to be a 2-D matrix, "
            f"but got {mat1.dim()}-D tensor"
        )
    if mat2.dim() != 2:
        raise RuntimeError(
            f"_sparse_addmm: Expected mat2 to be a 2-D matrix, "
            f"but got {mat2.dim()}-D tensor"
        )
    if mat1.dense_dim() != 0:
        raise RuntimeError("_sparse_addmm: Expected non-hybrid mat1 tensor")

    if mat1.dtype not in _SPARSE_ADDMM_DTYPES:
        raise RuntimeError(
            f"_sparse_addmm: Expected mat1 to be floating-point, "
            f"but got {mat1.dtype}"
        )
    if mat1.dtype != self.dtype or mat1.dtype != mat2.dtype:
        raise RuntimeError(
            f"_sparse_addmm: Expected all inputs to have the same dtype, "
            f"but got self={self.dtype}, mat1={mat1.dtype}, mat2={mat2.dtype}"
        )

    M, K = mat1.shape
    if mat2.shape[0] != K:
        raise RuntimeError("_sparse_addmm: mat1 and mat2 shapes cannot be multiplied")
    if mat1.layout == torch.sparse_coo and mat1.device.type == "flagos":
        return _coo_addmm(self, mat1, mat2, out, beta, alpha)
    N = mat2.shape[1]

    if out is None:
        out = torch.empty((M, N), dtype=mat2.dtype, device=mat2.device)
    else:
        if out.dtype != mat2.dtype:
            raise RuntimeError(
                f"_sparse_addmm: Expected out tensor to have dtype "
                f"{mat2.dtype}, but got {out.dtype} instead"
            )
        if out.shape != (M, N):
            # Native resize_out semantics: reuse the caller's storage and
            # write the (M, N) result in place.
            out.set_(out.untyped_storage(), 0, (M, N))
            out.zero_()

    if M == 0 or N == 0:
        return out

    csr = _to_csr(mat1)
    crow = csr.crow_indices()
    col = csr.col_indices()
    val = csr.values()
    nnz = val.numel()

    has_sparse = bool(alpha != 0.0 and K != 0 and nnz != 0)
    has_bias = bool(beta != 0.0)

    if not has_sparse and not has_bias:
        out.zero_()
        return out

    stride_self_m, stride_self_n = _bias_strides(self, M, N)
    if not has_bias:
        stride_self_m, stride_self_n = 0, 0

    block_n = min(triton.next_power_of_2(N), 256)
    grid = (M, triton.cdiv(N, block_n))
    with torch_device_fn.device(mat2.device):
        _sparse_addmm_kernel[grid](
            crow,
            col,
            val,
            mat2,
            self,
            out,
            alpha,
            beta,
            M,
            N,
            mat2.stride(0),
            mat2.stride(1),
            stride_self_m,
            stride_self_n,
            out.stride(0),
            out.stride(1),
            HAS_SPARSE=has_sparse,
            HAS_BIAS=has_bias,
            IS_FP64=mat2.dtype == torch.float64,
            BLOCK_N=block_n,
            num_warps=4,
        )
    return out


