def _sparse_addmm_kernel(
    crow_ptr,
    col_ptr,
    val_ptr,
    mat2_ptr,
    self_ptr,
    out_ptr,
    alpha,
    beta,
    M,
    N,
    stride_mat2_k,
    stride_mat2_n,
    stride_self_m,
    stride_self_n,
    stride_out_m,
    stride_out_n,
    HAS_SPARSE: tl.constexpr,
    HAS_BIAS: tl.constexpr,
    IS_FP64: tl.constexpr,
    BLOCK_N: tl.constexpr,
):
    """One program per (row, column block) of the dense output.

    Walks the CSR row ``[crow[row], crow[row + 1])`` and accumulates
    ``val[e] * mat2[col[e], :]`` in fp32/fp64, then applies the addmm
    epilogue ``alpha * acc + beta * self``.
    """
    row = ext.program_id(0)
    rn = ext.program_id(1) * BLOCK_N + tl.arange(0, BLOCK_N)
    rmask = rn < N
    row64 = row.to(tl.int64)
    col_off = (rn * stride_mat2_n).to(tl.int64)

    acc_dtype = tl.float64 if IS_FP64 else tl.float32
    acc = tl.zeros((BLOCK_N,), dtype=acc_dtype)

    if HAS_SPARSE:
        start = tl.load(crow_ptr + row64).to(tl.int64)
        end = tl.load(crow_ptr + row64 + 1).to(tl.int64)
        for e in range(start, end):
            c = tl.load(col_ptr + e).to(tl.int64)
            v = tl.load(val_ptr + e).to(acc_dtype)
            b = tl.load(
                mat2_ptr + c * stride_mat2_k + col_off,
                mask=rmask,
                other=0.0,
            ).to(acc_dtype)
            acc += b * v
        if alpha != 1.0:
            acc *= alpha

    if HAS_BIAS:
        bias = tl.load(
            self_ptr + row64 * stride_self_m + (rn * stride_self_n).to(tl.int64),
            mask=rmask,
            other=0.0,
        ).to(acc_dtype)
        if beta != 1.0:
            bias *= beta
        acc += bias

    cos = (row64 * stride_out_m + (rn * stride_out_n).to(tl.int64)).to(tl.int64)
    tl.store(out_ptr + cos, acc.to(out_ptr.dtype.element_ty), mask=rmask)


