def _bias_strides(self, M, N):
    """Return (stride_m, stride_n) implementing addmm's bias broadcasting."""
    if self.numel() == 1:
        return 0, 0
    if self.dim() == 1 and self.shape[0] == N:
        return 0, self.stride(0)
    if self.shape != (M, N):
        self = self.broadcast_to((M, N))
    return self.stride(0), self.stride(1)


