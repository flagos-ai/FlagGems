def foreach_pow_backward_kernel(
    meta_ptr,
    exp_ptr,
    exp_value: tl.float64,
    log_base: tl.float64,
    NT: tl.constexpr,
    DT: tl.constexpr,
    IS64: tl.constexpr,
    MODE: tl.constexpr,  # 0 = .List, 1 = .ScalarList, 2 = .ScalarAndTensor
    SCALAR_BY_VALUE: tl.constexpr,
    BLOCK: tl.constexpr,
):
    """One launch per ``(device, dtype)`` group.

    Metadata layout, all int64, ``NT`` entries per run::

        MODE == 0 (.List):
            [0,     NT)   grad_output pointers
            [NT,  2*NT)   self pointers
            [2*NT,3*NT)   exponent pointers
            [3*NT,4*NT)   grad_self pointers
            [4*NT,5*NT)   grad_exponent pointers
            [5*NT,6*NT)   element counts
            [6*NT,7*NT)   forward result pointers
        MODE in (1, 2):
            [0,     NT)   grad_output pointers
            [NT,  2*NT)   self pointers (base for MODE 2, self for MODE 1)
            [2*NT,3*NT)   result pointers (forward output)
            [3*NT,4*NT)   grad pointers
            [4*NT,5*NT)   element counts

    ``MODE 1`` takes the per-tensor exponent from ``exp_ptr`` (fp64) or the
    shared ``exp_value`` argument; ``MODE 2`` uses ``log_base`` directly.
    """
    t = tl.program_id(1)
    offset = tl.program_id(0) * BLOCK

    idx = offset + tl.arange(0, BLOCK)

    if MODE == 0:
        grad_raw = tl.load(meta_ptr + t)
        self_raw = tl.load(meta_ptr + NT + t)
        exp_raw = tl.load(meta_ptr + 2 * NT + t)
        out_self_raw = tl.load(meta_ptr + 3 * NT + t)
        out_exp_raw = tl.load(meta_ptr + 4 * NT + t)
        n_elements = tl.load(meta_ptr + 5 * NT + t)
        result_raw = tl.load(meta_ptr + 6 * NT + t)
        mask = idx < n_elements
        grad_ptr = grad_raw.to(tl.pointer_type(DT))
        self_ptr = self_raw.to(tl.pointer_type(DT))
        exp_dt_ptr = exp_raw.to(tl.pointer_type(DT))
        out_self_ptr = out_self_raw.to(tl.pointer_type(DT))
        out_exp_ptr = out_exp_raw.to(tl.pointer_type(DT))
        result_ptr = result_raw.to(tl.pointer_type(DT))

        grad = tl.load(grad_ptr + idx, mask=mask, other=0.0)
        s = tl.load(self_ptr + idx, mask=mask, other=0.0)
        e = tl.load(exp_dt_ptr + idx, mask=mask, other=0.0)
        # The exponent gradient needs the forward output ``result``: the
        # autograd node reads its saved tensor, so recomputing pow in-kernel
        # could round differently -- the wrapper stages the forward output.
        result = tl.load(result_ptr + idx, mask=mask, other=0.0)

        # grad_self = where(e == 0, 0, grad * (e * s.pow(e - 1)))
        # The ``e - 1`` subtraction is a *storage-dtype* op in the ATen chain
        # (``exponent - 1`` materialises an fp16/bf16 tensor before ``pow``
        # sees it), so the decrement rounds to DT first, not inside fp32.
        if IS64:
            p = _pow_aten(s, e - 1, IS64=IS64)
        else:
            em1 = (e - 1.0).to(DT)
            p = _pow_aten(s.to(tl.float32), em1.to(tl.float32), IS64=IS64).to(DT)
        gs = grad * (e * p)
        gs = tl.where(e == 0.0, 0.0, gs)
        # grad_exponent = grad * where((s == 0) & (e >= 0), 0, result * log(s))
        if IS64:
            lg = tl.log(s)
        else:
            lg = tl.log(s.to(tl.float32)).to(DT)
        ge = grad * (result * lg)
        cond = (s == 0.0) & (e >= 0.0)
        ge = tl.where(cond, 0.0, ge)
        tl.store(out_self_ptr + idx, gs.to(DT), mask=mask)
        tl.store(out_exp_ptr + idx, ge.to(DT), mask=mask)
    else:
        grad_raw = tl.load(meta_ptr + t)
        base_raw = tl.load(meta_ptr + NT + t)
        result_raw = tl.load(meta_ptr + 2 * NT + t)
        out_raw = tl.load(meta_ptr + 3 * NT + t)
        n_elements = tl.load(meta_ptr + 4 * NT + t)
        mask = idx < n_elements
        grad_ptr = grad_raw.to(tl.pointer_type(DT))
        base_ptr = base_raw.to(tl.pointer_type(DT))
        result_ptr = result_raw.to(tl.pointer_type(DT))
        out_ptr = out_raw.to(tl.pointer_type(DT))

        grad = tl.load(grad_ptr + idx, mask=mask, other=0.0)
        s = tl.load(base_ptr + idx, mask=mask, other=0.0)
        r = tl.load(result_ptr + idx, mask=mask, other=0.0)

        if MODE == 1:
            # grad_self = 0 if e == 0 else grad * (e * s.pow(e - 1)); e is fp64.
            if SCALAR_BY_VALUE:
                ev = exp_value
            else:
                ev = tl.load(exp_ptr + t)
            p = _pow(s.to(tl.float64), ev - 1.0)
            gs = grad.to(tl.float64) * (ev * p)
            gs = tl.where(ev == 0.0, 0.0, gs)
            tl.store(out_ptr + idx, gs.to(DT), mask=mask)
        else:
            # grad_exponent = grad * (result * log(base)); right-associated.
            ge = grad * (r * log_base)
            tl.store(out_ptr + idx, ge.to(DT), mask=mask)


def _group_indices(self_list: List[torch.Tensor]):
    """Group positions by ``(device, dtype)`` of the self operand."""
    groups = {}
    for i, t in enumerate(self_list):
        groups.setdefault((t.device, t.dtype), []).append(i)
    return groups


def _stage_meta(values: List[int], device: torch.device) -> torch.Tensor:
    """Ship the int64 pointer/count buffer without a synchronous H2D.

    ``torch.tensor(..., device=cuda)`` pays a synchronising pageable copy that
    measured ~2ms -- more than the kernel itself -- while the frombuffer +
    empty + copy_ composite stays ~17us.  Layout-only host plumbing, not
    tensor compute (the allow-torch-compute pragma must ride the call line).
    """
    buf = array.array("q", values)
    host = torch.frombuffer(buf, dtype=torch.int64)  # allow-torch-compute
    meta = torch.empty(len(values), dtype=torch.int64, device=device)
    meta.copy_(host, non_blocking=True)
    return meta


def _pick_block(nt: int, max_numel: int) -> int:
    """Largest block keeping the program count within the executor bound."""
    block = _BLOCK
    for candidate in (1024, 2048, 4096, 8192, 16384):
        block = candidate
        if nt * ((max_numel + candidate - 1) // candidate) <= (1 << 18):
            break
    return block


def _launch_list_group(
    indices, self_list, exponent_list, result_list, grad_list, device, dtype
) -> Tuple[List[torch.Tensor], List[torch.Tensor]]:
    """One dual-output launch for one ``(device, dtype)`` group of ``.List``."""
    nt = len(indices)
    numels = [self_list[i].numel() for i in indices]
    max_numel = max(numels)
    grad_self_out: List[torch.Tensor] = [None] * nt
    grad_exp_out: List[torch.Tensor] = [None] * nt
    grads_run: List[int] = []
    selves_run: List[int] = []
    exps_run: List[int] = []
    out_selves_run: List[int] = []
    out_exps_run: List[int] = []
    results_run: List[int] = []
    # The staged views below must outlive the kernel launch: a
    # ``.contiguous()`` copy whose only reference dies before the launch
    # returns its buffer to the caching allocator, and the kernel then reads
    # whatever the next allocation put there (flaky garbage in the
    # exponent-gradient outputs -- only visible when the forward output
    # arrives non-contiguous, i.e. every other call).
    staged = []
    for pos, i in enumerate(indices):
        a = self_list[i].contiguous()
        b = exponent_list[i].contiguous()
        g = grad_list[i].contiguous()
        rs = result_list[i].contiguous()
        staged.extend((a, b, g, rs))
        # The kernel writes through flat pointers, so the outputs must be
        # contiguous; ``empty_like`` would preserve non-contiguous strides.
        gs = torch.empty(a.shape, dtype=a.dtype, device=a.device)
        ge = torch.empty(b.shape, dtype=b.dtype, device=b.device)
        grad_self_out[pos] = gs
        grad_exp_out[pos] = ge
        grads_run.append(g.data_ptr())
        selves_run.append(a.data_ptr())
        exps_run.append(b.data_ptr())
        out_selves_run.append(gs.data_ptr())
        out_exps_run.append(ge.data_ptr())
        results_run.append(rs.data_ptr())
    if max_numel == 0:
        return grad_self_out, grad_exp_out

    values = (
        grads_run
        + selves_run
        + exps_run
        + out_selves_run
        + out_exps_run
        + numels
        + results_run
    )
    meta = _stage_meta(values, device)

    block = _pick_block(nt, max_numel)
    # The tensor index rides grid.y (NT-sized) and the block index grid.x:
    # CUDA allows 2**31 - 1 programs on the x axis, so a single 2**30-element
    # tensor never runs out of blocks.
    grid = (triton.cdiv(max_numel, block), nt)
    is64 = dtype is torch.float64
    with torch_device_fn.device(device):
        foreach_pow_backward_kernel[grid](
            meta,
            meta,  # exp_ptr unused in .List mode
            0.0,  # exp_value unused in .List mode
            0.0,  # log_base unused in .List mode
            nt,
            tl_dtype(dtype),
            IS64=is64,
            MODE=0,
            SCALAR_BY_VALUE=False,
            BLOCK=block,
            num_warps=_NUM_WARPS,
        )
    return grad_self_out, grad_exp_out


def _launch_scalar_group(
    indices,
    self_list,
    result_list,
    grad_list,
    scalars,
    log_base,
    mode,  # 1 = .ScalarList, 2 = .ScalarAndTensor
    device,
    dtype,
) -> List[torch.Tensor]:
    """One single-output launch for one ``(device, dtype)`` group."""
    nt = len(indices)
    numels = [self_list[i].numel() for i in indices]
    max_numel = max(numels)
    grad_out: List[torch.Tensor] = [None] * nt
    grads_run: List[int] = []
    bases_run: List[int] = []
    results_run: List[int] = []
    outs_run: List[int] = []
    staged = (
        []
    )  # keep .contiguous() copies alive past the launch (see _launch_list_group)
    for pos, i in enumerate(indices):
        a = self_list[i].contiguous()
        g = grad_list[i].contiguous()
        r = result_list[i].contiguous()
        staged.extend((a, g, r))
        o = torch.empty(a.shape, dtype=a.dtype, device=a.device)
        grad_out[pos] = o
        grads_run.append(g.data_ptr())
        bases_run.append(a.data_ptr())
        results_run.append(r.data_ptr())
        outs_run.append(o.data_ptr())
    if max_numel == 0:
        return grad_out

    values = grads_run + bases_run + results_run + outs_run + numels
    meta = _stage_meta(values, device)

    common = scalars[0] if len(set(scalars)) == 1 else None
    by_value = common is not None
    if by_value:
        exp_buf = meta  # unused by the kernel; keeps the pointer slot valid
        exp_value = float(common)
    else:
        exp_buf = torch.tensor([float(v) for v in scalars], dtype=torch.float64).to(
            device, non_blocking=True
        )
        exp_value = 0.0

    block = _pick_block(nt, max_numel)
    grid = (triton.cdiv(max_numel, block), nt)
    is64 = dtype is torch.float64
    with torch_device_fn.device(device):
        foreach_pow_backward_kernel[grid](
            meta,
            exp_buf,
            exp_value,
            log_base,
            nt,
            tl_dtype(dtype),
            IS64=is64,
            MODE=mode,
            SCALAR_BY_VALUE=by_value,
            BLOCK=block,
            num_warps=_NUM_WARPS,
        )
    return grad_out


def foreach_pow_backward(
    grad_output: Sequence[torch.Tensor],
    self_: Sequence[torch.Tensor],
    exponent: Sequence[torch.Tensor],
    result: Sequence[torch.Tensor],
) -> Tuple[List[torch.Tensor], List[torch.Tensor]]:
    """Gradients of ``torch._foreach_pow(self, exponent)`` (the ``.List`` overload).

    Args:
        grad_output: Upstream gradients, one per forward output.
        self_: Bases of the forward power, one tensor per position.
        exponent: Exponents, one tensor per position.
        result: The forward outputs ``self ** exponent`` -- the exponent
            gradient reads them (the autograd node saves ``result``), so the
            kernel loads the same values instead of recomputing them.

    Returns:
        Tuple ``(grad_self, grad_exponent)``: per-position gradients with the
        shapes and dtypes of ``self_`` and ``exponent``.

    The argument order follows the derivatives.yaml entry
    (``grads[i], self[i], exponent[i]``) with the grad list first, matching
    the ``div_backward`` entry point convention.
    """
    logger.debug("GEMS _FOREACH_POW_BACKWARD")
    grad_list = list(check_tensor_list(grad_output))
    self_list = list(check_tensor_list(self_))
    exponent_list = list(check_tensor_list(exponent))
    result_list = list(check_tensor_list(result))
    if not (len(grad_list) == len(self_list) == len(exponent_list) == len(result_list)):
        raise RuntimeError(
            "Tensor list must have same number of elements as grad_output, "
            f"got {len(self_list)}, {len(exponent_list)}, {len(result_list)} "
            f"and {len(grad_list)}"
        )
    for t in self_list:
        if t.dtype not in _GRAD_DTYPES:
            raise RuntimeError(
                f"foreach_pow_backward: dtype {t.dtype} is not differentiable "
                "(only float16, bfloat16, float32, float64 carry a gradient "
                "through _foreach_pow)"
            )
    for i, (a, b, g) in enumerate(zip(self_list, exponent_list, grad_list)):
        if b.dtype != a.dtype or g.dtype != a.dtype:
            raise RuntimeError(
                f"foreach_pow_backward: expected self, exponent and grad_output "
                f"to share a dtype at position {i}, got {a.dtype}, {b.dtype}, "
                f"{g.dtype}"
            )
        if g.shape != b.shape:
            raise RuntimeError(
                f"grad_output[{i}] shape {tuple(g.shape)} does not match the "
                f"exponent shape {tuple(b.shape)}"
            )
        if b.shape != a.shape:
            raise RuntimeError(
                f"exponent[{i}] shape {tuple(b.shape)} does not match the "
                f"self shape {tuple(a.shape)}"
            )

    grad_self_out: List[torch.Tensor] = [None] * len(self_list)
    grad_exp_out: List[torch.Tensor] = [None] * len(exponent_list)
    for (device, dtype), indices in _group_indices(self_list).items():
        gs, ge = _launch_list_group(
            indices, self_list, exponent_list, result_list, grad_list, device, dtype
        )
        for pos, i in enumerate(indices):
            grad_self_out[i] = gs[pos]
            grad_exp_out[i] = ge[pos]
    return grad_self_out, grad_exp_out


def foreach_pow_scalar_list_backward(
    grad_output: Sequence[torch.Tensor],
    self_: Sequence[torch.Tensor],
    exponents: Sequence[float],
) -> List[torch.Tensor]:
    """Gradient of ``torch._foreach_pow(self, exponents)`` (``.ScalarList``).

    The exponent is a Python scalar per position and carries no gradient, so
    one gradient list out.  Scalars stay at full double precision: ``0.3``
    keeps 0.3 inside ``pow``/``mul`` (ATen's ``exponent.toDouble()``), unlike
    the tensor dtype rounding ``_foreach_maximum`` applies to its scalar.
    """
    logger.debug("GEMS _FOREACH_POW_SCALAR_LIST_BACKWARD")
    grad_list = list(check_tensor_list(grad_output))
    self_list = list(check_tensor_list(self_))
    if len(grad_list) != len(self_list):
        raise RuntimeError(
            "Tensor list must have same number of elements as grad_output, "
            f"got {len(self_list)} and {len(grad_list)}"
        )
    if len(exponents) != len(self_list):
        raise RuntimeError(
            "Tensor list must have same number of elements as scalar list, "
            f"got {len(self_list)} and {len(exponents)}"
        )
    for t in self_list:
        if t.dtype not in _GRAD_DTYPES:
            raise RuntimeError(
                f"foreach_pow_scalar_list_backward: dtype {t.dtype} is not "
                "differentiable (only float16, bfloat16, float32, float64 "
                "carry a gradient through _foreach_pow)"
            )
    scalars = [float(v) for v in exponents]

    grad_self_out: List[torch.Tensor] = [None] * len(self_list)
    for (device, dtype), indices in _group_indices(self_list).items():
        # MODE 1 ignores the result pointers, but the shared layout requires
        # one; the self tensor doubles as the placeholder.
        out = _launch_scalar_group(
            indices,
            self_list,
            self_list,
            grad_list,
            [scalars[i] for i in indices],
            0.0,
            1,
            device,
            dtype,
        )
        for pos, i in enumerate(indices):
            grad_self_out[i] = out[pos]
    return grad_self_out


def foreach_pow_scalar_and_tensor_backward(
    grad_output: Sequence[torch.Tensor],
    result: Sequence[torch.Tensor],
    exponent: Sequence[torch.Tensor],
    base: float,
) -> List[torch.Tensor]:
    """Gradient of ``torch._foreach_pow(base, exponent)`` (``.ScalarAndTensor``).

    ``grad_exponent[i] = grad[i] * (result[i] * log(base))`` -- the
    right-associated product ATen's ``grad_lambda`` computes.  ``base`` is a
    Python scalar and carries no gradient, so one gradient list out.
    """
    logger.debug("GEMS _FOREACH_POW_SCALAR_AND_TENSOR_BACKWARD")
    grad_list = list(check_tensor_list(grad_output))
    result_list = list(check_tensor_list(result))
    exponent_list = list(check_tensor_list(exponent))
    if not (len(grad_list) == len(result_list) == len(exponent_list)):
        raise RuntimeError(
            "Tensor list must have same number of elements as grad_output, "
            f"got {len(exponent_list)}, {len(result_list)} and {len(grad_list)}"
        )
    for t in exponent_list:
        if t.dtype not in _GRAD_DTYPES:
            raise RuntimeError(
                f"foreach_pow_scalar_and_tensor_backward: dtype {t.dtype} is "
                "not differentiable (only float16, bfloat16, float32, float64 "
                "carry a gradient through _foreach_pow)"
            )
    for i, (r, e, g) in enumerate(zip(result_list, exponent_list, grad_list)):
        if r.dtype != e.dtype or g.dtype != e.dtype:
            raise RuntimeError(
                f"foreach_pow_scalar_and_tensor_backward: expected exponent, "
                f"result and grad_output to share a dtype at position {i}, "
                f"got {e.dtype}, {r.dtype}, {g.dtype}"
            )
        if g.shape != e.shape or r.shape != e.shape:
            raise RuntimeError(
                f"exponent[{i}] shape {tuple(e.shape)} must match result "
                f"{tuple(r.shape)} and grad_output {tuple(g.shape)}"
            )

    grad_exp_out: List[torch.Tensor] = [None] * len(exponent_list)
    for (device, dtype), indices in _group_indices(exponent_list).items():
        out = _launch_scalar_group(
            indices,
            exponent_list,
            result_list,
            grad_list,
            [base] * len(indices),
            math.log(float(base)),
            2,
            device,
            dtype,
        )
        for pos, i in enumerate(indices):
            grad_exp_out[i] = out[pos]
    return grad_exp_out


class ForeachPowFunction(torch.autograd.Function):
    """``_foreach_pow.List`` forward paired with the Triton backward above.

    ``aten::_foreach_pow.List`` drives its own ``ForeachPowBackward0`` node --
    not this kernel.  Use ``ForeachPowFunction.apply(self, exponent)`` (or the
    explicit ``flag_gems.foreach_pow_backward`` entry) to run the whole chain
    in FlagGems.
    """

    @staticmethod
    def forward(self_, exponent):
        from flag_gems.ops._foreach_binary import _foreach_pow_List

        # The forward returns one output tensor per position; autograd needs
        # real Tensor nodes to hang the graph on, and a list would silently
        # drop the grad_fn -- return the tuple.
        outs = _foreach_pow_List([self_], [exponent])
        return tuple(outs)

    @staticmethod
    def setup_context(ctx, inputs, output):
        self_, exponent = inputs
        # The exponent gradient needs the forward result for
        # ``result * log(self)`` -- save it alongside the operands.
        ctx.save_for_backward(self_, exponent, output[0])

    @staticmethod
    def backward(ctx, grad_output):
        if not ctx.needs_input_grad[0] and not ctx.needs_input_grad[1]:
            return None, None
        self_, exponent, result = ctx.saved_tensors
        grad_self, grad_exponent = foreach_pow_backward(
            [grad_output], [self_], [exponent], [result]
        )
        return grad_self[0], grad_exponent[0]


class ForeachPowScalarListFunction(torch.autograd.Function):
    """``_foreach_pow.ScalarList`` forward paired with the Triton backward."""

    @staticmethod
    def forward(self_, *exponents):
        from flag_gems.ops._foreach_binary import _foreach_pow_ScalarList

        outs = _foreach_pow_ScalarList([self_], list(exponents))
        return tuple(outs)

    @staticmethod
    def setup_context(ctx, inputs, output):
        self_, exponents = inputs[0], inputs[1:]
        ctx.save_for_backward(self_)
        ctx._foreach_exponents = exponents

    @staticmethod
    def backward(ctx, grad_output):
        if not ctx.needs_input_grad[0]:
            return (None,) * (1 + len(ctx._foreach_exponents))
        self_ = ctx.saved_tensors[0]
        grad_self = foreach_pow_scalar_list_backward(
            [grad_output], [self_], list(ctx._foreach_exponents)
        )[0]
        return (grad_self,) + (None,) * len(ctx._foreach_exponents)


class ForeachPowScalarAndTensorFunction(torch.autograd.Function):
    """``_foreach_pow.ScalarAndTensor`` forward paired with the Triton backward."""

    @staticmethod
    def forward(base, exponent):
        from flag_gems.ops._foreach_binary import _foreach_pow_ScalarAndTensor

        outs = _foreach_pow_ScalarAndTensor(base, [exponent])
        return tuple(outs)

    @staticmethod
    def setup_context(ctx, inputs, output):
        base, exponent = inputs
        # The kernel needs the forward result for ``result * log(base)``.
        ctx.save_for_backward(exponent, output[0])
        ctx._foreach_base = base

    @staticmethod
    def backward(ctx, grad_output):
        if not ctx.needs_input_grad[1]:
            return None, None
        exponent, result = ctx.saved_tensors
        grad_exponent = foreach_pow_scalar_and_tensor_backward(
            [grad_output], [result], [exponent], ctx._foreach_base
        )[0]
        return None, grad_exponent


