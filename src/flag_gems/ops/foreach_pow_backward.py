@triton.jit
def _pow_aten(s, x, IS64: tl.constexpr):
    """``pow_`` as ATen's CUDA device function computes it.

    fp64 is the CUDA ``pow`` (already matching libdevice); fp32 goes through
    the nvcc powf instruction sequence above so fp16/bf16 chains inherit
    bitwise-identical fp32 intermediates.  The asm body computes
    ``exp2(x * log2(|s|))``, so the negative-base cases powf documents get an
    explicit guard: NaN for a negative base with a finite non-integer
    exponent, ``(-1)^k * powf(|s|, x)`` for a negative base with an integral
    exponent (``|s|`` covers +-0 and the overflow lanes, matching the
    documented +-inf / +-0 table).
    """
    if IS64:
        return _pow(s, x)
    else:
        p = tl.inline_asm_elementwise(
            _POWF_ASM,
            "=f,f,f",
            [s, x],
            dtype=tl.float32,
            is_pure=True,
            pack=1,
        )
        # The asm body is ``exp2(x * log2(|s|))``: correct bitwise on
        # positive-finite bases, but the special cases powf documents need
        # explicit lanes.
        #   finite s < 0: NaN for a fractional x, else powf(|s|, x)
        #   s == +-0:     1 for x == 0, +-0 for x > 0 (sign only for an odd
        #                 integer x), +-inf for x < 0 (sign only odd integer)
        #   |s| == inf:   1 for x == 0, inf for x > 0, 0 for x < 0
        #   s is NaN or x is NaN: NaN (x == 0 with a NaN base still gives 1)
        neg = s < 0.0
        integral = x == tl.math.floor(x)
        s_nan = s != s
        x_nan = x != x
        x_zero = x == 0.0
        x_pos = x > 0.0
        odd = integral & (tl.math.floor(x * 0.5) * 2.0 != x)
        abs_inf = tl.abs(s) == float("inf")
        zero = (s == 0.0) | ((s == 0.0) & True)  # covers -0 via == 0
        one = x_zero | (tl.abs(s) == 1.0) & ~x_nan
        sign = tl.where(odd, tl.where(s < 0.0, -1.0, 1.0), 1.0)
        base_ok = p * 1.0
        pos_result = tl.where(x_zero, 1.0, base_ok)
        # zero base
        zero_result = tl.where(
            x_pos, sign * 0.0, tl.where(x_zero, 1.0, sign * float("inf"))
        )
        zero_result = tl.where(
            zero & (s < 0.0) & ~odd & (x < 0.0), float("inf"), zero_result
        )
        # infinite base
        inf_result = tl.where(
            x_zero,
            1.0,
            tl.where(x_pos, float("inf"), 0.0),
        )
        # negative finite base: NaN on fractional x, else powf(|s|, x)
        neg_result = tl.where(~integral, float("nan"), p)
        result = tl.where(zero, zero_result, pos_result)
        result = tl.where(abs_inf, inf_result, result)
        result = tl.where(neg & ~zero & ~abs_inf, neg_result, result)
        result = tl.where(one & ~zero & ~abs_inf & (tl.abs(s) == 1.0), 1.0, result)
        result = tl.where(s_nan | (x_nan & ~x_zero), float("nan"), result)
        return result


