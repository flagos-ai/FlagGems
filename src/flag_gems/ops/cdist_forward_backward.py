def _cdist_bwd_p2(
    GRAD,
    XK,
    XR,
    C,
    OUT,
    K,
    R,
    D,
    sgb,
    sgk,
    sgr,
    sxkb,
    sxkk,
    sxkd,
    sxrb,
    sxrr,
    sxrd,
    scb,
    sck,
    scr,
    sob,
    sok,
    sod,
    BM: tl.constexpr,
    BN: tl.constexpr,
    BD: tl.constexpr,
):
    """GEMM-form p==2 backward (hardware reduction, no broadcast/reduce).

    G[k, r] = grad / cdist (cdist == 0 lanes contribute zero):
      grad_x1[b,m,d] = s1[m]*x1[m,d] - sum_n G[m,n]*x2[n,d]
      grad_x2[b,n,d] = s2[n]*x2[n,d] - sum_m G[m,n]*x1[m,d]
    The second gradient uses diff=(x2-x1); the host swaps operands so both
    launches share the same s*xk - G@xr form with rows = kept index k.
    """
    pid_k = tl.program_id(0)
    pid_d = tl.program_id(1)
    pid_b = tl.program_id(2)

    rk = pid_k * BM + tl.arange(0, BM)
    rd = pid_d * BD + tl.arange(0, BD)
    kmask = rk < K
    dmask = rd < D

    xk = tl.load(
        XK + pid_b * sxkb + rk[:, None] * sxkk + rd[None, :] * sxkd,
        mask=kmask[:, None] & dmask[None, :],
        other=0.0,
    ).to(
        tl.float32
    )  # [BM, BD]

    acc = tl.zeros((BM, BD), dtype=tl.float32)
    s = tl.zeros((BM,), dtype=tl.float32)

    for r0 in range(0, R, BN):
        rn = r0 + tl.arange(0, BN)
        rmask = rn < R
        g = tl.load(
            GRAD + pid_b * sgb + rk[:, None] * sgk + rn[None, :] * sgr,
            mask=kmask[:, None] & rmask[None, :],
            other=0.0,
        ).to(
            tl.float32
        )  # [BM, BN]
        c = tl.load(
            C + pid_b * scb + rk[:, None] * sck + rn[None, :] * scr,
            mask=kmask[:, None] & rmask[None, :],
            other=1.0,
        ).to(
            tl.float32
        )  # [BM, BN]
        c = tl.where(c == 0.0, 1.0, c)
        G = g / c
        xr = tl.load(
            XR + pid_b * sxrb + rn[:, None] * sxrr + rd[None, :] * sxrd,
            mask=rmask[:, None] & dmask[None, :],
            other=0.0,
        ).to(
            tl.float32
        )  # [BN, BD]
        acc = tl.dot(G, xr, acc, input_precision="ieee")
        s += tl.sum(G, axis=1)

    res = s[:, None] * xk - acc

    tl.store(
        OUT + pid_b * sob + rk[:, None] * sok + rd[None, :] * sod,
        res.to(OUT.dtype.element_ty),
        mask=kmask[:, None] & dmask[None, :],
    )


def _p_mode(pf):
    if pf == 2.0:
        return 1
    if pf == 1.0:
        return 2
    if pf == 0.0:
        return 3
    if math.isinf(pf):
        return 4
    return 0


def cdist_forward_backward(grad, x1, x2, p, cdist):
    """Gradients of the p-norm pairwise distance (cdist) w.r.t. both inputs.

    Computes ``(grad_x1, grad_x2)`` matching
    ``torch.ops.aten._cdist_backward(grad, x1, x2, p, cdist)`` and
    ``torch.ops.aten._cdist_backward(grad^T, x2, x1, p, cdist^T)``.

    Args:
        grad: Upstream gradient of shape (..., n1, n2).
        x1: Left point set of shape (..., n1, dim).
        x2: Right point set of shape (..., n2, dim).
        p: p value for the p-norm distance (non-negative).
        cdist: Forward distances of shape (..., n1, n2), consistent with x1/x2.

    Returns:
        (grad_x1, grad_x2): gradients with the shapes of x1 and x2.
    """
    logger.debug("GEMS CDIST_FORWARD_BACKWARD")

    assert x1.device == x2.device == grad.device == cdist.device
    assert x1.shape[0] == x2.shape[0] == grad.shape[0] == cdist.shape[0], (
        "cdist_forward_backward requires equal batch sizes; use ATen for "
        "broadcast batch layouts"
    )
    assert x1.shape[2] == x2.shape[2], "feature dim must match"
    assert x1.dtype in (
        torch.float16,
        torch.bfloat16,
        torch.float32,
    ), f"Unsupported dtype: {x1.dtype}"
    assert p >= 0.0, "cdist only supports non-negative p values"

    B, M, D = x1.shape
    N = x2.shape[1]

    pf = float(p)
    pm = _p_mode(pf)

    if pm == 4:
        bd = triton.next_power_of_2(D)
        grid_d = 1
    else:
        bd = _BD if D >= _BD else triton.next_power_of_2(D)
        grid_d = triton.cdiv(D, bd)

    out1 = torch.empty_like(x1)
    out2 = torch.empty_like(x2)

    bm = _BM
    bn = _BN
    plt1 = 0.0 < pf < 1.0
    pm1 = pf - 1.0

    with torch_device_fn.device(x1.device):
        if pm == 1:
            # p == 2: GEMM-form kernel (hardware reduction, no broadcast/reduce).
            # Both launches use the same s*xk - G@xr form; the second swaps
            # operands so diff=(x2-x1) carries the sign.
            for out, xk_t, xr_t, swap in (
                (out1, x1, x2, False),
                (out2, x2, x1, True),
            ):
                gsb = grad.stride(0)
                if swap:
                    gsk, gsr = grad.stride(2), grad.stride(1)
                    csk, csr = cdist.stride(2), cdist.stride(1)
                else:
                    gsk, gsr = grad.stride(1), grad.stride(2)
                    csk, csr = cdist.stride(1), cdist.stride(2)
                _cdist_bwd_p2[(triton.cdiv(xk_t.shape[1], bm), grid_d, B)](
                    grad,
                    xk_t,
                    xr_t,
                    cdist,
                    out,
                    xk_t.shape[1],
                    xr_t.shape[1],
                    D,
                    gsb,
                    gsk,
                    gsr,
                    xk_t.stride(0),
                    xk_t.stride(1),
                    xk_t.stride(2),
                    xr_t.stride(0),
                    xr_t.stride(1),
                    xr_t.stride(2),
                    cdist.stride(0),
                    csk,
                    csr,
                    out.stride(0),
                    out.stride(1),
                    out.stride(2),
                    BM=bm,
                    BN=bn,
                    BD=bd,
                    num_warps=_WARPS,
                )
            return out1, out2

        # grad_x1: kept axis = M (x1 rows), reduction over N
        _cdist_bwd_kernel[(triton.cdiv(M, bm), grid_d, B)](
            grad,
            x1,
            x2,
            cdist,
            out1,
            M,
            N,
            D,
            grad.stride(0),
            grad.stride(1),
            grad.stride(2),
            x1.stride(0),
            x1.stride(1),
            x1.stride(2),
            x2.stride(0),
            x2.stride(1),
            x2.stride(2),
            cdist.stride(0),
            cdist.stride(1),
            cdist.stride(2),
            out1.stride(0),
            out1.stride(1),
            out1.stride(2),
            pm1,
            P_MODE=pm,
            NEG=0,
            P_LT1=plt1,
            BM=bm,
            BN=bn,
            BD=bd,
            num_warps=_WARPS,
        )
        # grad_x2: kept axis = N (x2 rows), reduction over M.
        # diff here is (x2 - x1) = -(x1 - x2), which already carries the
        # negation, so NEG=0.
        _cdist_bwd_kernel[(triton.cdiv(N, bm), grid_d, B)](
            grad,
            x2,
            x1,
            cdist,
            out2,
            N,
            M,
            D,
            grad.stride(0),
            grad.stride(2),
            grad.stride(1),
            x2.stride(0),
            x2.stride(1),
            x2.stride(2),
            x1.stride(0),
            x1.stride(1),
            x1.stride(2),
            cdist.stride(0),
            cdist.stride(2),
            cdist.stride(1),
            out2.stride(0),
            out2.stride(1),
            out2.stride(2),
            pm1,
            P_MODE=pm,
            NEG=0,
            P_LT1=plt1,
            BM=bm,
            BN=bn,
            BD=bd,
            num_warps=_WARPS,
        )
    return out1, out2
