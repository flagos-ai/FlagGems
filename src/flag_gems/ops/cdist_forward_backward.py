# cdist_forward_backward — Triton implementation
#
# Semantics (validated against torch.ops.aten._cdist_backward on the target):
#   diff[b,m,n,d] = x1[b,m,d] - x2[b,n,d]
#   p == 0   : grad_x1 = 0, grad_x2 = 0                     (exact)
#   p == inf : term = grad * sign(diff) * (|diff| == max_d|diff|)
#              (every argmax dim contributes; ties included)
#   0 < p < inf:
#       term = grad * sign(diff) * (|diff| / cdist) ** (p - 1)
#       grad_x1[b,m,d] =  sum_n term
#       grad_x2[b,n,d] = -sum_m term
#   p == 2 uses term = grad * diff / cdist (no transcendentals).
#   p == 1 uses term = grad * sign(diff).
