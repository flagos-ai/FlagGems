def _cdist_bwd_kernel(
    GRAD,
    XK,
    XR,
    C,
    OUT,
    K,
    R,
    D,
    sgb,
    sgk,
    sgr,
    sxkb,
    sxkk,
    sxkd,
    sxrb,
    sxrr,
    sxrd,
    scb,
    sck,
    scr,
    sob,
    sok,
    sod,
    pm1,
    P_MODE: tl.constexpr,  # 0 general, 1 p==2, 2 p==1, 3 p==0, 4 p==inf
    NEG: tl.constexpr,  # 1 -> store -acc (grad wrt x2)
    P_LT1: tl.constexpr,  # 1 -> 0 < p < 1, guard ad == 0
    BM: tl.constexpr,
    BN: tl.constexpr,
    BD: tl.constexpr,
):
    """Elementwise p-norm cdist backward for one kept-index tile.

    grad_x[k, d] = sum_r grad[k, r] * sign(diff) * (|diff| / cdist)**(p - 1)
    over the reduced axis r; the store may negate the accumulator (NEG=1) for
    the gradient that flows to the right-hand point set. Per-p specializations
    avoid transcendentals for p in {0, 1, 2, inf}; the general path folds the
    power into exp2/log2 and guards ad == 0 when 0 < p < 1.
    """
    pid_k = tl.program_id(0)
    pid_d = tl.program_id(1)
    pid_b = tl.program_id(2)

    rk = pid_k * BM + tl.arange(0, BM)
    rd = pid_d * BD + tl.arange(0, BD)
    kmask = rk < K
    dmask = rd < D

    xk = tl.load(
        XK + pid_b * sxkb + rk[:, None] * sxkk + rd[None, :] * sxkd,
        mask=kmask[:, None] & dmask[None, :],
        other=0.0,
    ).to(
        tl.float32
    )  # [BM, BD]

    acc = tl.zeros((BM, BD), dtype=tl.float32)

    if P_MODE != 3:
        for r0 in range(0, R, BN):
            rr = r0 + tl.arange(0, BN)
            rmask = rr < R
            xr = tl.load(
                XR + pid_b * sxrb + rr[:, None] * sxrr + rd[None, :] * sxrd,
                mask=rmask[:, None] & dmask[None, :],
                other=0.0,
            ).to(
                tl.float32
            )  # [BN, BD]
            g = tl.load(
                GRAD + pid_b * sgb + rk[:, None] * sgk + rr[None, :] * sgr,
                mask=kmask[:, None] & rmask[None, :],
                other=0.0,
            ).to(
                tl.float32
            )  # [BM, BN]
            c = tl.load(
                C + pid_b * scb + rk[:, None] * sck + rr[None, :] * scr,
                mask=kmask[:, None] & rmask[None, :],
                other=1.0,
            ).to(
                tl.float32
            )  # [BM, BN]

            diff = xk[:, None, :] - xr[None, :, :]  # [BM, BN, BD]
            if P_MODE == 1:
                term = g[:, :, None] * diff / c[:, :, None]
            elif P_MODE == 2:
                sg = tl.where(diff > 0.0, 1.0, 0.0) - tl.where(diff < 0.0, 1.0, 0.0)
                term = g[:, :, None] * sg
            elif P_MODE == 4:
                ad4 = tl.abs(diff)
                amax = tl.max(ad4, axis=2)[:, :, None]
                sg = tl.where(diff > 0.0, 1.0, 0.0) - tl.where(diff < 0.0, 1.0, 0.0)
                term = g[:, :, None] * sg * tl.where(ad4 == amax, 1.0, 0.0)
            else:
                ad = tl.abs(diff)
                sg = tl.where(diff > 0.0, 1.0, 0.0) - tl.where(diff < 0.0, 1.0, 0.0)
                # A zero distance makes the general term ill-conditioned
                # (0/0 or x/0 -> NaN/inf), so those lanes contribute zero.
                # ad == 0 only produces NaN when p < 1 ((0/c)^(p-1) = inf);
                # for p > 1 it folds to exp2(-inf) = 0 by itself, so the
                # extra guard is compiled out via the P_LT1 constexpr.
                c3 = c[:, :, None]
                c_zero = c3 == 0.0
                ad_safe = tl.where(c_zero, 1.0, ad)
                c_safe = tl.where(c_zero, 1.0, c3)
                y = tl.exp2(pm1 * tl.log2(ad_safe / c_safe))
                term = g[:, :, None] * sg * y
                term = tl.where(c_zero, 0.0, term)
                if P_LT1:
                    term = tl.where(ad > 0.0, term, 0.0)
                # Padded reduction lanes (rr >= R) load grad=0 but keep the
                # real xk values, so the general path can produce inf * 0
                # NaNs there; zero them before the reduction.
                term = tl.where(rmask[None, :, None], term, 0.0)
            acc += tl.sum(term, axis=1)

    if NEG:
        res = -acc
    else:
        res = acc

    tl.store(
        OUT + pid_b * sob + rk[:, None] * sok + rd[None, :] * sod,
        res.to(OUT.dtype.element_ty),
        mask=kmask[:, None] & dmask[None, :],
    )


_BM = 16
_BN = 16
_BD = 32
_WARPS = 8


