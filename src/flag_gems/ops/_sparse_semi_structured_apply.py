"""Triton implementation of ``aten::_sparse_semi_structured_apply``.

Mask semantics were reverse-engineered from the live native aten operator and
validated in Debug Jobs against every mask pattern used by the Gems pytest,
both supported dtypes, several tile shapes and all strided input/mask layouts:

    p = m % 8 , q = k % 8
    lane   = 4 * (p // 4) + 2 * (q // 4) + ((p // 2) % 2)
    bitpos = (p % 2) * 4 + (q % 4)
    bit(m, k) = (thread_masks[m // 8, k // 8, lane] >> bitpos) & 1

The native operator indexes ``thread_masks`` rows as packed ``(K/8)*8``-byte
records after the storage offset; ``thread_masks.stride(0)`` is ignored
(measured).  ``out0[m, c]`` packs the four mask-selected columns
``4*(c//2) + 0..3`` of row ``m``; ``out1[k, c]`` packs the four mask-selected
rows ``4*(c//2) + 0..3`` of column ``k``.  Both use the same
precedence-sensitive two-slot rule:

    slot0 = (b2 & b3) ? v2 : (b0 ? v0 : (b1 ? v1 : +0))
    slot1 = b3 ? v3 : (b2 ? v2 : ((b0 & b1) ? v1 : +0))

Selection is pure 16-bit data movement (bitcast to int16, integer bit tests), so
selected values stay bit-identical and unselected slots are bit-pattern +0.

Two bodies implement the same packing:

* ``_apply_kernel`` broadcasts the compact mask bytes into a full-tile bit
  tensor, which is fastest for the latency-bound tiles up to 1024x1024;
* ``_apply_kernel_compact`` keeps the bits inside the mask tile's own bytes and
  shifts out one nibble per slot group, which is fastest for the single
  wave-limited 2048x1024-sized tiles because it avoids the extra full-tile
  intermediate.
"""

