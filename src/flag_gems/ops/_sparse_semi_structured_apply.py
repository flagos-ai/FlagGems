@triton.jit
def _split_last4(x):
    """Split a trailing axis of length 4 (ordered 0,1,2,3) into four tensors."""
    x = tl.reshape(
        x,
        (x.shape[0], x.shape[1], x.shape[2], x.shape[3], x.shape[4], x.shape[5], 2, 2),
    )
    lo, hi = tl.split(x)  # r // 2 : lo -> r in {0, 2}, hi -> r in {1, 3}
    a, c = tl.split(lo)  # r = 0, r = 2
    b, d = tl.split(hi)  # r = 1, r = 3
    return a, b, c, d


@triton.jit
def _apply_kernel(
    in_ptr,
    mask_ptr,
    out0_ptr,
    out1_ptr,
    M,
    K,
    stride_im,
    stride_ik,
    BM: tl.constexpr,
    BK: tl.constexpr,
):
    """Broadcast variant: fastest for the latency-bound tiles <= 1024x1024."""
    MG: tl.constexpr = BM // 8
    KG: tl.constexpr = BK // 8
    M8 = M // 8
    K8 = K // 8

    pid_m = tl.program_id(0)
    pid_k = tl.program_id(1)

    off_m = pid_m * BM + tl.arange(0, BM)
    off_k = pid_k * BK + tl.arange(0, BK)
    m_ok = off_m < M
    k_ok = off_k < K

    # ---- input tile, read through its strides as raw 16-bit words ----------
    ptrs = in_ptr + off_m[:, None] * stride_im + off_k[None, :] * stride_ik
    t = tl.load(ptrs, mask=m_ok[:, None] & k_ok[None, :], other=0)
    t = t.to(tl.int16, bitcast=True)

    # ---- (MG, KG, 8) mask tile --------------------------------------------
    # The native operator indexes thread_masks rows as PACKED (K/8)*8-byte
    # records after the storage offset; thread_masks.stride(0) is ignored.
    B = _mask_tile(mask_ptr, pid_m, pid_k, M8, K8, MG, KG)

    # lane = 4*a + 2*d + b  (a = p//4, b = (p//2)%2, d = q//4)
    Bp = tl.permute(tl.reshape(B, (MG, KG, 2, 2, 2)), (0, 2, 4, 1, 3))
    Bexp = tl.reshape(Bp, (MG, 2, 2, 1, KG, 2, 1))

    c_ax = tl.arange(0, 2)
    r_ax = tl.arange(0, 4)
    bitpos = (
        4 * c_ax[None, None, None, :, None, None, None]
        + r_ax[None, None, None, None, None, None, :]
    )
    bit = (Bexp >> bitpos) & 1

    # tile element (mg, a, b, c, kg, d, r) is input row 8mg+4a+2b+c, col 8kg+4d+r
    t7 = tl.reshape(t, (MG, 2, 2, 2, KG, 2, 4))

    # ---- out0: pack the four (d, r) column-quads of each kg ----------------
    t4 = tl.reshape(t7, (MG, 2, 2, 2, KG, 2, 2, 2))
    b4 = tl.reshape(bit, (MG, 2, 2, 2, KG, 2, 2, 2))
    tA, tB = tl.split(t4)  # last axis r//2
    v0, v2 = tl.split(tA)  # r = 0, r = 2
    v1, v3 = tl.split(tB)  # r = 1, r = 3
    bA, bB = tl.split(b4)
    q0, q2 = tl.split(bA)
    q1, q3 = tl.split(bB)
    s0, s1 = _pack4(v0, v1, v2, v3, q0, q1, q2, q3)
    o0 = tl.reshape(tl.join(s0, s1), (BM, BK // 2))
    o0h = o0.to(out0_ptr.dtype.element_ty, bitcast=True)

    o0_cols = pid_k * (BK // 2) + tl.arange(0, BK // 2)
    st0 = out0_ptr + off_m[:, None] * (K // 2) + o0_cols[None, :]
    tl.store(st0, o0h, mask=m_ok[:, None] & (o0_cols[None, :] < K // 2))

    # ---- out1: pack the four (2b+c) row-quads of each (kg, d, r) -----------
    tp = tl.permute(t7, (4, 5, 6, 0, 1, 2, 3))  # (kg, d, r, mg, a, b, c)
    bp = tl.permute(bit, (4, 5, 6, 0, 1, 2, 3))
    tA, tB = tl.split(tp)  # last axis c
    v0, v2 = tl.split(tA)  # c = 0 -> p = 0, 2
    v1, v3 = tl.split(tB)  # c = 1 -> p = 1, 3
    bA, bB = tl.split(bp)
    q0, q2 = tl.split(bA)
    q1, q3 = tl.split(bB)
    s0, s1 = _pack4(v0, v1, v2, v3, q0, q1, q2, q3)
    o1 = tl.reshape(tl.join(s0, s1), (BK, BM // 2))
    o1h = o1.to(out1_ptr.dtype.element_ty, bitcast=True)

    o1_cols = pid_m * (BM // 2) + tl.arange(0, BM // 2)
    st1 = out1_ptr + off_k[:, None] * (M // 2) + o1_cols[None, :]
    tl.store(st1, o1h, mask=k_ok[:, None] & (o1_cols[None, :] < M // 2))


def _validate(input, thread_masks):
    if input.dtype not in _SUPPORTED_INPUT_DTYPES:
        raise RuntimeError(
            "Unsupported dtype - only `float16` and `bfloat16` are supported "
            "currently"
        )
    # native reads size(1) before its own rank check -> IndexError for rank < 2
    if input.dim() < 2:
        input.size(1)
    if input.dim() != 2:
        raise RuntimeError("expected a rank-2 input tile")
    M, K = input.size()
    if thread_masks.dtype is not _UINT8:
        raise RuntimeError("thread_masks must be uint8")
    if thread_masks.shape != (4 * ((M + 31) // 32), 8 * ((K + 63) // 64), 8):
        raise RuntimeError("Wrong threads_masks shape")
    mstride = thread_masks.stride()
    if mstride[1] != 8 or mstride[2] != 1:
        raise RuntimeError("Wrong threads_masks strides")
    if M % 32 or K % 64 or M <= 0 or K <= 0:
        raise RuntimeError("Wrong alignment shape[1]")
    istride = input.stride()
    if istride[0] != 1 and istride[0] % 8:
        raise RuntimeError("Row-major input requires stride(0) % 8 == 0")


def _sparse_semi_structured_apply(input, thread_masks):
    _validate(input, thread_masks)
    M, K = input.size()

    out0 = torch.empty((M, K // 2), dtype=input.dtype, device=input.device)
    out1 = torch.empty((K, M // 2), dtype=input.dtype, device=input.device)

    istride = input.stride()
    size = M * K
    if size > 1024 * 1024:
        # Only shapes this large exceed a single resident wave, and the
        # byte-shift body wins there (their full-tile bit intermediate is what
        # pushed them over the register limit).
        grid = (triton.cdiv(M, _LARGE_BM), triton.cdiv(K, _LARGE_BK))
        _apply_kernel_compact[grid](
            input,
            thread_masks,
            out0,
            out1,
            M,
            K,
            istride[0],
            istride[1],
            BM=_LARGE_BM,
            BK=_LARGE_BK,
            num_warps=4,
        )
    elif size <= 256 * 256:
        # The two smallest benchmark tiles are launch-bound, and a narrow
        # 16x32 tile with one 4-warp program per tile measured fastest.
        grid = (triton.cdiv(M, _SMALL_BM), triton.cdiv(K, _SMALL_BK))
        _apply_kernel[grid](
            input,
            thread_masks,
            out0,
            out1,
            M,
            K,
            istride[0],
            istride[1],
            BM=_SMALL_BM,
            BK=_SMALL_BK,
            num_warps=4,
        )
    else:
        # Latency-bound mid tiles hide better with 8 warps.
        grid = (triton.cdiv(M, _BM), triton.cdiv(K, _BK))
        _apply_kernel[grid](
            input,
            thread_masks,
            out0,
            out1,
            M,
            K,
            istride[0],
            istride[1],
            BM=_BM,
            BK=_BK,
            num_warps=8,
        )
    return out0, out1
