    pid_n = tl.program_id(1)

    offs_m = pid_m * BLOCK_M + tl.arange(0, BLOCK_M)
    offs_n = pid_n * BLOCK_N + tl.arange(0, BLOCK_N)
    m_mask = offs_m < batch_size
    n_mask = offs_n < hidden_size

    acc = tl.zeros([BLOCK_M, BLOCK_N], dtype=tl.float32)

    # --- ih = input @ W_ih^T  (reduction over input_size) ---
    for k in range(0, input_size, BLOCK_K):
        offs_k = k + tl.arange(0, BLOCK_K)
        k_mask = offs_k < input_size

        x_tile = tl.load(
            input_ptr + offs_m[:, None] * input_stride_b + offs_k[None, :],
            mask=m_mask[:, None] & k_mask[None, :],
            other=0.0,
        ).to(tl.float32)

        # W_ih is (hidden, input) row-major; load it transposed as
        # (BLOCK_K, BLOCK_N) so we can dot without an extra tl.trans copy.
        # Tile[i, j] == W_ih[n_j, k_i] == n_j * input_size + k_i.
        w_tile = tl.load(
            weight_ih_ptr + offs_n[None, :] * input_size + offs_k[:, None],
            mask=k_mask[:, None] & n_mask[None, :],
            other=0.0,
        ).to(tl.float32)

        acc += tl.dot(x_tile, w_tile)

    # --- hh = hx @ W_hh^T  (reduction over hidden_size) ---
    for k in range(0, hidden_size, BLOCK_K):
        offs_k = k + tl.arange(0, BLOCK_K)
        k_mask = offs_k < hidden_size

        h_tile = tl.load(
            hx_ptr + offs_m[:, None] * hx_stride_b + offs_k[None, :],
            mask=m_mask[:, None] & k_mask[None, :],
            other=0.0,
        ).to(tl.float32)

        # W_hh is (hidden, hidden) row-major; load transposed as (BLOCK_K, BLOCK_N).
        # Tile[i, j] == W_hh[n_j, k_i] == n_j * hidden_size + k_i.
        w_tile = tl.load(
            weight_hh_ptr + offs_n[None, :] * hidden_size + offs_k[:, None],
            mask=k_mask[:, None] & n_mask[None, :],
            other=0.0,
        ).to(tl.float32)

        acc += tl.dot(h_tile, w_tile)

    # --- biases + tanh ---
    if has_input_bias:
        b_ih = tl.load(bias_ih_ptr + offs_n, mask=n_mask, other=0.0).to(tl.float32)
        acc += b_ih[None, :]
    if has_hidden_bias:
        b_hh = tl.load(bias_hh_ptr + offs_n, mask=n_mask, other=0.0).to(tl.float32)
        acc += b_hh[None, :]

    acc = tl_extra_shim.tanh(acc)

    tl.store(
        output_ptr + offs_m[:, None] * out_stride_b + offs_n[None, :],
        acc.to(output_ptr.dtype.element_ty),
        mask=m_mask[:, None] & n_mask[None, :],
    )


