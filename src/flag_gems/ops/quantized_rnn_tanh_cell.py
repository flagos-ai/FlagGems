def _minmax_kernel(x_ptr, mn_ptr, mx_ptr, numel, BLOCK: tl.constexpr):
    """Global min/max reduction feeding ``ChooseQuantizationParams``.

    ``FindMinMax`` is a whole-tensor reduction; atomic min/max give the same
    result as the reference's per-thread scan.
    """
    pid = tl.program_id(0)
    offs = pid * BLOCK + tl.arange(0, BLOCK)
    mask = offs < numel
    values = tl.load(x_ptr + offs, mask=mask, other=0.0)
    tl.atomic_min(mn_ptr, tl.min(tl.where(mask, values, float("inf"))))
    tl.atomic_max(mx_ptr, tl.max(tl.where(mask, values, float("-inf"))))


@triton.jit
def _choose_activation_qparams(mn, mx):
    """Port of ``fbgemm::ChooseQuantizationParams`` for uint8 activations.

    Returns ``(scale, zero_point_int, zero_point_float)``. The arithmetic is
    carried out in float64 exactly like the reference, which computes the scale
    and the zero-point from ``double`` intermediates and only then narrows to
    ``float``; doing it in float32 can round the zero-point to a neighbouring
    integer when the initial value lands on a ``.5`` boundary.
    """
    mn = tl.minimum(mn, 0.0)
    mx = tl.maximum(mx, 0.0)

    scale = ((mx.to(tl.float64) - mn.to(tl.float64)) / (_QMAX - _QMIN)).to(tl.float32)
    # Avoid a zero scale / infinite reciprocal, as the reference does.
    scale = tl.where((scale == 0.0) | (1.0 / scale == float("inf")), 0.1, scale)

    # Cut off a scale that is too small, widening the [min, max] interval to
    # match the new scale.
    small = scale < _SMALL_SCALE_THRESHOLD
    widen = small & (mn != 0.0) & (mx != 0.0)
    amplifier = tl.where(widen, _SMALL_SCALE_THRESHOLD / scale, 1.0)
    mn = tl.where(widen, mn * amplifier, mn)
    mx = tl.where(widen, mx * amplifier, mx)
    mx = tl.where(small & (mn == 0.0), _SMALL_SCALE_THRESHOLD * (_QMAX - _QMIN), mx)
    mn = tl.where(small & (mx == 0.0), -_SMALL_SCALE_THRESHOLD * (_QMAX - _QMIN), mn)
    scale = tl.where(small, _SMALL_SCALE_THRESHOLD, scale)

    scale_d = scale.to(tl.float64)
    mn_d = mn.to(tl.float64)
    mx_d = mx.to(tl.float64)
    zp_from_min = _QMIN - mn_d / scale_d
    zp_from_max = _QMAX - mx_d / scale_d
    # Pick the variant that adds the smaller terms, then nudge to an integer.
    err_from_min = tl.abs(mn_d / scale_d)
    err_from_max = _QMAX + tl.abs(mx_d / scale_d)
    initial = tl.where(err_from_min < err_from_max, zp_from_min, zp_from_max)
    nudged = tl.minimum(tl.maximum(tl_extra_shim.rint(initial), _QMIN), _QMAX)
    return scale, nudged.to(tl.int32), nudged.to(tl.float32)


@triton.jit
def _quantize_activation(values, inv_scale, zero_point, valid):
    """uint8 affine quantization of the activations, FBGEMM AVX2 order.

    ``QuantizeAvx2`` computes ``fma(src, inverse_scale, zero_point)``, rounds
    with the current rounding mode (round-half-to-even) and clips to [0, 255];
    padded lanes are forced to zero after the shift so they contribute nothing
    to the GEMM.
    """
    transformed = tl.fma(values, inv_scale, zero_point)
    transformed = tl.minimum(transformed, _INT32_FLOAT_MAX)
    quantized = tl.minimum(
        tl.maximum(tl_extra_shim.rint(transformed), float(_QMIN)), float(_QMAX)
    )
    # The uint8 values are shifted by 128 so that tl.dot can use signed int8
    # operands; the shift is undone by the ``+128 * sum_k B`` term below.
    shifted = tl.where(valid, quantized - 128.0, 0.0)
    return shifted.to(tl.int8)


@triton.jit
def _quantize_weight_kernel(
    w_ptr, out_ptr, inv_scale, zero_point, numel, BLOCK: tl.constexpr
):
    """int8 quantization of a still-float weight, FBGEMM non-legacy order.

    ``fbgemm_linear_quantize_weight`` uses ``Quantize<int8_t, false>``, i.e.
    round first and add the integer zero-point afterwards.
    """
    pid = tl.program_id(0)
    offs = pid * BLOCK + tl.arange(0, BLOCK)
    mask = offs < numel
    values = tl.load(w_ptr + offs, mask=mask, other=0.0)
    values = tl.minimum(values, _INT32_FLOAT_MAX)
    quantized = tl_extra_shim.rint(values * inv_scale) + zero_point
    quantized = tl.minimum(tl.maximum(quantized, -128.0), 127.0)
    tl.store(out_ptr + offs, quantized.to(tl.int8), mask=mask)


