# FBGEMM quantizes the *activations* dynamically with a uint8 affine scheme over
# the whole input tensor (0/255 range), then runs an int8 GEMM and requantizes
# with the activation/weight scales, zero-points and column offsets. The
# constants below mirror fbgemm/src/QuantUtils.cc.
_QMIN = tl.constexpr(0)
_QMAX = tl.constexpr(255)
_SMALL_SCALE_THRESHOLD = tl.constexpr(6.1e-5)
# Largest int32 value exactly representable in float32; FBGEMM clips the scaled
# activation to this before converting to int32 so that inf/huge values do not
# wrap around (see QuantizeAvx2).
_INT32_FLOAT_MAX = tl.constexpr(2147483520.0)


@triton.jit
def _fill_minmax_kernel(out_ptr):
    """Seed the min/max buffers with the identity of the reduction."""
    tl.store(out_ptr, float("inf"))
    tl.store(out_ptr + 1, float("-inf"))


