def make_product_plan(inp, dim, keepdim):
    (shape, dtype, device) = (tuple(inp.shape), inp.dtype, inp.device)
    (dims, outer, osh, rsh, _, _) = reduction_plan(inp, dim)
    n = math.prod(rsh)
    rows = math.prod(osh)
    split = min(65535, max(1, triton.cdiv(n, 1024)))
    strides = []
    stride = 1
    for size in reversed(shape):
        strides.append(stride)
        stride *= size
    strides = tuple(reversed(strides))
    (oos, ors) = (tuple((strides[i] for i in outer)), tuple((strides[i] for i in dims)))
    grid = (rows, split, 1)

    def backward(x, grad, y, zeros):
        if not shape:
            return grad
        out = torch.empty(shape, dtype=dtype, device=device)
        if not x.numel():
            return out
        prefix = torch.empty(shape, dtype=dtype, device=device)
        gos = tuple((grad.stride(i) for i in outer)) if keepdim else tuple(grad.stride())
        constants = (n, osh, rsh, tuple((x.stride(i) for i in outer)), tuple((x.stride(i) for i in dims)), gos, oos, ors, rows, triton.next_power_of_2(rows), dim is None, 256, split)
        key = (device, dtype, grad.dtype, y.dtype, constants, x.data_ptr() & 15, grad.data_ptr() & 15, y.data_ptr() & 15, zeros.data_ptr() & 15)
        args = (x, grad, y, zeros, prefix, out, *constants)
        with torch_device_fn.device(device):
            launch = _CODE.get(key)
            if launch is None:
                compiled = _product_gradient[grid](*args, num_warps=4, enable_fp_fusion=False)
                _CODE[key] = compiled[grid]
            else:
                launch(*args)
        return out
    return backward
