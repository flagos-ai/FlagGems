def _prod_raw(inp, *, dtype=None):
    logger.debug("GEMS PROD")
    if dtype is None:
        dtype = inp.dtype

    M = inp.numel()
    block_size = triton.next_power_of_2(math.ceil(math.sqrt(M)))
    mid_size = triton.cdiv(M, block_size)
    block_mid = triton.next_power_of_2(mid_size)

    mid = torch.empty((mid_size,), dtype=dtype, device=inp.device)
    out = torch.empty([], dtype=dtype, device=inp.device)

    with torch_device_fn.device(inp.device):
        prod_kernel_mid[(mid_size, 1, 1)](inp, mid, M, block_size)
        prod_kernel_result[(1, 1, 1)](mid, out, mid_size, block_mid)
    return out

def _prod_dim_raw(inp, dim=None, keepdim=False, *, dtype=None):
    logger.debug("GEMS PROD_DIM")

    if not (-inp.ndim <= dim < inp.ndim):
        raise IndexError(
            f"Dimension out of range (expected to be in range of "
            f"[{-inp.ndim}, {inp.ndim - 1}])"
        )
    if dtype is None:
        dtype = inp.dtype

    shape = list(inp.shape)
    d = dim % inp.ndim
    N = inp.shape[d]
    M = _reduce(lambda x, y: x * y, shape[:d], 1)
    K = _reduce(lambda x, y: x * y, shape[d + 1 :], 1)
    shape[d] = 1
    out = torch.empty(shape, dtype=dtype, device=inp.device)

    if M == 0 or K == 0:
        # A spectator dimension is empty: the output is a valid empty tensor.
        if not keepdim:
            out = torch.squeeze(out, d)
        return out
    if N == 0:
        # The product over an empty dimension is the identity, 1 (unlike max/min
        # which have no identity). Fill the output rather than launching.
        out.fill_(1)
        if not keepdim:
            out = torch.squeeze(out, d)
        return out

    inp = inp.contiguous()
    with torch_device_fn.device(inp.device):
        if K == 1:
            grid = (M, 1, 1)
            prod_dim_kernel_inner[grid](out, inp, M, N)
        else:
            grid = lambda meta: (M, triton.cdiv(K, meta["TILE_K"]), 1)
            prod_dim_kernel_non_inner[grid](out, inp, M, N, K)
    if not keepdim:
        out = torch.squeeze(out, d)
    return out

class _ProdFunction(torch.autograd.Function):

    @staticmethod
    def forward(ctx, x, dim, keepdim, dtype):
        if dtype is not None and dtype != x.dtype:
            from flag_gems.ops.to import to_copy
            working = to_copy(x, dtype=dtype)
        else:
            working = x
        (y, nonzero, zeros) = reduce_values(working, dim, keepdim, product=True)
        ctx.save_for_backward(x, y, nonzero, zeros)
        (ctx.dim, ctx.keepdim) = (dim, keepdim)
        ctx.product_plan = make_product_plan(x, dim, keepdim)
        return y

    @staticmethod
    def backward(ctx, grad):
        (x, y, _, zeros) = ctx.saved_tensors
        return (ctx.product_plan(x, grad, y, zeros), None, None, None)
