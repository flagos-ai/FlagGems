def _sparse_sum_backward(grad, self, dim, out=None):
    if not getattr(self, "is_sparse", False) or self.layout != torch.sparse_coo:
        raise RuntimeError("_sparse_sum_backward: self must be a sparse COO tensor")

    shape = tuple(int(s) for s in self.shape)
    rank = len(shape)
    k = int(self.sparse_dim())

    if isinstance(dim, int):
        dims = [dim]
    else:
        dims = [int(d) for d in dim]
    norm = _validate_dims(dims, rank)
    summed = set(norm)

    ks = [d for d in range(k) if d not in summed]
    kd = [d for d in range(k, rank) if d not in summed]
    dense_sizes = list(shape[k:])
    R_out = _prod(dense_sizes)

    grad_sparse = bool(getattr(grad, "is_sparse", False))
    if ks:
        if not grad_sparse or grad.layout != torch.sparse_coo:
            raise RuntimeError(
                "_sparse_sum_backward: grad must be a sparse COO tensor when "
                "some sparse dims are retained"
            )
        gk = int(grad.sparse_dim())
        gshape = tuple(int(s) for s in grad.shape)
        if gk != len(ks) or (len(gshape) - gk) != len(kd):
            raise RuntimeError(
                "_sparse_sum_backward: grad shape is inconsistent with dim"
            )
        for t, d in enumerate(ks):
            if gshape[t] != shape[d]:
                raise RuntimeError("_sparse_sum_backward: grad sparse size mismatch")
        for t, d in enumerate(kd):
            gs = gshape[gk + t]
            if gs != shape[d] and gs != 1:
                raise RuntimeError("_sparse_sum_backward: grad dense size mismatch")
        if len(ks) != k and self.dtype not in (
            torch.float16,
            torch.float32,
            torch.float64,
        ):
            raise RuntimeError(
                '"_sparse_sum_backward_cuda" not implemented for ' f"'{self.dtype}'"
            )
    else:
        if grad_sparse:
            raise RuntimeError(
                "_sparse_sum_backward: grad must be dense when every sparse "
                "dim is summed"
            )
        if grad.dim() != len(kd):
            raise RuntimeError(
                "_sparse_sum_backward: grad rank does not match the retained "
                "dense dims"
            )
        for t, d in enumerate(kd):
            gs = int(grad.shape[t])
            if gs != shape[d] and gs != 1:
                raise RuntimeError("_sparse_sum_backward: grad dense size mismatch")

    device = self.device
    sidx = self._indices()
    sparse_sizes = [shape[d] for d in range(k)]

    if bool(self.is_coalesced()):
        nnz = int(sidx.shape[1])
        gather = bool(ks) and len(ks) != k
        same_row = False if not ks else (not gather)
    else:
        sidx, nnz = _sparsify(k, sidx, sparse_sizes, device)
        gather = bool(ks)
        same_row = False

    # kept-dense offset: a suffix of the dense dims collapses to one modulo.
    nkd = len(kd)
    # positional strides of the kept dense dims inside grad (or its values)
    if not ks:
        gsrc = grad
        gbase = 0
    else:
        gsrc = grad._values()
        gbase = 1
    gd_strides = [int(gsrc.stride(gbase + t)) for t in range(nkd)]

    # only when the kept dims form a suffix AND grad stores them compactly does
    # that offset collapse to a single modulo of `col`.
    if nkd == 0:
        dense_mode = _DM_SUFFIX
        d_keep_run = 1
    else:
        kept_sizes = [dense_sizes[d - k] for d in kd]
        compact = gd_strides == _rowmajor(kept_sizes)
        if kd == list(range(rank - nkd, rank)) and compact:
            dense_mode = _DM_SUFFIX
            d_keep_run = _prod(kept_sizes)
        else:
            dense_mode = _DM_GENERAL
            d_keep_run = 1

    out_vals = torch.empty((nnz,) + tuple(dense_sizes), dtype=self.dtype, device=device)
    n_elem = nnz * R_out
    if n_elem:
        grid = (triton.cdiv(n_elem, _BLOCK),)

        if not ks:
            gptr = grad
            grow_stride = 0
            gstrides = [
                0 if int(grad.shape[t]) == 1 else gd_strides[t] for t in range(nkd)
            ]
        else:
            gptr = gsrc
            grow_stride = int(gsrc.stride(0))
            gstrides = list(gd_strides)

        dense_kw = dict(DENSE_MODE=dense_mode, D_KEEP_RUN=d_keep_run)
        if dense_mode == _DM_GENERAL:
            dense_kw.update(
                KD_POS=nkd,
                KD_SIZES=tuple(dense_sizes[d - k] for d in kd),
                KD_STRIDES=tuple(_rowmajor(dense_sizes)[d - k] for d in kd),
                G_STRIDES=tuple(gstrides),
            )
        else:
            dense_kw.update(
                KD_POS=0,
                KD_SIZES=(),
                KD_STRIDES=(),
                G_STRIDES=(),
            )

        if gather:
            key_strides = _rowmajor([sparse_sizes[d] for d in ks])
            map_t = _make_map(
                ks,
                key_strides,
                _prod([sparse_sizes[d] for d in ks]),
                grad._indices(),
                int(grad._nnz()),
                device,
            )
            _ssb_gather[grid](
                gptr,
                sidx,
                map_t,
                out_vals,
                n_elem,
                grow_stride,
                _elem_strides(sidx)[0],
                _elem_strides(sidx)[1],
                R_OUT=R_out,
                NKS=len(ks),
                KS=tuple(ks),
                KEY_STRIDES=tuple(key_strides),
                BLOCK=_BLOCK,
                num_warps=_WARPS,
                **dense_kw,
            )
        else:
            # src == offs exactly: row(i) == i and both row strides are R_out
            identity = (
                same_row
                and dense_mode == _DM_SUFFIX
                and d_keep_run == R_out
                and grow_stride == R_out
            )
            _ssb_copy[grid](
                gptr,
                out_vals,
                n_elem,
                grow_stride,
                R_OUT=R_out,
                SAME_ROW=same_row,
                IDENTITY=identity,
                BLOCK=_BLOCK,
                num_warps=_WARPS,
                **dense_kw,
            )

    res = torch.sparse_coo_tensor(
        sidx, out_vals, shape, device=device, is_coalesced=True
    )
    if out is not None:
        out.copy_(res)
        return out
    return res
