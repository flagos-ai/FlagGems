"""Triton implementation of aten::_sparse_sum_backward.

Semantics (validated against the ATen CUDA kernel on the H20 target):

  Let self be SparseCOO with ``k = sparse_dim`` and rank ``r``.  ``dim`` is
  normalised (negatives add ``r``, a repeated axis raises, an out-of-range axis
  raises).  With ``S`` the normalised summed axes, ``KS`` the kept sparse axes
  and ``KD`` the kept dense axes, the result is SparseCOO with ``self.shape``,
  sparse_dim ``k`` and the sorted-unique sparsified ``self`` coordinate set as
  its indices (``self._indices()`` when ``self`` is already coalesced).  Its
  values have shape ``(nnz, *self.shape[k:])`` with

      values[i, j] = grad[row(i), kept_dense_offset(j)]

  where ``kept_dense_offset(j)`` is the row-major offset of ``j`` restricted to
  the kept dense axes and ``row(i)`` is
    * 0        when no sparse axis is kept (grad is dense), or
    * the grad row whose kept-sparse coordinate equals self's column ``i``
      (grad regathers; floating dtypes only, and when ``self`` is already
      coalesced and every sparse axis is kept this row is simply ``i``).

The operator is a pure gather/copy and the measured workloads are small, so the
implementation is organised to minimise per-call cost: two specialised value
kernels with short signatures, the very common "kept dense dims are a suffix"
layout folded into a single modulo, and no per-call recomputation beyond what
the branch needs.

Pointwise value movement happens only in the Triton kernels below; the host
wrapper performs allocation, metadata reads, and the in-place ``out=`` write.
"""

