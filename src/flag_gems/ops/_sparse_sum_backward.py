def _prod(xs):
    r = 1
    for x in xs:
        r *= x
    return r


def _rowmajor(sizes):
    st = [0] * len(sizes)
    s = 1
    for i in range(len(sizes) - 1, -1, -1):
        st[i] = s
        s *= sizes[i]
    return st


def _elem_strides(t):
    if t.dim() == 2:
        return int(t.stride(0)), int(t.stride(1))
    return 1, 1


def _sparsify(k, sidx, sparse_sizes, device):
    """Sorted-unique self columns over the k sparse axes, computed on device."""
    nkeys = max(_prod(sparse_sizes), 1)
    nnz = int(sidx.shape[1])
    sstr = _rowmajor(sparse_sizes)
    s0, s1 = _elem_strides(sidx)
    cnt = torch.zeros(nkeys, dtype=torch.int32, device=device)
    slot = torch.empty(nkeys, dtype=torch.int64, device=device)
    tot = torch.zeros(1, dtype=torch.int32, device=device)
    if k > 0 and nnz > 0:
        _ssb_hist[(triton.cdiv(nnz, _AUX_BLOCK),)](
            sidx,
            cnt,
            nnz,
            s0,
            s1,
            SD=k,
            SSTRIDES=tuple(sstr),
            BLOCK=_AUX_BLOCK,
            num_warps=_WARPS,
        )
    _ssb_scan_slots[(1,)](cnt, slot, tot, nkeys, BLOCK=_AUX_BLOCK, num_warps=_WARPS)
    nnz_out = int(tot.item())
    if nnz_out == 0:
        return torch.empty((k, 0), dtype=torch.long, device=device), 0
    out_idx = torch.empty((k, nnz_out), dtype=torch.long, device=device)
    _ssb_scatter[(triton.cdiv(nkeys, _AUX_BLOCK),)](
        slot,
        out_idx,
        nnz_out,
        nkeys,
        SD=k,
        SIZES=tuple(sparse_sizes),
        SSTRIDES=tuple(sstr),
        BLOCK=_AUX_BLOCK,
        num_warps=_WARPS,
    )
    return out_idx, nnz_out


def _make_map(ks, key_strides, nkeys, gidx, nnzg, device):
    map_t = torch.full((nkeys,), -1, dtype=torch.int64, device=device)
    if nnzg > 0 and nkeys > 0:
        gs0, gs1 = _elem_strides(gidx)
        _ssb_map[(triton.cdiv(nnzg, _BLOCK),)](
            gidx,
            map_t,
            nnzg,
            gs0,
            gs1,
            NKS=len(ks),
            KEY_STRIDES=tuple(key_strides),
            BLOCK=_BLOCK,
            num_warps=_WARPS,
        )
    return map_t


def _validate_dims(dims, rank):
    for d in dims:
        if rank == 0 or d < -rank or d >= rank:
            raise IndexError(
                "Dimension out of range (expected to be in range of "
                f"[{-rank}, {rank - 1}], but got {d})"
            )
    norm = [d % rank for d in dims] if rank else []
    if len(set(norm)) != len(norm):
        raise RuntimeError(
            f"dim {list(dims)} appears multiple times in the list of dims"
        )
    return norm


