def _ssb_copy(
    grad_ptr,
    out_ptr,
    n_elem,
    grow_stride,
    R_OUT: tl.constexpr,
    SAME_ROW: tl.constexpr,
    IDENTITY: tl.constexpr,
    DENSE_MODE: tl.constexpr,
    D_KEEP_RUN: tl.constexpr,
    KD_POS: tl.constexpr,
    KD_SIZES: tl.constexpr,
    KD_STRIDES: tl.constexpr,
    G_STRIDES: tl.constexpr,
    BLOCK: tl.constexpr,
):
    """row(i) is 0 (dense grad) or i (every sparse axis kept).

    ``IDENTITY`` marks the case where the gather source is exactly the flat
    output offset (row(i) == i and both row strides equal ``R_OUT``). The
    address is then ``pid * BLOCK + arange``, which Triton can prove contiguous
    and serve with wide vector loads.
    """
