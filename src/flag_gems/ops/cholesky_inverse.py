@triton.jit
def _triinv16(D, rowok, NSTEP: tl.constexpr):
    """Inverse of a lower-triangular 16x16 tile (padded rows -> identity)."""
    ii = tl.arange(0, 16)[:, None]
    jj = tl.arange(0, 16)[None, :]
    D = tl.where(ii >= jj, D, 0.0)
    dd = tl.sum(tl.where(ii == jj, D, 0.0), axis=1)
    dd = tl.where(rowok, dd, 1.0)
    dv = 1.0 / dd
    P = tl.where(ii > jj, -(D * dv[:, None]), 0.0)
    S = (ii == jj).to(D.dtype)
    for _ in tl.static_range(NSTEP):
        S = S + tl.dot(P, S, input_precision="ieee")
        P = tl.dot(P, P, input_precision="ieee")
    return S * dv[None, :]


@triton.jit
def _fused_kernel(
    Lp,
    Op,
    n,
    sb_in,
    ar,
    ac,
    sb_out,
    K: tl.constexpr,
    NSTEP: tl.constexpr,
):
    """One program per matrix; the whole problem stays in registers (K == 1)."""
    dt = Lp.dtype.element_ty
    pid = tl.program_id(0)
    bi = pid * sb_in
    bo = pid * sb_out
    r = tl.arange(0, 16)
    zero = tl.zeros((16, 16), dtype=dt)

    Dinv = ()
    for d in tl.static_range(K):
        rows = d * 16 + r
        D = tl.load(
            Lp + bi + rows[:, None] * ar + rows[None, :] * ac,
            mask=(rows[:, None] < n) & (rows[None, :] < n),
            other=0.0,
        )
        Dinv = Dinv + (_triinv16(D, rows < n, NSTEP),)

    # X[Iblk][jc] stored flat as X[jc * K + Iblk]
    X = ()
    for jc in tl.static_range(K):
        for Iblk in tl.static_range(K):
            if Iblk < jc:
                X = X + (zero,)
            elif Iblk == jc:
                X = X + (Dinv[jc],)
            else:
                Y = tl.zeros((16, 16), dtype=dt)
                for k in tl.static_range(jc, Iblk):
                    rows = Iblk * 16 + r
                    cols = k * 16 + r
                    Lk = tl.load(
                        Lp + bi + rows[:, None] * ar + cols[None, :] * ac,
                        mask=(rows[:, None] < n) & (cols[None, :] < n),
                        other=0.0,
                    )
                    Y = Y + tl.dot(Lk, X[jc * K + k], input_precision="ieee")
                X = X + (-tl.dot(Dinv[Iblk], Y, input_precision="ieee"),)

    for i in tl.static_range(K):
        for j in tl.static_range(K):
            acc = tl.zeros((16, 16), dtype=dt)
            for k in tl.static_range(max(i, j), K):
                acc = acc + tl.dot(
                    tl.trans(X[i * K + k]), X[j * K + k], input_precision="ieee"
                )
            rows = i * 16 + r
            cols = j * 16 + r
            tl.store(
                Op + bo + rows[:, None] * n + cols[None, :],
                acc,
                mask=(rows[:, None] < n) & (cols[None, :] < n),
            )


@triton.jit
def _dinv_kernel(Lp, Dp, n, sb_in, ar, ac, K: tl.constexpr, NSTEP: tl.constexpr):
    pid = tl.program_id(0)
    b = pid // K
    d = pid % K
    r = tl.arange(0, 16)
    rows = d * 16 + r
    D = tl.load(
        Lp + b * sb_in + rows[:, None] * ar + rows[None, :] * ac,
        mask=(rows[:, None] < n) & (rows[None, :] < n),
        other=0.0,
    )
    Dinv = _triinv16(D, rows < n, NSTEP)
    o = tl.arange(0, 16)
    tl.store(Dp + pid * 256 + o[:, None] * 16 + o[None, :], Dinv)


@triton.jit
def _trtri_kernel(Lp, Dp, Xp, n, sb_in, ar, ac, MP, K: tl.constexpr):
    """One program per (matrix, column block): X[:, jc] = L^{-1}[:, jc]."""
    dt = Lp.dtype.element_ty
    pid = tl.program_id(0)
    b = pid // K
    jc = pid % K
    bi = b * sb_in
    xb = b * MP * MP
    r = tl.arange(0, 16)
    ii = r[:, None]
    jj = r[None, :]

    Xc = ()
    for Iblk in tl.static_range(K):
        Di = tl.load(Dp + (b * K + Iblk) * 256 + ii * 16 + jj)
        Y = tl.zeros((16, 16), dtype=dt)
        for k in tl.static_range(K):
            if k < Iblk:
                if k >= jc:
                    rows = Iblk * 16 + r
                    cols = k * 16 + r
                    m = (rows[:, None] < n) & (cols[None, :] < n)
                    Lk = tl.load(
                        Lp + bi + rows[:, None] * ar + cols[None, :] * ac,
                        mask=m,
                        other=0.0,
                    )
                    Y = Y + tl.dot(Lk, Xc[k], input_precision="ieee")
        cur = -tl.dot(Di, Y, input_precision="ieee") * (Iblk > jc).to(dt) + Di * (
            Iblk == jc
        ).to(dt)
        Xc = Xc + (cur,)
        rows = Iblk * 16 + r
        cols = jc * 16 + r
        tl.store(
            Xp + xb + rows[:, None] * MP + cols[None, :],
            cur,
            mask=(Iblk >= jc) & (rows[:, None] < n) & (cols[None, :] < n),
        )


@triton.jit
def _trtri_row_kernel(
    Lp, Dp, Xp, n, sb_in, ar, ac, MP, Iblk: tl.constexpr, K: tl.constexpr
):
    """One program per (matrix, column block); computes block row Iblk of X.

    Used when K is large enough that the fully unrolled substitution would
    exceed the backend read-only-data limit.  Row Iblk is produced by a separate
    launch so that rows k < Iblk read by the k-loop are already committed, and the
    k-loop is statically unrolled to keep the generated code tiny.  Steps with
    k < jc contribute exact zeros and are skipped by a uniform branch.
    """
    dt = Lp.dtype.element_ty
    pid = tl.program_id(0)
    b = pid // K
    jc = pid % K
    bi = b * sb_in
    xb = b * MP * MP
    r = tl.arange(0, 16)
    ii = r[:, None]
    jj = r[None, :]

    Di = tl.load(Dp + (b * K + Iblk) * 256 + ii * 16 + jj)
    Y = tl.zeros((16, 16), dtype=dt)
    for k in tl.static_range(Iblk):
        if k >= jc:
            rows = Iblk * 16 + r
            cols = k * 16 + r
            ok = (rows[:, None] < n) & (cols[None, :] < n)
            Lk = tl.load(
                Lp + bi + rows[:, None] * ar + cols[None, :] * ac,
                mask=ok,
                other=0.0,
            )
            xrows = k * 16 + r
            xcols = jc * 16 + r
            okx = (xrows[:, None] < n) & (xcols[None, :] < n)
            Xk = tl.load(
                Xp + xb + xrows[:, None] * MP + xcols[None, :], mask=okx, other=0.0
            )
            Y = Y + tl.dot(Lk, Xk, input_precision="ieee")
    cur = -tl.dot(Di, Y, input_precision="ieee") * (Iblk > jc).to(dt) + Di * (
        Iblk == jc
    ).to(dt)
    rows = Iblk * 16 + r
    cols = jc * 16 + r
    tl.store(
        Xp + xb + rows[:, None] * MP + cols[None, :],
        cur,
        mask=(Iblk >= jc) & (rows[:, None] < n) & (cols[None, :] < n),
    )


@triton.jit
def _xtx_kernel(Xp, Op, n, MP, sb_out, K: tl.constexpr):
    """out[i, j] = X^T X: one program per i <= j tile, mirrored on store."""
    dt = Xp.dtype.element_ty
    pid = tl.program_id(0)
    b = pid // (K * K)
    t = pid % (K * K)
    i = t // K
    j = t % K
    xb = b * MP * MP
    r = tl.arange(0, 16)
    if i <= j:
        acc = tl.zeros((16, 16), dtype=dt)
        for k in tl.static_range(K):
            if k >= j:
                rows = k * 16 + r
                ci = i * 16 + r
                cj = j * 16 + r
                a = tl.load(
                    Xp + xb + rows[:, None] * MP + ci[None, :],
                    mask=(rows[:, None] < n) & (ci[None, :] < n),
                    other=0.0,
                )
                bb = tl.load(
                    Xp + xb + rows[:, None] * MP + cj[None, :],
                    mask=(rows[:, None] < n) & (cj[None, :] < n),
                    other=0.0,
                )
                acc = acc + tl.dot(tl.trans(a), bb, input_precision="ieee")
        rows = i * 16 + r
        cols = j * 16 + r
        tl.store(
            Op + b * sb_out + rows[:, None] * n + cols[None, :],
            acc,
            mask=(rows[:, None] < n) & (cols[None, :] < n),
        )
        if i < j:
            mrows = j * 16 + r
            mcols = i * 16 + r
            tl.store(
                Op + b * sb_out + mrows[:, None] * n + mcols[None, :],
                tl.trans(acc),
                mask=(mrows[:, None] < n) & (mcols[None, :] < n),
            )


def _nstep(n):
    if n >= 16:
        return _NSTEP16
    return max(1, (n - 1).bit_length())


def _inverse_f32(self, upper):
    n = self.shape[-1]
    B = self.numel() // (n * n)
    out = torch.empty(self.shape, dtype=self.dtype, device=self.device)

    if self.is_contiguous() or self.dim() == 2:
        sb = n * n
    else:
        sb = self.stride(0)

    rs = self.stride(-2)
    cs = self.stride(-1)
    if upper:
        ar, ac = cs, rs
    else:
        ar, ac = rs, cs

    K = (n + 15) // 16
    nstep = _nstep(n)

    if K == 1:
        _fused_kernel[(B,)](
            self,
            out,
            n,
            sb,
            ar,
            ac,
            n * n,
            K=K,
            NSTEP=nstep,
            num_warps=1,
        )
    elif K <= 8:
        MP = K * 16
        dinv = torch.empty((B * K, 16, 16), dtype=self.dtype, device=self.device)
        xtmp = torch.empty((B * MP, MP), dtype=self.dtype, device=self.device)
        _dinv_kernel[(B * K,)](self, dinv, n, sb, ar, ac, K=K, NSTEP=nstep, num_warps=1)
        _trtri_kernel[(B * K,)](self, dinv, xtmp, n, sb, ar, ac, MP, K=K, num_warps=1)
        _xtx_kernel[(B * K * K,)](xtmp, out, n, MP, n * n, K=K, num_warps=1)
    else:
        MP = K * 16
        dinv = torch.empty((B * K, 16, 16), dtype=self.dtype, device=self.device)
        xtmp = torch.empty((B * MP, MP), dtype=self.dtype, device=self.device)
        _dinv_kernel[(B * K,)](self, dinv, n, sb, ar, ac, K=K, NSTEP=nstep, num_warps=1)
        for Iblk in range(K):
            _trtri_row_kernel[(B * K,)](
                self, dinv, xtmp, n, sb, ar, ac, MP, Iblk, K=K, num_warps=1
            )
        _xtx_kernel[(B * K * K,)](xtmp, out, n, MP, n * n, K=K, num_warps=1)

    return out


def _cholesky_inverse_forward(L, upper=False):
    """Compute the inverse of a symmetric positive-definite matrix from its
    Cholesky decomposition.

    Given the Cholesky factor L (lower) where A = L @ L^T, computes A^{-1}.
    For upper=True, given U where A = U^T @ U, computes A^{-1}.

    Args:
        L: Tensor of shape (*, n, n) containing the Cholesky factor.
        upper: If True, L is upper triangular; otherwise lower triangular.

    Returns:
        The inverse of the original positive-definite matrix.
    """
    logger.debug("GEMS CHOLESKY_INVERSE")
    assert L.dtype in (
        torch.float32,
        torch.float64,
    ), "cholesky_inverse only supports float32 and float64"

    if L.numel() == 0:
        return L

    shape = L.shape
    if len(shape) < 2:
        raise ValueError("Input must be at least 2D")

    n = shape[-1]
    m = shape[-2]
    if n != m:
        raise ValueError("Input must be a square matrix")

    x = L if L.is_contiguous() else copy_tensor(L)
    with torch_device_fn.device(L.device):
        return _inverse_f32(x, upper)


@triton.jit
def _small_cholesky_backward(
    L,
    INV,
    G,
    OUT,
    N: tl.constexpr,
    LS0: tl.constexpr,
    LS1: tl.constexpr,
    LS2: tl.constexpr,
    GS0: tl.constexpr,
    GS1: tl.constexpr,
    GS2: tl.constexpr,
    UPPER: tl.constexpr,
    TILE: tl.constexpr,
):
    b = tl.program_id(0)
    r = tl.arange(0, TILE)
    mask = (r[:, None] < N) & (r[None, :] < N)
    factor = tl.load(L + b * LS0 + r[:, None] * LS1 + r[None, :] * LS2, mask, other=0)
    inverse = tl.load(INV + b * N * N + r[:, None] * N + r[None, :], mask, other=0)
    grad = tl.load(G + b * GS0 + r[:, None] * GS1 + r[None, :] * GS2, mask, other=0)
    sym = grad + tl.trans(grad)
    right = tl.dot(sym, inverse, input_precision="ieee")
    common = tl.dot(inverse, right, input_precision="ieee")
    if UPPER:
        output = -tl.dot(factor, common, input_precision="ieee")
    else:
        output = -tl.dot(common, factor, input_precision="ieee")
    tl.store(OUT + b * N * N + r[:, None] * N + r[None, :], output, mask)


class CholeskyInverseFunction(torch.autograd.Function):
    @staticmethod
    def forward(ctx, L, upper):
        output = _cholesky_inverse_forward(L, upper)
        ctx.save_for_backward(L, output)
        ctx.upper = upper
        return output

    @staticmethod
    @torch.autograd.function.once_differentiable
    def backward(ctx, grad):
        L, inverse = ctx.saved_tensors
        if L.numel() == 0:
            return torch.empty_like(L), None
        n = L.shape[-1]
        factor = (L if L.is_contiguous() else copy_tensor(L)).view(-1, n, n)
        g = (grad if grad.is_contiguous() else copy_tensor(grad)).view(-1, n, n)
        inv = inverse.view(-1, n, n)
        if n <= 64:
            output = torch.empty(L.shape, dtype=L.dtype, device=L.device)
            with torch_device_fn.device(L.device):
                _small_cholesky_backward[(factor.shape[0],)](
                    factor,
                    inv,
                    g,
                    output,
                    n,
                    *factor.stride(),
                    *g.stride(),
                    ctx.upper,
                    max(16, triton.next_power_of_2(n)),
                    num_warps=8 if n > 32 else 4,
                )
            return output, None
        symmetric = add(g, g.transpose(1, 2))
        common = bmm(inv, bmm(symmetric, inv))
        result = bmm(factor, common) if ctx.upper else bmm(common, factor)
        return neg(result).view(L.shape), None


def cholesky_inverse(L, upper=False):
    if torch.is_grad_enabled() and L.requires_grad:
        return CholeskyInverseFunction.apply(L, upper)
    return _cholesky_inverse_forward(L, upper)
