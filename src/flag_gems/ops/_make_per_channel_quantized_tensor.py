@triton.jit
def _mpcq_gather_strided(
    src_ptr,
    dst_ptr,
    n_elements,
    e1,
    e2,
    e3,
    e4,
    e5,
    e6,
    e7,
    s0,
    s1,
    s2,
    s3,
    s4,
    s5,
    s6,
    s7,  # source strides
    RANK: tl.constexpr,
    BLOCK: tl.constexpr,
):
    """Non-contiguous payload: gather elements into contiguous storage.

    The destination is contiguous, so a flat output index decomposes against
    the suffix products of the out sizes (``e_k`` = product of sizes[k:]):
    ``c_d = rem // e_{d+1}`` for d = 0..rank-2, and the last coordinate is the
    remainder itself. Each coordinate is re-based by the source stride.
    ``RANK`` folds unused trailing dims out at compile time.
    """
    pid = tl.program_id(0)
    offs = pid * BLOCK + tl.arange(0, BLOCK).to(tl.int64)
    mask = offs < n_elements
    src_off = tl.zeros([BLOCK], dtype=tl.int64)
    rem = offs
    if RANK > 1:
        c = rem // e1
        src_off += c * s0
        rem = rem % e1
    if RANK > 2:
        c = rem // e2
        src_off += c * s1
        rem = rem % e2
    if RANK > 3:
        c = rem // e3
        src_off += c * s2
        rem = rem % e3
    if RANK > 4:
        c = rem // e4
        src_off += c * s3
        rem = rem % e4
    if RANK > 5:
        c = rem // e5
        src_off += c * s4
        rem = rem % e5
    if RANK > 6:
        c = rem // e6
        src_off += c * s5
        rem = rem % e6
    if RANK > 7:
        c = rem // e7
        src_off += c * s6
        rem = rem % e7
    # After peeling dims 0..RANK-2 the remainder is the last coordinate.
    src_off += rem * s7
    tl.store(dst_ptr + offs, tl.load(src_ptr + src_off, mask=mask), mask=mask)


