def _validate(self, scale, zero_point):
    """Mirror the ATen argument contract of ``_make_per_channel_quantized_tensor``.

    The output quantized dtype is decided by the payload's integer dtype and
    the schema routes through ``aten::_empty_per_channel_affine_quantized``
    first, so an unsupported payload dtype is a backend NotImplementedError in
    ATen. The qparam vector checks mirror
    ``make_per_channel_affine_quantizer``.
    """
    if self.dtype not in _QINT_FROM_QDTYPE.values():
        raise NotImplementedError(
            "Could not run 'aten::_empty_per_channel_affine_quantized' with "
            "arguments from the CUDA backend: unsupported payload dtype "
            f"{self.dtype}"
        )
    if not scale.dtype.is_floating_point:
        raise RuntimeError("scale tensor must be floating point")
    if scale.dim() != 1:
        raise RuntimeError("scale tensor must have dimension 1")
    if zero_point.dim() != 1:
        raise RuntimeError("zero_points tensor must have dimension 1")
    if scale.numel() != zero_point.numel():
        raise RuntimeError("number of elements in scales and zero_points must match")
    for name, param in (("scale", scale), ("zero_point", zero_point)):
        if param.device != self.device:
            raise RuntimeError(
                f"Expected all tensors to be on the same device, but found at "
                f"least two devices, {self.device.type} and {param.device.type}! "
                f"(when checking argument for argument '{name}' in "
                "_make_per_channel_quantized_tensor)"
            )
    # The strided gather folds the payload into _MAX_RANK stride slots; a
    # higher-rank payload would silently lose dimensions.
    if self.dim() > _MAX_RANK:
        raise RuntimeError(
            f"_make_per_channel_quantized_tensor supports at most {_MAX_RANK} "
            f"dimensions, got {self.dim()}"
        )


