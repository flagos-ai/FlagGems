"""Gradient of convolution_overrideable w.r.t. its input (grad_input only).

Single-launch Triton gather formulation.  For a (non-)transposed forward
convolution the input gradient is a gather over the forward output grid:

* direct  forward:  gx[n,ci,i] = sum_{co,k} g[n,co,oh,ow] * w[co,ci_in,k]
                    with oh = (i + pad - k*dil)/stride  (must divide and be < T)
* transposed forward: gx[n,ci,i] = sum_{co,k} g[n,co,oh,ow] * w[ci,co_in,k]
                    with oh = i*stride - pad + k*dil

Both are one matmul per output element over the flat contraction
kk = co * prod(kernel) + kernel_position, so a single Triton kernel with tl.dot
covers 1D/2D/3D, groups, stride, padding and dilation with no intermediate
buffer and no extra launch.

These workloads are tiny (the worst case is well under one MFLOP), so the cost
is programme-launch and index arithmetic rather than the maths.  Two choices
target that:

* all spatial geometry enters the kernel as ``tl.constexpr``, so the index
  decomposition, the stride divisibility tests and the gather offsets fold at
  compile time; and
* the contraction is flattened over (co, kernel taps) and consumed in wide
  BLOCK_K chunks, so a 3D case issues ceil(432/64) = 7 dots instead of one
  16-wide dot per kernel tap, which shortens the dependent accumulator chain and
  gives tl.dot a k extent large enough to use the tensor cores efficiently.
"""

import logging

import torch
import triton
import triton.language as tl

logger = logging.getLogger(__name__)

# tl.dot requires both the M and N extents to be at least 16, so BLOCK_M and
# BLOCK_CI are pinned at that minimum: the tiny conv cases are launch-bound, and
# a wider tile would only add masked-off lanes. BLOCK_K = 64 keeps the flattened
# (co, kernel-tap) contraction wide enough for tensor-core-friendly dots while
# still dividing the 432-element worst case into ~7 chunks. 4 warps / 3 stages
# match the latency-hidden shape of these small tiles (deeper pipelining has too
# little loop trip count to pay off).
_BLOCK_M = 16
_BLOCK_CI = 16
_BLOCK_K = 64
_NUM_WARPS = 4
_NUM_STAGES = 3


def _spatial(value, ndim, fill):
    """Normalise a spatial spec to exactly three entries (missing -> fill)."""
    if isinstance(value, (list, tuple)):
        vals = [int(v) for v in value]
        if len(vals) == 1 and ndim > 1:
            vals = vals * ndim
    else:
        vals = [int(value)] * ndim
    vals = vals[:ndim]
    if len(vals) < 3:
        vals = vals + [fill] * (3 - len(vals))
    return vals


