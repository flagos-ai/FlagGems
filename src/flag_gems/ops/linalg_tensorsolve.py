"""Triton implementation of ``linalg_tensorsolve``.

Semantics (numpy/ATen compatible)
---------------------------------
Let ``A = self`` with ``a = A.ndim`` and ``B = other`` with ``b = B.ndim``
(``a >= b``).  ``dims`` selects ``k = a - b`` axes of ``A`` that are moved to
the right (in the given order); ``dims=None`` means "no reordering", so the
trailing ``k`` axes of ``A`` are used.  With ``A_p`` the reordered view:

    out_shape = A_p.shape[b:]
    P         = prod(out_shape)
    solution  = solve(A_p.reshape(P, P), B.reshape(P)).reshape(out_shape)

The whole ``P x P`` system is factorised by Gauss-Jordan elimination with
delayed partial pivoting inside a *single* Triton program: the matrix tile
lives in registers, so no inter-block synchronisation is required.

The pivot loop is the whole cost.  Each step needs exactly three cross-lane
reduction stages - the column-k extraction, the pivot pick and the pivot-row
extraction - which is the structural minimum for a register-tile solver, so
for the small systems that dominate this operator the pivot count is turned
into a compile-time constant and the loop is unrolled (``tl.static_range``),
which lets the per-step masks constant-fold and lets the scheduler overlap
the non-dependent parts of adjacent steps.

Numerics: the elimination runs in the input's own floating-point type, so an
fp64 system is factorised in fp64 instead of being narrowed first.  Narrower
inputs are widened to fp32, which is what keeps the pivot divisions meaningful
at those widths; the solution is cast to the output dtype at the final store.
"""

import torch
import triton
import triton.language as tl


@triton.jit
def _pick3(v1, c1, i1, v2, c2, i2):
    """Combine for the fused pivot reduction: keep the element with the
    larger key, breaking ties towards the smaller row index (the same
    left-tie-break rule ``tl.argmax`` uses)."""
    take = (v1 > v2) | ((v1 == v2) & (i1 < i2))
    return (tl.where(take, v1, v2), tl.where(take, c1, c2), tl.where(take, i1, i2))


@triton.jit
def _tensorsolve_kernel(
    A_ptr,  # *f32/*f64  (P rows x P cols, row-major) or strided gather
    B_ptr,  # *f32/*f64  (P,)
    O_ptr,  # *f32/*f64  (P,)
    ROW_ptr,  # *i32       row offsets (only when STRIDED)
    COL_ptr,  # *i32       col offsets (only when STRIDED)
    P,  # i32        runtime system size
    PC: tl.constexpr,  # compile-time system size (== P when UNROLL)
    UNROLL: tl.constexpr,  # statically unroll the pivot loop
    N: tl.constexpr,  # pow2 >= P
    STRIDED: tl.constexpr,
    ACC: tl.constexpr,  # floating type the elimination runs in
):
    i = tl.arange(0, N)
    j = tl.arange(0, N)
    am = (i[:, None] < P) & (j[None, :] < P)

    if STRIDED:
        ro = tl.load(ROW_ptr + i, mask=i < P, other=0)
        co = tl.load(COL_ptr + j, mask=j < P, other=0)
        a_off = ro[:, None] + co[None, :]
    else:
        a_off = i[:, None] * P + j[None, :]

    A = tl.load(A_ptr + a_off, mask=am, other=0.0).to(ACC)
    # Padding corner (rows/cols >= P) becomes an identity block, so the
    # padded unknowns decouple and every inner step needs no mask.
    A = tl.where(am, A, tl.where(i[:, None] == j[None, :], 1.0, 0.0))

    bm = i < P
    b = tl.load(B_ptr + i, mask=bm, other=0.0).to(ACC)

    # Delayed pivoting: no row of ``A`` (or of ``b``) is ever physically
    # moved.  ``used[i]`` marks a row already consumed as a pivot row (rows
    # in the identity padding block are pre-marked so they can never be
    # picked), and ``posv[k]`` records which physical row carries solution
    # component k.
    used = tl.where(bm, 0.0, 1.0)
    posv = i

    if UNROLL:
        for k in tl.static_range(0, PC):
            # --- R1: column k -------------------------------------------------
            colk = tl.sum(tl.where(j[None, :] == k, A, 0.0), axis=1)

            # --- R2: one cross-lane pass gives the pivot index and the
            #         signed pivot value together.
            absv = tl.where(used < 0.5, tl.abs(colk), -1.0)
            _mk, pk, piv = tl.reduce((absv, colk, i), 0, _pick3)
            isp = i == piv
            inv = 1.0 / pk

            # --- R3: pivot row (independent of the RHS pick below, so the
            #         two can overlap).
            rowp = tl.sum(tl.where(isp[:, None], A, 0.0), axis=0)
            prow_n = rowp * inv
            pb = tl.sum(tl.where(isp, b, 0.0), axis=0)

            # Multipliers are the (unscaled) column k; lane `piv` is set to
            # (pk - 1) so the one fused update both eliminates column k in
            # every other row and normalises the pivot row
            # (rowp - (pk-1)*rowp/pk == rowp/pk == prow_n).
            ck = tl.where(isp, pk - 1.0, colk)

            A = A - ck[:, None] * prow_n[None, :]
            b = b - ck * (pb * inv)

            used = tl.where(isp, 1.0, used)
            posv = tl.where(i == k, piv, posv)
    else:
        for k in range(0, P):
            colk = tl.sum(tl.where(j[None, :] == k, A, 0.0), axis=1)
            absv = tl.where(used < 0.5, tl.abs(colk), -1.0)
            _mk, pk, piv = tl.reduce((absv, colk, i), 0, _pick3)
            isp = i == piv
            inv = 1.0 / pk
            rowp = tl.sum(tl.where(isp[:, None], A, 0.0), axis=0)
            prow_n = rowp * inv
            pb = tl.sum(tl.where(isp, b, 0.0), axis=0)
            ck = tl.where(isp, pk - 1.0, colk)
            A = A - ck[:, None] * prow_n[None, :]
            b = b - ck * (pb * inv)
            used = tl.where(isp, 1.0, used)
            posv = tl.where(i == k, piv, posv)

    # One-off un-permutation: x[k] = b[posv[k]].
    x = tl.sum(tl.where(posv[:, None] == i[None, :], b[None, :], 0.0), axis=1)
    tl.store(O_ptr + i, x.to(O_ptr.dtype.element_ty), mask=bm)


def linalg_tensorsolve(self, other, dims=None):
    # ``aten::linalg_tensorsolve(Tensor self, Tensor other, int[]? dims=None)``
    # defaults ``dims``, so it defaults here too; otherwise the public
    # ``torch.linalg.tensorsolve(A, B)`` call cannot bind.
    A = self
    B = other
    a = A.dim()
    bn = B.dim()

    # ---- resolve `dims` -------------------------------------------------
    if dims is None:
        perm = list(range(a))
    else:
        if isinstance(dims, torch.Tensor):
            raw = dims.reshape(-1).tolist()
        else:
            raw = list(dims)
        # ``% a`` alone would silently wrap an out-of-range dim onto a valid
        # one and solve a different system; ATen raises instead.  Duplicates
        # are rejected for the same reason: the permutation would drop an axis.
        dl = []
        for d in raw:
            d = int(d)
            if d < -a or d >= a:
                raise IndexError(
                    "Dimension out of range (expected to be in range of "
                    "[%d, %d], but got %d)" % (-a, a - 1, d)
                )
            d = d % a
            if d in dl:
                raise RuntimeError(
                    "linalg.tensorsolve: dims must not contain duplicates, "
                    "but dimension %d appears more than once" % d
                )
            dl.append(d)
        rest = [d for d in range(a) if d not in dl]
        perm = rest + dl

    Ap = A if perm == list(range(a)) else A.permute(perm)

    lead_shape = Ap.shape[:bn]
    tail_shape = Ap.shape[bn:]
    P = 1
    for s in tail_shape:
        P *= int(s)
    nlead = 1
    for s in lead_shape:
        nlead *= int(s)

    out = torch.empty(tuple(tail_shape), dtype=B.dtype, device=A.device)
    if P == 0 or nlead == 0:
        return out
    if P != nlead or P != B.numel():
        raise RuntimeError("linalg_tensorsolve: non square / mismatching system")

    Bflat = B.reshape(-1)

    N = 1
    while N < P:
        N *= 2

    nw = 1
    if N >= 32:
        nw = 4
    if N >= 64:
        nw = 8

    unroll = P <= 32
    pc = P if unroll else 1

    # Eliminate in the input's own precision: narrowing an fp64 system to fp32
    # costs ~1e-5 relative error, far past what fp64 tolerance allows. Narrower
    # inputs are widened so the pivot divisions stay meaningful.
    acc = tl.float64 if Ap.dtype == torch.float64 else tl.float32

    if Ap.is_contiguous():
        _tensorsolve_kernel[(1,)](
            Ap,
            Bflat,
            out,
            out,
            out,
            P,
            PC=pc,
            UNROLL=unroll,
            N=N,
            STRIDED=False,
            ACC=acc,
            num_warps=nw,
        )
    else:
        # Separable addressing: addr(i, j) = row_off[i] + col_off[j]
        lstrides = Ap.stride()

        def _offsets(count, shape, strides):
            # ``count`` enumerates row-major flat indices, where the LAST axis
            # varies fastest, so the mixed-radix decomposition has to consume
            # the axes back to front.  Walking them front to back instead
            # treats the first axis as fastest and silently reads a
            # transposed system whenever the lead or tail spans more than one
            # axis of unequal size.
            out = []
            for flat in range(count):
                off = 0
                rem = flat
                for s, st in zip(reversed(shape), reversed(strides)):
                    off += (rem % int(s)) * int(st)
                    rem //= int(s)
                out.append(off)
            return out

        row = _offsets(nlead, lead_shape, lstrides[:bn])
        col = _offsets(P, tail_shape, lstrides[bn:])
        row_t = torch.tensor(row, dtype=torch.int32, device=A.device)
        col_t = torch.tensor(col, dtype=torch.int32, device=A.device)
        _tensorsolve_kernel[(1,)](
            Ap,
            Bflat,
            out,
            row_t,
            col_t,
            P,
            PC=pc,
            UNROLL=unroll,
            N=N,
            STRIDED=True,
            ACC=acc,
            num_warps=nw,
        )

    return out


