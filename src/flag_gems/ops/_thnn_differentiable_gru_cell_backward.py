def _gru_bias_backward_kernel(
    grad_input_gates,
    grad_hidden_gates,
    grad_input_bias,
    grad_hidden_bias,
    batch_size,
    gate_size,
    BLOCK_BATCH: tl.constexpr,
    IS_FP64: tl.constexpr,
):
    gate_offset = tl.program_id(0)
    batch_offsets = tl.arange(0, BLOCK_BATCH)
    if IS_FP64:
        input_accumulator = tl.zeros((BLOCK_BATCH,), dtype=tl.float64)
        hidden_accumulator = tl.zeros((BLOCK_BATCH,), dtype=tl.float64)
    else:
        input_accumulator = tl.zeros((BLOCK_BATCH,), dtype=tl.float32)
        hidden_accumulator = tl.zeros((BLOCK_BATCH,), dtype=tl.float32)

    for batch_start in range(0, batch_size, BLOCK_BATCH):
        rows = batch_start + batch_offsets
        mask = rows < batch_size
        offsets = rows * gate_size + gate_offset
        input_values = tl.load(grad_input_gates + offsets, mask=mask, other=0.0)
        hidden_values = tl.load(grad_hidden_gates + offsets, mask=mask, other=0.0)
        if IS_FP64:
            input_accumulator += input_values.to(tl.float64)
            hidden_accumulator += hidden_values.to(tl.float64)
        else:
            input_accumulator += input_values.to(tl.float32)
            hidden_accumulator += hidden_values.to(tl.float32)

    tl.store(grad_input_bias + gate_offset, tl.sum(input_accumulator, axis=0))
    tl.store(grad_hidden_bias + gate_offset, tl.sum(hidden_accumulator, axis=0))


def _validate_inputs(grad_hy, input_gates, hidden_gates, hx):
    if any(tensor.ndim != 2 for tensor in (grad_hy, input_gates, hidden_gates, hx)):
        raise RuntimeError("GRU cell backward expects all inputs to be 2-D tensors")
    if grad_hy.shape != hx.shape:
        raise RuntimeError("grad_hy and hx must have the same shape")
    batch_size, hidden_size = hx.shape
    expected_gate_shape = (batch_size, 3 * hidden_size)
    if (
        input_gates.shape != expected_gate_shape
        or hidden_gates.shape != expected_gate_shape
    ):
        raise RuntimeError(
            "input_gates and hidden_gates must have shape "
            f"({batch_size}, {3 * hidden_size})"
        )


def _thnn_differentiable_gru_cell_backward(
    grad_hy: torch.Tensor,
    input_gates: torch.Tensor,
    hidden_gates: torch.Tensor,
    hx: torch.Tensor,
    input_bias: torch.Tensor = None,
    hidden_bias: torch.Tensor = None,
):
    """Compute the five differentiable GRU-cell backward outputs."""
    logger.debug("GEMS _THNN_DIFFERENTIABLE_GRU_CELL_BACKWARD")
    _validate_inputs(grad_hy, input_gates, hidden_gates, hx)

    batch_size, hidden_size = hx.shape
    gate_size = 3 * hidden_size
    grad_input_gates = torch.empty(
        (batch_size, gate_size), dtype=input_gates.dtype, device=input_gates.device
    )
    grad_hidden_gates = torch.empty(
        (batch_size, gate_size), dtype=hidden_gates.dtype, device=hidden_gates.device
    )
    grad_hx = torch.empty((batch_size, hidden_size), dtype=hx.dtype, device=hx.device)

    n_elements = batch_size * hidden_size
    if n_elements != 0:
        block_size = 256
        grid = (triton.cdiv(n_elements, block_size),)
        input_bias_arg = input_bias if input_bias is not None else input_gates
        hidden_bias_arg = hidden_bias if hidden_bias is not None else hidden_gates
        with torch_device_fn.device(grad_hy.device):
            _gru_cell_backward_kernel[grid](
                grad_hy,
                input_gates,
                hidden_gates,
                hx,
                input_bias_arg,
                hidden_bias_arg,
                grad_input_gates,
                grad_hidden_gates,
                grad_hx,
                batch_size,
                hidden_size,
                grad_hy.stride(0),
                grad_hy.stride(1),
                input_gates.stride(0),
                input_gates.stride(1),
                hidden_gates.stride(0),
                hidden_gates.stride(1),
                hx.stride(0),
                hx.stride(1),
                input_bias_arg.stride(0),
                hidden_bias_arg.stride(0),
                BLOCK_SIZE=block_size,
                HAS_INPUT_BIAS=input_bias is not None,
                HAS_HIDDEN_BIAS=hidden_bias is not None,
                IS_FP64=input_gates.dtype == torch.float64,
                IS_FP16=input_gates.dtype == torch.float16,
                IS_BF16=input_gates.dtype == torch.bfloat16,
            )

    # ATen intentionally keys both optional bias gradients on input_bias.
    if input_bias is None:
        return grad_input_gates, grad_hidden_gates, grad_hx, None, None

    grad_input_bias = torch.empty(
        (gate_size,), dtype=input_gates.dtype, device=input_gates.device
    )
    grad_hidden_bias = torch.empty(
        (gate_size,), dtype=hidden_gates.dtype, device=hidden_gates.device
    )
    if gate_size != 0:
        with torch_device_fn.device(grad_hy.device):
            _gru_bias_backward_kernel[(gate_size,)](
                grad_input_gates,
                grad_hidden_gates,
                grad_input_bias,
                grad_hidden_bias,
                batch_size,
                gate_size,
                BLOCK_BATCH=256,
                IS_FP64=input_gates.dtype == torch.float64,
            )
    return (
        grad_input_gates,
        grad_hidden_gates,
        grad_hx,
        grad_input_bias,
        grad_hidden_bias,
    )
