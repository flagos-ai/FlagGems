        c_chunk = tl.load(
            C_ptr
            + bid * stride_cb
            + (i + m_offs[:, None]) * stride_cm
            + col_offs[None, :] * stride_cn,
            mask=m_mask[:, None] & col_mask[None, :],
            other=0.0,
        )

