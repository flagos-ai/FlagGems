class _OrmqrFunction(torch.autograd.Function):

    @staticmethod
    def forward(ctx, a, tau, other, left, transpose):
        ctx.save_for_backward(a, tau, other)
        ctx.left, ctx.transpose = (left, transpose)
        return _ormqr_raw(a, tau, other, left=left, transpose=transpose)

    @staticmethod
    def backward(ctx, grad):
        a, tau, other = ctx.saved_tensors
        da, dt, dc = ormqr_backward(a, tau, other, grad, ctx.left, ctx.transpose)
        return (da, dt, dc, None, None)
