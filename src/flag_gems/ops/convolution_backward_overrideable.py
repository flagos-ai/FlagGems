@triton.jit
def bias_grad_kernel(
    out_grad_pointer,
    bias_grad_pointer,
    numel_per_channel,
    out_c,
    BLOCK_SIZE: tl.constexpr,
):
    # One program per output channel. Reduce over the N * H * W elements that
    # belong to that channel. out_grad is assumed contiguous with layout
    # [N, C, H*W] so channel `c` of sample `n` starts at n * C * HW + c * HW.
    pid_c = tl.program_id(0)
    if pid_c >= out_c:
        return

    accum = tl.zeros((BLOCK_SIZE,), dtype=tl.float32)
    for off in range(0, numel_per_channel, BLOCK_SIZE):
        idx = off + tl.arange(0, BLOCK_SIZE)
        mask = idx < numel_per_channel
        ptr = out_grad_pointer + pid_c * numel_per_channel + idx
        vals = tl.load(ptr, mask=mask, other=0.0).to(tl.float32)
        accum += vals
    tl.store(bias_grad_pointer + pid_c, tl.sum(accum, axis=0))


def _compute_bias_grad(out_grad, out_channels, dtype):
    # out_grad: [N, C, H, W]. grad_bias[c] = sum over n, h, w of out_grad[n, c, h, w].
    # Rearrange to [C, N * H * W] so each channel's data is contiguous, then sum.
    n = out_grad.shape[0]
    spatial = out_grad.shape[2] * out_grad.shape[3] if out_grad.ndim == 4 else 1
    permuted = out_grad.permute(1, 0, 2, 3).contiguous()
    numel_per_channel = n * spatial
    bias_grad = torch.empty(out_channels, device=out_grad.device, dtype=torch.float32)
    # 1024 elements per block balances occupancy and per-thread reduction work
    # for the per-channel bias gradient reduction on typical conv output sizes.
    BLOCK_SIZE = 1024
    grid = (out_channels,)
    bias_grad_kernel[grid](
        permuted,
        bias_grad,
        numel_per_channel,
        out_channels,
        BLOCK_SIZE=BLOCK_SIZE,
    )
    return bias_grad.to(dtype)


def _conv2d_grad_input(
    out_grad, weight, input_shape, stride, padding, dilation, groups
):
    # Replicates the grad_input path of conv2d's backward: convolve out_grad with
    # a spatially-flipped, channel-transposed weight (a full-correlation), using
    # the shared conv2d Triton forward kernel.
    device = out_grad.device
    out_channels, weight_c, weight_height, weight_width = weight.shape
    out_c = out_channels // groups
    in_n, in_channels, input_height, input_width = input_shape

    stride_height, stride_width = stride
    padding_height, padding_width = padding
    dilation_height, dilation_width = dilation

    revert_padding_height = dilation_height * (weight_height - 1) - padding_height
    revert_padding_width = dilation_width * (weight_width - 1) - padding_width

    revert_weight = torch.flip(weight.clone(), dims=[2, 3]).contiguous()
    if groups != 1:
        revert_weight = revert_weight.reshape(
            groups, out_c, weight_c, weight_height, weight_width
        )
        revert_weight = revert_weight.transpose(1, 2)
        revert_weight = revert_weight.reshape(
            groups * weight_c, out_c, weight_height, weight_width
        ).contiguous()
    else:
        revert_weight = revert_weight.transpose(0, 1).contiguous()

    new_out_height = out_grad.shape[2] + (stride_height - 1) * (out_grad.shape[2] - 1)
    new_out_width = out_grad.shape[3] + (stride_width - 1) * (out_grad.shape[3] - 1)

    if stride_height > 1 or stride_width > 1:
        new_out = torch.zeros(
            out_grad.shape[0],
            out_grad.shape[1],
            new_out_height,
            new_out_width,
            device=device,
            dtype=out_grad.dtype,
        )
        new_out[:, :, ::stride_height, ::stride_width] = out_grad
    else:
        new_out = out_grad.contiguous()

    input_back = torch.zeros(
        in_n,
        weight_c * groups,
        input_height,
        input_width,
        dtype=torch.float32,
        device=device,
    )

    grid = lambda META: (
        triton.cdiv(
            out_grad.shape[0] * input_height * input_width, META["BLOCK_NI_HO_WO"]
        ),
        triton.cdiv(int(weight_c), META["BLOCK_CO"]),
        groups,
    )
    bias_zero = torch.zeros(groups * weight_c, device=device, dtype=out_grad.dtype)

    _MIN_DOT_K = 16
    bwd_weight_c = out_c
    if bwd_weight_c < _MIN_DOT_K:
        pad_c = _MIN_DOT_K - bwd_weight_c
        revert_weight = torch.nn.functional.pad(revert_weight, (0, 0, 0, 0, 0, pad_c))
        if groups == 1:
            new_out = torch.nn.functional.pad(new_out, (0, 0, 0, 0, 0, pad_c))
        else:
            n_bwd, c_bwd, h_bwd, w_bwd = new_out.shape
            new_out = new_out.reshape(n_bwd, groups, out_c, h_bwd, w_bwd)
            new_out = torch.nn.functional.pad(new_out, (0, 0, 0, 0, 0, pad_c))
            new_out = new_out.reshape(n_bwd, groups * (out_c + pad_c), h_bwd, w_bwd)
        bwd_weight_c = bwd_weight_c + pad_c

    new_out = new_out.contiguous()
    conv2d_forward_kernel[grid](
        new_out,
        revert_weight,
        input_back,
        bias_zero,
        out_grad.shape[0],
        new_out_height,
        new_out_width,
        groups * weight_c,
        input_height,
        input_width,
        *new_out.stride(),
        *revert_weight.stride(),
        *input_back.stride(),
        bwd_weight_c,
        weight_height,
        weight_width,
        1,
        1,
        revert_padding_height,
        revert_padding_width,
        dilation_height,
        dilation_width,
        groups=groups,
    )
    return input_back


def _conv2d_grad_weight(
    out_grad, input, weight_shape, stride, padding, dilation, groups
):
    # grad_weight[co, ci, kh, kw] = sum over (n, ho, wo) of
    #   out_grad[n, co, ho, wo] * input_patch[n, ci, kh, kw, ho, wo].
    # This is an im2col matmul: gather the input's receptive-field patches into
    # columns [N, Cin_g*kH*kW, Ho*Wo], then contract the Ho*Wo (and N) axes
    # against the output gradient [N, Cout_g, Ho*Wo] with a batched matmul and
    # sum the per-sample results over N. This hands the heavy reduction to a
    # tensor-core GEMM instead of the shared conv2d weight-gradient kernel, whose
    # per-output-pixel loop is orders of magnitude slower on large spatial sizes.
    #
    # The patches are materialized with as_strided (a pure view) rather than
    # torch.nn.functional.unfold: unfold would re-dispatch through FlagGems'
    # im2col kernel while this op runs under use_gems(), so keeping the gather as
    # a view sidesteps that and only bmm is delegated to a Triton kernel.
    out_channels, weight_c, weight_height, weight_width = weight_shape
    out_c = out_channels // groups
    in_n = input.shape[0]
    out_height, out_width = out_grad.shape[2], out_grad.shape[3]

    stride_height, stride_width = stride
    padding_height, padding_width = padding
    dilation_height, dilation_width = dilation

    out_grad = out_grad.contiguous()
    # Zero-pad the spatial dims up front so the strided patch gather stays fully
    # in-bounds; explicit padding also lets as_strided express the receptive
    # field with a simple stride pattern.
    if padding_height > 0 or padding_width > 0:
        input = torch.nn.functional.pad(
            input, (padding_width, padding_width, padding_height, padding_height)
        )
    input = input.contiguous()
    n_stride, c_stride, h_stride, w_stride = input.stride()

    def _grad_weight_group(input_g, grad_g):
        # input_g: [N, Cin_g, Hpad, Wpad]; grad_g: [N, Cout_g, Ho, Wo].
        # Patches shape [N, Cin_g, kH, kW, Ho, Wo]: kernel taps advance by the
        # dilation, output positions advance by the stride.
        cols = torch.as_strided(
            input_g,
            (in_n, weight_c, weight_height, weight_width, out_height, out_width),
            (
                n_stride,
                c_stride,
                h_stride * dilation_height,
                w_stride * dilation_width,
                h_stride * stride_height,
                w_stride * stride_width,
            ),
        ).reshape(in_n, weight_c * weight_height * weight_width, out_height * out_width)
        grad_flat = grad_g.reshape(in_n, out_c, out_height * out_width)
        # Contract in fp32. Under use_gems() the batched matmul is served by a
        # Triton kernel that accumulates in the input dtype, so a fp16 contraction
        # over the N * Ho * Wo terms would drift well past the test tolerance;
        # promoting the operands keeps the whole reduction (matmul + sum over N)
        # in fp32.
        # [N, Cout_g, Ho*Wo] @ [N, Ho*Wo, Cin_g*kH*kW] -> [N, Cout_g, Cin_g*kH*kW].
        per_sample = torch.bmm(grad_flat.float(), cols.float().transpose(1, 2))
        return per_sample.sum(0).reshape(out_c, weight_c, weight_height, weight_width)

    if groups == 1:
        weight_back = _grad_weight_group(input, out_grad)
        return weight_back.to(torch.float32)

    # Grouped conv: each group owns a contiguous slice of the input channels and
    # output-gradient channels; accumulate their weight gradients independently.
    parts = []
    for gi in range(groups):
        input_g = input[:, gi * weight_c : (gi + 1) * weight_c]
        grad_g = out_grad[:, gi * out_c : (gi + 1) * out_c]
        parts.append(_grad_weight_group(input_g, grad_g))
    weight_back = torch.cat(parts, dim=0).contiguous()
    return weight_back.to(torch.float32)


def _normalize_pair(value):
    if isinstance(value, (list, tuple)):
        if len(value) == 1:
            return (int(value[0]), int(value[0]))
        return (int(value[0]), int(value[1]))
    return (int(value), int(value))


