# BK x num_warps grid, the round-7 winner set, extended downwards to BK=1,2 so
# the low-parallelism shapes (batch=1, k=16) can raise their program count to
# cdiv(k, BK) instead of being pinned to a handful of CTAs.
_CONFIGS = [
    triton.Config({"BK": bk}, num_warps=nw, num_stages=1)
    for bk in (1, 2, 4, 8, 16, 32, 64)
    for nw in (1, 2, 4)
]


@triton.autotune(configs=_CONFIGS, key=["N", "k", "UPPER", "IS64"])
@triton.jit
def _csb_kernel(
    G,
    F,
    O,
    n,
    k,
    g_rs,
    g_cs,
    f_rs,
    f_cs,
    s0,
    s1,
    s2,
    s3,
    gs0,
    gs1,
    gs2,
    gs3,
    fs0,
    fs1,
    fs2,
    fs3,
    N: tl.constexpr,
    BN: tl.constexpr,
    BK: tl.constexpr,
    UPPER: tl.constexpr,
    IS64: tl.constexpr,
):
    pid = tl.program_id(0)
    ncb = (k + BK - 1) // BK
    b = pid // ncb
    cb = pid % ncb

    # Batch offsets: innermost batch dimension first.  Broadcast dims have
    # stride 0, so every program of a broadcast factor reads the same matrix.
    i0 = b % s0
    b = b // s0
    i1 = b % s1
    b = b // s1
    i2 = b % s2
    b = b // s2
    i3 = b % s3
    goff = i0 * gs0 + i1 * gs1 + i2 * gs2 + i3 * gs3
    foff = i0 * fs0 + i1 * fs1 + i2 * fs2 + i3 * fs3

    rows = tl.arange(0, BN)
    cols = tl.arange(0, BK)
    cidx = cb * BK + cols
    rmask = rows < N
    live = rmask[:, None] & (cidx < k)[None, :]

    gb = G + goff
    fb = F + foff

    acc = tl.load(
        gb + rows[:, None] * g_rs + cidx[None, :] * g_cs, mask=live, other=0.0
    )
    if not IS64:
        acc = acc.to(tl.float32)

    diag = tl.load(fb + rows * (f_rs + f_cs), mask=rmask, other=1.0)
    if not IS64:
        diag = diag.to(tl.float32)
    invd = tl.where(rmask, 1.0 / diag, 0.0)

    if UPPER:
        t1_rs = f_cs
        t1_cs = f_rs
        t2_rs = f_rs
        t2_cs = f_cs
    else:
        t1_rs = f_rs
        t1_cs = f_cs
        t2_rs = f_cs
        t2_cs = f_rs

    w = acc * invd[:, None]

    # Forward substitution: T1 * Y = G, T1 = L (lower) or U^T (upper).
    # The factor-column address does not depend on ``w``, so the stages let the
    # load of a later column overlap the serial update of the current one.
    for s in tl.range(0, N, num_stages=4):
        piv = tl.gather(w, tl.full([1, BK], s, tl.int32), 0)
        col = tl.load(fb + rows * t1_rs + s * t1_cs, mask=(rows > s) & rmask, other=0.0)
        if not IS64:
            col = col.to(tl.float32)
        w = w - (col * invd)[:, None] * piv

    # ``w`` holds the intermediate Y; rescale it for the second sweep.
    w = w * invd[:, None]

    # Backward substitution: T2 * X = Y, T2 = L^T (lower) or U (upper).
    for si in tl.range(0, N, num_stages=4):
        s = N - 1 - si
        piv = tl.gather(w, tl.full([1, BK], s, tl.int32), 0)
        col = tl.load(fb + rows * t2_rs + s * t2_cs, mask=(rows < s) & rmask, other=0.0)
        if not IS64:
            col = col.to(tl.float32)
        w = w - (col * invd)[:, None] * piv

    # ``out`` is freshly allocated and contiguous, so its batch offset is the
    # linear batch index times n*k.
    ob = O + (pid // ncb) * (n * k)
    tl.store(
        ob + rows[:, None] * k + cidx[None, :],
        w.to(O.dtype.element_ty),
        mask=live,
    )


def _batch_layout(g, factor):
    """(size, grad_stride, factor_stride) per batch dim group, innermost first.

    Both batch shapes are right-aligned; a dimension of extent 1 broadcasts
    with stride 0.  Adjacent outermost dims merge when their strides are
    contiguous in both operands, so at most four groups reach the kernel.
    """
    gnd = g.dim() - 2
    fnd = factor.dim() - 2
    nd = max(gnd, fnd)
    gshape = [1] * (nd - gnd) + list(g.shape[:gnd])
    gstride = [0] * (nd - gnd) + list(g.stride()[:gnd])
    fshape = [1] * (nd - fnd) + list(factor.shape[:fnd])
    fstride = [0] * (nd - fnd) + list(factor.stride()[:fnd])

    dims = []
    for d in range(nd - 1, -1, -1):
        gd = int(gshape[d])
        fd = int(fshape[d])
        size = max(gd, fd)
        if (gd != size and gd != 1) or (fd != size and fd != 1):
            raise NotImplementedError(
                "cholesky_solve_backward: incompatible batch shapes"
            )
        dims.append(
            [
                size,
                int(gstride[d]) if gd == size else 0,
                int(fstride[d]) if fd == size else 0,
            ]
        )

    merged = []
    for dim in dims:
        if merged:
            psize, pgs, pfs = merged[-1]
            if dim[1] == pgs * psize and dim[2] == pfs * psize:
                # ``dim`` is the next outer dimension of a contiguous group: the
                # merged group keeps the innermost stride and flat indexing.
                merged[-1] = [psize * dim[0], pgs, pfs]
                continue
        merged.append(list(dim))
    if len(merged) > 4:
        raise NotImplementedError("cholesky_solve_backward: too many batch dims")
    for _ in range(4 - len(merged)):
        merged.append([1, 0, 0])
    return merged


def _launch_shape(n, k, batch):
    """Kept as documentation of the pre-autotune heuristic; unused now."""
    BN = max(16, triton.next_power_of_2(n))
    budget = 4096
    bk = max(1, min(k, triton.next_power_of_2(max(1, budget // BN))))
    target = 78
    while bk > 1 and batch * ((k + bk - 1) // bk) < target:
        bk //= 2
    ncb = -(-k // bk)
    tiles = BN * bk
    if tiles <= 256:
        nwarps = 1
    elif tiles <= 1024:
        nwarps = 2
    elif tiles <= 2048:
        nwarps = 4
    else:
        nwarps = 8
    return BN, bk, ncb, nwarps


