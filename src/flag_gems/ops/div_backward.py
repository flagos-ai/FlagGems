"""First-order gradients of ``torch.div`` (true division).

``torch.ops.aten.div_backward`` does not exist in this Torch build: ATen derives
the gradients through the ``DivBackward0`` autograd node, which evaluates

    grad_self  = div_tensor_self_backward(grad, other, self_st)
               = grad / other
    grad_other = div_tensor_other_backward(grad, self, other)
               = -grad * (self / other / other)

Both formulas are reproduced *bit-exactly* on CUDA.  The exact rounding is
subtle and was derived by differential testing against ATen on the GPU:

* ``float64``: plain ``/`` in fp64 (IEEE round-to-nearest).
* ``float32``: Triton's default ``x / y`` on fp32 lowers to ``fdiv.approx`` on
  NVIDIA, which is *not* correctly rounded, so ``grad / other`` disagrees with
  ATen in ~1/3 of elements.  ``tl.math.div_rn`` (``__nv_fdiv_rn``) matches
  ATen bit-for-bit.
* ``float16`` / ``bfloat16``: ATen runs each elementwise op in fp32 opmath and
  *materialises the intermediate back into the storage dtype* between ops.
  Reproducing that chain (``a / b`` -> cast to fp16 -> ``/ b`` -> cast) is what
  makes the result bit-exact; computing ``(a / b) / b`` entirely in fp32 is off
  by 1-2 ULP in ~30% of the elements.

This module exposes

* ``div_backward(grad_output, self, other)`` -- the explicit Triton entry point
  returning ``(grad_self, grad_other)``, and
* ``DivFunction`` -- an ``autograd.Function`` that pairs the FlagGems ``div``
  forward with this backward kernel, for callers that want the whole autograd
  chain in Triton.

Because there is no standalone ``aten::div_backward`` schema to register a
kernel against, the surface here is the explicit function plus the bridge (same
pattern as ``digamma_backward`` / ``deg2rad_backward``).
"""

import logging

import torch
import triton
import triton.language as tl

from flag_gems.runtime import torch_device_fn

logger = logging.getLogger(__name__)

# 1024 elements per program: this is a pure elementwise read 3 / write 2 kernel,
# so a wide block amortises the launch overhead.  Measured on H20-3e, BLOCK=1024
# beats 256/512 on the large shapes while the small ones stay launch-bound.
_BLOCK = 1024
_NUM_WARPS = 4


@triton.jit
def _div_backward_kernel(
    grad_ptr,
    self_ptr,
    other_ptr,
    grad_self_ptr,
    grad_other_ptr,
    n_elements,
    IS64: tl.constexpr,
    BLOCK: tl.constexpr,
):
    pid = tl.program_id(axis=0)
    offsets = pid * BLOCK + tl.arange(0, BLOCK)
    mask = offsets < n_elements

    grad = tl.load(grad_ptr + offsets, mask=mask)
    a = tl.load(self_ptr + offsets, mask=mask)
    b = tl.load(other_ptr + offsets, mask=mask)

    if IS64:
        # fp64 division is already correctly rounded, so the plain operator is
        # bit-identical to ATen's div_tensor_{self,other}_backward.
        grad_self = grad / b
        grad_other = -grad * ((a / b) / b)
    else:
        # fp32 and lower: force IEEE round-to-nearest division; Triton's `/` on
        # fp32 compiles to fdiv.approx, which differs from ATen.
        dt = grad_ptr.dtype.element_ty
        g32 = grad.to(tl.float32)
        a32 = a.to(tl.float32)
        b32 = b.to(tl.float32)

        grad_self = tl.math.div_rn(g32, b32).to(dt)
        # ATen materialises each elementwise result in the storage dtype before
        # feeding it to the next op, so round the intermediate back down.
        ab = tl.math.div_rn(a32, b32).to(dt)
        ab_over_b = tl.math.div_rn(ab.to(tl.float32), b32).to(dt)
        grad_other = (-grad * ab_over_b).to(dt)

    tl.store(grad_self_ptr + offsets, grad_self, mask=mask)
    tl.store(grad_other_ptr + offsets, grad_other, mask=mask)


def _div_backward_impl(grad_output: torch.Tensor, a: torch.Tensor, b: torch.Tensor):
    """Equal-shape contiguous Triton path."""
    grad_contig = grad_output.contiguous()
    a_contig = a.contiguous()
    b_contig = b.contiguous()

    grad_self = torch.empty(a.shape, dtype=a.dtype, device=a.device)
    grad_other = torch.empty(b.shape, dtype=b.dtype, device=b.device)

    n_elements = a_contig.numel()
    if n_elements == 0:
        return grad_self, grad_other

