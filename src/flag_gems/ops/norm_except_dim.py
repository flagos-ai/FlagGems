    c = tl.program_id(1)
    start = c * chunk
    end = tl.minimum(start + chunk, inner)
    base = i * inner
    acc = tl.zeros([BLOCK], tl.float32)
    for q0 in range(start, end, BLOCK):
        q = q0 + tl.arange(0, BLOCK)
        mask = q < end
