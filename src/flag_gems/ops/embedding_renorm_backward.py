@triton.jit
def _p2(base, e):
    # base ** e via exp2/log2; the caller guards base == 0 (log2(0) = -inf
    # would poison the multiply with NaN before exp2 clamps it back).
    return tl.exp2(e * tl.log2(base))


@triton.jit
def _p2_safe(base, e):
    # base ** e with base == 0 defined as 0 for e > 0, 1 for e == 0.
    is_zero = base == 0.0
    safe = tl.where(is_zero, 1.0, base)
    return tl.where(is_zero, 0.0, tl.exp2(e * tl.log2(safe)))


@libentry()
@triton.jit
def _renorm_bwd_row(
    weight_ptr,
    grad_ptr,
    out_ptr,
    idx_ptr,
    D,
    max_norm,
    p,
    BLOCK_D: tl.constexpr,
    IS_P2: tl.constexpr,
    IS_FP64: tl.constexpr,
):
    pid = tl.program_id(0)
    row = tl.load(idx_ptr + pid)
    offs = tl.arange(0, BLOCK_D)
    m = offs < D
    base = row * D

    x = tl.load(weight_ptr + base + offs, mask=m, other=0.0)
    g = tl.load(grad_ptr + base + offs, mask=m, other=0.0)

    if IS_FP64:
        fdt: tl.constexpr = tl.float64
        xw = x
        gw = g
    else:
        fdt: tl.constexpr = tl.float32
        xw = x.to(tl.float32)
        gw = g.to(tl.float32)

    one = tl.zeros([], dtype=fdt) + 1.0
    zero = tl.zeros([], dtype=fdt)

    if IS_P2:
        n = tl.sqrt(tl.sum(xw * xw, axis=0))
    else:
        n = _p2_safe(tl.sum(_p2_safe(tl.abs(xw), p), axis=0), 1.0 / p)

    denom = n + 1e-7
    rescaled = n > max_norm
    c = tl.where(rescaled, max_norm / denom, one)

    if IS_P2:
        coef = tl.where(rescaled, (max_norm / (denom * denom)) * (one / n), zero)
        t = tl.sum(gw * xw, axis=0)
        grad = c * gw - coef * t * xw
    else:
        coef = tl.where(
            rescaled, (max_norm / (denom * denom)) * _p2_safe(n, 1.0 - p), zero
        )
        sgn = tl.where(xw > 0, one, tl.where(xw < 0, -one, zero))
        apm = _p2_safe(tl.abs(xw), p - 1.0)
        t = tl.sum(gw * apm * sgn, axis=0)
        grad = c * gw - coef * t * apm * sgn

    tl.store(out_ptr + base + offs, grad.to(g.dtype), mask=m)


@libentry()
@triton.jit
def _renorm_bwd_fused(
    weight_ptr,
    grad_ptr,
    out_ptr,
    flags_ptr,
    V,
    D,
    max_norm,
    p,
    BLOCK_ROWS: tl.constexpr,
    BLOCK_D: tl.constexpr,
    IS_P2: tl.constexpr,
    IS_FP64: tl.constexpr,
):
    pid = tl.program_id(0)
    rows = pid * BLOCK_ROWS + tl.arange(0, BLOCK_ROWS)
    cols = tl.arange(0, BLOCK_D)
    rmask = rows < V
    cmask = cols < D
    m2 = rmask[:, None] & cmask[None, :]
    off = rows[:, None] * D + cols[None, :]

    g = tl.load(grad_ptr + off, mask=m2, other=0.0)
    fl = tl.load(flags_ptr + rows, mask=rmask, other=0)
    sel = (fl != 0)[:, None] & m2

    x = tl.load(weight_ptr + off, mask=sel, other=0.0)

    if IS_FP64:
        fdt: tl.constexpr = tl.float64
        xw = x
        gw = g
    else:
        fdt: tl.constexpr = tl.float32
        xw = x.to(tl.float32)
        gw = g.to(tl.float32)

    one = tl.zeros([], dtype=fdt) + 1.0
    zero = tl.zeros([], dtype=fdt)

    if IS_P2:
        n = tl.sqrt(tl.sum(xw * xw, axis=1))
    else:
        n = _p2_safe(tl.sum(_p2_safe(tl.abs(xw), p), axis=1), 1.0 / p)

    n_safe = tl.maximum(n, 1.0e-30)
    denom = n + 1e-7
    rescaled = (n > max_norm)[:, None]
    c = tl.where(rescaled, max_norm / denom[:, None], one)

    if IS_P2:
        coef = tl.where(
            rescaled,
            (max_norm / (denom * denom))[:, None] * (one / n_safe)[:, None],
            zero,
        )
        t = tl.sum(gw * xw, axis=1)
        grad = c * gw - coef * t[:, None] * xw
    else:
        coef = tl.where(
            rescaled,
            (max_norm / (denom * denom))[:, None] * _p2_safe(n_safe, 1.0 - p)[:, None],
            zero,
        )
        sgn = tl.where(xw > 0, one, tl.where(xw < 0, -one, zero))
        apm = _p2_safe(tl.abs(xw), p - 1.0)
        t = tl.sum(gw * apm * sgn, axis=1)
        grad = c * gw - coef * t[:, None] * apm * sgn

    res = tl.where(sel, grad.to(g.dtype), g)
    tl.store(out_ptr + off, res, mask=m2)


