def _blocks(c_out, c_in):
    """Return (BLOCK_N, BLOCK_K) rounded to powers of two and clamped to [16, 64]."""
    block_k = max(16, min(64, triton.next_power_of_2(int(c_in))))
    block_n = max(16, min(64, triton.next_power_of_2(int(c_out))))
    return block_n, block_k


def _fwd_tile(m, c_out, is_fp32):
    """Pick (BLOCK_M, num_warps, num_stages) for the tap-loop forward kernel.

    Profiler evidence (round-6 analysis) shows these kernels are pinned at
    ~25% occupancy by a 128-register allocation, so register pressure, not
    DRAM, sets the tile. Measured on the benchmark shapes with an otherwise
    identical kernel:
      * fp32 with C_out >= 64: BLOCK_M 32 beats 64 by 1.5-1.7x (0.115->0.076,
        0.100->0.060, 0.125->0.075 ms) while C_out < 64 prefers 64 (32 costs
        0.67-0.91x there), so the split follows C_out.
      * fp16/bf16 with M >= 65536: BLOCK_M 128 beats 64 by 1.14x; smaller M
        keeps 64.
      * Two pipeline stages beat the default three on every tap-loop cell.
    """
    if is_fp32:
        block_m = 32 if c_out >= 64 else 64
        return block_m, 8, 2
    block_m = 128 if m >= 65536 else 64
    return block_m, 4, 2


def _launch_forward(x, weight, bias, out, dims):
    k_h, k_w, s_h, s_w, p_h, p_w, h_out, w_out = dims
    n, c_in, h, w = x.shape
    c_out = weight.shape[0]
    m = n * h_out * w_out

    x_sn, x_sc, x_sh, x_sw = x.stride()
    wp = weight.permute(2, 3, 1, 0)
    w_skh, w_skw, w_sk, w_sn = wp.stride()
    b_sn = bias.stride(0) if bias is not None else 0
    b_arg = bias if bias is not None else x
    o_sn, o_sc, o_sh, o_sw = out.stride()
    has_bias = bias is not None
    is_f64 = x.dtype == torch.float64

    if is_f64:
        grid = (triton.cdiv(m, 16), triton.cdiv(c_out, 16))
        _conv2d_fwd_fma_kernel[grid](
            x,
            wp,
            b_arg,
            out,
            n,
            c_in,
            c_out,
            h,
            w,
            h_out,
            w_out,
            m,
            x_sn,
            x_sc,
            x_sh,
            x_sw,
            w_skh,
            w_skw,
            w_sk,
            w_sn,
            b_sn,
            o_sn,
            o_sc,
            o_sh,
            o_sw,
            K_H=k_h,
            K_W=k_w,
            SH=s_h,
            SW=s_w,
            PH=p_h,
            PW=p_w,
            HAS_BIAS=has_bias,
            IS_F64=True,
            BLOCK_M=16,
            BLOCK_N=16,
            num_warps=4,
        )
        return out

    block_n, block_k = _blocks(c_out, c_in)
    is_fp32 = x.dtype == torch.float32
    one_by_one = (
        k_h == 1 and k_w == 1 and s_h == 1 and s_w == 1 and p_h == 0 and p_w == 0
    )
    # The (kH,kW,ci,co) view puts co at stride C_in*kH*kW, so the (BLOCK_K,
    # BLOCK_N) weight tile would end on a huge-stride axis and every element
    # would land in its own 32-byte sector. A dense copy of the same permutation
    # makes co unit stride; measured against an otherwise identical kernel this
    # was 0.538 -> 0.163 ms (fp32 1x1 128x128), 1.065 -> 0.404 ms (fp32 3x3
    # 56x56), 0.536 -> 0.402 ms (fp16 3x3 128x128) and 0.0303 -> 0.0244 ms
    # (fp16 3x3 stride-2 64x64), at a copy cost of 0.002-0.020 ms. It must run
    # before the 1x1 dispatch too: a 1x1 weight is already K-contiguous, and
    # skipping the copy there leaves the specialised kernel reading co at
    # stride C_in (0.543 vs 0.148 ms on fp32 1x1 128x128).
    wp = wp.contiguous()
    w_skh, w_skw, w_sk, w_sn = wp.stride()
    if one_by_one:
        # Pure GEMM: no tap loop and no padding masks. Measured best with
        # BLOCK_M=128 for fp32 (0.131 vs 0.157 ms at M=64 on 32x64x128x128);
        # the 1x1 kernel has no tap loop to amortise a small tile.
        block_m = 128 if is_fp32 else 64
        grid = (triton.cdiv(m, block_m), triton.cdiv(c_out, block_n))
        _conv2d_fwd_1x1_kernel[grid](
            x,
            wp,
            b_arg,
            out,
            n,
            c_in,
            c_out,
            h,
            w,
            m,
            x_sn,
            x_sc,
            x_sh,
            x_sw,
            w_sn,
            w_sk,
            b_sn,
            o_sn,
            o_sc,
            o_sh,
            o_sw,
            HAS_BIAS=has_bias,
            PREC_IEEE=is_fp32,
            BLOCK_M=block_m,
            BLOCK_N=block_n,
            BLOCK_K=block_k,
            num_warps=4,
            num_stages=2,
        )
        return out
    block_m, warps, stages = _fwd_tile(m, c_out, is_fp32)
    grid = (triton.cdiv(m, block_m), triton.cdiv(c_out, block_n))
    _conv2d_fwd_dot_kernel[grid](
        x,
        wp,
        b_arg,
        out,
        n,
        c_in,
        c_out,
        h,
        w,
        h_out,
        w_out,
        m,
        x_sn,
        x_sc,
        x_sh,
        x_sw,
        w_skh,
        w_skw,
        w_sk,
        w_sn,
        b_sn,
        o_sn,
        o_sc,
        o_sh,
        o_sw,
        K_H=k_h,
        K_W=k_w,
        SH=s_h,
        SW=s_w,
        PH=p_h,
        PW=p_w,
        HAS_BIAS=has_bias,
        PREC_IEEE=is_fp32,
        BLOCK_M=block_m,
        BLOCK_N=block_n,
        BLOCK_K=block_k,
        num_warps=warps,
        num_stages=stages,
    )
    return out


def _forward(x, weight, bias, dims, out=None):
    k_h, k_w, s_h, s_w, p_h, p_w, h_out, w_out = dims
    n = x.shape[0]
    c_out = weight.shape[0]
    if out is None:
        out = torch.empty((n, c_out, h_out, w_out), device=x.device, dtype=x.dtype)
    return _launch_forward(x, weight, bias, out, dims)


def _backward(x, weight, bias, grad_out, dims, needs):
    k_h, k_w, s_h, s_w, p_h, p_w, h_out, w_out = dims
    n, c_in, h, w = x.shape
    c_out = weight.shape[0]
    is_f64 = x.dtype == torch.float64
    go = grad_out
    if not go.is_contiguous():
        go = go.contiguous()
    go_sn, go_sc, go_sh, go_sw = go.stride()

    grad_x = grad_w = grad_b = None

    if needs[0]:
        grad_x = torch.empty_like(x)
        total = n * c_in * h * w
        x_sn, x_sc, x_sh, x_sw = x.stride()
        w_sn, w_sc, w_sh, w_sw = weight.stride()
        gi_sn, gi_sc, gi_sh, gi_sw = grad_x.stride()
        block = 256
        grid = (triton.cdiv(total, block),)
        _conv2d_bwd_input_kernel[grid](
            go,
            weight,
            grad_x,
            n,
            c_in,
            c_out,
            h,
            w,
            h_out,
            w_out,
            go_sn,
            go_sc,
            go_sh,
            go_sw,
            w_sn,
            w_sc,
            w_sh,
            w_sw,
            gi_sn,
            gi_sc,
            gi_sh,
            gi_sw,
            total,
            K_H=k_h,
            K_W=k_w,
            SH=s_h,
            SW=s_w,
            PH=p_h,
            PW=p_w,
            IS_F64=is_f64,
            BLOCK=block,
            num_warps=4,
        )

    if needs[1]:
        grad_w = torch.empty_like(weight)
        x_sn, x_sc, x_sh, x_sw = x.stride()
        gw_sn, gw_sc, gw_sh, gw_sw = grad_w.stride()
        total = n * h_out * w_out
        block = 128
        grid = (c_out, c_in)
        _conv2d_bwd_weight_kernel[grid](
            go,
            x,
            grad_w,
            n,
            c_in,
            c_out,
            h,
            w,
            h_out,
            w_out,
            go_sn,
            go_sc,
            go_sh,
            go_sw,
            x_sn,
            x_sc,
            x_sh,
            x_sw,
            gw_sn,
            gw_sc,
            gw_sh,
            gw_sw,
            total,
            K_H=k_h,
            K_W=k_w,
            SH=s_h,
            SW=s_w,
            PH=p_h,
            PW=p_w,
            IS_F64=is_f64,
            BLOCK=block,
            num_warps=4,
        )

    if needs[2] and bias is not None:
        grad_b = torch.empty_like(bias)
        total = n * h_out * w_out
        block = 256
        grid = (c_out,)
        _conv2d_bwd_bias_kernel[grid](
            go,
            grad_b,
            n,
            c_out,
            h_out,
            w_out,
            go_sn,
            go_sc,
            go_sh,
            go_sw,
            total,
            IS_F64=is_f64,
            BLOCK=block,
            num_warps=4,
        )

    return grad_x, grad_w, grad_b


class _SlowConv2dForward(torch.autograd.Function):
    @staticmethod
    def forward(ctx, x, weight, bias, dims):
        out = _forward(x, weight, bias, dims)
        ctx.dims = dims
        ctx.has_bias = bias is not None
        ctx.needs = (
            ctx.needs_input_grad[0],
            ctx.needs_input_grad[1],
            ctx.needs_input_grad[2],
        )
        ctx.save_for_backward(x, weight, bias)
        return out

    @staticmethod
    def backward(ctx, grad_out):
        x, weight, bias = ctx.saved_tensors
        if grad_out is None:
            return None, None, None, None
        gx, gw, gb = _backward(x, weight, bias, grad_out, ctx.dims, ctx.needs)
        return gx, gw, gb, None


def _slow_conv2d_forward(
    self, weight, kernel_size, bias=None, stride=None, padding=None, output=None
):
    """Compute ``_slow_conv2d_forward`` for the FlagGems pytest contract."""
    logger.debug("GEMS _SLOW_CONV2D_FORWARD")
    x = self
    # ATen's ``_slow_conv2d_forward`` schema makes stride and padding required
    # positional arguments; this wrapper accepts ``None`` as well and resolves
    # it to the values ATen's convolution path uses when they are omitted.
    if stride is None:
        stride = (1, 1)
    if padding is None:
        padding = (0, 0)
    dims = _validate(x, weight, kernel_size, bias, stride, padding, output)

    if output is not None:
        return _forward(x, weight, bias, dims, out=output)

    needs_grad = (
        x.requires_grad
        or weight.requires_grad
        or (bias is not None and bias.requires_grad)
    )
    if needs_grad:
        return _SlowConv2dForward.apply(x, weight, bias, dims)
    return _forward(x, weight, bias, dims)
