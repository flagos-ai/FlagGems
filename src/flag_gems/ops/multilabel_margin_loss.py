def _strides2d(t):
    """(row_stride, class_stride) for a rank<=2 tensor viewed as (rows, classes)."""
    if t.dim() == 0:
        return 1, 1
    if t.dim() == 1:
        return 0, t.stride(0)
    return t.stride(0), t.stride(1)


def _row_col(t):
    if t.dim() == 0:
        return 1, 1
    if t.dim() == 1:
        return 1, int(t.shape[0])
    return int(t.shape[0]), int(t.shape[1])


def _result_shape(rows, reduction, rank_leq_1):
    if rows == 0:
        return (0,)
    if reduction == 0 and not rank_leq_1:
        return (rows,)
    return ()


def _row_losses(self, target, dest):
    """Write the per-row losses (already divided by C) into ``dest``.

    The class axis is split across ``n_ct`` programs per row, so the benchmark's
    few-row shapes still cover the whole device; when a row spans a single class
    tile the 1/C fold is done inside the row kernel and no partial buffer or
    second launch is needed.
    """
    rows, n_classes = _row_col(self)
    acc64 = self.dtype == torch.float64
    acc_dtype = torch.float64 if acc64 else torch.float32
    srs, scs = _strides2d(self)
    trs, tcs = _strides2d(target)
    n_ct = -(-n_classes // _BLOCK_C)
    with torch_device_fn.device(self.device):
        if n_ct == 1:
            _row_loss_kernel[(rows, 1)](
                self,
                target,
                dest,
                rows,
                n_classes,
                1,
                1,
                srs,
                scs,
                trs,
                tcs,
                ACC64=acc64,
                FINAL=True,
                BLOCK_T=_BLOCK_T,
                BLOCK_C=_BLOCK_C,
                BLOCK_J=_BLOCK_J,
            )
            return
        part = torch.empty((rows, n_ct), dtype=acc_dtype, device=self.device)
        _row_loss_kernel[(rows, n_ct)](
            self,
            target,
            part,
            rows,
            n_classes,
            n_ct,
            n_ct,
            srs,
            scs,
            trs,
            tcs,
            ACC64=acc64,
            FINAL=False,
            BLOCK_T=_BLOCK_T,
            BLOCK_C=_BLOCK_C,
            BLOCK_J=_BLOCK_J,
        )
        _finish_kernel[(rows,)](
            part,
            dest,
            n_classes,
            n_ct,
            ACC64=acc64,
            BLOCK=_FINISH_BLOCK,
        )


def _launch_forward(self, target, reduction, dest):
    """Run the forward kernels and write the requested reduction into ``dest``.

    Reduction 0 (a (rows,) result) whose class axis fits one capped tile is
    computed by a single launch covering the whole axis, which saves the partial
    buffer and the second launch.  The cap keeps the BLOCK_J x BLOCK_C pair tile
    inside the register budget (it is tighter for fp64, whose elements are twice
    as wide); wider rows -- and every scalar reduction -- take the split grid.
    """
    rows, n_classes = _row_col(self)
    acc64 = self.dtype == torch.float64
    acc_dtype = torch.float64 if acc64 else torch.float32
    srs, scs = _strides2d(self)
    trs, tcs = _strides2d(target)
    block_cap = _R0_SINGLE_TILE_BLOCK_CAP_FP64 if acc64 else _R0_SINGLE_TILE_BLOCK_CAP
    single_tile_max = min(_R0_SINGLE_TILE_MAX, block_cap)
    if reduction == 0 and not (self.dim() <= 1) and n_classes <= single_tile_max:
        with torch_device_fn.device(self.device):
            _row_loss_kernel[(rows, 1)](
                self,
                target,
                dest,
                rows,
                n_classes,
                1,
                1,
                srs,
                scs,
                trs,
                tcs,
                ACC64=acc64,
                FINAL=True,
                BLOCK_T=_BLOCK_T,
                BLOCK_C=triton.next_power_of_2(n_classes),
                BLOCK_J=_BLOCK_J,
            )
        return
    if reduction == 0 and not (self.dim() <= 1):
        _row_losses(self, target, dest)
        return
    with torch_device_fn.device(self.device):
        row_buf = torch.empty(rows, dtype=acc_dtype, device=self.device)
        _row_losses(self, target, row_buf)
        _reduce_rows_kernel[(1,)](
            row_buf,
            dest,
            rows,
            MEAN=(reduction == 1),
            ACC64=acc64,
            BLOCK=_REDUCE_BLOCK,
        )


def _launch_backward(self, target, reduction, grad_out):
    """Gradient of the loss w.r.t. ``self``, produced by the kernels above.

    ``g`` is allocated in the input dtype and each class tile stores its slice
    exactly once, so the gradient needs no accumulator buffer, no atomics and no
    host-side cast.  ``grad_out`` is read through its own stride rather than
    being made contiguous first, so a strided upstream gradient costs no copy.
    """
    rows, n_classes = _row_col(self)
    acc64 = self.dtype == torch.float64
    device = self.device
    srs, scs = _strides2d(self)
    trs, tcs = _strides2d(target)
    # Passed as an integer so the kernel can build the scale in its own
    # accumulator precision; a host float would arrive as fp32.
    n_mean = rows if reduction == 1 else 1
    # A 0-dim upstream gradient (reductions 1 and 2, and rank<=1 at reduction 0)
    # is read by every row, which stride 0 expresses directly; a per-row one is
    # read at its own stride, so a strided view costs no copy.
    gos = grad_out.stride(0) if grad_out.dim() == 1 else 0
    with torch_device_fn.device(device):
        mult = torch.empty((rows, n_classes), dtype=torch.int32, device=device)
        _membership_kernel[(rows,)](
            target,
            mult,
            n_classes,
            trs,
            tcs,
            BLOCK_T=_BLOCK_T,
            BLOCK_C=_BLOCK_C,
        )
        g = torch.empty((rows, n_classes), dtype=self.dtype, device=device)
        _grad_kernel[(rows, triton.cdiv(n_classes, _GRAD_BLOCK_D))](
            self,
            mult,
            g,
            grad_out,
            n_classes,
            srs,
            scs,
            gos,
            n_mean,
            ACC64=acc64,
            BLOCK_D=_GRAD_BLOCK_D,
            BLOCK_K=_GRAD_BLOCK_K,
        )
    return g.reshape(self.shape)


class _MMLFunction(torch.autograd.Function):
    """Autograd wrapper so the allocating overload stays differentiable."""

    @staticmethod
    def forward(ctx, x, target, reduction):
        rows, _ = _row_col(x)
        result = torch.empty(
            _result_shape(rows, reduction, x.dim() <= 1), dtype=x.dtype, device=x.device
        )
        _launch_forward(x, target, reduction, result)
        ctx.reduction = reduction
        ctx.save_for_backward(x, target)
        return result

    @staticmethod
    def backward(ctx, grad_out):
        x, target = ctx.saved_tensors
        return _launch_backward(x, target, ctx.reduction, grad_out), None, None


def multilabel_margin_loss(self, target, reduction=1, out=None):
    logger.debug("GEMS MULTILABEL_MARGIN_LOSS")
    if isinstance(reduction, bool) or not isinstance(reduction, int):
        raise RuntimeError(
            "multilabel_margin_loss: reduction must be an integer (0, 1 or 2)"
        )
    if reduction not in (0, 1, 2):
        # The native kernel maps every other integer to "sum".
        reduction = 2

    ndim = self.dim()
    if ndim > 2:
        raise RuntimeError("multilabel_margin_loss: input must be scalar, 1D or 2D")
    if tuple(self.shape) != tuple(target.shape):
        raise RuntimeError(
            "multilabel_margin_loss: target shape must exactly match input shape"
        )
    if self.device != target.device:
        raise RuntimeError(
            "multilabel_margin_loss: input and target must be on the same device"
        )
    if target.dtype != torch.int64:
        raise RuntimeError("multilabel_margin_loss: target must have dtype int64")
    if self.dtype not in _FLOAT_DTYPES:
        raise RuntimeError(
            "multilabel_margin_loss: input must have a floating point dtype"
        )

    rows, n_classes = _row_col(self)
    if n_classes == 0:
        raise RuntimeError("multilabel_margin_loss: class dimension must be non-empty")

    rank_leq_1 = ndim <= 1
    shape = _result_shape(rows, reduction, rank_leq_1)

    if out is not None:
        if out.device != self.device:
            raise RuntimeError(
                "multilabel_margin_loss: out must be on the same device as input"
            )
        if out.dtype not in _FLOAT_DTYPES:
            raise RuntimeError(
                "multilabel_margin_loss: out must have a floating point dtype"
            )
        if tuple(out.shape) != tuple(shape):
            out.resize_(shape)
        if rows != 0:
            # The native overload writes the result contiguously from the
            # buffer's base regardless of the buffer's strides (probed on CUDA:
            # a (8,) stride-2 out at reduction 0 received all eight per-row
            # values in consecutive storage slots, so its logical view read back
            # [r0, r2, r4, r6, fill, fill, fill, fill]).  Writing through the
            # kernel's flat indexing reproduces that, so no stride handling is
            # added here; see the note in the test module.
            _launch_forward(self, target, reduction, out)
        return out

    if rows == 0:
        return torch.empty((0,), dtype=self.dtype, device=self.device)

    if self.requires_grad and torch.is_grad_enabled():
        return _MMLFunction.apply(self, target, reduction)

    result = torch.empty(shape, dtype=self.dtype, device=self.device)
    _launch_forward(self, target, reduction, result)
    return result
