@triton.jit
def _finish_kernel(
    part_ptr,
    out_ptr,
    C,
    n_ct,
    ACC64: tl.constexpr,
    BLOCK: tl.constexpr,
):
    """Fold the per-class-tile partials of one row and apply the 1/C scale."""
    row = tl.program_id(0)
    if ACC64:
        acc = tl.zeros([BLOCK], dtype=tl.float64)
    else:
        acc = tl.zeros([BLOCK], dtype=tl.float32)
    for c0 in range(0, n_ct, BLOCK):
        offs = c0 + tl.arange(0, BLOCK)
        v = tl.load(part_ptr + row * n_ct + offs, mask=offs < n_ct, other=0.0)
        acc += v
    tl.store(out_ptr + row, (tl.sum(acc, axis=0) / C).to(out_ptr.dtype.element_ty))


@libentry()
@triton.jit
def _reduce_rows_kernel(
    rows_ptr,
    out_ptr,
    N,
    MEAN: tl.constexpr,
    ACC64: tl.constexpr,
    BLOCK: tl.constexpr,
):
    """Vectorised tree reduction of the per-row losses into one scalar."""
    if ACC64:
        acc = tl.zeros([BLOCK], dtype=tl.float64)
    else:
        acc = tl.zeros([BLOCK], dtype=tl.float32)
    for r0 in range(0, N, BLOCK):
        offs = r0 + tl.arange(0, BLOCK)
        v = tl.load(rows_ptr + offs, mask=offs < N, other=0.0)
        acc += v
    total = tl.sum(acc, axis=0)
    if MEAN:
        total = total / N
    tl.store(out_ptr, total.to(out_ptr.dtype.element_ty))


