import triton
import triton.language as tl

from flag_gems.ops.cudnn_convolution import cudnn_convolution

logger = logging.getLogger(__name__)

# The fused cuDNN operation is
#     out = relu(conv(input, weight) + bias + alpha * z)
# (see raw_cudnn_convolution_add_relu_fallback_out in ATen, whose composition is
# exactly `reshape_bias(input.dim(), bias) + alpha * z` accumulated onto the
# convolution and then relu'd). The convolution itself is the Triton
# implicit-GEMM / direct-multiply-accumulate dispatch in
# flag_gems.cudnn_convolution; the elementwise epilogue is fused into one
# further Triton pass, so the operator is Triton end to end.
#
# The epilogue is a hand-written flat kernel rather than a pointwise_dynamic
# one. With a (1, C, 1, ..., 1) bias operand pointwise_dynamic cannot collapse
# the task to one dimension and falls back to its strided broadcast path, which
# measured ~3x the latency of the flat kernel on the same (16, 32, 32, 32) fp16
# tensor (0.056ms vs 0.018ms). All three inputs here are dense and share the
# convolution's shape, so a single flat index is an exact address for every one
# of them; the bias index is derived from that flat index arithmetically.


# One program handles BLOCK contiguous elements of the flattened output. 1024
# balances occupancy against the per-program index arithmetic; the measured
# spread over 512/1024/2048/4096 was under 5% on the shapes above, so this is a
# representative pick rather than a tuned optimum.
_EPILOGUE_BLOCK = 1024


@triton.jit
def _conv_add_relu_epilogue(
    conv_ptr,
    z_ptr,
    bias_ptr,
    out_ptr,
    alpha,
    total,
    plane,
    C,
    HAS_BIAS: tl.constexpr,
    BLOCK: tl.constexpr,
):
    # ``plane`` is the number of output elements per (batch, channel) slice --
    # the product of the spatial extents -- so the channel of a flat index is
    # (index // plane) % C for the NCHW / NCDHW layout the convolution returns.
    offs = tl.program_id(0) * BLOCK + tl.arange(0, BLOCK)
    mask = offs < total
    acc = tl.load(conv_ptr + offs, mask=mask, other=0.0).to(tl.float32)
    acc += alpha * tl.load(z_ptr + offs, mask=mask, other=0.0).to(tl.float32)
    if HAS_BIAS:
        acc += tl.load(bias_ptr + (offs // plane) % C, mask=mask, other=0.0).to(
            tl.float32
        )
    # ReLU as aten's is `max(x, 0)`, which propagates a NaN rather than dropping
    # it to 0; Triton's tl.maximum defaults to the non-propagating variant.
    acc = tl.maximum(acc, 0.0, propagate_nan=tl.PropagateNan.ALL)
    tl.store(out_ptr + offs, acc.to(out_ptr.dtype.element_ty), mask=mask)


