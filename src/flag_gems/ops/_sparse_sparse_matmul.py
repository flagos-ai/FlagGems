"""Sparse x sparse matrix multiplication (SpGEMM).

``aten::_sparse_sparse_matmul(self, other)`` multiplies two 2-D sparse
tensors.  The aten CUDA backend
(``aten/src/ATen/native/sparse/cuda/SparseMatMul.cu``,
``sparse_sparse_matmul_cuda``) only dispatches for **COO** operands - CSR/CSC
raise ``NotImplementedError`` - and internally converts both operands to CSR
before running cuSPARSE SpGEMM.  The result is a coalesced row-major sorted
sparse **COO** tensor whose support set is the deterministic intersection
pattern of the two operand structures: every (i, j) with at least one k such
that both (i, k) and (k, j) are stored becomes a stored entry, and structural
zeros are preserved (``[[1, 1]] @ [[1], [-1]]`` keeps one stored entry with
value 0).

This implementation follows the same contract with a five-phase Triton
pipeline:

1. ``_sspm_hist``/``_sspm_scan``/``_sspm_scatter`` build the CSR grouping of
   the second operand (histogram + exclusive scan + scatter); the histogram
   doubles as the scatter cursor and self-zeroes.
2. ``_sspm_accum`` walks one program per A entry (i, k) and accumulates
   ``a_val * b_val`` into dense (M, N) count/value buffers with atomics
   (fp32 accumulate for fp16/bf16/fp32, fp64 for fp64).
3. ``_sspm_rowcount``/``_sspm_scan`` turn the dense flags into the exact
   per-row counts and the row-major output offsets.
4. ``_sspm_emit`` gathers the stored (row, col, val) triples in row-major
   order, preserving structural zeros, and writes the output metadata.

The wrapper mirrors the aten argument checks (2-D, no dense dims, matching
shape/dtype, floating dtype) and coalesces both operands, so the output
support set and values match the aten kernel exactly (the low-precision
accumulate rounding of fp16/bf16 is part of the contract and covered by the
test tolerances).
"""

