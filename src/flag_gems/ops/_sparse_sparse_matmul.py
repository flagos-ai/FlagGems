def _sspm_coo_heads(keys, perm, heads, nnz, BLOCK: tl.constexpr):
    i = tl.program_id(0) * BLOCK + tl.arange(0, BLOCK)
    mask = i < nnz
    cur = tl.load(perm + i, mask=mask, other=0)
