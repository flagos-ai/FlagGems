"""Single-step LSTM cell (``aten::lstm_cell``) in Triton.

    gates     = linear(input, w_ih, b_ih) + linear(hx[0], w_hh, b_hh)
    i, f, g, o = gates.chunk(4, dim=1)
    cy        = sigmoid(f) * hx[1] + sigmoid(i) * tanh(g)
    hy        = sigmoid(o) * tanh(cy)

ATen runs the two ``linear`` calls and then ``_thnn_fused_lstm_cell``, so both
``(batch, 4 * hidden)`` gate matrices plus a workspace tensor are materialized
in global memory.  Here one program computes all eight gate slices for its
``(BLOCK_B, BLOCK_H)`` output tile in registers: the four slices of a linear
share the same activation operand tile, so each reduced GEMM reads ``input`` /
``hx[0]`` once and only the weight tiles differ.  Only ``hy`` and ``cy`` are
written, and the backward workspace is never built.

The arithmetic reproduces ATen's rounding boundaries rather than being more
accurate than ATen, which is what the accuracy tests compare against.  ATen
calls ``matmul`` without the bias and hands both bias vectors to the fused
kernel, so each GEMM rounds to the input dtype on its own and the biases are
then added in accumulator precision with no rounding in between.  The gate
chain runs in that same precision and only the two stores round.  Accumulation
is fp32, or fp64 for double input, so for fp32 and fp64 the whole path is exact
in the input precision.
"""

