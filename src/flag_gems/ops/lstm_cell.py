        acc_f = tl.dot(x, wf, acc_f, input_precision="ieee", out_dtype=ACC_DTYPE)
        acc_g = tl.dot(x, wg, acc_g, input_precision="ieee", out_dtype=ACC_DTYPE)
        acc_o = tl.dot(x, wo, acc_o, input_precision="ieee", out_dtype=ACC_DTYPE)
