def lstm_cell(input, hx, w_ih, w_hh, b_ih=None, b_hh=None):
    """Single LSTM cell step.

    Args:
        input: Input of shape ``(batch, input_size)``.
        hx: Two-element sequence holding the hidden and cell state, each of
            shape ``(batch, hidden_size)``.
        w_ih: Input-hidden weights of shape ``(4 * hidden_size, input_size)``.
        w_hh: Hidden-hidden weights of shape ``(4 * hidden_size, hidden_size)``.
        b_ih: Optional input-hidden bias of shape ``(4 * hidden_size,)``.
        b_hh: Optional hidden-hidden bias of shape ``(4 * hidden_size,)``.

    Returns:
        A ``(hy, cy)`` tuple, each of shape ``(batch, hidden_size)``.
    """
    logger.debug("GEMS LSTM_CELL")
    if len(hx) != 2:
        raise RuntimeError("lstm_cell expects two hidden states")
    h_prev, c_prev = hx[0], hx[1]
    _check_cell_args("lstm_cell", input, h_prev, w_ih, w_hh, b_ih, b_hh, 4)
    if c_prev.dim() != 2 or c_prev.shape[0] != input.shape[0]:
        raise RuntimeError(
            "Input batch size %d doesn't match hidden1 batch size %d"
            % (input.shape[0], c_prev.shape[0])
        )
    if c_prev.shape[1] != w_hh.shape[1]:
        raise RuntimeError(
            "hidden1 has inconsistent hidden_size: got %d, expected %d"
            % (c_prev.shape[1], w_hh.shape[1])
        )

    batch, input_size = input.shape
    hidden_size = w_hh.shape[1]
    hy = torch.empty((batch, hidden_size), dtype=input.dtype, device=input.device)
    cy = torch.empty((batch, hidden_size), dtype=input.dtype, device=input.device)
    if batch == 0 or hidden_size == 0:
        return hy, cy

    block_b = _block(batch, 16)
    block_h = _block(hidden_size, 32)
    block_k = _block(max(input_size, hidden_size), 64)

    _lstm_cell_kernel[(triton.cdiv(batch, block_b), triton.cdiv(hidden_size, block_h))](
        input,
        h_prev,
        c_prev,
        w_ih,
        w_hh,
        b_ih if b_ih is not None else input,
        b_hh if b_hh is not None else input,
        hy,
        cy,
        batch,
        input_size,
        hidden_size,
        input.stride(0),
        input.stride(1),
        h_prev.stride(0),
        h_prev.stride(1),
        c_prev.stride(0),
        c_prev.stride(1),
        w_ih.stride(0),
        w_ih.stride(1),
        w_hh.stride(0),
        w_hh.stride(1),
        hy.stride(0),
        hy.stride(1),
        HAS_BIH=b_ih is not None,
        HAS_BHH=b_hh is not None,
        ACC_DTYPE=_ACC_DTYPE[input.dtype],
        ROUND_DTYPE=_ROUND_DTYPE[input.dtype],
        BLOCK_B=block_b,
        BLOCK_H=block_h,
        BLOCK_K=block_k,
        num_warps=4,
        num_stages=3,
    )
    return hy, cy
