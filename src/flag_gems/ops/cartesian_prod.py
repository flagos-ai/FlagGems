"""Triton implementation of aten::cartesian_prod(Tensor[] tensors) -> Tensor.

out has shape (M, N), M = prod_k s_k, and out[row, k] = tensors[k][(row // PR[k]) % s_k]
with PR[k] = prod_{j>k} s_j (row-major product; the last tensor varies fastest).

The op is a pure gather/copy, but the ATen reference is meshgrid+stack and therefore
differentiable, so the forward is wrapped in a custom autograd Function whose backward
scatters grad_out[:, k] back into input k with a second Triton kernel.
"""

