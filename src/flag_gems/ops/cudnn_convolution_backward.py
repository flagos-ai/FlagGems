def _grad_input(grad_output, input, weight, pad, stride, dilation, groups):
    ndim = weight.dim() - 2
    out = torch.empty_like(input)
    if ndim == 2:
        return _launch_2d(
            grad_output, input, weight, pad, stride, dilation, groups, out
        )
    if ndim == 3:
        return _launch_3d(
            grad_output, input, weight, pad, stride, dilation, groups, out
        )
    # 1D: promote the single spatial axis to a 2D problem whose H == 1.
    flat = _launch_2d(
        grad_output.unsqueeze(-2),
        input.unsqueeze(-2),
        weight.unsqueeze(-2),
        (0, pad[0]),
        (1, stride[0]),
        (1, dilation[0]),
        groups,
        out.unsqueeze(-2),
    )
    return flat.squeeze(-2)


def cudnn_convolution_backward(
    grad_output,
    input,
    weight,
    padding,
    stride,
    dilation,
    groups,
    benchmark=False,
    deterministic=False,
    allow_tf32=False,
):
    """Gradient of ``cudnn_convolution`` w.r.t. its input.

    ``cudnn_convolution`` is a plain (never transposed) convolution without
    bias, so the input gradient is a transposed convolution of ``grad_output``
    with ``weight``, cropped back to ``input``'s spatial extent.

    Only ``grad_input`` is returned. ATen's ``_cudnn_convolution_backward``
    returns ``(grad_input, grad_weight)``; ``grad_weight`` is a separate
    weight-shaped correlation reduction and is out of scope for this
    single-return ABI. ``benchmark``/``deterministic``/``allow_tf32`` only tune
    the forward algorithm and do not affect the gradient.
    """
    logger.debug("GEMS CUDNN_CONVOLUTION_BACKWARD")
    ndim = weight.dim() - 2
    groups = int(groups)
    pad = _spatial_tuple(padding, ndim)
    strd = _spatial_tuple(stride, ndim)
    dil = _spatial_tuple(dilation, ndim)
    return _grad_input(grad_output, input, weight, pad, strd, dil, groups)
