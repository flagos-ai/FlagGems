@triton.jit
def _combine_cast(part_ptr, out_ptr, per, KD: tl.constexpr, BLOCK: tl.constexpr):
    pid = tl.program_id(0)
    off = pid * BLOCK + tl.arange(0, BLOCK)
    m = off < per
    acc = tl.zeros((BLOCK,), dtype=tl.float32)
    for i in range(KD):
        acc += tl.load(part_ptr + i * per + off, mask=m, other=0.0)
    tl.store(out_ptr + off, acc, mask=m)


