def _next_pow2(x):
    x = int(x)
    if x <= 1:
        return 1
    return 1 << (x - 1).bit_length()


def _spatial_tuple(value, ndim):
    if isinstance(value, (list, tuple)):
        vals = [int(v) for v in value]
        if len(vals) == 1:
            vals = vals * ndim
        return tuple(vals[:ndim])
    return (int(value),) * ndim


