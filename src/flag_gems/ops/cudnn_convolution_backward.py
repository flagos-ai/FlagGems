"""Triton implementation of ``cudnn_convolution_backward`` (grad w.r.t. input).

``cudnn_convolution`` is a bias-free, never-transposed convolution, so its input
gradient is a transposed convolution of ``grad_output`` with ``weight``, cropped
back to ``input``'s spatial extent.  Rather than materialising an im2col or
transposed-convolution intermediate, each program gathers directly:

    gi[n, ci, p] = sum_{co, k} go[n, g*COG+co, ho] * w[g*COG+co, ci, k]

with ``ho = (p + pad - k*dil) / stride`` accepted only when that division is
exact and ``ho`` falls inside ``grad_output``.  Positions with no contributing
``(k, ho)`` pair therefore stay zero, reproducing the reference crop exactly.

The reduction over out-channels is expressed as one ``tl.dot`` per kernel tap
(``[BLOCK_S, BLOCK_CO] @ [BLOCK_CO, BLOCK_CI]``), so the bulk of the arithmetic
runs on tensor cores instead of a long chain of rank-1 updates.  Accumulation is
fp32 for every dtype and the result is cast once on store.
"""

