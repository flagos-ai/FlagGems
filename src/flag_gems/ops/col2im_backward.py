@libentry()
@triton.jit
def _tile_kernel(
    grad_ptr,
    out_ptr,
    SH,
    SW,
    OH,
    OW,
    C: tl.constexpr,
    KK: tl.constexpr,
    KW: tl.constexpr,
    L: tl.constexpr,  # row length of the column tensor (== OH*OW)
    sN: tl.constexpr,
    sC: tl.constexpr,
    sH: tl.constexpr,
    sW: tl.constexpr,
    stH: tl.constexpr,
    stW: tl.constexpr,
    dH: tl.constexpr,
    dW: tl.constexpr,
    pH: tl.constexpr,
    pW: tl.constexpr,
    BOW: tl.constexpr,
    BOH: tl.constexpr,
    BND: tl.constexpr,
    TAILH: tl.constexpr,
    TAILW: tl.constexpr,
):
    pid_w = tl.program_id(0)
    pid_h = tl.program_id(1)
    row = tl.program_id(2)  # (n*C + c)*KK + kk, scalar

    ow = pid_w * BOW + tl.arange(0, BOW)
    oh = pid_h * BOH + tl.arange(0, BOH)

    # the whole row decomposition is scalar per program: one division by a constexpr
    kk = row % KK
    nc = row // KK
    c = nc % C
    n = nc // C
    kh = kk // KW
    kw = kk - kh * KW

    ih = (oh * stH - pH + kh * dH)[:, None]
    iw = (ow * stW - pW + kw * dW)[None, :]

    src = n * sN + c * sC + ih * sH + iw * sW

    # store mask: which output cells this tile owns. Padded cells ARE owned, so they
    # must be written -- with the zero produced by other=0 below.
    if TAILH:
        store_m = (oh < OH)[:, None] & tl.full((1, BOW), 1, tl.int1)
    else:
        store_m = tl.full((BOH, 1), 1, tl.int1) & tl.full((1, BOW), 1, tl.int1)
    if TAILW:
        store_m = store_m & (ow < OW)[None, :]

    # load mask: only cells whose source position is inside grad_output are read.
    if BND:
        load_m = store_m & (ih >= 0) & (ih < SH) & (iw >= 0) & (iw < SW)
    else:
        load_m = store_m

    val = tl.load(grad_ptr + src, mask=load_m, other=0)

    out_off = row * L + oh[:, None] * OW + ow[None, :]
    tl.store(out_ptr + out_off, val, mask=store_m)


@libentry()
@triton.jit
def _im2col_kernel(
    grad_ptr,
    out_ptr,
    TOTAL,
    SH,
    SW,
    dH,
    dW,
    pH,
    pW,
    stH,
    stW,
    sN,
    sC,
    sH,
    sW,
    C: tl.constexpr,
    KK: tl.constexpr,
    KW: tl.constexpr,
    L: tl.constexpr,  # row length of the column tensor (== OH*OW)
    OW: tl.constexpr,  # column-grid width
    BLOCK: tl.constexpr,
    I64: tl.constexpr,
    BND: tl.constexpr,
    TAIL: tl.constexpr,
):
    idx = tl.program_id(0) * BLOCK + tl.arange(0, BLOCK)

    l = idx % L  # constexpr divisor -> strength reduced
    row = idx // L
    kk = row % KK  # constexpr
    nc = row // KK
    c = nc % C  # constexpr
    n = nc // C
    kh = kk // KW  # constexpr
    kw = kk - kh * KW

    oh = l // OW  # constexpr divisor -> strength reduced
    ow = l - oh * OW

    h = oh * stH - pH + kh * dH
    w = ow * stW - pW + kw * dW

    if I64:
        src = n.to(tl.int64) * sN + c.to(tl.int64) * sC
        src = src + h.to(tl.int64) * sH + w.to(tl.int64) * sW
    else:
        src = n * sN + c * sC + h * sH + w * sW

    if BND:
        ok = (h >= 0) & (h < SH) & (w >= 0) & (w < SW)
        if TAIL:
            val = tl.load(grad_ptr + src, mask=ok & (idx < TOTAL), other=0)
        else:
            val = tl.load(grad_ptr + src, mask=ok, other=0)
    else:
        if TAIL:
            val = tl.load(grad_ptr + src, mask=idx < TOTAL, other=0)
        else:
            val = tl.load(grad_ptr + src)

    if TAIL:
        tl.store(out_ptr + idx, val, mask=idx < TOTAL)
    else:
        tl.store(out_ptr + idx, val)


def _pair(v):
    if isinstance(v, (tuple, list)):
        if len(v) == 1:
            return int(v[0]), int(v[0])
        return int(v[0]), int(v[-1])
    return int(v), int(v)


def _pow2(x):
    return triton.next_power_of_2(max(int(x), 1))


_NUM_SM = 78
# Below this element count the problem is still governed by single-launch latency.
_LARGE = 8192
# Tile budget for the unit-stride path: 512 elements over 128 threads gives each
# lane 4 contiguous ow elements, i.e. an 8-byte store instead of a 2-byte one.
_TILE = 512
_TILE_WARPS = 4


def col2im_backward(
    grad_output, self, output_size, kernel_size, dilation, padding, stride
):
    logger.debug("GEMS COL2IM_BACKWARD")
    gd = grad_output
    KH, KW = _pair(kernel_size)
    dH, dW = _pair(dilation)
    pH, pW = _pair(padding)
    stH, stW = _pair(stride)

    out = torch.empty(self.shape, dtype=self.dtype, device=gd.device)
    total = int(out.numel())
    if total == 0:
        return out

    sh = gd.shape
    nd = gd.dim()
    if nd == 4:
        N, C, SH, SW = int(sh[0]), int(sh[1]), int(sh[2]), int(sh[3])
        sN, sC, sH, sW = (int(x) for x in gd.stride())
    elif nd == 3:
        N, C, SH, SW = 1, int(sh[0]), int(sh[1]), int(sh[2])
        sN = 0
        sC, sH, sW = (int(x) for x in gd.stride())
    elif nd == 2:
        N, C, SH, SW = 1, 1, int(sh[0]), int(sh[1])
        sN = sC = 0
        sH, sW = int(gd.stride(0)), int(gd.stride(1))
    else:
        return out

    if C <= 0 or SH <= 0 or SW <= 0 or KH <= 0 or KW <= 0:
        return out

    KK = KH * KW
    L = int(self.shape[-1])
    if L <= 0:
        return out

    OH = (SH + 2 * pH - dH * (KH - 1) - 1) // stH + 1
    OW = (SW + 2 * pW - dW * (KW - 1) - 1) // stW + 1
    if OH * OW != L:
        # reconcile against the authoritative column length self.shape[-1]
        if OH > 0 and L % OH == 0:
            OW = L // OH
        elif OW > 0 and L % OW == 0:
            OH = L // OW
        else:
            OW = L
            OH = 1

    # interior-only fast path: no tap can leave the input window
    safe = (
        pH == 0
        and pW == 0
        and (OH - 1) * stH + (KH - 1) * dH < SH
        and (OW - 1) * stW + (KW - 1) * dW < SW
    )

    # ---- TILE path: large, unit-stride gather in memory ---------------------------
    # stW*sW == 1 makes the gathered column a contiguous ramp, so the loaded tile and
    # the contiguous output tile can share one register layout and Triton emits no
    # shared-memory transposition and no barrier.
    if total >= _LARGE and stW * sW == 1 and OH > 0 and OW > 0 and N * C * KK > 0:
        BOW = min(128, _pow2(OW))
        BOH = min(max(1, _TILE // BOW), _pow2(OH))
        with torch_device_fn.device(gd.device):
            _tile_kernel[(triton.cdiv(OW, BOW), triton.cdiv(OH, BOH), N * C * KK)](
                gd,
                out,
                SH,
                SW,
                OH,
                OW,
                C=C,
                KK=KK,
                KW=KW,
                L=L,
                sN=sN,
                sC=sC,
                sH=sH,
                sW=sW,
                stH=stH,
                stW=stW,
                dH=dH,
                dW=dW,
                pH=pH,
                pW=pW,
                BOW=BOW,
                BOH=BOH,
                BND=not safe,
                TAILH=(OH % BOH) != 0,
                TAILW=(OW % BOW) != 0,
                num_warps=_TILE_WARPS,
                num_stages=1,
            )
        return out

    # ---- FLAT path: large strided gathers, and every launch-bound small shape -----
    # Every workload here moves at most a few hundred KB, so latency is governed by
    # resident warps and the per-thread dependent path rather than by bandwidth. The
    # large problems are given one element per lane with fixed 4-warp CTAs, which
    # maximizes resident warps and hence in-flight load requests; the small ones keep
    # one short CTA per SM, all a launch-latency-bound problem can use.
    if total >= _LARGE:
        BLOCK = 128
        num_warps = 4
    else:
        BLOCK = min(512, max(32, _pow2(-(-total // _NUM_SM))))
        BLOCK = min(BLOCK, _pow2(total))
        num_warps = max(1, min(4, BLOCK // 128))

    with torch_device_fn.device(gd.device):
        _im2col_kernel[(-(-total // BLOCK),)](
            gd,
            out,
            total,
            SH,
            SW,
            dH,
            dW,
            pH,
            pW,
            stH,
            stW,
            sN,
            sC,
            sH,
            sW,
            C=C,
            KK=KK,
            KW=KW,
            L=L,
            OW=OW,
            BLOCK=BLOCK,
            I64=total >= 2**31,
            BND=not safe,
            TAIL=(total % BLOCK) != 0,
            num_warps=num_warps,
            num_stages=1,
        )
    return out
