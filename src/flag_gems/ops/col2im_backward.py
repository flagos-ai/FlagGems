"""col2im_backward: the adjoint of fold/col2im, i.e. a strided im2col (unfold) gather.

fold (col2im) maps cols[n, c*KH*KW + kh*KW + kw, oh*OW + ow] into
Y[n, c, oh*stH - pH + kh*dH, ow*stW - pW + kw*dW] with accumulation, so its
backward with respect to cols needs no accumulation at all: every output element
has exactly one source element in grad_output or a constant zero.

    out[n, c*KH*KW + kh*KW + kw, oh*OW + ow]
        = grad_output[n, c, oh*stH - pH + kh*dH, ow*stW - pW + kw*dW]

with 0 wherever that source position falls outside grad_output (padding). The
operator is therefore a pure strided copy: no arithmetic, no reductions and no
atomics, so it is bit-exact for every dtype.

The host dispatches on two structural properties of the problem -- the output
element count and whether the gather is unit-stride in memory (`stW * sW == 1`) --
because those select genuinely different optimal decompositions:

* TILE, for large unit-stride problems. A 3D grid (ow tile, oh tile, kk-row) with
  the lane axis running along `ow` as a literal tl.arange. Every address
  coefficient (the grad strides and the whole unfold geometry) is a compile-time
  constant, so the address is a provably affine ramp and the per-element integer
  division of the flat form disappears entirely -- measured on this target as a
  149 -> 50 instruction body. Crucially, OH*OW == L means the (oh, ow) rectangle
  for one row is itself a contiguous run of the output, so the store vectorizes
  across the whole tile. Each lane holds TILE/128 contiguous ow elements so that
  store is 8 bytes wide rather than 2.

  This path is restricted to unit-stride gathers on purpose: for a strided gather
  the loaded tile and the contiguous store tile cannot share one register layout,
  so Triton inserts a shared-memory round trip plus a CTA-wide barrier (measured:
  1 KB of STS.U16 -> BAR.SYNC -> LDS.U16). That cost is pure overhead and the flat
  form avoids it.

* FLAT, for large strided gathers and for every small problem. One flat 1D grid
  over the contiguous output with all index divisors passed as constexpr so each
  `//`/`%` is strength-reduced, which keeps the layout 1D end to end and so never
  needs a shared-memory transposition. For the small shapes it also keeps the grid
  at one short CTA per SM, which is all a launch-latency-bound problem can use.

Both paths specialize their masks at compile time: BND vanishes when the padding
window is provably interior, and tile tails vanish when the block divides the grid
extent exactly. The store predicate is always the tile-ownership mask, never the
in-window mask, so padded cells are still written -- with the exact zero produced
by `other=0` on the load.
"""
