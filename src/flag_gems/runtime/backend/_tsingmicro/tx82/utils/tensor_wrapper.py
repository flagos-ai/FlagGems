import math

import torch

import flag_gems


class TypedPtr:
    """This is a minimal requirement for a type to be treated as a tensor in triton jit
    function. Basically it is a typed pointer, without knowning the device, size, shape,
    strides, etc.
    """

    def __init__(self, ptr: int, dtype: torch.dtype):
        self.ptr = ptr
        self.dtype = dtype

    def data_ptr(self) -> int:
        return self.ptr

    def untyped_storage(self):
        return self

    @classmethod
    def from_tensor(cls, tensor: torch.Tensor, offset: int = 0):
        return cls(tensor.data_ptr() + tensor.element_size() * offset, tensor.dtype)

    @classmethod
    def reinterpret_tensor(cls, tensor: torch.Tensor, dtype: torch.dtype, offset=0):
        return cls(tensor.data_ptr() + dtype.itemsize * offset, dtype)


class StridedBuffer:
    """A drop-in replacement of torch.Tensor that can be used in wrapper generated by
    PointwiseDynamicFunction. It allows us to use a different shape, stride, data
    pointer that that of the base tensor.

    It is a kind of reinterpretation of the base tensor. We make this class since we
    cannot get a Tensor view with negative strides via torch APIs, while we need this
    to implement flip op.

    Although generated code can accept torch.Tensor & StridedBuffer, but StridedBuffer
    may not have all the methods as torch.Tensors do. We add some attributes & methods
    with the same name as torch.Tensor, which are used in the generated code. But we
    may not cover all the methods, add one if what you need is missing here.

    And can also be used in triton kernels since it also has dtype & data_ptr().
    """

    def __init__(
        self,
        base: torch.Tensor,
        shape=None,
        strides=None,
        dtype=None,
        offset=0,
        offsets=None,
    ):
        self._base = base
        self.dtype = dtype or base.dtype
        self.offset = offset

        if offsets is not None:
            # per-dim element offsets, passed to the kernel separately instead of
            # being folded into the data pointer. Used with negative strides (flip).
            # Keeps the DMA base address inside the allocation so that the driver's
            # OOB check can read the real header and report an accurate error.
            assert offset == 0, "offset and offsets are mutually exclusive"
            self._offsets = tuple(offsets)
            offset_bytes = 0
            self._data_ptr = self._base.data_ptr()
        elif offset == 0:
            self._offsets = None
            offset_bytes = 0
            self._data_ptr = self._base.data_ptr()
        else:
            self._offsets = None
            # TODO[kunlunxin]: we will upgrade torch version in 2025.04
            if flag_gems.vendor_name == "kunlunxin":

                def get_dtype_bytes(dtype):
                    if dtype.is_floating_point:
                        return int(torch.finfo(dtype).bits / 8)
                    else:
                        return int(torch.iinfo(dtype).bits / 8)

                offset_bytes = get_dtype_bytes(self.dtype) * offset
            else:
                offset_bytes = self.dtype.itemsize * offset

            self._data_ptr = self._base.data_ptr() + offset_bytes
        self.shape = tuple(shape if shape is not None else self._base.shape)
        self._strides = tuple(strides if strides is not None else self._base.stride())
        self.device = self._base.device
        self.ndim = len(self.shape)

        self._check_span_in_storage(offset_bytes)

    def offsets(self):
        """Per-dim element offsets: addr = base + sum((logical_i - offset_i) * stride_i).
        With a negative stride and offset_i = shape_i - 1 this expresses a
        reflected (flipped) view without shifting the base pointer. Returns all
        zeros for tensors without an explicit per-dim offset.
        """
        if self._offsets is None:
            return (0,) * self.ndim
        return self._offsets

    def _check_span_in_storage(self, offset_bytes):
        """Defensive check: the address range covered by this view must stay
        inside the base tensor's storage.

        A legal torch.Tensor always satisfies this. Views whose declared shape
        exceeds the underlying storage (as_strided out of bounds, block-pool
        reuse) fold a large offset into the data pointer; downstream DMA then
        walks out of the allocation and kills the device with a hardware OOB
        fatal. Rejecting them here turns that into a catchable host error.
        """
        if not isinstance(self._base, torch.Tensor) or self.numel() == 0:
            return
        storage_nbytes = self._base.untyped_storage().nbytes()
        view_itemsize = self.dtype.itemsize
        min_off = offset_bytes
        max_off = offset_bytes
        for n, s, off in zip(self.shape, self._strides, self.offsets()):
            if n <= 1:
                continue
            # physical offset = (logical - off) * s, logical in [0, n); covers
            # both the folded scalar offset (offsets() == all 0) and the
            # per-dim offsets mode (flip's reflected views).
            lo_i = (0 - off) * s * view_itemsize
            hi_i = (n - 1 - off) * s * view_itemsize
            min_off += min(lo_i, hi_i)
            max_off += max(lo_i, hi_i)
        base_off = self._base.storage_offset() * self._base.element_size()
        lo = base_off + min_off
        hi = base_off + max_off + view_itemsize
        if lo < 0 or hi > storage_nbytes:
            raise RuntimeError(
                f"StridedBuffer view byte range [{lo}, {hi}) exceeds base "
                f"storage [0, {storage_nbytes}): shape={self.shape}, "
                f"strides={self._strides}, offset={self.offset} elem. "
                f"Base tensor shape={tuple(self._base.shape)}, "
                f"storage_offset={self._base.storage_offset()}. "
                f"Declared shape exceeds underlying storage — the producer of "
                f"this view is buggy."
            )

    def stride(self):
        return self._strides

    def size(self):
        return self.shape

    def element_size(self):
        return self.dtype.itemsize

    def numel(self):
        return math.prod(self.shape)

    def dim(self):
        return self.ndim

    def unwrap(self):
        return self._base

    def data_ptr(self):
        return self._data_ptr

    def untyped_storage(self):
        return self._base.untyped_storage()

    def clone(self):
        return StridedBuffer(
            self._base.clone(),
            shape=self.shape,
            strides=self._strides,
            dtype=self.dtype,
            offset=self.offset,
        )

    def copy_(self, src):
        if isinstance(src, StridedBuffer):
            self._base.copy_(src._base)
            self._strides = src._strides
            self.shape = src.shape
            self.dtype = src.dtype
            self.device = src.device
            self.offset = src.offset
        else:
            src_buffer = StridedBuffer(src)
            self.copy_(src_buffer)
        return self
