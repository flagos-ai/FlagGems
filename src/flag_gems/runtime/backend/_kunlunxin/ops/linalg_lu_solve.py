"""Triton implementation of aten::linalg_lu_solve.

Solves a linear system from a packed LU factorization (torch.lu_factor output).
Only Triton kernels produce the returned value; the host wrapper allocates the
output and maps (left, adjoint) onto zero-copy strided views.

Measured constraints of this target (Kunlunxin P800 / flagtree Triton 3.6):
  * only last-axis reductions are accepted, all reductions in one kernel must
    share one blocking, and a 2-D tile carried through the substitution loop
    faulted at run time -> the solve uses pure 1-D tiles;
  * 1-D tiles of width 256 hit a codegen bug, so tiles are capped at 128 and
    n > 128 is covered by two tiles per program;
  * a standalone 128-wide integer select chain fails to compile, so the row
    permutation is recomputed inside the (float+int) solve kernels;
  * torch.linalg.lu_factor returns 1-based pivot indices.
"""

