import logging

import torch
import triton
import triton.language as tl

logger = logging.getLogger(__name__)

# Kunlunxin `tl.dot` accepts only ieee/tf32 (never tf32x3). The generic
# corrcoef covariance kernel calls `tl.dot` with the default input_precision,
# which lowers to ieee (exact fp32, scalar rate ~0.6 TFLOPS) on this backend.
# Pinning the long-reduction case to tf32 moves the Gram GEMM onto tensor cores
# (~10-40 TFLOPS) while keeping ieee for short reductions where tf32's ~1e-3
# relative error would exceed the accuracy tolerance. This mirrors the
# cov override, whose identical covariance GEMM passes at ~2.1x.
_DOT_PRECISION_HIGH = tl.constexpr("ieee")
_DOT_PRECISION = tl.constexpr("tf32")


@triton.jit
def _corrcoef_mean_kernel(
    x_ptr, mean_ptr, n_rows, n_cols, stride_xn, stride_xm, BLOCK_M: tl.constexpr
):
    # Each program reduces one row to its mean over the observation axis.
    row = tl.program_id(0)
    acc = tl.zeros([BLOCK_M], dtype=tl.float32)
    for m_start in range(0, n_cols, BLOCK_M):
        offs = m_start + tl.arange(0, BLOCK_M)
        mask = offs < n_cols
        x = tl.load(x_ptr + row * stride_xn + offs * stride_xm, mask=mask, other=0.0)
        x = x.to(tl.float32)
        acc += x
    mean = tl.sum(acc) / n_cols
    tl.store(mean_ptr + row, mean)


@triton.jit
def _corrcoef_cov_kernel(
    x_ptr,
    mean_ptr,
    c_ptr,
    n_rows,
    n_cols,
    stride_xn,
    stride_xm,
    stride_cn,
    stride_cm,
    HIGH_PRECISION: tl.constexpr,
    BLOCK_N: tl.constexpr,
    BLOCK_M: tl.constexpr,
):
    # 2D-tiled covariance: c[i, j] = sum_k (x[i, k] - mean[i]) * (x[j, k] - mean[j])
    # divided by (n_cols - 1). Centering is fused into the GEMM to avoid an
    # extra global-memory round trip over the centered matrix.
    pid_i = tl.program_id(0)
    pid_j = tl.program_id(1)

    offs_i = pid_i * BLOCK_N + tl.arange(0, BLOCK_N)
    offs_j = pid_j * BLOCK_N + tl.arange(0, BLOCK_N)

    mi = tl.load(mean_ptr + offs_i, mask=offs_i < n_rows, other=0.0)
    mj = tl.load(mean_ptr + offs_j, mask=offs_j < n_rows, other=0.0)

    acc = tl.zeros([BLOCK_N, BLOCK_N], dtype=tl.float32)

    for m_start in range(0, n_cols, BLOCK_M):
        offs_m = m_start + tl.arange(0, BLOCK_M)
        mask_m = offs_m < n_cols

        mask_i = offs_i < n_rows
        mask_j = offs_j < n_rows

        xi = tl.load(
            x_ptr + offs_i[:, None] * stride_xn + offs_m[None, :] * stride_xm,
            mask=mask_i[:, None] & mask_m[None, :],
            other=0.0,
        ).to(tl.float32)
        xj = tl.load(
            x_ptr + offs_j[:, None] * stride_xn + offs_m[None, :] * stride_xm,
            mask=mask_j[:, None] & mask_m[None, :],
            other=0.0,
        ).to(tl.float32)

        xi_centered = xi - mi[:, None]
        xj_centered = xj - mj[:, None]

        # Re-zero padding lanes (not -mean) so the dot product stays exact for
        # observation counts that are not a multiple of BLOCK_M. Scaling by a
        # float32 0/1 column vector is equivalent to the where-select it
        # replaces, but avoids materializing a broadcast i1 mask: the XPU
        # backend (flagtree 0.7.0, the CI compiler) aborts such broadcasts with
        # "Unsupported data element type".
        col_valid = mask_m.to(tl.float32)
        xi_centered = xi_centered * col_valid[None, :]
        xj_centered = xj_centered * col_valid[None, :]

        if HIGH_PRECISION:
            acc += tl.dot(
                xi_centered, tl.trans(xj_centered), input_precision=_DOT_PRECISION_HIGH
            )
        else:
            acc += tl.dot(
                xi_centered, tl.trans(xj_centered), input_precision=_DOT_PRECISION
            )

    c = acc / (n_cols - 1)

    mask_ij = (offs_i[:, None] < n_rows) & (offs_j[None, :] < n_rows)
    tl.store(
        c_ptr + offs_i[:, None] * stride_cn + offs_j[None, :] * stride_cm,
        c,
        mask=mask_ij,
    )


@triton.jit
def _corrcoef_inv_std_kernel(
    c_ptr, inv_std_ptr, n_rows, stride_cn, stride_cm, BLOCK: tl.constexpr
):
    # Computes inv_std[i] = 1 / sqrt(c[i, i]) from the covariance diagonal. The
    # diagonal gather is strided (stride_cn + stride_cm), so it is isolated here
    # into a tiny n_rows-wide pass rather than being repeated inside the 2D
    # normalization tile where it would defeat block-DMA vectorization.
    pid = tl.program_id(0)
    offs = pid * BLOCK + tl.arange(0, BLOCK)
    mask = offs < n_rows
    diag = tl.load(c_ptr + offs * stride_cn + offs * stride_cm, mask=mask, other=0.0)
    inv_std = 1.0 / tl.sqrt(diag)
    tl.store(inv_std_ptr + offs, inv_std, mask=mask)


@triton.jit
def _corrcoef_norm_kernel(
    c_ptr,
    inv_std_ptr,
    out_ptr,
    n_rows,
    BLOCK: tl.constexpr,
):
    # corr[i, j] = c[i, j] * inv_std[i] * inv_std[j]. One program per row; the
    # innermost access is a contiguous run of columns, which this backend lowers
    # to block DMA. A 2D-tiled formulation (offs_i[:, None] * n_rows +
    # offs_j[None, :]) instead issues per-row strided accesses and runs ~5x
    # slower on Kunlunxin, so the row layout is deliberate.
    row = tl.program_id(0)
    inv_si = tl.load(inv_std_ptr + row)
    for c_start in range(0, n_rows, BLOCK):
        cols = c_start + tl.arange(0, BLOCK)
        mask = cols < n_rows
        c = tl.load(c_ptr + row * n_rows + cols, mask=mask, other=0.0)
        sj = tl.load(inv_std_ptr + cols, mask=mask, other=0.0)
        tl.store(out_ptr + row * n_rows + cols, c * inv_si * sj, mask=mask)


def _pick_tile(n: int) -> int:
    # 32 is the minimum that keeps the GEMM (and 2D tiles) well-formed; 128 is
    # the sweet spot for tensor-core/utilization on this backend. Small rows
    # fall back to the minimum so the grid stays at least 1x1 without oversized
    # padding tiles.
    if n >= 128:
        return 128
    if n >= 64:
        return 64
    return 32


def corrcoef(input: torch.Tensor) -> torch.Tensor:
    """Estimates the Pearson product-moment correlation coefficient matrix.

    Rows of ``input`` are the variables and columns are the observations. The
    output is an N x N correlation matrix where ``R[i, j] = C[i, j] /
    sqrt(C[i, i] * C[j, j])`` and ``C`` is the covariance matrix. The
    computation is carried out in float32 internally and the result is cast
    back to the input dtype, matching the precision behaviour expected from a
    stable Triton implementation.
    """
    logger.debug("GEMS_KUNLUNXIN CORRCOEF")

    # A single variable (1D/0D input, or a 2D input with one row) correlates
    # perfectly with itself, so torch.corrcoef returns the scalar 1.0.
    if input.dim() < 2 or input.shape[0] == 1:
        return torch.ones((), dtype=input.dtype, device=input.device)

    x = input.contiguous()
    n_rows, n_cols = x.shape
    device = x.device
    out_dtype = x.dtype

    # Per-variable means, kept in float32 for numerical stability across dtypes.
    mean = torch.empty(n_rows, device=device, dtype=torch.float32)
    # Column reduction tile: up to 512 (the largest power-of-2 <= the wide
    # observation counts) so the reduction runs in fewer, wider trips.
    BLOCK_M = min(512, max(32, triton.next_power_of_2(n_cols)))
    _corrcoef_mean_kernel[(n_rows,)](
        x, mean, n_rows, n_cols, x.stride(0), x.stride(1), BLOCK_M=BLOCK_M
    )

    # Covariance accumulates in float32 for stability, then normalizes to dtype.
    cov = torch.empty(n_rows, n_rows, device=device, dtype=torch.float32)
    # Row tile for the 2D covariance grid. Larger tiles amortize the per-program
    # launch/load overhead and give the dot larger M/N (tensor-core friendly).
    BLOCK_N = _pick_tile(n_rows)
    grid_n = triton.cdiv(n_rows, BLOCK_N)
    # Precision policy keyed on the reduction length n_cols (see cov.py): tf32
    # for long reductions (tensor cores), ieee for short ones (accuracy).
    HIGH_PRECISION = n_cols < 32
    _corrcoef_cov_kernel[(grid_n, grid_n)](
        x,
        mean,
        cov,
        n_rows,
        n_cols,
        x.stride(0),
        x.stride(1),
        cov.stride(0),
        cov.stride(1),
        HIGH_PRECISION=HIGH_PRECISION,
        BLOCK_N=BLOCK_N,
        BLOCK_M=128,
    )

    out = torch.empty(n_rows, n_rows, device=device, dtype=out_dtype)
    # Normalization is split into a tiny n_rows-wide diagonal pass (sqrt of the
    # covariance diagonal, a strided gather) plus a 2D unit-stride multiply, so
    # the 2D tile never does a strided diagonal gather or per-element sqrt.
    inv_std = torch.empty(n_rows, device=device, dtype=torch.float32)
    BLOCK_DIAG = 128
    _corrcoef_inv_std_kernel[(triton.cdiv(n_rows, BLOCK_DIAG),)](
        cov,
        inv_std,
        n_rows,
        cov.stride(0),
        cov.stride(1),
        BLOCK=BLOCK_DIAG,
    )
    BLOCK_N_OUT = min(512, max(32, triton.next_power_of_2(n_rows)))
    _corrcoef_norm_kernel[(n_rows,)](
        cov,
        inv_std,
        out,
        n_rows,
        BLOCK=BLOCK_N_OUT,
    )

    return out
