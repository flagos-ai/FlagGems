def grid_sampler_3d(
    input,
    grid,
    interpolation_mode=0,
    padding_mode=0,
    align_corners=False,
):
    """Grid sampler 3D with trilinear or nearest interpolation."""
    logger.debug("GEMS_KUNLUNXIN GRID_SAMPLER_3D")

    N, C, ID, IH, IW = input.shape
    OD, OH, OW = grid.shape[1:4]

    output = torch.empty(
        (N, C, OD, OH, OW),
        dtype=input.dtype,
        device=input.device,
    )

    if output.numel() == 0:
        return output

    input = input.contiguous()
    grid = grid.contiguous()

    total = N * C * OD * OH * OW

    def get_grid(meta):
        return (triton.cdiv(total, meta["BLOCK_SIZE"]),)

    grid_sampler_3d_kernel[get_grid](
        input,
        grid,
        output,
        N,
        C,
        ID,
        IH,
        IW,
        OD,
        OH,
        OW,
        total,
        interpolation_mode,
        padding_mode,
        align_corners,
        BLOCK_SIZE=128,
    )

    return output
