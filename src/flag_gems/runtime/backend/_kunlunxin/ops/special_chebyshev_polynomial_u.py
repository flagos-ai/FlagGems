# ---------------------------------------------------------------------------
@triton.jit
def _cheb_u_uni_gen(
    x_ptr,
    out_ptr,
    meta_ptr,
    R,
    total,
    degree,
    BLOCK: tl.constexpr,
    CT_F64: tl.constexpr,
):
    pid = tl.program_id(0).to(tl.int64)
    offs = pid * BLOCK + tl.arange(0, BLOCK)
    mask = offs < total
    xo = tl.zeros([BLOCK], dtype=tl.int64)
    for d in range(0, R):
        ostr = tl.load(meta_ptr + (R + d))
        sz = tl.load(meta_ptr + d)
        c = (offs // ostr) % sz
        xo += c * tl.load(meta_ptr + (2 * R + d))
    if CT_F64:
        xv = tl.load(x_ptr + xo, mask=mask).to(tl.float64)
    else:
        xv = tl.load(x_ptr + xo, mask=mask).to(tl.float32)
    two_x = xv + xv
    a = xv * 0.0 + 1.0
    b = two_x
    for k in range(2, degree + 1):
        c = two_x * b - a
        a = b
        b = c
    res = tl.where(degree == 0, 1.0, b)
    res = tl.where(degree < 0, 0.0, res)
    tl.store(out_ptr + offs, res, mask=mask)


