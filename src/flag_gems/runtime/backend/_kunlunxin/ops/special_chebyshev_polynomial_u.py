def _tensor_n_range(n):
    dev = n.device
    total = n.numel()
    g = triton.cdiv(total, 4096)
    lo = torch.empty(g, dtype=torch.int32, device=dev)
    hi = torch.empty(g, dtype=torch.int32, device=dev)
    _n_range_stage1[(g,)](n, lo, hi, total, BLOCK=4096, num_warps=_NUM_WARPS)
    b2 = 1
    while b2 < g:
        b2 <<= 1
    out = torch.empty(2, dtype=torch.int32, device=dev)
    _n_range_stage2[(1,)](lo, hi, out, g, BLOCK=b2, num_warps=_NUM_WARPS)
    return int(out[0].item()), int(out[1].item())


def special_chebyshev_polynomial_u(x, n):
    # FlagGems contract: only degrees n in [0, 5] are supported (explicit
    # polynomial formulas). Out-of-range degrees must raise ValueError.
    with torch_device_fn.device((x if isinstance(x, torch.Tensor) else n).device):
        if isinstance(n, numbers.Number):
            n_min = n_max = int(n)
        elif n.numel() == 1:
            n_min = n_max = int(n.reshape(()).item())
        else:
            n_min, n_max = _tensor_n_range(n)
        if n_max > 5 or n_min < 0:
            raise ValueError(
                "Chebyshev polynomial order n must be in [0, 5], "
                "got values in [%d, %d]" % (n_min, n_max)
            )

        x_shape = tuple(x.shape)

        n_is_number = isinstance(n, numbers.Number)

        if n_is_number:
            out_shape = x_shape
        else:
            out_shape = torch.broadcast_shapes(x_shape, tuple(n.shape))

        out_numel = 1
        for s in out_shape:
            out_numel *= int(s)

        if n_is_number:
            od = _out_dtype(
                x.dtype,
                torch.int64 if isinstance(n, numbers.Integral) else torch.float64,
            )
        else:
            od = _out_dtype(x.dtype, n.dtype)

        out = torch.empty(out_shape, dtype=od, device=x.device)
        if out_numel == 0:
            return out

        ct_f64 = od == torch.float64
        grid = (triton.cdiv(out_numel, _BLOCK),)

        if n_is_number:
            degree = int(n)
            if x.is_contiguous():
                if out_numel <= (1 << 14):
                    BLOCK, NW = 1024, 4
                else:
                    BLOCK, NW = 8192, 16
                grid = (triton.cdiv(out_numel, BLOCK),)
                _cheb_u_uni_lin[grid](
                    x, out, out_numel, DEG=degree, BLOCK=BLOCK, num_warps=NW
                )
            else:
                meta = torch.tensor(
                    _meta(out_shape, x_shape, tuple(x.stride())),
                    dtype=torch.int64,
                    device=x.device,
                )
                _cheb_u_uni_gen[grid](
                    x,
                    out,
                    meta,
                    len(out_shape),
                    out_numel,
                    degree,
                    BLOCK=_BLOCK,
                    CT_F64=ct_f64,
                    num_warps=_NUM_WARPS,
                )
            return out

        # tensor n below
        n_is_int = not n.dtype.is_floating_point
        n_shape = tuple(n.shape)

        if x.is_contiguous() and n.is_contiguous() and x_shape == n_shape:
            _cheb_u_var_lin[grid](
                x,
                n,
                out,
                out_numel,
                BLOCK=_BLOCK,
                CT_F64=ct_f64,
                N_IS_INT=n_is_int,
                num_warps=_NUM_WARPS,
            )
        elif n.numel() == 1 and x.is_contiguous():
            _cheb_u_uni_tensor[grid](
                x,
                n.reshape(()),
                out,
                out_numel,
                BLOCK=_BLOCK,
                CT_F64=ct_f64,
                num_warps=_NUM_WARPS,
            )
        else:
            meta = torch.tensor(
                _meta(
                    out_shape, x_shape, tuple(x.stride()), n_shape, tuple(n.stride())
                ),
                dtype=torch.int64,
                device=x.device,
            )
            R = len(out_shape)
            _cheb_u_var_gen[grid](
                x,
                n,
                out,
                meta,
                R,
                out_numel,
                BLOCK=_BLOCK,
                CT_F64=ct_f64,
                N_IS_INT=n_is_int,
                num_warps=_NUM_WARPS,
            )
        return out
