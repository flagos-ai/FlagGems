# Kernel 1: uniform integer degree in [0,5], x read linearly (contiguous).
# Degree is a compile-time constant so the exact closed-form U_n(x) is emitted
# with no dynamic loop, which allows very large BLOCK sizes on the XPU backend.
# ---------------------------------------------------------------------------
@triton.jit
def _cheb_u_uni_lin(x_ptr, out_ptr, total, DEG: tl.constexpr, BLOCK: tl.constexpr):
    pid = tl.program_id(0).to(tl.int64)
    offs = pid * BLOCK + tl.arange(0, BLOCK)
    mask = offs < total
    xv = tl.load(x_ptr + offs, mask=mask).to(tl.float32)
    if DEG == 0:
        r = xv * 0.0 + 1.0
    elif DEG == 1:
        r = xv + xv
    else:
        x2 = xv * xv
        if DEG == 2:
            r = 4.0 * x2 - 1.0
        else:
            x3 = x2 * xv
            if DEG == 3:
                r = 8.0 * x3 - 4.0 * xv
            else:
                x4 = x3 * xv
                if DEG == 4:
                    r = 16.0 * x4 - 12.0 * x2 + 1.0
                else:
                    x5 = x4 * xv
                    r = 32.0 * x5 - 32.0 * x3 + 6.0 * xv
    tl.store(out_ptr + offs, r, mask=mask)


