from flag_gems.utils import libentry

logger = logging.getLogger(__name__)

# Combine kernel's contiguous run length.  512 floats = 2 KiB is comfortably in
# one DMA transfer; anything wider buys no extra bandwidth and only costs
# registers / occupancy on the smaller rows.
_MAX_COMBINE_BLOCK_H = 512


@triton.jit
def _sigmoid_fast(x):
    # sigmoid(x) = 1 / (1 + exp(-x)); the core tl.exp is the native fast path.
    return 1.0 / (1.0 + tl.exp(-x))


@triton.jit
def _tanh_fast(x):
    # tanh(x) = 1 - 2 / (exp(2x) + 1); saturates correctly for |x| -> inf.
    e = tl.exp(2.0 * x)
    return 1.0 - 2.0 / (e + 1.0)


@libentry()
@triton.jit
def _gru_cell_combine_kernel(
    gi_ptr,
    gh_ptr,
    h_ptr,
    b_ih_ptr,
    b_hh_ptr,
    out_ptr,
    H: tl.constexpr,
    s_gb,
    s_gn,
    s_hb,
    s_hk,
    s_ob,
    s_on,
    HAS_BIH: tl.constexpr,
    HAS_BHH: tl.constexpr,
    ACC_DTYPE: tl.constexpr,
    BLOCK_H: tl.constexpr,
):
    # One program per (batch row, hidden chunk); the chunk is a full contiguous
    # row when BLOCK_H == H, so every load here is a contiguous DMA block.
    b = tl.program_id(0)
    offs_n = tl.program_id(1) * BLOCK_H + tl.arange(0, BLOCK_H)
    n_mask = offs_n < H

    base = b * s_gb
    # The rounded projections are loaded separately: the fused kernel adds each
    # bias to its own projection and only then sums the two.
    gi_r = tl.load(gi_ptr + base + offs_n * s_gn, mask=n_mask, other=0.0)
    gi_z = tl.load(gi_ptr + base + (H + offs_n) * s_gn, mask=n_mask, other=0.0)
    gi_n = tl.load(gi_ptr + base + (2 * H + offs_n) * s_gn, mask=n_mask, other=0.0)
    gh_r = tl.load(gh_ptr + base + offs_n * s_gn, mask=n_mask, other=0.0)
    gh_z = tl.load(gh_ptr + base + (H + offs_n) * s_gn, mask=n_mask, other=0.0)
    gh_n = tl.load(gh_ptr + base + (2 * H + offs_n) * s_gn, mask=n_mask, other=0.0)

    if HAS_BIH:
        gi_r += tl.load(b_ih_ptr + offs_n, mask=n_mask, other=0.0).to(ACC_DTYPE)
        gi_z += tl.load(b_ih_ptr + H + offs_n, mask=n_mask, other=0.0).to(ACC_DTYPE)
        gi_n += tl.load(b_ih_ptr + 2 * H + offs_n, mask=n_mask, other=0.0).to(ACC_DTYPE)
    if HAS_BHH:
        gh_r += tl.load(b_hh_ptr + offs_n, mask=n_mask, other=0.0).to(ACC_DTYPE)
        gh_z += tl.load(b_hh_ptr + H + offs_n, mask=n_mask, other=0.0).to(ACC_DTYPE)
        gh_n += tl.load(b_hh_ptr + 2 * H + offs_n, mask=n_mask, other=0.0).to(ACC_DTYPE)

    reset = _sigmoid_fast(gi_r + gh_r)
    update = _sigmoid_fast(gi_z + gh_z)
    new = _tanh_fast(gi_n + reset * gh_n)

    hx_tile = tl.load(h_ptr + b * s_hb + offs_n * s_hk, mask=n_mask, other=0.0).to(
        ACC_DTYPE
    )
    hy = (hx_tile - new) * update + new

    tl.store(
        out_ptr + b * s_ob + offs_n * s_on,
        hy.to(out_ptr.dtype.element_ty),
        mask=n_mask,
    )


def gru_cell(input, hx, w_ih, w_hh, b_ih=None, b_hh=None):
    """Single GRU cell step (Kunlunxin/XPU specialization)."""
    logger.debug("GEMS_KUNLUNXIN GRU_CELL")
    _check_cell_args("gru_cell", input, hx, w_ih, w_hh, b_ih, b_hh, 3)

    batch, input_size = input.shape
    hidden_size = w_hh.shape[1]
    out = torch.empty((batch, hidden_size), dtype=input.dtype, device=input.device)
    if batch == 0 or hidden_size == 0:
        return out

    block_b = _block(batch, 32)
    block_h = _block(hidden_size, 64)
    block_k = _block(max(input_size, hidden_size), 128)
    grid = (triton.cdiv(batch, block_b), triton.cdiv(hidden_size, block_h))

    # Rounded ``linear(input, w_ih)`` and ``linear(hx, w_hh)`` tiles, in
    # accumulator precision, consumed by the combine kernel.
    gi = torch.empty(
        (batch, 3 * hidden_size),
        dtype=_ACC_TORCH_DTYPE[input.dtype],
        device=input.device,
    )
    gh = torch.empty_like(gi)

    if input_size == 0:
        # An empty reduction contributes nothing (the bias is added by the
        # combine kernel), and a zero-trip loop is miscompiled on XPU, so write
        # the zeros directly instead of launching the projection kernel.
        gi.zero_()
    else:
        _gru_cell_ih_kernel[grid](
            input,
            w_ih,
            gi,
            batch,
            input_size,
            hidden_size,
            input.stride(0),
            input.stride(1),
            w_ih.stride(0),
            w_ih.stride(1),
            gi.stride(0),
            gi.stride(1),
            ACC_DTYPE=_ACC_DTYPE[input.dtype],
            ROUND_DTYPE=_ROUND_DTYPE[input.dtype],
            BLOCK_B=block_b,
            BLOCK_H=block_h,
            BLOCK_K=block_k,
            num_warps=4,
            num_stages=3,
        )
    _gru_cell_hh_kernel[grid](
        hx,
        w_hh,
        gh,
        batch,
        hidden_size,
        hx.stride(0),
        hx.stride(1),
        w_hh.stride(0),
        w_hh.stride(1),
        gh.stride(0),
        gh.stride(1),
        ACC_DTYPE=_ACC_DTYPE[input.dtype],
        ROUND_DTYPE=_ROUND_DTYPE[input.dtype],
        BLOCK_B=block_b,
        BLOCK_H=block_h,
        BLOCK_K=block_k,
        num_warps=4,
        num_stages=3,
    )
    block_hc = min(triton.next_power_of_2(hidden_size), _MAX_COMBINE_BLOCK_H)
    grid_c = (batch, triton.cdiv(hidden_size, block_hc))
    _gru_cell_combine_kernel[grid_c](
        gi,
        gh,
        hx,
        b_ih if b_ih is not None else input,
        b_hh if b_hh is not None else input,
        out,
        H=hidden_size,
        s_gb=gi.stride(0),
        s_gn=gi.stride(1),
        s_hb=hx.stride(0),
        s_hk=hx.stride(1),
        s_ob=out.stride(0),
        s_on=out.stride(1),
        HAS_BIH=b_ih is not None,
        HAS_BHH=b_hh is not None,
        ACC_DTYPE=_ACC_DTYPE[input.dtype],
        BLOCK_H=block_hc,
        num_warps=4,
        num_stages=3,
    )
    return out
