@triton.jit
def _conv_fwd_kernel(
    x_ptr,
    w_ptr,
    b_ptr,
    o_ptr,
    IC,
    PLANE,
    H,
    h_ow,
    sxc,
    xn_stride,
    on_stride,
    swo,
    swc,
    HAS_BIAS: tl.constexpr,
    COMPENSATE: tl.constexpr,
    BLOCK: tl.constexpr,
    W: tl.constexpr,
    OW: tl.constexpr,
    ROW_DELTA: tl.constexpr,
    KH: tl.constexpr,
    KW: tl.constexpr,
    PH: tl.constexpr,
    PW: tl.constexpr,
    SH: tl.constexpr,
    SW: tl.constexpr,
):
    """One program owns a contiguous [BLOCK] span of one (n, oc) output plane.

    The tile is 1-D along the fastest output axis (ow), so the store is a single
    contiguous DMA (`pattern-xpu3-2d-tile-runtime-rowstride-slow`: a 2-D tile
    whose fastest axis is the strided `oc` axis stores one short DMA per row).

    The load address of every tap is `lane + constant` with `lane` a per-lane
    value computed once from the flat output index; on the SAME-padding geometry
    (``ROW_DELTA == 0``) that is exactly ``q + constant``, i.e. provably
    contiguous (`pattern-xpu3-depthwise-stencil-affine-planemap`).  Any per-lane
    `tl.minimum/tl.maximum` in the address devectorizes the load into a per-lane
    gather (measured 16x), so the address is never clamped: the host instead
    stages the input inside a zero-cost margin allocation that keeps every tap
    address inside the allocation (see ``_forward``).  Border correctness comes
    from the value mask, matching the depthwise-stencil recipe.

    Accumulation uses the branchless Knuth TwoSum error term.  It is the exact
    rounding error of each addition (the same quantity the previous Neumaier
    step computed through a `tl.where`); on this backend `tl.where` costs ~13x
    in the tap loop while TwoSum is free, and the compensation is what
    reproduces the NNPACK oracle's overflow-to-NaN behaviour.
    """
    pid_c = tl.program_id(0)
    oc = tl.program_id(1)
    pid_n = tl.program_id(2)

    q = pid_c * BLOCK + tl.arange(0, BLOCK)
    valid = q < PLANE
    # `oh` is derived from the clamped index only so that the (row-invariant)
    # `oh * ROW_DELTA` term stays bounded; the address itself keeps the raw
    # `q`, which is what makes it provably contiguous for the SAME-padding
    # geometry.  The tail lanes overhang by at most BLOCK elements, and the
    # host sizes the input margins to cover that overhang, so every address
    # stays inside the allocation.
    quad = tl.minimum(q, PLANE - 1)
    oh = quad // OW
    ow = quad - oh * OW
    lane = q * SW + oh * ROW_DELTA

    s = tl.zeros((BLOCK,), dtype=tl.float32)
    c = tl.zeros((BLOCK,), dtype=tl.float32)
    x_n = x_ptr + pid_n * xn_stride
    w_oc = w_ptr + oc * swo

    for ic_i in range(0, IC):
        for kh_i in tl.static_range(0, KH):
            if SH == 1:
                # Row validity is a contiguous interval of the flat plane index
                # with compile-time bounds.  Expressing it on `q` (instead of on
                # a per-lane `oh`) lets `oh` die after `lane` is built: keeping
                # that 4096-wide vector alive across the unrolled tap body costs
                # ~1.8x on the 25-tap shapes.
                ok_h = (q >= (PH - kh_i) * OW) & (q < h_ow + (PH - kh_i) * OW)
            else:
                ih = oh * SH + (kh_i - PH)
                ok_h = (ih >= 0) & (ih < H)
            for kw_i in tl.static_range(0, KW):
                iw = ow * SW + (kw_i - PW)
                xv = tl.load(x_n + ic_i * sxc + lane + ((kh_i - PH) * W + (kw_i - PW)))
                # `valid` is deliberately absent: tail lanes are dropped by the
                # store mask, and their (uninitialised, possibly non-finite)
                # loads only ever touch their own accumulator lanes.
                xv = tl.where(ok_h & (iw >= 0) & (iw < W), xv, 0.0)
                wv = tl.load(w_oc + ic_i * swc + (kh_i * KW + kw_i))
                v = xv * wv
                t = s + v
                if COMPENSATE:
                    z = t - s
                    c += (s - (t - z)) + (v - z)
                s = t

    acc = s + c if COMPENSATE else s
    if HAS_BIAS:
        acc += tl.load(b_ptr + oc)

    optr = o_ptr + pid_n * on_stride + oc * PLANE + q
    tl.store(optr, acc, mask=valid)


