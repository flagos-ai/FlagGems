    nspatial = N * OH * OW
    for sp in tl.range(0, nspatial):
        n = sp // (OH * OW)
        rem = sp - n * (OH * OW)
        oh = rem // OW
        ow = rem - oh * OW
        ih = oh * SH - PH + kh
        iw = ow * SW - PW + kw
        ok = (ih >= 0) & (ih < H) & (iw >= 0) & (iw < W)
        ih_s = tl.minimum(tl.maximum(ih, 0), H - 1)
        iw_s = tl.minimum(tl.maximum(iw, 0), W - 1)
        gv = tl.load(g_ptr + n * sgn + occ_s * sgc + (oh * sgh + ow * sgw))
        gv = tl.where(ok, gv, 0.0)
        xv = tl.load(x_ptr + n * sxn + ic * sxc + (ih_s * sxh + iw_s * sxw))
        acc += gv * xv
    tl.store(
        dw_ptr + occ_s * (IC * KH * KW) + ic * (KH * KW) + (kh * KW + kw),
        acc,
        mask=occ < OC,
    )


