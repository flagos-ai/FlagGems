@triton.jit
def _conv_fwd_kernel(
    x_ptr,
    w_ptr,
    b_ptr,
    o_ptr,
    N,
    IC,
    H,
    W,
    OC,
    OH,
    OW,
    PH,
    PW,
    SH,
    SW,
    sxn,
    sxc,
    sxh,
    sxw,
    swo,
    swc,
    swh,
    sww,
    son,
    soc,
    soh,
    sow,
    HAS_BIAS: tl.constexpr,
    COMPENSATE: tl.constexpr,
    BLOCK_W: tl.constexpr,
    BLOCK_OC: tl.constexpr,
    KH: tl.constexpr,
    KW: tl.constexpr,
):
    pid_w = tl.program_id(0)
    oh = tl.program_id(1)
    pid_n = tl.program_id(2)

    ow = pid_w * BLOCK_W + tl.arange(0, BLOCK_W)
    ow_valid = ow < OW
    oc = tl.arange(0, BLOCK_OC)
    oc_valid = oc < OC

    # s holds the running sum, c the Neumaier correction.
    s = tl.zeros((BLOCK_W, BLOCK_OC), dtype=tl.float32)
    c = tl.zeros((BLOCK_W, BLOCK_OC), dtype=tl.float32)

    x_n = x_ptr + pid_n * sxn
    w_oc = w_ptr + oc * swo

    for ic_i in range(0, IC):
        for kh_i in tl.static_range(0, KH):
            ih = oh * SH - PH + kh_i
            for kw_i in tl.static_range(0, KW):
                iw = ow * SW - PW + kw_i
                m = ow_valid & (ih >= 0) & (ih < H) & (iw >= 0) & (iw < W)
                # Kunlunxin: masked load with a negative/out-of-range offset
                # returns garbage even when masked off; clamp the address and
                # keep the mask (masked+valid-addr is exact on XPU).
                ih_safe = tl.minimum(tl.maximum(ih, 0), H - 1)
                iw_safe = tl.minimum(tl.maximum(iw, 0), W - 1)
                xv = tl.load(x_n + ic_i * sxc + ih_safe * sxh + iw_safe * sxw)
                xv = tl.where(m, xv, 0.0)
                wv = tl.load(
                    w_oc + ic_i * swc + (kh_i * swh + kw_i * sww),
                    mask=oc_valid,
                    other=0.0,
                )
                v = xv[:, None] * wv[None, :]
                t = s + v
                if COMPENSATE:
                    # Neumaier step: capture the rounding error of this addition
                    # that the running sum does not recover.
                    cc = tl.where(tl.abs(s) >= tl.abs(v), (s - t) + v, (v - t) + s)
                    c += cc
                s = t

    acc = s + c if COMPENSATE else s
    if HAS_BIAS:
        acc += tl.load(b_ptr + oc, mask=oc_valid, other=0.0)[None, :]

    # Element offsets are int64: the 1x1x32768x32768 timed workload exceeds the
    # int32 element index range.
    optr = (
        o_ptr
        + pid_n.to(tl.int64) * son
        + (oh * soh + ow * sow).to(tl.int64)[:, None]
        + oc.to(tl.int64)[None, :] * soc
    )
    tl.store(optr, acc, mask=ow_valid[:, None] & oc_valid[None, :])


