    logpi = 1.1447298858494002
    inf = float("inf")

    # Tiny |x| (< 1e-37, incl. subnormals) would be flushed by FTZ hardware in
    # the Lanczos/reflection path; there log|Gamma(x)| ~= -log|x|.
    # log(x) for subnormals x = m*2^-149 (m in [1, 2^23)): bit extraction.
    xabs = tl.abs(x)
    is_tiny = (xabs > 0.0) & (xabs < 1.0e-37)
    bits = xabs.to(tl.int32, bitcast=True)
    is_sub = (bits & 2139095040) == 0  # exponent field zero
    mf = (bits & 8388607).to(tl.float32)
    logx = tl.where(is_sub, 103.27892990343185 - tl.log(mf), -tl.log(xabs))
    # (for is_sub inputs logx == -log(xabs); normal-tiny branch is direct)

    # For x > 0 use Lanczos directly (log|Gamma(x)|). For x < 0 reflect:
    # log|Gamma(x)| = log(pi) - log|sin(pi*x)| - log|Gamma(1-x)|.
    y = tl.where(x < 0.0, 1.0 - x, x)
    base = _lanczos_lgamma(y)

    r = x - tl.floor(x + 0.5)  # r in [-0.5, 0.5]; 0 at integer x
    lnsin = _log_sin_pi(r)

    out = tl.where(x < 0.0, logpi - lnsin - base, base)
    out = tl.where(is_tiny, logx, out)

    # +/-inf map to +inf (torch semantics); NaN propagates as NaN.
    is_inf = (x == inf) | (x == -inf)
    out = tl.where(is_inf, inf, out)
    return out


