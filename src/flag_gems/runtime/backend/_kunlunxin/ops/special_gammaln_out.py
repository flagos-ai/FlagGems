@triton.jit
def _lanczos_lgamma(u):
    # log|Gamma(u)| via Lanczos g=7, n=9. Accurate for all u > 0 in fp32
    # (arguments map to u+1 in (1, inf) where the approximation is smooth).
    t = u + 7.5
    s = (
        1.0
        + 676.5203681218851 / (u + 1.0)
        + (-1259.1392167224028) / (u + 2.0)
        + 771.32342877765313 / (u + 3.0)
        + (-176.61502916214059) / (u + 4.0)
        + 12.507343278686905 / (u + 5.0)
        + (-0.13857109526572012) / (u + 6.0)
        + 9.9843695780195716e-06 / (u + 7.0)
        + 1.5056327351493116e-07 / (u + 8.0)
    )
    logsqrt2pi = 0.9189385332046727
    lg1 = logsqrt2pi + (u + 0.5) * tl.log(t) - t + tl.log(s)
    return lg1 - tl.log(u)


@triton.jit
def _log_sin_pi(r):
    # log|sin(pi*r)| for r in [-0.5, 0.5], single-log form.
    # For |r| >= 0.05 use |sin(pi*r)| directly (>= 0.156, well conditioned).
    # For smaller |r| use sin(pi*r)/(pi*r) = 1 + q, so that
    #   |sin(pi*r)| = pi*|r| * (1 + q),  q = -(pi*r)^2/6 + (pi*r)^4/120 - ...
    # This avoids the hardware sin's large absolute error near 0.
    # Pole (r == 0) gives log(0) = -inf.
    pi = 3.141592653589793
    a = tl.abs(r)
    u = (pi * a) * (pi * a)  # <= (pi/2)^2; subnormal u just yields q = 0
    q = (
        -0.16666666666666666 * u
        + 0.008333333333333333 * u * u
        - 0.0001984126984126984 * u * u * u
        + 2.7557319223985893e-06 * u * u * u * u
    )
    m = tl.where(a < 0.05, pi * a * (1.0 + q), tl.abs(tl.sin(pi * a)))
    return tl.log(m)


