@triton.jit
def _jagged_to_padded_dense_rpc_kernel(
    values_ptr,
    offsets_ptr,
    out_ptr,
    padding_value,
    B: tl.constexpr,
    M: tl.constexpr,
    R: tl.constexpr,
    BLOCK: tl.constexpr,
):
    """Rows-per-CTA: R independent batch rows are processed per program.

    Each output element is written exactly once:
      out[row, col] = values[offsets[row] + col]  for col < seq_len (<= M)
                      padding_value                otherwise
    """
    pid = tl.program_id(0)
    for r in range(0, R):
        row = pid * R + r
        if row < B:
            s = tl.load(offsets_ptr + row)
            seq = tl.load(offsets_ptr + row + 1) - s
            for c in range(0, M, BLOCK):
                col = c + tl.arange(0, BLOCK)
                src = (col < seq) & (col < M)
                val = tl.load(values_ptr + s + col, mask=src, other=padding_value)
                res = tl.where(col < seq, val, padding_value)
                tl.store(out_ptr + row * M + col, res, mask=col < M)


def _next_pow2(x):
    p = 1
    while p < x:
        p *= 2
    return p


def _rows_per_cta(batch, block):
    """Empirically good R: one program per ~sqrt(batch) rows, power of two,
    additionally capped so a CTA never owns more than ~8K element lanes."""
    if batch <= 1:
        return 1
    r = int(math.isqrt(batch))
    p = 1
    while p * 2 <= r:
        p *= 2
    p = max(1, min(p, 64))
    cap = max(1, 8192 // block)
    if p > cap:
        p = cap
    if p > batch:
        p = batch
    return p


