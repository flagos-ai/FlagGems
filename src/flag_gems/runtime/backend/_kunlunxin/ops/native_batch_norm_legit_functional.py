# ---------------------------------------------------------------------------
# Batch norm forward, functional variant of
# torch.ops.aten._native_batch_norm_legit_functional.
#
# Contiguous [N, C, *spatial] input: slice (n, c) is `spatial_dim` contiguous
# elements at offset (n*C + c)*spatial_dim.  Per channel the batch statistics
# reduce over N * spatial_dim elements.
#
# Training (track_running_stats) semantics reproduced here:
#   mean  = sum / count
#   var   = max(sumsq / count - mean^2, 0)                 (biased, used for norm)
#   inv   = 1 / sqrt(var + eps)
#   out   = weight * (x - mean) * inv + bias
#   running_mean = (1-momentum)*running_mean + momentum*mean
#   running_var  = (1-momentum)*running_var  + momentum*var*(count/(count-1))
# Returns the same 5-tuple as the aten op:
#   (out, save_mean, save_invstd, running_mean, running_var)
# where save_mean / save_invstd are per-channel tensors in the input dtype and
# Private copies of running_mean/running_var are updated and returned.
#
# The TritonXPU compiler only accepts reductions that are NOT inside a
# loop-carried scalar accumulator, so statistics accumulate in TILE-wide
# vector registers and are reduced once after the loops.
# ---------------------------------------------------------------------------


@triton.jit
def _bn_fused_train(
    x_ptr,
    y_ptr,
    w_ptr,
    b_ptr,
    rm_ptr,
    rv_ptr,
    save_mean_ptr,
    save_var_ptr,
    batch_dim,
    feat_dim,
    spatial_dim,
    inv_count,
    unbias_scale,
    momentum,
    eps,
    HAS_W: tl.constexpr,
    HAS_B: tl.constexpr,
    HAS_RM: tl.constexpr,
    HAS_RV: tl.constexpr,
    TILE_S: tl.constexpr,
):
    c = tl.program_id(0)
    row_stride = feat_dim * spatial_dim
    offs = tl.arange(0, TILE_S)
    mask = offs < spatial_dim

    s = tl.zeros([TILE_S], dtype=tl.float32)
    sq = tl.zeros([TILE_S], dtype=tl.float32)
    for b in range(0, batch_dim):
        base = b * row_stride + c * spatial_dim
        x = tl.load(x_ptr + base + offs, mask=mask, other=0.0).to(tl.float32)
        s += x
        sq += tl.where(mask, x * x, 0.0)

    tsum = tl.sum(s)
    tsq = tl.sum(sq)
    mean = tsum * inv_count
    var = tsq * inv_count - mean * mean
    var = tl.maximum(var, 0.0)
    inv = 1.0 / tl.sqrt(var + eps)

    tl.store(save_mean_ptr + c, mean.to(save_mean_ptr.dtype.element_ty))
    tl.store(save_var_ptr + c, inv.to(save_var_ptr.dtype.element_ty))

    if HAS_RM:
        old = tl.load(rm_ptr + c).to(tl.float32)
        new = (1.0 - momentum) * old + momentum * mean
        tl.store(rm_ptr + c, new.to(rm_ptr.dtype.element_ty))
    if HAS_RV:
        old = tl.load(rv_ptr + c).to(tl.float32)
        uvar = var * unbias_scale
        new = (1.0 - momentum) * old + momentum * uvar
        tl.store(rv_ptr + c, new.to(rv_ptr.dtype.element_ty))

    if HAS_W:
        w = tl.load(w_ptr + c).to(tl.float32)
    else:
        w = 1.0
    if HAS_B:
        bb = tl.load(b_ptr + c).to(tl.float32)
    else:
        bb = 0.0
    scale = w * inv
    shift = bb - mean * scale

    for b in range(0, batch_dim):
        base = b * row_stride + c * spatial_dim
        x = tl.load(x_ptr + base + offs, mask=mask).to(tl.float32)
        y = x * scale + shift
        tl.store(y_ptr + base + offs, y, mask=mask)


@triton.jit
def _bn_slice_stats(
    x_ptr,
    part_sum_ptr,
    part_sq_ptr,
    batch_dim,
    feat_dim,
    spatial_dim,
    TILE_S: tl.constexpr,
):
    pid = tl.program_id(0)
    c = pid % feat_dim
    n = pid // feat_dim
    out_idx = c * batch_dim + n
    base = pid * spatial_dim
    s = tl.zeros([TILE_S], dtype=tl.float32)
    sq = tl.zeros([TILE_S], dtype=tl.float32)
    for off in range(0, spatial_dim, TILE_S):
        idx = off + tl.arange(0, TILE_S)
        m = idx < spatial_dim
        x = tl.load(x_ptr + base + idx, mask=m, other=0.0).to(tl.float32)
        s += x
        sq += tl.where(m, x * x, 0.0)
    tl.store(part_sum_ptr + out_idx, tl.sum(s))
    tl.store(part_sq_ptr + out_idx, tl.sum(sq))


@triton.jit
def _bn_combine(
    part_sum_ptr,
    part_sq_ptr,
    mean_f_ptr,
    inv_f_ptr,
    save_mean_ptr,
    save_var_ptr,
    rm_ptr,
    rv_ptr,
    batch_dim,
    feat_dim,
    count,
    unbias_scale,
    momentum,
    eps,
    HAS_RM: tl.constexpr,
    HAS_RV: tl.constexpr,
    TILE_N: tl.constexpr,
):
    c = tl.program_id(0)
    idx = tl.arange(0, TILE_N)
    m = idx < batch_dim
    psum = tl.load(part_sum_ptr + c * batch_dim + idx, mask=m, other=0.0)
    psq = tl.load(part_sq_ptr + c * batch_dim + idx, mask=m, other=0.0)
    tsum = tl.sum(psum)
    tsq = tl.sum(psq)
    mean = tsum / count
    var = tsq / count - mean * mean
    var = tl.maximum(var, 0.0)
    inv = 1.0 / tl.sqrt(var + eps)

    tl.store(mean_f_ptr + c, mean)
    tl.store(inv_f_ptr + c, inv)
    tl.store(save_mean_ptr + c, mean.to(save_mean_ptr.dtype.element_ty))
    tl.store(save_var_ptr + c, inv.to(save_var_ptr.dtype.element_ty))

    if HAS_RM:
        old = tl.load(rm_ptr + c).to(tl.float32)
        new = (1.0 - momentum) * old + momentum * mean
        tl.store(rm_ptr + c, new.to(rm_ptr.dtype.element_ty))
    if HAS_RV:
        old = tl.load(rv_ptr + c).to(tl.float32)
        uvar = var * unbias_scale
        new = (1.0 - momentum) * old + momentum * uvar
        tl.store(rv_ptr + c, new.to(rv_ptr.dtype.element_ty))


@triton.jit
def _bn_eval_prep(
    rm_ptr,
    rv_ptr,
    mean_f_ptr,
    inv_f_ptr,
    save_mean_ptr,
    save_var_ptr,
    eps,
):
    c = tl.program_id(0)
    mean = tl.load(rm_ptr + c).to(tl.float32)
    var = tl.maximum(tl.load(rv_ptr + c).to(tl.float32), 0.0)
    inv = 1.0 / tl.sqrt(var + eps)
    tl.store(mean_f_ptr + c, mean)
    tl.store(inv_f_ptr + c, inv)
    tl.store(save_mean_ptr + c, mean.to(save_mean_ptr.dtype.element_ty))
    tl.store(save_var_ptr + c, inv.to(save_var_ptr.dtype.element_ty))


@triton.jit
def _bn_normalize(
    x_ptr,
    y_ptr,
    mean_f_ptr,
    inv_f_ptr,
    w_ptr,
    b_ptr,
    feat_dim,
    spatial_dim,
    HAS_W: tl.constexpr,
    HAS_B: tl.constexpr,
    TILE_S: tl.constexpr,
):
    pid = tl.program_id(0)
    c = pid % feat_dim
    base = pid * spatial_dim

    mean = tl.load(mean_f_ptr + c)
    inv = tl.load(inv_f_ptr + c)
    if HAS_W:
        w = tl.load(w_ptr + c).to(tl.float32)
    else:
        w = 1.0
    if HAS_B:
        bb = tl.load(b_ptr + c).to(tl.float32)
    else:
        bb = 0.0
    scale = w * inv
    shift = bb - mean * scale

    for off in range(0, spatial_dim, TILE_S):
        idx = off + tl.arange(0, TILE_S)
        m = idx < spatial_dim
        x = tl.load(x_ptr + base + idx, mask=m).to(tl.float32)
        y = x * scale + shift
        tl.store(y_ptr + base + idx, y, mask=m)


_FUSED_MAX_SPATIAL = 4096
_FUSED_MAX_BATCH = 64


def _tile(n):
    return min(triton.next_power_of_2(n), 4096)


def native_batch_norm_legit_functional(
    input,
    weight=None,
    bias=None,
    running_mean=None,
    running_var=None,
    training=False,
    momentum=0.1,
    eps=1e-05,
):
    with torch_device_fn.device(input.device):
        input = input.contiguous()
        weight = weight.contiguous() if weight is not None else None
        bias = bias.contiguous() if bias is not None else None
        running_mean = (
            running_mean.clone(memory_format=torch.contiguous_format)
            if running_mean is not None
            else None
        )
        running_var = (
            running_var.clone(memory_format=torch.contiguous_format)
            if running_var is not None
            else None
        )
        N = input.shape[0]
        C = input.shape[1]
        S = 1
        for d in range(2, input.dim()):
            S = S * input.shape[d]
        dev = input.device
        dt = input.dtype

        out = torch.empty_like(input)
        save_mean = torch.empty(C, dtype=dt, device=dev)
        save_var = torch.empty(C, dtype=dt, device=dev)
        mean_f = torch.empty(C, dtype=torch.float32, device=dev)
        inv_f = torch.empty(C, dtype=torch.float32, device=dev)

        w = weight if weight is not None else input
        b = bias if bias is not None else input
        has_w = weight is not None
        has_b = bias is not None
        has_rm = running_mean is not None
        has_rv = running_var is not None
        rm = running_mean if has_rm else input
        rv = running_var if has_rv else input

        count = N * S

        if training:
            if S <= _FUSED_MAX_SPATIAL and N <= _FUSED_MAX_BATCH:
                _bn_fused_train[(C,)](
                    input,
                    out,
                    w,
                    b,
                    rm,
                    rv,
                    save_mean,
                    save_var,
                    N,
                    C,
                    S,
                    1.0 / float(count),
                    float(count) / float(count - 1) if count > 1 else 1.0,
                    float(momentum),
                    float(eps),
                    HAS_W=has_w,
                    HAS_B=has_b,
                    HAS_RM=has_rm,
                    HAS_RV=has_rv,
                    TILE_S=_tile(S),
                    num_warps=4,
                )
            else:
                n_slices = N * C
                part_sum = torch.empty(n_slices, dtype=torch.float32, device=dev)
                part_sq = torch.empty(n_slices, dtype=torch.float32, device=dev)
                tile_s = _tile(S)
                _bn_slice_stats[(n_slices,)](
                    input,
                    part_sum,
                    part_sq,
                    N,
                    C,
                    S,
                    TILE_S=tile_s,
                    num_warps=4,
                )
                _bn_combine[(C,)](
                    part_sum,
                    part_sq,
                    mean_f,
                    inv_f,
                    save_mean,
                    save_var,
                    rm,
                    rv,
                    N,
                    C,
                    float(count),
                    float(count) / float(count - 1) if count > 1 else 1.0,
                    float(momentum),
                    float(eps),
                    HAS_RM=has_rm,
                    HAS_RV=has_rv,
                    TILE_N=_tile(N),
                    num_warps=4,
                )
                _bn_normalize[(n_slices,)](
                    input,
                    out,
                    mean_f,
                    inv_f,
                    w,
                    b,
                    C,
                    S,
                    HAS_W=has_w,
                    HAS_B=has_b,
                    TILE_S=tile_s,
                    num_warps=4,
                )
        else:
            if not (has_rm and has_rv):
                raise RuntimeError(
                    "running_mean/running_var must be defined in evaluation mode"
                )
            n_slices = N * C
            tile_s = _tile(S)
            _bn_eval_prep[(C,)](
                rm,
                rv,
                mean_f,
                inv_f,
                save_mean,
                save_var,
                float(eps),
            )
            _bn_normalize[(n_slices,)](
                input,
                out,
                mean_f,
                inv_f,
                w,
                b,
                C,
                S,
                HAS_W=has_w,
                HAS_B=has_b,
                TILE_S=tile_s,
                num_warps=4,
            )

        if not training:
            save_mean = torch.empty(0, dtype=dt, device=dev)
            save_var = torch.empty(0, dtype=dt, device=dev)
        return (out.view(input.shape), save_mean, save_var, running_mean, running_var)


_native_batch_norm_legit_functional = native_batch_norm_legit_functional
