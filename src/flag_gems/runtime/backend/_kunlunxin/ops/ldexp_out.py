    exp_t = None
    if torch.is_tensor(other):
        exp_t = other
    elif isinstance(other, float):
        raise RuntimeError("ldexp: exponent must be an integer")
    else:
        scalar_exp = int(other)

    if not torch.is_tensor(self):
        raise TypeError("ldexp: self must be a Tensor")
    if not torch.is_tensor(out):
        raise TypeError("ldexp: out must be a Tensor")

    dev = self.device
    if exp_t is not None and exp_t.device != dev:
        if (
            exp_t.dim() == 0
            and exp_t.device.type == "cpu"
            and not exp_t.dtype.is_floating_point
            and not exp_t.dtype.is_complex
        ):
            scalar_exp = int(exp_t.item())
            exp_t = None
        else:
            raise RuntimeError(
                "Expected all tensors to be on the same device, but found at "
                "least two devices"
            )
    if out.device != dev:
        raise RuntimeError(
            "Expected all tensors to be on the same device, but found at "
            "least two devices"
        )

    sdt = self.dtype
    if exp_t is not None and (exp_t.dtype.is_floating_point or exp_t.dtype.is_complex):
        raise RuntimeError("ldexp: exponent must be an integral tensor")

    odt = out.dtype
    if sdt.is_complex:
        comp64 = sdt == torch.complex128
    else:
        comp64 = sdt == torch.float64
    # Shape/dtype metadata or a storage-sharing view; no tensor computation.
    result_dtype = sdt if sdt.is_floating_point or sdt.is_complex else torch.float32
    if not torch.can_cast(result_dtype, odt):  # allow-torch-compute
        raise RuntimeError(
            "result type {} can't be cast to the desired output type {}".format(
                sdt, odt
            )
        )

    oshape = (
        # Shape/dtype metadata or a storage-sharing view; no tensor computation.
        self.shape
        if exp_t is None
        else torch.broadcast_shapes(self.shape, exp_t.shape)  # allow-torch-compute
    )
    if tuple(out.shape) != tuple(oshape):
        out.resize_(oshape)

    if _overlap(out, self) == "partial":
        raise RuntimeError(_OVERLAP_MSG)
    if exp_t is not None and _overlap(out, exp_t) == "partial":
        raise RuntimeError(_OVERLAP_MSG)

    cplx = out.is_complex()
    if cplx:
        # Shape/dtype metadata or a storage-sharing view; no tensor computation.
        if sdt.is_complex:
            x_t = torch.view_as_real(self)  # allow-torch-compute
        else:
            x_t = self
        # Shape/dtype metadata or a storage-sharing view; no tensor computation.
        o_t = torch.view_as_real(out)  # allow-torch-compute
    else:
        x_t = self
        o_t = out

    nreal = o_t.numel()
    if nreal == 0:
        return out
    tile = _pick_tile(nreal)
    warps = _pick_warps(tile)
    # A float16 value container needs only a +-41 exponent clamp, which makes a
    # single exact power-of-two multiply sufficient.  If the result must be held
    # in a wider container (float32/bfloat16/float64) the wider clamp is needed.
    f16c = odt == torch.float16 and sdt == torch.float16 and not comp64

    if scalar_exp is None:
        e64 = exp_t.dtype == torch.int64 or exp_t.dtype == torch.uint64
    else:
        e64 = False
        scalar_exp = max(-2099, min(2099, scalar_exp))

    # ---- fast path: everything contiguous over the same logical shape -----
    flat_ok = (
        x_t.is_contiguous()
        and o_t.is_contiguous()
        and tuple(x_t.shape) == tuple(o_t.shape)
    )
    grid = (triton.cdiv(nreal, tile),)
    masked = (nreal % tile) != 0
    if flat_ok and scalar_exp is not None:
        _ldexp_flat[grid](
            x_t,
            x_t,
            o_t,
            nreal,
            BLOCK=tile,
            F64=comp64,
            E64=False,
            ESCALAR=True,
            NS=scalar_exp,
            E_HALF=False,
            MASKED=masked,
            F16C=f16c,
            num_warps=warps,
        )
        return out
    if flat_ok and exp_t is not None:
        if exp_t.is_contiguous() and tuple(exp_t.shape) == tuple(oshape):
            _ldexp_flat[grid](
                x_t,
                exp_t,
                o_t,
                nreal,
                BLOCK=tile,
                F64=comp64,
                E64=e64,
                ESCALAR=False,
                NS=0,
                E_HALF=cplx,
                MASKED=masked,
                F16C=f16c,
                num_warps=warps,
            )
            return out

    # ---- generic path -----------------------------------------------------
    rank = len(oshape)
    if cplx:
        if sdt.is_complex:
            xs = _bstride(x_t.shape[:-1], x_t.stride()[:-1], rank) + [
                int(x_t.stride()[-1])
            ]
        else:
            xs = _bstride(x_t.shape, x_t.stride(), rank) + [0]
        os_ = _bstride(o_t.shape[:-1], o_t.stride()[:-1], rank) + [
            int(o_t.stride()[-1])
        ]
        sizes = list(oshape) + [2]
    else:
        xs = _bstride(x_t.shape, x_t.stride(), rank)
        os_ = _bstride(o_t.shape, o_t.stride(), rank)
        sizes = list(oshape)
    if exp_t is None:
        es = [0] * len(sizes)
    else:
        es = _bstride(exp_t.shape, exp_t.stride(), rank)
        if cplx:
            es = es + [0]
    sizes, (xs, es, os_) = _collapse(sizes, [xs, es, os_])
    nd = len(sizes)
    if nd > _MAXDIM:
        raise RuntimeError("ldexp: unsupported tensor rank {}".format(nd))
    pad = _MAXDIM - nd
    sizes = sizes + [1] * pad
    xs = xs + [0] * pad
    es = es + [0] * pad
    os_ = os_ + [0] * pad

    grid = (triton.cdiv(nreal, tile),)
    _ldexp_gen[grid](
        x_t,
        x_t if exp_t is None else exp_t,
        o_t,
        nreal,
        *sizes,
        *xs,
        *es,
        *os_,
        BLOCK=tile,
        NDIM=nd,
        F64=comp64,
        E64=e64,
        ESCALAR=(exp_t is None),
        NS=(scalar_exp if scalar_exp is not None else 0),
        F16C=f16c,
        REAL_TO_COMPLEX=cplx and not sdt.is_complex,
        num_warps=warps,
    )
    return out


