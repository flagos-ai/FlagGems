def _pick_tile(n):
    tile = _TILE_MAX
    while tile > _TILE_MIN and n // tile < _MIN_PROGRAMS:
        tile //= 2
    return tile


def _pick_warps(tile):
    # warp count does not change the generated code on this backend (verified by
    # compile probe), so cap it at the largest value already measured.
    return min(16, max(4, tile // 512))


