def _bilinear_reciprocal_scale(src_size, dst_size, align_corners, scale):
    if align_corners:
        if dst_size > 1:
            return (src_size - 1) / (dst_size - 1)
        else:
            return 0.0
    else:
        if scale is not None and scale > 0:
            return 1.0 / scale
        else:
            return src_size / dst_size


def _fast_2x_shape(input, output_size, align_corners, scales_h, scales_w):
    """Return (N, C, IH, IW, OH, OW) when the exact-2x fast path applies."""
    if align_corners or input.ndim != 4 or not input.is_contiguous():
        return None
    N, C, IH, IW = input.shape
    OH, OW = output_size
    if IH < 1 or IW < _UB2D_MIN_IW or (IW & (IW - 1)) != 0:
        return None
    if OH != 2 * IH or OW != 2 * IW:
        return None
    for scale in (scales_h, scales_w):
        if scale is not None and float(scale) != 2.0:
            return None
    if input.dtype not in (torch.float16, torch.bfloat16, torch.float32):
        return None
    return N, C, IH, IW, OH, OW


def _launch_fast_2x(input, output, NC, IH, IW):
    T = 2 * IW
    is32 = input.dtype == torch.float32
    is_bf16 = input.dtype == torch.bfloat16
    fast_k = _ub2d_2x_kernel_32 if is32 else _ub2d_2x_kernel_16
    edge_k = _ub2d_2x_edge_kernel_32 if is32 else _ub2d_2x_edge_kernel_16
    if is32:
        ptr_o = output.view(torch.uint64)
    else:
        ptr_o = output.view(torch.uint32)

    if NC == 1:
        spans = [(0, 1, 2, IH - 4)]  # only the doubly-interior rows
    else:
        spans = [
            (0, 1, 2, IH - 2),  # image 0, skip the two top rows
            (1, NC - 2, 0, IH),  # interior images, every row
            (NC - 1, 1, 0, IH - 2),  # last image, skip the two bottom rows
        ]

    with torch_device_fn.device(input.device):
        for nc_start, nc_count, h_start, h_count in spans:
            if nc_count <= 0 or h_count <= 0:
                continue
            grid = (h_count, nc_count)
            if is32:
                fast_k[grid](ptr_o, input, h_start, nc_start, IH=IH, IW=IW, T=T)
            else:
                fast_k[grid](
                    ptr_o,
                    input,
                    h_start,
                    nc_start,
                    IH=IH,
                    IW=IW,
                    T=T,
                    IS_BF16=is_bf16,
                )
        if is32:
            edge_k[(4,)](ptr_o, input, NC, IH=IH, IW=IW, T=T)
        else:
            edge_k[(4,)](ptr_o, input, NC, IH=IH, IW=IW, T=T, IS_BF16=is_bf16)
    return output


def upsample_bilinear2d(
    input: torch.Tensor,
    output_size: Tuple[int],
    align_corners: bool = False,
    scales_h: Optional[float] = None,
    scales_w: Optional[float] = None,
) -> torch.Tensor:
    logger.debug("GEMS_KUNLUNXIN UPSAMPLE_BILINEAR2D")
    assert input.device.type == device
    assert input.ndim == 4, "The ndim of input must be 4"
    assert len(output_size) == 2, "The len of output_size must be 2"

    OH, OW = output_size
    N, C, IH, IW = input.shape

    fast = _fast_2x_shape(input, output_size, align_corners, scales_h, scales_w)
    if fast is not None:
        output = torch.empty((N, C, OH, OW), device=input.device, dtype=input.dtype)
        return _launch_fast_2x(input, output, N * C, IH, IW)

    reciprocal_scale_h = _bilinear_reciprocal_scale(IH, OH, align_corners, scales_h)
    reciprocal_scale_w = _bilinear_reciprocal_scale(IW, OW, align_corners, scales_w)

    output = torch.empty((N, C, OH, OW), device=input.device, dtype=input.dtype)
    # Row-grid: one program per output row; BX covers the full row (padded to a
    # power of two, masked tail).
    block_size = triton.next_power_of_2(OW) if OW > 0 else 1
    grid = (N * C * OH,)

    with torch_device_fn.device(input.device):
        upsample_bilinear2d_kernel[grid](
            output,
            input,
            OH,
            OW,
            IH,
            IW,
            reciprocal_scale_h,
            reciprocal_scale_w,
            N,
            C,
            align_corners,
            BX=block_size,
        )
    return output
