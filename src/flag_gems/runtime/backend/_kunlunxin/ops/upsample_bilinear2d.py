@triton.jit
def upsample_bilinear2d_kernel(
    ptr_o,
    ptr_i,
    OH,
    OW,
    IH,
    IW,
    reciprocal_scale_h,
    reciprocal_scale_w,
    N: tl.constexpr,
    C: tl.constexpr,
    ALIGN_CORNERS: tl.constexpr,
    BX: tl.constexpr,
):
    row = ext.program_id(axis=0)
    oh = row % OH
    nc = row // OH
    c = nc % C
    n = nc // C

    ow = tl.arange(0, BX)
    mask = ow < OW

    # Compute the source coordinates (ATen area_pixel_compute_source_index).
    if ALIGN_CORNERS:
        # When align_corners is True, map corners to corners:
        # real = oh * (IH - 1) / (OH - 1), 0 when OH == 1.
        real_h = tl.where(
            OH > 1,
            oh.to(tl.float32) * (IH - 1) / (OH - 1),
            0.0,
        )
        real_w = tl.where(
            OW > 1,
            ow.to(tl.float32) * (IW - 1) / (OW - 1),
            0.0,
        )
    else:
        # When align_corners is False: real = (oh + 0.5) * scale - 0.5.
        real_h = (oh.to(tl.float32) + 0.5) * reciprocal_scale_h - 0.5
        real_w = (ow.to(tl.float32) + 0.5) * reciprocal_scale_w - 0.5

    # Clamp to valid range.
    real_h = tl.maximum(real_h, 0.0)
    real_w = tl.maximum(real_w, 0.0)

    # Top-left corner of the 2x2 region.
    h0 = tl.minimum(real_h.to(tl.int32), IH - 1)
    w0 = tl.minimum(real_w.to(tl.int32), IW - 1)
    h1 = tl.minimum(h0 + 1, IH - 1)
    w1 = tl.minimum(w0 + 1, IW - 1)

    # Interpolation weights, clamped to [0, 1].
    h_weight = real_h - h0.to(tl.float32)
    w_weight = real_w - w0.to(tl.float32)
    h_weight = tl.maximum(tl.minimum(h_weight, 1.0), 0.0)
    w_weight = tl.maximum(tl.minimum(w_weight, 1.0), 0.0)

    base = (n * C + c) * (IH * IW)
    off_00 = base + h0 * IW + w0
    off_01 = base + h0 * IW + w1
    off_10 = base + h1 * IW + w0
    off_11 = base + h1 * IW + w1

    data_00 = tl.load(ptr_i + off_00, mask=mask, other=0.0)
    data_01 = tl.load(ptr_i + off_01, mask=mask, other=0.0)
    data_10 = tl.load(ptr_i + off_10, mask=mask, other=0.0)
    data_11 = tl.load(ptr_i + off_11, mask=mask, other=0.0)

    w00 = (1.0 - h_weight) * (1.0 - w_weight)
    w01 = (1.0 - h_weight) * w_weight
    w10 = h_weight * (1.0 - w_weight)
    w11 = h_weight * w_weight

    result = (
        data_00.to(tl.float32) * w00
        + data_01.to(tl.float32) * w01
        + data_10.to(tl.float32) * w10
        + data_11.to(tl.float32) * w11
    )
    result = result.to(data_00.dtype)

    # Store index row*OW + ow is affine/stride-1 in the lanes -> block DMA.
    tl.store(ptr_o + row * OW + ow, result, mask=mask)


# ---------------------------------------------------------------------------
# Exact-2x fast path (align_corners=False, OH == 2*IH, OW == 2*IW)
#
# XPU3 profiling (harness/perf_ir/prof_ub2d_*): the generic per-output-row
# kernel is 99.5% of the device time and is bound by (a) one short 512B-4KB DMA
# per program (55-60 ns fixed cost each) and (b) per-lane gather loads.
#
# The fast path keeps every access a 1-D contiguous block: one program handles
# the two output rows generated by one input row with 2*IW lanes.  With the lane
# index t = which*IW + k (which in {0,1} selects the even/odd output row, k is
# the input column) the two source rows of the vertical pair are *adjacent* in
# memory:
#     A span = in_img + (h-1)*IW + t   -> rows (h-1 | h)
#     B span = A span + IW             -> rows (h   | h+1)
# so six plain contiguous loads read everything.  The vertical weight is 0.75
# for the first half and 0.25 for the second, and the two output words for lane
# t sit at (nc*OH + 2*h)*IW + t, i.e. both output rows go out with one
# contiguous store.  Loads are unmasked: the ATen row clamp is applied as a
# value select, and the program grid is trimmed (on the host) so no unmasked
# access steps outside the tensor.  The handful of trimmed (image, row) pairs
# are finished by `_ub2d_2x_edge_kernel`, which keeps the masked/clamped form.
# ---------------------------------------------------------------------------
_UB2D_MIN_IW = 128  # 2*IW lanes must be a power-of-two block of >= 256 lanes


@triton.jit
def _f32_to_bf16_bits(x):
    b = x.to(tl.uint32, bitcast=True)
    # round-half-to-even on the discarded 16 mantissa bits
    b = b + 0x7FFF + ((b >> 16) & 1)
    return b >> 16


@triton.jit
def _ub2d_2x_kernel_16(
    ptr_o32,
    ptr_i,
    H_START,
    NC_START,
    IH: tl.constexpr,
    IW: tl.constexpr,
    T: tl.constexpr,
    IS_BF16: tl.constexpr,
):
    h = tl.program_id(0) + H_START
    nc = tl.program_id(1) + NC_START
    t = tl.arange(0, T)
    which = t // IW
    k = t % IW
    lim = IW - 1
    bb = nc * IH * IW + (h - 1) * IW
    aAm = tl.load(ptr_i + bb + t - 1)
    aA0 = tl.load(ptr_i + bb + t)
    aAp = tl.load(ptr_i + bb + t + 1)
    aBm = tl.load(ptr_i + bb + IW + t - 1)
    aB0 = tl.load(ptr_i + bb + IW + t)
    aBp = tl.load(ptr_i + bb + IW + t + 1)
    # ATen clamps the source row into the image; only the half whose row falls
    # outside needs replacing (the other half already holds that row).
    m0 = (which == 0) & (h == 0)
    aAm = tl.where(m0, aBm, aAm)
    aA0 = tl.where(m0, aB0, aA0)
    aAp = tl.where(m0, aBp, aAp)
    m1 = (which == 1) & (h == IH - 1)
    aBm = tl.where(m1, aAm, aBm)
    aB0 = tl.where(m1, aA0, aB0)
    aBp = tl.where(m1, aAp, aBp)
    aAm = aAm.to(tl.float32)
    aA0 = aA0.to(tl.float32)
    aAp = aAp.to(tl.float32)
    aBm = aBm.to(tl.float32)
    aB0 = aB0.to(tl.float32)
    aBp = aBp.to(tl.float32)
    w = 0.75 - 0.5 * which.to(tl.float32)
    eA = tl.where(k == 0, aA0, 0.25 * aAm + 0.75 * aA0)
    oA = tl.where(k == lim, aA0, 0.75 * aA0 + 0.25 * aAp)
    eB = tl.where(k == 0, aB0, 0.25 * aBm + 0.75 * aB0)
    oB = tl.where(k == lim, aB0, 0.75 * aB0 + 0.25 * aBp)
    E = (1.0 - w) * eA + w * eB
    odd_w = (1.0 - w) * oA + w * oB
    if IS_BF16:
        # bf16 = top 16 bits of the fp32 pattern with round-half-to-even; the
        # fp16/bf16 bitcast spellings hit an XPU lowering limit, so round here.
        lo = _f32_to_bf16_bits(E)
        hi = _f32_to_bf16_bits(odd_w)
    else:
        lo = E.to(tl.float16).to(tl.uint16, bitcast=True).to(tl.uint32)
        hi = odd_w.to(tl.float16).to(tl.uint16, bitcast=True).to(tl.uint32)
    tl.store(ptr_o32 + (nc * 2 * IH + 2 * h) * IW + t, lo | (hi << 16))


@triton.jit
def _ub2d_2x_kernel_32(
    ptr_o64,
    ptr_i,
    H_START,
    NC_START,
    IH: tl.constexpr,
    IW: tl.constexpr,
    T: tl.constexpr,
):
    h = tl.program_id(0) + H_START
    nc = tl.program_id(1) + NC_START
    t = tl.arange(0, T)
    which = t // IW
    k = t % IW
    lim = IW - 1
    bb = nc * IH * IW + (h - 1) * IW
    aAm = tl.load(ptr_i + bb + t - 1)
    aA0 = tl.load(ptr_i + bb + t)
    aAp = tl.load(ptr_i + bb + t + 1)
    aBm = tl.load(ptr_i + bb + IW + t - 1)
    aB0 = tl.load(ptr_i + bb + IW + t)
    aBp = tl.load(ptr_i + bb + IW + t + 1)
    m0 = (which == 0) & (h == 0)
    aAm = tl.where(m0, aBm, aAm)
    aA0 = tl.where(m0, aB0, aA0)
    aAp = tl.where(m0, aBp, aAp)
    m1 = (which == 1) & (h == IH - 1)
    aBm = tl.where(m1, aAm, aBm)
    aB0 = tl.where(m1, aA0, aB0)
    aBp = tl.where(m1, aAp, aBp)
