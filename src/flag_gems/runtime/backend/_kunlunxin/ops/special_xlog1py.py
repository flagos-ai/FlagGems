import torch
import triton
import triton.language as tl

# Generated by KernelGen: https://github.com/flagos-ai/KernelGen
from flag_gems.runtime import torch_device_fn


@triton.jit
def _xlog1py_kernel(
    A, B, output_ptr, n_elements, BLOCK: tl.constexpr, UPCAST: tl.constexpr
):
    pid = tl.program_id(0)
    offs = pid * BLOCK + tl.arange(0, BLOCK)
    mask = offs < n_elements
    a = tl.load(A + offs, mask=mask, other=0.0)
    b = tl.load(B + offs, mask=mask, other=0.0)
    if UPCAST:
        a = a.to(tl.float32)
        b = b.to(tl.float32)
    lp = tl.log(1.0 + b)
    r = a * lp
    # torch xlog1py semantics: when `a` is exactly +/-0 the result is +0,
    # except that a NaN in `b` still propagates
    # (xlog1py(0, nan) == nan, xlog1py(-0, -1) == 0, xlog1py(0, -inf) == 0).
    # `a*a == 0` is true exactly for +/-0 (robust on this backend).
    za = a * a == 0.0
    r = tl.where(za & (b == b), 0.0, r)
    r = r.to(output_ptr.dtype.element_ty)
    tl.store(output_ptr + offs, r, mask=mask)


def special_xlog1py(A, B):
    with torch_device_fn.device(A.device):
        out = torch.empty_like(A)
        n_elements = A.numel()
        if n_elements == 0:
            return out
        upcast = A.dtype in (torch.float16, torch.bfloat16)
        # Size-adaptive dispatch: the 8192/8 config is fastest for large tensors,
        # but a single oversized CTA hurts the ~4K-element workloads.
        if n_elements <= 4096:
            BLOCK = 1024
            num_warps = 4
        else:
            BLOCK = 8192
            num_warps = 8
        grid = (triton.cdiv(n_elements, BLOCK),)
        _xlog1py_kernel[grid](
            A,
            B,
            out,
            n_elements,
            BLOCK=BLOCK,
            UPCAST=upcast,
            num_warps=num_warps,
        )
        return out
