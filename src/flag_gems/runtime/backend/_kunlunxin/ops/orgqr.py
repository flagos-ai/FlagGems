"""orgqr (LAPACK ORGQR / torch.linalg.householder_product) in Triton.

Q = H_1 H_2 ... H_k with H_j = I - tau_j v_j v_j^T, where
v_j[i] = 0 (i < j), v_j[j] = 1, v_j[i] = self[..., i, j] (i > j).

Column j of the result is (H_1 ... H_min(j,k)) e_j because H_l e_j = e_j for
l > j, so the reflectors that matter for output column j are
k = min(tau_len, j + 1) - 1 ... 0 (descending, matching ATen's order).

Backend notes for this flagtree/triton-xpu target (established with compile
probes): tl.sum(x, axis=0) on a 2D tile is rejected, a 2D tile carried through a
dynamic scf.for with tt.reduce breaks the TritonXPU passes, and tt.trans on a 2D
tile aborts the compiler, so everything here is 1-D.  A store mask formed as
`tensor_mask & <scalar bool>` (or as a second tensor comparison) does not
suppress the store on this backend, so column guards are runtime scalar `if`
statements.

Measured cost model (rounds 2-4): time = steps x (F + BC*R) with F ~ 140-190 ns
per (program, reflector) step and R ~ 45-140 ns per additional output column
reduce.  Sharing one step across BC=4 adjacent output columns cuts the step count
~BC-fold and wins on the larger shapes; the two smallest shapes are dominated by
per-call launch overhead and are faster with BC=1, hence the dispatch below.
"""

