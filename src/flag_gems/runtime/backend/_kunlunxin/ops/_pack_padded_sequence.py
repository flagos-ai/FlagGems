@triton.jit
def _index_kernel(
    lengths_ptr,
    src_ptr,  # int64 scratch length S+1: source element offset per packed row
    S,
    B,
    st,
    sb,
    BLOCK_B: tl.constexpr,
):
    """grid=(max_len, B), unsorted fallback: gather index of (t, b).

    Inactive (t, b) pairs store into the padding slot S (never read), so the
    store needs no mask: scalar store masks are not honoured by this backend.
    """
    t = tl.program_id(0)
    b = tl.program_id(1)
    b_idx = tl.arange(0, BLOCK_B)
    Lb = tl.load(lengths_ptr + b_idx, mask=b_idx < B, other=0).to(tl.int32)
    rank = tl.sum(((b_idx < b) & (Lb > t)).to(tl.int32), axis=0)
    C = tl.sum(tl.minimum(Lb, t), axis=0)
    myL = tl.load(lengths_ptr + b).to(tl.int32)
    dst = tl.where(myL > t, C + rank, S)
    tl.store(src_ptr + dst.to(tl.int64), t.to(tl.int64) * st + b.to(tl.int64) * sb)


