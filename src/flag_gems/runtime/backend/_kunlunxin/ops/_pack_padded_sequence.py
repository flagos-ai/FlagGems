@triton.jit
def _pack_flat_kernel(
    x_ptr,
    out_ptr,
    lengths_ptr,
    buf_ptr,  # int64 scratch: [S, max_len, counts(T), flags(T)]
    T,
    F,
    st,
    B,
    BLOCK_B: tl.constexpr,
    BLOCK: tl.constexpr,
):
    """grid=(T,): per time step -- batch_sizes[t], offsets, and the packed row run.

    The lengths load is mask-free (indices clamped, out-of-range lanes cancelled
    arithmetically), so the run copy carries the only tile mask.
    """
    t = tl.program_id(0)
    b_ar = tl.arange(0, BLOCK_B)
    ok = b_ar < B
    Lraw = tl.load(lengths_ptr + tl.minimum(b_ar, B - 1)).to(tl.int32)
    Lb = tl.where(ok, Lraw, 0)
    act = (Lraw > t) & ok
    cnt = tl.sum(act.to(tl.int32), axis=0)
    C = tl.sum(tl.minimum(Lb, t), axis=0)
    mxb = tl.max(tl.where(act, b_ar, -1), axis=0)
    tl.store(buf_ptr + 2 + t, cnt.to(tl.int64))
    tl.store(buf_ptr + 2 + T + t, (mxb == cnt - 1).to(tl.int64))
    tl.store(buf_ptr + 0, tl.sum(Lb, axis=0).to(tl.int64))
    tl.store(buf_ptr + 1, tl.max(Lb, axis=0).to(tl.int64))

    n = cnt * F
    nfull = n // BLOCK * BLOCK
    src = t.to(tl.int64) * st
    dst = C.to(tl.int64) * F
    ar = tl.arange(0, BLOCK)
    gi = ar.to(tl.int64)
    for i0 in range(0, nfull, BLOCK):
        off = i0.to(tl.int64) + gi
        v = tl.load(x_ptr + src + off)
        tl.store(out_ptr + dst + off, v)
    for i0 in range(nfull, n, BLOCK):
        i = i0 + ar
        m = i < n
        v = tl.load(x_ptr + src + i.to(tl.int64), mask=m)
        tl.store(out_ptr + dst + i.to(tl.int64), v, mask=m)


