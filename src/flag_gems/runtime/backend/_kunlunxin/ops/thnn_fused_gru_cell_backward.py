def _gru_bias_backward_kernel(
    grad_input_gates,
    grad_hidden_gates,
    grad_input_bias,
    grad_hidden_bias,
    batch_size,
    GATE_SIZE: tl.constexpr,
    COLUMN_BLOCKS: tl.constexpr,
    BLOCK_COL: tl.constexpr,
    BLOCK_ROW: tl.constexpr,
    CAST_OUTPUT: tl.constexpr,
    FILL_ZERO: tl.constexpr,
    STRIDED: tl.constexpr,
    input_bias_stride,
    hidden_bias_stride,
    input_row_stride,
    input_column_stride,
    hidden_row_stride,
    hidden_column_stride,
):
    """Fold ``BLOCK_ROW`` rows of both gate gradients into one column row.

    One program owns ``BLOCK_ROW`` consecutive rows of one column block; the
    reduction is a plain elementwise accumulate over unrolled rows, so the
    column axis stays the contiguous one.
    """
    pid = tl.program_id(0)
    row_block = pid // COLUMN_BLOCKS
    column_block = pid % COLUMN_BLOCKS
    cols = column_block * BLOCK_COL + tl.arange(0, BLOCK_COL)
    col_mask = cols < GATE_SIZE
    input_accumulator = tl.zeros((BLOCK_COL,), dtype=tl.float32)
    hidden_accumulator = tl.zeros((BLOCK_COL,), dtype=tl.float32)

    if not FILL_ZERO:
        for index in tl.static_range(BLOCK_ROW):
            row = row_block * BLOCK_ROW + index
            # A clamped row index keeps every lane in bounds; rows past the end
            # are dropped with a zero factor instead of a predicate.
            clamped = tl.minimum(row, batch_size - 1)
            keep = tl.where(row < batch_size, 1.0, 0.0)
            if STRIDED:
                input_offsets = clamped * input_row_stride + cols * input_column_stride
                hidden_offsets = (
                    clamped * hidden_row_stride + cols * hidden_column_stride
                )
            else:
                input_offsets = clamped * GATE_SIZE + cols
                hidden_offsets = input_offsets
            input_accumulator += (
                tl.load(grad_input_gates + input_offsets, mask=col_mask).to(tl.float32)
                * keep
            )
            hidden_accumulator += (
                tl.load(grad_hidden_gates + hidden_offsets, mask=col_mask).to(
                    tl.float32
                )
                * keep
            )

    if CAST_OUTPUT:
        tl.store(
            grad_input_bias + cols * input_bias_stride,
            input_accumulator.to(grad_input_bias.dtype.element_ty),
            mask=col_mask,
        )
        tl.store(
            grad_hidden_bias + cols * hidden_bias_stride,
            hidden_accumulator.to(grad_hidden_bias.dtype.element_ty),
            mask=col_mask,
        )
    else:
        out_offsets = row_block * GATE_SIZE + cols
        tl.store(grad_input_bias + out_offsets, input_accumulator, mask=col_mask)
        tl.store(grad_hidden_bias + out_offsets, hidden_accumulator, mask=col_mask)


@triton.jit
def _gru_bias_fold_kernel(
    source,
    target,
    batch_size,
    out_plane,
    GATE_SIZE: tl.constexpr,
    COLUMN_BLOCKS: tl.constexpr,
    ROW_BLOCKS: tl.constexpr,
    BLOCK_COL: tl.constexpr,
    BLOCK_ROW: tl.constexpr,
    CAST_OUTPUT: tl.constexpr,
):
    """Fold ``BLOCK_ROW`` rows of one gate gradient into one column row.

    One program owns a single gradient, so the unrolled fan-in stays at
    ``BLOCK_ROW`` loads instead of ``2 * BLOCK_ROW``; the second gradient is
    covered by its own half of the grid. Both gradients sit next to each other
    in the caller's buffer, so the ``which`` half is a constant pointer offset.
    """
    pid = tl.program_id(0)
    span = ROW_BLOCKS * COLUMN_BLOCKS
    which = pid // span
    rest = pid % span
    row_block = rest // COLUMN_BLOCKS
    column_block = rest % COLUMN_BLOCKS
    cols = column_block * BLOCK_COL + tl.arange(0, BLOCK_COL)
    col_mask = cols < GATE_SIZE
    accumulator = tl.zeros((BLOCK_COL,), tl.float32)
    base = source + which * batch_size * GATE_SIZE
    for index in tl.static_range(BLOCK_ROW):
        row = row_block * BLOCK_ROW + index
        clamped = tl.minimum(row, batch_size - 1)
        keep = tl.where(row < batch_size, 1.0, 0.0)
        accumulator += (
            tl.load(base + clamped * GATE_SIZE + cols, mask=col_mask).to(tl.float32)
            * keep
        )
    offset = which * out_plane + (cols if CAST_OUTPUT else row_block * GATE_SIZE + cols)
    if CAST_OUTPUT:
        tl.store(
            target + offset, accumulator.to(target.dtype.element_ty), mask=col_mask
        )
    else:
        tl.store(target + offset, accumulator, mask=col_mask)


def _validate_inputs(grad_hy, workspace):
    if grad_hy.ndim != 2 or workspace.ndim != 2:
        raise RuntimeError("fused_gru_cell_backward expects two 2-D tensors")
    batch_size, hidden_size = grad_hy.shape
    if workspace.shape != (batch_size, 5 * hidden_size):
        raise RuntimeError(
            "workspace must have shape "
            f"({batch_size}, {5 * hidden_size}), got {tuple(workspace.shape)}"
        )
    if workspace.dtype != grad_hy.dtype:
        raise RuntimeError("grad_hy and workspace must have the same dtype")
    if workspace.device != grad_hy.device:
        raise RuntimeError("grad_hy and workspace must be on the same device")


def _prepare_out(out, shape, dtype, device, name):
    if out.dtype != dtype:
        raise RuntimeError(f"Expected {name} to have dtype {dtype}, got {out.dtype}")
    if out.device != device:
        raise RuntimeError(f"Expected {name} to be on {device}, got {out.device}")
    if tuple(out.shape) != tuple(shape):
        out.resize_(shape)


def _row_major_block(n_elements):
    """Smallest power-of-two block that keeps the per-program footprint high."""
    block = 2048
    if n_elements > 16384:
        block = 8192
    return block


# Smallest tensor that is folded back onto itself.
_FOLD_MIN_ELEMENTS = 32


def _fold_modulus(n_elements):
    """Modulus keeping every lane of a single-block tensor in range, or 0.

    Only a whole tensor that fits one block is folded, and only when its
    length is a power of two: that is where folding keeps the block-wide
    access pattern and has been verified to be computed correctly.
    """
    if n_elements < _FOLD_MIN_ELEMENTS or n_elements & (n_elements - 1):
        return 0
    return n_elements


# Rows one program of the row kernel walks at a time.
_ROW_KERNEL_ROWS = 8


def _row_kernel_rows(batch_size):
    return max(1, min(_ROW_KERNEL_ROWS, batch_size))


def _column_blocks(gate_size):
    """Widest power-of-two column block that still covers a whole gate row."""
    block_col = 16
    while block_col < 1024 and block_col < gate_size:
        block_col *= 2
    return block_col


# Rows one fold program may cover when it owns a single gradient.
_FOLD_FANIN = 64

_FOLD_SCRATCH = {}


def _fold_scratch(length, device):
    """Reusable fold buffer: the fold rewrites its whole live prefix."""
    key = (device, length)
    buffer = _FOLD_SCRATCH.get(key)
    if buffer is None:
        buffer = torch.empty(length, dtype=torch.float32, device=device)
        _FOLD_SCRATCH[key] = buffer
    return buffer


def _adjacent(first, second):
    """True when ``second`` starts right after ``first`` in the same buffer."""
    return first.data_ptr() + first.numel() * first.element_size() == second.data_ptr()


def _bias_column_sums(
    grad_input_gates, grad_hidden_gates, grad_input_bias, grad_hidden_bias, scratch=None
):
    """Column-sum both gate gradients into the two bias vectors.

    The reduced axis is the row axis, which is the outer (strided) one, so the
    fold is done in a chain of row-block kernels: each level folds
    ``BLOCK_ROW`` rows elementwise into one row until a single row is left.

    When the two gradients and the two biases are adjacent in one buffer (the
    normal allocation path) the fold handles one gradient per program, which
    doubles the unrolled fan-in per program and, for a batch that fits one
    fan-in, removes a whole level from the chain.
    """
    gate_size = grad_input_gates.shape[1]
    block_col = _column_blocks(gate_size)
    column_blocks = triton.cdiv(gate_size, block_col)
    device = grad_input_gates.device
    rows = grad_input_gates.shape[0]
    simple = (
        grad_input_gates.stride(1) == 1
        and grad_hidden_gates.stride(1) == 1
        and grad_input_gates.stride(0) == gate_size
        and grad_hidden_gates.stride(0) == gate_size
    )
    split_ok = (
        simple
        and rows > 0
        and _adjacent(grad_input_gates, grad_hidden_gates)
        and _adjacent(grad_input_bias, grad_hidden_bias)
        and grad_input_bias.stride(0) == 1
        and grad_hidden_bias.stride(0) == 1
    )
    if split_ok and rows <= _FOLD_FANIN:
        # One level: both gradients, one program per (gradient, column block).
        _gru_bias_fold_kernel[(2 * column_blocks,)](
            grad_input_gates,
            grad_input_bias,
            rows,
            gate_size,
            GATE_SIZE=gate_size,
            COLUMN_BLOCKS=column_blocks,
            ROW_BLOCKS=1,
            BLOCK_COL=block_col,
            BLOCK_ROW=rows,
            CAST_OUTPUT=True,
        )
        return
    if split_ok:
        row_blocks = triton.cdiv(rows, _FOLD_FANIN)
        span = row_blocks * gate_size
        if scratch is None:
            scratch = _fold_scratch(2 * span, device)
        _gru_bias_fold_kernel[(2 * row_blocks * column_blocks,)](
            grad_input_gates,
            scratch,
            rows,
            span,
            GATE_SIZE=gate_size,
            COLUMN_BLOCKS=column_blocks,
            ROW_BLOCKS=row_blocks,
            BLOCK_COL=block_col,
            BLOCK_ROW=_FOLD_FANIN,
            CAST_OUTPUT=False,
        )
        # The partial sums are one row per folded block; keep folding them
        # until a single row is left (a batch above 2048 needs more than one).
        _bias_column_sums(
            scratch[:span].view(row_blocks, gate_size),
            scratch[span:].view(row_blocks, gate_size),
            grad_input_bias,
            grad_hidden_bias,
        )
        return
    if simple:
        row_layout = (gate_size, 1, gate_size, 1)
    else:
        row_layout = (
            grad_input_gates.stride(0),
            grad_input_gates.stride(1),
            grad_hidden_gates.stride(0),
            grad_hidden_gates.stride(1),
        )
    if rows == 0:
        # An empty batch sums to zero rather than to anything it could read.
        _gru_bias_backward_kernel[(column_blocks,)](
            grad_input_gates,
            grad_hidden_gates,
            grad_input_bias,
            grad_hidden_bias,
            0,
            GATE_SIZE=gate_size,
            COLUMN_BLOCKS=column_blocks,
            BLOCK_COL=block_col,
            BLOCK_ROW=1,
            CAST_OUTPUT=True,
            FILL_ZERO=True,
            input_bias_stride=grad_input_bias.stride(0),
            hidden_bias_stride=grad_hidden_bias.stride(0),
            STRIDED=not simple,
            input_row_stride=row_layout[0],
            input_column_stride=row_layout[1],
            hidden_row_stride=row_layout[2],
            hidden_column_stride=row_layout[3],
        )
        return
    source_input, source_hidden = grad_input_gates, grad_hidden_gates
    while True:
        block_row = min(32, rows)
        row_blocks = triton.cdiv(rows, block_row)
        last = row_blocks == 1
        if last:
            target_input, target_hidden = grad_input_bias, grad_hidden_bias
            input_stride = grad_input_bias.stride(0)
            hidden_stride = grad_hidden_bias.stride(0)
        else:
            span = row_blocks * gate_size
            if scratch is None:
                scratch = _fold_scratch(2 * span, device)
            target_input = scratch[:span]
            target_hidden = scratch[span : 2 * span]
            input_stride = hidden_stride = gate_size
        _gru_bias_backward_kernel[(row_blocks * column_blocks,)](
            source_input,
            source_hidden,
            target_input,
            target_hidden,
            rows,
            GATE_SIZE=gate_size,
            COLUMN_BLOCKS=column_blocks,
            BLOCK_COL=block_col,
            BLOCK_ROW=block_row,
            CAST_OUTPUT=last,
            FILL_ZERO=False,
            input_bias_stride=input_stride,
            hidden_bias_stride=hidden_stride,
            STRIDED=not simple,
            input_row_stride=row_layout[0],
            input_column_stride=row_layout[1],
            hidden_row_stride=row_layout[2],
            hidden_column_stride=row_layout[3],
        )
        if last:
            return
        source_input, source_hidden = target_input, target_hidden
        rows = row_blocks
        # Later levels read the flat scratch buffer.
        simple = True
        row_layout = (gate_size, 1, gate_size, 1)


def _launch_gru_cell_backward(
    grad_hy,
    workspace,
    has_bias,
    grad_input_gates,
    grad_hidden_gates,
    grad_hx,
    grad_input_bias,
    grad_hidden_bias,
):
    batch_size, hidden_size = grad_hy.shape
    n_elements = batch_size * hidden_size
    with torch_device_fn.device(grad_hy.device):
        if n_elements:
            block_size = _row_major_block(n_elements)
            flat = (
                grad_hy.is_contiguous()
                and workspace.is_contiguous()
                and grad_input_gates.is_contiguous()
                and grad_hidden_gates.is_contiguous()
                and grad_hx.is_contiguous()
            )
            if flat and not n_elements % block_size:
                _gru_cell_backward_contiguous_kernel[(n_elements // block_size,)](
                    grad_hy,
                    workspace,
                    grad_input_gates,
                    grad_hidden_gates,
                    grad_hx,
                    batch_size,
                    0,
                    HIDDEN=hidden_size,
                    BLOCK_SIZE=block_size,
                    IS_FP64=grad_hy.dtype == torch.float64,
                    MASKED=False,
                    MOD=0,
                )
            elif flat and n_elements < block_size and _fold_modulus(n_elements):
                _gru_cell_backward_contiguous_kernel[(1,)](
                    grad_hy,
                    workspace,
                    grad_input_gates,
                    grad_hidden_gates,
                    grad_hx,
                    batch_size,
                    0,
                    HIDDEN=hidden_size,
                    BLOCK_SIZE=block_size,
                    IS_FP64=grad_hy.dtype == torch.float64,
                    MASKED=True,
                    MOD=_fold_modulus(n_elements),
                )
            else:
                block_col = _column_blocks(hidden_size)
                column_blocks = triton.cdiv(hidden_size, block_col)
                rows = _row_kernel_rows(batch_size)
                _gru_cell_backward_row_kernel[
                    (triton.cdiv(batch_size, rows) * column_blocks,)
                ](
                    grad_hy,
                    workspace,
                    grad_input_gates,
                    grad_hidden_gates,
                    grad_hx,
                    batch_size,
                    grad_hy.stride(0),
                    grad_hy.stride(1),
                    workspace.stride(0),
                    workspace.stride(1),
                    grad_input_gates.stride(0),
                    grad_input_gates.stride(1),
                    grad_hidden_gates.stride(0),
                    grad_hidden_gates.stride(1),
                    grad_hx.stride(0),
                    grad_hx.stride(1),
                    HIDDEN=hidden_size,
                    BLOCK_COL=block_col,
                    COLUMN_BLOCKS=column_blocks,
                    ROWS=rows,
                    IS_FP64=grad_hy.dtype == torch.float64,
                )
        gate_size = 3 * hidden_size
        if has_bias and gate_size != 0:
            _bias_column_sums(
                grad_input_gates,
                grad_hidden_gates,
                grad_input_bias,
                grad_hidden_bias,
            )


def _thnn_fused_gru_cell_backward(
    grad_hy: torch.Tensor, workspace: torch.Tensor, has_bias: bool
):
    logger.debug("GEMS_KUNLUNXIN _THNN_FUSED_GRU_CELL_BACKWARD")
    _validate_inputs(grad_hy, workspace)
    batch_size, hidden_size = grad_hy.shape
    gate_size = 3 * hidden_size
    gate_elements = batch_size * gate_size
    hidden_elements = batch_size * hidden_size
    sizes = [gate_elements, gate_elements, hidden_elements]
    if has_bias:
        sizes += [gate_size, gate_size]
    storage = torch.empty(sum(sizes), dtype=grad_hy.dtype, device=grad_hy.device)
    grad_input_gates, grad_hidden_gates, grad_hx, *bias = storage.split(sizes)
    grad_input_gates = grad_input_gates.view(batch_size, gate_size)
    grad_hidden_gates = grad_hidden_gates.view(batch_size, gate_size)
    grad_hx = grad_hx.view(batch_size, hidden_size)
    if has_bias:
        grad_input_bias, grad_hidden_bias = bias
    else:
        grad_input_bias = None
        grad_hidden_bias = None
    _launch_gru_cell_backward(
        grad_hy,
        workspace,
        has_bias,
        grad_input_gates,
        grad_hidden_gates,
        grad_hx,
        grad_input_bias,
        grad_hidden_bias,
    )
    return (
        grad_input_gates,
        grad_hidden_gates,
        grad_hx,
        grad_input_bias,
        grad_hidden_bias,
    )


def _thnn_fused_gru_cell_backward_out(
    grad_hy: torch.Tensor,
    workspace: torch.Tensor,
    has_bias: bool,
    *,
    out0: torch.Tensor,
    out1: torch.Tensor,
    out2: torch.Tensor,
    out3: torch.Tensor,
    out4: torch.Tensor,
):
    logger.debug("GEMS_KUNLUNXIN _THNN_FUSED_GRU_CELL_BACKWARD_OUT")
    _validate_inputs(grad_hy, workspace)
    if not has_bias:
        raise RuntimeError("the out overload requires has_bias=True")
    batch_size, hidden_size = grad_hy.shape
    gate_shape = (batch_size, 3 * hidden_size)
    bias_shape = (3 * hidden_size,)
    for out, shape, name in (
        (out0, gate_shape, "out0"),
        (out1, gate_shape, "out1"),
        (out2, (batch_size, hidden_size), "out2"),
        (out3, bias_shape, "out3"),
        (out4, bias_shape, "out4"),
    ):
        _prepare_out(out, shape, grad_hy.dtype, grad_hy.device, name)

    _launch_gru_cell_backward(
        grad_hy,
        workspace,
        True,
        out0,
        out1,
        out2,
        out3,
        out4,
    )
    return out0, out1, out2, out3, out4
