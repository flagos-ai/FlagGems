@triton.jit
def _ir_count(idx_ptr, cnt_ptr, S, istride, BI: tl.constexpr):
    """Per-target hit counts (one program per target).

    This vectorised form is the fastest of the four counter designs measured on
    this target: cost tracks (programs x trips) x per-trip overhead, so it is
    better to process BI index values per trip with a scalar accumulator than to
    shorten the chain with more programs or to widen the target tile.
    """
    j = tl.program_id(0)
    total = 0
    for i0 in range(0, S, BI):
        offs = i0 + tl.arange(0, BI)
        iv = tl.load(idx_ptr + offs * istride, mask=offs < S, other=-1).to(tl.int32)
        total += tl.sum((iv == j).to(tl.int32))
    tl.store(cnt_ptr + j, total)


