"""Triton implementation of aten::index_reduce (functional form).

out = self.clone(); index_reduce_(out, dim, index, source, reduce, include_self)
(the result is a new, contiguous tensor; inputs are never mutated)

Reference semantics (verified against the reference on this target):
  amax/amin: max/min(include_self ? self : +-inf, over hits)
  prod:      (include_self ? self : 1) * product over hits
  mean:      ((include_self ? self : 0) + sum over hits) / ((include_self ? 1 : 0) + #hits)
  include_self == False and no hit  ->  self value (pass-through)
  empty index -> pure copy of self
  16-bit prod/mean are accumulated in fp32 and rounded once, like the reference.

FAST path (floating dtypes, include_self, contiguous self/source): the columns of
  the reduced axis are partitioned across programs and every program *owns* its
  columns exclusively, so each hit is applied with a plain load/combine/store
  inside one kernel - no atomics at all (this backend's atomics lose updates
  under contention and fp16/bf16 atomic_max/min do not compile).  Work is
  O(numel + C*S) element work, where C=numel/self.size(dim) and S=index.numel().
  Each column-block program scans all S indices; mean additionally performs
  O(self.size(dim)*S) index-count work. 'prod' needs no atomic multiply.

FALLBACK path (non-contiguous layouts, include_self == False, integer dtypes):
  an atomic-free tiled gather over arbitrary strides (correctness first).

Backend rules that constrain every kernel here (measured on this target):
  * a program whose tile holds fewer than 64 elements is replicated across the
    64 cores, so a non-idempotent update would be applied 64/tile times;
  * a dynamic loop cannot carry a tensor iter_arg, and a mask built inside a
    loop from a tensor defined outside it is rejected by the legalizer, so hot
    loops keep 1D tiles, scalar accumulators and loop-invariant masks only.
"""

