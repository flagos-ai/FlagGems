@triton.jit
def _ir_scatter_col(
    src_ptr,
    idx_ptr,
    acc_ptr,
    C,
    D,
    S,
    istride,
    INNER,
    REDUCE: tl.constexpr,
    BC: tl.constexpr,
):
    """One program per block of columns.  A column (and therefore every target of
    that column) belongs to exactly one program, so the per-hit
    read-modify-write is race-free without atomics."""
    cc = tl.program_id(0) * BC + tl.arange(0, BC)
    cmask = cc < C
    outer = cc // INNER
    inr = cc - outer * INNER
    cbase_src = outer * (S * INNER) + inr
    cbase_acc = outer * (D * INNER) + inr

    for i in range(0, S):
        iv = tl.load(idx_ptr + i * istride).to(tl.int64)
        s = tl.load(src_ptr + cbase_src + i * INNER, mask=cmask, other=0).to(
            acc_ptr.dtype.element_ty
        )
        off = cbase_acc + iv * INNER
        target_mask = cmask & (iv >= 0) & (iv < D)
        v = tl.load(acc_ptr + off, mask=target_mask, other=0)
        if REDUCE == 0:
            nv = tl.maximum(v, s)
        elif REDUCE == 1:
            nv = tl.minimum(v, s)
        elif REDUCE == 2:
            nv = v * s
        else:
            nv = v + s
        tl.store(acc_ptr + off, nv, mask=target_mask)


@triton.jit
def _ir_final(
    acc_ptr, out_ptr, rinv_ptr, n, D, INNER, DIVIDE: tl.constexpr, BLOCK: tl.constexpr
):
    off = tl.program_id(0) * BLOCK + tl.arange(0, BLOCK)
    m = off < n
    v = tl.load(acc_ptr + off, mask=m, other=0.0)
