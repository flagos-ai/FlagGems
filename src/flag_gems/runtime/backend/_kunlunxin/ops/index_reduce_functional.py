def _index_reduce(self, dim, index, source, reduce, include_self):
    rid = _REDUCE_ID.get(reduce)
    if rid is None:
        raise AssertionError(f"Unsupported reduce: {reduce}")

    nd = self.dim()
    if dim < -nd or dim >= nd:
        raise IndexError(
            "Dimension out of range (expected to be in range of [{}, {}], "
            "but got {})".format(-nd, nd - 1, dim)
        )
    d = dim % nd

    if index.ndim != 1 or index.dtype not in (torch.int32, torch.int64):
        raise RuntimeError("index_reduce(): index must be a vector of int32 or int64")
    if source.ndim != nd or source.dtype != self.dtype:
        raise RuntimeError("index_reduce(): source must match self rank and dtype")
    if source.device != self.device or index.device != self.device:
        raise RuntimeError("index_reduce(): all tensors must be on the same device")
    if index.numel() != source.shape[d] or any(
        source.shape[k] != self.shape[k] for k in range(nd) if k != d
    ):
        raise RuntimeError("index_reduce(): source shape does not match self and index")
    if nd > 8:
        raise NotImplementedError(
            "index_reduce(): at most eight dimensions are supported"
        )
    if index.numel():
        valid = torch.empty((), dtype=torch.int32, device=self.device)
        _ir_validate_index[(1,)](
            index, valid, index.numel(), self.shape[d], index.stride(0), 256
        )
        # XPU device_assert is a no-op. Read the Triton validation result before
        # any scatter launch; masking below also prevents out-of-bounds accesses.
        if not valid.item():
            raise IndexError("index_reduce(): index out of range")

    # the reference returns a fresh contiguous result tensor
    out = torch.empty(self.shape, dtype=self.dtype, device=self.device)
    numel = self.numel()
    D = self.shape[d]
    if numel == 0 or D == 0:
        return out

    S = index.numel()
    C = numel // D
    inner = 1
    for k in range(d + 1, nd):
        inner *= self.shape[k]
    istride = index.stride(0) if index.dim() > 0 else 1

    inc = bool(include_self)
    acc_int = not self.dtype.is_floating_point

    # ---- fast path: ownership based read-modify-write, no atomics
    if (
        inc
        and (not acc_int)
        and (rid != 3 or 0 < S <= 16384)
        and self.is_contiguous()
        and source.is_contiguous()
    ):
        # mean and 16-bit prod accumulate in fp32 and round once, like the reference
        stage = (rid == 3) or (rid == 2 and self.dtype.itemsize < 4)
        blk = _COPY_BLOCK
        grid1 = (_cdiv(numel, blk),)
        bc, nw = _col_cfg(C, inner)
        if stage:
            acc = torch.empty(numel, dtype=torch.float32, device=self.device)
            rinv = out
            if rid == 3:
                dpad = _cdiv(D, _CNT_BLOCK) * _CNT_BLOCK
                cnt = torch.empty(dpad, dtype=torch.int32, device=self.device)
                rinv = torch.empty(dpad, dtype=torch.float32, device=self.device)
                _ir_count[(D,)](index, cnt, S, istride, _COUNT_BLOCK)
                _ir_rinv[(_cdiv(D, _CNT_BLOCK),)](cnt, rinv, D, _CNT_BLOCK)
            _ir_copy[grid1](self, acc, numel, blk)
            if S > 0:
                _ir_scatter_col[(_cdiv(C, bc),)](
                    source,
                    index,
                    acc,
                    C,
                    D,
                    S,
                    istride,
                    inner,
                    rid,
                    bc,
                    num_warps=nw,
                    num_stages=1,
                )
            _ir_final[grid1](acc, out, rinv, numel, D, inner, rid == 3, blk)
            return out

        _ir_copy[grid1](self, out, numel, blk)
        if S > 0:
            _ir_scatter_col[(_cdiv(C, bc),)](
                source,
                index,
                out,
                C,
                D,
                S,
                istride,
                inner,
                rid,
                bc,
                num_warps=nw,
                num_stages=1,
            )
        return out

    # ---- fallback gather over arbitrary strides (correctness first)
    need_cnt = (rid == 3) or (not inc)
    bc, bj = _pick_blocks(C, D, need_cnt)
    grid = (_cdiv(C, bc), _cdiv(D, bj))
    shp = list(self.shape) + [1] * (8 - nd)
    sts = list(self.stride()) + [0] * (8 - nd)
    qts = list(source.stride()) + [0] * (8 - nd)
    ots = list(out.stride()) + [0] * (8 - nd)
    _ir_gather_strided[grid](
        self,
        source,
        index,
        out,
        C,
        D,
        S,
        istride,
        shp[0],
        shp[1],
        shp[2],
        shp[3],
        shp[4],
        shp[5],
        shp[6],
        shp[7],
        sts[0],
        sts[1],
        sts[2],
        sts[3],
        sts[4],
        sts[5],
        sts[6],
        sts[7],
        qts[0],
        qts[1],
        qts[2],
        qts[3],
        qts[4],
        qts[5],
        qts[6],
        qts[7],
        ots[0],
        ots[1],
        ots[2],
        ots[3],
        ots[4],
        ots[5],
        ots[6],
        ots[7],
        sts[d],
        qts[d],
        ots[d],
        nd,
        d,
        rid,
        inc,
        acc_int,
        need_cnt,
        bc,
        bj,
    )
    return out


def index_reduce_out(self, dim, index, source, reduce, *, include_self=True, out=None):
    logger.debug("GEMS_KUNLUNXIN INDEX_REDUCE_OUT")
    if out is None:
        return index_reduce(self, dim, index, source, reduce, include_self)
    if out.dtype != self.dtype:
        raise RuntimeError(
            f"Expected out tensor to have dtype {self.dtype}, but got {out.dtype}"
        )
    if out.device != self.device:
        raise RuntimeError(
            f"Expected out tensor to be on device {self.device}, but got {out.device}"
        )
    if any(size > 1 and stride == 0 for size, stride in zip(out.shape, out.stride())):
        raise RuntimeError("unsupported operation: output elements overlap in memory")
    with torch_device_fn.device(self.device):
        # Finish reading self/source before touching out, including when out
        # aliases an input. Copy through the backend's stride-aware Triton op.
        result = _index_reduce(self, dim, index, source, reduce, include_self)
        if out.shape != self.shape:
            out.resize_(self.shape)
        copy_(out, result)
    return out
