# ------------------------------------------------------------------------ helpers
def _pow2_at_most(v, cap):
    p = 1
    while p * 2 <= v and p * 2 <= cap:
        p *= 2
    return p


def _pick_blocks(C, D, need_cnt):
    limit = 512 if need_cnt else 1024
    bj = _pow2_at_most(max(D, 1), 64)
    bc = _pow2_at_most(max(C, 1), 8)
    while bc * bj > limit and bc > 1:
        bc //= 2
    while bc * bj > limit and bj > 1:
        bj //= 2
    return bc, bj


def _cdiv(a, b):
    return (a + b - 1) // b


def _col_cfg(C, inner):
    """Tile and warp count for the ownership kernel.

    Measured constraints on this target:
      * the tile must hold at least 64 elements, because the backend replicates a
        program across its 64 cores when it holds fewer, which would apply every
        update 64/BC times;
      * one element per thread beats two, so width and num_warps move together
        (num_warps = BC/32) and the total warp count stays C/32;
      * the cost is (programs x trips) because every program rescans the whole
        index array, so a wider tile wins - but only while enough programs
        remain and the per-program working set stays small.  256/8 measured
        better for the innermost-stride shapes with C >= 2048 and worse for the
        strided-axis shape, which keeps 128/4.
    """
    if inner == 1 and C >= 2048:
        return 256, 8
    return 128, 4


