        w01 = (p00 * e[2] + p01 * e[6]) * i01 + (p00 * e[3] + p01 * e[7]) * i11
        w10 = (p10 * e[2] + p11 * e[6]) * i00 + (p10 * e[3] + p11 * e[7]) * i10
