        p00 = e[5] * gp
        p01 = -e[1] * gp
        p10 = -e[4] * gp
        p11 = e[0] * gp
        # T = R P^-1
        t00 = e[8] * p00 + e[9] * p10
        t01 = e[8] * p01 + e[9] * p11
        t10 = e[12] * p00 + e[13] * p10
        t11 = e[12] * p01 + e[13] * p11
        # U = T Q, Sm = S - U
