"""Triton implementation of aten::linalg_inv (batched matrix inverse).

Two device kernels, dispatched on the matrix size:

``_inv_small`` (n <= 4) computes the inverse in closed form from scalar element
loads, for the 4x4 case through a 2x2 block inversion.  It issues no
cross-lane reductions at all, which matters because on this backend a full
reduction is a fixed-cost cross-core synchronisation (~0.34us) whatever the
register width, so the reduce-free path removes the dominant term for small n.

``_inv_kernel`` (n >= 5) keeps the working matrix and the accumulated inverse
as separate 1-D row registers (a fully unrolled Python tuple of ``n`` vectors of
length ``BN``) and runs a partial-pivoted Gauss-Jordan elimination.

The row-wise (1-D) formulation is deliberate: the XPU backend's core-tiling pass
rejects ``axis = 0`` reductions on 2-D tiles, reductions over broadcast-derived
tiles, and any reduction whose operand already came out of a reduction, so a
2-D register-tile formulation cannot be compiled here.  Every reduction in
``_inv_kernel`` is a full reduce of a 1-D vector that is an elementwise function
of a global load, which this backend tiles correctly.
"""

