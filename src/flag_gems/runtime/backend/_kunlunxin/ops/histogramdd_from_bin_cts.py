def histogramdd_from_bin_cts_kernel(
    inp_ptr,  # (M, N) contiguous float input
    weight_ptr,  # (M,) contiguous weights, or None
    out_ptr,  # (num_bins,) flattened histogram buffer (accumulator)
    M,
    N,
    left_ptr,  # (N,) left edges
    right_ptr,  # (N,) right edges
    edges_ptr,  # (N, MAX_EDGES) per-dimension bin edges, row-padded
    strides_ptr,  # (N,) row-major strides in bins
    bins_ptr,  # (N,) number of bins per dim
    MAX_EDGES: tl.constexpr,
    N_CONST: tl.constexpr,
    HAS_WEIGHT: tl.constexpr,
    ACC_DTYPE: tl.constexpr,
    BLOCK_SIZE: tl.constexpr,
):
    """Compute a multi-dimensional histogram from bin counts.

    One program computes one flattened bin: it scans every point, derives the
    point's row-major bin index the same way ATen does (an upper-bound search
    over the materialised ``linspace`` edges), and accumulates the matching
    contributions locally. There are no global atomics -- concurrent same-address
    ``atomic_add`` is lossy on this backend (``atomic-sim``), so a per-bin
    reduction is used instead. Accumulation runs in fp64 so large point clouds
    and fp64 inputs stay exact; the result is narrowed on the store.
    """
    bin_id = ext.program_id(0)
    acc = tl.zeros((), dtype=ACC_DTYPE)

    for start in range(0, M, BLOCK_SIZE):
        # M is pre-padded to a multiple of BLOCK_SIZE and the padding rows hold
        # NaN, so there are no partial (tail) blocks and no masked loads -- the
        # tail masked-load is unreliable on this backend. NaN rows fall out of
        # range naturally below.
        offs = start + tl.arange(0, BLOCK_SIZE)
        valid = tl.full((BLOCK_SIZE,), 1, dtype=tl.int1)
        linear_idx = tl.zeros((BLOCK_SIZE,), dtype=tl.int64)

        # Walk over each dimension (unrolled at compile time via N_CONST).
        for d in range(N_CONST):
            coord = tl.load(inp_ptr + offs * N_CONST + d).to(ACC_DTYPE)
            left = tl.load(left_ptr + d).to(ACC_DTYPE)
            right = tl.load(right_ptr + d).to(ACC_DTYPE)
            nbins = tl.load(bins_ptr + d)
            stride = tl.load(strides_ptr + d)

            # ATen compares in the input dtype, so keep the comparisons in
            # ACC_DTYPE (fp32 for fp32 inputs; fp64 is downcast to fp32 on this
            # backend anyway).
            coord_cmp = coord
            left_cmp = left
            right_cmp = right

            # Only count points inside [left, right] (NaN fails both comparisons).
            in_range = (coord_cmp >= left_cmp) & (coord_cmp <= right_cmp)
            valid = valid & in_range

            # Last edge <= coord, i.e. ATen's upper_bound - 1. Padding lanes hold
            # +inf and never count for a finite coord.
            row = edges_ptr + d * MAX_EDGES
            bin_idx = tl.full((BLOCK_SIZE,), -1, dtype=tl.int32)
            for e in tl.static_range(MAX_EDGES):
                edge = tl.load(row + e).to(ACC_DTYPE)
                bin_idx = tl.where(edge <= coord_cmp, bin_idx + 1, bin_idx)

            # The rightmost bin is inclusive of its right edge.
            nbins_i32 = nbins.to(tl.int32)
            bin_idx = tl.where(bin_idx >= nbins_i32, nbins_i32 - 1, bin_idx)
            bin_idx = tl.where(bin_idx < 0, 0, bin_idx)

            linear_idx = linear_idx + bin_idx.to(tl.int64) * stride

        if HAS_WEIGHT:
            contrib = tl.load(weight_ptr + offs).to(ACC_DTYPE)
        else:
            contrib = tl.full((BLOCK_SIZE,), 1.0, dtype=ACC_DTYPE)

        hit = (linear_idx == bin_id.to(tl.int64)) & valid
        # Avoid tl.where inside the reduction: that pattern miscompiles on this
        # backend. Multiply by the hit mask instead (0.0 / 1.0), then sum.
        acc += tl.sum(contrib * hit.to(ACC_DTYPE), axis=0)

    tl.store(out_ptr + bin_id, acc)


