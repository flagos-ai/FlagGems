def histogramdd_log_volume_kernel(
    width_ptr,  # (N,) per-dimension width
    bins_ptr,  # (N,) per-dimension bin count
    log_width_ptr,  # () out: sum of log|width / bins|
    sign_ptr,  # () out: product of the signs
    N,
    ACC_DTYPE: tl.constexpr,
    BLOCK_N: tl.constexpr,
):
    """Reduce the per-dimension bin widths into a signed log bin volume.

    Accumulating ``log|width / bins|`` and tracking the sign separately keeps a
    high-dimensional product from overflowing or underflowing before the division
    in ``histogramdd_total_scale_kernel``.
    """
    offs = tl.arange(0, BLOCK_N)
    m = offs < N
    width = tl.load(width_ptr + offs, mask=m, other=1.0).to(ACC_DTYPE)
    nbins = tl.load(bins_ptr + offs, mask=m, other=1).to(ACC_DTYPE)
    per_dim = width / nbins
    # Masked lanes contribute log(1) == 0 to the sum and +1 to the sign product.
    mag = tl.where(m, tl.abs(per_dim), 1.0)
    tl.store(log_width_ptr, tl.sum(tl.log(mag), axis=0))
    negatives = tl.sum(tl.where(m & (per_dim < 0), 1, 0), axis=0)
    tl.store(sign_ptr, tl.where(negatives % 2 == 0, 1.0, -1.0).to(ACC_DTYPE))


def _format_bound(value):
    """Format a range bound the way ATen's range messages do.

    ATen uses the default C++ stream formatting, which is ``%g`` (six
    significant digits, scientific notation outside a fixed exponent window),
    so ``0.123456789`` prints as ``0.123457`` and ``1e7`` as ``1e+07``.
    """
    return "%g" % value


def _resolve_range(inp, range_, N, acc_dtype):
    """Return (lefts, rights) tensors of shape (N,) on the input device.

    The edges are always carried in float64, whatever the input dtype: an explicit
    ``range`` arrives as Python doubles and ATen derives the (fp32) bin edges from
    those doubles, so narrowing the endpoints up front would perturb the bin edges
    by an ulp and misplace points that sit exactly on one.

    If `range_` is None the range for each dimension is derived from the data's
    per-dimension min/max on the device, matching torch.histogramdd: a dimension
    whose min equals max is expanded to (min - 0.5, max + 0.5).
    """
    if range_ is not None:
        # range_ is a flat sequence [l0, r0, l1, r1, ...].
        rng = [float(v) for v in range_]
        if len(rng) != 2 * N:
            raise RuntimeError(
                f"torch.histogramdd: for a {N}-dimensional histogram range should "
                f"have {2 * N} elements, but got {len(rng)}"
            )
        # ATen validates every dimension's bounds in this order: first that they
        # are finite, then that min <= max. An explicit non-finite bound is
        # rejected too, not just a non-finite auto-range, so a `range` of
        # e.g. [inf, inf] must raise rather than silently build a histogram.
        for d in range(N):
            lo, hi = rng[2 * d], rng[2 * d + 1]
            if not (math.isfinite(lo) and math.isfinite(hi)):
                raise RuntimeError(
                    f"torch.histogramdd: dimension {d}'s range "
                    f"[{_format_bound(lo)}, {_format_bound(hi)}] is not finite"
                )
            if lo > hi:
                raise RuntimeError(
                    f"torch.histogramdd: min should not exceed max, but got "
                    f"min {_format_bound(lo)} max {_format_bound(hi)} for "
                    f"dimension {d}"
                )
        # ATen then widens a zero-width dimension before building the edges
        # ("Expand empty range to match numpy behavior and avoid division by 0
        # in normalization"), so an explicit [1.0, 1.0] behaves exactly like the
        # degenerate *auto*-range case above: the edges become linspace(l - .5,
        # r + .5, bins + 1) and a point at 1.0 lands in bin bins // 2 rather
        # than being folded into the last bin.
        for d in range(N):
            if rng[2 * d] == rng[2 * d + 1]:
                rng[2 * d] -= 0.5
                rng[2 * d + 1] += 0.5
        lefts = torch.tensor(rng[0::2], dtype=torch.float64, device=inp.device)
        rights = torch.tensor(rng[1::2], dtype=torch.float64, device=inp.device)
        return lefts, rights

    lefts = torch.empty(N, dtype=torch.float64, device=inp.device)
    rights = torch.empty(N, dtype=torch.float64, device=inp.device)
    M = inp.shape[0]
    if M == 0:
        # No data to reduce over; ATen's empty-input range collapses to (0, 1) per
        # dimension after the degenerate-range expansion of (inf, -inf) is skipped.
        lefts.fill_(0.0)
        rights.fill_(1.0)
        return lefts, rights

    BLOCK_M = 256
    # Pad to a full block so the per-column kernel has no partial (tail) masked
    # load. NaN padding rows are ignored by the min/max reduction and excluded
    # from the non-finite check by ``rows < real_M``.
    padded_M = triton.cdiv(M, BLOCK_M) * BLOCK_M
    if padded_M != M:
        inp = torch.cat(
            [
                inp,
                torch.full(
                    (padded_M - M, N), float("nan"), dtype=inp.dtype, device=inp.device
                ),
            ],
            dim=0,
        )
    # Per-column lowest-non-finite flag (sentinel N = all finite). No cross-
    # program atomic is used; the host reduces the N tiny scalars instead.
    nonfinite_flags = torch.full((N,), N, dtype=torch.int32, device=inp.device)
    with torch_device_fn.device(inp.device):
        histogramdd_col_range_kernel[(N,)](
            inp,
            lefts,
            rights,
            nonfinite_flags,
            padded_M,
            M,
            N,
            ACC_DTYPE=tl.float32,
            BLOCK_M=BLOCK_M,
            SENTINEL=N,
        )
    _check_finite_auto_range(lefts, rights, nonfinite_flags, N)
    return lefts, rights


def _check_finite_auto_range(lefts, rights, nonfinite_flags, N):
    """Reject a non-finite auto-range, with ATen's message.

    ``nonfinite_flags`` is a per-dimension tensor: a finite column holds the
    sentinel ``N``, a non-finite column holds its own dimension index. The lowest
    such index identifies the offending dimension for the error message. ``%g``
    reproduces ATen's formatting.
    """
    dim = int(nonfinite_flags.min().item())
    if dim >= N:
        return
    raise RuntimeError(
        f"torch.histogramdd: dimension {dim}'s range "
        f"[{_format_bound(lefts[dim].item())}, {_format_bound(rights[dim].item())}] "
        "is not finite"
    )


def _histogramdd_from_bin_cts_impl(
    self, bins, *, range=None, weight=None, density=False, out=None
):
    """Shared implementation for the base and ``.out`` ATen variants."""
    logger.debug("GEMS _HISTOGRAMDD_FROM_BIN_CTS")

    if self.ndim < 2:
        raise RuntimeError(
            "torch.histogramdd: input tensor should have at least 2 dimensions"
        )
    if self.shape[-1] != len(bins):
        raise RuntimeError(
            "histogramdd: The size of bins must be equal to the innermost "
            "dimension of the input."
        )

    # torch._histogramdd_from_bin_cts is only implemented for floating types.
    if not self.is_floating_point():
        raise NotImplementedError('"histogramdd" not implemented for this dtype')

    if weight is not None and weight.dtype != self.dtype:
        raise RuntimeError(
            "torch.histogramdd: if weight tensor is provided, input tensor and "
            "weight tensor should have the same dtype, but got "
            f"input({self.dtype}), and weight({weight.dtype})"
        )

    N = self.shape[-1]
    bins_list = [int(b) for b in bins]
    out_shape = tuple(bins_list)

    # Flatten all leading dims to (M, N) and make contiguous.
    inp = self.reshape(-1, N).contiguous()
    M = inp.shape[0]
    out_dtype = self.dtype

    # Accumulate in the input's dtype: float32 for float32 inputs and float64 for
    # float64 inputs, so double-precision inputs keep their precision through the
    # atomic-add reductions. (float16/bfloat16 are unsupported by the ATen op.)
    acc_dtype = self.dtype
    acc_triton_dtype = tl.float64 if acc_dtype == torch.float64 else tl.float32

    # Allocate / validate the output buffer. ATen resizes a mis-shaped out tensor
    # in place and keeps the caller's object identity, but rejects a dtype
    # mismatch outright, so a wrong dtype must raise rather than be re-bound
    # through .to() (which would leave the caller's buffer untouched).
    if out is not None:
        if out.dtype != out_dtype:
            raise RuntimeError(
                f"Expected out tensor to have dtype {out_dtype}, but got "
                f"{out.dtype} instead"
            )
        if out.device != self.device:
            raise RuntimeError(
                f"Expected out tensor to have device {self.device}, but got "
                f"{out.device} instead"
            )
        if tuple(out.shape) != out_shape:
            out.resize_(out_shape)
    else:
        out = torch.empty(out_shape, dtype=out_dtype, device=self.device)

    if out.numel() == 0:
        # No bins to fill; zero the output and return.
        out.zero_()
        return out

    lefts, rights = _resolve_range(inp, range, N, acc_dtype)

    # Row-major stride[d] = prod(bins[d+1:]); derived from the bins list, which is
    # already host data, so no device round-trip is involved.
    strides_host = [1] * N
    for d in _builtins.range(N - 2, -1, -1):
        strides_host[d] = strides_host[d + 1] * bins_list[d + 1]
    strides = torch.tensor(strides_host, dtype=torch.int64, device=inp.device)
    bins_tensor = torch.tensor(bins_list, dtype=torch.int64, device=inp.device)

    # Per-dimension widths and inverse bin widths are computed in a kernel: the
    # edges may come from the data, and reading them back per dimension would both
    # break the host-function convention and force a sync.
    widths = torch.empty(N, dtype=torch.float64, device=inp.device)
    bin_widths = torch.empty(N, dtype=torch.float64, device=inp.device)
    BLOCK_N = triton.next_power_of_2(N)
    # Edge table for the binning search: one padded row per dimension.
    # The edges are exactly torch.linspace(left, right, nbins + 1), which is how
    # ATen materialises its bin boundaries. We build that table on the host from
    # the (tiny) resolved range so the boundaries are bit-identical to ATen's,
    # then upload it. lefts/rights hold N scalars each, so the single sync is
    # negligible; the actual histogram accumulation over the M points still runs
    # entirely in the device kernel below.
    max_edges = max(bins_list) + 1
    lefts_host = lefts.detach().cpu().tolist()
    rights_host = rights.detach().cpu().tolist()
    edges_host = torch.full((N, max_edges), float("inf"), dtype=acc_dtype)
    for d in _builtins.range(N):
        e = torch.linspace(lefts_host[d], rights_host[d], bins_list[d] + 1, dtype=acc_dtype)
        edges_host[d, : bins_list[d] + 1] = e
    edges = edges_host.to(self.device)
    with torch_device_fn.device(self.device):
        histogramdd_bin_geometry_kernel[(triton.cdiv(N, BLOCK_N),)](
            lefts,
            rights,
            bins_tensor,
            widths,
            bin_widths,
            N,
            ACC_DTYPE=tl.float64,
            BLOCK_N=BLOCK_N,
        )

    num_bins = 1
    for b in bins_list:
        num_bins *= b

    if density:
        # Density rescales every count, so we need the raw counts separately.
        hist_acc = torch.zeros(num_bins, dtype=acc_dtype, device=inp.device)
        hist_ptr = hist_acc
    else:
        # For the plain histogram, write straight into the output buffer: out's
        # dtype is validated to equal the input dtype, which is also the
        # accumulator dtype, so no final copy is needed. A non-contiguous out
        # cannot be viewed as flat, so accumulate into a temporary instead.
        hist_dense = out if out.is_contiguous() else torch.empty_like(out)
        hist_dense.zero_()
        hist_ptr = hist_dense.view(num_bins)

    if M > 0:
        # One program per point-tile; 1024 points per program amortizes launch
        # overhead while keeping occupancy high for typical point-cloud sizes.
        BLOCK_SIZE = 256
        grid = (num_bins,)

        has_weight = weight is not None
        if has_weight:
            weight = weight.reshape(-1).contiguous()
            if weight.numel() != M:
                raise RuntimeError(
                    "_histogramdd_from_bin_cts: weight must have the same number "
                    "of rows as the input"
                )
        else:
            weight = None

        # Pad the point count up to a full block so the kernel never issues a
        # partial (tail) masked load, which this backend handles unreliably.
        # Padding rows are NaN (and padding weights are 0), so they fall out of
        # range and contribute nothing.
        padded_M = triton.cdiv(M, BLOCK_SIZE) * BLOCK_SIZE
        if padded_M != M:
            pad_rows = padded_M - M
            inp = torch.cat(
                [
                    inp,
                    torch.full(
                        (pad_rows, N), float("nan"), dtype=inp.dtype, device=inp.device
                    ),
                ],
                dim=0,
            )
            if has_weight:
                weight = torch.cat(
                    [
                        weight,
                        torch.zeros(pad_rows, dtype=weight.dtype, device=weight.device),
                    ],
                    dim=0,
                )
        weight_ptr = (
            weight
            if has_weight
            else torch.empty(1, dtype=inp.dtype, device=inp.device)
        )
        M = padded_M

        with torch_device_fn.device(self.device):
            histogramdd_from_bin_cts_kernel[grid](
                inp,
                weight_ptr,
                hist_ptr,
                M,
                N,
                lefts,
                rights,
                edges,
                strides,
                bins_tensor,
                max_edges,
                N_CONST=N,
                HAS_WEIGHT=has_weight,
                ACC_DTYPE=acc_triton_dtype,
                BLOCK_SIZE=BLOCK_SIZE,
            )

    if density:
        # density[i] = count[i] / (total_count * bin_volume), where bin_volume is
        # the volume of a single (equal-width) N-dimensional bin, i.e. the product
        # of the per-dimension bin widths = prod((right - left) / bins). Both the
        # total count and bin widths are tiny scalars, so move them to the host
        # (one sync) and compute the scale in Python instead of launching extra
        # CUDA reductions.
        log_vol = torch.empty((), dtype=acc_dtype, device=self.device)
        vol_sign = torch.empty((), dtype=acc_dtype, device=self.device)
        scale_t = torch.empty((), dtype=acc_dtype, device=self.device)
        with torch_device_fn.device(self.device):
            histogramdd_log_volume_kernel[(1,)](
                widths,
                bins_tensor,
                log_vol,
                vol_sign,
                N,
                ACC_DTYPE=acc_triton_dtype,
                BLOCK_N=BLOCK_N,
            )
            # The division is deliberately unguarded: ATen divides by the total
            # count directly, so an empty or fully out-of-range input yields NaN
            # and weights that cancel to zero yield +-inf. Forcing the scale to
            # zero here would silently diverge from that.
            histogramdd_total_scale_kernel[(1,)](
                hist_acc,
                log_vol,
                vol_sign,
                scale_t,
                num_bins,
                ACC_DTYPE=acc_triton_dtype,
                BLOCK_SIZE=1024,
            )
        # A non-contiguous out (ATen accepts one) cannot be viewed as flat, so
        # write into a temporary and copy back, preserving the caller's layout.
        dense = out if out.is_contiguous() else torch.empty_like(out)
        out_flat = dense.view(num_bins)
        if num_bins > 0:
            # One program per bin-tile; 1024 bins per program covers typical
            # per-dimension bin counts in a single launch-friendly tile.
            BLOCK = 1024
            grid = (triton.cdiv(num_bins, BLOCK),)
            with torch_device_fn.device(self.device):
                histogramdd_density_kernel[grid](
                    hist_acc,
                    out_flat,
                    scale_t,
                    num_bins,
                    ACC_DTYPE=acc_triton_dtype,
                    BLOCK_SIZE=BLOCK,
                )
        if dense is not out:
            out.copy_(dense)
    elif hist_dense is not out:
        out.copy_(hist_dense)

    return out


def _histogramdd_from_bin_cts(self, bins, *, range=None, weight=None, density=False):
    """aten::_histogramdd_from_bin_cts(Tensor self, int[] bins, *, float[]? range=None,
    Tensor? weight=None, bool density=False) -> Tensor
    """
    return _histogramdd_from_bin_cts_impl(
        self, bins, range=range, weight=weight, density=density, out=None
    )


def _histogramdd_from_bin_cts_out(
    self, bins, *, range=None, weight=None, density=False, out
):
    """aten::_histogramdd_from_bin_cts.out(Tensor self, int[] bins, *, float[]? range=None,
    Tensor? weight=None, bool density=False, Tensor(a!) out) -> Tensor(a!)
    """
    return _histogramdd_from_bin_cts_impl(
        self, bins, range=range, weight=weight, density=density, out=out
    )
