def _zero_fill_kernel(
    ptr,
    n,
    BLOCK: tl.constexpr,
    EVEN: tl.constexpr,
    LONG: tl.constexpr,
):
    """Store ``BLOCK`` zeros at ``pid * BLOCK + arange`` in ``ptr``'s dtype."""
    pid = tl.program_id(0)
    if LONG:
        offs = pid.to(tl.int64) * BLOCK + tl.arange(0, BLOCK).to(tl.int64)
    else:
        offs = pid * BLOCK + tl.arange(0, BLOCK)
    zeros = tl.zeros([BLOCK], dtype=ptr.dtype.element_ty)
    if EVEN:
        tl.store(ptr + offs, zeros)
    else:
        tl.store(ptr + offs, zeros, mask=offs < n)


