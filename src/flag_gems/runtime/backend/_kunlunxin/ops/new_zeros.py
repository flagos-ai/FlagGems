def _contiguous_target(tensor):
    """Reinterpret each element as an equally wide integer zero word."""
    words = {
        1: torch.uint8,
        2: torch.int16,
        4: torch.int32,
        8: torch.int64,
    }
    word = words.get(tensor.element_size())
    if word is None or tensor.dtype == word:
        return tensor
    try:
        return tensor.view(word)
    except RuntimeError:
        return tensor


