    """Generic strided copy: one complex (re, im) pair per gathered index.

    ``n0``/``s0`` describe the fastest-varying dimension (innermost first) and
    every stride is expressed in real elements, i.e. twice the complex stride.
    """
    pid = tl.program_id(0)
    offs = pid * BLOCK + tl.arange(0, BLOCK)
    mask = offs < numel
    idx = offs.to(tl.int64)
    src_off = tl.zeros([BLOCK], dtype=tl.int64)
    if NDIM > 0:
        c = idx % n0
        idx = idx // n0
        src_off += c * s0
    if NDIM > 1:
        c = idx % n1
        idx = idx // n1
        src_off += c * s1
    if NDIM > 2:
        c = idx % n2
        idx = idx // n2
        src_off += c * s2
    if NDIM > 3:
        c = idx % n3
        idx = idx // n3
        src_off += c * s3
    if NDIM > 4:
        c = idx % n4
        src_off += c * s4
    re_v = tl.load(src + src_off, mask=mask)
    im_v = tl.load(src + src_off + 1, mask=mask)
    if NEG_RE:
        re_v = -re_v
    if NEG_IM:
        im_v = -im_v
    base = (pid * BLOCK).to(tl.int64) * 2
    lanes = 2 * tl.arange(0, BLOCK)
    tl.store(dst + base + lanes, re_v, mask=mask)
    tl.store(dst + base + lanes + 1, im_v, mask=mask)


