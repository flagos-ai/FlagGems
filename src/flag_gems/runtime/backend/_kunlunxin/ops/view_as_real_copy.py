@triton.jit
def _row_copy_kernel(
    src,
    dst,
    cols,
    src_row_stride,
    n_rows,
    NEG_RE: tl.constexpr,
    NEG_IM: tl.constexpr,
    ROWS: tl.constexpr,
    FULL: tl.constexpr,
    BLOCK: tl.constexpr,
):
    """Copy ``cols`` contiguous reals from every source row into a packed dst.

    Each program covers ``ROWS`` rows so its payload is not capped by one row.
    The row index is clamped instead of guarded: re-copying the last row writes
    identical bytes, which is harmless for a copy.
    """
    pid = tl.program_id(0)
    n_tiles = (cols + BLOCK - 1) // BLOCK
    tile = pid % n_tiles
    row0 = (pid // n_tiles) * ROWS
    off = tile * BLOCK + tl.arange(0, BLOCK)
    for i in tl.static_range(ROWS):
        row = tl.minimum(row0 + i, n_rows - 1)
        sptr = src + row.to(tl.int64) * src_row_stride
        dptr = dst + row.to(tl.int64) * cols
        if FULL:
            v = tl.load(sptr + off)
        else:
            v = tl.load(sptr + off, mask=off < cols)
        if NEG_RE or NEG_IM:
            odd = (off & 1) == 1
            if NEG_RE and NEG_IM:
                v = -v
            elif NEG_IM:
                v = tl.where(odd, -v, v)
            else:
                v = tl.where(odd, v, -v)
        if FULL:
            tl.store(dptr + off, v)
        else:
            tl.store(dptr + off, v, mask=off < cols)


