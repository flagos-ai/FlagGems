def view_as_real_copy(self):
    x = self
    if not x.is_complex():
        raise RuntimeError("view_as_real is only supported for complex tensors")

    # Metadata-only view: real-component dtype and the raw source pointer.
    real_view = x.real
    real_dtype = real_view.dtype
    out = torch.empty(tuple(x.shape) + (2,), dtype=real_dtype, device=x.device)
    numel = out.numel() // 2
    if numel == 0:
        return out

    is_neg = bool(x.is_neg())
    neg_re = is_neg
    neg_im = bool(x.is_conj()) != is_neg

    plan = _plan(tuple(x.shape), tuple(x.stride()))
    kind = plan[0]

    if kind == "flat":
        n = 2 * plan[2]
        itemsize = real_view.element_size()
        count = (n * itemsize) // 8
        rest = n - (count * 8) // itemsize
        if count and not neg_re and not neg_im and real_view.data_ptr() % 8 == 0:
            # Flag-free and 8-byte aligned: copy through the widest carrier.
            src_flat = (x if x.dim() else x.unsqueeze(0)).view(real_dtype).reshape(-1)
            _flat_copy_i64(
                _i64_view(src_flat, count),
                _i64_view(out.reshape(-1), count),
                count,
            )
            if rest:
                _flat_tail_kernel[(1,)](
                    real_view,
                    out,
                    n,
                    n - rest,
                    False,
                    False,
                    BLOCK=_TAIL_BLOCK,
                    num_warps=1,
                )
        else:
            _flat_copy_native(real_view, out, n, neg_re, neg_im)
        return out

    if kind == "rows" and plan[2] >= _ROW_MIN_COLS:
        rows = plan[1]
        cols = 2 * plan[2]
        src_row_stride = 2 * plan[3]
        # Size one program to ~64 KB of row bytes (or the whole row if shorter):
        # per-program payload is the parameter that controlled the flat copy.
        itemsize = real_view.element_size()
        budget = cols * itemsize
        if budget > _ROW_BYTES:
            budget = _ROW_BYTES
        block = budget // itemsize
        block = 1 << (block.bit_length() - 1)
        if block < 1024:
            block = 1024
        n_tiles = (cols + block - 1) // block
        # Several rows per program raise the payload past the one-row cap.
        row_groups = (rows + _ROW_GROUP - 1) // _ROW_GROUP
        _row_copy_kernel[(row_groups * n_tiles,)](
            real_view,
            out,
            cols,
            src_row_stride,
            rows,
            neg_re,
            neg_im,
            _ROW_GROUP,
            cols % block == 0,
            BLOCK=block,
            num_warps=_ROW_WARPS,
        )
        return out

    flat_args = []
    for n_d, s_d in _gather_dims(plan):
        flat_args.append(n_d)
        flat_args.append(s_d)
    grid = (triton.cdiv(numel, _GATHER_BLOCK),)
    _gather_copy_kernel[grid](
        real_view,
        out,
        numel,
        *flat_args,
        len(flat_args) // 2,
        neg_re,
        neg_im,
        BLOCK=_GATHER_BLOCK,
        num_warps=4,
    )
    return out
