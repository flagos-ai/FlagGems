def _plan(shape, stride):
    """Classify the copy as flat / row-collapsed / generic gather.

    Units are complex elements: the trailing contiguous run is detected first,
    then the remaining leading dims collapse to one row index when regular.
    """
    rank = len(shape)
    cols = 1
    k = rank
    while k > 0 and stride[k - 1] == cols:
        cols *= shape[k - 1]
        k -= 1
    if k == 0:
        return ("flat", 1, cols, cols)
    regular = True
    for d in range(k - 1):
        if stride[d] != stride[d + 1] * shape[d + 1]:
            regular = False
            break
    if regular:
        rows = 1
        for d in range(k):
            rows *= shape[d]
        row_stride = stride[k - 1]
        if row_stride == cols:
            return ("flat", 1, cols, cols)
        return ("rows", rows, cols, row_stride)
    return ("gather", shape, stride)


def _gather_dims(plan):
    """Innermost-first (extent, stride) pairs, strides in real elements."""
    if plan[0] == "rows":
        dims = [(plan[2], 1), (plan[1], plan[3])]
    else:
        dims = list(zip(plan[1], plan[2]))[::-1]
    if len(dims) > _MAX_GATHER_DIMS:
        raise RuntimeError("view_as_real_copy supports at most 5 dimensions")
    while len(dims) < _MAX_GATHER_DIMS:
        dims.append((1, 0))
    return [(extent, 2 * stride) for extent, stride in dims]


def _i64_view(flat, count):
    """Zero-copy int64 view over the first ``count`` 8-byte elements of flat."""
    es = flat.element_size()
    if es == 8:
        return flat[:count]
    return flat[: (8 // es) * count].view(torch.int64)


