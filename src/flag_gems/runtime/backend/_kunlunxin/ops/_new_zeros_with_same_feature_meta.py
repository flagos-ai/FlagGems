def _zero(t):
    """Fill ``t`` with zeros, reinterpreting dtypes Triton cannot store.

    The reinterpreted view aliases ``t``, so ``t`` itself is always returned.
    """
    if t.is_complex():
        # Triton has no complex store: fill the equivalent real block.
        _fill_zeros(torch.view_as_real(t))
    elif t.dtype == torch.bool:
        # One byte per logical element on the device: identical reinterpretation.
        _fill_zeros(t.view(torch.uint8))
    else:
        _fill_zeros(t)
    return t


