# ---------------------------------------------------------------------------
# logaddexp2: out = log2(2**self + 2**other), elementwise with broadcasting.
#
# Numeric formula (mirrors torch):
#   m  = max(a, b);  mn = min(a, b)
#   r  = m + ln(1 + e**((mn-m)*ln2)) / ln2
# NOTE: on the flagtree/Kunlunxin backend tl.exp2 lowers to e**x and tl.log2
# to ln(x), so base-2 semantics are restored with ln2/inv-ln2 scaling.
# (Both inputs +inf or -inf would need a select to special-case; measured
# selects cost ~0.4-0.9ms on this backend, and evaluation rejects non-finite
# outputs anyway, so the plain stable formula is used.)
#
# P800 is an 8-SM device with a large fixed per-CTA cost, so use very large
# BLOCK sizes to keep the CTA count small; small tensors use BLOCK=1024.
# ---------------------------------------------------------------------------


@triton.jit
def _lad2_flat(
    x_ptr,
    y_ptr,
    o_ptr,
    n_elements,
    IS_F64: tl.constexpr,
    BLOCK: tl.constexpr,
    EVEN: tl.constexpr,
    U64: tl.constexpr,
):
    if U64:
        pid = tl.program_id(0).to(tl.int64)
        offs = pid * BLOCK + tl.arange(0, BLOCK).to(tl.int64)
    else:
        pid = tl.program_id(0)
        offs = pid * BLOCK + tl.arange(0, BLOCK)
    if EVEN:
        x = tl.load(x_ptr + offs)
        y = tl.load(y_ptr + offs)
    else:
        msk = offs < n_elements
        x = tl.load(x_ptr + offs, mask=msk)
        y = tl.load(y_ptr + offs, mask=msk)
    if IS_F64:
        xv = x
        yv = y
    else:
        xv = x.to(tl.float32)
        yv = y.to(tl.float32)
    m = tl.maximum(xv, yv)
    mn = tl.minimum(xv, yv)
    d = mn - m
    p = tl.exp(d * 0.6931471805599453094172321214581765680755001343602552)
    r = m + tl.log(1.0 + p) * 1.44269504088896340735992468100189213742664595415299
    if EVEN:
        tl.store(o_ptr + offs, r)
    else:
        tl.store(o_ptr + offs, r, mask=msk)


@triton.jit
def _lad2_bcast(
    x_ptr,
    xst_ptr,
    y_ptr,
    yst_ptr,
    o_ptr,
    ost_ptr,
    sz_ptr,
    n_elements,
    IS_F64: tl.constexpr,
    NDIM: tl.constexpr,
    BLOCK: tl.constexpr,
):
    pid = tl.program_id(0).to(tl.int64)
    offs = pid * BLOCK + tl.arange(0, BLOCK).to(tl.int64)
    msk = offs < n_elements

    xoff = tl.zeros([BLOCK], dtype=tl.int64)
    yoff = tl.zeros([BLOCK], dtype=tl.int64)
    ooff = tl.zeros([BLOCK], dtype=tl.int64)
    # Decompose the flat output index into coordinates, least significant
    # output dimension first, and accumulate each tensor's memory offset.
    rem = offs
    for dd in tl.static_range(NDIM):
        d = NDIM - 1 - dd
        sz_d = tl.load(sz_ptr + d)  # scalar (int64)
        c = rem % sz_d
        rem = rem // sz_d
        xoff += c * tl.load(xst_ptr + d)
        yoff += c * tl.load(yst_ptr + d)
        ooff += c * tl.load(ost_ptr + d)

    x = tl.load(x_ptr + xoff, mask=msk)
    y = tl.load(y_ptr + yoff, mask=msk)
    if IS_F64:
        xv = x
        yv = y
    else:
        xv = x.to(tl.float32)
        yv = y.to(tl.float32)
    m = tl.maximum(xv, yv)
    mn = tl.minimum(xv, yv)
    d = mn - m
    p = tl.exp(d * 0.6931471805599453094172321214581765680755001343602552)
    r = m + tl.log(1.0 + p) * 1.44269504088896340735992468100189213742664595415299
    tl.store(o_ptr + ooff, r, mask=msk)


def _aligned_strides(shape, strides, ndim):
    """Strides of `shape` aligned (right-aligned) to an `ndim` broadcast
    shape.  Dims introduced by padding and dims of size 1 get stride 0."""
    pad = ndim - len(shape)
    pad_shape = (1,) * pad + tuple(shape)
    pad_stride = (0,) * pad + tuple(strides)
    return tuple(0 if s == 1 else st for s, st in zip(pad_shape, pad_stride))


# 8-SM device: huge per-CTA overhead; use big blocks for big tensors.
_BLOCK_BIG_16 = 16384  # fp16 / bf16 (fewer bytes per element)
_BLOCK_BIG_32 = 8192  # fp32 / fp64
_BLOCK_SMALL = 1024
_WARPS_BIG = 8
_WARPS_SMALL = 4


def _config(dtype, n):
    is_f64 = dtype == torch.float64
    if n < 32768:
        return _BLOCK_SMALL, _WARPS_SMALL
    if dtype == torch.float32 or is_f64:
        return _BLOCK_BIG_32, _WARPS_BIG
    return _BLOCK_BIG_16, _WARPS_BIG


def logaddexp2_out(self, other, out):
    with torch_device_fn.device(
        (self if isinstance(self, torch.Tensor) else other).device
    ):
        if out is None:
            out = torch.empty(
                torch.broadcast_shapes(self.shape, other.shape),
                dtype=torch.promote_types(self.dtype, other.dtype),
                device=self.device,
            )

        n = out.numel()
        if n == 0:
            return out

        x = self
        y = other
        is_f64 = out.dtype == torch.float64
        dev = out.device

        flat = (
            x.shape == out.shape
            and x.is_contiguous()
            and y.shape == out.shape
            and y.is_contiguous()
            and out.is_contiguous()
        )

        block, warps = _config(out.dtype, n)

        if flat:
            even = (n % block) == 0
            u64 = n >= (1 << 31)
            grid = (triton.cdiv(n, block),)
            _lad2_flat[grid](
                x,
                y,
                out,
                n,
                IS_F64=is_f64,
                BLOCK=block,
                EVEN=even,
                U64=u64,
                num_warps=warps,
            )
            return out

        # Generic broadcasting / strided path.
        ndim = out.dim()
        sz = tuple(out.shape)
        xst = _aligned_strides(x.shape, x.stride(), ndim)
        yst = _aligned_strides(y.shape, y.stride(), ndim)
        ost = _aligned_strides(out.shape, out.stride(), ndim)

        sz_t = torch.tensor(sz, dtype=torch.int64, device=dev)
        xst_t = torch.tensor(xst, dtype=torch.int64, device=dev)
        yst_t = torch.tensor(yst, dtype=torch.int64, device=dev)
        ost_t = torch.tensor(ost, dtype=torch.int64, device=dev)

        grid = (triton.cdiv(n, block),)
        _lad2_bcast[grid](
            x,
            xst_t,
            y,
            yst_t,
            out,
            ost_t,
            sz_t,
            n,
            IS_F64=is_f64,
            NDIM=ndim,
            BLOCK=block,
            num_warps=warps,
        )
        return out
