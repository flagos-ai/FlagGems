@triton.jit
def _to_bf16_rne(x):
    bits = x.to(tl.int32, bitcast=True)
    inc = 0x7FFF + ((bits >> 16) & 1)
    return (((bits + inc) >> 16) << 16).to(tl.float32, bitcast=True).to(tl.bfloat16)


