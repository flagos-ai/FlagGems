def _tiles(m, n, k):
    """Keep at least 8 programs in flight and avoid long serialized K chains."""
    key = (m, n, k)
    cached = _BLOCK_TILES.get(key)
    if cached is not None:
        return cached
    bk = 16
    while bk * 2 <= k and bk < 128:
        bk *= 2
    best = (16, 16)
    for bm, bn in _TILE_CANDIDATES:
        best = (bm, bn)
        if triton.cdiv(m, bm) * triton.cdiv(n, bn) >= 8:
            break
    if best[0] * best[1] >= 16384 and bk > 64:
        bk = 64
    result = (best[0], best[1], bk)
    if len(_BLOCK_TILES) < 256:
        _BLOCK_TILES[key] = result
    return result


def _warps(bm, bn):
    if bm * bn >= 4096:
        return 8
    if bm * bn >= 512:
        return 4
    return 2


