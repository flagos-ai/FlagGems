@triton.jit
def _conv_kernel(X, Y, NN, BLK: tl.constexpr):
    off = tl.program_id(0) * BLK + tl.arange(0, BLK)
    mask = off < NN
    x = tl.load(X + off, mask=mask, other=0.0)
    tl.store(Y + off, x, mask=mask)


