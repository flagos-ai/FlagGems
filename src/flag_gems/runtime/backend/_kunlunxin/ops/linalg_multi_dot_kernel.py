def _chain_order(shapes):
    """Classical matrix-chain DP over host ints; matches ATen's association."""
    cached = _CHAIN_SPLITS.get(shapes)
    if cached is not None:
        return cached
    count = len(shapes)
    dims = [shapes[0][0]] + [shape[1] for shape in shapes]
    costs = [[0] * count for _ in range(count)]
    splits = [[0] * count for _ in range(count)]
    for length in range(2, count + 1):
        for start in range(count - length + 1):
            end = start + length - 1
            best = None
            best_split = start
            for split in range(start, end):
                cost = (
                    costs[start][split]
                    + costs[split + 1][end]
                    + dims[start] * dims[split + 1] * dims[end + 1]
                )
                if best is None or cost < best:
                    best = cost
                    best_split = split
            costs[start][end] = best
            splits[start][end] = best_split
    if len(_CHAIN_SPLITS) < 256:
        _CHAIN_SPLITS[shapes] = splits
    return splits


def _multiply_chain(arrays, splits, start, end, target, out_mat=None):
    if start == end:
        return arrays[start]
    split = splits[start][end]
    left = _multiply_chain(arrays, splits, start, split, target)
    right = _multiply_chain(arrays, splits, split + 1, end, target)
    final = out_mat is not None
    if out_mat is None:
        out_mat = torch.empty(
            (left.shape[0], right.shape[1]), dtype=target, device=left.device
        )
    return _mm(left, right, out_mat, target, final)


def _multiply_three(arrays, target, out_mat):
    a, b, c = arrays
    rows, inner_ab = a.shape
    inner_bc, columns = c.shape
    left_cost = rows * inner_bc * (inner_ab + columns)
    right_cost = inner_ab * columns * (rows + inner_bc)
    if left_cost > right_cost:
        return _mm(a, _mm(b, c, None, target, False), out_mat, target, True)
    return _mm(_mm(a, b, None, target, False), c, out_mat, target, True)


