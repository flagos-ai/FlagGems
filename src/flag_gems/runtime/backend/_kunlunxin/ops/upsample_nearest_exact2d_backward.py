# ---------------------------------------------------------------------------
# Fast path: exact 2x upsample backward (outH == 2*inH and outW == 2*inW).
# Preimage of input row/col i under floor(r*(o+0.5)), r = 0.5, is exactly
# {2i, 2i+1}, so grad_input[n,c,h,w] = sum of grad_output over the 2x2 block
# (2h..2h+1, 2w..2w+1).  Deterministic, no atomics, one store per input elem.
# ---------------------------------------------------------------------------
@triton.jit
def _upsample_nearest_exact2d_bwd_2x_kernel(
    grad_out,
    grad_in,
    total,  # N*C*inH*inW
    inW,
    outW,
    BLOCK: tl.constexpr,
):
    pid = tl.program_id(0)
    idx = pid * BLOCK + tl.arange(0, BLOCK)
    m = idx < total
    row_in = idx // inW  # nc*inH + h1
    w1 = idx - row_in * inW  # % inW

    # out flat offset of (nc, 2*h1, 2*w1) == 2*row_in*outW + 2*w1
    off = row_in * (2 * outW) + 2 * w1

    a = tl.load(grad_out + off, mask=m, other=0.0).to(tl.float32)
    b = tl.load(grad_out + off + 1, mask=m, other=0.0).to(tl.float32)
    c = tl.load(grad_out + off + outW, mask=m, other=0.0).to(tl.float32)
    d = tl.load(grad_out + off + outW + 1, mask=m, other=0.0).to(tl.float32)
    acc = a + b + c + d
    tl.store(grad_in + idx, acc, mask=m)


# ---------------------------------------------------------------------------
# General fallback: scatter each grad_output element to its input location
# with fp32 atomic accumulation (exact source-index mapping of torch's
# upsample_nearest_exact2d: ih = floor((oh+0.5)*r), r = in/out or 1/scale).
# ---------------------------------------------------------------------------
@triton.jit
def _upsample_nearest_exact2d_bwd_general_kernel(
    grad_out,
    grad_in32,  # fp32 zeroed accumulator
    total_out,  # N*C*outH*outW
    inH,
    inW,
    outH,
    outW,
    rh,
    rw,
    BLOCK: tl.constexpr,
):
    pid = tl.program_id(0)
    idx = pid * BLOCK + tl.arange(0, BLOCK)
    m = idx < total_out
    ow = idx % outW
    tmp = idx // outW
    oh = tmp % outH
    nc = tmp // outH

    ih = ((oh.to(tl.float32) + 0.5) * rh).to(tl.int32)
    iw = ((ow.to(tl.float32) + 0.5) * rw).to(tl.int32)
    ih = tl.minimum(ih, inH - 1)
    iw = tl.minimum(iw, inW - 1)

    off_i = (nc * inH + ih) * inW + iw
    v = tl.load(grad_out + idx, mask=m, other=0.0).to(tl.float32)
    tl.atomic_add(grad_in32 + off_i, v, mask=m)


def _f32(x: float) -> float:
    return float(torch.tensor(x, dtype=torch.float32).item())


def upsample_nearest_exact2d_backward(
    grad_output, output_size, input_size, scales_h=None, scales_w=None
):
    with torch_device_fn.device(grad_output.device):
        N, C, inH, inW = (int(x) for x in input_size)
        outH, outW = (int(x) for x in output_size)
        NC = N * C

        if scales_h is not None and scales_h > 0.0:
            rh = _f32(1.0 / float(scales_h))
        else:
            rh = _f32(float(inH) / float(outH))
        if scales_w is not None and scales_w > 0.0:
            rw = _f32(1.0 / float(scales_w))
        else:
            rw = _f32(float(inW) / float(outW))

        grad_output = grad_output.contiguous()
        dtype = grad_output.dtype
        dev = grad_output.device
        grad_in = torch.empty((N, C, inH, inW), dtype=dtype, device=dev)

        if outH == 2 * inH and outW == 2 * inW and rh == 0.5 and rw == 0.5:
            total = N * C * inH * inW
            BLOCK = 512
            grid = (triton.cdiv(total, BLOCK),)
            _upsample_nearest_exact2d_bwd_2x_kernel[grid](
                grad_output,
                grad_in,
                total,
                inW,
                outW,
                BLOCK=BLOCK,
                num_warps=8,
            )
            return grad_in

        # general path: fp32 atomic scatter + one dtype conversion
        gin32 = torch.zeros((N, C, inH, inW), dtype=torch.float32, device=dev)
        total_out = NC * outH * outW
        BLOCK = 128
        grid = (triton.cdiv(total_out, BLOCK),)
        _upsample_nearest_exact2d_bwd_general_kernel[grid](
            grad_output,
            gin32,
            total_out,
            inH,
            inW,
            outH,
            outW,
            rh,
            rw,
            BLOCK=BLOCK,
            num_warps=4,
        )
        return gin32.to(dtype)


