"""Triton implementation of ATen's ``_dirichlet_grad``.

The op is the reparameterized gradient of the Dirichlet distribution.  The
reference (``ATen::native::dirichlet_grad_one`` in ``Distributions.h``) is a
piecewise ``if -> return`` cascade of four approximations of
``-(d/dalpha cdf)/pdf`` of a Beta distribution:

    small      : Taylor expansion around x = 0           (x <= 0.5, boundary < 2.5)
    beta_small : Taylor expansion around x = 1           (x >= 0.5, boundary < 0.75)
    mid        : Rice saddle-point expansion             (alpha > 6, beta > 6)
    rational   : log-polynomial rational correction      (everything else)

with ``beta = total - alpha`` and ``boundary = total * x * (1 - x)``.  The naive
closed form ``alpha * (digamma(total) - digamma(alpha) + log(x))`` is only
asymptotically correct and does not match the reference.

This backend cannot legalize ``tl.map_elementwise`` (the scalar-control-flow form
the reference uses), so all four branches are evaluated branchlessly on the tile
and merged with ``tl.where`` using the reference's own cascade predicates.  The
only two digammas the branches need (``total`` and ``alpha``; the ``beta_small``
branch needs ``digamma(alpha + beta) - digamma(beta) == digamma(total) -
digamma(alpha)``) are computed once and hoisted, and every branch keeps the
reference's exact operation order and correctly-rounded divisions.
"""

