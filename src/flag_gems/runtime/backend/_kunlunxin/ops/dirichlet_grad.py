@triton.jit
def _digamma(x):
    """Cephes-style digamma for strictly positive arguments."""
    PSI_10: tl.constexpr = 2.25175258906672110764

    result = tl.zeros_like(x)
    y = x
    for _ in tl.static_range(10):
        c = y < 10.0
        result = tl.where(c, result - _div_rn(1.0, y), result)
        y = tl.where(c, y + 1.0, y)

    a0 = 8.33333333333333333333e-2
    a1 = -2.10927960927960927961e-2
    a2 = 7.57575757575757575758e-3
    a3 = -4.16666666666666666667e-3
    a4 = 3.96825396825396825397e-3
    a5 = -8.33333333333333333333e-3
    a6 = 8.33333333333333333333e-2
    z = _div_rn(1.0, y * y)
    poly = (((((a6 * z + a5) * z + a4) * z + a3) * z + a2) * z + a1) * z + a0
    series = z * poly
    tail = result + tl.log(y) - _div_rn(0.5, y) - series
    return tl.where(y == 10.0, result + PSI_10, tail)


@triton.jit
def _beta_grad_alpha_small(x, alpha, beta, dig_alpha, dig_total):
    """Taylor expansion of the reparameterized Beta(alpha, beta) gradient at x=0."""
    factor = dig_alpha - dig_total - tl.log(x)
    numer = tl.zeros_like(x) + 1.0
    inv_alpha = _div_rn(1.0, alpha)
    series = _div_rn(numer, alpha) * (factor + inv_alpha)
    for i in tl.static_range(1, 11):
        ci = 1.0 * i
        numer = numer * (ci - beta) * x / ci
        denom = alpha + ci
        inv_denom = _div_rn(1.0, denom)
        series = series + _div_rn(numer, denom) * (factor + inv_denom)
    result = x * _pow(1.0 - x, -beta) * series
    return tl.where(result != result, 0.0, result)


@triton.jit
def _beta_grad_beta_small(x1, a, b, dig_total, dig_alpha):
    """Taylor expansion around x=1; called with (1 - x, beta, alpha) and negated.

    ``factor = digamma(a + b) - digamma(b) == digamma(total) - digamma(alpha)``.
    """
    factor = dig_total - dig_alpha
    numer = tl.zeros_like(x1) + 1.0
    betas = tl.zeros_like(x1) + 1.0
    dbetas = tl.zeros_like(x1)
    series = _div_rn(factor, a)
    for i in tl.static_range(1, 9):
        ci = 1.0 * i
        numer = numer * (-x1 / ci)
        dbetas = dbetas * (b - ci) + betas
        betas = betas * (b - ci)
        series = series + _div_rn(numer, a + ci) * (dbetas + factor * betas)
    result = -_pow(1.0 - x1, 1.0 - b) * series
    return tl.where(result != result, 0.0, result)


@triton.jit
def _log1p(v):
    # Accurate log(1 + v) without an extern call.
    #
    # ``tl.log(1.0 + v)`` loses relative accuracy for small ``|v|`` because
    # ``1.0 + v`` rounds away the low bits of ``v`` (log(r) ~ v, so the error
    # of the rounded sum is amplified by 1/v).  The saddle-point branch below
    # feeds it ratios that are close to 1 and multiplies the (small) log by a
    # large ``alpha``/``beta``, so this matters.  For small ``|v|`` use the
    # Taylor series; otherwise ``1 + v`` is far enough from 1 that the plain
    # log keeps full relative accuracy.
    small = tl.abs(v) < 0.25
    # Taylor series, truncated after v^10 (truncation error < 3e-8 for |v| <= 0.25).
    poly = tl.zeros_like(v)
    term = v
    for k in range(1, 11):
        poly = poly + term * (1.0 / k)
        term = -term * v
    return tl.where(small, poly, tl.log(1.0 + v))


@triton.jit
def _beta_grad_alpha_mid(x, alpha, beta):
    """Rice saddle-point expansion for alpha, beta both large.

    This branch is ill-conditioned: ``term4_base`` is a cancellation of two large
    log terms, so ``pow(term4_base, -1.5)`` amplifies any 1-ulp deviation, and the
    ``+-0.1 * std`` near-mode window is narrower than the rounding of ``mean``.
    Every division therefore uses the correctly-rounded form (C++ ``a / b``
    semantics) and the two powers use ``pow`` exactly as the reference does.
    """
    total = alpha + beta
    mean = _div_rn(alpha, total)
    std = _div_rn(_ld.sqrt(_div_rn(alpha * beta, total + 1.0)), total)
    near_mean = (mean - 0.1 * std <= x) & (x <= mean + 0.1 * std)

    # Polynomial form, valid close to the mode.
    b2 = beta * beta
    b3 = b2 * beta
    b4 = b2 * b2
    poly = 47.0 * x * b4 + alpha * (
        (43.0 + 20.0 * (16.0 + 27.0 * beta) * x) * b3
        + alpha
        * (
            3.0 * (59.0 + 180.0 * beta - 90.0 * x) * b2
            + alpha
            * (
                (453.0 + 1620.0 * beta * (1.0 - x) - 455.0 * x) * beta
                + alpha * (8.0 * (1.0 - x) * (135.0 * beta - 11.0))
            )
        )
    )
    prefactor_num = _div_rn((1.0 + 12.0 * alpha) * (1.0 + 12.0 * beta), total * total)
    prefactor_den = 12960.0 * alpha * alpha * alpha * beta * beta * (1.0 + 12.0 * total)
    poly_value = _div_rn(prefactor_num, (1.0 - x)) * _div_rn(poly, prefactor_den)

    # Saddle-point form.
    prefactor = _div_rn(-x, _ld.sqrt(_div_rn(2.0 * alpha * beta, total)))
    stirling = _div_rn(
        (1.0 + _div_rn(1.0, 12.0 * alpha) + _div_rn(1.0, 288.0 * alpha * alpha))
        * (1.0 + _div_rn(1.0, 12.0 * beta) + _div_rn(1.0, 288.0 * beta * beta)),
        (1.0 + _div_rn(1.0, 12.0 * total) + _div_rn(1.0, 288.0 * total * total)),
    )
    term1_num = (
        2.0 * alpha * alpha * (x - 1.0) + alpha * beta * (x - 1.0) - x * (beta * beta)
    )
    axbx = tl.fma(total, x, -alpha)
    term1_den = _ld.sqrt(_div_rn(2.0 * alpha, beta)) * _ld.pow(total, 1.5) * axbx * axbx
    term1 = _div_rn(term1_num, term1_den)
    log_a_over_total_x = _log1p(_div_rn(-axbx, total * x))
    term2 = 0.5 * log_a_over_total_x
    term3_num = _ld.sqrt(_div_rn(8.0 * alpha * beta, total))
    term3 = _div_rn(term3_num, axbx)
    log_b_over_total_1mx = _log1p(_div_rn(axbx, total * (1.0 - x)))
    term4_base = beta * log_b_over_total_1mx + alpha * log_a_over_total_x
    term4 = _ld.pow(term4_base, -1.5)
    term1234 = tl.where(
        x < mean,
        term1 + term2 * (term3 + term4),
        term1 + term2 * (term3 - term4),
    )
    saddle = stirling * prefactor * term1234

    return tl.where(near_mean, poly_value, saddle)


@triton.jit
def _dirichlet_grad_one(x, alpha, total):
    beta = total - alpha
    boundary = total * x * (1.0 - x)

    # The two digammas the cascade can need, evaluated once.
    dig_total = _digamma(total)
    dig_alpha = _digamma(alpha)

    m_small = (x <= 0.5) & (boundary < 2.5)
    m_beta = (x >= 0.5) & (boundary < 0.75)
    m_mid = (alpha > 6.0) & (beta > 6.0)

    v_small = _beta_grad_alpha_small(x, alpha, beta, dig_alpha, dig_total)
    v_beta = -_beta_grad_beta_small(1.0 - x, beta, alpha, dig_total, dig_alpha)
    v_mid = _beta_grad_alpha_mid(x, alpha, beta)

    # Rational-correction fallback: 3x3 double polynomial in (log x, log alpha - log x).
    u = tl.log(x)
    a = tl.log(alpha) - u
    b = tl.log(total) - a

    pow_u1 = u
    pow_u2 = u * u
    pow_a1 = a
    pow_a2 = a * a

    p = tl.zeros_like(x)
    q = tl.zeros_like(x)

    ua = 1.0
    p = p + ua * (
        1.003668233 + b * (-0.01061107488 + b * (-0.0657888334 + b * 0.01201642863))
    )
    q = q + ua * (
        1.0 + b * (-0.02924021934 + b * (-0.04438342661 + b * 0.007285809825))
    )

    ua = pow_a1
    p = p + ua * (
        0.6336835991 + b * (-0.3557432599 + b * (0.05486251648 + b * -0.001465281033))
    )
    q = q + ua * (
        0.6357567472 + b * (-0.3473456711 + b * (0.05454656494 + b * -0.002407477521))
    )

    ua = pow_a2
    p = p + ua * (
        -0.03276231906
        + b * (0.004474107445 + b * (0.002429354597 + b * -0.0001557569013))
    )
    q = q + ua * (
        -0.03301322327
        + b * (0.004845219414 + b * (0.00231480583 + b * -0.0002307248149))
    )

    ua = pow_u1
    p = p + ua * (
        0.221950385 + b * (-0.3187676331 + b * (0.01799915743 + b * 0.01074823814))
    )
    q = q + ua * (
        0.5925320577 + b * (-0.1757678135 + b * (0.01505928619 + b * 0.000564515273))
    )

    ua = pow_u1 * pow_a1
    p = p + ua * (
        -0.2951249643 + b * (0.06219954479 + b * (0.01535556598 + b * 0.001550077057))
    )
    q = q + ua * (
        0.1014815858 + b * (-0.06589186703 + b * (0.01272886114 + b * -0.0007316646956))
    )

    ua = pow_u1 * pow_a2
    p = p + ua * (
        0.02155310298
        + b * (0.004170831599 + b * (0.001292462449 + b * 6.976601077e-05))
    )
    q = q + ua * (
        -0.007258081865
        + b * (0.001096195486 + b * (0.0003934994223 + b * -4.12701925e-05))
    )

    ua = pow_u2
    p = p + ua * (
        -0.05980841433 + b * (0.008441916499 + b * (0.01085618172 + b * 0.002319392565))
    )
    q = q + ua * (
        0.06469649321
        + b * (-0.0236701437 + b * (0.002902096474 + b * -5.896963079e-05))
    )

    ua = pow_u2 * pow_a1
    p = p + ua * (
        0.02911413504 + b * (0.01400243777 + b * (-0.002721828457 + b * 0.000751041181))
    )
    q = q + ua * (
        0.001925008108
        + b * (-0.002869809258 + b * (0.0008000589141 + b * -6.063713228e-05))
    )

    ua = pow_u2 * pow_a2
    p = p + ua * (
        0.005900514878
        + b * (-0.001936558688 + b * (-9.495446725e-06 + b * 5.385558597e-05))
    )
    q = q + ua * (
        -0.0003477407336
        + b * (6.95975487e-05 + b * (1.097287507e-05 + b * -1.650969693e-06))
    )

    approx = _div_rn(x * (dig_total - dig_alpha), beta)
    v_rat = _div_rn(p, q) * approx

    return tl.where(
        m_small, v_small, tl.where(m_beta, v_beta, tl.where(m_mid, v_mid, v_rat))
    )


