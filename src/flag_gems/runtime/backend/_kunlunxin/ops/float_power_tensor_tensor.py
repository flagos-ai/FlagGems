@triton.jit
def _pow32(x, e):
    # pow(a, e) = exp2(e * log2(|a|)) with the ATen/C++ pow corner cases.
    r = tl.exp2(tl.log2(tl.abs(x)) * e)
    # (+-1)^any == 1 (incl. 1^(+-inf/NaN)) and e == 0 -> 1 (incl. 0^0, NaN^0)
    r = tl.where((tl.abs(x) == 1.0) | (e == 0.0), 1.0, r)
    # Integrality/parity of the exponent taken from the fp32 bits: the backend
    # cannot select fp_to_sint from a bf16 value (LLVM "Cannot select"), and an
    # integer->float conversion must not be folded into one.
    eb = e.to(tl.int32, bitcast=True)
    eabs = eb & 0x7FFFFFFF
    ee = eabs >> 23
    mant = eabs & 0x7FFFFF
    k = ee - 127
    kc = tl.minimum(tl.maximum(k, 0), 23)
    sh = 23 - kc
    # integer iff the (23-k) lowest mantissa bits are zero (k >= 23 always is)
    e_int = (k >= 23) | ((k >= 0) & ((mant & ((1 << sh) - 1)) == 0))
    # parity of the integer value is mantissa bit (23-k); k == 0 -> value +-1
    e_odd = ((k == 0) | (((mant >> sh) & 1) != 0)) & (k >= 0) & (k <= 23)
    neg = x.to(tl.int32, bitcast=True) < 0
    r = tl.where(neg & e_int & e_odd, -r, r)
    # only a strictly-negative finite base with a non-integer exponent -> NaN
    r = tl.where(neg & (x < 0.0) & (x > -float("inf")) & (~e_int), float("nan"), r)
    return r


