@triton.jit
def _rint_even(v, RMODE: tl.constexpr):
    """Round half to even (matches std::nearbyint / torch.round)."""
    if RMODE == 0:
        return _libdevice.nearbyint(v)
    f = tl.math.floor(v)
    d = v - f
    odd = (f - 2.0 * tl.math.floor(f * 0.5)) != 0.0
    return tl.where((d > 0.5) | ((d == 0.5) & odd), f + 1.0, f)


