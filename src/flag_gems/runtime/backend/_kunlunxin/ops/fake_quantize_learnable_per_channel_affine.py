def _inner_stride(shape, strides, ax, ndim):
    """Stride of the flattened (ax+1..ndim-1) index, or None if not collapsible."""
    if ax + 1 >= ndim:
        return 1
    for d in range(ax + 2, ndim):
        if strides[d - 1] != strides[d] * shape[d]:
            return None
    return strides[ndim - 1]


def _outer_stride(shape, strides, ax):
    """Stride of the flattened (0..ax-1) index, or None if not collapsible."""
    for d in range(ax - 1, 0, -1):
        if strides[d - 1] != strides[d] * shape[d]:
            return None
    return strides[0] if ax > 0 else 0


def _next_pow2(n):
    p = 1
    while p < n:
        p *= 2
    return p


