_BLOCK_WIDE = 32768
_WARPS_WIDE = 32
_BLOCK_NATIVE = 4096
_WARPS_NATIVE = 8


def _kg_contig_run(inp, d, s, L):
    """Copy a single contiguous byte narrow_copy: inp narrow (d, s, L) -> fresh out."""
    srcv = inp.narrow(d, s, L)  # zero-copy view, contiguous
    out = torch.empty_like(srcv)
    n = out.numel()
    if n == 0:
        return out
    es = out.element_size()
    obytes = srcv.storage_offset() * es
    nbytes = n * es
    if obytes % 8 == 0 and nbytes % 8 == 0:
        n8 = nbytes // 8
        try:
            srcw = srcv.view(torch.int64)
            outw = out.view(torch.int64)
        except RuntimeError:  # trailing dim not divisible; flatten first
            srcw = srcv.reshape(-1).view(torch.int64)
            outw = out.reshape(-1).view(torch.int64)
        # launch geometry tiers: tiny copies need only a small CTA, the
        # largest copies benefit from the widest tiles.
        if n8 <= 1024:
            BLOCK, WARPS = 1024, 2
        elif n8 <= 8192:
            BLOCK, WARPS = 8192, 8
        elif n8 <= (1 << 18):
            BLOCK, WARPS = 16384, 16
        else:
            BLOCK, WARPS = _BLOCK_WIDE, _WARPS_WIDE
        grid = (triton.cdiv(n8, BLOCK),)
        _kg_nc_copy_i64[grid](srcw, outw, n8, BLOCK=BLOCK, num_warps=WARPS)
    else:
        grid = (triton.cdiv(n, _BLOCK_NATIVE),)
        _kg_nc_copy_native[grid](
            srcv, out, n, BLOCK=_BLOCK_NATIVE, num_warps=_WARPS_NATIVE
        )
    return out


