@triton.jit
def _kg_nc_affine_kernel(
    in_ptr,
    out_ptr,
    R,
    K,
    SI,
    Cpb,
    BLOCK: tl.constexpr,
):
    pid = tl.program_id(0).to(tl.int64)
    row = pid // Cpb
    chunk = pid - row * Cpb
    offs = chunk * BLOCK + tl.arange(0, BLOCK).to(tl.int64)
    mask = offs < R
    src = row * K + SI + offs
    dst = row * R + offs
    val = tl.load(in_ptr + src, mask=mask)
    tl.store(out_ptr + dst, val, mask=mask)


