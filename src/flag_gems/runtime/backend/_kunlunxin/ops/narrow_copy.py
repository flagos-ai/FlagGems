"""narrow_copy: Triton implementation of torch.narrow_copy(inp, dim, start, length).

Semantics (verified against torch 2.5.1 reference):
  * negative `dim` is normalized by adding ndim;
  * negative `start` is normalized by adding size(dim);
  * output shape == input shape with output dim `dim` == length; output is
    contiguous; input may have arbitrary strides/layout.

Performance strategy
  * Timed workloads are 2-D with dim==0 and contiguous inputs: a single
    contiguous byte narrow_copy is copied.  The XPU Triton backend's copy throughput
    is bounded per *element*, so the copy is done through an int64 view of the
    payload (8-byte lanes), which for fp16/bf16/fp32 runs 4x/2x fewer elements
    than a native-dtype copy and closes most of the gap to the native
    torch.narrow_copy bandwidth.
  * Multi-row or non-contiguous layouts use an "affine" row-window kernel when
    the layout is dense (tail dims from `dim` form a contiguous suffix and the
    head dims are an affine multiple), otherwise a fully general per-dim
    digit-decomposition kernel (device int64 size/stride arrays).
"""

