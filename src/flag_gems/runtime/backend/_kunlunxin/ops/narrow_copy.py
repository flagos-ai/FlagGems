@triton.jit
def _kg_nc_general_kernel(
    in_ptr,
    out_ptr,
    sz_ptr,
    st_ptr,
    total,
    L,
    S,
    ND: tl.constexpr,
    D: tl.constexpr,
    BLOCK: tl.constexpr,
):
    pid = tl.program_id(0).to(tl.int64)
    offs = pid * BLOCK + tl.arange(0, BLOCK).to(tl.int64)
    mask = offs < total
    f = offs
    acc = tl.zeros((BLOCK,), dtype=tl.int64)
    for j in tl.static_range(ND - 1, -1, -1):
        if j == D:
            idx = f % L
            f = f // L
            idx = idx + S
        else:
            sz = tl.load(sz_ptr + j)
            idx = f % sz
            f = f // sz
        st = tl.load(st_ptr + j)
        acc += idx * st
    val = tl.load(in_ptr + acc, mask=mask)
    tl.store(out_ptr + offs, val, mask=mask)


_BLOCK_AFFINE = 1024
_WARPS_AFFINE = 4
_BLOCK_GEN = 256
_WARPS_GEN = 4


def _kg_scalar(v):
    if isinstance(v, torch.Tensor):
        return int(v.item())
    return int(v)


def narrow_copy(inp, dim, start, length):
    with torch_device_fn.device(inp.device):
        nd = inp.dim()
        d = _kg_scalar(dim)
        if d < 0:
            d += nd
        s = _kg_scalar(start)
        L = _kg_scalar(length)
        if s < 0:
            s += inp.shape[d]

        shape = inp.shape

        # ---- single contiguous narrow_copy (contiguous input, head dims all size 1) ----
        single = inp.is_contiguous()
        if single:
            for j in range(d):
                if shape[j] != 1:
                    single = False
                    break
        if single:
            return _kg_contig_run(inp, d, s, L)

        # ---- general path ------------------------------------------------
        out_shape = list(shape)
        out_shape[d] = L
        out = torch.empty(out_shape, dtype=inp.dtype, device=inp.device)
        total = out.numel()
        if total == 0:
            return out

        sz = shape
        st = inp.stride()

        input_view = 1
        for j in range(d + 1, nd):
            input_view *= sz[j]

        tail_ok = True
        p = 1
        for j in range(nd - 1, d - 1, -1):
            if st[j] != p:
                tail_ok = False
                break
            p *= sz[j]

        head_ok = True
        K = 0
        if tail_ok and d > 0:
            K = st[d - 1]
            q = sz[d - 1]
            for j in range(d - 2, -1, -1):
                if st[j] != K * q:
                    head_ok = False
                    break
                q *= sz[j]

        if tail_ok and head_ok:
            R = L * input_view
            output_ptr = math.prod(sz[:d])
            cpb = (R + _BLOCK_AFFINE - 1) // _BLOCK_AFFINE
            grid = (output_ptr * cpb,)
            _kg_nc_affine_kernel[grid](
                inp,
                out,
                R,
                K,
                s * input_view,
                cpb,
                BLOCK=_BLOCK_AFFINE,
                num_warps=_WARPS_AFFINE,
            )
        else:
            dev_sz = torch.tensor(tuple(sz), dtype=torch.int64, device=inp.device)
            dev_st = torch.tensor(tuple(st), dtype=torch.int64, device=inp.device)
            grid = (triton.cdiv(total, _BLOCK_GEN),)
            _kg_nc_general_kernel[grid](
                inp,
                out,
                dev_sz,
                dev_st,
                total,
                L,
                s,
                ND=nd,
                D=d,
                BLOCK=_BLOCK_GEN,
                num_warps=_WARPS_GEN,
            )
        return out
