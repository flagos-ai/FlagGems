"""Triton implementation of _upsample_nearest_exact3d_backward_grad_input.

Backward of nearest-exact 3-D upsampling, out variant.  For input coordinate i on an
axis with forward scale s (= provided scale, or O/I), the preimage in the output axis is
the half-open integer interval

    [ceil(i * s - 0.5), ceil((i + 1) * s - 0.5))   clamped to O

so the 3-D preimage of one input element is an axis-aligned box of grad_output.  The
kernel is a pure gather: one lane owns one grad_input element, accumulates its box in
fp32 and stores unconditionally (so input elements with an empty preimage become 0
without any zero-fill pass).

Backend note (flagtree/TritonXPU): `tl.load(mask=..., other=...)` does NOT honour an
interior mask on this target - masked-off lanes read the real memory value, which would
add wrong grad_output elements.  The box predicate is therefore applied arithmetically
(`tl.where`) and every gathered offset is clamped to the last valid grad_output element
with `tl.minimum` so the load never leaves the allocation.  Only the outermost store
mask is a real mask.
"""

