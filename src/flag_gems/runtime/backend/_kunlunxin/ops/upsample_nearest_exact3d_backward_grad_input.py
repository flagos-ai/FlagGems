@triton.jit
def _gi_zero_fill_kernel(gi_ptr, numel, BLOCK: tl.constexpr):
    """Write 0 into every grad_input element (unmasked interior, masked tail only)."""
    off = tl.program_id(0) * BLOCK + tl.arange(0, BLOCK)
    tl.store(gi_ptr + off, tl.zeros((BLOCK,), dtype=tl.float32), mask=off < numel)


@triton.jit
def _gi_scatter_pow2_kernel(
    go_ptr,
    gi_ptr,
    OSP,  # OD * OH * OW
    GODMAX,  # N*C*OSP - 1
    IN,  # ID * IH * IW
    OW: tl.constexpr,
    OH: tl.constexpr,
    OD: tl.constexpr,
    IW: tl.constexpr,
    IH: tl.constexpr,
    ID: tl.constexpr,
    BLOCK: tl.constexpr,
):
    """Power-of-two downsampling scatter: one lane per grad_output element.

    With I = O * 2^k on every axis the half-open preimage intervals
    [ceil(i*s - 0.5), ceil((i+1)*s - 0.5)) have width <= 1 and partition the output
    axis, so every grad_output element feeds exactly one grad_input element and no
    accumulation (and no atomics) is needed.  The exact inverse of that partition is
    i = ((2*o + 1) * I) // (2*O); with O a constexpr this is a multiply-high plus a
    shift, and every intermediate is exactly representable in float32 too, so this
    matches the float32 bound formula bit for bit.
    """
    pid = tl.program_id(0)
    nc = tl.program_id(1)
    o = pid * BLOCK + tl.arange(0, BLOCK)
    valid = o < OSP

    ow = o % OW
    rest = o // OW
    oh = rest % OH
    od = rest // OH

    iw = ((2 * ow + 1) * IW) // (2 * OW)
    ih = ((2 * oh + 1) * IH) // (2 * OH)
    id_ = ((2 * od + 1) * ID) // (2 * OD)

    v = tl.load(go_ptr + tl.minimum(nc * OSP + o, GODMAX))
    tl.store(gi_ptr + (nc * IN + (id_ * IH + ih) * IW + iw), v, mask=valid)


def _scale_value(scale, output_size: int, input_size: int) -> float:
    # Mirrors ATen compute_scales_value_backwards: a positive supplied forward scale
    # wins, otherwise the effective scale is output/input.
    if scale is not None and scale > 0:
        return float(scale)
    return output_size / input_size


def _pow2_down_ok(o: int, i: int) -> bool:
    """True when i == o * 2**k for some k >= 0, i.e. an exactly dyadic downsample."""
    if o <= 0 or i < o or i % o != 0:
        return False
    q = i // o
    return (q & (q - 1)) == 0


_BLOCK = 256
_SCATTER_BLOCK = 256
_FILL_BLOCK = 1024
_INT32_LIMIT = 2**31 - 1


def _upsample_nearest_exact3d_backward_grad_input(
    grad_output: torch.Tensor,
    output_size: Tuple[int, int, int],
    input_size: Tuple[int, int, int, int, int],
    scales_d: Optional[float] = None,
    scales_h: Optional[float] = None,
    scales_w: Optional[float] = None,
    *,
    grad_input: Optional[torch.Tensor] = None,
) -> torch.Tensor:
    od, oh, ow = int(output_size[0]), int(output_size[1]), int(output_size[2])
    n, c, id_, ih, iw = (
        int(input_size[0]),
        int(input_size[1]),
        int(input_size[2]),
        int(input_size[3]),
        int(input_size[4]),
    )
    shape = (n, c, id_, ih, iw)
    if grad_input is None:
        grad_input = torch.empty(
            shape, dtype=grad_output.dtype, device=grad_output.device
        )
    elif tuple(grad_input.shape) != shape:
        # Native out-overload semantics: an empty destination is resized in place.
        grad_input.resize_(shape)

    numel = grad_input.numel()
    if numel == 0 or grad_output.numel() == 0:
        return grad_input

    scale_d = _scale_value(scales_d, od, id_)
    scale_h = _scale_value(scales_h, oh, ih)
    scale_w = _scale_value(scales_w, ow, iw)

    max_d: int = max(1, math.ceil(scale_d))
    max_h: int = max(1, math.ceil(scale_h))
    max_w: int = max(1, math.ceil(scale_w))

    dtype = grad_output.dtype
    is_fp64 = dtype == torch.float64
    is_byte = dtype == torch.uint8
    block = _BLOCK

    go_offsets = n * c * od * oh * ow
    gi_offsets = numel
    max_off = go_offsets - 1
    contiguous = (
        grad_output.is_contiguous()
        and grad_input.is_contiguous()
        and n * c <= 65535
        and max(go_offsets, gi_offsets) <= _INT32_LIMIT
    )
    if contiguous:
        # Exactly dyadic downsampling on all three axes: every grad_input element
        # receives at most one grad_output element, so zero-fill (cheap per element)
        # plus a coalesced scatter over the much smaller grad_output is strictly
        # cheaper than a per-element gather.  The scale equality checks keep the
        # float32 ATen bound semantics identical to the integer inverse used below.
        if (
            _pow2_down_ok(ow, iw)
            and _pow2_down_ok(oh, ih)
            and _pow2_down_ok(od, id_)
            and scale_w == ow / iw
            and scale_h == oh / ih
            and scale_d == od / id_
        ):
            osp = od * oh * ow
            inner = id_ * ih * iw
            fill_block = _FILL_BLOCK
            _gi_zero_fill_kernel[(triton.cdiv(numel, fill_block),)](
                grad_input, numel, fill_block
            )
            scatter_block = _SCATTER_BLOCK
            grid = (triton.cdiv(osp, scatter_block), n * c)
            _gi_scatter_pow2_kernel[grid](
                grad_output,
                grad_input,
                osp,
                go_offsets - 1,
                inner,
                ow,
                oh,
                od,
                iw,
                ih,
                id_,
                scatter_block,
            )
            return grad_input

        inner = id_ * ih * iw
        grid = (triton.cdiv(inner, block), n * c)
        _gi_gather_kernel[grid](
            grad_output,
            grad_input,
            inner,
            iw,
            ih,
            od,
            oh,
            ow,
            max_off,
            scale_d,
            scale_h,
            scale_w,
            max_d,
            max_h,
            max_w,
            block,
            is_fp64,
            is_byte,
        )
    else:
        grid = (triton.cdiv(numel, block),)
        _gi_strided_kernel[grid](
            grad_output,
            grad_input,
            numel,
            c,
            id_,
            ih,
            iw,
            od,
            oh,
            ow,
            *grad_output.stride(),
            *grad_input.stride(),
            max_off,
            scale_d,
            scale_h,
            scale_w,
            max_d,
            max_h,
            max_w,
            block,
            is_fp64,
            is_byte,
        )
    return grad_input
