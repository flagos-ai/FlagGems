"""Kunlunxin vendor override for ``flag_gems.rrelu_`` (training path).

The public ``rrelu_train_kernel`` launches one program per ``BLOCK * UNROLL``
elements and, inside it, executes four sub-stores whose masks are
``off_i < n_elements``.  On this TritonXPU stack a program that runs a fully
masked store drops the *active* lanes of its other masked stores:

* ``n = 266``  (test shape ``(2, 19, 7)``): sub-stores 1..3 are fully masked,
  the active lanes of sub-store 0 are dropped -> output unchanged (slope 1.0
  in the test), verified ``0/266`` elements changed.
* ``n = 4097``: the tail program (1 active lane of 1024) loses that lane,
  verified ``4096/4097`` changed.
* ``n = 1024*1024``: all sub-stores fully active -> correct (slope in
  ``[0.125, 0.333]``).

A single masked (or unmasked) store per program is bit-exact on this stack
(verified for every ``n`` down to 64), so this override keeps the public
philox RNG stream layout but uses one store per program; the tail program's
suffix mask is safe, and when ``n`` divides the block the store runs unmasked.
"""

