logger = logging.getLogger(__name__)

TRAIN_BLOCK = 1024


@triton.jit(do_not_specialize=["lower", "upper", "philox_seed", "philox_offset"])
def _rrelu_train_kernel_xpu(
    x_ptr,
    out_ptr,
    n_elements,
    lower,
    upper,
    philox_seed,
    philox_offset,
    BLOCK: tl.constexpr,
    NEED_MASK: tl.constexpr,
):
    offsets = tl.program_id(0) * BLOCK + tl.arange(0, BLOCK)
    philox_seed = philox_seed.to(tl.int64)
    philox_offset = philox_offset.to(tl.int64)
    c0 = (philox_offset & 0xFFFFFFFF).to(tl.uint32)
    c1 = ((philox_offset >> 32) & 0xFFFFFFFF).to(tl.uint32)
    c0 += offsets
    _O = c0 * 0
    r0, r1, r2, r3 = tl.philox(philox_seed, c0, c1, _O, _O)
    u0 = uint_to_uniform_float(r0)
    slope = lower.to(tl.float32) + u0 * (upper.to(tl.float32) - lower.to(tl.float32))

    if NEED_MASK:
        mask = offsets < n_elements
        x = tl.load(x_ptr + offsets, mask=mask, other=0.0)
        y = tl.where(x >= 0, x, x * slope)
        tl.store(out_ptr + offsets, y, mask=mask)
    else:
        x = tl.load(x_ptr + offsets)
        y = tl.where(x >= 0, x, x * slope)
        tl.store(out_ptr + offsets, y)


def _rrelu_train_(A, lower, upper, generator=None):
    n_elements = A.numel()
    if n_elements == 0:
        return A
    grid = (triton.cdiv(n_elements, TRAIN_BLOCK),)
    # Keep the public RNG increment formula so the stream is only relaid out,
    # not re-seeded differently.
    increment = triton.cdiv(n_elements, 4)
    philox_seed, philox_offset = philox_backend_seed_offset(
        increment, generator=generator
    )
    with torch_device_fn.device(A.device):
        _rrelu_train_kernel_xpu[grid](
            A,
            A,
            n_elements,
            float(lower),
            float(upper),
            philox_seed,
            philox_offset,
            BLOCK=TRAIN_BLOCK,
            NEED_MASK=(n_elements % TRAIN_BLOCK != 0),
            num_warps=4,
        )
    return A


