# ---------------------------------------------------------------------------
# bitwise_xor_tensor_: in-place element-wise XOR  A = A ^ B  (torch semantics:
# A.bitwise_xor_(B); out aliases A and A is mutated).  B is broadcastable to
# A's shape and cast to A's dtype when dtypes differ.
#
# Fast paths (equal shape, both contiguous, equal dtypes):
#   * XOR is bit-lane independent, so 1-byte and 2-byte integer dtypes are
#     XORed through zero-copy int32 views of the same storage (4/2 elements
#     per int32).  This cuts per-CTA scheduling overhead and raises achieved
#     bandwidth on the P800.
#   * Very wide CTAs (BLOCK 16384/32768, 1024 threads) are used because
#     measured per-CTA overhead dominates small blocks on this device.
#   * The bulk of every tensor is processed with unmasked kernels.  A leftover
#     that is not a multiple of the wide block is finished by one masked
#     1024-block kernel WITHOUT `other=` on its loads: on this XPU/flagtree
#     backend masked 32-bit loads with `other=0` miscompile, and masked-off
#     lanes are never stored so leaving them undefined is safe.
#
# General fallback (_xor_bcast_kernel) handles broadcasting / non-contiguous
# layouts / mixed dtypes via per-dim coordinate decomposition.
# ---------------------------------------------------------------------------

_BLOCK_WIDE = 32768
_BLOCK_BOOL = 16384
_WARPS_WIDE = 32


@triton.jit
def _xor_flat_masked_kernel(
    a_ptr,
    b_ptr,
    n_elements,
    BLOCK: tl.constexpr,
    NEED_CAST: tl.constexpr,
):
    pid = tl.program_id(0)
    offs = pid * BLOCK + tl.arange(0, BLOCK)
    m = offs < n_elements
    av = tl.load(a_ptr + offs, mask=m)
    bv = tl.load(b_ptr + offs, mask=m)
    if NEED_CAST:
        bv = bv.to(av.dtype)
    tl.store(a_ptr + offs, av ^ bv, mask=m)


