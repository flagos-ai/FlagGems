@triton.jit
def _xor_bcast_kernel(
    a_ptr,
    b_ptr,
    meta_ptr,
    n_elements,
    RANK: tl.constexpr,
    BLOCK: tl.constexpr,
    NEED_CAST: tl.constexpr,
):
    pid = tl.program_id(0)
    offs = pid * BLOCK + tl.arange(0, BLOCK)
    mask = offs < n_elements
    r = offs
    a_off = tl.zeros([BLOCK], dtype=tl.int32)
    b_off = tl.zeros([BLOCK], dtype=tl.int32)
    for d in tl.static_range(RANK):
        vs = tl.load(meta_ptr + 3 * d)
        ats = tl.load(meta_ptr + 3 * d + 1)
        bts = tl.load(meta_ptr + 3 * d + 2)
        c = r // vs
        r = r - c * vs
        a_off = a_off + c * ats
        b_off = b_off + c * bts
    av = tl.load(a_ptr + a_off, mask=mask)
    bv = tl.load(b_ptr + b_off, mask=mask)
    if NEED_CAST:
        bv = bv.to(av.dtype)
    tl.store(a_ptr + a_off, av ^ bv, mask=mask)


def _launch(A, B, n, cast, block_main):
    """Flat kernel chain over 1-D contiguous views A, B (n elements):
    one wide unmasked bulk kernel plus one masked 1024-block tail."""
    if n == 0:
        return
    off = 0
    if n >= block_main:
        nb = n // block_main
        _xor_flat_kernel[(nb,)](
            A, B, BLOCK=block_main, NEED_CAST=cast, num_warps=_WARPS_WIDE
        )
        off = nb * block_main
    rem = n - off
    if rem:
        At = A if off == 0 else A.as_strided((rem,), (1,), A.storage_offset() + off)
        Bt = B if off == 0 else B.as_strided((rem,), (1,), B.storage_offset() + off)
        _xor_flat_masked_kernel[(triton.cdiv(rem, 1024),)](
            At, Bt, rem, BLOCK=1024, NEED_CAST=cast, num_warps=4
        )


def bitwise_xor_tensor_(A, B):
    with torch_device_fn.device(A.device):
        n = A.numel()
        if n == 0:
            return A
        sa = A.shape
        sb = B.shape

        same_shape = sa == sb
        both_contig = A.is_contiguous() and B.is_contiguous()
        same_dtype = A.dtype == B.dtype
        cast = not same_dtype
        itemsize = A.element_size()

        if same_shape and both_contig and same_dtype and itemsize in (1, 2):
            # XOR is lane independent: pack 1-byte (x4) / 2-byte (x2) elements
            # into int32 through zero-copy views of the same storage.
            factor = 4 // itemsize
            if n % factor == 0 and A.data_ptr() % 4 == 0 and B.data_ptr() % 4 == 0:
                Ap = A.reshape(-1).view(torch.int32)
                Bp = B.reshape(-1).view(torch.int32)
                block = _BLOCK_BOOL if itemsize == 1 else _BLOCK_WIDE
                _launch(Ap, Bp, Ap.numel(), False, block)
                return A

        if same_shape and both_contig:
            # equal shape, contiguous: flat element i maps to the same logical
            # element in A and B (cast inside kernel when dtypes differ).
            block = _BLOCK_BOOL if itemsize == 1 else _BLOCK_WIDE
            _launch(A.reshape(-1), B.reshape(-1), n, cast, block)
            return A

        if A.is_contiguous() and B.is_contiguous() and B.numel() == n:
            # Both contiguous with equal numel and B broadcastable to A implies
            # identical flat mappings (covers 0-d and unit-dim equal cases).
            block = _BLOCK_BOOL if itemsize == 1 else _BLOCK_WIDE
            _launch(A.reshape(-1), B.reshape(-1), n, cast, block)
            return A

        # General: broadcasting or strided layouts.
        r = A.ndim
        ss = A.stride()
        rb = B.ndim
        sbv = B.shape
        sbstr = B.stride()
        meta = []
        for d in range(r):
            prod = 1
            for k in range(d + 1, r):
                prod *= sa[k]
            meta.append(prod)
            meta.append(ss[d])
            j = d - (r - rb)
            if j < 0 or sbv[j] <= 1:
                meta.append(0)
            else:
                meta.append(sbstr[j])
        meta_t = torch.tensor(meta, dtype=torch.int32, device=A.device)
        grid = (triton.cdiv(n, 1024),)
        _xor_bcast_kernel[grid](
            A, B, meta_t, n, RANK=r, BLOCK=1024, NEED_CAST=cast, num_warps=4
        )
        return A
