def _pick_config(n_lanes):
    """Tile width and warp count from the lane count.

    No runtime autotune: the per-call autotuner key computation would be a
    measurable share of the small (4 KB) timed workloads, which sit at a ~5 us
    per-call dispatch floor.  Profiling this target showed the copy cost is
    ~2 us fixed + ~0.94 us/MB of logical traffic regardless of grid size, with
    per-thread tile depth the only configuration axis that changed the slope
    (32 int64 lanes/thread with 4 warps beat 8 lanes/thread with 8 warps), so
    the largest buckets deepen the tile further at constant warp count.
    """
    if n_lanes <= 8192:
        return 1024, 4
    if n_lanes <= 16384:
        return 2048, 4
    if n_lanes < 131072:
        return 4096, 4
    if n_lanes < 524288:
        return 8192, 4
    return 16384, 4


def _flat(x, out):
    nbytes = x.numel() * x.element_size()
    ptr = x.data_ptr()
    if not nbytes % 8 and not ptr % 8:
        lane, width = _I64, 8
    elif not nbytes % 4 and not ptr % 4:
        lane, width = _I32, 4
    elif not nbytes % 2 and not ptr % 2:
        lane, width = _I16, 2
    else:
        lane, width = _U8, 1
    try:
        src = x.reshape(-1).view(lane)
        dst = out.reshape(-1).view(lane)
        n = nbytes // width
    except RuntimeError:
        # A tensor carrying the lazy neg bit rejects dtype-converting views.
        # This backend materialises the negation, so the storage already holds
        # the logical values and the natural element width is copied as is.
        src = x.reshape(-1)
        dst = out.reshape(-1)
        if x.element_size() == 1 and x.dtype is not _U8:
            try:
                src = src.view(_U8)
                dst = dst.view(_U8)
            except RuntimeError:
                pass
        n = x.numel()
    block, warps = _pick_config(n)
    _copy_flat[(max(1, (n + block - 1) // block),)](
        src, dst, n, BLOCK=block, num_warps=warps
    )


def _collapse(shape, istr, ostr):
    """Merge adjacent dimensions that are contiguous in both operands."""
    dims = []
    cur = None
    for k in range(len(shape) - 1, -1, -1):
        sz = shape[k]
        if sz == 1:
            continue
        i_s = istr[k]
        o_s = ostr[k]
        if cur is not None and i_s == cur[0] * cur[1] and o_s == cur[0] * cur[2]:
            cur = (cur[0] * sz, i_s, o_s)
        else:
            if cur is not None:
                dims.append(cur)
            cur = (sz, i_s, o_s)
    if cur is not None:
        dims.append(cur)
    dims.reverse()
    return dims


def _strided(x, out):
    if x.numel() == 0:
        _flat(x.reshape(-1), out.reshape(-1))
        return
    dims = _collapse(tuple(x.shape), x.stride(), out.stride())
    if not dims:
        dims = [(1, 0, 0)]
    if len(dims) > _MAX_DIMS:
        # Irregular layouts of rank > 8: recurse slice by slice on the
        # outermost dimension (each slice is a zero-copy view).
        for k in range(dims[0][0]):
            _strided(x.select(0, k), out.select(0, k))
        return
    args = []
    for pick in (1, 2, 0):
        for k in range(_MAX_DIMS):
            args.append(dims[k][pick] if k < len(dims) else (0 if pick else 1))
    src = x
    dst = out
    if x.element_size() == 1:
        src = x.view(_U8)
        dst = out.view(_U8)
    n = x.numel()
    block = 1024
    _copy_strided[((n + block - 1) // block,)](
        src, dst, n, *args, NRANK=len(dims), BLOCK=block, num_warps=4
    )


def detach_copy(self, out=None):
    x = self
    if out is None:
        out = torch.empty_like(x, memory_format=torch.contiguous_format)
    elif out.dtype != x.dtype:
        raise TypeError(f"detach_copy(): expected out dtype {x.dtype}, got {out.dtype}")
    if x.dtype.is_complex:
        # Triton has no complex element type; the real view is a zero-copy
        # reinterpretation that preserves the byte stream.
        x = torch.view_as_real(x)  # allow-torch-compute: view only
        v = torch.view_as_real(out)  # allow-torch-compute: view only
    else:
        v = out
    if x.is_contiguous() and v.is_contiguous():
        _flat(x, v)
    else:
        _strided(x, v)
    return out
