"""Triton implementation of ``aten::detach_copy`` (functional copy with detach).

Contract reproduced from native aten behaviour (probed on this target):
  * the output is a *fresh* allocation that is always ``contiguous`` — native
    does not preserve a non-contiguous input layout (unlike ``clone()``), so the
    output is allocated with ``memory_format=torch.contiguous_format``;
  * values are copied bit-exactly (NaN payloads, -0.0, subnormals survive);
  * ``torch._neg_view`` inputs need no per-element negation here: this backend
    materialises the negation eagerly, so the raw storage already holds the
    logical values (verified against native ``aten::detach_copy``);
  * 0-dim and empty inputs are supported (one masked launch, never grid == 0);
  * the ``out=`` overload writes into and returns the caller's buffer and
    rejects a dtype mismatch.

Fast path: flat contiguous input and output copied as wide integer lanes
(8/4/2/1 bytes) so the backend issues 16-byte vector accesses.  Non-contiguous
inputs go through a stride-decomposing gather kernel that walks the logical
index space and honours both input and output strides.
"""

