@triton.jit
def _erfc_core(x):
    a = tl.abs(x)
    y = a * a
    e = tl.exp(-y)
    t = a * (1.0 / 3.0) - 1.0
    t = tl.minimum(t, 1.0)
    h = 0.0
    for j in tl.static_range(0, 21):
        h = h * t + _H20[20 - j]
    r = e * h
    return tl.where(x < 0.0, 2.0 - r, r)


