# erfc(x):  a = |x|,  erfc(a) = exp(-a^2) * H(a)   for all a >= 0
# where H(a) = exp(a^2)*erfc(a) is smooth on [0,6] (H(0)=1, H(6)~0.0925,
# and beyond a=6 we clamp the Chebyshev variable, which makes H ~ H(6),
# an error far below fp32 resolution because exp(-a^2) is < 2.3e-16).
# H is evaluated as a degree-20 polynomial in t = (a-3)/3 in [-1,1]
# (power basis in t is well conditioned: max |coef| ~ 0.18).
# For x < 0: erfc(x) = 2 - erfc(|x|).
# ---------------------------------------------------------------

