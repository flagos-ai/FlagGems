import math

import torch
import triton
import triton.language as tl

# Generated by KernelGen: https://github.com/flagos-ai/KernelGen
from flag_gems.runtime import torch_device_fn


@triton.jit
def _pdist_pairpers_kernel(
    x_ptr,
    out_ptr,
    N,
    M,
    p_val,
    total,
    p_mode: tl.constexpr,
    BLOCK_M: tl.constexpr,
    HAS_MASK: tl.constexpr,
):
    """pdist forward, flat condensed output order.

    A small grid of persistent programs strides over all N*(N-1)//2 condensed
    output slots (pair (i, j), i < j, slot i*(2N-i-1)//2 + (j-i-1)).  Each slot
    is resolved to its row pair by an exact closed-form inverse of the
    triangular index (float sqrt plus a 2-step integer correction), then the
    two rows are loaded and reduced over M features.
    """
    pid = tl.program_id(0)
    nblk = tl.num_programs(0)
    twoN1 = 2 * N - 1
    m = tl.arange(0, BLOCK_M)
    for pair in range(pid, total, nblk):
        # i = largest row with base(i) = i*(2N-1-i)//2 <= pair, via quadratic inverse
        disc = twoN1 * twoN1 - 8 * pair
        i = ((twoN1.to(tl.float32) - tl.sqrt(disc.to(tl.float32))) * 0.5).to(tl.int32)
        for _ in tl.static_range(2):
            b = i * (twoN1 - i) // 2
            i = tl.where(b > pair, i - 1, i)
            b1 = (i + 1) * (twoN1 - i - 1) // 2
            i = tl.where(b1 <= pair, i + 1, i)
        base_i = i * (twoN1 - i) // 2
        row_j = i + 1 + (pair - base_i)
        if HAS_MASK:
            mm = m < M
            xi = tl.load(x_ptr + i * M + m, mask=mm, other=0.0).to(tl.float32)
            xj = tl.load(x_ptr + row_j * M + m, mask=mm, other=0.0).to(tl.float32)
        else:
            xi = tl.load(x_ptr + i * M + m).to(tl.float32)
            xj = tl.load(x_ptr + row_j * M + m).to(tl.float32)
        df = tl.abs(xi - xj)
        if p_mode == 0:  # p == 2
            res = tl.sqrt(tl.sum(df * df))
        elif p_mode == 1:  # p == 1
            res = tl.sum(df)
        elif p_mode == 2:  # p == 0: number of non-zero differences
            res = tl.sum(tl.where(df > 0.0, 1.0, 0.0))
        elif p_mode == 3:  # p == inf
            res = tl.max(df)
        else:  # general finite p
            acc = tl.sum(tl.where(df > 0.0, tl.exp(p_val * tl.log(df)), 0.0))
            res = tl.where(acc > 0.0, tl.exp(tl.log(acc) / p_val), 0.0)
        tl.store(out_ptr + pair, res)


def _next_pow2(n):
    return 1 << (n - 1).bit_length()


def pdist_forward(x, p=2.0):
    with torch_device_fn.device(x.device):
        if x.dim() != 2:
            raise ValueError("pdist expects a 2D input of shape (N, M)")
        N, M = x.shape
        if N < 1 or M < 1:
            raise ValueError("pdist requires a non-empty input")
        if p < 0:
            raise ValueError("p must be non-negative")

        if p == 2.0:
            mode = 0
        elif p == 1.0:
            mode = 1
        elif p == 0.0:
            mode = 2
        elif math.isinf(p):
            mode = 3
        else:
            mode = 4

        total = N * (N - 1) // 2
        out = torch.empty(total, dtype=x.dtype, device=x.device)
        if total == 0:
            return out

        x = x.contiguous()
        N, M = x.shape
        if M > 1024:
            raise ValueError("pdist feature dimension > 1024 is not supported")

        BM = _next_pow2(M)
        if BM < 64:
            BM = 64
        has_mask = BM != M

        nblk = total if total < 256 else 256
        _pdist_pairpers_kernel[(nblk,)](
            x,
            out,
            N,
            M,
            float(p),
            total,
            p_mode=mode,
            BLOCK_M=BM,
            HAS_MASK=has_mask,
            num_warps=1,
        )
        return out


_pdist_forward = pdist_forward
