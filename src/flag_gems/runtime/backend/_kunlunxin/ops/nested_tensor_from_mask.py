import triton.language as tl

_VIOLATION_TAG = 1 << 24
_MSG = "Mask must be left-aligned without gaps"
_CFG = {}

# bound once: the per-call python path is part of the O(1) cost
_empty = torch.empty
_narrow = torch.Tensor.narrow
# Materialize the legacy strided NestedTensor container from tensor views.
