_next_pow2 = triton.next_power_of_2


@triton.jit
def _mask_info_kernel(
    mask_ptr,
    lens_ptr,
    L: tl.constexpr,
    stride_n: tl.constexpr,
    stride_l: tl.constexpr,
    BLOCK: tl.constexpr,
    NCHUNK: tl.constexpr,
    MASK_CHECK: tl.constexpr,
):
    pid = tl.program_id(0)
    base = mask_ptr + pid.to(tl.int64) * stride_n
    idx = tl.arange(0, BLOCK)

    count = 0
    last = -1
    for c in tl.static_range(NCHUNK):
        i = c * BLOCK + idx
        # clamped load instead of a masked load: the KL3 mask pass rejects it
        m = tl.load(base + tl.minimum(i, L - 1) * stride_l).to(tl.int32)
        m = tl.where(i < L, m, 0)
        count += tl.sum(m, axis=0)
        if MASK_CHECK:
            last = tl.maximum(last, tl.max(tl.where(m != 0, i, -1), axis=0))

    if MASK_CHECK:
        # left aligned iff the last True sits at index count-1 (cumprod(mask)==mask)
        viol = (count > 0) & (last != count - 1)
        count = count + tl.where(viol, 1 << 24, 0)

    # scalar store: vector stores of reductions are miscompiled on this backend
    tl.store(lens_ptr + pid, count)


