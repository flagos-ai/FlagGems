# Correctly rounded f32 of a non-negative double (round-to-nearest-even),
# returned as a python float whose value is exactly the f32.
def _round_f32(x: float) -> float:
    if x == 0.0 or not math.isfinite(x):
        return x
    e = math.floor(math.log2(x))
    m = x * math.ldexp(1.0, 23 - e)  # in [2^23, 2^24)
    q = math.floor(m)
    frac = m - q
    if frac > 0.5 or (frac == 0.5 and (q % 2 == 1)):
        q += 1.0
    if q >= 2.0**24:
        q /= 2.0
        e += 1
    return math.ldexp(q, int(e) - 23)


