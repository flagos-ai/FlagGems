import logging

import torch
import triton
import triton.language as tl

from flag_gems.utils import pointwise_dynamic

logger = logging.getLogger(__name__)

_INT32_LIMIT = 2**31 - 1


@triton.jit
def _to_compute_dtype(x):
    # Promote 16-bit floats to fp32 for arithmetic (matches torch opmath_type);
    # keep fp32/fp64/integer dtypes in their native precision.
    if x.dtype == tl.float16:
        return x.to(tl.float32)
    elif x.dtype == tl.bfloat16:
        return x.to(tl.float32)
    else:
        return x


# ------------------------- fast path kernels -------------------------
# Hand-written flat 1D kernels with plain pointer arithmetic. On some backends
# these measurably beat the block-pointer based kernels generated by
# pointwise_dynamic. Used only when every operand is contiguous, same-shaped
# and same-dtype; otherwise the generic pointwise_dynamic path is taken.


@triton.jit
def _clamp_tensor_kernel(x_ptr, lo_ptr, hi_ptr, out_ptr, N, BLOCK: tl.constexpr):
    pid = tl.program_id(0).to(tl.int64)
    offs = pid * BLOCK + tl.arange(0, BLOCK)
    mask = offs < N
    x = _to_compute_dtype(tl.load(x_ptr + offs, mask=mask))
    lo = _to_compute_dtype(tl.load(lo_ptr + offs, mask=mask))
    hi = _to_compute_dtype(tl.load(hi_ptr + offs, mask=mask))
    tl.store(out_ptr + offs, tl.minimum(hi, tl.maximum(lo, x)), mask=mask)


@triton.jit
def _clamp_min_tensor_kernel(x_ptr, lo_ptr, out_ptr, N, BLOCK: tl.constexpr):
    pid = tl.program_id(0).to(tl.int64)
    offs = pid * BLOCK + tl.arange(0, BLOCK)
    mask = offs < N
    x = _to_compute_dtype(tl.load(x_ptr + offs, mask=mask))
    lo = _to_compute_dtype(tl.load(lo_ptr + offs, mask=mask))
    tl.store(out_ptr + offs, tl.maximum(lo, x), mask=mask)


@triton.jit
def _clamp_max_tensor_kernel(x_ptr, hi_ptr, out_ptr, N, BLOCK: tl.constexpr):
    pid = tl.program_id(0).to(tl.int64)
    offs = pid * BLOCK + tl.arange(0, BLOCK)
    mask = offs < N
    x = _to_compute_dtype(tl.load(x_ptr + offs, mask=mask))
    hi = _to_compute_dtype(tl.load(hi_ptr + offs, mask=mask))
    tl.store(out_ptr + offs, tl.minimum(hi, x), mask=mask)


def _clamp_fast_path_ok(*tensors):
    t0 = tensors[0]
    if t0.dtype not in (torch.float16, torch.bfloat16, torch.float32, torch.float64):
        return False
    for t in tensors[1:]:
        if (
            not isinstance(t, torch.Tensor)
            or t.dtype != t0.dtype
            or t.shape != t0.shape
            or not t.is_contiguous()
        ):
            return False
    return t0.is_contiguous()


def _launch_clamp(kernel, out, *ins):
    N = out.numel()
    BLOCK = 2048
    grid = (triton.cdiv(N, BLOCK),)
    kernel[grid](*ins, out, N, BLOCK=BLOCK, num_warps=8)
    return out


# ------------------------- generic path kernels -------------------------


@pointwise_dynamic(promotion_methods=[(0, 1, 2, "DEFAULT")])
@triton.jit
def clamp_func_tensor(x, mini, maxi):
    return tl.minimum(maxi, tl.maximum(mini, x.to(tl.float32)))


@pointwise_dynamic(promotion_methods=[(0, 1, "DEFAULT")])
@triton.jit
def clamp_func_min_tensor(x, mini):
    return tl.maximum(mini, x.to(tl.float32))


@pointwise_dynamic(promotion_methods=[(0, 1, "DEFAULT")])
@triton.jit
def clamp_func_max_tensor(x, maxi):
    return tl.minimum(maxi, x.to(tl.float32))


def clamp_tensor(A, mini=None, maxi=None):
    logger.debug("GEMS_HYGON CLAMP_TENSOR")
    if mini is None and maxi is None:
        raise ValueError("At least one of mini or maxi must not be None")
    elif mini is None:
        if _clamp_fast_path_ok(A, maxi):
            return _launch_clamp(_clamp_max_tensor_kernel, torch.empty_like(A), A, maxi)
        return clamp_func_max_tensor(A, maxi)
    elif maxi is None:
        if _clamp_fast_path_ok(A, mini):
            return _launch_clamp(_clamp_min_tensor_kernel, torch.empty_like(A), A, mini)
        return clamp_func_min_tensor(A, mini)
    else:
        if _clamp_fast_path_ok(A, mini, maxi):
            return _launch_clamp(
                _clamp_tensor_kernel, torch.empty_like(A), A, mini, maxi
            )
        return clamp_func_tensor(A, mini, maxi)


def clamp_tensor_(A, mini=None, maxi=None):
    logger.debug("GEMS_HYGON CLAMP_TENSOR_")
    if mini is None and maxi is None:
        raise ValueError("At least one of mini or maxi must not be None")
    elif mini is None:
        if _clamp_fast_path_ok(A, maxi):
            return _launch_clamp(_clamp_max_tensor_kernel, A, A, maxi)
        return clamp_func_max_tensor(A, maxi, out0=A)
    elif maxi is None:
        if _clamp_fast_path_ok(A, mini):
            return _launch_clamp(_clamp_min_tensor_kernel, A, A, mini)
        return clamp_func_min_tensor(A, mini, out0=A)
    else:
        if _clamp_fast_path_ok(A, mini, maxi):
            return _launch_clamp(_clamp_tensor_kernel, A, A, mini, maxi)
        return clamp_func_tensor(A, mini, maxi, out0=A)


@pointwise_dynamic(
    is_tensor=[True, False, False], promotion_methods=[(0, 1, 2, "DEFAULT")]
)
@triton.jit
def clamp_func(x, mini, maxi):
    return tl.minimum(maxi, tl.maximum(mini, x.to(tl.float32)))


@pointwise_dynamic(is_tensor=[True, False], promotion_methods=[(0, 1, "DEFAULT")])
@triton.jit
def clamp_func_min(x, mini):
    return tl.maximum(mini, x.to(tl.float32))


@pointwise_dynamic(is_tensor=[True, False], promotion_methods=[(0, 1, "DEFAULT")])
@triton.jit
def clamp_func_max(x, maxi):
    return tl.minimum(maxi, x.to(tl.float32))


def clamp_min(A, mini):
    logger.debug("GEMS_HYGON CLAMP_MIN")
    if mini is None:
        raise ValueError("Mini must not be None")
    return clamp_func_min(A, mini)


def clamp_min_(A, mini):
    logger.debug("GEMS_HYGON CLAMP_MIN_")
    if mini is None:
        raise ValueError("Mini must not be None")
    return clamp_func_min(A, mini, out0=A)


def clamp(A, mini=None, maxi=None):
    logger.debug("GEMS_HYGON CLAMP")
    if mini is None and maxi is None:
        raise ValueError("At least one of mini or maxi must not be None")
    elif mini is None:
        return clamp_func_max(A, maxi)
    elif maxi is None:
        return clamp_func_min(A, mini)
    else:
        return clamp_func(A, mini, maxi)


def clamp_(A, mini=None, maxi=None):
    logger.debug("GEMS_HYGON CLAMP_")
    if mini is None and maxi is None:
        raise ValueError("At least one of mini or maxi must not be None")
    elif mini is None:
        return clamp_func_max(A, maxi, out0=A)
    elif maxi is None:
        return clamp_func_min(A, mini, out0=A)
    else:
        return clamp_func(A, mini, maxi, out0=A)
