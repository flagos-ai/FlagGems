def _may_overlap(lhs, rhs):
    overlaps = getattr(torch._C, "_overlaps", None)
    if overlaps is not None:
        return overlaps(lhs, rhs)

    lhs_base = lhs.untyped_storage().data_ptr()
    rhs_base = rhs.untyped_storage().data_ptr()
    return lhs_base == rhs_base


