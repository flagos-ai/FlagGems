    assert mat1.shape[1] == mat2.shape[0], "Incompatible dimensions"
    assert broadcastable_to(
        self.shape, (mat1.shape[0], mat2.shape[1])
    ), "Incompatible input shape"

    logger.debug("GEMS ADDMM_")

    if self.numel() == 0:
        return self

    out_shape = (mat1.shape[0], mat2.shape[1])
    if (
        self.shape == out_shape
        and not _may_overlap(self, mat1)
        and not _may_overlap(self, mat2)
    ):
        return addmm_out(self, mat1, mat2, beta=beta, alpha=alpha, out=self)

    result = addmm(self, mat1, mat2, beta=beta, alpha=alpha)
    return self.copy_(result)
