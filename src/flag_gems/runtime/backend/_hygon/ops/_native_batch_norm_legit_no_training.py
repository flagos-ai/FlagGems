# For contiguous NCHW-style input, the elements of one (batch, channel) slab
# are fully contiguous, so the whole problem flattens to independent 1D tiles
# of the spatial dim with a per-channel affine transform. This launches
# batch_dim * feat_dim * cdiv(spatial_dim, BLOCK) programs instead of only
# feat_dim programs, which is critical when feat_dim is small (e.g. 6-16)
# relative to the number of compute units.


@triton.jit
def batch_norm_legit_no_training_contig_kernel(
    input_pointer,
    weight_pointer,
    bias_pointer,
    output_pointer,
    running_mean_pointer,
    running_var_pointer,
    feat_dim,
    spatial_dim,
    num_s_tiles,
    eps,
    HAS_WEIGHT: tl.constexpr,
    HAS_BIAS: tl.constexpr,
    BLOCK: tl.constexpr,
):
    pid = tl.program_id(0)
    slab_pid = pid // num_s_tiles
    s_tile = pid % num_s_tiles
    c = slab_pid % feat_dim

    # Per-channel affine: output = input * a + b where
    # a = weight * inv_std, b = bias - mean * a.
    running_mean = tl.load(running_mean_pointer + c).to(tl.float32)
    running_var = tl.load(running_var_pointer + c).to(tl.float32)
    inv_std = rsqrt(running_var + eps)

    if HAS_WEIGHT:
        weight = tl.load(weight_pointer + c).to(tl.float32)
    else:
        weight = 1.0
    if HAS_BIAS:
        bias = tl.load(bias_pointer + c).to(tl.float32)
    else:
        bias = 0.0

    a = weight * inv_std
    b = bias - running_mean * a

    offset = s_tile * BLOCK + tl.arange(0, BLOCK)
    mask = offset < spatial_dim
    base = slab_pid.to(tl.int64) * spatial_dim
    curr_input = tl.load(input_pointer + base + offset, mask=mask).to(tl.float32)
    output = curr_input * a + b
    tl.store(output_pointer + base + offset, output, mask=mask)


