    slab_pid = pid // num_s_tiles
    s_tile = pid % num_s_tiles
    c = slab_pid % feat_dim

    # Per-channel affine: output = input * a + b where
    # a = weight * inv_std, b = bias - mean * a.
    acc_dtype = save_mean_pointer.dtype.element_ty
