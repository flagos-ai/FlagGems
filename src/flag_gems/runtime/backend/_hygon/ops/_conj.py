import triton.language as tl

from flag_gems.utils import libentry

logger = logging.getLogger(__name__)

_SIGN_BIT_I64 = tl.constexpr(-9223372036854775808)  # 0x8000000000000000

# Tuned on DCU (sweep at 8MiB-2GiB working sets, torch copy_ roofline =
# 1381 GB/s). 512 int64 lanes per block with 8 warps saturates the stream
# bandwidth (1379 GB/s) for large tensors; below ~512MiB of u64 lanes the
# launch geometry favors 1024 lanes per block (1353 vs 1335 GB/s at 128MiB).
# Eviction-policy/cache-modifier hints and multi-tile grids were also
# measured and do not beat the plain single-tile kernel.
BLOCK_SIZE_LARGE = 512
BLOCK_SIZE_SMALL = 1024
LARGE_THRESHOLD = 1 << 26  # u64 lanes, i.e. a 512MiB read+write stream
NUM_WARPS = 8


def _block_size(n_i64: int) -> int:
    return BLOCK_SIZE_LARGE if n_i64 >= LARGE_THRESHOLD else BLOCK_SIZE_SMALL


@libentry()
@triton.jit
def _conj_kernel_u64(
    in_ptr,
    out_ptr,
    n_i64,
    FLIP: tl.constexpr,  # 0 = pure copy, 1 = flip every lane, 2 = flip odd lanes
    BLOCK_SIZE: tl.constexpr,
):
    # Conjugate = flip the sign bit of the imaginary lane. Treating the data as
    # uint64 lanes gives perfectly coalesced wide accesses:
    #   complex64  -> one u64 per element, flip the high 32 bits (imag lane)
    #   complex128 -> two u64 per element, flip the odd lanes only
    pid = tl.program_id(0)
    offsets = pid * BLOCK_SIZE + tl.arange(0, BLOCK_SIZE)
    mask = offsets < n_i64
    v = tl.load(in_ptr + offsets, mask=mask)
    if FLIP == 1:
        v = v ^ _SIGN_BIT_I64
    elif FLIP == 2:
        v = v ^ tl.where(offsets % 2 == 1, _SIGN_BIT_I64, 0)
    tl.store(out_ptr + offsets, v, mask=mask)


