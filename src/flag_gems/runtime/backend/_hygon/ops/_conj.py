def _u64_view(t: torch.Tensor) -> torch.Tensor:
    """Reinterpret a complex tensor's storage as int64 lanes.

    Works even when the conj bit is set (dtype-reinterpret views are rejected
    on conj views) by aliasing the untyped storage directly. Requires
    contiguous layout.
    """
    if not t.is_conj():
        return t.view(torch.int64)
    n_i64 = t.numel() * t.element_size() // 8
    u64 = torch.empty(0, dtype=torch.int64, device=t.device)
    u64.set_(t.untyped_storage(), t.storage_offset() * t.element_size() // 8,
             (n_i64,))
    return u64


