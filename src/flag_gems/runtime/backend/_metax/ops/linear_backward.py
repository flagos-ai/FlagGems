def linear_backward(input, grad_output, weight, output_mask):
    m0 = bool(output_mask[0])
    m1 = bool(output_mask[1])
    m2 = bool(output_mask[2])

    M, K = input.shape
    N = grad_output.shape[1]
    dev = input.device
    is_fp32 = input.dtype == torch.float32

    gi = torch.empty((M, K), device=dev, dtype=input.dtype) if m0 else None
    gw = torch.empty((N, K), device=dev, dtype=weight.dtype) if m1 else None
    gb = torch.empty((N,), device=dev, dtype=grad_output.dtype) if m2 else None

    if is_fp32:
        if K < 256:
            # ---- exact tf32 reference semantics (correctness shapes) ----
            if m0:
                _gi_kernel[(triton.cdiv(M, 64) * triton.cdiv(K, 32),)](
                    grad_output,
                    weight,
                    gi,
                    M,
                    N,
                    K,
                    BM=64,
                    BN=64,
                    BK=32,
                    MODE=1,
                    num_warps=4,
                    num_stages=1,
                )
            if m1:
                _gw_kernel[(triton.cdiv(N, 64) * triton.cdiv(K, 32),)](
                    input,
                    grad_output,
                    gw,
                    gb if m2 else gw,
                    M,
                    N,
                    K,
                    BM=64,
                    BN=64,
                    BK=32,
                    MODE=1,
                    DO_BIAS=m2,
                    num_warps=4,
                    num_stages=1,
                )
            elif m2:
                _bias_kernel[(triton.cdiv(N, 64),)](
                    grad_output, gb, M, N, BN=64, BM=64, num_warps=4
                )
        elif K < 2048:
            # ---- fp16 in-kernel-cast path: fused single launch when possible
            grid = triton.cdiv(M, 16) * triton.cdiv(K, 32) + triton.cdiv(
                N, 64
            ) * triton.cdiv(K, 32)
            _gi_gw_kernel[(grid,)](
                grad_output,
                weight,
                input,
                gi if m0 else gw,
                gw if m1 else gb,
                gb if m2 else gb,
                M,
                N,
                K,
                BM=16,
                BK=32,
                BN_GI=64,
                BN_GW=64,
                DO_BIAS=m2,
                CAST=True,
                DO_GI=m0,
                DO_GW=m1,
                num_warps=4,
                num_stages=2,
            )
        else:
            # ---- pre-cast fp16 path (big gemms): cast3 + transpose + 2 MMA
            go16 = torch.empty((M, N), device=dev, dtype=torch.float16)
            w16 = torch.empty((N, K), device=dev, dtype=torch.float16)
            inp16 = torch.empty((M, K), device=dev, dtype=torch.float16)
            n_go = M * N
            n_w = N * K
            n_inp = M * K
            grid3 = (
                triton.cdiv(n_go, 4096)
                + triton.cdiv(n_w, 4096)
                + triton.cdiv(n_inp, 4096)
            )
            _cast3_kernel[(grid3,)](
                grad_output,
                weight,
                input,
                go16,
                w16,
                inp16,
                n_go,
                n_w,
                n_inp,
                BLK=2048,
                num_warps=4,
            )
            if m1:
                goT16 = torch.empty((N, M), device=dev, dtype=torch.float16)
                _transpose_kernel[(triton.cdiv(M, 64) * triton.cdiv(N, 64),)](
                    go16, goT16, M, N, BM=64, BN=64, num_warps=4
                )
            if m0:
                _gi_kernel[(triton.cdiv(M, 64) * triton.cdiv(K, 64),)](
                    go16,
                    w16,
                    gi,
                    M,
                    N,
                    K,
                    BM=64,
                    BN=64,
                    BK=64,
                    MODE=0,
                    num_warps=4,
                    num_stages=3,
                )
            if m1:
                _gwT_kernel[(triton.cdiv(N, 128) * triton.cdiv(K, 64),)](
                    goT16,
                    inp16,
                    gw,
                    gb if m2 else gw,
                    M,
                    N,
                    K,
                    BM=64,
                    BN=128,
                    BK=64,
                    DO_BIAS=m2,
                    num_warps=4,
                    num_stages=2,
                )
            elif m2:
                _bias_kernel[(triton.cdiv(N, 64),)](
                    grad_output, gb, M, N, BN=64, BM=64, num_warps=4
                )
    else:
        # ---- native fp16/bf16 path: fused single launch when possible ----
        grid = triton.cdiv(M, 32) * triton.cdiv(K, 64) + triton.cdiv(
            N, 128
        ) * triton.cdiv(K, 64)
        _gi_gw_kernel[(grid,)](
            grad_output,
            weight,
            input,
            gi if m0 else gw,
            gw if m1 else gb,
            gb if m2 else gb,
            M,
            N,
            K,
            BM=32,
            BK=64,
            BN_GI=64,
            BN_GW=128,
            DO_BIAS=m2,
            CAST=False,
            DO_GI=m0,
            DO_GW=m1,
            num_warps=4,
            num_stages=3,
        )

    return gi, gw, gb
