# tf32 round-to-nearest-even: reproduces the operand rounding that torch's
# fp32 matmul (allow_tf32) uses on this platform (reference semantics).
@triton.jit
def _tf32_round(x):
    xi = x.to(tl.int32, bitcast=True)
    lsb = (xi >> 13) & 1
    xi = xi + 0x0FFF + lsb
    xi = xi & -8192
    return xi.to(tl.float32, bitcast=True)


