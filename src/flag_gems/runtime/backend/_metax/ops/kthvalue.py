logger = logging.getLogger(__name__)


def _muxi_topk(x, k, descending):
    """2-stage chunked topk selection on Muxi GPU.

    The generic topk falls back to a single-stage bitonic sort for small N,
    which is O(N log^2 N) on the full array. This function always uses the
    two-stage approach (chunk -> local topk -> merge) regardless of N, since
    only k elements are needed and k is typically small for kthvalue.
    """
    topk_elem_cnt = x.shape[-1]
    batch_size = math.prod(x.shape) // topk_elem_cnt

    if topk_elem_cnt <= 128:
        chunk_size = max(triton.next_power_of_2(topk_elem_cnt), 64)
        chunk_size = max(chunk_size, triton.next_power_of_2(k))
    elif topk_elem_cnt <= 1024:
        chunk_size = 256
    else:
        chunk_size = 1024

    if chunk_size < k:
        chunk_size = triton.next_power_of_2(k)
    if not (chunk_size & (chunk_size - 1)) == 0:
        chunk_size = triton.next_power_of_2(chunk_size)

    chunk_num = triton.cdiv(topk_elem_cnt, chunk_size)

    stage1_out = torch.empty(batch_size * chunk_num * k, device=x.device, dtype=x.dtype)
    stage1_out_idx = torch.empty(
        batch_size * chunk_num * k, device=x.device, dtype=torch.int64
    )

    out_shape = x.shape[:-1] + (k,)
    stage2_out = torch.empty(out_shape, device=x.device, dtype=x.dtype)
    stage2_out_idx = torch.empty(out_shape, device=x.device, dtype=torch.int64)

    with torch_device_fn.device(x.device):
        topk_stage1_kernel[
            batch_size,
            chunk_num,
        ](
            stage1_out,
            stage1_out_idx,
            x,
            k,
            topk_elem_cnt,
            chunk_size,
            descending,
        )

    stage2_elem_cnt = chunk_num * k
    BLOCK_SIZE = triton.next_power_of_2(stage2_elem_cnt)

    with torch_device_fn.device(x.device):
        topk_stage2_kernel[batch_size,](
            stage2_out,
            stage2_out_idx,
            stage1_out,
            stage1_out_idx,
            -1,
            k,
            stage2_elem_cnt,
            BLOCK_SIZE,
            descending,
        )

    return stage2_out, stage2_out_idx


def kthvalue(inp, k, dim=-1, keepdim=False):
    """Return the k-th smallest elements and their indices along a dimension.

    Muxi-optimized: delegates to a 2-stage iterative min/max selection kernel
    instead of the generic single-stage bitonic sort, reducing the compute
    complexity from O(N log^2 N) to O(N k) per reduction axis.
    """
    logger.debug("GEMS_METAX KTHVALUE")

    original_dtype = inp.dtype
    if inp.dtype not in (torch.float32,):
        inp = inp.to(torch.float32)

    ndim = inp.ndim

    if dim < -ndim or dim >= ndim:
        raise IndexError(
            "Dimension out of range (expected to be in range of"
            f" [{-ndim}, {ndim - 1}], but got {dim})"
        )

    if dim < 0:
        dim = dim + ndim

    dim_size = inp.shape[dim]

    if dim_size == 0:
        raise IndexError(
            f"kthvalue(): Expected reduction dim {dim}" " to have non-zero size."
        )

    if k < 1 or k > dim_size:
        raise RuntimeError(
            f"kthvalue(): selected number k out of range" f" for dimension {dim}"
        )

    if inp.numel() == 0:
        out_shape = list(inp.shape)
        if keepdim:
            out_shape[dim] = 1
        else:
            del out_shape[dim]
        return (
            torch.empty(out_shape, dtype=inp.dtype, device=inp.device),
            torch.empty(out_shape, dtype=torch.int64, device=inp.device),
        )

    need_transpose = dim != ndim - 1

    if need_transpose:
        perm = list(range(ndim))
        perm[dim] = ndim - 1
        perm[-1] = dim
        inp = inp.permute(perm).contiguous()

    # Find k smallest via 2-stage iterative selection.
    values, indices = _muxi_topk(inp, k, descending=False)

    # Extract the k-th element (index k-1 in 0-indexed).
    slice_idx = k - 1
    if k == 1:
        values_kth = values
        indices_kth = indices
    else:
        if ndim == 1:
            values_kth = values[slice_idx : slice_idx + 1]
            indices_kth = indices[slice_idx : slice_idx + 1]
        elif ndim == 2:
            values_kth = values[:, slice_idx : slice_idx + 1]
            indices_kth = indices[:, slice_idx : slice_idx + 1]
        else:
            values_kth = values[..., slice_idx : slice_idx + 1]
            indices_kth = indices[..., slice_idx : slice_idx + 1]

    if need_transpose:
        inv_perm = list(range(ndim))
        inv_perm[dim] = ndim - 1
        inv_perm[-1] = dim

        values = values_kth.permute(inv_perm)
        indices = indices_kth.permute(inv_perm)

        if not keepdim:
            values = values.squeeze(dim)
            indices = indices.squeeze(dim)
    else:
        if not keepdim:
            values = values_kth.squeeze(-1)
            indices = indices_kth.squeeze(-1)
        else:
            values = values_kth
            indices = indices_kth

    return values.to(original_dtype), indices
