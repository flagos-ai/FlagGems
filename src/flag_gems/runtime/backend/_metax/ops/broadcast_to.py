import logging

import torch

logger = logging.getLogger(__name__)


def broadcast_to(x, size):
    """Muxi-specific broadcast_to (pure view, zero-copy).

    ``broadcast_to`` is a pure meta/view operation: PyTorch eager
    resolves it with near-zero overhead by adjusting shape/strides
    without copying data.  The generic implementation launches Triton
    kernels that materialize a full O(n) data copy, which is strictly
    more expensive for every shape.

    This specialization constructs a strided view via
    ``torch.as_strided``, matching PyTorch's O(1) metadata-only
    semantics.
    """
    logger.debug("GEMS_METAX BROADCAST_TO")

    if not isinstance(size, (list, tuple, torch.Size)):
        raise TypeError("broadcast_to size must be a list/tuple/torch.Size of ints")

    size = list(size)
    in_shape = list(x.shape)
    in_ndim = len(in_shape)
    out_ndim = len(size)

    if in_ndim > out_ndim:
        raise RuntimeError(
            f"broadcast_to: requested size has fewer dimensions "
            f"({out_ndim}) than input ({in_ndim})"
        )

    # Prepend singleton dims when target has more dims than input
    if out_ndim > in_ndim:
        pad = out_ndim - in_ndim
        in_shape = [1] * pad + in_shape
        x = x.view(in_shape)

    in_strides = list(x.stride())

    # Resolve -1 and validate broadcastability
    out_shape = []
    for d in range(out_ndim):
        req = size[d]
        src = in_shape[d]
        if req == -1:
            target = src
        else:
            target = req
        if src != target and src != 1:
            raise RuntimeError(
                f"The expanded size of the tensor ({target}) must match "
                f"the existing size ({src}) at non-singleton dimension "
                f"{d}. Target sizes must be the same, or -1, or the "
                f"size of dimension in the original tensor must be 1."
            )
        out_shape.append(int(target))

    # Effective strides: 0 for broadcasted (singleton) dims, the source
    # stride otherwise.  ``as_strided`` returns a view, so no data is
    # copied and no kernel is launched.
    strides = [in_strides[d] if in_shape[d] != 1 else 0 for d in range(out_ndim)]

    return torch.as_strided(x, out_shape, strides)
