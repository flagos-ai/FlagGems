        z = x_fp * beta
        # d/dx softplus(x, beta) = sigmoid(beta*x) when z <= threshold
        dydx = tl.where(z > threshold, 1.0, tl.sigmoid(z))
        dx = (grad * dydx).to(x.dtype)

        tl.store(output_ptr + offsets, dx, mask=mask)


