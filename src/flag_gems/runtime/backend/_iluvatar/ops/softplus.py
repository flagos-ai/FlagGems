    num_programs = tl.num_programs(0)

    block_start = pid * BLOCK_SIZE
    num_total_blocks = num_programs * BLOCK_SIZE
    for block_idx in range(0, tl.cdiv(n_elements, num_total_blocks)):
        current_start = block_start + block_idx * num_total_blocks
        offsets = current_start + tl.arange(0, BLOCK_SIZE)
        mask = offsets < n_elements

        x = tl.load(x_ptr + offsets, mask=mask)
        grad = tl.load(grad_output_ptr + offsets, mask=mask)

