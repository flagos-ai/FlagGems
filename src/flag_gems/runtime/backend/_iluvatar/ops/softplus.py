def _softplus_backward_contiguous_kernel(
    grad_output_ptr,
    x_ptr,
    output_ptr,
    n_elements,
    beta,
    threshold,
    BLOCK_SIZE: tl.constexpr,
):
    """Autotuned kernel for contiguous softplus backward pass.

    Uses a grid-stride loop to handle tensors of any size with a
    single launch configuration per tensor size.  This provides
    better memory throughput than block-pointer codegen for
    half-precision types because Triton can merge adjacent loads
    into wider vectorized transactions.
    """
