# ---- Euclidean GCD core (one cheap integer div per iteration) ----


@triton.jit
def _gcd_euclid_i32(x, y):
    """Per-lane Euclid-by-remainder GCD for i16/i32.

    Operates in unsigned to handle INT_MIN safely.  Lanes converge
    independently; the ``tl.sum`` ballot only needs to wait for the
    slowest lane, not rebuild a mask across the full block.

    On Iluvatar hardware a single integer div/rem is much cheaper
    than the multiple ffs (ctz) + where chains of the generic binary
    GCD.
    """
    ax = x.to(tl.uint32)
    ay = y.to(tl.uint32)
    a = ax
    b = ay
    active = b != 0
    while tl.sum(active.to(tl.int32), axis=0) > 0:
        safe_b = tl.where(active, b, 1)
        r = a % safe_b
        a = tl.where(active, b, a)
        b = tl.where(active, r, b)
        active = active & (b != 0)
    return a.to(tl.int32)


