@triton.jit
def _copy_kernel(in_ptr, out_ptr, n, BLOCK_SIZE: tl.constexpr):
    """Flat-memory copy with grid-stride loop."""
    pid = tl.program_id(0)
    num_programs = tl.num_programs(0)
    block_start = pid * BLOCK_SIZE
    num_total = num_programs * BLOCK_SIZE
    for off in range(0, tl.cdiv(n, num_total)):
        idx = block_start + off * num_total + tl.arange(0, BLOCK_SIZE)
        mask = idx < n
        tl.store(out_ptr + idx, tl.load(in_ptr + idx, mask=mask), mask=mask)


