#
# Core optimization: modulo precomputation + stride-skipping.
#
# Instead of evaluating ``(pos + pad - k) % stride == 0`` for every
# element in the BLOCK_H×BLOCK_W tile (O(kernel³ × block_size) modulo
# ops), we precompute ``base = (pos + pad) % stride`` once per position
# and then check ``k % stride == base`` — a scalar comparison.
#
# Additionally, the outer kd-loop skips iterations where
# ``kd % stride_d != base_d``, halving the loop body for stride=2.
# ---------------------------------------------------------------------------


