@triton.jit
def _index_copy_flat_kernel(
    inp_ptr,
    src_ptr,
    index_ptr,
    dim_size,
    L,
    outer,
    BLOCK: tl.constexpr,
):
    # inner == 1 specialization: one output element per (o, i) pair.
    # grid = (cdiv(L, BLOCK), outer).  A small BLOCK (256) wins on this backend
    # by keeping many small blocks in flight for the scattered destination
    # writes.  The index vector is loaded once per block.
    pid0 = tl.program_id(0)
    pid1 = tl.program_id(1)
    i = (pid0 * BLOCK + tl.arange(0, BLOCK)).to(tl.int64)
