    idx = tl.load(index_ptr + i, mask=mask, other=0).to(tl.int64)
    o = pid1
    src_off = o * L + i
    dst_off = o * dim_size + idx
    v = tl.load(src_ptr + src_off, mask=mask)
    tl.store(inp_ptr + dst_off, v, mask=mask)


