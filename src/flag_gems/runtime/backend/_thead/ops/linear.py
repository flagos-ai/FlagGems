def _pick_config(dtype, M, N, K):
    mx = max(M, N)
    if dtype == torch.float32:
        if M * N <= _SMALL_MN:
            # Small fp32 (strict functional tolerance regime): exact IEEE dot.
            return 64, 64, 32, 4, 3, "ieee", False
        if mx <= 512:
            # tf32 dot path.
            return 64, 64, 64, 4, 3, "tf32", False
        # Bigger squares: pre-cast fp32 -> fp16 in a single device kernel and
        # run the fast fp16 dot path (fp16 mantissa == tf32 mantissa, error
        # measured <= tf32 error).
        return 128, 256, 32, 8, 5, "tf32", True
    # fp16 / bf16
    if mx <= 512:
        return 64, 64, 64, 4, 3, "tf32", False
    ns = 3 if mx <= 1024 else 5
    return 128, 256, 32, 8, ns, "tf32", False


