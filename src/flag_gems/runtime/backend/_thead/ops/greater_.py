def _broadcast_shape(sa, sb):
    r = max(len(sa), len(sb))
    pa = (1,) * (r - len(sa)) + tuple(sa)
    pb = (1,) * (r - len(sb)) + tuple(sb)
    out = []
    for x, y in zip(pa, pb):
        if x == y:
            out.append(x)
        elif x == 1:
            out.append(y)
        elif y == 1:
            out.append(x)
        else:
            raise RuntimeError(
                "The size of tensor a ({}) must match the size of tensor b ({}) "
                "at non-singleton dimension".format(sa, sb)
            )
    return tuple(out)


def _cmp_kind(dtype):
    if dtype == torch.float64:
        return 1
    if dtype.is_floating_point:
        return 0
    if dtype in (torch.int64, torch.uint64):
        return 3
    return 2


def _bcast_strides(shape_b, stride_b, shape_out):
    """Right-align ``other`` onto the output shape, 0-stride where it broadcasts."""
    pad = len(shape_out) - len(shape_b)
    sb = (0,) * pad + tuple(stride_b)
    sh = (1,) * pad + tuple(shape_b)
    return tuple(0 if sh[d] == 1 else sb[d] for d in range(len(shape_out)))


def _collapse(shape, sa, sb):
    """Drop size-1 dims and merge neighbouring dims that stay linear for both operands.

    Returns dims ordered innermost (fastest varying) first, matching the kernel's
    row-major peeling order ``c = idx % s; idx //= s``.
    """
    items = [(s, x, y) for s, x, y in zip(shape, sa, sb) if s != 1]
    if not items:
        return [(1, 0, 0)]
    res = [list(items[-1])]
    for d in range(len(items) - 2, -1, -1):
        s, x, y = items[d]
        sn, xn, yn = res[-1]
        if x == xn * sn and y == yn * sn:
            res[-1] = [s * sn, xn, yn]
        else:
            res.append([s, x, y])
    return [tuple(r) for r in res]


def _f64_halves(value):
    bits = struct.unpack("<q", struct.pack("<d", float(value)))[0]
    hi = bits >> 32
    lo = bits & 0xFFFFFFFF
    if lo >= 0x80000000:
        lo -= 0x100000000
    return hi, lo


