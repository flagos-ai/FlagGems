def _launch(a, b, n, kern, blk, warps):
    """Launch ``kern``, reusing its compiled entry point once it is known.

    Triton's JITFunction.run rebinds arguments, recomputes the specialization key
    and re-derives the device and stream on every call, which dominates a
    few-thousand-element kernel. The compiled launcher and its packed metadata are
    cached against everything that key depends on (kernel variant, dtype, element
    count and both 16-byte alignment specializations) and re-invoked directly; on
    any surprise the normal public launch is used.
    """
    g = (n + blk - 1) // blk
    if _FAST[0]:
        try:
            key = (
                kern is _k_flat_eq_big,
                a.dtype,
                n,
                a.data_ptr() & 15 == 0,
                b.data_ptr() & 15 == 0,
            )
            ent = _LC.get(key)
            if ent is None:
                k = kern.warmup(a, b, n, grid=(g,), num_warps=warps)
                ent = (k.run, k.function, k.packed_metadata)
                _LC[key] = ent
            dev = _ACT.get_current_device()
            ent[0](
                g,
                1,
                1,
                _ACT.get_current_stream(dev),
                ent[1],
                ent[2],
                None,
                None,
                None,
                a,
                b,
                n,
            )
            return
        except Exception:
            _FAST[0] = False
    kern[(g,)](a, b, n, num_warps=warps)


def _run_tensor(a, other):
    shape = tuple(a.shape)
    bshape = _broadcast_shape(shape, tuple(other.shape))
    if bshape != shape:
        raise RuntimeError(
            "output with shape {} doesn't match the broadcast shape {}".format(
                list(shape), list(bshape)
            )
        )

    n = a.numel()
    if n == 0:
        return a

    if a.dtype == other.dtype:
        cmp_kind = _cmp_kind(a.dtype)
    else:
        cmp_kind = _cmp_kind(torch.result_type(a, other))
    a_bool = a.dtype == torch.bool
    b_bool = other.dtype == torch.bool
    a_contig = a.is_contiguous()
    b_contig = other.is_contiguous() and tuple(other.shape) == shape
    grid = (triton.cdiv(n, _BLOCK),)

    if a_contig and other.numel() == 1:
        _greater_flat[grid](
            a,
            other,
            n,
            BLOCK=_BLOCK,
            CMP=cmp_kind,
            A_BOOL=a_bool,
            B_BOOL=b_bool,
            B_SCALAR=True,
            num_warps=_NUM_WARPS,
        )
        return a

    if a_contig and b_contig:
        _greater_flat[grid](
            a,
            other,
            n,
            BLOCK=_BLOCK,
            CMP=cmp_kind,
            A_BOOL=a_bool,
            B_BOOL=b_bool,
            B_SCALAR=False,
            num_warps=_NUM_WARPS,
        )
        return a

    _launch_general(
        a,
        other,
        n,
        shape,
        a_contig,
        b_contig,
        cmp_kind,
        a_bool,
        b_bool,
        False,
        False,
        0,
        0,
        0,
    )
    return a


def _run_scalar(a, other):
    n = a.numel()
    if n == 0:
        return a
    cmp_dtype = torch.result_type(a, other)
    cmp_kind = _cmp_kind(cmp_dtype)
    a_bool = a.dtype == torch.bool
    scalar_f64 = cmp_dtype.is_floating_point
    if scalar_f64:
        shi, slo = _f64_halves(other)
        si = 0
    else:
        shi, slo, si = 0, 0, int(other)

    if a.is_contiguous():
        grid = (triton.cdiv(n, _BLOCK),)
        _greater_flat_scalar[grid](
            a,
            n,
            shi,
            slo,
            si,
            BLOCK=_BLOCK,
            CMP=cmp_kind,
            A_BOOL=a_bool,
            SCALAR_F64=scalar_f64,
            num_warps=_NUM_WARPS,
        )
    else:
        _launch_general(
            a,
            None,
            n,
            tuple(a.shape),
            False,
            False,
            cmp_kind,
            a_bool,
            False,
            True,
            scalar_f64,
            shi,
            slo,
            si,
        )
    return a
