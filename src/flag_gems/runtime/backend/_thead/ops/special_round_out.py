import logging

import torch
import triton
import triton.language as tl

logger = logging.getLogger(__name__)


@triton.jit
def _round_half_even(x):
    # Round to nearest integer, ties to even. Uses only floor (no tl.math.round
    # on this backend). For every non-tie, floor(x + 0.5) is the nearest
    # integer. For a tie x == n + 0.5 (n = floor(x)), floor(x + 0.5) == n + 1,
    # which is correct iff n is odd; when n is even the result must be n.
    # A negative input that rounds to zero must yield -0.0 (nearbyint keeps the
    # sign of zero), hence the x * 0.0 fix-up. Works for fp32 and fp64.
    fl = tl.math.floor(x)
    fr = x - fl
    tie = fr == 0.5
    n_half = fl * 0.5
    n_even = n_half == tl.math.floor(n_half)
    # base = nearest integer. Computed as fl + (fr >= 0.5) instead of
    # floor(x + 0.5): the fp32 addition x + 0.5 rounds up to k+1 when x is the
    # largest fp32 below a half-integer that is a power-of-two binade boundary
    # (e.g. x = 0.49999997, x+0.5 = 0.99999997 -> 1.0). fl and fr = x - fl are
    # exact, and fl + 1.0 is exact for |fl| < 2^23 (fp32) / 2^52 (fp64).
    base = fl + tl.where(fr >= 0.5, 1.0, 0.0)
    y = tl.where(tie & n_even, fl, base)
    y = tl.where(y == 0.0, x * 0.0, y)
    return y


