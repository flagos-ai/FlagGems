# Gather-style backward kernel.
#
# The generic implementation scatters every output position into the input
# gradient with ``tl.atomic_add`` accumulated in a float32 staging buffer,
# then casts back to the input dtype in a separate kernel. On the PPU that
# means three launches (zeros + scatter + cast) plus atomic contention, which
# dominates latency on the small feature maps this op sees.
#
# Here we invert the mapping: each program owns one *input* gradient pixel and
# sums the contiguous block of output positions that map to it. For the
# nearest(-exact) forward index ``ih = floor(oh * reciprocal_scale)`` the set
# of ``oh`` mapping to a given ``ih`` is the half-open range
# ``[ceil(ih / reciprocal_scale), ceil((ih + 1) / reciprocal_scale))``. These
# ranges tile ``[0, OH)`` exactly, so the gathered sum is over the identical
# set of gradient values as the scatter — numerics are unchanged. Because no
# lane writes the same address twice, atomics are unnecessary and the sum is
# accumulated in fp32 registers and cast once on store, removing the float32
# buffer and the trailing cast kernel entirely.
