@triton.jit
def _rep_pad2d_flat_kernel(
    in_ptr,
    out_ptr,
    nout,
    W: tl.constexpr,
    H: tl.constexpr,
    OW: tl.constexpr,
    OH: tl.constexpr,
    left: tl.constexpr,
    top: tl.constexpr,
    BLOCK: tl.constexpr,
):
    """Flat gather over the whole output: out[e] = in[rest, ih, iw].

    e is a flat output index; row = e // OW, col = e - row*OW,
    rest = row // OH, oh = row - rest*OH, ih = clamp(oh - top, 0, H-1),
    iw = clamp(col - left, 0, W-1). Geometry is constexpr (magic-number
    division); stores are perfectly contiguous.
    """
    pid = tl.program_id(0)
    e = pid * BLOCK + tl.arange(0, BLOCK)
    m = e < nout

    row = e // OW
    col = e - row * OW
    rest = row // OH
    oh = row - rest * OH
    ih = tl.minimum(tl.maximum(oh - top, 0), H - 1)
    iw = tl.minimum(tl.maximum(col - left, 0), W - 1)

    vals = tl.load(in_ptr + rest * (H * W) + ih * W + iw, mask=m)
    tl.store(out_ptr + e, vals, mask=m)


