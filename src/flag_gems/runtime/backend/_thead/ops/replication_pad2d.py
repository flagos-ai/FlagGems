def _as_padding4(padding):
    if isinstance(padding, (int,)) and not isinstance(padding, bool):
        return (padding, padding, padding, padding)
    if torch.is_tensor(padding):
        pad = padding.detach().cpu().reshape(-1).tolist()
    else:
        pad = list(padding)
    if len(pad) == 1:
        pad = pad * 4
    if len(pad) != 4:
        raise ValueError(
            "replication_pad2d expects 4 padding values (left, right, top, bottom)"
        )
    return (int(pad[0]), int(pad[1]), int(pad[2]), int(pad[3]))


def replication_pad2d(input, padding):
    logger.debug("GEMS_THEAD REPLICATION_PAD2D")
    if not torch.is_tensor(input):
        raise TypeError("input must be a torch.Tensor")
    if input.dim() < 2:
        raise ValueError("input must have at least 2 dims (H, W)")

    l, r, t, b = _as_padding4(padding)
    H = input.shape[-2]
    W = input.shape[-1]
    OH = H + t + b
    OW = W + l + r
    if OH <= 0 or OW <= 0:
        raise ValueError("padding results in non-positive output size")

    out = torch.empty(
        (*input.shape[:-2], OH, OW), dtype=input.dtype, device=input.device
    )
    if out.numel() == 0:
        return out

    if input.numel() >= 2**31 or out.numel() >= 2**31:
        raise NotImplementedError("tensor too large for int32 indexing")

    if not input.is_contiguous():
        input = input.contiguous()

    nout = out.numel()

    # Launch config: 256-element blocks with 2-4 elems/thread on the large
    # workloads (probe-tuned); wide blocks with more warps at the launch
    # floor for tiny tensors.
    esize = input.element_size()
    if nout < 4096:
        bw = 1 << (min(nout, 1024) - 1).bit_length()  # pow2ceil, capped 1024
        if bw < 1:
            bw = 1
        if bw >= 512:
            nw = 8
        elif bw >= 128:
            nw = 4
        else:
            nw = 1
    else:
        bw = 256
        nw = 2 if esize <= 2 else 4

    if nout % bw == 0:
        _rep_pad2d_flat_kernel_notail[(nout // bw,)](
            input,
            out,
            W=W,
            H=H,
            OW=OW,
            OH=OH,
            left=l,
            top=t,
            BLOCK=bw,
            num_warps=nw,
        )
    else:
        _rep_pad2d_flat_kernel[((nout + bw - 1) // bw,)](
            input,
            out,
            nout,
            W=W,
            H=H,
            OW=OW,
            OH=OH,
            left=l,
            top=t,
            BLOCK=bw,
            num_warps=nw,
        )
    return out
