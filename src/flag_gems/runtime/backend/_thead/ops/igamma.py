def _stirling_lgamma(a):
    """ln Gamma(a) via Stirling + Bernoulli terms (accurate for a >= ~4)."""
    inv = 1.0 / a
    inv2 = inv * inv
    poly = inv * (_B1 + inv2 * (_B2 + inv2 * (_B3 + inv2 * _B4)))
    return (a - 0.5) * tl.log(a) - a + _HALF_LOG_2PI + poly


@triton.jit
def _log_pref_small(a, x):
    """log(x^a e^-x / Gamma(a)) via the plain form (safe for a < 4).

    lgamma(a) = lgamma(a+2) - log(a (a+1)); the a+2 Stirling series is accurate
    to ~1e-6 absolute there.
    """
    return a * tl.log(x) - x - (_stirling_lgamma(a + 2.0) - tl.log(a * (a + 1.0)))


@triton.jit
def _log_pref_big(a, x):
    """Cancellation-free form for a >= 4 (Stirling remainder + log1p series)."""
    d = x - a
    u = d / a
    q = d * u  # d^2 / a
    ser = q * (-0.5 + u * (0.3333333333333333 + u * (-0.25 + u * 0.2)))
    big = a * tl.log(x / a) - d
    delta = tl.where(tl.abs(u) <= 0.25, ser, big)

    inv = 1.0 / a
    inv2 = inv * inv
    rem = (
        0.5 * tl.log(a)
        - _HALF_LOG_2PI
        - inv * (_B1 + inv2 * (_B2 + inv2 * (_B3 + inv2 * _B4)))
    )
    return rem + delta


