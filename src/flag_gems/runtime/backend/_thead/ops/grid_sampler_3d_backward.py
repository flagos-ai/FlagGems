@triton.jit
def _reflect_and_deriv(v, min_v, span):
    # PyTorch reflect_coordinates(v, 2*min, 2*(min+span)) and its derivative.
    a = tl.abs(v - min_v)
    fl = tl.floor(a / span)
    extra = a - fl * span
    fli = fl.to(tl.int32)
    even = (fli % 2) == 0
    gx = tl.where(even, extra + min_v, span - extra + min_v)
    d = tl.where(
        extra == 0.0,
        0.0,
        tl.where(even, 1.0, -1.0) * tl.where(v > min_v, 1.0, -1.0),
    )
    return gx, d


@triton.jit
def _nearbyint(v):
    # round-half-to-even
    r = tl.floor(v)
    frac = v - r
    ri = r.to(tl.int32)
    even = (ri % 2) == 0
    res = tl.where(
        frac < 0.5, r, tl.where(frac > 0.5, r + 1.0, tl.where(even, r, r + 1.0))
    )
    return res


