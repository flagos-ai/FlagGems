_COPY_BLOCK = 1024
_NUM_WARPS = 4


def _pick_config(mask_numel, is_fp16):
    # Measured on PPU-ZW810E (triton.testing.do_bench median).  The recurring
    # winner is 1 elem/thread for fp32 (BLOCK=128/warps=2): fp32 8x128 EXACT
    # 2.92us vs 3.44us at 256/w8; fp32 4096 3.24-3.48us.  fp16 prefers
    # BLOCK=256/warps=8 for small/mid and BLOCK=128/warps=8 for large (fp16
    # emulated atomics need more warps in flight).
    if mask_numel <= 1024:
        return (256, 8) if is_fp16 else (128, 2)
    if is_fp16:
        return (128, 8) if mask_numel > 16384 else (256, 8)
    return (128, 8) if mask_numel > 16384 else (128, 2)


