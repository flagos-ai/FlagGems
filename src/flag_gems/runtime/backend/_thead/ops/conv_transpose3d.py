# conv_transpose3d, output-stationary (gather) formulation.
#
#   out[n, co, od, oh, ow] =
#       bias[co] + sum_{ci', kd, kh, kw}
#           x[n, g*Cig + ci', id, ih, iw] * W[g*Cig + ci', co - g*Cog, kd, kh, kw]
#   with id = (od + pd - kd*dil_d) / sd  (only when divisible and in range)
#
# Three device paths, selected from tensor metadata on the host:
#   * _conv_transpose3d_dot_kernel: implicit GEMM, one tl.dot per kernel tap
#     with the contraction over the group-local input channels, dense output
#     mapping. Used for stride 1 with Cig, Cog <= 64.
#   * _conv_transpose3d_dot_row_kernel: same contraction but with a row-aligned
#     output mapping so od/oh are scalars and taps that cannot contribute are
#     skipped. Used for stride > 1 with Cig, Cog <= 64.
#   * _conv_transpose3d_kernel: broadcast-FMA outer product per (tap, channel).
#     Used for fp64 and for channel counts beyond the dot paths.
# fp16/bf16 contract on tensor cores with fp32 accumulation; fp32 contracts
# with input_precision="tf32x3" (3-pass tile-core emulation, measured max
# absolute error ~3e-7 versus float64 for K=128, i.e. fp32 grade).
# ---------------------------------------------------------------------------


