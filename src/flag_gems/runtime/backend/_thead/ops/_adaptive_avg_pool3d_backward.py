def _max_count(in_size, out_size):
    # exact maximum over input positions i of |[floor(i*out/in), ceil((i+1)*out/in)-1]|
    if in_size == out_size:
        return 1
    g = gcd(in_size, out_size)
    p = out_size // g
    q = in_size // g
    return (p + 2 * q - 2) // q


