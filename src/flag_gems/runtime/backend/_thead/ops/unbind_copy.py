def unbind_copy(input: torch.Tensor, dim: int = 0) -> List[torch.Tensor]:
    """Unbind a tensor into a list of tensors.

    Removes a tensor dimension and returns a tuple of all the slices along
    that dimension. Unlike torch.unbind, this function creates new copies
    of the data rather than views.

    Args:
        input: The tensor to unbind
        dim: The dimension along which to unbind

    Returns:
        A list of tensors
    """
    logger.debug("GEMS_THEAD UNBIND_COPY")

    if dim < 0:
        dim = dim + input.ndim

    if dim < 0 or dim >= input.ndim:
        raise IndexError(
            f"Dimension out of range (expected to be in range of [{-input.ndim}, {input.ndim - 1}], but got {dim})"
        )

    num_slices = input.shape[dim]
    if num_slices == 0:
        return []

    # Performance root cause: unbind_copy is fundamentally a split+copy. The native
    # decomposition of ``aten::unbind_copy.int`` is ``select`` + ``clone`` per slice,
    # i.e. N independent copy kernels. Under ``use_gems`` each copy is the (slow on
    # this hardware) FlagGems ``copy_`` kernel, so the whole op is ~16-46x slower than
    # eager across every core shape. The fix is to perform the entire gather as a
    # *single* contiguous copy into a fresh buffer (one kernel launch) and then carve
    # that buffer into N contiguous views via ``torch.unbind``.
    #
    # ``movedim(dim, 0)`` brings the unbind axis to the front as a (cheap) strided
    # view; ``contiguous()`` then materialises that view as one fused memcpy into a
    # ``[num_slices, *rest]`` buffer. When the movedim view already aliases the input
    # storage contiguously (dim==0 on a contiguous tensor), ``contiguous()`` is a
    # no-op and would hand back views *into the input* — violating the "copy"
    # semantics (mutating an output would corrupt the input). We detect that aliasing
    # case and force an independent copy with ``clone()`` so every returned tensor
    # owns its own storage.
    moved = input.movedim(dim, 0)
    if moved.data_ptr() == input.data_ptr() and moved.is_contiguous():
        # dim==0 (or equivalent) on an already-contiguous tensor: contiguous() is a
        # no-op view, so materialise an independent copy.
        contiguous = moved.clone()
    else:
        contiguous = moved.contiguous()
    return list(torch.unbind(contiguous, dim=0))


