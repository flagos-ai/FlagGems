    tiles_per_channel = n_tiles * tl.cdiv(batch_dim, BLOCK_M)
    feat_pid = pid // tiles_per_channel
    tile_off = pid % tiles_per_channel
    m_idx = tile_off // n_tiles
    n_idx = tile_off % n_tiles

    mean = tl.load(feat_pid + mean_pointer).to(tl.float32)
    var = tl.load(feat_pid + var_pointer).to(tl.float32)
    inv_std = tl_extra_shim.rsqrt(var + eps)

    batch_offset = m_idx * BLOCK_M + tl.arange(0, BLOCK_M)
    batch_mask = batch_offset < batch_dim

    spatial_offset = n_idx * BLOCK_N + tl.arange(0, BLOCK_N)
    spatial_mask = spatial_offset < spatial_dim

    curr_grad_output_pointer = (
        grad_output_pointer
        + grad_output_feat_stride * feat_pid
        + grad_output_batch_stride * batch_offset[:, None]
        + grad_output_spatial_stride * spatial_offset[None, :]
    )
    curr_input_pointer = (
        input_pointer
        + input_feat_stride * feat_pid
        + input_batch_stride * batch_offset[:, None]
        + input_spatial_stride * spatial_offset[None, :]
    )

    mask = batch_mask[:, None] & spatial_mask[None, :]
    curr_input = tl.load(curr_input_pointer, mask=mask, other=0.0).to(tl.float32)
    curr_norm = (curr_input - mean) * inv_std
    curr_grad_output = tl.load(curr_grad_output_pointer, mask=mask, other=0.0).to(
        tl.float32
    )

    term1_scalar = tl.sum(curr_norm * curr_grad_output)
    term2_scalar = tl.sum(curr_grad_output)

    store_idx = pid
    tl.store(store_idx + partial_term1_pointer, term1_scalar)
    tl.store(store_idx + partial_term2_pointer, term2_scalar)


