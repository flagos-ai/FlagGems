# Per-channel element count beyond which the multi-tile two-kernel
# approach is used.  Below this the generic layer's autotuned kernel
# is already well-tuned.
_MULTI_TILE_THRESHOLD = 500_000


def make_3d_for_bn(input: Tensor) -> Tensor:
    """
    Converts the input to a 3D view for batch normalization.

    Args:
        input: Input to render 3D.

    Returns:
        Input's 3D view.
    """
    if input.ndim == 2:
        input = input.unsqueeze(-1)

    elif input.ndim >= 4:
        input = input.flatten(2, -1)

    return input


