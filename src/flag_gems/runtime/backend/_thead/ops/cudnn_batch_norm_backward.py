def _multi_tile_config(batch_dim, spatial_dim):
    """Tile shape for the per-tile kernels."""
    BLOCK_M = min(32, triton.next_power_of_2(batch_dim))
    BLOCK_N = min(64, triton.next_power_of_2(spatial_dim))
    m_tiles = triton.cdiv(batch_dim, BLOCK_M)
    n_tiles = triton.cdiv(spatial_dim, BLOCK_N)
    return BLOCK_M, BLOCK_N, m_tiles, n_tiles


@triton.jit
def partial_reduce_kernel(
    grad_output_pointer,
    input_pointer,
    mean_pointer,
    var_pointer,
    partial_term1_pointer,
    partial_term2_pointer,
    batch_dim,
    spatial_dim,
    grad_output_batch_stride,
    grad_output_feat_stride,
    grad_output_spatial_stride,
    input_batch_stride,
    input_feat_stride,
    input_spatial_stride,
    eps,
    n_tiles: tl.constexpr,
    BLOCK_M: tl.constexpr,
    BLOCK_N: tl.constexpr,
):
    """Compute per-tile term1 and term2 partial sums.

    Grid: (feat_dim * m_tiles * n_tiles,).
    """
