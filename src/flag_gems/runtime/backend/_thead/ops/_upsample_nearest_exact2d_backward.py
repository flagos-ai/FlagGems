@triton.jit
def _recon64(hi, lo):
    # Reconstruct an exact float64 scalar from its two int32 halves.  Scalar
    # fp64 kernel args (Python floats or np.float64) are demoted to fp32 by
    # the Triton binder on this PPU backend, which corrupts the boundary-exact
    # index math (e.g. r=0.64: floor((12.5)*r) flips from 8 to 7).  Passing
    # the raw IEEE-754 bits as two int32 args and bitcasting in-kernel keeps
    # the full 53-bit mantissa.
    bits = ((hi.to(tl.int64) & 0xFFFFFFFF) << 32) | (lo.to(tl.int64) & 0xFFFFFFFF)
    return bits.to(tl.float64, bitcast=True)


@triton.jit
def _dlo_scale(k, out, r):
    # Smallest d in [0, out-1] with floor((d+0.5)*r) >= k, or `out` if none.
    # r is the fp64 scale ratio; matches the reference's fp64 index math.
    c0 = tl.ceil(k.to(tl.float64) / r - 0.5)
    c = c0.to(tl.int64)
    c = tl.minimum(tl.maximum(c, 0), out)
    s = tl.floor((c.to(tl.float64) + 0.5) * r).to(tl.int64)
    c = tl.minimum(tl.where(s < k, c + 1, c), out)
    s = tl.floor((c.to(tl.float64) + 0.5) * r).to(tl.int64)
    c = tl.minimum(tl.where(s < k, c + 1, c), out)
    s = tl.floor((c.to(tl.float64) - 0.5) * r).to(tl.int64)
    c = tl.where((c > 0) & (s >= k), c - 1, c)
    return c


