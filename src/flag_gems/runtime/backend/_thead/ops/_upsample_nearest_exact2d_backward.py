def _dlo_int(k, out, inp):
    # Smallest d in [0, out-1] with floor((2d+1)*inp / (2*out)) >= k,
    # or `out` (sentinel) if none. Exact integer math (matches fp64 reference).
    return ((2 * k * out + inp - 1) // inp) // 2


