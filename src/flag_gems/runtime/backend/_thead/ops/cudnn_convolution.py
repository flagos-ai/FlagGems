def _conv_out_size(in_size, kernel_size, stride, padding, dilation):
    return (in_size + 2 * padding - dilation * (kernel_size - 1) - 1) // stride + 1


# tl.dot needs K >= 16. The K dim of the conv im2col matmul is BLOCK_CI tiling
# over weight_c, so when weight_c * kH * kW < 16 the channel dim must be padded
# (same trick as the generic layer).
_MIN_DOT_K = 16


def _pad_for_dot(input, weight, groups, weight_c, kh, kw):
    add = math.ceil(_MIN_DOT_K / (kh * kw)) - weight_c
    if add <= 0:
        return input, weight, weight_c
    pad_dims = (0, 0) * (input.ndim - 2) + (0, add)
    if groups == 1:
        input = torch.nn.functional.pad(input, pad_dims)
    else:
        # Pad each group's channels independently: (N, G*C, ...) ->
        # (N, G, C, ...) -> pad C -> (N, G*(C+add), ...).
        n = input.shape[0]
        rest = input.shape[2:]
        input = input.reshape(n, groups, weight_c, *rest)
        input = torch.nn.functional.pad(input, pad_dims)
        input = input.reshape(n, groups * (weight_c + add), *rest)
    weight = torch.nn.functional.pad(weight, pad_dims)
    return input, weight, weight_c + add


