# Batch-size ceiling for the gram+eigvalsh fast path. The PPU vendor solver
# aborts the whole process on batched syevBatched (cusolverDnXsyevBatched is
# not supported), so batched inputs are solved with a small per-matrix
# eigvalsh loop. Each vendor eigvalsh call carries a fixed launch cost
# (~0.5-1 ms), which exceeds the generic one-kernel Jacobi for tiny batched
# matrices; only batches of sufficiently large matrices take the loop.
_EIGVALSH_MIN_BATCH_K = 128


def _gram_eigvalsh_svdvals(a: torch.Tensor) -> torch.Tensor:
    """Singular values from the eigenvalues of the Gram matrix A^T A (or A A^T).

    The Gram matrix is formed on the min(m, n) side so it is k x k, then the
    vendor's eigvalsh solver computes its eigenvalues; singular values are
    sqrt of the (clamped, non-negative) eigenvalues in descending order.
    """
    m, n = a.shape[-2], a.shape[-1]
    if m >= n:
        gram = a.transpose(-1, -2) @ a
    else:
        gram = a @ a.transpose(-1, -2)
    if gram.dim() > 2:
        # Batched syev is unsupported by the vendor solver; loop per matrix.
        eigvals = torch.stack(
            [torch.linalg.eigvalsh(gram[i]) for i in range(gram.shape[0])]
        )
    else:
        eigvals = torch.linalg.eigvalsh(gram)
    return eigvals.flip(-1).clamp_min(0.0).sqrt()


