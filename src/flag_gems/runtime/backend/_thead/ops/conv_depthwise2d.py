    # (groups == in_channels) means output channel oc reads only input channel
    # ic = oc // MULT and weight row oc; no channel reduction / im2col matmul.
    pid = tl.program_id(0)
    offs = pid * BLOCK + tl.arange(0, BLOCK)
    total = N * OC * OH * OW
    mask = offs < total

    ow = offs % OW
    tmp = offs // OW
    oh = tmp % OH
    tmp = tmp // OH
    oc = tmp % OC
    n = tmp // OC
    ic = oc // MULT

    # Base pointers into the per-element input channel and output element.
