    if isinstance(padding, (list, tuple)):
        pad_h, pad_w = padding[0], padding[1]
    else:
        pad_h = pad_w = padding
    if isinstance(dilation, (list, tuple)):
        dil_h, dil_w = dilation[0], dilation[1]
    else:
        dil_h = dil_w = dilation

    N, C, IH, IW = input.shape
    out_c, _, KH, KW = weight.shape
    assert (
        out_c % C == 0
    ), f"depthwise out-channels {out_c} must be a multiple of in-channels {C}"
    mult = out_c // C

    OH = _conv_out_size(IH, KH, stride_h, pad_h, dil_h)
    OW = _conv_out_size(IW, KW, stride_w, pad_w, dil_w)

