        ih = oh * sH - pH + kh * dH
        ih_valid = (ih >= 0) & (ih < H)
        for kw in tl.static_range(K_W):
            iw = ow * sW - pW + kw * dW
            iw_valid = (iw >= 0) & (iw < W)
            valid = n_mask & ih_valid & iw_valid
