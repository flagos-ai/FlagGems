    OW = (W + 2 * pW - dW * (kW - 1) - 1) // sW + 1
    mult = OC // C

    out = torch.empty((N, OC, OH, OW), device=input.device, dtype=input.dtype)

    # v4-shaped CTAs (num_warps=2 -> 4 contiguous elements/thread) only help
    # when taps vectorize (stride 1) and there is enough work per launch;
    # strided and small workloads prefer num_warps=4.
    if sH == 1 and sW == 1:
        if N * OH * OW >= 10_000:
            BLOCK_N = 256
            num_warps = 2
        else:
            BLOCK_N = 256
            num_warps = 4
    else:
        # stride > 1: strided taps cannot vectorize, but a 512-wide block at
        # 4 elems/thread amortizes index math and halves CTA count (measured
        # 1.44x faster than 256/4 on the worst stride-2 fp32 workload).
        BLOCK_N = 512
        num_warps = 4

    grid = (triton.cdiv(N * OH * OW, BLOCK_N), mult, C)

    b_ptr = input if bias is None else bias
    ws = weight.stride()
