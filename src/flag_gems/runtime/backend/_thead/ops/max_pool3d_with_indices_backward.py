def _pow2_ceil(v):
    return 1 << max(0, (v - 1).bit_length())


def _pick_config(in_h, in_w):
    bh = min(32, _pow2_ceil(in_h))
    bw = min(64, _pow2_ceil(in_w))
    tile = bh * bw
    if tile >= 1024:
        num_warps = 8
    elif tile >= 256:
        num_warps = 4
    elif tile >= 64:
        num_warps = 2
    else:
        num_warps = 1
    return bh, bw, num_warps


