def _scatter_kernel(
    grad_out_ptr,
    indices_ptr,
    grad_in_ptr,
    ow_total,
    is_total,
    BLOCK: tl.constexpr,
):
    pid_x = tl.program_id(0)
    pid_y = tl.program_id(1).to(tl.int64)
    k = pid_x * BLOCK + tl.arange(0, BLOCK)
    mask = k < ow_total
    base_out = pid_y * ow_total
    base_in = pid_y * is_total
    idx = tl.load(indices_ptr + base_out + k, mask=mask, other=-1)
    val = tl.load(grad_out_ptr + base_out + k, mask=mask, other=0.0)
    loc = base_in + idx
    wmask = mask & (idx >= 0)
    tl.atomic_add(grad_in_ptr + loc, val, mask=wmask, sem="relaxed", scope="gpu")


