@triton.jit
def _f16_reconstruct(b16):
    # Rebuild the fp32 value of an fp16 bit pattern by hand (exact for all
    # inputs including subnormals, inf, nan). The backend's fp16->fp32
    # conversion instruction flushes subnormal lanes to zero in mixed vectors,
    # which would turn lgamma(tiny) into lgamma(0) = +inf.
    b = b16.to(tl.int32)
    exp = (b >> 10) & 0x1F
    mant = b & 0x3FF
    sign = (b >> 15) & 0x1
    e32 = tl.where(exp == 31, 255, exp + 112)
    b32 = (sign << 31) | (e32 << 23) | (mant << 13)
    normal_val = b32.to(tl.float32, bitcast=True)
    denorm_val = mant.to(tl.float32) * 5.960464477539063e-08
    denorm_val = tl.where(sign == 1, -denorm_val, denorm_val)
    return tl.where(exp > 0, normal_val, denorm_val)


