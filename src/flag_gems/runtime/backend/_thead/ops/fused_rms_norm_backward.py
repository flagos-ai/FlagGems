        if CONTIG:
            xoff = rows[:, None] * N + cols[None, :]
            goff = xoff
        else:
            xoff = rows[:, None] * srx + cols[None, :] * scx
            goff = rows[:, None] * sgr + cols[None, :] * sgc
        rr = tl.load(R + rows, mask=rm, other=0.0).to(tl.float32)
        x = tl.load(X + xoff, mask=m2, other=0.0).to(tl.float32)
        dy = tl.load(G + goff, mask=m2, other=0.0).to(tl.float32)
        xhat = x * rr[:, None]
        if NEED_DW:
            acc += xhat * dy
        if NEED_DX:
            if HAS_W:
                gw = dy * w[None, :]
            else:
                gw = dy
            dot = tl.load(DOT + rows, mask=rm, other=0.0).to(tl.float32)
            dx = (gw - (xhat / N) * dot[:, None]) * rr[:, None]
