    for start in range(0, N, BLOCK_N):
        cols = start + tl.arange(0, BLOCK_N)
        cm = cols < N
        if CONTIG:
            xoff = cols
            goff = cols
        else:
            xoff = cols * scx
            goff = cols * sgc
        x = tl.load(xp + xoff, mask=cm, other=0.0).to(tl.float32)
        g = tl.load(gp + goff, mask=cm, other=0.0).to(tl.float32)
