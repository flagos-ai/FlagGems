logger = logging.getLogger(__name__)

_TILE_MAX = 8192  # max BLOCK_M * BLOCK_N for the single-pass fused kernel
_FULL_N_MAX = 2048  # largest N that fits one register-resident row tile
_SM = 64  # PPU-ZW810E multiprocessor count
_GROUPS_TARGET = 4 * _SM  # row groups to aim for in the bandwidth-bound regime
_SMALL_E = 1 << 21  # element count below which latency, not traffic, limits


@triton.jit
def _fused_rows_kernel(
    X,
    G,
    W,
    R,
    DX,
    DW,
    M,
    N,
    srx,
    scx,
    sgr,
    sgc,
    sdx,
    sdc,
    NEED_DX: tl.constexpr,
    NEED_DW: tl.constexpr,
    HAS_W: tl.constexpr,
    DIRECT: tl.constexpr,
    CONTIG: tl.constexpr,
    BLOCK_M: tl.constexpr,
    BLOCK_N: tl.constexpr,
):
    """One pass over a whole (BLOCK_M, N) row tile: dx, dw partial (or direct)."""
    pid = tl.program_id(0)
    rows = pid * BLOCK_M + tl.arange(0, BLOCK_M)
    rm = rows < M
    cols = tl.arange(0, BLOCK_N)
    cm = cols < N
    m2 = rm[:, None] & cm[None, :]

    if CONTIG:
        xoff = rows[:, None] * N + cols[None, :]
        goff = xoff
    else:
        xoff = rows[:, None] * srx + cols[None, :] * scx
        goff = rows[:, None] * sgr + cols[None, :] * sgc

    rr = tl.load(R + rows, mask=rm, other=0.0).to(tl.float32)
    x = tl.load(X + xoff, mask=m2, other=0.0).to(tl.float32)
    dy = tl.load(G + goff, mask=m2, other=0.0).to(tl.float32)
    if HAS_W:
        w = tl.load(W + cols, mask=cm, other=0.0).to(tl.float32)
        gw = dy * w[None, :]
    else:
        gw = dy

    xhat = x * rr[:, None]
    dot = tl.sum(xhat * gw, axis=1)

    if NEED_DX:
        dx = (gw - (xhat / N) * dot[:, None]) * rr[:, None]
        if CONTIG:
            doff = xoff
        else:
            doff = rows[:, None] * sdx + cols[None, :] * sdc
        tl.store(DX + doff, dx.to(DX.dtype.element_ty), mask=m2)
    if NEED_DW:
        dwp = tl.sum(xhat * dy, axis=0)
        if DIRECT:
            tl.store(DW + cols, dwp.to(DW.dtype.element_ty), mask=cm)
        else:
            tl.store(DW + pid * N + cols, dwp, mask=cm)


