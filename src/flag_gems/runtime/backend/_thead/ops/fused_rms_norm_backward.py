def _cdiv(a, b):
    return -(-a // b)


def _warps(tile):
    if tile <= 64:
        return 1
    if tile <= 512:
        return 2
    if tile <= 2048:
        return 4
    return 8


def _fused_rms_norm_backward(
    grad_out, input, normalized_shape, rstd, weight=None, output_mask=(True, True)
):
    logger.debug("GEMS_THEAD FUSED_RMS_NORM_BACKWARD")

    if len(output_mask) != 2:
        raise ValueError("output_mask must contain two booleans")
    need_dx = bool(output_mask[0])
    need_dw = bool(output_mask[1])
    if need_dw and weight is None:
        raise RuntimeError("weight gradient requested without a weight tensor")

    nshape = [int(s) for s in normalized_shape]
    rank = len(nshape)
    N = 1
    for s in nshape:
        N *= s

    nd = input.ndim
    dim = nd - rank
    M = (input.numel() // N) if N else 0

    if dim > 0:
        srx = input.stride(dim - 1)
        sgr = grad_out.stride(dim - 1)
    else:
        srx = 0
        sgr = 0
    scx = input.stride(nd - 1) if rank > 0 else 1
    sgc = grad_out.stride(nd - 1) if rank > 0 else 1

    dx = torch.empty_like(input) if need_dx else None
    dw = (
        torch.empty(tuple(nshape), dtype=input.dtype, device=input.device)
        if need_dw
        else None
    )

    E = M * N
    if E == 0:
        return dx, dw

    # Flat row-major addressing (row*N + col) is valid when every row-major
    # tensor is contiguous; this lets the kernels emit vectorized loads.
    contig = input.is_contiguous() and grad_out.is_contiguous()
    if need_dx and not dx.is_contiguous():
        contig = False
    if dim > 0 and srx != N:
        contig = False
    if dim > 0 and sgr != N:
        contig = False

    sdx = dx.stride(dim - 1) if (need_dx and dim > 0) else 0
    sdc = dx.stride(nd - 1) if (need_dx and rank > 0) else 1

    xp = input
    gp = grad_out
    wp = weight if weight is not None else input
    has_w = weight is not None

    # ------------------------------------------------ short rows: single pass
    if N <= _FULL_N_MAX:
        block_n = triton.next_power_of_2(N)
        tile_cap = max(1, _TILE_MAX // block_n)
        if E <= 4096:
            # One launch already wins here: the tile chain is short.
            block_m = min(triton.next_power_of_2(M), tile_cap, 64)
        elif E <= _SMALL_E:
            # Latency-bound regime: exactly one row per program maximizes the
            # resident block count (M programs) and minimizes the tile, which is
            # the configuration that hides the per-row load/reduce latency.
            block_m = 1
        else:
            # Bandwidth-bound regime: fewer, larger row groups keep the fp32
            # dw partial buffer small relative to the streamed data.
            block_m = max(1, min(_cdiv(M, _GROUPS_TARGET), tile_cap, 64))
        groups = _cdiv(M, block_m)
        direct = groups == 1
        if need_dw and not direct:
            part = torch.empty((groups, N), dtype=torch.float32, device=input.device)
            dwp = part
        else:
            dwp = dw if need_dw else input
        _fused_rows_kernel[(groups,)](
            xp,
            gp,
            wp,
            rstd,
            dx if need_dx else input,
            dwp,
            M,
            N,
            srx,
            scx,
            sgr,
            sgc,
            sdx,
            sdc,
            NEED_DX=need_dx,
            NEED_DW=need_dw,
            HAS_W=has_w,
            DIRECT=direct,
            CONTIG=contig,
            BLOCK_M=block_m,
            BLOCK_N=block_n,
            num_warps=_warps(block_m * block_n),
        )
        if need_dw and not direct:
            # Consume all partial rows with one register accumulator and expose
            # as many column blocks as the tile budget allows: this pass is a
            # pure streaming sum and must not serialize over row chunks.
            blk_s = min(triton.next_power_of_2(groups), 512)
            blk_n = max(16, min(triton.next_power_of_2(N), _TILE_MAX // blk_s))
            _dw_reduce_kernel[(_cdiv(N, blk_n),)](
                part,
                dw,
                N,
                groups,
                BLOCK_S=blk_s,
                BLOCK_N=blk_n,
                num_warps=_warps(blk_s * blk_n),
            )
        return dx, dw

    # ------------------------------------------------------ long rows: tiled
    if need_dx and not need_dw:
        _dx_loop_kernel[(M,)](
            xp,
            gp,
            wp,
            rstd,
            dx,
            N,
            srx,
            scx,
            sgr,
            sgc,
            sdx,
            sdc,
            HAS_W=has_w,
            CONTIG=contig,
            BLOCK_N=2048,
            num_warps=8,
        )
        return dx, dw

    if need_dx and need_dw:
        dot = torch.empty((M,), dtype=torch.float32, device=input.device)
        _dot_rows_kernel[(M,)](
            xp,
            gp,
            wp,
            rstd,
            dot,
            N,
            srx,
            scx,
            sgr,
            sgc,
            HAS_W=has_w,
            CONTIG=contig,
            BLOCK_N=1024,
            num_warps=8,
        )
    else:
        dot = input

    block_n = 512
    nb = _cdiv(N, block_n)
    block_r = 4
    max_s = max(1, _cdiv(M, block_r))
    # The column-strip pass streams both inputs plus the dx store.  With only
    # two blocks per SM the per-block memory parallelism cannot keep the pipe
    # busy (the per-row dot pass reaches full occupancy at the same data),
    # so aim for several blocks per SM; the extra dw partial rows cost O(S*N)
    # and stay negligible next to the streamed data.
    S = max(1, min(_cdiv(8 * _SM, nb), max_s))
    chunk = _cdiv(M, S)
    direct = S == 1
    if need_dw and not direct:
        part = torch.empty((S, N), dtype=torch.float32, device=input.device)
        dwp = part
    else:
        dwp = dw if need_dw else input
    _dx_dw_tiled_kernel[(nb, S)](
        xp,
        gp,
        wp,
        rstd,
        dot,
        dx if need_dx else input,
        dwp,
        M,
        N,
        srx,
        scx,
        sgr,
        sgc,
        sdx,
        sdc,
        chunk,
        NEED_DX=need_dx,
        NEED_DW=need_dw,
        HAS_W=has_w,
        DIRECT=direct,
        CONTIG=contig,
        BLOCK_R=block_r,
        BLOCK_N=block_n,
        num_warps=4,
    )
    if need_dw and not direct:
        blk_n = min(triton.next_power_of_2(N), 256)
        _dw_reduce_kernel[(_cdiv(N, blk_n),)](
            part,
            dw,
            N,
            S,
            BLOCK_S=16,
            BLOCK_N=blk_n,
            num_warps=4,
        )
    return dx, dw
