# Triton implementation of aten::conv_tbc_backward.
#
# conv_tbc(input=(T, N, C), weight=(K, C, O), bias=(O), pad) computes
#     out[t, n, o] = bias[o] + sum_k sum_c input[t - pad + k, n, c] * weight[k, c, o]
# with output length Tout = T + 2*pad - K + 1.
#
# Backward (dO = grad_output, shape (Tout, N, O)):
#     grad_bias[o]            = sum_{t,n} dO[t, n, o]
#     grad_weight[k, c, o]    = sum_{t,n} input[t-pad+k, n, c] * dO[t, n, o]
#     grad_input[s, n, c]     = sum_k sum_o dO[s+pad-k, n, o] * weight[k, c, o]
#
# Flattening m = t*N + n makes the time shift a pure row shift of (k-pad)*N and
# the validity test 0 <= row < T*N, because n always stays inside [0, N).


@triton.jit
def _dw_db_kernel(
    DO,
    X,
    DW,
    DB,
    M,
    TOT,
    T,
    N,
    C,
    O,
    pad,
    sOt,
    sOn,
    sOo,
    sXt,
    sXn,
    sXc,
    sDWk,
    sDWc,
    sDWo,
    BLOCK_M: tl.constexpr,
    BLOCK_C: tl.constexpr,
    BLOCK_O: tl.constexpr,
    FAST: tl.constexpr,
    TF32X3: tl.constexpr,
):
    """grad_weight[k, c, o] and grad_bias[o]."""
    pid = tl.program_id(0)
    no = tl.cdiv(O, BLOCK_O)
    nc = tl.cdiv(C, BLOCK_C)
    k = pid // (nc * no)
    rem = pid - k * (nc * no)
    ci = rem // no
    oi = rem - ci * no

    offs_c = ci * BLOCK_C + tl.arange(0, BLOCK_C)
    offs_o = oi * BLOCK_O + tl.arange(0, BLOCK_O)
    mask_c = offs_c < C
    mask_o = offs_o < O

    acc = tl.zeros((BLOCK_C, BLOCK_O), dtype=tl.float32)
    db = tl.zeros((BLOCK_O,), dtype=tl.float32)
    take_bias = (k == 0) & (ci == 0)

    shift = (k - pad) * N
    for m0 in range(0, TOT, BLOCK_M):
        ms = m0 + tl.arange(0, BLOCK_M)
        rows = ms + shift
        valid_in = (rows >= 0) & (rows < T * N)
        valid_do = ms < TOT
        if FAST:
            xp = X + rows[:, None] * sXn + offs_c[None, :] * sXc
            dop = DO + ms[:, None] * sOn + offs_o[None, :] * sOo
        else:
            trow = rows // N
            nrow = rows - trow * N
            xp = X + trow[:, None] * sXt + nrow[:, None] * sXn + offs_c[None, :] * sXc
            tdo = ms // N
            ndo = ms - tdo * N
            dop = DO + tdo[:, None] * sOt + ndo[:, None] * sOn + offs_o[None, :] * sOo
        x = tl.load(xp, mask=valid_in[:, None] & mask_c[None, :], other=0.0)
        do = tl.load(dop, mask=valid_do[:, None] & mask_o[None, :], other=0.0)
        if TF32X3:
            acc += tl.dot(tl.trans(x), do, input_precision="tf32x3")
        else:
            acc += tl.dot(tl.trans(x), do, allow_tf32=False)
        if take_bias:
            db += tl.sum(do.to(tl.float32), 0)

    dwp = DW + k * sDWk + offs_c[:, None] * sDWc + offs_o[None, :] * sDWo
    tl.store(
        dwp,
        acc.to(DW.dtype.element_ty),
        mask=mask_c[:, None] & mask_o[None, :],
    )
    if take_bias:
        tl.store(DB + offs_o, db.to(DB.dtype.element_ty), mask=mask_o)


