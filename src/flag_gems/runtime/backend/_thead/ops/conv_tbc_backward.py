            w = tl.load(
                wb + offs_c[:, None] * sWc + offs_o[None, :] * sWo,
                mask=mask_c[:, None] & mask_o[None, :],
                other=0.0,
            )
            if TF32X3:
                acc += tl.dot(do, tl.trans(w), input_precision="tf32x3")
            else:
                acc += tl.dot(do, tl.trans(w), allow_tf32=False)

