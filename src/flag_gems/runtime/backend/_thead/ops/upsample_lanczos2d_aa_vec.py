    pid_h = tl.program_id(1)
    pid_p = tl.program_id(2)

    oy = pid_h * BLOCK_H + tl.arange(0, BLOCK_H)
    ox = pid_w * BLOCK_W + tl.arange(0, BLOCK_W)
    ox_safe = tl.minimum(ox, W2 - 1)
    oy_safe = tl.minimum(oy, H2 - 1)

    half = tl.full((), 0.5, DT)
    sc_h = tl.full((), SCALE_H, DT)
    sc_w = tl.full((), SCALE_W, DT)
    supp_h = tl.full((), SUPP_H, DT)
    supp_w = tl.full((), SUPP_W, DT)
    one = tl.full((), 1.0, DT)

    cy = sc_h * (oy.to(DT) + half)
    cx = sc_w * (ox.to(DT) + half)
    i0y = tl.maximum((cy - supp_h + half).to(tl.int32), 0)
    i0x = tl.maximum((cx - supp_w + half).to(tl.int32), 0)

    ka = tl.arange(0, KP_H)
    kb = tl.arange(0, KP_W)
    wy_t = tl.load(WT + WOFF + ka[None, :] * H2 + oy_safe[:, None])
    wx_t = tl.load(WT + kb[None, :] * W2 + ox_safe[:, None])
    sy = tl.sum(wy_t, axis=1)
    sx = tl.sum(wx_t, axis=1)
    sy = tl.where(sy != 0.0, sy, one)
    sx = tl.where(sx != 0.0, sx, one)
    wy_t = wy_t / sy[:, None]
    wx_t = wx_t / sx[:, None]

    iy_off = i0y[:, None] + ka[None, :]
    ix = tl.minimum(i0x[:, None] + kb[None, :], W1 - 1) * sW

    n_idx = pid_p // C
    c_idx = pid_p - n_idx * C
    base = n_idx * sN + c_idx * sC

    r_lo = tl.min(i0y)
    acc = tl.zeros((BLOCK_H, BLOCK_W), DT)
    for i in tl.range(0, N_ROWS):
        rr = r_lo + i
        r_use = tl.minimum(rr, H1 - 1)
        v = tl.load(X + (base + r_use * sH) + ix)
        hrow = tl.sum(v * wx_t, axis=1)
        coef = tl.sum(tl.where(iy_off == rr, wy_t, 0.0), axis=1)
        acc += coef[:, None] * hrow[None, :]

    offs = pid_p * (H2 * W2) + oy[:, None] * W2 + ox[None, :]
    mask = (oy[:, None] < H2) & (ox[None, :] < W2)
    tl.store(OUT + offs, acc, mask=mask)


