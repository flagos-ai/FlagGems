    cy = sc_h * (oy.to(DT) + half)
    cx = sc_w * (ox.to(DT) + half)
    i0y = tl.maximum((cy - supp_h + half).to(tl.int32), 0)
    i0x = tl.maximum((cx - supp_w + half).to(tl.int32), 0)
    ny = tl.minimum((cy + supp_h + half).to(tl.int32), H1) - i0y
    nx = tl.minimum((cx + supp_w + half).to(tl.int32), W1) - i0x

    ka = tl.arange(0, KP_H)
    kb = tl.arange(0, KP_W)
    d_y = (i0y[:, None].to(DT) + ka[None, :].to(DT) - cy[:, None] + half) * inv_h
    d_x = (i0x[:, None].to(DT) + kb[None, :].to(DT) - cx[:, None] + half) * inv_w
