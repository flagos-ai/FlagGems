def _lanczos_rowreuse1d_kernel(
    X,
    WT,
    OUT,
    C,
    H1,
    W1,
    H2,
    W2,
    WOFF,
    sN,
    sC,
    sH,
    sW,
    SCALE_H: tl.constexpr,
    SCALE_W: tl.constexpr,
    SUPP_H: tl.constexpr,
    SUPP_W: tl.constexpr,
    K_H: tl.constexpr,
    K_W: tl.constexpr,
    N_ROWS: tl.constexpr,
    IS_FP64: tl.constexpr,
    BLOCK_H: tl.constexpr,
    BLOCK_W: tl.constexpr,
):
    """Same row-reuse scheme with register-resident reductions.

    Preferred when the column tile fits a single warp (BLOCK_W <= 32): the 13
    live tap weight vectors then cost little register pressure and the
    per-iteration shared-memory reductions disappear entirely.
    """
    DT: tl.constexpr = tl.float64 if IS_FP64 else tl.float32

    pid_w = tl.program_id(0)
    pid_h = tl.program_id(1)
    pid_p = tl.program_id(2)

