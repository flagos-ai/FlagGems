@triton.jit
def _lanczos3(x, DT: tl.constexpr):
    ax = tl.abs(x)
    pix = x * 3.141592653589793
    pix3 = pix / 3.0
    one = tl.full((), 1.0, DT)
    zero = tl.full((), 0.0, DT)
    s1 = tl.where(ax == 0.0, one, tl.sin(pix) / pix)
    s3 = tl.where(ax == 0.0, one, tl.sin(pix3) / pix3)
    return tl.where(ax < 3.0, s1 * s3, zero)


