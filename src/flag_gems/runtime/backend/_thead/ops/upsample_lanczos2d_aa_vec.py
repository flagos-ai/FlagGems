    ox = pid_w * BLOCK_W + tl.arange(0, BLOCK_W)

    half = tl.full((), 0.5, DT)
    sc_h = tl.full((), SCALE_H, DT)
    sc_w = tl.full((), SCALE_W, DT)
    inv_h = tl.full((), INV_H, DT)
    inv_w = tl.full((), INV_W, DT)
    supp_h = tl.full((), SUPP_H, DT)
    supp_w = tl.full((), SUPP_W, DT)
