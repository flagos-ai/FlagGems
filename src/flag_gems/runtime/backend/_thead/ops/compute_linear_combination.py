def _align(x):
    """Largest power of two (<= 128) dividing x; enables compile-time mask elision."""
    a = x & -x
    return a if a < 128 else 128


def _compute_linear_combination(input, coefficients, *, out=None):
    logger.debug("GEMS_THEAD COMPUTE_LINEAR_COMBINATION")
    nd = input.ndim
    assert nd > 0 and input.numel() > 0, "Empty tensor not supported"
    assert coefficients.dim() == 2, "coefficients must be 2-dimensional"

    m = coefficients.size(0)
    n = coefficients.size(1)
    assert input.size(0) == n, "incompatible dimensions: input and coefficients"

    if out is None:
        out = torch.empty(
            (m,) + tuple(input.shape[1:]), dtype=input.dtype, device=input.device
        )

    K = input.numel() // n
    if m == 0 or K == 0:
        return out

    i_shape = input.shape
    i_stride = input.stride()
    stride_i0 = i_stride[0]
    packed = True
    acc_s = 1
    for d in range(nd - 1, 0, -1):
        if i_stride[d] != acc_s:
            packed = False
            break
        acc_s *= i_shape[d]

    stride_c0 = coefficients.stride(0)
    stride_c1 = coefficients.stride(1)
    mixed = input.dtype != coefficients.dtype
    prec = "tf32x3" if input.dtype == torch.float32 else "ieee"

    if packed:
        grid = lambda meta: (
            triton.cdiv(m, meta["BLOCK_M"]) * triton.cdiv(K, meta["BLOCK_K"]),
        )
        _lcomb_packed[grid](
            input,
            coefficients,
            out,
            m,
            K,
            n,
            stride_i0,
            stride_c0,
            stride_c1,
            PREC=prec,
            MIXED=mixed,
            M_ALIGN=_align(m),
            K_ALIGN=_align(K),
            N_ALIGN=_align(n),
        )
    else:
        ndim_trail = nd - 1
        assert ndim_trail <= _MAX_TRAIL, "input rank too large"
        S = [1] * _MAX_TRAIL
        T = [1] * _MAX_TRAIL
        for d in range(1, nd):
            S[d - 1] = i_shape[d]
            T[d - 1] = i_stride[d]
        grid = (triton.cdiv(m, 32), triton.cdiv(K, 32))
        _lcomb_strided[grid](
            input,
            coefficients,
            out,
            m,
            K,
            n,
            stride_i0,
            stride_c0,
            stride_c1,
            S[0],
            S[1],
            S[2],
            S[3],
            S[4],
            S[5],
            S[6],
            S[7],
            T[0],
            T[1],
            T[2],
            T[3],
            T[4],
            T[5],
            T[6],
            T[7],
            NDIM=ndim_trail,
            PREC=prec,
            MIXED=mixed,
            BLOCK_M=32,
            BLOCK_N=32,
            BLOCK_K=32,
        )
    return out
