"""Triton fractional_max_pool2d_backward.

grad_input[p, j] = sum over output positions o of plane p whose recorded
forward index equals j (plane-relative flat offset h*W + w).  Everything else
is zero.

Two legal launch shapes, chosen from the tensor geometry:

* fused (default): one program owns one (n, c) plane, writes that plane's
  zeros, then scatters the plane's grad_output values into the recorded
  positions after a block barrier.  A single launch, which is what matters when
  the whole op is launch-latency bound, and full-device occupancy whenever the
  plane count is large.
* split (few planes, large output): a flat zero-fill kernel over the whole
  output plus a flat scatter kernel over every (plane, output position) pair,
  so both phases fill the device even when there are only a handful of planes.

The output is written directly in the requested dtype: no float32 staging
buffer and no second cast pass.
"""

import logging

import torch
import triton
import triton.language as tl

logger = logging.getLogger(__name__)

# Below this size the op is launch-latency bound, so an extra launch is fatal.
_SPLIT_MIN_ELEMS = 200000
# With this few planes, or planes this small, the fused per-plane program is
# starved (a handful of blocks) or cannot fill the memory pipe of a plane-sized
# program, so the flat two-launch pipeline is used instead.
_MIN_FUSED_PLANES = 64
_MIN_FUSED_PLANE_ELEMS = 1024


@triton.jit
def _zero_kernel(ptr, n, BLOCK: tl.constexpr):
    offs = tl.program_id(0) * BLOCK + tl.arange(0, BLOCK)
    tl.store(ptr + offs, tl.zeros((BLOCK,), dtype=ptr.dtype.element_ty), mask=offs < n)


@triton.jit
def _plane_kernel(
    go_ptr,
    idx_ptr,
    out_ptr,
    in_hw,
    out_hw,
    out_w,
    go_s0,
    go_s1,
    idx_s0,
    idx_s1,
    in_c,
    go_sh,
    go_sw,
    idx_sh,
    idx_sw,
    ZBLOCK: tl.constexpr,
    OBLOCK: tl.constexpr,
    CONTIG: tl.constexpr,
):
    pid = tl.program_id(0)
    n = pid // in_c
    c = pid % in_c

    out_base = out_ptr + pid * in_hw

    # Phase 1: zero the whole plane owned by this program.
    for j in range(0, tl.cdiv(in_hw, ZBLOCK)):
        offs = j * ZBLOCK + tl.arange(0, ZBLOCK)
        tl.store(
            out_base + offs,
            tl.zeros((ZBLOCK,), dtype=out_ptr.dtype.element_ty),
            mask=offs < in_hw,
        )

    tl.debug_barrier()

    # Phase 2: scatter grad_output into the recorded positions.
    go_base = go_ptr + n * go_s0 + c * go_s1
    idx_base = idx_ptr + n * idx_s0 + c * idx_s1
    for j in range(0, tl.cdiv(out_hw, OBLOCK)):
        o = j * OBLOCK + tl.arange(0, OBLOCK)
        m = o < out_hw
        if CONTIG:
            idx = tl.load(idx_base + o, mask=m, other=-1)
            g = tl.load(go_base + o, mask=m, other=0)
        else:
            oh = o // out_w
            ow = o - oh * out_w
            idx = tl.load(idx_base + oh * idx_sh + ow * idx_sw, mask=m, other=-1)
            g = tl.load(go_base + oh * go_sh + ow * go_sw, mask=m, other=0)
        tl.atomic_add(
            out_base + idx.to(tl.int32), g, mask=m & (idx >= 0), sem="relaxed"
        )


@triton.jit
def _scatter_kernel(
    go_ptr,
    idx_ptr,
    out_ptr,
    total,
    out_hw,
    in_hw,
    out_w,
    go_s0,
    go_s1,
    idx_s0,
    idx_s1,
    in_c,
    go_sh,
    go_sw,
    idx_sh,
    idx_sw,
    BLOCK: tl.constexpr,
    CONTIG: tl.constexpr,
):
    t = tl.program_id(0) * BLOCK + tl.arange(0, BLOCK)
    m = t < total

    plane = t // out_hw
    rem = t - plane * out_hw
    pn = plane // in_c
    pc = plane - pn * in_c
    base_go = pn * go_s0 + pc * go_s1
    base_idx = pn * idx_s0 + pc * idx_s1

    if CONTIG:
        go_off = base_go + rem
        idx_off = base_idx + rem
    else:
        oh = rem // out_w
        ow = rem - oh * out_w
        go_off = base_go + oh * go_sh + ow * go_sw
        idx_off = base_idx + oh * idx_sh + ow * idx_sw

    idx = tl.load(idx_ptr + idx_off, mask=m, other=-1)
    g = tl.load(go_ptr + go_off, mask=m, other=0)
    tl.atomic_add(
        out_ptr + plane * in_hw + idx.to(tl.int32),
        g,
        mask=m & (idx >= 0),
        sem="relaxed",
    )


def fractional_max_pool2d_backward(
    grad_output, self, kernel_size, output_size, indices
):
    logger.debug("GEMS_THEAD FRACTIONAL_MAX_POOL2D_BACKWARD")
    shape = self.shape
    rank = len(shape)
    in_hw = shape[-2] * shape[-1]
    ow = grad_output.shape[-1]
    out_hw = grad_output.shape[-2] * ow

    if rank == 4:
        in_c = shape[1]
        p = shape[0] * in_c
        go_s0 = grad_output.stride(0)
        go_s1 = grad_output.stride(1)
        idx_s0 = indices.stride(0)
        idx_s1 = indices.stride(1)
    else:
        in_c = shape[0]
        p = in_c
        go_s0 = grad_output.stride(0)
        go_s1 = 0
        idx_s0 = indices.stride(0)
        idx_s1 = 0

    out = torch.empty(shape, dtype=grad_output.dtype, device=grad_output.device)
    numel = out.numel()
    if numel == 0:
        return out
    if out_hw == 0:
        _zero_kernel[(triton.cdiv(numel, 1024),)](out, numel, BLOCK=1024)
        return out

    go_sh = grad_output.stride(-2)
    go_sw = grad_output.stride(-1)
    idx_sh = indices.stride(-2)
    idx_sw = indices.stride(-1)
    contig = go_sw == 1 and go_sh == ow and idx_sw == 1 and idx_sh == ow

    if numel < _SPLIT_MIN_ELEMS or (
        p >= _MIN_FUSED_PLANES and in_hw > _MIN_FUSED_PLANE_ELEMS
    ):
        # Zero tile: one 16 B vector store per thread.  Scatter tile: bound one
        # warp's atomic destinations to about one 128 B line (2 lanes/thread for
        # 2-byte dtypes, 1 for 4-byte).  That narrowing pays off only while the
        # atomic phase is bandwidth bound; launch-bound shapes prefer fewer,
        # wider iterations instead.
        esize = grad_output.element_size()
        if in_hw > 1024:
            zblock = 1024
            num_warps = 4
        else:
            zblock = min(2048, max(32, triton.next_power_of_2(in_hw)))
            num_warps = max(1, min(8, zblock // 256))
        if numel >= _SPLIT_MIN_ELEMS:
            lanes = max(1, 128 // (32 * esize))
        else:
            lanes = 2
        oblock = min(max(16, triton.next_power_of_2(out_hw)), num_warps * 32 * lanes)
        _plane_kernel[(p,)](
            grad_output,
            indices,
            out,
            in_hw,
            out_hw,
            ow,
            go_s0,
            go_s1,
            idx_s0,
            idx_s1,
            in_c,
            go_sh,
            go_sw,
            idx_sh,
            idx_sw,
            ZBLOCK=zblock,
            OBLOCK=oblock,
            CONTIG=contig,
            num_warps=num_warps,
        )
    else:
        _zero_kernel[(triton.cdiv(numel, 2048),)](out, numel, BLOCK=2048, num_warps=8)
        total = p * out_hw
        # Bound the scatter tile so one warp's atomic destinations span about
        # one 128 B line (2 lanes/thread for 2-byte dtypes, 1 for 4-byte):
        # the wide tile measured ~2.8x lower delivered bandwidth at equal
        # occupancy in the fused kernel.
        esize = grad_output.element_size()
        sblock = 128 * max(1, 128 // (32 * esize))
        _scatter_kernel[(triton.cdiv(total, sblock),)](
            grad_output,
            indices,
            out,
            total,
            out_hw,
            in_hw,
            ow,
            go_s0,
            go_s1,
            idx_s0,
            idx_s1,
            in_c,
            go_sh,
            go_sw,
            idx_sh,
            idx_sw,
            BLOCK=sblock,
            CONTIG=contig,
            num_warps=4,
        )
    return out
