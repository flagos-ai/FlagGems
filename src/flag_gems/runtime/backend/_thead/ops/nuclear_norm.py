@triton.jit
def _nn_fused_kernel(
    A,
    AW,
    OUT,
    STRIDE_AM,
    STRIDE_AN,
    S0,
    S1,
    S2,
    S3,
    K: tl.constexpr,
    ROWS: tl.constexpr,
    ROUND: tl.constexpr,
    B0: tl.constexpr,
    B1: tl.constexpr,
    B2: tl.constexpr,
    B3: tl.constexpr,
    TALL: tl.constexpr,
    BLOCK_R: tl.constexpr,
    HALF: tl.constexpr,
    HALF_REAL: tl.constexpr,
    SWEEPS: tl.constexpr,
    EXACT: tl.constexpr,
):
    """One program per matrix: load, all Jacobi stages, final sum, one launch."""
    pid = tl.program_id(0)

    i3 = pid % B3
    rest = pid // B3
    i2 = rest % B2
    rest = rest // B2
    i1 = rest % B1
    i0 = rest // B1
    off = i0 * S0 + i1 * S1 + i2 * S2 + i3 * S3

    r = tl.arange(0, BLOCK_R)
    slot = tl.arange(0, HALF)
    rmask = r < ROWS
    smask = slot < HALF_REAL
    row = r[None, :]
    base = AW + pid * (K + 1) * ROWS
    a_base = A + off
    nchunk = (K + HALF) // HALF  # covers columns 0..K (K = zero scratch lane)
    m1 = ROUND - 1
    eps = 1.0e-20

    # ---- load the tall-orientation columns into the workspace -------------
    for ci in tl.range(0, nchunk):
        cc = ci * HALF + slot
        ok_src = (cc < K)[:, None] & rmask[None, :]
        ok_dst = (cc <= K)[:, None] & rmask[None, :]
        if TALL:
            v = tl.load(
                a_base + cc[:, None] * STRIDE_AN + row * STRIDE_AM,
                mask=ok_src,
                other=0.0,
            )
        else:
            v = tl.load(
                a_base + cc[:, None] * STRIDE_AM + row * STRIDE_AN,
                mask=ok_src,
                other=0.0,
            )
        tl.store(base + cc[:, None] * ROWS + row, v.to(tl.float32), mask=ok_dst)

    tl.debug_barrier()

    # ---- round-robin one-sided Jacobi ------------------------------------
    if EXACT:
        # power-of-two matrix with an even k: every slot holds a real, disjoint
        # pair, so no masking or scratch routing is needed at all.
        for _sw in tl.range(0, SWEEPS):
            for step in tl.range(0, ROUND - 1):
                p = tl.where(slot == 0, step, (step + slot) % m1)
                q = tl.where(slot == 0, m1, ((step - slot) % m1 + m1) % m1)
                pr = base + p[:, None] * ROWS + row
                qr = base + q[:, None] * ROWS + row
                ap = tl.load(pr)
                aq = tl.load(qr)
                alpha = tl.sum(ap * ap, axis=1)
                beta = tl.sum(aq * aq, axis=1)
                gamma = tl.sum(ap * aq, axis=1)
                active = tl.abs(gamma) > 1.0e-7 * tl.sqrt(alpha * beta + eps)
                safe_gamma = tl.where(active, gamma, 1.0)
                tau = (beta - alpha) / (2.0 * safe_gamma)
                sign_tau = tl.where(tau >= 0.0, 1.0, -1.0)
                t = sign_tau / (tl.abs(tau) + tl.sqrt(1.0 + tau * tau))
                c = tl.rsqrt(1.0 + t * t)
                s = t * c
                c = tl.where(active, c, 1.0)
                s = tl.where(active, s, 0.0)
                c2 = c[:, None]
                s2 = s[:, None]
                tl.store(pr, c2 * ap - s2 * aq)
                tl.store(qr, s2 * ap + c2 * aq)
                # columns written here are re-read by other lanes next stage
                tl.debug_barrier()
    else:
        for _sw in tl.range(0, SWEEPS):
            for step in tl.range(0, ROUND - 1):
                pp = (step + slot) % m1
                qq = ((step - slot) % m1 + m1) % m1
                p = tl.where(slot == 0, step, pp)
                q = tl.where(slot == 0, m1, qq)
                valid = smask & (p < K) & (q < K)
                pf = tl.where(valid, p, K)
                qf = tl.where(valid, q, K)

                ap = tl.load(
                    base + pf[:, None] * ROWS + row, mask=rmask[None, :], other=0.0
                )
                aq = tl.load(
                    base + qf[:, None] * ROWS + row, mask=rmask[None, :], other=0.0
                )

                alpha = tl.sum(ap * ap, axis=1)
                beta = tl.sum(aq * aq, axis=1)
                gamma = tl.sum(ap * aq, axis=1)

                active = valid & (tl.abs(gamma) > 1.0e-7 * tl.sqrt(alpha * beta + eps))
                safe_gamma = tl.where(active, gamma, 1.0)
                tau = (beta - alpha) / (2.0 * safe_gamma)
                sign_tau = tl.where(tau >= 0.0, 1.0, -1.0)
                t = sign_tau / (tl.abs(tau) + tl.sqrt(1.0 + tau * tau))
                c = tl.rsqrt(1.0 + t * t)
                s = t * c
                c = tl.where(active, c, 1.0)
                s = tl.where(active, s, 0.0)
                c2 = c[:, None]
                s2 = s[:, None]

                tl.store(
                    base + pf[:, None] * ROWS + row,
                    c2 * ap - s2 * aq,
                    mask=rmask[None, :],
                )
                tl.store(
                    base + qf[:, None] * ROWS + row,
                    s2 * ap + c2 * aq,
                    mask=rmask[None, :],
                )
                # columns written here are re-read by other lanes next stage
                tl.debug_barrier()

    tl.debug_barrier()

    # ---- sum the orthogonalised column norms ------------------------------
    total = 0.0
    for ci in tl.range(0, nchunk):
        cc = ci * HALF + slot
        keep = cc < K
        cf = tl.where(keep, cc, K)
        colv = tl.load(
            base + cf[:, None] * ROWS + row,
            mask=keep[:, None] & rmask[None, :],
            other=0.0,
        )
        norms = tl.sqrt(tl.maximum(tl.sum(colv * colv, axis=1), 0.0))
        total += tl.sum(tl.where(keep, norms, 0.0))
    tl.store(OUT + pid, total.to(OUT.dtype.element_ty))


@triton.jit
def _nn_persist_kernel(
    A,
    AW,
    OUT,
    FLAGS,
    PART,
    STRIDE_AM,
    STRIDE_AN,
    S0,
    S1,
    S2,
    S3,
    K: tl.constexpr,
    ROWS: tl.constexpr,
    ROUND: tl.constexpr,
    NSTAGE: tl.constexpr,
    GRID: tl.constexpr,
    B0: tl.constexpr,
    B1: tl.constexpr,
    B2: tl.constexpr,
    B3: tl.constexpr,
    TALL: tl.constexpr,
    BLOCK_R: tl.constexpr,
    SPC: tl.constexpr,
    HALF_REAL: tl.constexpr,
):
    """Persistent grid: all Jacobi stages in one launch, synced by a spin barrier.

    GRID co-operating programs (one per device SM) each own SPC column pairs of
    every stage; a per-stage counter in FLAGS is used as an arrival counter and
    spin-waited, so no host launch is needed between stages.  Tile loads bypass
    L1 (cache_modifier=".cg") because the columns a program reads were written
    by other programs in the previous stage.
    """
    pid = tl.program_id(0)
    bidx = pid // GRID
    cta = pid % GRID

    i3 = bidx % B3
    rest = bidx // B3
    i2 = rest % B2
    rest = rest // B2
    i1 = rest % B1
    i0 = rest // B1
    off = i0 * S0 + i1 * S1 + i2 * S2 + i3 * S3

    r = tl.arange(0, BLOCK_R)
    row = r[None, :]
    rmask = r < ROWS
    slot0 = tl.arange(0, SPC)
    base = AW + bidx * (K + 1) * ROWS
    a_base = A + off
    flag_base = FLAGS + bidx * (NSTAGE + 1)
    m1 = ROUND - 1
    eps = 1.0e-20

    # ---- init: each program copies its own subset of columns --------------
    for jj in tl.range(0, (K + GRID) // GRID):
        j = cta + jj * GRID
        if j <= K:
            if j < K:
                if TALL:
                    v = tl.load(
                        a_base + j * STRIDE_AN + r * STRIDE_AM,
                        mask=rmask,
                        other=0.0,
                    )
                else:
                    v = tl.load(
                        a_base + j * STRIDE_AM + r * STRIDE_AN,
                        mask=rmask,
                        other=0.0,
                    )
            else:
                v = tl.zeros((BLOCK_R,), dtype=tl.float32)
            tl.store(base + j * ROWS + r, v.to(tl.float32), mask=rmask)

    tl.debug_barrier()
    tl.atomic_add(flag_base + NSTAGE, 1)
    cnt = tl.atomic_add(flag_base + NSTAGE, 0)
    while cnt < GRID:
        cnt = tl.atomic_add(flag_base + NSTAGE, 0)

    # ---- all Jacobi stages ------------------------------------------------
    slotv = cta + slot0 * GRID
    sv_ok = slotv < HALF_REAL
    for stg in tl.range(0, NSTAGE):
        step = stg % m1
        p = tl.where(slotv == 0, step, (step + slotv) % m1)
        q = tl.where(slotv == 0, m1, ((step - slotv) % m1 + m1) % m1)
        ok = sv_ok & (p < K) & (q < K)
        pf = tl.where(ok, p, K)
        qf = tl.where(ok, q, K)
        pr = base + pf[:, None] * ROWS + row
        qr = base + qf[:, None] * ROWS + row

        if ROWS == BLOCK_R:
            ap = tl.load(pr, cache_modifier=".cg")
            aq = tl.load(qr, cache_modifier=".cg")
        else:
            ap = tl.load(pr, mask=rmask[None, :], other=0.0, cache_modifier=".cg")
            aq = tl.load(qr, mask=rmask[None, :], other=0.0, cache_modifier=".cg")

        alpha = tl.sum(ap * ap, axis=1)
        beta = tl.sum(aq * aq, axis=1)
        gamma = tl.sum(ap * aq, axis=1)
        active = ok & (tl.abs(gamma) > 1.0e-7 * tl.sqrt(alpha * beta + eps))
        safe_gamma = tl.where(active, gamma, 1.0)
        tau = (beta - alpha) / (2.0 * safe_gamma)
        sign_tau = tl.where(tau >= 0.0, 1.0, -1.0)
        t = sign_tau / (tl.abs(tau) + tl.sqrt(1.0 + tau * tau))
        c = tl.rsqrt(1.0 + t * t)
        sn = t * c
        c = tl.where(active, c, 1.0)
        sn = tl.where(active, sn, 0.0)
        c2 = c[:, None]
        s2 = sn[:, None]
        if ROWS == BLOCK_R:
            tl.store(pr, c2 * ap - s2 * aq)
            tl.store(qr, s2 * ap + c2 * aq)
        else:
            tl.store(pr, c2 * ap - s2 * aq, mask=rmask[None, :])
            tl.store(qr, s2 * ap + c2 * aq, mask=rmask[None, :])

        tl.debug_barrier()
        tl.atomic_add(flag_base + stg, 1)
        cnt = tl.atomic_add(flag_base + stg, 0)
        while cnt < GRID:
            cnt = tl.atomic_add(flag_base + stg, 0)

    # ---- per-program partial sum of the column norms ----------------------
    part = 0.0
    for jj in tl.range(0, (K + GRID - 1) // GRID):
        j = cta + jj * GRID
        if j < K:
            col = tl.load(
                base + j * ROWS + r, mask=rmask, other=0.0, cache_modifier=".cg"
            )
            part += tl.sqrt(tl.maximum(tl.sum(col * col), 0.0))
    tl.store(PART + bidx * GRID + cta, part)

    tl.debug_barrier()
    tl.atomic_add(flag_base + NSTAGE, 1)
    cnt = tl.atomic_add(flag_base + NSTAGE, 0)
    while cnt < GRID * 2:
        cnt = tl.atomic_add(flag_base + NSTAGE, 0)

    if cta == 0:
        pv = tl.load(PART + bidx * GRID + tl.arange(0, GRID))
        tl.store(OUT + bidx, tl.sum(pv).to(OUT.dtype.element_ty))


@triton.jit
def _nn_init_kernel(
    A,
    AW,
    STRIDE_AM,
    STRIDE_AN,
    S0,
    S1,
    S2,
    S3,
    K,
    ROWS,
    B0: tl.constexpr,
    B1: tl.constexpr,
    B2: tl.constexpr,
    B3: tl.constexpr,
    TALL: tl.constexpr,
    BLOCK_R: tl.constexpr,
):
    """Copy the k columns of each matrix into a dense (B, K+1, ROWS) workspace."""
    pid = tl.program_id(0)
    j = tl.program_id(1)

    i3 = pid % B3
    rest = pid // B3
    i2 = rest % B2
    rest = rest // B2
    i1 = rest % B1
    i0 = rest // B1
    off = i0 * S0 + i1 * S1 + i2 * S2 + i3 * S3

    r = tl.arange(0, BLOCK_R)
    mask = (r < ROWS) & (j < K)
    a_base = A + off
    if TALL:
        v = tl.load(a_base + r * STRIDE_AM + j * STRIDE_AN, mask=mask, other=0.0)
    else:
        v = tl.load(a_base + j * STRIDE_AM + r * STRIDE_AN, mask=mask, other=0.0)
    tl.store(AW + (pid * (K + 1) + j) * ROWS + r, v.to(tl.float32), mask=r < ROWS)


@triton.jit
def _nn_stage_pair_kernel(
    AW,
    K,
    ROWS,
    STEP,
    ROUND: tl.constexpr,
    BLOCK_R: tl.constexpr,
):
    """One program per (matrix, disjoint column pair) for one Jacobi stage."""
    pid = tl.program_id(0)
    slot = tl.program_id(1)
    m1 = ROUND - 1

    if slot == 0:
        p = STEP
        q = m1
    else:
        p = (STEP + slot) % m1
        q = ((STEP - slot) % m1 + m1) % m1

    if p < K:
        if q < K:
            r = tl.arange(0, BLOCK_R)
            rmask = r < ROWS
            base = AW + pid * (K + 1) * ROWS
            ap = tl.load(base + p * ROWS + r, mask=rmask, other=0.0)
            aq = tl.load(base + q * ROWS + r, mask=rmask, other=0.0)
            eps = 1.0e-20
            alpha = tl.sum(ap * ap)
            beta = tl.sum(aq * aq)
            gamma = tl.sum(ap * aq)
            active = tl.abs(gamma) > 1.0e-7 * tl.sqrt(alpha * beta + eps)
            safe_gamma = tl.where(active, gamma, 1.0)
            tau = (beta - alpha) / (2.0 * safe_gamma)
            sign_tau = tl.where(tau >= 0.0, 1.0, -1.0)
            t = sign_tau / (tl.abs(tau) + tl.sqrt(1.0 + tau * tau))
            c = tl.rsqrt(1.0 + t * t)
            s = t * c
            c = tl.where(active, c, 1.0)
            s = tl.where(active, s, 0.0)
            tl.store(base + p * ROWS + r, c * ap - s * aq, mask=rmask)
            tl.store(base + q * ROWS + r, s * ap + c * aq, mask=rmask)


@triton.jit
def _nn_final_kernel(AW, OUT, K, ROWS, BLOCK_R: tl.constexpr):
    """Sum the 2-norms of the orthogonalised columns -> nuclear norm."""
    pid = tl.program_id(0)
    r = tl.arange(0, BLOCK_R)
    rmask = r < ROWS
    base = AW + pid * (K + 1) * ROWS
    total = 0.0
    for j in tl.range(0, K):
        col = tl.load(base + j * ROWS + r, mask=rmask, other=0.0)
        total += tl.sqrt(tl.maximum(tl.sum(col * col), 0.0))
    tl.store(OUT + pid, total.to(OUT.dtype.element_ty))


@triton.jit
def _nn_zero_kernel(OUT):
    pid = tl.program_id(0)
    off = pid + tl.arange(0, 1)
    tl.store(OUT + off, tl.zeros((1,), dtype=OUT.dtype.element_ty))


