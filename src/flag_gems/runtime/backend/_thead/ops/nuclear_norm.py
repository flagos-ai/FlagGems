_FUSED_MAX_K = 128
_PERSIST_GRID = 64


def _sweeps_for(k):
    if k <= 8:
        return 8
    if k <= 128:
        return 5
    return 4


def _num_warps(n_elems):
    if n_elems <= 256:
        return 1
    if n_elems <= 1024:
        return 2
    if n_elems <= 4096:
        return 8
    return 32


def nuclear_norm(self, keepdim=False):
    logger.debug("GEMS_THEAD NUCLEAR_NORM")
    A = self
    if A.dim() < 2:
        raise RuntimeError(
            "linalg.matrix_norm: The input tensor A must have at least 2 dimensions."
        )

    m = A.shape[-2]
    n = A.shape[-1]
    k = min(m, n)
    rows = max(m, n)

    batch_shape = tuple(A.shape[:-2])
    B = 1
    for d in batch_shape:
        B *= d

    out_shape = batch_shape + ((1, 1) if keepdim else ())
    out = torch.empty(out_shape, dtype=A.dtype, device=A.device)

    if k == 0:
        _nn_zero_kernel[(B,)](out)
        return out

    # batch dims (up to 4, most-minor last) for base-offset computation
    bs = list(batch_shape)
    st = [A.stride(i) for i in range(len(batch_shape))]
    while len(bs) < 4:
        bs.insert(0, 1)
        st.insert(0, 0)
    if len(bs) > 4:
        raise RuntimeError("nuclear_norm: too many batch dimensions")

    aw = torch.empty((B, k + 1, rows), dtype=torch.float32, device=A.device)
    block_r = triton.next_power_of_2(rows)
    nwarp = 1 if block_r <= 64 else 4
    tall = m >= n

    round_size = k if k % 2 == 0 else k + 1
    sweeps = _sweeps_for(k)

    if k <= _FUSED_MAX_K:
        half_real = round_size // 2
        half = triton.next_power_of_2(half_real)
        exact = (block_r == rows) and (half == half_real) and (round_size == k)
        _nn_fused_kernel[(B,)](
            A,
            aw,
            out,
            A.stride(-2),
            A.stride(-1),
            st[0],
            st[1],
            st[2],
            st[3],
            K=k,
            ROWS=rows,
            ROUND=round_size,
            B0=bs[0],
            B1=bs[1],
            B2=bs[2],
            B3=bs[3],
            TALL=tall,
            BLOCK_R=block_r,
            HALF=half,
            HALF_REAL=half_real,
            SWEEPS=sweeps,
            EXACT=exact,
            num_warps=_num_warps(block_r * half),
        )
        return out

    if B * _PERSIST_GRID <= _PERSIST_GRID:
        # large single matrix: every stage inside one persistent launch, with a
        # spin barrier between stages instead of a host launch per stage.
        nstage = sweeps * (round_size - 1)
        half_real = round_size // 2
        spc = (half_real + _PERSIST_GRID - 1) // _PERSIST_GRID
        flags = torch.zeros((B * (nstage + 1),), dtype=torch.int32, device=A.device)
        part = torch.empty((B * _PERSIST_GRID,), dtype=torch.float32, device=A.device)
        pwarps = 8 if spc * block_r > 1024 else 4
        _nn_persist_kernel[(B * _PERSIST_GRID,)](
            A,
            aw,
            out,
            flags,
            part,
            A.stride(-2),
            A.stride(-1),
            st[0],
            st[1],
            st[2],
            st[3],
            K=k,
            ROWS=rows,
            ROUND=round_size,
            NSTAGE=nstage,
            GRID=_PERSIST_GRID,
            B0=bs[0],
            B1=bs[1],
            B2=bs[2],
            B3=bs[3],
            TALL=tall,
            BLOCK_R=block_r,
            SPC=spc,
            HALF_REAL=half_real,
            num_warps=pwarps,
        )
        return out

    _nn_init_kernel[(B, k + 1)](
        A,
        aw,
        A.stride(-2),
        A.stride(-1),
        st[0],
        st[1],
        st[2],
        st[3],
        k,
        rows,
        B0=bs[0],
        B1=bs[1],
        B2=bs[2],
        B3=bs[3],
        TALL=tall,
        BLOCK_R=block_r,
        num_warps=nwarp,
    )
    for _ in range(sweeps):
        for step in range(round_size - 1):
            _nn_stage_pair_kernel[(B, round_size // 2)](
                aw,
                k,
                rows,
                step,
                ROUND=round_size,
                BLOCK_R=block_r,
                num_warps=nwarp,
            )
    _nn_final_kernel[(B,)](aw, out, k, rows, BLOCK_R=block_r, num_warps=nwarp)
    return out
