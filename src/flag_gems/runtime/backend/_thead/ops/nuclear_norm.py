"""Nuclear norm (sum of singular values) implemented with Triton kernels.

Reference semantics (torch.linalg.matrix_norm(A, ord="nuc")):
  out = sum of singular values over the last two dims of ``self``.
  * 2-D input  -> 0-dim output (keepdim=True -> (1, 1))
  * batched    -> batch_shape (keepdim=True -> batch_shape + (1, 1))
  * output dtype == input dtype.

Algorithm: one-sided (Hestenes) Jacobi on the "tall" orientation of each
matrix.  The singular values are the 2-norms of the Jacobi-orthogonalised
columns, so the nuclear norm is their sum.  All arithmetic is fp32; the result
is cast to the input dtype once.

The rotation schedule is the round-robin ("circle") pairing: every stage
rotates ROUND/2 mutually disjoint column pairs, so a whole stage is evaluated
as one vectorised step (three reductions per stage instead of three per pair).

Path selection:
  * k <= 128 : one program per matrix does load + all sweeps + final sum in a
    single kernel launch, with a CTA barrier between stages (columns written by
    one lane are re-read by other lanes in the next stage).
  * k > 128, single matrix : one persistent launch of 64 programs (one per SM)
    that synchronise between stages through a per-stage release/acquire atomic
    spin barrier, avoiding one host launch per stage.
  * otherwise : one program per disjoint pair, one launch per stage.
"""

