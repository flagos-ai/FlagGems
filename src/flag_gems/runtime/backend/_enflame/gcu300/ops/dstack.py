"""GCU300 specialization of ``aten::dstack``.

The generic implementation builds every lane-varying offset in int64
(``program_id.to(tl.int64) * BLOCK + arange.to(tl.int64)`` plus
``tl.full((), X, tl.int64)`` scalars).  GCU300 miscompiles lane-varying int64
arithmetic once a program covers 256 or more lanes: only the first 32-lane
group stays truthful, so roughly half of the output is written to the wrong
address or never written at all.  Uniform (scalar) 64-bit arithmetic is fine.

This override keeps every lane-varying value 32-bit from the start; the tile
index comes from ``tl.program_id`` (which is int32) and is never narrowed from
an int64 value (``arith.trunci`` on a vector aborts this backend during pointer
analysis).  Inputs whose addressable extent exceeds ``2**31`` elements take a
second kernel that splits the copy into per-outer-row program ranges: the row
base stays a scalar in int64 and only the intra-row offset, which is bounded by
``BLOCK``, is a 32-bit vector.  The launch shape, dtype promotion and
interleaving heuristics are unchanged from the generic module.
"""

from __future__ import annotations

import logging

import torch
import triton
import triton.language as tl

logger = logging.getLogger(__name__)

_BLOCK_WIDE = 1024
_BLOCK_NARROW = 2048
_WARPS = 4
_MAX_GROUP = 4
_TOKEN_OB_LARGE = 256
_TOKEN_OB_SMALL = 64
_TOKEN_RP_LARGE = 2
_TOKEN_RP_SMALL = 4
_TOKEN_WARPS_LARGE = 2
_TOKEN_WARPS_SMALL = 4
_TOKEN_OB_CUTOFF = 1 << 19

# Lane-varying indices are 32-bit on this backend, so a flat kernel can only
# address an output of at most 2**31 elements; larger outputs use the
# row-split kernel whose per-program base is a scalar.
_MAX_I32 = 1 << 31

_REAL_OF_COMPLEX = {
    torch.complex32: torch.float16,
    torch.complex64: torch.float32,
    torch.complex128: torch.float64,
}

# The multi-pointer select cannot compile for fp8 element types (the masked load
# cannot produce an fp8 value from an integer default); those stay on the copy path.
_MULTI_SELECT_UNSUPPORTED = {
    torch.float8_e4m3fn,
    torch.float8_e5m2,
    torch.float8_e4m3fnuz,
    torch.float8_e5m2fnuz,
    torch.float8_e8m0fnu,
}


def _next_pow2(value: int) -> int:
    power = 1
    while power < value:
        power *= 2
    return power


@triton.jit
def _dstack_copy_kernel(
    out_ptr, in_ptr, cnt, seg, out_row, out_off, BLOCK: tl.constexpr
):
    """Copy ``cnt`` contiguous copy units of one input into its output slice.

    ``g`` is the flat copy-unit index within the input; ``seg = K_i * inner``
    units form one outer row, so ``o = g // seg`` and ``t = g - o * seg`` give
    the destination row and slot inside the output slice.  ``g`` and every
    derived offset stay 32-bit (see the module docstring).
    """
    g = tl.program_id(0) * BLOCK + tl.arange(0, BLOCK)
    mask = g < cnt
    o = g // seg
    t = g - o * seg
    tl.store(
        out_ptr + o * out_row + out_off + t, tl.load(in_ptr + g, mask=mask), mask=mask
    )


@triton.jit
def _dstack_copy_row_kernel(
    out_ptr, in_ptr, seg, out_row, out_off, chunks, BLOCK: tl.constexpr
):
    """Copy one contiguous chunk of one outer row of one input.

    ``pid // chunks`` selects the outer row and ``pid % chunks`` the chunk
    inside its ``seg`` copy units, so the whole program range is a contiguous
    run in the input and in the output.  The row bases are scalars in int64;
    only the intra-row index, bounded by ``BLOCK``, is a 32-bit vector.
    """
    pid = tl.program_id(0)
    o = pid // chunks
    chunk = pid - o * chunks
    row_base = o.to(tl.int64) * seg
    start = chunk.to(tl.int64) * BLOCK
    remaining = seg - start
    lim = tl.minimum(remaining, BLOCK).to(tl.int32)
    idx = tl.arange(0, BLOCK)
    mask = idx < lim
    src_base = in_ptr + row_base + start
    dst_base = out_ptr + o.to(tl.int64) * out_row + out_off + start
    tl.store(dst_base + idx, tl.load(src_base + idx, mask=mask), mask=mask)


@triton.jit
def _dstack_token_kernel(
    out_ptr,
    src0,
    src1,
    src2,
    src3,
    rows,
    RP: tl.constexpr,
    P: tl.constexpr,
    OB: tl.constexpr,
    KP: tl.constexpr,
):
    """Interleave up to four single-token inputs (``inner == 1``, ``K_i == 1``).

    Output row ``r`` holds the ``P`` inputs' token ``r`` back to back.  Tile row
    ``o`` owns output rows ``[o * RP, o * RP + RP)``, so lane ``k`` addresses
    output element ``o * RP * P + k``, source row ``o * RP + k // P`` and input
    ``k % P``.  ``KP >= RP * P`` pads the lane count; ``k < rows * P`` is
    guaranteed by the row bound, and the extra padded lanes are store-masked.

    ``o``, ``base`` and ``row`` stay 32-bit: the caller only takes this path
    when the output fits ``2**31`` elements (see the module docstring).
    """
    o = tl.program_id(0) * OB + tl.arange(0, OB)
    k = tl.arange(0, KP)
    base = o * RP
    sid = k % P
    row = base[:, None] + (k // P)[None, :]
    active = row < rows
    v0 = tl.load(src0 + row, mask=active & (sid[None, :] == 0), other=0.0)
    v1 = tl.load(src1 + row, mask=active & (sid[None, :] == 1), other=0.0)
    v2 = tl.load(src2 + row, mask=active & (sid[None, :] == 2), other=0.0)
    v3 = tl.load(src3 + row, mask=active & (sid[None, :] == 3), other=0.0)
    value = tl.where(
        sid[None, :] == 0,
        v0,
        tl.where(sid[None, :] == 1, v1, tl.where(sid[None, :] == 2, v2, v3)),
    )
    keep = active & (k[None, :] < RP * P)
    tl.store(out_ptr + base[:, None] * P + k[None, :], value, mask=keep)


def _prod(values) -> int:
    out = 1
    for value in values:
        out *= int(value)
    return int(out)


def _atleast_3d(shape):
    """atleast_3d promotion: 0-D -> (1,1,1), 1-D -> (1,N,1), 2-D -> (M,N,1)."""
    dims = [int(x) for x in shape]
    if len(dims) == 0:
        return [1, 1, 1]
    if len(dims) == 1:
        return [1, dims[0], 1]
    if len(dims) == 2:
        return [dims[0], dims[1], 1]
    return dims


def _real_dtype(dtype):
    return _REAL_OF_COMPLEX.get(dtype)


def _as_copy_tensor(tensor, real_dtype):
    """Zero-copy reinterpretation of ``tensor`` in the copy element dtype."""
    if real_dtype is None:
        return tensor
    if tensor.dim() == 0:
        # A 0-D complex tensor cannot be reinterpreted in place (the element
        # size changes); materialise the single element as a 1-D view first.
        return tensor.reshape(1).view(real_dtype)
    return tensor.view(real_dtype)


def run(tensors, out=None, **kwargs):
    """``aten::dstack(Tensor[] tensors) -> Tensor``, plus the ``out=`` overload."""
    del kwargs
    items = [tensors] if isinstance(tensors, torch.Tensor) else list(tensors)
    if len(items) == 0:
        raise RuntimeError("dstack expects a non-empty TensorList")
    for item in items:
        if not isinstance(item, torch.Tensor):
            raise TypeError(
                "dstack(): argument 'tensors' must be a list of Tensors, "
                f"but found {type(item).__name__}"
            )

    # Both kernels address their input with a flat linear index, which only
    # matches logical element order when the tensor is contiguous.  Strided,
    # transposed and expanded views have to be materialised first, otherwise
    # they are read in storage order and silently give the wrong answer.
    items = [item if item.is_contiguous() else item.contiguous() for item in items]

    promoted = [_atleast_3d(item.shape) for item in items]
    first = promoted[0]
    outer = first[0] * first[1]
    inner = _prod(first[3:])
    for shape in promoted[1:]:
        if shape[0] != first[0] or shape[1] != first[1] or _prod(shape[3:]) != inner:
            raise RuntimeError(
                "Sizes of tensors must match except in dimension 2. "
                f"Expected size {first[0]} and {first[1]} but got size {shape[0]} "
                f"and {shape[1]}"
            )

    depth = [shape[2] for shape in promoted]
    total = sum(depth)
    result_shape = [first[0], first[1], total, *first[3:]]
    dtype = items[0].dtype
    for item in items[1:]:
        dtype = torch.promote_types(dtype, item.dtype)
    result = (
        torch.empty(result_shape, dtype=dtype, device=items[0].device)
        if out is None
        else out
    )

    real_dtype = _real_dtype(result.dtype)
    unit = 1 if real_dtype is None else 2
    if result.numel() == 0:
        return result

    out_view = _as_copy_tensor(result, real_dtype)
    # Every flat address of a copy has to stay in the 32-bit lane range, and the
    # scalar arguments (row counts and strides) have to be typed int32 as well,
    # so the bound is exclusive.
    fits_i32 = out_view.numel() < _MAX_I32

    # Single-token inputs interleave one element of every input into each output
    # row, so a rows-by-slots tile can write whole rows contiguously.
    if (
        fits_i32
        and inner == 1
        and unit == 1
        and len(items) <= _MAX_GROUP
        and len(set(depth)) == 1
        and depth[0] == 1
        and real_dtype is None
        and all(item.dtype not in _MULTI_SELECT_UNSUPPORTED for item in items)
    ):
        sources = [items[i] if i < len(items) else items[0] for i in range(_MAX_GROUP)]
        if outer >= _TOKEN_OB_CUTOFF:
            rp, ob, warps = _TOKEN_RP_LARGE, _TOKEN_OB_LARGE, _TOKEN_WARPS_LARGE
        else:
            rp, ob, warps = _TOKEN_RP_SMALL, _TOKEN_OB_SMALL, _TOKEN_WARPS_SMALL
        grid = (triton.cdiv(outer, rp * ob),)
        _dstack_token_kernel[grid](
            out_view,
            sources[0],
            sources[1],
            sources[2],
            sources[3],
            outer,
            RP=rp,
            P=len(items),
            OB=ob,
            KP=_next_pow2(rp * len(items)),
            num_warps=warps,
        )
        return result

    out_row = total * inner * unit
    offset = 0
    for item, depth_i in zip(items, depth):
        if item.numel() > 0:
            source = _as_copy_tensor(item, _real_dtype(item.dtype))
            seg = depth_i * inner * unit
            count = outer * seg
            if count > 0 and fits_i32:
                # Short rows (one slice per outer row) are bound by the number of
                # live programs, so they take the wider block; longer runs were
                # measured to prefer the smaller one.
                block = _BLOCK_WIDE if seg <= 4 else _BLOCK_NARROW
                grid = (triton.cdiv(count, block),)
                _dstack_copy_kernel[grid](
                    out_view,
                    source,
                    count,
                    seg,
                    out_row,
                    offset * inner * unit,
                    BLOCK=block,
                    num_warps=_WARPS,
                )
            elif count > 0:
                # The flat index of this input does not fit int32: one program
                # owns a contiguous chunk inside a single outer row, so the row
                # base is a uniform int64 and the lane offset stays int32.
                block = _BLOCK_WIDE if seg <= 4 else _BLOCK_NARROW
                chunks = triton.cdiv(seg, block)
                grid = (outer * chunks,)
                _dstack_copy_row_kernel[grid](
                    out_view,
                    source,
                    seg,
                    out_row,
                    offset * inner * unit,
                    chunks,
                    BLOCK=block,
                    num_warps=_WARPS,
                )
        offset += depth_i
    return result


