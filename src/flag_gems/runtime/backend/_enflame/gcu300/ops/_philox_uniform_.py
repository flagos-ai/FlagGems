"""GCU300 specialization of ``aten::_philox_uniform_``.

The generic implementation builds the element index and the ``base < N`` store
mask from lane-varying 64-bit values.  GCU300 miscompiles lane-varying 64-bit
arithmetic once a block holds 256 or more lanes: a standalone probe that only
stores ``(chunks * 4) < N`` reports 32 truthful lanes out of 512/1024 and
false elsewhere, so most stores mask themselves off and the output stays
partially unwritten.

This override keeps every lane-varying value 32-bit:

* the per-program counter base ``offset + program_id * BLOCK`` is a scalar and
  stays 64-bit, so offsets beyond ``2**32`` still produce the right stream;
* the scalar base is split into 32-bit halves and the low-word overflow is
  carried into the high word with a 32-bit compare;
* element indices and store masks are 32-bit.

``float64`` is rejected: the device has no fp64 support (doubles are emulated
as floats) and the fp64 ``uitofp`` does not lower on this backend.
"""

import logging

import torch
import triton
import triton.language as tl

from flag_gems.runtime import torch_device_fn

logger = logging.getLogger(__name__)

# Number of mantissa bits extracted from each 32-bit Philox word, matching
# ATen's ``transformation::uniform_real`` with ``numeric_limits<T>::digits``
# (11 for half, 24 for float, 8 for bfloat16).
_HALF_DIGITS = 11
_BFLOAT16_DIGITS = 8
_FLOAT_DIGITS = 24

# Lane-varying indices stay 32-bit on this backend, so a single launch covers
# fewer than 2**31 elements.
_MAX_I32 = 1 << 31

# Elements produced by one Philox counter value for the supported dtypes.
_PER_COUNTER = 4


@triton.jit
def _philox_uniform_kernel(
    out_ptr,
    key_ptr,
    N,
    low,
    high,
    BLOCK: tl.constexpr,
    DIGITS: tl.constexpr,
):
    """Fill ``out_ptr`` with uniform samples from a stateless Philox stream.

    ``key_ptr`` addresses a ``(seed, offset)`` pair. Element ``i`` of the output
    comes from the ``i // 4``-th Philox 4x32 counter value; each of the four
    words maps through ATen's ``uniform_real``: mask to
    ``numeric_limits<T>::digits`` bits, scale by ``2**-digits`` and affine-map
    to ``[low, high)``, mirroring ``cuda/PhiloxDistribution.cu``.
    """
    seed = tl.load(key_ptr).to(tl.uint64)
    offset = tl.load(key_ptr + 1).to(tl.uint64)
    # Scalar 64-bit arithmetic is fine on GCU300; the counter base is uniform
    # across the program. Split it so every lane-varying value below is 32-bit.
    counter_base = offset + tl.program_id(0).to(tl.int64) * BLOCK
    base_lo = (counter_base & 0xFFFFFFFF).to(tl.uint32)
    base_hi = ((counter_base >> 32) & 0xFFFFFFFF).to(tl.uint32)
    lane = tl.arange(0, BLOCK)
    c0 = base_lo + lane.to(tl.uint32)
    # 32-bit wrap of the low word must carry into the high word.
    carry = (c0 < base_lo).to(tl.uint32)
    c1 = base_hi + carry
    zero = c0 * 0
    r0, r1, r2, r3 = tl.philox(seed, c0, c1, zero, zero)

    mask = (1 << DIGITS) - 1
    divisor = 1.0 / float(1 << DIGITS)
    dtype = out_ptr.dtype.element_ty
    # ATen casts low/high to the output scalar type before computing the
    # range, so half/bfloat16 inputs quantize the endpoints (and hence the
    # generated values) to the storage precision; the arithmetic itself
    # runs in the float accumulator type.
    lo = low.to(dtype).to(tl.float32)
    hi = high.to(dtype).to(tl.float32)
    rng = hi - lo
    if DIGITS != 24:
        # c10::Half/BFloat16 operator- rounds the difference back to the
        # storage dtype before it re-enters the float arithmetic.
        rng = rng.to(dtype).to(tl.float32)
    x0 = (r0 & mask).to(tl.uint32).to(tl.float32) * divisor
    x1 = (r1 & mask).to(tl.uint32).to(tl.float32) * divisor
    x2 = (r2 & mask).to(tl.uint32).to(tl.float32) * divisor
    x3 = (r3 & mask).to(tl.uint32).to(tl.float32) * divisor
    n = N.to(tl.int32)
    base = (tl.program_id(0) * BLOCK + lane) * 4
    tl.store(out_ptr + base, (x0 * rng + lo).to(dtype), mask=base < n)
    tl.store(out_ptr + base + 1, (x1 * rng + lo).to(dtype), mask=base + 1 < n)
    tl.store(out_ptr + base + 2, (x2 * rng + lo).to(dtype), mask=base + 2 < n)
    tl.store(out_ptr + base + 3, (x3 * rng + lo).to(dtype), mask=base + 3 < n)


def _uniform_real_digits(dtype):
    if dtype == torch.float64:
        return 53
    if dtype == torch.float32:
        return _FLOAT_DIGITS
    if dtype == torch.float16:
        return _HALF_DIGITS
    return _BFLOAT16_DIGITS


def _launch(out, key, low, high):
    n = out.numel()
    if out.dtype == torch.float64:
        raise NotImplementedError("_philox_uniform_: GCU300 does not support float64")
    if n >= _MAX_I32:
        raise NotImplementedError(
            f"_philox_uniform_: GCU300 supports at most {_MAX_I32} elements "
            f"per call, got {n}"
        )
    digits = _uniform_real_digits(out.dtype)
    block = 1024
    grid = (triton.cdiv(n, block * _PER_COUNTER),)
