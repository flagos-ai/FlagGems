def _launch(x: torch.Tensor, out: torch.Tensor):
    n = x.numel()
    if n == 0:
        return out
    if n <= SMALL_N:
        block, warps = BLOCK_SMALL, WARPS_SMALL
        for limit, tile in SMALL_TILE_LEVELS:
            if n <= limit:
                block = tile
                break
    else:
        block, warps = BLOCK_BIG, WARPS_BIG
    nblocks = (n + block - 1) // block
    nprog = max(min(nblocks, _MIN_PROGRAMS), (nblocks + _ITERS - 1) // _ITERS)
    with torch_device_fn.device(x.device):
        special_modified_bessel_k1_kernel[(min(nprog, _MAX_GRID),)](
            x, out, n, BLOCK=block, num_warps=warps
        )
    return out


