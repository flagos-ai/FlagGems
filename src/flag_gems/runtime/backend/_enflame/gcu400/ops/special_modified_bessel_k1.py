    is_non_positive = x <= 0.0
    x_safe = tl.where(is_non_positive, 0.1, x)

    # ln(x/2) + gamma, via log2 so the backend can use its native log unit
    ln_term = (tl.math.log2(x_safe) - 1.0) * _LN2 + _GAMMA

    # ---- series branch (x < 0.5) -------------------------------------------
    x2 = x_safe * x_safe
    x4 = x2 * x2
    x6 = x4 * x2
    x8 = x4 * x4
    x10 = x8 * x2

    term1 = 1.0 / x_safe
    term2 = x_safe * 0.5 * (ln_term - 0.5)
    term3 = x2 * x_safe * 0.0625 * (ln_term - 5.0 / 6.0)
    term4 = x4 * x_safe * 0.0078125 * (ln_term - 23.0 / 24.0)
    term5 = x6 * x_safe * (1.0 / 2304.0) * (ln_term - 235.0 / 276.0)
    term6 = x8 * x_safe * (1.0 / 41472.0) * (ln_term - 1469.0 / 1560.0)
    term7 = x10 * x_safe * (1.0 / 74304.0) * (ln_term - 7519.0 / 7080.0)
    series_result = term1 + term2 + term3 + term4 + term5 + term6 + term7

    # ---- asymptotic branch (x > 1.5) ---------------------------------------
    r = tl.math.rsqrt(x_safe)
    u = r * r
    asymp_correction = 1.0 + u * (0.375 + u * (-0.1171875 + u * 0.1025390625))
    asymp_result = (
        _SQRT_PI_OVER_2 * r * tl.math.exp2(-x_safe * _LOG2E) * asymp_correction
    )

    blend = tl.where(
        x_safe <= 0.5,
        1.0,
        tl.where(x_safe >= 1.5, 0.0, 1.0 - (x_safe - 0.5)),
    )
    # Select *outside* the blend: x = +inf makes the series branch inf*0 = NaN
    # and must resolve to the asymptotic zero instead.
    blended = series_result * blend + asymp_result * (1.0 - blend)
    result = tl.where(
        x_safe <= 0.5,
        series_result,
        tl.where(x_safe >= 1.5, asymp_result, blended),
    )

    # x <= 0 -> NaN without a fp64 constant (IXRTC ERROR_UNSUPPORTED_CAST)
    zero = x - x
    return tl.where(is_non_positive, zero / zero, result)


