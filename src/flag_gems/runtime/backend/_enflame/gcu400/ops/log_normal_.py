U32 = tl.constexpr(2.3283064365386963e-10)  # 2^-32
A16 = tl.constexpr(9.587379924285257e-05)  # 2*pi * 2^-16 (angle fold, exact algebra)
PI = tl.constexpr(3.141592653589793)

