# GCU400 customization (2026-11-17):
# 1) Fix grid out-of-range crash: the original implementation used 1 block/CTA with BLOCK_SIZE=1024; when the element
#    count > 64Mi
#    grid.x exceeds the hard limit of 65535, aten::resize fails outright with OutOfResources (the 512Mi core bench
#    shape always crashes). Changed to the same Fixed-Grid GSL as the enflame pointwise framework: always 48 CTAs
#    (codegen config max_grid_size=(48,1,1)), each CTA strides over multiple tiles, so any scale
#    stays within the limit; the 1 block/CTA form is also measured to be 30-50x catastrophically worse on GCU (issue
#    tax).
# 2) Clamp the copy count to min(inp.numel(), out.numel()): the original implementation reads src according to
# out.numel(),
#    which reads out of bounds when growing the tensor (a RAS risk on GCU); native aten::resize semantics
#    are a linear prefix copy (the grown tail is uninitialized data); after clamping, semantics match and no
# out-of-bounds access occurs.
# 3) 2026-11-21 retune: unify the tile ladder with alias_copy (measured DMA bandwidth rises from
#    ~1.5 TB/s at a 64 KiB tile to ~1.73 TB/s at 512 KiB), so the fp32 big band moves from a 256 KiB
#    to a 512 KiB tile and the 16-bit medium/big bands stop paying the int32 widening round trip.
import logging

import torch
import triton
import triton.language as tl

from flag_gems.runtime import torch_device_fn

logger = logging.getLogger(__name__)

_FIXED_CTAS = 48  # enflame codegen max_grid_size[0]

# --- TUNING PARAMS START ---
_TINY_N = 4096
_SMALL_N = 1 << 20
_LARGE_N = 1 << 26
_LARGE_TILE_BYTES = 512 * 1024
_MEDIUM_TILE_BYTES = 256 * 1024
_SMALL_TILE_BYTES = 32 * 1024
_MEDIUM_WIDE_TILE_BYTES = 64 * 1024
_TINY_TILE = 4096
# --- TUNING PARAMS END ---


@triton.jit
def _resize_copy_kernel(
    src_ptr,
    dst_ptr,
    n_elements,
    num_tiles,
    BLOCK: tl.constexpr,
    MASKED: tl.constexpr,
    IDX64: tl.constexpr,
):
    """Grid-stride tile copy (linear prefix semantics, std::copy style)."""
    pid = tl.program_id(axis=0)
    num_ctas = tl.num_programs(axis=0)
    lane_offset = tl.arange(0, BLOCK)
    for tile_id in tl.range(pid, num_tiles, num_ctas):
        if IDX64:
            offs = tile_id.to(tl.int64) * BLOCK + lane_offset
        else:
            offs = tile_id * BLOCK + lane_offset
        if MASKED:
            mask = offs < n_elements
            tl.store(dst_ptr + offs, tl.load(src_ptr + offs, mask=mask), mask=mask)
        else:
            tl.store(dst_ptr + offs, tl.load(src_ptr + offs))


def _pick_launch(n, element_size):
    """Return (view_bytes, tile_bytes, num_warps) for this element count/width."""
    if n <= _TINY_N:
        return element_size, _TINY_TILE, 4
    if n <= _SMALL_N:
        return element_size, _SMALL_TILE_BYTES, 4
    if n >= _LARGE_N:
        return element_size, _LARGE_TILE_BYTES, 4
    if element_size == 4:
        # Medium fp32 band: 8-byte lanes keep the DMA queue full.
        return 8, _MEDIUM_WIDE_TILE_BYTES, 4
    return element_size, _MEDIUM_TILE_BYTES, 2


def _widen(t, view_bytes):
    """Reinterpret a contiguous tensor with wider lanes (pure metadata view).

    The flat view is taken first: ``Tensor.view(dtype)`` alone requires the last
    dimension to divide evenly, which fails for shapes such as 16x7x57x32x29 even
    though the total element count is even.
    """
    if view_bytes == 8:
        return t.view(-1).view(torch.int64) if t.element_size() == 4 else None
    if view_bytes == 4:
        return t.view(-1).view(torch.int32) if t.element_size() == 2 else None
    return None


def _launch_copy(inp, out, n):
    view_bytes, tile_bytes, num_warps = _pick_launch(n, inp.element_size())
    src, dst = inp, out
    if view_bytes > inp.element_size():
        # Contiguity has to hold before the flat dtype view can even be built.
        legal = inp.is_contiguous() and out.is_contiguous()
        if legal:
            wide_src, wide_dst = _widen(inp, view_bytes), _widen(out, view_bytes)
            legal = (
                wide_src is not None
                and wide_dst is not None
                and inp.data_ptr() % view_bytes == 0
                and out.data_ptr() % view_bytes == 0
            )
        if legal:
            src, dst = wide_src, wide_dst
        else:
            tile_bytes, num_warps = _MEDIUM_TILE_BYTES, 4
    block = max(tile_bytes // src.element_size(), 64)
    num_tiles = triton.cdiv(src.numel(), block)
    ncta = min(max(num_tiles, 1), _FIXED_CTAS)
    _resize_copy_kernel[(ncta, 1, 1)](
        src,
        dst,
        src.numel(),
        num_tiles,
        BLOCK=block,
        MASKED=bool(src.numel() % block),
        IDX64=bool(src.numel() >= 2**31),
        num_warps=num_warps,
    )


def resize(inp: torch.Tensor, size, memory_format=None):
    out = torch.empty(size, device=inp.device, dtype=inp.dtype)
    n_out = out.numel()
    if n_out == 0:
        return out
    n_in = inp.numel()
    if n_in == 0:
        return out
    # native aten::resize semantics: linear raw-storage prefix copy of
    # min(numel) elements into a freshly allocated contiguous tensor.
    n = n_out if n_out < n_in else n_in
    with torch_device_fn.device(inp.device):
        _launch_copy(inp, out, n)
    return out


def resize_(inp: torch.Tensor, size, memory_format=None):
    logger.debug("GEMS_ENFLAME RESIZE_")
    inp.set_(inp.untyped_storage(), 0, size)
    return inp
