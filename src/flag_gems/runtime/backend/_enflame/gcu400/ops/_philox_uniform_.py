# Launch ladder (do_bench kernel mode, median w1000/r100 for the bench shapes
# and w200/r50 for the sweep, GCU400, 2026-11-19 full resweep):
# below 16K elements every configuration sits at the ~4.2us launch floor, so
# the one-block-per-program shape wins; above that the persistent kernel runs
# at BLOCK=512 for every size and dtype, with num_warps=4 for the 4-byte
# stores and num_warps=2 for the packed 16-bit stores. The previous round
# laddered BLOCK=2048 below 2**29 on the strength of a "BLOCK=512 regresses
# 33% at 2**24" measurement; today's resweep reverses that verdict across the
# whole band (fp32: 2**15 4.6 vs 6.7us, 2**18 6.2 vs 9.4, 2**20 10.7 vs 16.4,
# 2**24 109.0 vs 152.0, 2**28 1633 vs 2245, 2**30 6481 vs 8756) and the
# 16-bit arm prefers num_warps=2 (2**20 10.4 vs 12.7, 2**24 104.3 vs 107.2,
# 2**30 6435 within noise of every healthy configuration). num_warps=1 or 2
# on the 4-byte path and num_warps=4 on the packed path lose 8-100%.
#
# The 1GiB shapes sit at a structural floor documented by the ablation ladder
# (2026-11-19, probe_ablation.py / probe_variants.py, B512/P48/nw4):
#   * store-only floor (no philox, values from the index): 6027us -- the four
#     stride-4 stores forced by the counter->word mapping cost more than
#     the philox chain itself;
#   * philox + transform + a single quarter store: 4515us;
#   * full kernel: 6498us ~= store floor + philox floor with a small overlap
#     gap. fp16 (packed, cheaper stores) lands at the same ~6.43ms, i.e. the
#     RNG arithmetic saturates the device once the stores are packed.
# Every attempt to beat the store floor failed and is recorded as rejected:
#   - packing two fp32 lanes into one uint64 store halves the store count but
#     changes nothing (6523 vs 6498us): the u64 build costs what the stores
#     save;
#   - rebuilding the block as one contiguous (BLOCK*4,) register tensor via
#     tl.join/tl.permute/tl.reshape (or a 3D value+pointer store) is
