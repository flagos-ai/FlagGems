def _philox_uniform_gcu400(
    out_ptr,
    key_ptr,
    n_elem,
    low,
    high,
    num_prog,
    BLOCK: tl.constexpr,
    DIGITS: tl.constexpr,
    PACK2: tl.constexpr,
    EVEN: tl.constexpr,
    PERSIST: tl.constexpr,
):
    """Fill ``out_ptr`` with uniform samples from a stateless Philox stream.

    Element ``i`` comes from the ``i // 4``-th Philox 4x32 counter value
    (counter = offset + i // 4, subsequence zero), word ``i % 4``, mapped
    through ATen's ``uniform_real``: mask to ``digits`` mantissa bits, scale
    by ``2**-digits`` and affine-map to ``[low, high)``. The 32-bit fast
    path is taken per launch via a runtime scalar branch; both branches
    produce identical values for the same (seed, offset).
    """
    seed = tl.load(key_ptr).to(tl.uint64)
    offset = tl.load(key_ptr + 1).to(tl.uint64)
    pid = tl.program_id(0)
    total_blocks = (n_elem + BLOCK * 4 - 1) // (BLOCK * 4)
    # uint32 fast path: the whole counter window and the flat element
    # offsets must stay inside 32 bits. Checked on the device because the
    # (seed, offset) pair lives in a device tensor; a host-side check would
    # sync every call. offset < 2**32 is implied by the first bound.
    u32_ok = (n_elem < 0x80000000) & (
        offset + total_blocks.to(tl.uint64) * BLOCK <= 0x100000000
    )
    dtype = out_ptr.dtype.element_ty
    mask = (1 << DIGITS) - 1
    divisor = 1.0 / float(1 << DIGITS)
    # ATen casts low/high to the output scalar type before computing the
    # range; c10::Half/BFloat16 operator- rounds the difference back to the
    # storage dtype before it re-enters the float arithmetic.
    lo = low.to(dtype).to(tl.float32)
    hi = high.to(dtype).to(tl.float32)
    rng = hi - lo
    if DIGITS != 24:
        rng = rng.to(dtype).to(tl.float32)

    if PERSIST:
        if u32_ok:
            for block_idx in range(pid, total_blocks, num_prog):
                chunks = block_idx * BLOCK + tl.arange(0, BLOCK).to(tl.uint32)
                c0 = offset.to(tl.uint32) + chunks
                z = c0 * 0
                r0, r1, r2, r3 = tl.philox(seed, c0, z, z, z)
                x0 = (r0 & mask).to(tl.float32) * divisor
                x1 = (r1 & mask).to(tl.float32) * divisor
                x2 = (r2 & mask).to(tl.float32) * divisor
                x3 = (r3 & mask).to(tl.float32) * divisor
                v0 = (x0 * rng + lo).to(dtype)
                v1 = (x1 * rng + lo).to(dtype)
                v2 = (x2 * rng + lo).to(dtype)
                v3 = (x3 * rng + lo).to(dtype)
                if PACK2:
                    u0 = v0.to(tl.uint16, bitcast=True).to(tl.uint32)
                    u1 = v1.to(tl.uint16, bitcast=True).to(tl.uint32)
                    u2 = v2.to(tl.uint16, bitcast=True).to(tl.uint32)
                    u3 = v3.to(tl.uint16, bitcast=True).to(tl.uint32)
                    w0 = u0 | (u1 << 16)
                    w1 = u2 | (u3 << 16)
                    wbase = chunks * 2
                    words_ptr = out_ptr.to(tl.pointer_type(tl.uint32))
                    if EVEN:
                        tl.store(words_ptr + wbase, w0)
                        tl.store(words_ptr + wbase + 1, w1)
                    else:
                        n_words = (n_elem // 2).to(tl.uint32)
                        tl.store(words_ptr + wbase, w0, mask=wbase < n_words)
                        tl.store(words_ptr + wbase + 1, w1, mask=wbase + 1 < n_words)
                else:
                    base = chunks * 4
                    if EVEN:
                        tl.store(out_ptr + base, v0)
                        tl.store(out_ptr + base + 1, v1)
                        tl.store(out_ptr + base + 2, v2)
                        tl.store(out_ptr + base + 3, v3)
                    else:
                        n32 = n_elem.to(tl.uint32)
                        tl.store(out_ptr + base, v0, mask=base < n32)
                        tl.store(out_ptr + base + 1, v1, mask=base + 1 < n32)
                        tl.store(out_ptr + base + 2, v2, mask=base + 2 < n32)
                        tl.store(out_ptr + base + 3, v3, mask=base + 3 < n32)
        else:
            for block_idx in range(pid, total_blocks, num_prog):
                chunks64 = block_idx.to(tl.int64) * BLOCK + tl.arange(0, BLOCK).to(
                    tl.int64
                )
                counter = offset + chunks64.to(tl.uint64)
                c0 = (counter & 0xFFFFFFFF).to(tl.uint32)
                c1 = ((counter >> 32) & 0xFFFFFFFF).to(tl.uint32)
                z = c0 * 0
                r0, r1, r2, r3 = tl.philox(seed, c0, c1, z, z)
                x0 = (r0 & mask).to(tl.float32) * divisor
                x1 = (r1 & mask).to(tl.float32) * divisor
                x2 = (r2 & mask).to(tl.float32) * divisor
                x3 = (r3 & mask).to(tl.float32) * divisor
                v0 = (x0 * rng + lo).to(dtype)
                v1 = (x1 * rng + lo).to(dtype)
                v2 = (x2 * rng + lo).to(dtype)
                v3 = (x3 * rng + lo).to(dtype)
                base64 = chunks64 * 4
                tl.store(out_ptr + base64, v0, mask=base64 < n_elem)
                tl.store(out_ptr + base64 + 1, v1, mask=base64 + 1 < n_elem)
                tl.store(out_ptr + base64 + 2, v2, mask=base64 + 2 < n_elem)
                tl.store(out_ptr + base64 + 3, v3, mask=base64 + 3 < n_elem)
    else:
        if u32_ok:
            chunks = pid * BLOCK + tl.arange(0, BLOCK).to(tl.uint32)
            c0 = offset.to(tl.uint32) + chunks
            z = c0 * 0
            r0, r1, r2, r3 = tl.philox(seed, c0, z, z, z)
            x0 = (r0 & mask).to(tl.float32) * divisor
            x1 = (r1 & mask).to(tl.float32) * divisor
            x2 = (r2 & mask).to(tl.float32) * divisor
            x3 = (r3 & mask).to(tl.float32) * divisor
            v0 = (x0 * rng + lo).to(dtype)
            v1 = (x1 * rng + lo).to(dtype)
            v2 = (x2 * rng + lo).to(dtype)
            v3 = (x3 * rng + lo).to(dtype)
            if PACK2:
                u0 = v0.to(tl.uint16, bitcast=True).to(tl.uint32)
                u1 = v1.to(tl.uint16, bitcast=True).to(tl.uint32)
                u2 = v2.to(tl.uint16, bitcast=True).to(tl.uint32)
                u3 = v3.to(tl.uint16, bitcast=True).to(tl.uint32)
                w0 = u0 | (u1 << 16)
                w1 = u2 | (u3 << 16)
                wbase = chunks * 2
                words_ptr = out_ptr.to(tl.pointer_type(tl.uint32))
                if EVEN:
                    tl.store(words_ptr + wbase, w0)
                    tl.store(words_ptr + wbase + 1, w1)
                else:
                    n_words = (n_elem // 2).to(tl.uint32)
                    tl.store(words_ptr + wbase, w0, mask=wbase < n_words)
                    tl.store(words_ptr + wbase + 1, w1, mask=wbase + 1 < n_words)
            else:
                base = chunks * 4
                if EVEN:
                    tl.store(out_ptr + base, v0)
                    tl.store(out_ptr + base + 1, v1)
                    tl.store(out_ptr + base + 2, v2)
                    tl.store(out_ptr + base + 3, v3)
                else:
                    n32 = n_elem.to(tl.uint32)
                    tl.store(out_ptr + base, v0, mask=base < n32)
                    tl.store(out_ptr + base + 1, v1, mask=base + 1 < n32)
                    tl.store(out_ptr + base + 2, v2, mask=base + 2 < n32)
                    tl.store(out_ptr + base + 3, v3, mask=base + 3 < n32)
        else:
            chunks64 = pid.to(tl.int64) * BLOCK + tl.arange(0, BLOCK).to(tl.int64)
            counter = offset + chunks64.to(tl.uint64)
            c0 = (counter & 0xFFFFFFFF).to(tl.uint32)
            c1 = ((counter >> 32) & 0xFFFFFFFF).to(tl.uint32)
            z = c0 * 0
            r0, r1, r2, r3 = tl.philox(seed, c0, c1, z, z)
            x0 = (r0 & mask).to(tl.float32) * divisor
            x1 = (r1 & mask).to(tl.float32) * divisor
            x2 = (r2 & mask).to(tl.float32) * divisor
            x3 = (r3 & mask).to(tl.float32) * divisor
            v0 = (x0 * rng + lo).to(dtype)
            v1 = (x1 * rng + lo).to(dtype)
            v2 = (x2 * rng + lo).to(dtype)
            v3 = (x3 * rng + lo).to(dtype)
            base64 = chunks64 * 4
            tl.store(out_ptr + base64, v0, mask=base64 < n_elem)
            tl.store(out_ptr + base64 + 1, v1, mask=base64 + 1 < n_elem)
            tl.store(out_ptr + base64 + 2, v2, mask=base64 + 2 < n_elem)
            tl.store(out_ptr + base64 + 3, v3, mask=base64 + 3 < n_elem)


@triton.jit(do_not_specialize=["n_elem", "num_prog"])
def _philox_uniform_f64_gcu400(
    out_ptr,
    key_ptr,
    n_elem,
    low,
    high,
    num_prog,
    BLOCK: tl.constexpr,
):
    """float64 arm: two samples per counter, 64-bit counter math, grid-stride.

    Kept for ATen parity; gcu400 has no fp64 arithmetic, so this kernel is
    never exercised by the accuracy suite on this target (fp64 is filtered
    from the test dtypes). The counter math mirrors the generic
    implementation exactly.
    """
    seed = tl.load(key_ptr).to(tl.uint64)
    offset = tl.load(key_ptr + 1).to(tl.uint64)
    pid = tl.program_id(0)
    total_blocks = (n_elem + BLOCK * 2 - 1) // (BLOCK * 2)
    lo = low.to(tl.float64)
    hi = high.to(tl.float64)
    rng = hi - lo
    for block_idx in range(pid, total_blocks, num_prog):
        chunks = block_idx.to(tl.int64) * BLOCK + tl.arange(0, BLOCK).to(tl.int64)
        counter = offset + chunks.to(tl.uint64)
        c0 = (counter & 0xFFFFFFFF).to(tl.uint32)
        c1 = ((counter >> 32) & 0xFFFFFFFF).to(tl.uint32)
        z = c0 * 0
        r0, r1, r2, r3 = tl.philox(seed, c0, c1, z, z)
        # Each double consumes one full Philox result: two uint32 words
        # packed into a 64-bit value, of which the low 53 mantissa bits
        # survive.
        w0 = ((r0.to(tl.uint64) << 32) | r1.to(tl.uint64)) & 0x1FFFFFFFFFFFFF
        w1 = ((r2.to(tl.uint64) << 32) | r3.to(tl.uint64)) & 0x1FFFFFFFFFFFFF
        base = chunks * 2
        tl.store(
            out_ptr + base,
            w0.to(tl.float64) * 1.1102230246251565e-16 * rng + lo,
            mask=base < n_elem,
        )
        tl.store(
            out_ptr + base + 1,
            w1.to(tl.float64) * 1.1102230246251565e-16 * rng + lo,
            mask=base + 1 < n_elem,
        )


def _uniform_real_digits(dtype):
    if dtype == torch.float64:
        return _DOUBLE_DIGITS
    if dtype == torch.float32:
        return _FLOAT_DIGITS
    if dtype == torch.float16:
        return _HALF_DIGITS
    return _BFLOAT16_DIGITS


def _launch(out, key, low, high):
    n = out.numel()
    if out.dtype == torch.float64:
        block = _F64_BLOCK
        grid = min(triton.cdiv(n, block * 2), _MAX_GRID_X)
        with torch_device_fn.device(out.device):
            _philox_uniform_f64_gcu400[(grid,)](
                out,
                key,
                n,
                float(low),
                float(high),
                grid,
                BLOCK=block,
                num_warps=4,
            )
        return

    digits = _uniform_real_digits(out.dtype)
    is_16bit = out.dtype in (torch.float16, torch.bfloat16)
    pack2 = is_16bit and n % 2 == 0 and n >= _PACK2_MIN_NUMEL
    if n <= _SMALL_MAX_NUMEL:
        block = _SMALL_BLOCK
        grid = triton.cdiv(n, block * 4)
        with torch_device_fn.device(out.device):
            _philox_uniform_gcu400[(grid,)](
                out,
                key,
                n,
                float(low),
                float(high),
                grid,
                BLOCK=block,
                DIGITS=digits,
                PACK2=pack2,
                EVEN=n % (block * 4) == 0,
                PERSIST=False,
                num_warps=_SMALL_NUM_WARPS,
            )
        return

    if is_16bit:
        block = _PERSIST_BLOCK_16BIT
        warps = _PERSIST_NUM_WARPS_16BIT
    else:
        block = _PERSIST_BLOCK_32BIT
        warps = _PERSIST_NUM_WARPS_32BIT
    grid = min(triton.cdiv(n, block * 4), _PERSIST_NUM_PROG)
    with torch_device_fn.device(out.device):
        _philox_uniform_gcu400[(grid,)](
            out,
            key,
            n,
            float(low),
            float(high),
            grid,
            BLOCK=block,
            DIGITS=digits,
            PACK2=pack2,
            EVEN=n % (block * 4) == 0,
            PERSIST=True,
            num_warps=warps,
        )


def _check_args(self, key):
    if not self.is_floating_point():
        raise RuntimeError(
            f"_philox_uniform_: self must be a floating point tensor, got {self.dtype}"
        )
    if key.dtype != torch.uint64:
        raise RuntimeError(
            f"_philox_uniform_: key must have dtype uint64, got {key.dtype}"
        )
    if self.device != key.device:
        raise RuntimeError(
            f"_philox_uniform_: self and key must be on the same device, got "
            f"{self.device} and {key.device}"
        )
    if key.dim() < 1 or key.size(-1) != 2:
        raise RuntimeError(
            f"_philox_uniform_: key must have shape (2,) or (*batch, 2), got "
            f"{tuple(key.shape)}"
        )
    if key.dim() > 1 and key.dim() != self.dim() + 1:
        raise RuntimeError(
            f"_philox_uniform_: batched key must have ndim == output ndim + 1, got "
            f"key shape {tuple(key.shape)} with output shape {tuple(self.shape)}"
        )


def _batched_key_plan(out, key):
    """Split a batched key into per-key output blocks and key indices.

    ATen derives the elements one key owns by counting the output's trailing
    dimensions that the key leaves unsized (``key.size(i) == 1``); a key with
    shape ``(4, 1, 1, 2)`` against output ``(4, 10, 100)`` therefore feeds 1000
    elements. The remaining key dimensions broadcast, so the key index for a
    block is the flat index of a zero-based multi-index along those dims.
    """
    elems_per_key = 1
    key_dims = out.dim()
    for i in range(out.dim() - 1, -1, -1):
        if key.size(i) != 1:
            break
        elems_per_key *= out.size(i)
        key_dims -= 1

    key_batch = tuple(key.shape[:key_dims])
    out_batch = tuple(out.shape[:key_dims])
    for ks, os_ in zip(key_batch, out_batch):
        if ks != os_ and ks != 1:
            raise RuntimeError(
                f"_philox_uniform_: key batch shape {key_batch} is not "
                f"broadcastable with output shape {out_batch}"
            )

    num_blocks = out.numel() // elems_per_key
    # Walk the batch dims in output order, advancing the key's flat index only
    # where the key is actually sized (broadcast dims keep their index).
    strides = []
    acc = 1
    for ks in reversed(key_batch):
        strides.append(0 if ks == 1 else acc)
        acc *= ks
    strides.reverse()

    block = []
    for b in range(num_blocks):
        idx = 0
        rem = b
        for dim in range(key_dims - 1, -1, -1):
            size = out_batch[dim]
            coord = rem % size if size else 0
            rem //= size if size else 1
            idx += coord * strides[dim]
        block.append(idx)
    return elems_per_key, block


def _philox_uniform_(self, key, low=0.0, high=1.0):
    logger.debug("GEMS_ENFLAME _PHILOX_UNIFORM_")
    _check_args(self, key)
    if self.numel() == 0:
        return self

    key = key.contiguous()
    # Non-contiguous outputs are filled through a contiguous staging buffer and
    # copied back, so the kernel can rely on plain linear indexing.
    contiguous = self.is_contiguous()
    out = self if contiguous else self.contiguous()

    if key.dim() == 1:
        _launch(out, key, low, high)
    else:
        elems_per_key, block_keys = _batched_key_plan(out, key)
        key_flat = key.reshape(-1, 2)
        out_flat = out.reshape(-1, elems_per_key)
        for block_idx, key_idx in enumerate(block_keys):
            _launch(out_flat[block_idx], key_flat[key_idx], low, high)

    if not contiguous:
        self.copy_(out)
    return self


