# keeps pointing at the generic implementation -- whose uncapped grid cannot
# launch the benchmark's 1Gi-element shapes at all. Publish this module over
# the generic package attribute (the same pattern as ``conj_physical`` /
# ``_conj_physical`` / ``_linalg_det``) so every entry point resolves to the
# implementation that actually runs on this backend.
