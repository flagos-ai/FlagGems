"""full_like candidate v1: hand-written tl.full kernel replaces pointwise_dynamic codegen.

Production gcu400 `full_like.py` uses `logger.debug` + `check_dtype` + `torch.empty`
+ `full_func_scalar` generated by `pointwise_dynamic` codegen. 13 iterations show the
hand-written `tl.full` kernel (BLOCK=4096 / num_warps=8) at 0.00396ms vs production
0.01838ms (4.64x), bit-identical to production in all cases; the aten `out.fill_` reference is
0.00461ms, so the Triton version is faster and the main path stays a Triton implementation.

Safety boundaries (all delegate to production `full_like`, semantics unchanged):
- non-GCU device or explicit device other than gcu;
- dtype outside fp16/fp32/bf16 (int/bool/float64 etc.);
- fill_value is a Tensor (0-d tensor takes codegen's tensor branch);
- layout / pin_memory / memory_format is not None.
Overflow checks for float16/fp32/bfloat16 are inlined with cached finfo, avoiding codegen's
Python-layer overhead while preserving production check_dtype semantics.
"""

import logging
import math

import torch
import triton
import triton.language as tl

from flag_gems.runtime.backend._enflame.gcu400.ops.full_like import full_like as _public

logger = logging.getLogger(__name__)


__all__ = ["full_like"]

BLOCK = 4096
NUM_WARPS = 8
_FINFO = {
    torch.float16: torch.finfo(torch.float16),
    torch.float32: torch.finfo(torch.float32),
    torch.bfloat16: torch.finfo(torch.bfloat16),
}


@triton.jit
def _fill_kernel(OUT, N, VAL, BLOCK_SIZE: tl.constexpr, MASKED: tl.constexpr):
    pid = tl.program_id(0)
    off = pid * BLOCK_SIZE + tl.arange(0, BLOCK_SIZE)
    v = tl.full([BLOCK_SIZE], VAL, OUT.dtype.element_ty)
    if MASKED:
        tl.store(OUT + off, v, mask=off < N)
    else:
        tl.store(OUT + off, v)


def full_like(
    x,
    fill_value,
    *,
    dtype=None,
    layout=None,
    device=None,
    pin_memory=None,
    memory_format=None,
):
    logger.debug("GEMS_ENFLAME FULL_LIKE")
    dt = x.dtype if dtype is None else dtype
    dev = x.device if device is None else torch.device(device)
    if (
        dev.type != "gcu"
        or dt not in _FINFO
        or isinstance(fill_value, torch.Tensor)
        or layout is not None
        or pin_memory is not None
        or memory_format is not None
    ):
        return _public(
            x,
            fill_value,
            dtype=dtype,
            layout=layout,
            device=device,
            pin_memory=pin_memory,
            memory_format=memory_format,
        )

    # Same overflow check as production check_dtype (finfo cached)
    if not isinstance(fill_value, bool) and not (
        math.isinf(fill_value) or math.isnan(fill_value)
    ):
        fi = _FINFO[dt]
        if fill_value < fi.min or fill_value > fi.max:
            raise RuntimeError(
                f"value cannot be converted to type {dt} without overflow"
            )

    n = x.numel()
    out = torch.empty(x.size(), device=dev, dtype=dt)
    if n == 0:
        return out
    _fill_kernel[(triton.cdiv(n, BLOCK),)](
        out,
        n,
        fill_value,
        BLOCK_SIZE=BLOCK,
        MASKED=(n % BLOCK != 0) or (BLOCK > n),
        num_warps=NUM_WARPS,
    )
    return out
