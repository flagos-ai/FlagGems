"""Batched matrix inverse (linalg_inv) in Triton.

Algorithm: in-register Gauss-Jordan elimination with partial (row) pivoting on
the augmented system [A | I].  One program instance owns one full matrix:
a (BLOCK_N, BLOCK_N) register tile `a` for the (evolving) left block and a
second register tile `x` initialized to the identity and evolved into A^{-1}.

At step k we select p = argmax_{active, i < N} |a[i, k]| together with the
signed pivot value a[p, k] in a single tuple reduction, form
factor_i = a[i, k] * (1/a[p, k]) for i != p, apply row rank-1 updates to both
the `a` and the `x` tiles, then write the scaled pivot row.  Rows already used
as pivots still receive the rank-1 update (that is what zeroes their column-k
entry) but are excluded from later pivot searches via the `used` mask.

After N steps physical row p_k of `x` holds logical inverse row k.  The inverse
scatter permutation is built directly (`pos[p_k] = k`), so the store writes
`x[j, :]` to output row `pos[j]`.

Latency-oriented choices (profiling of the previous round showed the kernel is
latency bound on the per-step dependency chain, not bandwidth or issue bound):
  * the pivot search and the pivot-value extraction are fused into ONE tuple
    reduction instead of separate argmax + masked-sum collectives;
  * the pivot row is written by a single select that also carries the rank-1
    update for every other row (no separate "zero the factor at the pivot"
    select and no separate full-vector "mask padded rows" select);
  * the per-row normalisation uses one reciprocal plus multiplies instead of
    a BLOCK_N-wide division.

No tl.dot is used anywhere, so the TF32 hazard of the default fp32 dot path is
irrelevant here.  Everything runs in fp64 when the input is fp64.
"""

import torch
import triton
import triton.language as tl


@triton.jit
def _pick_max_mag(mx, ix, vx, my, iy, vy):
    """Combine for a (|value|, index, signed value) tuple reduction."""
    take = mx > my
    return tl.where(take, mx, my), tl.where(take, ix, iy), tl.where(take, vx, vy)


@triton.jit
def _inv_kernel(
    A_ptr,
    O_ptr,
    N,
    str_r,
    str_c,
    str_or,
    str_oc,
    tiny,
    R: tl.constexpr,
    d0,
    d1,
    d2,
    d3,
    e0,
    e1,
    e2,
    e3,
    IS64: tl.constexpr,
    IS16: tl.constexpr,
    ISBF16: tl.constexpr,
    BLOCK_N: tl.constexpr,
):
    pid = tl.program_id(0)
    rem = pid.to(tl.int64)
    off = rem * 0
    if R >= 1:
        off += (rem % d0) * e0
        rem = rem // d0
    if R >= 2:
        off += (rem % d1) * e1
        rem = rem // d1
    if R >= 3:
        off += (rem % d2) * e2
        rem = rem // d2
    if R >= 4:
        off += (rem % d3) * e3
        rem = rem // d3

    offs_r = tl.arange(0, BLOCK_N)
    offs_c = tl.arange(0, BLOCK_N)
    rows_ok = offs_r < N
    cols_ok = offs_c < N
    m2 = rows_ok[:, None] & cols_ok[None, :]
    diag = offs_r[:, None] == offs_c[None, :]

    a_ptrs = A_ptr + off + offs_r[:, None] * str_r + offs_c[None, :] * str_c
    a = tl.load(a_ptrs, mask=m2, other=0.0)

    if IS64:
        a = a.to(tl.float64)
    elif IS16 or ISBF16:
        a = a.to(tl.float32)

    idt = tl.where(m2 & diag, 1.0, 0.0)
    if IS64:
        x = idt.to(tl.float64)
    else:
        x = idt.to(tl.float32)

    used = tl.zeros((BLOCK_N,), dtype=tl.int32)
    pos = tl.zeros((BLOCK_N,), dtype=tl.int32)
    z_a = a * 0.0
    z_x = x * 0.0
    idx_f = offs_r.to(a.dtype)

    for k in range(0, N):
        # column k of the working block
        colk = tl.sum(tl.where(offs_c[None, :] == k, a, z_a), axis=1)
        valid = rows_ok & (used == 0)
        mag = tl.where(valid, tl.abs(colk), -1.0)
        # ONE collective returns the winning magnitude, its row index and the
        # signed pivot value.
        mag, p_f, piv = tl.reduce((mag, idx_f, colk), 0, _pick_max_mag)
        p = p_f.to(tl.int32)

        denom = tl.where(tl.abs(piv) < tiny, 1.0, piv)
        if IS64:
            # fp32 seed + two fp64 Newton steps: reaches fp64-accurate
            # reciprocal without the long emulated fp64 divide sequence that
            # profiling showed dominating the fp64 instruction stream.
            d32 = denom.to(tl.float32)
            r = (1.0 / d32).to(tl.float64)
            r = r * (2.0 - denom * r)
            inv = r * (2.0 - denom * r)
        else:
            inv = 1.0 / denom

        factor = colk * inv
        ap = tl.sum(tl.where((offs_r == p)[:, None], a, z_a), axis=0)
        xp = tl.sum(tl.where((offs_r == p)[:, None], x, z_x), axis=0)

        sel = (offs_r == p)[:, None]
        aps = ap * inv
        xps = xp * inv
        a = tl.where(sel, aps[None, :], a - factor[:, None] * ap[None, :])
        x = tl.where(sel, xps[None, :], x - factor[:, None] * xp[None, :])

        used = used | tl.where(offs_r == p, 1, 0)
        pos = tl.where(offs_r == p, k, pos)

    o_ptrs = O_ptr + off + pos[:, None] * str_or + offs_c[None, :] * str_oc
    if IS64 or (not IS16 and not ISBF16):
        tl.store(o_ptrs, x, mask=m2)
    elif IS16:
        tl.store(o_ptrs, x.to(tl.float16), mask=m2)
    else:
        tl.store(o_ptrs, x.to(tl.bfloat16), mask=m2)


def _collapse(shape, strides):
    """Collapse consecutive batch dims that are uniformly strided (innermost first)."""
    dims = []
    strs = []
    acc = 1
    for D, S in zip(reversed(shape), reversed(strides)):
        if dims and S == acc * strs[-1]:
            dims[-1] *= D
            acc *= D
        else:
            dims.append(D)
            strs.append(S)
            acc = D
    return dims, strs


def linalg_inv(A):
    # Without these guards a non-square or 1-D input silently flows through the
    # batch reshape and produces a finite but meaningless result, where ATen
    # raises.  Low-precision dtypes are rejected for the same reason ATen
    # rejects them: the pivoted elimination cannot hold accuracy in half.
    if A.dim() < 2:
        raise RuntimeError(
            "linalg.inv: The input tensor A must have at least 2 dimensions."
        )
    if A.shape[-1] != A.shape[-2]:
        raise RuntimeError(
            "linalg.inv: A must be batches of square matrices, but they are "
            "%d by %d matrices" % (A.shape[-2], A.shape[-1])
        )
    if A.dtype in (torch.float16, torch.bfloat16):
        raise RuntimeError(
            "linalg.inv: Low precision dtypes not supported. Got %s"
            % ("Half" if A.dtype == torch.float16 else "BFloat16")
        )
    N = A.shape[-1]
    out = torch.empty(A.shape, dtype=A.dtype, device=A.device)

    batch_shape = tuple(A.shape[:-2])
    B = 1
    for s in batch_shape:
        B *= int(s)
    if B == 0 or N == 0 or A.numel() == 0:
        return out

    if A.is_contiguous():
        str_r = N
        str_c = 1
        if batch_shape:
            dims, strs = [B], [N * N]
        else:
            dims, strs = [], []
    else:
        st = A.stride()
        str_r = int(st[-2])
        str_c = int(st[-1])
        dims, strs = _collapse(batch_shape, st[:-2])

    R = len(dims)
    if R > 4:
        # Uniformly-strided collapse failed; refuse rather than silently mis-index.
        raise RuntimeError("unsupported batch layout for linalg_inv kernel")

    padded_d = list(dims) + [1] * (4 - R)
    padded_e = list(strs) + [0] * (4 - R)

    BLOCK_N = max(1, triton.next_power_of_2(N))
    if BLOCK_N <= 8:
        num_warps = 1
    elif BLOCK_N <= 32:
        num_warps = 2
    elif BLOCK_N <= 64:
        num_warps = 4
    else:
        num_warps = 8

    dt = A.dtype
    is64 = dt == torch.float64
    is16 = dt == torch.float16
    isbf16 = dt == torch.bfloat16
    tiny = 1e-30

    grid = (B,)
    _inv_kernel[grid](
        A,
        out,
        N,
        str_r,
        str_c,
        N,
        1,
        tiny,
        R=R,
        d0=padded_d[0],
        d1=padded_d[1],
        d2=padded_d[2],
        d3=padded_d[3],
        e0=padded_e[0],
        e1=padded_e[1],
        e2=padded_e[2],
        e3=padded_e[3],
        IS64=is64,
        IS16=is16,
        ISBF16=isbf16,
        BLOCK_N=BLOCK_N,
        num_warps=num_warps,
        num_stages=1,
    )
    return out


