    # Promote 1-D diagonals and scalar offsets to the native 2-D/1-D forms.
    diagonals_2d = diagonals.unsqueeze(0) if diagonals.dim() == 1 else diagonals
    offsets_1d = offsets.unsqueeze(0) if offsets.dim() == 0 else offsets

    if diagonals_2d.dim() != 2:
        raise RuntimeError("Diagonals must be vector or matrix")
    if offsets_1d.dim() != 1:
        raise RuntimeError("Offsets must be scalar or vector")
    if len(shape) != 2:
        raise RuntimeError("Output shape must be 2d")

    if layout is not None and layout not in (
        torch.sparse_coo,
        torch.sparse_csr,
        torch.sparse_csc,
    ):
        raise RuntimeError(
            "Only output layouts (Sparse, SparseCsc, SparseCsr) are supported, "
            f"got {layout}"
        )

    if offsets_1d.dtype != torch.int64:
        raise RuntimeError(
            f"Offset Tensor must have dtype Long but got {offsets_1d.dtype}"
        )

    if diagonals_2d.dtype in _UNSUPPORTED_DTYPES:
        raise RuntimeError(
            f"spdiags with {diagonals_2d.dtype} diagonals is not supported on "
            "the enflame backend: GCU has no 64-bit or complex floating point"
        )

    num_diags = diagonals_2d.shape[0]
    diag_len = diagonals_2d.shape[1]
    nrows, ncols = shape

    if offsets_1d.shape[0] != num_diags:
        raise RuntimeError(
            f"Number of diagonals ({num_diags}) does not match "
            f"the number of offsets ({offsets_1d.shape[0]})"
        )

    # Handle empty case
    if num_diags == 0 or diag_len == 0 or nrows == 0 or ncols == 0:
        return _empty_result(diagonals, shape, layout)

    diagonals_contig = diagonals_2d.contiguous()
    offsets_contig = offsets_1d.contiguous()
    numel_max = num_diags * diag_len
    if numel_max > 0x7FFFFFFF:
        raise RuntimeError(
            f"spdiags input has {numel_max} elements, exceeding the supported 2^31 - 1"
        )

    # GCU's Triton backend steps an int64 pointer by four bytes per element, so
    # an int64 offsets load reads the wrong half of every entry: the kernel has
    # to consume int32 offsets. The narrow is lossless because torch_gcu already
    # replaces Long with Int (``torch.tensor([2**40 + 5], dtype=int64,
    # device="gcu")`` reads back as 5), so int64 device tensors hold nothing
    # beyond the low word anyway. ``view(torch.int32)`` would avoid this extra
    # op but is unusable: torch_gcu does not reinterpret bytes there, it casts
    # and leaves the tail uninitialized.
    offsets_i32 = offsets_contig.to(torch.int32)

    # The generic path compacts with a nonzero + index_select chain whose
    # int64 cumsum scan aborts the GCU runtime. Here the kernel writes the
    # compacted COO directly: one blocking offsets read (the output size is
    # data-dependent, so a device-to-host sync is unavoidable), one kernel,
    # no scratch, no compaction.
    #
    # Fast path (num_diags <= grid.y limit): enqueue everything before
    # blocking on the offsets read - the kernel derives the column-block
    # base itself, so only the read itself stays inside the sync window.
    if num_diags <= _MAX_GRID_Y:
        try:
            stage, sync_event = _get_pinned_stage()
        except Exception:
            stage = None
        if stage is not None:
            stage[:num_diags].copy_(offsets_i32, non_blocking=True)
            sync_event.record()
            n_blocks, block_size = _launch_grid(diag_len)
            # int32 staging: GCU cannot address or store int64, so the kernel
            # writes int32 rows/columns and the host widens them once.
            indices_flat = torch.empty(
                (2 * numel_max,), dtype=torch.int32, device=diagonals.device
            )
            values_buf = torch.empty(
                (numel_max,), dtype=diagonals.dtype, device=diagonals.device
            )
            with torch_device_fn.device(diagonals.device):
                spdiags_kernel[(n_blocks, num_diags)](
                    diagonals_contig,
                    offsets_i32,
                    indices_flat,
                    values_buf,
                    0,
                    0,
                    0,
                    num_chunk=num_diags,
                    diag_len=diag_len,
                    nrows=nrows,
                    ncols=ncols,
                    OFF_PAD=max(_MIN_OFF_PAD, triton.next_power_of_2(num_diags)),
                    BLOCK_SIZE=block_size,
                    INLINE_NNZ=True,
                    num_warps=4,
                )
            sync_event.synchronize()
            offsets_host = stage[:num_diags].tolist()
            # Duplicate detection + valid-entry accounting in one pass.
            nnz = 0
            seen = set()
            for off in offsets_host:
                if off in seen:
                    raise RuntimeError("Offset tensor contains duplicate values")
                seen.add(off)
                lo = off if off > 0 else 0
                hi = min(diag_len, ncols, nrows + off)
                if hi > lo:
                    nnz += hi - lo
            if nnz == 0:
                return _empty_result(diagonals, shape, layout)
            if nnz > 0x7FFFFFFF:
                raise RuntimeError(
                    f"spdiags result has {nnz} nonzeros, exceeding the supported 2^31 - 1"
                )
            indices = indices_flat[: 2 * nnz].to(torch.int64).view(2, nnz)
            values = values_buf[:nnz]
