        if EVEN_N:
            self_v = tl.load(self_ptr + off)
            target_v = tl.load(target_ptr + off)
        else:
            mask = off < N_total
            self_v = tl.load(self_ptr + off, mask=mask, other=0.0)
            target_v = tl.load(target_ptr + off, mask=mask, other=0.0)
        self_f = self_v.to(tl.float32)
        target_f = target_v.to(tl.float32)
        # aten: grad = grad_output * (-target) / (1 + exp(target * self)),
        # computed in fp32 opmath for half/bfloat16 inputs.
        # 1/(1+exp(z)) == sigmoid(-z): one sigmoid builtin replaces exp+divide. Interleaved
        # A/B (min-of-4, 2026-11-19) measured fp32 2**30 1.31x, fp16 2**30 1.13x, fp16 2**28
        # 1.38x, fp16 2**22 1.16x and fp32 2**22 1.11x, and it removes the bimodal slow tier of
        # the exp form (the same kernel re-run at 8.4ms/15.3ms); relative error <= 3.9e-7
        # (bit-identical for fp16 inputs).
        grad = -target_f * tl.sigmoid(-(target_f * self_f))
