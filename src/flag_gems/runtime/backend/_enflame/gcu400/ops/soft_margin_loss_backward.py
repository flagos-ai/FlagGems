    # (soft_margin_loss / smooth_l1_loss / mse_loss_backward family form).
    # The grid-stride loop keeps grid.x <= NUM_SIPS * 4, so the GCU 65535
    # grid.x limit can never be hit; the one-block-per-program KernelGen
    # layout launched 1048576 programs for 2**30 elements (BLOCK=1024) and
    # raised OutOfResources (P19).  EVEN_N elides the per-element mask; the
    # host A/B (see _backward_config) picks masked vs mask-free per bucket
    # because the win flips between datatypes and cache regimes on this
    # backend.  The mean scaling is applied as a host-precomputed
    # reciprocal multiply (the per-element vector division on this backend
    # is a reciprocal approximation + Newton step; for power-of-two N the
    # multiply is bitwise equal to the division, otherwise within 1 ulp -
    # the same trade smooth_l1_loss / mse_loss_backward make).
