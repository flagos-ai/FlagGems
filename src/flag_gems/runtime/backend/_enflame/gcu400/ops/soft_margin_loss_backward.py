def _backward_config(n_elements, itemsize):
    """(BLOCK_SIZE, num_warps, num_stages, grid_cap, force_masked) ladder.

    DSM per program: 4 streams * BLOCK * itemsize (3 loads + 1 store); every
    bucket below stays at or under the 512KB/CTA 4-stream point where the
    mse_loss_backward band calibration saw bandwidth saturate (16-bit 65536
    -> 512KB, fp32 32768 -> 512KB), far under the 917504B dsm hard limit.

    force_masked: do_bench A/B (official w1000/r100 median, two interleaved
    rounds, 2026-11-17) shows the masked code path is FASTER for every
    16-bit bucket on this op (2^30 fp16 3633 vs 3783us, 2^22 28.6 vs 29.5)
    and for the fp32 L2-regime 2^24 bucket (120.9 vs 127.8us), while fp32
    DRAM-regime shapes want the mask-free path when N divides (2^30 fp32
    6287 vs 8609us) - so fp32 keeps even = (n % BLOCK == 0) there.
    """
    if itemsize >= 4:
        if n_elements <= 4096:
            return triton.next_power_of_2(max(n_elements, 1)), 4, 3, NUM_SIPS * 2, False
        if n_elements <= (1 << 22):
            return 8192, 4, 3, NUM_SIPS * 2, False
        if n_elements <= (1 << 24):
            return 4096, 4, 3, NUM_SIPS * 2, True
        if n_elements <= (1 << 26):
            return 8192, 4, 3, NUM_SIPS * 2, False
        return 32768, 2, 2, NUM_SIPS * 2, False
    if n_elements <= 4096:
        return triton.next_power_of_2(max(n_elements, 1)), 4, 3, NUM_SIPS * 2, True
    if n_elements <= (1 << 22):
        return 8192, 2, 3, NUM_SIPS * 2, True
    if n_elements <= (1 << 24):
        return 32768, 2, 3, NUM_SIPS * 2, True
    return 65536, 2, 3, NUM_SIPS * 2, True


