def _low_words(t):
    """Flat int32 view of an int64 tensor.

    This backend stores int64 as ONE dense int32 word per element (the value
    lives in word i, not word 2i), so element i is read at word offset i.
    """
    n = t.numel()
    if t.is_contiguous():
        return t.view(-1).view(torch.int32)[:n]
    st = t.untyped_storage()
    v = torch.empty(0, dtype=torch.int32, device=t.device)
    v = v.set_(st, 0, (st.size() // 4,), (1,))
    off = t.storage_offset()
    return v[off : off + n]


def _f32_words(t):
    """Flat float32 view of the dense value words of a float64 tensor."""
    if t.is_contiguous():
        return t.view(-1).view(torch.float32)
    st = t.untyped_storage()
    v = torch.empty(0, dtype=torch.float32, device=t.device)
    v = v.set_(st, 0, (st.size() // 4,), (1,))
    off = t.storage_offset()
    return v[off:] if off else v


def _eff_strides(t, out_shape):
    lead = len(out_shape) - t.dim()
    st = []
    for i in range(len(out_shape)):
        j = i - lead
        if j < 0 or t.size(j) == 1:
            st.append(0)
        else:
            st.append(t.stride(j))
    return st


def _collapse(sizes, xs, ns):
    cs, cx, cn = [], [], []
    for i in range(len(sizes) - 1, -1, -1):
        if cs and xs[i] == cx[-1] * cs[-1] and ns[i] == cn[-1] * cs[-1]:
            cs[-1] *= sizes[i]
        else:
            cs.append(sizes[i])
            cx.append(xs[i])
            cn.append(ns[i])
    return cs[::-1], cx[::-1], cn[::-1]


def special_hermite_polynomial_h(x, n):
    logger.debug("GEMS SPECIAL_HERMITE_POLYNOMIAL_H")
    if not isinstance(x, torch.Tensor):
        raise ValueError("First argument must be a tensor")
    if x.dtype not in (torch.float32, torch.float64):
        raise ValueError("Unsupported dtype %s" % (x.dtype,))

    n_is_tensor = isinstance(n, torch.Tensor)
    deg_scalar = 0
    if n_is_tensor:
        if n.shape == x.shape:
            out_shape = x.shape
        else:
            out_shape = torch.broadcast_shapes(x.shape, n.shape)
        ndeg = n
    elif isinstance(n, (bool, int, float)):
        deg_scalar = int(n)
        if deg_scalar < 0 or deg_scalar > _MAX_DEG:
            raise ValueError(
                "special_hermite_polynomial_h only supports n in [0, 9], "
                "got n=%s" % (n,)
            )
        out_shape = x.shape
        ndeg = None
    else:
        raise ValueError("Second argument must be a Tensor or a number")

    wordify = x.dtype is torch.float64
    out = torch.empty(out_shape, dtype=x.dtype, device=x.device)
    total = out.numel()
    if total == 0:
        return out
    blkc = _BLOCK_BIG if total >= _BIG_TOTAL else _BLOCK

    if wordify:
        xarg = _f32_words(x)
        oarg = _f32_words(out)
    else:
        xarg = x
        oarg = out

    if n_is_tensor:
        ndt = ndeg.dtype
        nint64 = ndt is torch.int64
        if nint64:
            narg = _low_words(ndeg)
        elif ndt in (torch.int32, torch.int16, torch.int8, torch.uint8, torch.float32):
            narg = ndeg
        elif ndt is torch.bool:
            narg = ndeg.view(torch.uint8)
        else:
            narg = ndeg.to(torch.int32)

        if (
            x.is_contiguous()
            and ndeg.is_contiguous()
            and x.numel() == total
            and ndeg.numel() == total
        ):
            ndim = 1
            xflat = True
            nflat = True
            xs = [2, 1, 1, 1, 1, 1]
            ns = [2, 1, 1, 1, 1, 1]
            sizes = [total, 1, 1, 1, 1, 1]
        else:
            xs = _eff_strides(x, out_shape)
            ns = _eff_strides(ndeg, out_shape)
            sizes, xs, ns = _collapse(list(out_shape), xs, ns)
            ndim = len(sizes)
            if ndim > 6:
                raise NotImplementedError("hermite_polynomial_h supports <= 6 dims")
            xflat = ndim == 1 and xs[0] == 1
            nflat = ndim == 1 and ns[0] == 1
            pad = 6 - ndim
            xs = [v + 1 for v in xs] + [1] * pad
            ns = [v + 1 for v in ns] + [1] * pad
            sizes = sizes + [1] * pad
        grid_n = min(triton.cdiv(total, blkc), _MAX_GRID)
        if total >= _GRID_CAP_FROM:
            grid_n = min(grid_n, _GRID_CAP)
        grid = (grid_n,)
        # A per-program violation spool needs no zero-initialisation launch but
        # costs a host-side scan, so it is only used for small grids.
        spool = grid_n <= _SPOOL_MAX
        if spool:
            flag = torch.empty(grid_n, dtype=torch.int32, device=x.device)
        else:
            flag = torch.zeros(1, dtype=torch.int32, device=x.device)
        _hermite_tensor_kernel[grid](
            xarg,
            narg,
            oarg,
            flag,
            total,
            xs[0],
            xs[1],
            xs[2],
            xs[3],
            xs[4],
            xs[5],
            ns[0],
            ns[1],
            ns[2],
            ns[3],
            ns[4],
            ns[5],
            sizes[0],
            sizes[1],
            sizes[2],
            sizes[3],
            sizes[4],
            sizes[5],
            NDIM=ndim,
            XFLAT=xflat,
            NFLAT=nflat,
            NINT64=nint64,
            SPOOL=spool,
            BLOCK=blkc,
            num_warps=_NUM_WARPS,
        )
        if spool:
            if grid_n == 1:
                bad = flag.item() > 0
            else:
                bad = max(flag.tolist()) > 0
            if bad:
                raise ValueError(
                    "special_hermite_polynomial_h only supports n in [0, 9], "
                    "got an out-of-range degree"
                )
        elif flag.item() != 0:
            raise ValueError(
                "special_hermite_polynomial_h only supports n in [0, 9], "
                "got an out-of-range degree"
            )
        return out

    if x.is_contiguous():
        ndim = 1
        xflat = True
        xs = [2, 1, 1, 1, 1, 1]
        sizes = [total, 1, 1, 1, 1, 1]
    else:
        xs = _eff_strides(x, out_shape)
        sizes, xs, _ = _collapse(list(out_shape), xs, [0] * len(xs))
        ndim = len(sizes)
        if ndim > 6:
            raise NotImplementedError("hermite_polynomial_h supports <= 6 dims")
        xflat = ndim == 1 and xs[0] == 1
        pad = 6 - ndim
        xs = [v + 1 for v in xs] + [1] * pad
        sizes = sizes + [1] * pad
    grid_n = min(triton.cdiv(total, blkc), _MAX_GRID)
    if total >= _GRID_CAP_FROM:
        grid_n = min(grid_n, _GRID_CAP)
    grid = (grid_n,)
    _hermite_scalar_kernel[grid](
        xarg,
        oarg,
        total,
        xs[0],
        xs[1],
        xs[2],
        xs[3],
        xs[4],
        xs[5],
        sizes[0],
        sizes[1],
        sizes[2],
        sizes[3],
        sizes[4],
        sizes[5],
        NDIM=ndim,
        XFLAT=xflat,
        DEG=deg_scalar,
        BLOCK=blkc,
        num_warps=_NUM_WARPS,
    )
    return out


