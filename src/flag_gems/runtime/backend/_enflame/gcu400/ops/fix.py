        # Upcast to fp32 for stable math, then cast back to input dtype.
        # float -> int conversion rounds toward zero, i.e. it *is* trunc(), and
        # it is far cheaper than the floor/ceil + select it replaces. Values of
        # magnitude >= 2**23 are integral already and must bypass the cast.
