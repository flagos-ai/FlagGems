MAX_GRID = 48

# Streaming pointwise work is fastest with a single wave of 48 CTAs and a wide
# per-CTA tile: 8192 elements per iteration keeps the DTE pipeline full for
# medium sizes, while very large tensors benefit from a 65536-element tile.
SMALL_BLOCK_SIZE = 8192
LARGE_BLOCK_SIZE = 65536
LARGE_TILE_ELEMENTS = 1 << 27

# Every fp32 value with |x| >= 2**23 is already integral (the spacing of such
# floats is at least 1), so truncation only has to re-round the magnitudes that
# fit exactly into int32.
INTEGRAL_MAGNITUDE = 8388608.0


def _pick_block_size(n_elements: int) -> int:
    return LARGE_BLOCK_SIZE if n_elements >= LARGE_TILE_ELEMENTS else SMALL_BLOCK_SIZE


