"""Triton implementation of aten::cartesian_prod(Tensor[] tensors) -> Tensor.

out has shape (M, N), M = prod_k s_k, and out[row, k] = tensors[k][(row // PR[k]) % s_k]
with PR[k] = prod_{j>k} s_j (row-major product; the last tensor varies fastest).

The generic kernel gathers each column with a computed per-row index, which
lowers to a per-lane gather on GCU and dominates the runtime (repeated-address
vector loads are not merged by the hardware). The fast path instead aligns one
program to the radix structure of the product: with B = s_{N-2} * s_{N-1}
(both powers of two), every block of B rows starting at a multiple of B sees
column N-2 constant along q1 (value = in[N-2][q0]), column N-1 constant along
q0 (value = in[N-1][q1]) and every slower column uniform, so all loads become
scalar or contiguous vector loads and each column is written with one strided
1D store. Shapes without a power-of-two tail keep the generic gather kernel.

The op is a pure gather/copy, but the ATen reference is meshgrid+stack and
therefore differentiable, so the forward is wrapped in a custom autograd
Function whose backward scatters grad_out[:, k] back into input k with a
second Triton kernel.
"""

