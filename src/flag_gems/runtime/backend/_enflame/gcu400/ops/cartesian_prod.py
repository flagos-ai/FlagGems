def _suffix_products(sizes):
    n = len(sizes)
    prs = [1] * n
    acc = 1
    for k in range(n - 2, -1, -1):
        acc *= sizes[k + 1]
        prs[k] = acc
    return prs


def _plan(m, n):
    """Launch geometry and index width for one output size."""
    if m * n > _INT32_SAFE:
        return _BLOCK_ROWS_WIDE, 8, True
    return _BLOCK_ROWS, _NUM_WARPS, False


def _fast_plan(sizes, m, n):
    """Radix-tile plan, or None to keep the generic gather kernel.

    The fast kernels need every load to be a scalar or a contiguous vector
    and every program to cover whole radix cycles: the trailing sizes must
    be powers of two, M must divide evenly (guaranteed by structure), the
    flat output must stay inside int32 and the grid inside the x limit.
    """
    if m * n > _INT32_SAFE:
        return None
    if n == 2:
        s0, s1 = sizes
        if s1 < 2 or s1 & (s1 - 1):
            return None
        b_cap = min(_FAST_TILE_MAX, _FAST_TILE_MAX_LANES // n)
        # G-axis form: fold a power-of-two factor G of s0 into the radix tile
        # (A0 = G, A1 = s1) so one program covers G full cycles of column 1.
        g = 1
        while g * 2 <= b_cap // s1 and s0 % (g * 2) == 0:
            g *= 2
        if g >= 2 and g * s1 >= _FAST_TILE_MIN:
            b = g * s1
            grid = m // b
            if grid and grid <= _FAST_GRID_MAX and m % b == 0:
                return ("tile3", (g, s1), grid)
        # odd s0 (G == 1): direct two-column form with B | s1
        b = s1 if s1 <= b_cap else b_cap
        if b < _FAST_TILE_MIN:
            return None
        grid = m // b
        if grid == 0 or grid > _FAST_GRID_MAX or m % b:
            return None
        return ("tile2", b, grid)
    if n >= 3:
        a0, a1 = sizes[-2], sizes[-1]
        if a0 < 2 or a1 < 2 or (a0 & (a0 - 1)) or (a1 & (a1 - 1)):
            return None
        b = a0 * a1
        if b < _FAST_TILE_MIN or b > _FAST_TILE_MAX or b * n > _FAST_TILE_MAX_LANES:
            return None
        grid = m // b
        if grid == 0 or grid > _FAST_GRID_MAX or m % b:
            return None
        return ("tile3", (a0, a1), grid)
    return None


class _CartesianProd(torch.autograd.Function):
    @staticmethod
    def forward(ctx, n, sizes, *tensors):
        ctx.n = n
        ctx.sizes = sizes
        m = 1
        for s in sizes:
            m *= s
        out = torch.empty((m, n), dtype=tensors[0].dtype, device=tensors[0].device)
        if m == 0:
            return out

        fast = _fast_plan(sizes, m, n)
        if fast is not None:
            kind, b, grid = fast
            if kind == "tile2":
                _cartesian_prod_fwd_tile2[(grid,)](
                    out,
                    m,
                    tensors[0],
                    tensors[1],
                    sizes[0],
                    sizes[1],
                    N=n,
                    B=b,
                    num_warps=_FAST_NUM_WARPS,
                )
            else:
                a0, a1 = b
                pad = _MAX_TENSORS - n
                ptrs = tensors + (tensors[0],) * pad
                szs = tuple(sizes) + (1,) * pad
                prs = tuple(_suffix_products(sizes)) + (1,) * pad
                _cartesian_prod_fwd_tile3[(grid,)](
                    out,
                    m,
                    *ptrs,
                    *szs,
                    *prs,
                    N=n,
                    A0=a0,
                    A1=a1,
                    num_warps=_FAST_NUM_WARPS,
                )
            return out

        pad = _MAX_TENSORS - n
        ptrs = tensors + (tensors[0],) * pad
        szs = sizes + (1,) * pad
        prs = tuple(_suffix_products(sizes)) + (1,) * pad
        block_rows, num_warps, wide = _plan(m, n)
        _cartesian_prod_fwd_kernel[(triton.cdiv(m, block_rows),)](
            out,
            m,
            *ptrs,
            *szs,
            *prs,
            N=n,
            WIDE=wide,
            BLOCK_ROWS=block_rows,
            BLOCK_N=triton.next_power_of_2(n),
            num_warps=num_warps,
        )
        return out

    @staticmethod
    def backward(ctx, grad_out):
        n = ctx.n
        sizes = ctx.sizes
        needs = ctx.needs_input_grad[2:]
        acc_dtype = torch.float64 if grad_out.dtype == torch.float64 else torch.float32
        accs = [
            (
                torch.zeros(s, dtype=acc_dtype, device=grad_out.device)
                if needs[i]
                else None
            )
            for i, s in enumerate(sizes)
        ]

        m = 1
        for s in sizes:
            m *= s
        live = next((a for a in accs if a is not None), None)
        if m > 0 and live is not None:
            gout = grad_out.contiguous()
            pad = _MAX_TENSORS - n
            qs = tuple(a if a is not None else live for a in accs) + (live,) * pad
            szs = tuple(sizes) + (1,) * pad
            prs = tuple(_suffix_products(sizes)) + (1,) * pad
            _cartesian_prod_bwd_kernel[(triton.cdiv(m, _BLOCK_ROWS_BWD),)](
                gout,
                m,
                *qs,
                *szs,
                *prs,
                N=n,
                WIDE=m * n > _INT32_SAFE,
                BLOCK_ROWS=_BLOCK_ROWS_BWD,
                num_warps=_NUM_WARPS,
            )
        return (None, None) + tuple(
            None if a is None else a.to(grad_out.dtype) for a in accs
        )


def run(*args, **kwargs):
    logger.debug("GEMS_ENFLAME_GCU400 RUN")
    tensors = _normalize(args, kwargs)
    n = len(tensors)
    if n == 0:
        # reference (ATen -> meshgrid) raises this for an empty tensor list
        raise RuntimeError("meshgrid expects a non-empty TensorList")

    for t in tensors:
        if t.dim() != 1:
            raise RuntimeError(
                "Expect a 1D vector, but got shape " + str(list(t.shape))
            )

    if n == 1:
        # reference returns the single tensor unchanged: shape (s0,)
        return tensors[0]

    dtype = tensors[0].dtype
    for t in tensors[1:]:
        if t.dtype != dtype:
            # reference forbids mixed dtypes (ATen meshgrid check)
            raise RuntimeError("meshgrid expects all tensors to have the same dtype")

    tensors = [t if t.is_contiguous() else t.contiguous() for t in tensors]
    sizes = tuple(t.shape[0] for t in tensors)
    return _CartesianProd.apply(n, sizes, *tensors)


