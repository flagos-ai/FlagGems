@triton.jit(do_not_specialize=["M"])
def _cartesian_prod_fwd_tile2(
    out_ptr,
    M,
    p0,
    p1,
    s0: tl.constexpr,
    s1: tl.constexpr,
    N: tl.constexpr,
    B: tl.constexpr,
):
    # Two-tensor fast path, host-guaranteed: B is a power of two dividing s1,
    # so r0 = pid * B satisfies r0 % s1 + B <= s1. Column 1 is then one
    # affine run (idx = r0 % s1 + j) and column 0 is uniform per program.
    # M % B == 0 by structure, so no masks are needed anywhere.
    pid = tl.program_id(0)
    j = tl.arange(0, B)
    out_ty = out_ptr.dtype.element_ty
    base = pid * (B * N)
    offs = j * N
    base0 = (pid * B) // s1 % s0
    sv = tl.load(p0 + base0).to(out_ty)
    tl.store(out_ptr + base + offs + 0, tl.zeros([B], dtype=out_ty) + sv)
    c1 = (pid * B) % s1
    vb = tl.load(p1 + c1 + j).to(out_ty)
    tl.store(out_ptr + base + offs + 1, vb)


