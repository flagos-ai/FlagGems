    # the exact-grid flat kernel on every >= 2**24 band (probe r3, sibling of
    # the eq_ in-place re-probe).
    if n > _INT32_SAFE_LIMIT - block:
        return False
    _less_cmp_strided_kernel[(_NPROGS,)](A, B, A, n, BLOCK=block, num_warps=4)
    return True


