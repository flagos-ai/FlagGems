import logging

import torch
import triton
import triton.language as tl

from flag_gems.utils import libentry
from flag_gems.utils import pointwise_dynamic

logger = logging.getLogger(__name__)

# GCU400 retune (2026-11-21, do_bench A/B on the benchmark shapes): the flat
# 8K/nw4 tiling left 2.2-4.0x of bandwidth unused because every load/store
# carried a tail predicate (blocking the wide vector path) and 8K elements is
# too little in flight per program. New recipe: a persistent grid of one program
# per SIP (fp32: two per SIP) walking 64K-element tiles with 8 warps, with the
# mask compiled out whenever the tile divides numel exactly.
# 16.7M fp16: 257us -> 64us (native 64us); 16.7M fp32: 284us -> 122us
# (native 122us); 1G bf16: 12.7ms -> 4.07ms (native 5.5ms).
_NUM_SIPS = 24
# 65536 elements per tile keeps the three tile buffers (x, weight, out) inside
# the 896KB dsm budget for 4-byte dtypes; wider tiles fail to compile.
_PRELU_TILE_MAX = 65536
_PRELU_NUM_WARPS = 8
# dsm budget per tile buffer (bytes)
_PRELU_TILE_BYTES_MAX = 262144


@pointwise_dynamic(is_tensor=[True, True], promotion_methods=[(0, 1, "DEFAULT")])
@triton.jit
def _prelu_kernel_func(x, weight):
    return tl.where(x >= 0, x, weight * x)


# libentry caches the launch metadata: the JIT dispatch path costs ~20us of host
# time per call, which is a third of the 64us kernel at the 16.7M band.
@libentry()
@triton.jit
def _prelu_flat_kernel(
    x_ptr,
    weight_ptr,
    out_ptr,
    numel,
    BLOCK: tl.constexpr,
    MASKED: tl.constexpr,
):
    """Elementwise PReLU for identical shapes: out = x >= 0 ? x : weight * x.

    An elementwise op has no cross-element dependency, so blocking the elements
    contiguously gives the widest vectorization and avoids the index computation
    and broadcast overhead of the generic pointwise template.

    A persistent grid walks the tiles with a stride of num_programs, so the tile
    count is no longer bounded by grid.x and no 2D grid folding is needed. When
    BLOCK divides numel the tail predicate is dropped entirely (MASKED=False),
    which is what unblocks the wide vector loads/stores.
    """
    lane = tl.arange(0, BLOCK)
    pid = tl.program_id(0)
    num_pids = tl.num_programs(0)
    num_blocks = (numel + BLOCK - 1) // BLOCK
    for block_id in tl.range(pid, num_blocks, num_pids):
        offsets = block_id * BLOCK + lane
        if MASKED:
            mask = offsets < numel
            x = tl.load(x_ptr + offsets, mask=mask)
            weight = tl.load(weight_ptr + offsets, mask=mask)
            tl.store(out_ptr + offsets, tl.where(x >= 0, x, weight * x), mask=mask)
        else:
            x = tl.load(x_ptr + offsets)
            weight = tl.load(weight_ptr + offsets)
            tl.store(out_ptr + offsets, tl.where(x >= 0, x, weight * x))


def _choose_launch(numel, itemsize):
    # 16-bit tiles saturate with one program per SIP; 4-byte tiles need two
    # programs per SIP to keep the wider store path busy.
    num_programs = _NUM_SIPS if itemsize <= 2 else 2 * _NUM_SIPS
    tile_bytes = max(_PRELU_TILE_BYTES_MAX // max(itemsize, 1), 1024)
    block = min(_PRELU_TILE_MAX, tile_bytes, triton.next_power_of_2(numel))
    block = max(block, 128)
    return block, num_programs, (numel % block != 0)


