def _next_pow2(n, cap, lo):
    p = lo
    while p < n and p < cap:
        p *= 2
    return p


def reflection_pad3d_backward(grad_output, self, padding):
    """Compute gradient of reflection_pad3d forward pass.

    Args:
        grad_output: Gradient of the loss with respect to the output of reflection_pad3d.
                    Shape: (N, C, D + pad_d0 + pad_d1, H + pad_h0 + pad_h1, W + pad_w0 + pad_w1)
        self: Original input tensor before padding. Shape: (N, C, D, H, W)
        padding: Tuple of 6 ints (pad_d0, pad_d1, pad_h0, pad_h1, pad_w0, pad_w1)

    Returns:
        Gradient with respect to self. Shape: (N, C, D, H, W)
    """
    logger.debug("GEMS_ENFLAME REFLECTION_PAD3D_BACKWARD")

    if isinstance(padding, int):
        pad_d0 = pad_d1 = pad_h0 = pad_h1 = pad_w0 = pad_w1 = padding
    else:
        pad_d0, pad_d1, pad_h0, pad_h1, pad_w0, pad_w1 = padding

    # Validate input
    if self.dim() != 5:
        raise ValueError("input must be a 5D tensor")

    N, C, D_in, H_in, W_in = self.shape
    D_out, H_out, W_out = (
        D_in + pad_d0 + pad_d1,
        H_in + pad_h0 + pad_h1,
        W_in + pad_w0 + pad_w1,
    )

    # Validate shapes
    expected_grad_shape = (N, C, D_out, H_out, W_out)
    if tuple(grad_output.shape) != expected_grad_shape:
        raise ValueError(
            f"grad_output has shape {tuple(grad_output.shape)}, expected {expected_grad_shape}"
        )

    # Handle empty padding case - just reshape
    if (
        pad_d0 == 0
        and pad_d1 == 0
        and pad_h0 == 0
        and pad_h1 == 0
        and pad_w0 == 0
        and pad_w1 == 0
    ):
        return grad_output.clone()

    grad_output = grad_output.contiguous()

    # every output element is written exactly once by its owning row chunk,
    # so a plain empty buffer replaces the old zeros + atomics scheme
    out = torch.empty((N, C, D_in, H_in, W_in), device=self.device, dtype=self.dtype)
    if out.numel() == 0:
        return out

    rows_per_img = D_in * H_in
    BW = _next_pow2(W_in, 8192, 2)
    nchunk = triton.cdiv(W_in, BW)
    work_total = N * C * rows_per_img * nchunk

    def _launch():
        reflection_pad3d_backward_kernel[(min(48, work_total),)](
            grad_output,
            out,
            work_total,
            rows_per_img,
            D_in,
            H_in,
            W_in,
            W_out,
            pad_d0,
            pad_d1,
            pad_h0,
            pad_h1,
            pad_w0,
            pad_w1,
            D_out * H_out * W_out,
            H_out * W_out,
            W_out,
            D_in * H_in * W_in,
            HAS_PD0=pad_d0 > 0,
            HAS_PD1=pad_d1 > 0,
            HAS_PH0=pad_h0 > 0,
            HAS_PH1=pad_h1 > 0,
            HAS_PW0=pad_w0 > 0,
            HAS_PW1=pad_w1 > 0,
            NCHUNK=nchunk,
            WIDE=work_total >= 2**31,
            BW=BW,
            num_warps=8 if BW >= 4096 else (4 if BW >= 256 else 2),
        )

    # cold compiles hit the documented node-level toolchain flakiness (P02
    # family): a fresh-compile subprocess can die before producing a cache
    # entry; retrying the launch re-enters compilation and succeeds
    # (reflection_pad2d / atan2_ / _pad_circular precedent).
    for attempt in range(3):
        try:
            with torch_device_fn.device(self.device):
                _launch()
            break
        except Exception:
            if attempt == 2:
                raise

    return out
