    num_pids = tl.num_programs(0)
    arange = tl.arange(0, BLOCK)
    num_blocks = (N_total + BLOCK - 1) // BLOCK
    for block_id in tl.range(pid, num_blocks, num_pids):
        off = block_id * BLOCK + arange
        mask = off < N_total
        x = tl.load(X + off, mask=mask, other=1.0).to(tl.float32)
        z = tl.abs(x)
        small = z <= _HALF
        t = tl.where(small, z, tl.sqrt(_HALF - _HALF * z))
        t2 = t * t
        p = t2 * _P2 + _P1
        p = t2 * p + _P0
        a = t + t * t2 * p
        res = tl.where(small, _PIO2 - a, _TWO * a)
        xneg = x.to(tl.int32, bitcast=True) < 0
        res = tl.where(xneg, _PI - res, res)
        tl.store(Y + off, res.to(Y.dtype.element_ty), mask=mask)


