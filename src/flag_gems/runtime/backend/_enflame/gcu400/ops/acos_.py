def _choose_block(N_total, dtype):
    # do_bench(median) sweep vs torch.acos_ on GCU400.  The fp32 body peaks on
    # wide tiles above 2^24 (512M: 2994us @65536/2 vs 3151 @4096/4) but small
    # buckets prefer 4096/4 (16.7M: 103.7 vs 109.5 @32768/2); 16-bit keeps
    # 4096/4 on every measured bucket (512M: 2989us, 16.7M: 98.1) because the
    # ~15-op ALU body spills to slower schedules at wider tiles (8192+: 1.2x
    # worse, 65536: 2.4x).  Tiny sizes sit on the ~3.7us launch floor at 512/4.
    if N_total <= 4096:
        return 512, 4
    if dtype == torch.float32 and N_total > (1 << 24):
        return 65536, 2
    return 4096, 4


def _launch_acos_flat(inp, out, N_total, dtype):
    BLOCK, num_warps = _choose_block(N_total, dtype)
    grid_size = min(triton.cdiv(N_total, BLOCK), NUM_SIPS * 2)
    # The external llvm converter intermittently fails on cold compiles
    # (nondeterministic; observed as converterResult=-2 and a misresolved
    # converter helper script during a host-level userland flake window);
    # retrying the launch recompiles and succeeds.  3 attempts keep
    # deterministic breakage loud while riding out the flake (sinh.py /
    # acosh.py / atan2_.py precedent for the same toolchain family).
    for attempt in range(3):
        try:
            with torch_device_fn.device(inp.device):
                acos_flat_kernel[(grid_size,)](
                    inp, out, N_total, BLOCK=BLOCK, num_warps=num_warps
                )
            return
        except Exception as exc:
            if attempt == 2:
                raise
            logger.warning(
                "acos flat kernel launch failed (attempt %d): %s", attempt + 1, exc
            )


