logger = logging.getLogger(__name__)

NUM_SIPS = 24

# GCU400 override of the generic pointwise_dynamic implementation.  The vendor
# copy used to lower to the extern `__ef_acosf` inside the codegen
# pointwise_dynamic wrapper, which benchmarked at 0.48x of torch native
# (13.1ms vs 4.67ms on the 512M-element core shape).  Two measured pathologies
# drive the rewrite (do_bench kernel median, warmup 1000ms / rep 100ms):
#   * the extern call is a software slow path: an otherwise identical flat
#     kernel with the extern body needs 3680us (fp16 512M) where a branch
#     minimax asin polynomial of degree 2 in t^2 reaches 2989us;
#   * the codegen wrapper's fixed small tile leaves the memory pipeline
#     under-saturated (same family as the acosh fixed-BLOCK pathology).
# The fast path evaluates acos entirely in fp32 Triton math:
#   z = |x|; t = z            if z <= 1/2      -> acos = pi/2 - asin(t)
#            = sqrt((1-z)/2)  otherwise        -> acos = 2*asin(t), sign-fixed
# with one shared odd asin polynomial  asin(t) = t + t^3*P(t^2)  fitted by
# weighted least squares on [0, 1/2] (Chebyshev nodes): max abs error 5.9e-7
# in fp64 and 6.2e-7 measured in fp32 Horner order, i.e. >100x inside the
# 1e-4 atol gate; NaN for |x| > 1 falls out of sqrt(negative) naturally.
# BLOCK ladder (512M / 16.7M / 4096-element buckets, both widths):
#   fp32: 65536/nw2 above 2^24 (2994us = 1.50x native), 4096/nw4 below,
#   512/nw4 tiny;  16-bit: 4096/nw4 everywhere past tiny (2989us = 1.56x
#   native fp16; wider tiles spill the ~15-op body and get 1.2-2.4x slower).
# A HAS_TAIL (mask-free on exact divides) variant was measured and rejected:
# tailfree runs 3-4% SLOWER at the 4096/4 sweet spots and only +1% at fp32
# 65536/2 (within noise), unlike the arcsin/erfc wins for other bodies.

_HALF = tl.constexpr(0.5)
_TWO = tl.constexpr(2.0)
_PIO2 = tl.constexpr(1.5707963267948966)
_PI = tl.constexpr(3.141592653589793)
_P0 = tl.constexpr(1.668569157e-01)
_P1 = tl.constexpr(7.126710583e-02)
_P2 = tl.constexpr(6.578840389e-02)


