    reduce_dim = reduce_dims[0]
    shape = list(inp.shape)
    N = shape[reduce_dim]
    M = 1
    for s in shape[:reduce_dim]:
        M *= s
    K = inp.numel() // (M * N) if N > 0 else 0

    if (
        K <= 1
        or N <= 1
        or inp.dtype not in (torch.float16, torch.bfloat16, torch.float32)
        or inp.numel() > _MAX_FAST_NUMEL
    ):
        # Inner (K == 1) row reductions, non-fp dtypes and oversized inputs stay
        # on the tuned local sum_dim paths (dim_compress + inner/non-inner).
        return sum_dim(inp, reduce_dims, keepdim=True)

    config = _non_inner_config(N, K, inp.element_size())
    if config is None:
        return sum_dim(inp, reduce_dims, keepdim=True)

    BLOCK_I, BLOCK_K, num_warps_, num_stages_ = config
    BLOCK_I = min(BLOCK_I, triton.next_power_of_2(N))
    BLOCK_K = min(BLOCK_K, triton.next_power_of_2(K))

    # Square-ish shapes with too few k tiles to fill 48 SPs: split the reduced
    # dim across row groups instead (partial + merge keeps fp32 accuracy).
    if M == 1 and N >= 512 and M * triton.cdiv(K, BLOCK_K) < _STARVED_TASKS:
        split = _starved_split_config(inp.element_size())
        if split is not None:
            return _split_reduce(inp, reduce_dim, N, K, split)

    inp = inp.contiguous()
    out_shape = list(shape)
    out_shape[reduce_dim] = 1
    out = torch.empty(out_shape, dtype=inp.dtype, device=inp.device)

    num_k_tile = triton.cdiv(K, BLOCK_K)
    num_task = M * num_k_tile
    grid = min(_MAX_GRID, num_task)
    with torch_device_fn.device(inp.device):
        sum_to_size_non_inner_kernel[(grid,)](
            inp,
            out,
            M,
            N,
            K,
            num_task,
            BLOCK_I=BLOCK_I,
            BLOCK_K=BLOCK_K,
            num_stages=num_stages_,
            num_warps=num_warps_,
        )
    return out


