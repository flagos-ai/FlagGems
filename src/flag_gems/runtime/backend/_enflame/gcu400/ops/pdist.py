def _mode_of(p):
    if p == 2.0:
        return _MODE_P2
    if p == 1.0:
        return _MODE_P1
    if math.isinf(p):
        return _MODE_INF
    if p == 0.0:
        return _MODE_COUNT
    return _MODE_GENERAL


