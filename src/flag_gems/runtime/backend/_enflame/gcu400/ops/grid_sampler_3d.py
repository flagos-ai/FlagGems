def grid_sampler_3d(
    input,
    grid,
    interpolation_mode=0,
    padding_mode=0,
    align_corners=False,
):
    """Grid sampler 3D with trilinear or nearest interpolation.

    Blocked, vectorized port of the generic ``grid_sampler`` 5D kernel: each
    program handles BLOCK_SIZE output elements (channels folded into the flat
    index) and the launch grid is clamped to the GCU grid.x hardware cap with
    an in-kernel grid-stride loop, so the benchmark's largest shape
    (N*OD*OH*OW = 262144) stays launchable.
    """
    logger.debug("GEMS GRID_SAMPLER_3D")

    N, C, in_d, in_h, in_w = input.shape
    out_d, out_h, out_w = grid.shape[1:4]

    output = torch.empty(
        (N, C, out_d, out_h, out_w),
        dtype=input.dtype,
        device=input.device,
    )

    if output.numel() == 0:
        return output

    total_out = N * C * out_d * out_h * out_w

    def get_grid(meta):
        return (min(triton.cdiv(total_out, meta["BLOCK_SIZE"]), _MAX_GRID_X),)

    grid_sampler_3d_kernel[get_grid](
        input,
        grid,
        output,
        N,
        C,
        in_d,
        in_h,
        in_w,
        out_d,
        out_h,
        out_w,
        *input.stride(),
        *grid.stride(),
        *output.stride(),
        total_out,
        interpolation_mode,
        padding_mode,
        align_corners,
        # Volumetric 5D data is memory-bound; a smaller block keeps the
        # 8-corner gather pipelines full without blowing the register budget
        # (matches grid_sampler's 5D kernel).
        BLOCK_SIZE=256,
    )

    return output
