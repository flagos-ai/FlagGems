def _fast_path_ok(x, y, out):
    """Fast-path condition: same shape, all three contiguous, 16/32-bit lanes, numel within int32."""
    if x.dtype != y.dtype or x.dtype != out.dtype:
        return False
    if x.shape != y.shape or x.shape != out.shape:
        return False
    if not (x.is_contiguous() and y.is_contiguous() and out.is_contiguous()):
        return False
    if x.element_size() not in (2, 4):
        return False
    return x.numel() <= MAX_NUMEL


def _launch_1d(x, y, out):
    numel = x.numel()
    if numel == 0:
        return out
    is_16_bit = x.element_size() == 2
    # Tile = numel / PERSIST_GRID rounded up to a power of two, clamped to the streaming sweet
    # spot: a large tensor keeps a 32K tile on a 48-CTA persistent grid, a small one picks a tile
    # that still fills the grid (never below MIN_BLOCK_ELEMS) so no lane idles.
    per_cta = triton.next_power_of_2(triton.cdiv(numel, PERSIST_GRID))
    block = min(max(per_cta, MIN_BLOCK_ELEMS), MAX_BLOCK_ELEMS)
    # A tensor smaller than the minimum tile must not pay for masked-off lanes.
    block = min(block, triton.next_power_of_2(numel))
    if is_16_bit and numel >= LARGE_16BIT_ELEMS:
        # A multi-tens-of-MB 16-bit stream wants 64K tiles and one tile per CTA: at 67M elements
        # that measures 0.35 ms against 0.40 ms for the 32K/48-CTA shape, and at 1G it keeps the
        # 16384 CTAs the wide case needs (the persistent grid drops to 6.4 ms there).
        block = MAX_BLOCK_ELEMS * 2
        grid = (min(triton.cdiv(numel, block), 65535),)
    else:
        grid = (min(triton.cdiv(numel, block), PERSIST_GRID),)
    tail = bool(numel % block)
    if is_16_bit:
        _nextafter_1d_16[grid](
            x,
            y,
            out,
            numel,
            block,
            x.dtype == torch.bfloat16,
            tail,
            num_warps=NUM_WARPS,
        )
    else:
        _nextafter_1d_32[grid](x, y, out, numel, block, tail, num_warps=NUM_WARPS)
    return out


