        y_is_nan = ((y_int & exp_mask) == exp_mask) & ((y_int & frac_mask) != 0)
        is_nan = x_is_nan | y_is_nan

        # Same value: return input (matches IEEE 754)
        is_equal = input == other

        sign_bit = 0x8000
        is_positive = (x_int & sign_bit) == 0
        is_going_up = input < other

        # --- uint16 constants via bitwise ops (arithmetic on uint16 + Python int
        #     would promote to int32, breaking the final bitcast) ---
