def _nextafter_1d_16(
    x_ptr,
    y_ptr,
    o_ptr,
    numel,
    BLOCK: tl.constexpr,
    IS_BF16: tl.constexpr,
    TAIL: tl.constexpr,
):
    """1-D contiguous fp16/bf16 fast path: uint16 bit tricks yield the next representable value.

    Two advantages over the libdevice path (widen to fp32, compute, write back): no double
    rounding on write-back (which can return the original value) and no transcendental call.
    The grid is persistent (one CTA per SIP) and walks the tensor with a grid-stride loop.
    """
