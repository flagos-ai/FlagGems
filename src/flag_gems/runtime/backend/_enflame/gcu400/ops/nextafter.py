        uint_one = uint_zero | 1  # uint16(1)
        uint_neg_one = ~uint_zero  # uint16(0xFFFF) = -1 in uint16 arithmetic
        cross_const = uint_zero | 0x8001  # uint16(0x8001)

        # Manipulate the unsigned integer representation.
        # IEEE 754 sign-magnitude means that for positive numbers a larger
        # uint corresponds to a larger float value, while for negative numbers
        # a larger uint corresponds to a more-negative (smaller) float value.
        #
        # Normal increment:
        #   positive going up:     x_int + 1
        #   positive going down:   x_int - 1  (= x_int + 0xFFFF in uint16)
        #   negative going up:     x_int - 1  (less negative)
        #   negative going down:   x_int + 1  (more negative)
        normal_inc = tl.where(
            is_positive,
            tl.where(is_going_up, uint_one, uint_neg_one),
            tl.where(is_going_up, uint_neg_one, uint_one),
        )

        # Zero-crossing needs special handling:
        #   +0 going down: 0x0000 should become 0x8001 (largest negative subnormal)
        #   -0 going up:   0x8000 should become 0x0001 (smallest positive subnormal)
        # In both cases x_int + 0x8001 gives the correct result in uint16:
        #   0x0000 + 0x8001 = 0x8001  (target)
        #   0x8000 + 0x8001 = 0x0001  (wraps around in uint16)
        pos_zero_down = is_positive & ~is_going_up & (x_int == 0)
        neg_zero_up = ~is_positive & is_going_up & (x_int == 0x8000)
        is_zero_cross = pos_zero_down | neg_zero_up

        # IEEE 754: nextafter(NaN, any) = NaN and nextafter(any, NaN) = NaN.
        # Return a canonical quiet NaN bit pattern when either operand is NaN;
        # this must take precedence over both is_equal and the increments.
        # Fold the NaN bit pattern to a compile-time constant so OR-ing it with
        # the uint16 tensor does not promote to int32 (see cross_const above).
        nan_const: tl.constexpr = exp_mask | 0x0001  # smallest quiet NaN
        nan_bits = uint_zero | nan_const
        result_int = tl.where(
            is_nan,
            nan_bits,
            tl.where(
                is_equal,
                x_int,  # same value: return input as-is
                tl.where(is_zero_cross, x_int + cross_const, x_int + normal_inc),
            ),
        )

        return result_int.to(input.dtype, bitcast=True)
