    for start in range(tl.program_id(0) * BLOCK, numel, tile_stride):
        offs = start + tl.arange(0, BLOCK)
        # Tell the compiler that this range is a contiguous full block, to facilitate wide vectorized load/store
        offs = tl.max_contiguous(tl.multiple_of(offs, BLOCK), BLOCK)
        if TAIL:
            mask = offs < numel
            x = tl.load(x_ptr + offs, mask=mask)
            y = tl.load(y_ptr + offs, mask=mask)
        else:
            x = tl.load(x_ptr + offs)
            y = tl.load(y_ptr + offs)

        if IS_BF16:
            exp_mask: tl.constexpr = 0x7F80
            frac_mask: tl.constexpr = 0x007F  # noqa: F841
        else:
            exp_mask: tl.constexpr = 0x7C00  # noqa: F841
            frac_mask: tl.constexpr = 0x03FF  # noqa: F841

        x_int = x.to(tl.uint16, bitcast=True)
        y_int = y.to(tl.uint16, bitcast=True)

        # Derive uint16 constants from the tensor itself, to avoid Python ints in the computation causing type promotion
        # to int32
        uint_zero = x_int & 0
        uint_one = uint_zero | 1
        uint_neg_one = ~uint_zero  # 0xFFFF in uint16, i.e. -1 in bit pattern
        cross_const = uint_zero | 0x8001  # Bit step that crosses +-0 in one hop

        # Direction: a positive lane steps up (bit +1) when y is above x, a negative
        # lane steps up when y is below x. One sign compare + one float compare +
        # one xor replace the previous and/cmp/eq chain.
        is_away = (x < y) != (x_int < 0x8000)
        normal_inc = tl.where(is_away, uint_neg_one, uint_one)

        # +-0 needs a special step only in the two directions that leave zero
        # (+0 downward -> 0x8001, -0 upward -> 0x0001); the two directions that enter
        # the subnormals are already produced by the normal +-1 step above.
        leave_zero = ((x_int & 0x7FFF) == 0) & is_away
        step = tl.where(leave_zero, cross_const, normal_inc)
        result_int = x_int + step
        # The two "keep x bits" cases (x == y and x is NaN) are folded into one select:
        # both return the x_int bit pattern, which drops one compare + select pair.
        keep_x_int = (x == y) | (x != x)
        result_int = tl.where(keep_x_int, x_int, result_int)
        result_int = tl.where(y != y, y_int, result_int)
        result = result_int.to(x.dtype, bitcast=True)
        if TAIL:
            tl.store(o_ptr + offs, result, mask=mask)
        else:
            tl.store(o_ptr + offs, result)


