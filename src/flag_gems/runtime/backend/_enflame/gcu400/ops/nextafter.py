    # casting back would silently skip intermediate fp16/bf16 values because the
    # float32 next value may round to the same lower-precision value (e.g.
    # nextafter(1., 2.) in fp16 is 1.0009765625, but the fp32 next value
    # 1.00000012 rounds back to 1.0 in fp16).
    # For float32: use libdevice's nextafter (which also handles NaN / Inf / same).
