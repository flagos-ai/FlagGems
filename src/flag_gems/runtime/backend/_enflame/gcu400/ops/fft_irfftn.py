def _real_view_dtype(complex_dtype):
    view = _REAL_VIEW.get(complex_dtype)
    if view is None:
        raise ValueError(f"Unsupported complex dtype: {complex_dtype}")
    return view


def _tl_dtype(torch_dtype):
    return _TL_DTYPE[torch_dtype]


def _pick_irfft_cfg(n_real):
    """(BLOCK_M, BLOCK_K, num_warps) for the c2r stage.

    gcu400 sweep (N=1024): multi-chunk k-loops need >=4096-elem tiles to stay
    launch-bound (BM=8/BK=64 = 8 chunks measured ~47us kernel vs ~1us at
    BM=16/BK=256 = 2 chunks). grid.y = ceil(N/BLOCK_M) <= 255; tile <= 8192
    elems keeps the DSM budget (~917504 B/CTA) comfortable.
    """
    BLOCK_M = 16 if n_real >= 256 else 8
    while (n_real + BLOCK_M - 1) // BLOCK_M > 255:
        BLOCK_M *= 2
    k_end = n_real // 2
    BLOCK_K = 16
    while BLOCK_K < 256 and BLOCK_K < k_end:
        BLOCK_K *= 2
    while BLOCK_M * BLOCK_K > 8192 and BLOCK_K > 16:
        BLOCK_K //= 2
    return BLOCK_M, BLOCK_K, 4


def _pick_ifft_cfg(n):
    """(BLOCK_M, BLOCK_K, num_warps) for the c2c stage; grid.y <= 255."""
    BLOCK_M = 16 if n >= 256 else 8
    while (n + BLOCK_M - 1) // BLOCK_M > 255:
        BLOCK_M *= 2
    BLOCK_K = 16
    while BLOCK_K < 256 and BLOCK_K < n:
        BLOCK_K *= 2
    while BLOCK_M * BLOCK_K > 8192 and BLOCK_K > 16:
        BLOCK_K //= 2
    return BLOCK_M, BLOCK_K, 4


def _grid_rows(n_rows):
    """Rows per program so that grid.x = ceil(n_rows/RPP) <= 65535."""
    RPP = (n_rows + 65534) // 65535
    grid0 = (n_rows + RPP - 1) // RPP
    return RPP, grid0


