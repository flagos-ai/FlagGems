def _launch_hooks_clear():
    state = _KNOBS_RUNTIME[0]
    try:
        if state is None:
            from triton import knobs as _knobs

            state = _KNOBS_RUNTIME[0] = _knobs.runtime
        return not state.launch_enter_hook.calls and not state.launch_exit_hook.calls
    except Exception:
        return False


def _fast_launch(kernel, key, grid, tail, launch_kwargs, dev_idx):
    entry = _LAUNCH_CACHE.get(key)
    if entry is not None and _launch_hooks_clear():
        run, function, packed = entry
        try:
            run(
                grid[0],
                grid[1],
                1,
                driver.active.get_current_stream(dev_idx),
                function,
                packed,
                None,
                None,
                None,
                *tail,
            )
            return
        except Exception:
            _LAUNCH_CACHE.pop(key, None)
    compiled = kernel[grid](*tail, **launch_kwargs)
    if compiled is not None:
        try:
            _LAUNCH_CACHE[key] = (
                compiled.run,
                compiled.function,
                compiled.packed_metadata,
            )
        except Exception:
            pass


def _ifft_dim(x, d, out=None):
    """Unnormalized 1D inverse c2c FFT along dim d of a contiguous complex x."""
    shape = x.shape
    n = shape[d]
    n_rows = x.numel() // n
    if n_rows == 0:
        if out is None:
            out = torch.empty(shape, dtype=x.dtype, device=x.device)
        return out
    real_dtype = _real_view_dtype(x.dtype)
    x_f = x.view(real_dtype)
    if out is None:
        out = torch.empty(shape, dtype=x.dtype, device=x.device)
    y_f = out.view(real_dtype)
    P = math.prod(shape[d + 1 :])
    BLOCK_M, BLOCK_K, num_warps = _pick_ifft_cfg(n)
    RPP, grid0 = _grid_rows(n_rows)
    nblk = (n + BLOCK_M - 1) // BLOCK_M
    COMP_TL = _tl_dtype(torch.float64 if x.dtype == torch.complex128 else torch.float32)
    IN_TL = _tl_dtype(real_dtype)
    WIDE = n > _MAX_SAFE_PROD_N
    tail = (
        x_f,
        y_f,
        n_rows,
        P,
        n,
        BLOCK_M,
        BLOCK_K,
        RPP,
        IN_TL,
        IN_TL,
        COMP_TL,
        WIDE,
    )
    key = (
        "i",
        n,
        n_rows,
        P,
        x_f.data_ptr() % 16 == 0,
        y_f.data_ptr() % 16 == 0,
        real_dtype,
        x.device.index,
        BLOCK_M,
        BLOCK_K,
        RPP,
        COMP_TL,
        WIDE,
        num_warps,
    )
    _fast_launch(
        _ifft_dim_kernel,
        key,
        (grid0, nblk),
        tail,
        dict(num_warps=num_warps),
        x.device.index,
    )
    return out


def _irfft_dim(x, d, n_real, out_dtype, compute_dtype, scale):
    """1D inverse real FFT along dim d of a contiguous complex x, scaled."""
    shape = x.shape
    n_in = shape[d]
    n_rows = x.numel() // n_in
    real_dtype = _real_view_dtype(x.dtype)
    x_f = x.view(real_dtype)
    out_shape = list(shape)
    out_shape[d] = n_real
    y = torch.empty(out_shape, dtype=out_dtype, device=x.device)
    if n_rows == 0:
        return y
    P = math.prod(shape[d + 1 :])
    BLOCK_M, BLOCK_K, num_warps = _pick_irfft_cfg(n_real)
    RPP, grid0 = _grid_rows(n_rows)
    nblk = (n_real + BLOCK_M - 1) // BLOCK_M
    COMP_TL = _tl_dtype(compute_dtype)
    OUT_TL = _tl_dtype(out_dtype)
    IN_TL = _tl_dtype(real_dtype)
    WIDE = n_real > _MAX_SAFE_PROD_N
    tail = (
        x_f,
        y,
        n_rows,
        P,
        n_real,
        n_in,
        BLOCK_M,
        BLOCK_K,
        RPP,
        scale,
        IN_TL,
        OUT_TL,
        COMP_TL,
        WIDE,
    )
    key = (
        "r",
        n_real,
        n_in,
        n_rows,
        P,
        x_f.data_ptr() % 16 == 0,
        y.data_ptr() % 16 == 0,
        real_dtype,
        out_dtype,
        x.device.index,
        BLOCK_M,
        BLOCK_K,
        RPP,
        scale,
        COMP_TL,
        WIDE,
        num_warps,
    )
    _fast_launch(
        _irfft_dim_kernel,
        key,
        (grid0, nblk),
        tail,
        dict(num_warps=num_warps),
        x.device.index,
    )
    return y


def _run_stages(input, cplx_dims, real_dim, n_real, out_dtype, compute_dtype, scale):
    """c2c ifft over cplx_dims then scaled c2r irfft over real_dim."""
    work = input
    k = len(cplx_dims)
    if k == 1:
        work = _ifft_dim(work, cplx_dims[0])
    elif k >= 2:
        buf0 = torch.empty(work.shape, dtype=work.dtype, device=work.device)
        buf1 = torch.empty_like(buf0)
        for i, d in enumerate(cplx_dims):
            work = _ifft_dim(work, d, out=buf0 if i % 2 == 0 else buf1)
    return _irfft_dim(work, real_dim, n_real, out_dtype, compute_dtype, scale)


def fft_irfftn(input: torch.Tensor, s=None, dim=None, norm="backward"):
    """Compute the N-dimensional inverse of torch.fft.rfftn.

    Args:
        input: Complex tensor (half-Hermitian from rfftn).
        s: Output size for each transformed dimension.
        dim: Dimensions to transform. dim[-1] is the real (c2r) dimension;
             dim[:-1] are complex (c2c) dimensions. Tuple order matters.
        norm: "backward" (default) / "forward" / "ortho".

    Returns:
        Real tensor.
    """
    logger.debug("GEMS_ENFLAME FFT_IRFFTN")

    if not input.is_complex():
        raise ValueError("Input must be a complex tensor")

    if dim is None and s is None:
        # Fast default path: transform every dim, sizes derived from input
        # (identical semantics to the generic baseline's dim/s defaults).
        shape = input.shape
        ndim = input.ndim
        n_in = shape[-1]
        n_real = 2 * (n_in - 1)  # even; n_real // 2 + 1 == n_in by construction
        numel = input.numel()
        if numel == 0:
            out_shape = list(shape)
            out_shape[-1] = n_real
            out_dtype = _OUT_DTYPE.get(input.dtype)
            return torch.empty(out_shape, dtype=out_dtype, device=input.device)
        if 2 * numel > _MAX_I32_ELEMS or numel // n_in * n_real > _MAX_I32_ELEMS:
            raise ValueError(
                "fft_irfftn: tensor too large for i32 addressing on this backend"
            )
        work = input if input.is_contiguous() else input.contiguous()
        cplx_prod = 1
        for d in range(ndim - 1):
            cplx_prod *= shape[d]
        if norm == "backward":
            scale = 1.0 / (cplx_prod * n_real)
        elif norm == "ortho":
            scale = 1.0 / math.sqrt(cplx_prod * n_real)
        elif norm == "forward":
            scale = 1.0
        else:
            raise ValueError(f"Invalid norm: {norm}")
        out_dtype, compute_dtype = _OUT_DTYPE[work.dtype], _COMPUTE_DTYPE[work.dtype]
        return _run_stages(
            work,
            list(range(ndim - 1)),
            ndim - 1,
            n_real,
            out_dtype,
            compute_dtype,
            scale,
        )

    # Generic path: explicit s and/or dim, same validation as the baseline.
    if dim is None:
        dim = tuple(range(-len(s), 0))
    if isinstance(dim, int):
        dim = (dim,)
    dim = tuple(d % input.ndim for d in dim)

    # Normalize s: default to input length along c2c dims, 2*(N_in-1) along the real dim.
    if s is None:
        s = tuple(
            2 * (input.shape[d] - 1) if d == dim[-1] else input.shape[d] for d in dim
        )
    if isinstance(s, int):
        s = (s,)
    if len(s) != len(dim):
        raise ValueError(f"s length {len(s)} != dim length {len(dim)}")

    s_map = {dim[i]: s[i] for i in range(len(dim))}
    real_dim = dim[-1]
    cplx_dims = list(dim[:-1])
    n_real = s_map[real_dim]

    out_dtype = _OUT_DTYPE.get(input.dtype)
    compute_dtype = _COMPUTE_DTYPE.get(input.dtype)
    if out_dtype is None:
        raise ValueError(f"Unsupported complex dtype: {input.dtype}")

    n_in_expected = n_real // 2 + 1
    if input.shape[real_dim] != n_in_expected:
        raise ValueError(
            f"Input shape at dim {real_dim} is {input.shape[real_dim]}, "
            f"expected {n_in_expected} for n_real={n_real}"
        )

    out_numel = input.numel() // input.shape[real_dim] * n_real
    if 2 * input.numel() > _MAX_I32_ELEMS or out_numel > _MAX_I32_ELEMS:
        raise ValueError(
            "fft_irfftn: tensor too large for i32 addressing on this backend"
        )

    if input.numel() == 0:
        out_shape = list(input.shape)
        out_shape[real_dim] = n_real
        return torch.empty(out_shape, dtype=out_dtype, device=input.device)

    if not input.is_contiguous():
        input = input.contiguous()

    for d in cplx_dims:
        n = s_map[d]
        if n != input.shape[d]:
            raise NotImplementedError(
                "fft_irfftn: s truncation/padding along non-real dims not supported; "
                "input length along dim must equal s"
            )

    # Normalization, folded into the final c2r kernel as SCALE:
    #   backward: 1 / (N_cplx_prod * n_real); forward: 1 (unnormalized);
    #   ortho:    1 / sqrt(N_cplx_prod * n_real).
    cplx_N_prod = 1
    for d in cplx_dims:
        cplx_N_prod *= s_map[d]
    if norm == "backward":
        scale = 1.0 / (cplx_N_prod * n_real)
    elif norm == "forward":
        scale = 1.0
    elif norm == "ortho":
        scale = 1.0 / math.sqrt(cplx_N_prod * n_real)
    else:
        raise ValueError(f"Invalid norm: {norm}")

    return _run_stages(
        input, cplx_dims, real_dim, n_real, out_dtype, compute_dtype, scale
    )
