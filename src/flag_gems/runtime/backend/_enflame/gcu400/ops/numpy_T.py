_MATERIALIZED = {}

# Reversed axis orders cached per rank -- ``numpy_T``'s only permute argument.
# Building the tuple costs ~95 ns per call; the dict hit is ~55 ns.
_REV_DIMS = {}


@triton.jit
def _reverse_order_kernel(order_ptr, BLOCK: tl.constexpr):
    """Materialize the reversed axis order ``order[k] == BLOCK - 1 - k``.

    The program takes no runtime operand: the block width is a ``constexpr``
    and the written values follow from it, so the launch carries a single
    pointer argument and the store needs no mask.  One compiled binary exists
    per block width.
    """
    pos = tl.arange(0, BLOCK)
    tl.store(order_ptr + pos, BLOCK - 1 - pos)


def _order_workspace(device):
    """Return this device's int32 order buffer, creating it on first use."""
    key = getattr(device, "index", None)
    buffer = _ORDER_WORKSPACE.get(key)
    if buffer is None:
        buffer = torch.empty(64, dtype=torch.int32, device=device)
        _ORDER_WORKSPACE[key] = buffer
    return buffer


