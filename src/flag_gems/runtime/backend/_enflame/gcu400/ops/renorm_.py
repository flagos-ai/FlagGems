def renorm_(input, p, dim, maxnorm):
    logger.debug("GEMS_ENFLAME RENORM")
    d = _renorm_dim(input, dim)
    p_mode, pf, inv_p = _renorm_prepare(p)
    maxn = float(maxnorm)
    if input.numel() == 0:
        return input
    # Q == 1 fast path: reduction along the leading axes, tuned per-slice
    # walk (single launch, U=4 loads in flight, one lane per slice).
    lead_prod = 1
    for sz in input.shape[:d]:
        lead_prod *= sz
    trail_prod = 1
    for sz in input.shape[d + 1 :]:
        trail_prod *= sz
    if trail_prod == 1 and lead_prod > 1:
        axes = _renorm_axes(input, d, False)
        if axes is not None:
            M, _, P, sM, _, sP = axes
            BM = 256 if M <= 4096 else 512
            if triton.cdiv(M, BM) <= 65535:
                _renorm_last_kernel[(triton.cdiv(M, BM),)](
                    input,
                    M,
                    P,
                    sM,
                    sP,
                    pf,
                    inv_p,
                    maxn,
                    P_MODE=p_mode,
                    BM=BM,
                    U=4,
                    num_warps=1,
                    num_stages=1,
                )
                return input
    # Q > 1 (the old tile kernel miscompiled here) and degenerate corners:
    # share the fused kernels with the out-of-place op. In-place is safe -
    # the reduction pass never writes, and the scale pass loads each tile
    # before storing it back.
    if _renorm_fused(input, input, d, p_mode, pf, inv_p, maxn):
        return input
    # Non-collapsible layout: renormalize a permuted contiguous copy.
    ndim = input.dim()
    perm = [d] + [i for i in range(ndim) if i != d]
    inv_perm = [0] * ndim
    for i, pi in enumerate(perm):
        inv_perm[pi] = i
    x_perm = input.permute(perm).contiguous()
    renorm_(x_perm, p, 0, maxn)
    input.copy_(x_perm.permute(inv_perm))
    return input
