"""GCU400 specialization of aten::_sparse_softmax_backward_data.

The math is identical to the generic kernel set: for stored entry ``j`` with
``S_j = sum(dy_i * y_i)`` over the entries sharing ``j``'s coordinate on every
dim except the reduced one, the result is ``y_j * (dy_j - S_j)``.

Only the launch geometry differs.  ``nnz * D`` (stored entries times the dense
block size) reaches 64Mi on the benchmark shapes, so the generic
``cdiv(nnz * D, BLOCK)`` grid asks for 65536 programs and trips the device
``grid.x`` limit of 65535.  Every elementwise kernel below therefore launches a
capped grid and strides over the remaining tiles with ``tl.num_programs(0)``.
"""

