@triton.jit
def _ssbd_coalesce_val(
    val_ptr, perm_ptr, slot_ptr, out_ptr, nnz, dn, BLOCK: tl.constexpr
):
    """Sum duplicate entries into their coalesced group."""
    n_lanes = nnz * dn
    grid = tl.num_programs(0)
    tile = tl.program_id(0)
    while tile * BLOCK < n_lanes:
        lanes = tile * BLOCK + tl.arange(0, BLOCK)
        mask = lanes < n_lanes
        e = lanes // dn
        off = lanes - e * dn
        src = tl.load(perm_ptr + e, mask=mask, other=0).to(tl.int64)
        g = tl.load(slot_ptr + e, mask=mask, other=0)
        v = tl.load(val_ptr + src * dn + off, mask=mask, other=0.0)
        tl.atomic_add(out_ptr + g * dn + off, v, mask=mask)
        tile += grid


@triton.jit
def _ssbd_coalesce_idx(
    idx_ptr,
    perm_ptr,
    key_ptr,
    slot_ptr,
    out_ptr,
    out_stride,
    nnz,
    sd,
    BLOCK: tl.constexpr,
):
    """Keep one coordinate per group: the first position of each sorted run."""
    grid = tl.num_programs(0)
    tile = tl.program_id(0)
    while tile * BLOCK < nnz:
        p = tile * BLOCK + tl.arange(0, BLOCK)
        mask = p < nnz
        key = tl.load(key_ptr + p, mask=mask, other=0)
        prev = tl.load(key_ptr + p - 1, mask=mask & (p > 0), other=-1)
