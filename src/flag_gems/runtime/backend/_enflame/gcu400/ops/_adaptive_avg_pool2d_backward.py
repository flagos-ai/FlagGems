    in_write_mask = h_valid[:, None] & w_valid[None, :]
    grad_input_store_ptr = (
        grad_input_base
        + h_in_offsets[:, None] * in_stride_h
        + w_in_offsets[None, :] * in_stride_w
    )
    tl.store(
        grad_input_store_ptr,
        grad_acc.to(grad_input_ptr.type.element_ty),
        mask=in_write_mask,
    )


