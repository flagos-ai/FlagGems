            # own ranges include this (oh, ow); masked lanes contribute 0.
            grad_out_val = tl.load(
                oh_row_base[:, None] + ow[None, :] * out_stride_w,
                mask=m_h[:, None] & m_w[None, :],
                other=0.0,
            ).to(tl.float32)
