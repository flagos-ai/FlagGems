# GCU400 特化修复：torch_gcu 未注册稀疏后端（P21）——aten 参考腿静默回退 CPU 且输出
# 留在 CPU，而 `torch.sparse_coo_tensor(..., device=gcu)` 产出设备元数据不一致的半残
# 张量（.device 误报 cpu、values 悬 gcu）。参照 `_embedding_bag_sparse_backward.py`
# 先例：Triton kernel 仍在 GCU 计算 values，仅把 indices/values `.detach().cpu()` 后
# 在 CPU 构造 COO（USE_CPU_SPARSE=1），输出设备与平台原生回退行为对齐，数值语义不变。
# 另修 P17：无 TORCH_GCU_ENABLE_INT64_AND_UINT64 时 int64 索引紧凑 4B 存储 + 8B 步长
# 交错错值（padding 行漏置零）——host 侧 `.to(torch.int32)` 归一（embedding 索引域
# < num_weights << 2^31，i32 精确保值）＋ kernel load 后 `.to(tl.int32)`，
# 两种 env 布局下均确定正确。
import logging

import torch
import triton
import triton.language as tl

import flag_gems

logger = logging.getLogger(__name__)

# --- TUNING PARAMS START ---
# 由优化迭代驱动脚本按轮次生成；只影响稀疏输出落盘设备，不影响数值语义。
USE_CPU_SPARSE = 1
