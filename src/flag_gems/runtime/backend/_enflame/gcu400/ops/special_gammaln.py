# gammaln on GCU400: tl_extra_shim.lgamma resolves to a slow software path on
# this target (16.7M fp32 elements took 47.5ms, ~40x slower than the native
# torch kernel).  A pure-arithmetic Lanczos approximation plus the reflection
# formula needs only ~20 vector instructions per element and reaches ~1.2ms for
# the same size, so the operator is implemented as an explicit flat kernel
# instead of pointwise_dynamic + tl_extra_shim.lgamma.
import logging

import torch
import triton
import triton.language as tl

import flag_gems
from flag_gems.runtime import torch_device_fn
from flag_gems.utils.triton_lang_helper import _fallback_lgamma

logger = logging.getLogger(__name__)

_MAX_GRID = 65535
_MIN_PROGRAMS = 256
_ITERS = 16

# Launch geometry measured on gcu:0 with do_bench(warmup=25ms, rep=80ms,
# median).  Fat tiles lose on this part because each program costs ~0.5us of
# dispatch: for 16.7M fp32 elements BLOCK=4096/num_warps=4 runs in 1.19ms while
# BLOCK=65536/num_warps=1 needs 2.29ms.  Tensors up to SMALL_N elements keep the
# finer-grained tile ladder instead, which beats one big tile there.
SMALL_N = 1 << 16
# (tile size, num_warps, program count): fp32 prefers a small CTA count with a
# grid-stride loop (1.19ms for 16.7M), while 16-bit dtypes are 2.2x faster with
# one tile per CTA (1.36ms vs 3.02ms) because the loop keeps the widening/
# narrowing conversions live across iterations.  "None" means one CTA per tile.
_LARGE_CONFIG = {
    torch.float16: (8192, 4, None),
    torch.bfloat16: (8192, 4, None),
    torch.float32: (4096, 4, 256),
    torch.float64: (4096, 4, 256),
}
# (inclusive upper bound on numel, tile size); num_warps stays 4 in this range.
_SMALL_TILE_LEVELS = ((8192, 512), (16384, 1024), (32768, 2048))
_SMALL_TILE_DEFAULT = 4096


