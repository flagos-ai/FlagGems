def _flat_launch(g, s, out, n, even, native):
    # shrink the tile for launch-bound sizes (a 16K-wide masked block on a 4K
    # tensor costs a few us more than an exactly sized one)
    block = _FLAT_BLOCK
    while block > n:
        block //= 2
    grid = (min(triton.cdiv(n, block), _FLAT_CAP),)
    _hsb_flat[grid](
        g,
        s,
        out,
        n,
        BLOCK=block,
        CAP=_FLAT_CAP,
        CHUNKED=False,
        EVEN=even,
        NATIVE=native,
        num_warps=_FLAT_WARPS,
    )


def _numel(shape):
    n = 1
    for d in shape:
        n *= int(d)
    return n


def _grid_for(n, block):
    total = triton.cdiv(n, block)
    if total > _MAX_GRID:
        total = _MAX_GRID
    return (total,)


def hardsigmoid_backward(grad_output, self):
    logger.debug("GEMS HARDSIGMOID_BACKWARD")
    if (
        grad_output.shape == self.shape
        and grad_output.dtype is self.dtype
        and grad_output.is_contiguous()
        and self.is_contiguous()
    ):
        n = grad_output.numel()
        out = torch.empty_like(grad_output)
        if n == 0:
            return out
        _flat_launch(
            grad_output,
            self,
            out,
            n,
            (n % _ALIGN) == 0,
            grad_output.dtype is not torch.float32,
        )
        return out

    shape = torch.broadcast_shapes(grad_output.shape, self.shape)
    out_dtype = torch.promote_types(grad_output.dtype, self.dtype)
    out = torch.empty(shape, dtype=out_dtype, device=grad_output.device)
    n = _numel(shape)
    if n == 0:
        return out

    g = grad_output.expand(shape)
    s = self.expand(shape)

    # Collapse contiguous neighbouring dimensions and drop size-1 dims.
    cdims, cg, cs = [], [], []
    for d, gd, sd in zip(shape, g.stride(), s.stride()):
        d = int(d)
        if d == 1:
            continue
        if cdims and cg[-1] == gd * d and cs[-1] == sd * d:
            cdims[-1] *= d
        else:
            cdims.append(d)
            cg.append(gd)
            cs.append(sd)

    if not cdims:
        cdims, cg, cs = [1], [0], [0]

    ndim = len(cdims)
    if ndim > _MAX_NDIM:
        raise RuntimeError("hardsigmoid_backward: unsupported tensor rank")

    pad = _MAX_NDIM - ndim
    params = torch.tensor(
        cdims + [1] * pad + cg + [0] * pad + cs + [0] * pad,
        dtype=torch.int32,
        device=grad_output.device,
    )

    _hsb_strided[_grid_for(n, 1024)](
        grad_output,
        self,
        out,
        params,
        n,
        BLOCK=1024,
        NDIM=ndim,
        FP64=(out_dtype == torch.float64),
        num_warps=1,
    )
    return out


