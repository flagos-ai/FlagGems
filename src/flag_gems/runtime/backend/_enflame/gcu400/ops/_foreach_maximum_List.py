"""GCU400-specific ``_foreach_maximum_List`` (out-of-place ``.List``).

The shared ``foreach_binary_list`` carries the tensor list on a 2-D grid, and GCU400's
``grid.y`` cap of 255 makes large shapes ``out of resource``. This file earlier avoided that
with a per-tensor 1-D flat kernel, but every call launched once per tensor in the list: for a
16-tensor list the ``@libentry`` host dispatch alone was a constant ~310us (independent of
shape/dtype), 0.16-0.45x on the official bench, making it the last member of the
clamp/maximum family not consolidated into a single launch.

Here paired contiguous float lists go through a metadata-fused single-launch kernel -- four
int64 metadata segments (input/output/second-operand addresses plus element counts) go through
the shared read-only cache keyed by ``(device, address, element count)``, so steady-state calls
(the allocator reuses the same addresses) need zero H2D, consistent with the already optimized
``_foreach_minimum`` / ``_foreach_clamp_min`` siblings; broadcast ``.List`` goes through the
per-tensor flat kernel, and non-float / non-contiguous / mixed dtype / empty-tensor forms fall
back to the shared ``_apply_list``, keeping dtype policy and error semantics.

The fused kernel linearizes ``(tensor, part)``, which requires the grid to be an integer
multiple of the tensor count (``_foreach_flat._fused_grid`` with ``fixed_grid % NT != 0``
leaves tail tensors without a part and drops odd tiles); this file avoids that by construction
with the always-divisible ``_maximum_grid`` (a 16-tensor optimizer list at 16x256^2 direct-call
comparison: with a non-divisible grid half the tensors held garbage/NaN, with a divisible one bit-identical).

Cold-L2 attribution (official do_bench, kernel-only closure, all 9 cells) shows every wrapper
host path is fully hidden by launch pipelining (host gap ~ 0), so the remaining headroom is all
kernel-side cold bandwidth: only ~0.95TB/s on 256^2, ~1.7TB/s on 512^2, and 1024^2 already sits
on the 2R1W structural ceiling. The per-tile bounds mask is the biggest lever -- when ``numel``
divides ``BLOCK`` the load/store predicates disappear (``EXACT`` path); interleaved A/B in the
official setup: fp32 all three tiers -17.4%/-9.6%/-4.7%, 16-bit with ``BLOCK=16384`` gives
-7%~-3% (bf16 at an 8192 tile regresses -1.3~-2.8% by dropping the mask and flips positive at a
16384 tile -- tile width and predicate tax are coupled to dtype, so each dtype takes its own optimum).
"""

import logging

import torch
import triton
import triton.language as tl
from triton import knobs
from triton.runtime import driver as _triton_driver

from flag_gems.ops._foreach_binary import _apply_list
