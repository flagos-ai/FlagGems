NUM_SIPS = 16

# GCU400 override of the generated heaviside_ kernel.  The generated form
# launches one program per 1024-element tile, which overflows the grid.x
# hardware limit (65535) on the 1Gi benchmark shape (2^30 elements ->
# 2^20 programs: "out of resource: grid.x, Required: 1048576").  The flat
# grid-stride kernel below treats the pair as one dense 1D range and keeps
# the exact where-chain body of the generated kernel, so numerics (including
# the NaN propagation through x + x) are bit-identical.  Shape/block
# selection follows the add.py flat-kernel form with a heaviside_-specific
# ladder (in-place 2-load 1-store traffic, measured on L600 with the core
# benchmark protocol, do_bench kernel median):
#   - fp16/bf16 >= 2^24 elements: B65536/nw2 reaches 2.96TB/s at 2^30
#     (2112-2126us, 12.6% over B32768/nw1 for bf16); BLOCK 131072 is flat
#     and 262144 exceeds DSM (required 1048576 vs dsmSize 917504);
#   - fp32 >= 2^22: B32768/nw2 (23.9us at 2^22, 72.3us at 2^24, 4322us at
#     2^30);
#   - grid is capped at NUM_SIPS*3 (48) CTAs: 48 CTAs fill every SP, while
#     32-way leaves a third of the SPs idle (bandwidth drops to ~2.07TB/s);
#   - EXACT skips the tail mask when N % BLOCK == 0 (every core shape is a
#     power of two), SCALAR broadcasts a 0-dim values tensor without
#     materializing a full-size v operand, and WIDE widens the block offset
#     arithmetic to int64 once N exceeds the int32 safe domain
#     (2^31 - BLOCK, randn.py WIDE precedent: without the grid.x bound the
#     int32 offset domain is silently reachable again).


