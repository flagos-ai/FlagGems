def heaviside_(self: torch.Tensor, values: torch.Tensor):
    logger.debug("GEMS_ENFLAME HEAVISIDE_")

    if not torch.is_tensor(values):
        v_tensor = torch.as_tensor(values, device=self.device, dtype=self.dtype)
    else:
        v_tensor = values.to(device=self.device, dtype=self.dtype)

    n_elements = self.numel()
    if n_elements == 0:
        return self

    # Scalar / one-element values: the kernel broadcasts the single v element
    # per block, avoiding both the full-size v materialization and its loads.
    if v_tensor.numel() == 1 and self.is_contiguous():
        _launch_heaviside_flat(self.view(-1), v_tensor.view(-1), n_elements, True)
        return self

    # Same-extent contiguous pair (the benchmark hot path): launch directly,
    # no broadcast materialization and no host-side copies.
    if (
        v_tensor.numel() == n_elements
        and self.is_contiguous()
        and v_tensor.is_contiguous()
    ):
        _launch_heaviside_flat(self.view(-1), v_tensor.view(-1), n_elements, False)
        return self

    # General fallback: broadcast values to the input shape (in-place: self
    # keeps its shape), then take the same flat kernel.
    v_tensor = v_tensor.expand_as(self).contiguous()
    x_contig = self.contiguous()
    _launch_heaviside_flat(x_contig.view(-1), v_tensor.view(-1), n_elements, False)
    if x_contig is not self:
        self.copy_(x_contig)

    return self
