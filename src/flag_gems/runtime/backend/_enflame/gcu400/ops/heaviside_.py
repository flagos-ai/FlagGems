def _choose_block_and_warps(n_elements, itemsize):
    if n_elements <= 4096:
        return max(triton.next_power_of_2(n_elements), 256), 2
    if n_elements <= 65536:
        return 2048, 4
    if n_elements <= (1 << 21):
        return 8192, 4
    if itemsize == 2:
        # fp16 / bf16 in-place 2R1W sweep (2026-11-18, heaviside_ L600,
        # do_bench kernel median): (2^21, 2^23] prefers 16384/nw4 (14.4/15.9us
        # at 2^22); >= 2^24 prefers 65536/nw2 (40.1us at 2^24; 2112-2126us at
        # 2^30 = 2.96TB/s, 12.6% over 32768/nw1 for bf16 at 1Gi).  BLOCK
        # 131072 is flat and 262144 exceeds DSM (required total 1048576 vs
        # dsmSize 917504); grid 48 stays (g32 within run-to-run noise).
        if n_elements <= (1 << 23):
            return 16384, 4
        return 65536, 2
    # fp32: >= 2^22 prefers 32768/nw2 across the band (23.9us at 2^22, 72.3us
    # at 2^24, 4322us at 2^30 — tied with 65536/nw2 within noise); BLOCK
    # 131072 exceeds DSM.
    return 32768, 2


