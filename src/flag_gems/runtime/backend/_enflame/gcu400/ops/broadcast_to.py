        cols = out_shape[-1]
        # 列宽对齐大 BLOCK 时整列/整行单任务更省调度; 否则回退小 BLOCK 防 mask 空转。
        if cols % 4096 == 0:
            BLOCK_SIZE = 4096
        elif cols % 2048 == 0 and cols >= 2048:
            BLOCK_SIZE = 2048
        else:
            BLOCK_SIZE = 1024
        NUM_GRID = min(48, triton.cdiv(n_elements, BLOCK_SIZE))
        grid = (NUM_GRID,)
