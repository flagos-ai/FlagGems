        mask = offsets < n_elements
        in_offsets = tl.zeros([BLOCK_SIZE], dtype=tl.int32)
        for d in range(0, ndims):
            s = tl.load(out_shape_ptr + d)
            stride_right = tl.load(out_cumprod_ptr + d)
            in_stride = tl.load(in_stride_ptr + d)
