# GCU400 rewrite (job j20261117192759_beadde2a): the generic kernel maps the
# flattened (N*C) row axis onto grid.x, so shape (128, 512, 128) requires
# grid.x = 65536 and dies on the 65535 hardware limit. It also launches one
# tiny CTA per row chunk, which streams at ~30-250 GB/s on GCU400 (probe
# 2026-11-17: 0.12x-0.55x vs the native op). This rewrite keeps the exact
# generic semantics (strict-greater max, first-occurrence indices, int64
# indices, dtype-min for fully-masked windows) but tiles (ROWS, BLOCK_L)
# output blocks per program on a flat 1D grid capped at 65535 with a
# grid-stride tail loop. i32 addressing is guarded by the host on numel
# (< 2**31 both sides) with a WIDE (i64) arm for pathological sizes.
# Tile geometry: BLOCK_L spans out_l in <=1024-wide chunks. The per-program
# element budget and warp count are picked per row length (2026-11-19 sweep:
# 11 variants x 4 shapes, correctness checked inline). Long rows (out_l >= 256)
# are occupancy/latency bound and win with a 2048-element tile over 4 warps -
# 1.9x at (16,64,1024), 1.4x at (32,128,512), 1.5x at (8,32,4096); the previous
# 8192/4096-element single-warp tile wasted the per-program register budget.
# Short rows (out_l < 256) stay on the 4096-element single-warp tile, which is
# still the best of the swept configs there (the flat tile grid would otherwise
# grow 2-4x for no gain). A span-load arm that reduces the 3-tap stride-2 input
# amplification via register reshape/split/argmax/weighted-sum extraction was
# prototyped and rejected: tl.split miscompiles on multi-chunk launches,
# tl.argmax and axis-2 sums scalarize (~5-40x slower), and bool one-hot selects
# hit ld.lld relocation errors (tops_cvt_v0_si8_to_vbool) - see compiler_issues/.
import logging
import time

import torch
import triton
import triton.language as tl

from flag_gems.utils import libentry
from flag_gems.utils.limits import get_dtype_min

logger = logging.getLogger(__name__)

_GRID_LIMIT = 65535
_INT32_ELEMENT_LIMIT = 2**31
_MAX_ROWS = 32768
_MIN_BLOCK_L = 64
_MAX_BLOCK_L = 1024
# Row length above which a launch is treated as "long" (small tile, 4 warps).
_LONG_ROW_L = 256

# Sweep knob: a probe may emulate a persistent-style capped launch by
# overriding this module global through the registered function's __globals__.
_GRID_CAP = _GRID_LIMIT


def max_pool1d_output_size(
    in_size: int,
    kernel_size: int,
    stride: int,
    padding: int,
    dilation: int,
    ceil_mode: bool = False,
) -> int:
    effective_kernel_size = (kernel_size - 1) * dilation + 1
    numerator = in_size + 2 * padding - effective_kernel_size
    if ceil_mode:
        output_size = (numerator + stride - 1) // stride + 1
        # PyTorch-compatible adjustment for ceil_mode
        if (output_size - 1) * stride >= in_size + padding:
            output_size -= 1
    else:
        output_size = numerator // stride + 1

    return output_size


@libentry()
@triton.jit
def max_pool1d_forward_kernel(
    input_ptr,
    output_ptr,
    indices_ptr,
    # Tensor strides (input is host-guaranteed contiguous, inner stride == 1)
    in_stride_nc,
    out_stride_nc,
    # Extents
    nc_total,
    in_l,
    out_l,
    # Flat-grid tiling
    total_tiles,
    l_blocks,
    # Pooling parameters
    kernel_l: tl.constexpr,
    stride_l: tl.constexpr,
    padding_l: tl.constexpr,
    dilation_l: tl.constexpr,
    # Meta-parameters for tiling
    BLOCK_L: tl.constexpr,
    ROWS: tl.constexpr,
    # Static specializations computed on the host
    EVEN_NC: tl.constexpr,
    EVEN_OL: tl.constexpr,
    NEED_IN_MASK: tl.constexpr,
    WIDE: tl.constexpr,
):
    pid = tl.program_id(axis=0)
    num_pids = tl.num_programs(axis=0)
    dtype = input_ptr.type.element_ty
    min_val = get_dtype_min(dtype)

    for tile in tl.range(pid, total_tiles, num_pids):
        row_chunk = tile // l_blocks
        l_chunk = tile - row_chunk * l_blocks

        row_ids = row_chunk * ROWS + tl.arange(0, ROWS)
        l_out = l_chunk * BLOCK_L + tl.arange(0, BLOCK_L)

        if WIDE:
            # Pathological extents: every derived offset is computed in i64.
            row_ids = row_ids.to(tl.int64)
            l_out = l_out.to(tl.int64)

        in_row_base = input_ptr + row_ids * in_stride_nc
        out_row_base = output_ptr + row_ids * out_stride_nc
        idx_row_base = indices_ptr + row_ids * out_stride_nc

        max_val_acc = tl.full((ROWS, BLOCK_L), min_val, dtype=dtype)
        # Accumulate the window index in i32 on the narrow arm (input length
        # fits i32 there) and widen only on the store: i64 lanes double the
        # register traffic for every tap of the max/where chain. The WIDE arm
        # keeps i64 because its offsets may exceed 2**31.
        if WIDE:
            max_idx_acc = tl.full((ROWS, BLOCK_L), -1, dtype=tl.int64)
        else:
            max_idx_acc = tl.full((ROWS, BLOCK_L), -1, dtype=tl.int32)

        for kl in tl.static_range(0, kernel_l):
            l_in = l_out * stride_l - padding_l + kl * dilation_l
            tap_ptr = in_row_base[:, None] + l_in[None, :]
            if NEED_IN_MASK:
                lane_ok = (l_in >= 0) & (l_in < in_l)
                if EVEN_NC:
                    load_mask = lane_ok[None, :]
                else:
                    load_mask = lane_ok[None, :] & (row_ids[:, None] < nc_total)
                current_val = tl.load(tap_ptr, mask=load_mask, other=min_val)
                take = (current_val > max_val_acc) & load_mask
            else:
                current_val = tl.load(tap_ptr)
                take = current_val > max_val_acc
            # Strict-greater keeps the first-occurrence index, matching
            # the generic kernel and the PyTorch CPU reference.
            max_val_acc = tl.where(take, current_val, max_val_acc)
            if WIDE:
                max_idx_acc = tl.where(take, l_in[None, :], max_idx_acc)
            else:
                max_idx_acc = tl.where(take, l_in.to(tl.int32)[None, :], max_idx_acc)

        if EVEN_NC and EVEN_OL:
            tl.store(out_row_base[:, None] + l_out[None, :], max_val_acc)
            tl.store(idx_row_base[:, None] + l_out[None, :], max_idx_acc.to(tl.int64))
        else:
            store_mask = (row_ids[:, None] < nc_total) & (l_out[None, :] < out_l)
            tl.store(
                out_row_base[:, None] + l_out[None, :], max_val_acc, mask=store_mask
            )
            tl.store(
                idx_row_base[:, None] + l_out[None, :],
                max_idx_acc.to(tl.int64),
                mask=store_mask,
            )


def _launch_with_retry(launch):
    # Flaky external toolchain (fresh-compile segv windows on the shared
    # node): retry compile-time failures only, re-raise the original error
    # once exhausted so real failures are never masked.
    for attempt in range(6):
        try:
            launch()
            return
        except Exception:
            if attempt == 5:
                raise
            time.sleep(1.0)


def _parse_pool_params(kernel_size, stride, padding, dilation):
    def _single(value, name):
        if isinstance(value, (list, tuple)):
            if len(value) != 1:
                raise ValueError(f"{name} must be a single int for 1D pooling")
            return int(value[0])
        return int(value)

    kernel_l = _single(kernel_size, "kernel_size")

    if stride is None or (isinstance(stride, (list, tuple)) and len(stride) == 0):
        stride_l = kernel_l
    else:
        stride_l = _single(stride, "stride")

    padding_l = _single(padding, "padding")
    dilation_l = _single(dilation, "dilation")

    if kernel_l <= 0:
        raise ValueError(f"kernel_size must be positive, but got {kernel_l}")
    if stride_l <= 0:
        raise ValueError(f"stride must be positive, but got {stride_l}")
    if padding_l < 0:
        raise ValueError(f"padding must be non-negative, but got {padding_l}")
    if dilation_l <= 0:
        raise ValueError(f"dilation must be positive, but got {dilation_l}")

    return kernel_l, stride_l, padding_l, dilation_l


def _select_launch_config(nc_total, out_l, target_elems=None):
    """Heuristic (BLOCK_L, ROWS, l_blocks, num_warps) tile for a GCU400 launch.

    BLOCK_L covers out_l in as few power-of-two chunks as possible (capped at
    _MAX_BLOCK_L); ROWS then grows the per-program tile toward target_elems
    (2048 for long rows, 4096 otherwise - the 2026-11-19 GCU400 sweep winners
    for every core bench shape), and keeps growing until the flat tile grid
    fits the 65535 hard limit.
    """
    block_l = _MIN_BLOCK_L
    while block_l < out_l and block_l < _MAX_BLOCK_L:
        block_l *= 2
    l_blocks = triton.cdiv(out_l, block_l)

    if target_elems is None:
        target_elems = 2048 if out_l >= _LONG_ROW_L else 4096
    rows = max(1, target_elems // block_l)
    while triton.cdiv(nc_total, rows) * l_blocks > _GRID_LIMIT and rows < _MAX_ROWS:
        rows *= 2

    # Long rows are occupancy bound: the 2048-element tile needs several warps
    # to keep the 3-tap loads in flight. Short rows run on small grids where the
    # single-warp CTA still wins (see the module header note).
    num_warps = 4 if out_l >= _LONG_ROW_L else 1
    return block_l, rows, l_blocks, num_warps


def max_pool1d_with_indices(
    input: torch.Tensor,
    kernel_size,
    stride=None,
    padding=0,
    dilation=1,
    ceil_mode=False,
):
    logger.debug("GEMS_ENFLAME MAX_POOL1D_WITH_INDICES")

    kernel_l, stride_l, padding_l, dilation_l = _parse_pool_params(
        kernel_size, stride, padding, dilation
    )

    # Input may be (C, L) or (N, C, L). Normalize to 3D for the kernel launch.
    squeeze_batch = input.dim() == 2
    if squeeze_batch:
        input = input.unsqueeze(0)

    input = input.contiguous()
    in_n, in_c, in_l = input.shape
    out_l = max_pool1d_output_size(
        in_l, kernel_l, stride_l, padding_l, dilation_l, ceil_mode
    )

    output = torch.empty((in_n, in_c, out_l), device=input.device, dtype=input.dtype)
    indices = torch.empty((in_n, in_c, out_l), device=input.device, dtype=torch.int64)

    nc_total = in_n * in_c
    out_numel = nc_total * out_l
    if out_numel != 0:
        block_l, rows, l_blocks, num_warps = _select_launch_config(nc_total, out_l)
        total_tiles = triton.cdiv(nc_total, rows) * l_blocks
        grid = (min(total_tiles, _GRID_CAP),)

        # i32 fast path is only safe when both sides stay below 2**31
        # elements; the WIDE arm recomputes all offsets in i64 otherwise.
        wide = (
            input.numel() >= _INT32_ELEMENT_LIMIT or out_numel >= _INT32_ELEMENT_LIMIT
        )
        even_nc = nc_total % rows == 0
        even_ol = out_l % block_l == 0
        # Taps of a fully-covered, floor-mode, unpadded window are provably
        # in-bounds, so loads only need masking when the host says otherwise.
        need_in_mask = padding_l > 0 or ceil_mode or not even_ol or not even_nc
        _launch_with_retry(
            lambda: max_pool1d_forward_kernel[grid](
                input,
                output,
                indices,
                input.stride(1),
                out_l,
                nc_total,
                in_l,
                out_l,
                total_tiles,
                l_blocks,
                kernel_l,
                stride_l,
                padding_l,
                dilation_l,
                BLOCK_L=block_l,
                ROWS=rows,
                EVEN_NC=even_nc,
                EVEN_OL=even_ol,
                NEED_IN_MASK=need_in_mask,
                WIDE=wide,
                num_warps=num_warps,
                num_stages=1,
            )
        )

    if squeeze_batch:
        output = output.squeeze(0)
        indices = indices.squeeze(0)

    return output, indices


