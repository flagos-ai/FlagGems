def hash_tiled_kernel(
    x_ptr,
    out_ptr,
    M,
    N,
    row_stride,
    col_stride,
    n_split_size,
    out_row_stride,
    dtype_code: tl.constexpr,
    BLOCK_M: tl.constexpr,
    BLOCK_N: tl.constexpr,
):
    """XOR-reduce a logical (M, N) matrix along N. Each program handles a
    BLOCK_M block of output rows and an [pid_s*n_split_size, +n_split_size)
    slice of the reduction dim, producing one uint64 partial per row."""
    pid_m = tl.program_id(0)
    pid_s = tl.program_id(1)

    m_idx = pid_m * BLOCK_M + tl.arange(0, BLOCK_M)
    m_mask = m_idx < M

    n_start = pid_s * n_split_size
    n_stop = n_start + n_split_size

    acc = tl.zeros([BLOCK_M], dtype=tl.uint64)
    for n0 in range(n_start, n_stop, BLOCK_N):
        n_idx = n0 + tl.arange(0, BLOCK_N)
        # Bound by both the tensor extent and this split's own slice.
        n_mask = (n_idx < N) & (n_idx < n_stop)
        offs = m_idx[:, None] * row_stride + n_idx[None, :] * col_stride
        mask = m_mask[:, None] & n_mask[None, :]
        v = tl.load(x_ptr + offs, mask=mask, other=0)
        u = _to_u64(v, dtype_code)
        u = tl.where(mask, u, 0)
        acc ^= tl.reduce(u, 1, _xor_combine)

    out_off = m_idx * out_row_stride + pid_s
    tl.store(out_ptr + out_off, acc, mask=m_mask)


@functools.lru_cache(maxsize=1024)
def _tile_shape(M, N, row_contig, elem_size):
    """Select tile size from the problem shape and input element width.

    Tuned by sweeping representative shapes. Every element is widened to 64 bits
    inside the kernel, so narrow inputs can afford a wider tile for the same
    register budget. Cached because it is a pure function of its arguments and
    small shapes are launch-bound.
    """
    np2 = triton.next_power_of_2
    # Reduce contiguous N (common case): wide BLOCK_N for coalescing, small
    # BLOCK_M to keep occupancy high and register pressure low.
    if not row_contig:
        if N >= 8192:
            # 1- and 2-byte inputs take the wider tile; 4- and 8-byte inputs
            # would spill, so they halve it.
            block_n = 2048 if elem_size <= 2 else 1024
            block_m = 2
        elif N >= 1024:
            block_n = 1024
            block_m = 1 if M >= 1024 else 2
        else:
            block_n = min(np2(N), 256)
            block_m = min(np2(M), 4)
    else:
        # Row-contiguous (M coalesced): wider M tiles, moderate N.
        block_m = min(np2(M), 128)
        block_n = max(1, min(np2(N), 1024))
    # gcu400 caps grid.x at 65535 and on-chip (DSM) memory at 917504 bytes;
    # every element is widened to 64 bits (plus a uint64 accumulator per row),
    # so a tile must hold at most ~32768 elements.  A 128x1024 tile asked for
    # 1.46 MiB and a 1-row tile overflowed grid.x, so size BLOCK_M for the grid
    # and then shrink BLOCK_N to fit the tile budget.
    need_m = np2(max(1, (M + 65534) // 65535))
    block_m = max(block_m, need_m)
    tile_budget = 32768
    if block_m * block_n > tile_budget:
        block_n = np2(max(1, tile_budget // block_m))
    return block_m, block_n


