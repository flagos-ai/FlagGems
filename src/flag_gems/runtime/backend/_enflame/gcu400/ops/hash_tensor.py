@triton.jit
def _f32_to_f64_bits(x):
    """IEEE-754 double bit pattern of a float32 value, in integer arithmetic.

    gcu400 has no fp64 support: ``x.to(tl.float64)`` fails to legalize
    ("Pipeline run failed") and takes the compiler down with a segfault for
    this kernel, so the exact widening is rebuilt from the fp32 fields.  The
    result is bit-identical to a real float32 -> float64 conversion for every
    value, including subnormals, inf and NaN.
    """
    b = x.to(tl.uint32, bitcast=True)
    sign = (b >> 31).to(tl.uint64) << 63
    exp32 = (b >> 23) & 0xFF
    frac32 = b & 0x7FFFFF

    # 1 <= exp32 <= 254: re-bias the exponent (127 -> 1023); frac32 << 29 and
    # 896 << 52 land in disjoint fields, so the plain add cannot carry.
    normal = sign | ((b & 0x7FFFFFFF).to(tl.uint64) << 29)
    normal = normal + (tl.full((), 896, tl.uint64) << 52)

    # exp32 == 255: inf/NaN keep their payload with the exponent saturated.  A
    # real widening conversion quiets signalling NaNs (sets payload bit 22,
    # which lands on the double quiet bit), so mirror that here.
    payload = tl.where(frac32 == 0, frac32, frac32 | 0x400000)
    inf_nan = (
        sign | (tl.full((), 0x7FF, tl.uint64) << 52) | (payload.to(tl.uint64) << 29)
    )

    # exp32 == 0: +-0 keeps just the sign; subnormals (value = frac32 * 2^-149)
    # become normal doubles and need the highest set bit of frac32, found by
    # the shift-count loop below (at most 23 steps).
    m = frac32
    e = tl.full((), 897, tl.uint32)  # 1023 - 149 + 23
    for _ in tl.static_range(23):
        shift = (m != 0) & (m < (1 << 23))
        m = tl.where(shift, m << 1, m)
        e = tl.where(shift, e - 1, e)
    sub = tl.where(
        m == 0,
        sign,
        sign | (e.to(tl.uint64) << 52) | ((m & 0x7FFFFF).to(tl.uint64) << 29),
    )

    return tl.where(exp32 == 0, sub, tl.where(exp32 == 255, inf_nan, normal))


