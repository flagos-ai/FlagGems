    # values+offsets 组装：dim-0 拼接对各组件是一次整块平坦拷贝——快路径
    # 单 kernel launch 完成、offsets 同 kernel 设备侧写出（Host 侧无 aten
    # 计算外流、零 H2D）；域外（>4 组件 / 非 float dtype / 非连续 / 超大）
    # 组合复用 enflame cat 算子；非 GCU 设备保留公版行为（该路径不经 GCU
    # dispatch，仅直调可达）。
