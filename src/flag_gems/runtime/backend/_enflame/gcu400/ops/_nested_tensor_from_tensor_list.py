def _contiguous_strides(shape):
    strides = []
    stride = 1
    for dim_size in reversed(tuple(shape)):
        strides.append(stride)
        stride *= dim_size
    strides.reverse()
    return strides


def _try_fast_concat(components):
    """dim-0 连续块拼接快路径：命中返回 ``(values, offsets)``，否则 None。

    语义与 ``torch.cat(components, dim=0)`` 逐位一致（纯拷贝、输出全新连续
    缓冲）。所有组件连续、同 dtype、同尾随形状、同设备时，拼接对每个组件
    就是一次平坦整块搬运；offsets 一并由同一 kernel 在设备侧写出，整个
    values+offsets 组装只花一次 kernel launch、零 host->device 拷贝。
    """
    count = len(components)
    if count == 0 or count > _MAX_POINTERS:
        return None
    first = components[0]
    if first.device.type not in ("gcu", "cuda"):
        return None
    dtype = first.dtype
    if dtype not in _FAST_DTYPES:
        return None
    trailing = tuple(first.shape[1:])
    itemsize = first.element_size()
    numels = []
    leads = []
    for tensor in components:
        if (
            tensor.dtype != dtype
            or tensor.device != first.device
            or not tensor.is_contiguous()
            or tuple(tensor.shape[1:]) != trailing
        ):
            return None
        numels.append(tensor.numel())
        leads.append(tensor.shape[0])
    total = sum(numels)
    if total * itemsize > _INT32_LIMIT_BYTES:
        return None

    out_shape = (sum(leads),) + trailing
    out = torch.empty_strided(
        out_shape,
        _contiguous_strides(out_shape),
        dtype=dtype,
        device=first.device,
    )
    offsets = torch.empty_strided(
        (count + 1,), (1,), dtype=torch.int64, device=first.device
    )
    offsets_list = [0]
    for lead in leads:
        offsets_list.append(offsets_list[-1] + lead)
    if total == 0:
        # 零体积：不 launch，offsets 直接以 pinned CPU 张量异步入队（一次性
        # 小拷贝，此路径无后续 kernel 争用）。
        try:
            offsets = torch.tensor(offsets_list, dtype=torch.int64, pin_memory=True).to(
                first.device, non_blocking=True
            )
        except Exception:
            offsets = torch.tensor(offsets_list, dtype=torch.int64, device=first.device)
        return out, offsets

    # 宽通道条件：dtype 字节数 <= 4、各组件字节数 8 对齐且数据指针 8B 对齐
    # （kernel 侧按 int64 位重解释；未对齐视图走元素路径保正确）。
