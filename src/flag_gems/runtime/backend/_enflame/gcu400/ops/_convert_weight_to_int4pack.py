@libentry()
@triton.jit
def convert_weight_to_int4pack_kernel(
    inp_ptr,
    out_ptr,
    M,
    N,
    innerKTiles: tl.constexpr,
    BLOCK_SIZE: tl.constexpr,
):
    """
    Convert weight tensor to int4 packed format.

    Input: int32 tensor of shape (M, N)
    Output: uint8 tensor of shape (M, N//2) where each byte contains two 4-bit values

    The packing follows the pattern: for each pair of int4 values (a, b),
    they are packed as: (b << 4) | a  (little-endian within the byte)
    """
    # Each program processes one row
    row_idx = tle.program_id(0)
    if row_idx >= M:
        return

    # Each thread processes BLOCK_SIZE output elements
    col_offs = tl.arange(0, BLOCK_SIZE)
    out_n = col_offs
    out_mask = out_n < (N // 2)

    # Input offsets for even and odd positions
    even_inp_offs = out_n * 2
    odd_inp_offs = out_n * 2 + 1
    inp_even_mask = even_inp_offs < N
    inp_odd_mask = odd_inp_offs < N

    # Load values
    even_ptrs = inp_ptr + row_idx * N + even_inp_offs
    odd_ptrs = inp_ptr + row_idx * N + odd_inp_offs

    even_val = tl.load(even_ptrs, mask=inp_even_mask, other=0)
    odd_val = tl.load(odd_ptrs, mask=inp_odd_mask, other=0)

    # Mask to 4 bits (int4 range: 0-15)
    even_val = even_val & 0xF
    odd_val = odd_val & 0xF

    # Pack: lower 4 bits = even, upper 4 bits = odd
    packed = (odd_val << 4) | even_val

    # Store output
    out_ptrs = out_ptr + row_idx * (N // 2) + out_n
    tl.store(out_ptrs, packed, mask=out_mask)


