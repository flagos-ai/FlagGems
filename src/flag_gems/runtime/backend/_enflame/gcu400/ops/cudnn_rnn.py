def _compute_offsets(batch_sizes):
    """Return (input_offsets, output_offsets) for packed sequences."""
    inp_offs = [0]
    for bs in batch_sizes:
        inp_offs.append(inp_offs[-1] + bs)
    inp_offs.pop()  # remove last (total_len)
    out_offs = list(inp_offs)  # same layout for output
    return inp_offs, out_offs


def _triton_layer_forward(
    input_seq,
    hx,
    cx,
    w_ih,
    w_hh,
    b_ih,
    b_hh,
    w_hr,
    mode,
    reverse,
    batch_size,
    seq_len,
    input_dim,
    hidden_size,
    proj_size,
    batch_first,
    batch_sizes=None,
):
    """Run one RNN layer+dir using Triton kernels.

    When ``batch_sizes`` is not None, uses the packed variant.
    """
    device = input_seq.device
    dtype = input_seq.dtype
    hidden_out = proj_size if (proj_size > 0 and mode == _LSTM) else hidden_size
    is_packed = batch_sizes is not None
    max_batch = max(batch_sizes) if is_packed else batch_size

    # Reverse input if needed (non-packed only; packed handles reverse in-kernel)
    if reverse and not is_packed:
        input_seq = flip(input_seq, [0]).contiguous()

    # Compute offsets for packed layout
    inp_offs, out_offs = _compute_offsets(batch_sizes) if is_packed else (None, None)

    # Allocate output (use new_empty from input to get real tensors
    # even under flag_gems.use_gems() dispatch)
    if is_packed:
        total_len = input_seq.size(0)
        output = input_seq.new_empty(total_len, hidden_out, dtype=dtype)
    else:
        output = input_seq.new_empty(seq_len, max_batch, hidden_out, dtype=dtype)

    scratch_dim = max(hidden_out, hidden_size) if mode == _LSTM else hidden_out
    h_scratch = input_seq.new_empty(max_batch, scratch_dim, dtype=torch.float32)
    h_read = input_seq.new_empty(max_batch, scratch_dim, dtype=torch.float32)
    # raw hidden state feeding the LSTM projection; only used when proj_size > 0
    h_proj = (
        input_seq.new_empty(max_batch, hidden_size, dtype=torch.float32)
        if (w_hr is not None and mode == _LSTM)
        else input_seq.new_empty(0, dtype=torch.float32)
    )

    hy_out = input_seq.new_empty(max_batch, hidden_out, dtype=dtype)
    cy_out = (
        input_seq.new_empty(max_batch, hidden_size, dtype=dtype)
        if mode == _LSTM
        else None
    )
    c_scratch = (
        input_seq.new_empty(max_batch, hidden_size, dtype=torch.float32)
        if mode == _LSTM
        else None
    )

    grid = (max_batch,)

    has_bias_flag = b_ih is not None
    if not has_bias_flag:
        b_dummy = input_seq.new_empty(0, dtype=torch.float32)
        b_ih_ptr = b_hh_ptr = b_dummy
    else:
        b_ih_ptr = b_ih.contiguous()
        b_hh_ptr = b_hh.contiguous()

    w_hr_ptr = (
        w_hr if (w_hr is not None) else input_seq.new_empty(0, dtype=torch.float32)
    )

    with runtime.torch_device_fn.device(device):
        if is_packed:
            # Packed path
            bs_t = torch.tensor(batch_sizes, dtype=torch.int32, device=device)
            io_t = torch.tensor(inp_offs, dtype=torch.int32, device=device)
            oo_t = torch.tensor(out_offs, dtype=torch.int32, device=device)
            num_steps = len(batch_sizes)

            if mode in (_RNN_RELU, _RNN_TANH):
                nonlinearity = 0 if mode == _RNN_RELU else 1
                _rnn_packed_kernel[grid](
                    input_seq,
                    hx,
                    w_ih,
                    w_hh,
                    b_ih_ptr,
                    b_hh_ptr,
                    output,
                    hy_out,
                    h_scratch,
                    h_read,
                    bs_t,
                    io_t,
                    oo_t,
                    num_steps,
                    max_batch,
                    input_dim,
                    hidden_out,
                    nonlinearity,
                    has_bias_flag,
                    reverse,
                    BLOCK_SIZE=64,
                )
            elif mode == _LSTM:
                _lstm_packed_kernel[grid](
                    input_seq,
                    hx,
                    cx,
                    w_ih,
                    w_hh,
                    w_hr_ptr,
                    b_ih_ptr,
                    b_hh_ptr,
                    output,
                    hy_out,
                    cy_out,
                    h_scratch,
                    h_read,
                    h_proj,
                    c_scratch,
                    bs_t,
                    io_t,
                    oo_t,
                    num_steps,
                    max_batch,
                    input_dim,
                    hidden_size,
                    proj_size,
                    has_bias_flag,
                    w_hr is not None,
                    reverse,
                    BLOCK_SIZE=64,
                )
            elif mode == _GRU:
                _gru_packed_kernel[grid](
                    input_seq,
                    hx,
                    w_ih,
                    w_hh,
                    b_ih_ptr,
                    b_hh_ptr,
                    output,
                    hy_out,
                    h_scratch,
                    h_read,
                    bs_t,
                    io_t,
                    oo_t,
                    num_steps,
                    max_batch,
                    input_dim,
                    hidden_size,
                    has_bias_flag,
                    reverse,
                    BLOCK_SIZE=64,
                )
        else:
            # Uniform batch path
            if mode in (_RNN_RELU, _RNN_TANH):
                nonlinearity = 0 if mode == _RNN_RELU else 1
                _rnn_kernel[grid](
                    input_seq,
                    hx,
                    w_ih,
                    w_hh,
                    b_ih_ptr,
                    b_hh_ptr,
                    output,
                    hy_out,
                    h_scratch,
                    h_read,
                    seq_len,
                    max_batch,
                    input_dim,
                    hidden_out,
                    batch_first,
                    nonlinearity,
                    has_bias_flag,
                    BLOCK_SIZE=64,
                )
            elif mode == _LSTM:
                c_scratch = torch.empty(
                    max_batch, hidden_size, device=device, dtype=torch.float32
                )
                _lstm_kernel[grid](
                    input_seq,
                    hx,
                    cx,
                    w_ih,
                    w_hh,
                    w_hr_ptr,
                    b_ih_ptr,
                    b_hh_ptr,
                    output,
                    hy_out,
                    cy_out,
                    h_scratch,
                    h_read,
                    h_proj,
                    c_scratch,
                    seq_len,
                    max_batch,
                    input_dim,
                    hidden_size,
                    proj_size,
                    batch_first,
                    has_bias_flag,
                    w_hr is not None,
                    BLOCK_SIZE=64,
                )
            elif mode == _GRU:
                _gru_kernel[grid](
                    input_seq,
                    hx,
                    w_ih,
                    w_hh,
                    b_ih_ptr,
                    b_hh_ptr,
                    output,
                    hy_out,
                    h_scratch,
                    h_read,
                    seq_len,
                    max_batch,
                    input_dim,
                    hidden_size,
                    batch_first,
                    has_bias_flag,
                    BLOCK_SIZE=64,
                )

    # Reverse output back if needed (non-packed only; packed handles in-kernel)
    if reverse and not is_packed:
        output = flip(output, [0]).contiguous()

    return output, hy_out, cy_out


