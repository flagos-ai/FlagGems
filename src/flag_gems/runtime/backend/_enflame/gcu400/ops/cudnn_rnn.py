def _lstm_kernel(
    input_ptr,
    hx_ptr,
    cx_ptr,
    weight_ih_ptr,
    weight_hh_ptr,
    w_hr_ptr,
    bias_ih_ptr,
    bias_hh_ptr,
    output_ptr,
    hy_ptr,
    cy_ptr,
    h_scratch_ptr,
    h_read_ptr,
    h_proj_ptr,
    c_scratch_ptr,
    seq_len,
    batch_size,
    input_dim,
    hidden_size,
    proj_size,
    batch_first: tl.constexpr,
    has_bias: tl.constexpr,
    has_proj: tl.constexpr,
    BLOCK_SIZE: tl.constexpr,
):
    """Single-layer LSTM — uniform batch.  Grid: ``(batch_size,)``."""
    batch_idx = tl.program_id(0)
    if batch_idx >= batch_size:
        return

    CHUNK: tl.constexpr = 64
    hidden_out = proj_size if has_proj else hidden_size
    num_cell_blocks = tl.cdiv(hidden_size, BLOCK_SIZE)
    chunk_offs = tl.arange(0, CHUNK)
    bid_offs = tl.arange(0, BLOCK_SIZE)

    _init_hidden(
        h_scratch_ptr,
        hx_ptr,
        batch_idx,
        hidden_out,
        tl.cdiv(hidden_out, BLOCK_SIZE),
        BLOCK_SIZE,
    )
    _init_cell(
        c_scratch_ptr, cx_ptr, batch_idx, hidden_size, num_cell_blocks, BLOCK_SIZE
    )

    if batch_first:
        batch_inp_stride = seq_len * input_dim
        batch_out_stride = seq_len * hidden_out
    else:
        batch_inp_stride = input_dim
        batch_out_stride = hidden_out

    h_scratch_base = h_scratch_ptr + batch_idx * hidden_out
    h_read_base = h_read_ptr + batch_idx * hidden_out
    h_proj_base = h_proj_ptr + batch_idx * hidden_size
    c_scratch_base = c_scratch_ptr + batch_idx * hidden_size

    for t in range(seq_len):
        if batch_first:
            t_inp_off = batch_idx * batch_inp_stride + t * input_dim
            t_out_off = batch_idx * batch_out_stride + t * hidden_out
        else:
            t_inp_off = t * (batch_size * input_dim) + batch_idx * input_dim
            t_out_off = t * (batch_size * hidden_out) + batch_idx * hidden_out

        # double-buffer snapshot
        for hid_block in range(tl.cdiv(hidden_out, BLOCK_SIZE)):
            offs = hid_block * BLOCK_SIZE + bid_offs
            mask = offs < hidden_out
            tl.store(
                h_read_base + offs,
                tl.load(h_scratch_base + offs, mask=mask, other=0.0),
                mask=mask,
            )
        # h_read is read by other warps below; fence the stores first.
        tl.debug_barrier()

        # ---- step 1: compute LSTM gates per hidden_size block ----
        for cell_block in range(num_cell_blocks):
            cell_start = cell_block * BLOCK_SIZE
            c_offs = cell_start + bid_offs
            c_mask = c_offs < hidden_size
            cell_val = tl.load(c_scratch_base + c_offs, mask=c_mask, other=0.0).to(
                tl.float32
            )

            i_gate = tl.zeros([BLOCK_SIZE], dtype=tl.float32)
            f_gate = tl.zeros([BLOCK_SIZE], dtype=tl.float32)
            g_gate = tl.zeros([BLOCK_SIZE], dtype=tl.float32)
            o_gate = tl.zeros([BLOCK_SIZE], dtype=tl.float32)

            for gate_idx in tl.static_range(4):
                gate_offs = cell_start + gate_idx * hidden_size + bid_offs
                gate_mask = (cell_start + bid_offs) < hidden_size

                # ---- ih ----
                ih_acc = tl.zeros([BLOCK_SIZE], dtype=tl.float32)
                for inp_start in range(0, input_dim, CHUNK):
                    i_offs = inp_start + chunk_offs
                    i_mask = i_offs < input_dim
                    w_offs = gate_offs[:, None] * input_dim + i_offs[None, :]
                    w_mask = gate_mask[:, None] & i_mask[None, :]
                    w_tile = tl.load(weight_ih_ptr + w_offs, mask=w_mask, other=0.0).to(
                        tl.float32
                    )
                    x_tile = tl.load(
                        input_ptr + t_inp_off + i_offs, mask=i_mask, other=0.0
                    ).to(tl.float32)
                    ih_acc += tl.sum(w_tile * x_tile[None, :], axis=1)
                if has_bias:
                    ih_acc += tl.load(
                        bias_ih_ptr + gate_offs, mask=gate_mask, other=0.0
                    ).to(tl.float32)

                # ---- hh ----
                hh_acc = tl.zeros([BLOCK_SIZE], dtype=tl.float32)
                for hid_in_start in range(0, hidden_out, CHUNK):
                    j_offs = hid_in_start + chunk_offs
                    j_mask = j_offs < hidden_out
                    w_offs = gate_offs[:, None] * hidden_out + j_offs[None, :]
                    w_mask = gate_mask[:, None] & j_mask[None, :]
                    w_tile = tl.load(weight_hh_ptr + w_offs, mask=w_mask, other=0.0).to(
                        tl.float32
                    )
                    h_tile = tl.load(h_read_base + j_offs, mask=j_mask, other=0.0).to(
                        tl.float32
                    )
                    hh_acc += tl.sum(w_tile * h_tile[None, :], axis=1)
                if has_bias:
                    hh_acc += tl.load(
                        bias_hh_ptr + gate_offs, mask=gate_mask, other=0.0
                    ).to(tl.float32)

                gate = ih_acc + hh_acc
                if gate_idx == 0:
                    i_gate = tl.sigmoid(gate)
                elif gate_idx == 1:
                    f_gate = tl.sigmoid(gate)
                elif gate_idx == 2:
                    g_gate = tl_extra_shim.tanh(gate)
                else:
                    o_gate = tl.sigmoid(gate)

            c_new = f_gate * cell_val + i_gate * g_gate
            h_raw = o_gate * tl_extra_shim.tanh(c_new)

            tl.store(c_scratch_base + c_offs, c_new, mask=c_mask)

            if not has_proj:
                tl.store(
                    output_ptr + t_out_off + cell_start + bid_offs, h_raw, mask=c_mask
                )
                tl.store(h_scratch_base + cell_start + bid_offs, h_raw, mask=c_mask)
            else:
                # keep the raw h for the projection step; h_scratch holds the
                # projected values and h_read the recurrent snapshot, so the
                # raw h needs its own buffer
                tl.store(h_proj_base + cell_start + bid_offs, h_raw, mask=c_mask)
        # the gate loop writes h_proj, read by the projection step below.
        if has_proj:
            tl.debug_barrier()

        # ---- step 2: projection ----
        if has_proj:
            for proj_block in range(tl.cdiv(proj_size, BLOCK_SIZE)):
                p_start = proj_block * BLOCK_SIZE
                p_offs = p_start + bid_offs
                p_mask = p_offs < proj_size

                proj_acc = tl.zeros([BLOCK_SIZE], dtype=tl.float32)
                for hid_in_start in range(0, hidden_size, CHUNK):
                    j_offs = hid_in_start + chunk_offs
                    j_mask = j_offs < hidden_size
                    w_offs = p_offs[:, None] * hidden_size + j_offs[None, :]
                    w_mask = p_mask[:, None] & j_mask[None, :]
                    w_tile = tl.load(w_hr_ptr + w_offs, mask=w_mask, other=0.0).to(
                        tl.float32
                    )
                    h_tile = tl.load(h_proj_base + j_offs, mask=j_mask, other=0.0).to(
                        tl.float32
                    )
                    proj_acc += tl.sum(w_tile * h_tile[None, :], axis=1)

                tl.store(
                    output_ptr + t_out_off + p_start + bid_offs, proj_acc, mask=p_mask
                )
                tl.store(h_scratch_base + p_start + bid_offs, proj_acc, mask=p_mask)

    # final → hy, cy
    for hid_block in range(tl.cdiv(hidden_out, BLOCK_SIZE)):
        offs = hid_block * BLOCK_SIZE + bid_offs
        mask = offs < hidden_out
        tl.store(
            hy_ptr + batch_idx * hidden_out + offs,
            tl.load(h_scratch_base + offs, mask=mask, other=0.0),
            mask=mask,
        )
    for cell_block in range(num_cell_blocks):
        offs = cell_block * BLOCK_SIZE + bid_offs
        mask = offs < hidden_size
        tl.store(
            cy_ptr + batch_idx * hidden_size + offs,
            tl.load(c_scratch_base + offs, mask=mask, other=0.0),
            mask=mask,
        )


