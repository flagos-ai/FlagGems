# =============================================================================
# Conventions for this operator (kept self-consistent across kernel, test, benchmark):
#
# 1. mat2 shape: (N, K//2) dtype=uint8
#    - N = output channels, K = input features (must be even).
#    - Each byte packs two int4 values: low nibble (bits 0-3) for even column 2*j,
#      high nibble (bits 4-7) for odd column (2*j+1).
#    - This is the same byte-pair packing used by _convert_weight_to_int4pack.
#
# 2. int4 value interpretation: unsigned 0..15.
#    Dequant: w = (q - zero) * scale
#    where q ∈ [0, 15] is the unsigned 4-bit value.
#
# 3. qScale shape: (G, N) where G = K // qGroupSize, dtype = same as A.
#    qZeros shape: (G, N), dtype = same as A.
#    - Grouping is along the K dimension: features k in range
#      [g*qGroupSize, (g+1)*qGroupSize) share scale/zero qScale[g, n] / qZeros[g, n]
#      for output channel n.
#    - qGroupSize must divide K evenly.
#
# 4. Output shape: (M, N) = matmul(A, W_deq) where A is (M, K) and
#    W_deq is the dequantized weight matrix of shape (K, N).
#    Output dtype matches A's dtype.
#
# GCU400 structure notes (triton_gcu 4.1.6):
#
# a) No layout-conversion chain. A historical form interleaved the two nibble
#    fragments with tl.join + tl.permute + tl.reshape before a single tl.dot;
#    on this toolchain that chain silently corrupts output for K >= 2048 and
#    transiently emits NaN when several constexpr variants are compiled in one
#    process. All arms decode the nibbles arithmetically instead:
#
#    - SPLIT_DOTS (K > 32): sum_k a[k]*w[k] is split into
#      dot(a_even, w_lo) + dot(a_odd, w_hi) over the two nibble fragments.
#      WIDE_A loads A as one full-width (BLOCK_M, BLOCK_K) tile (stride-1
#      columns) and de-interleaves with tl.reshape + tl.split -- measured
#      1.15-1.35x over two stride-2 half-width loads on K >= 2048 shapes
#      (e.g. (1024,4096,1024) 2062 -> 1942us; (2048,4096,4096) 19331 -> 14400us;
#      skinny (8,4096,4096) 395 -> 218us at BN=128). tl.reshape+tl.split is a
#      different lowering path from the miscompiling join+permute chain and is
#      accuracy-checked fresh-process deterministic up to K = 8192.
#    - byte-repeat arm (K <= 32): each mat2 byte is loaded onto its two
#      consecutive K rows and the parity of k selects the nibble via a
#      variable shift; a single full-K dot follows. This is the latency
#      winner in the tiny-K regime (GCU400 do_bench at M=4,K=16,N=8:
#      7.4us vs 9.8us for the split arm).
#
# b) Tile/flag specialization (host-side metadata only):
#    - BLOCK sizes bucket by (M, N, K): BLOCK_M in {16,32,64,128},
#      BLOCK_N in {16,32,64,128} (occupancy-aware shrink for N > 128 so at
#      least ~24 programs stay live), BLOCK_K = K for K <= 32, else
#      {64, 128, 256} by K bucket.
#    - num_warps = 1 / num_stages <= 2: the dot-dense small-tile family rule.
#      num_warps=2 on (128,128,256) tiles doubles per-program DSM past the
#      448KB 48-way threshold (606KB -> 24-way) and costs 2.7x.
#    - SINGLE_GROUP (qGroupSize >= BLOCK_K): the whole K-block shares one
#      quantization group, so scale/zero load as a single (BLOCK_N,) row and
#      broadcast instead of the redundant-row (BLOCK_K//2, BLOCK_N) tile.
#    - EVEN_K / EVEN_M / EVEN_N: compile-time drop of bounds masks when the
#      corresponding dimension divides its block exactly.
#    - EVEN_QGROUP (split arm): when qGroupSize is even both nibbles of a byte
#      share one quantization group, so scale/zero are loaded once, not twice.
#    - GROUP_M = 8 pid swizzle for L2 reuse on wide-K split launches.
#
# c) The kernel reads its program id with plain `tl.program_id(0)` (int32) on
#    purpose: `tle.program_id` widens the id to int64, which propagates i64
#    through every tile offset and address computation. On GCU400 that alone
#    costs ~6x on this GEMM family (same-process A/B at (8,4096,4096),
#    (16,128,256,nw1,ns2) tiles: 1128us with i64 pid vs 186us with i32 pid,
#    bitwise-identical outputs). Grid stays far below 2^31 programs, so i32
#    is the safe domain here.
#
# d) Measured (GCU400/Libra, triton_gcu 4.1.6, fp16, qGroupSize=64,
#    full op path do_bench median w1000/r100 unless noted):
#    bench tiny shapes topsprof kernel Avg 7.46/6.52/7.23/13.37us (2026-11-13
#    round) -> 4.85/5.02/5.85/6.83us; production shapes 258.7 -> 145.1us
#    ((256,2048,256)), 6366 -> 1887us ((1024,4096,1024)), 50075 -> 14013us
#    ((2048,4096,4096)), 833.6 -> 212.1us ((8,4096,4096)), decode
#    (1,4096,11008) -> 434.6us. The official legacy benchmark wraps
#    `use_gems()` inside the timed closure (~17ms of per-call ATen
#    registration), so its recorded speedup stays ~0.3x regardless of
#    kernel time; the numbers above are the op-level truth.
# =============================================================================


