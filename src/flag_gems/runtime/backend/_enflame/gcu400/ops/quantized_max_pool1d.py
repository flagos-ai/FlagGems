# GCU quantized-tensor carrier (torch_gcu has no Quantizedgcu kernels).
#
# torch_gcu registers none of the aten primitives that mint a quantized tensor
# on the GCU (``empty_quantized`` / ``_empty_affine_quantized`` /
# ``quantize_per_tensor`` / ``quantize_per_channel`` /
# ``_make_per_tensor_quantized_tensor`` / a quantized ``.to("gcu")`` all raise
# "Could not run ... with arguments from the 'Quantizedgcu' backend"), so
# ``aten::quantized_max_pool1d`` cannot even be fed on this backend.  The
# workaround mirrors the P21 ``quantized_max_pool3d`` delivery: represent a GCU
# quantized tensor as a CPU-built QuantizedCPU tensor whose storage has been
# swapped (``Tensor.set_``) onto a plain GCU integer buffer.  All metadata
# (dtype / scale / zero_point / qscheme / sizes / strides / offset) stays on
# the tensor, while the data path goes through plain integer views (``uint8``
# / ``int8`` / ``int32``), which GCU fully supports.  Every interception below
# is restricted to the quantized + gcu domain, which natively fails 100% of
# the time today, so there is no behaviour to fall back over; everything else
# is forwarded to the original primitives untouched.
_QSHIM_ATTR = "_flaggems_gcu_quantized_shim"


