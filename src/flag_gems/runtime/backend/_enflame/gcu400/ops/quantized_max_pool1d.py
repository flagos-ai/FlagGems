        if param is None or isinstance(param, int):
            return
        if not isinstance(param, (list, tuple)):
            raise RuntimeError(f"max_pool1d() {name} must be an int or a list of ints")
        if len(param) != 1:
            raise RuntimeError(message.format(size=len(param)))

