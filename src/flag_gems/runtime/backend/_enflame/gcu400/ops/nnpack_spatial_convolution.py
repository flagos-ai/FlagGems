                    m = ow_valid & (ih >= 0) & (ih < H) & (iw >= 0) & (iw < W)
                    xv = tl.load(
                        x_n + ic_i * sxc + ih * sxh + iw * sxw, mask=m, other=0.0
                    )
                    wv = tl.load(
                        w_ptr + oc * swo + ic_i * swc + (kh_i * swh + kw_i * sww),
                        mask=oc_valid,
                        other=0.0,
                    )
                    v = wv[:, None] * xv[None, :]
                    t = s + v
