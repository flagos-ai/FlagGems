def _fill_word(padding_value, dtype):
    """Bit pattern of the padding value replicated to fill one int32 word.

    The flat kernels move data as int32 words (2 bytes/element dtypes pack the
    same 16-bit pattern twice), so the fill constant must be pre-computed on
    the host in the word domain.
    """
    try:
        scalar = torch.tensor(padding_value, dtype=dtype)
    except (TypeError, RuntimeError, ValueError):
        # Integer targets with fractional padding: aten truncates toward zero.
        scalar = torch.tensor(int(padding_value), dtype=dtype)
    if scalar.element_size() == 4:
        word = scalar.view(torch.int32).item() & 0xFFFFFFFF
    else:
        half = scalar.view(torch.int16).item() & 0xFFFF
        word = half | (half << 16)
    return word - (1 << 32) if word >= (1 << 31) else word


