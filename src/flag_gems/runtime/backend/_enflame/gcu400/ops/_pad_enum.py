# GCU400 (Libra) launch form: one 48-program wave plus a grid-stride loop over
# row x column tiles.  The old one-program-per-BLOCK flat launch exceeded the
# 65535 grid.x hardware cap for >= 2^30-element tensors (benchmark
# OutOfResources), and grids beyond one wave pay ~2.4us per extra 48-program
# batch (measured in as_strided_copy), so the tile count never enters the
# grid.  Tiles carry ~128 KiB per load/store buffer (ROWS x BLOCK_COL x esize,
# capped by _TILE_BYTES), keeping the load+store+mask DSM peak <= ~320 KiB,
# inside the 448 KiB per-program budget that preserves dual-program/SP
# scheduling.
_GRID_CAP = 48
_TILE_BYTES = 131072
_BC_MAX = 32768
_NUM_WARPS = 4
_RU2 = 512
_RU3 = 16
# Large-tensor safety gate (device-measured): the enflame Triton backend
# lowers a masked vector load to tops_masked_gather with 32-bit scaled
# offsets whenever the mask is not a plain trailing slice bound.  The byte
# offset (element offset x dtype size) then wraps past 2^31, so any kernel
# relying on that form corrupts unmapped VA and aborts with a SIP fault once
# the tensor byte reach crosses ~2 GiB (3 GiB fp32 aborts while 2 GiB fp32 /
# 2 GiB fp16 pass).  Below the gate the tiled kernel is safe; above it the
# large kernel uses only unmasked affine loads/stores with computed i64
# offsets (the randn WIDE / as_strided divmod classes), which stay 64-bit
# safe at any size.
_SAFE_BYTES = 2**31 - 2**20


