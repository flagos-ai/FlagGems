def _pad_enum_boundary_pass(
    x_ptr,
    out_ptr,
    value,
    pid,
    in_shape: tl.constexpr,
    out_shape: tl.constexpr,
    in_stride: tl.constexpr,
    row_stride: tl.constexpr,
    pad_left: tl.constexpr,
    NDIM: tl.constexpr,
    MODE: tl.constexpr,
    W_IN: tl.constexpr,
    W_OUT: tl.constexpr,
    PAD_L: tl.constexpr,
    D: tl.constexpr,
    C_BASE: tl.constexpr,
    C_LEN: tl.constexpr,
    NBLK: tl.constexpr,
    RU3: tl.constexpr,
    BC3: tl.constexpr,
    GRID: tl.constexpr,
):
    # Rows whose coordinate along outer dim D lies in [C_BASE, C_BASE + C_LEN).
    # Those rows are the contiguous range [j*P + C_BASE*S'_D, ... + C_LEN*S'_D)
    # for each period j < NBLK (P = out_shape[D]*S'_D), all constexpr-derived.
    PERIOD: tl.constexpr = row_stride[D] * out_shape[D]
    BLOCK_ROWS: tl.constexpr = C_LEN * row_stride[D]
    TPB: tl.constexpr = (BLOCK_ROWS + RU3 - 1) // RU3
    COL_TILES: tl.constexpr = (W_OUT + BC3 - 1) // BC3
    total = NBLK * TPB * COL_TILES
