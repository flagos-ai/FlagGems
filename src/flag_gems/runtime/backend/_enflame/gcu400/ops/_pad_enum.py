def _pad_enum_edge_pass(
    x_ptr,
    out_ptr,
    value,
    n_rows,
    pid,
    in_shape: tl.constexpr,
    out_shape: tl.constexpr,
    in_stride: tl.constexpr,
    row_stride: tl.constexpr,
    pad_left: tl.constexpr,
    NDIM: tl.constexpr,
    MODE: tl.constexpr,
    W_IN: tl.constexpr,
    W_OUT: tl.constexpr,
    PAD_L: tl.constexpr,
    C_BASE: tl.constexpr,
    C_LEN: tl.constexpr,
    BCE: tl.constexpr,
    RU2: tl.constexpr,
    GRID: tl.constexpr,
):
    # Edge columns [C_BASE, C_BASE + C_LEN) of every row.  The column tile
    # width is the padded power of two >= C_LEN; lanes past the end clamp
    # onto the region's last column (idempotent).  Out-of-range rows are not
    # redirected here: every value this pass computes for them equals what
    # phase 3 writes, so the overlap is idempotent.
    tiles = tl.cdiv(n_rows, RU2)
    for t in tl.range(pid, tiles, GRID):
        rows = t * RU2 + tl.arange(0, RU2)
        rows = tl.minimum(rows, n_rows - 1)
        in_base = tl.zeros((RU2,), dtype=tl.int64)
        for d in tl.static_range(NDIM - 1):
            c = (rows // row_stride[d]) % out_shape[d]
            j = c - pad_left[d]
            coord = _mode_row_coord(j, in_shape[d], MODE)
            in_base = in_base + coord.to(tl.int64) * in_stride[d]
        cols = C_BASE + tl.arange(0, BCE)
        cols = tl.minimum(cols, C_BASE + C_LEN - 1)
        rows64 = rows.to(tl.int64)
        offs_out = rows64[:, None] * W_OUT + cols[None, :]
        if MODE == 3:
            val = tl.full([1], value, dtype=out_ptr.dtype.element_ty)
            tl.store(out_ptr + offs_out, val)
        else:
            rel = cols - PAD_L
            in_col = _mode_col_offset(rel, W_IN, MODE)
            offs_in = in_base[:, None] + in_col[None, :]
            tl.store(out_ptr + offs_out, tl.load(x_ptr + offs_in))


