    num_pids = tl.num_programs(0)
    col_offsets = tl.arange(0, BLOCK_N)
    mask = col_offsets < N
    for row_id in tl.range(pid, num_rows, num_pids):
        offsets = row_id * stride_m + col_offsets
        row = tl.load(input_ptr + offsets, mask=mask, other=-float("inf")).to(
            tl.float32
        )
