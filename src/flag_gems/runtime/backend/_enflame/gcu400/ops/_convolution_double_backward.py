def _install_convolution_opad_bridge():
    if getattr(torch, _CONV_BRIDGE_FLAG, None) is not None:
        return
    if not hasattr(torch.library, "get_kernel"):
        return

    from flag_gems.runtime import device as _runtime_device

    dispatch_key = _runtime_device.dispatch_key
    try:
        native = torch.library.get_kernel(
            torch.ops.aten.convolution.default, dispatch_key
        )
        keyset = torch._C.DispatchKeySet(getattr(torch._C.DispatchKey, dispatch_key))
    except Exception:
        # No native kernel to delegate to (or unsupported torch build): keep
        # the default dispatch untouched instead of installing a bridge that
        # could never complete a call.
        return
    if native is None:
        return

    def _aten_convolution_gcu(
        input,
        weight,
        bias,
        stride,
        padding,
        dilation,
        transposed,
        output_padding,
        groups,
    ):
        if transposed and (
            any(int(p) != 0 for p in (output_padding or ())) or weight.dim() - 2 == 3
        ):
            return _conv_transpose_opad_rescue(
                input, weight, bias, stride, padding, dilation, output_padding, groups
            )
        return native.call_boxed(
            keyset,
            input,
            weight,
            bias,
            stride,
            padding,
            dilation,
            transposed,
            output_padding,
            groups,
        )

    library = torch.library.Library("aten", "IMPL")
    try:
        library.impl(
            "convolution", _aten_convolution_gcu, dispatch_key, allow_override=True
        )
    except TypeError:
        # Older torch builds have no allow_override parameter.
        library.impl("convolution", _aten_convolution_gcu, dispatch_key)

    setattr(
        torch,
        _CONV_BRIDGE_FLAG,
        types.SimpleNamespace(native=native, library=library),
    )


