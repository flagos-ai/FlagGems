"""GCU400-specific _foreach_pow_.List (in-place) and _foreach_pow.List (out-of-place).

The common foreach executor carries the tensor list in a 2D grid, and GCU400's ``grid.y``
limit of 255 causes ``out of resource`` on large shapes. Contiguous float lists use the
1D fixed grid / metadata fused kernel from ``_foreach_flat``; non-float,
non-contiguous or broadcast shapes still delegate to the common executor to keep dtype policy and exception semantics.

The out-of-place ``.List`` overload keeps its own single-launch kernel here: the
shared ``_foreach_binary`` flat path settles on a 2-parts/16384 geometry that leaves
16 of the 48 cores idle on a sixteen-tensor list, while ``pow`` is transcendental
bound (probe ladder: the exp2/log2 math is ~75% of the runtime), so it prefers
the full 48-program grid with narrower tiles and an unmasked exact arm.
Broadcast ``.List`` forms (single-element second operands) route through the
same per-tensor broadcast layer the in-place overload uses: the shared flat
and common executors read the second list with the first list's flat index,
which is an out-of-bounds read against a one-element allocation.
"""

import logging
from math import gcd

import torch
import triton
import triton.language as tl

from flag_gems.ops._foreach_binary import _apply_list
from flag_gems.utils import libentry
from flag_gems.utils.foreach import _device_meta

from ._foreach_binary import _apply_list as _apply_list_local
from ._foreach_binary import _pow_fn
from ._foreach_flat import (
    _TL_DTYPES,
    FALLBACK,
    MODE_LIST,
    OP_POW,
    can_use_flat,
    run_binary,
)

logger = logging.getLogger(__name__)

# --- TUNING PARAMS START ---
# Generated by the optimization iteration driver in rounds; all are compile-time/launch-time settings and do not change
# operator semantics.
# Fast-path geometry (on this machine with the new stack Triton GCU 4.1.6, 20 P×B×w combinations × 3 dtypes × 3
# core shapes interleaved with do_bench and full coverage validation per combination): P3B32768w4s1 wins with
# mean 85.8us; B65536 is rejected for exceeding the compile-time DSM limit (1.18MB > 917KB),
# and P2/P4/P5/P6 and the B16384 tier are all 4-34% worse, while stages/warps are within the noise band.
FAST_PARTS_CAP = 3
FAST_BLOCK = 32768
FAST_WARPS = 4
FAST_STAGES = 1
# out-of-place .List fast-path geometry (2026-11-19 incremental round, 9 cells x {P2..P6} x
# {B4k..B32k} x {w1,w2,w4,w8} x {EXACT,mask} interleaved do_bench + probe ladder):
# pow's exp2/log2 math is ~75% of runtime (L0 floor 1024^2 16-bit 28.5us vs 122us full compute),
# so the geometry uses P3 (all 48 programs), the narrow tile B8192 and the EXACT mask-free arm;
# w2 is consistently -7~-10% vs w4 (w1/w8 regress), and s2/s1 fall inside the noise band so the
# simpler one is kept. Per-combo 16-tensor full-value verification (300^2 ragged masked arm
# included) all PASS.
OOP_PARTS_CAP = 3
OOP_BLOCK = 8192
OOP_WARPS = 2
OOP_STAGES = 1
# Narrow tiles for small lists. A masked tile much wider than the tensor leaves
# most lanes idle: 16x1024 elements cost 62.5us at B8192 but 4.2us at B1024, and
# 16x8192 elements cost 62.3us at B8192-masked but 6.1us at B2048. The 2026-11-20
# sweep over B{1k,2k,4k,8k} x n{512..16384} x 3 dtypes picks the widest tile that
# still fits the tensor, capped by OOP_BLOCK.
OOP_SMALL_NUMEL = 1024
OOP_SMALL_BLOCK = 1024
OOP_MEDIUM_NUMEL = 8192
OOP_MEDIUM_BLOCK = 2048
# Second-level broadcast path (run_binary) geometry, keeping the historical tiers.
FIXED_GRID = 48
BLOCK_SIZE = 1024
NUM_WARPS = 4
NUM_STAGES = 1
USE_DEVICE_CONTEXT = 0
FP32_PROMOTE = 1
FUSED_LAUNCH = 1
FALLBACK_TO_PUBLIC = 0
# --- TUNING PARAMS END ---

# GCU400 grid.x hard limit; the fast-path grid = nt * parts must stay entirely within the limit.
_MAX_GRID_X = 65535


@libentry()
@triton.jit
def fused_pow_list_ip_kernel(
    meta_ptr,
    fn: tl.constexpr,
    NT: tl.constexpr,
    A_DT: tl.constexpr,
    BLOCK: tl.constexpr,
    PARTS: tl.constexpr,
):
    """One launch performs in-place ``self ** other`` over the whole paired list.

    ``meta_ptr`` holds input, second operand and output (the input itself when in-place)
    addresses plus per-tensor element counts (NT items each, int64). The grid is linear over
    ``(tensor, part)`` and always ``NT * PARTS``: each tensor's ``PARTS`` programs split tiles
    with a stride of ``PARTS``, and coverage holes do not exist by construction.
    """
    pid = tl.program_id(0)
    tensor_id = pid % NT
    part_id = pid // NT

    a_ptr = tl.load(meta_ptr + tensor_id).to(tl.pointer_type(A_DT))
    b_ptr = tl.load(meta_ptr + NT + tensor_id).to(tl.pointer_type(A_DT))
    out_ptr = tl.load(meta_ptr + 2 * NT + tensor_id).to(tl.pointer_type(A_DT))
    n_elements = tl.load(meta_ptr + 3 * NT + tensor_id)

    arange = tl.arange(0, BLOCK)
    # Keep the tile count as i32, consistent with the address-arithmetic width of the common executor.
    num_tiles = tl.cdiv(n_elements, BLOCK).to(tl.int32)
    for block_id in tl.range(part_id, num_tiles, PARTS):
        idx = block_id * BLOCK + arange
        mask = idx < n_elements
        a = tl.load(a_ptr + idx, mask=mask, other=0)
        b = tl.load(b_ptr + idx, mask=mask, other=0)
        tl.store(out_ptr + idx, fn(a, b).to(A_DT), mask=mask)


@libentry()
@triton.jit
def fused_pow_list_kernel(
    meta_ptr,
    fn: tl.constexpr,
    NT: tl.constexpr,
    A_DT: tl.constexpr,
    EXACT: tl.constexpr,
    BLOCK: tl.constexpr,
    PARTS: tl.constexpr,
):
    """One launch performs out-of-place ``self ** other`` over the whole paired list.

    Shares the ``meta_ptr`` layout with the in-place version (input, second operand, output
    addresses and element counts, NT items each, int64), and the grid is likewise linear over
    ``(tensor, part)`` and always ``NT * PARTS`` with no coverage holes by construction. ``EXACT``
    removes the per-tile boundary mask when every element count divides ``BLOCK`` (the mask-free
    arm follows the maximum_List / addcdiv__Scalar family precedent); non-divisible ragged shapes
    take the masked arm with unchanged semantics.
    """
    pid = tl.program_id(0)
    tensor_id = pid % NT
    part_id = pid // NT

    a_ptr = tl.load(meta_ptr + tensor_id).to(tl.pointer_type(A_DT))
    b_ptr = tl.load(meta_ptr + NT + tensor_id).to(tl.pointer_type(A_DT))
    out_ptr = tl.load(meta_ptr + 2 * NT + tensor_id).to(tl.pointer_type(A_DT))
    n_elements = tl.load(meta_ptr + 3 * NT + tensor_id)

    arange = tl.arange(0, BLOCK)
    # Tile counts stay i32, matching the shared executor's address arithmetic width.
    num_tiles = tl.cdiv(n_elements, BLOCK).to(tl.int32)
    if EXACT:
        for block_id in tl.range(part_id, num_tiles, PARTS):
            idx = block_id * BLOCK + arange
            a = tl.load(a_ptr + idx)
            b = tl.load(b_ptr + idx)
            tl.store(out_ptr + idx, fn(a, b).to(A_DT))
    else:
        for block_id in tl.range(part_id, num_tiles, PARTS):
            idx = block_id * BLOCK + arange
            mask = idx < n_elements
            a = tl.load(a_ptr + idx, mask=mask, other=0)
            b = tl.load(b_ptr + idx, mask=mask, other=0)
            tl.store(out_ptr + idx, fn(a, b).to(A_DT), mask=mask)


def _scan_paired_list(self, other):
    """Validate a paired float list and collect pointers and counts in one pass.

    Equivalent to ``can_use_flat(self, other, MODE_LIST)`` plus the two extra
    conditions this file needs (equal element counts, one device), but expressed
    as a single traversal that also collects the pointers and element counts the
    metadata table needs. The shared helper walks the same list five times over
    (validation, element-count equality, device equality, pointers, counts),
    which costs ~25us of host time on a sixteen-tensor list and dominates the
    small shapes because the kernel itself is only a few microseconds.

    Returns ``(a_ptrs, b_ptrs, numels, max_numel, numel_gcd)`` or ``None`` when
    the caller must fall back to the shared executors. ``numel_gcd`` is the
    greatest common divisor of every element count, so a candidate tile width
    ``block`` is mask-free for the whole list exactly when
    ``numel_gcd % block == 0``, which keeps the tile decision free of a second
    pass over the list. A bitwise AND must not be used here: it reports "aligned"
    for the ragged list ``[128, 7]`` because the AND of the two counts is zero.
    """
    num_tensors = len(self)
    if (
        not num_tensors
        or not isinstance(other, (list, tuple))
        or len(other) != num_tensors
    ):
        return None
    first = self[0]
    if not isinstance(first, torch.Tensor):
        return None
    dtype = first.dtype
    if dtype not in _TL_DTYPES:
        return None
    device = first.device
    a_ptrs = []
    b_ptrs = []
    numels = []
    max_numel = 0
    numel_gcd = 0
    for tensor, other_tensor in zip(self, other):
        if (
            not isinstance(tensor, torch.Tensor)
            or not isinstance(other_tensor, torch.Tensor)
            or tensor.dtype != dtype
            or other_tensor.dtype != dtype
            or tensor.device != device
            or other_tensor.device != device
            or not tensor.is_contiguous()
            or not other_tensor.is_contiguous()
        ):
            return None
        numel = tensor.numel()
        # A single-element second operand is a broadcast form, not a paired one:
        # the broadcast layer reads it once per program, this kernel does not.
        if numel == 0 or numel != other_tensor.numel():
            return None
        a_ptrs.append(tensor.data_ptr())
        b_ptrs.append(other_tensor.data_ptr())
        numels.append(numel)
        if numel > max_numel:
            max_numel = numel
        numel_gcd = gcd(numel_gcd, numel)
    return a_ptrs, b_ptrs, numels, max_numel, numel_gcd


def _oop_block_for(max_numel):
    """Tile width for the out-of-place kernel, fitted to the largest tensor.

    A tile wider than the tensor wastes a masked arm on the whole list, so the
    width tracks the element count: 1024 up to OOP_SMALL_NUMEL, 2048 up to
    OOP_MEDIUM_NUMEL and OOP_BLOCK beyond that, where wide tiles win because each
    program can then stream several tiles.
    """
    if max_numel <= OOP_SMALL_NUMEL:
        return OOP_SMALL_BLOCK
    if max_numel <= OOP_MEDIUM_NUMEL:
        return OOP_MEDIUM_BLOCK
    return OOP_BLOCK


def _alloc_oop_outputs(self, numels, dtype, device):
    """Fresh contiguous outputs plus their addresses for the out-of-place path.

    A single flat allocation sliced into ``as_strided`` views was measured on the
    sixteen-tensor cells of the official benchmark: it saves ~32us of wall time
    per call but is invisible in the do_bench median, so the aten-identical
    per-tensor form is kept (independent storages, no aliasing).
    """
    outputs = [torch.empty_like(tensor) for tensor in self]
    return outputs, [tensor.data_ptr() for tensor in outputs]


def _run_pow_list_cached(self, other):
    """Uniform float paired list on one in-place launch (metadata read-only cache).

    Returns ``FALLBACK`` for every form the single-launch kernel cannot serve: a
    broadcast second list, mixed dtype / device / layout, or a grid above the
    hardware limit. The metadata table only holds addresses and element counts,
    so caching it never changes the computed values.
    """
    num_tensors = len(self)
    if not num_tensors or num_tensors * FAST_PARTS_CAP > _MAX_GRID_X:
        return FALLBACK
    scanned = _scan_paired_list(self, other)
    if scanned is None:
        return FALLBACK
    a_ptrs, b_ptrs, numels, max_numel, _ = scanned
    meta = _device_meta(a_ptrs + b_ptrs + a_ptrs + numels, self[0].device)
    parts = max(1, min(FAST_PARTS_CAP, -(-max_numel // FAST_BLOCK)))
    fused_pow_list_ip_kernel[(num_tensors * parts,)](
        meta,
        _pow_fn,
        num_tensors,
        _TL_DTYPES[self[0].dtype],
        FAST_BLOCK,
        parts,
        num_warps=FAST_WARPS,
        num_stages=FAST_STAGES,
    )
    return None


def _foreach_pow__List(self, other):
    logger.debug("GEMS_GCU400 _FOREACH_POW__LIST")

    def fallback():
        return _apply_list("pow", self, other, inplace=True)

    if FALLBACK_TO_PUBLIC:
        return fallback()
    result = _run_pow_list_cached(self, other)
    if result is not FALLBACK:
        # in-place schema contract: the dispatcher must return None.
        return None
    result = run_binary(
        self,
        other,
        OP_POW,
        MODE_LIST,
        True,
        fixed_grid=FIXED_GRID,
        block_size=BLOCK_SIZE,
        num_warps=NUM_WARPS,
        num_stages=NUM_STAGES,
        use_device_context=USE_DEVICE_CONTEXT,
        fp32_promote=FP32_PROMOTE,
        fused=FUSED_LAUNCH,
    )
    if result is FALLBACK:
        return fallback()
    return result


def _run_pow_list_oop(self, other):
    """Uniform float paired list on one out-of-place launch.

    Outputs are freshly allocated on every call, so their addresses differ
    between calls and the metadata cache simply misses, exactly like the shared
    flat path. Broadcast lists, mixed dtype / device / layout, empty tensors and
    grids above the hardware limit answer ``FALLBACK`` so that the shared
    executor keeps the dtype policy and the exception wording.
    """
    num_tensors = len(self)
    if not num_tensors or num_tensors * OOP_PARTS_CAP > _MAX_GRID_X:
        return FALLBACK
    scanned = _scan_paired_list(self, other)
    if scanned is None:
        return FALLBACK
    a_ptrs, b_ptrs, numels, max_numel, numel_gcd = scanned
    dtype = self[0].dtype
    device = self[0].device
    outputs, out_ptrs = _alloc_oop_outputs(self, numels, dtype, device)
    meta = _device_meta(a_ptrs + b_ptrs + out_ptrs + numels, device)
    block = _oop_block_for(max_numel)
    parts = max(1, min(OOP_PARTS_CAP, -(-max_numel // block)))
    exact = int(numel_gcd % block == 0)
    fused_pow_list_kernel[(num_tensors * parts,)](
        meta,
        _pow_fn,
        num_tensors,
        _TL_DTYPES[dtype],
        exact,
        block,
        parts,
        num_warps=OOP_WARPS,
        num_stages=OOP_STAGES,
    )
    return outputs


def _foreach_pow_List(self, other):
    logger.debug("GEMS_GCU400 _FOREACH_POW_LIST")

    results = _run_pow_list_oop(self, other)
    if results is not FALLBACK:
        return results
    if can_use_flat(self, other, MODE_LIST) and not all(
        other_tensor.numel() == tensor.numel()
        for tensor, other_tensor in zip(self, other)
    ):
        # Broadcast ``.List`` (second operand contains a 1-element tensor): both the shared flat
        # path and the shared executor read the second list by paired flat index, which is an
        # out-of-bounds read for a 1-element allocation (measured garbage output, while native
        # aten / CPU reference use broadcast semantics). This routes through the same per-tensor
        # broadcast layer as the in-place path (all three dtypes align with native, 0-dim and (1,)
        # second operands both covered).
        result = run_binary(
            self,
            other,
            OP_POW,
            MODE_LIST,
            False,
            fixed_grid=FIXED_GRID,
            block_size=BLOCK_SIZE,
            num_warps=NUM_WARPS,
            num_stages=NUM_STAGES,
            use_device_context=USE_DEVICE_CONTEXT,
            fp32_promote=FP32_PROMOTE,
            fused=FUSED_LAUNCH,
        )
        if result is not FALLBACK:
            return result
    # The shared ``_foreach_binary`` executor is the existing production path: the family flat
    # kernel goes first, anomalous shapes fall back, and bool rejection / dtype promotion / length checks are unchanged.
    return _apply_list_local("pow", self, other, inplace=False)
