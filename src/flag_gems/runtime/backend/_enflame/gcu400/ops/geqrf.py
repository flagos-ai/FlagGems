        # and the just-packed column j stay untouched); the reduction runs
        # along the last axis -- lane-local in this orientation
        vj = tl.where(
            reflect,
            tl.where(rows > j, v_tail, tl.where(rows == j, one, zero)),
            tl.where(rows == j, one, zero),
        )
