@triton.jit
def _block_pair(slot, step, m, inv2):
    ps = (step - slot) % m
    ps = tl.where(ps < 0, ps + m, ps)
    j0 = (step * inv2) % m
    ps = tl.where(slot == j0, m, ps)
    ps = tl.where(slot == m, j0, ps)
    return ps


