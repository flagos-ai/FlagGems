def _payload_view(qtensor, storage_dtype):
    """Alias a quantized tensor's storage as a plain integer tensor.

    Plain-tensor ``set_`` dispatches under the (working) gcu key, so the view
    is writable by ordinary kernels whatever layout the quantized tensor has;
    the storage offset is part of ``data_ptr()``, so an offset view addresses
    its own slice.
    """
    return torch.empty(0, dtype=storage_dtype, device=qtensor.device).set_(
        qtensor.untyped_storage(),
        qtensor.storage_offset(),
        tuple(qtensor.shape),
        qtensor.stride(),
    )


