def _int32_safe(a, out_int):
    """True when every address either side touches fits in an int32 index."""
    if a.numel() > _INT32_MAX or out_int.numel() > _INT32_MAX:
        return False

    def span(shape, strides):
        return sum((size - 1) * stride for size, stride in zip(shape, strides))

    return (
        span(a.shape, a.stride()) <= _INT32_MAX
        and span(out_int.shape, out_int.stride()) <= _INT32_MAX
    )


def _padded(values, ndim):
    """Pad a shape/stride tuple with 1s up to ``MAX_NDIM`` dimensions."""
    return tuple(values) + (1,) * (MAX_NDIM - ndim)


def _inv_scale_f32(scale):
    """fl32(1.0 / fl32(scale)) with torch's IEEE fp32 scalar division.

    ATen's CPU quantizer computes ``inverse_scale = 1.0f / (float)scale``;
    reproducing the exact same fp32 reciprocal (torch scalar division is
    correctly rounded, unlike the backend's fast reciprocal) keeps the kernel
    bit-identical to the runnable CPU reference. Results are cached per scale.
    """
    key = float(scale)
    cached = _INV_SCALE_CACHE.get(key)
    if cached is None:
        one = torch.tensor(1.0, dtype=torch.float32)
        s = torch.tensor(key, dtype=torch.float32)
        cached = float(one / s)
        _INV_SCALE_CACHE[key] = cached
    return cached


_INV_SCALE_CACHE = {}


def _f32_clamp_bounds(qmin, qmax):
    """Clamp bounds in the fp32 domain, kept inside the int32 representable range."""
    return (float(qmin), min(float(qmax), _F32_BELOW_INT32_MAX))


