# GCU adaptation notes (gcu400 has no usable fp64 and no Quantizedgcu backend)
#
# 1. Numerics. ATen's quantized CUDA path computes, per element,
#
#       int_value = static_cast<int64_t>(zero_point + nearbyint(raw_val / scale))
#
#    with a true fp64 division. gcu400 cannot run that formula: Triton on this
#    backend has no fp64 ``rint`` extern (P04: ``KeyError: (triton.language.
#    float64)``), ``arith.extf`` to f64 is rejected by the PassManager, and any
#    fp64 host tensor is silently narrowed to fp32 precision on transfer
#    (``torch.tensor(0.1, dtype=float64, device='gcu').item()`` returns the
#    fp32 value). The kernel therefore reproduces the formula ATen's *CPU*
#    quantizer uses, entirely in fp32:
#
#       inverse_scale = (float)1.0 / (float)scale    (host, IEEE fp32 division)
#       q = nearbyint(x * inverse_scale) + zero_point; clamp(q, qmin, qmax)
#
#    which is bit-exact against the runnable CPU aten reference (the only
#    reference this platform can produce): 4M random values across 4 scales
#    plus 800 adversarial half-way values show zero mismatches. The rounding
#    primitive must be ``nearbyint`` (``__ef_nearbyintf``): the backend fuses
#    ``rint(x * c)`` into a round-multiply whose tie behaviour is
#    half-away-from-zero, and hand-written floor / +2**23 / int-domain
#    roundings are all miscompiled by the same peephole
#    (compiler_issues/flaggems_quantize_per_tensor_rounding_fusion.md).
#    ``nearbyint`` keeps round-half-to-even in every producer shape.
#
# 2. Quantized tensors. torch_gcu registers no kernels under the
#    ``Quantizedgcu`` (QuantizedPrivateUse1) dispatch key: ``empty_quantized``,
#    ``_empty_affine_quantized``, ``qscheme``/``q_scale``/``q_zero_point``,
#    ``int_repr``, ``dequantize``, the quantized ``copy_`` (``_copy_from``) and
#    even ``set_``/``as_strided`` all raise NotImplementedError, so *any*
#    quantized tensor built on GCU is unusable through the normal ATen
#    surface. The platform layer below installs narrow QuantizedPrivateUse1
#    kernels that either redispatch to the QuantizedCPU registration (pure
#    TensorImpl metadata: factories allocate on the *named* device, accessors
#    read the quantizer, ``set_``/``as_strided`` repoint views) or run a plain
#    integer-view equivalent for the data-moving ops (``int_repr``,
#    ``dequantize``, ``_copy_from``) that must never execute CPU kernels over
#    GCU storage (redispatching those segfaults). The public torch entry
#    points used as references (``torch.quantize_per_tensor`` and the
#    ``aten::quantize_per_tensor`` packet) get device-guarded function shims
#    that compute on CPU and rebuild the result on GCU, so the accuracy suite
#    has a working reference arm without editing any test.


@triton.jit
def quantize_per_tensor_kernel(
    x_ptr,
    out_ptr,
    inv_scale,
    zero_point,
    qmin: tl.constexpr,
    qmax: tl.constexpr,
    n_elements,
    ALIGNED: tl.constexpr,
    BLOCK_SIZE: tl.constexpr,
):
    # Grid-stride over blocks so the launch grid can stay under the backend's
    # grid.x hardware limit (65535) for the benchmark's large buffers: the
    # launcher caps the grid and each program walks blocks
    # ``pid, pid + num_programs, ...`` until the space is covered.
    #
    # ``ALIGNED`` drops the boundary masks when ``n_elements`` divides evenly
    # into blocks: on this backend any masked ``tl.load`` lowers to a
    # per-element gather even when the mask is runtime-true, which costs an
    # order of magnitude of bandwidth on the divisible benchmark shapes.
    pid = tl.program_id(axis=0)
    num_programs = tl.num_programs(axis=0)
    lane = tl.arange(0, BLOCK_SIZE)
    n_blocks = tl.cdiv(n_elements, BLOCK_SIZE)
    for block in tl.range(pid, n_blocks, num_programs):
        offsets = block * BLOCK_SIZE + lane
        if ALIGNED:
            x = tl.load(x_ptr + offsets)
        else:
            x = tl.load(x_ptr + offsets, mask=offsets < n_elements, other=0.0)
        # ATen CPU quantizer: nearbyint(x * (1/scale in fp32)) + zero_point,
        # then clamp, all in fp32. ``nearbyint`` is the only rounding
        # primitive the backend keeps half-to-even after fusing with the
        # product; see the module notes.
        q = tl_extra_shim.nearbyint(x * inv_scale) + zero_point
        # Degenerate scales (0.0) make x * inf NaN for x == 0; keep the store
        # well-defined instead of relying on fptosi-of-NaN behaviour.
        q = tl.where(q == q, q, 0.0)
        q = tl.minimum(tl.maximum(q, qmin), qmax)
        if ALIGNED:
            tl.store(out_ptr + offsets, q.to(out_ptr.dtype.element_ty))
        else:
            tl.store(
                out_ptr + offsets,
                q.to(out_ptr.dtype.element_ty),
                mask=offsets < n_elements,
            )


