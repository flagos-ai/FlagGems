# 2**31 - 1, the largest value an int32 index can hold before the address
# arithmetic overflows.
_INT32_MAX = 2**31 - 1

# Largest fp32 strictly below 2**31; clamping qint32 to this bound keeps the
# fp32 -> int32 narrowing in range (float(2**31 - 1) rounds up to 2**31,
# whose fptosi is undefined).
_F32_BELOW_INT32_MAX = 2147483520.0

