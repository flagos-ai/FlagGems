def _upper_left_causal_mask(max_q, max_k, device):
    """Boolean causal mask aligned on the upper-left corner.

    ``True`` marks a masked-out (future) position, i.e. ``key_index >
    query_index``, which is the alignment used by the flash-attention reference
    reachable on this backend.  Only the non-square case needs it: for
    ``max_q == max_k`` the upper-left and the lower-right alignments coincide.
    """
    q_index = torch.arange(max_q, device=device)[:, None]
    k_index = torch.arange(max_k, device=device)[None, :]
    return k_index > q_index


