    oh = (offs // OW) % OH
    od = offs // (OW * OH)

    # Map output coordinates back to source (input) space.
    if SAME_D:
        src_d = od.to(tl.float32)
    else:
        src_d = od.to(tl.float32) * scale_d + bias_d
    if SAME_H:
        src_h = oh.to(tl.float32)
    else:
        src_h = oh.to(tl.float32) * scale_h + bias_h
