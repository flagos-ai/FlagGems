    col_offs = tl.arange(0, BLOCK_W)
    for tile in range(pid, total_tiles, num_programs):
        rb = tile // num_w_blocks
        cb = tile - rb * num_w_blocks
        rows = rb * RB + row_offs
        row_ok = rows < total_rows
        img = rows // in_h
        h = rows - img * in_h
        cols = cb * BLOCK_W + col_offs
        col_ok = cols < in_w
        mask2d = row_ok[:, None] & col_ok[None, :]
