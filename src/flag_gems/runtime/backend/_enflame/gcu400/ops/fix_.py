"""GCU400 fix_ (truncate toward zero): int-domain trunc chain, 1R1W launch shape.

The previous body spent two extern rounds (``floor`` + ``ceil``) plus a select,
and pinned the launch at B1024 with grid<=48 CTAs, which measured 0.33-0.43x
native on the big core cases (fp32 512M 6405us vs native 2108us = 1R1W
2.04TB/s).

Truncation toward zero is exactly what an int32 round-trip does in the storage
domain, so the body collapses to one cvt chain (same recipe as the sibling
``ceil.py`` / ``floor__opt.py`` chains, correction term dropped because int
casting already truncates toward zero):

* fp16: every finite fp16 fits int32, so only inf/NaN need the ``x - x == 0``
  exclusion;
* bf16/fp32: finite values beyond int32 exist and are already integral, so
  lanes with ``|x| >= 2^31`` (inf/NaN included) pass the input through.

Launch shape follows the 1R1W stream family recipe used by ``ceil.py``: a flat
grid-stride kernel capped at ``NUM_SIPS * 2`` CTAs, an EVEN arm that drops masks
when the tile divides the element count, and the same per-band BLOCK/num_warps
ladder (that ladder was re-scanned across probe2-probe4 for the 1R1W family and
the trunc body tracks the floor/ceil siblings within a few percent, so it is
reused as-is here). In-place is the only entry point for ``fix_``.
"""

