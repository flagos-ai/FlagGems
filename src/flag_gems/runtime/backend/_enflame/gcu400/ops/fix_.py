def fix_generic_kernel(x_ptr, n_elements, BLOCK: tl.constexpr):
    """Dtype-agnostic truncation (floor for x>=0, ceil for x<0); rare dtype path."""
    pid = tl.program_id(0)
    num_pids = tl.num_programs(0)
    lane_offsets = tl.arange(0, BLOCK)
    num_blocks = (n_elements + BLOCK - 1) // BLOCK
    for block_id in tl.range(pid, num_blocks, num_pids):
        offsets = block_id * BLOCK + lane_offsets
        mask = offsets < n_elements
