def _bessel_y0(x):
    x2 = x * x
    # Block-uniform test: when no lane of this block can reach the asymptotic
    # range, only the (much cheaper) x <= 5 branch is evaluated.
    if tl.max(x) <= 5.0:
        y = _y0_small(x, x2)
    else:
        y = tl.where(x <= 5.0, _y0_small(x, x2), _y0_large(x, x2))
    # Defined boundary / out-of-domain behaviour (matches ATen exactly).
    y = tl.where(x == 0.0, float("-inf"), y)
    y = tl.where(x < 0.0, float("nan"), y)
    y = tl.where(x != x, x, y)
    return y


