    rem = offs.to(tl.int64)
    for d in tl.static_range(MAXD):
        dd = ndim - 1 - d
        active = dd >= 0
        dd_safe = tl.maximum(dd, 0)
        s = tl.load(shape_ptr + dd_safe).to(tl.int64)
        st = tl.load(stride_ptr + dd_safe).to(tl.int64)
