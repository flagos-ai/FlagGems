@triton.jit
def _plane_kernel(
    grad_out_ptr,
    grad_in_ptr,
    ODHW: tl.constexpr,
    OW: tl.constexpr,
    OH: tl.constexpr,
    IW: tl.constexpr,
    IH: tl.constexpr,
    QD: tl.constexpr,
    QH: tl.constexpr,
    NLOG: tl.constexpr,
    INV: tl.constexpr,
    OD: tl.constexpr,
    ID: tl.constexpr,
    B: tl.constexpr,
):
    """Exact-ratio expansion with provably affine (vectorised) global accesses.

    One program owns ``B`` consecutive whole output planes (``od`` block) of
    one ``(n, c)`` image.  The source ``[B, OH, OW]`` tile is a single
    contiguous run of ``B*OH*OW`` elements, so the load is fully coalesced;
    the W expansion is a register ``tl.interleave`` (needs ``QW`` to be a power
    of two) and the H/D expansion is expressed as ``QD*QH`` stores of the same
    tile with constant row strides.  This avoids the per-lane gather that made
    the flat kernel (and the div/mod derived row base of the row kernel) an
    order of magnitude slower than the copy roofline.
    """
    pid = tl.program_id(0)
    ob = pid % (OD // B)
    nc = pid // (OD // B)

    s = ob * B + tl.arange(0, B)[:, None, None]  # source plane index (od)
    oh = tl.arange(0, OH)[None, :, None]
    ow = tl.arange(0, OW)[None, None, :]

    g = tl.load(grad_out_ptr + nc * (OD * ODHW) + s * ODHW + oh * OW + ow)
    val = g.to(tl.float32) * INV
    for _ in tl.static_range(NLOG):
        val = tl.interleave(val, val)
    v = val.to(grad_in_ptr.dtype.element_ty)

    iw = tl.arange(0, IW)[None, None, :]
    obase = grad_in_ptr + nc * (ID * IH * IW)
    for dd in tl.static_range(QD):
        for r in tl.static_range(QH):
            tl.store(
                obase + s * (QD * IH * IW) + dd * (IH * IW) + (oh * QH + r) * IW + iw,
                v,
            )


