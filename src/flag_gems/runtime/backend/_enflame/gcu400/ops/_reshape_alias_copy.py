# GCU400/L600 tuning (2026-11-19 probe, official bench shapes, do_bench cold):
#   - Per-CTA dispatch on this stack costs ~53ns, so kernels use a fixed
#     grid of at most _NUM_SPC CTAs with an internal grid-stride loop over
#     chunks/tiles. This also keeps grid.x far below the 65535 hardware
#     limit for any tensor size (the previous cdiv(n, 1024) grid overflowed
#     and hard-failed for n >= 67108864).
#   - Contiguous copy sweet spot: 32KB per chunk (BLOCK=16384 for 2-byte
#     dtypes, 8192 for 4-byte), num_warps=4, mask-free when divisible.
#   - Rank-2 views with a unit stride (transposes, row segments) use a 2D
#     tiled kernel instead of per-element div/mod decomposition.
_NUM_SPC = 48
_MAX_RANK = 8
_LIMIT_I32 = 2**31
_MIN_BLOCK = 1024
_MAX_BLOCK = 16384
_CHUNK_BYTES = 32768


