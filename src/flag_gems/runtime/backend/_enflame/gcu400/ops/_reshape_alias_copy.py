def _reshape_alias_copy_t2d_kernel(
    src_ptr,
    dst_ptr,
    d0,
    d1,
    s0,
    s1,
    BM: tl.constexpr,
    BN: tl.constexpr,
    NT0: tl.constexpr,
    NT1: tl.constexpr,
    NPROG: tl.constexpr,
    WIDE: tl.constexpr,
):
    """Mask-free tiled copy for rank-2 strided views with a unit stride axis.

    Both sides see contiguous runs: along dim0 when s0 == 1 (e.g. transposed
    views) and along dim1 when s1 == 1 (row segments). The destination is
    always row-major contiguous, so its runs follow dim1.

    The host only routes shapes with d0 % BM == 0 and d1 % BN == 0 here.
    Masked 2D tiles are NOT used: this backend family silently drops masked
    tile stores for degenerate/partial shapes (compiler_problems P15), so
    non-divisible shapes take the flat div/mod kernel instead.
    """
    pid = tl.program_id(axis=0)
    n_tiles = NT0 * NT1
    for tid in tl.range(pid, n_tiles, NPROG):
        i0 = tid // NT1
        i1 = tid % NT1
        if WIDE:
            a = i0.to(tl.int64) * BM + tl.arange(0, BM).to(tl.int64)
            b = i1.to(tl.int64) * BN + tl.arange(0, BN).to(tl.int64)
        else:
            a = i0 * BM + tl.arange(0, BM)
            b = i1 * BN + tl.arange(0, BN)
        src_off = a[:, None] * s0 + b[None, :] * s1
        dst_off = a[:, None] * d1 + b[None, :]
        values = tl.load(src_ptr + src_off)
        tl.store(dst_ptr + dst_off, values)


