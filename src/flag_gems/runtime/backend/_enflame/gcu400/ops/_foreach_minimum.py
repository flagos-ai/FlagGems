"""GCU400-specific scalar overloads of _foreach_minimum / _foreach_minimum_.

The common foreach executor carries the tensor list in a 2D grid, and GCU400's ``grid.y``
limit of 255 causes ``out of resource`` on large shapes. Contiguous float lists use the
1D fixed grid / metadata fused kernel from ``_foreach_flat``; non-float,
non-contiguous or broadcast shapes still delegate to the common executor to keep dtype policy and exception semantics.

The paired ``.List`` path runs its own single-launch kernel (``_minimum_list_kernel``):
same four-segment int64 metadata and ``(tensor, part)`` linearization as the common
``fused_binary_list_kernel``, with two GCU400-specific refinements measured on the
official do_bench kernel protocol (fresh stack re-anchor, jobs/j20261119081737):

* the grid is an exact multiple of the tensor count by construction (see
  ``_minimum_grid``), so every tile of every tensor is covered for any list
  length -- ``_foreach_flat._fused_grid`` caps by ``min(fixed_grid, NT*tiles)``
  and left the tiles of the trailing ``grid % NT`` tensors unvisited for list
  lengths that do not divide the cap;
* ``EXACT`` drops the per-tile bounds mask when every element count divides
  the chosen ``BLOCK``, and the block is tiered by dtype: fp32 stays at 8192,
  16-bit moves to 16384. On this stack EXACT@8192 wins for fp32 (-17/-11/-5%
  at 256^2/512^2/1024^2) while for bf16 the same 8192 tile *regresses*
  (+2~3%) and only the 16384 tile turns the mask removal into a win -- the
  (dtype, tile) coupling first measured on ``_foreach_maximum_List``
  reproduces here. Ragged lists keep the shipped masked 8192 body.
"""

import logging

import torch
import triton
import triton.language as tl

from flag_gems.ops._foreach_binary import _apply_list, _apply_scalar
from flag_gems.utils import libentry
from flag_gems.utils.foreach import _device_meta

from ._foreach_flat import (
    _TL_DTYPES,
    FALLBACK,
    MODE_LIST,
    MODE_SCALAR,
    MODE_SCALAR_LIST,
    OP_MIN,
    can_use_flat,
    fused_binary_scalar_kernel,
    run_binary,
)

logger = logging.getLogger(__name__)

# Output allocation is on the per-call host path of a list op (16 tensors => 16 calls), and the
# python-level ``torch.empty_like`` goes through the torch_gcu argument-translation shim on every
# call. The aten form is the same allocation without that shim; both preserve shape/dtype/device/
# memory-format, so the output layout is bit-identical to ``torch.empty_like``.
_EMPTY_LIKE = torch.ops.aten.empty_like.default

# --- TUNING PARAMS START ---
# Generated by the optimization-iteration driver per round; all of it is compile/launch-time
# config and never changes operator semantics.
# Official do_bench kernel-mode (w1000/r100 median) kernel-only variant sweep
# (Triton GCU 4.1.6, jobs/j20261119081737 fresh re-anchor):
#   * EXACT mask-free is coupled to (dtype, tile) (maximum_List precedent reproduced on this stack):
#     fp32 uses 8192 (-17/-11/-5% @256^2/512^2/1024^2) and 16384 ties with it;
#     16-bit uses 16384 (fp16 -5%/-4%, bf16 -4%), while 8192+EXACT regresses bf16
#     (+2~3% on the 512^2/1024^2 tiers);
#   * when any tensor element count does not divide the chosen BLOCK the whole table falls back
#     to 8192+mask (shipped behavior, bit-identical);
#   * the grid is always a multiple of the tensor count (_minimum_grid); at nt=16 it is the same
#     48 programs as the old _fused_grid, and the tail-tensor write hole is fixed for other lengths;
#   * num_warps 8 and 4 are identical tier by tier (same addcmul family precedent), and the backend
#     does not pipeline this tile loop, so num_stages stays 1.
# Program-count budget handed to ``_minimum_grid`` (a 16-tensor list yields 3 parts per tensor = 48
# programs); it must stay a multiple of the tensor count so every tensor gets the same number of parts.
FIXED_GRID = 48
BLOCK_SIZE = 8192
BLOCK_SIZE_16BIT = 16384
NUM_WARPS = 4
NUM_STAGES = 1
USE_DEVICE_CONTEXT = 0
FP32_PROMOTE = 0
FUSED_LAUNCH = 1
FALLBACK_TO_PUBLIC = 0
# When every numel divides the chosen BLOCK, take the mask-free EXACT kernel variant (decided
# after BLOCK is picked per dtype); any non-divisible tensor puts the whole batch on the mask path.
USE_EXACT = 1
# All overloads reuse the _device_meta read-only cache, removing the steady-state synchronous H2D.
USE_META_CACHE = 1
# The fp32 scalar table for .ScalarList is cached separately by (device, value).
USE_SCALAR_CACHE = 1
SCALAR_CACHE_LIMIT = 64
# --- TUNING PARAMS END ---

# Read-only metadata cache: the key contains only device and address/element count, not tensor data; the kernel still
# fully reads inputs and recomputes each time, so address reuse or in-place content changes do not affect correctness.
_SCALAR_CACHE = {}


@libentry()
@triton.jit
def _minimum_list_kernel(
    meta_ptr,
    NT: tl.constexpr,
    A_DT: tl.constexpr,
    FP32_PROMOTE: tl.constexpr,
    BLOCK: tl.constexpr,
    EXACT: tl.constexpr,
):
    """``.List`` minimum: one launch handles the whole paired tensor list.

    ``meta_ptr`` holds input pointers, output pointers, second-operand pointers and element
    counts in order (NT items each, int64). grid.x is linearized by ``(tensor, part)`` and is a
    multiple of NT by construction (see ``_minimum_grid``). It mirrors the shared
    ``fused_binary_list_kernel`` with two differences: OP is fixed to minimum (dropping the
    compile-time dispatch chain), and ``EXACT`` skips the per-tile bounds mask when every
    element count divides ``BLOCK`` -- under the official do_bench kernel protocol the mask
    predicate is the main kernel-side cost on small shapes.
    """
    pid = tl.program_id(0)
    num_programs = tl.num_programs(0)
    tensor_id = pid % NT
    part_id = pid // NT
    num_parts = tl.cdiv(num_programs, NT)

    a_raw = tl.load(meta_ptr + tensor_id)
    out_raw = tl.load(meta_ptr + NT + tensor_id)
    b_raw = tl.load(meta_ptr + 2 * NT + tensor_id)
    num_elems = tl.load(meta_ptr + 3 * NT + tensor_id)

    a_ptr = a_raw.to(tl.pointer_type(A_DT))
    out_ptr = out_raw.to(tl.pointer_type(A_DT))
    b_ptr = b_raw.to(tl.pointer_type(A_DT))

    arange = tl.arange(0, BLOCK)
    num_tiles = tl.cdiv(num_elems, BLOCK)
    for block_id in tl.range(part_id, num_tiles, num_parts):
        offs = block_id * BLOCK + arange
        if EXACT:
            a = tl.load(a_ptr + offs)
            b = tl.load(b_ptr + offs)
            if FP32_PROMOTE:
                a = a.to(tl.float32)
                b = b.to(tl.float32)
            tl.store(out_ptr + offs, tl.minimum(a, b))
        else:
            mask = offs < num_elems
            a = tl.load(a_ptr + offs, mask=mask)
            b = tl.load(b_ptr + offs, mask=mask)
            if FP32_PROMOTE:
                a = a.to(tl.float32)
                b = b.to(tl.float32)
            tl.store(out_ptr + offs, tl.minimum(a, b), mask=mask)


def _minimum_grid(numels, fixed_grid, block_size):
    """The grid is always a multiple of the tensor count: every tensor gets the same number of parts.

    ``(tensor, part)`` linearization requires ``num_programs % NT == 0``; otherwise tail tensors
    lack a part and the tile loop striding by ``num_parts`` skips blocks nobody covers
    (``_foreach_flat._fused_grid`` with a 24 grid carrying a 16-tensor list measured half the
    tensors losing their odd tiles, see the ``_foreach_maximum_List`` comparison record).
    Here divisibility holds by construction.
    ``numels`` is the element-count list the caller already materialized for the metadata, so the
    per-call host path does not walk the tensor list a second time.
    """
    num_tensors = len(numels)
    blocks_per_tensor = triton.cdiv(max(numels), block_size)
    parts = max(1, min(fixed_grid // num_tensors, blocks_per_tensor))
    return (num_tensors * parts,)


def _cached_scalar_tensor(scalars, device):
    """The ScalarList fp32 scalar table (read-only), cached by (device, value tuple)."""
    key = (str(device), tuple(scalars))
    cached = _SCALAR_CACHE.get(key)
    if cached is not None:
        return cached
    if len(_SCALAR_CACHE) >= SCALAR_CACHE_LIMIT:
        _SCALAR_CACHE.clear()
    cached = torch.tensor(scalars, dtype=torch.float32, device=device)
    _SCALAR_CACHE[key] = cached
    return cached


def _run_minimum_cached(self, operand, mode, inplace):
    """Lean single-launch path for the three operand forms (metadata goes through the read-only cache).

    Inapplicable forms return ``FALLBACK`` and the caller picks the fallback target: broadcast
    ``.List`` needs ``run_binary``'s per-tensor kernel; the rest fall back to the shared executor.
    The four metadata segments (input/output/second-operand addresses plus element counts) match
    ``_foreach_flat``'s fused kernel layout exactly.

    Paired ``.List`` goes through ``_minimum_list_kernel``: BLOCK is tiered by dtype (fp32 8192,
    16-bit 16384) before deciding ``EXACT`` mask-free; when any tensor element count does not
    divide the chosen BLOCK the whole table falls back to 8192 + mask, matching the historical
    shipped behavior.
    """
    if not can_use_flat(self, operand, mode):
        return FALLBACK
    num_tensors = len(self)
    in_ptrs = [tensor.data_ptr() for tensor in self]
    outputs = self if inplace else [_EMPTY_LIKE(tensor) for tensor in self]
    out_ptrs = in_ptrs if inplace else [tensor.data_ptr() for tensor in outputs]
    numels = [tensor.numel() for tensor in self]
    dtype = self[0].dtype
    triton_dtype = _TL_DTYPES[dtype]
    device = self[0].device

    if mode == MODE_LIST:
        # Reuse the element counts already collected above instead of re-walking both lists.
        if not all(other.numel() == numel for other, numel in zip(operand, numels)):
            # Broadcast .List does not share flat indices with the inputs, so hand it to the per-tensor kernel.
            return FALLBACK
        b_ptrs = [other.data_ptr() for other in operand]
        meta = _device_meta(in_ptrs + out_ptrs + b_ptrs + numels, device)
        if USE_EXACT and dtype is not torch.float32:
            block = BLOCK_SIZE_16BIT
        else:
            block = BLOCK_SIZE
        if USE_EXACT and all(numel % block == 0 for numel in numels):
            exact = 1
        else:
            block = BLOCK_SIZE
            exact = 0
        grid = _minimum_grid(numels, FIXED_GRID, block)
        _minimum_list_kernel[grid](
            meta,
            num_tensors,
            triton_dtype,
            FP32_PROMOTE,
            block,
            exact,
            num_warps=NUM_WARPS,
            num_stages=NUM_STAGES,
        )
    elif mode == MODE_SCALAR_LIST:
        if USE_SCALAR_CACHE:
            scalar_tensor = _cached_scalar_tensor(operand, device)
        else:
            scalar_tensor = torch.tensor(operand, dtype=torch.float32, device=device)
        meta = _device_meta(in_ptrs + out_ptrs + [0] * num_tensors + numels, device)
        grid = _minimum_grid(numels, FIXED_GRID, BLOCK_SIZE)
        fused_binary_scalar_kernel[grid](
            meta,
            scalar_tensor,
            num_tensors,
            OP_MIN,
            triton_dtype,
            0,
            triton_dtype,
            0.0,
            1,
            FP32_PROMOTE,
            BLOCK_SIZE,
            num_warps=NUM_WARPS,
            num_stages=NUM_STAGES,
        )
    else:
        meta = _device_meta(in_ptrs + out_ptrs + [0] * num_tensors + numels, device)
        grid = _minimum_grid(numels, FIXED_GRID, BLOCK_SIZE)
        fused_binary_scalar_kernel[grid](
            meta,
            self[0],
            num_tensors,
            OP_MIN,
            triton_dtype,
            0,
            triton_dtype,
            float(operand),
            0,
            FP32_PROMOTE,
            BLOCK_SIZE,
            num_warps=NUM_WARPS,
            num_stages=NUM_STAGES,
        )
    return None if inplace else outputs


def _dispatch(self, operand, mode, inplace, fallback):
    """Lean single-launch path first; broadcast/anomalous forms fall back to shared semantics."""
    if FALLBACK_TO_PUBLIC:
        return fallback()
    if USE_META_CACHE:
        result = _run_minimum_cached(self, operand, mode, inplace)
        if result is not FALLBACK:
            return result
        if mode != MODE_LIST:
            # can_use_flat failed: leave dtype policy and exception semantics to the common executor.
            return fallback()
    result = run_binary(
        self,
        operand,
        OP_MIN,
        mode,
        inplace,
        fixed_grid=FIXED_GRID,
        block_size=BLOCK_SIZE,
        num_warps=NUM_WARPS,
        num_stages=NUM_STAGES,
        use_device_context=USE_DEVICE_CONTEXT,
        fp32_promote=FP32_PROMOTE,
        fused=FUSED_LAUNCH,
    )
    if result is FALLBACK:
        return fallback()
    return result


def _foreach_minimum_List(self, other):
    logger.debug("GEMS_GCU400 _FOREACH_MINIMUM_SCALARLIST")
    return _dispatch(
        self,
        other,
        MODE_LIST,
        False,
        lambda: _apply_list("minimum", self, other, False),
    )


def _foreach_minimum__List(self, other):
    return _dispatch(
        self,
        other,
        MODE_LIST,
        True,
        lambda: _apply_list("minimum", self, other, True),
    )


