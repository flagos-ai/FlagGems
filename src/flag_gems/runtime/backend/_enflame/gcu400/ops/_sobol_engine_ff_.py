    # 闭式快进（与逐步 ctz 循环严格等价，见模块 docstring）：
    #   quasi ^ XOR_{j: delta 的第 j 位为 1} sobolstate[dim, j]
    #   delta = gray(num_generated + n) ^ gray(num_generated)
    # n / num_generated 均为 constexpr，delta 在编译期折叠成常量，
    # static_range + 静态 if 只保留置位 bit 的 load，运行期无循环。
    start = num_generated
    end = num_generated + n
    delta = (end ^ (end >> 1)) ^ (start ^ (start >> 1))

    for bit_pos in tl.static_range(MAXBIT):
        if (delta >> bit_pos) & 1:
            direction = tl.load(
                sobolstate_ptr + dims * MAXBIT + bit_pos, mask=dim_mask, other=0
            )
            quasi_val = quasi_val ^ direction

    # Store result
    tl.store(quasi_ptr + dims, quasi_val, mask=dim_mask)


