def _fast_path_config(numel, dtype):
    # (block, num_warps) measured on GCU400. Tiny tensors are launch bound so
    # they keep a small tile; the sin pipeline only saturates above ~4M
    # elements, where the largest tiles win.
    if numel < 8192:
        return 256, 2
    if numel < 256 * 1024:
        return 4096, 4
    if numel < 4 * 1024 * 1024:
        return 16384, 2
    if numel < 16 * 1024 * 1024:
        return 32768, 2
    if numel < 256 * 1024 * 1024:
        return 65536, 2
    # Only the very large tiles benefit from a wider tile, and only for 16-bit
    # inputs: they move half the bytes, while fp32 stays math bound and loses
    # from the extra tile state.
    if dtype == torch.float32:
        return 65536, 2
    return 131072, 2


