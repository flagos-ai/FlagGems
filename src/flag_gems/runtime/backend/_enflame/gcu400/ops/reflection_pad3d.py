# GCU400 reflection_pad3d strategy (2026-11-17 fix+perf rewrite):
# The KernelGen baseline walked the flat D_out*H_out*W_out output space with
# per-lane `//`/`%` decode plus abs/%/where reflection chains on all three
# axes, launched as grid=(B, cdiv(D_out*H_out*W_out, 256)): the big bench
# shape (1,1,32,64,128) needs grid.y=1530 > 255 (hard OutOfResources), and
# every lane paid 3 div/mod chains + a gather-form load. The rewrite keeps
# one kernel launch and decomposes the op along output rows (an output
# "row" is a W_out-wide line at fixed (b, d, h)); a row's interior segment
# maps to ONE contiguous W-wide source line at the (d,h)-reflected source
# row, so:
#   * phase 1 (bulk): every output row copies its W-wide interior segment
#     (source row = (d,h)-reflected) as ONE flat `base + tl.arange` pair;
#     U consecutive rows are grouped so all U loads are in flight before
#     the U stores (hides the ~450ns per-op latency that serializes
#     narrow rows). Interior-band groups take an affine fast path
#     (s_i = s0 + i*W); tail / band-crossing / mirror-band groups take
#     the per-row chain.
#   * phase 2 (pads): the left/right mirror lanes (pl+pr per row, a few
#     percent of the output) are copied by a per-lane gather loop, so bulk
#     programs never issue tiny ops.
# Top/bottom (h) and front/back (d) mirror bands need no special casing:
# their interiors ride the bulk row loop (reflected source row) and their
# mirror columns ride the pad gather.
# Pow2 row widths (H % 16 == 0) take the faster rowsgeo path instead: the
# h-interior band of EVERY output plane (mirror-d planes included) maps to
# the reflected source plane contiguously on both sides, so the whole
# interior rides maskless affine U-row groups (loop A) and only the
# h-mirror rows (loop B, V-row chained groups) plus the pad lanes (loop C)
# pay per-lane reflection. Non-pow2 W keeps the masked rowseg path.
# Grid is capped at 48 (one program per SPC); rows/lanes are grid-strided.
# U (rows per group) dispatch mirrors reflection_pad2d tiering: wide rows
# are bandwidth-bound (small U), narrow rows are latency-bound (large U).
# Element offsets stay in the int32 domain (< 2^31 elements), same as the
# generic baseline.


@triton.jit
def _refl3d_row_src(r, W, DoHo, Ho, D, H, pld, plh):
    # scalar source row base (element offset) of output row r under
    # (d,h)-reflection; r encodes (b, d, h) over B*D_out*H_out rows
    b = r // DoHo
    k = r - b * DoHo
    d = k // Ho
    h = k - d * Ho
    sd = d - pld
    sd = tl.where(sd < 0, -sd, sd)
    sd = tl.where(sd >= D, 2 * (D - 1) - sd, sd)
    sh = h - plh
    sh = tl.where(sh < 0, -sh, sh)
    sh = tl.where(sh >= H, 2 * (H - 1) - sh, sh)
    return (b * D + sd) * H * W + sh * W


