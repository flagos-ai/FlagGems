@triton.jit
def reflection_pad3d_wide_kernel(
    x_ptr,
    o_ptr,
    R,
    W,
    Wo,
    plw,
    DoHo,
    Ho,
    D,
    H,
    pld,
    plh,
    BLOCK: tl.constexpr,
    FPAD: tl.constexpr,
):
    # general path for very wide rows (W > 8192): per-row chunked interior
    # copy plus chunked mirror copies; correctness-first, off the hot path.
    pid = tl.program_id(0)
    G = tl.num_programs(0)
    prw = Wo - W - plw
    CB = (W + BLOCK - 1) // BLOCK
    CL = (plw + FPAD - 1) // FPAD
    CR = (prw + FPAD - 1) // FPAD
    offs_b = tl.arange(0, BLOCK)
    offs_f = tl.arange(0, FPAD)
    for r in range(pid, R, G):
        srow = _refl3d_row_src(r, W, DoHo, Ho, D, H, pld, plh)
        drow = r * Wo
        for c in range(0, CB):
            ob = c * BLOCK + offs_b
            m = ob < W
            tl.store(
                o_ptr + drow + plw + ob,
                tl.load(x_ptr + srow + ob, mask=m),
                mask=m,
            )
        for c in range(0, CL):
            ol = c * FPAD + offs_f
            ml = ol < plw
            sl = tl.where(ml, plw - ol, 0)
            tl.store(o_ptr + drow + ol, tl.load(x_ptr + srow + sl, mask=ml), mask=ml)
        for c in range(0, CR):
            orr = c * FPAD + offs_f
            mr = orr < prw
            sr = tl.where(mr, W - 2 - orr, 0)
            tl.store(
                o_ptr + drow + W + plw + orr,
                tl.load(x_ptr + srow + sr, mask=mr),
                mask=mr,
            )


def _next_pow2(n, cap):
    p = 1
    while p < n and p < cap:
        p *= 2
    return p


def launch_reflection_pad3d(input: torch.Tensor, padding, out: torch.Tensor = None):
    # Validate padding format
    if not isinstance(padding, (list, tuple)):
        raise ValueError("padding must be a sequence")
    if len(padding) != 6:
        raise ValueError(
            "padding must be a sequence of length 6: (pad_left, pad_right, pad_top, pad_bottom, pad_front, pad_back)"
        )
    pad_l, pad_r, pad_t, pad_b, pad_f, pad_ba = [int(p) for p in padding]

    # Validate padding values
    if pad_l < 0 or pad_r < 0 or pad_t < 0 or pad_b < 0 or pad_f < 0 or pad_ba < 0:
        raise ValueError("padding values must be >= 0")

    # Handle 4D input (N, C, H, W) -> (1, N, C, H, W) by unsqueezing
    is_4d = input.dim() == 4
    if is_4d:
        input = input.unsqueeze(0)

    # Validate input
    if input.dim() < 5:
        raise ValueError("input must have at least 5 dimensions")
    if input.device.type != flag_gems.device:
        raise ValueError(f"input must be a {flag_gems.device} tensor")

    x = input.contiguous()
    N, C, D_in, H_in, W_in = x.shape

    # Validate reflection padding constraints
    if D_in < 2 or H_in < 2 or W_in < 2:
        raise ValueError(
            "input spatial dimensions must be at least 2 for reflection padding when padding > 0"
        )
    if D_in <= 0 or H_in <= 0 or W_in <= 0:
        raise ValueError("spatial dimensions must be > 0")
    if (
        pad_l >= W_in
        or pad_r >= W_in
        or pad_t >= H_in
        or pad_b >= H_in
        or pad_f >= D_in
        or pad_ba >= D_in
    ):
        raise ValueError(
            "padding values must be less than the input spatial dimensions for reflection padding"
        )

    D_out = D_in + pad_f + pad_ba
    H_out = H_in + pad_t + pad_b
    W_out = W_in + pad_l + pad_r

    # Handle output tensor
    if out is None:
        out = torch.empty((N, C, D_out, H_out, W_out), device=x.device, dtype=x.dtype)
    else:
        if out.device.type != flag_gems.device:
            raise ValueError(f"out must be a {flag_gems.device} tensor")
        expected_shape = (N, C, D_out, H_out, W_out)
        if tuple(out.shape) != expected_shape:
            raise ValueError(
                f"out tensor has shape {tuple(out.shape)}, expected {expected_shape}"
            )
        if out.dtype != x.dtype:
            raise ValueError(
                f"out dtype {out.dtype} does not match input dtype {x.dtype}"
            )
        if out.device != x.device:
            raise ValueError("out must be on the same device as input")
        out = out.contiguous()

    B = N * C
    R = B * D_out * H_out
    DoHo = D_out * H_out
    PW = W_out - W_in
    pad_right_w = PW - pad_l

    def _launch():
        if W_in > 8192:
            # very wide rows: chunked general path
            FPAD = max(16, _next_pow2(max(pad_l, pad_right_w, 1), 1024))
            grid = (min(48, max(1, R)),)
            reflection_pad3d_wide_kernel[grid](
                x,
                out,
                R,
                W_in,
                W_out,
                pad_l,
                DoHo,
                H_out,
                D_in,
                H_in,
                pad_f,
                pad_t,
                BLOCK=8192,
                FPAD=FPAD,
                num_warps=8,
            )
        elif (W_in & (W_in - 1)) == 0 and H_in % 16 == 0:
            # pow2 row widths: geometric split — the h-interior band of every
            # output plane (mirror-d planes included) maps to the reflected
            # source plane contiguously on both sides, so the whole interior
            # rides maskless affine U-row groups; only h-mirror rows and the
            # pad lanes pay per-lane reflection. num_warps=2 measured best
            # on all bench shapes (nw=4 costs 9-16% on U=32 shapes).
            U = 32 if H_in % 32 == 0 else 16
            GH = (H_in + U - 1) // U
            Mh = pad_t + pad_b
            TOT_GA = B * D_out * GH
            TOT_BND = B * D_out * Mh
            total = R * PW
            grid = (
                min(
                    48,
                    max(1, TOT_GA + (TOT_BND + 7) // 8 + (total + 1023) // 1024),
                ),
            )
            reflection_pad3d_rowsgeo_kernel[grid](
                x,
                out,
                TOT_GA,
                TOT_BND,
                R,
                W_in,
                W_out,
                pad_l,
                GH,
                Mh,
                D_out,
                DoHo,
                H_out,
                D_in,
                H_in,
                pad_f,
                pad_t,
                BLOCK=W_in,
                GBLOCK=1024,
                U=U,
                V=8,
                num_warps=2,
            )
        else:
            # rows per group: wide rows are bandwidth-bound (small groups),
            # narrow rows are latency-bound (large groups hide the ~450ns
            # per-op latency). U=20 measured best for W in [64, 768) on the
            # reflection_pad2d sibling; U=8 for narrower/wider rows.
            # Small R clamp: when fewer groups than programs would result,
            # prefer more programs with smaller groups.
            if W_in >= 2048:
                U = 4
            elif W_in >= 768 or W_in < 64:
                U = 8
            else:
                U = 20
            n_min = (R + 47) // 48
            if n_min <= 4:
                U_r = 4
            elif n_min <= 8:
                U_r = 8
            else:
                U_r = 20
            U = min(U, U_r)
            nw = 2 if U == 20 else 4
            BLOCK = _next_pow2(W_in, 8192)
            total = R * PW
            grid = (min(48, max(1, (R + U - 1) // U + (total + 1023) // 1024)),)
            reflection_pad3d_rowsseg_kernel[grid](
                x,
                out,
                R,
                W_in,
                W_out,
                pad_l,
                DoHo,
                H_out,
                D_in,
                H_in,
                pad_f,
                pad_t,
                BLOCK=BLOCK,
                GBLOCK=1024,
                U=U,
                num_warps=nw,
            )

    # cold compiles hit the documented node-level toolchain flakiness
    # (P02 family): a fresh-compile subprocess can die before producing a
    # cache entry; retrying the launch re-enters compilation and succeeds
    # (atan2_/sinh/_pad_circular/reflection_pad2d precedent).
    for attempt in range(3):
        try:
            with torch_device_fn.device(x.device):
                _launch()
            break
        except Exception:
            if attempt == 2:
                raise
    return out.squeeze(0) if is_4d else out


def reflection_pad3d(input: torch.Tensor, padding, *, out: torch.Tensor = None):
    logger.debug("GEMS_ENFLAME REFLECTION_PAD3D")
    return launch_reflection_pad3d(input, padding, out=out)


