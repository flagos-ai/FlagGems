"""GCU400-specific ``_foreach_lerp_.List`` (in-place): single-launch fused kernel.

The old implementation launched a 1-D kernel per tensor (a 16-tensor list meant 16 launches,
BLOCK=65536 with one program striding serially), measuring ~250-280us at 16x256^2, ~45% slower
than native ATen (official bench core: mean 0.55x). This converges to a single launch with the
same fix pattern as ``_foreach_pow__List``:

1. Uniform float, same-shape triple lists go through this file's fused kernel: address and
   element-count metadata goes through the shared ``_device_meta`` read-only cache (zero
   synchronous H2D on steady-state calls), ``grid = NT * PARTS`` is always a multiple of the
   tensor count, and each tensor gets exactly ``PARTS`` programs splitting tiles with a ``PARTS``
   stride -- the (part, tensor) linearization drops tiles when the grid does not divide the
   tensor count (with 24 % 16 != 0 tensors 8-15 only get part 0 and the stride of 2 skips odd
   tiles), so this path excludes that form by construction; the math keeps the current fp32
   promotion semantics (matching ATen opmath and the family ``fused_lerp_scalar_list_kernel``);
   for fp32 with every numel dividing BLOCK it takes the EXACT full-block mask-free arm (same
   geometry, -3~-15%), while 16-bit and ragged shapes take the masked arm.
2. Non-float, non-contiguous, mixed dtype, broadcast weight and cross-device forms fall back to
   the shared ``_apply_lerp``, keeping dtype policy and error semantics unchanged.
"""

import logging

import torch
import triton
import triton.language as tl

from flag_gems.ops._foreach_binary import _apply_lerp
from flag_gems.utils import libentry
from flag_gems.utils.foreach import _device_meta

from ._foreach_flat import _TL_DTYPES

logger = logging.getLogger(__name__)

# --- TUNING PARAMS START ---
# Generated by the optimization-iteration driver per round; compile/launch-time config only.
# Fast-path geometry (this machine, new stack Triton GCU 4.1.6, P{1..6}xB{4096..32768}xwxs
# interleaved sweep plus a P{2,3,4}xB{4096,8192,16384} fine scan, every combo verified by
# full-value coverage over 16 tensors): P3B8192w4s1 wins in aggregate (fp16 wins every tier,
# fp32 trails the B4096 tier by 3-16% but still normalizes to 1.04 and wins); P3B32768 regresses
# 5-15% along the pow 2R1W convention (3R1W matches the family ScalarList fused 48-grid/B8192
# recipe), and w8/s2 sit inside the noise band, so the simplest is kept.
# 2026-11-19 P3 incremental round: the EXACT mask-free arm (maximum_List precedent,
# (dtype, BLOCK) coupled) -- fp32 at the same B8192 geometry gives -14.8/-6.9/-3.1%
# (256^2/512^2/1024^2), while 16-bit EXACT is neutral-to-negative (+0.3~2.3%) and the 4-stream
# B16384 arm regresses +8.7~19.3% (addcmul precedent: the maximum_List 16-bit B16384 gain is
# 2R1W-specific); fp32 EXACT is P6 +1.1~12.6% and nw2/B16384 ties -- so EXACT is enabled only for
# fp32 with every numel dividing BLOCK, while 16-bit and ragged shapes keep the masked geometry.
FAST_PARTS_CAP = 3
FAST_BLOCK = 8192
FAST_WARPS = 4
FAST_STAGES = 1
FP32_PROMOTE = 1
FALLBACK_TO_PUBLIC = 0
# --- TUNING PARAMS END ---

# GCU400 hard limit on grid.x; the fast-path grid = nt * parts must fit entirely within the limit.
_MAX_GRID_X = 65535

_FLOAT_DTYPES = (torch.float16, torch.float32, torch.bfloat16)


@libentry()
@triton.jit
def fused_lerp_list_ip_kernel(
    meta_ptr,
    NT: tl.constexpr,
    A_DT: tl.constexpr,
    FP32_PROMOTE: tl.constexpr,
    EXACT: tl.constexpr,
    BLOCK: tl.constexpr,
    PARTS: tl.constexpr,
):
    """One launch performs in-place ``self + w*(end-self)`` over the whole triple list.

    ``meta_ptr`` holds the input, end, weight and output (the input itself when in-place)
    addresses plus element counts (NT items each, int64). The grid is linearized by
    ``(tensor, part)`` and is always ``NT * PARTS``: each tensor gets ``PARTS`` programs that
    split tiles with a ``PARTS`` stride, so coverage holes do not exist by construction.

    When ``EXACT`` is true every tensor element count divides ``BLOCK`` (guaranteed by the host),
    so all tiles are full and the load/store predicates are dropped (fp32 measured -3~-15%;
    16-bit gains nothing so it stays off); otherwise the masked path keeps the semantics.
    """
    pid = tl.program_id(0)
    tensor_id = pid % NT
    part_id = pid // NT

    a_ptr = tl.load(meta_ptr + tensor_id).to(tl.pointer_type(A_DT))
    b_ptr = tl.load(meta_ptr + NT + tensor_id).to(tl.pointer_type(A_DT))
    w_ptr = tl.load(meta_ptr + 2 * NT + tensor_id).to(tl.pointer_type(A_DT))
    out_ptr = tl.load(meta_ptr + 3 * NT + tensor_id).to(tl.pointer_type(A_DT))
    n_elements = tl.load(meta_ptr + 4 * NT + tensor_id)

    arange = tl.arange(0, BLOCK)
    # Tile counts stay i32, matching the shared executor's address arithmetic width.
    if EXACT:
        num_tiles = (n_elements // BLOCK).to(tl.int32)
    else:
        num_tiles = tl.cdiv(n_elements, BLOCK).to(tl.int32)
    for block_id in tl.range(part_id, num_tiles, PARTS):
        idx = block_id * BLOCK + arange
        if EXACT:
            a = tl.load(a_ptr + idx)
            b = tl.load(b_ptr + idx)
            w = tl.load(w_ptr + idx)
            if FP32_PROMOTE:
                # Promote low precision to fp32 first (ATen opmath semantics), then demote before the store.
                a = a.to(tl.float32)
                b = b.to(tl.float32)
                w = w.to(tl.float32)
            tl.store(out_ptr + idx, (a + w * (b - a)).to(A_DT))
        else:
            mask = idx < n_elements
            a = tl.load(a_ptr + idx, mask=mask)
            b = tl.load(b_ptr + idx, mask=mask)
            w = tl.load(w_ptr + idx, mask=mask)
            if FP32_PROMOTE:
                a = a.to(tl.float32)
                b = b.to(tl.float32)
                w = w.to(tl.float32)
            tl.store(out_ptr + idx, (a + w * (b - a)).to(A_DT), mask=mask)


def _run_lerp_list_cached(self, tensors1, weight):
    """Single-launch in-place path for uniform float, same-shape triple lists.

    Unsatisfied preconditions (broadcast weight, cross-device, non-contiguous, mixed dtype, over
    the grid cap) return ``FALLBACK`` and the caller falls back to the shared executor; metadata
    holds only addresses and element counts while the kernel still reads and computes the tensor
    data on every call, so the cache only removes the per-call synchronous H2D. Empty tensors
    have zero tiles, the in-kernel loop idles naturally, and semantics are unchanged.
    """
    if FALLBACK_TO_PUBLIC:
        return False
    if not isinstance(self, (list, tuple)) or not self:
        return False
    if not isinstance(tensors1, (list, tuple)) or not isinstance(weight, (list, tuple)):
        return False
    if len(tensors1) != len(self) or len(weight) != len(self):
        return False
    num_tensors = len(self)
    if num_tensors * FAST_PARTS_CAP > _MAX_GRID_X:
        return False
    first = self[0]
    if not isinstance(first, torch.Tensor) or first.dtype not in _FLOAT_DTYPES:
        return False
    dtype = first.dtype
    device = first.device
    for a, b, w in zip(self, tensors1, weight):
        if not (
            isinstance(a, torch.Tensor)
            and isinstance(b, torch.Tensor)
            and isinstance(w, torch.Tensor)
        ):
            return False
        if a.dtype is not dtype or b.dtype is not dtype or w.dtype is not dtype:
            return False
        if a.device != device or b.device != device or w.device != device:
            return False
        if not (a.is_contiguous() and b.is_contiguous() and w.is_contiguous()):
            return False
        # Broadcasting (including a 0-d weight) doesn't share flat indices with the input, so fall back to the common
        # executor.
        if b.shape != a.shape or w.shape != a.shape:
            return False

    in_ptrs = [t.data_ptr() for t in self]
    b_ptrs = [t.data_ptr() for t in tensors1]
    w_ptrs = [t.data_ptr() for t in weight]
    numels = [t.numel() for t in self]
    meta = _device_meta(in_ptrs + b_ptrs + w_ptrs + in_ptrs + numels, device)
    parts = max(1, min(FAST_PARTS_CAP, triton.cdiv(max(numels), FAST_BLOCK)))
    # The EXACT arm applies only to fp32 with every numel dividing BLOCK: full blocks drop the
    # mask predicate for a measured -3~-15%; 16-bit gains nothing (the (dtype, BLOCK) coupling)
    # and ragged shapes stay masked.
    use_exact = dtype == torch.float32 and all(n % FAST_BLOCK == 0 for n in numels)
    fused_lerp_list_ip_kernel[(num_tensors * parts,)](
        meta,
        num_tensors,
        _TL_DTYPES[dtype],
        FP32_PROMOTE,
        use_exact,
        FAST_BLOCK,
        parts,
        num_warps=FAST_WARPS,
        num_stages=FAST_STAGES,
    )
    return True


def _foreach_lerp__List(self, tensors1, weight):
    logger.debug("GEMS_GCU400 FOREACH_LERP__LIST")
    if not _run_lerp_list_cached(self, tensors1, weight):
        return _apply_lerp(self, tensors1, weight, True)
    # in-place schema contract: the dispatcher side must return None.
    return None
