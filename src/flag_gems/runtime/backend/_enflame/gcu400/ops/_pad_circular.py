# GCU400 pad_circular strategy (2026-11-10 perf rewrite):
# The old per-lane wrapped offsets (tl.where chains on the offset vector) and
# 2D row tiles hit the gcu400 memory-path laws: offsets through tl.where
# downgrade to per-lane gather, 2D row-base tiles are 8.5x slower than flat,
# and one program per row pays the ~52ns/program dispatch floor (the original
# grids of 8k-33k programs were 100% dispatch-bound: measured latencies were
# dtype-independent). The rewrite keeps one kernel launch and decomposes the
# op into flat contiguous runs:
#   * phase 1 (bulk): every output row copies its mid width segment as ONE
#     flat `base + tl.arange` pair; U consecutive rows are grouped so all U
#     loads are in flight before the U stores (hides the ~450ns per-op
#     latency that serializes narrow rows). A fast path computes the group's
#     src rows affinely (s_i = s0 + i*W) when no h-wrap / sh-jump falls
#     inside the group; tail and jump groups take the slow per-row chain.
#   * phase 2 (pads): the left/right pad lanes are a tiny fraction of the
#     output and are copied by a per-lane gather loop (cheap at few lanes),
#     so bulk programs never issue tiny ops.
# grid is capped at 48 (one program per SPC); G>48 measured flat-to-worse.
# U (rows per group) dispatch by row width W: wide rows are bandwidth-bound
# (small U), narrow rows are latency-bound (large U).


@triton.jit
def _row_src(r, W, Ho, H, Do, D, plh, pld, NPAD: tl.constexpr):
    if NPAD == 1:
        srow = r * W
    elif NPAD == 2:
        b = r // Ho
        h = r % Ho
        sh = h - plh
        sh = tl.where(sh < 0, sh + H, sh)
        sh = tl.where(sh >= H, sh - H, sh)
        srow = (b * H + sh) * W
    else:
        b = r // (Do * Ho)
        rem = r % (Do * Ho)
        d = rem // Ho
        h = rem % Ho
        sd = d - pld
        sd = tl.where(sd < 0, sd + D, sd)
        sd = tl.where(sd >= D, sd - D, sd)
        sh = h - plh
        sh = tl.where(sh < 0, sh + H, sh)
        sh = tl.where(sh >= H, sh - H, sh)
        srow = ((b * D + sd) * H + sh) * W
    return srow


