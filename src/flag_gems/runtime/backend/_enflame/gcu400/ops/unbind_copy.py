"""GCU400-specific ``unbind_copy`` implementation.

The output is ``num_slices`` independent copies placed in one contiguous storage and viewed as slices.
Problems with the original implementation (official bench core/kernel measurements):

* ``torch.empty`` goes through GEMS's empty override, launching an extra
  zero-fill kernel per call (use ``torch.empty_strided`` instead, restoring a single launch);
* ``@triton.autotune`` on GCU400 picks a tier per dtype x num_elements by in-process lottery,
  ``(16,32)``/``(32,64,128)`` and other multi-slice shapes can degrade 6-20x and are unstable across processes,
  so use host-side deterministic tiering;
* with ``dim == 0`` the output storage is byte-identical to the input, yet the original kernel still does
  ``idx // dim_prod_post`` per element and launches a 2D grid (second dim = slice count),
  so on GCU400 program count grows nearly linearly with slices (2D tile tax); use a flat 1D copy instead.

Path dispatch:

* ``dim == 0``: flat 1D memcpy - when itemsize<=4 and pointers are aligned, reinterpret pointers
  as 8-byte wide channels inside the kernel (host needs no int64 view), with BLOCK tiered by size (small
  <=8192 lanes keep one wave; >256K lanes use 16384 for bandwidth, 64MB measured 2551GB/s
  vs 8192's 1904GB/s), with masks omitted on exact division;
* other dims: output written contiguously as ``[slice][pre][post]``, input read by gather. When post's
  power-of-two factor >=128 use the block-aligned arm (each program does only scalar division, no mask),
  otherwise the per-element arm is the fallback (correctness path, only small test shapes).

Limitation: keep int32 offsets from the old implementation, requiring total elements < 2^31.
"""

import logging
from typing import List

import torch
import triton
import triton.language as tl

logger = logging.getLogger(__name__)

# Constants below are A/B probe calibrations (2026-11-13, official bench do_bench):
# 1MB copy is best with 16-32 programs (4.6us), 4 programs degrade to 6.2us;
# 64MB copy with BLOCK=16384 reaches 2551GB/s, 8192 only 1904GB/s.
_FLAT_SMALL_CAP = 8192
_FLAT_LARGE_BLOCK = 16384
_FLAT_LARGE_THRESHOLD = 262144
_FLAT_WARPS = 4
_GATHER_BLOCK = 1024
_ALIGNED_MIN_BLOCK = 128
_ALIGNED_CAP = 4096


@triton.jit
def _unbind_flat_copy_kernel(
    src_ptr,
    dst_ptr,
    num_lanes,
    BLOCK: tl.constexpr,
    EVEN: tl.constexpr,
    WIDE: tl.constexpr,
):
    """``dim == 0`` path: contiguous copy where output storage is byte-identical to input layout.

    Indices use only multiply-add, no division and no 2D grid; masks are omitted with EVEN. With WIDE, pointers are
    reinterpreted as 8-byte wide channels inside the kernel (host needs no int64 view; pointer
    reinterpretation is safe in flat form; alignment is guarded on the host).
    """
    if WIDE:
        src = src_ptr.to(tl.pointer_type(tl.int64))
        dst = dst_ptr.to(tl.pointer_type(tl.int64))
    else:
        src = src_ptr
        dst = dst_ptr
    offsets = tl.program_id(0) * BLOCK + tl.arange(0, BLOCK)
    if EVEN:
        tl.store(dst + offsets, tl.load(src + offsets))
    else:
        active = offsets < num_lanes
        tl.store(dst + offsets, tl.load(src + offsets, mask=active), mask=active)


@triton.jit
def _unbind_gather_aligned_kernel(
    input_ptr,
    output_ptr,
    dim_size,
    dim_prod_post,
    post,
    BLOCK: tl.constexpr,
):
    """Block-aligned gather arm: ``post % BLOCK == 0`` puts a whole block inside one (slice, pre) row.

    Division happens only on program-level scalars; in-block input offsets are contiguous and the output side is always
    a contiguous flat write.
    """
    block_start = tl.program_id(0) * BLOCK
    slice_id = block_start // dim_prod_post
    remainder = block_start - slice_id * dim_prod_post
    pre_idx = remainder // post
    post_idx = remainder - pre_idx * post
    input_base = (pre_idx * dim_size + slice_id) * post + post_idx
    offsets = tl.arange(0, BLOCK)
    tl.store(
        output_ptr + block_start + offsets,
        tl.load(input_ptr + input_base + offsets),
    )


@triton.jit
def _unbind_gather_element_kernel(
    input_ptr,
    output_ptr,
    dim_size,
    dim_prod_post,
    post,
    total_elements,
    BLOCK: tl.constexpr,
):
    """Per-element gather fallback arm: output written contiguously, input located by two divisions."""
    flat = tl.program_id(0) * BLOCK + tl.arange(0, BLOCK)
    active = flat < total_elements
    slice_id = flat // dim_prod_post
    remainder = flat - slice_id * dim_prod_post
    pre_idx = remainder // post
    post_idx = remainder - pre_idx * post
    input_off = (pre_idx * dim_size + slice_id) * post + post_idx
    tl.store(
        output_ptr + flat, tl.load(input_ptr + input_off, mask=active), mask=active
    )


def _next_power_of_two(value: int) -> int:
    power = 1
    while power < value:
        power *= 2
    return power


def _largest_power_of_two_divisor(value: int) -> int:
    divisor = 1
    while value % 2 == 0:
        value //= 2
        divisor *= 2
    return divisor


def _launch_flat_copy(input: torch.Tensor, storage: torch.Tensor, total: int) -> None:
    """``dim == 0``: whole-block flat copy with an 8-byte wide channel inside the kernel."""
    element_size = input.element_size()
    num_bytes = total * element_size
    # The wide channel requires total bytes and pointers both 8-byte aligned; otherwise fall back to native element
    # channels.
    wide = (
        element_size <= 4
        and num_bytes % 8 == 0
        and input.data_ptr() % 8 == 0
        and storage.data_ptr() % 8 == 0
    )
    num_lanes = num_bytes // 8 if wide else total
    if num_lanes <= _FLAT_LARGE_THRESHOLD:
        block = min(_next_power_of_two(num_lanes), _FLAT_SMALL_CAP)
    else:
        block = _FLAT_LARGE_BLOCK
    grid = (triton.cdiv(num_lanes, block),)
    _unbind_flat_copy_kernel[grid](
        input,
        storage,
        num_lanes,
        BLOCK=block,
        EVEN=num_lanes % block == 0,
        WIDE=wide,
        num_warps=_FLAT_WARPS,
    )


def unbind_copy(input: torch.Tensor, dim: int = 0) -> List[torch.Tensor]:
    """Unbind a tensor into a list of tensors.

    Removes a tensor dimension and returns a tuple of all the slices along
    that dimension. Unlike torch.unbind, this function creates new copies
    of the data rather than views.

    Args:
        input: The tensor to unbind
        dim: The dimension along which to unbind

    Returns:
        A list of tensors
    """
    logger.debug("GEMS_ENFLAME_GCU400 UNBIND_COPY")

    if dim < 0:
        dim = dim + input.ndim

    if dim < 0 or dim >= input.ndim:
        raise IndexError(
            f"Dimension out of range (expected to be in range of [{-input.ndim}, {input.ndim - 1}], but got {dim})"
        )

    num_slices = input.shape[dim]
    if num_slices == 0:
        return []

    # Get the shape of each output tensor (without the unbind dimension)
    output_shape = list(input.shape)
    del output_shape[dim]

    num_elements_per_slice = 1
    for s in output_shape:
        num_elements_per_slice *= s

    if num_elements_per_slice == 0:
        # Return empty list of outputs
        return [
            torch.empty(output_shape, dtype=input.dtype, device=input.device)
            for _ in range(num_slices)
        ]

    total_elements = num_slices * num_elements_per_slice
    # GEMS's empty override launches an extra zero-fill kernel; this op's kernel
    # writes every element, so use empty_strided for pure allocation.
    output_storage = torch.empty_strided(
        (total_elements,),
        (1,),
        dtype=input.dtype,
        device=input.device,
    )

    if not input.is_contiguous():
        input = input.contiguous()

    if dim == 0:
        # Output storage is byte-identical to input: whole-block flat copy.
        _launch_flat_copy(input, output_storage, total_elements)
    else:
        dim_prod_post = 1
        for i in range(dim + 1, input.ndim):
            dim_prod_post *= input.shape[i]
        aligned_block = min(_largest_power_of_two_divisor(dim_prod_post), _ALIGNED_CAP)
        if aligned_block >= _ALIGNED_MIN_BLOCK:
            # total = S * pre * post, and post % BLOCK == 0 guarantees exact division and no mask.
            grid = (total_elements // aligned_block,)
            _unbind_gather_aligned_kernel[grid](
                input,
                output_storage,
                num_slices,
                num_elements_per_slice,
                dim_prod_post,
                BLOCK=aligned_block,
                num_warps=_FLAT_WARPS,
            )
        else:
            block = min(_next_power_of_two(total_elements), _GATHER_BLOCK)
            grid = (triton.cdiv(total_elements, block),)
            _unbind_gather_element_kernel[grid](
                input,
                output_storage,
                num_slices,
                num_elements_per_slice,
                dim_prod_post,
                total_elements,
                BLOCK=block,
                num_warps=_FLAT_WARPS,
            )

    # Split the storage into individual output tensors. One as_strided call
    # gives a view of the final shape directly, halving the
    # host cost of two slice+view dispatcher calls (with many slices, host time leaks into kernel-mode timing).
    output_strides = []
    stride = 1
    for dim_size in reversed(output_shape):
        output_strides.append(stride)
        stride *= dim_size
    output_strides.reverse()
    outputs = [
        torch.as_strided(
            output_storage, output_shape, output_strides, i * num_elements_per_slice
        )
        for i in range(num_slices)
    ]

    return outputs
