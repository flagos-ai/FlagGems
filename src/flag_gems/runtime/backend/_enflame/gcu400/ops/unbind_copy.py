import torch
import triton
import triton.language as tl

logger = logging.getLogger(__name__)

# 以下常量为 A/B 探针定标值（2026-11-13，官方 bench 同口径 do_bench）：
# 1MB 拷贝 16-32 programs 最优（4.6us），4 programs 劣化到 6.2us；
# 64MB 拷贝 BLOCK=16384 达 2551GB/s，8192 仅 1904GB/s。
_FLAT_SMALL_CAP = 8192
_FLAT_LARGE_BLOCK = 16384
_FLAT_LARGE_THRESHOLD = 262144
_FLAT_WARPS = 4
_GATHER_BLOCK = 1024
_ALIGNED_MIN_BLOCK = 128
_ALIGNED_CAP = 4096


@triton.jit
def _unbind_flat_copy_kernel(
    src_ptr,
    dst_ptr,
    num_lanes,
    BLOCK: tl.constexpr,
    EVEN: tl.constexpr,
    WIDE: tl.constexpr,
):
    """``dim == 0`` 路径：输出存储与输入布局逐字节一致的连续拷贝。

    索引只有乘加，无除法、无 2D grid；EVEN 时免 mask。WIDE 时在 kernel 内
    把指针重解释成 8 字节宽通道（host 免做 int64 视图，flat 形态下指针
    重解释安全；对齐性由 host 守卫）。
    """
    if WIDE:
        src = src_ptr.to(tl.pointer_type(tl.int64))
        dst = dst_ptr.to(tl.pointer_type(tl.int64))
    else:
        src = src_ptr
        dst = dst_ptr
    offsets = tl.program_id(0) * BLOCK + tl.arange(0, BLOCK)
    if EVEN:
        tl.store(dst + offsets, tl.load(src + offsets))
    else:
        active = offsets < num_lanes
        tl.store(dst + offsets, tl.load(src + offsets, mask=active), mask=active)


@triton.jit
def _unbind_gather_aligned_kernel(
    input_ptr,
    output_ptr,
    dim_size,
    dim_prod_post,
    post,
    BLOCK: tl.constexpr,
):
    """块对齐 gather 臂：``post % BLOCK == 0`` 时整块落在单个 (slice, pre) 行内。

    除法只发生在 program 级标量上；块内输入偏移连续，输出侧恒为连续 flat 写。
    """
    block_start = tl.program_id(0) * BLOCK
    slice_id = block_start // dim_prod_post
    remainder = block_start - slice_id * dim_prod_post
    pre_idx = remainder // post
    post_idx = remainder - pre_idx * post
    input_base = (pre_idx * dim_size + slice_id) * post + post_idx
    offsets = tl.arange(0, BLOCK)
    tl.store(
        output_ptr + block_start + offsets,
        tl.load(input_ptr + input_base + offsets),
    )


@triton.jit
def _unbind_gather_element_kernel(
    input_ptr,
    output_ptr,
    dim_size,
    dim_prod_post,
    post,
    total_elements,
    BLOCK: tl.constexpr,
):
    """逐元素 gather 兜底臂：输出连续写，输入用两组除法定位。"""
    flat = tl.program_id(0) * BLOCK + tl.arange(0, BLOCK)
    active = flat < total_elements
    slice_id = flat // dim_prod_post
    remainder = flat - slice_id * dim_prod_post
    pre_idx = remainder // post
    post_idx = remainder - pre_idx * post
    input_off = (pre_idx * dim_size + slice_id) * post + post_idx
    tl.store(
        output_ptr + flat, tl.load(input_ptr + input_off, mask=active), mask=active
    )


def _next_power_of_two(value: int) -> int:
    power = 1
    while power < value:
        power *= 2
    return power


def _largest_power_of_two_divisor(value: int) -> int:
    divisor = 1
    while value % 2 == 0:
        value //= 2
        divisor *= 2
    return divisor


def _launch_flat_copy(input: torch.Tensor, storage: torch.Tensor, total: int) -> None:
    """``dim == 0``：整块 flat 拷贝，kernel 内 8 字节宽通道。"""
    element_size = input.element_size()
    num_bytes = total * element_size
    # 宽通道要求总字节数与指针同时对 8 字节；不满足时退回原生元素通道。
    wide = (
        element_size <= 4
        and num_bytes % 8 == 0
        and input.data_ptr() % 8 == 0
        and storage.data_ptr() % 8 == 0
    )
    num_lanes = num_bytes // 8 if wide else total
    if num_lanes <= _FLAT_LARGE_THRESHOLD:
        block = min(_next_power_of_two(num_lanes), _FLAT_SMALL_CAP)
    else:
        block = _FLAT_LARGE_BLOCK
    grid = (triton.cdiv(num_lanes, block),)
    _unbind_flat_copy_kernel[grid](
        input,
        storage,
        num_lanes,
        BLOCK=block,
        EVEN=num_lanes % block == 0,
        WIDE=wide,
        num_warps=_FLAT_WARPS,
    )


def unbind_copy(input: torch.Tensor, dim: int = 0) -> List[torch.Tensor]:
    """Unbind a tensor into a list of tensors.

    Removes a tensor dimension and returns a tuple of all the slices along
    that dimension. Unlike torch.unbind, this function creates new copies
    of the data rather than views.

    Args:
        input: The tensor to unbind
        dim: The dimension along which to unbind

    Returns:
        A list of tensors
    """
    logger.debug("GEMS UNBIND_COPY")

    if dim < 0:
        dim = dim + input.ndim

    if dim < 0 or dim >= input.ndim:
        raise IndexError(
            f"Dimension out of range (expected to be in range of [{-input.ndim}, {input.ndim - 1}], but got {dim})"
        )

    num_slices = input.shape[dim]
    if num_slices == 0:
        return []

    # Get the shape of each output tensor (without the unbind dimension)
    output_shape = list(input.shape)
    del output_shape[dim]

    num_elements_per_slice = 1
    for s in output_shape:
        num_elements_per_slice *= s

    if num_elements_per_slice == 0:
        # Return empty list of outputs
        return [
            torch.empty(output_shape, dtype=input.dtype, device=input.device)
            for _ in range(num_slices)
        ]

    total_elements = num_slices * num_elements_per_slice
    # GEMS 的 empty override 会额外启动一次 zero-fill kernel；本 op 的 kernel
    # 会写满全部元素，用 empty_strided 纯分配即可。
    output_storage = torch.empty_strided(
        (total_elements,),
        (1,),
        dtype=input.dtype,
        device=input.device,
    )

    if not input.is_contiguous():
        input = input.contiguous()

    if dim == 0:
        # 输出存储与输入逐字节相同：整块 flat 拷贝。
        _launch_flat_copy(input, output_storage, total_elements)
    else:
        dim_prod_post = 1
        for i in range(dim + 1, input.ndim):
            dim_prod_post *= input.shape[i]
        aligned_block = min(_largest_power_of_two_divisor(dim_prod_post), _ALIGNED_CAP)
        if aligned_block >= _ALIGNED_MIN_BLOCK:
            # total = S * pre * post，post % BLOCK == 0 保证整除、免 mask。
            grid = (total_elements // aligned_block,)
            _unbind_gather_aligned_kernel[grid](
                input,
                output_storage,
                num_slices,
                num_elements_per_slice,
                dim_prod_post,
                BLOCK=aligned_block,
                num_warps=_FLAT_WARPS,
            )
        else:
            block = min(_next_power_of_two(total_elements), _GATHER_BLOCK)
            grid = (triton.cdiv(total_elements, block),)
            _unbind_gather_element_kernel[grid](
                input,
                output_storage,
                num_slices,
                num_elements_per_slice,
                dim_prod_post,
                total_elements,
                BLOCK=block,
                num_warps=_FLAT_WARPS,
            )

    # Split the storage into individual output tensors. as_strided 一次调用
    # 直接给出最终形状的视图，比 slice+view 两次 dispatcher 调用省一半
    # host 开销（多片 shape 下 host 耗时会泄气进 kernel 模式的计时窗）。
    output_strides = []
    stride = 1
    for dim_size in reversed(output_shape):
        output_strides.append(stride)
        stride *= dim_size
    output_strides.reverse()
    outputs = [
        torch.as_strided(
            output_storage, output_shape, output_strides, i * num_elements_per_slice
        )
        for i in range(num_slices)
    ]

    return outputs
