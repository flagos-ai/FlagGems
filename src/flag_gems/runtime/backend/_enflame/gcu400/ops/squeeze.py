"""Metadata-only ``aten::squeeze`` for the enflame backend.

``squeeze`` never reads or writes element data: it only relabels the axes of
its input, so the whole operator cost is host-side. The implementation below
therefore keeps a single ``as_strided`` call site per outcome and resolves the
kept axes with plain tuple/list comprehensions, avoiding helper calls, per-entry
``set`` allocation and repeated ``shape`` / ``stride`` / ``storage_offset``
queries on the hot path.

Semantics match ``aten::squeeze``:
  - a size-1 axis listed in ``dim`` is dropped, a non size-1 axis is left alone;
  - ``dim=None`` drops every size-1 axis;
  - the result is a view aliasing the input, keeping its storage offset and lazy
    conjugate/negative bits (``torch.as_strided`` inherits both).
"""

import torch

# Hot-path alias: saves a module attribute lookup per call.
_as_strided = torch.as_strided


def squeeze(self: torch.Tensor, dim=None) -> torch.Tensor:
    """Return a view of the tensor with selected size-1 dimensions removed.

    Args:
        self: Input tensor.
        dim: ``None`` (drop every size-1 dimension), an ``int`` dimension, or a
            list/tuple of dimensions.

    Returns:
        torch.Tensor: A view of ``self`` with the selected size-1 dimensions
        removed, which is 0-d when every dimension was dropped.
    """
    shape = self.shape
    strides = self.stride()
    offset = self.storage_offset()
    ndim = len(shape)

    if dim is None:
        # Drop every size-1 axis in one pass over the (size, stride) pairs.
        return _as_strided(
            self,
            [size for size in shape if size != 1],
            [stride for size, stride in zip(shape, strides) if size != 1],
            offset,
        )

    # A 0-d tensor has no real axis, yet aten accepts both 0 and -1 for it, so
    # the accepted range is widened to at least one axis.
    max_dim = ndim if ndim > 0 else 1

    if isinstance(dim, int):
        if not -max_dim <= dim < max_dim:
            raise IndexError(
                f"Dimension out of range (expected to be in range of "
                f"[-{max_dim}, {max_dim - 1}], but got {dim})"
            )
        axis = dim if dim >= 0 else dim + max_dim
        # ``ndim`` guards the 0-d case, where the accepted axis (0 or -1) has no
        # entry in ``shape`` and every axis is trivially dropped.
        if ndim and shape[axis] != 1:
            # Nothing is dropped: still return a fresh view over the same
            # geometry, as aten does.
            return _as_strided(self, shape, strides, offset)
        kept = [i for i in range(ndim) if i != axis]
        return _as_strided(
            self, [shape[i] for i in kept], [strides[i] for i in kept], offset
        )

    if not isinstance(dim, (list, tuple)):
        raise TypeError(
            f"squeeze(): 'dim' must be None, an int or a list of ints, but got "
            f"{type(dim).__name__}"
        )

    # aten processes the entries in order: each dim is range-checked first (and
    # reported exactly as the caller passed it in), then checked for repeats. A
    # dim repeating later in the list is therefore reported before an
    # out-of-range entry that comes after it.
    droppable = set()
    for entry in dim:
        if not isinstance(entry, int):
            raise TypeError(
                f"squeeze(): 'dim' must be an int or a list of ints, but got "
                f"{type(entry).__name__}"
            )
        if not -max_dim <= entry < max_dim:
            raise IndexError(
                f"Dimension out of range (expected to be in range of "
                f"[-{max_dim}, {max_dim - 1}], but got {entry})"
            )
        axis = entry if entry >= 0 else entry + max_dim
        if axis in droppable:
            raise RuntimeError(f"dim {axis} appears multiple times in the list of dims")
        droppable.add(axis)

    # Only axes that are both requested and size 1 are dropped; an empty list
    # therefore leaves the shape untouched, as in aten.
    kept = [
        axis for axis, size in enumerate(shape) if not (size == 1 and axis in droppable)
    ]
    return _as_strided(
        self, [shape[i] for i in kept], [strides[i] for i in kept], offset
    )
