def _launch_tile(x, out, numel, C, HW, cpg, groups, batch, elem_size):
    if elem_size == 2 and HW % 2 == 0:
        x_k = x.view(-1).view(torch.int32)
        out_k = out.view(-1).view(torch.int32)
        hw = HW // 2
    else:
        x_k = x
        out_k = out
        hw = HW
    block_s = min(2048, _next_pow2(hw))
    block_c = max(1, 32768 // block_s)
    while triton.cdiv(C, block_c) > _MAX_GRID_Y:
        block_c *= 2
    while (
        block_c > 1
        and block_c * block_s > 4096
        and batch * triton.cdiv(hw, block_s) * triton.cdiv(C, block_c) < 64
    ):
        block_c //= 2
    n_sb = triton.cdiv(hw, block_s)
    grid = (batch * n_sb, triton.cdiv(C, block_c))
    even = C % block_c == 0 and hw % block_s == 0
    channel_shuffle_tile_kernel[grid](
        x_k,
        out_k,
        C,
        hw,
        cpg,
        groups,
        n_sb,
        BLOCK_C=block_c,
        BLOCK_S=block_s,
        EVEN=even,
        num_warps=4,
    )


def channel_shuffle(input: torch.Tensor, groups: int) -> torch.Tensor:
    logger.debug("GEMS_ENFLAME CHANNEL_SHUFFLE")
    x = input
    if not x.is_contiguous():
        x = x.contiguous()

    # Channel shuffle expects (*, C, H, W) where C is divisible by groups
    if x.ndim < 3:
        raise ValueError(
            f"Input must have at least 3 dimensions (C, H, W), got {x.ndim}"
        )

    N, C, H, W = x.shape[-4:]
    g = int(groups)
    assert g > 0, "groups must be > 0"
    assert C % g == 0, f"C ({C}) must be divisible by groups ({g})"

    out = torch.empty_like(x)
    n_elements = x.numel()
    if n_elements == 0:
        return out

    HW = H * W
    cpg = C // g
    # Leading dims fold into the batch index; the channel permutation only
    # touches the last 4 dims.
    batch = n_elements // (C * HW)
    pow2_dims = _is_pow2(C) and _is_pow2(HW) and _is_pow2(W) and _is_pow2(cpg)
    elem_size = x.element_size()
    pairable = elem_size == 2 and HW % 2 == 0
    n_bytes = n_elements * elem_size
    flat_limit = _FLAT_MAX_BYTES if pairable else _FLAT_MAX_BYTES // 2

    with torch_device_fn.device(x.device):
        if pow2_dims and n_bytes <= flat_limit:
            _launch_flat(x, out, n_elements, C, HW, W, cpg, g, elem_size)
        elif n_elements > _SMALL_NUMEL:
            _launch_tile(x, out, n_elements, C, HW, cpg, g, batch, elem_size)
        else:
            grid = (triton.cdiv(n_elements, 1024),)
            channel_shuffle_kernel[grid](
                x,
                out,
                n_elements,
                N,
                C,
                H,
                W,
                g,
                C,
                BLOCK_SIZE=1024,
            )
    return out
