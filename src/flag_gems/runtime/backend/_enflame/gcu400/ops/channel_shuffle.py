@triton.jit
def channel_shuffle_kernel(
    in_ptr,
    out_ptr,
    n_elements,
    N,
    C,
    H,
    W,
    groups,
    C_out,
    BLOCK_SIZE: tl.constexpr,
):
    pid = tl.program_id(axis=0)
    block_start = pid * BLOCK_SIZE
    offsets = block_start + tl.arange(0, BLOCK_SIZE)
    mask = offsets < n_elements

    # Strides for contiguous NCHW
    sN_in = C * H * W
    sC_in = H * W
    sH_in = W

    sN_out = C * H * W
    sC_out = H * W
    sH_out = W
    sW_out = 1

    # Decode input linear index into (n, c, h, w)
    n = offsets // sN_in
    rem1 = offsets - n * sN_in
    c = rem1 // sC_in
    rem2 = rem1 - c * sC_in
    h = rem2 // sH_in
    w = rem2 - h * sH_in

    # Channel shuffle: divide into groups and rearrange
    # Original: (n, c, h, w) where c in [0, C)
    # After reshape to (n, groups, C//groups, h, w):
    #   group_id = c // (C // groups) = c * groups // C
    #   channel_in_group = c % (C // groups)
    # After transpose to (n, C//groups, groups, h, w):
    #   new channel = channel_in_group * groups + group_id
    c_per_group = C // groups
    group_id = c // c_per_group
    channel_in_group = c - group_id * c_per_group
    new_c = channel_in_group * groups + group_id

    # Compute output linear index
    out_index = n * sN_out + new_c * sC_out + h * sH_out + w * sW_out

    x = tl.load(in_ptr + offsets, mask=mask)
    tl.store(out_ptr + out_index, x, mask=mask)


