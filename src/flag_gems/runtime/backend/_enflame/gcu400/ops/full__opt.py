"""GCU400-specific ``full``: hand-written tl.full kernel replaces pointwise_dynamic codegen.

Production ``gcu400/ops/full.py`` uses logger + check_dtype + torch.empty +
the full_func_scalar generated by pointwise_dynamic codegen; for a pure fill operator almost all
time is spent in codegen's Python layer. Here fp16/fp32/bf16 scalar fills on GCU
use a single Triton launch; all other dtypes / Tensor fill_value / non-GCU devices
delegate to production, keeping dtype policy and overflow-check semantics unchanged.
"""

import logging
import math

import torch
import triton
import triton.language as tl

from flag_gems.runtime.backend._enflame.gcu400.ops.full import full as _public

logger = logging.getLogger(__name__)


__all__ = ["full"]

# --- TUNING PARAMS START ---
BLOCK = 65536
NUM_WARPS = 4
NUM_STAGES = 1
FIXED_GRID = 0
# --- TUNING PARAMS END ---

_FINFO = {
    torch.float16: torch.finfo(torch.float16),
    torch.float32: torch.finfo(torch.float32),
    torch.bfloat16: torch.finfo(torch.bfloat16),
}


@triton.jit
def _full_kernel(
    OUT,
    N,
    VAL,
    BLOCK_SIZE: tl.constexpr,
    MASKED: tl.constexpr,
    FIXED_GRID: tl.constexpr,
):
    """Each program produces a constant vector; with FIXED_GRID>0 programs are reused by in-kernel striding."""
    arange = tl.arange(0, BLOCK_SIZE)
    values = tl.full([BLOCK_SIZE], VAL, OUT.dtype.element_ty)
    if FIXED_GRID > 0:
        pid = tl.program_id(0)
        num_programs = tl.num_programs(0)
        for block_id in tl.range(pid, tl.cdiv(N, BLOCK_SIZE), num_programs):
            offs = block_id * BLOCK_SIZE + arange
            if MASKED:
                tl.store(OUT + offs, values, mask=offs < N)
            else:
                tl.store(OUT + offs, values)
    else:
        offs = tl.program_id(0) * BLOCK_SIZE + arange
        if MASKED:
            tl.store(OUT + offs, values, mask=offs < N)
        else:
            tl.store(OUT + offs, values)


def full(size, fill_value, *, dtype=None, layout=None, device=None, pin_memory=None):
    logger.debug("GEMS_ENFLAME_GCU400 FULL")
    dev = torch.device(device) if device is not None else torch.device("cpu")
    if dtype is None:
        if isinstance(fill_value, bool):
            dt = torch.bool
        elif isinstance(fill_value, int):
            dt = torch.int64
        else:
            dt = torch.get_default_dtype()
    else:
        dt = dtype

    if (
        dev.type != "gcu"
        or dt not in _FINFO
        or isinstance(fill_value, torch.Tensor)
        or layout is not None
        or pin_memory is not None
    ):
        return _public(
            size,
            fill_value,
            dtype=dtype,
            layout=layout,
            device=device,
            pin_memory=pin_memory,
        )

    # Same semantics as production check_dtype: bool scalars under a floating dtype are cast to int first, then
    # overflow-checked.
    if isinstance(fill_value, bool):
        fill_value = int(fill_value)
    if not (math.isinf(fill_value) or math.isnan(fill_value)):
        finfo = _FINFO[dt]
        if fill_value < finfo.min or fill_value > finfo.max:
            raise RuntimeError(
                f"value cannot be converted to type {dt} without overflow"
            )

    out = torch.empty(size, device=dev, dtype=dt)
    num_elems = out.numel()
    if num_elems == 0:
        return out
    if FIXED_GRID > 0:
        grid = (min(triton.cdiv(num_elems, BLOCK), FIXED_GRID),)
    else:
        grid = (triton.cdiv(num_elems, BLOCK),)
    _full_kernel[grid](
        out,
        num_elems,
        fill_value,
        BLOCK_SIZE=BLOCK,
        MASKED=(num_elems % BLOCK != 0) or (BLOCK > num_elems),
        FIXED_GRID=FIXED_GRID,
        num_warps=NUM_WARPS,
        num_stages=NUM_STAGES,
    )
    return out
