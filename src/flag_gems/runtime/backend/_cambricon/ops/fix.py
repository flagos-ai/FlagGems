@libtuner(
    configs=[
        triton.Config(kwargs={"BLOCK_SIZE": 4096}, num_stages=1, num_warps=1),
        triton.Config(kwargs={"BLOCK_SIZE": 16384}, num_stages=1, num_warps=1),
        triton.Config(kwargs={"BLOCK_SIZE": 65536}, num_stages=1, num_warps=1),
        triton.Config(kwargs={"BLOCK_SIZE": 131072}, num_stages=1, num_warps=1),
    ],
    key=["n_elements", "is_floating_point"],
    restore_value=["OUT_ptr"],
)
@libentry()
@triton.jit
def fix_kernel(
    X_ptr,
    OUT_ptr,
    n_elements,
    is_floating_point: tl.constexpr,
    BLOCK_SIZE: tl.constexpr,
):
    pid = tl.program_id(0)
    num_jobs = tl.num_programs(0)
    block_start = (pid * BLOCK_SIZE).to(tl.int64)
    step = num_jobs * BLOCK_SIZE

    for off in range(block_start, n_elements, step):
        offsets = off + tl.arange(0, BLOCK_SIZE)
        mask = offsets < n_elements
        x = tl.load(X_ptr + offsets, mask=mask)

        out = x
        if is_floating_point:
            x_fp32 = x.to(tl.float32)
            res_pos = tl.floor(x_fp32)
            res_neg = tl.ceil(x_fp32)
            out = tl.where(x_fp32 >= 0, res_pos, res_neg).to(x.dtype)

        tl.store(OUT_ptr + offsets, out, mask=mask)


def _launch_fix_kernel(input: torch.Tensor, out: torch.Tensor):
    input = input.contiguous()
    n_elements = input.numel()
    if n_elements == 0:
        return out

