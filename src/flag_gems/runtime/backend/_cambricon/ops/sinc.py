import logging
import math

import triton
import triton.language as tl

from ..utils.pointwise_dynamic import pointwise_dynamic

logger = logging.getLogger(__name__)


@pointwise_dynamic(is_tensor=[True, False], promotion_methods=[(0, "INT_TO_FLOAT")])
@triton.jit
def sinc_func(x, inplace):
    x_f32 = x.to(tl.float32)
    px = math.pi * x_f32
    px2 = px * px
    taylor = 1.0 - px2 / 6.0
    result = tl.sin(px) / px
    return tl.where(tl.abs(x_f32) < 2.0e-2, taylor, result)


def sinc(A):
    logger.debug("GEMS_CAMBRICON SINC")
    return sinc_func(A, False)


def sinc_(A):
    logger.debug("GEMS_CAMBRICON SINC_")
    sinc_func(A, True, out0=A)
    return A
